def sum_basis(deal: dict[str, Any]) -> str:
    """Что означает число в `sum` — единственное место, где это решается
    (клиент с 6 сентября 2026 копии не держит: читает facts.price.meaning).

    До 6 сентября 2026 смысл суммы нигде не хранился и не вычислялся: топ
    «Аналитики» и мультипликаторы читали `sum` как цену, если в строке не
    было слова «оценк». Так в «покупки» попали 320 млрд ₽ структурной сделки
    под залог и допэмиссия Segezha, а в мультипликаторы — стартовая цена
    торгов и «более 200 млрд ₽» (аудит, раунды 1 и 2). Явное поле карточки
    `sum_basis` сильнее разбора текста — им рутина или человек помечают
    то, чего по тексту не видно (компенсация по иску, оценка всей компании)."""
    explicit = deal.get('sum_basis')
    if explicit in SUM_BASES:
        return explicit
    text = str(deal.get('sum') or '')
    if _UNDISCLOSED.match(text):
        return 'undisclosed'
    if _FOREIGN.search(text) and '₽' not in text:
        return 'foreign_currency'
    if _AUCTION_START.search(text):
        return 'auction_start'
    # «2,5 тыс. ₽ (номинальная цена по решению суда)» — число есть, цены нет;
    # нашлось третьим уровнем проверки (facts.number_checks: порядок величины).
    if re.search(r'номинальн|заявлено как объем инвестиц|не цена', text, re.I):
        return 'not_a_price'
    if _RANGE.search(text):
        return 'range'
    if _ESTIMATE.search(text):
        return 'estimate'
    if _LOWER_BOUND.search(text):
        return 'lower_bound'
    if '₽' not in text:
        return 'foreign_currency' if _FOREIGN.search(text) else 'unparsed'
    if not _RUB_AMOUNT.search(text):
        return 'unparsed'  # «несколько млрд ₽ (точно не указана)» — рубли есть, числа нет
    return 'disclosed'


# ЦЕНА В ВАЛЮТЕ (26 сентября 2026). Одна сумма в долларах или евро — «$484 млн»,
# «531 млн €», «€285 млн», «$550 000». Пересчет в рубли по курсу ЦБ делает
# facts.py (через fx.py); здесь только разбор: какая валюта, сколько и ЧТО это
# за число — тем же правилом, что у рублевой суммы («до $150 млн» — оценка,
# «$25–50 млн» — диапазон, «более $1 млрд» — нижняя граница). Две суммы в одной
# строке («€1 + долг €100 млн», «$12 млн (в т.ч. $10 млн от…)»), другие валюты
# (кроны, франки) и рубли рядом — не разбираются вовсе: какое число считать
# ценой, из строки не видно.
_FX_NUM = r'\d[\d\s\xa0]*(?:[.,]\d+)?'
_FX_AMOUNT = re.compile(
    r'(?P<sym1>[$€])\s*(?P<n1>' + _FX_NUM + r')(?:\s*[–—-]\s*(?P<n2>' + _FX_NUM + r'))?'
    r'(?:\s*(?P<unit1>тыс|млн|млрд|трлн)\.?)?'
    r'|(?P<n3>' + _FX_NUM + r')(?:\s*[–—-]\s*(?P<n4>' + _FX_NUM + r'))?\s*(?P<unit2>тыс|млн|млрд|трлн)\.?'
    r'\s*(?P<sym2>[$€]|долл[а-яё]*|USD|евро|EUR)',
    re.I)
_FX_OTHER = re.compile(r'крон|франк|юан|фунт|иен|£|¥|₽|руб', re.I)
_FX_NOT_PRICE = re.compile(r'разглаш|раскры|возможн', re.I)


def foreign_price(text: str | None) -> dict[str, Any] | None:
    """{'currency': 'USD'|'EUR', 'amount': число в валюте, 'meaning': смысл по
    тем же правилам, что у рублевой суммы} или None, если в строке не ровно
    одна сумма в долларах или евро."""
    text = str(text or '')
    if not text or _FX_OTHER.search(text) or _FX_NOT_PRICE.search(text):
        return None
    found = list(_FX_AMOUNT.finditer(text))
    if len(found) != 1:
        return None
    m = found[0]
    n1, n2 = (m.group('n1'), m.group('n2')) if m.group('sym1') else (m.group('n3'), m.group('n4'))
    unit = (m.group('unit1') or m.group('unit2') or '').lower()
    sym = (m.group('sym1') or m.group('sym2') or '').lower()
    currency = 'EUR' if sym in ('€', 'eur') or sym.startswith('евро') else 'USD'

    def num(x: str) -> float:
        return float(x.replace(' ', '').replace('\xa0', '').replace(',', '.'))
    mult = UNIT_MULT.get(unit, 1)
    lo = num(n1) * mult
    hi = num(n2) * mult if n2 else lo
    # Смысл — по ТОЙ ЖЕ строке, где сумма заменена рублевой: «≈», «до»,
    # «по оценке», «этап», диапазон решаются одним правилом для всех валют.
    as_rub = text[:m.start()] + ('1–2 млн ₽' if n2 else '1 млн ₽') + text[m.end():]
    return {'currency': currency, 'amount': (lo + hi) / 2, 'meaning': sum_basis({'sum': as_rub})}


