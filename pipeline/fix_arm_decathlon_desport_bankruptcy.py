import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g60280ac0'

OLD_EXTRA = (
    'Сделка находится в процессе закрытия. Получены разрешения '
    'государственных органов. Покупатель — ООО «АРМ» (владелец/'
    'генеральный директор Вячеслав Мареев, основные доли принадлежат '
    'кипрской компании «Трибалон лтд.»). Продавец — французская '
    'компания Decathlon. После закрытия сделки магазины планируют '
    'открыться в октябре-ноябре под новым брендом.'
)
NEW_EXTRA = (
    'Сделка закрыта. Покупатель — ООО «АРМ» (владелец/генеральный '
    'директор Вячеслав Мареев, основные доли принадлежат кипрской '
    'компании «Трибалон лтд.»). Продавец — французская компания '
    'Decathlon. Новый владелец был обязан сохранить рабочие места '
    '909 сотрудникам сети. Магазины сначала планировали назвать All Do '
    'Sport (ADS), но открылись 10 декабря 2023 года под брендом '
    'Desport — в Краснодаре, Москве, Казани, Санкт-Петербурге, Самаре, '
    'Перми и Уфе.'
)

OLD_ECO_CONTEXT = (
    'Мареев также является владельцем или управляющим ряда юрлиц, '
    'которые занимаются ресторанным бизнесом. Например, это '
    'франчайзинг «Шоколадницы», «Бургер Кинга», «Чайхоны №1», '
    'ресторана «Сыроварня»'
)
NEW_ECO_CONTEXT = (
    'Мареев также является владельцем или управляющим ряда юрлиц, '
    'которые занимаются ресторанным бизнесом. Например, это '
    'франчайзинг «Шоколадницы», «Бургер Кинга», «Чайхоны №1», '
    'ресторана «Сыроварня», а также в России развивал по франшизе бренд '
    'Mango. Мареев — партнёр Андрея Бокарева, одного из основателей '
    '«Трансмашхолдинга»; вместе они владеют ООО «Атрилэнд», сдающим в '
    'аренду помещения в ТЦ «Атриум» у метро «Курская» в Москве. Сеть '
    'сократилась с 35 магазинов на момент сделки до 22 к октябрю 2025 '
    'года и 19 к марту 2026-го. В 2024 году выручка АО «Октоблу» '
    '(юрлицо сети) выросла почти в шесть раз, до 5 млрд ₽, но с '
    'убытком почти 3 млрд ₽; 22 октября 2025 года кредитор подал в суд '
    'заявление о банкротстве компании (всего накопилось 123 иска на '
    '847,6 млн ₽), а 31 августа 2026 года Арбитражный суд Москвы начал '
    'процедуру наблюдения — первую стадию банкротства.'
)

NEW_SRC = [
    ['Sostav.ru', 'https://www.sostav.ru/publication/decathlon-63423.html'],
    ['РБК-Кубань', 'https://kuban.rbc.ru/krasnodar/freenews/657613f99a79471828e154e3'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8160622'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8922319'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA
    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
