import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'ga1828730'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Закрыта'

OLD_CONTEXT = (
    'Доля трейдера в капитале компании одно время доходила почти до '
    '50%. Но в 2016 году пакет швейцарской компании был размыт до 24% '
    'в результате допэмиссии в рамках подготовки «Русснефти» к IPO. На '
    'данный момент Glencore через свою структуру Rambero Holding '
    'владеет 23,46% уставного капитала «Русснефти» (31,28% обыкновенных '
    'акций). Решение о выходе из «Русснефти» Glencore принял еще в '
    '2021 году. Закрыть сделку стороны собирались в первом полугодии '
    '2022 года, однако начало боевых действий на Украине и ограничения '
    'на вывод иностранного капитала из РФ потребовали длительных '
    'согласований.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' Выход завершён в 2025 году двумя траншами. В январе 2025 года '
    '12,75% уставного капитала (17% обыкновенных акций, 50,4 млн акций '
    'по 55 руб. за акцию, 2,75 млрд руб.) выкупила сама «Русснефть» '
    'через дочернее ООО «Белые ночи» (казначейский пакет). Оставшаяся '
    'часть (12,25% уставного капитала) в апреле 2025 года перешла к '
    'зарегистрированной в ОАЭ OCN International, а к 24 июня 2025 года '
    '16,33% обыкновенных акций оказались у Заиры Гудаевой через ООО '
    '«Неолайн Активы» — с косвенной, но не подтверждённой напрямую '
    'связью с окружением Михаила Гуцериева через ГК А101 и Билана '
    'Ужахова.'
)

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/business/1044349'],
    ['Moscow Times', 'https://www.themoscowtimes.com/2025/04/24/swiss-commodities-giant-glencore-sells-off-russneft-stake-a88864'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/7854465'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS
    assert deal['eco']['context'] == OLD_CONTEXT

    new_src = deal['src'] + NEW_SRC

    print('=== status: станет ===')
    print(NEW_STATUS)
    print('\n=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['status'] = NEW_STATUS
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
