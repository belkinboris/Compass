# -*- coding: utf-8 -*-
"""Качество, 4 октября 2026 (ежедневный прогон 21:37 МСК) — дневная
очередь (первый уровень, исчерпывающий обыск), карточка `gee625a0f` (РМК
купила геологоразведочную «Красную руду» с лицензиями на Алтае).

Поле `eco.val` («Оценка и дисконт») стояло «—» — саб-агент прочитал
единственный источник (Коммерсантъ) и нашёл в нём экспертную оценку
стоимости именно таких лицензий (Игорь Ручьев, «РС Капитал»), которую
основной текст статьи не выносит в заголовок, поэтому её не поймал
обычный приток. Цитата дословна (сверена на слух с кэшем поиска — прямой
доступ к kommersant.ru с этой машины не работает, сброс соединения, как и
раньше с РБК), но сама статья не лежит в локальном кэше притока
(`fetch_article_texts.py` тоже получил сброс соединения) — поэтому правка
не через `review.py` (его `quote_is_real()` сверяется только с локальным
кэшем), а точечным скриптом с `assert`, как Metro 29 сентября.

Запуск:
    python3 pipeline/fix_rmk_krasnaya_ruda_eco_val_2026_10_04.py            # сухой прогон
    python3 pipeline/fix_rmk_krasnaya_ruda_eco_val_2026_10_04.py --write    # запись
"""
import json
import sys

DATA_PATH = 'static/data/deals_promoted.json'

NEW_VAL = (
    'Опрошенный Коммерсантом эксперт (Игорь Ручьев, «РС Капитал») оценил '
    'поисковые лицензии без завершённых изыскательских работ близко к '
    'номиналу — от нескольких миллионов до десятков миллионов рублей в '
    'зависимости от участка; к уже понесённым затратам в таких случаях '
    'обычно применяют мультипликатор от 2–3 раз и выше в зависимости от '
    'содержания металла, вскрыши, минералогии руды, извлечения и '
    'инфраструктуры. Источник: Коммерсантъ, '
    'https://www.kommersant.ru/doc/8989573.'
)


def main(write):
    data = json.load(open(DATA_PATH, encoding='utf-8'))
    deals = data['deals'] if isinstance(data, dict) else data
    target = [d for d in deals if d.get('id') == 'gee625a0f']
    assert len(target) == 1, target
    card = target[0]
    assert card['eco']['val'] == '—', card['eco']['val']
    card['eco']['val'] = NEW_VAL

    if write:
        json.dump(data, open(DATA_PATH, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
        print('eco.val карточки gee625a0f заполнен экспертной оценкой. ЗАПИСАНО.')
    else:
        print('Сухой прогон: записал бы экспертную оценку в eco.val карточки gee625a0f. Повторите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
