# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g8e7eee71 (АО «СХП «Колос»» приобрела 50% ООО «Колос Кубани»,
08.12.2023, статус «Закрыта») — предмет карточки продан целиком, но
новому владельцу, чья связь со сторонами этой сделки не установлена;
решение о новой карточке — за приютоком/человеком, не этой рутиной.

Проверено лично прямым WebFetch (Коммерсантъ, 02.03.2026,
doc/8477794): «Компания «Магнит»» купила «Колос Кубани» за оценочные
1,8 млрд руб. («рыночная стоимость садов составляет 1–1,3 млрд руб.,
остальная сумма объясняется учетом долгов компании» — Юрий Левицкий,
BGP Capital); владелец на момент продажи — «Денис Таран (руководитель
и бенефициар компании «Колос Кубани», зарегистрированной в 2018
году)» — то есть 50/50-структура из карточки (АО «СХП «Колос»»/ЗАО
«Династия») к моменту продажи Магниту консолидировалась в одних
руках, связь Тарана со сторонами исходной сделки источники не
называют.

НЕ ВКЛЮЧЕНО (по данным саб-агента, без дозаверки WebFetch): точная
дата и обстоятельства консолидации 100% у Тарана; финансовые
показатели 2024 года (выручка 183,2 млн ₽, убыток 100,58 млн ₽);
прогнозы урожая на 2026 год — планы нового владельца, не отчёт о
прошлом; развитие самого АО «СХП «Колос»» на Ставрополье — новых
сделок не нашлось.

Запуск: python3 pipeline/fix_kolos_kubani_sold_to_magnit_postdeal.py
        python3 pipeline/fix_kolos_kubani_sold_to_magnit_postdeal.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g8e7eee71'

OLD_EXTRA = (
    'Сделка закрыта 8 декабря 2023 года. АО «СХП «Колос»» приобрела '
    '50% долей производителя яблок и голубики ООО «Колос Кубани» у '
    'Владислава Пономаренко. Оставшимися 50% владеет ЗАО «Династии».'
)
NEW_EXTRA = OLD_EXTRA + (
    ' 2 марта 2026 года «Колос Кубани» продан целиком: покупателем '
    'стал «Магнит» (оценочно 1,8 млрд ₽), а владельцем компании на '
    'момент продажи числился уже не АО «СХП «Колос»»/ЗАО «Династия», '
    'а Денис Таран — связь которого со сторонами этой сделки '
    'источники не называют.'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8477794'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
