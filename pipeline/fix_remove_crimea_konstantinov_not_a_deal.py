import json
import sys

DATA_PATH = 'static/data/pending.json'


def main(write):
    data = json.load(open(DATA_PATH, encoding='utf-8'))
    cards = data['cards']
    target = [c for c in cards if c['id'] == 'g2d97c0a2']
