    'Росимущества к ООО «Мегатэк», 99% которого принадлежит ООО «БФ Прямые инвестиции» '
    '(владельцы не раскрыты в ЕГРЮЛ); до марта 2022 эта компания принадлежала ООО '
    '«Бизнес-финанс» — дочерней структуре ВТБ. В агросекторе банк уже бывал раньше: до лета '
    '2023 года ему принадлежала «Деметра-Холдинг» — крупная вертикально-интегрированная '
    'зерновая компания, из капитала которой он затем вышел. Еще в декабре 2025 Костин '
    'говорил о планах создать на базе «Лабинского» отдельный агрохолдинг — то есть скорее о '
    'покупке, чем о продаже; аналитик Пешков допускает и другую причину разворота — слабые '
    'финансовые показатели самих агропредприятий. Победителем в поиске покупателя, который '
    'вели среди «Агрокомплекса им. Ткачева» и «Просторов», стали структуры «Просторов» — '
    'холдинга, который по данным ЕГРЮЛ в октябре 2024 получил 99% долей ООО «Инвестком», '
    'контролирующего 11 сельхозкомпаний, включая производителя круп АФГ «Националь» и '
    'производителя мраморной говядины группу «Заречное»; тем же путем «Просторы» ранее '
    'получили растениеводческий холдинг «Дон-Агро» — выкупили его у экс-депутата Госдумы '
    'Евгения Туголукова. Бенефициаром «Инвесткома» называли Ивана Юзефовича, партнера '
