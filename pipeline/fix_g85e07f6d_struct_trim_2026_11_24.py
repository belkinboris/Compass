import json
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(ROOT, '..', 'static', 'data', 'deals_promoted.json')
CARD_ID = 'g85e07f6d'
OLD = ('Конкурентных торгов не было: заявку подало только ООО НПО «РТС», и комиссия признала '
       'компанию единственным участником аукциона. Прием заявок открылся 8 октября 2026 года, '
       'торги назначили на 20 ноября, но итог определился уже при рассмотрении заявок; '
       'итоговый протокол опубликован на портале «ГИС Торги» 19 ноября. Задаток составлял 10% '
       'начальной цены, шаг аукциона — 599 тыс. ₽. По правилам аукциона с единственным '
       'участником договор заключают по начальной цене уже после протокола — право '
       'собственности переходит покупателю не в день протокола, а при подписании договора.')
NEW = ('Конкурентных торгов не было: заявку подало только ООО НПО «РТС», и комиссия признала '
       'компанию единственным участником аукциона. Прием заявок открылся 8 октября 2026 года, '
       'торги назначили на 20 ноября, но итог определился уже при рассмотрении заявок; '
       'итоговый протокол опубликован на портале «ГИС Торги» 19 ноября. Задаток составлял 10% '
       'начальной цены, шаг аукциона — 599 тыс. ₽. По правилам аукциона с единственным '
       'участником договор заключают по начальной цене уже после протокола.')


def apply(data):
    card = next(c for c in data['deals'] if c['id'] == CARD_ID)
    assert card['law']['struct'] == OLD, 'текст уже изменен кем-то другим'
    card['law']['struct'] = NEW


def main(write):
    data = json.load(open(DATA, encoding='utf-8'))
    apply(data)
    print('law.struct обновлен')
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return 0
    data = json.load(open(DATA, encoding='utf-8'))
    apply(data)
    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
        f.write('\n')
    print('ЗАПИСАНО.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main('--write' in sys.argv[1:]))
