# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка g8a67edea (Выкуп российских
активов Rockwool у датского собственника): проверка статуса — обязательный
угол для сделки со статусом «Обсуждается» — подтвердила, что сделка
ДЕЙСТВИТЕЛЬНО ещё не завершена (окончательного перехода прав собственности
не произошло, статус в карточке верен). Но нашлось два крупных новых
факта: внутригрупповой судебный иск (август 2026) и конкретные шаги РСА
по перезапуску производства — не через review.py, три разных источника
на одно поле.

Источники — читал напрямую (fetch_article_texts.py, все закэшированы):
Коммерсантъ (13.08.2026, doc/8878435), Интерфакс (13.08.2026,
business/1109055), Коммерсантъ (19.05.2026, doc/8673079), rwl.ru (интервью
гендиректора РСА Тимура Амирова, май 2026).
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g8a67edea'
OLD_CONTEXT = (
    'До февраля 2022 года Rockwool был важным поставщиком для российского '
    'ВПК, в частности для Объединенной судостроительной корпорации (ОСК). '
    'Компания поставляла специализированную шумоизоляцию, используемую при '
    'строительстве атомных подводных лодок и других военных кораблей. '
    'Однако после начала специальной военной операции датские акционеры в '
    'одностороннем порядке прекратили сотрудничество.'
)
ADDITION = (
    '11 августа 2026 года российское ООО «Роквул» подало в Арбитражный '
    'суд Московской области иск на 8,6 млрд рублей к своей материнской '
    'компании — датскому производителю изоляционных материалов Rockwool '
    'A/S, требуя взыскания задолженности по договору займа от 29 октября '
    '2020 года, в котором датская Rockwool выступала заёмщиком: в '
    '2020–2021 годах российская компания предоставила два транша на общую '
    'сумму 5 млрд руб. — основной долг, 3,04 млрд руб. — начисленные '
    'проценты и 557 млн руб. — неустойка. РСА тем временем объявила о '
    'планах перезапуска производства: «намерено до 2028 года вложить в '
    'диверсификацию производства около 10 млрд рублей», а гендиректор РСА '
    'Тимур Амиров рассказал о возобновлении выпуска изоляции для ВПК '
    '(«Сейчас начинаем процедуру получения необходимой сертификации. Это '
    'займет несколько месяцев, но производство уже готово», «Наша цель, '
    'как минимум, вернуть объём заказов к уровню 2022 года») и о новом '
    'направлении — выпуске быстровозводимых модульных строений («Второе '
    'направление – выпуск быстровозводимых строений. Об этом будет '
    'объявлено дополнительно в ближайшие пару месяцев»).'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} eco.context: += иск «Роквула» к Rockwool A/S и планы РСА")
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
