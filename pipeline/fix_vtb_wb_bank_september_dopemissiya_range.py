# -*- coding: utf-8 -*-
"""ВТБ/WB Банк (`c51d0bb64`): заметка партнёра (id решения 407, 31 августа
2026) о сырье «Покупку ВТБ 5% в WB-банке перенесли на сентябрь» (mergers.ru)
попросила проверить, нет ли уже карточки в стадии обсуждения, которую можно
обогатить, — карточка была, и сам факт переноса на сентябрь там уже стоял
(запись от 28 августа с той же цитатой Пьянова про «чрезвычайные события»).
Новое в сегодняшней статье — тот же зампред ВТБ Дмитрий Пьянов лично уточнил
параметры допэмиссии: не расплывчатое «может превысить 547 млрд рублей» (уже
стоит в `law.terms`, атрибутировано «Ведомостям»), а «в старых диапазонах
300-400 млрд рублей ближе к нижней границе диапазона», плюс отдельная деталь
про скромное участие розничных инвесторов из-за разрыва в цене акций.

Старое значение `law.terms` не трогается и не объявляется ошибкой: разные
источники называли разные числа в разное время, и более новая цитата от
первого лица не доказывает, что цифра «Ведомостей» была неверной — обе
цифры остаются на карточке, каждая при своей атрибуции (родня уже
записанного правила «правку без более сильного подтверждения не делать»).
Дополнение идёт в `eco.context`, куда уже была внесена цитата от 28 августа
о том же зампреде и том же переносе — простое `review.py` не подходит:
`check()` требует, чтобы ВСЁ новое значение целиком лежало в одной цитате
дословно, а здесь добавляется только последнее предложение к уже стоящему
тексту (та же граница, что у `pipeline/fix_afk_sistema_vtb_ozon_structure_
detail.py` и других дополнений уже тронутых полей).

Источник — Mergers.ru (добавлен в `src` тем же прогоном через таблицу
FIXES, pipeline/ingest/fixes/batch_2026_08_31_vtb_wb_bank_september_
placeholder_narrowed.py); обычный `fetch_article_texts.py` дважды подряд
отрапортовал успешную загрузку и записал в кэш пустую строку — текст получен
WebFetch и вручную дописан в кэш `data/inbox/raw/2026-08-31-articles.jsonl`.

Запуск: python3 pipeline/fix_vtb_wb_bank_september_dopemissiya_range.py           # проверка
        python3 pipeline/fix_vtb_wb_bank_september_dopemissiya_range.py --write   # запись
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'c51d0bb64'
OLD_CONTEXT = (
    'Статья описывает стратегическое партнерство между ВТБ и Wildberries '
    '(группой RWB) по развитию WB Банка. ВТБ предоставляет готовую '
    'инфраструктуру (розничные отделения, сеть банкоматов, кредитные и '
    'инвестиционные продукты). ВТБ объявил о планах допэмиссии акций. 28 '
    'августа 2026 года первый зампред ВТБ Дмитрий Пьянов сообщил, что '
    'сделка по покупке миноритарной доли в WB-банке и финтех-активах '
    'перенесена на сентябрь, но параметры допэмиссии под неё принципиально '
    'не пересматривались: «Мы не форсируем ее, понимая, что управленческие, '
    'человеческие ресурсы нашего партнера сейчас направлены на решение '
    'проблем, связанных с чрезвычайными событиями».'
)
ADDITION = (
    '31 августа 2026 года он уточнил параметры допэмиссии: «Допэмиссия для '
    'целей приобретения будет осуществлена в старых диапазонах 300-400 млрд '
    'рублей ближе к нижней границе диапазона. Мы понимаем, что участие '
    'розничных инвесторов будет скромным в силу разрыва в цене акций».'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + ADDITION
NEW_SRC = ['Mergers.ru',
           'https://mergers.ru/news/Pokupku-VTB-5-d-WB-banke-perenesli-na-sentyabr-87451']


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    card = next((c for c in data['deals'] if c['id'] == CARD_ID), None)
    assert card is not None, '%r не найдена в базе' % CARD_ID
    assert card.get('eco', {}).get('context') == OLD_CONTEXT, (
        'eco.context уже другое: %r' % card.get('eco', {}).get('context'))
    src_already_present = NEW_SRC in card.get('src', [])

    print('ДОБАВЛЕНО: %r' % ADDITION)
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return 1

    card['eco']['context'] = NEW_CONTEXT
    if not src_already_present:
        card.setdefault('src', []).append(NEW_SRC)
    json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('ЗАПИСАНО.')
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv[1:]))
