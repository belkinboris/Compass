# -*- coding: utf-8 -*-
"""«Цель сделки», дословно равная «Дополнительной информации», — 530 карточек.

НАЙДЕНО вычиткой 15 случайных карточек (просьба владельца 15 августа 2026:
проверить «на повторы»). У 5 карточек из 15 поле `eco.rationale` оказалось
дословной копией `extra` — а замер по базе дал 530 из 1574, то есть КАЖДУЮ
ТРЕТЬЮ карточку. Дефект системный: его делает не человек, а сам компактный
импорт, который клал один и тот же синтезированный абзац в оба поля.
В CLAUDE.md он уже описан («Один и тот же текст лежит в двух полях»,
«„Цель сделки", совпадающая с „Дополнительной информацией" слово в слово, —
это не заполненное поле»), но чинился до сих пор поштучно.

ЧТО ЧИТАТЕЛЬ ВИДИТ НА САМОМ ДЕЛЕ. Не два одинаковых абзаца: `extraHtml()`
в `index.html` выбрасывает из «Дополнительного контекста» предложения,
которые уже сказаны в полях `eco`, и при полном совпадении выбрасывает весь
блок. То есть блок «Дополнительный контекст» ПРОПАДАЕТ, а весь текст
показывается под заголовком «Цель сделки». А текст этот — не цель:
замер по 530 карточкам показал, что маркер цели («цель сделки», «чтобы»,
«позволит») есть лишь у 8, остальные 522 — фактическое описание сделки
(«Сделка закрыта в феврале 2025 года. ГАП „Ресурс"… приобрела…»,
«Результаты конкурса по продаже 100% акций…»). Подпись «Цель сделки» над
таким абзацем просто неверна — тот же класс, что уже записан в CLAUDE.md
про подписи к числам: подпись обязана называть то, что под ней лежит.

ПОЭТОМУ ЧИНИТСЯ СНЯТИЕМ `eco.rationale`, А НЕ `extra`. Как только копия
уходит из `rationale`, `extraHtml()` перестаёт считать абзац дублем и
показывает его под верной подписью «Дополнительный контекст». Текст не
пропадает и не меняется ни на символ — он переезжает под правильный
заголовок. Проверено: ни у одной из 530 карточек в `eco` не остаётся пусто,
у всех есть другие заполненные поля, так что линза «Экономист» нигде не
обнуляется.

СЕМЬ ИСКЛЮЧЕНИЙ — там, где цель НАЗВАНА. У них из общего абзаца в
`rationale` переносится ровно то предложение, которое говорит о цели
(остальное остаётся в `extra` и покажется «Дополнительным контекстом»).
Восьмая карточка с маркером, g01b8b8f6, в исключения НЕ входит: её
«Условие сделки: покупатель должен не находиться под санкциями, чтобы
позволить завершение расчетов» — это условие, а не цель, и «чтобы» там
служебное.

ЧЕТЫРЕ ГРАММАТИЧЕСКИЕ ПРАВКИ, найденные при чтении этих же восьми:
  * gdd67ffde: «Цель сделки — диверсификациЮ продуктового портфеля» —
    винительный падеж вместо именительного после тире-связки.
  * gfc3c7ec8: «100% акционНОГО капитала» — опечатка, надо «акционерного».
  * gb70b4830: «Покупатель — ГАП „Ресурс" (…), позволит получить…» — у
    «позволит» нет подлежащего; восстановлена точка и подлежащее «Сделка».
  * g3fdf0220: хвост «(Росатом (через компанию „Рэнера"))» — протёкшая
    пометка роли, которую общий прогон не снял (внутри не ролевое слово).

Запуск:
    python3 pipeline/fix_rationale_duplicating_extra.py            # сухой прогон
    python3 pipeline/fix_rationale_duplicating_extra.py --write    # запись
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

EXPECTED_DUPLICATES = 530

# Правки текста самого `extra` — грамматика, найденная при чтении.
EXTRA_REWRITES = {
    'gdd67ffde': ('Цель сделки — диверсификацию продуктового портфеля',
                  'Цель сделки — диверсификация продуктового портфеля'),
    'gfc3c7ec8': ('100% акционного капитала', '100% акционерного капитала'),
    'gb70b4830': ('около 100 млрд руб.), позволит получить дополнительные возможности '
                  'сбыта собственной продукции.',
                  'около 100 млрд руб.). Сделка позволит получить дополнительные '
                  'возможности сбыта собственной продукции.'),
    'g3fdf0220': (' (Росатом (через компанию «Рэнера»))', ''),
}

# Карточки, где цель НАЗВАНА: в `rationale` остаётся только это предложение.
# Текст каждого — дословный кусок `extra` ПОСЛЕ правок выше.
PURPOSE_SENTENCE = {
    'g630c3361': 'Интеграция позволит создать цифровую экосистему от записи пациентов '
                 'до интеграции со страховыми компаниями.',
    'gb70b4830': 'Сделка позволит получить дополнительные возможности сбыта '
                 'собственной продукции.',
    'g807a5625': 'Приобретение позволит VK подключиться к данной госпрограмме и '
                 'потенциально стать единым оператором программы.',
    'gfc3c7ec8': 'Сделка позволит «Невской косметике» войти в десятку крупных '
                 'производителей рынка.',
    'gdd67ffde': 'Цель сделки — диверсификация продуктового портфеля и развитие '
                 'глубокой переработки мяса',
    'g9ec93147': 'Сделка позволит «Медскану» расширить присутствие на региональных '
                 'рынках.',
    'g3fdf0220': 'Цель сделки — получение технологии NMC для запуска завода мощностью '
                 '4 ГВт•ч в год в Калининградской области осенью 2025 года.',
}


def norm(s):
    return re.sub(r'\s+', ' ', str(s or '')).strip()


def main(argv):
    data = json.load(open(DATA, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}

    dups = [d for d in data['deals']
            if norm(d.get('extra'))
            and norm(d.get('extra')) == norm((d.get('eco') or {}).get('rationale'))]
    assert len(dups) == EXPECTED_DUPLICATES, \
        'ожидалось %d карточек-дублей, найдено %d — состояние базы изменилось' \
        % (EXPECTED_DUPLICATES, len(dups))

    dup_ids = {d['id'] for d in dups}
    for cid in list(EXTRA_REWRITES) + list(PURPOSE_SENTENCE):
        assert cid in dup_ids, '%s больше не дубль — проверьте вручную' % cid

    # Каждая правка обязана найтись в тексте, а результат — лечь дословно.
    for cid, (old, new) in EXTRA_REWRITES.items():
        assert old in by_id[cid]['extra'], '%s: не найден фрагмент %r' % (cid, old[:40])

    for cid, sentence in PURPOSE_SENTENCE.items():
        text = by_id[cid]['extra']
        if cid in EXTRA_REWRITES:
            old, new = EXTRA_REWRITES[cid]
            text = text.replace(old, new)
        assert norm(sentence) in norm(text), \
            '%s: предложение о цели не лежит в extra дословно' % cid

    print('Карточек с дублем «Цель сделки» = «Дополнительная информация»: %d' % len(dups))
    print('  снимаем дубль целиком: %d' % (len(dups) - len(PURPOSE_SENTENCE)))
    print('  оставляем только предложение о цели: %d' % len(PURPOSE_SENTENCE))
    print('  грамматических правок в extra: %d' % len(EXTRA_REWRITES))
    for cid, (old, new) in EXTRA_REWRITES.items():
        print('    %s: %r -> %r' % (cid, old[:52], new[:52]))

    if '--write' not in argv:
        print('\nСухой прогон. Запись — с ключом --write.')
        return 0

    for cid, (old, new) in EXTRA_REWRITES.items():
        by_id[cid]['extra'] = by_id[cid]['extra'].replace(old, new).strip()

    for d in dups:
        if d['id'] in PURPOSE_SENTENCE:
            d['eco']['rationale'] = PURPOSE_SENTENCE[d['id']]
        else:
            d['eco'].pop('rationale', None)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('ЗАПИСАНО.')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
