import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g0e7acc4d'

OLD_CONTEXT = (
    'Компания перешла под контроль холдинга через ООО «Завод Техно», '
    'которое принадлежит одному из основателей «Технониколь» Игорю '
    'Рыбакову. Об этом стало известно в конце сентября 2025 года. Как '
    'сообщает «Коммерсантъ», смена собственника ООО ТД ЛТМ '
    'зарегистрирована 17 сентября 2025 года. Ранее компанией на '
    'паритетных началах владели Сергей Зубков и Алексей Лабутин.'
)
ADDITION = (
    'Сделка включает обязательства по модернизации и наращиванию '
    'мощностей на 50%, обновлению складской инфраструктуры, оптимизации '
    'логистики и системы обращения с отходами; на этапе перехода '
    'продукция выпускается под прежним брендом, позднее — под маркой '
    '«Технониколь». Спустя полгода, в апреле 2026 года, «Технониколь» '
    'сообщила об итогах: инвестиции в модернизацию завода в Рузе '
    'составили 15 млн руб. (новые станки нанесения грунта, заменена '
    'сушильная печь, внедрены принципы бережливого производства 5S), '
    'завод подписал государственный контракт с Московским фондом '
    'капитального ремонта и полностью закроет необходимый объём плит '
    'для реновации в Москве и Подмосковье.'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} eco.context: += обязательства сделки, итог модернизации (апрель 2026)")
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
