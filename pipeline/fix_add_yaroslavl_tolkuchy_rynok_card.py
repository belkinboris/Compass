"""Приток, 12:20 МСК 30 сентября 2026: АБН24 (со ссылкой на «Коммерсантъ»)
сообщил, что в Ярославле сорвался аукцион по продаже помещений в здании
«Новообщественный ряд толкучего рынка» (объект культурного наследия,
ул. Андропова) — заявок не подано ни одной. Помещения конфискованы у
предпринимателя Максима Каткова после обрушения 2022 года (незаконное
заглубление подвала привело к обрушению лестниц, перекрытий и фасадной
стены, погиб рабочий). Ворота не пропустили черновик автоматически.
Собрал вручную, тот же класс случая, что карточки Боброва и
«Великоленского».

Саб-агент независимого подтверждения почти не нашёл: похожее обрушение в
центре Ярославля в марте 2022 года есть в bfm.ru, но на ДРУГОЙ улице
(Депутатская, а не Андропова) и без имени Каткова — это может быть тот же
случай (совпадает механизм: заглубление подвала, один погибший), а может и
не быть; оригинал статьи «Коммерсанта» не нашёлся. Поэтому это совпадение
в карточку НЕ вношу — только то, что дословно есть в привязанном
источнике. Источник единственный (АБН24) — `--mark-read`, не `--mark-deep`.

Запуск: python3 pipeline/fix_add_yaroslavl_tolkuchy_rynok_card.py [--write]
"""
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'ingest'))

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')


def main(write=False):
    import promote

    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    ids = {c['id'] for c in data['deals']}
    new_id = promote.new_id(ids)

    draft = {
        'date': '2026-09-30',
        'title': 'Аукцион по продаже конфискованных у бизнесмена помещений в Ярославле не состоялся',
        'ind': 'Недвижимость',
        'type': 'Продажа с торгов',
        'status': 'Не состоялась',
        'sum': '51,8 млн ₽',
        'seller': 'Максим Катков (имущество конфисковано)',
        'asset': 'помещения (556 м²) в здании «Новообщественный ряд толкучего рынка» на ул. Андропова в Ярославле',
        'src': [['АБН24', 'https://abnews.ru/center/news/yaroslavl/2026/9/30/v-yaroslavle-ne-smogli-prodat-obrushivshijsya-pamyatnik-arhitektury']],
        'events': [
            {'kind': 'cancelled', 'date': '2026-09-30', 'title': 'Торги признаны несостоявшимися',
             'note': 'На участие в аукционе не поступило ни одной заявки.',
             'source': ['АБН24', 'https://abnews.ru/center/news/yaroslavl/2026/9/30/v-yaroslavle-ne-smogli-prodat-obrushivshijsya-pamyatnik-arhitektury']},
        ],
    }
    card = promote.to_card(draft, new_id)
    card['eco']['sum'] = draft['sum']
    card['eco']['context'] = (
        'Здание имеет статус объекта культурного наследия. На торги выставлялись '
        'подвальные помещения и площади на первом и втором этажах. Помещения '
        'конфискованы после трагедии 2022 года: незаконное заглубление подвала '
        'привело к обрушению лестничных пролётов, перекрытий и фасадной стены, погиб '
        'рабочий. В документации к аукциону отдельно указана стоимость восстановления: '
        'на реставрацию и ремонт потенциальному покупателю потребовалось бы '
        'дополнительно вложить 4,4 млн ₽.'
    )
    card['themes'] = ['Продажа с торгов', 'Недвижимость']
    # `to_card` не ставит `added` — обычно его ставит `approve.py` при выводе
    # карточки из pending.json; прямая запись минует этот путь, дата не
    # выдумана — карточка правда добавлена сегодня.
    card['added'] = '2026-09-30'

    data['deals'].append(card)
    print('Добавлена карточка %s: %s' % (new_id, card['title']))

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
