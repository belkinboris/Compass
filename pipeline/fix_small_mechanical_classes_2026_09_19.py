# -*- coding: utf-8 -*-
"""Живой скан `accept_card.findings()` по ВСЕЙ базе (не только очереди приёмки)
19 сентября 2026 нашёл несколько уже механически распознаваемых дефектов на
СТАРЫХ карточках — те же проверки, что `accept_card.py` ставит на входе
новым карточкам, никогда не прогонялись по базе целиком. Здесь — только
безопасные, чисто механические случаи (без догадки, без чтения источника):

  * `duplicate_text` — `extra` дословно повторяет другое поле без нового
    факта (известный класс, см. CLAUDE.md «Счётчик заполненных полей легко
    накрутить»): `extra` очищается, факт остаётся в исходном поле.
  * `straight_quotes` — прямые кавычки вместо «»: `drafter.normalize_quotes`
    (тот же преобразователь, что `review.check()` уже предлагает как
    исправление для НОВЫХ правок).
  * `tadviser_markup` — служебная вики-разметка TAdviser («История NNNN: »
    повтор заголовка, инлайновые "Компания:"/"Персона:" перед именем)
    просочилась в `events[].note`. Здесь снят не только распознаваемый
    регэкспом префикс `История NNNN: `, но и соседние с ним инлайн-метки —
    проверено вручную по каждой карточке: под меткой всегда стоит то же имя,
    что уже названо в предложении, факт не меняется, только убирается
    вики-глюк источника.

НЕ включены в этот скрипт (осознанно, требуют чтения источника, не формы):
`target_fin_prose` (3 карточки — описание вместо цифр, дописать числа можно
только источником), `why` (1 карточка — «Цель сделки» с оценки рынка вместо
мотива, нужно найти в источнике предложение о мотиве), `stale_statement`
(g79f683bc — уже известное, верное исключение, см.
CARD_ACCEPTANCE_BRIEF.md; gfcfba8c9 — статус «Закрыта», но law.struct
описывает спор по одному из двух объектов лота, нужно перечитать источник,
что стало со зданием в Сургуте).

Запуск:
    python3 pipeline/fix_small_mechanical_classes_2026_09_19.py            # сухой прогон
    python3 pipeline/fix_small_mechanical_classes_2026_09_19.py --write
"""
import json
import sys

sys.path.insert(0, 'pipeline/ingest')
import draft as drafter  # noqa: E402

PATH = 'static/data/deals_promoted.json'


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deals = {d['id']: d for d in data['deals']}
    changes = []

    d = deals['c59e65efb']
    old = 'Российский миллиардер Роман Абрамович через инвестиционный фонд Target Global вложил свыше $63 млн в европейские технологические стартапы, среди которых — Auto1, Flo, Revolut, Cazoo, Circ и др.'
    assert d.get('extra') == old, 'c59e65efb/extra уже другое'
    assert d.get('eco', {}).get('share') == old, 'c59e65efb/eco.share изменилось — дубль уже не дословный'
    changes.append((d, ('extra',), old, None))

    d = deals['c71e19cc1']
    old = ('Gunvor пытался купить международные активы «Лукойла» — зарубежную добычу, ключевые НПЗ в Европе '
           'и сеть АЗС. Под сделку компания привлекала финансирование в $2,81 млрд от американских '
           'подразделений мировых банков. После недели переговоров с OFAC Gunvor отказался от сделки: '
           'Минфин США назвал компанию «марионеткой Кремля» и отказал в лицензии.')
    assert d.get('extra') == old, 'c71e19cc1/extra уже другое'
    assert d.get('eco', {}).get('context') == old, 'c71e19cc1/eco.context изменилось — дубль уже не дословный'
    changes.append((d, ('extra',), old, None))

    d = deals['cf2375bf5']
    old = 'Группа компаний ПАО «ГК "Самолет"»'
    assert d.get('seller') == old, 'cf2375bf5/seller уже другое: %r' % d.get('seller')
    new = drafter.normalize_quotes(old)
    assert '"' not in new
    changes.append((d, ('seller',), old, new))

    d = deals['gc5951fac']
    old = ('История 2026: Владельцы логистической платформы ATI.SU купили CARGO.RUN В августе 2026 года '
           'стало известно о том, что совладельцы цифровой логистической площадки Компания:ATI.SU, АТИ.СУ '
           '(ранее АвтоТрансИнфо), Персона:Вильде Святослав Вольдемарович и Олег Круглов, стали владельцами '
           '25-процентной доли в компании «Цифровизация Транспорт», которая развивает сервис CARGO.RUN для '
           'управления грузоперевозками и автопарками.')
    assert d['events'][0]['note'] == old, 'gc5951fac/events[0].note уже другое'
    new = ('В августе 2026 года стало известно о том, что совладельцы цифровой логистической площадки '
           'ATI.SU, АТИ.СУ (ранее АвтоТрансИнфо), Вильде Святослав Вольдемарович и Олег Круглов, стали '
           'владельцами 25-процентной доли в компании «Цифровизация Транспорт», которая развивает сервис '
           'CARGO.RUN для управления грузоперевозками и автопарками.')
    changes.append((d['events'][0], ('note',), old, new))

    d = deals['gac1a0c11']
    old = ('История 2026: Совладелец R-Vision купил долю в Sentra В начале августа 2026 года стало '
           'известно о том, что сооснователь российского разработчика ИБ-продуктов Компания:R-Vision '
           '(Р-Вижн) Персона:Сметанев Игорь Михайлович приобрел долю в российском стартапе Sentra '
           '(ООО «Защищенные системы»).')
    assert d['events'][0]['note'] == old, 'gac1a0c11/events[0].note уже другое'
    new = ('В начале августа 2026 года стало известно о том, что сооснователь российского разработчика '
           'ИБ-продуктов R-Vision (Р-Вижн) Сметанев Игорь Михайлович приобрел долю в российском стартапе '
           'Sentra (ООО «Защищенные системы»).')
    changes.append((d['events'][0], ('note',), old, new))

    d = deals['gb0f1f736']
    old = ('История 2026: «Альфа-Банк» купил WhoIsBlogger В сентябре 2026 года «Альфа-Банк» объявил о '
           'приобретении платформы WhoIsBlogger (юрлицо - «Даблюайби»), специализирующейся на аналитике и '
           'подборе блогеров. Сделка была закрыта в рамках стратегии развития…')
    assert d['events'][1]['note'] == old, 'gb0f1f736/events[1].note уже другое'
    new = ('В сентябре 2026 года «Альфа-Банк» объявил о приобретении платформы WhoIsBlogger (юрлицо - '
           '«Даблюайби»), специализирующейся на аналитике и подборе блогеров. Сделка была закрыта в рамках '
           'стратегии развития…')
    changes.append((d['events'][1], ('note',), old, new))

    print('ПРАВКИ (%d):' % len(changes))
    for obj, path, old, new in changes:
        label = obj.get('id') or '<events[i]>'
        print('  %s %s' % (label, '.'.join(path)))
        print('    было: %r' % (old,))
        print('    стало: %r' % (new,))
        if write:
            target = obj
            for p in path[:-1]:
                target = target.setdefault(p, {})
            if new is None:
                target.pop(path[-1], None)
            else:
                target[path[-1]] = new

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=1, ensure_ascii=False)
        print('\nЗАПИСАНО в', PATH)
    else:
        print('\nСУХОЙ ПРОГОН — для записи добавьте --write')
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
