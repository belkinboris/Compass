# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
geda130b6 (Артём Чайка приобрёл 49% основного юрлица 3S Group,
28.12.2023, статус «Закрыта») — консолидация продолжилась: Чайка
довёл долю до 99%, Сеюков полностью вышел, а сам Чайка попал под
санкции Великобритании (за другой, непрофильный актив).

Проверено лично прямым WebFetch (Коммерсантъ, 20.05.2024,
doc/6712251): «Руслан Сеюков намерен выйти из основанной им
девелоперской компании 3S Group. По информации "Ъ", его доля перейдет
другим учредителям — сыну экс-генпрокурора РФ Юрия Чайки Артему и
Александру Китаеву». По данным саб-агента (ЕРЗ.РФ, 10.06.2024, и
ABN, 05.06.2024, не дозаверено отдельным WebFetch, но текст статьи
Коммерсанта не противоречит и предшествует): в июне 2024 Чайка выкупил
оставшиеся 50% у Сеюкова, доведя долю до 99% (1% остался у Китаева).

Санкции — по данным саб-агента (Ведомости, 14.02.2025, не дозаверено
отдельным WebFetch): Великобритания ввела ограничения против Чайки
как главы «Нерудной компании Бердяуш» — старый непрофильный актив
(щебёночный бизнес), не связанный с 3S Group.

НЕ ВКЛЮЧЕНО: масштаб текущих проектов 3S Group (119 тыс. кв. м в
стройке, отказ от прав на ТРЦ у Кленового бульвара, Ведомости
29.04.2026) — по данным саб-агента, не дозаверено отдельным WebFetch
в этом заходе; предполагаемые санкции Канады — саб-агент прямо
отметил, что дословного первоисточника не нашёл (только пересказ в
Википедии), в базу не идёт.

Запуск: python3 pipeline/fix_chaika_3s_group_full_consolidation.py
        python3 pipeline/fix_chaika_3s_group_full_consolidation.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'geda130b6'

OLD_EXTRA = (
    'Артём Чайка получил 49% в компаниях-разработчиках 3S Group '
    '(«Три эс девелопмент», «Три эс групп», «Три эс проект»). Ранее '
    'он владел такой же долей до 2020 года, затем передал её '
    'партнёрам Руслану Сеюкову и Александру Китаеву. В конце декабря '
    '2023 г. доля возвращена Чайке.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Консолидация продолжилась: в июне 2024 года Чайка выкупил у '
    'Руслана Сеюкова оставшиеся 50%, доведя свою долю до 99% (1% '
    'остался у Александра Китаева) — Сеюков полностью вышел из '
    'компании. В феврале 2025 года Великобритания ввела санкции '
    'против Чайки как главы «Нерудной компании Бердяуш» — старого, '
    'не связанного с 3S Group непрофильного актива.'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6712251'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
