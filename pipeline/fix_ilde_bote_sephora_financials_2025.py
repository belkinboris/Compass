import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g0e8b9617'

OLD_ECO_CONTEXT = 'По неофициальным данным, сделка была завершена 7 октября.'
NEW_ECO_CONTEXT = (
    'Сделка закрылась 7 октября 2022 года — это подтверждают независимо '
    'друг от друга несколько изданий, а не только неофициальные данные. '
    'Сеть не переименовывалась: она вернулась к своему прежнему имени '
    '«Иль де Ботэ», под которым работала до ребрендинга в Sephora. После '
    'сделки сеть два года была убыточной (убыток 1,5 млрд ₽ в 2023 году), '
    'а в 2024 году впервые вышла в прибыль — 1 млрд ₽ при выручке 8,23 '
    'млрд ₽ (падение выручки на 5% к предыдущему году). К июлю 2025 года '
    'у сети было более 60 магазинов в 25 городах России, и она просила '
    'торговые центры снизить арендные ставки почти вдвое. С мая 2025 '
    'года операционное управление передано ООО «Иль-Де Ботэ '
    'Менеджмент», единственным владельцем остаётся Евгений Дроздов '
    '(100% доли).'
)

OLD_SRC = [['Ведомости', 'https://www.vedomosti.ru/business/news/2023/01/27/960637-lvmh-otsenila-ubitki']]
NEW_SRC = OLD_SRC + [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/5606517'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/7872221'],
    ['Retail.ru', 'https://www.retail.ru/rbc/tradingnetworks/il_de_bote/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
