import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g551049ec'

OLD_DATE = '2022-10-01'
NEW_DATE = '2023-04-21'

OLD_SUM = '1,8–2 млрд $'
NEW_SUM = '$702,5 млн'

OLD_ECO_SUM = '$1,8–2 млрд'
NEW_ECO_SUM = '$702,5 млн'

OLD_EXTRA = (
    'Яндекс выкупил у Uber 29% в голландской компании MLU B.V., которая '
    'управляет такси-бизнесом под брендами Яндекс.Такси, Yango и Uber в '
    'России и СНГ. Компания воспользовалась правом преимущественного '
    'выкупа и заплатит небольшую премию к альтернативному предложению '
    'Kismet Capital Group.'
)
NEW_EXTRA = (
    'Яндекс выкупил у Uber оставшуюся долю в голландской компании MLU '
    'B.V., которая управляет такси-бизнесом под брендами Яндекс.Такси, '
    'Yango и Uber в России и СНГ, и стал единственным владельцем '
    'совместного предприятия. Сделка закрылась не реализацией опциона '
    '2021 года (право выкупа по нему стоило $1,8–2 млрд и действовало '
    'до сентября 2023 года), а отдельным соглашением — и по более '
    'низкой цене, чем обе прежние оценки.'
)

OLD_ECO_CONTEXT = '—'
NEW_ECO_CONTEXT = (
    'В 2021 году, реструктурируя совместный бизнес с Uber, Яндекс '
    'получил право выкупить оставшуюся долю партнёра в MLU B.V. до '
    'сентября 2023 года за $1,8–2 млрд. В декабре 2022 года структура '
    'Ивана Таврина Kismet Capital Group предложила Uber за эту долю '
    '$925 млн — это подтолкнуло цену вверх. В итоге сделка была '
    'закрыта не реализацией опциона, а отдельным соглашением — и по '
    'более низкой цене, чем обе прежние оценки: $702,5 млн.'
)

OLD_SRC = [['Forbes', 'https://www.forbes.ru/tekhnologii/484583-andeks-vykupit-dolu-uber-v-sovmestnom-predpriatii']]
NEW_SRC = OLD_SRC + [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/5951573'],
    ['Интерфакс', 'https://www.interfax.ru/business/897186'],
    ['Интерфакс', 'https://www.interfax.ru/business/802235'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['date'] == OLD_DATE
    assert deal['sum'] == OLD_SUM
    assert deal['eco']['sum'] == OLD_ECO_SUM
    assert deal['extra'] == OLD_EXTRA
    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== date/sum/eco.sum: станет ===')
    print(NEW_DATE, '|', NEW_SUM, '|', NEW_ECO_SUM)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['date'] = NEW_DATE
        deal['sum'] = NEW_SUM
        deal['eco']['sum'] = NEW_ECO_SUM
        deal['extra'] = NEW_EXTRA
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
