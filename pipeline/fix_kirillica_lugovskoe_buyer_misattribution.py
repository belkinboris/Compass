# -*- coding: utf-8 -*-
"""ПОЛОМКА, найденная health-check'ом (проверка страницы компании g308a4b2a,
«ГАП «Ресурс»»): в списке «Другие сделки» у агропромышленной группы (мясо
птицы, комбикорм) висела карточка g670ed747 — «ГК «Кириллица» (ООО «Оил
Ресурс Добыча») купила Луговское нефтегазовое месторождение». `buyer` этой
карточки указывал на g308a4b2a, хотя источник (kommersant.ru/doc/8689315,
проверено лично прямым WebFetch) называет покупателем СОВСЕМ ДРУГУЮ
компанию: «дочерняя компания ГК «Кириллица» «Оил ресурс добыча»» — группу,
которая «занимается оптовой торговлей нефтью и нефтепродуктами,
нефтесервисом, а также реализует проекты в сфере АПК, внутрироссийской и
международной логистики, редкоземельных металлов и наукоемкого
машиностроения», гендиректор Семён Гарагуль. Ничего общего с
птицеводческим холдингом «ГАП «Ресурс»», кроме слова «Ресурс» в названии
дочерней структуры покупателя.

Корень найден: `match_keys['g308a4b2a'] = ['гап ресурс', 'ресурс']` — сам
по себе честный алиас (это правда часть названия «ГАП «Ресурс»»), но
опасно общий: любая другая компания со словом «Ресурс» в имени при
сопоставлении на притоке рискует задвоиться на этот профиль. Измерено по
всей базе: из 9 карточек, ссылающихся на g308a4b2a, ошибочна ровно ОДНА
(g670ed747) — остальные восемь подлинные сделки «ГАП «Ресурс»» (Granmulino,
Кропоткинский элеватор, «Рубеж», Миллеровский элеватор и т.д.), то есть
это не системный дефект, а один разовый промах сопоставления, и матч-кей
«ресурс» не тронут (сузить его без замера остальных 1560+ карточек было бы
риском обратного дефекта — потерять правильные будущие совпадения).

Заведён отдельный профиль «ГК «Кириллица»», `buyer` карточки g670ed747
переключен на него.

Запуск:
    python3 pipeline/fix_kirillica_lugovskoe_buyer_misattribution.py
    python3 pipeline/fix_kirillica_lugovskoe_buyer_misattribution.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g670ed747'
OLD_BUYER = 'g308a4b2a'
NEW_BUYER_ID = 'gkirillicagroup1'

NEW_COMPANY = {
    'name': 'ГК «Кириллица»',
    'ind': 'Нефть и газ',
    'desc': ('Российская группа компаний: оптовая торговля нефтью и '
             'нефтепродуктами, нефтесервис, а также проекты в сфере АПК, '
             'внутрироссийской и международной логистики, редкоземельных '
             'металлов и наукоёмкого машиностроения. Покупки оформляются '
             'через дочерние структуры (например, ООО «Оил Ресурс '
             'Добыча»).'),
    'kpi': ['Профиль', 'Автоматический'],
}


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['buyer'] == OLD_BUYER, 'buyer уже другой — уже правили?'
    assert NEW_BUYER_ID not in data['companies'], 'профиль уже существует'

    print(f'{DEAL_ID}: buyer {OLD_BUYER} ("ГАП «Ресурс»", агро) -> '
          f'{NEW_BUYER_ID} ("ГК «Кириллица»", нефть и газ)')

    if write:
        data['companies'][NEW_BUYER_ID] = dict(NEW_COMPANY)
        deal['buyer'] = NEW_BUYER_ID
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
