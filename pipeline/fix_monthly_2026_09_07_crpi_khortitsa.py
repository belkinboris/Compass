def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    crpi = by_id[CRPI_ID]
    kh = by_id[KH_ID]

    assert crpi['eco']['context'] == CRPI_OLD_CONTEXT
    assert kh['eco']['context'] == KH_OLD_CONTEXT
    assert kh['law']['terms'] == KH_OLD_TERMS

    print('=== g6e1bb001: eco.context ===')
    print(CRPI_NEW_CONTEXT)
    print()
    print('=== g01e3fd26: eco.context ===')
    print(KH_NEW_CONTEXT)
    print()
    print('=== g01e3fd26: law.terms ===')
    print(KH_NEW_TERMS)

    if write:
        crpi['eco']['context'] = CRPI_NEW_CONTEXT
        kh['eco']['context'] = KH_NEW_CONTEXT
        kh['law']['terms'] = KH_NEW_TERMS
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
