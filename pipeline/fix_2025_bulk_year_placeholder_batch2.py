# -*- coding: utf-8 -*-
"""Четыре карточки несли год-заглушку («2025», без месяца и дня), а
источники называют другой год — три 2026-й, одна 2024-й.

ЧТО СЛОМАНО. Тот же класс дефекта, что уже чинил
`fix_2025_bulk_year_placeholder.py`: компактный импорт поставил год без
подтверждения, а при дочитывании очереди 2025 года источники оказались
статьями, точно датированными другим годом.

  - g9d9e7ab6 (ГК «Астра»/стратегический инвестор, «Росатом»): pro.rbc.ru
    датирует материал «Опубликовано 19.01.2026, 10:40».
  - ga971155a (розничная сеть «Гулливер»): kommersant.ru — «22.01.2026,
    07:00». У этой же карточки — второй, независимый дефект: `eco.rationale`
    приписывал «Гулливеру» финансовые показатели ООО «ТК ЛЕТО» (114 млрд
    руб. выручки), хотя по тексту источника ООО «ТК Лето» — операционное
    юрлицо СОСЕДНЕЙ сети группы, дискаунтера «Победа», а не самого
    «Гулливера» (у которого отдельное юрлицо АО «Гулливер» с выручкой
    20,3 млрд руб.). Число верное, но относится не к тому предмету — тот
    же класс, что уже описан в CLAUDE.md («Разбор источника доверяет числу
    из чужого абзаца», «Число может быть верным фактом и совсем не той
    величиной»). Правка `eco.rationale` идёт через review.py (см. FIXES
    партии 31), а не через этот скрипт — здесь только год.
  - gd2196acd (Совкомбанк/«Рокет», бывший Рокетбанк): kommersant.ru — статья
    «Совкомбанк возродит Рокетбанк» датирована «15.11.2024, 01:27» — год
    ещё РАНЬШЕ, не позже: карточка на самом деле из 2024 года.
  - gd2696c44 (Tutu.ru/Trivio): iz.ru — метатег публикации
    «2026-01-20T00:40:00+03:00», в подписи «20 января 2026, 00:40».

ПОЧЕМУ НЕ ЧЕРЕЗ `review.py`. `date_is_supported()` намеренно запрещает
менять год — перенос года обязан быть отдельным, явным решением с
проверяемым источником, а не автоматической правкой в общей таблице.

Все четыре карточки этим переносом выходят из среза 2025 года.

Запуск:
    python3 pipeline/fix_2025_bulk_year_placeholder_batch2.py            # сухой прогон
    python3 pipeline/fix_2025_bulk_year_placeholder_batch2.py --write    # записать
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

FIXES = [
    dict(id='g9d9e7ab6', old_date='2025', new_date='2026-01-19',
         quote='pro.rbc.ru: «Опубликовано 19.01.2026, 10:40»'),
    dict(id='ga971155a', old_date='2025', new_date='2026-01-22',
         quote='kommersant.ru датирует материал «22.01.2026, 07:00»'),
    dict(id='gd2196acd', old_date='2025', new_date='2024-11-15',
         quote='kommersant.ru: «Совкомбанк возродит Рокетбанк», датирована '
               '«15.11.2024, 01:27»'),
    dict(id='gd2696c44', old_date='2025', new_date='2026-01-20',
         quote='iz.ru: метатег публикации «2026-01-20T00:40:00+03:00», '
               'в подписи «20 января 2026, 00:40»'),
]


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}

    for fix in FIXES:
        deal = by_id.get(fix['id'])
        assert deal is not None, 'нет сделки %s' % fix['id']
        assert deal.get('date') == fix['old_date'], \
            '%s: дата уже другая: %r, ожидали %r' % (
                fix['id'], deal.get('date'), fix['old_date'])
        print('%s: date %r -> %r' % (fix['id'], fix['old_date'], fix['new_date']))
        print('  цитата: %r' % fix['quote'])

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    for fix in FIXES:
        by_id[fix['id']]['date'] = fix['new_date']

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
