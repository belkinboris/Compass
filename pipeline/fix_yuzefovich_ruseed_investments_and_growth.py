import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g6783c136'

NEW_EXTRA = (
    'Покупатель Иван Юзефович — партнёр Искандара Махмудова по '
    'агробизнесу (владеет 30% ООО «Группа КМ», контролируемой '
    'Махмудовым; структура Юзефовича также владеет агрохолдингом «АФГ '
    'Националь», отдельным от Ruseed). Часть заявленных инвестиций '
    'реализована: в сентябре 2024 открыта первая очередь '
    'селекционно-семеноводческого центра в Адыгее (мощность до 10 тыс. '
    'т семян подсолнечника в год — четверть всего высеваемого объёма '
    'в стране), позже начато строительство агробиотехнопарка (900 '
    'млн ₽). Компания быстро растёт: по словам управляющего партнёра '
    'Марка Гехта, за пять лет производство семян выросло в 30 раз.'
)

NEW_SRC = [
    ['Агроинвестор', 'https://www.agroinvestor.ru/companies/news/43000-ruseed-otkryla-pervuyu-ochered-selektsionno-semenovodcheskogo-tsentra/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal.get('extra') in (None, '')

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
