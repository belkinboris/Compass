# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
`g3e3f5e9c` («Крост» выкупил завод железобетонных панелей КПСК у
СУ-155», закрыта, только год) — точная дата уже была в тексте
карточки, но не в поле `date`; дочитывание нашло продолжение сюжета —
завод переименован и модернизируется под новым владельцем.

Проверено (по докладу саб-агента, дословные цитаты):
- kommersant.ru/doc/5985465 (источник карточки, перепрочитан
  полностью): «завод по выпуску железобетонных панелей, позволяющий
  строить 300 тыс. кв. м жилья в год»; на рынке допускают, что
  большую часть продукции девелопер направит на проекты, связанные с
  реновацией в Москве (мнение аналитиков, не заявление сторон).
- vmo24.ru/news/zavod_zhbi_klin_voshedshiy_v_koncern_krost_ozhidaet_
  masshtabnaya_modernizaciya (23.08.2023): «Завод ЖБИ Клин» (новое имя
  бывшего КПСК) стал «23-м предприятием, вошедшим в концерн «КРОСТ»»;
  «здесь занято уже более 250 человек»; завод ожидает модернизацию —
  реконструкция и расширение цеха в ближайшие полтора года, обновление
  социальной инфраструктуры для сотрудников (бассейн, общежитие,
  столовая) — со слов замгендиректора концерна Андрея Сазонова.

НЕ ВНЕСЕНО: (1) точная дата закрытия сделки — известна только дата
обнародования договора на Федресурсе (11 мая 2023 года), сама
страница Федресурса не читается инструментом (JS-рендер), день
регистрации перехода прав отдельно не подтверждён — `date` не
меняется; (2) штат и выручка самого завода НА МОМЕНТ ПРОДАЖИ (эти 250+
сотрудников — уже после присоединения к «Кросту») — источник о
продаже эту цифру не называет; (3) торги или прямая продажа
конкурсным управляющим, имя управляющего — ни один источник не
подтверждает и не опровергает (документ просто «обнародован» на
Федресурсе); (4) фактический запуск обновлённого производства и
конкретные проекты потребления продукции в 2024-2026 годах — свежих
публикаций после августа 2023 года не нашлось.

Запуск: python3 pipeline/fix_krost_kpsk_fullscan.py
        python3 pipeline/fix_krost_kpsk_fullscan.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g3e3f5e9c'

OLD_ECO_TARGET_FIN = '—'
NEW_ECO_TARGET_FIN = (
    'Завод способен выпускать панели для строительства до 300 тыс. '
    'кв. м жилья в год.'
)

OLD_LAW_STRUCT = (
    '11 мая 2023 года был обнародован договор купли-продажи имущества '
    'АО «Клинский проектно-строительный комбинат», входившего в '
    'группу СУ-155. По договору активы проданы ООО «Энки» за 431 млн '
    '₽. Новый владелец завода связан с концерном «Крост» Алексея '
    'Добашина.'
)
NEW_LAW_STRUCT = (
    OLD_LAW_STRUCT + ' Завод переименован в «Завод ЖБИ Клин» и стал '
    '23-м предприятием концерна «Крост».'
)

OLD_ECO_CONTEXT = (
    'Активы группы, объединявшей более 80 предприятий, выкупают '
    'другие игроки. Годом ранее Серпуховский лифтостроительный завод '
    'купили структуры, связанные с ГК «Садовое кольцо», которая '
    'строит жильё в Татарстане, Башкортостане и Подмосковье.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' К августу 2023 года на заводе работало более '
    '250 человек; «Крост» объявил о модернизации — реконструкции и '
    'расширении цеха в ближайшие полтора года, а также обновлении '
    'социальной инфраструктуры для сотрудников.'
)

OLD_SRC = [['Коммерсантъ', 'https://www.kommersant.ru/doc/5985465']]
NEW_SRC = OLD_SRC + [
    ['ВМО24', 'https://vmo24.ru/news/zavod_zhbi_klin_voshedshiy_v_koncern_krost_ozhidaet_masshtabnaya_modernizaciya'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['target_fin'] == OLD_ECO_TARGET_FIN
    assert deal['law']['struct'] == OLD_LAW_STRUCT
    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== eco.target_fin: станет ===')
    print(NEW_ECO_TARGET_FIN)
    print('\n=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['eco']['target_fin'] = NEW_ECO_TARGET_FIN
        deal['law']['struct'] = NEW_LAW_STRUCT
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
