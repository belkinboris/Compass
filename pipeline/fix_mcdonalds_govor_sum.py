# -*- coding: utf-8 -*-
"""У карточки `g9dd54742` («Продажа российского бизнеса McDonald's...
франчайзи Александру Говору») `sum`/`eco.sum` несли «$1,2 млрд» — но
собственное поле `extra` этой же карточки честно объясняет, откуда это
число: «McDonald's списал $1,2 млрд до налогообложения» — это
БУХГАЛТЕРСКОЕ СПИСАНИЕ (обесценение активов при выходе), а не цена,
уплаченная Говором. Источник (Интерфакс) называет его именно так:
«сократила чистую прибыль... списав $1,2 млрд в связи с продажей
российского бизнеса» — глагол «списав», а не «продав за». Независимая
проверка живым поиском (Интерфакс-Россия, «Коммерсантъ», РБК) подтверждает:
реальная цена сделки не раскрыта, Говор публично называл её «символической
платой» много ниже рыночной стоимости и отказался уточнить, «стоила ли
сделка 1 руб., доллар или евро», сославшись на соглашение о
неразглашении. Родня уже записанного класса уроков «число может быть
верным фактом и совсем не той величиной» (Арнест/Reckitt — убыток продавца
вместо цены актива).

Почему не через review.py: `sum_is_supported()` подтвердил бы обратное —
$1,2 млрд дословно лежит в кэшированном источнике, но именно ПОЭТОМУ
механическая проверка не спасает от этой ошибки: дословность есть, а
величина не та. Значение — не оценка, а фактическое списание, поэтому
пометка «(по оценке)» тоже не подходит; честная замена — «Не раскрыта».

Запуск: python3 pipeline/fix_mcdonalds_govor_sum.py
        python3 pipeline/fix_mcdonalds_govor_sum.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.join(os.path.dirname(ROOT), 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g9dd54742'
OLD_SUM = '$1,2 млрд'
NEW_SUM = 'Не раскрыта'
NEW_ECO_VAL = (
    'Александр Говор публично называл цену сделки «символической платой», '
    'значительно ниже рыночной стоимости бизнеса, и отказался уточнить, '
    'составляла ли она 1 рубль, доллар или евро, сославшись на соглашение '
    'о неразглашении. $1,2 млрд, которые упоминаются в связи со сделкой, — '
    'это списание McDonald\'s Corp. по итогам II квартала 2022 года при '
    'выходе из России (бухгалтерское обесценение), а не цена, уплаченная '
    'покупателем. (Источник: обогащение/веб-поиск — Интерфакс-Россия, '
    '«Коммерсантъ».)'
)


def main(write=False):
    data = json.load(open(BASE, encoding='utf-8'))
    card = next(d for d in data['deals'] if d['id'] == CARD_ID)
    if card['sum'] == NEW_SUM and card['eco']['sum'] == NEW_SUM:
        print('УЖЕ ПРИМЕНЕНО %s' % CARD_ID)
        return
    assert card['sum'] == OLD_SUM, '%s: sum уже другой' % CARD_ID
    assert card['eco']['sum'] == OLD_SUM, '%s: eco.sum уже другой' % CARD_ID
    assert card['eco']['val'] == '—', '%s: eco.val уже не пуст' % CARD_ID
    print('ПРАВИМ  %s sum и eco.sum: «%s» -> «%s» (это списание McDonald\'s, '
          'а не цена сделки); заполняю eco.val' % (CARD_ID, OLD_SUM, NEW_SUM))
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return
    card['sum'] = NEW_SUM
    card['eco']['sum'] = NEW_SUM
    card['eco']['val'] = NEW_ECO_VAL
    json.dump(data, open(BASE, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
