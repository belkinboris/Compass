# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка gf63744d6 (Газпромбанк через
АО «ААА Управление Капиталом» купил 22% ПАО «Южуралзолото», декабрь 2024):
дельта-поиск нашёл прямую связь с делом о национализации ЮГК 2025 года —
пакет Газпромбанка НЕ вошёл в периметр изъятия. Иск Генпрокуратуры (июль
2025) касался только личных акций основателя Константина Струкова (67,85%)
и 100% УК ЮГК — доля Газпромбанка не упоминается среди арестованного
имущества (подтверждено дословной цитатой «Ведомостей»). После национализации
и продажи доли Струкова на торгах структуре Руслана Байсарова («БТС-Мост
Холдинг», июнь 2026, компания переименована в «БТС-Золото») новый мажоритарий
направил в Банк России оферту миноритариям на 32,8% акций — это именно доля
Газпромбанка (22%) плюс свободное обращение (~10,5%): пакет банка уцелел как
миноритарный и стал предметом отдельного тендерного предложения. Поле было
прочерком — не через review.py: факты из НЕСКОЛЬКИХ новых источников,
образующих связный сюжет (арест → продажа доли Струкова → оферта
миноритариям), а не одну дословную вставку в существующий текст.

Запуск: python3 pipeline/fix_ygk_gazprombank_stake_survived_nationalization_context.py
        python3 pipeline/fix_ygk_gazprombank_stake_survived_nationalization_context.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gf63744d6'

OLD_CONTEXT = '—'
NEW_CONTEXT = (
    'Пакет Газпромбанка не вошёл в периметр национализации ЮГК 2025 года: '
    'иск Генпрокуратуры (июль 2025) касался только личных акций основателя '
    'Константина Струкова и 100% управляющей компании ЮГК — «в их числе все '
    'принадлежащие Струкову акции в ПАО «Южуралзолото группа компаний» и '
    '100% ООО «Управляющая компания ЮГК»» (Ведомости), доля Газпромбанка '
    'среди арестованного не упоминается. После национализации акции '
    'Струкова (67,85%) проданы на торгах в июне 2026 года структуре Руслана '
    'Байсарова «БТС-Мост Холдинг», компания переименована в «БТС-Золото». '
    'В 2026 году «БТС-Мост Холдинг» направил в Банк России оферту '
    'миноритариям — «оферта касается 32,8% бумаг компании» (Коммерсантъ), '
    'что соответствует доле Газпромбанка (22%) и свободному обращению '
    '(~10,5%): пакет банка сохранился как миноритарный.'
)

NEW_SRC = [
    ['Ведомости', 'https://www.vedomosti.ru/society/articles/2025/07/04/1122039-kak-aktivi-yuzhuralzolota-okazalis-pod-arestom'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8859999'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
