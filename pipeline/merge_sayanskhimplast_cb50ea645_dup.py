# -*- coding: utf-8 -*-
"""Месячная очередь, 8 сентября 2026 — карточка `cb50ea645» («Продажа
имущества АО «Саянскхимпласт» и дочерних компаний на аукционе ПСБ»,
добавлена 2026-08-03) оказалась ДУБЛЕМ уже существующей, гораздо более
полной карточки `gcc232775» («Роснефть выкупила Саянскхимпласт на торгах
за 30,3 млрд рублей», добавлена 2026-07-15, уже вычитана, уже несёт
followup_researched от 16 августа): одна и та же дата (2026-04-13), одна
и та же сумма (30,33 млрд ₽), один и тот же покупатель (РН-Коммерция /
Роснефть) и один и тот же лот (Саянскхимпласт + 4 аффилированные
структуры). Ни один сканер дублей это не поймал — заголовки не совпадают
буквально («Продажа имущества...» vs «Роснефть выкупила...»).

Личный WebFetch (kommersant.ru/doc/8588983) подтвердил обе даты/сумму/
покупателя дословно (уже сделан в этот час при попытке дочитать
`cb50ea645» саму по себе, до того как обнаружился дубль). Все поля
`cb50ea645» (buyer_name, eco.target_fin, eco.share, eco.context) уже
присутствуют в `gcc232775» в равном или БОЛЕЕ полном виде (у `gcc232775»
есть подтверждённый ИНН цели, полный `law.struct», восемь источников
против одного, и уже стоит факт о национализации мая 2025 года — то, чего
`cb50ea645» не знала вовсе). Переносить из дубля НЕЧЕГО — только
RBC-ссылка `cb50ea645» добавляется в `src» оставшейся карточки как
дополнительный источник.

Отдельная, новая находка того же личного WebFetch (ircity.ru,
21.03.2026, https://ircity.ru/text/economics/2026/03/21/76323741/):
20 марта 2026 года Хамовнический райсуд Москвы ОТДЕЛЬНЫМ решением изъял
у Виктора Круглова (и, видимо, его семьи) ЛИЧНОЕ имущество — доли в
юрлицах и ценные бумаги на сумму свыше 10 млрд ₽ плюс 1,2 млрд ₽ на
банковских счетах. Это НЕ то же самое, что национализация самого
«Саянскхимпласта» (май 2025, уже описана в карточке) — отдельный,
более поздний эпизод личной конфискации, добавлен коротким предложением
в `eco.context» как связанный факт.

Запуск:
    python3 pipeline/merge_sayanskhimplast_cb50ea645_dup.py            # сухой прогон
    python3 pipeline/merge_sayanskhimplast_cb50ea645_dup.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'
DROP_ID = 'cb50ea645'
KEEP_ID = 'gcc232775'

DROP_SRC = ['@dealsma (Telegram)', 'https://www.rbc.ru/industries/news/69cf8b819a794762a06fddad']

OLD_CONTEXT = (
    'Активы были обращены в доход государства в мае 2025 года решением '
    'Хамовнического райсуда Москвы по иску Генпрокуратуры к фактическому '
    'владельцу — экс-спикеру Законодательного собрания Иркутской области '
    'Виктору Круглову (имущество признано нажитым коррупционным путём). '
    'На момент изъятия активы оценивались более чем в 92 млрд ₽, тогда как '
    'стартовая цена торгов составила лишь 30,33 млрд ₽.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' 20 марта 2026 года тот же Хамовнический суд отдельным решением изъял '
    'у Круглова ещё и его личное имущество — доли в юрлицах и ценные бумаги '
    'на сумму свыше 10 млрд ₽, а также 1,2 млрд ₽ на банковских счетах.'
)


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    drop = by_id[DROP_ID]
    keep = by_id[KEEP_ID]

    assert drop['date'] == keep['date'] == '2026-04-13'
    assert keep['eco']['context'] == OLD_CONTEXT, \
        'gcc232775: eco.context уже другой: %r' % (keep['eco']['context'],)
    assert DROP_ID not in data.get('merged', {})
    assert not any(s == DROP_SRC for s in keep['src'])

    print('Сливаем %s -> %s' % (DROP_ID, KEEP_ID))
    print('  + src: %r' % (DROP_SRC,))
    print('  eco.context: дополняется фактом об изъятии личного имущества '
          'Круглова (20 марта 2026)')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    keep['src'].append(DROP_SRC)
    keep['eco']['context'] = NEW_CONTEXT

    data['deals'] = [d for d in data['deals'] if d['id'] != DROP_ID]
    data.setdefault('merged', {})[DROP_ID] = KEEP_ID

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
