import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gfd78ef6d'

OLD_ECO_RATIONALE = (
    'Привлечённые средства компания направит на развитие продуктов, '
    'усиление команды, маркетинг и выход на рынки Ближнего Востока, '
    'Африки и Латинской Америки.'
)
NEW_ECO_RATIONALE = (
    'MTS AI выбрала Primo RPA по итогам технического тестирования пяти '
    'самых популярных российских RPA-платформ — она показала лучший '
    'функционал для разработки роботов. ' + OLD_ECO_RATIONALE
)

OLD_ECO_TARGET_FIN = (
    'По данным «СПАРК-Интерфакс», в 2022 году выручка «Примо РПА» '
    'составила 36,3 млн ₽, чистая прибыль — 27,1 млн ₽. В прошлом году '
    'разработчик выполнил более 40 проектов для промышленных и '
    'финансовых компаний и для розничной торговли.'
)
NEW_ECO_TARGET_FIN = (
    OLD_ECO_TARGET_FIN + ' По данным реестровых агрегаторов, выручка '
    '«Примо РПА» выросла до 314,4 млн ₽ в 2024 году и 575 млн ₽ в 2025 '
    'году, чистая прибыль за 2025 год составила 121,4 млн ₽.'
)

OLD_ECO_CONTEXT = '—'
NEW_ECO_CONTEXT = (
    '26 июня 2025 года MTS AI полностью вышла из капитала «Примо РПА» '
    '— доля вернулась к основателю Михаилу Иванову (100%). Причину '
    'выхода открытые источники не называют.'
)

OLD_LAW_STRUCT = '—'
NEW_LAW_STRUCT = (
    'ООО «Примо РПА» зарегистрировано как самостоятельное юрлицо в '
    'сентябре 2022 года — менее чем за год до сделки; сама платформа '
    'разрабатывалась с 2009 года на базе более раннего продукта, права '
    'на неё переданы новому юрлицу в ноябре 2022 года.'
)

OLD_SRC = [['Интерфакс', 'https://www.interfax.ru/amp/911415']]
NEW_SRC = OLD_SRC + [
    ['CNews', 'https://www.cnews.ru/news/line/2023-07-13_mts_ai_investirovala_v_kompaniyu'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['rationale'] == OLD_ECO_RATIONALE
    assert deal['eco']['target_fin'] == OLD_ECO_TARGET_FIN
    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['law']['struct'] == OLD_LAW_STRUCT
    assert deal['src'] == OLD_SRC

    print('=== eco.rationale: станет ===')
    print(NEW_ECO_RATIONALE)
    print('\n=== eco.target_fin: станет ===')
    print(NEW_ECO_TARGET_FIN)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['eco']['rationale'] = NEW_ECO_RATIONALE
        deal['eco']['target_fin'] = NEW_ECO_TARGET_FIN
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['law']['struct'] = NEW_LAW_STRUCT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
