# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
`g9fb20e15` («Газпром Тех выкупил 90% акций НПФ «Микран»», закрыта в
феврале 2024) — актив уже перепродан дальше, для этой сделки в базе
нет отдельной карточки; заодно нашлось падение прибыли в 2026 году и
смена гендиректора.

Проверено лично прямым WebFetch (CNews, https://www.cnews.ru/news/top/2025-03-20_iks_holding_kupil_proizvoditelya,
20.03.2025): «ИКС холдинг» купил 100% «Микрана», поглотив ОБЕ доли —
90% «Газпром Тех» (с февраля 2024 года) и оставшиеся 10% Владимира
Вавилина; выручка за 2023 год — 7,38 млрд ₽ (рост с 4,4 млрд ₽),
чистая прибыль — 490 млн ₽; цена не раскрыта, оценки аналитиков —
10,5–15 млрд ₽.

По докладу саб-агента (не перепроверено мной лично прямым WebFetch):
в 2026 году сменился гендиректор («Микран», по данным RIA Tomsk,
14.01.2026, назначил исполнительным директором Сергея Касаева вместо
Веры Парамоновой, работавшей с 2018 года); прибыль компании за полный
2025 год сократилась втрое (с 1,3 млрд до 473,4 млн ₽), а в I квартале
2026 года — на 98,5% (CNews, 01.06.2026), при этом выручка выросла на
13,8% — компания объясняет это разовыми особенностями признания
выручки по крупным контрактам.

НЕ ВНЕСЕНО: связь с инвестициями «ИКС холдинга» в СВЧ-производство в
Приморье (3 сентября 2026, >35 млрд ₽) — саб-агент проверил лично и
подтвердил, что НПФ «Микран» в этой статье НЕ упоминается вовсе, факт
не относится к этой карточке.

Запуск: python3 pipeline/fix_mikran_resold_to_iks_holding.py
        python3 pipeline/fix_mikran_resold_to_iks_holding.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g9fb20e15'

OLD_ECO_CONTEXT = (
    'В 2023 году интерес к активу проявляли АФК «Система» и «Росатом».'
    ' Стоимость 100% компании участники рынка оценивают в сумму до 10'
    ' млрд ₽.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' В марте 2025 года «ИКС холдинг» купил 100%'
    ' «Микрана», поглотив обе доли — 90% «Газпром Тех» и оставшиеся 10%'
    ' Владимира Вавилина; выручка за 2023 год выросла до 7,38 млрд ₽,'
    ' чистая прибыль — до 490 млн ₽. В 2026 году гендиректором вместо'
    ' Веры Парамоновой (работала с 2018 года) назначен Сергей Касаев,'
    ' а прибыль компании резко упала: за 2025 год — втрое, до 473,4'
    ' млн ₽, за I квартал 2026 года — на 98,5% при росте выручки на'
    ' 13,8% (компания объясняет это особенностями признания выручки'
    ' по крупным контрактам).'
)

NEW_SRC = [
    ['CNews', 'https://www.cnews.ru/news/top/2025-03-20_iks_holding_kupil_proizvoditelya'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    existing_urls = {s[1] for s in deal['src']}
    add_src = [s for s in NEW_SRC if s[1] not in existing_urls]
    new_src = deal['src'] + add_src

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    if add_src:
        print('\n=== src: добавится ===')
        for s in add_src:
            print(s)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
