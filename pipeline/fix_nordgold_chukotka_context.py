# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка g948e18e1 (Nordgold
рассматривает продажу активов в Буркина-Фасо): проверка статуса —
обязательный угол — подтвердила, что сама сделка остаётся в переговорах,
новых фактов о её закрытии/срыве нет. Найден релевантный контекст о
продавце: Nordgold продолжает M&A-активность на других рынках (Чукотка),
что согласуется с уже записанным мотивом продажи («нарастить свободный
денежный поток для новых приобретений»). Не через review.py: поле уже
занято текстом из другого источника.

Источник — читал напрямую (fetch_article_texts.py, закэширован):
abn.agency (15.07.2026).
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g948e18e1'
OLD_CONTEXT = (
    'Группа «Окто» рассматривает покупку активов международной '
    'золотодобывающей компании Nordgold в Буркина-Фасо. Об этом сообщил '
    '«Интерфакс» со ссылкой на источник. Nordgold входит в «Севергрупп» '
    'Алексея Мордашова. По информации другого собеседника «Интерфакса», '
    'представители одного из претендентов на активы Nordgold недавно '
    'осматривали площадку в Буркина-Фасо. Источник агентства не уточнил, '
    'кто это был. По информации «Известий», обсуждаемая сумма сделки по '
    'продаже активов Nordgold в африканской стране — от $1 млрд. Nordgold '
    'была основана в 2007 году как подразделение «Северстали». У '
    'компании восемь действующих рудников: четыре в России, один в '
    'Казахстане, два в Буркина-Фасо и один в Гвинее. По последним '
    'раскрытым данным компании за 2021 год, производство на двух '
    'рудниках в Буркина-Фасо — Bissa и Bouly — составило 270 тыс. унций. '
    '«Окто» — частная многопрофильная группа, которая занимается '
    'проектами в сфере добычи полезных ископаемых, в том числе угля и '
    'золота. В 2025 году компания купила золотодобывающую группу '
    'Zapadnaya Gold Mining.'
)
ADDITION = (
    'Сама сделка по Буркина-Фасо к августу 2026 года не закрылась и не '
    'сорвалась публично — переговоры, судя по открытым источникам, '
    'продолжаются без объявленного результата. Тем временем 15 июля 2026 '
    'года ООО «Нордголд Развитие» стало владельцем ООО «Новая сырьевая '
    'компания», которая планирует добычу золота на Чукотке — Nordgold '
    'продолжает расширяться на других рынках независимо от исхода '
    'переговоров по африканским активам.'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} eco.context: += продолжение M&A-активности Nordgold (Чукотка)")
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
