# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g399c1f98
(МТС приобрела 51% в разработчике решений для видеоконференц-связи
Vinteo) — искали, реализовала ли МТС опционное соглашение на выкуп
оставшихся 49%, и как прошла интеграция.

Опцион НЕ реализован — структура собственности не изменилась. Косвенное
подтверждение проверено лично прямым WebFetch (ComNews, 22.04.2026):
Роман Самойлов по-прежнему выступает гендиректором ООО «Винтео»,
обсуждая планы компании на 2026–2030 годы — признаков консолидации
100% или смены руководства нет.

Интеграция подтверждена (CNews, 03.03.2025): «завершили интеграцию
сервера Vinteo MCU с экосистемой "МТС Линк"». Бренд Vinteo сохранён
(не переименован). Финансовые показатели консолидируются без разбивки
по юрлицам (ict-online.ru, 10.03.2026, о МТС Линк в целом, не только о
Vinteo): «Выручка группы выросла на 39% год к году и составила 2,532 '
млрд рублей» — это показатель ВСЕЙ группы МТС Линк (включая ООО
«Вебинар» и «Вебинар Технологии»), а не отдельно Vinteo; отдельных
цифр по Vinteo за 2024/2025 годы не публиковалось — не переносим
общегрупповую цифру на предмет сделки, чтобы не приписать ей чужой
масштаб.

`eco.context` дополнен фактом интеграции и статус-кво по опциону.

НЕ ВКЛЮЧЕНО: финансовые показатели Vinteo за 2024-2025 годы отдельно —
не публиковались (последние опубликованные цифры — за 2023 год, уже
стоят в `eco.target_fin`). Судьба Алексея Ликина и Дмитрия Серого — ни
в одном свежем источнике не упоминаются, не найдено ни продолжения
работы, ни ухода.

Запуск: python3 pipeline/fix_mts_vinteo_integration_and_status_quo.py
        python3 pipeline/fix_mts_vinteo_integration_and_status_quo.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g399c1f98'

OLD_CONTEXT = (
    'Изначально по 32,8% в компании принадлежали ее гендиректору '
    'Роману Самойлову, Алексею Ликину и Дмитрию Серому. Еще 1,5% '
    'владел Фонд развития интернет-инициатив (ФРИИ). В 2017 г. ФРИИ '
    'вышел из проекта, продав свою долю Самойлову (после этого доля '
    'Самойлова выросла до 34,35%). После сделки с МТС 51% в ООО '
    '«Винтео» принадлежат ООО «Вебинар». Доли Самойлова, Ликина и '
    'Серого сократились у каждого до 16,08%.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' Опцион на выкуп оставшихся 49% не реализован: структура долей не '
    'менялась, Роман Самойлов по-прежнему гендиректор «Винтео» (ComNews, '
    '22 апреля 2026 года). Интеграция состоялась: «завершили интеграцию '
    'сервера Vinteo MCU с экосистемой "МТС Линк"» (CNews, 3 марта 2025 '
    'года), бренд Vinteo сохранён.'
)

NEW_SRC = [
    ['ComNews', 'https://www.comnews.ru/content/244892/2026-04-22/2026-w17/1008/razrabotchiki-programmnykh-produktov-opredelilis-planami-pyatiletku'],
    ['CNews', 'https://www.cnews.ru/news/line/2025-03-03_mts_link_i_vinteo_predstavili'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT

    new_src = deal['src'] + NEW_SRC

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
