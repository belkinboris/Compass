def main():
    data = json.load(open(PATH, encoding="utf-8"))
    changed = []
    for d in data["deals"]:
        if d["id"] == "g85e07f6d":
            assert d["eco"]["share"] == "—"
            d["eco"]["share"] = G85E_SHARE
            d["eco"]["context"] = G85E_CONTEXT_OLD
            changed.append(d["id"])
        elif d["id"] == "g69fe736c":
            assert d["eco"]["share"] == "—"
            d["eco"]["share"] = G69FE_SHARE
            d["eco"]["context"] = G69FE_CONTEXT_OLD
            changed.append(d["id"])
    assert changed == ["g85e07f6d", "g69fe736c"], f"откатили: {changed}"
    json.dump(data, open(PATH, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("откатил:", changed)


if __name__ == "__main__":
    main()
