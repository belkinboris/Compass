# -*- coding: utf-8 -*-
"""Карточка `g3cc2009d` (Petropavlovsk/УГМК-Инвест) несла три отдельных
дефекта, найденные владельцем 10 августа при живом просмотре сайта:

1. Поле `asset` не было заполнено вовсе (при `target: null` и
   `target_was_seller: true` — предмет сделки не компания с профилем, а
   набор конкретных рудников). Пустой предмет включает в вёрстке два
   запасных состояния: плашка «Структура сделки» подставляет вместо
   названия предмета СУММУ СДЕЛКИ (`static/index.html`, `dp-asset
   only-sum` — предмет читался как «$600 млн», хотя это цена, а не то,
   что покупали), и снизу печатается служебная фраза «Приобретаемый актив
   отдельной карточки компании не имеет...». Факты для `asset` уже лежали
   в `eco.share` этой же карточки — перенос, а не новый источник.

2. `eco.share` и `eco.target_fin` были ДОСЛОВНО одинаковы — тот же класс
   дефекта, что уже описан в CLAUDE.md про `eco.rationale`/`extra`, только
   между другой парой полей. Текст состоял из двух разных фактов
   (состав активов; финансовый итог банкротства), сшитых в одно
   предложение, — просто разошёлся по двум полям целиком вместо того,
   чтобы каждый факт лёг в своё поле.

3. Тот же текст «В периметр сделки вошли...» ещё раз, целиком, повторялся
   в `extra` — там он снят, а уникальная часть `extra` (даты подписания и
   закрытия, передача кредита Газпромбанком) осталась.

Запуск: python3 pipeline/fix_petropavlovsk_asset_and_duplication.py
        python3 pipeline/fix_petropavlovsk_asset_and_duplication.py --write
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
BASE = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g3cc2009d'

ASSET = 'золотодобывающие активы Petropavlovsk PLC'
# Первая версия ('золотодобывающие активы Petropavlovsk: 100% Албынского
# рудника, доля в Покровском руднике, Маломырский рудник и 75% в проекте
# Эльга', 131 знак) была заметно длиннее типичного asset по базе (медиана 26,
# p90 55) — риск переполнения в компактной плашке «Структура сделки».
# Разбивка активов и так есть в eco.share, полю asset достаточно короткого
# узнаваемого имени.

OLD_SHARE = OLD_TARGET_FIN = (
    'В периметр сделки вошли 100% Албынского рудника, доля в Покровском '
    'руднике (через Eponymousco), Маломырский рудник и 75% в проекте Эльга; '
    'администраторы подтвердили, что выручки достаточно для полного расчёта '
    'с кредиторами, однако акционеры не получат ничего.')
NEW_SHARE = ('В периметр сделки вошли 100% Албынского рудника, доля в '
             'Покровском руднике (через Eponymousco), Маломырский рудник и '
             '75% в проекте Эльга.')
NEW_TARGET_FIN = ('Администраторы подтвердили, что выручки достаточно для '
                   'полного расчёта с кредиторами, однако акционеры не '
                   'получат ничего.')

OLD_EXTRA = (
    'Соглашение о купле-продаже подписано 1 августа 2022 года; фактическое '
    'закрытие сделки состоялось 7 сентября 2022 года — досрочно относительно '
    'контрактного дедлайна 30 сентября. Сделке предшествовала передача '
    'Газпромбанком прав требования по срочному кредиту Petropavlovsk на '
    '$201 млн структуре УГМК в апреле 2022 года, что сделало УГМК '
    'крупнейшим кредитором золотодобытчика. В периметр сделки вошли 100% '
    'Албынского рудника, доля в Покровском руднике (через Eponymousco), '
    'Маломырский рудник и 75% в проекте Эльга; администраторы подтвердили, '
    'что выручки достаточно для полного расчёта с кредиторами, однако '
    'акционеры не получат ничего. Разрешение президента РФ Владимира '
    'Путина на сделку было получено в начале сентября 2022 года.')
NEW_EXTRA = (
    'Соглашение о купле-продаже подписано 1 августа 2022 года; фактическое '
    'закрытие сделки состоялось 7 сентября 2022 года — досрочно относительно '
    'контрактного дедлайна 30 сентября. Сделке предшествовала передача '
    'Газпромбанком прав требования по срочному кредиту Petropavlovsk на '
    '$201 млн структуре УГМК в апреле 2022 года, что сделало УГМК '
    'крупнейшим кредитором золотодобытчика. Разрешение президента РФ '
    'Владимира Путина на сделку было получено в начале сентября 2022 года.')


def main(write=False):
    data = json.load(open(BASE, encoding='utf-8'))
    card = next(d for d in data['deals'] if d['id'] == CARD_ID)
    assert 'asset' not in card, '%s: asset уже задан' % CARD_ID
    assert card['eco']['share'] == OLD_SHARE, '%s: eco.share уже другое' % CARD_ID
    assert card['eco']['target_fin'] == OLD_TARGET_FIN, '%s: eco.target_fin уже другое' % CARD_ID
    assert card['extra'] == OLD_EXTRA, '%s: extra уже другое' % CARD_ID
    print('ПРАВИМ  %s: asset, eco.share/target_fin (снимаю дубль), extra (снимаю повтор)' % CARD_ID)
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return
    card['asset'] = ASSET
    card['eco']['share'] = NEW_SHARE
    card['eco']['target_fin'] = NEW_TARGET_FIN
    card['extra'] = NEW_EXTRA
    json.dump(data, open(BASE, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
