# -*- coding: utf-8 -*-
"""Месячное дочитывание карточки `gcaa03820` (ПСБ купил 16,9% акций «Атома»
(АО «Кама»), закрыто 12 августа 2026) — третий уровень очереди
(`REVISION_BRIEF.md`), первое чтение спустя месяц после первого обыска
(14 августа 2026).

Проверено WebSearch/WebFetch: ни IPO, ни другие инвесторы допэмиссии
(КамАЗ, «Росатом», «Ренова», РФПИ, Газпромбанк — все они назывались только
как ВОЗМОЖНЫЕ покупатели в статье 2024 года про спор Васина) за месяц не
продвинулись — ни одного нового источника. Единственная новая проверяемая
находка — операционная: реальный темп поставок серьёзно отстаёт от плана.

`eco.target_fin` дополнен: по данным «Автостата» (Сергей Целиков, zr.ru,
11.09.2026), за август на учёт встали только 11 экземпляров «Атома», а за
всё время — 40 единиц — при плане не менее 3 тыс. машин в четвёртом
квартале.

НЕ добавлено намеренно: более ранняя (июль 2026, до этой сделки) публикация
про задержки зарплат в АО «Кама» из-за «кассового разрыва по вине задержки
траншей от банка ПСБ» — ПСБ эту версию отверг («финансирование... в полном
объёме и в установленные сроки»). Транши в этом споре — похоже на ДОЛГОВОЕ
проектное финансирование, отдельное от разовой покупки 16,98% акций за живые
деньги, описанной в этой карточке; переносить факт без уверенности, что речь
об ОДНОМ и том же инструменте, значило бы повторить ошибку из уже описанных
в CLAUDE.md случаев смешения разных финансовых потоков одного проекта.

Запуск:
    python3 pipeline/fix_atom_kama_followup.py            # сухой прогон
    python3 pipeline/fix_atom_kama_followup.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'
CID = 'gcaa03820'

OLD_TARGET_FIN = (
    'Автомобиль стоит 3,98 млн ₽, с учётом госпрограммы льготного '
    'кредитования — 3,055 млн ₽. В июле первые машины получили клиенты, '
    'оформившие ранние предзаказы. До 15 октября компания планирует '
    'завершить выдачу первой партии, а до конца года передать ещё не менее '
    '3 тыс. серийных автомобилей.'
)
NEW_TARGET_FIN = OLD_TARGET_FIN + (
    ' По данным «Автостата», реальный темп поставок сильно отстаёт от '
    'плана: за август на учёт встали только 11 экземпляров «Атома», а за '
    'всё время — 40 единиц.'
)

NEW_SOURCES = [
    ['За рулём', 'https://www.zr.ru/content/news/985703-ehlektromobil-atom-kak-idut/'],
]


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    deals = {d['id']: d for d in data['deals']}
    card = deals[CID]

    if card['eco']['target_fin'] == NEW_TARGET_FIN:
        print('Уже применено — нечего делать (скрипт идемпотентен).')
        return

    assert card['eco']['target_fin'] == OLD_TARGET_FIN
    existing_urls = {u for _, u in card['src']}
    to_add = [pair for pair in NEW_SOURCES if pair[1] not in existing_urls]

    print('Правки для %s (%s):' % (CID, card['title']))
    print('  eco.target_fin: +реальный темп поставок (Автостат)')
    print('  src: +%d адресов' % len(to_add))

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    card['eco']['target_fin'] = NEW_TARGET_FIN
    card['src'].extend(to_add)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
