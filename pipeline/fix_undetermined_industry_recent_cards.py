# -*- coding: utf-8 -*-
"""15 августа 2026, разбор жалобы владельца: пять свежих карточек (добавлены
10-14 августа) висят с «Отрасль: Не определена», хотя предмет сделки
известен и легко проверяется. Причина в классификаторе притока
(`guess_industry`/`industry_by_words` в draft.py) — расследование показало,
что путь через профиль компании ломается на падеже («Самолета» не находит
профиль «ГК «Самолет»») и на обрубленном имени компании с нестандартной
приставкой («АФК «Система»» → core «афк «система без закрывающей кавычки).
Пробное исправление в draft.py измеримо УХУДШИЛО общую точность (230 неверных
угадываний вместо 187 на всей базе — падёж, допущенный для ЛЮБОГО совпадения
в кавычках, ловит однофамильцев вроде банка «Санкт-Петербург», совпадающего
с городом, или группы «Аврора», совпадающей с ОС «Аврора») — отклонено,
правки в draft.py не внесены (сам код классификатора остаётся прежним,
проблема системная и ждёт более аккуратного решения отдельным прогоном).

Здесь — точечная правка только этих пяти карточек, отрасль для каждой
проверена по уже существующим в базе аналогам (профиль компании или
однотипная сделка того же продавца/предмета), а не угадана:
  * g8e30b9a8 (Башнефть) — сестринская карточка gf6232eec о том же активе
    уже несёт «Нефть и газ».
  * g63c7d1bb (спиртзавод «Амбер Талвис») — тот же актив уже фигурирует в
    карточке c46d3e581 («Пищепром и напитки»), и все прочие сделки
    «Росспиртпрома» в базе — та же категория.
  * gcaa03820 (Атом) — профиль компании g0993ebfa («АО «Кама» (проект
    электромобиля «Атом»)») несёт «Автопром».
  * g0551fc60 (Самолет) — профиль компании g12111389 («ГК «Самолет»»)
    несёт «Недвижимость».
  * g8e2e28d5 (офис «Открытия») — предмет сделки офисное здание, категория
    по типу актива, а не по стороне сделки (Wildberries/ВТБ) — «Недвижимость».

ЗАПУСК:
    python3 pipeline/fix_undetermined_industry_recent_cards.py            # сухой прогон
    python3 pipeline/fix_undetermined_industry_recent_cards.py --write    # запись
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

FIXES = [
    ('g8e30b9a8', 'Нефть и газ'),
    ('g63c7d1bb', 'Пищепром и напитки'),
    ('gcaa03820', 'Автопром'),
    ('g0551fc60', 'Недвижимость'),
    ('g8e2e28d5', 'Недвижимость'),
]


def main(argv):
    data = json.load(open(DATA, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}

    for cid, new_ind in FIXES:
        deal = by_id[cid]
        assert deal.get('ind') == 'Не определена', \
            '%s: ind уже другое: %r' % (cid, deal.get('ind'))
        print('ПРАВИМ %s.ind: Не определена -> %r  (%s)' % (cid, new_ind, deal.get('title')[:60]))

    if '--write' not in argv:
        print('\nСухой прогон. Запись — с ключом --write.')
        return 0

    for cid, new_ind in FIXES:
        by_id[cid]['ind'] = new_ind
    json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('ЗАПИСАНО.')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
