import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'ga3afca6c'

NEW_ECO_TARGET_FIN = (
    'По итогам 2023 года выручка группы «Кассир.ру» составила 1,9 млрд ₽, '
    'чистая прибыль — 271 млн ₽.'
)

NEW_ECO_CONTEXT = (
    'К июлю 2024 года доля АО «АБ Холдинг» снизилась до 22% (причина не '
    'раскрывалась). В октябре 2024 года VK закрыла отдельную сделку по '
    'покупке 10% «Кассир.ру» (ориентировочно 500 млн ₽) с целью «укрепить '
    'позиции на рынке» и интегрировать сервисы. Основной акционер Евгений '
    'Финкельштейн отдельно, в 2024 году, купил контрольный пакет в '
    'разработчике ПО «Инфотех» (по оценке источников отрасли, 300–450 '
    'млн ₽) — покупка позволит «Кассир.ру» выйти в спортивный сегмент и '
    'нарастить оборот на 20–25% в течение трёх лет.'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6835890'],
    ['SPbIT', 'https://www.spbit.ru/news/VK-kupil-10-v-Kassir-ru-297797'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['target_fin'] == '—'
    assert deal['eco']['context'] == '—'

    new_src = deal['src'] + NEW_SRC

    print('=== eco.target_fin: станет ===')
    print(NEW_ECO_TARGET_FIN)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['target_fin'] = NEW_ECO_TARGET_FIN
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
