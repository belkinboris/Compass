import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g4f24faca'

OLD_TARGET_FIN = (
    '«Никольское» зарегистрировано в Тверской области в 2014 году,'
    ' уставный капитал — 36 тыс. ₽, руководитель — Александр Климов.'
    ' Выручка в 2022 году составила 17,6 млрд, чистый убыток — 9 млн ₽.'
)
NEW_TARGET_FIN = (
    '«Никольское» зарегистрировано в Тверской области в 2014 году,'
    ' уставный капитал — 36 тыс. ₽, руководитель — Александр Климов.'
    ' Выручка в 2022 году составила 17,6 млн ₽ (в источнике — опечатка в'
    ' единице измерения, «млрд»; подтверждено независимым отраслевым'
    ' СМИ и реестровым агрегатором), чистый убыток — 9 млн ₽.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['target_fin'] == OLD_TARGET_FIN

    print('=== eco.target_fin: станет ===')
    print(NEW_TARGET_FIN)

    if write:
        deal['eco']['target_fin'] = NEW_TARGET_FIN
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
