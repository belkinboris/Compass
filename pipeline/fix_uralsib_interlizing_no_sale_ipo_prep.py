import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g2800e337'

OLD_CONTEXT = '—'
NEW_CONTEXT = (
    'По состоянию на 2025 год ни один из пяти претендентов не подтверждён'
    ' как реальный покупатель. Вместо продажи стратегу — внутренняя'
    ' реструктуризация: в сентябре 2024 года Людмила Коган передала свою'
    ' 100%-ю долю на созданное ею же ООО «Ил Холдинг» (сохранив 99,99% в'
    ' новой структуре), в феврале 2025 года назначен новый генеральный'
    ' директор. По собственным заявлениям компании (июнь 2024 года),'
    ' готовится к IPO, размещение на тот момент не состоялось.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
