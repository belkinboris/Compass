# -*- coding: utf-8 -*-
"""Разовая правка g998e5eb5 (МКБ/Дальневосточный банк): реорганизация, а не M&A.

ЧТО НЕВЕРНО. Владелец указал: присоединение ДВБ к МКБ — форма РЕОРГАНИЗАЦИИ
(ст. 57-58 ГК РФ: слияние/присоединение/разделение/выделение/преобразование),
а не покупка компании: нет продавца, нет предмета сделки в смысле «купили
актив» — есть правопреемник (МКБ) и общество, которое к нему присоединяется
и прекращает существовать (ДВБ), а имущество и обязательства переходят по
универсальному правопреемству. `type: "M&A"` заставлял интерфейс подписывать
стороны «Покупатель»/«Продавец»/«Предмет сделки» — юридически неточно для
этой формы сделки. Заведён новый тип `type: "Реорганизация"` (см. правку
static/index.html и TYPE_WORDS в pipeline/ingest/review.py) — интерфейс
показывает для него «Правопреемник» / «Присоединяемое общество».

Плюс две находки по содержанию той же карточки:

1. `eco.share` нёс «Объединенная сеть теперь включает более 100 офисов и 800
   банкоматов…» — это НЕ предмет/доля сделки (для реорганизации это поле
   вообще не имеет смысла — доли в процентах нет), а факт ПОСЛЕ объединения.
   Перенесено в `eco.context` (было пустым), откуда рендерится как контекст,
   а не подписывается как «Предмет».
2. `law.terms` нёс «По завершении сделки во Владивостоке открылся центр МКБ
   «Дальневосточный». Новый центр позволит оперативно принимать решения с
   учетом местной специфики» — открытие регионального офиса ПОСЛЕ сделки не
   является договорным условием (заверения, индемнити, ограничение
   ответственности, отлагательные условия, эскроу, неконкуренция и т. п. —
   см. CLAUDE.md, раздел «Что искать для линзы „Юрист"»). Это операционная
   деталь интеграции, не условие сделки — снято без замены (поле было бы
   честнее пустым, чем со случайным фактом не по теме).

Источник (Коммерсантъ, уже стоит в src) прямо описывает механизм: «Сделка
проводилась путем конвертации акций ДВБ в акции Московского кредитного
банка. Для этих целей МКБ объявил допэмиссию, которая увеличила его капитал
на 4,4%» — это уже лежит в law.struct и не меняется.

Запуск:
    python3 pipeline/fix_mkb_dvb_reorganization.py            # сухой прогон
    python3 pipeline/fix_mkb_dvb_reorganization.py --write    # запись
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(ROOT)
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g998e5eb5'
OLD_TYPE = 'M&A'
NEW_TYPE = 'Реорганизация'
OLD_SHARE = ('Объединенная сеть теперь включает более 100 офисов и 800 '
             'банкоматов в 66 населенных пунктах и 19 регионах России')
OLD_CONTEXT = '—'
NEW_CONTEXT = OLD_SHARE
OLD_TERMS = ('По завершении сделки во Владивостоке открылся центр МКБ '
             '«Дальневосточный». Новый центр позволит оперативно принимать '
             'решения с учетом местной специфики')
NEW_TERMS = '—'


def main(argv):
    data = json.load(open(DATA, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['type'] == OLD_TYPE, 'type карточки уже другое'
    assert deal['eco']['share'] == OLD_SHARE, 'eco.share карточки уже другое'
    assert deal['eco']['context'] == OLD_CONTEXT, 'eco.context карточки уже другое'
    assert deal['law']['terms'] == OLD_TERMS, 'law.terms карточки уже другое'

    print('type:', OLD_TYPE, '->', NEW_TYPE)
    print('eco.share:', repr(OLD_SHARE), '-> "—"')
    print('eco.context: "—" ->', repr(NEW_CONTEXT))
    print('law.terms:', repr(OLD_TERMS), '-> "—"')

    if '--write' not in argv:
        print('\nСухой прогон. Запись — с ключом --write.')
        return 0

    deal['type'] = NEW_TYPE
    deal['eco']['share'] = '—'
    deal['eco']['context'] = NEW_CONTEXT
    deal['law']['terms'] = NEW_TERMS
    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('ЗАПИСАНО.')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
