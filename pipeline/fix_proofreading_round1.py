# Поля, где `eco.context` карточки надо снять целиком (обрывок без подлежащего).
DROP_FIELDS = [('g88304d3a', 'eco.context',
                'Андрей Кобец (71,48%), Кирилл Запутряев (11%) и Андрей Лукьянов (0,83%).')]

# Ложный консультант: юрист КОММЕНТИРОВАЛ прессе процедуру банкротства, а не
# сопровождал сделку. Снимается строка целиком, поле остаётся пустым списком —
# честнее, чем называть консультантом того, кто им не был.
DROP_ADVISOR = [('ga5336065', 'Ляпунов, Терехин и партнеры')]

RANGE_DASH = re.compile(r'(?<=\d)\s*-\s*(?=\d)')
NUM = re.compile(r'\d[\d\s.,]*\d|\d')


def get_field(card, path):
    obj = card
    for part in path.split('.'):
        if not isinstance(obj, dict):
            return None
        obj = obj.get(part)
    return obj


def set_field(card, path, value):
    parts = path.split('.')
    obj = card
    for part in parts[:-1]:
        obj = obj.setdefault(part, {})
    obj[parts[-1]] = value


def digits(s):
    return re.sub(r'[^\d]', '', str(s or ''))


def main(argv):
    data = json.load(open(DATA, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}

    # --- проверки переводов: все числа оригинала обязаны быть в переводе ---
    for cid, field, head, ru in TRANSLATIONS:
        cur = get_field(by_id[cid], field)
        assert isinstance(cur, str) and cur.startswith(head), \
            '%s.%s: оригинал не совпал с ожидаемым началом %r' % (cid, field, head[:40])
        src_nums = set(re.findall(r'\d+(?:[.,]\d+)?', cur.replace(',', '')))
        ru_nums = set(re.findall(r'\d+(?:[.,]\d+)?', ru.replace(' ', '').replace(',', '.')))
        ru_flat = digits(ru)
        missing = [n for n in src_nums if digits(n) not in ru_flat]
        assert not missing, \
            '%s.%s: числа оригинала потеряны в переводе: %s' % (cid, field, missing)

    # --- проверки точечных правок ---
    for cid, field, old, new in CARD_FIXES:
        cur = get_field(by_id[cid], field)
        assert isinstance(cur, str), '%s.%s: поле не строка (%r)' % (cid, field, cur)
        assert old in cur, '%s.%s: не найден фрагмент %r' % (cid, field, old[:50])

    for cid, field, expected in DROP_FIELDS:
        cur = get_field(by_id[cid], field)
        assert cur == expected, '%s.%s: значение уже другое: %r' % (cid, field, cur)

    for cid, firm in DROP_ADVISOR:
        rows = (by_id[cid].get('law') or {}).get('adv') or []
        assert any(firm in str(r) for r in rows), \
            '%s: строка консультанта %r уже не найдена' % (cid, firm)

    # --- замер дефиса в диапазонах сумм ---
    dash_targets = []
    for d in data['deals']:
        for field in ('sum', 'eco.sum'):
            v = get_field(d, field)
            if isinstance(v, str) and RANGE_DASH.search(v):
                dash_targets.append((d['id'], field, v, RANGE_DASH.sub('–', v)))

    print('Переводов с иностранного: %d полей у %d карточек'
          % (len(TRANSLATIONS), len({t[0] for t in TRANSLATIONS})))
    print('Дефис -> тире в диапазоне суммы: %d полей' % len(dash_targets))
    print('Точечных правок по карточкам: %d' % (len(CARD_FIXES) + len(DROP_FIELDS)))
    for cid, field, old, new in CARD_FIXES[:6]:
        print('  %s %-12s %r -> %r' % (cid, field, old[:44], new[:44]))

    if '--write' not in argv:
        print('\nСухой прогон. Запись — с ключом --write.')
        return 0

    for cid, field, _head, ru in TRANSLATIONS:
        set_field(by_id[cid], field, ru)
    for cid, field, old, new in CARD_FIXES:
        set_field(by_id[cid], field, get_field(by_id[cid], field).replace(old, new))
    for cid, field, _expected in DROP_FIELDS:
        group, key = field.split('.')
        by_id[cid][group].pop(key, None)
    for cid, firm in DROP_ADVISOR:
        law = by_id[cid]['law']
        law['adv'] = [r for r in law.get('adv') or [] if firm not in str(r)]
    for cid, field, _old, new in dash_targets:
        set_field(by_id[cid], field, new)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('ЗАПИСАНО.')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
