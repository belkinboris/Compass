"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
gd99824b6 (Инвестфонд Tier 5 выкупил 25% в облачном провайдере
Selectel, 01.12.2023, статус «Закрыта») — структура Вермишяна сначала
нарастила долю, потом продала её крупную часть совместному предприятию
«Интерроса» и «Т-Технологий»; IPO, о котором говорили, так и не
состоялось.

Рост выручки — проверено лично прямым WebFetch (пресс-релиз Selectel,
10.04.2025): «Выручка Selectel увеличилась на 29% год к году до 13,2
млрд рублей», чистая прибыль выросла на 19% до 3,3 млрд руб.

Продажа доли — проверено лично прямым WebFetch: Коммерсантъ
(29.12.2025) называет покупателя — «Компания «Каталитик пипл» —
совместное предприятие «Интерроса» и «Т-технологий»» — и сумму (16
млрд руб. за 25%), но продавца называет обобщённо («действующие
акционеры компании»); имя продавца («у инвестиционных структур
Геворка Вермишяна и прочих акционеров») дословно подтверждено ОТДЕЛЬНЫМ
прямым WebFetch на CNews (29.12.2025) — оба источника проверены лично,
каждый подтверждает свою часть факта.

НЕ ВКЛЮЧЕНО: точная доля, оставшаяся у структур Вермишяна/Tier 5
после этой продажи, — ни один источник (Коммерсантъ, Ведомости,
CNews) её не называет, это честный пробел; промежуточный рост доли
Вермишяна до 34% в мае 2025 года (покупка ещё 10% через «Солнечный
ветер») — по данным саб-агента (Интерфакс, 05.05.2025), не
дозаверено отдельным WebFetch; отсутствие IPO подтверждено
косвенно (компания продолжает называть его «одним из вариантов», без
сроков), не решающий факт для карточки о сделке 2023 года.

Запуск: python3 pipeline/fix_selectel_tier5_ownership_growth_and_sale.py
        python3 pipeline/fix_selectel_tier5_ownership_growth_and_sale.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gd99824b6'

OLD_EXTRA = (
    'Фонд Tier 5, основанный бывшим генеральным директором «Мегафона» '
    'Геворком Вермишяном, приобрел 25% провайдера IT-инфраструктуры '
    '«Селектел».'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Выручка Selectel продолжила расти (13,2 млрд руб. за 2024 год, '
    '+29%), а обсуждавшееся IPO так и не состоялось. 29 декабря 2025 '
    'года структуры Вермишяна продали 25% Selectel совместному '
    'предприятию «Интерроса» и «Т-Технологий» — «Каталитик пипл» — за '
    '16 млрд руб.; точная доля, оставшаяся у Вермишяна после этой '
    'продажи, источниками не названа.'
)

NEW_SRC = [
    ['Selectel', 'https://selectel.ru/about/newsroom/news/vyruchka-selectel-ot-oblachnyh-infrastrukturnyh-servisov-vyrosla-na-32-po-itogam-2024-goda/'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8335416'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
