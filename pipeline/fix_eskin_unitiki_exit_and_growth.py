# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
gb97fb345 (Андрей Еськин приобрел 21% агрегатора автобусных билетов
Unitiki, 20.12.2023, статус «Закрыта») — компания выросла, а
покупатель этой самой сделки вышел из бизнеса и ликвидировал свою
структуру.

Финансовые показатели «Юнитики» — проверено лично прямым WebFetch
(saby.ru, зеркало ФНС): выручка 2023 — 192,5 млн ₽, 2024 — 278,42 млн
₽, 2025 — 743,3 млн ₽ (рост в 2,7 раза за год). Выход Еськина —
проверено лично прямым WebFetch (audit-it.ru): ООО «Олеот» (структура
Еськина) — «ликвидация юридического лица», «Дата ликвидации:
18.12.2025», «Председатель ликвидационной комиссии: Еськин Андрей
Валерьевич (назначен 26.05.2025)»; по данным саб-агента (audit-it.ru),
доля «Олеот» в «Юнитики» (17,63%) прекратилась 20 февраля 2025 года.

НЕ ВКЛЮЧЕНО: версия саб-агента о том, что долю выкупило АО «Топтех»
(появилось в реестре в тот же день с тем же процентом) — это его
собственная реконструкция по совпадению дат в реестре, а не факт из
источника; прямого подтверждения такой сделки нет, и в базу это не
идёт. Другие проекты Еськина («Мэритайм Кэпитал Инвестментс» с
Абрамовичем, доля в «Восток-Контракте») — либо уже известны, либо не
относятся к этой карточке.

Запуск: python3 pipeline/fix_eskin_unitiki_exit_and_growth.py
        python3 pipeline/fix_eskin_unitiki_exit_and_growth.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gb97fb345'

OLD_EXTRA = (
    'Сделка по приобретению 21% доли в ООО «Юнитики» (агрегатор '
    'автобусных билетов Unitiki). Покупатель — ООО «Олеот», '
    'подконтрольное Андрею Еськину, партнеру Романа Абрамовича. В '
    'числе других владельцев: Филипп Величко (63%), ООО «Форсайт '
    'плюс» под управлением Александра Зимина (8%), Сергей Шашурин '
    '(5,5%), Анатолий Захаров (2,4%).'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Бизнес вырос: выручка «Юнитики» поднялась с 192,5 млн ₽ (2023) '
    'до 743,3 млн ₽ (2025). Сам покупатель этой доли из бизнеса вышел: '
    'ООО «Олеот» ликвидировано 18 декабря 2025 года, председателем '
    'ликвидационной комиссии выступил сам Еськин.'
)

NEW_SRC = [
    ['audit-it.ru', 'https://www.audit-it.ru/contragent/1237700784309_ooo-oleot'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
