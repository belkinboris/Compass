# -*- coding: utf-8 -*-
"""Заметка 488 (консоль, 4 сентября 2026): «В раздел дополнительная
информация в карточке сделки это можно отразить», отвечая на карточку
`g60280ac0» (Decathlon продал 35 магазинов и склад ООО «АРМ», бренд
Desport).

Известная проблема (CLAUDE.md) уже нашла и лично проверила прямым
чтением (Disclose.ngo, декабрь 2023): по словам бывшего сотрудника,
Decathlon хотела продолжать продавать товар в России летом 2023 года
под кодовым именем «Sports_R», используя контракт на поставку новому
российскому покупателю на $12 млн (1,2 млн изделий) через сингапурскую
«дочку» Decathlon (Desipro) и дубайскую фирму-«пустышку» Phenix Limited.
Сама Decathlon на прямой запрос журналистов по существу не ответила.

Это не подтверждено самой Decathlon — поэтому формулировка в карточке
атрибутирует факт расследованию одного издания, а не подаёт его как
доказанное. Владелец прямо разрешил внести это в «Дополнительную
информацию».

Запуск: python3 pipeline/fix_decathlon_arm_disclose_investigation.py [--write]
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g60280ac0'

OLD_EXTRA = (
    'Сделка закрыта. Покупатель — ООО «АРМ»: его владелец и генеральный '
    'директор — Вячеслав Мареев, основные доли принадлежат кипрской '
    'компании «Трибалон лтд.». Продавец — французская компания '
    'Decathlon. Новый владелец обязался сохранить рабочие места 909 '
    'сотрудникам сети. Магазины сначала хотели назвать All Do Sport '
    '(ADS), но 10 декабря 2023 года они открылись под брендом Desport — '
    'в Краснодаре, Москве, Казани, Санкт-Петербурге, Самаре, Перми и Уфе.'
)

ADDITION = (
    ' По расследованию Disclose.ngo (декабрь 2023 года), Decathlon '
    'намеревалась продолжать поставлять товар в Desport уже после '
    'продажи — по словам бывшего сотрудника компании, летом 2023 года '
    'обсуждался контракт на $12 млн (1,2 млн изделий) через сингапурскую '
    '«дочку» Decathlon и дубайскую фирму без сайта и штата. Сама '
    'Decathlon на прямой вопрос журналистов по существу не ответила.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {c['id']: c for c in data['deals']}
    card = by_id[CARD_ID]
    assert card['extra'] == OLD_EXTRA, card['extra']
    card['extra'] = OLD_EXTRA + ADDITION

    print(f'{CARD_ID}.extra: добавлена находка Disclose.ngo про поставки после продажи')

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
            f.write('\n')
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
