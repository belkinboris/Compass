# -*- coding: utf-8 -*-
"""Новая карточка: АО «Соликамскбумпром» (Пермский край, один из крупнейших
в России производителей газетной бумаги, в процедуре банкротства) на
судебном заседании заявило о соглашении о намерениях с китайской
компанией «Юнь Чоу» — та должна купить 83,3% акций и закрыть долги
комбината. Статус «Обсуждается»: суд ничего не одобрил, подписания
договора купли-продажи ещё не было, а кредиторы публично считают
условия завода неисполнимыми (запуск всех четырёх бумагоделательных
машин и заморозка долгов на семь лет).

Источники (прочитаны полностью, кэш data/inbox/raw/2026-10-14-articles.jsonl):
  URA.RU (14.10.2026, пересказ Коммерсантъ-Прикамье, цитаты из суда)
    https://ura.news/news/1053135987
  Коммерсантъ (07.10.2026, тот же сюжет неделей раньше — пока без доли в %)
    https://www.kommersant.ru/doc/9007628
  Коммерсантъ (04.08.2026, привлечение акционеров и руководства к делу)
    https://www.kommersant.ru/doc/8861083

Цифра 83,3% и формулировка «соглашение о намерении уже заключено» —
только со слов представителей завода на суде (пересказ URA.RU со ссылкой
на Коммерсантъ-Прикамье); в собственном материале Коммерсанта от 7
октября той же сделки доля не называется, только переговоры об
инвестициях на 20 млрд ₽. Долг — тоже разнится: источник карточки
называет «более 5 млрд ₽», Коммерсантъ 7 октября — «более 15 млрд ₽»;
обе цифры приведены с атрибуцией, не выбрана одна.

Запуск:
    python3 build_solikamskbumprom_2026_10_14.py            # сухой прогон
    python3 build_solikamskbumprom_2026_10_14.py --write    # применить
"""
import json
import os
import sys

ROOT = '/home/user/Compass'
sys.path.insert(0, os.path.join(ROOT, 'pipeline', 'ingest'))
import promote  # noqa: E402

PENDING = os.path.join(ROOT, 'static', 'data', 'pending.json')
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

SRC_URA = ['URA.RU', 'https://ura.news/news/1053135987']
SRC_KOM_OCT7 = ['Коммерсантъ', 'https://www.kommersant.ru/doc/9007628']
SRC_KOM_AUG = ['Коммерсантъ (привлечение акционеров к делу)', 'https://www.kommersant.ru/doc/8861083']

DRAFT = {
    'date': '2026-10-14',
    'title': '«Соликамскбумпром» заявил о соглашении с китайским инвестором «Юнь Чоу»',
    'ind': 'Лесопром',
    'type': 'M&A',
    'status': 'Обсуждается',
    'src': [SRC_URA, SRC_KOM_OCT7, SRC_KOM_AUG],
    'buyer_name': '«Юнь Чоу»',
    'asset': '83,3% акций АО «Соликамскбумпром»',
}


def main(write=False):
    pending = json.load(open(PENDING, encoding='utf-8'))
    promoted = json.load(open(DATA, encoding='utf-8'))
    existing_ids = {c['id'] for c in pending['cards']} | {d['id'] for d in promoted['deals']}
    if any('Соликамскбумпром' in (c.get('title') or '') for c in pending['cards']):
        print('ОТКАЗ: похожая карточка уже в pending.json')
        return 1

    card_id = promote.new_id(existing_ids)
    card = promote.to_card(DRAFT, card_id)
    card['eco']['share'] = (
        'Представители «Соликамскбумпрома» заявили на суде, что «Юнь Чоу» купит 83,3% '
        'акций комбината — эта цифра и утверждение «соглашение о намерении уже заключено» '
        'известны только со слов завода на процессе (пересказ URA.RU со ссылкой на '
        '«Коммерсантъ-Прикамье»); подписания самого договора купли-продажи пока не было, '
        'и ни суд, ни кредиторы это соглашение не подтвердили.'
    )
    card['eco']['val'] = (
        'Цена пакета не называется ни одной стороной. Общий долг комбината источники '
        'оценивают по-разному: URA.RU (14 октября) — «более 5 млрд ₽», Коммерсантъ (7 '
        'октября) — «более 15 млрд ₽».'
    )
    card['eco']['rationale'] = (
        'По словам представителей завода, «Юнь Чоу» должна закрыть долги комбината перед '
        'кредиторами и наладить производственный процесс, а до конца октября провести '
        'переговоры с ресурсоснабжающими организациями о реструктуризации задолженности. '
        'Кредиторы (в их числе «Газпром межрегионгаз Пермь», «Пермэнергосбыт», '
        '«ЭлектроТехКонтроль») считают, что завод вводит суд в заблуждение: по их данным, '
        '«Юнь Чоу» согласится войти в проект только при условии запуска всех четырёх '
        'бумагоделательных машин комбината и заморозки всех долгов на семь лет.'
    )
    card['eco']['context'] = (
        '«Соликамскбумпром» — один из крупнейших в России производителей газетной бумаги, '
        'находится в процедуре банкротства: с августа 2026 года к делу привлечены '
        'президент компании Наталия Ступникова, председатель совета директоров Валерий '
        'Писоцкий и структуры, связанные с семьёй покойного экс-президента Виктора '
        'Баранова (умер в 2023 году). Прокуратура Пермского края на заседании заявила, '
        'что не возражает против введения процедуры наблюдения. «Юнь Чоу» — китайская '
        'компания, импортирующая из России лес и экспортирующая бумагоделательное '
        'оборудование; представители «Соликамскбумпрома» ссылаются на её прежний опыт '
        'работы с Селенгинским целлюлозно-картонным комбинатом в Бурятии как на удачный '
        'прецедент — этот эпизод подтверждён только их собственными словами в суде.'
    )

    print('НОВАЯ КАРТОЧКА %s: %s' % (card_id, card['title']))
    if not write:
        print('\nСухой прогон. Применение — с ключом --write.')
        return 0

    fresh = json.load(open(PENDING, encoding='utf-8'))
    if any(c['id'] == card_id for c in fresh['cards']):
        print('ОТКАЗ: id уже занят — перечитайте и повторите')
        return 1
    fresh['cards'].append(card)
    json.dump(fresh, open(PENDING, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('\nПрименено.')
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
