# -*- coding: utf-8 -*-
"""Дневная очередь 12 сентября 2026: у карточки «Вектор Рейл» (gdffd613c)
дописан ход публичного аукциона ПСБ по продаже национализированного 100%
пакета — источник mergers.ru (кэш притока, 2026-09-08.jsonl) назвал «Сбер»
основным претендентом и его собственную оценку компании; источник 1prime.ru
(прямое чтение WebFetch) подтвердил перенос торгов с 4 на 17 сентября и
уточнённую стартовую цену 20,35 млрд ₽ (была 20,3 млрд — то же число,
округлённое иначе). Через review.py не проводится: цитата 1prime.ru не
лежит в кэше притока (fetch.py её не забирал), а привести факт без второго,
проверяемого чтением источника было бы шагом назад по строгости, принятой
для мультипликаторов и раскрытий 6 сентября. Assert на исходном состоянии —
как везде.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gdffd613c'

OLD_CONTEXT = (
    'По итогам 2021 года доля «СГ-Транса» в перевозках СУГ по сети ОАО РЖД '
    'составляла 64%, говорится в проспекте выпуска облигаций. Парк насчитывал '
    '31 тыс. единиц, в том числе 24,6 тыс. цистерн для СУГ (из них 4,2 тыс. '
    '— в паритетном СП с СИБУРом НХТК), 6,7 тыс. танк-контейнеров и 4,5 тыс. '
    'фитинговых платформ. Купленный в этой сделке пакет позже изъят '
    'государством: 23 апреля 2025 года суд по иску Генпрокуратуры обратил в '
    'доход РФ 100% «Вектор Рейл» вместе с «СГ-Транс» и «Химинвесттранс» — с '
    'Салмана Бабаева (бывшего вице-президента РЖД), его сыновей Тимура и '
    'Руслана Бабаевых и Алексея Тайчера взыскано солидарно 30,1 млрд ₽, а '
    'всего по делу изъято 12 компаний на около 242 млрд ₽; 27 августа 2025 '
    'года апелляция решение оставила в силе. С марта 2026 года ПСБ выставил '
    '100% «Вектор Рейл» на электронный аукцион со стартовой ценой 20,3 млрд ₽.'
)

ADDITION = (
    ' Торги неоднократно переносились (с 10 августа на 4 сентября, затем на '
    '17 сентября), стартовая цена уточнена до 20,35 млрд ₽. Основным '
    'претендентом на покупку выступает «Сбер», оценивший индикативную '
    'стоимость группы в 6–10 млрд ₽ при цене отсечения аукциона на понижение '
    'в 10,2 млрд ₽; сделка ещё не закрыта.'
)
# ПРАВЛЕНО тем же прогоном: первая версия несла «По данным mergers.ru» —
# пресс-атрибуция в прозаическом поле запрещена (издание уже названо в
# `src`), снята отдельной правкой сразу после записи этого скрипта.

NEW_CONTEXT = OLD_CONTEXT + ADDITION

NEW_SOURCES = [
    ['mergers.ru', 'https://mergers.ru/news/Sber-stanet-osnovnym-pretendentom-na-priobretenie-nacionalizirovannoj-lizingovoj-kompanii-Vektor-Rejl-87407'],
    ['ПРАЙМ', 'https://1prime.ru/20260902/auktsion-872904719.html'],
]


def main(write):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    card = next(d for d in data['deals'] if d['id'] == CARD_ID)
    assert card['eco']['context'] == OLD_CONTEXT, 'eco.context уже другое'
    for name, url in NEW_SOURCES:
        assert [name, url] not in card['src'], 'источник уже есть'
    card['eco']['context'] = NEW_CONTEXT
    card['src'] = card['src'] + NEW_SOURCES
    print('Обновлено:', CARD_ID)
    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
            f.write('\n')
        print('Записано.')
    else:
        print('Сухой прогон — для записи передайте --write')


if __name__ == '__main__':
    import sys
    main('--write' in sys.argv)
