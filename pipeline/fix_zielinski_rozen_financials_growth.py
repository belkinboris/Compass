# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g0f7d3941 (ГК «Галс Девелопмент» продала 2,7 га на Старообрядческой
улице компании Zielinski & Rozen, закрыта 2 октября 2023) — бизнес
бренда вырос, структура собственности не менялась.

Проверено лично прямым WebFetch (Интерфакс,
https://www.interfax.ru/business/1018296): «увеличило выручку на
27,1%, до 6,8 млрд рублей» (2024 год), «Валовая прибыль выросла на
25,8% и составила 5,8 млрд рублей», «Чистая прибыль компании снизилась
на 5,5%, до 1,9 млрд рублей».

НЕ ВКЛЮЧЕНО: судьба самого участка на Старообрядческой — саб-агент
нашёл официальное градостроительное решение по офисно-производственному
комплексу 18 тыс. кв.м на том же адресе (mskagency.ru, март 2025), но
связь именно с Zielinski & Rozen подтверждена только совпадением
адреса и площади, не дословной цитатой, — слишком шаткое основание,
чтобы писать как факт; официальная сумма сделки задним числом —
по-прежнему не раскрыта нигде; структура владения (Розен 45% / Никулин
48% / Мамин 7%) не менялась по данным на июль 2025 — это подтверждение
статус-кво, а не новый факт, отдельно не пишу.

Запуск: python3 pipeline/fix_zielinski_rozen_financials_growth.py
        python3 pipeline/fix_zielinski_rozen_financials_growth.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g0f7d3941'

OLD_EXTRA = (
    'Продажа 100% долей ООО «Эксперт недвижимость», владеющего 2,7 га '
    'на Старообрядческой улице на юго-востоке Москвы. Участок перешел '
    'от группы ВТБ, которая получила его в результате реструктуризации '
    'долгов «Мосметростроя». На площадке планируется строительство '
    'складского комплекса или офисной недвижимости.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Бизнес бренда растёт: выручка ООО «Зелинский и Розен Парфюмерия» '
    'за 2024 год выросла на 27,1% до 6,8 млрд ₽, валовая прибыль — на '
    '25,8% до 5,8 млрд ₽, при этом чистая прибыль снизилась на 5,5% до '
    '1,9 млрд ₽ (рост коммерческих расходов).'
)

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/business/1018296'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
