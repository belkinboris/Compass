# -*- coding: utf-8 -*-
"""Месячная очередь, 8 сентября 2026 (третий час подряд) — три карточки
одной партии импорта (2026-08-03), у всех дата стояла голым годом
«2024» — та же ошибка, что чинили весь день. Личный WebFetch подтвердил
все три случая напрямую.

1) `caeac8f4e` («Портфель активов Raven Russia выставлен на продажу за
   90,09 млрд рублей»). У карточки уже стояла ПОДТВЕРЖДЁННАЯ (verified)
   внутренняя дата в слое `facts.date.value` = «2025-10-28» — верхний
   уровень просто не был приведён в соответствие. Личный WebFetch
   (kommersant.ru/doc/8160509) подтвердил дословно: «28.10.2025, 21:10»
   и «в начале 2025 года активы Raven Russia были обращены в доход
   государства». Дата исправлена на 2025-10-28, год национализации («2
   февраля») уточнён в `law.appr` (2025). Статус — «Обсуждается»:
   аукцион был назначен на 3 декабря 2025 года, но исход торгов ни в
   одном источнике не нашёлся (не выдумываем закрытие).

2) `c49c9d8b0` («Акционеры «Волга-Днепр» заявили об отказе от акций в
   пользу государства»). Личный WebFetch (kommersant.ru/doc/8005070)
   подтвердил дословно: «29.08.2025, 16:59» и «Владельцы авиакомпании
   «Волга-Днепр» направили в правительство заявление о добровольном
   отказе от прав собственности». Это НЕ дубль уже существующей
   карточки `c6fd3a848` (24.08.2025, «Не состоялась» — основатель
   Исайкин объявил коллективу о ПЛАНАХ передать активы) — это следующий,
   более формальный этап той же истории 5 днями позже (акционеры подали
   письменное заявление). Итоговый исход всей саги уже в базе:
   `g1caed4b7` (30.12.2025, «Закрыта») — реальным покупателем стал
   Евгений Солодилин/ЕАС Групп, а не государство. Дата карточки
   исправлена на 2025-08-29, статус — «Не состоялась» (формальный отказ
   от акций в пользу государства тоже не реализовался), перекрёстная
   ссылка на реальный исход добавлена в `eco.context`.

3) `cb44ed7f0` («Возможная продажа сети «Рив Гош» компании
   «Севергрупп»»). Личный WebFetch (kommersant.ru/doc/7988676)
   подтвердил дословно: «24.08.2025, 17:47», «Двое из них называют
   основным претендентом на актив структуры «Севергрупп» Алексея
   Мордашова» и цитату о выручке «Аромалюкс» за 2024 год (данные СПАРК
   внутри статьи 2025 года — типичный лаг отчётности, не признак
   неверного года самой статьи). Переговоры с «Севергрупп» не привели к
   сделке — реальным покупателем стала Wildberries & Russ, уже
   заведённая отдельной, полной карточкой `g94683ed2` (15.12.2025,
   «Закрыта», источник kommersant.ru/doc/8292342 и другие). Дата
   исправлена на 2025-08-24, статус — «Не состоялась» (кандидат
   «Севергрупп» не выкупил актив), перекрёстная ссылка на реальную
   сделку добавлена в `eco.context`.

Запуск:
    python3 pipeline/fix_raven_volga_rivgauche_year.py            # сухой прогон
    python3 pipeline/fix_raven_volga_rivgauche_year.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_DATE = '2024'

OLD_LAW_APPR_RAVEN = (
    '2 февраля Арбитражный суд Москвы полностью удовлетворил иск '
    'Генпрокуратуры России к Raven Russia. По решению суда 16 складских '
    'комплексов компании, построенных или купленных девелопером с 2005 '
    'года, признаны транспортными терминалами и подлежат передаче '
    'Росимуществу.'
)
NEW_LAW_APPR_RAVEN = OLD_LAW_APPR_RAVEN.replace(
    '2 февраля Арбитражный суд', '2 февраля 2025 года Арбитражный суд'
)

OLD_ECO_CONTEXT_VOLGA = (
    'На рынке обсуждают несколько версий: от попытки спасти убыточный '
    'бизнес — минус 88 млн ₽ в 2023 году — до подготовки сделки с '
    '«Ростехом», которому могут быть интересны самолёты для военных '
    'перевозок. В Red Wings, дочерней компании «Ростеха», эту версию '
    'назвали беспочвенной.'
)
NEW_ECO_CONTEXT_VOLGA = OLD_ECO_CONTEXT_VOLGA + (
    ' Ни план передачи государству (см. также карточку c6fd3a848 от '
    '24 августа 2025 года), ни формальный отказ от акций не '
    'реализовались: реальным покупателем группы стал Евгений '
    'Солодилин через ЕАС Групп (карточка g1caed4b7, сделка закрыта '
    '30 декабря 2025 года).'
)

OLD_ECO_CONTEXT_RIVGAUCHE = (
    'Статья содержит аналитический обзор возможной сделки. Источники '
    'указывают, что договоренность могла быть достигнута в ходе '
    'обсуждения покупки «Улыбки радуги». При закрытии сделки «Рив Гош» '
    'может быть интегрирована в ритейл-дивизион с оптимизацией '
    'бэк-офиса, логистики, закупок и складских мощностей с участием '
    '«Ленты» и «Улыбки радуги».'
)
NEW_ECO_CONTEXT_RIVGAUCHE = OLD_ECO_CONTEXT_RIVGAUCHE + (
    ' Переговоры с «Севергрупп» не завершились сделкой: реальным '
    'покупателем сети стала Wildberries & Russ (карточка g94683ed2, '
    'сделка закрыта 15 декабря 2025 года).'
)


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    raven = by_id['caeac8f4e']
    volga = by_id['c49c9d8b0']
    rivgauche = by_id['cb44ed7f0']

    assert raven['date'] == OLD_DATE, 'caeac8f4e date уже другая: %r' % (raven['date'],)
    assert raven.get('status') is None, 'caeac8f4e status уже занят: %r' % (raven.get('status'),)
    assert raven['law']['appr'] == OLD_LAW_APPR_RAVEN, \
        'caeac8f4e law.appr уже другой: %r' % (raven['law']['appr'],)
    assert volga['date'] == OLD_DATE, 'c49c9d8b0 date уже другая: %r' % (volga['date'],)
    assert volga.get('status') is None, 'c49c9d8b0 status уже занят: %r' % (volga.get('status'),)
    assert volga['eco']['context'] == OLD_ECO_CONTEXT_VOLGA, \
        'c49c9d8b0 eco.context уже другой: %r' % (volga['eco']['context'],)
    assert rivgauche['date'] == OLD_DATE, 'cb44ed7f0 date уже другая: %r' % (rivgauche['date'],)
    assert rivgauche.get('status') is None, 'cb44ed7f0 status уже занят: %r' % (rivgauche.get('status'),)
    assert rivgauche['eco']['context'] == OLD_ECO_CONTEXT_RIVGAUCHE, \
        'cb44ed7f0 eco.context уже другой: %r' % (rivgauche['eco']['context'],)

    print('caeac8f4e: date %r -> "2025-10-28"; status None -> "Обсуждается"; '
          'law.appr уточнён (год суда)' % (OLD_DATE,))
    print('c49c9d8b0: date %r -> "2025-08-29"; status None -> "Не состоялась"; '
          'eco.context дополнен (реальный исход — ЕАС Групп)' % (OLD_DATE,))
    print('cb44ed7f0: date %r -> "2025-08-24"; status None -> "Не состоялась"; '
          'eco.context дополнен (реальный покупатель — Wildberries & Russ)' % (OLD_DATE,))

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    raven['date'] = '2025-10-28'
    raven['status'] = 'Обсуждается'
    raven['law']['appr'] = NEW_LAW_APPR_RAVEN

    volga['date'] = '2025-08-29'
    volga['status'] = 'Не состоялась'
    volga['eco']['context'] = NEW_ECO_CONTEXT_VOLGA

    rivgauche['date'] = '2025-08-24'
    rivgauche['status'] = 'Не состоялась'
    rivgauche['eco']['context'] = NEW_ECO_CONTEXT_RIVGAUCHE

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
