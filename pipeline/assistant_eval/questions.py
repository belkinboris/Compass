# «Подготовка к встрече» — как static/index.html, meetingPrepQuestion(name, about)
# ---------------------------------------------------------------------------
def meeting_prep_question(name: str, about: str = "") -> str:
    facts = ("Что важно знать о компании для этой встречи: чем занимается, кому принадлежит, масштаб. "
             "Её главные сделки за последние годы — списком со ссылками на карточки «Компаса» и с ролью компании в каждой; "
             "а если для моей цели важно, с кем из юристов и банков она работала, — назови их.")
    if not about:
        return (f"Готовлюсь к встрече с компанией «{name}». Коротко, по пунктам. {facts} "
                "Потом — что подготовить заранее и на что опереться в разговоре. Советы мне, участнику встречи; "
                "список вопросов к компании не составляй.")
    return (f"Готовлюсь к встрече с компанией «{name}». Обо мне и о встрече: «{about[:1200]}». "
            f"Помоги подготовиться именно к этой встрече, исходя из того, кто я и чего хочу. Коротко, по пунктам. {facts} "
            "Потом — как подготовиться и построить разговор, чтобы добиться моей цели: на какие сделки и факты опереться, "
            "что принести или показать. Советы мне, участнику встречи, а не компании; "
            "список вопросов к компании не составляй.")


