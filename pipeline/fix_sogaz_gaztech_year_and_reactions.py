import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g3bb1fadb'

OLD_DATE = '2024'
NEW_DATE = '2026'

OLD_CONTEXT = (
    'Хотя европейские компании получат компенсацию, размер которой '
    'определяет правительство, эти средства будут заморожены в России '
    'на счетах типа С. Как отмечал «Ъ», это был первый случай '
    'принудительной продажи активов собственников из недружественных '
    'стран.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' Wintershall Dea назвала продажу экспроприацией: «Wintershall Dea '
    'инициировала два арбитражных разбирательства против РФ, ссылаясь '
    'на "экспроприацию" российских активов», оценив убытки в €5,3 млрд '
    '(Коммерсантъ, 2 октября 2024).'
)

NEW_SRC = ['Коммерсантъ', 'https://www.kommersant.ru/doc/7197940']


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['date'] == OLD_DATE
    assert deal['eco']['context'] == OLD_CONTEXT
    assert not any(s[1] == NEW_SRC[1] for s in deal['src']), 'источник уже в src'

    print('=== date: станет ===')
    print(NEW_DATE)
    print('\n=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src добавится ===')
    print(NEW_SRC)

    if write:
        deal['date'] = NEW_DATE
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].append(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
