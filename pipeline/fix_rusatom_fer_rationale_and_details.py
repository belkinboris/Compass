import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gd38acdec'

NEW_RATIONALE = (
    'Сделка по приобретению доли в ООО «ФЭР» позволит нам укрепить позиции '
    'на рынке продукции для очистки выхлопных газов, где мы уже являемся '
    'лидерами в производстве автокатализаторов, — заявила президент АО '
    '«ТВЭЛ» Наталья Никипелова (речь о другой «дочке» ТВЭЛ, новоуральском '
    '«Экоальянсе»).'
)

OLD_CONTEXT = (
    'По оценке эксперта, доля ФЭР на российском рынке катализаторов '
    '(систем очистки отработанных выхлопных газов) составляет 60–70%.'
)
CONTEXT_ADDITION = (
    ' Остальные 50% ФЭР по-прежнему у менеджмента Faurecia: «Изначально по '
    '35% в этой компании было у гендиректора пяти структур Faurecia в '
    'России Татьяны Громовой и операционного директора Faurecia в России '
    'Оливье Гриненберже, остальные доли по 6%... у директоров площадок в '
    'Тольятти Николая Афанасьева и Марины Давыденко» (Коммерсантъ) — '
    'Громова сейчас числится гендиректором самого ФЭР. До сделки, в 2023 '
    'году, «Форесия экологичные решения» получила заключения по 719-му '
    'постановлению правительства РФ о локализации «заднего глушителя в '
    'сборе «Гранта»» и каталитического конвертера — актив уже был '
    'локализован на момент покупки.'
)
NEW_CONTEXT = OLD_CONTEXT + CONTEXT_ADDITION

OLD_TARGET_FIN = '—'
NEW_TARGET_FIN = (
    'За 2024 год выручка ООО «ФЭР» составила 3 167 521 000 ₽, чистая '
    'прибыль — 585 263 000 ₽ (РБК Компании, по данным ФНС).'
)

NEW_SRC = [
    ['Атомная энергия 2.0', 'https://www.atomic-energy.ru/news/2024/08/23/148708'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6454433'],
    ['РБК Компании', 'https://companies.rbc.ru/id/1096320015604-ooo-foresiya-metalloproduktsiya-ikzost-sistems/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert 'rationale' not in deal['eco'] or not deal['eco']['rationale']
    assert deal['eco']['context'] == OLD_CONTEXT
    assert deal['eco']['target_fin'] == OLD_TARGET_FIN
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.rationale (новое поле): станет ===')
    print(NEW_RATIONALE)
    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('=== eco.target_fin: станет ===')
    print(NEW_TARGET_FIN)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['rationale'] = NEW_RATIONALE
        deal['eco']['context'] = NEW_CONTEXT
        deal['eco']['target_fin'] = NEW_TARGET_FIN
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
