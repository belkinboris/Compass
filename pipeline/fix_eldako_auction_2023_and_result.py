# -*- coding: utf-8 -*-
"""Месячная очередь качества, 11 сентября 2026 — карточка `ca754c77a`
(«Продажа завода «Эльдако» через аукцион») несла ГОД «2024», хотя её
единственный источник (Абирег) датирован 11 июля 2023 года, а исход
торгов подтверждён вторым, более поздним материалом того же издания —
15 августа 2023 года. Год сделки был неверен, а не только день/месяц —
такое `review.py` не умеет чинить по таблице (см. CLAUDE.md, «review.py
не умеет переносить сделку в другой год»), поэтому правка одноразовым
скриптом.

Личный WebFetch подтвердил дословно:

1) https://abireg.ru/newsitem/98356 (уже в `src`) — дата публикации
   «11.07.2023, 14:16»: год исходного объявления о торгах — 2023, не
   2024.

2) https://abireg.ru/newsitem/98827/ (новый источник, тот же Абирег,
   более поздняя статья с итогами торгов) — дата «15.08.2023, 10:46»;
   «победителем торгов стало «Управление известково-цементными
   активами», предложившее 610 млн рублей»; конкурент — «ООО «Рудпром»
   предложило сумму в 600 млн рублей за 100% акций завода «Эльдако»».
   Покупатель и сумма (610 млн ₽) уже верно стояли в карточке —
   подтверждены независимой (второй) статьёй, торги состоялись и
   исход не оспаривается.

`status` карточки был не заполнен вовсе — торги завершились реальной
продажей, ставится «Закрыта».

Запуск:
    python3 pipeline/fix_eldako_auction_2023_and_result.py            # сухой прогон
    python3 pipeline/fix_eldako_auction_2023_and_result.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_DATE = '2024'
NEW_DATE = '2023-08-15'

NEW_SRC = ['Абирег', 'https://abireg.ru/newsitem/98827/']


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['ca754c77a']

    assert d['date'] == OLD_DATE, 'date уже другая: %r' % (d['date'],)
    assert d.get('status') is None, 'status уже занят: %r' % (d.get('status'),)
    urls = {s[1] for s in d['src']}
    assert NEW_SRC[1] not in urls, 'источник уже добавлен'

    print('ca754c77a: date исправлена с 2024 (ошибочный год) на 2023-08-15 '
          '(дата итогов торгов), status -> Закрыта, добавлен подтверждающий '
          'источник (вторая статья Абирег с итогами торгов)')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['date'] = NEW_DATE
    d['status'] = 'Закрыта'
    d['src'].append(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
