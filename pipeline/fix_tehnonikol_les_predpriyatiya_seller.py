# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
`gf2080ce8` («Технониколь приобрела четыре лесопромышленных и
деревообрабатывающих предприятия», октябрь 2022, Закрыта) — продавец
не был назван вовсе ни у одного из четырёх предприятий.

Проверено ЛИЧНО прямым WebFetch (дословные цитаты):
- kommersant.ru/doc/5759905 (Коммерсантъ-Нижний Новгород, 10.01.2023):
  «По данным «СПАРК-Интерфакс», ООО МКД зарегистрировано в Нижнем
  Новгороде с 2007 года. Предлагает панельно-каркасные дома и дома из
  клееного бруса. Бенефициар – Андрей Пчелкин.»; «Назвать сумму сделок
  в пресс-службе компании отказались» — продавец нижегородского
  предприятия «Малоэтажные комфортные дома» установлен.

НЕ ВНЕСЕНО: (1) продавцы красноярских предприятий («ЛесСервис» и ДК
«Премьер-Лес») и свердловского «ДОК ТН-Нижний Тагил» — не названы ни в
одном проверенном источнике; (2) для «ДОК ТН-Нижний Тагил» нашёлся
настораживающий признак (юрлицо зарегистрировано в 2021 году
структурами, уже связанными с Технониколь, а не независимым
продавцом, и купило имущество ОБАНКРОТИВШЕГОСЯ Выйского ДОК на торгах
ещё в мае 2021-го — за год до даты этой карточки) — но это не
проверено дословной цитатой, относящей именно ЭТУ транзакцию (120 млн
₽, октябрь 2022) к тому же событию, поэтому не вносится; требует
отдельной проверки, прежде чем менять природу сделки для этого
предприятия; (3) подтверждение освоения заявленных 600 млн ₽ на
модернизацию — источников с прямой цитатой не нашлось; (4) смена
бренда/названия — не произошла ни у одного из четырёх предприятий.

Запуск: python3 pipeline/fix_tehnonikol_les_predpriyatiya_seller.py
        python3 pipeline/fix_tehnonikol_les_predpriyatiya_seller.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gf2080ce8'

OLD_ECO_CONTEXT = '—'
NEW_ECO_CONTEXT = (
    'Продавцом нижегородского предприятия «Малоэтажные комфортные '
    'дома» выступил его прежний владелец Андрей Пчелкин; сумму этой '
    'части сделки стороны не раскрыли. Продавцы трёх остальных '
    'предприятий — красноярских «ЛесСервис»/«Премьер-Лес» и '
    'свердловского «ДОК ТН-Нижний Тагил» — в открытых источниках не '
    'названы.'
)

OLD_SRC = [['РИА Недвижимость', 'https://realty.ria.ru/20230117/tekhnonikol-1845482123.html']]
NEW_SRC = OLD_SRC + [
    ['Коммерсантъ (Нижний Новгород)', 'https://www.kommersant.ru/doc/5759905'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
