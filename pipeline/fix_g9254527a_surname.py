# -*- coding: utf-8 -*-
"""Карточка g9254527a: фамилия в заголовке разошлась с телом самой статьи.

ЧТО СЛОМАНО. Заголовок карточки — «Компания ресторатора Флеганова приобрела
усадьбу в Екатеринбурге» — скопирован из заголовка источника (РИА
Недвижимость), но ТЕЛО той же статьи называет учредителя ООО «СтройИнвест»
иначе и со ссылкой на официальный реестр: «Согласно ЕГРЮЛ, учредителем ООО
"СтройИнвест" является Олег Ферганов, развивающий сеть ресторанов в
Екатеринбурге.» Расхождение — внутри самого источника (заголовок против
текста), не между источником и карточкой.

ПОЧЕМУ «ФЕРГАНОВ», А НЕ «ФЛЕГАНОВ». Тело статьи ссылается на ЕГРЮЛ —
официальный реестр юрлиц — для этого конкретного факта; заголовок такой
ссылки не несёт и типичен для того, где журналистские заголовки чаще
ошибаются в фамилиях, чем текст, сверенный с документом. Решение: доверять
формулировке, подкреплённой ссылкой на реестр.

ПОЧЕМУ НЕ ЧЕРЕЗ `review.py`. Его FIXES-таблица проверяет, что НОВОЕ значение
поля — дословная подстрока цитаты (для `seller`/`buyer_name` — с допуском на
падеж). Здесь правится ЗАГОЛОВОК целиком, а не одно значение стороны:
подстрочная проверка по цитате про ЕГРЮЛ не сработает на всём предложении
заголовка. Правка точечная (одно слово) и однократная, поэтому отдельный
скрипт с тем же уровнем строгости — `assert` на исходный текст перед записью.

Запуск:
    python3 pipeline/fix_g9254527a_surname.py            # сухой прогон
    python3 pipeline/fix_g9254527a_surname.py --write    # записать
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'
DEAL_ID = 'g9254527a'
OLD_TITLE = 'Компания ресторатора Флеганова приобрела усадьбу в Екатеринбурге'
NEW_TITLE = 'Компания ресторатора Ферганова приобрела усадьбу в Екатеринбурге'
QUOTE = ('Согласно ЕГРЮЛ, учредителем ООО "СтройИнвест" является Олег '
         'Ферганов, развивающий сеть ресторанов в Екатеринбурге.')


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}
    deal = by_id.get(DEAL_ID)
    assert deal is not None, 'нет сделки %s' % DEAL_ID
    assert deal.get('title') == OLD_TITLE, \
        'заголовок уже другой: %r' % deal.get('title')

    print('%s: title %r -> %r' % (DEAL_ID, OLD_TITLE, NEW_TITLE))
    print('  цитата (тело статьи, со ссылкой на ЕГРЮЛ): %r' % QUOTE)

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    deal['title'] = NEW_TITLE
    assert deal['title'] == NEW_TITLE, 'заголовок не записался'

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
