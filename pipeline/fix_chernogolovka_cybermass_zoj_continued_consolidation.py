# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g44fc5b69
(ГК «Черноголовка» купила производителя спортивного питания Cybermass,
ООО «Беркана») — искали продолжение стратегии консолидации предпринима-
теля Алексея Четвергова (ГК ЗОЖ) и уточняли цифру «60,2» (млн или млрд)
из уже стоявшего в карточке текста.

Цифра «60,2 млн руб.» ПРОВЕРЕНА лично прямым WebFetch (kommersant.ru/
doc/7478323) и оказалась УЖЕ ВЕРНОЙ в живой базе — опасение, что могла
закрасться опечатка «млрд», не подтвердилось: «с совокупной выручкой по
итогам 2023 года 60,2 млн руб.» — правка не нужна, отмечено здесь, чтобы
не тратить время повторной проверкой в будущем.

Консолидация продолжилась за пределы спортивного питания. Проверено
лично прямым WebFetch (shoppers.media, 18.02.2026): «АО "ГК ЗОЖ",
основанное гендиректором "Черноголовки" Алексеем Четверговым, приобрело
100% долей Московской ореховой компании, а также по 100% связанных с
ней "МОК-производство", "Стройсервис" и "Натс-трейд"» — бренд орешков
«Джаз», продавцы Евгений Зубенко и Алексей Скороходов, оценка суммы
(эксперт Артём Моторный) — «не более 600–700 млн руб.».

`eco.context` дополнен фактом о новой покупке как продолжении стратегии
консолидации того же предпринимателя.

НЕ ВКЛЮЧЕНО: регистрация ГК ЗОЖ товарного знака Fortex (категория
интимной гигиены) — отдельное, не связанное со спортпитом направление
того же владельца, слишком далеко от предмета этой карточки, чтобы
включать без искажения фокуса. Судьба бренда Cybermass (ребрендинг,
новые линейки) — ничего не найдено ни в одном источнике, бренд
продолжает продаваться без изменений. Консолидированные финансовые
показатели всей группы «ГК ЗОЖ» — не публиковались.

Запуск: python3 pipeline/fix_chernogolovka_cybermass_zoj_continued_consolidation.py
        python3 pipeline/fix_chernogolovka_cybermass_zoj_continued_consolidation.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g44fc5b69'

OLD_CONTEXT = (
    'Консолидировать активы в сфере спортивного питания предприниматель '
    'начал два года назад, выкупив производителя «Прайм-Крафт» (см. '
    '«Ъ» от 17 мая 2023 года). За 2023 год выручка этой компании '
    'составила 827,8 млн руб., увеличившись год к году на 33,9%. Кроме '
    'того, под контролем ГК ЗОЖ еще три небольшие профильные структуры '
    '— «Вижн Чейн», «Мэджик Сториз» и «Плантаго» — с совокупной '
    'выручкой по итогам 2023 года 60,2 млн руб.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' Консолидация продолжилась за пределы спортпита: «АО "ГК ЗОЖ",'
    ' основанное гендиректором "Черноголовки" Алексеем Четверговым, '
    'приобрело 100% долей Московской ореховой компании» (бренд орешков '
    '«Джаз»), а также связанных с ней «МОК-производство», «Стройсервис» '
    'и «Натс-трейд» (shoppers.media, 18 февраля 2026 года).'
)

NEW_SRC = [
    ['shoppers.media', 'https://shoppers.media/news/26996_kompaniia-gendirektora-cernogolovki-kupila-proizvoditelia-oreskov-dzaz'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT

    new_src = deal['src'] + NEW_SRC

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
