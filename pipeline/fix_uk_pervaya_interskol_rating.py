"""Месячная очередь (REVISION_BRIEF), карточка g942865d3 (УК «Первая»/
«Интерскол»): дельта-поиск нашёл независимое (от рейтингового агентства
НКР) подтверждение того, что заявленная цель инвестиции — снижение
долговой нагрузки — реально сработала: доля собственного капитала
выросла с 11% до 30% «в результате вхождения новых инвесторов», и
кредитный рейтинг «КЛС-Трейд» повышен. Не через review.py: старое
значение eco.context — о структуре собственности, из другого источника,
не образует непрерывный кусок с этой цитатой.

Источник — читал напрямую (fetch_article_texts.py, закэширован):
НКР (ratings.ru, 19.06.2026), уже добавлен в src.
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g942865d3'

OLD_CONTEXT = (
    'Совладельцами АО «Интерскол групп» согласно системе СПАРК с 2016 '
    'года значатся четверо российских граждан. Основная часть бизнеса '
    'сосредоточена в 100-процентной дочерней компании «КЛС-трейд». В '
    'структуру группы также входит компания «СБК инструмент».'
)
ADDITION = (
    'НКР повысило кредитный рейтинг «КЛС-Трейд» с BB+.ru до BBB-.ru, '
    'прогноз — стабильный: доля собственного капитала компании '
    'увеличилась с 11% до 30% в результате вхождения новых инвесторов '
    'в состав акционеров и внесения ими денежных средств на депозит '
    'компании — независимое подтверждение того, что заявленная цель '
    'инвестиции (снижение долговой нагрузки) реализована.'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} eco.context: += независимое подтверждение снижения "
          f"долговой нагрузки (НКР)")
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
