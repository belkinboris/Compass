# -*- coding: utf-8 -*-
"""Заметка владельца 11 сентября 2026 (id решения 605, карточка g4165ba00,
«ГК «Мать и дитя» рассматривает приобретение сети лабораторий «Инвитро»»):
«еще даже 2 года не прошло, конечно оставляем, что обсуждается. В разделе
"Условия сделки" в разделе юрист написано "Собственники «Инвитро» при этом
не ищут покупателей на свой актив." это даже близко не условия сделки. ты
вообще карту эту вычитывал или нет?»

Статус НЕ меняется (владелец явно сказал оставить «Обсуждается»). Дефект —
только в `law.terms`: фраза про отсутствие интереса продавца к продаже —
это факт о контексте/правдоподобии сделки, а не условие сделки (заверение,
опцион, earn-out и т. п. — см. CLAUDE.md, «Что искать для линзы «Юрист»»).
`law.terms` очищен, факт перенесён в `eco.context` рядом с уже стоящим там
опровержением Курцера — там ему самое место.

Запуск: python3 pipeline/fix_mat_i_ditya_invitro_terms_cleanup.py [--write]
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE_PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g4165ba00'
OLD_TERMS = 'Собственники «Инвитро» при этом не ищут покупателей на свой актив.'
OLD_CONTEXT = ('В 2023 году основатель и владелец «Инвитро» Александр '
               'Островский продал сеть предпринимателю Роману Мирончику; '
               'партнёром Мирончика называют Алексея Крапивина, чьи '
               'интересы связывают с Аркадием Ротенбергом. Если сделка '
               'состоится, это будет второе крупное объединение после '
               'сделки «Медскан» и KDL. 29 августа 2025 года гендиректор '
               '«Мать и дитя» Марк Курцер публично опроверг сами '
               'переговоры: публикация стала для компании неожиданностью, '
               'переговоров с собственниками «Инвитро» не было и не '
               'планировалось, а сотрудничество двух компаний '
               'ограничивается диагностикой. С этой даты тема в прессе не '
               'всплывала.')
NEW_CONTEXT = (OLD_CONTEXT + ' Собственники «Инвитро» при этом не ищут '
               'покупателей на свой актив.')


def main(write=False):
    with open(BASE_PATH, encoding='utf-8') as f:
        base = json.load(f)

    card = next((c for c in base['deals'] if c['id'] == CARD_ID), None)
    assert card is not None, 'карточка %s не найдена' % CARD_ID
    assert card['law']['terms'] == OLD_TERMS, 'law.terms уже другой'
    assert card['eco']['context'] == OLD_CONTEXT, 'eco.context уже другой'
    assert card['status'] == 'Обсуждается', 'статус уже другой — не трогать'

    card['law']['terms'] = '—'
    card['eco']['context'] = NEW_CONTEXT

    print('Правка %s: law.terms очищен, факт перенесён в eco.context; '
          'статус не менялся.' % CARD_ID)

    if write:
        with open(BASE_PATH, 'w', encoding='utf-8') as f:
            json.dump(base, f, ensure_ascii=False, indent=1)
            f.write('\n')
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
