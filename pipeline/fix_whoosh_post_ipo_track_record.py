# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка g58d70492 (IPO Whoosh):
дельта-поиск нашёл, как сложилась публичная судьба компании за три года
после IPO — капитализация упала втрое, а из двух объявленных дивидендов
ни один не был выплачен по итогам ПОЛНОГО года. В карточке этого не было
вовсе — eco.context заканчивался на моменте самого размещения 2022 года.

Источники: пресс-релиз Московской биржи к третьей годовщине листинга
(капитализация, free-float) и официальная страница дивидендов Whoosh
(таблица выплат) — оба читал напрямую, не через агента.

Не через review.py: два факта из двух РАЗНЫХ источников, дословная
проверка по одной цитате здесь не подходит.
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g58d70492'
OLD_CONTEXT = (
    'Более половины общего объема выкупили ведущие российские '
    'инвестиционные фонды, сообщила компания в пресс-релизе. Также '
    'акционерами стали более 20 000 частных инвесторов.'
)
ADDITION = (
    'К третьей годовщине листинга (14 декабря 2025 года) рыночная '
    'капитализация компании снизилась до 10,3 млрд руб. против 20,6 млрд '
    'руб. на момент IPO, а доля акций в свободном обращении выросла '
    'примерно до 38% (пресс-релиз Московской биржи). Компания дважды '
    'выплачивала дивиденды за промежуточные периоды — 10,25 руб. на акцию '
    'за 9 месяцев 2023 года и 2,11 руб. на акцию за 9 месяцев 2024 года, '
    'но по итогам ни одного полного финансового года с 2022 по 2025 '
    'дивиденды так и не выплачивались.'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} eco.context: += капитализация и дивидендная история "
          "за три года после IPO")
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
