# -*- coding: utf-8 -*-
"""Дата-заглушка «известен только год» (1 января) — там, где источник знает день.

ЧТО СЛОМАНО. 339 карточек несут дату вида `YYYY-01-01` — заглушку «год
известен, день нет». У 23 из них единственный источник — статья, чей URL сам
несёт дату публикации, отличную от года заглушки. `fix_brookes_school_date.py`
починил первую такую карточку (Brookes School) точечно; здесь — измеренный
остаток партии (см. PRODUCT_ROADMAP.md, «работай по отчёту»).

КАЖДАЯ ИЗ 23 ПРОЧИТАНА ВРУЧНУЮ — правило «дата в URL отличается от даты
карточки» само по себе ничего не доказывает (урок этого же прогона:
`g2544a5cb` совпало формально, а по факту источник — статья 2014 года про
пенсионные деньги «Роснефти», к покупке клиник Литфонда отношения не имеющая).
Проверка на каждую карточку: слаг URL (название сторон/предмета в адресе
статьи) обязан называть ТЕ ЖЕ стороны/предмет, что в заголовке карточки.

20 КАРТОЧЕК — слаг называет ту же сделку, дата берётся из даты публикации.

1 КАРТОЧКА С ПОПРАВКОЙ (`g2bb8cf3a`, ПСБ/СМП-банк). Наивное правило «первый
источник в списке» дало бы 2022-09-08 (Ведомости, «сделка идёт по плану» —
статья о ХОДЕ сделки, не о её закрытии). У карточки восемь источников;
РБК и РИА Новости датированы 30 декабря 2022 года и оба говорят о сделке как
о СВЕРШИВШЕЙся («ПСБ подтвердил покупку» — заголовок Forbes из того же
списка), это и есть настоящая дата, а не дата статьи о промежуточном статусе.

3 КАРТОЧКИ НЕ ТРОГАЕМ — здесь дело не в дате, а в самом источнике: слаг URL
называет СОВСЕМ ДРУГИЕ стороны/предмет, чем заголовок карточки:
  * `g7ae9bb53` («Энерготехника Северо-Запад» / «Ямалдорстрой») — источник
    dp.ru про «бенефициара «Петербургской звезды»», ни одно имя не совпадает.
  * `gfcfba8c9` (ТЦ «Аура» → «Металлист») — источник про производителя
    стройматериалов Grand Line, покупающего торговые центры; «Металлист» в
    заголовке источника не упомянут, связь не подтверждена.
  * `g2544a5cb` (клиники Литфонда) — источник 2014 года про пенсионные деньги
    «Роснефти», другая тема и десятилетием раньше.
Похоже, что при разборе к этим трём карточкам приклеился чужой источник —
это отдельный, более серьёзный дефект (не дата, а сама ссылка), для починки
нужен вживую читаемый текст статьи, которого у нас нет. Записано в бэклог.

Запуск:
    python3 pipeline/fix_placeholder_dates_from_sources.py            # сухой прогон
    python3 pipeline/fix_placeholder_dates_from_sources.py --write    # записать
"""
import json
import sys

PATH = 'static/data/deals_promoted.json'

# id -> (было, стало)
FIXES = {
    'gfa0fe27a': ('2024-01-01', '2023-04-19'),
    'g3e3f233c': ('2024-01-01', '2023-09-26'),
    'gafe121ae': ('2024-01-01', '2026-04-21'),
    'geb8edd5c': ('2024-01-01', '2025-09-15'),
    'g7e90c94a': ('2024-01-01', '2025-04-21'),
    'gf3c5069f': ('2024-01-01', '2025-03-05'),
    'g44aef88b': ('2024-01-01', '2025-02-05'),
    'gd75ae46f': ('2024-01-01', '2023-04-06'),
    'g8ce554c5': ('2024-01-01', '2023-12-21'),
    'g9a575c07': ('2024-01-01', '2023-10-06'),
    'gb5e69c73': ('2024-01-01', '2023-09-20'),
    'g7d5f252d': ('2024-01-01', '2023-08-29'),
    'g5ddac2b5': ('2024-01-01', '2023-08-10'),
    'g1d76aeb5': ('2024-01-01', '2023-08-11'),
    'g8fb922a6': ('2024-01-01', '2023-04-21'),
    'g23827051': ('2024-01-01', '2023-02-20'),
    'gdf91b653': ('2024-01-01', '2023-01-19'),
    'g5b65aad0': ('2024-01-01', '2022-12-13'),
    # Не первый источник в списке — см. docstring: РБК/РИА (30.12.2022)
    # говорят о свершившейся сделке, Ведомости (08.09.2022) — о ходе.
    'g2bb8cf3a': ('2023-01-01', '2022-12-30'),
    'g5fd0e682': ('2022-01-01', '2023-05-19'),
}

# Не трогаем: слаг источника называет другую сделку. Список — чтобы следующий
# прогон не подхватил их автоматически, а показал явно, что они пропущены
# намеренно, а не забыты.
SKIPPED_WRONG_SOURCE = {
    'g7ae9bb53': 'источник dp.ru про «Петербургскую звезду» — не про «Ямалдорстрой»',
    'gfcfba8c9': 'источник про Grand Line — «Металлист» в нём не назван',
    'g2544a5cb': 'источник 2014 года про пенсионные деньги «Роснефти» — другая тема',
}


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    changes = []
    for did, (old, new) in FIXES.items():
        d = by_id[did]
        actual = d.get('date')
        assert actual == old, f'{did}.date: ожидали {old!r}, нашли {actual!r}'
        changes.append((did, old, new))
        if write:
            d['date'] = new

    print(f'правок: {len(changes)}')
    for did, old, new in changes:
        print(f'  {did}: {old!r} -> {new!r}')
    print(f'\nпропущено (источник о другой сделке, не трогаем): {len(SKIPPED_WRONG_SOURCE)}')
    for did, why in SKIPPED_WRONG_SOURCE.items():
        print(f'  {did}: {why}')

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=1, ensure_ascii=False)
        print('\nЗАПИСАНО в', PATH)
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
