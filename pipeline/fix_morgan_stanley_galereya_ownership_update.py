import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g577cd599'

OLD_ECO_CONTEXT = (
    'Его в 2010 г. построила казахстанская Meridian Capital, вложив в '
    'проект свыше $500 млн. Спустя год «Галерею» за рекордные $1,1 млрд '
    'приобрел фонд Morgan Stanley. Почти 75% средств на эту сделку '
    'предоставила китайская China Investment Corporation (CIC).'
)
NEW_ECO_CONTEXT = OLD_ECO_CONTEXT + (
    ' Даже спустя почти три года после объявления сделка публично не '
    'подтверждена ни как закрытая, ни как сорвавшаяся: в июне 2026 '
    'источники по-прежнему пишут, что «официальных заявлений, что сделка '
    'состоялась, не было». При этом сама SPV, владеющая ТРЦ (ООО '
    '«Строительная Компания Бриз»), сменила собственника 3 декабря 2025 '
    'года — единственный участник новой структуры («Гринвич») называется '
    'Galaxy 59 Holding Limited (ОАЭ), но ни один источник не подтверждает, '
    'что это структура именно Mubadala. Номинальная стоимость перешедшей '
    'доли — 975,25 млн ₽, доля в залоге у Сбербанка. Остаётся открытым и '
    'вопрос, требовалось ли для этого перехода согласие государственных '
    'органов — источники называют это невыясненным, поскольку конечный '
    'бенефициар остаётся иностранным.'
)

OLD_ECO_VAL = 'Экспертные оценки; 60–106 млрд ₽ (по оценке) или безденежная сделка'
NEW_ECO_VAL = OLD_ECO_VAL + (
    '. В сентябре 2023 года встречалась и более узкая вилка — 30–50 '
    'млрд ₽ (со ссылкой на «Ведомости») — обе оценки экспертные и '
    'относятся к одному и тому же периоду.'
)

OLD_ECO_TARGET_FIN = '—'
NEW_ECO_TARGET_FIN = (
    'ООО «Строительная Компания Бриз» (SPV, владеет ТРЦ «Галерея»): '
    'выручка за 2024 год — 11,5 млрд ₽, активы — 36,8 млрд ₽, чистые '
    'активы — 27,2 млрд ₽; за 2025 год выручка — 11,2 млрд ₽ (−3%), '
    'чистая прибыль упала в 6,3 раза, до 1,3 млрд ₽.'
)

NEW_SRC = [
    ['dp.ru', 'https://www.dp.ru/a/2025/12/19/trk-galereja-smenil-sobstvennika'],
    ['Fontanka', 'https://www.fontanka.ru/2026/06/18/76479677/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['eco']['val'] == OLD_ECO_VAL
    assert deal['eco']['target_fin'] == OLD_ECO_TARGET_FIN

    new_src = deal['src'] + NEW_SRC

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== eco.val: станет ===')
    print(NEW_ECO_VAL)
    print('\n=== eco.target_fin: станет ===')
    print(NEW_ECO_TARGET_FIN)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['eco']['val'] = NEW_ECO_VAL
        deal['eco']['target_fin'] = NEW_ECO_TARGET_FIN
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
