# -*- coding: utf-8 -*-
"""Правит два дефекта, вскрытых тестами после записи партии 5 агентов
(14 августа 2026): 6 юридических полей начинались со строчной буквы (перенос
цитаты не подхватывал заглавную), и одна цитата в `law.appr` оказалась не
согласованием, а описанием ареста акций — судебное ограничение, а не
разрешение регулятора, ему место в «Условиях».

1) КАПИТАЛИЗАЦИЯ. Все 6 значений — законченные предложения с подлежащим на
месте (у пяти оно названо прямо: «ПГК», «банк», «Севергрупп», «предприятие»,
«покупка», «компания»), просто цитата начиналась не с начала предложения
источника. Правится заглавной буквой на месте, факт не меняется.

2) g926d097b/law.appr — «акции «Приосколья» сейчас арестованы... продажа
будет реальна лишь после снятия этой меры» не называет ни один орган
согласования (`test_approval_names_a_body` тест прав: это не согласование, а
отлагательное условие — что должно произойти до закрытия сделки). Переносится
в `law.terms` (вторым абзацем к уже стоящему там факту о структуре владения),
`law.appr` возвращается к честному прочерку «Публично не сообщалось» — того
же значения, что было до записи 14 августа.

Запуск: python3 pipeline/fix_agents100_test_failures.py            # сухой
        python3 pipeline/fix_agents100_test_failures.py --write    # запись
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CAPITALIZE = [
    ('gb101d54d', 'struct',
     'в феврале 2024 года ПГК заложила в качестве обеспечения 66,8 тыс. '
     'вагонов стоимостью 92,1 млрд руб.'),
    ('gfecb608d', 'struct',
     'банк не выступает покупателем напрямую в связи с тем, что сделку '
     'провели через аффилированные со Сбербанком компании, но в его '
     'интересах'),
    ('g8c32cefd', 'struct',
     'с 1 октября «Севергрупп» получила в собственность активы предприятий '
     'группы «Метеор» в Энгельсе, а также группы компаний «Кордиант».'),
    ('g1e73548b', 'struct',
     'предприятие, ранее принадлежавшее французской Leoni Wiring Systems '
     'France (62,49%), а также немецким Leoni Bordnetz-Systeme GmbH '
     '(37,49%) и Leoni Bordnetze Verwaltungs GmbH (0,015%), с 28 февраля '
     'перешло под контроль нижегородского ООО "Импульс".'),
    ('g1e73548b', 'appr',
     'покупка была одобрена правительственной комиссией РФ по контролю за '
     'осуществлением иностранных инвестиций.'),
    ('ge571a54e', 'appr',
     'компания получила все необходимые для сделки корпоративные '
     'одобрения, а также разрешения регулирующих органов Республики '
     'Армения - Государственной комиссии защиты экономической конкуренции '
     'и Комиссии по регулированию общественных услуг.'),
]

MOVE_ID = 'g926d097b'
MOVE_OLD_APPR = (
    'Однако один из собеседников издания на рынке говорит, что акции '
    '«Приосколья» сейчас арестованы. В этом случае, по словам руководителя '
    'практики банкротства компании «Митра» Антона Томилина, продажа будет '
    'реальна лишь после снятия этой меры, и такая возможность не исключена.')
MOVE_NEW_APPR = 'Публично не сообщалось'
MOVE_OLD_TERMS = (
    'Партнер юрфирмы «Рустам Курмаев и партнеры» Дмитрий Клеточкин пояснил '
    'газете, что если конечный бенефициар владеет бизнесом через третьих лиц, '
    'то продать актив несложно. В случае если компания принадлежит ему '
    'напрямую, то возможно оформление в другой стране по нотариальной '
    'доверенности.')
MOVE_NEW_TERMS = MOVE_OLD_TERMS + ' ' + MOVE_OLD_APPR


def main(argv):
    data = json.load(open(DATA, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}
    write = '--write' in argv

    for cid, field, old in CAPITALIZE:
        deal = by_id[cid]
        cur = (deal.get('law') or {}).get(field)
        assert cur == old, '%s law.%s уже другое: %r' % (cid, field, cur)
        new = old[0].upper() + old[1:]
        print('КАПИТАЛИЗАЦИЯ %s law.%s' % (cid, field))
        if write:
            deal['law'][field] = new

    deal = by_id[MOVE_ID]
    assert deal['law']['appr'] == MOVE_OLD_APPR, 'law.appr уже другое'
    assert deal['law']['terms'] == MOVE_OLD_TERMS, 'law.terms уже другое'
    print('ПЕРЕНОС %s: арест акций из law.appr в law.terms, law.appr -> %r'
          % (MOVE_ID, MOVE_NEW_APPR))
    if write:
        deal['law']['appr'] = MOVE_NEW_APPR
        deal['law']['terms'] = MOVE_NEW_TERMS

    if not write:
        print('\nСухой прогон. Запись — с ключом --write.')
        return 0

    json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('ЗАПИСАНО.')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
