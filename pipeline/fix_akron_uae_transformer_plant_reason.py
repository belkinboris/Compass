import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g507c9a35'

OLD_CONTEXT = '—'
NEW_CONTEXT = (
    'Сделка сорвалась из-за разногласий в оценке предмета: «Разногласия '
    'в оценке бизнеса, финансовом результате. Мы отправили предоплату, '
    'после этого сделали аудит, не получили необходимую финмодель, и, '
    'фактически, потеряли задаток» (Павел Морозов, гендиректор Акрон '
    'холдинга, Интерфакс, 29 апреля 2025 года). На вопрос о новых '
    'проектах на Ближнем Востоке Морозов ответил: «Пока нет».'
)

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/business/1023418'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT

    new_src = deal['src'] + NEW_SRC

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
