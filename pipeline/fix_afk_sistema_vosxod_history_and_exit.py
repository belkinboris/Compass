import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g424715f8'

OLD_EXTRA = (
    'АФК «Система» продала 22,5% акций рыбопромышленного холдинга '
    '«Восход» компании АО «Краунинвест», владельцем которой является '
    'Ольга Зачиняева. РПХ «Восход» был создан АФК осенью 2021 года и '
    'объединяет активы добычи, переработки, хранения и трейдинга '
    'рыбопродукции с годовым объемом вылова 27–35 тысяч тонн.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Холдинг собирался из нескольких приобретений: в июле 2022 года '
    'АФК купила 75% ООО «Кристалл Фиш», 10% ООО «Хангар» и довела долю '
    'в ООО «Заря» до 90% (за неё заплачено 6,2 млрд ₽), а в январе '
    '2023 года — 100% ООО «Лойд-Фиш» на западном побережье Камчатки '
    '(девять рыболовных участков, 16 судов, два завода мощностью '
    '440 тонн в сутки), после чего «Восход» стал одним из крупнейших '
    'холдингов по вылову тихоокеанского лосося в России. Позже '
    '«Краунинвест» вышел из состава учредителей «Восхода» — куда '
    'перешла его доля, освещено в карточке о следующей смене контроля '
    'над холдингом.'
)

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/business/852315'],
    ['1prime.ru', 'https://1prime.ru/business/20230109/839417864.html'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/7695106'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
