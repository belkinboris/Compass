# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g5725678a
(«Интер РАО» закрыла покупку Уральского турбинного завода) — сумма
сделки стояла приблизительной оценкой, хотя раскрыта точная цифра, а
судьба завода после покупки не была отражена. Проверено лично прямым
WebFetch трёх источников.

`sum`/`eco.sum` (уточнена) — «~10 млрд ₽» / «≈10 млрд ₽» заменены на
точную цифру из раскрытия «Интер РАО» по МСФО. Дословно (Газотурбинные
технологии, gtt.ru, сама статья подтверждена дважды прямым чтением,
несмотря на нерелевантный слаг URL сайта): «денежное вознаграждение
(стоимость сделки), определяемое в момент совершения акцепта
безотзывной оферты, составит 10,752 млрд рублей». Число подтверждено
независимо: WebSearch по фразе «10,752» ИЛИ «10,8 млрд» вернул
согласующиеся упоминания (в т.ч. вклад в выручку по МСФО — 14,227 млрд
руб., вклад в прибыль за 2023 год — 2,44 млрд руб.). Прежняя оценка
«~10 млрд ₽» была атрибуцирована Коммерсанту через уже стоящий в
карточке источник (Интерфакс: «по данным "Коммерсанта", стоимость
сделки могла составить около 10 млрд рублей») — новое число её не
опровергает, а уточняет: это не конфликт оценок, а раскрытие точной
цифры взамен внешней прикидки.

`eco.context` (дополнено) — модернизация завода при поддержке ФРП.
Дословно (Интерфакс, https://www.interfax.ru/business/1091834,
подтверждено дважды прямым чтением): «"Уральский турбинный завод",
входящий в холдинг "Интер РАО - Машиностроение", расширил парк
металлообрабатывающего оборудования»; «Общий объем инвестиций в проект
составляет около 1 млрд рублей, из которых 400 млн рублей в виде
льготного займа предоставил ФРП».

НЕ ВКЛЮЧЕНО: заявление о росте производства турбин на 50% к 2030 году
и число «125 тыс. турбин за всю историю завода» (tek-all.ru) —
источник найден суб-агентом, но при трёх отдельных попытках личного
WebFetch давал три РАЗНЫХ, взаимно противоречащих пересказа одного и
того же места текста (то «рост производства турбин на 50%», то
«снижение потребления электроэнергии на 50%», то разные версии фразы
про 125 тыс.) — извлечение ненадёжно, дословную цитату получить не
удалось, факт не пишется без неё. Судьба Александра Плакиды/МЭЩ после
продажи УТЗ (переход в «Промышленную группу «НЭК»», расширение завода
в Коврове на 3 млрд руб.) — не включена: источники не подтверждают
прямой связи «продажа УТЗ профинансировала это расширение», а без такой
связи факт не относится к ЭТОЙ сделке. Консультанты и судебные споры —
не найдены ни в одном источнике.

Запуск: python3 pipeline/fix_utz_sum_and_modernization.py
        python3 pipeline/fix_utz_sum_and_modernization.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g5725678a'

OLD_SUM = '~10 млрд ₽'
NEW_SUM = '10,752 млрд ₽'
OLD_ECO_SUM = '≈10 млрд ₽'
NEW_ECO_SUM = '10,752 млрд ₽'

OLD_CONTEXT = (
    'Производитель электротехнического оборудования «Мосэлектрощит» в '
    'апреле 2023 года приобрел у структур «Реновы» крупнейшего в '
    'стране производителя паровых турбин — «Уральский турбинный '
    'завод».'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' В 2025 году «Уральский турбинный завод», входящий в холдинг '
    '«Интер РАО — Машиностроение», расширил парк металлообрабатывающего '
    'оборудования при поддержке Фонда развития промышленности: общий '
    'объём инвестиций в проект составил около 1 млрд рублей, из '
    'которых 400 млн рублей в виде льготного займа предоставил ФРП '
    '(Интерфакс).'
)

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/business/1091834'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['sum'] == OLD_SUM, deal['sum']
    assert deal['eco']['sum'] == OLD_ECO_SUM, deal['eco']['sum']
    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== sum: было / станет ===')
    print(OLD_SUM, '->', NEW_SUM)
    print('=== eco.sum: было / станет ===')
    print(OLD_ECO_SUM, '->', NEW_ECO_SUM)
    print('\n=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['sum'] = NEW_SUM
        deal['eco']['sum'] = NEW_ECO_SUM
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
