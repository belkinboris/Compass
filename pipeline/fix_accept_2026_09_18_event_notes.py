# -*- coding: utf-8 -*-
"""Приёмка карточек притока 18.09.2026: `events[0].note` у двух карточек
обрывался многоточием на середине предложения (класс уже описан в
CLAUDE.md — «Один и тот же обрыв на ~260 знаках»). `review.py`'s
`get_field()`/`set_field()` не адресуют элементы списка `events[]` по
`.`-пути (`events.0.note` — не вложенный словарь), поэтому правка идёт
здесь, с `assert` на исходное значение, как и `fix_g21795ec9_truncated_note.py`.

- gb1efa21d (Selectel/M1Cloud): дописано до конца цитаты Mergers.ru.
- g7c2329a4 («Зарубежнефть»/«Русхим»): служебный дайджест-хвост
  («🟢 Статус сделки: закрыта…») заменён связным пересказом закрытия из
  основной статьи Коммерсанта (та же цитата, что уже стоит в `src`/
  `buyer_name` этой карточки).

Запуск: python3 pipeline/fix_accept_2026_09_18_event_notes.py [--write]
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'pending.json')

OLD_SELECTEL = (
    'Сделка, общая сумма которой составит не более 2,6 млрд рублей, позволит укрепить '
    'позиции Selectel на облачном рынке, рассчитывают в компании. «Всю команду M1Cloud, '
    'которая занимается поддержкой продукта, работой с клиентами, мы намерены сохранить и…'
)
NEW_SELECTEL = (
    'Сделка, общая сумма которой составит не более 2,6 млрд рублей, позволит укрепить '
    'позиции Selectel на облачном рынке, рассчитывают в компании. «Всю команду M1Cloud, '
    'которая занимается поддержкой продукта, работой с клиентами, мы намерены сохранить и '
    'интегрировать к нам», — говорит Любимов.'
)

OLD_ZN = (
    '«Зарубежнефть» выкупила газовые активы «Русхима» в НАО 🟢 Статус сделки: закрыта в '
    '15 сентября 2026 Об объекте сделки Компании, владеющие лицензиями на разработку '
    'Кумжинского и Коровинского газоконденсатных месторождений в Ненецком автономном '
    'округе. АО «СН…'
)
NEW_ZN = (
    'Структура государственной «Зарубежнефти» «ЗН Перспектива» приобрела у «Русхима» ООО '
    'ЕСН, владеющее лицензией на Коровинское месторождение газа в Ненецком автономном '
    'округе. Соответствующие изменения в ЕГРЮЛ внесены 15 сентября. В тот же день '
    'гендиректор «ЗН Перспектива» Вячеслав Терентьев возглавил АО «СН Инвест», которому '
    'принадлежит лицензия на Кумжинское месторождение.'
)


def main(write):
    data = json.load(open(PATH, encoding='utf-8'))
    by_id = {c['id']: c for c in data['cards']}

    card = by_id['gb1efa21d']
    assert card['events'][0]['note'] == OLD_SELECTEL, card['events'][0]['note']
    card['events'][0]['note'] = NEW_SELECTEL

    card = by_id['g7c2329a4']
    assert card['events'][0]['note'] == OLD_ZN, card['events'][0]['note']
    card['events'][0]['note'] = NEW_ZN

    print('gb1efa21d, g7c2329a4: events[0].note дописаны до конца.')
    if write:
        json.dump(data, open(PATH, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
        print('ЗАПИСАНО.')
    else:
        print('Сухой прогон. Запись — с ключом --write.')


if __name__ == '__main__':
    main('--write' in sys.argv)
