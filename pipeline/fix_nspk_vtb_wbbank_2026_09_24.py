# -*- coding: utf-8 -*-
"""Приток 24 сентября 2026 (12:20 МСК), два новых этапа уже известных сделок.

gmru-nspk-privatization («Банк России готовит частичную приватизацию НСПК»):
на банковском форуме глава ВТБ Андрей Костин впервые назвал конкретный
размер доли, которую банк готов купить (5%), а глава ЦБ Эльвира Набиуллина
сообщила срок начала переговоров с покупателями (октябрь) и назвала новых
названных ранее претендентов (Wildberries, Ozon, МТС, «Яндекс» — они уже
были в новостях до этого дня, здесь впервые собраны в одном источнике).
Не веха (`negotiations` не входит в POSTWORTHY_MILESTONE_KINDS) — новый
этап дописывается в events без отдельного поста в канал.

c51d0bb64 («Партнерство Wildberries и ВТБ по развитию WB Банка»): SPO ВТБ
под сделку снова перенесено — с сентября на октябрь (третий перенос: было
август → сентябрь → сентябрь → октябрь). Тоже не веха.

Прямым скриптом, а не review.py FIXES, — оба поля eco.context дописывают
цитату к уже стоящему тексту (генерик-проверка check() требует, чтобы ВЕСЬ
новый текст поля лежал в цитате целиком, а не только добавленный кусок; то
же ограничение, что уже отмечено для gb7ea4703 и g17fc21d6, см. KNOWN_ISSUES.md),
а добавление events[] дотированные пути review.py не поддерживают.

Источники: https://www.vedomosti.ru/finance/news/2026/09/24/1231443-vtb-nspk,
https://www.interfax.ru/russia/1118184, https://www.interfax.ru/business/1118185,
https://www.dp.ru/a/2026/09/24/glava-vtb-zajavil-o-planah — все прочитаны
целиком, кэш в data/inbox/raw/2026-09-24-articles.jsonl.

Запуск: python3 pipeline/fix_nspk_vtb_wbbank_2026_09_24.py --write
"""
import argparse
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

VEDOMOSTI = ['Ведомости', 'https://www.vedomosti.ru/finance/news/2026/09/24/1231443-vtb-nspk']
INTERFAX_NSPK = ['Интерфакс', 'https://www.interfax.ru/russia/1118184']
INTERFAX_WB = ['Интерфакс', 'https://www.interfax.ru/business/1118185']
DP_RU = ['Деловой Петербург', 'https://www.dp.ru/a/2026/09/24/glava-vtb-zajavil-o-planah']

# --- НСПК ---------------------------------------------------------------
NSPK_ID = 'gmru-nspk-privatization'
NSPK_OLD_CONTEXT = (
    'На Финконгрессе глава РСХБ Борис Листов заявил, что войти в её капитал '
    'могут около 20 новых участников и Россельхозбанк готов стать одним из '
    'них. Набиуллина заявила 2 июля 2026 года: приватизация «до конца этого '
    'года вряд ли... случится» — сначала регулятор рассчитывает завершить '
    'оценку рыночной стоимости НСПК. К претендентам добавился ВТБ: первый '
    'зампред правления Дмитрий Пьянов заявил 28 июля 2026 года, что банк '
    'рассмотрит участие «после завершения оценки и появления предложения», '
    'а «условия частичной приватизации пока неизвестны».'
)
NSPK_QUOTE_ADD = (
    '24 сентября 2026 года на Международном банковском форуме глава ВТБ '
    'Андрей Костин впервые назвал конкретный размер доли: «Мы заинтересованы. '
    'Мы готовы купить 5%», — сказал он, отвечая на вопрос о возможном '
    'вхождении ВТБ в капитал НСПК. В тот же день глава Банка России Эльвира '
    'Набиуллина сообщила, что оценка НСПК завершается и в октябре регулятор '
    'рассчитывает начать консультации с потенциальными покупателями, '
    'подписавшими NDA; интерес она назвала большим. Ранее интерес к покупке '
    'доли в НСПК проявили Wildberries (группа RWB), Ozon, МТС и «Яндекс».'
)
NSPK_EVENT_NOTE = '«Мы заинтересованы. Мы готовы купить 5%», – сказал Костин, отвечая на вопрос о возможном вхождении ВТБ в капитал НСПК.'

# --- WB Банк --------------------------------------------------------------
WB_ID = 'c51d0bb64'
WB_OLD_CONTEXT = (
    '28 августа 2026 года первый зампред ВТБ Дмитрий Пьянов сообщил, что '
    'покупка миноритарной доли в WB-банке и финтех-активах перенесена на '
    'сентябрь, но параметры допэмиссии под неё принципиально не '
    'пересматривались: банк не форсирует сделку, понимая, что управленческие '
    'и человеческие ресурсы партнёра заняты последствиями чрезвычайных '
    'событий. 31 августа 2026 года он уточнил, что допэмиссия пройдёт в '
    'прежних диапазонах 300–400 млрд рублей, ближе к нижней границе, а '
    'участие розничных инвесторов будет скромным из-за разрыва в цене акций. '
    'Под вход в WB Банк ВТБ проводит допэмиссию около 500 млрд ₽ — это объём '
    'размещения акций самого банка, а не цена партнёрства; стоимость доли не '
    'раскрыта.'
)
WB_QUOTE_ADD = (
    '24 сентября 2026 года глава ВТБ Андрей Костин сообщил о новом переносе: '
    '«Да, она (допэмиссия — ИФ) перенеслась, но она будет», — сказал он, '
    'отвечая на вопрос, перенеслось ли SPO на октябрь.'
)
WB_EVENT_NOTE = '"Да, она ( допэмиссия - ИФ ) перенеслась, но она будет", - сказал Костин, отвечая на вопрос, перенеслось ли SPO на октябрь.'


def main(write):
    data = json.load(open(DATA, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}

    nspk = by_id[NSPK_ID]
    assert nspk['eco']['context'] == NSPK_OLD_CONTEXT
    nspk['eco']['context'] = NSPK_OLD_CONTEXT + ' ' + NSPK_QUOTE_ADD
    for pair in (VEDOMOSTI, INTERFAX_NSPK, DP_RU):
        if pair[1] not in {s[1] for s in nspk['src'] if len(s) > 1}:
            nspk['src'].append(pair)
    nspk.setdefault('events', []).append({
        'kind': 'negotiations',
        'date': '2026-09-24',
        'title': 'ВТБ заявил о готовности купить 5%',
        'note': NSPK_EVENT_NOTE,
        'source': VEDOMOSTI,
    })

    wb = by_id[WB_ID]
    assert wb['eco']['context'] == WB_OLD_CONTEXT
    wb['eco']['context'] = WB_OLD_CONTEXT + ' ' + WB_QUOTE_ADD
    if INTERFAX_WB[1] not in {s[1] for s in wb['src'] if len(s) > 1}:
        wb['src'].append(INTERFAX_WB)
    assert not wb.get('events')
    wb['events'] = [{
        'kind': 'negotiations',
        'date': '2026-09-24',
        'title': 'Допэмиссию под сделку снова перенесли — на октябрь',
        'note': WB_EVENT_NOTE,
        'source': INTERFAX_WB,
    }]

    if write:
        json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
        print('Записано: НСПК (eco.context, src, events) и WB Банк (eco.context, src, events).')
    else:
        print('Сухой прогон (--write, чтобы записать).')


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('--write', action='store_true')
    main(p.parse_args().write)
