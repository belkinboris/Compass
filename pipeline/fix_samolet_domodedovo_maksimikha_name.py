# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g2653122b
(«Самолёт» выкупил земельный актив у группы ВТБ под Домодедовом,
668 га рядом с ОЭЗ «Максимиха») — карточка закрыта и не менялась с
момента появления; найдено имя и параметры проекта, которых не было ни
в заголовке, ни в тексте.

Проверено лично прямым WebFetch (nsp.ru, 23 апреля 2024):
«В марте 2024-го Градсовет округа Домодедово Московской области
одобрил концепцию кластера ИЖС «Максимиха»», «На территории 668
гектаров будет построено 6,6 тысячи индивидуальных жилых домов (790
тысяч кв. м)», «Проект рассчитывают завершить в 2032 году».

НЕ ВКЛЮЧЕНО: сведений о начале строительства, продаже домов или
финансовых проблемах «Самолёта», привязанных именно к этому участку, за
2025-2026 годы не нашлось ни в одном источнике (проверены Ведомости,
Коммерсантъ, РБК Недвижимость, Metrium, сайт «Самолёта» и наш.дом.рф —
последние два недоступны прямым WebFetch, 401/403). Статья Metrium от
10.01.2025 упоминает участок мимоходом, без новых деталей сверх уже
известного и найденного здесь. Другие проекты «Самолёта» в Домодедово
(ЖК «Прибрежный Парк») и в Новой Москве (проданный в 2026 году участок
в Щаповском) — другие площадки, отношения к этой сделке не имеют.

Запуск: python3 pipeline/fix_samolet_domodedovo_maksimikha_name.py
        python3 pipeline/fix_samolet_domodedovo_maksimikha_name.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g2653122b'

OLD_EXTRA = (
    '«Самолет» выкупил у группы ВТБ бывший актив Coalco Василия '
    'Анисимова — 668 га земли рядом с ОЭЗ «Максимиха» под Домодедовом. '
    'Сделка пройдёт в несколько этапов. На площадке планируется '
    'строительство 810 000 кв. м малоэтажного жилья и инфраструктурных '
    'объектов (физкультурно-спортивный и термальный комплексы, '
    'досуговый центр, коворкинг). Ожидаемая численность жителей поселка '
    '— 18 000 человек.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' В марте 2024 года Градсовет округа Домодедово одобрил концепцию '
    'проекта под названием кластер ИЖС «Максимиха»: 6,6 тысячи '
    'индивидуальных жилых домов на 790 тысяч кв. м, завершение '
    'запланировано на 2032 год.'
)

NEW_SRC = [
    ['NSP.ru', 'https://nsp.ru/38697-masstabnye-proekty-izs-na-tysyacu-domov-i-bolee-riskovanny-no-obeshhayut-bolsie-pribyli'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
