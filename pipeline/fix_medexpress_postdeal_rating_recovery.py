# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g5d4b3840 (Allianz Group продала «Медэкспресс» «Юнион Апарт»,
02.11.2023, статус «Закрыта») — компания пережила спад сборов и
понижение рейтинга сразу после смены акционеров, но к 2025 году
стабилизировалась.

Проверено лично прямым WebFetch (Эксперт РА, 17.11.2025): «"Эксперт
РА" подтвердил кредитный рейтинг САО "Медэкспресс" на уровне ruA-»,
прогноз изменён на «стабильный» (был «развивающийся»), «взносы
компании составили 701,1 млн рублей, что на 2,7% больше, чем за
аналогичный период прошлого года» (9 месяцев 2025). По данным
саб-агента (Эксперт РА, 20.11.2024, не дозаверено отдельным
WebFetch): годом раньше рейтинг был понижен до ruA- (с ruA) со
сборами за 9 месяцев 2024 «665,8 млн рублей... на 0,4% меньше»
аналогичного периода 2023 года и убытком 15,4 млн руб. за 2023 год —
агентство прямо связывало понижение с «продолжающейся адаптацией
бизнес-процессов после смены акционеров».

НЕ ВКЛЮЧЕНО: расширение сети клиник «Мояклиника» — саб-агент проверил
и ОТКЛОНИЛ один кандидат (статья РБК оказалась про другую сеть,
«Скандинавия»/AVA-Peter, не связанную с «Медэкспрессом»); другие
приобретения Виктора Полугрудова/«Юнион Апарт» — не найдено; выход
Allianz из ОСТАЛЬНОГО российского бизнеса — это отдельная, более
ранняя история (продажа 50,1% «Интерхолдингу» ещё в мае 2023 года, до
сделки с «Медэкспрессом»), не относящаяся к этой карточке напрямую.

Запуск: python3 pipeline/fix_medexpress_postdeal_rating_recovery.py
        python3 pipeline/fix_medexpress_postdeal_rating_recovery.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g5d4b3840'

OLD_EXTRA = (
    'Закрытие сделки по продаже 100% акций петербургской страховой '
    'компании САО «Медэкспресс» (с сетью медцентров «Мояклиника») от '
    'Allianz Group к ООО «Юнион Апарт». Согласие Правительственной '
    'комиссии по контролю за иностранными инвестициями ожидалось '
    'более года. Юнион Апарт владеет Виктор Полугрудов (85%) и Иван '
    'Смирнов (15%).'
)
NEW_EXTRA = OLD_EXTRA + (
    ' После смены акционеров компания пережила спад: в ноябре 2024 '
    'года «Эксперт РА» понизил рейтинг до ruA- на фоне снижения '
    'сборов и убытка за 2023 год, связав это с «продолжающейся '
    'адаптацией бизнес-процессов после смены акционеров». К ноябрю '
    '2025 года ситуация стабилизировалась: рейтинг подтверждён на '
    'том же уровне, прогноз улучшен до «стабильного», сборы за 9 '
    'месяцев 2025 года выросли на 2,7% до 701,1 млн руб.'
)

NEW_SRC = [
    ['Эксперт РА', 'https://raexpert.ru/releases/2025/nov17e'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
