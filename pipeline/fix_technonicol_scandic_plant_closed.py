import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g8e78bbb2'

OLD_TARGET_FIN = '—'
NEW_TARGET_FIN = (
    'ООО «Скандик Констракшен» было убыточным ещё до сделки: убыток 6,8 '
    'млн руб. (2022), 46,6 млн руб. (2023). После сделки, в 2024 году, '
    'выручка составила 181,6 млн руб. при чистом убытке 115,8 млн руб. '
    '(runews24.ru).'
)

OLD_CONTEXT = '—'
NEW_CONTEXT = (
    'Предмет сделки — «крупнейшее предприятие каркасного домостроения '
    'по технологии префаб в северной Европе», на рынке домокомплектов '
    'более 20 лет, мощность — более 400 домов в год (Интерфакс). На '
    'момент покупки Технониколь планировала «сохранить все '
    'технологические разработки предприятия и предложить рынку '
    'премиальную серию проектов «Скандик»» (AKM). Но 6 октября '
    '2025 года, через 15 месяцев после покупки, компания объявила о '
    'закрытии завода в Буграх Ленинградской области с переносом '
    'производства на площадку в Семёнове (Нижегородская область) — '
    'причина не в предмете сделки, а в обвале рынка индивидуального '
    'жилищного строительства (в июне 2025 года падение достигало 40% '
    'год к году) (runews24.ru).'
)

NEW_SRC = [
    ['runews24.ru', 'https://runews24.ru/business/06/10/2025/texnonikol-zakroet-zavod-v-leningradskoj-oblasti'],
    ['Интерфакс', 'https://www.interfax.ru/business/969906'],
    ['AK&M', 'https://www.akm.ru/news/tekhnonikol_kupila_scandic_construction/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['target_fin'] == OLD_TARGET_FIN
    assert deal['eco']['context'] == OLD_CONTEXT

    new_src = deal['src'] + NEW_SRC

    print('=== eco.target_fin: станет ===')
    print(NEW_TARGET_FIN)
    print('\n=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['target_fin'] = NEW_TARGET_FIN
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
