# -*- coding: utf-8 -*-
"""Кто сопровождал сделку: имя фирмы из объявления, а не из догадки.

ПОЧЕМУ НЕ «ИСКАТЬ КОНСУЛЬТАНТА В ТЕКСТЕ». Первая попытка искала в посте слова
«консультант»/«советник» и любое знакомое название фирмы рядом. Замер на 133
живых постах девяти каналов: 11 срабатываний, ВЕРНЫХ НОЛЬ. В юридических
каналах «советник» — должность сотрудника («советник ККМП Алексей Чернышев»),
а «консультант» — слово из рейтингов («топ-5 юридических консультантов»);
правило поймало мастер-класс по арбитражу и пост про космонавтов.

ЧТО РАБОТАЕТ. Объявление о сопровождении — это пресс-релиз, и он устроен
одинаково: пост НАЧИНАЕТСЯ с имени фирмы, сразу за ним идёт глагол действия
по сделке. Замер на 669 постах канала @LawFirms: 18 срабатываний, все 18 —
настоящие объявления («White Square консультировала Nordgold…», «NEXTONS
представляла интересы «Ленты»…», «Юридическая фирма «Восход» сообщает о
сопровождении…»). Имя берётся ИЗ НАЧАЛА поста, а не ищется по всему тексту —
в этом вся разница: «советник LEVEL Legal Services провела мастер-класс»
таким правилом не проходит, потому что глагол не про сделку.

ГРАНИЦА. Модуль отвечает только на вопрос «какая фирма и что сделала». Он НЕ
решает, о какой сделке речь (это `match.py`) и является ли пост сделкой
вообще (это `classify.py`): «Юристы BGP Litigation сопровождали процесс
взыскания…» — верное срабатывание правила и не сделка M&A, отсекать такое
должен фильтр, а не переусложнённый шаблон имени.

СТОРОНА СДЕЛКИ не выводится догадкой: она ставится, только если в предложении
названа ровно одна из сторон («интересы покупателя», «на стороне продавца»).
Иначе роль остаётся общей — пустое поле честнее выдуманного.
"""
import re

# Глагол действия ПО СДЕЛКЕ. Именно он отделяет объявление от новости про
# должность или рейтинг. Все формы — включая именительный род («сопровождал»,
# «сопровождала», «сопровождали», «сопровождало»): урок про `продавц\w*`,
# который не совпадает со словом «Продавец».
#
# «выступил» само по себе слишком слабо: «Прокуратура ВЫСТУПИЛА ПРОТИВ
# принудительного выселения певицы» проходило бы как объявление о
# сопровождении. Поэтому у этого глагола обязательно требуем роль рядом
# (консультант/советник/юридический), а у «консультировал» и «сопровождал»
# роль уже внутри самого слова.
VERB = (r'(?:консультировал\w*|сопровождал[аио]?|сопровождали|сопровождает'
        r'|выступил[аио]?\s+(?:\w+\s+){0,3}(?:консультант\w*|советник\w*|юридическ\w+|финансов\w+)'
        r'|выступали\s+(?:\w+\s+){0,3}(?:консультант\w*|советник\w*)'
        r'|представлял[аи]?\s+интерес\w*'
        r'|оказал[аи]?\s+(?:\w+\s+){0,2}(?:юридическ\w+|правов\w+)\s+поддержк\w*'
        r'|[сc]ообщает\s+о\s+сопровождении|[сc]ообщил[аи]?\s+о\s+сопровождении'
        # «Команда LEVEL Legal Services завершила юридическое сопровождение
        # сделки…» — форма, которой не было в первом списке: правило молча
        # пропускало такие объявления, пока это не всплыло на партии из 10.
        r'|заверш\w+\s+(?:\w+\s+){0,3}сопровождени\w+'
        # Ещё три формы того же смысла, найденные при разборе оставшихся 468
        # постов канала: «обеспечила полное юридическое сопровождение»,
        # «осуществила комплексное юридическое сопровождение», «сообщает о
        # консультировании». Первый список был собран по одной партии из
        # десяти постов — и оказался списком ТЕХ ФОРМУЛИРОВОК, а не всех:
        # ровно тот же класс, что «правило, написанное для начала строки, не
        # видит того же дефекта в конце».
        r'|обеспечил\w*\s+(?:\w+\s+){0,3}сопровождени\w+'
        r'|осуществил\w*\s+(?:\w+\s+){0,3}сопровождени\w+'
        r'|[сc]ообщает\s+о\s+консультировании|[сc]ообщил[аи]?\s+о\s+консультировании)')

# Наречие между именем и глаголом («успешно завершила», «полностью
# сопровождала») попадает в захваченное имя и портит его.
TRAILING_ADVERB = re.compile(
    r'\s+(?:успешно|полностью|комплексно|также|недавно|ранее|оперативно)$', re.I)

# Между именем и глаголом сделки часто вклинивается «сообщает: её команда»:
# «VERBA LEGAL сообщает: её команда обеспечила юридическое сопровождение
# RWB…», «АЛРУД сообщает: фирма обеспечила сопровождение Покупателя…».
# Без этой вставки правило требовало глагол сразу за именем и такие
# объявления молча пропускало.
SAYS = r'(?:[сc]ообща\w+|[сc]ообщил\w*|информирует)\s*[:,–—-]?\s*(?:\w+\s+){0,4}'

# Имя фирмы стоит первым и начинается с ЗАГЛАВНОЙ. `(?-i:...)` обязателен:
# под `re.I` класс `[A-ZА-ЯЁ]` совпал бы и со строчной, и правило молча
# ловило бы любую фразу.
LEAD = re.compile(r'^\s*[«"“]?\s*((?-i:[A-ZА-ЯЁ])[^.!?\n]{1,70}?)\s*[»"”]?\s+(?:' + SAYS + r')?'
                  + VERB, re.I)

# Родовые слова перед именем: они часть фразы, а не часть названия фирмы.
# «Практика рынков капитала Better Chance обеспечила…» — практика фирмы, а не
# фирма: без этого в название попадало «Практика рынков капитала Better
# Chance», и на экране появился бы консультант с таким именем.
ROLE_PREFIX = re.compile(
    r'^(?:юридическ\w+\s+фирм\w+|юрфирм\w+|юрист\w+|команда\s+юрист\w+|команда'
    r'|коллеги\w+\s+адвокатов|адвокатско\w+\s+бюро|аб|бюро'
    # Квантификатор ЛЕНИВЫЙ (`{0,3}?`): жадный съедал «рынков капитала Better»
    # целиком — за ним тоже стоит заглавная («Chance»), и проверка «дальше имя
    # с заглавной» проходила на середине названия. Имя фирмы превращалось в
    # «Chance».
    r'|(?:команда\s+)?практик\w+\s+(?:\w+\s+){0,3}?(?=(?-i:[A-ZА-ЯЁ])))\s*', re.I)

# «X» сообщает: её команда… — хвост после имени не входит в название.
# `[сc]` — не опечатка: в канале встречается ЛАТИНСКАЯ «c» вместо кириллической
# («Nextons cообщает о запуске…»), и шаблон с одной кириллицей молча не
# срабатывает. Тот же класс беззвучного отказа, что `\b` после приставки.
TAIL_CUT = re.compile(r'\s*(?:[сc]ообща\w+|[сc]ообщил\w*|информирует)\b.*$', re.I)

SIDE_BUYER = re.compile(r'покупател\w+|инвестор\w*|приобретател\w+', re.I)
SIDE_SELLER = re.compile(r'продавц\w+|продавец|продающ\w+', re.I)
KIND_FIN = re.compile(r'финансов\w+\s+(?:консультант\w*|советник\w*)', re.I)


def strip_prefix(name):
    """Снять ВСЕ родовые слова подряд, а не одно.

    `RODE_PREFIX.sub` с якорем `^` срабатывает один раз, а родовых слов бывает
    два: «Команда практики рынков капитала White Square» — сначала «Команда»,
    потом «практики рынков капитала». Одного прохода хватало, чтобы на экране
    появился консультант с именем «практики рынков капитала White Square».
    """
    name = str(name or '').strip()
    while True:
        shorter = ROLE_PREFIX.sub('', name).strip()
        if shorter == name or not shorter:
            return name
        name = shorter


def clean_name(raw):
    """Из захваченного куска — название фирмы: без родового слова, без кавычек
    и без хвоста «сообщает…»."""
    name = TAIL_CUT.sub('', str(raw or '')).strip()
    name = strip_prefix(name)
    name = TRAILING_ADVERB.sub('', name).strip()
    name = name.strip('«»"“” \t')
    name = re.sub(r'\s+', ' ', name)
    return name


def split_firms(name):
    """Несколько фирм в одном объявлении разделяются, ОДНА фирма с запятой в
    названии — нет. Различает их кавычка: «Меллинг, Войтишкин и Партнеры» —
    одно имя (было в кавычках), Freshfields, Latham & Watkins и Hengeler
    Mueller — три (кавычек не было). Поэтому режем только то, что пришло
    без кавычек."""
    parts = re.split(r'\s*,\s*|\s+и\s+', name)
    parts = [p.strip() for p in parts if p.strip()]
    return parts if len(parts) > 1 else [name]


def role_label(sentence, side_known=True):
    kind = 'Финансовый консультант' if KIND_FIN.search(sentence) else 'Юридический консультант'
    if not side_known:
        return kind
    buyer, seller = bool(SIDE_BUYER.search(sentence)), bool(SIDE_SELLER.search(sentence))
    if buyer and not seller:
        return kind + ' покупателя'
    if seller and not buyer:
        return kind + ' продавца'
    return kind


def lead_advisor(text):
    """(список фирм, роль, первое предложение) или None.

    Смотрим ТОЛЬКО начало поста: объявление о сопровождении всегда начинается
    с имени фирмы. Упоминание фирмы в середине текста — это не заявление о её
    роли в сделке, и правило намеренно его не берёт.
    """
    body = re.sub(r'\s+', ' ', str(text or '')).strip()
    # Пост часто начинается с эмодзи или маркера («⚡️ Команда LEVEL Legal
    # Services завершила…»), и якорь `^` тогда не срабатывает — правило молча
    # пропускало такие объявления. Снимаем всё, что стоит перед первой буквой
    # или кавычкой; сам текст при этом не меняется, только точка отсчёта.
    body = re.sub(r'^[^0-9A-Za-zА-Яа-яЁё«"“]+', '', body)
    m = LEAD.match(body)
    if not m:
        return None
    # «АБ «Андрей Городисский и Партнеры»» — родовое слово стоит СНАРУЖИ
    # кавычек, а имя внутри своих. Кавычку ищем после снятия родового слова,
    # иначе имя с «и» внутри разрежется пополам на две несуществующие фирмы.
    inner = strip_prefix(TAIL_CUT.sub('', m.group(1)).strip())
    quoted = bool(re.match(r'^[«"“]', inner)) or bool(re.match(r'^\s*[«"“]', body))
    name = clean_name(m.group(1))
    if len(name) < 2 or len(name) > 70:
        return None
    firms = [name] if quoted else split_firms(name)
    # Первое предложение — то, из чего взята роль; храним его как обоснование.
    sentence = re.split(r'(?<=[.!?])\s+(?=(?-i:[А-ЯЁA-Z]))', body)[0]
    return firms, role_label(sentence), sentence



# Вводная часть объявления — «<Фирма> консультировала…» — мешает сопоставлять
# пост с карточкой: `match.py` считает общие слова и названия в кавычках, а в
# начале пресс-релиза стоит имя фирмы и её боилерплей, а не предмет сделки.
# Замер: сопоставлений 12 без отрезания и 18 с отрезанием (+50%), и все шесть
# добавившихся верны («Капитал Life»/Совкомбанк, «Арнест»/Avon, IPO GloraX,
# «Жилкапинвест»/Glorax, Центральный телеграф, «Яндекс.Здоровье»/Genotek).
STRIP_LEAD = re.compile(r'^.{0,120}?' + VERB + r'\s*', re.I)


def deal_text(text):
    """Текст поста без вводной «<Фирма> сопровождала» — то, что описывает саму
    сделку. Если вводной нет, возвращается исходный текст: правило не должно
    молча съедать пост, который устроен иначе."""
    body = re.sub(r'\s+', ' ', str(text or '')).strip()
    body = re.sub(r'^[^0-9A-Za-zА-Яа-яЁё«"“]+', '', body)
    return STRIP_LEAD.sub('', body) or body


# Правило проверяется на себе: заведомо верные объявления обязаны проходить,
# заведомо чужие тексты — нет. Это те самые случаи, на которых прошлая версия
# ошибалась (должность сотрудника, слово из рейтинга).
assert lead_advisor('White Square консультировала Nordgold в связи с приобретением актива.')[0] == ['White Square']
assert lead_advisor('NEXTONS представляла интересы «Ленты» в сделке по приобретению активов.')[0] == ['NEXTONS']
assert lead_advisor('Юридическая фирма «Восход» сообщает о сопровождении сделки.')[0] == ['Восход']
assert lead_advisor('Юристы BGP Litigation сопровождали процесс взыскания.')[0] == ['BGP Litigation']
assert lead_advisor('Freshfields, Latham & Watkins и Hengeler Mueller сопровождали IPO.')[0] == \
    ['Freshfields', 'Latham & Watkins', 'Hengeler Mueller']
assert lead_advisor('«Меллинг, Войтишкин и Партнеры» сообщает: её команда представляла интересы группы.')[0] == \
    ['Меллинг, Войтишкин и Партнеры']
assert lead_advisor('советник LEVEL Legal Services провела мастер-класс по арбитражу') is None
assert lead_advisor('ALUMNI Partners вошла в топ-5 юридических консультантов рейтинга') is None
assert lead_advisor('В этот раз в нем участвовали 26 юридических консультантов.') is None
assert lead_advisor('') is None
# Родовое слово снаружи, имя в своих кавычках — одна фирма, а не две.
assert lead_advisor('АБ «Андрей Городисский и Партнеры» выступили юридическим консультантом сделки.')[0] == \
    ['Андрей Городисский и Партнеры']
# «выступил» без роли рядом — это не объявление о сопровождении.
assert lead_advisor('Прокуратура выступила против принудительного выселения певицы.') is None
# Латинская «c» вместо кириллической встречается в самом канале.
assert lead_advisor('Nextons cообщает о сопровождении сделки.')[0] == ['Nextons']
# Сторона ставится, только когда названа ровно одна из них.
assert lead_advisor('NSP сопровождало продавца в сделке.')[1] == 'Юридический консультант продавца'
assert lead_advisor('NSP сопровождало покупателя и продавца в сделке.')[1] == 'Юридический консультант'
