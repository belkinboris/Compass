# -*- coding: utf-8 -*-
"""Слова оценки в цитате источника — одно определение для review.py и enrich.py."""
import re

# Слова, по которым цитата говорит об оценке, а не о названной цене. До 19 ноября 2026 —
# только «оцен…» и «могла составить»: «может вложить 500–600 млн руб.» («Туту») проходило фактом.
ESTIMATE_WORDS = re.compile(
    r'оцен|мо(?:жет|гут|г|гла|гло|гли)\s+(?:бы\s+)?(?:\w+\s+){0,2}?(?:состав|стоить|обойтись|вложить|заплатить|потратить|достиг)'
    r'|предполага|ориентировочн|неофициальн', re.I)
