# -*- coding: utf-8 -*-
"""Стиль заголовка карточки — чистая проверка для приемки новой карточки
(бэклог G3; docs/card_parties.md, раздел «Заголовок»; WRITING_BRIEF.md, `title`).

Владелец 31 октября 2026 («да, перепиши, надо чтобы все единообразно было»)
снял старое правило «старые карточки не переименовываются под стиль»: база
приведена к одному стилю партией `fixes/written_titles_g3_2026_11_01.py`, а
новые карточки держит эта проверка. Она не читает базу и не ходит в сеть:
на вход — заголовок, профили сторон карточки и статус; на выход — список
находок словами для человека (пустой список — заголовок по стилю).

Что считается дефектом:
- длиннее 110 знаков (норма — до ~90, одна мысль);
- начинается с формы юрлица (ООО, АО, ПАО, ЗАО, ОАО, НАО, МКПАО, ИП), хотя у
  профиля стороны есть узнаваемое имя без этой формы. Если имя профиля само
  «ООО «…»» (анонимная SPV), юрлицо остается. «НАО» без кавычек после — округ,
  а не юрлицо;
- канцелярит: «консолидировал», «в рамках», «стал владельцем/собственником»,
  «реализация/реализовал», «осуществ…», «путем»;
- «вложил(ся/ась)» вместо «проинвестировал(а)» (владелец, 21 октября 2026);
- вторая мысль: вторая фраза через точку (точка после сокращения «им.», «Dr.»,
  инициала или внутри названия в кавычках — не граница фразы), или после тире/запятой идет
  придаточное с глаголом («— доля структур X размыта», «, не назвав
  покупателя», «. Сделку оценили в …»). Тире между сторонами или перед
  приложением-именем («— бывший завод Bosch») — допустимо;
- глагол не по статусу: закрытая сделка с «покупает/планирует», обсуждаемая —
  с «купил/продал».
"""
import re

LEGAL_FORMS = ('ООО', 'АО', 'ПАО', 'ЗАО', 'ОАО', 'НАО', 'МКПАО', 'ИП')
MAX_LEN = 110

_LEGAL_START = re.compile(r'^\s*(?:%s)\s+«([^»]+)»' % '|'.join(LEGAL_FORMS))
_LEGAL_NAME = re.compile(r'^\s*(?:%s)\s+[«"]' % '|'.join(LEGAL_FORMS))
_CANCEL = re.compile(r'консолидир\w*|в рамках|стал[аио]?\s+(?:владельц\w*|собственник\w*)|'
                     r'реализ(?:ац\w*|овал\w*|у[яе]\w*)|осуществ\w*|путем', re.I)
_INVESTED = re.compile(r'\bвложил(?:ся|ась|ись|а|о|и)?\b', re.I)
# Придаточное после тире или запятой: глагол или причастие, которые начинают
# вторую мысль. Список намеренно короткий — ложная находка дороже пропуска.
_CLAUSE = re.compile(r'(?:\s[—–-]\s|,\s)[^—–,]*?\b(?:не\s+назвав\w*|размыт\w*|национализирован\w*|'
                     r'изъят\w*|оценил\w*|оценива\w*|сорвал\w*|остал\w*|получил\w*|стал[аио]?\b|'
                     r'отменив\w*|выкупив\w*|продав\w*|купив\w*|заплатив\w*|войд\w*|'
                     r'котор\w+|чтобы\b|если\b|когда\b|пока\b|хотя\b)', re.I)
# Две фразы: точка после русского слова (не после сокращения «им.», «Dr.»,
# инициала «В. Ф.») и не внутри названия в кавычках («Среда. Царицыно»,
# «Консорциум. Первый») — кавычки заменяются словом-заглушкой перед поиском.
_TWO_SENTENCES = re.compile(r'[а-яё]{3,}»?[.!?]\s+[А-ЯA-Z«]')
_QUOTED = re.compile(r'«[^«»]*»')
_PRESENT = re.compile(r'\b(?:покупа(?:ет|ют)|приобрета(?:ет|ют)|прода(?:ет|ют)|выкупа(?:ет|ют)|'
                      r'планиру(?:ет|ют)|рассматрива(?:ет|ют)|намерен[аы]?|собира(?:ет|ют)ся|'
                      r'договарива(?:ет|ют)ся|ищ(?:ет|ут)|готовит\w*)\b', re.I)
_PAST = re.compile(r'\b(?:купил[аио]?|приобрел[аио]?|продал[аио]?|выкупил[аио]?|проинвестировал[аио]?|'
                   r'получил[аио]?|закрыл[аио]?)\b', re.I)


def _flat(s):
    return re.sub(r'[^\wа-яё]+', '', str(s or ''), flags=re.I).lower()


def _names(companies):
    """Имена профилей сторон: словарь id → профиль, список профилей или список строк."""
    if not companies:
        return []
    items = companies.values() if isinstance(companies, dict) else companies
    out = []
    for c in items:
        name = c.get('name') if isinstance(c, dict) else c
        if name:
            out.append(str(name))
    return out


def title_style_findings(title, companies, status):
    """Список находок по стилю заголовка; пустой список — заголовок по стилю."""
    title = str(title or '').strip()
    out = []
    if not title:
        return ['пустой заголовок']
    if len(title) > MAX_LEN:
        out.append('заголовок длиннее %d знаков (%d): одна мысль, до ~90 знаков' % (MAX_LEN, len(title)))
    m = _LEGAL_START.match(title)
    if m:
        inner = _flat(m.group(1))
        for name in _names(companies):
            if _LEGAL_NAME.match(name):
                continue  # имя профиля само «ООО «…»» — юрлицо и есть имя
            flat_name = _flat(name)
            if inner and (inner in flat_name or flat_name in inner):
                out.append('заголовок начинается с юрлица «%s», хотя у профиля есть имя «%s» — '
                           'пишите имя, глагол — под новое подлежащее' % (m.group(0).strip(), name))
                break
    c = _CANCEL.search(title)
    if c:
        out.append('канцелярит «%s» — скажите проще: купил, выкупил, довел долю, продал с торгов'
                   % c.group(0))
    if _INVESTED.search(title):
        out.append('в заголовке «вложил(ся/ась)» — пишем «проинвестировал(а)»')
    if _TWO_SENTENCES.search(_QUOTED.sub('«имярек»', title)):
        out.append('две фразы через точку — в заголовке одна мысль, вторая уходит в поля карточки')
    else:
        k = _CLAUSE.search(title)
        if k:
            out.append('вторая мысль после тире или запятой («%s») — заголовок держит одну мысль, '
                       'доля и подробности живут в полях' % k.group(0).strip())
    status = str(status or '')
    if status == 'Закрыта' and _PRESENT.search(title):
        out.append('сделка закрыта, а глагол в настоящем времени («%s») — пишите прошедшее'
                   % _PRESENT.search(title).group(0))
    elif status in ('Обсуждается', 'Подписана', 'Согласование получено') and _PAST.search(title):
        out.append('сделка еще идет («%s»), а глагол в прошедшем времени («%s») — пишите настоящее'
                   % (status, _PAST.search(title).group(0)))
    return out
