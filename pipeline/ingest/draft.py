COMMODITY_LOT = re.compile(r'^парти[юя]\s', re.I)
FROM_WHOM = re.compile(r'\bу\s+((?:[а-яё]+\s+){0,3}[«"А-ЯЁA-Z][^.;,]{2,60})')
