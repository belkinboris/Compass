# --- сумма -----------------------------------------------------------------
# Формат один на всю базу (CLAUDE.md): значок валюты, а не слово.
CUR = [(r'руб(?:л(?:ей|я|ь))?\.?|₽|rub', '₽'), (r'долл(?:ар(?:ов|а))?\.?|\$|usd', '$'),
       (r'евро|€|eur', '€')]
SUM_RE = re.compile(
    r'(?<![\w])(\d[\d\s]*(?:[.,]\d+)?)\s*(млрд|млн|тыс)\.?\s*'
    r'(руб(?:л(?:ей|я|ь))?\.?|₽|долл(?:ар(?:ов|а))?\.?|\$|евро|€)', re.I)
SUM_RE_PRE = re.compile(
    r'([$€])\s?(\d[\d\s]*(?:[.,]\d+)?)\s*(млрд|млн|тыс)', re.I)


def guess_sum(text):
    """«12 млрд рублей» -> «12 млрд ₽»; «$230 млн» -> «$230 млн». Иначе None."""
    text = str(text or '')
    m = SUM_RE.search(text)
    if m:
        num, scale, cur = m.group(1).strip(), m.group(2).lower(), m.group(3).lower()
        sign = next((s for pat, s in CUR if re.fullmatch(pat, cur, re.I)), None)
        if not sign:
            return None
        num = re.sub(r'\s+', ' ', num)
        return ('%s %s %s' % (num, scale, sign)) if sign == '₽' else ('%s%s %s' % (sign, num, scale))
    m = SUM_RE_PRE.search(text)
    if m:
        return '%s%s %s' % (m.group(1), re.sub(r'\s+', ' ', m.group(2).strip()), m.group(3).lower())
    return None


# --- тип сделки ------------------------------------------------------------
TYPE_RULES = [
    ('IPO', r'\bipo\b|\bspo\b|размещ\w+\s+акци|выход\w*\s+на\s+бирж'),
    ('Продажа с торгов', r'\bторг(?:ах|и|ов)\b|аукцион|конкурсн\w+\s+производств|банкротн'),
    ('Финансирование · структурная сделка',
     r'структурн\w+\s+\w*\s*сделк|под\s+залог|предоплатн\w+\s+финансир|синдицированн|кредитн\w+\s+лини'),
    ('Инвестиция',
     r'раунд|series\s+[abcd]\b|\bseed\b|pre-?ipo|венчурн|инвестиц\w+\s+в\b|инвестировал'),
    ('M&A', r'.'),                       # по умолчанию — покупка/продажа
]


def guess_type(text):
    text = str(text or '')
    for name, pattern in TYPE_RULES:
        if re.search(pattern, text, re.I):
            return name
    return 'M&A'


# --- статус ----------------------------------------------------------------
FUTURE = r'план\w+|намерен|ведёт\s+переговоры|ведет\s+переговоры|может\s+(?:купить|продать|приобрести)' \
         r'|рассматрива\w+|обсужда\w+|договорил\w+|намерева'
SIGNED = r'подписал\w*\s+(?:соглашени|договор)|заключил\w*\s+(?:соглашени|договор)'
APPROVED = r'(?:получил|получила|получило|получили)\s+(?:согласие|одобрение|разрешение)' \
           r'|(?:фас|регулятор|правкомисси\w*|правительственн\w+\s+комисси\w*)\s+(?:одобрил|одобрила|согласовал|разрешил)'
DONE = r'закрыл\w*\s+сделку|сделка\s+закрыта|завершил\w*|купил|приобр(?:е|ё)л|продал|выкупил'
CANCELLED = r'сделка\s+не\s+состоял|отказал\w*\s+от\s+сделк|переговоры\s+прекращен|сделк\w*\s+отмен'


def guess_status(text):
    text = str(text or '')
    if re.search(CANCELLED, text, re.I):
        return 'Не состоялась'
    if re.search(DONE, text, re.I):
        return 'Закрыта'
    if re.search(APPROVED, text, re.I):
        return 'Согласование получено'
    if re.search(SIGNED, text, re.I):
        return 'Подписана'
    if re.search(FUTURE, text, re.I):
        return 'Обсуждается'
    return None


def guess_event(item):
    """Один подтверждённый этап из одной новости, без пересказа от модели.

    Заголовок этапа определяется закрытыми правилами, дата и ссылка берутся из
    самой записи. Если новость не содержит маркера этапа, возвращаем None —
    лишний этап хуже пропущенного.
    """
    text = ' '.join(x for x in (item.get('title'), item.get('summary')) if x)
    status = guess_status(text)
    if not status:
        return None
    kind = {
        'Обсуждается': 'negotiations',
        'Подписана': 'signed',
        'Согласование получено': 'approval',
        'Закрыта': 'closed',
        'Не состоялась': 'cancelled',
    }[status]
    title = {
        'negotiations': 'Переговоры',
        'signed': 'Документы подписаны',
        'approval': 'Согласование получено',
        'closed': 'Сделка завершена',
        'cancelled': 'Сделка не состоялась',
    }[kind]
    summary = re.sub(r'\s+', ' ', str(item.get('summary') or '')).strip()
    return {
        'kind': kind,
        'date': item.get('date') or 'unknown',
        'title': title,
        'note': summary[:260].rstrip(' ,;:-—') if summary else '',
        'source': [item.get('source_name') or item.get('source_id') or 'источник',
                   item.get('url')] if item.get('url') else None,
    }


# --- стороны ---------------------------------------------------------------
# «ПОКУПАЕТ» ЧЕТЫРЕ ПРОГОНА БЫЛО НЕВИДИМЫМ. `\bкуп…` требует границы слова
# перед «куп», а в слове «покупает» перед ним стоит приставка — границы там нет
# (тот же класс, что `^не\s+раскры\b` и `продавц\w*`, не совпадающий со словом
# «Продавец»). На базе это 40 заголовков с известным покупателем, где правило
# молчало: «Selectel покупает облачного провайдера servers.ru», «VK покупает
# сеть школ английского языка Ufirst». Глагольные окончания выписаны поимённо,
# чтобы правило не срабатывало на существительное «покупку»: «рассматривает
# покупку X» — это слух, а не сделка.
BUY_VERB = re.compile(
    r'\b(?:куп(?:ил[аио]?|ит|ят|ует)|покупа(?:ет|ют|л[аио]?)'
    r'|приобр(?:е|ё)(?:л[аио]?|тает|тёт|тет|тают)|выкуп(?:ил[аио]?|ает|ают|ит)'
    r'|консолидировал[аи]?|получил[аио]?)\b', re.I)

# Действие названо существительным, а глагол при нём служебный: «закрыла сделку
# по покупке», «объявил о приобретении», «договорился о выкупе». Ровно так
# написан заголовок mergers.ru про «Риглу» и «Здоровый город», из-за которого
# сделка неделю пролежала в очереди. Служебные глаголы взяты ТОЛЬКО
# завершающие: «изучает возможность покупки» и «рассматривает покупку» — это
# слух, и в список они намеренно не попали.
BUY_NOUN = re.compile(
    r'\b(?:закр(?:ыл[аио]?|ывает)|заверш(?:ил[аио]?|ает)|объяв(?:ил[аио]?|ляет)'
    r'|договорил(?:ся|ась|ись)|подписал[аи]?)\s+'
    r'(?:об?\s+)?(?:сделк\w+\s+(?:по\s+)?)?(?:покупк\w+|приобретени\w+|выкуп\w+)\s*',
    re.I)

# Вложение — это тоже вход стороны в актив: «X инвестировал в Y», «X вложил
# 325 млн рублей в Y». На базе 31 заголовок с известным покупателем.
INVEST_VERB = re.compile(
    r'\b(?:про)?инвестир(?:овал[аио]?|ует|уют)\b|\bвложил[аио]?\b', re.I)

# Обратный порядок: подлежащее — предмет, а инвестор стоит после «от».
# «Онлайн-школа Allright.io привлекла $1,5 млн от Buran Venture Capital» —
# на базе 31 такой заголовок, и во всех покупателем записан именно инвестор.
RAISED = re.compile(r'\bпривл(?:ек|ёк)\w*\b', re.I)
FROM_INVESTOR = re.compile(r'\bот\s+((?:[а-яё]+\s+){0,2}[«"А-ЯЁA-Z][^.;]{2,70})')

# Имя стороны обязано выглядеть именем: кавычки, заглавная буква или цифра.
# Без этой проверки «перешёл к новому собственнику» дал бы покупателя «новому
# собственнику», а «привлёк средства от частного инвестора» — «частного
# инвестора». Это не имена, а описания, и в карточке им не место.
LOOKS_LIKE_NAME = re.compile(r'[«"А-ЯЁA-Z0-9]')

SELL_VERB = re.compile(r'\b(?:прода(?:л[аио]?|ёт|ет|ст)|реализовал[аи]?)\b', re.I)
FROM_WHOM = re.compile(r'\bу\s+((?:[а-яё]+\s+){0,3}[«"А-ЯЁA-Z][^.;,]{2,60})')
SALE_BUYER_MARKER = re.compile(
    r'\b(?:компании|группе|банку|фонду|структуре|холдингу|инвестору|'
    r'консорциуму|менеджменту|сотрудникам|покупателю|ритейлеру|девелоперу|'
    r'оператору|предпринимателю|владельцу)\s+', re.I)
GENERIC_ASSET_END = re.compile(
    r'(?:^|\s)(?:дол[яиюей]|акци[яиюй]|пакет|бизнес|активы?|контроль|общество|'
    r'предприятие|компания|100%)\s*(?:в)?$', re.I)


def clean_name(text):
    text = re.sub(r'\s+', ' ', str(text or '')).strip(' ,;:-—')
    text = re.sub(r'^(?:компании|компания|группы|группа|банка|банк|фонда|фонд|холдинга|холдинг|'
                  r'структур[ыа]?|девелопера|аэропорта|альянса)\s+', '', text, flags=re.I)
    text = re.sub(r'\s+за\s+[\d$€].*$', '', text)
    return text.strip()


def _split_sale_tail(tail):
    """Разделить «актив компании/банку покупателю» без догадки по падежу.

    Берём только явный служебный маркер покупателя. Конструкция «доля в
    компании X» намеренно не разбирается: в ней X обычно является предметом,
    а не покупателем.
    """
    matches = list(SALE_BUYER_MARKER.finditer(tail))
    if len(matches) > 1:
        # Заголовок может описывать две параллельные продажи. Такой текст
        # нельзя сводить к одному покупателю автоматически.
        return clean_name(tail), None
    for marker in reversed(matches):
        prefix = tail[:marker.start()].strip(' ,;:-—')
        suffix = tail[marker.end():].strip(' ,;:-—')
        before = tail[max(0, marker.start()-3):marker.start()].lower().strip()
        if not prefix or not suffix or before == 'в':
            continue
        marker_word = marker.group(0).strip().lower()
        if marker_word == 'компании' and not re.search(r'[«"А-ЯЁA-Z0-9]', prefix):
            # «Продала дочерние компании (X и Y)» — здесь слово «компании»
            # описывает предмет, а не вводит покупателя.
            continue
        if GENERIC_ASSET_END.search(prefix):
            continue
        if len(suffix) > 100 or not re.search(r'[«"А-ЯЁA-Z0-9]', suffix):
            continue
        return clean_name(prefix), clean_name(suffix)
    return clean_name(tail), None


LEADING_SHARE = re.compile(
    r'^\s*(?:\d+[,.]?\d*%|\d+%|долю|доли|пакет|акции|контроль)\s*(?:в|акций)?\s*', re.I)


# Кусок заголовка перед глаголом — не всегда подлежащее. «Пошли в «отказ». Кто
# и почему продаёт пункты выдачи Wildberries» — это обзорная статья, и «продаёт»
# в ней стоит после КОНЦА первого предложения и вопросительных слов. Если такой
# кусок записать продавцом, в базе появится карточка, у которой сторона сделки
# — заголовок статьи. Границу предложения ищем правилом «точка, пробел,
# заглавная»: список сокращений ненадёжен («18,8 млрд руб.», «Fortum B.V.»), а
# это правило ошибается в безопасную сторону.
NOT_A_PARTY = re.compile(r'[.!?]\s+(?-i:[А-ЯЁA-Z])|(?-i:\b[Кк]то\b|\b[Пп]очему\b|'
                         r'\b[Зз]ачем\b|\b[Сс]колько\b)', re.I)


def _named(text):
    """Имя или описание? Ни описание, ни кусок чужого предложения в карточку не пишем."""
    if not text or not LOOKS_LIKE_NAME.search(text) or NOT_A_PARTY.search(text):
        return None
    return text


def guess_parties(title):
    """(покупатель, предмет, продавец) — только явно названные стороны.

    Подлежащее до глагола покупки — покупатель; сторона после «у» — продавец.
    Для заголовков о продаже покупатель извлекается только после явного
    маркера («компании», «банку», «фонду», «структуре» и т. п.).

    Разбираются четыре формы заголовка, и это не украшение: замер на 1541
    выверенной карточке дал 651 попадание по покупателю до правки и 729 после,
    при неизменной точности (90,7% -> 90,2%). Формы такие:
      «X купил Y»                       — глагол покупки (BUY_VERB);
      «X закрыл сделку по покупке Y»    — существительное (BUY_NOUN);
      «X инвестировал в Y»              — вложение (INVEST_VERB);
      «Y привлёк N от X»                — обратный порядок (RAISED).
    Порядок проверки важен: «закрыла сделку по покупке» содержит и BUY_NOUN, и
    ничего из BUY_VERB, а вот «привлёк инвестиции и купил» разбирается как
    покупка — сначала прямая форма, потом обратная.
    """
    title = re.sub(r'\s+', ' ', str(title or '')).strip()
    buyer = asset = seller = None

    m = BUY_VERB.search(title) or BUY_NOUN.search(title)
    if m:
        head = title[:m.start()].strip()
        if head and len(head) < 70:
            buyer = _named(clean_name(head))
        tail = title[m.end():]
        u = FROM_WHOM.search(tail)
        if u:
            seller = _named(clean_name(u.group(1)))
            tail = tail[:u.start()]
        asset = clean_name(LEADING_SHARE.sub('', tail.strip()))
    elif INVEST_VERB.search(title):
        m = INVEST_VERB.search(title)
        head = title[:m.start()].strip()
        if head and len(head) < 70:
            buyer = _named(clean_name(head))
        # «вложил 325 млн рублей в X» — предмет стоит после «в», а не сразу
        # за глаголом: между ними сумма.
        into = re.search(r'\bв\s+(.+)$', title[m.end():].strip())
        asset = clean_name(into.group(1)) if into else None
    elif RAISED.search(title):
        m = RAISED.search(title)
        head = title[:m.start()].strip()
        if head and len(head) < 70:
            asset = clean_name(head)
        investor = FROM_INVESTOR.search(title[m.end():])
        if investor:
            buyer = _named(clean_name(investor.group(1)))
    else:
        m = SELL_VERB.search(title)
        if m:
            head = title[:m.start()].strip()
            if head and len(head) < 70:
                seller = _named(clean_name(head))
            asset, buyer = _split_sale_tail(title[m.end():].strip())
            buyer = _named(buyer)
    cut = lambda s: (s[:100].rstrip(' ,;:-—') if s else None)
    return cut(buyer), cut(asset), cut(seller)


def raw_subject(title):
    """Кусок заголовка про ПРЕДМЕТ, без чистки родового слова.

    `clean_name` снимает родовое слово в начале имени: «девелопера «Инград»»
    превращается в ««Инград»». Для имени это правильно, а для отрасли ровно
    это слово и есть признак — «девелопер» отличает недвижимость, а «Инград»
    не отличает ничего. Поэтому отрасль читается по НЕОЧИЩЕННОМУ куску, но по
    тому же самому: покупатель в него по-прежнему не попадает, а именно ради
    этого предмет и выделяли (замер прогона 47: 180 ошибок из 1066, когда
    отрасль бралась по всему заголовку и прилетала от покупателя).
    """
    title = re.sub(r'\s+', ' ', str(title or '')).strip()
    m = BUY_VERB.search(title) or BUY_NOUN.search(title)
    if m:
        tail = title[m.end():]
        u = FROM_WHOM.search(tail)
        return (tail[:u.start()] if u else tail).strip()
    m = INVEST_VERB.search(title)
    if m:
        into = re.search(r'\bв\s+(.+)$', title[m.end():])
        return into.group(1).strip() if into else ''
    m = RAISED.search(title)
    if m:
        return title[:m.start()].strip()
    m = SELL_VERB.search(title)
    if m:
        return title[m.end():].strip()
    return ''


def _parties_self_check():
    """Проверка правил на себе: каждая форма заголовка и каждый отказ."""
    assert guess_parties('Selectel покупает облачного провайдера servers.ru')[0] == 'Selectel'
    b, a, _ = guess_parties('Группа «Ригла-Здравсити» закрыла сделку по покупке '
                            'сети «Здоровый город» в Воронежской области')
    # «Группа» — родовое слово, его снимает clean_name; имя остаётся.
    assert b == '«Ригла-Здравсити»' and a.startswith('сети «Здоровый город»')
    b, a, _ = guess_parties('Фонд НТИ вложил 325 млн рублей в Medical Visual Systems')
    assert b == 'НТИ' and a == 'Medical Visual Systems'
    b, a, _ = guess_parties('Онлайн-школа Allright.io привлекла $1,5 млн от Buran Venture Capital')
    assert b == 'Buran Venture Capital' and a == 'Онлайн-школа Allright.io'
    # Слух — не сделка: служебный глагол в BUY_NOUN должен быть завершающим.
