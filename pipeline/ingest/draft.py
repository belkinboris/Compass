def normalize_quotes(text):
    """Прямые кавычки " " -> ёлочки « » в СТРУКТУРНЫХ полях (title, имена сторон).

    ПОЧЕМУ ЗДЕСЬ. Три раунда ручных чисток одного и того же дефекта —
    `fix_straight_quotes.py` (2 августа, 12 карточек),
    `fix_new_card_titles_batch3.py` (8 августа, приток принёс его снова),
    `fix_straight_quotes_batch1.py` (16 августа) — чинили симптом на каждом
    прогоне заново, потому что источник дефекта, `build()` в этом файле,
    копировал `title` из статьи ДОСЛОВНО, а статьи почти всегда набраны
    прямыми кавычками. Владелец 16 августа спросил прямо: «как так получилось,
    что в названии оказались прямые кавычки?» — здесь ответ и починка корня,
    а не очередная запись в таблицу разовых правок.

    КАК. Прямые кавычки не различают открывающую/закрывающую графически —
    отличить их можно только по порядку: нечётная встреча — открывающая,
    чётная — закрывающая. Ровно так и работает: i-я (1-based) пара кавычек
    красится в «/» — независимо от того, сколько пар в строке. Заголовок с
    ДВУМЯ независимыми именами («"Внуково" ... "Домодедово" ...») красится
    верно, потому что для заголовков и коротких имён сторон вложенность
    (имя внутри имени) практически не встречается — она нужна прозе
    («Торговый дом "Меридиан"» уже внутри «»), а не короткому фрагменту.

    ЧЕГО НЕ ДЕЛАЕТ. Нечётное число прямых кавычек — верный признак, что
    что-то уже оборвано (пропущена одна кавычка) — трогать такую строку
    вслепую опаснее, чем оставить как есть; функция возвращает исходный
    текст без изменений. Тексты, где кавычки — часть дословной ЦИТАТЫ
    источника (eco.*/law.*/extra, проверяются `review.py` на дословность
    посимвольно), НЕ проходят через эту функцию — это отдельный класс полей,
    где стиль пунктуации источника обязан остаться как есть.
    """
    s = str(text or '')
    if s.count('"') < 2 or s.count('"') % 2 != 0:
        return s
    parts = s.split('"')
    out = [parts[0]]
    for i in range(1, len(parts)):
        out.append('«' if i % 2 == 1 else '»')
        out.append(parts[i])
    return ''.join(out)


def clean_name(text):
    text = re.sub(r'\s+', ' ', str(text or '')).strip(' ,;:-—')
    text = re.sub(r'^(?:компании|компания|группы|группа|банка|банк|фонда|фонд|холдинга|холдинг|'
                  r'структур[ыа]?|девелопера|аэропорта|альянса)\s+', '', text, flags=re.I)
    text = re.sub(r'\s+за\s+[\d$€].*$', '', text)
    return normalize_quotes(text.strip())


def _split_sale_tail(tail):
    """Разделить «актив компании/банку покупателю» без догадки по падежу.

    Берём только явный служебный маркер покупателя. Конструкция «доля в
    компании X» намеренно не разбирается: в ней X обычно является предметом,
    а не покупателем.
    """
    matches = list(SALE_BUYER_MARKER.finditer(tail))
    if len(matches) > 1:
        # Заголовок может описывать две параллельные продажи. Такой текст
        # нельзя сводить к одному покупателю автоматически.
        return clean_name(tail), None
    for marker in reversed(matches):
        prefix = tail[:marker.start()].strip(' ,;:-—')
        suffix = tail[marker.end():].strip(' ,;:-—')
        before = tail[max(0, marker.start()-3):marker.start()].lower().strip()
        if not prefix or not suffix or before == 'в':
            continue
        marker_word = marker.group(0).strip().lower()
        if marker_word == 'компании' and not re.search(r'[«"А-ЯЁA-Z0-9]', prefix):
            # «Продала дочерние компании (X и Y)» — здесь слово «компании»
            # описывает предмет, а не вводит покупателя.
            continue
        if GENERIC_ASSET_END.search(prefix):
            continue
        if len(suffix) > 100 or not re.search(r'[«"А-ЯЁA-Z0-9]', suffix):
            continue
        return clean_name(prefix), clean_name(suffix)
    return clean_name(tail), None


LEADING_SHARE = re.compile(
    r'^\s*(?:\d+[,.]?\d*%|\d+%|долю|доли|пакет|акции|контроль)\s*(?:в|акций)?\s*', re.I)


# Кусок заголовка перед глаголом — не всегда подлежащее. «Пошли в «отказ». Кто
# и почему продаёт пункты выдачи Wildberries» — это обзорная статья, и «продаёт»
# в ней стоит после КОНЦА первого предложения и вопросительных слов. Если такой
# кусок записать продавцом, в базе появится карточка, у которой сторона сделки
# — заголовок статьи. Границу предложения ищем правилом «точка, пробел,
# заглавная»: список сокращений ненадёжен («18,8 млрд руб.», «Fortum B.V.»), а
# это правило ошибается в безопасную сторону.
NOT_A_PARTY = re.compile(r'[.!?]\s+(?-i:[А-ЯЁA-Z])|(?-i:\b[Кк]то\b|\b[Пп]очему\b|'
                         r'\b[Зз]ачем\b|\b[Сс]колько\b)|'
                         # ДОЛЯ РЫНКА — НЕ СТОРОНА СДЕЛКИ. «59% россиян покупают
                         # книги на маркетплейсах — исследование» разобралось
                         # покупателем «59% россиян»: заголовок опросного
                         # исследования начинается с числа и демографической
                         # группы, а не с имени стороны. Замер: во всей базе
                         # ни один настоящий buyer_name/seller не начинается с
                         # «N% строчное слово» (0 из 1571 карточки) — только
                         # «N% АКЦИЙ/ДОЛЕЙ Компании», где после % идёт родовое
                         # слово предмета, не подлежащее.
                         r'(?-i:^\d+[.,]?\d*\s*%\s+[а-яё])|'
                         # МЕСТО/ПЕРИОД — НЕ СТОРОНА. «На Петербургской бирже
                         # в первом полугодии продали 505 кг серебра» — это
                         # сводка объёма торгов, а не сделка: голова до
                         # «продали» — обстоятельство места-времени, а не
                         # подлежащее. Замер: ни один настоящий buyer_name/
                         # seller во всей базе не начинается с предлога перед
                         # словом (0 из 1571).
                         r'(?-i:^(?:На|В|Во|От|Для|У|С|Со)\s+[А-ЯЁа-яё])|'
                         # ДВОЕТОЧИЕ — ЗАГОЛОВОК-ЯРЛЫК, А НЕ ПОДЛЕЖАЩЕЕ.
                         # «Акции, облигации, паи: как инвестировали кандидаты
                         # в Госдуму. Инфографика» (16 августа) — «как» перед
                         # глаголом разобралось «покупателем», обрезанным
                         # ровно на двоеточии, потому что весь кусок ДО
                         # двоеточия — тема-ярлык жанра «Тема: подробности»
                         # или атрибуция источника («Nikkei: Sony и TSMC…»,
                         # «МИД РФ: Европа получила предупреждение»), а не имя
                         # стороны сделки. Замер по всей базе (1574 карточки):
                         # ни один настоящий buyer_name/seller двоеточия не
                         # содержит.
                         r':|'
                         # ОБРЕЗАННАЯ ОТКРЫВАЮЩАЯ КАВЫЧКА — ГОЛОВА ОБОРВАНА
                         # ВНУТРИ ЧУЖОЙ ЦИТАТЫ. «„Не купят — буду
                         # деактивировать". Что происходит с рынком ПВЗ
                         # маркетплейсов» (18 августа) — заголовок открывается
                         # цитатой-крючком в кавычках, глагол покупки («купят»)
                         # оказался ВНУТРИ неё, и голова обрезалась на
                         # ««Не» — открывающая кавычка без единой закрывающей
                         # в оставшемся куске. Замер по всей базе и кэшу
                         # притока (11648 заголовков): ни один настоящий
                         # buyer_name/seller не начинается с кавычки, которая
                         # нигде дальше не закрывается — это отличает случай
                         # от вложенных названий («ООО «ТД «Нефтетехснаб»» и
                         # подобные), которые НЕ начинаются с самой кавычки.
                         r'(?-i:^[«"][^«»"]*$)|'
                         # ЖИТЕЛИ — ДЕМОГРАФИЧЕСКАЯ ГРУППА, НЕ СТОРОНА. «Жители
                         # Подмосковья за месяц купили почти 22 млн кг мяса»
                         # (19 августа) — сводка розничных продаж, а не сделка;
                         # «Жительница Хабаровского края получила 10 лет…» из
                         # того же потока — вообще не про рынок. Родня уже
                         # исключённой «N% демографической группы»: 0 из 1571
                         # настоящих buyer_name/seller начинаются с «Жител…».
                         r'(?-i:^Жител[а-яё]*)|'
                         # РОССИЯНЕ — ТОЖЕ ДЕМОГРАФИЧЕСКАЯ ГРУППА. «Россияне
                         # купили в июле рекордные 549 тыс. подержанных авто»
                         # (21 августа) — сводка рынка, а не сделка. Не
                         # «^Росси[яе]», чтобы не задеть «Россия»/«Российская
                         # Федерация» как законную сторону (продавец в двух
                         # карточках базы) — только форму множественного
                         # числа демонима.
                         r'(?-i:^Россиян)|'
                         # ФАРМ-КЛУБ — СПОРТИВНЫЙ ТЕРМИН, НЕ СТОРОНА M&A.
                         # «Фарм-клуб "Сакраменто" приобрел права на Лахина»
                         # (21 августа, РИА со ссылкой на NBA) — резервная
                         # команда баскетбольного клуба выкупила права на
                         # игрока, а не купила компанию. Родня уже
                         # исключённой футбольной позиции в SPORTS_POSITION
                         # (форвард/вратарь), только здесь спортивный термин
                         # в СТОРОНЕ, а не в предмете. Замер: 0 из 1565.
                         r'(?-i:^Фарм-клуб)', re.I)

# РОДОВОЕ ОПИСАНИЕ ВМЕСТО ИМЕНИ. Журнал правок чтением (learn.py) показал три
# случая, где механика уверенно записала стороной не имя, а описание роли:
# «Владелец Yadro» (владелец — не Yadro), «Бывший топ-менеджер «Лукойла»»,
# «ресторатора Флеганова», «Экс-акционер Башкирской содовой компании».
# На экране это выглядит как факт, хотя настоящее имя в статье обычно есть —
# просто ниже заголовка. Молчание тут честнее: имя дочитает шаг чтения.
#
# Роли разделены на два списка, и это не придирка. У РОЛИ-ЧЕЛОВЕКА имя в
# кавычках чужое: «топ-менеджер «Лукойла»» — это человек ИЗ «Лукойла», а сам
# «Лукойл» стороной не является. У РОЛИ-ОРГАНИЗАЦИИ имя в кавычках своё:
# «Группа «Астра»», «сеть «Магнит»» — это и есть сторона, трогать нельзя.
PERSON_ROLE = re.compile(
    r'^(?:бывш\w+\s+|экс-|быв\.\s*)?'
    r'(?:ресторатор|топ-менеджер|менеджер|акционер|совладел\w+|владел\w+|'
    r'основател\w+|предпринимател\w+|бизнесмен|инвестор|наследник|партнёр|партнер)\w*\b', re.I)
ORG_ROLE = re.compile(
    r'^(?:бывш\w+\s+|экс-)?'
    r'(?:компани\w+|фонд|группа|холдинг|структур\w+)\w*\b', re.I)


# ЭТАП 9, П4-9: «неназванную брокерскую компанию» дословно копирует в
# `asset` заявление источника, что имени НЕТ, — а на посте канала это
# читается как кусок заголовка, повторённый строкой «Предмет:» (реакция
# партнёров на карточку «Алор брокер», g6bf41023). `is_generic_description`
# уже ловит этот класс для СТОРОН («Владелец Yadro»), но не применяется к
# `asset` вовсе — управление глагола там другое, и родовые слова в начале
# («доля в», «контроль в», «пакет акций») не совпадают с ORG_ROLE/PERSON_ROLE.
UNDISCLOSED_OR_GENERIC_ASSET = re.compile(
    r'\bне\s*названн\w*\b|\bненазванн\w*\b|\bнеизвестн\w*\b|'
    r'\bодн\w+\s+из\s+(?:крупнейших|ведущих|известных|топ)\w*\b', re.I)


def _asset_names_something(text):
    """Есть ли в предмете хоть одно собственное имя — кавычки, латиница, или
    заглавная буква НЕ на первом слове? Если да, предмет несёт факт сверх
    декларации «имя не названо» и его нельзя стирать целиком: у «27,4%
    акций Ozon неизвестному покупателю» реальное имя актива (Ozon) есть,
    просто рядом приклеена фраза про покупателя — в отличие от «неназванная
    брокерская компания», где имени нет вообще нигде в строке."""
    if '«' in text or '"' in text:
        return True
    if re.search(r'[A-Za-z]', text):
        return True
    words = text.split()
    return any(re.match(r'(?-i:[А-ЯЁ])', w) for w in words[1:])


def is_generic_description(name):
    """Родовое описание роли («Владелец Yadro») вместо имени стороны?

    Замер по базе: из 111 сторон, записанных текстом, правило считает
    описанием 5, и все пять — действительно описания («Группа инвесторов»,
    «Совладелец R-Vision», «фонд под управлением «ВИМ Сбережения»»). Ни одно
    настоящее имя («МКБ», «Wildberries», «Семья бизнесмена Говора») не задето.
    """
    n = str(name or '').strip()
    if not n:
        return False
    person = PERSON_ROLE.match(n)
    if person:
        return True                     # роль человека — имя всегда ниже, не здесь
    org = ORG_ROLE.match(n)
    if not org:
        return False
    tail = n[org.end():].strip(' ,;:-—')
    # «Группа «Астра»», «Группа Циан» — имя своё (кавычки или заглавная
    # буква), оставляем. «Группа инвесторов», «Компания в структуре группы
    # «Колди»» — после родового слова идёт строчное слово, имени нет.
    return not re.match(r'^[«"]|^(?-i:[А-ЯЁA-Z])', tail)


def _named(text):
    """Имя или описание? Ни описание, ни кусок чужого предложения в карточку не пишем."""
    if not text or not LOOKS_LIKE_NAME.search(text) or NOT_A_PARTY.search(text):
        return None
    if is_generic_description(text):
        return None
    return text


NEGATED_VERB = re.compile(r'\bне\s*$', re.I)


def _first_affirmative(pattern, title):
    """Первое совпадение глагола, которому не предшествует «не».

    «Пашинян не продал абрикосы европейцам» (19 августа) — SELL_VERB
    находил «продал», а отрицание перед ним никто не проверял: разбор читал
    заголовок как сделку, хотя источник сообщает об ОТСУТСТВИИ продажи.
    Замер по базе и всему кэшу притока (14613 заголовков): 3 заголовка с
    «не» перед глаголом покупки/продажи/инвестиции, и ни один не был бы
    настоящей сделкой — молчание тут ничего не стоит."""
    for m in pattern.finditer(title):
        if not NEGATED_VERB.search(title[:m.start()]):
            return m
    return None


def guess_parties(title):
    """(покупатель, предмет, продавец) — только явно названные стороны.

    Подлежащее до глагола покупки — покупатель; сторона после «у» — продавец.
    Для заголовков о продаже покупатель извлекается только после явного
    маркера («компании», «банку», «фонду», «структуре» и т. п.).

    Разбираются четыре формы заголовка, и это не украшение: замер на 1541
    выверенной карточке дал 651 попадание по покупателю до правки и 729 после,
    при неизменной точности (90,7% -> 90,2%). Формы такие:
      «X купил Y»                       — глагол покупки (BUY_VERB);
      «X закрыл сделку по покупке Y»    — существительное (BUY_NOUN);
      «X инвестировал в Y»              — вложение (INVEST_VERB);
      «Y привлёк N от X»                — обратный порядок (RAISED).
    Порядок проверки важен: «закрыла сделку по покупке» содержит и BUY_NOUN, и
    ничего из BUY_VERB, а вот «привлёк инвестиции и купил» разбирается как
    покупка — сначала прямая форма, потом обратная.
    """
    title = re.sub(r'\s+', ' ', str(title or '')).strip()
    buyer = asset = seller = None

    m = _first_affirmative(BUY_VERB, title) or _first_affirmative(BUY_NOUN, title)
    if m:
        head = title[:m.start()].strip()
        if head and len(head) < 70:
            buyer = _named(clean_name(head))
        tail = title[m.end():]
        u = FROM_WHOM.search(tail)
        if u:
            seller = _named(clean_name(u.group(1)))
            tail = tail[:u.start()]
        asset = clean_name(LEADING_SHARE.sub('', tail.strip()))
    elif _first_affirmative(INVEST_VERB, title):
        m = _first_affirmative(INVEST_VERB, title)
        head = title[:m.start()].strip()
        if head and len(head) < 70:
            buyer = _named(clean_name(head))
        # «вложил 325 млн рублей в X» — предмет стоит после «в», а не сразу
        # за глаголом: между ними сумма.
        into = re.search(r'\bв\s+(.+)$', title[m.end():].strip())
        asset = clean_name(into.group(1)) if into else None
    elif _first_affirmative(RAISED, title):
        m = _first_affirmative(RAISED, title)
        head = title[:m.start()].strip()
        if head and len(head) < 70:
            asset = clean_name(head)
        investor = FROM_INVESTOR.search(title[m.end():])
        if investor:
            buyer = _named(clean_name(investor.group(1)))
    else:
        m = _first_affirmative(SELL_VERB, title)
        if m:
            head = title[:m.start()].strip()
            if head and len(head) < 70:
                seller = _named(clean_name(head))
            asset, buyer = _split_sale_tail(title[m.end():].strip())
            buyer = _named(buyer)
    cut = lambda s: (s[:100].rstrip(' ,;:-—') if s else None)
    asset = cut(asset)
    if asset:
        # Управление глагола ставит предмет не в именительном («купил X» —
        # винительный, «присоединение X» — родительный): то же согласование,
        # что уже применяется к именам сторон (name_is_supported в review.py),
        # только здесь механически, а не как допуск проверки. Правило нарочно
        # консервативное — см. docstring casing.py, что и почему пропускает.
        asset, _ = to_nominative_asset(asset)
    # ЭТАП 9, П4-9: предмет, заявляющий отсутствие имени («неназванную
    # брокерскую компанию»), или родовое описание с превосходной степенью
    # без имени («один из крупнейших…») — не имя, а пересказ заголовка;
    # писать его в `asset` нечего (см. UNDISCLOSED_OR_GENERIC_ASSET).
    if asset and UNDISCLOSED_OR_GENERIC_ASSET.search(asset) and not _asset_names_something(asset):
        asset = None
    # ТРАНСФЕР ИГРОКА — НЕ M&A. «"Динамо" покупает форварда у
    # "Индепендьенте"» (21 августа) разобралось СТОРОНАМИ верно (оба клуба
    # — реальные названия в кавычках), а предметом — футбольной позицией,
    # а не активом или компанией. Язык трансферов и M&A совпадает
    # («купил», «продал», «у») — отличает их только то, ЧТО покупают.
    # Замер по базе (1565 карточек) и кэшу притока: ни один настоящий
    # asset не начинается с позиции футболиста (0 из 1565).
    if asset and SPORTS_POSITION.match(asset):
        return None, None, None
    # СПОТОВАЯ ЗАКУПКА ТОВАРА — НЕ M&A. «Индия купила партию СПГ по
    # рекордно высокой цене» разобралось сторонами верно (страна выглядит
    # именем), а предметом — грузом биржевого товара, а не компанией или
    # долей. Замер: 0 из 1567.
    if asset and COMMODITY_LOT.match(asset):
        return None, None, None
    return cut(buyer), asset, cut(seller)


def raw_subject(title):
    """Кусок заголовка про ПРЕДМЕТ, без чистки родового слова.

    `clean_name` снимает родовое слово в начале имени: «девелопера «Инград»»
    превращается в ««Инград»». Для имени это правильно, а для отрасли ровно
    это слово и есть признак — «девелопер» отличает недвижимость, а «Инград»
    не отличает ничего. Поэтому отрасль читается по НЕОЧИЩЕННОМУ куску, но по
    тому же самому: покупатель в него по-прежнему не попадает, а именно ради
    этого предмет и выделяли (замер прогона 47: 180 ошибок из 1066, когда
    отрасль бралась по всему заголовку и прилетала от покупателя).
    """
    title = re.sub(r'\s+', ' ', str(title or '')).strip()
    m = BUY_VERB.search(title) or BUY_NOUN.search(title)
    if m:
        tail = title[m.end():]
        u = FROM_WHOM.search(tail)
        return (tail[:u.start()] if u else tail).strip()
    m = INVEST_VERB.search(title)
    if m:
        into = re.search(r'\bв\s+(.+)$', title[m.end():])
        return into.group(1).strip() if into else ''
    m = RAISED.search(title)
    if m:
        return title[:m.start()].strip()
    m = SELL_VERB.search(title)
    if m:
        return title[m.end():].strip()
    return ''


