def _write_registry(root):
    import os
    import sys
    sys.path.insert(0, os.path.join(root, 'pipeline'))
    import fns_registry
    have = fns_registry.by_company_id()
    rows = [r for r in _registry_rows() if r[0] not in have]
    if not rows:
        return 0
    path = os.path.join(root, 'pipeline', 'fns_registry.py')
    src = open(path, encoding='utf-8').read()
    block = '# Вычитка базы, партия 2026_11_27_b (pipeline/ingest/fixes/reread_2026_11_27_b.py).\nREGISTRY += [\n'
    for cid, inn, why in rows:
        block += ('    {"company_id": %r, "decision": "confirmed", "inn": %r,\n     "reason": %r,\n     "date": %r},\n'
                  % (cid, inn, why, ONEOFF_DAY))
    block += ']\n\n'
    anchor = 'def by_company_id()'
    assert src.count(anchor) == 1
    open(path, 'w', encoding='utf-8').write(src.replace(anchor, block + anchor))
    return len(rows)


def _oneoff_main(write):
    import json
    import os
    import sys
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
    sys.path.insert(0, os.path.join(root, 'pipeline'))
    import fact_edit_guard
    import mass_edit_guard
    path = os.path.join(root, 'static', 'data', 'deals_promoted.json')
    raw = open(path, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    n = _oneoff_apply(data)
    if not n:
        print('Уже применено.')
        return 0
    mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
    bad = fact_edit_guard.unbacked(old, data)
    assert not bad, bad
    if not write:
        print('Сухой прогон: %d правок. Запись — с ключом --write.' % n)
        return 0
    fresh_raw = open(path, encoding='utf-8').read()
    fresh = json.loads(fresh_raw)
    _oneoff_apply(fresh)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(json.dumps(fresh, ensure_ascii=False, indent=1) + ('\n' if fresh_raw.endswith('\n') else ''))
    print('ЗАПИСАНО: %d правок; реестр ИНН: %d записей.' % (n, _write_registry(root)))
    return 0


if __name__ == '__main__':
    import sys
    sys.exit(_oneoff_main('--write' in sys.argv[1:]))
