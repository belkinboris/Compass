def _card(data, cid):
    return next(d for d in data['deals'] if d['id'] == cid)


def _inn_ok(inn):
    d = [int(x) for x in inn]
    w = (2, 4, 10, 3, 5, 9, 4, 6, 8)
    return len(d) == 10 and sum(a * b for a, b in zip(w, d)) % 11 % 10 == d[9]


