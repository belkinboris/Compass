NOTE_SET = {
    ('gc708f8c0', 'no_inn', 'target'): 'ЗПИФ своего ИНН не имеет: в ЕГРЮЛ у участника стоит ИНН управляющей '
                                       'компании — до 26 марта 2026 года АО «УК «Бизнес и инвестиции»» (7704504286), '
                                       'затем АО «УК «Экто Прайм»» (9703220084); оба — Saby и DataNewton.',
}
NOTE_DROP = [('gc708f8c0', 'checked', 'date_not_in_source')]


def _oneoff(write):
    import hashlib
    import json
    import os
    import sys
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
    sys.path.insert(0, os.path.join(root, 'pipeline'))
    sys.path.insert(0, os.path.join(root, 'pipeline', 'ingest'))
    import fact_edit_guard
    import mass_edit_guard
    import review
    data_path = os.path.join(root, 'static', 'data', 'deals_promoted.json')
    mine = {(f['id'], f['field'], json.dumps(f['new'], ensure_ascii=False)) for f in FIXES}

    def new_id(comps, name):
        for n in range(1000):
            cid = 'g' + hashlib.sha1(('%s|%d' % (name, n)).encode('utf-8')).hexdigest()[:8]
            if cid not in comps:
                return cid
        raise RuntimeError(name)

    def apply(data):
        by = {d['id']: d for d in data['deals']}
        comps = data['companies']
        n = 0
        ids = {}

        def replace_in(c, field, old, new):
            nonlocal n
            head, tail = field.split('.')
            cur = c[head][tail]
            if new in cur and (not old or old not in cur):
                return
            assert cur.count(old) == 1, (c['id'], field, cur)
            c[head][tail] = cur.replace(old, new)
            n += 1

        # g09f3b6a7: месяц отказа Верховного суда.
        replace_in(by['g09f3b6a7'], 'eco.context', VS_OLD, VS_NEW)
        # gbe9338ea: снять нашу оценку и фразу о статьях (замена на пустое — проверка «уже применено» по old).
        c = by['gbe9338ea']
        if SEN_OLD in c['eco']['context']:
            c['eco']['context'] = c['eco']['context'].replace(SEN_OLD, '')
            n += 1
        replace_in(c, 'eco.context', SEN_FIRST_OLD, SEN_FIRST_NEW)
        # g1475c63b: итог апелляции.
        replace_in(by['g1475c63b'], 'law.appr', AR_OLD, AR_NEW)

        # gaa5d4eb6: стороны — юрлица из ЕГРЮЛ; дата — день записи; «Цель» без автора — снята.
        c = by['gaa5d4eb6']
        if c.get('buyer') != SSK_BUYER:
            assert c.get('buyer') == SSK_BUYER_OLD and not c.get('buyer_name'), c.get('buyer')
            assert c.get('seller_id') == SSK_SELLER_OLD and c.get('seller') == 'ГК «Носта»', c.get('seller')
            assert SSK_BUYER in comps and SSK_SELLER in comps
            c['buyer'] = SSK_BUYER
            c['seller_id'] = SSK_SELLER
            c['seller'] = 'АО «Ремида»'
            c.setdefault('retracted', {}).setdefault('seller', [])
            if 'ГК «Носта»' not in c['retracted']['seller']:
                c['retracted']['seller'].append('ГК «Носта»')
            fact_edit_guard.log(c, 'buyer', SSK_BUYER, FRIHAUZ_Q, DN_FRIHAUZ, BY, DAY)
            fact_edit_guard.log(c, 'seller', 'АО «Ремида»', FRIHAUZ_Q, DN_FRIHAUZ, BY, DAY)
            n += 1
        if c.get('date') != '2026-09-09':
            assert c.get('date') == '2026', c.get('date')
            c['date'] = '2026-09-09'
            c['date_basis'] = 'registry'
            fact_edit_guard.log(c, 'date', '2026-09-09', FRIHAUZ_Q, DN_FRIHAUZ, BY, DAY)
            n += 1
        ev = c['events'][0]
        if ev.get('date') != '2026-09-09':
            assert ev['date'] == '2026-11-02' and ev['kind'] == 'closed', ev
            ev['date'] = '2026-09-09'
            ev['note'] = SSK_EVENT_NOTE
            ev['source'] = ['ЕГРЮЛ (DataNewton): участники ООО СЗ «Фрихауз»', DN_FRIHAUZ]
            n += 1
        if c['eco'].get('rationale') != '—':
            assert c['eco']['rationale'] == SSK_RAT_OLD, c['eco']['rationale']
            c['eco']['rationale'] = '—'
            n += 1

        # g654a1ce5: предмет — с адресом.
        c = by['g654a1ce5']
        if c.get('asset') != TY_NEW:
            assert c.get('asset') == TY_OLD, c.get('asset')
            c['asset'] = TY_NEW
            fact_edit_guard.log(c, 'asset', TY_NEW, TY_Q, TY_URL, BY, DAY)
            n += 1

        # gc708f8c0: участник СП — фонд (профиль заводится), дата по реестру, клиент консультанта.
        c = by['gc708f8c0']
        have = [k for k, v in comps.items() if v.get('name') == FUND['name']]
        fid = have[0] if have else new_id(comps, FUND['name'])
        ids[FUND['name']] = fid
        if not have:
            comps[fid] = dict(FUND)
            n += 1
        if c.get('target') != fid:
            assert c.get('target') == SV_OLD_TARGET, c.get('target')
            c['target'] = fid
            fact_edit_guard.log(c, 'target', fid, SV_DATE_Q, DN_SVRATA, BY, DAY)
            n += 1
        if c.get('date') != '2025-04-14':
            assert c.get('date') == '2025', c.get('date')
            c['date'] = '2025-04-14'
            c['date_basis'] = 'registry'
            fact_edit_guard.log(c, 'date', '2025-04-14', SV_DATE_Q, DN_SVRATA, BY, DAY)
            n += 1
        if c['law'].get('adv') != SV_ADV_NEW:
            assert c['law'].get('adv') == SV_ADV_OLD, c['law'].get('adv')
            c['law']['adv'] = [list(r) for r in SV_ADV_NEW]
            fact_edit_guard.log(c, 'law.adv', SV_ADV_NEW, SV_ADV_Q, SV_ADV_URL, BY, DAY)
            n += 1
        if comps[SV_OLD_TARGET].get('desc') != EKTO_DESC_NEW:
            assert comps[SV_OLD_TARGET].get('desc') == EKTO_DESC_OLD, comps[SV_OLD_TARGET].get('desc')
            comps[SV_OLD_TARGET]['desc'] = EKTO_DESC_NEW
            n += 1

        for cid, text in REGISTRY.items():
            notes = by[cid].setdefault('accepted_notes', {})
            if (notes.get('checked') or {}).get('registry_owners') != text:
                notes.setdefault('checked', {})['registry_owners'] = text
                n += 1
        for (cid, key, role), text in NOTE_SET.items():
            notes = by[cid].setdefault('accepted_notes', {}).setdefault(key, {})
            if notes.get(role) != text:
                notes[role] = text
                n += 1
        for cid, key, role in NOTE_DROP:
            notes = (by[cid].get('accepted_notes') or {}).get(key) or {}
            if role in notes:
                notes.pop(role)
                if not notes:
                    by[cid]['accepted_notes'].pop(key)
                n += 1

        # Прежние записи таблицы на поля, которые эта партия переписывает (своей записью или здесь):
        # отпечаток в proofread_absorbed, иначе две живые записи одного поля (docs/card_editing.md).
        keys = {(f['id'], f['field']) for f in FIXES if f['field'] != 'src'} | {
            ('g09f3b6a7', 'eco.context'), ('gbe9338ea', 'eco.context'), ('g1475c63b', 'law.appr'),
            ('gaa5d4eb6', 'eco.rationale'), ('gaa5d4eb6', 'buyer_name'), ('gaa5d4eb6', 'seller'),
            ('g654a1ce5', 'asset')}
        for f in review.FIXES:
            if (f['id'], f['field']) not in keys or f['new'] is None:
                continue
            if (f['id'], f['field'], json.dumps(f['new'], ensure_ascii=False)) in mine:
                continue
            marks = by[f['id']].setdefault('proofread_absorbed', {}).setdefault(f['field'], [])
            fp = review.fix_fingerprint(f['new'])
            if fp not in marks:
                marks.append(fp)
                n += 1
        return n, ids

    raw = open(data_path, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    n, ids = apply(data)
    if not n:
        print('Уже применено.')
        return 0
    mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
    bad = fact_edit_guard.unbacked(old, data)
    assert not bad, bad
    if not write:
        print('Сухой прогон: %d правок базы (новые профили: %s). Запись — с ключом --write.' % (n, ids))
        return 0
    fresh_raw = open(data_path, encoding='utf-8').read()     # перечитать прямо перед записью
    fresh = json.loads(fresh_raw)
    _n, ids2 = apply(fresh)
    assert ids2 == ids, (ids, ids2)
    with open(data_path, 'w', encoding='utf-8') as f:
        f.write(json.dumps(fresh, ensure_ascii=False, indent=1) + ('\n' if fresh_raw.endswith('\n') else ''))
    print('ЗАПИСАНО: %d правок базы.' % n)
    return 0


if __name__ == '__main__':
    import sys as _sys
    _sys.exit(_oneoff('--write' in _sys.argv))
