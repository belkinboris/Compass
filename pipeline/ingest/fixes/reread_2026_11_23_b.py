def _card(data, cid):
    return next(d for d in data['deals'] if d['id'] == cid)


def _oneoff_apply(data, strict=True):
    import fact_edit_guard
    n = 0
    # g772c17d9: продавец — участники по реестру
    c = _card(data, 'g772c17d9')
    if c.get('seller') != SVYAZ_SELLER_NEW:
        assert c.get('seller') == SVYAZ_SELLER_OLD, c.get('seller')
        c['seller'] = SVYAZ_SELLER_NEW
        r = c.setdefault('retracted', {}).setdefault('seller', [])
        if SVYAZ_SELLER_OLD not in r:
            r.append(SVYAZ_SELLER_OLD)
        fact_edit_guard.log(c, 'seller', SVYAZ_SELLER_NEW, SVYAZ_SELLER_QUOTE, IZ_SVYAZ, ONEOFF_BY, ONEOFF_DAY)
        n += 1
    chk = c.setdefault('accepted_notes', {}).setdefault('checked', {})
    if chk.get('registry_owners') != SVYAZ_REGISTRY:
        chk['registry_owners'] = SVYAZ_REGISTRY
        n += 1
    # g772c17d9: «Известия» — первоисточник (Frank Media и Retailer.ru пересказывают их) — первыми
    urls = [s[1] for s in c['src']]
    assert IZ_SVYAZ in urls, urls
    if urls[0] != IZ_SVYAZ:
        c['src'] = [s for s in c['src'] if s[1] == IZ_SVYAZ] + [s for s in c['src'] if s[1] != IZ_SVYAZ]
        n += 1
    # ge6b04680: полная статья «Коммерсанта» — первой
    c = _card(data, 'ge6b04680')
    urls = [s[1] for s in c['src']]
    if KOM_BK not in urls:
        assert not strict, 'сначала review.py --write: источник doc/9112983 добавляет таблица'
        print('(сухой прогон: doc/9112983 появится после review.py --write — перестановка источников пропущена)')
    elif urls[0] != KOM_BK:
        c['src'] = [s for s in c['src'] if s[1] == KOM_BK] + [s for s in c['src'] if s[1] != KOM_BK]
        n += 1
    # gb82efd9f: доля — формой «N% доли в ООО «X»»
