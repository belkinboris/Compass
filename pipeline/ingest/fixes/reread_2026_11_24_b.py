def _card(data, cid):
    return next(d for d in data['deals'] if d['id'] == cid)


def _oneoff_apply(data, strict=True):
    import fact_edit_guard
    n = 0
    # суммы: «Не раскрыта» (оценка аналитика или адвоката — не цена; «—» — не форма поля)
    for cid, old_sum, old_eco, quote, url in SUMS:
        c = _card(data, cid)
        eco = c.setdefault('eco', {})
        if eco.get('sum') == NOT_DISCLOSED and (old_sum is None or c.get('sum') == NOT_DISCLOSED):
            continue
        assert eco.get('sum') == old_eco, (cid, eco.get('sum'))
        assert c.get('sum') == old_sum, (cid, c.get('sum'))
        eco['sum'] = NOT_DISCLOSED
        fact_edit_guard.log(c, 'eco.sum', NOT_DISCLOSED, quote, url, ONEOFF_BY, ONEOFF_DAY)
        if old_sum is not None:
            c['sum'] = NOT_DISCLOSED
            fact_edit_guard.log(c, 'sum', NOT_DISCLOSED, quote, url, ONEOFF_BY, ONEOFF_DAY)
            r = c.setdefault('retracted', {}).setdefault('sum', [])
            if old_sum not in r:
                r.append(old_sum)
        if c.get('sum_basis') == 'estimate':
            c.pop('sum_basis')
        n += 1
    # gfa56e747: контекст — точечные замены (декабрь 2024 года — из реестра, review.py его в цитате не найдет).
    # Почему: «сменив самого Устаева» — разговорное «сам»; «на прошлой неделе» — относительное время статьи
    # от 19 ноября; «бизнесмена Алексея Устаева» — статья пишет «который связывают с бизнесменом»; «вложения
    # в стройку» — в статье «инвестиций в проект». Цитата — DP_KVS_CONTEXT_Q.
    c = _card(data, 'gfa56e747')
    eco = c['eco']
    if eco.get('context') != KVS_CONTEXT_NEW:
        assert eco.get('context') == KVS_CONTEXT_OLD, eco.get('context')
        eco['context'] = KVS_CONTEXT_NEW
        n += 1
    # g70cf2d0f: предмет — с заглавной буквы
    c = _card(data, 'g70cf2d0f')
    if c.get('asset') != TURA_ASSET_NEW:
        assert c.get('asset') == TURA_ASSET_OLD, c.get('asset')
        c['asset'] = TURA_ASSET_NEW
        fact_edit_guard.log(c, 'asset', TURA_ASSET_NEW, TURA_ASSET_Q, URA_TURA, ONEOFF_BY, ONEOFF_DAY)
        n += 1
    # gba506a58: «Коммерсантъ» — первоисточник, первым
    c = _card(data, 'gba506a58')
    urls = [s[1] for s in c['src']]
    if KOM_SKY not in urls:
        assert not strict, 'сначала review.py --write: источник doc/9127312 добавляет таблица'
        print('(сухой прогон: doc/9127312 появится после review.py --write — перестановка источников пропущена)')
    elif urls[0] != KOM_SKY:
        c['src'] = [s for s in c['src'] if s[1] == KOM_SKY] + [s for s in c['src'] if s[1] != KOM_SKY]
        n += 1
    # профиль фондов «Томь» и «Гало»
    p = data['companies']['g1a2329ed']
    if p.get('desc') != FUNDS_DESC_NEW:
        assert p.get('desc') == FUNDS_DESC_OLD, p.get('desc')
        p['desc'] = FUNDS_DESC_NEW
        n += 1
    return n


def _oneoff_main(write):
    import json
    import os
    import sys
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
    sys.path.insert(0, os.path.join(root, 'pipeline'))
    import fact_edit_guard
    import mass_edit_guard
    path = os.path.join(root, 'static', 'data', 'deals_promoted.json')
    raw = open(path, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    n = _oneoff_apply(data, strict=write)
    if not n:
        print('Уже применено.')
        return 0
    mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
    bad = fact_edit_guard.unbacked(old, data)
    assert not bad, bad
    if not write:
        print('Сухой прогон: %d правок. Запись — с ключом --write.' % n)
        return 0
    fresh_raw = open(path, encoding='utf-8').read()
    fresh = json.loads(fresh_raw)
    _oneoff_apply(fresh)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(json.dumps(fresh, ensure_ascii=False, indent=1) + ('\n' if fresh_raw.endswith('\n') else ''))
    print('ЗАПИСАНО: %d правок.' % n)
    return 0


if __name__ == '__main__':
    import sys
    sys.exit(_oneoff_main('--write' in sys.argv[1:]))
