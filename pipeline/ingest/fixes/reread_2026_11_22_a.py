def _oneoff(write):
    import json
    import os
    import sys
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
    sys.path.insert(0, os.path.join(root, 'pipeline'))
    sys.path.insert(0, os.path.join(root, 'pipeline', 'ingest'))
    import fact_edit_guard
    import mass_edit_guard
    import review
    data_path = os.path.join(root, 'static', 'data', 'deals_promoted.json')
    reg_path = os.path.join(root, 'pipeline', 'fns_registry.json')

    def apply(data):
        by = {d['id']: d for d in data['deals']}
        n = 0
        for cid, field, old, new, quote, url in FACTS:
            c = by[cid]
            cur = (c.get('eco') or {}).get(field[4:]) if field.startswith('eco.') else c.get(field)
            if cur == new:
                continue
            assert cur == old, (cid, field, cur)
            if field.startswith('eco.'):
                c.setdefault('eco', {})[field[4:]] = new
            else:
                c[field] = new
            fact_edit_guard.log(c, field, new, quote, url, BY, DAY)
            n += 1
        for cid, field, val in RETRACT:
            lst = by[cid].setdefault('retracted', {}).setdefault(field, [])
            if val not in lst:
                lst.append(val)
                n += 1
        for cid, field, old_new in ABSORB:
            marks = by[cid].setdefault('proofread_absorbed', {}).setdefault(field, [])
            fp = review.fix_fingerprint(old_new)
            if fp not in marks:
                marks.append(fp)
                n += 1
        for cid, text in REGISTRY.items():
            c = by[cid]
            if (c.get('checked') or {}).get('registry_owners') == text:
                continue
            c.setdefault('checked', {})['registry_owners'] = text
            n += 1
        return n

    def registry():
        import fns_registry
        raw = open(reg_path, encoding='utf-8').read()
        rows = json.loads(raw)
        n = 0
        for row in REGISTRY_ADD:
            have = [r for r in rows if r.get('company_id') == row['company_id']]
            if have:
                assert have[0].get('inn') == row['inn'], (row['company_id'], have)
                continue
            assert fns_registry.inn_is_valid(row['inn']), row['inn']
            assert not [r for r in rows if r.get('inn') == row['inn']], 'ИНН уже у другого профиля'
            rows.append(dict(row))
            print('реестр %s: + ИНН %s' % (row['company_id'], row['inn']))
            n += 1
        return n, rows, raw

    raw = open(data_path, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    n = apply(data)
    m, rows, reg_raw = registry()
    if not n and not m:
        print('Уже применено.')
        return 0
    mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
    bad = fact_edit_guard.unbacked(old, data)
    assert not bad, bad
    if not write:
        print('Сухой прогон: %d правок базы, %d строк реестра. Запись — с ключом --write.' % (n, m))
        return 0
    if n:
        fresh_raw = open(data_path, encoding='utf-8').read()     # перечитать прямо перед записью
        fresh = json.loads(fresh_raw)
        apply(fresh)
        with open(data_path, 'w', encoding='utf-8') as f:
            f.write(json.dumps(fresh, ensure_ascii=False, indent=1) + ('\n' if fresh_raw.endswith('\n') else ''))
    if m:
        with open(reg_path, 'w', encoding='utf-8') as fh:
            fh.write(json.dumps(rows, ensure_ascii=False, indent=1) + ('\n' if reg_raw.endswith('\n') else ''))
    print('ЗАПИСАНО: %d правок базы, %d строк реестра.' % (n, m))
    return 0


