# Поля, которые правит таблица FIXES этого файла и у которых есть прежние записи: их отпечатки — в proofread_absorbed.
_ABSORB_FOR_TABLE = [('ksk', 'eco.context')]


def _get(card, field):
    o = card
    for p in field.split('.'):
        o = o.get(p) if isinstance(o, dict) else None
    return o


def _set(card, field, value):
    parts = field.split('.')
    o = card
    for p in parts[:-1]:
        o = o.setdefault(p, {})
    if value is None:
        o.pop(parts[-1], None)
    else:
        o[parts[-1]] = value


def _absorb(card, cid, field, review):
    marks = card.setdefault('proofread_absorbed', {}).setdefault(field, [])
    for f in review.FIXES:
        if f['id'] == cid and f['field'] == field and f.get('new') is not None and f not in FIXES:
            fp = review.fix_fingerprint(f['new'])
            if fp not in marks:
                marks.append(fp)


def _apply(data, review):
    deals = {d['id']: d for d in data['deals']}
    for cid, adv in _ADV.items():
        card = deals[cid]
        law = card.setdefault('law', {})
        firms = [a[1] for a in (law.get('adv') or [])]
        assert firms == _ADV_OLD_FIRMS[cid], (cid, firms)
        law['adv'] = [list(a) for a in adv]
    for cid, field, old, new in _SET:
        card = deals[cid]
        assert _get(card, field) == old, (cid, field, _get(card, field))
        _set(card, field, new)
        _absorb(card, cid, field, review)
