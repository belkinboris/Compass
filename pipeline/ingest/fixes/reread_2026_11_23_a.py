def _oneoff(write):
    import hashlib
    import json
    import os
    import sys
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
    sys.path.insert(0, os.path.join(root, 'pipeline'))
    sys.path.insert(0, os.path.join(root, 'pipeline', 'ingest'))
    import fact_edit_guard
    import mass_edit_guard
    import review
    data_path = os.path.join(root, 'static', 'data', 'deals_promoted.json')
    reg_path = os.path.join(root, 'pipeline', 'fns_registry.json')
    mine = {(f['id'], f['field'], json.dumps(f['new'], ensure_ascii=False)) for f in FIXES}

    def new_id(comps, name):
        for n in range(1000):
            cid = 'g' + hashlib.sha1(('%s|%d' % (name, n)).encode('utf-8')).hexdigest()[:8]
            if cid not in comps:
                return cid
        raise RuntimeError(name)

    def apply(data):
        by = {d['id']: d for d in data['deals']}
        comps = data['companies']
        n = 0
        ids = {}

        def setf(c, field, old, new, quote, url):
            nonlocal n
            cur = (c.get('eco') or {}).get(field[4:]) if field.startswith('eco.') else \
                (c.get('law') or {}).get(field[4:]) if field.startswith('law.') else c.get(field)
            if cur == new:
                return
            assert cur == old, (c['id'], field, cur)
            if field.startswith('eco.') or field.startswith('law.'):
                c.setdefault(field[:3], {})[field[4:]] = new
            elif new is None:
                c.pop(field, None)
            else:
                c[field] = new
            if field in fact_edit_guard.FACT_FIELDS:
                fact_edit_guard.log(c, field, new, quote, url, BY, DAY)
            n += 1

        # g53ebfe72: продавался имущественный комплекс должника, а не сама компания «Донстар»:
        # профиль «Донстар» — продавец (как у «Евродон-Юга»), предмет — лот текстом.
        d = by['g53ebfe72']
        if d.get('seller_id') != 'g94365711':
            setf(d, 'asset', None, DONSTAR_LOT, DONSTAR_Q, DONSTAR_URL)
            setf(d, 'target', 'g94365711', None, DONSTAR_Q, DONSTAR_URL)
            assert d.get('seller') == 'ООО «Донстар»' and not d.get('seller_id')
            d['seller_id'] = 'g94365711'
            n += 1
        # g6c7dad8f: приговор — не условие сделки (перенесен в eco.context записью таблицы).
        setf(by['g6c7dad8f'], 'law.terms', PETRUS_TERMS_OLD, '—', '', PETRUS_URL)
        # g8eb9ed40: предмет с заглавной (форма, не факт).
        setf(by['g8eb9ed40'], 'asset', TIKH_OLD, TIKH_NEW, 'В Омской области продают гигантский агрохолдинг, '
             'основанный на базе бывшего совхоза «Тихвинский».', TIKH_URL)
        # g4e184429: предмет — имя объекта (деловой центр «Волна»), а не описание со строчной буквы.
        setf(by['g4e184429'], 'asset', VOLNA_OLD, VOLNA_NEW, VOLNA_Q, 'https://ura.news/news/1053141325')
        # gb89d3a84: дефис вместо тире в диапазоне оценки (форма; review.py считает дефис и тире одним).
        v = by['gb89d3a84']['eco']
        if v.get('val') != VAL_NEW:
            assert v.get('val') == VAL_OLD, v.get('val')
            v['val'] = VAL_NEW
            n += 1
        # gb89d3a84: стороны текстом -> профили.
        for p in NEW_PROFILES:
            c = by[p['card']]
            have = [k for k, v in comps.items() if v.get('name') == p['name'] and v.get('legal_short') == p['legal_short']]
            cid = have[0] if have else new_id(comps, p['name'])
            ids[p['name']] = cid
            if not have:
                comps[cid] = {'name': p['name'], 'ind': p['ind'], 'desc': p['desc'], 'kpi': [],
                              'legal_short': p['legal_short']}
                n += 1
            if p['role'] == 'buyer' and c.get('buyer') != cid:
                assert c.get('buyer_name') == 'АО «Медприбор»' and not c.get('buyer'), c.get('buyer')
                c.pop('buyer_name')
                c['buyer'] = cid
                fact_edit_guard.log(c, 'buyer', cid, VTS_Q, VTS_DN, BY, DAY)
                fact_edit_guard.log(c, 'buyer_name', None, VTS_Q, VTS_DN, BY, DAY)
                n += 1
            if p['role'] == 'target' and c.get('target') != cid:
                assert not c.get('target') and c.get('asset') == 'ООО «ВТС»'
                c['target'] = cid
                fact_edit_guard.log(c, 'target', cid, VTS_Q, VTS_DN, BY, DAY)
                n += 1
        # Этап gb89d3a84: день — запись ЕГРЮЛ, а не день заметки агрегатора; без «по данным Коммерсанта».
        ev = by['gb89d3a84']['events'][0]
        if ev.get('date') != '2026-10-19':
            assert ev['date'] == '2026-11-09' and ev['kind'] == 'closed', ev
            ev['date'] = '2026-10-19'
            ev['note'] = ('АО «Медприбор», связанное с группой «Центральная медицинская база» Эдуарда Иванова, купило '
                          'ООО «ВТС» у прежней владелицы Александры Губы: переход 100% долей записан в ЕГРЮЛ '
                          '19 октября 2026 года.')
            ev['source'] = ['Коммерсантъ', KS_URL]
            n += 1
        for cid, url, why in SRC_DROP:
            c = by[cid]
            before = len(c['src'])
            c['src'] = [s for s in c['src'] if s[1] != url]
            n += before - len(c['src'])
        for cid, url, row, why in SRC_REPLACE:
            c = by[cid]
            for i, s in enumerate(c['src']):
                if s[1] == url:
                    c['src'][i] = list(row)
                    n += 1
        for cid, short in LEGAL_SHORT.items():
            if comps[cid].get('legal_short') != short:
                assert not comps[cid].get('legal_short')
                comps[cid]['legal_short'] = short
                n += 1
        for cid, (old, new) in DESC.items():
            if comps[cid].get('desc') != new:
                assert comps[cid].get('desc') == old, comps[cid].get('desc')
                comps[cid]['desc'] = new
                n += 1
        for cid, text in REGISTRY.items():
            c = by[cid]
            notes = c.setdefault('accepted_notes', {})
            if (notes.get('checked') or {}).get('registry_owners') != text:
                notes.setdefault('checked', {})['registry_owners'] = text
                n += 1
        for (cid, key, role), text in NOTE_SET.items():
            notes = by[cid].setdefault('accepted_notes', {}).setdefault(key, {})
            if notes.get(role) != text:
                notes[role] = text
                n += 1
        for cid, key, role in NOTE_DROP:
            notes = (by[cid].get('accepted_notes') or {}).get(key) or {}
            if role in notes:
                notes.pop(role)
                if not notes:
                    by[cid]['accepted_notes'].pop(key)
                n += 1
        # Прежние записи таблицы на поля, которые эта партия переписывает (своей записью или здесь):
        # отпечаток в proofread_absorbed, иначе две живые записи одного поля (docs/card_editing.md).
        keys = {(f['id'], f['field']) for f in FIXES if f['field'] != 'src'} | {
            ('g6c7dad8f', 'law.terms'), ('g8eb9ed40', 'asset')}
        for f in review.FIXES:
            if (f['id'], f['field']) not in keys or f['new'] is None:
                continue
            if (f['id'], f['field'], json.dumps(f['new'], ensure_ascii=False)) in mine:
                continue
            marks = by[f['id']].setdefault('proofread_absorbed', {}).setdefault(f['field'], [])
            fp = review.fix_fingerprint(f['new'])
            if fp not in marks:
                marks.append(fp)
                n += 1
        return n, ids

    def registry(ids):
        import fns_registry
        raw = open(reg_path, encoding='utf-8').read()
        rows = json.loads(raw)
        known = {r.get('company_id') for r in fns_registry.REGISTRY}
        add = list(REGISTRY_ADD) + [
            {'company_id': ids[p['name']], 'decision': 'confirmed', 'inn': p['inn'], 'reason': p['reason'], 'date': DAY}
            for p in NEW_PROFILES]
        m = 0
        for row in add:
            have = [r for r in fns_registry.REGISTRY if r.get('company_id') == row['company_id']]
            if have:
                assert have[0].get('inn') == row['inn'], (row['company_id'], have)
                continue
            assert fns_registry.inn_is_valid(row['inn']), row['inn']
            assert not [r for r in fns_registry.REGISTRY if r.get('inn') == row['inn']], ('ИНН уже у другого профиля', row)
            rows.append(dict(row))
            print('реестр %s: + ИНН %s' % (row['company_id'], row['inn']))
            m += 1
        return m, rows, raw

    raw = open(data_path, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    n, ids = apply(data)
    m, rows, reg_raw = registry(ids)
    if not n and not m:
        print('Уже применено.')
        return 0
    mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
    bad = fact_edit_guard.unbacked(old, data)
    assert not bad, bad
    if not write:
        print('Сухой прогон: %d правок базы, %d строк реестра (новые профили: %s). Запись — с ключом --write.'
              % (n, m, ids))
        return 0
    if n:
        fresh_raw = open(data_path, encoding='utf-8').read()     # перечитать прямо перед записью
        fresh = json.loads(fresh_raw)
        _n, ids2 = apply(fresh)
        assert ids2 == ids, (ids, ids2)
        with open(data_path, 'w', encoding='utf-8') as f:
            f.write(json.dumps(fresh, ensure_ascii=False, indent=1) + ('\n' if fresh_raw.endswith('\n') else ''))
    if m:
        with open(reg_path, 'w', encoding='utf-8') as fh:
            fh.write(json.dumps(rows, ensure_ascii=False, indent=1) + ('\n' if reg_raw.endswith('\n') else ''))
    print('ЗАПИСАНО: %d правок базы, %d строк реестра.' % (n, m))
    return 0


if __name__ == '__main__':
    import sys as _sys
    _sys.exit(_oneoff('--write' in _sys.argv))
