# `review.py` не пишет `law.adv` списком и не пишет только по одной карточке (`--write` применяет
# все живые партии, в том числе чужие) (новое значение должно лежать в цитате дословно —
# docs/card_editing_scripts.md, «Когда review.py не подходит»), поэтому записи выше
# применяются этим же файлом, с assert на старое значение; после записи review.py видит
# ее примененной (поле совпадает с `new`).
#     python3 pipeline/ingest/fixes/lenta_rbf_2026_11_11.py          # сухой прогон
#     python3 pipeline/ingest/fixes/lenta_rbf_2026_11_11.py --write  # записать
if __name__ == '__main__':
    import json
    import os
    import sys
    data = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..',
                        'static', 'data', 'deals_promoted.json')
    base = json.load(open(data, encoding='utf-8'))          # перечитано прямо перед записью
    cards = {d['id']: d for d in base['deals']}
    for fix in FIXES + ONE_OFF:
        card = cards[fix['id']]
        sec, key = fix['field'].split('.') if '.' in fix['field'] else (None, fix['field'])
        holder = card[sec] if sec else card
        current = holder.get(key)
        if current == fix['new']:
            print('уже применено:', fix['id'], fix['field'])
            continue
        assert current == fix['old'], (fix['id'], current)
        print('ПРАВИМ', fix['id'], fix['field'])
        holder[key] = fix['new']
    if '--write' in sys.argv:
        with open(data, 'w', encoding='utf-8') as f:
            json.dump(base, f, ensure_ascii=False, indent=1)
            f.write('\n')
        print('записано')
    else:
        print('сухой прогон')
