def _card(data, cid):
    return next(d for d in data['deals'] if d['id'] == cid)


def _oneoff_apply(data, strict=True):
    import fact_edit_guard
    n = 0
    # --- gdfce7e3d: сумма — та же оценка, что уже стоит в eco.sum (записью таблицы выше)
    c = _card(data, 'gdfce7e3d')
    if c.get('sum') != OBS_RETRACTED:
        assert c.get('sum') == 'Не раскрыта', c.get('sum')
        if strict:
            assert c['eco'].get('sum') == OBS_RETRACTED, c['eco'].get('sum')
        c['sum'] = OBS_RETRACTED
        fact_edit_guard.log(c, 'sum', OBS_RETRACTED, Q_OBS_SUM, VED_OBS, ONEOFF_BY, ONEOFF_DAY)
        n += 1
    # --- g3ecb7b86: отрасль — по предмету (словарь review.py слова «лифт» не знает)
    c = _card(data, 'g3ecb7b86')
    if c.get('ind') != LIFT_IND_NEW:
        assert c.get('ind') == LIFT_IND_OLD, c.get('ind')
        c['ind'] = LIFT_IND_NEW
        n += 1
    # --- gdfce7e3d: возвращенная в сумму оценка уходит из retracted (иначе enrich.py сочтет ее снятой)
    c = _card(data, 'gdfce7e3d')
    retr = (c.get('retracted') or {}).get('sum') or []
    if OBS_RETRACTED in retr and c.get('sum') == OBS_RETRACTED:   # сумма поставлена выше
        retr.remove(OBS_RETRACTED)
        if not retr:
            c['retracted'].pop('sum')
        if not c['retracted']:
            c.pop('retracted')
        n += 1
    # --- c51d0bb64: слова Пьянова 28 августа, а не 31 августа
    c = _card(data, 'c51d0bb64')
    ctx = c['eco']['context']
    if WB_CTX_NEW not in ctx:
        assert ctx.count(WB_CTX_OLD) == 1, ctx[:200]
        c['eco']['context'] = ctx.replace(WB_CTX_OLD, WB_CTX_NEW)
        n += 1
    # --- заметки о реестре (находки registry_owners_unchecked)
    for cid, path, text in NOTES:
        c = _card(data, cid)
        notes = c.setdefault('accepted_notes', {}).setdefault(path[0], {})
        if notes.get(path[1]) != text:
            notes[path[1]] = text
            n += 1
    return n


def _oneoff_main(write):
    import json
    import os
    import sys
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
    sys.path.insert(0, os.path.join(root, 'pipeline'))
    import fact_edit_guard
    import mass_edit_guard
    path = os.path.join(root, 'static', 'data', 'deals_promoted.json')
    raw = open(path, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    n = _oneoff_apply(data, strict=write)
    if not n:
        print('Уже применено.')
        return 0
    mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
