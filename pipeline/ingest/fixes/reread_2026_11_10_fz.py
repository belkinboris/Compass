def _get(card, field):
    o = card
    for p in field.split('.'):
        o = o.get(p) if isinstance(o, dict) else None
    return o


def _set(card, field, value):
    parts = field.split('.')
    o = card
    for p in parts[:-1]:
        o = o.setdefault(p, {})
    if value is None:
        o.pop(parts[-1], None)
    else:
        o[parts[-1]] = value


def _apply(data, review=None):
    deals = {d['id']: d for d in data['deals']}
    for cid, adv in _ADV.items():
        law = deals[cid].setdefault('law', {})
        firms = [a[1] for a in (law.get('adv') or [])]
        assert firms == _ADV_OLD_FIRMS[cid], (cid, firms)
        law['adv'] = [list(a) for a in adv]
    for cid, field, old, new in _SET:
        card = deals[cid]
        assert _get(card, field) == old, (cid, field, _get(card, field))
        _set(card, field, new)
    for cid, field, value in _RETRACT:
        lst = deals[cid].setdefault('retracted', {}).setdefault(field, [])
        if value not in lst:
            lst.append(value)
    for cid, ev in _EVIDENCE.items():
        deals[cid].setdefault('party_evidence', {}).update(ev)
    for cid, notes in _NOTES.items():
        acc = deals[cid].setdefault('accepted_notes', {})
        for k, v in notes.items():
            if isinstance(v, dict):
                acc.setdefault(k, {}).update(v)
            else:
                acc[k] = v


