def _apply(data):
    sys.path.insert(0, os.path.join(ROOT, 'pipeline'))
    sys.path.insert(0, os.path.join(ROOT, 'pipeline', 'ingest'))
    import fact_edit_guard
    deals = {d['id']: d for d in data['deals']}
    comps = data['companies']
    for cid, field, old, new, quote, url in _SET:
        card = deals[cid]
        assert _get(card, field) == old, (cid, field, _get(card, field))
        _set(card, field, new)
        if field in FACT:
            assert quote and url, (cid, field)
            fact_edit_guard.log(card, field, new, quote, url, BY)
    for cid, i, old, new, _q in _EVENTS:
        ev = deals[cid]['events'][i]
        assert ev.get('note') == old, (cid, i, ev.get('note'))
        ev['note'] = new
    for cid, field, value in _RETRACT:
        lst = deals[cid].setdefault('retracted', {}).setdefault(field, [])
        if value not in lst:
            lst.append(value)
    for comp, field, old, new in _COMPANY:
        assert comps[comp].get(field) == old, (comp, field, comps[comp].get(field))
        comps[comp][field] = new


def _apply_registry(write):
    path = os.path.join(ROOT, 'pipeline', 'fns_registry.json')
    rows = json.load(open(path, encoding='utf-8'))
    for comp, old, new, reason in _REGISTRY:
        row = [r for r in rows if r.get('company_id') == comp]
        assert len(row) <= 1, (comp, row)
        if not row:
            assert old is None, comp
            rows.append({'company_id': comp})
            row = rows[-1:]
        assert row[0].get('inn') == old, (comp, row)
        row[0].update({'inn': new, 'decision': 'confirmed', 'reason': reason, 'date': '2026-11-12'})
    if write:
        json.dump(rows, open(path, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
        open(path, 'a', encoding='utf-8').write('\n')


