def _get(obj, field):
    for p in field.split('.'):
        obj = obj.get(p) if isinstance(obj, dict) else None
    return obj


def _set(obj, field, value):
    parts = field.split('.')
    for p in parts[:-1]:
        obj = obj.setdefault(p, {})
    if value is DEL:
        obj.pop(parts[-1], None)
    elif value is None:
        obj.pop(parts[-1], None)
    else:
        obj[parts[-1]] = value


def _apply(data):
    """Повторный запуск ничего не ломает: уже примененное пропускается.
    old=None в _SET у прозы значит «любое прежнее значение» (длинный текст сверен вычиткой глазами)."""
    import fact_edit_guard
    deals = {d['id']: d for d in data['deals']}
    for comp, field, old, new in _COMPANY:
        if field == '*':
            if comp not in data['companies']:
                data['companies'][comp] = dict(new)
            continue
        c = data['companies'][comp]
        if c.get(field) == new:
            continue
        assert c.get(field) == old, (comp, field, c.get(field))
        c[field] = new
    for cid, field, old, new, quote, url in ONE_OFF:
        card = deals[cid]
        if _get(card, field) == new:
            continue
        assert _get(card, field) == old, (cid, field, _get(card, field))
        _set(card, field, new)
        fact_edit_guard.log(card, field, new, quote, url, _BY)
    for cid, field, old, new in _SET:
        cur = _get(deals[cid], field)
        if (new is DEL and cur is None) or cur == new:
            continue
        if old is not None or field.startswith('accepted_notes') or field.endswith('_basis'):
            assert cur == old, (cid, field, cur)
        _set(deals[cid], field, new)
    for cid, field, value in _RETRACT:
        lst = deals[cid].setdefault('retracted', {}).setdefault(field, [])
        if value not in lst:
            lst.append(value)
    for cid, src in _SRC:
        card = deals[cid]
        have = {s[1] for s in card.get('src') or []}
        assert have <= {s[1] for s in src}, (cid, 'src теряет адрес')
        card['src'] = [list(s) for s in src]


