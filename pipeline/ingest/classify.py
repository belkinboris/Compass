"""Фильтр притока: эта новость — о сделке или нет.

ЗАЧЕМ. Источник отдаёт всё подряд: котировки, назначения, отчётность. В базу
должны попадать только сделки, и решать это надо ДО того, как карточка будет
собрана: разбирать всё подряд дорого, а мусор в базе дороже вдвойне.

ПОЧЕМУ ПРАВИЛАМИ, А НЕ МОДЕЛЬЮ. У нас есть 1333 заголовка настоящих сделок —
на них правило можно измерить прямо сейчас, без сети и без денег. Модель имеет
смысл там, где правило уже не тянет; сначала надо знать, где именно оно не
тянет.

КАК ИЗМЕРЯЕТСЯ. `--measure` прогоняет правило по заголовкам базы (полнота: их
все нужно узнать) и по списку заведомо НЕ-сделочных заголовков внутри этого
файла (точность: ни один не должен пройти). Список отрицательных примеров
написан руками и намеренно состоит из соседних тем, на которых правило легко
ошибается: котировки, отчётность, назначения, запуск продукта, суды.

ЧТО ВАЖНО ПОНИМАТЬ ПРО ГРАНИЦУ. «Ведёт переговоры о покупке» — это сделка:
в базе такие карточки есть со статусом «Обсуждается». А «акции подорожали
после новости о покупке» — не сделка, а рынок: решает не наличие слова, а то,
о чём предложение.

Запуск:
    python3 pipeline/ingest/classify.py --measure
"""
