# --- признаки сделки -------------------------------------------------------
# Основы даны так, чтобы ловить все падежи и виды: «продавец» в именительном
# падеже прошлые прогоны пропускали именно из-за «продавц\w*» (CLAUDE.md).
# «приобрёл» и «приобрел» — разные строки: без ё правило теряло каждую пятую
# карточку. То же с «продаст» (будущее время) и инфинитивами «купить/продать»,
# которых в заголовках о переговорах большинство.
# «куп» обязан начинаться со слова: без границы слева «закупить автобусы»
# (госзакупка, не сделка) проходил через «купить» внутри «закупить». Зеркало
# урока про «\b после приставки»: там граница мешала ловить «покупает», здесь
# её отсутствие ловило чужую приставку. «выкупить» жив — у него своя ветка.
BUY = (r'(?<![а-яё])куп(?:ил|ила|ило|ит|ят|ует|уют|ля|или|ить)|покуп(?:к[аиуе]|кой|ает|ают)'
       r'|приобр(?:е|ё)(?:л|ла|ло|ли|сти|тен|тет|тает|тают|тём|тет)'
       r'|выкуп(?:ил|ила|ит|ает|лен|ает|ить|а\b|)|консолидир|получил[аои]?\s+\d+[,.]?\d*%')
SELL = (r'прода(?:л|ла|ло|ли|ёт|ет|жа|жи|же|ют|ст|дут|ть|вать)'
        r'|выстав(?:ил[аи]?|ля\w+|лени\w+)\s+на\s+(?:продажу|торги|аукцион)'
        r'|реализовал[аи]?\s+(?:пакет|долю|акции)'
        r'|избав(?:ил[аи]?сь|ится)\s+от')
# «Присоединение» — форма реорганизации, то есть та же покупка: «МКБ завершил
# присоединение Дальневосточного банка». Без него правило теряло реальные
# банковские слияния целиком.
MERGE = (r'слия\w+|поглощ\w+|объедин(?:яют|ились|ение)\s+(?:бизнес|компан|актив)'
         r'|присоедин(?:ение|ил[аи]?|ение)\s+\w*\s*(?:банк|компани|актив|бизнес|общест)'
         r'|завершил[аи]?\s+присоединение')
# Смена собственника по решению государства — тоже смена собственника. В базе
# это отдельная тема («Национализация / иск Генпрокуратуры»), и терять её нельзя.
SEIZURE = (r'национализирова\w+|деприватизац|обращен\w+\s+в\s+доход\s+государства'
           r'|изъят\w+\s+в\s+(?:пользу|доход)\s+государства|отобрал[аи]\s+у\b')
STAKE = (r'\b(?:вой(?:ти|д[её]т)|вош(?:ёл|ел|ла)|выш(?:ёл|ел|ла))\s+в?\s*'
         r'(?:капитал|состав\s+акционеров|число\s+акционеров)'
         r'|смен(?:ил|ила|а)\s+(?:собственник|владельц)'
         r'|перед(?:ал|ала|аны|ача)\s+[^.;]{0,30}(?:долю|доли|%|контроль|акци|актив)'
         r'|переш(?:ёл|ел|ла|ло|ли)\s+(?:к|в\s+собственность|под\s+контроль)'
         r'|увеличил[аи]?\s+долю|нарастил[аи]?\s+(?:долю|пакет)')
ROUND = (r'привл(?:е|ё)к\w*\s+[^.;]{0,40}(?:млн|млрд|раунд|инвестиц|финансиров)'
         r'|привл(?:е|ё)к\w*\s+[^.;]{0,40}(?:тыс|\$|€|₽)'
         r'|\bround\b|раунд[аеы]?\b|series\s+[abcd]\b|\bseed\b|pre-?ipo|допэмисси'
         r'|запуск\w*\s+[^.;]{0,20}фонда')
IPO = r'\bipo\b|\bspo\b|размещ\w+\s+акци|выход\w*\s+на\s+бирж'
# «Торги» по-русски — это И продажа с молотка, И биржевые торги. Голое слово
# ловило «объём торгов на Мосбирже», «по итогам торгов», «завершил торги»: на
# живом потоке это была САМАЯ частая ложная сработка — 9 из 74 ошибок одним
# признаком. Требуем контекст продажи имущества.
# Основа «выстав», а НЕ «выставл»: «выставило на торги» — самая частая форма, и
# «выставл» с ней не совпадает (совпадает только «выставлен», «выставляет»).
# Третий раз те же грабли, что с «продавц\w*» и «\b» после приставки.
AUCTION = (r'(?:выстав|реализац|прода|куп|выкуп|приобре)\w*[^.;]{0,60}(?:на\s+торг|с\s+торгов)'
           r'|торг(?:и|ов)\s+по\s+(?:продаже|реализации)'
           r'|аукцион|конкурсн\w+\s+производств|лот\s+выставлен')
DEAL_WORD = (r'\bm&a\b|сделк\w+\s+(?:по|с)\s+(?:покупк|продаж|приобрет)|закрыл[аи]?\s+сделку'
             r'|структурн\w+\s+\w*\s*сделк|сделка\s+на\s+\d')
# Заголовок бывает не предложением, а именной группой: «Инвестиции X в Y»,
# «Создание СП», «Приобретение Z». Глагола в нём нет вовсе, и без этих правил
# правило теряло каждую десятую карточку базы.
NOUN = (r'\bинвестиц\w+\s+[^.;]{0,90}\bв\b|инвестировал\w*\s+[^.;]{0,40}\bв\b'
        r'|вложил\w*\s+[^.;]{0,40}\bв\b|созда(?:ли|ла|ют)\s+[^.;]{0,40}платформу'
        r'|создани\w+\s+(?:сп\b|совместн)|совместн\w+\s+предприят'
        r'|деконсолидац|выход\s+из\s+(?:сп\b|капитала|проекта|бизнеса)'
        r'|учрежда\w+\s+[^.;]{0,25}фонд|рассматрива\w+\s+(?:продажу|покупку|приобретение)'
        r'|передан\w+\s+(?:во\s+временное\s+управление|в\s+собственность)'
        r'|безвозмездно\s+перед|соглашени\w+\s+об?\s+(?:продаже|покупке|приобретении)')

POSITIVE = re.compile('|'.join('(?:%s)' % p for p in
                               (BUY, SELL, MERGE, SEIZURE, STAKE, ROUND, IPO, AUCTION, DEAL_WORD, NOUN)), re.I)

