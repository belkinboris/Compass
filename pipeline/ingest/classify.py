# -*- coding: utf-8 -*-
"""Фильтр притока: эта новость — о сделке или нет.

ЗАЧЕМ. Источник отдаёт всё подряд: котировки, назначения, отчётность. В базу
должны попадать только сделки, и решать это надо ДО того, как карточка будет
собрана: разбирать всё подряд дорого, а мусор в базе дороже вдвойне.

ПОЧЕМУ ПРАВИЛАМИ, А НЕ МОДЕЛЬЮ. У нас есть 1333 заголовка настоящих сделок —
на них правило можно измерить прямо сейчас, без сети и без денег. Модель имеет
смысл там, где правило уже не тянет; сначала надо знать, где именно оно не
тянет.

КАК ИЗМЕРЯЕТСЯ. `--measure` прогоняет правило по заголовкам базы (полнота: их
все нужно узнать) и по списку заведомо НЕ-сделочных заголовков внутри этого
файла (точность: ни один не должен пройти). Список отрицательных примеров
написан руками и намеренно состоит из соседних тем, на которых правило легко
ошибается: котировки, отчётность, назначения, запуск продукта, суды.

ЧТО ВАЖНО ПОНИМАТЬ ПРО ГРАНИЦУ. «Ведёт переговоры о покупке» — это сделка:
в базе такие карточки есть со статусом «Обсуждается». А «акции подорожали
после новости о покупке» — не сделка, а рынок: решает не наличие слова, а то,
о чём предложение.

Запуск:
    python3 pipeline/ingest/classify.py --measure
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

# --- признаки сделки -------------------------------------------------------
# Основы даны так, чтобы ловить все падежи и виды: «продавец» в именительном
# падеже прошлые прогоны пропускали именно из-за «продавц\w*» (CLAUDE.md).
# «приобрёл» и «приобрел» — разные строки: без ё правило теряло каждую пятую
# карточку. То же с «продаст» (будущее время) и инфинитивами «купить/продать»,
# которых в заголовках о переговорах большинство.
BUY = (r'куп(?:ил|ила|ило|ит|ят|ует|уют|ля|или|ить)|покуп(?:к[аиуе]|кой|ает|ают)'
       r'|приобр(?:е|ё)(?:л|ла|ло|ли|сти|тен|тет|тает|тают|тём|тет)'
       r'|выкуп(?:ил|ила|ит|ает|лен|ает|ить|а\b|)|консолидир|получил[аои]?\s+\d+[,.]?\d*%')
SELL = (r'прода(?:л|ла|ло|ли|ёт|ет|жа|жи|же|ют|ст|дут|ть|вать)'
        r'|выстав(?:ил[аи]?|ля\w+|лени\w+)\s+на\s+(?:продажу|торги|аукцион)'
        r'|реализовал[аи]?\s+(?:пакет|долю|акции)'
        r'|избав(?:ил[аи]?сь|ится)\s+от')
MERGE = r'слия\w+|поглощ\w+|объедин(?:яют|ились|ение)\s+(?:бизнес|компан|актив)'
STAKE = (r'\b(?:вой(?:ти|д[её]т)|вош(?:ёл|ел|ла)|выш(?:ёл|ел|ла))\s+в?\s*'
         r'(?:капитал|состав\s+акционеров|число\s+акционеров)'
         r'|смен(?:ил|ила|а)\s+(?:собственник|владельц)'
         r'|перед(?:ал|ала|аны|ача)\s+[^.;]{0,30}(?:долю|доли|%|контроль|акци|актив)'
         r'|переш(?:ёл|ел|ла|ло|ли)\s+(?:к|в\s+собственность|под\s+контроль)'
         r'|увеличил[аи]?\s+долю|нарастил[аи]?\s+(?:долю|пакет)')
ROUND = (r'привл(?:е|ё)к\w*\s+[^.;]{0,40}(?:млн|млрд|раунд|инвестиц|финансиров)'
         r'|привл(?:е|ё)к\w*\s+[^.;]{0,40}(?:тыс|\$|€|₽)'
         r'|\bround\b|раунд[аеы]?\b|series\s+[abcd]\b|\bseed\b|pre-?ipo|допэмисси'
         r'|запуск\w*\s+[^.;]{0,20}фонда')
IPO = r'\bipo\b|\bspo\b|размещ\w+\s+акци|выход\w*\s+на\s+бирж'
AUCTION = r'\bторг(?:ах|и|ов)\b|аукцион|конкурсн\w+\s+производств'
DEAL_WORD = (r'\bm&a\b|сделк\w+\s+(?:по|с)\s+(?:покупк|продаж|приобрет)|закрыл[аи]?\s+сделку'
             r'|структурн\w+\s+\w*\s*сделк|сделка\s+на\s+\d')
# Заголовок бывает не предложением, а именной группой: «Инвестиции X в Y»,
# «Создание СП», «Приобретение Z». Глагола в нём нет вовсе, и без этих правил
# правило теряло каждую десятую карточку базы.
NOUN = (r'\bинвестиц\w+\s+[^.;]{0,90}\bв\b|инвестировал\w*\s+[^.;]{0,40}\bв\b'
        r'|вложил\w*\s+[^.;]{0,40}\bв\b|созда(?:ли|ла|ют)\s+[^.;]{0,40}платформу'
        r'|создани\w+\s+(?:сп\b|совместн)|совместн\w+\s+предприят'
        r'|деконсолидац|выход\s+из\s+(?:сп\b|капитала|проекта|бизнеса)'
        r'|учрежда\w+\s+[^.;]{0,25}фонд|рассматрива\w+\s+(?:продажу|покупку|приобретение)'
        r'|передан\w+\s+(?:во\s+временное\s+управление|в\s+собственность)'
        r'|безвозмездно\s+перед|соглашени\w+\s+об?\s+(?:продаже|покупке|приобретении)')

POSITIVE = re.compile('|'.join('(?:%s)' % p for p in
                               (BUY, SELL, MERGE, STAKE, ROUND, IPO, AUCTION, DEAL_WORD, NOUN)), re.I)

# --- признаки «это не сделка» ---------------------------------------------
# Проверяются ПОСЛЕ положительных: заголовок про котировки почти всегда
# содержит слово «покупка», а про отчётность — «выручка от продаж».
MARKET = r'котиров|подорожал|подешевел|акции\s+(?:вырос|упал|снизил|прибавил)|индекс\s+мосбирж|дивиденд|курс\s+(?:рубл|доллар|валют)'
REPORT = r'выручк|чист(?:ая|ую)\s+прибыл|EBITDA|отч[её]тност|результат\w*\s+за\s+(?:\d|перв|втор|трет|четв|квартал|полугод|год)|финпоказател'
PEOPLE = (r'назначен|покинул\s+пост|уволен|ушёл\s+в\s+отставку|сменил\s+гендиректор'
          r'|возглавил[аи]?\s+(?:компани|банк|бизнес|совет|правлени|департамент|направлени)')
LAUNCH = r'запустил|открыл\s+(?:магазин|офис|завод|точк)|представил\s+(?:новый|обновл)|выпустил\s+(?:новую|обновл)'
COURT = r'\bиск\b|подал[аи]?\s+в\s+суд|оштрафов|уголовн\w+\s+дел|обыск'
RETAIL = (r'куп(?:ил|ить)\s+(?:квартир|дом|автомобил|машин|билет)'
          r'|продаж[аи]\s+[^.]{0,30}(?:вырос|упал|снизил|сократил|увеличил)'
          r'|продажи\s+(?:автомобил|товар|жиль|смартфон)')
NEGATIVE = re.compile('|'.join('(?:%s)' % p for p in
                               (MARKET, REPORT, PEOPLE, LAUNCH, COURT, RETAIL)), re.I)

# Отрицательные примеры для замера точности. Написаны руками; специально взяты
# соседние темы, на которых правило легко ошибается.
NOT_DEALS = [
    'Акции «Магнита» подорожали на 3% после новости о покупке сети «Дикси»',
    'Мосбиржа: индекс вырос на 1,2% на фоне корпоративных новостей',
    '«Лента» отчиталась о росте выручки на 24% за первое полугодие',
    'Чистая прибыль Сбербанка по МСФО выросла до 1,5 трлн рублей',
    'Совет директоров рекомендовал дивиденды за 2025 год',
    'Гендиректором «Магнита» назначен Анатолий Иванов',
    'Основатель Wildberries покинул пост генерального директора',
    '«Яндекс» запустил новый сервис доставки продуктов',
    'X5 открыл тысячный магазин «Чижик» в Подмосковье',
    'ФАС оштрафовала «Ozon» за нарушение рекламного законодательства',
    'Суд признал банкротом сеть кинотеатров «Синема Парк»',
    'Роспотребнадзор подал иск к производителю детского питания',
    'Средний россиянин купил квартиру в ипотеку на 25 лет',
    'Курс доллара опустился ниже 90 рублей',
    'Продажи автомобилей в России выросли на 12%',
    '«Аэрофлот» представил новую программу лояльности',
    'Выручка от продаж «Детского мира» в третьем квартале снизилась',
    'Котировки «Газпрома» отреагировали на решение совета директоров',
]


def looks_like_deal(title, text=''):
    """Заголовок (и, если есть, первый абзац) сообщают о сделке?"""
    blob = ' '.join(x for x in (title, text) if x)
    if not POSITIVE.search(blob):
        return False
    if NEGATIVE.search(blob):
        return False
    return True


def why(title, text=''):
    """Что именно сработало — для отладки и для журнала прогона."""
    blob = ' '.join(x for x in (title, text) if x)
    pos = POSITIVE.search(blob)
    neg = NEGATIVE.search(blob)
    return {'positive': pos.group(0) if pos else None,
            'negative': neg.group(0) if neg else None,
            'verdict': bool(pos and not neg)}


def measure():
    data = json.load(open(DATA, encoding='utf-8'))
    titles = [str(d.get('title') or '') for d in data['deals']]
    found = [t for t in titles if looks_like_deal(t)]
    missed = [t for t in titles if not looks_like_deal(t)]
    passed = [t for t in NOT_DEALS if looks_like_deal(t)]
    print('ПОЛНОТА на своих данных: %d из %d заголовков базы узнаны как сделка (%.1f%%)'
          % (len(found), len(titles), 100.0 * len(found) / len(titles)))
    print('ТОЧНОСТЬ на ручном списке: пропущено %d из %d не-сделок' % (len(passed), len(NOT_DEALS)))
    for t in passed:
        print('   ложно принято за сделку:', t[:100], '|', why(t))
    print('\nНе узнаны (первые 15 из %d) — по ним видно, чего правилу не хватает:' % len(missed))
    for t in missed[:15]:
        print('  ', t[:110])


if __name__ == '__main__':
    if '--measure' in sys.argv:
        measure()
    else:
        print(__doc__)
