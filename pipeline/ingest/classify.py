def looks_like_deal(title, text=''):
    """Заголовок сообщает о сделке — и текст этому не противоречит.

    ПРИЗНАК СДЕЛКИ ИЩЕТСЯ ТОЛЬКО В ЗАГОЛОВКЕ, а текст используется лишь чтобы
    ОТКАЗАТЬ. Раньше искали по обоим, и это давало половину всех ложных
    срабатываний живого потока: «Российский разработчик получил патент США»
    прошло из-за «вложил $5 млн в» в аннотации, «Диверсификация не нужна» — из-за
    «продал», «В Прикамье жителей проинформируют о выборах» — из-за «перешла к».
    Обзор, дайджест и аналитическая колонка ВСЕГДА упоминают чужие сделки
    мимоходом; заголовок же говорит о том, чему посвящен текст. Тот же урок, что
    в CLAUDE.md про пресс-релиз («два текста, склеенных вместе») и про заголовок
    против «Дополнительной информации».
    """
    if not title or not POSITIVE.search(_tidy(title)):
        return False
    blob = ' '.join(x for x in (title, text) if x).replace('ё', 'е').replace('Ё', 'Е')
    if NEGATIVE.search(blob):
        return False
    return True


def why(title, text=''):
    """Что именно сработало — для отладки и для журнала прогона."""
    blob = ' '.join(x for x in (title, text) if x).replace('ё', 'е').replace('Ё', 'Е')
    pos = POSITIVE.search(_tidy(title))
    neg = NEGATIVE.search(blob)
    return {'positive': pos.group(0) if pos else None,
            'negative': neg.group(0) if neg else None,
            'verdict': bool(pos and not neg)}


def measure():
    data = json.load(open(DATA, encoding='utf-8'))
    titles = [str(d.get('title') or '') for d in data['deals']]
    found = [t for t in titles if looks_like_deal(t)]
    missed = [t for t in titles if not looks_like_deal(t)]
    passed = [t for t in NOT_DEALS if looks_like_deal(t)]
    print('ПОЛНОТА на своих данных: %d из %d заголовков базы узнаны как сделка (%.1f%%)'
          % (len(found), len(titles), 100.0 * len(found) / len(titles)))
    print('ТОЧНОСТЬ на ручном списке: пропущено %d из %d не-сделок' % (len(passed), len(NOT_DEALS)))
    for t in passed:
        print('   ложно принято за сделку:', t[:100], '|', why(t))
    print('\nНе узнаны (первые 15 из %d) — по ним видно, чего правилу не хватает:' % len(missed))
    for t in missed[:15]:
        print('  ', t[:110])


