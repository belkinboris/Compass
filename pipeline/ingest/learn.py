"""Обучение механики: чему научили правки, сделанные чтением.

ЗАЧЕМ. Таблица `FIXES` в review.py — это накопленный журнал ОШИБОК МЕХАНИКИ:
каждая запись говорит «правило этого не увидело, человек/модель увидели, вот
цитата». Полтора месяца этот журнал никто не разбирал, хотя он и есть готовый
учебный материал: если один и тот же класс ошибки повторяется, значит нужно
не чинить карточки по одной, а править правило.

ЧТО СЧИТАЕТСЯ КЛАССОМ. Поле + вид промаха: механика ПРОМОЛЧАЛА (поле было
пустым) или механика СОВРАЛА (поле было заполнено неверно). Второе дороже: в
базу и в канал уходит правдоподобная неправда. Замер 9 августа на 156 правках:
128 молчаний против 28 враний, и внутри враний самые крупные классы — отрасль
(9) и сумма (5).

ЧЕГО ЭТОТ СКРИПТ НЕ ДЕЛАЕТ. Он не меняет правила сам. Он показывает, где
болит, и хранит РЕЗУЛЬТАТЫ УЖЕ ПРОВЕРЕННЫХ ГИПОТЕЗ (`REJECTED` ниже) — чтобы
следующий прогон не тратил токены на переоткрытие того, что уже измерено и
отвергнуто. Это прямое продолжение культуры CLAUDE.md: отвергнутая гипотеза с
цифрами ценнее, чем ненаписанное правило.

Запуск:
    python3 pipeline/ingest/learn.py            # что болит и что уже пробовали
"""
