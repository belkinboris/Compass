def failure_classes(fixes):
    """(поле, вид промаха) -> сколько раз. Вид: «соврала» дороже «промолчала»."""
    classes = collections.Counter()
    for f in fixes:
        empty = f['old'] in (None, '—', '')
        classes[(f['field'], 'промолчала' if empty else 'СОВРАЛА')] += 1
    return classes


def main():
    fixes = review.FIXES
    classes = failure_classes(fixes)
    lied = {k: v for k, v in classes.items() if k[1] == 'СОВРАЛА'}
    silent = {k: v for k, v in classes.items() if k[1] == 'промолчала'}

    print('Журнал правок чтением: %d записей.' % len(fixes))
    print('Механика соврала: %d | промолчала: %d'
          % (sum(lied.values()), sum(silent.values())))

    print('\nГДЕ МЕХАНИКА ВРЁТ (чинить правилом в первую очередь):')
    for (field, _), n in sorted(lied.items(), key=lambda x: -x[1]):
        mark = ''
        if any(l['field'] == field for l in LEARNED):
            mark = '  <- правило уже выведено'
        elif any(r['field'] == field for r in REJECTED):
            mark = '  <- гипотезы проверены и отвергнуты, см. ниже'
        print('  %-16s %3d%s' % (field, n, mark))

    print('\nГДЕ МЕХАНИКА МОЛЧИТ (это норма, если поле требует смысла):')
    for (field, _), n in sorted(silent.items(), key=lambda x: -x[1])[:8]:
        print('  %-16s %3d' % (field, n))

    print('\nУЖЕ ВЫВЕДЕНО ИЗ ЭТОГО ЖУРНАЛА:')
    for r in LEARNED:
        print('  [%s] %s' % (r['date'], r['rule']))
        print('        замер: %s -> %s' % (r['measured'], r['result']))

    print('\nПРОВЕРЕНО И ОТВЕРГНУТО (не переоткрывать):')
    for r in REJECTED:
        print('  [%s] %s' % (r['date'], r['rule']))
        print('        замер: %s -> %s' % (r['measured'], r['result']))
        print('        почему: %s' % r['why'])

    print('\nКАК ПОЛЬЗОВАТЬСЯ. Класс из «врёт» с 3+ записями и без строки в '
          '«отвергнуто» — кандидат\nна новое правило. Правило пишется с замером '
          'ПО ВСЕЙ базе (полнота и точность до и после),\nи результат — принят '
          'или отвергнут — дописывается сюда, а не остаётся в голове прогона.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
