#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Стороны сделки ссылаются на профили компаний, а не остаются текстом.

ЗАЧЕМ. 11 сентября 2026 владелец открыл свежую карточку и спросил: «почему
не кликабелен ни предмет, ни покупатель?» Замер в тот же час: из 145
карточек, заведённых притоком, 107 не имеют НИ привязанного предмета, НИ
привязанного покупателя — то есть три четверти свежих карточек ведут в
никуда. Причина не в конкретной карточке: приток пишет стороны текстом
(`asset`, `buyer_name`, `seller`) и никогда не проверяет, нет ли у этой
компании профиля в базе. Профили при этом заводятся другими путями
(дочитывание, кампании описаний) — и карточка, написанная РАНЬШЕ профиля,
о нём не узнаёт сама никогда.

ЧТО ДЕЛАЕТ. Для каждой роли, у которой стоит текст и НЕ стоит ссылка,
ищет профиль в базе и проставляет `target` / `buyer` / `seller_id`.
Идемпотентен: заполненную ссылку не трогает, поэтому его можно звать
каждым прогоном притока и публикации.

ЧЕГО НЕ ДЕЛАЕТ — И ЭТО ГРАНИЦА, А НЕ НЕДОДЕЛКА. Профиль не ЗАВОДИТСЯ.
Замер того же дня: у 117 предметов, 72 покупателей и 67 продавцов профиля
в базе нет вовсе, и завести их механически нельзя — среди «похожих на имя»
строк лежат доли («14% в группе «Полипластик»»), недвижимость («бывший
офис банка «Открытие»»), пары людей («Алексей Деревянко и Герман
Лабазин») и регионы («Башкирия»). Отличить компанию от описания предмета
может только чтение (тот же урок, что «признак дефекта — повод прочитать,
а не основание стереть»), поэтому заведение профилей — отдельная кампания
чтения, а не правило здесь.

ПОЧЕМУ КЛЮЧ — ТОТ ЖЕ, ЧТО У ТЕСТА БЛИЗНЕЦОВ. Точное совпадение имени
находит 17 привязок, транслитерационный ключ `test_no_company_twins` —
19, и качественнее: он видит «Selectel» и «ООО «Селектел»», «ПАО
«МТС-Банк»» и «МТС Банк» как одну компанию. Брать второй ключ безопасно
ровно потому, что он УЖЕ объявлен в репозитории критерием «это одна и та
же компания»: если бы он путал разные компании, тест близнецов давно
покраснел бы. Омонимов (ключ ведёт больше чем в один профиль) в замере не
нашлось ни одного; на такой случай привязка не делается — выбирать
профиль наугад хуже, чем оставить текст.

ПАРЫ, ПРОВЕРЕННЫЕ ГЛАЗАМИ И ПРИЗНАННЫЕ РАЗНЫМИ КОМПАНИЯМИ, лежат в
`NOT_THE_SAME`. Их две, и обе — та самая ловушка «похожее имя, другая
сущность», о которой уже есть уроки: «Продо» в карточке — агрохолдинг, а
профиль «Пермская птицефабрика (Продо)» — его бывшая дочка (родня
УГМК/УГМК-Инвест); «ООО «ТД Эдельвейс»» и «АО «Эдельвейс»» — разные
юрлица. Список убывающий по смыслу: он не поблажка правилу, а запись
прочитанного решения.

Запуск:
    python3 pipeline/ingest/link_parties.py            # показать, что свяжется
    python3 pipeline/ingest/link_parties.py --write    # связать в базе
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

# Роль -> (поле с текстом, поле со ссылкой). Предмет проверяется по обоим
# полям привязки: `asset_id` — второй, равноправный способ указать профиль
# предмета (22 карточки), и карточка с ним привязанной уже кликабельна.
ROLES = (
    ('предмет', 'asset', 'target', ('target', 'asset_id')),
    ('покупатель', 'buyer_name', 'buyer', ('buyer',)),
    ('продавец', 'seller', 'seller_id', ('seller_id',)),
)

# Прочитано глазами: похожее имя, но РАЗНАЯ компания. Пара — (текст в
# карточке, имя профиля).
NOT_THE_SAME = {
    # Агрохолдинг «Продо» против его бывшей дочки (родня УГМК/УГМК-Инвест).
    ('«Продо»', 'Пермская птицефабрика (Продо)'),
    # Торговый дом и акционерное общество — разные юрлица одной группы.
    ('ООО «ТД Эдельвейс»', 'АО «Эдельвейс»'),
    # Шведский продавец против ПРЕДМЕТА сделки: профиль «ООО «Аутолив»» —
    # это завод в Тольятти, который у Autoliv и купили. Связать значило бы
    # сделать продавца предметом собственной сделки.
    ('Autoliv', 'ООО «Аутолив»'),
    # Полные омонимы: предмет — ООО «Глобус», присоединённое к авиакомпании
    # «Сибирь»; профиль «ЗАО «Глобус»» — новосибирский владелец отеля и ТРК.
    ('ООО «Глобус»', 'ЗАО «Глобус»'),
}

_CYR = {"а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e", "ж": "zh",
        "з": "z", "и": "i", "й": "i", "к": "k", "л": "l", "м": "m", "н": "n", "о": "o",
        "п": "p", "р": "r", "с": "s", "т": "t", "у": "u", "ф": "f", "х": "h", "ц": "ts",
        "ч": "ch", "ш": "sh", "щ": "sch", "ъ": "", "ы": "i", "ь": "", "э": "e",
        "ю": "iu", "я": "ia"}


def company_key(name):
    """Ключ «это одна и та же компания» — дословно тот же, что в
    `test_data.py::test_no_company_twins`. Держать копию, а не импортировать
    из теста, приходится потому, что тесты не являются модулем пайплайна;
    расхождение ловит `test_link_parties_key_matches_the_twins_test`."""
    s = re.sub(r"\b(ооо|оао|зао|пао|ао|нао|гк|пкф|тд)\b\.?", " ", str(name or "").lower())
    s = "".join(_CYR.get(ch, ch) for ch in s)
    s = re.sub(r"[^a-z0-9]+", "", s)
    for a, b in (("ph", "f"), ("sch", "sh"), ("ck", "k"), ("ts", "s"), ("x", "ks"),
                 ("w", "v"), ("q", "k"), ("y", "i"), ("j", "i")):
        s = s.replace(a, b)
    s = s.replace("ch", "\x00").replace("c", "k").replace("\x00", "ch")
    return re.sub(r"(.)\1+", r"\1", s)


def build_index(companies, match_keys=None):
    """ключ -> множество id профилей. Только по ИМЕНАМ профилей.

    ПСЕВДОНИМЫ `match_keys` СЮДА НЕ ИДУТ, и это проверено на живом прогоне,
    а не выведено из общих соображений. Первая версия брала их наравне с
    именами — казалось, что псевдоним для того и заведён, чтобы узнавать
    компанию, названную иначе. Сухой прогон показал, что так связываются
    РАЗНЫЕ сущности: продавец «JetBrains» уехал в профиль «JetBrains
    (офисная недвижимость СПб)», «Caterpillar» — в «Caterpillar
    (российские активы)», «Heineken» — в «Heineken (российский бизнес)»,
    и так семь раз. У всех этих профилей псевдоним — голое имя
    иностранного владельца, потому что заведены они для ПРЕДМЕТА сделки
    (проданный российский бизнес), а не для самой компании. Ровно эта
    ловушка уже описана в `link_named_parties_to_existing_profiles.py`:
    «Продавец — Морган Стэнли» и профиль «Morgan Stanley (ТРЦ
    «Галерея»)» — разные сущности. Псевдоним отвечает на вопрос «где эту
    компанию упоминают», а не «кто она»; для привязки роли годится только
    второй вопрос."""
    index = {}
    for cid, c in (companies or {}).items():
        k = company_key(c.get('name'))
        if len(k) >= 3:
            index.setdefault(k, set()).add(cid)
    return index


def link_card(card, index, companies):
    """Проставляет ссылки на профили. Возвращает список описаний того, что
    связано (пусто — значит связывать было нечего)."""
    done = []
    for role, text_field, id_field, guard_fields in ROLES:
        if any(card.get(f) for f in guard_fields):
            continue
        text = card.get(text_field)
        if not text:
            continue
        found = index.get(company_key(text))
        # Омоним: ключ ведёт в несколько профилей — выбирать наугад нельзя.
        if not found or len(found) != 1:
            continue
        cid = next(iter(found))
        profile_name = (companies.get(cid) or {}).get('name')
        if (text, profile_name) in NOT_THE_SAME:
            continue
        # ОДНА КОМПАНИЯ — ОДНА РОЛЬ В СДЕЛКЕ. Профиль, уже стоящий в другой
        # роли этой же карточки, занимать нельзя: у «Медскан»/«Нетрика
        # Медицина» покупатель и предмет назывались одинаково, и привязка
        # сделала «Медскан» одновременно предметом и продавцом — карточка
        # стала утверждать, что компания купила сама себя. Поймано
        # инвариантом `test_one_company_holds_one_role_in_a_deal`, который
        # для того и заведён.
        if cid in {card.get(f) for f in ('target', 'asset_id', 'buyer', 'seller_id')}:
            continue
        card[id_field] = cid
        # Пара «ссылка + текст» у покупателя не может существовать разом:
        # это ловит test_buyer_is_named_once. У продавца текст остаётся
        # рядом со ссылкой — так уже устроено, интерфейс предпочитает профиль.
        if id_field == 'buyer':
            card.pop('buyer_name', None)
        done.append('%s: %r -> %s (%s)' % (role, text, cid, profile_name))
    return done


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    index = build_index(data["companies"])

    total = 0
    for card in data['deals']:
        done = link_card(card, index, data['companies'])
        for line in done:
            print('  %s | %s' % (card['id'], line))
        total += len(done)

    print('\nСвязано ролей: %d' % total)
    if not write:
        print('(сухой прогон, для записи — --write)')
        return total
    if total:
        with open(DATA, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=1, ensure_ascii=False)
            f.write('\n')
        print('Записано.')
    return total


if __name__ == '__main__':
    main(write='--write' in sys.argv)
