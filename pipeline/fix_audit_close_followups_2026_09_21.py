# -*- coding: utf-8 -*-
"""Две доводки к смешанной партии — обе нашёл полный pytest, а не читатель.

1. САХАЛИН-2 (`g6d74bc39`). Читатель проставил покупателя — «Газпром», и по
   факту он прав: карточка дважды прямо его называет. Но золотая выборка по
   ЭТОЙ карточке говорит другое: «два чтения дали одну цену, но разные даты
   — дата спорная… структуру карточки решает человек». Карточка смешивает
   два события (разрешение НОВАТЭКу 2023 года и покупку «Газпромом» 2024-го),
   и любое уточнение полей делает её кандидатом в мультипликаторы раньше,
   чем человек решит, о каком событии она вообще. Ссылка снята обратно,
   находка уходит владельцу вместе с остальными.

   Это ровно то, ради чего золотая выборка и заведена: ожидание записано
   НЕЗАВИСИМО от кода, и когда правка ему противоречит — падает тест, а не
   выходит на сайт молча.

2. ЛОТ «молочный комплекс в Воронеже» (`g2e94515b`). Читатель верно
   пометил профиль лотом (продавались два юрлица разом), но лот обязан
   назвать свой состав там, где его видит читатель
   (`test_lot_profile_composition_is_named_somewhere_the_reader_sees`) —
   иначе на странице стоит «комплекс», а из чего он состоит, не сказано
   нигде. Состав дословно есть в самой карточке (`eco.share`): дописан в
   описание. Заодно `lot` записан булевым значением: у 48 профилей базы
   True, и только у этого была строка «true» — тот же класс, что
   «соглашение базы соблюдается, а не переизобретается».

    python3 pipeline/fix_audit_close_followups_2026_09_21.py
    python3 pipeline/fix_audit_close_followups_2026_09_21.py --write
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "static" / "data" / "deals_promoted.json"

LOT_DESC = ("Лот из двух юрлиц — «Бутурлиновский агрокомплекс» и «Пузевское»; "
            "в 2025 году их продал концерн «Детскосельский» компании «Плодородие», "
            "независимая оценка двух предприятий составила 500–600 млн ₽.")

# Вторая волна доводок — их поймал тот же полный pytest на следующей партии.
CAT_DESC = ("Российские активы Caterpillar, проданные одним лотом: ООО «Катерпиллар "
            "Евразия», ООО «Солар Турбинс СиАйЭс», ООО «Катерпиллар Дистрибьюшн "
            "Интернейшнл» и ООО «Электро-Мотив Локомотив Текнолоджис».")


def main(write: bool) -> int:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    cards = {d["id"]: d for d in data["deals"]}
    log = []

    card = cards.get("g6d74bc39")
    if card is not None and card.get("buyer"):
        log.append("g6d74bc39: покупатель снят обратно — золотая выборка "
                   "оставляет структуру этой карточки человеку")
        if write:
            card.pop("buyer", None)

    prof = data["companies"].get("g2e94515b")
    if prof is not None:
        if prof.get("lot") is not True:
            log.append("g2e94515b: lot записан булевым значением, как у остальных 48")
            if write:
                prof["lot"] = True
        if "Бутурлиновский" not in str(prof.get("desc") or ""):
            log.append("g2e94515b: в описание лота дописан его состав из eco.share карточки")
            if write:
                prof["desc"] = LOT_DESC

    # ВТОРАЯ ВОЛНА. Читатели следующей партии пометили лотами ещё четыре
    # профиля — признак верный, но у лота есть обязанности, о которых
    # находка не знала.
    comp = data["companies"]

    # Caterpillar: состав лота назван в карточке (eco.share), а в описании
    # профиля его не было — читатель на странице компании видел «российские
    # активы» и ни одного юрлица.
    cat = comp.get("gc129d375")
    if cat is not None and "Катерпиллар Евразия" not in str(cat.get("desc") or ""):
        log.append("gc129d375: в описание лота Caterpillar дописаны все четыре юрлица")
        if write:
            cat["desc"] = CAT_DESC

    # «Кама-Трейд Татарстан»: пометка лотом противоречит тому, что профиль
    # сопоставлен с ОДНИМ юрлицом по ИНН (`test_...lot_check`). Признак снят,
    # находка уходит владельцу: чтобы сделать из этого лот, нужно и имя, и
    # состав, и снятие сопоставления — это правка профиля, а не пометка.
    kama = comp.get("g7e235832")
    if kama is not None and kama.get("lot"):
        log.append("g7e235832: пометка лотом снята — профиль сопоставлен с одним юрлицом по ИНН")
        if write:
            kama.pop("lot", None)

    # Профиль переименован из описания в настоящее имя («Структура Дмитрия
    # Зеленина» → «ООО «Дебаркадер»»), а псевдоним остался от старого имени и
    # перестал пересекаться с новым: по такому псевдониму поиск не сработает
    # никогда. Тот же случай, что с CanPack накануне.
    mk = data.get("match_keys") or {}
    if mk.get("g86d9684f") == ["структура дмитрия зеленина"]:
        log.append("g86d9684f: псевдоним от старого имени-описания заменён на новое имя")
        if write:
            mk["g86d9684f"] = ["ооо дебаркадер"]

    # Покупателя Сахалина-2 второй читатель проставил снова — та же правка,
    # тот же отказ по той же причине (см. выше).
    sah = cards.get("g6d74bc39")
    if sah is not None and sah.get("buyer"):
        log.append("g6d74bc39: покупатель снят повторно — структуру этой карточки решает человек")
        if write:
            sah.pop("buyer", None)

    for line in log:
        print("   " + line)
    if not log:
        print("Все доводки уже внесены.")
        return 0
    if not write:
        print("\n(сухой прогон; чтобы записать — --write)")
        return 0
    DATA.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    print("\nзаписано")
    return 0


if __name__ == "__main__":
    sys.exit(main("--write" in sys.argv))
