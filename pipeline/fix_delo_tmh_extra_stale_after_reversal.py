# -*- coding: utf-8 -*-
"""После смены статуса g24e6d8ee на «Не состоялась»
(pipeline/fix_delo_tmh_rosatom_jv_reversed.py) поле `extra` осталось
нетронутым и продолжало говорить о плане в настоящем/будущем времени
(«На текущем этапе ТМХ выкупит 1%... По завершении планируется
объединение... с последующим привлечением новых инвесторов») — тот самый
класс дефекта из REVISION_BRIEF.md («после правки — перечитайте карточку
целиком, не только своё поле»).

Запуск: python3 pipeline/fix_delo_tmh_extra_stale_after_reversal.py
        python3 pipeline/fix_delo_tmh_extra_stale_after_reversal.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g24e6d8ee'

OLD_EXTRA = (
    'Договорённость между «Росатомом» (49% в УК «Дело»), ТМХ (выкупает 1% '
    'у Шишкарева) и бизнесменом Сергеем Шишкарев (основатель и '
    'крупнейший бенефициар «Дела») о консолидации логистических активов. '
    'На текущем этапе ТМХ выкупит 1% управляющей компании «Дело». По '
    'завершении планируется объединение всех логистических активов '
    'сторон до конца 2025 года с последующим привлечением новых '
    'инвесторов. (Новость о консолидации активов трёх сторон)'
)
NEW_EXTRA = (
    'Договорённость между «Росатомом» (49% в УК «Дело»), ТМХ (выкупил 1% '
    'у Шишкарева) и бизнесменом Сергеем Шишкаревым (основатель и '
    'крупнейший бенефициар «Дела») о консолидации логистических активов. '
    'Планы не реализовались: «Росатом» и ТМХ не договорились о цене доли '
    '«Росатома», сделка расторгнута в ноябре 2025 года, а 1% УК «Дело» '
    'по условиям обратного выкупа вернулся Шишкареву 25 февраля 2026 '
    'года. (Новость о несостоявшейся консолидации активов трёх сторон)'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA, 'extra изменился с момента чтения'

    print('=== extra: станет ===')
    print(NEW_EXTRA)

    if write:
        deal['extra'] = NEW_EXTRA
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
