# -*- coding: utf-8 -*-
"""Продолжение обязательной проверки статуса карточки g8af20254 (МФК
«Займер»/ГК Qiwi): статус уже исправлен на «Закрыта» через review.py
(batch_monthly_2026_08_23_r59.py), но поле `extra` всё ещё говорило
«Сделка находится в стадии согласования» — прямое противоречие новому
статусу. Заодно дописаны операционные подробности из статьи о закрытии
(запуск займов водителям, роль банка «Евроальянс» и МКК Seller Capital)
— несколько фактов из ОДНОЙ статьи, но в разные поля, которые уже были
частично заполнены другим текстом, поэтому не через review.py.

Источник — читал напрямую (fetch_article_texts.py, закэширован):
Ведомости (13.02.2026).
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g8af20254'

OLD_EXTRA = (
    'Сделка находится в стадии согласования. МФК «Займер» планирует '
    'приобрести по 50% в ООО «КИВИ ТЕХНОЛОГИИ» (бренд «Таксиагрегатор») '
    'и ООО «ИНТЕЛЛЕКТМАНИ» (бренд IntellectMoney) у ГК Qiwi. Остальные '
    '50% в каждой компании останутся у Qiwi.'
)
NEW_EXTRA = (
    'Сделка закрыта 13 февраля 2026 года: МФК «Займер» купила по 50% в '
    'ООО «КИВИ ТЕХНОЛОГИИ» (бренд «Таксиагрегатор») и ООО '
    '«ИНТЕЛЛЕКТМАНИ» (бренд IntellectMoney) у ГК Qiwi. Остальные 50% в '
    'каждой компании остались у Qiwi.'
)

OLD_CONTEXT = (
    'Киви» и «Займер» — давние партнеры, однако до сих пор '
    'ограничивались совместными проектами, например запуском '
    'электронного кошелька (см. «Ъ» от 17 декабря 2025 года). Это '
    'первая сделка по приобретению активов между компаниями.'
)
ADDITION = (
    'После закрытия «Займер» начал разворачивать сервисы: «МКК начнет '
    'предоставлять займы водителям, подключенным к «Таксиагретагору», '
    'пилотный проект уже запущен», банк группы «Евроальянс» будет '
    '«осуществлять процессинг платежей пользователей IntellectMoney, '
    '«Таксиагрегатора» и обслуживание счетов водителей, подключенных к '
    '«Таксиагрегатору»» (запуск услуг — в середине 2026 года), а МКК '
    'Seller Capital «сможет предложить займы водителям и таксопаркам, '
    'подключенным к «Таксиагрегатору»», а также «займы МСБ-мерчантам из '
    'числа пользователей IntellectMoney».'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['extra'] == OLD_EXTRA, f"extra: неожиданное значение {deal['extra']!r}"
    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"
    assert deal['status'] == 'Закрыта', \
        f"status: ожидали «Закрыта», в базе {deal['status']!r}"

    print(f"{CARD_ID} extra: приведено в соответствие со статусом «Закрыта»")
    print(f"{CARD_ID} eco.context: += операционные планы после закрытия")
    deal['extra'] = NEW_EXTRA
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
