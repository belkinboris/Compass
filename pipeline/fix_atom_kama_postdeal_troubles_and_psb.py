import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g6e3bcb70'

OLD_EXTRA = (
    'Описывается инвестиция дочерней компании Росатома Рэнеры в АО '
    'Кама, разработчика электромобиля Атом. Росатом также выступает '
    'технологическим партнером по разработке и производству тяговой '
    'батареи.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' В июле 2026 года начата выдача первых серийных «Атомов»'
    ' покупателям — компания планирует передать ещё не менее 3 тысяч '
    'машин до конца года. Проект столкнулся с финансовыми трудностями: '
    'с конца июня 2026 года задержки зарплаты затронули весь персонал '
    '(1259 человек), возможно сокращение штата вдвое — по версии '
    'компании, причина в задержке траншей от банка ПСБ, сам банк это '
    'отрицает. В августе 2026 года ПСБ выкупил 16,98% АО «Кама» почти '
    'за 10 млрд руб. с целью вывода компании на IPO, размыв доли всех '
    'прежних акционеров, включая «Рэнеру». Один из основателей, Рубен '
    'Варданян, вышел из капитала материнского «Восхода» в октябре 2025 '
    'года — он находится под арестом в Азербайджане с сентября 2023 '
    'года.'
)

NEW_SRC = [
    ['Fontanka.ru', 'https://www.fontanka.ru/2026/07/17/76540913/'],
    ['Habr (со ссылкой на Ведомости)', 'https://habr.com/ru/news/1057116/'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8877492'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8098539'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
