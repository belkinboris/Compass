"""Приток 18.09.2026, часовой прогон 14:20 МСК — ответ на заметки владельца
№671 и №673 (обе — «Оставляем обсуждается и отметка что больше 2х лет
прошло. Нужно чтобы аналогичные карты так решались, не надо это в
консоль»). Карточка gc64703e2 («Газпромбанк Лизинг инвестирует в
кикшеринг Urent») к моменту заметки уже стояла со статусом «Не
состоялась» — владелец явно попросил ВЕРНУТЬ «Обсуждается», а не
подтверждать срыв: обсуждение без единого прямого опровержения дольше
двух лет — это открытый вопрос без ответа, а не установленный факт срыва.
Заметка №671 (карточка «Салаев продаёт два торговых центра») ссылается
на id, которого в базе больше нет (см. read_notes.py --reply 671) — тот
же принцип к ней применить нельзя, потому что применить негде.

Правило на будущее (записано в PRODUCT_ROADMAP.md тем же прогоном):
карточка «Обсуждается» дольше двух лет без единого подтверждения ИЛИ
опровержения остаётся «Обсуждается» с честной пометкой возраста
обсуждения — это НЕ равнозначно «Не состоялась» и не выносится в
консоль повторным вопросом.
"""
import json
import sys

DATA_PATH = 'static/data/deals_promoted.json'

OLD_CONTEXT = (
    'Рыночная стоимость электросамоката Segway Ninebot, которыми пользуется «Юрент», — от '
    '75 000 до 90 000 ₽, но массовая закупка должна была пройти по нижней границе диапазона. '
    'Самокаты предполагалось поставить за три года: 35 000 штук в 2023 году, ещё по 25 000 в '
    '2024 и 2025 годах. По независимым данным, сделка так и не закрылась: 15 января 2024 года '
    'МТС отдельной сделкой довела долю в ООО «Юрентбайк.ру» с 11,77% до 80,58% при оценке '
    'компании в 7–8 млрд ₽. «Газпромбанк Лизинг» ни в этом, ни в последующих раскрытиях '
    'состава акционеров не упоминается. Обсуждение тянется больше двух лет без единого '
    'подтверждения — есть вероятность, что сделка не состоялась.'
)


def main(write):
    data = json.load(open(DATA_PATH, encoding='utf-8'))
    card = next(d for d in data['deals'] if d['id'] == 'gc64703e2')
    assert card['status'] == 'Не состоялась', repr(card['status'])
    assert card['eco']['context'] == OLD_CONTEXT, repr(card['eco']['context'])
    card['status'] = 'Обсуждается'

    if write:
        json.dump(data, open(DATA_PATH, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
        print('gc64703e2: статус возвращён к «Обсуждается». ЗАПИСАНО.')
    else:
        print('Сухой прогон: вернул бы gc64703e2 к «Обсуждается». Повторите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
