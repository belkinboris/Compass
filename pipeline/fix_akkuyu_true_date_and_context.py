import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g2f22b1dc'

OLD_DATE = '2026-09-01'
NEW_DATE = '2026-08-07'

OLD_EXTRA = ''
NEW_EXTRA = (
    'Заявление Росатома впервые прозвучало 7 августа 2026 года '
    '(Известия) — источник в карточке (URA.RU) republish месяц спустя, '
    'без новых фактов. Переговоры о вхождении в капитал ведутся и с '
    'турецкими компаниями: «Мы с рядом турецких компаний приступили к '
    'предметному обсуждению параметров участия в уставном капитале», — '
    'сказал глава Росатома Алексей Лихачёв (21 апреля 2026). Параллельно '
    'готовится выпуск облигаций «Атомэнергопрома» в китайских юанях и '
    'исламских облигаций (сукук) для финансирования АЭС «Аккую». По '
    'данным Минэнерго Турции (январь 2026), готовность первого '
    'энергоблока станции составляет 95%.'
)

NEW_SRC = [
    ['Известия', 'https://iz.ru/2145245/2026-08-07/rosatom-vedet-peregovory-o-prodazhe-doli-proekta-aes-akkuiu'],
    ['Интерфакс', 'https://www.interfax.ru/business/1085120'],
    ['Атомная энергия 2.0', 'https://www.atomic-energy.ru/news/2026/02/02/163076'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['date'] == OLD_DATE
    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== date: станет ===')
    print(NEW_DATE)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['date'] = NEW_DATE
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
