# спорят друг с другом: первый же прогон review.py после этого скрипта
# упирался в «поле уже другое: ожидали None». У поля один хозяин.
PENDING_FIXES = {}


def apply(path, table, write):
    data = json.load(open(path, encoding='utf-8'))
    key = 'deals' if 'deals' in data else 'cards'
    cards = {c['id']: c for c in data[key]}

    plan, refused = [], []
    for cid, (field, old, new, why) in table.items():
        card = cards.get(cid)
        if not card:
            refused.append((cid, 'карточки нет в файле'))
            continue
        cur = card.get(field)
        if cur != old:
            refused.append((cid, 'поле уже другое: %r' % (str(cur)[:60])))
            continue
        plan.append((cid, card, field, old, new, why))

    for cid, why in refused:
        print('  ОТКАЗ %s: %s' % (cid, why))
    for cid, _card, field, old, new, why in plan:
        print('  %-11s %s' % (cid, field))
        print('        было:  %s' % old)
        print('        стало: %s' % ('— (поле очищено)' if new is None else new))
        print('        %s' % why)

    if refused:
        return None, len(plan), len(refused)
    if not write:
        return None, len(plan), 0

    for _cid, card, field, _old, new, _why in plan:
        if new is None:
            card.pop(field, None)
        else:
            card[field] = new
    json.dump(data, open(path, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    return path, len(plan), 0


def main(write=False):
    total = bad = 0
    for path, table in ((BASE, FIXES), (PENDING, PENDING_FIXES)):
        print('\n%s' % os.path.relpath(path, ROOT))
        _p, n, r = apply(path, table, write)
        total += n
        bad += r
    print('\nправок %d, отказов %d' % (total, bad))
    if bad:
        print('Есть отказы — не пишем НИЧЕГО.')
        return 1
    print('ЗАПИСАНО.' if write else 'Сухой прогон. Запись — с ключом --write.')
    return 0


