def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}
    card = by_id[CARD_ID]

    already_applied = card['eco']['share'] == NEW_SHARE and card['eco']['context'] == NEW_CONTEXT
    if already_applied:
        print('Уже применено (карточка %s в финальном виде). Это запись-документация.' % CARD_ID)
        return 0

    assert card['eco']['share'] == OLD_SHARE
    assert card['eco']['val'] == OLD_VAL
    assert card['eco']['context'] == OLD_CONTEXT
    assert card.get('status') == 'Обсуждается'
    assert not any((e.get('source') or [None, None])[1] == VEDOMOSTI[1] for e in card.get('events') or [])

    print('ПРАВКА %s: eco.share, eco.val, eco.context, +событие closed' % CARD_ID)
    if not write:
        print('\nСухой прогон. Применение — с ключом --write.')
        return 0

    card['eco']['share'] = NEW_SHARE
    card['eco']['val'] = NEW_VAL
    card['eco']['context'] = NEW_CONTEXT
    card.setdefault('events', []).append(dict(NEW_EVENT))

    existing_urls = {s[1] for s in card.get('src', []) if len(s) > 1}
    for src in (VEDOMOSTI, KOMMERSANT):
        if src[1] not in existing_urls:
            card.setdefault('src', []).append(list(src))
            existing_urls.add(src[1])

    fresh = json.load(open(DATA, encoding='utf-8'))
    fresh_by_id = {d['id']: d for d in fresh['deals']}
    fresh_card = fresh_by_id[CARD_ID]
    assert fresh_card['eco']['share'] == OLD_SHARE, 'карточку кто-то уже поправил — перечитайте'
    idx = fresh['deals'].index(fresh_card)
    fresh['deals'][idx] = card
    json.dump(fresh, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('\nПрименено.')
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
