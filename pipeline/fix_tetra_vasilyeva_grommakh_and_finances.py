# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка ge292671d
(Максим Волков и Анна Васильева приобрели 100% ООО «Тетра»). Дельта-поиск
нашёл в ТОМ ЖЕ источнике карточки (Коммерсантъ) факты, не перенесённые
при первом разборе. Проверено лично прямым WebFetch.

1) `law.struct` (новое поле) — правдоподобное объяснение, почему
контрольный пакет (80,5%) достался именно Анне Васильевой, а не более
известному Волкову: «Анна Васильева, согласно СПАРК, также контролирует
75% в ООО «Громмах». На балансе этой компании складской комплекс (19,4
тыс. кв. м) в Сергиевом Посаде, который арендует Сясьский ЦБК» — Сясьский
ЦБК производит именно те бренды («Мягкий знак», Kleo), которые
дистрибутирует «Тетра». Причинно-следственная связь прямо в тексте не
названа — перенесено как факт, а не как готовый вывод.

2) `eco.target_fin` (новое поле) — финансы предмета за 2024 год, ПОСЛЕ
сделки (New-Retail.ru, 09.10.2024): «Выручка ООО «Тетра» в 2024 году
составила 328,4 млн рублей (-3,8% год к году), чистая прибыль
сократилась в 8,6 раз, до 3 млн рублей» — снижение, а не рост.

НЕ включены: мотив продажи Лукиным — сам он «сообщил "Ъ", что владел и
управлял бизнесом самостоятельно» и от комментариев по существу сделки
отказался (уже отражено в law.terms); второй независимой оценки суммы
нет — цифра 150–200 млн ₽ в обоих найденных упоминаниях восходит к
одному и тому же эксперту (Бурмистров); консультанты сделки и новости
2025-2026 годов — не нашлось ничего свежее октября 2024 года ни в одном
источнике.

Запуск: python3 pipeline/fix_tetra_vasilyeva_grommakh_and_finances.py
        python3 pipeline/fix_tetra_vasilyeva_grommakh_and_finances.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'ge292671d'

NEW_STRUCT = (
    'Анна Васильева, согласно СПАРК, также контролирует 75% в ООО '
    '«Громмах». На балансе этой компании складской комплекс (19,4 тыс. '
    'кв. м) в Сергиевом Посаде, который арендует Сясьский ЦБК — '
    'производитель брендов «Мягкий знак» и Kleo, которые дистрибутирует '
    '«Тетра».'
)

NEW_TARGET_FIN = (
    'Выручка ООО «Тетра» в 2024 году составила 328,4 млн рублей (-3,8% '
    'год к году), чистая прибыль сократилась в 8,6 раз, до 3 млн рублей '
    '(New-Retail.ru).'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['law']['struct'] == '—'
    assert deal['eco']['target_fin'] == '—'

    print('=== law.struct (новое поле): станет ===')
    print(NEW_STRUCT)
    print('=== eco.target_fin (новое поле): станет ===')
    print(NEW_TARGET_FIN)

    if write:
        deal['law']['struct'] = NEW_STRUCT
        deal['eco']['target_fin'] = NEW_TARGET_FIN
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
