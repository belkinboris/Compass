# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g42e42759
(«Аэрофлот» приобретает долю в АО «Аэромар») — статус «Обсуждается»
держится два года, и за это время обнаружился нетипичный факт: указ
президента пришлось переиздавать. Проверено лично прямым WebFetch трёх
источников.

`eco.context` (заполнено, было «—»). Дословно (Коммерсантъ,
03.12.2025): ««Аэрофлот» (MOEX: AFLT) планирует завершить покупку 49%
акций компании «Аэромар» к концу года» — гендиректор Сергей
Александровский сообщил ТАСС, что сделка близка к завершению, и
ожидал закрытия в 2025 году. Однако срок не был соблюдён: дословно
(Интерфакс, 16.03.2026): «Президент РФ Владимир Путин разрешил
"Аэрофлоту" выкупить долю структуры Lufthansa (Германия) в
"Аэромаре"» — это ВТОРОЕ распоряжение о той же сделке (те же 4900
акций у Truffel 2 GmbH), спустя ровно два года после первого
(№ 74-рп от 16.03.2024, уже в карточке). Ни Интерфакс, ни Ведомости не
объясняют причину повторного распоряжения и не упоминают прежнее —
похоже, что срок действия первого истёк, а сделка за два года не была
закрыта.

НЕ ВКЛЮЧЕНО: статус на «Закрыта» — юридического подтверждения перехода
4900 акций (реестр акционеров АО «Аэромар» непубличен, ЕГРЮЛ-агрегаторы
недоступны — checko.ru 403) найти не удалось. Один найденный источник
через WebSearch-резюме называл дату закрытия «31 марта 2026» и сумму
56,4 млн ₽ — при прямой проверке (AKM.RU) эти цифры оказались о СОВСЕМ
ДРУГОЙ компании («Аэромил», Красноярск — тоже кейтеринг для Lufthansa,
но отдельное юрлицо и отдельная сделка): ИИ-резюме перепутало две
похожие сделки, факт не переносится. Сумма сделки по «Аэромару» и
данные о производственных показателях после сделки — не раскрыты
нигде.

Запуск: python3 pipeline/fix_aeroflot_aeromar_second_decree.py
        python3 pipeline/fix_aeroflot_aeromar_second_decree.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g42e42759'

OLD_CONTEXT = '—'
NEW_CONTEXT = (
    '«Аэрофлот» (MOEX: AFLT) планировал завершить покупку 49% акций '
    '«Аэромара» к концу 2025 года — гендиректор Сергей Александровский '
    'сообщил ТАСС, что сделка близка к завершению (Коммерсантъ, '
    '03.12.2025). Срок не был соблюдён: 16 марта 2026 года президент '
    'РФ издал ВТОРОЕ распоряжение о той же сделке (те же 4900 акций у '
    'Truffel 2 GmbH) — «Президент РФ Владимир Путин разрешил '
    '"Аэрофлоту" выкупить долю структуры Lufthansa (Германия) в '
    '"Аэромаре"» (Интерфакс), спустя ровно два года после первого '
    '(№ 74-рп от 16.03.2024). Ни один из проверенных источников не '
    'подтверждает, что сделка после этого была фактически закрыта.'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8250351'],
    ['Интерфакс', 'https://www.interfax.ru/business/1078186'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, deal['eco']['context']
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
