"""Одно определение «поле пусто» для всего кода (H5 аудита кода, 31 октября 2026).

До этого дня «пусто» было записано восемью разными регэкспами: accept_card,
card_text, promote, write_card, check_post, format_post, proofread,
subscription_feed, assistant_retrieval, deal_export, две копии в test_data.py
и одна на экране (`PLACEHOLDER` в static/index.html). Они расходились:
accept_card считал заполненными «–» (среднее тире), «н/д» и «не раскрыта.»
с точкой; promote — «нет данных» и «не привлекался»; check_post — «н/д».
Одна и та же строка в одном гейте была пустотой, в другом — фактом.

Замер по базе (31 октября 2026): реально встречаются «—» (6747), None (4414),
«публично не сообщалось» (1834), «не раскрыта» (938), '' (43), «не раскрывался»
(8), «не раскрывалось/лась» (2), «не раскрыта.» (единично). «н/д», «n/a»,
«нет данных», «не определена», «неизвестно» в базе не встречаются — их ловит
только регэксп, чтобы они и не появились.

Правило: заглушкой считается только строка, в которой КРОМЕ формулировки
отсутствия ничего нет (анкер с обеих сторон). «не раскрыта (EV оценена в
21 млрд ₽)» — факт, а не пустота (g5e0f6a47, 9 таких мест).

Особенность по полю: у `status` заглушки не бывает — там слова и есть
значения («Закрыта», «Объявлена»), и регэксп к ним не применяется.

Кто зовет: accept_card, promote, check_post, proofread, subscription_feed,
assistant_retrieval, deal_export, test_data. `card_text.has` намеренно свое:
ему нужно ПОКАЗЫВАТЬ «не раскрыта» читателю, а не прятать. write_card и
format_post переводятся следующим заходом (их правит другой агент).
Экран (`PLACEHOLDER` в index.html) держит тот же набор —
`test_data.test_placeholder_canon_matches_the_screen`.

    from pipeline import placeholders
    placeholders.has(card.get('sum'))            # True — есть факт
    placeholders.is_empty(card.get('seller'))    # True — пусто или заглушка
"""
import re

# Строки, которые пусты без всякого регэкспа: прочерки всех трех видов и
# «None»/«null», которые попадают в поля через str(None) и JSON-пересборку.
DASHES = frozenset({'', '—', '-', '–', 'None', 'null'})

# Самый полный из восьми регэкспов (proofread.py) плюс «не определена»,
# «неизвестно» и «n/a», которые ловили только accept_card/check_post/ассистент.
# Классы [а-яё], а не \w — \w на кириллице ведет себя по-разному в JS и Python.
PLACEHOLDER = re.compile(
    r"^(?:[—–-]|н/д|n/?a|нет\s+данных|не\s+определен[а-яё]*|неизвест[а-яё]*"
    r"|(?:публично|официально)\s+(?:об?\s+\S+\s+)?не\s+(?:раскры|сообщал|разглаш)[а-яё]*"
    r"|не\s+(?:раскры|сообщал|привлекал|указан|назван|разглаш)[а-яё]*"
    r"(?:\s+(?:официально|публично))?)[.\s]*$", re.I)

# Поля, где слова — значения, а не рассказ об отсутствии.
NO_PLACEHOLDER_FIELDS = frozenset({'status'})

# Примеры заглушек — каждый обязан ловиться каноном и экраном (держит test_data).
EXAMPLES = (
    '', '—', '-', '–', 'None', 'null', 'н/д', 'n/a', 'N/A', 'нет данных',
    'не раскрыта', 'не раскрыта.', 'Не раскрывался', 'не раскрывалось', 'не раскрывалась',
    'не раскрыто', 'не раскрывается', 'публично не сообщалось', 'Публично не сообщалась',
    'публично о согласованиях не сообщалось', 'официально не раскрывалась',
    'не привлекался', 'не привлекались', 'не указан', 'не назван', 'не разглашается',
    'не сообщалось официально', 'не определена', 'неизвестно', 'неизвестен',
)
# Строки, которые заглушками НЕ являются, хотя похожи, — факт рядом с оговоркой.
NOT_EXAMPLES = (
    'не раскрыта (EV оценена в 21 млрд ₽)', '1,2 млрд ₽', 'ФАС', 'Закрыта',
    'публично не сообщалось, но по данным СПАРК — 300 млн ₽', '0', 'нет данных о покупателе, кроме имени',
)


def _text(value):
    return re.sub(r'\s+', ' ', str(value)).strip()


def is_empty(value, field=None):
    """Поле пусто: None, пустая строка, прочерк, «None» или формулировка
    отсутствия без единого факта рядом. Не-строки (списки, числа, флаги)
    пусты по обычной истинности Python: [] и 0 — пусто, [x] и 1 — нет."""
    if value is None:
        return True
    if not isinstance(value, str):
        return not value
    text = _text(value)
    if text in DASHES:
        return True
    if field in NO_PLACEHOLDER_FIELDS:
        return False
    return bool(PLACEHOLDER.match(text))


def has(value, field=None):
    """Поле несет факт — противоположность `is_empty`."""
    return not is_empty(value, field)


def _self_check():
    for s in EXAMPLES:
        assert is_empty(s), 'заглушка не поймана: %r' % s
    for s in NOT_EXAMPLES:
        assert has(s), 'факт принят за заглушку: %r' % s
    assert is_empty(None) and is_empty([]) and has(['x']) and has(1) and is_empty(0)
    assert has('не определена', field='status') and is_empty('—', field='status')


_self_check()
