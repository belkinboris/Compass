# -*- coding: utf-8 -*-
"""`ga4082daa` («Мечел» продал зарубежные активы) — владелец 11 сентября
2026, читая ту же карточку, что ЗАВТРА сама переслала ему консоль как
открытый вопрос: «столько комментариев». Четыре отдельных находки.

**(1) `law.struct` нёс факт не о структуре сделки.** «По данным сервиса
Moneyhouse, в августе швейцарские Mechel Carbon AG и Mechel International
Holdings GmbH сменили названия на Teiwaz A Group AG и A Group Switzerland
Holdings GmbH.» — дословно верно (запись `FIXES`, партия 5 агентов
14.08.2026), но это позднейшее корпоративное переименование, а не то, как
устроена ЭТА сделка; тот же класс, что уже чинился сегодня для БКС/
«Форштадт» и «Аквариуса»/S8 Capital. Снято с `law.struct`; факт остаётся в
`eco.context`, рядом с уже стоявшей там фразой «Покупатель по-прежнему
нигде не назван» — туда же добавлена вторая, конфликтующая версия из
LRT.lt (Mechel International Holdings GmbH «передана» другой швейцарской
компании, «Fehu Services GmbH» — именно её просил назвать владелец: «то
что в литовском издании»), без выбора победителя: обе цитаты проверены
прямым чтением (WebFetch) сегодня, ни один источник не называет
настоящего бенефициара ни одной из структур. Открытый вопрос в CLAUDE.md
(«решение за человеком») этим не закрыт — только перестал маскироваться
под структуру сделки.

**(2) Покупателя не переносим — его в источниках нет.** Владелец
предположил: «наверное литовский завод продали литовской компании, а
другие активы другим покупателям» — прямое чтение трёх источников
сегодня (Коммерсантъ, Интерфакс, LRT.lt) этого не подтвердило. Коммерсантъ
и Интерфакс дословно говорят только «третьей стороне», имени нет; LRT.lt
говорит, что «Мечел» заявил о продаже каунасской компании, но деталей не
приводит, а про смену собственника завода — что она не устранила
зависимость от Игоря Зюзина (тот же факт уже стоит в `eco.context`).
Присочинять литовского или европейского покупателя значило бы нарушить
собственное правило репозитория «переносить факт в правильное поле можно,
сочинять — нет»; `buyer`/`buyer_name` остаются пустыми.

**(3) Предмет — не одна компания, и не должен быть кликабельным
профилем.** `target` указывал на профиль `ga921f4f8», а `fns_registry.py`
уже честно записал по нему `no_match` с причиной «описание группы
зарубежных активов (Швейцария, Литва), не название одного российского
юридического лица» (28.08.2026) — то есть механизм сам обнаружил
несоответствие ещё три недели назад, просто карточка его не услышала.
Владелец прав: разнородный список активов без данных по каждому не
компания. `target` снят, взамен — текстовый `asset` (тот же путь, что уже
у 206 карточек базы без привязанного профиля), с заглавной буквы, как и
просил владелец. Профиль `ga921f4f8` удалён — ссылок на него нигде
больше нет (проверено: ни в других сделках, ни в `merged`, ни в таблицах
`FIXES`). Запись `no_match` по этому же `company_id` в
`pipeline/fns_registry.py` снята ОТДЕЛЬНОЙ правкой того же файла (не
этим скриптом — та же граница, что уже применялась при слиянии
профилей-близнецов, см. `merge_company_twins_fns_campaign_batch3.py`):
`test_fns_registry_company_ids_exist_in_base` требует, чтобы каждый
`company_id` реестра существовал в базе.

**(4) «Мечел» — то с кавычками, то без, в четырёх разных местах одной
карточки.** Замер по всем полям `ga4082daa`: `title` и `seller` — без
кавычек, `extra` — дважды без кавычек, `eco.context` — трижды с
кавычками и один раз без («сделка принесла Мечелу убыток»). Замер по
остальной базе (например, `g9c247746`, «Продажа «Мечелом» 51% Эльги»)
показывает: домашний стиль — «Мечел» с кавычками-ёлочками, без ПАО.
Приведено к этому стилю во всех полях карточки; профиль-продавец
(`g4576b0c2`, name=«Мечел») уже был в кавычках и не менялся.

Запуск:
    python3 pipeline/fix_mechel_field_placement_and_naming.py
    python3 pipeline/fix_mechel_field_placement_and_naming.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(ROOT)
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'ga4082daa'
ASSET_ID = 'ga921f4f8'

OLD_STRUCT = (
    'По данным сервиса Moneyhouse, в августе швейцарские Mechel Carbon AG и '
    'Mechel International Holdings GmbH сменили названия на Teiwaz A Group '
    'AG и A Group Switzerland Holdings GmbH.'
)

OLD_CONTEXT = (
    'Ожидание прибыли в 5–7 млрд ₽ не подтвердилось: по факту сделка '
    'принесла Мечелу убыток. Убыток от потери контроля и выбытия '
    'зарубежных активов из группы «Мечел» оценивает в 14 млрд ₽: 12,3 '
    'млрд ₽ от основной сделки плюс дополнительные 1,7 млрд ₽ от '
    'вынужденной продажи угольного трейдера в Азии. Судьба завода в '
    'Литве: несмотря на смену собственника, литовская Служба '
    'расследования финансовых преступлений установила, что изменения в '
    'управлении в 2024–2025 годах не устранили зависимость «Мечел '
    'Нямунас» от находящегося под санкциями Игоря Зюзина; 29 июля 2025 '
    'года компания обанкротилась с накопленными убытками 11,8 млн евро '
    '(по данным LRT.lt). Покупатель по-прежнему нигде не назван. '
    'Показатели самого «Мечела» в последующие годы: чистый убыток по '
    'МСФО составил 37,1 млрд ₽ за 2024 год (против прибыли 22,3 млрд ₽ '
    'в 2023 году) и 78,6 млрд ₽ за 2025 год — эти убытки группы в целом '
    'объясняются совокупностью факторов, не только этой сделкой.'
)
NEW_CONTEXT = OLD_CONTEXT.replace(
    'принесла Мечелу убыток', 'принесла «Мечелу» убыток',
) + (
    ' Источники расходятся даже в судьбе самих швейцарских холдингов, '
    'через которые был устроен владевший активами контур: по данным '
    'сервиса Moneyhouse, «Mechel Carbon AG» и «Mechel International '
    'Holdings GmbH» в августе сменили названия на «Teiwaz A Group AG» и '
    '«A Group Switzerland Holdings GmbH»; литовское издание LRT.lt, со '
    'ссылкой на реестровые данные, пишет, что «Mechel International '
    'Holdings GmbH» была передана другой швейцарской компании — «Fehu '
    'Services GmbH». Какая версия верна и кто настоящий бенефициар, ни '
    'один источник не подтверждает.'
)

OLD_TITLE = (
    'Мечел продал зарубежные активы: швейцарские структуры, завод в '
    'Литве и торговые компании'
)
NEW_TITLE = (
    '«Мечел» продал зарубежные активы: швейцарские структуры, завод в '
    'Литве и торговые компании'
)

OLD_SELLER = 'Мечел'
NEW_SELLER = '«Мечел»'

OLD_EXTRA = (
    'Группа Мечел продала швейцарские структуры и металлургический завод '
    'Мечел Нямунас в Литве, утратила контроль над металлотрейдером в '
    'Европе и реализовала углеводородного трейдера в Азии в связи с '
    'санкциями США и опасениями вторичных санкций.'
)
NEW_EXTRA = (
    'Группа «Мечел» продала швейцарские структуры и металлургический '
    'завод «Мечел Нямунас» в Литве, утратила контроль над металлотрейдером '
    'в Европе и реализовала углеводородного трейдера в Азии в связи с '
    'санкциями США и опасениями вторичных санкций.'
)

OLD_ASSET_PROFILE_NAME = (
    'швейцарские структуры, завод «Мечел Нямунас» в Литве и торговые '
    'компании Мечела'
)
NEW_ASSET_TEXT = (
    'Швейцарские структуры, завод «Мечел Нямунас» в Литве и торговые '
    'компании «Мечела»'
)


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    deal = next((d for d in data['deals'] if d['id'] == DEAL_ID), None)
    assert deal is not None, '%r не найдена' % DEAL_ID

    assert deal['law'].get('struct') == OLD_STRUCT, (
        'law.struct изменился, ожидали %r, сейчас %r'
        % (OLD_STRUCT, deal['law'].get('struct')))
    assert deal['eco'].get('context') == OLD_CONTEXT, (
        'eco.context изменился, ожидали %r, сейчас %r'
        % (OLD_CONTEXT, deal['eco'].get('context')))
    assert deal.get('title') == OLD_TITLE, (
        'title изменился, ожидали %r, сейчас %r' % (OLD_TITLE, deal.get('title')))
    assert deal.get('seller') == OLD_SELLER, (
        'seller изменился, ожидали %r, сейчас %r' % (OLD_SELLER, deal.get('seller')))
    assert deal.get('extra') == OLD_EXTRA, (
        'extra изменился, ожидали %r, сейчас %r' % (OLD_EXTRA, deal.get('extra')))
    assert deal.get('target') == ASSET_ID, (
        'target изменился, ожидали %r, сейчас %r' % (ASSET_ID, deal.get('target')))
    assert 'asset' not in deal, 'у сделки уже есть текстовый asset: %r' % deal.get('asset')

    asset_profile = data['companies'].get(ASSET_ID)
    assert asset_profile is not None, '%r не найден в companies' % ASSET_ID
    assert asset_profile.get('name') == OLD_ASSET_PROFILE_NAME, (
        'имя профиля изменилось, ожидали %r, сейчас %r'
        % (OLD_ASSET_PROFILE_NAME, asset_profile.get('name')))

    referenced_elsewhere = any(
        d is not deal and ASSET_ID in (d.get('target'), d.get('asset_id'),
                                        d.get('buyer'), d.get('seller_id'))
        for d in data['deals']
    )
    assert not referenced_elsewhere, (
        '%r используется ещё где-то — удалять профиль нельзя' % ASSET_ID)
    assert ASSET_ID not in data.get('merged', {}), '%r в merged' % ASSET_ID
    assert ASSET_ID not in data.get('merged', {}).values(), '%r в merged' % ASSET_ID

    print('ПРАВИМ %r:' % DEAL_ID)
    print('  law.struct -> «—» (переименование швейцарских холдингов — не '
          'структура сделки; перенесено в eco.context)')
    print('  eco.context -> дополнен переименованием и версией LRT.lt (Fehu '
          'Services GmbH), обе версии без выбора победителя')
    print('  title/seller/extra -> «Мечел» с кавычками, единый стиль')
    print('  target -> снят; asset -> текст с заглавной буквы, без ссылки '
          'на профиль')
    print('  companies[%r] -> удалён (не компания, а список активов; '
          'fns_registry.py уже отметил его no_match)' % ASSET_ID)

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    deal['law']['struct'] = '—'
    deal['eco']['context'] = NEW_CONTEXT
    deal['title'] = NEW_TITLE
    deal['seller'] = NEW_SELLER
    deal['extra'] = NEW_EXTRA
    del deal['target']
    deal['asset'] = NEW_ASSET_TEXT

    del data['companies'][ASSET_ID]
    data.get('match_keys', {}).pop(ASSET_ID, None)

    json.dump(data, open(DATA, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
