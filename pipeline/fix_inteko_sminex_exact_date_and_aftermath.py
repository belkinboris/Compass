import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g16a70078'

OLD_DATE = '2022'
NEW_DATE = '2022-12-14'

OLD_ECO_CONTEXT = (
    'Sminex пыталась купить активы «Интеко» ещё в 2021 году. Аукцион со '
    'стартовой ценой 37,4 млрд ₽ должен был пройти 16 ноября 2021 года, '
    'но торги отменили из-за судебных споров: суд Никосии на Кипре по иску '
    'Morden Finance Ltd, владевшей тогда 5% акций застройщика, запретил '
    '«Трасту» проводить аукцион.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' Спор с Morden Finance Ltd продолжился и после '
    'закрытия сделки: в 2023 году «Траст» подал в суд Кипра иск на '
    '2,85 млрд ₽ к '
    'бывшим топ-менеджерам «Интеко» (Олегу Солощанскому, Константину '
    'Эделю, Светлане Стрелиной), а Высокий суд Лондона арестовал их '
    'активы. Ростовские активы «Интеко» Sminex продал холдингу TEN в июне '
    '2023 года; непрофильную промзону бывшего завода «Крион» на юге '
    'Москвы — в апреле 2024 года.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['date'] == OLD_DATE
    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    print('=== date: станет ===')
    print(NEW_DATE)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)

    if write:
        deal['date'] = NEW_DATE
        deal['eco']['context'] = NEW_ECO_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
