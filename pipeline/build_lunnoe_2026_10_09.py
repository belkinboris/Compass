# -*- coding: utf-8 -*-
"""Приток 18:20 МСК 9 октября 2026: Роснедра повторно выставили на аукцион
оловорудное месторождение «Лунное» (Чукотка) — летом 2025 года аукцион уже
проходил со стартовым платежом 212,855 млн ₽, сейчас цена выросла примерно
на 33% до 282,978 млн ₽ (ПРАЙМ, со ссылкой на ГИС «Торги» и приказ
Дальнедра). Ворота не распознали сделку (нет явного «X продаёт Y» в
заголовке, только разбор аукционного объявления) — тот же класс, что и
Тенкергин (g73a51452) на прошлом прогоне. Роснедра — госорган, профиль не
заводим (прецедент g51fa80ce, «Голдрупп»); eco.share пустое по тому же
прецеденту — предмет уже назван в asset, детали лицензии/запасов — в
context.

Запуск: python3 pipeline/build_lunnoe_2026_10_09.py [--write]
"""
import json
import sys

sys.path.insert(0, 'pipeline/ingest')
import promote  # noqa: E402

PENDING = 'static/data/pending.json'
URL = 'https://1prime.ru/20261009/rosnedra-874121041.html'

DRAFT = {
    'draft_id': 'd-lunnoe-2026-10-09',
    'title': 'Роснедра снова выставляют на торги оловорудное «Лунное» в Чукотке — цена выросла на треть',
    'date': '2026-10-09',
    'src': [['ПРАЙМ', URL]],
    'sum': '282,978 млн ₽',
    'type': 'Продажа с торгов',
    'status': 'Обсуждается',
    'events': [],
    'buyer_name': None,
    'asset': 'право геологического изучения и добычи на оловорудном месторождении Лунное',
    'seller': 'Роснедра',
    'parsed_parties': {'buyer': None,
                        'asset': 'право геологического изучения и добычи на оловорудном месторождении Лунное',
                        'seller': 'Роснедра'},
    'ind': 'ГМК и добыча',
    'needs_review': True,
}


def main(write):
    pending = json.load(open(PENDING, encoding='utf-8'))
    existing = {c['id'] for c in pending['cards']}
    deal_id = promote.new_id(existing)
    card = promote.to_card(DRAFT, deal_id)
    card['eco']['sum'] = '282,978 млн ₽'
    card['eco']['share'] = '—'
    card['eco']['context'] = (
        'Месторождение «Лунное» (Чукотский автономный округ), участок 16,81 кв. км, '
        'лицензия на 25 лет. Заявки принимают до 5 ноября, сами торги назначены на '
        '23 ноября. Летом 2025 года аукцион по тому же участку уже проходил со '
        'стартовым платежом 212,855 млн ₽ — нынешняя цена выросла примерно на 33%. '
        'На государственном балансе на 1 января 2026 года — запасы рудного олова по '
        'категории C2 (30,26 тыс. т) и россыпного олова по категории C1 (4 т); '
        'прогнозные ресурсы рудного олова по категории P1 — 27,96 тыс. т, олова по '
        'категории P2 — 19,56 тыс. т (данные приказа Дальнедра).'
    )
    card['themes'] = ['Продажа с торгов']
    card['pending_since'] = '2026-10-09T18:20:00+00:00'
    if not write:
        print('Сухой прогон. Карточка была бы: %s' % deal_id)
        print(json.dumps(card, ensure_ascii=False, indent=2))
        return
    pending['cards'].append(card)
    with open(PENDING, 'w', encoding='utf-8') as f:
        json.dump(pending, f, ensure_ascii=False, indent=1)
        f.write('\n')
    print('Записано: %s добавлена в pending.json' % deal_id)


if __name__ == '__main__':
    main('--write' in sys.argv)
