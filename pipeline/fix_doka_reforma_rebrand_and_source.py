import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g981fc9c5'

OLD_CONTEXT = (
    'Производственная площадка в Липецке рассчитанная на производство до '
    '70 тыс. кв. м. опалубки в год была запущена в 2019 году и является '
    'единственным современным опалубочным заводом, построенным мировым '
    'лидером в России. Капиталовложения в проект составили около 10 млн '
    'евро. Завод в Липецке стал первым производственным подразделением '
    'австрийского концерна за пределами Евросоюза.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' «18.06.2024: The full name was changed from DOKA RUS LLC to REFORM '
    'LLC» (leave-russia.org). «ООО «Реформа» запустило на грязинской '
    'площадке особой экономической зоны «Липецк» производство '
    'металлической опалубки»; «На предприятии сохранены технологии и '
    'оборудование австрийской компании»; «Все процессы на заводе '
    'полностью локализованы, составляющие для продукции исключительно '
    'российские»; «До конца года руководство намерено выйти на три '
    'рабочие смены, в середине 2025 года — на четыре»; «планируется '
    'создание около 200 рабочих мест» (Коммерсантъ).'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6763099'],
    ['leave-russia.org', 'https://leave-russia.org/doka-gmbh'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6905521'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context (новое поле): станет ===')
    print(NEW_CONTEXT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
