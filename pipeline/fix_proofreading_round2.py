def get_field(card, path):
    obj = card
    for part in path.split('.'):
        if not isinstance(obj, dict):
            return None
        obj = obj.get(part)
    return obj


def set_field(card, path, value):
    parts = path.split('.')
    obj = card
    for part in parts[:-1]:
        obj = obj.setdefault(part, {})
    if value is None:
        obj.pop(parts[-1], None)
    else:
        obj[parts[-1]] = value


def main(argv):
    data = json.load(open(DATA, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}
    comps = data['companies']

    for cid, field, old, new in REPLACES:
        value = get_field(by_id[cid], field)
        assert isinstance(value, str) and old in value, \
            '%s.%s: не найден фрагмент %r' % (cid, field, old[:50])

    for cid, field, old, _new in SETS:
        current = get_field(by_id[cid], field)
        assert current == old, \
            '%s.%s: поле уже другое: %r, ожидали %r' % (cid, field, str(current)[:60], str(old)[:60])

    for cid, url_pair in NEW_SRC:
        urls = {s[1] for s in by_id[cid].get('src') or [] if len(s) > 1}
        assert url_pair[1] not in urls, '%s: источник уже добавлен' % cid

    for pid, old, _new in COMPANY_RENAMES:
        assert comps[pid]['name'] == old, \
            '%s: имя профиля уже другое: %r' % (pid, comps[pid]['name'])

    n = len(REPLACES) + len(SETS) + len(APPENDS) + len(NEW_SRC) + len(COMPANY_RENAMES)
    print('Правок: %d (замен %d, присвоений %d, дописок %d, источников %d, '
          'переименований профилей %d)'
          % (n, len(REPLACES), len(SETS), len(APPENDS), len(NEW_SRC), len(COMPANY_RENAMES)))

    if '--write' not in argv:
        print('\nСухой прогон. Запись — с ключом --write.')
        return 0

    for cid, field, old, new in REPLACES:
        set_field(by_id[cid], field, get_field(by_id[cid], field).replace(old, new))
    for cid, field, _old, new in SETS:
        set_field(by_id[cid], field, new)
    for cid, field, text in APPENDS:
        current = get_field(by_id[cid], field)
        if isinstance(current, str) and current.strip() not in ('', '—'):
            set_field(by_id[cid], field, current.rstrip() + ' ' + text)
        else:
            set_field(by_id[cid], field, text)
    for cid, url_pair in NEW_SRC:
        by_id[cid].setdefault('src', []).append(url_pair)
    for pid, _old, new in COMPANY_RENAMES:
        comps[pid]['name'] = new

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('ЗАПИСАНО.')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
