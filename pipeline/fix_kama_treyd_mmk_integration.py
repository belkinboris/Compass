# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка g335d3cdc (Торговый дом
ММК приобрёл «Кама-Трейд Татарстан»): дельта-поиск нашёл, как актив
интегрируется в сбытовую сеть ММК — новое направление переработки и
загруженные мощности. Не через review.py: поле «rationale» уже занято
текстом из другого источника (обоснование сделки от ММК), а это —
результат ПОСЛЕ интеграции, из отдельной статьи три месяца спустя.

Источник — читал напрямую (fetch_article_texts.py, закэширован):
УрБК (13.02.2026), со слов замдиректора по продажам ТД ММК Александра
Сиража на конференции «Региональная металлоторговля России».
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g335d3cdc'
OLD_RATIONALE = (
    'В ММК уточнили “Ъ”, что приобретение позволит увеличить ежегодные '
    'продажи металлопродукции на 35–40 тыс. тонн.'
)
ADDITION = (
    'Три месяца спустя в ММК подтвердили, что интеграция состоялась: '
    '«В результате присоединения к сбытовой сети ММК металлоторговой '
    'компании «Кама-Трейд Татарстан» освоено новое направление – '
    'EPS-очистка горячекатаного проката (экологически безопасная '
    'технология очистки металла от окалины и ржавчины смесью воды и '
    'стальной дроби, не требующая применения химических веществ). В '
    'настоящее время мощности по дробеструйной очистке загружены '
    'полностью», — сообщили в пресс-службе. «В планах ТД ММК – '
    'дальнейшее развитие услуги EPS-очистки, увеличение объемов '
    'металлопереработки за счет малотоннажных партий эксклюзивных '
    'размеров, расширение сортамента листа нестандартных размеров, '
    'масштабирование системы штрихкодирования и адресного хранения на '
    'все подразделения сбытовой сети», — рассказал А. Сираж.'
)
NEW_RATIONALE = OLD_RATIONALE + ' ' + ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['rationale'] == OLD_RATIONALE, \
        f"eco.rationale: неожиданное значение {deal['eco']['rationale']!r}"

    print(f"{CARD_ID} eco.rationale: += интеграция в сбытовую сеть ММК (февраль 2026)")
    deal['eco']['rationale'] = NEW_RATIONALE

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
