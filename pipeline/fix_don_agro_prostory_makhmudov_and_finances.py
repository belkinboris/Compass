import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gaa59d3a1'

NEW_RATIONALE = (
    'Рентабельность агробизнеса упала почти до нуля: «Если в лучшие '
    'годы она достигала десятки процентов, то теперь близка к нулю» '
    '(директор «Совэкон» Андрей Сизов). «Сейчас агробизнес требует '
    'много внимания и поэтому он малоинтересен для Евгения Туголукова» '
    '(инвестбанкир Илья Шумов).'
)

NEW_CONTEXT = (
    'За формальным покупателем «Просторы» стоит Искандар Махмудов: '
    '«Компания с начала 2024 года выступает учредителем ООО '
    '«Косминвест», которое ранее через ООО «Виолан» контролировал '
    'Искандар Махмудов, сооснователь Уральской горно-металлургической '
    'компании» (Коммерсантъ). По итогам 2024 года группа компаний '
    '«Дон Агро» «продемонстрировала совокупный убыток в размере 337 млн '
    'руб.», выручка «незначительно снизилась до 1,93 млрд руб. в 2024 '
    'году с 2 млрд руб. в 2023 году» (AK&M).'
)

NEW_SRC = [
    ['Ведомости-Юг', 'https://south.vedomosti.ru/south/news/2024/08/08/1054712-krupnii-agrarnii-holding-iz-rostovskoi-oblasti-smenil-sobstvennika'],
    ['AK&M', 'https://www.akm.ru/news/vyruchka_predpriyatiy_agrokholdinga_prostory_po_itogam_2024_goda_sostavila_65_57_mlrd_rub/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert not deal['eco'].get('rationale')
    assert deal['eco']['context'] == '—'
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.rationale (новое поле): станет ===')
    print(NEW_RATIONALE)
    print('=== eco.context (новое поле): станет ===')
    print(NEW_CONTEXT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['rationale'] = NEW_RATIONALE
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
