# -*- coding: utf-8 -*-
"""Месячная очередь, карточка g139db8c2 (S8 Capital и ГК «МТ-Интеграция»
приобрели 79% акций «Аквариуса»): дельта-поиск нашёл, что один из ДВУХ
заявленных в заголовке покупателей публично опроверг своё участие.

22 августа 2025 года, на следующий день после публикации Ведомостей (на
которой держится карточка), ГК «МТ-Интеграция» разместила на своём сайте
пресс-релиз: «Информация о входе ГК «МТ-Интеграция» в состав акционеров
группы компаний «Аквариус» не соответствует действительности». При этом
более поздний источник (CTA.ru со ссылкой на CNews, 02.10.2025) ПРОДОЛЖАЕТ
называть обе компании совместными владельцами 79% и явно отмечает, что
ключевые посты в «Аквариусе» заняли представители именно S8 Capital (не
МТ-Интеграции) — то есть опровержение не было ни подтверждено, ни
однозначно опровергнуто в свою очередь. Тот же класс, что уже
задокументированные случаи БКС/«Форштадт» и Газпромбанк/«Медскан»:
статус (здесь — состав покупателей) не меняется механически, вопрос
записан отдельно в CLAUDE.md для решения человеком.

Заодно найдены: расхождение в доле «Сберинвеста» (24% до сделки, по
карточке и mergers.ru, против 21% после — источники разницу не
объясняют), экстренное финансирование от S8 Capital (5 млрд ₽ на
зарплаты и иски, сентябрь 2025) и фон предыдущих владельцев (Алексей
Калинин и Владимир Степанов через АО «А-Холдинг»).

Не через review.py: поле eco.context уже несёт содержание, новые факты
из нескольких источников не образуют с ним непрерывный кусок текста.

Источники — читал напрямую (fetch_article_texts.py, закэшированы):
https://ermolaevv.ru/tpost/0ri3as2y11-prodazha-kompanii-akvarius-zagadochnaya
https://www.cta.ru/news/cta/182329.html
https://mergers.ru/news/Gruppa-kompanij-Maksima-i-S8-Capital-stanut-sovladelcami-Akvariusa-85755

Запуск: python3 pipeline/fix_akvarius_mt_integration_denial_context.py [--write]
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g139db8c2'

OLD_CONTEXT = (
    'Сейчас структура владения и руководство АО «Группа Аквариус» скрыты '
    'в ЕГРЮЛе. В ноябре 2024 г. «Сберинвест», входящий в блок '
    'корпоративно-инвестиционного бизнеса Сбербанка, получил 12% в '
    'капитале «Аквариуса», об этом сообщал РБК. Затем «Сберинвест» '
    'приобрел еще 12%, доведя свой пакет в «Аквариусе» до 24%.'
)
CONTEXT_ADDITION = (
    'До сделки крупные доли «Аквариуса», помимо «Сберинвеста», '
    'принадлежали Алексею Калинину и президенту группы Владимиру '
    'Степанову через АО «А-Холдинг». 22 августа 2025 года, на следующий '
    'день после публикации о сделке, ГК «МТ-Интеграция» опубликовала '
    'пресс-релиз: «Информация о входе ГК «МТ-Интеграция» в состав '
    'акционеров группы компаний «Аквариус» не соответствует '
    'действительности». Более поздний источник (02.10.2025) по-прежнему '
    'называет обе компании совладельцами 79% и отмечает, что ключевые '
    'посты в «Аквариусе» заняли представители именно S8 Capital — '
    'опровержение МТ-Интеграции ничем не подтверждено и не опровергнуто '
    'в свою очередь. После сделки доля «Сберинвеста» указывается как 21% '
    '(источники не объясняют расхождение с 24% до сделки). В сентябре '
    '2025 года S8 Capital выделил «Аквариусу» экстренные 5 млрд ₽ на '
    'зарплаты и урегулирование судебных исков — по оценке экспертов, '
    'этой суммы хватит только до конца 2025 года.'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + CONTEXT_ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} eco.context: += опровержение МТ-Интеграции, фон "
          f"прежних владельцев, расхождение доли Сберинвеста, экстренное "
          f"финансирование — состав покупателей под вопросом, см. "
          f"CLAUDE.md")
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
