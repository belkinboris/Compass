def main(write=False):
    data = json.load(open(BASE, encoding='utf-8'))
    cards = {d['id']: d for d in data['deals']}
    todo = {}

    for cid, old_full, tag in TAG_FIXES:
        card = cards[cid]
        new_full = old_full[:-len(tag)]
        if card['extra'] == new_full:
            print('УЖЕ ПРИМЕНЕНО %s' % cid)
            continue
        assert card['extra'] == old_full, '%s: extra уже другое' % cid
        todo[cid] = new_full
        print('ПРАВИМ  %s extra: снята протёкшая пометка роли' % cid)

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return
    for cid, new_full in todo.items():
        cards[cid]['extra'] = new_full
    if todo:
        json.dump(data, open(BASE, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
