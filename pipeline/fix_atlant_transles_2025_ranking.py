# -*- coding: utf-8 -*-
"""Месячная очередь, 8 сентября 2026 — карточка `c0ea790b6» (оператор
«Атлант»/«Трансфин-М» консолидировал 100% «ТрансЛес» и «Грузовую
компанию» у «Деметра-Холдинг», июнь 2025). Найдено продолжение: по
итогам 2025 года «Атлант» поднялся до 4-го места среди железнодорожных
операторов по выручке и 2-го по числу вагонов в оперировании — личный
WebFetch (expert.ru/transport/vagony-vyezzhayut-v-rynok, 20.03.2026,
статья о продаже «Вектор Рейл», где «Атлант» упомянут контекстом): «По
итогам 2025 г. она вышла на 4-ую строчку по выручке, а по количеству
вагонов в оперировании на второе, уступив только ФГК»; «несколько лет
назад компания занимала 8-10-е место в рейтинге крупнейших
железнодорожных операторов» — то есть заметный рост именно за счёт
консолидации 2024-2025 годов, описанной этой карточкой.

Поле `eco.context` уже прошло вычитку (`proofread_absorbed`) — за основу
слияния взят ТЕКУЩИЙ (уже вычитанный) текст с диска.

Запуск:
    python3 pipeline/fix_atlant_transles_2025_ranking.py            # сухой прогон
    python3 pipeline/fix_atlant_transles_2025_ranking.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'
CARD_ID = 'c0ea790b6'

OLD_CONTEXT = (
    'В конце 2024 года «Атлант» купил у «Деметры» 51% «Транслеса» за '
    '5,75 млрд ₽, а теперь консолидировал 100% компании.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' По итогам 2025 года «Атлант» поднялся до 4-го места среди '
    'железнодорожных операторов по выручке и до 2-го по числу вагонов в '
    'оперировании, уступив только ФГК, — несколько лет назад компания '
    'занимала 8–10-е место в этом рейтинге.'
)


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}
    card = by_id[CARD_ID]

    assert card['eco']['context'] == OLD_CONTEXT, \
        'eco.context уже другой: %r' % (card['eco']['context'],)

    print('eco.context: добавляется факт о месте в рейтинге операторов '
          '2025 года (Эксперт, 20.03.2026)')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    card['eco']['context'] = NEW_CONTEXT

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
