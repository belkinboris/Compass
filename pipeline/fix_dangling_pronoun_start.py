# -*- coding: utf-8 -*-
"""Каталог вычитки, класс B3: анафора без антецедента в начале поля.

Прогон по всей базе (18 августа 2026) дал 39 полей, начинающихся с «Это
общество/Эта компания/Собеседник/Он /Она », — каталог предупреждал, что
БОЛЬШИНСТВО из них легитимны, и это подтвердилось чтением всех 39:

  * «Собеседник «Ъ»/издания…» (13 полей) — анонимный источник, не анафора:
    антецедент не нужен, «собеседник «Ъ»» сам по себе полное указание.
  * «Она позволит…», «Он будет предоставлять…» (несколько полей) —
    местоимение отсылает к самой сделке/фонду, названному в заголовке
    карточки, — тот же класс, что разрешённый каталогом пример «Это уже
    вторая сделка X за год».
  * Остальные — местоимение отсылает к стороне/предмету, но БЕЗ имени ни в
    самом поле, ни где-либо ещё в структурных данных карточки (титул,
    buyer/seller/target); подставить факт означало бы читать первоисточник
    заново, а не распространять уже найденное — вне рамок этого прогона.

РЕАЛЬНЫХ ДЕФЕКТОВ С ИМЕНЕМ, ВЫВОДИМЫМ ИЗ ДАННЫХ ТОЙ ЖЕ КАРТОЧКИ, — 3:

  * g324faec6 (eco.target_fin) — «Он выпускает…» без имени; предмет сделки
    (`target`) — «Венталл Стальные Решения», это и есть подлежащее.
  * g352131ac (law.terms) — «Эта компания владеет единственной лицензией…»;
    держателя лицензии называет `extra` той же карточки: «Норникель
    продаёт непрофильный актив через ГРК «Быстринское»».
  * g0b733c0f (eco.context) — «Она была создана…»; предмет сделки
    (`target`) — «AB InBev Efes», названо и в заголовке.

Запуск:
    python3 pipeline/fix_dangling_pronoun_start.py            # сухой прогон
    python3 pipeline/fix_dangling_pronoun_start.py --write    # запись
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

SETS = [
    ('g324faec6', 'eco.target_fin',
     'Он выпускает, по собственным данным, более 120 000 т металлических '
     'конструкций, свыше 3 млн кв. м сэндвич-панелей в год, годовой объем '
     'горячего цинкования превышает 25 000 т.',
     '«Венталл Стальные Решения» выпускает, по собственным данным, более '
     '120 000 т металлических конструкций, свыше 3 млн кв. м сэндвич-'
     'панелей в год, годовой объем горячего цинкования превышает 25 000 т.'),

    ('g352131ac', 'law.terms',
     'Эта компания владеет единственной лицензией – на разведку и добычу '
     'полезных ископаемых на Быстринско-Ширинском месторождении рудного '
     'золота. Она действует до 31 мая 2029 г.',
     '«ГРК Быстринское» владеет единственной лицензией – на разведку и '
     'добычу полезных ископаемых на Быстринско-Ширинском месторождении '
     'рудного золота. Она действует до 31 мая 2029 г.'),

    ('g0b733c0f', 'eco.context',
     'Она была создана в ходе объединения активов бельгийской AB InBev и '
     'турецкой Anadolu Efes на территории России в 2018 г.',
     '«AB InBev Efes» была создана в ходе объединения активов бельгийской '
     'AB InBev и турецкой Anadolu Efes на территории России в 2018 г.'),
]


def get_field(card, path):
    obj = card
    for part in path.split('.'):
        if not isinstance(obj, dict):
            return None
        obj = obj.get(part)
    return obj


def set_field(card, path, value):
    parts = path.split('.')
    obj = card
    for part in parts[:-1]:
        obj = obj.setdefault(part, {})
    obj[parts[-1]] = value


def main(argv):
    data = json.load(open(DATA, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}

    for cid, field, old, _new in SETS:
        current = get_field(by_id[cid], field)
        assert current == old, \
            '%s.%s: поле уже другое: %r' % (cid, field, str(current)[:60])

    print('Правок: %d' % len(SETS))
    for cid, field, old, new in SETS:
        print('  %s %-16s %r -> %r' % (cid, field, old[:44], new[:44]))

    if '--write' not in argv:
        print('\nСухой прогон. Запись — с ключом --write.')
        return 0

    for cid, field, _old, new in SETS:
        set_field(by_id[cid], field, new)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('ЗАПИСАНО.')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
