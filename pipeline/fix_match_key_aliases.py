def contains(text, key):
    """Тот же предикат, что `containsKey` в интерфейсе: короткие ключи — только
    по границам слова, иначе «инга» нашлась бы внутри «Башинформсвязи»."""
    t, k = str(text or '').lower(), key.lower()
    if len(k) > 4:
        return k in t
    return re.search(r'(?<![a-zа-яё0-9])%s(?![a-zа-яё0-9])' % re.escape(k), t) is not None


# Ролевые и долевые слова — тем же шаблоном мерился класс. Псевдоним, в котором
# такого слова нет, считаем именем.
PHRASE = re.compile(
    r'\b(выкуп\w*|покупк\w*|продаж\w*|приобрет\w*|продавец|покупатель|инвестор|доли|долей'
    r'|долю|акци\w+|пакет\w*|бизнес|актив\w*|до \d+|\d+\s?%|оставш\w+|структур\w+|владелец'
    r'|наследник\w*|основател\w*|бывш\w+|сооснователь)\b', re.I)


def looks_like_name(alias):
    return not PHRASE.search(alias)


def main(write):
    data = json.load(open(PATH, encoding='utf-8'))
    keys, comps, deals = data['match_keys'], data['companies'], data['deals']

    for cid, old, new, expected in TRIM:
        assert cid in keys and old in keys[cid], '%s: псевдонима «%s» больше нет' % (cid, old)
        assert new in old and new != old, '%s: «%s» не вырезано из «%s»' % (cid, new, old)
        assert len(new) >= 5, '%s: слишком короткий ключ «%s»' % (cid, new)
        hits = sum(1 for d in deals if contains(d.get('title'), new))
        assert hits == expected, \
            '%s: «%s» находит %d заголовков, а в таблице записано %d' % (cid, new, hits, expected)
    for cid, alias in DROP:
        assert cid in keys and alias in keys[cid], '%s: псевдонима «%s» больше нет' % (cid, alias)
        # Сравнивать остаток с именем профиля посимвольно нельзя: у «Reg.ru»
        # уцелевшие псевдонимы — «рег.ру» и «рег ру», то есть то же имя другим
        # алфавитом. Проверяем слабее, но по существу: остался ли хоть один
        # псевдоним, который выглядит именем, а не куском фразы.
        left = [a for a in keys[cid] if a != alias and looks_like_name(a)]
        assert left, '%s: после удаления не осталось псевдонима-имени' % cid
    for cid, (alias, _why) in KEEP.items():
        assert alias in keys.get(cid, []), '%s: псевдоним «%s» уже правили' % (cid, alias)

    added = sum(e for _c, _o, _n, e in TRIM)
    print('ОБРЕЗАТЬ (%d): приставка доли отрезана, имя осталось' % len(TRIM))
    for cid, old, new, expected in TRIM:
        print('  %-11s %-52s -> %-38s заголовков: %d'
              % (cid, old[:52], new[:38], expected))
    print('\nУДАЛИТЬ (%d): обрывок без имени, чистый псевдоним у профиля уже есть' % len(DROP))
    for cid, alias in DROP:
        print('  %-11s %-46s («%s»)' % (cid, alias[:46], comps[cid]['name'][:34]))
    print('\nОСТАВИТЬ КАК ЕСТЬ (%d): короткая форма опаснее длинной' % len(KEEP))
    for cid, (alias, why) in KEEP.items():
        print('  %-11s %-46s\n              %s' % (cid, alias[:46], why))
    print('\nИтого правок: %d из 35 дефектных псевдонимов; заголовков, которые начнут '
          'узнаваться: %d' % (len(TRIM) + len(DROP), added))

    if not write:
        print('\nСухой прогон. Запись — с ключом --write.')
        return

    было = sum(len(v) for v in keys.values())
    for cid, old, new, _e in TRIM:
        keys[cid] = [new if a == old else a for a in keys[cid]]
        keys[cid] = list(dict.fromkeys(keys[cid]))
    for cid, alias in DROP:
        keys[cid] = [a for a in keys[cid] if a != alias]
    стало = sum(len(v) for v in keys.values())
    assert стало == было - len(DROP), 'потеряно не столько псевдонимов, сколько удаляли'
    with open(PATH, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('\nЗаписано. Псевдонимов: %d (было %d).' % (стало, было))


if __name__ == '__main__':
    main('--write' in sys.argv)
