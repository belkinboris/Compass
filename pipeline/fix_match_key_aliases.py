# -*- coding: utf-8 -*-
"""Бэклог A23: псевдоним компании — кусок заголовка, а не имя.

ЧТО СЛОМАНО. `match_keys` — это список имён, под которыми компанию узнают в
тексте заголовка: по ним страница компании собирает «упоминания» (сделки, где
компания названа, но структурно не привязана). У части профилей вместо имени
там стоит обрывок фразы из заголовка: «долей русинжгидро», «до 90% акций
уральского турбинного завода», «продавец 80% долей», «выкуп reg». Такой ключ
срабатывает только на дословном повторе всей фразы — то есть практически
никогда, и компания в новой формулировке не узнаётся.

ЗАМЕР СВОИМ ОПРЕДЕЛЕНИЕМ, А НЕ ЗАПИСАННОЙ ЦИФРОЙ. В бэклоге стояло «22
псевдонима» — это была цифра одного узкого шаблона. Пересчёт: псевдоним считаем
дефектным, если он (1) не пересекается с именем своего профиля и (2) содержит
ролевое или долевое слово. Таких **35 из 2322** у 35 профилей. Разница в 13
записей — ровно тот случай, о котором предупреждает CLAUDE.md: перемерьте хвост
своим определением, прежде чем его доделывать.

ТРИ РАЗНЫХ СЛУЧАЯ — ТРИ РАЗНЫЕ ПРАВКИ. Одним правилом их не чинят:
  * ОБРЕЗАТЬ (22). Имя есть, но с приставкой доли: «долей лойд-фиш» ->
    «лойд-фиш». Новое значение обязано быть ПОДСТРОКОЙ старого — вырезать
    можно, сочинять нельзя, и это assert. После обрезки 12 профилей начинают
    находить в заголовках 13 упоминаний, которых раньше не видели («АО «Е1
    Групп» купила 100% ООО «Энгельс Электроинструменты»» — таких два).
  * УДАЛИТЬ (11). Обрывок не содержит имени вовсе («продавец 80% долей»,
    «финский концерн, продавец»), а псевдоним-имя у профиля уже есть.
    Удаление ничего не теряет — это тоже assert.
  * ОСТАВИТЬ КАК ЕСТЬ (2), потому что короткая форма опаснее длинной:
    - «оставшиеся 49 9% акций информ»: обрезка до «информ» ловит
      «Башинформсвязь», «ОМЗ — Информационные Технологии» и «Медицинские
      информационные решения» — три чужие сделки вместо одной своей;
    - «долей агроинвест»: «агроинвест» ловит «Бумеранг агроинвест» — другую
      компанию.
  Полные формы с хвостом в скобках («осина екатерина борисовна (продавец 80%
  долей)») дефектными не считаются и не трогаются: они начинаются с имени,
  никому не мешают и остаются следом исходной записи.

ПОЧЕМУ НЕЛЬЗЯ ПРОСТО ВЫРЕЗАТЬ ПРИСТАВКУ ПРАВИЛОМ. Обрезка меняет то, что
показывается пользователю: каждое новое совпадение — это строка «упоминания» на
странице компании. Поэтому у каждой обрезки в таблице записано ОЖИДАЕМОЕ число
заголовков, которые она находит; если данные изменятся и число разъедется,
скрипт упадёт, а не молча добавит компании чужие сделки.

Запуск:
    python3 pipeline/fix_match_key_aliases.py            # сухой прогон
    python3 pipeline/fix_match_key_aliases.py --write    # записать
"""
