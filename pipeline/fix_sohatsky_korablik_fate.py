import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g0885d151'

OLD_ECO_CONTEXT = (
    'На конец 2022 года краткосрочные обязательства ООО «Кораблик-Р» '
    'составляли 3,4 млрд ₽, из них 3 млрд ₽ — кредиторская '
    'задолженность.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' Сохацкий — бенефициар самой МТК «Алиса», того '
    'самого крупного поставщика «Кораблика», о котором говорит выше '
    'эксперт. Уже в апреле 2023 года Сохацкий продал 100% АО '
    '«Кораблик» структурам бизнесмена Александра Мамута (ООО '
    '«Веспер», принадлежащее Надежде Ермаковой), а затем судился с '
    'покупателем из-за недоплаченных 43 млн ₽. Новые владельцы '
    'запустили бренд Toyspro и к 2024 году закрыли все магазины '
    '«Кораблик» (осталось 11 точек Toyspro); выручка рухнула с 13,2 '
    'млрд ₽ (2019) до 1 млрд ₽ (2023). В 2024–2026 годах компания '
    'пережила несколько попыток банкротства: в ноябре 2025 года суд '
    'прекратил дело за отсутствием имущества, а в 2026 году новую '
    'попытку инициировал кредитор «Крок Инкорпорейтед»; действующих '
    'магазинов на конец 2025 года не найдено.'
)

OLD_SRC = [['Коммерсантъ', 'https://www.kommersant.ru/doc/5886683']]
NEW_SRC = OLD_SRC + [
    ['Интерфакс', 'https://www.interfax.ru/business/894605'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8608380'],
    ['KIAP', 'https://www.kiap.com/press-centr/public/1444.html'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
