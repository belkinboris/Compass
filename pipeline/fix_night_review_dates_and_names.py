# -*- coding: utf-8 -*-
"""Два дефекта из ночной вычитки 40 карточек (17-18 августа 2026), которые
`review.py` не умеет чинить через таблицу FIXES: смена ГОДА в дате (что
сознательно запрещено — см. урок CLAUDE.md про `date_is_supported()`) и
замена значения, которое не было пустым (не empty-fill, а фактическая
ошибка).

- g43c78df8 (МТС/«СКАУТ-КР»): дата стояла 2022-04-01, источник (Интерфакс,
  interfax.ru/amp/898045, 14:25, 27 апреля 2023) прямо датирует сделку
  апрелем 2023 года («МТС вошла в капитал «СКАУТ-КР» в середине апреля»,
  сама статья от 27.04.2023) — год ошибочен, не просто день. Имя продавца
  тоже перепутано: «Марина Александровна» вместо «Мария Алексеевна» —
  разные имя и отчество, не опечатка в одной букве (подтверждено профилем
  TAdviser: «Висневская Мария Алексеевна — 44,1%»).
- c51d0bb64 (Wildberries/ВТБ, партнёрство по WB Банку): дата стояла годом
  «2024», но единственный источник карточки (republished Forbes, ссылка на
  которую при повторном скачивании отдаёт пустой текст — заблокирован для
  автоматического дозабора) обсуждается вторичными источниками (rb.ru,
  vc.ru, smart-lab.ru, посты на Т-Инвестициях) как новость мая 2026 года,
  а не 2024-го — расхождение на два года. День и месяц не восстанавливаем
  (не нашлось прямой дословной цитаты с числом), меняем только год —
  тот же принцип, что уже применялся к `fix_osnova_sviblovo_date.py`.

Запуск:
    python3 pipeline/fix_night_review_dates_and_names.py            # сухой прогон
    python3 pipeline/fix_night_review_dates_and_names.py --write     # запись
"""
import json
import sys

PATH = "static/data/deals_promoted.json"


def main(write):
    with open(PATH, encoding="utf-8") as f:
        base = json.load(f)
    by_id = {d["id"]: d for d in base["deals"]}

    d = by_id["g43c78df8"]
    assert d["date"] == "2022-04-01", "g43c78df8.date уже другая — уже правили?"
    d["date"] = "2023-04-13"

    old_seller = "Висневская Марина Александровна и Висневский Юрий Алексеевич"
    assert d["seller"] == old_seller, "g43c78df8.seller уже другой — уже правили?"
    d["seller"] = "Висневская Мария Алексеевна и Висневский Юрий Алексеевич"

    old_extra = ("Сделка заключена в середине апреля 2022 года. МТС "
                 "увеличила долю в ООО Проектная среда (группа "
                 "СКАУТ-Корпоративные решения) с 15% до 51%, получив "
                 "контроль в компании. Продавцы: Висневская Марина "
                 "Александровна и Висневский Юрий Алексеевич.")
    assert d["extra"] == old_extra, "g43c78df8.extra уже другой — уже правили?"
    d["extra"] = ("Сделка заключена в середине апреля 2023 года. МТС "
                  "увеличила долю в ООО Проектная среда (группа "
                  "СКАУТ-Корпоративные решения) с 15% до 51%, получив "
                  "контроль в компании. Продавцы: Висневская Мария "
                  "Алексеевна и Висневский Юрий Алексеевич.")
    print("g43c78df8: date (2022->2023), seller и extra (Марина Александровна "
          "-> Мария Алексеевна) исправлены")

    d2 = by_id["c51d0bb64"]
    assert d2["date"] == "2024", "c51d0bb64.date уже другая — уже правили?"
    d2["date"] = "2026"
    print("c51d0bb64: date (2024 -> 2026) исправлена")

    if write:
        with open(PATH, "w", encoding="utf-8") as f:
            json.dump(base, f, ensure_ascii=False, indent=1)
        print("\nЗАПИСАНО.")
    else:
        print("\nСухой прогон — ничего не записано. Добавьте --write.")


if __name__ == "__main__":
    main(write="--write" in sys.argv)
