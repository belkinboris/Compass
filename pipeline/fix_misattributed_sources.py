# -*- coding: utf-8 -*-
"""Проверка боем 3 «подозрительных источников» из прошлого прогона — и поправка.

ЧТО БЫЛО. `fix_placeholder_dates_from_sources.py` не тронул 3 карточки, у
которых слаг URL источника выглядел НЕ про ту сделку, что в заголовке карточки,
и записал это в бэклог как «похоже, источник перепутан при разборе». Владелец
попросил разобраться до конца, а не оставлять как подозрение.

ЧТО ПОКАЗАЛА ПРОВЕРКА ЖИВЫМ ПОИСКОМ. Из трёх подозрений подтвердилось только
одно:
  * `g7ae9bb53` («Энерготехника Северо-Запад» / «Ямалдорстрой») — ЛОЖНАЯ
    ТРЕВОГА. Слаг «beneficiar-peterburgskoj-zvezdi» не называет стороны сделки
    напрямую, но статья РЕАЛЬНО про неё: Алексей Костин, владелец
    «Энерготехники Северо-Запад», связан с ПАО «Звезда» (в заголовке статьи),
    и именно он купил «Ямалдорстрой» — источник корректен, дата тоже.
  * `gfcfba8c9` (ТЦ «Аура» → «Металлист») — ЛОЖНАЯ ТРЕВОГА. «Металлист» —
    юрлицо, «Grand Line» (упомянут в слаге) — бренд стройматериалов ТОГО ЖЕ
    производителя. Источник верный.
  * `g2544a5cb` (клиники Литфонда) — ПОДТВЕРЖДЁН как дефект. Источник
    («Ведомости», 2014, «кто распоряжается пенсионными деньгами Роснефти») не
    про эту сделку ни по теме, ни по времени. Три отдельных поисковых запроса
    (по названию клиники, по названию сделки, по именам сторон) не нашли
    настоящую статью — восстановить верный источник нечем.

ЧТО ДЕЛАЕМ.
  * `g7ae9bb53`, `gfcfba8c9` — те же правки дат, что и остальные 20 карточек
    партии: дата публикации подтверждённого источника.
  * `g2544a5cb` — источник ОЧИЩЕН (пустой список), а не оставлен неверным:
    ссылка, которая не подтверждает карточку, хуже отсутствия ссылки — по ней
    перейдёт пользователь, ожидающий подтверждения именно этой сделки, и
    увидит статью про другое. Дату-заглушку НЕ трогаем (год без источника —
    недоказанное предположение, дата 2024-01-01 остаётся тем, чем была,
    заглушкой, а не подтверждённым фактом). Текст карточки (заголовок, сумма,
    стороны) не трогаем — эти факты, скорее всего, взяты из настоящей статьи
    при исходном разборе, просто ссылка на неё потерялась; удалять сам факт
    из-за потерянной ссылки означало бы вычеркнуть данные, а не почистить их.

ЧЕГО НЕ ДЕЛАЕМ. Не подставляем правдоподобную замену ссылки для `g2544a5cb` —
её не нашли, а не досочинили.

Запуск:
    python3 pipeline/fix_misattributed_sources.py            # сухой прогон
    python3 pipeline/fix_misattributed_sources.py --write    # записать
"""
import json
import sys

PATH = 'static/data/deals_promoted.json'

DATE_FIXES = {
    'g7ae9bb53': ('2023-01-01', '2026-03-12'),
    'gfcfba8c9': ('2024-01-01', '2026-03-06'),
}
CLEAR_SRC = {
    'g2544a5cb': [['@dealsma (Telegram)', 'https://www.vedomosti.ru/newspaper/articles/2014/02/24/kto-rasporyazhaetsya-pensionnymi-dengami-rosnefti']],
}


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    changes = []
    for did, (old, new) in DATE_FIXES.items():
        d = by_id[did]
        actual = d.get('date')
        assert actual == old, f'{did}.date: ожидали {old!r}, нашли {actual!r}'
        changes.append((did, 'date', old, new))
        if write:
            d['date'] = new

    for did, old_src in CLEAR_SRC.items():
        d = by_id[did]
        actual = d.get('src')
        assert actual == old_src, f'{did}.src изменился с прошлого замера: {actual!r}'
        changes.append((did, 'src', old_src, []))
        if write:
            d['src'] = []

    print(f'правок: {len(changes)}')
    for did, field, old, new in changes:
        print(f'  {did} [{field}]: {old!r} -> {new!r}')

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=1, ensure_ascii=False)
        print('\nЗАПИСАНО в', PATH)
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
