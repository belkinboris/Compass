# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g807a5625
(VK приобрел 40% в билетном сервисе Intickets.ru) — сумма стояла
заглушкой «Не раскрыта», хотя точная цифра есть в консолидированной
отчётности VK; структура сделки (допэмиссия, а не выкуп доли у
продавца) не была отражена вовсе. Проверено лично прямым WebFetch двух
источников.

1) `sum`/`eco.sum` — точная сумма. Дословно (CNews, со ссылкой на
отчётность VK): «VK потратила 472 млн руб. на приобретение 40% доли...
«Интикетс»... Дополнительно компания должна будет выплатить отложенный
платеж в размере 251 млн руб. То есть общая сумма сделки составит 721
млн руб.» Это раскрытая самой VK цифра (из документов компании), а не
сторонняя оценка — пометка «(по оценке)» не нужна. Прежняя оценка в
`eco.val` (собеседник «Ъ», ноябрь 2023, 1 млрд руб. за 100% на этапе
переговоров) НЕ заменяется — это независимая оценка ДО сделки, стоит
рядом как история, а не как противоречие итоговой цифре.

2) `law.struct` (новое поле) — механизм: допэмиссия, а не выкуп доли.
Дословно (mergers.akm.ru): «Сделка прошла через увеличение уставного
капитала» — 27 июня 2024 «ООО «Компания ВК» стало владельцем 15% ООО
«ИНТИКЕТС»», после чего «доли оставшихся участников пропорционально
уменьшились»: Анна Субчева — до 8,5%, Александр/Александра Кондратенко
— до 76,5% (расхождение пола в разных источниках не разрешено, имя
оставлено как в этом источнике). Это CASH-IN: деньги идут самой
компании, а не продающему акционеру — `seller` НЕ заполняется
механически для этой части сделки (родня уроку CLAUDE.md про ПСБ/
«Атом»: допэмиссия за деньги — не то же самое, что продажа доли).
Дальнейший рост доли VK с 15% до 40% к августу 2024 года (Субчева вышла
из капитала полностью) — механизм второго транша (капитал vs выкуп)
источники не называют напрямую, поэтому не утверждается.

НЕ ВКЛЮЧЕНО: продавец как структурное поле — по причине, описанной выше
(cash-in, а не выкуп, для первого транша; механизм второго транша не
подтверждён); консультанты — не найдены ни в одном из ~10 проверенных
источников; согласование ФАС — не подтверждено официально, только
мнение рыночного эксперта («явно никакой монополизации не возникает»,
BFM.ru) — это спекуляция, не заявление органа, для `law.appr` не
годится; развитие Intickets под частичным контролем VK в 2025-2026 —
новых фактов не найдено, структура долей (VK 40%/Кондратенко 60%) не
менялась по последним данным.

Запуск: python3 pipeline/fix_vk_intickets_sum_and_structure.py
        python3 pipeline/fix_vk_intickets_sum_and_structure.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g807a5625'

OLD_SUM = 'Не раскрыта'
NEW_SUM = '721 млн ₽'

NEW_STRUCT = (
    '«Сделка прошла через увеличение уставного капитала» (mergers.akm.ru) '
    '— 27 июня 2024 года ООО «Компания ВК» стало владельцем 15% ООО '
    '«Интикетс», после чего доли остальных участников пропорционально '
    'уменьшились: Анна Субчева — до 8,5%, Кондратенко — до 76,5%. Это '
    'допэмиссия за деньги (cash-in): средства получила сама компания, а '
    'не продающий акционер. К августу 2024 года доля VK выросла до 40%, '
    'Субчева полностью вышла из капитала — механизм этого второго этапа '
    'источники не называют.'
)

NEW_SRC = [
    ['CNews', 'https://www.cnews.ru/news/top/2025-01-02_kak_vk_potratil_bolee_12_mlrd'],
    ['mergers.akm.ru', 'https://mergers.akm.ru/news/vk_priobrela_15_onlayn_servisa_prodazhi_biletov_intickets/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['sum'] == OLD_SUM
    assert deal['eco']['sum'] == OLD_SUM
    assert deal['law']['struct'] == '—'
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print(f'=== sum/eco.sum: {OLD_SUM!r} -> {NEW_SUM!r} ===')
    print('=== law.struct: станет ===')
    print(NEW_STRUCT)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['sum'] = NEW_SUM
        deal['eco']['sum'] = NEW_SUM
        deal['law']['struct'] = NEW_STRUCT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
