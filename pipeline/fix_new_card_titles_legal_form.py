# -*- coding: utf-8 -*-
"""G3: заголовки новых карточек — убрать юрлицо там, где узнаваемое имя уже есть.

ЗАМЕР (9 августа). Правило для НОВЫХ карточек (`from_ingest: true`, всего 84)
— заголовок не копирует источник дословно, в заголовке узнаваемый бренд, а не
юрлицо, вместо «крупнейший производитель X» настоящее имя. Замерено по всем
84: превосходная степень без имени — 0 нарушений; юрлицо (ООО/АО/ПАО/ОАО) в
заголовке — 13 карточек; заголовок дословно совпадает с заголовком источника
— 21 карточка (все — mergers.ru, чьи заголовки сами по себе написаны
по-человечески, поэтому дословное совпадение здесь не читается как «набор
данных»; правки текста без факта не делаем — это не то же самое, что «звучит
как результат работы с данными»).

ЧТО ПРАВИМ. Из 13 карточек с юрлицом в заголовке — только там, где после
юрлица уже стоит своё узнаваемое имя и снятие приставки (ООО/АО/ПАО) НЕ
требует склонения этого имени (риск ошибки в падеже — отдельный, хорошо
задокументированный класс дефектов в CLAUDE.md, тут его не трогаем):
  - «IPO/SPO + название» — общий заголовочный паттерн, здесь название после
    IPO/SPO не управляется падежом (сравните «IPO Ozon», «IPO Yandex»), снять
    приставку можно без склонения (`g3acbe2ec`, `g4c98dcba`, `gb1cacbc1`);
  - юрлицо стоит подлежащим в начале предложения (именительный падеж и без
    приставки, и с ней) — `g17a6fd62`, `g37a1b2e2` (плюс согласование глагола
    по роду: «ПАО» — средний род, «Банк» — мужской, «привлекло» -> «привлёк»);
  - иностранное имя в кавычках после «на акции» — иностранные заголовки в
    кавычках по-русски обычно НЕ склоняются и без юрлица перед ними —
    `gec757ede`.
  - брендовое название уже в заголовке, но ПОСЛЕ юрлица через тире — вынесено
    вперёд, юрлицо осталось в скобках (юрлицо не потеряно, а не в заголовке
    первым, как просит правило): `gbcc32684` (Lamoda/Selfmade), `geb221705`
    (X5/MAY24).

ДВЕ КАРТОЧКИ С ЮРЛИЦОМ НЕ ТРОНУТЫ НАМЕРЕННО: у `gmru-razvitie-stroy-aktivov-
akzo` (АО «Развитие строительных активов») и `g6e1bb001` (АО «Центр Развития
Портовой Инфраструктуры») своего узнаваемого бренда нет вовсе — юрлицо и есть
единственное имя. Ещё две — `gb0759159` («Кузнецкая ТЭЦ») и `g92ef210a`
(«Уралхиммаш») — сняли бы юрлицо ТОЛЬКО ценой склонения имени в родительном
падеже («акций АО «Кузнецкая ТЭЦ»» -> «акций «Кузнецкой ТЭЦ»»), а это риск
ошибки того же класса, что уже не раз ловился на этой базе (см. уроки про
падеж предмета в CLAUDE.md) — оставлены как есть до отдельной, более
осторожной правки.

ОДНА ДЛИННАЯ ЗАГОЛОВОК УКОРОЧЕН: `gc5951fac` — «Владельцы логистической
платформы ATI.SU купили разработчика системы для управления автомобильными
грузоперевозками CARGO.RUN» звучит как перечисление полей из карточки, а не
как заголовок; полное описание CARGO.RUN уже есть в поле `asset` карточки.

Запуск:
    python3 pipeline/fix_new_card_titles_legal_form.py            # сухой прогон
    python3 pipeline/fix_new_card_titles_legal_form.py --write    # записать
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

# id -> (старый заголовок, новый заголовок)
TITLE_FIXES = {
    'g3acbe2ec': (
        'IPO ПАО «Группа Аренадата» на Московской бирже',
        'IPO «Группа Аренадата» на Московской бирже',
    ),
    'g4c98dcba': (
        'SPO ПАО «Группа Астра»: продано 21 млн акций по 555 ₽',
        'SPO «Группа Астра»: продано 21 млн акций по 555 ₽',
    ),
    'gb1cacbc1': (
        'IPO ПАО «Группа Астра» на Московской бирже',
        'IPO «Группа Астра» на Московской бирже',
    ),
    'g17a6fd62': (
        'ООО «Пункт Е» купило 100% «Ситроникс Электро» у группы «Ситроникс»',
        '«Пункт Е» купило 100% «Ситроникс Электро» у группы «Ситроникс»',
    ),
    'g37a1b2e2': (
        'ПАО «МТС-Банк» привлекло около 4 млрд ₽ через дополнительную эмиссию акций',
        '«МТС-Банк» привлёк около 4 млрд ₽ через дополнительную эмиссию акций',
    ),
    'gec757ede': (
        'Публичный обмен ГДР Fix Price Group PLC на акции ПАО «Фикс Прайс»',
        'Публичный обмен ГДР Fix Price Group PLC на акции «Фикс Прайс»',
    ),
    'gbcc32684': (
        'Lamoda приобрела 90% ООО «Фаст Фешн» — владельца бренда Selfmade',
        'Lamoda приобрела 90% бренда Selfmade (ООО «Фаст Фешн»)',
    ),
    'geb221705': (
        'X5 Group приобрела 100% ООО «МАЙ24» — цифровую площадку MAY24',
        'X5 Group приобрела 100% цифровой площадки MAY24 (ООО «МАЙ24»)',
    ),
    'gc5951fac': (
        'Владельцы логистической платформы ATI.SU купили разработчика системы '
        'для управления автомобильными грузоперевозками CARGO.RUN',
        'Владельцы логистической платформы ATI.SU купили разработчика '
        'сервиса CARGO.RUN',
    ),
}


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    deals = {d['id']: d for d in data['deals']}

    changed = 0
    for cid, (old, new) in TITLE_FIXES.items():
        d = deals.get(cid)
        assert d, 'карточки %s нет в базе' % cid
        assert d['title'] == old, ('заголовок %s уже другой: %r (ожидали %r)'
                                    % (cid, d['title'], old))
        print('  %-12s %r\n               -> %r' % (cid, old, new))
        d['title'] = new
        changed += 1

    print('\nЗаголовков изменено: %d' % changed)
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return 0
    json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('Записано.')
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
