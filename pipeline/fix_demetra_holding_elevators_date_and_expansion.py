import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g5809b7a2'

OLD_DATE = '2023-08-01'
NEW_DATE = '2023-09-01'

NEW_ECO_VAL = (
    'По оценке Артёма Тузова (ИК «ИВА Партнерс»), стоимость двух новых '
    'активов «Деметра Трейдинг» могла составить от 2,5 до 5 млрд ₽.'
)

OLD_ECO_CONTEXT = '—'
NEW_ECO_CONTEXT = (
    'В июле 2023 года стало известно, что «Деметра-холдинг» готовится к '
    'передаче части акций Southern Sea Investment LLC из Омана — это даст '
    'холдингу экспортный «коридор» на Аравийский полуостров, и, по оценке '
    'аналитика, покупка элеваторов, скорее всего, связана с планируемыми '
    'объёмами поставок. В декабре 2024 года на Димитровградском элеваторе '
    'началось строительство новых силосов — мощность должна вырасти на '
    '20%, с 85,4 до 103,2 тыс. т, к II кварталу 2025 года; по словам '
    'управляющего директора «Деметра Трейдинг» Романа Крона, проект '
    'должен превратить линейный элеватор в полноценный перевалочный хаб.'
)

NEW_SRC = [
    ['АКМ', 'https://www.akm.ru/news/demetra_kholding_priobrel_u_gruppy_bi_ay_granum_eshche_odin_elevator/'],
    ['Zerno.ru', 'https://www.zerno.ru/node/23913'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/7404437'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['date'] == OLD_DATE
    assert deal['eco']['val'] == '—'
    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    new_src = deal['src'] + NEW_SRC

    print('=== date: станет ===', NEW_DATE)
    print('\n=== eco.val: станет ===')
    print(NEW_ECO_VAL)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['date'] = NEW_DATE
        deal['eco']['val'] = NEW_ECO_VAL
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
