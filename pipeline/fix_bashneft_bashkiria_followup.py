# -*- coding: utf-8 -*-
"""Месячное дочитывание карточки `g8e30b9a8` (Башкирия продаёт «Роснефти»
оставшуюся часть пакета «Башнефти», объявлено 12 августа 2026) — третий
уровень очереди (`REVISION_BRIEF.md`), первое чтение спустя месяц после
первого обыска (14 августа 2026).

Проверено WebSearch/WebFetch: сделка НЕ закрылась за месяц — ни цена, ни
размер оставшегося пакета, ни решение ФАС ни разу не назывались ни одним
источником вплоть до 13 сентября 2026. Статус «Обсуждается» не меняется.

Что добавлено, каждая цитата подтверждена прямым WebFetch (не по пересказу
саб-агента):

1. `eco.context` — причина срочности, которой не было в карточке: решение о
   продаже пришлось на серию ударов украинских беспилотников по Уфимскому
   НПЗ (The Moscow Times: «трижды попадали под удары украинских дронов» в
   августе, 5 августа один из аппаратов вызвал пожар на «Башнефть-УНПЗ»).

2. `eco.context` — рыночная реакция и риск для миноритариев (Интерфакс,
   business/1109059, 13.08.2026): аналитики ИФК «Солид Инвестиции»
   предупредили, что после продажи оставшегося пакета миноритарии лишатся
   защиты региональных властей; привилегированные акции подешевели на
   объявлении.

3. `eco.rationale` — дословная цитата Хабирова (Коммерсантъ, doc/8878147,
   12.08.2026) про дыру в бюджете и рекомендацию Минфина продавать всё, что
   есть — то же объяснение, что уже пересказано прозой, но своими словами
   первого лица.

Источники добавлены в `src`.

Запуск:
    python3 pipeline/fix_bashneft_bashkiria_followup.py            # сухой прогон
    python3 pipeline/fix_bashneft_bashkiria_followup.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'
CID = 'g8e30b9a8'

OLD_RATIONALE = (
    'Хабиров напомнил, что первый пакет акций республика уже продала '
    '«Роснефти», и подтвердил намерение продать ей оставшуюся часть. После '
    'продажи первого пакета республика утратила контроль над предприятием, '
    'поэтому оставшиеся акции потеряли смысл. Вырученные средства позволят '
    'региону закрыть текущие обязательства и запустить новые проекты.'
)
NEW_RATIONALE = OLD_RATIONALE + (
    ' Сам Хабиров объяснил это прямо: «Есть дыра в бюджете. Мы продали '
    'часть пакета "Башнефти". Будем продавать ещё. В условиях, когда денег '
    'не хватает, Минфин рекомендует продавать все, что есть».'
)

OLD_CONTEXT = (
    'В начале июня премьер-министр республики Андрей Назаров рассказал, что '
    'Башкирия продала часть своего пакета «Башнефти» с условием обратного '
    'выкупа — когда у республики появится такая возможность. Покупателем '
    'выступила «Роснефть». Стоимость проданного пакета составила 14,8 млрд '
    'рублей, уточняла исполняющая обязанности министра финансов республики '
    'Светлана Малинская.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' Решение о продаже пришлось на серию атак украинских беспилотников на '
    'Уфимский НПЗ: в августе завод трижды подвергался ударам дронов, а '
    '5 августа один из аппаратов вызвал пожар на объекте «Башнефть-УНПЗ». '
    'Аналитики ИФК «Солид Инвестиции» предупредили, что после продажи '
    'оставшегося пакета миноритарные акционеры лишатся защиты со стороны '
    'регионального правительства — на объявлении привилегированные акции '
    '«Башнефти» подешевели.'
)

NEW_SOURCES = [
    ['The Moscow Times', 'https://ru.themoscowtimes.com/2026/08/12/vlasti-bashkortostana-reshili-prodat-rosnefti-ufimskie-npz-posle-udarov-dronov-i-diri-v-byudzhete-na-17-mlrd-rublei-a203331'],
    ['Интерфакс', 'https://www.interfax.ru/business/1109059'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8878147'],
]


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    deals = {d['id']: d for d in data['deals']}
    card = deals[CID]

    already_applied = (card['eco']['rationale'] == NEW_RATIONALE
                        and card['eco']['context'] == NEW_CONTEXT)
    if already_applied:
        print('Уже применено — нечего делать (скрипт идемпотентен).')
        return

    assert card['eco']['rationale'] == OLD_RATIONALE
    assert card['eco']['context'] == OLD_CONTEXT
    existing_urls = {u for _, u in card['src']}
    to_add = [pair for pair in NEW_SOURCES if pair[1] not in existing_urls]

    print('Правки для %s (%s):' % (CID, card['title']))
    print('  eco.rationale: +цитата Хабирова про дыру в бюджете')
    print('  eco.context: +удары дронов по УНПЗ, +риск для миноритариев')
    print('  src: +%d адресов' % len(to_add))

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    card['eco']['rationale'] = NEW_RATIONALE
    card['eco']['context'] = NEW_CONTEXT
    card['src'].extend(to_add)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
