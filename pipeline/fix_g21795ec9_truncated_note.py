# -*- coding: utf-8 -*-
"""events[0].note карточки g21795ec9 (совладелец «Депо Три Вокзала» продал
долю в «Алми прайм») обрублен с ОБОИХ концов — начинается с середины слова
«[Ком]пания» и обрывается на «...собственное оте[чественное]». Найдено
ночной вычиткой 40 карточек (17-18 августа 2026); текст рендерится прямо на
экране (`events[].note` в `static/index.html`), дефект виден пользователю.

Полный текст восстановлен по источнику (tadviser.ru/a/489134,
data/inbox/raw) — тот же приём, что `fix_truncated_fields.py`/
`fix_truncated_field_heads.py`, только источник не `extra` этой же карточки,
а страница компании на TAdviser. Заодно нормализована капитализация «Х
Программное обеспечение» -> «программное обеспечение» — артефакт извлечения
текста из вики-ссылок TAdviser (заглавная буква посреди предложения не
несёт смысла), и «рынок России» -> «рынке России» — опечатка склонения в
самом источнике, которую можно поправить по правилу review.py «вырезать
лишнее и поставить заглавную букву», не искажая факт.

Запуск:
    python3 pipeline/fix_g21795ec9_truncated_note.py            # сухой прогон
    python3 pipeline/fix_g21795ec9_truncated_note.py --write     # запись
"""
import json
import sys

PATH = "static/data/deals_promoted.json"
ID = "g21795ec9"

OLD = ('пания ALMI Partner (Группа компаний «АЛМИ») работает на ИТ-рынок '
       'России более 23 лет и оказывает полный спектр услуг в ИТ-секторе '
       '(по состоянию на 2024 г.). В рамках осуществления стратегии '
       'импортозамещения ALMI Partner разрабатывает и внедряет собственное '
       'оте')
NEW = ('Компания ALMI Partner (Группа компаний «АЛМИ») работает на '
       'ИТ-рынке России более 23 лет и оказывает полный спектр услуг в '
       'ИТ-секторе (по состоянию на 2024 г.). В рамках осуществления '
       'стратегии импортозамещения ALMI Partner разрабатывает и внедряет '
       'собственное отечественное программное обеспечение, включая '
       'офисный пакет AlterOffice и операционную систему AlterOS.')


def main(write):
    with open(PATH, encoding="utf-8") as f:
        base = json.load(f)
    by_id = {d["id"]: d for d in base["deals"]}
    d = by_id[ID]
    assert d["events"][0]["note"] == OLD, "events[0].note уже другой — уже правили?"
    d["events"][0]["note"] = NEW
    print(f"{ID}: events[0].note восстановлен (был обрублен с обоих концов)")

    if write:
        with open(PATH, "w", encoding="utf-8") as f:
            json.dump(base, f, ensure_ascii=False, indent=1)
        print("\nЗАПИСАНО.")
    else:
        print("\nСухой прогон — ничего не записано. Добавьте --write.")


if __name__ == "__main__":
    main(write="--write" in sys.argv)
