"""Месячная очередь (REVISION_BRIEF), карточка gef02a680 («Мультимедиа
Холдинг»): дельта-поиск проверил, что стало с продажей больше чем через
год после выставления холдинга на рынок (июнь 2024). Ни продажи
целиком, ни продажи НСН отдельно не случилось — Богданов остаётся
владельцем и (с 8 сентября 2025 года) сам занимает пост генерального
директора. Единственный найденный потенциальный покупатель
(«Европейская медиагруппа») публично отказался ещё в июне 2024 года.

Статус карточки НЕ меняю на «Не состоялась» — ни один источник не
объявляет продажу сорванной прямо, это скорее «не осветили», чем
«отменили» (тот же класс, что уже записан в CLAUDE.md для сделок VIM/
Поклонка и Суточно.ру/OneTwoTrip).

Источники: РБК Компании (текущая финансовая карточка, ЕГРЮЛ) и AdPass
(отказ «Европейской медиагруппы») — оба читал напрямую. Не через
review.py: факт складывается из двух разных источников.
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gef02a680'
OLD_CONTEXT = (
    'Часть собеседников «Ъ» в индустрии развлечений полагают, что НСН '
    'будет продана отдельно от других активов «Мультимедиа Холдинга».'
)
ADDITION = (
    'К августу 2026 года продажа не состоялась ни целиком, ни по '
    'частям: Богданов остаётся владельцем холдинга и с 8 сентября 2025 '
    'года сам занимает пост генерального директора. Гендиректор '
    '«Европейской медиагруппы» Роман Емельянов ещё в июне 2024 года '
    'публично назвал приобретение холдинга «в данный момент не '
    'интересным».'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} eco.context: += продажа не состоялась к августу "
          "2026 года")
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
