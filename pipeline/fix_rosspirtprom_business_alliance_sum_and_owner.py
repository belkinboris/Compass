# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g5d1be523
(Государство продало Росспиртпром компании «Бизнес-Альянс»). Заголовок
и сумма несли неточную округлённую цифру, а сама карточка держалась на
Telegram-агрегаторе вместо настоящего первоисточника. Проверено лично
прямым WebFetch.

1) `title`/`sum`/`eco.sum` — были «8 миллиардов рублей»/«8 млрд ₽», хотя
собственное поле `eco.context` уже верно называло 8,3 млрд. Коммерсантъ
(настоящий первоисточник, не агрегатор), дословно: «Победителем торгов
стало ООО «Бизнес Альянс», предложившее за актив 8,289 млрд руб.»;
«Стартовая стоимость лота была на уровне 10,61 млрд руб.»
Источник: https://www.kommersant.ru/doc/6662266

2) `eco.context` — дополнено эволюцией структуры владения и судьбой
компании. Ведомости (30.12.2025), дословно: «Это общество [«Бизнес-
Альянс»], по данным «СПАРК-Интерфакса», контролируют закрытый паевой
инвестиционный фонд «Батман» под управлением ООО «Финансовый партнер» и
бизнесмен Владимир Акаев» — с июля 2025 года 51% принадлежит структуре
фонда, а не единолично Акаеву, как было на момент покупки в 2024 году.
В декабре 2025 года «Росспиртпром» закрыл покупку 100% АО
«Татспиртпром» у правительства Татарстана — создан вертикально
интегрированный холдинг.

ГИПОТЕЗА О КОНЕЧНОМ ВЛАДЕЛЬЦЕ — включена с явной пометкой источника и
статуса неопределённости, а не как факт: издание The Insider (внесено в
РФ в реестр иностранных агентов/нежелательных организаций — статус
называется прямо, читатель решает сам, доверять ли), со ссылкой на
«внутреннюю финансовую документацию» фонда «Батман», утверждает, что
единственным вкладчиком фонда является Аркадий Ротенберг. Это ПРЯМО
СОВПАДАЕТ с версией, которую ещё в 2024 году высказывали «два
собеседника «Ъ» в отрасли» (уже стоит в `eco.val`) о том, что «конечным
владельцем актива может стать совсем другая компания» — но подтверждено
только одним, спорным по репутации источником, поэтому включено как
предположение, а не установленный факт (тот же класс осторожности, что
уже применён в CLAUDE.md к делам БКС/«Форштадт» и Шишкарев/«Дело»/
Ростех).

НЕ ВКЛЮЧЕНО: консультанты сделки — не найдены ни в одном из ~10
проверенных источников.

Запуск: python3 pipeline/fix_rosspirtprom_business_alliance_sum_and_owner.py
        python3 pipeline/fix_rosspirtprom_business_alliance_sum_and_owner.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g5d1be523'

OLD_TITLE = 'Государство продало Росспиртпром компании Бизнес Альянс за 8 миллиардов рублей'
NEW_TITLE = 'Государство продало Росспиртпром компании Бизнес Альянс за 8,3 миллиарда рублей'

OLD_SUM = '8 млрд ₽'
NEW_SUM = '8,289 млрд ₽'

OLD_CONTEXT = 'Пакет куплен за 8,3 млрд рублей при начальной цене лота в 10,6 млрд рублей.'
NEW_CONTEXT = OLD_CONTEXT + (
    ' С июля 2025 года структура владения «Бизнес-Альянсом» изменилась: '
    '«это общество... контролируют закрытый паевой инвестиционный фонд '
    '«Батман» под управлением ООО «Финансовый партнер» и бизнесмен '
    'Владимир Акаев» (Ведомости) — 51% у структуры фонда, 49% у Акаева. '
    'The Insider (СМИ, признанное в РФ иностранным агентом/нежелательной '
    'организацией), ссылаясь на «внутреннюю финансовую документацию» '
    'фонда, утверждает, что его единственный вкладчик — Аркадий '
    'Ротенберг; это совпадает с версией «двух собеседников «Ъ»» 2024 '
    'года о «совсем другой компании», но подтверждено только этим одним '
    'источником, не установленный факт. В декабре 2025 года '
    '«Росспиртпром» закрыл покупку 100% АО «Татспиртпром» у правительства '
    'Татарстана, создав вертикально интегрированный холдинг.'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6662266'],
    ['Ведомости', 'https://www.vedomosti.ru/business/articles/2025/12/30/1167582-rosspirtprom-zakril-sdelku'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['title'] == OLD_TITLE
    assert deal['sum'] == OLD_SUM
    assert deal['eco']['sum'] == OLD_SUM
    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print(f'=== title: {OLD_TITLE!r} -> {NEW_TITLE!r} ===')
    print(f'=== sum/eco.sum: {OLD_SUM!r} -> {NEW_SUM!r} ===')
    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['title'] = NEW_TITLE
        deal['sum'] = NEW_SUM
        deal['eco']['sum'] = NEW_SUM
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
