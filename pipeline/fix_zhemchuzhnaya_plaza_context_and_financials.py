# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка ge56325d9 (Группа Аврора/
ТРЦ «Жемчужная плаза», SIIC): дельта-поиск нашёл историю доли SRV
(Ведомости — та же статья, что уже в src, но абзац о смене планов SRV
раньше не переносился) и бенефициара покупателя (Деловой Петербург), а
также баланс объекта за 2024 год (abn.agency — редомициляция
управляющей структуры в РФ). Не через review.py: каждое поле уже несёт
текст из ДРУГОГО источника, а review.py требует, чтобы итоговое значение
поля лежало дословно в ОДНОЙ цитате.

Источники — читал напрямую (fetch_article_texts.py, закэшированы):
Ведомости (13.11.2025, тот же материал, что уже в src карточки), Деловой
Петербург (27.02.2026), abn.agency (05.12.2025).
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'ge56325d9'

OLD_CONTEXT = (
    'Также в портфеле компании — торговые комплексы «Невский Центр», '
    '«Владимирский Пассаж», «Космос» и «Авеню», саратовский ТРЦ «Триумф '
    'Молл» и красноярский ТК «На Свободном». Стоимость сделки не '
    'раскрывается. Известно, что китайской компании принадлежала половина '
    'объекта. SRV после закрытия сделки по своим 50% долей в 2024 году '
    'отчиталась о цене продажи примерно в 11 млн евро.'
)
CONTEXT_ADDITION = (
    'Изначально владельцем этого объекта помимо SIIC была финская SRV '
    'Group. Последняя еще в 2022 г. приняла решение уйти из России. Она '
    'договорилась о продаже своей доли с екатеринбургской «Проспект '
    'групп», но затем передумала. В итоге половина комплекса перешла '
    'инвесткомпании Central Properties. Тогда консультанты предполагали, '
    'что она в итоге выкупит и долю SIIC. Но, как оказалось, доля '
    'досталась «Авроре». В числе бенефициаров «Авроры» называют '
    'совладельца «Адаманта» миллиардера Владимира Голубева.'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + CONTEXT_ADDITION

OLD_TARGET_FIN = (
    'За 2024 год прибыль компании составляет — 657 772 000 ₽, выручка за '
    '2024 год — 1 917 484 000 ₽.'
)
TARGET_FIN_ADDITION = (
    'На 31 декабря 2024 года совокупные активы компании достигли 5,9 млрд '
    'рублей — на 408 млн рублей (7,5%) больше, чем годом ранее. При этом '
    'чистые активы оставались отрицательными и составили минус 145 млн '
    'рублей.'
)
NEW_TARGET_FIN = OLD_TARGET_FIN + ' ' + TARGET_FIN_ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"
    assert deal['eco']['target_fin'] == OLD_TARGET_FIN, \
        f"eco.target_fin: неожиданное значение {deal['eco']['target_fin']!r}"

    print(f"{CARD_ID} eco.context: += история доли SRV и бенефициар «Авроры»")
    print(f"{CARD_ID} eco.target_fin: += баланс объекта на конец 2024 года")
    deal['eco']['context'] = NEW_CONTEXT
    deal['eco']['target_fin'] = NEW_TARGET_FIN

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
