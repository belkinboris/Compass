def _twin_key(name):
    """Тот же ключ, что в test_data.test_no_company_twins."""
    cyr = dict(zip('абвгдеёжзийклмнопрстуфхцчшщъыьэюя',
                   ['a', 'b', 'v', 'g', 'd', 'e', 'e', 'zh', 'z', 'i', 'i', 'k', 'l', 'm', 'n', 'o',
                    'p', 'r', 's', 't', 'u', 'f', 'h', 'ts', 'ch', 'sh', 'sch', '', 'i', '', 'e', 'iu', 'ia']))
    s = re.sub(r"\b(ооо|оао|зао|пао|ао|нао|гк|пкф|тд)\b\.?", " ", str(name or "").lower())
    s = "".join(cyr.get(ch, ch) for ch in s)
    s = re.sub(r"[^a-z0-9]+", "", s)
    for a, b in (("ph", "f"), ("sch", "sh"), ("ck", "k"), ("ts", "s"), ("x", "ks"),
                 ("w", "v"), ("q", "k"), ("y", "i"), ("j", "i")):
        s = s.replace(a, b)
    s = s.replace("ch", "\x00").replace("c", "k").replace("\x00", "ch")
    return re.sub(r"(.)\1+", r"\1", s)


def _new_id(base, name):
    for n in range(1000):
        cid = 'g' + hashlib.sha1(('%s|%d' % (name, n)).encode('utf-8')).hexdigest()[:8]
        if cid not in base['companies']:
            return cid
    raise RuntimeError('не удалось выбрать id профиля')


def _blank(v):
    return v in (None, '', '—') or bool(re.match(r'^\s*(не\s+раскры|нет\s+данных|—)', str(v), re.I))


def apply(base, registry_src):
    """Меняет base на месте; возвращает (строки отчёта, новые строки реестра)."""
    sys.path.insert(0, os.path.join(ROOT, 'pipeline'))
    import fns_registry
    known_inn = {r.get('inn') for r in fns_registry.REGISTRY if r.get('inn')}
    cards = {d['id']: d for d in base['deals']}
    comps = base['companies']
    twins = {_twin_key(c.get('name')) for c in comps.values()}
    out, reg_rows, new_ids = [], [], {}
    assert len({r['id'] for r in R} | {i for i, _ in INVEST}) == len(R) + len(INVEST), 'карточка дважды'
