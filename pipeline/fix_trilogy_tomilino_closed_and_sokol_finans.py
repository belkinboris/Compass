# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g23827051 (PPF Real Estate продает 75% долей в логопарке «Трилоджи
парк Томилино» структуре Остапишиных, статус «Обсуждается» с февраля
2023 года) — сделка закрылась вскоре после анонса, и уже через год
половина актива перешла дальше.

Косвенное подтверждение закрытия — проверено лично прямым WebFetch
(CRE.ru, 17.05.2023, спустя три месяца после анонса): Алексей
Остапишин цитируется как представитель владеющей компании,
объявляющий о новом арендаторе — то есть Остапишины уже управляли
активом как собственники.

Дальнейшая перепродажа половины — проверено лично прямым WebFetch
(IBCRealEstate.ru, 07.05.2024): «"Сокол финанс" стала владельцем 50%
ООО "Томилино парк"», сумма — «"Сокол финанс" могла потратить на
приобретение доли в этом объекте 2,2-2,4 млрд руб.» (оценка, не
объявленная сторонами сумма).

Выход PPF из России — проверено лично прямым WebFetch (РИА
Недвижимость, 18.12.2023): «"Метрополис" площадью 110 тысяч квадратных
метров - последний объект чешской PPF Real Estate на российском рынке,
с его продажей компания полностью уйдет из страны» — то есть к декабрю
2023 года логопарк уже не входил в портфель PPF, что подтверждает
закрытие сделки этой карточки к тому моменту.

`status`: «Обсуждается» → «Закрыта» — дата остаётся прежней (2023-02-20,
день анонса), так как точный день закрытия источники не называют, а
менять уже указанный год не на что.

НЕ ВКЛЮЧЕНО: точная связь между «прежним держателем доли» в сделке с
«Сокол финанс» и структурой Остапишиных — источник не называет
прежнего владельца дословно; финальная сумма самой сделки PPF/
Остапишины по-прежнему нигде не раскрыта.

Запуск: python3 pipeline/fix_trilogy_tomilino_closed_and_sokol_finans.py
        python3 pipeline/fix_trilogy_tomilino_closed_and_sokol_finans.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g23827051'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Закрыта'

OLD_EXTRA = (
    'Продажа 75% долей в логопарке «Трилоджи парк Томилино» (107 000 '
    'кв.м) в Подмосковье. Покупатель — структура братьев Алексея и '
    'Александра Остапишиных, которые являются совладельцами и '
    'строителями комплекса. Сумма сделки не раскрыта, объект '
    'оценивается в 6,2–7,5 млрд руб.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Сделка закрылась вскоре после анонса — уже в мае 2023 года '
    'Алексей Остапишин публично выступал как представитель владеющей '
    'компании. В мае 2024 года половина актива перешла дальше:'
    ' «Сокол финанс» стала владельцем 50% ООО «Томилино парк» '
    '(оценочно за 2,2-2,4 млрд руб.). PPF Real Estate к декабрю 2023 '
    'года полностью вышла из России, продав последний актив в стране.'
)

NEW_SRC = [
    ['CRE.ru', 'https://cre.ru/news/90918'],
    ['IBC Real Estate', 'https://ibcrealestate.ru/news/trilodzhi-park-tomilino-podelili-popolam/'],
    ['РИА Недвижимость', 'https://realty.ria.ru/20231218/ppf-1916403264.html'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS
    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== status: станет ===')
    print(NEW_STATUS)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['status'] = NEW_STATUS
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
