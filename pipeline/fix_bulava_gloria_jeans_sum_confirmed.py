# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g39527843
(Компания «Булава» приобрела четыре швейные фабрики «Глория Джинс») —
`extra` карточки утверждал «Сумма этой части сделки не раскрыта», хотя
top-level `sum` уже нёс конкретную цифру («191,7 млн ₽») — рассогласование
между двумя полями одной карточки.

Проверено лично прямым WebFetch (kommersant.ru/doc/7737066, 21.05.2025,
10:55): «четыре чеха в Звереве, Усть-Донецке, Красном Сулине и Гуково за
191,7 млн рублей» — это ЦЕНА ИМЕННО ЭТИХ ЧЕТЫРЁХ ФАБРИК «Булавы», а не
ошибка и не сумма по другой части сделки. Та же статья также называет
сумму другой сделки в рамках распродажи (для контекста, не для этой
карточки): «АО "БТК групп", которая купила фабрику... в Кабардино-
Балкарии за 200 млн руб.» — эта фабрика к «Булаве» отношения не имеет,
не добавляется в её карточку.

`extra` переписан: убрано устаревшее «сумма не раскрыта», добавлена
атрибуция цифры и уточнение, что «Булава» — не единственный покупатель
в общей распродаже семи фабрик.

НЕ ВКЛЮЧЕНО: судьба остальных площадок «Глория Джинс» (Шахты,
Новошахтинск, Миллерово) — отдельный, более поздний и не завершённый
сюжет (поиск арендатора/покупателя продолжается по данным 161.ru,
июнь 2026), не относится к сделке «Булавы» и не эта карточка. Смена
профиля производства («переориентация на военную и специальную одежду»,
The Moscow Times, апрель 2026) — источник не уточняет, относится ли это
именно к ростовским площадкам «Булавы» или к другим активам концерна
«Калашников»; неоднозначный факт не внесён, чтобы не приписать
конкретным фабрикам то, что могло произойти на других.

Запуск: python3 pipeline/fix_bulava_gloria_jeans_sum_confirmed.py
        python3 pipeline/fix_bulava_gloria_jeans_sum_confirmed.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g39527843'

OLD_EXTRA = (
    'Компания «Булава» (аффилирована с концерном «Калашников») '
    'приобрела четыре швейные фабрики «Глория Джинс» в городах '
    'Ростовской области (Гуково, Зверево, Красном Сулине и поселке '
    'Усть-Донецком). Это часть более крупного пакета из 7 швейных '
    'производств, проданных в конце прошлого года — начале текущего '
    'года. Сумма этой части сделки не раскрыта; общая выручка от '
    'продажи 7 фабрик — 398 млн рублей.'
)
NEW_EXTRA = (
    'Компания «Булава» (аффилирована с концерном «Калашников») '
    'приобрела четыре швейные фабрики «Глория Джинс» в городах '
    'Ростовской области (Гуково, Зверево, Красном Сулине и поселке '
    'Усть-Донецком) за 191,7 млн рублей. Это часть более крупного '
    'пакета из 7 швейных производств, проданных в конце прошлого года — '
    'начале текущего года; остальные покупатели, включая АО «БТК '
    'групп» (фабрика в Кабардино-Балкарии за 200 млн руб.), к «Булаве» '
    'отношения не имеют.'
)

NEW_SRC_KOMMERSANT = ['Коммерсантъ', 'https://www.kommersant.ru/doc/7737066']


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + [NEW_SRC_KOMMERSANT]

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    print(NEW_SRC_KOMMERSANT)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
