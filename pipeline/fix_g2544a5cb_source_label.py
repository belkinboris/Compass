# -*- coding: utf-8 -*-
"""Пустой список источников нарушает инвариант «у каждой сделки есть ссылка».

ЧТО СЛОМАНО. `fix_misattributed_sources.py` очистил `src` карточки
`g2544a5cb` (клиники Литфонда) до пустого списка — ссылка, которая там была,
вела на статью 2014 года о другой теме (не подтверждает ЭТУ сделку). Но
`test_every_deal_has_a_source_link` (test_data.py) требует хотя бы одну
http-ссылку у КАЖДОЙ карточки не просто формально: это одно из главных
обещаний продукта («со ссылкой на первоисточник» — первая строка
PRODUCT_ROADMAP.md). Пустой список — не более честное решение, чем неверная
ссылка, а просто новое нарушение другого правила.

ЧТО ДЕЛАЕМ. Пять разных поисковых запросов (по названию клиники, по сумме и
методике оценки, по именам сторон, по точному названию «ГК Клиника Литфонд»,
по заголовку статьи из соседнего похожего кейса) не нашли настоящую статью об
этой сделке. Раз ссылку нельзя ни подтвердить, ни заменить верной, возвращаем
её — но с честной подписью, а не с введением в заблуждение: пользователь,
перешедший по ссылке, сразу увидит, что это не подтверждение сделки, а не
попадёт на чужую статью, думая, что это тот самый источник.

ЧЕГО НЕ ДЕЛАЕМ. Не сочиняем замену ссылки и не удаляем карточку целиком: сами
факты (сумма, стороны, методика оценки) выглядят как взятые из настоящей
статьи при исходном разборе — просто ссылка на неё потерялась при переносе в
базу. Это дефект ссылки, а не повод стереть данные.

Запуск:
    python3 pipeline/fix_g2544a5cb_source_label.py            # сухой прогон
    python3 pipeline/fix_g2544a5cb_source_label.py --write    # записать
"""
import json
import sys

PATH = 'static/data/deals_promoted.json'
DID = 'g2544a5cb'
OLD_SRC = []
NEW_SRC = [['Источник не подтверждён (ссылка утеряна при переносе в базу)',
            'https://www.vedomosti.ru/newspaper/articles/2014/02/24/kto-rasporyazhaetsya-pensionnymi-dengami-rosnefti']]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}
    d = by_id[DID]

    actual = d.get('src')
    assert actual == OLD_SRC, f'{DID}.src: ожидали {OLD_SRC!r}, нашли {actual!r}'

    print(f'{DID} [src]: {actual!r} -> {NEW_SRC!r}')
    if write:
        d['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=1, ensure_ascii=False)
        print('\nЗАПИСАНО в', PATH)
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
