# -*- coding: utf-8 -*-
"""Месячная очередь, 8 сентября 2026 — карточка `c2c719a9a` («АО
«Калашников» назначена управляющей компанией АО «ЛОМО»», 14 мая 2024)
стояла без `status` вовсе.

Личный WebFetch источника (kommersant.ru/doc/6692847) подтвердил
дословно: «Петербургское предприятие АО «ЛОМО» перешло под контроль
ижевского [концерна]... все управленческие и распорядительные действия
по вопросам финансово-хозяйственной деятельности с 14 мая находятся в
распоряжении ижевского концерна» — событие карточки (14 мая 2024) не
сам указ (он подписан на 14 месяцев раньше, 03.03.2023), а дата
РЕАЛЬНОГО вступления в управление. Слово «перешл[о]» входит в список
`STATUS_WORDS['Закрыта']` — событие, которое карточка описывает,
состоялось на указанную дату.

Важная оговорка, уже верно зафиксированная в `law.struct` карточки: это
НЕ продажа и не национализация — акционеры формально сохраняют право
собственности, приостановлены только их полномочия («речи о какой-либо
сделке между акционерами и концерном не идет»). `status: "Закрыта"`
здесь означает «событие карточки — установление временного управления —
состоялось», а не «актив продан»; уточнение уже стоит в `law.struct` и
не дублируется.

Дельта-поиск (WebSearch) не нашёл ни продажи, ни возврата акционерам, ни
национализации в доход государства за прошедшие два года — управление
продолжается: в июне 2026 года гендиректор «Калашникова» подписал с
правительством Петербурга соглашение о создании промышленного кластера
на площадке ЛОМО (dp.ru, 04.06.2026, не проверено личным WebFetch — не
меняет статус карточки, только подтверждает, что управление действует).

Запуск:
    python3 pipeline/fix_lomo_kalashnikov_status.py            # сухой прогон
    python3 pipeline/fix_lomo_kalashnikov_status.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'
CARD_ID = 'c2c719a9a'


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}
    card = by_id[CARD_ID]

    assert card.get('status') is None, 'status уже занят: %r' % (card.get('status'),)

    print('status None -> "Закрыта" (установление временного управления, '
          'не продажа — уточнение уже в law.struct)')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    card['status'] = 'Закрыта'

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
