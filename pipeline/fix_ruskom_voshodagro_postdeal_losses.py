"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
`ga8cb5cab` («Сибирский агрохолдинг «Руском» приобрел сельхозпредприятие
«Восходагро» в Тюменской области», закрыта 10.04.2023) — сама сделка
уже была тщательно прочитана и заполнена (стороны, оценка суммы,
финансы предмета на 2022 год); дочитывание месячного уровня нашло
только один новый, безопасный, аддитивный факт — судьбу предприятия
ПОСЛЕ сделки.

Проверено лично прямым WebFetch (два независимых агрегатора реестровых
данных, НЕ пресса — цифры выручки у них расходятся, но чистый
убыток/год совпадает почти точно):
- vbankcenter.ru, https://vbankcenter.ru/contragent/1157232013828:
  «Чистая прибыль, ₽ -21,15млн (2025 г)»; из динамики выводится
  2024 год — убыток около -17,15 млн ₽.
- saby.ru, https://saby.ru/contragents/7205027856/720501001: чистая
  прибыль 2023 — -23,2 млн ₽, 2024 — -17,2 млн ₽, 2025 — -21,2 млн ₽.

Предприятие, прибыльное в 2022 году (43,5 млн ₽ чистой прибыли — уже
в `eco.target_fin`), устойчиво убыточно все три года после смены
собственника. Точная выручка по годам не вносится — агрегаторы
расходятся (202,5/80,5 млн ₽ против 80,46 млн ₽ за 2025 год и т. д.),
а убыток у обоих совпадает почти дословно.

НЕ ВНЕСЕНО: судебные споры компании с администрацией Абатского
муниципального района (vbankcenter.ru называет 22 дела) — все датированы
сентябрём-октябрём 2022 года, то есть ДО этой сделки (10.04.2023) и,
похоже, относятся к периоду прежних владельцев, не к «Рускому»; не
связаны с этой сделкой напрямую. Отдельная, не относящаяся к этой
карточке находка — Группа «Руском» в декабре 2024 года продала СОВСЕМ
ДРУГОЙ актив (птицефабрику в Голышманово, другое юрлицо, другой
сектор — птицеводство, а не зерно/молоко) группе «Черкизово» —
записано отдельно в CLAUDE.md, «Известные проблемы», как кандидат на
новую карточку для притока.

Запуск: python3 pipeline/fix_ruskom_voshodagro_postdeal_losses.py
        python3 pipeline/fix_ruskom_voshodagro_postdeal_losses.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'ga8cb5cab'

OLD_ECO_CONTEXT = (
    'Группа «Руском» объединяет сельскохозяйственные предприятия в '
    'Омской, Тюменской областях и Алтайском крае. В нее, в частности, '
    'входят «Морозовская птицефабрика», компании «Рус\xadком-агро», '
    '«Сибирские колбасы», «Алтайские колбасы» и др.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' По данным реестровых агрегаторов (не прессы),'
    ' после смены собственника предприятие устойчиво убыточно: чистый'
    ' убыток составил около 23,2 млн ₽ в 2023 году, 17,2 млн ₽ в 2024'
    ' году и 21,2 млн ₽ в 2025 году — против 43,5 млн ₽ чистой прибыли'
    ' в 2022 году, последнем полном году при прежних владельцах.'
)

NEW_SRC = [
    ['vbankcenter.ru', 'https://vbankcenter.ru/contragent/1157232013828'],
    ['saby.ru', 'https://saby.ru/contragents/7205027856/720501001'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    existing_urls = {s[1] for s in deal['src']}
    add_src = [s for s in NEW_SRC if s[1] not in existing_urls]
    new_src = deal['src'] + add_src

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    if add_src:
        print('\n=== src: добавится ===')
        for s in add_src:
            print(s)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
