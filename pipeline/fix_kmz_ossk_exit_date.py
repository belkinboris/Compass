# -*- coding: utf-8 -*-
"""Карточка gd6b3c796 («ОСК вышла из капитала КМЗ, вернув актив семье
основателя Даниленко») несла 2025 год вместо 2026.

ЧТО СЛОМАНО. Поле `date` стояло «2025-01-16». Единственный источник карточки
— fontanka.ru, и сам адрес статьи содержит дату публикации в URL:
«/2026/01/14/76215445/». Текст статьи это подтверждает без всякой
двусмысленности: «Представители ОСК и Кингисеппского машиностроительного
завода 14 января заявили о прекращении сотрудничества» — с явным указанием
года публикации «14 января 2026, 17:51» в шапке материала, и далее «Согласно
сведениям из ЕГРЮЛ, в начале 2026 года действительно произошли изменения в
составе участников единственного владельца КМЗ». Заголовок карточки
(«вышла», прошедшее время) описывает именно этот выход, а не более раннюю
покупку («купленные летом 2025 года» — там же, в тексте статьи, но это уже
другое событие, не то, что несёт заголовок карточки).

ПОЧЕМУ НЕ ЧЕРЕЗ `review.py`. `date_is_supported()` намеренно запрещает
менять год — перенос года обязан быть отдельным, явным решением с
проверяемым источником (см. урок CLAUDE.md про g6d73538c / «Основа»/
промзона «Свиблово»), а не автоматической правкой в общей таблице.

ПОЧЕМУ ПОЛНАЯ ДАТА. Источник называет не только год, но и точный день и
месяц («14 января»), подтверждённый датой публикации самой статьи —
ничего не приходится досочинять.

Запуск:
    python3 pipeline/fix_kmz_ossk_exit_date.py            # сухой прогон
    python3 pipeline/fix_kmz_ossk_exit_date.py --write    # записать
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'
DEAL_ID = 'gd6b3c796'
OLD_DATE = '2025-01-16'
NEW_DATE = '2026-01-14'
QUOTE = ('Представители ОСК и Кингисеппского машиностроительного завода '
         '14 января заявили о прекращении сотрудничества — статья '
         'fontanka.ru датирована «14 января 2026, 17:51», адрес статьи '
         'содержит «/2026/01/14/»')


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}
    deal = by_id.get(DEAL_ID)
    assert deal is not None, 'нет сделки %s' % DEAL_ID
    assert deal.get('date') == OLD_DATE, \
        'дата уже другая: %r, ожидали %r' % (deal.get('date'), OLD_DATE)

    print('%s: date %r -> %r' % (DEAL_ID, OLD_DATE, NEW_DATE))
    print('  цитата: %r' % QUOTE)

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    deal['date'] = NEW_DATE
    assert deal['date'] == NEW_DATE, 'дата не записалась'

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
