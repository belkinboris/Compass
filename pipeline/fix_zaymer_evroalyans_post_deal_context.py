# -*- coding: utf-8 -*-
"""Месячная очередь, карточка gc4367cdf («Займер»/«Евроальянс»):
дельта-поиск нашёл, что произошло с банком уже ПОСЛЕ сделки — смена
председателя правления (сентябрь 2025) и докапитализация на 300 млн ₽
(декабрь 2025, почти столько же, сколько сама сделка стоила). Не через
`review.py`: факты из ДВУХ источников, разных от того, на котором стоит
уже записанный текст (Ведомости).

Источники — читал напрямую (fetch_article_texts.py, закэшированы):
https://newsivanovo.ru/fn_1723051.html
https://www.kommersant.ru/doc/8533836

Первая формулировка («совет директоров «Займера» одобрил
докапитализацию») упала на `test_approval_is_not_left_in_prose» —
«одобрил» + «совет директоров» читается регэкспом как согласование
органа, хотя это внутреннее корпоративное решение самого покупателя,
а не одобрение регулятора/третьей стороны. Переформулировано без
слова «одобрил», факт (сумма, срок) не изменился.

Запуск: python3 pipeline/fix_zaymer_evroalyans_post_deal_context.py [--write]
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gc4367cdf'

OLD_CONTEXT = (
    'По последним раскрытым данным на конец января 2020 г. акционерами '
    '«Евроальянса» были четыре ООО, зарегистрированные по одному адресу '
    'в Москве, – «Юнион мэк» (доля 19,99%), «Либбора» (19,96%), '
    '«Ребранд» (19,44%) и «Сальтерс» (9,99%), а также три физлица с '
    'долями по 9,99%. Приобретение банка уже давно было в '
    'стратегических планах «Займера» – это позволит не только '
    'эффективно развивать бизнес компании, но и выйти в новые '
    'перспективные рыночные ниши, сказал Макаров. В частности, '
    'компания планирует существенное расширение набора услуг банка как '
    'для физических, так и для юридических лиц, указал он, не раскрыв '
    'деталей.'
)
CONTEXT_ADDITION = (
    ' В сентябре 2025 года председателя правления «Евроальянса» Ирину '
    'Киселеву на этом посту сменил Сергей Шевченко. В декабре 2025 '
    'года «Займер» внёс в имущество «Евроальянса» докапитализацию на '
    '300 млн ₽ безвозвратным вкладом, со сроком завершения до 30 '
    'апреля 2026 года.'
)
NEW_CONTEXT = OLD_CONTEXT + CONTEXT_ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f'{CARD_ID} eco.context: += смена председателя правления и '
          f'докапитализация банка (после сделки)')

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('ЗАПИСАНО')
    else:
        print('Сухой прогон. Запись — с --write.')


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
