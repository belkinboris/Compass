import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g5f4bbb4f'

OLD_SUM = '1–1,2 млрд ₽'
NEW_SUM = None

OLD_CONTEXT = (
    'С 2021 года элеватор принадлежал Агропромышленному холдингу '
    '«Грейнрус» через ООО «Грейнрус Трейд».'
)
CONTEXT_ADDITION = (
    ' Сделка была частью более крупного пакета: «в результате сделок '
    'купли-продажи с «Грейнрусом» «Ресурс» получил более 220 объектов, '
    'среди которых был элеваторный комплекс общей площадью порядка '
    '103 200 кв. метров и две железнодорожные ветки длиной 500 метров» '
    '(Ведомости). В апреле 2026 года кредитор («Каргис») заявил о '
    'намерении добиваться банкротства покупателя, РЗК «Ресурс»: компания '
    'раскрыла убытки «1,3 млрд руб., 5,6 млрд руб. и 5,9 млрд руб.» за '
    '2023-2025 годы и падение оборота вдвое, «до 6,6 млрд руб.» в 2025-м — '
    'речь о финансах покупателя в целом, а не о результатах именно этого '
    'элеватора (Город N).'
)
NEW_CONTEXT = OLD_CONTEXT + CONTEXT_ADDITION

OLD_TARGET_FIN = (
    'В 2023 году элеватор принял на хранение и подработку 79,5 тыс. тонн '
    'сельхозпродукции, в том числе 65,7 тыс. тонн пшеницы и подсолнечника.'
)
TARGET_FIN_ADDITION = (
    ' За 9 месяцев 2024 года элеватор снизил выручку на 20% и чистую '
    'прибыль в 2,2 раза — до 13,3 млн руб. (Oleoscope).'
)
NEW_TARGET_FIN = OLD_TARGET_FIN + TARGET_FIN_ADDITION

NEW_SRC = [
    ['Ведомости', 'https://www.vedomosti.ru/business/articles/2025/04/30/1107892-gap-usilila-prisutstvie'],
    ['Oleoscope', 'https://oleoscope.com/news/rostovskaya-zernovaya-kompaniya-vykupit-akcii/'],
    ['Город N', 'https://gorodn.ru/online_news/kreditor_zayavil_o_namerenii_bankrotit_rostovskuyu_zernovuyu_kompaniyu_resurs/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['sum'] == OLD_SUM
    assert deal['eco']['sum'] == OLD_SUM
    assert deal['eco']['context'] == OLD_CONTEXT
    assert deal['eco']['target_fin'] == OLD_TARGET_FIN
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== sum/eco.sum: было', repr(OLD_SUM), '-> станет', repr(NEW_SUM), '(снято как неподтверждённое) ===')
    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('=== eco.target_fin: станет ===')
    print(NEW_TARGET_FIN)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['sum'] = NEW_SUM
        deal['eco']['sum'] = NEW_SUM
        deal['eco']['context'] = NEW_CONTEXT
        deal['eco']['target_fin'] = NEW_TARGET_FIN
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
