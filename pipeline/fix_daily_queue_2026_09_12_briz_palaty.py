# -*- coding: utf-8 -*-
"""Дневная очередь качества, 12 сентября 2026 — карточка `gce803e3f`
(«Дом.РФ» продал на торгах палаты Кожевенной слободы XVII века). Полный
обыск саб-агентом: стартовая цена лота (67,4 млн ₽ против итоговых
100,5 млн ₽) и связь покупателя «Бриз» с девелопером «Крост» УЖЕ стояли в
`events[0].note`, но не были видны в структурных полях; добавлена
историческая справка о здании, которой не было нигде.

НЕ ВНЕСЕНО (проверено, не нашлось): число участников торгов — ни в одном
из 8+ источников; точный ИНН покупателя «Бриз» — под этим именем в ЕГРЮЛ
множество не связанных друг с другом юрлиц-омонимов (Москва, СПб,
регионы), ни одно явно не подтверждается как структура «Кроста» — вносить
конкретный ИНН значило бы рискнуть чужим юрлицом (уже зафиксировано в
`accepted_notes`, повторной проверки это не изменило); происхождение права
собственности «Дом.РФ» на палаты — ни один источник не объясняет, как
здание попало к госкорпорации.

eco.context (расширено): историческая справка по mskagency.ru/materials/
3560471 — «Палаты являются наиболее старинной сохранившейся постройкой
Кожевенной слободы» допетровской эпохи; первый этаж изначально использовался
для хранения товаров и администрирования торговли, после петровских реформ
здание стало городской таможней; с 1983 до конца 2010-х там располагалась
редакция журнала «Знание — сила».

law.terms (было «—»): по тому же материалу (mskagency.ru/materials/3565755)
покупатель обязан провести работы по сохранению объекта культурного
наследия и содержать его согласно требованиям закона об охране памятников.

Запуск:
    python3 pipeline/fix_daily_queue_2026_09_12_briz_palaty.py            # сухой прогон
    python3 pipeline/fix_daily_queue_2026_09_12_briz_palaty.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_ECO_CONTEXT = (
    'Памятник архитектуры можно приспособить под ресторан, офис или другое '
    'коммерческое использование. В лот входит аренда земельного участка '
    '0,18 гектара.'
)

NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' Палаты — старейшая сохранившаяся постройка '
    'Кожевенной слободы: изначально здание использовалось для хранения '
    'товаров и администрирования торговли, после петровских реформ стало '
    'городской таможней, а с 1983 до конца 2010-х годов в нём размещалась '
    'редакция журнала «Знание — сила».'
)

NEW_LAW_TERMS = (
    'Покупатель обязан провести работы по сохранению объекта культурного '
    'наследия и содержать его согласно требованиям закона об охране '
    'памятников.'
)

NEW_SRC = [
    ['Агентство «Москва»', 'https://www.mskagency.ru/materials/3560471'],
    ['Агентство «Москва»', 'https://www.mskagency.ru/materials/3565755'],
]


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}
    d = by_id['gce803e3f']

    assert d['eco']['context'] == OLD_ECO_CONTEXT, 'eco.context уже другое: %r' % (d['eco']['context'],)
    assert d['law']['terms'] == '—', 'law.terms уже занято: %r' % (d['law']['terms'],)
    urls = {s[1] for s in d['src']}
    for name, url in NEW_SRC:
        assert url not in urls, 'источник уже добавлен: %s' % url

    print('gce803e3f: расширяю eco.context (историческая справка о здании), '
          'заполняю law.terms (обязанность сохранения памятника), '
          'добавляю 2 источника (Агентство «Москва»)')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['eco']['context'] = NEW_ECO_CONTEXT
    d['law']['terms'] = NEW_LAW_TERMS
    d['src'].extend(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
