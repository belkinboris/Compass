# -*- coding: utf-8 -*-
"""Приток, 11:20 МСК 29 сентября 2026: Право.ру сообщило, что аукцион ПСБ
по продаже четырёх изъятых у Алексея Боброва агрокомпаний («Ударник»,
«Агро-Клевер», «Петелино», «Земля Сажинская», начальная цена 571,2 млн ₽)
не состоялся — заявок не поступило (данные ГИС «Торги»). Ворота не
пропустили черновик как новую сделку («заполнено: sum, ind» — ни
покупатель, ни продавец не разобраны автоматически из заголовка), и в
базе такой карточки ещё не было (проверил по именам «Бобров»,
«Облкоммунэнерго», по всем четырём агрокомпаниям — нет совпадений).
Собрал отдельной карточкой вручную, тот же класс случая, что Клячин/
Еврострой/Смыслов 28 сентября: данные надёжны, но механика притока не
довела их до пишущего скрипта.

Актив — часть крупного дела о национализации: в 2025 году Ленинский
райсуд Екатеринбурга по иску Генпрокуратуры взыскал в доход государства
свыше 80 компаний, включая «Корпорацию СТС», «Сибирско-Уральскую
энергетическую компанию» и саму «Агро-Клевер» (дело № 2-5756/2025) — тема
уже отслеживается в базе (59 карточек с темой «Национализация / иск
Генпрокуратуры»), это очередной эпизод той же истории, не первое
упоминание Боброва. По версии следствия Бобров и его соответчик Артём
Биков получили активы, пользуясь неформальными связями с руководством
федеральных и региональных госструктур — прямая цитата из источника,
перенесена в law.struct без пересказа.

Статус «Не состоялась» — тип сделки решает, что написано в карточке
(`review.STATUS_WORDS`), но точных слов из словаря («не состоял»,
«отказал» и т.п.) в источнике нет — есть «провалился», «желающих
поучаствовать в торгах не нашлось». Ставлю статус вручную (как поле
данных, не через review.py --write), значение верно по существу.

Источник единственный (Право.ру) — честно указано в eco.context.

Урок того же часа (карточка `gafde5488`, тот же прогон): поле `sum` держат
голым числом, без слов вроде «начальная цена» — на мобильной ширине
`.deal-meta` это flex-строка «сумма + метка отрасли», и слово `начальн`
включает `_AUCTION_START` в `deal_multiples.py`, из-за чего к сумме
приписывается «(стартовая цена торгов)» и строка выбивается из общего
ряда карточек в ленте (`test_ui.py::test_feed_card_without_sum_keeps_
industry_tag_aligned`). Метка появляется сама по типу/статусу, писать её
в `sum` не нужно. Ещё одна ловушка: `facts_derive.py --write` обязателен
после ЛЮБОЙ правки поля `sum` — клиент читает не текст, а закэшированное
`facts.price.meaning`, и без пересчёта тест видит старое значение.

Запуск: python3 pipeline/fix_add_bobrov_agro_auction_failed_card.py [--write]
"""
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'ingest'))

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')


def main(write=False):
    import promote

    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    ids = {c['id'] for c in data['deals']}
    new_id = promote.new_id(ids)

    draft = {
        'date': '2026-09-29',
        'title': 'Аукцион по продаже изъятого у Алексея Боброва агробизнеса не состоялся',
        'ind': 'Агро',
        'type': 'Продажа с торгов',
        'status': 'Не состоялась',
        'sum': '571,2 млн ₽',
        'seller': 'ПСБ (от имени государства)',
        'asset': '100% акций в четырёх компаниях — «Ударник», «Агро-Клевер», «Петелино», «Земля Сажинская»',
        'src': [['Право.ру', 'https://pravo.ru/news/266020/']],
        'events': [
            {'kind': 'cancelled', 'date': '2026-09-29', 'title': 'Аукцион признан несостоявшимся',
             'note': 'Аукцион по продаже принадлежавших ранее бизнесмену Алексею Боброву '
                     'сельскохозяйственных компаний провалился из-за отсутствия заявок, '
                     'следует из данных ГИС «Торги».',
             'source': ['Право.ру', 'https://pravo.ru/news/266020/']},
        ],
    }
    card = promote.to_card(draft, new_id)
    # `to_card` не зеркалит `sum` в `eco.sum` сама (см. баг, найденный и
    # починенный в `pipeline/ingest/enrich.py` 28 сентября — тот же класс,
    # для прямой сборки карточки чинится тут же руками).
    card['eco']['sum'] = draft['sum']
    card['eco']['context'] = (
        'Пока единственный источник — Право.ру. ПСБ пытался реализовать 100% акций в '
        'четырёх структурах с начальной ценой 571,2 млн ₽. Заявки принимали с 21 по '
        '25 сентября, подведение итогов было запланировано на 29 сентября — желающих '
        'не нашлось.'
    )
    card['law']['struct'] = (
        'В 2025 году Ленинский райсуд Екатеринбурга по иску Генпрокуратуры конфисковал '
        'крупнейшее в Свердловской области предприятие коммунальной энергетики '
        '«Облкоммунэнерго» (дело № 2-5756/2025). По этому иску в доход государства '
        'взыскали более 80 компаний, включая «Корпорацию СТС», «Сибирско-Уральскую '
        'энергетическую компанию», «Агро-Клевер» и другие. По версии следствия, Бобров '
        'и его соответчик — бизнесмен Артём Биков — получили спорные активы незаконно, '
        'пользуясь неформальными связями с руководством федеральных и региональных '
        'госструктур.'
    )
    card['themes'] = ['Национализация / иск Генпрокуратуры', 'Продажа с торгов']
    # `to_card` не ставит `added` — обычно его ставит `approve.py` при выводе
    # карточки из pending.json; прямая запись минует этот путь, дата не
    # выдумана — карточка правда добавлена сегодня.
    card['added'] = '2026-09-29'

    data['deals'].append(card)
    print('Добавлена карточка %s: %s' % (new_id, card['title']))

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
