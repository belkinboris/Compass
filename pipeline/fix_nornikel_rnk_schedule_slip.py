# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g97e55758 (Норникель приобрел долю в проекте РНК по производству
нержавеющей стали, 18.12.2023, статус «Закрыта») — график стройки
сдвинулся, но проект не остановлен.

Проверено лично прямым WebFetch (volpromex.ru, 08.07.2026): «Запуск
двух цехов [холодного и горячего проката] запланирован на вторую
половину 2026 года» (было — холодная прокатка отдельно в IV квартале
2025), «Выплавку стали и производство собственных нержавеющих слябов
компания намерена начать в первой половине 2027 года», «Выход всего
комплекса на проектную мощность ожидается в четвертом квартале 2027
года».

НЕ ВКЛЮЧЕНО: изменение доли «Норникеля» — ни один источник 2024-2026
годов не упоминает изменение состава участников (по-прежнему 50/50 с
Волжским трубным заводом); более широкая диверсификация «Норникеля»
(палладиевые технологии в Мончегорске) — не связана с этим проектом
напрямую.

Запуск: python3 pipeline/fix_nornikel_rnk_schedule_slip.py
        python3 pipeline/fix_nornikel_rnk_schedule_slip.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g97e55758'

OLD_EXTRA = (
    'Норникель приобрел долю в ООО «РНК-Холдинг», холдинговой '
    'компании «Русской нержавеющей компании». РНК строит '
    'производственный комплекс в Волжском Волгоградской области '
    'мощностью до 500 000 т готовой продукции в год с запуском цехов '
    'холодной прокатки (2025), горячей прокатки (2026) и '
    'электросталеплавильного цеха (2027). Участие соответствует целям '
    'компании по наращиванию доли внутреннего потребления металлов '
    'Норникеля.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' График сдвинулся: к июлю 2026 года запуск цехов холодной и '
    'горячей прокатки объединён и перенесён на вторую половину 2026 '
    'года, выплавку стали и производство слябов планируется начать в '
    'первой половине 2027 года, а выход всего комплекса на проектную '
    'мощность — в IV квартале 2027 года. Строительство продолжается, '
    'проект не остановлен.'
)

NEW_SRC = [
    ['volpromex.ru', 'https://volpromex.ru/proizvodstvo/metalurgija/rnk-namerena-snizit-zavisimost-rossijskogo-rynka-nerzhavejushhego-prokata-ot-importa.html'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
