import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g37f106cd'

OLD_ECO_CONTEXT = (
    'Раньше Бобров был основным владельцем группы «Балтийский берег». '
    'Кроме одноимённой компании в неё входило предприятие «Русский '
    'лосось», управлявшее рыбоводными хозяйствами в Мурманской области. '
    'В 2015 году группа столкнулась с подорожанием валютных кредитов и '
    'массовой гибелью рыбы, из-за чего получила убыток 1,5 млрд ₽. '
    'Структуры «Балтийского берега» инициировали собственное '
    'банкротство, после чего контроль над «Балтийским берегом» и '
    '«Русским лососем» перешёл к Сбербанку, выкупившему их долги. В '
    '2022 году Бобров вместе с партнёрами вернул себе «Русского '
    'лосося», выкупив предприятие у Сбербанка.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' К 2025 году группа реорганизована в холдинг '
    '«Марэкс»: компания готовит pre-IPO — акции новой эмиссии объёмом '
    'до 15% увеличенного капитала должны привлечь до 4,5 млрд ₽, '
    'полноценное IPO намечено на 2026 год. Выручка за 2024 год — '
    '19 млрд ₽, EBITDA — 1,4 млрд ₽. Средства планируется направить в '
    'том числе на новое производство в Санкт-Петербурге, которое '
    'позволит вдвое увеличить объём выпуска.'
)

OLD_SRC = [['Коммерсантъ', 'https://www.kommersant.ru/amp/5941195']]
NEW_SRC = OLD_SRC + [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/7532986'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
