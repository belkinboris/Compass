# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
`gbf1e6917` («Глеб Фетисов приобретает картофельные хозяйства
(Аксентис, Пуцко, МАПС)», февраль 2023, «Обсуждается») — по крайней
мере часть заявленной сделки не состоялась: «Аксентис» позже купил
СОВСЕМ ДРУГОЙ покупатель.

Проверено ЛИЧНО прямым WebFetch (дословные цитаты):
- kommersant.ru/doc/7232873 (более поздняя статья о реальной продаже
  «Аксентиса»): «Хотя регулятор согласовал сделку, она не состоялась,
  так как стороны не сошлись в цене» — про заявку АПК Фетисова 2023
  года; реальным покупателем стала структура «Агроинвестпроект» Сергея
  Хаванова, владельца агрохолдинга АТМ — приобретено «75% ООО
  "Аксентис"» за «предположительно 1–1,3 млрд рублей» (полная оценка
  бизнеса — 1,8–2,2 млрд ₽ с учётом долга); выручка «Аксентиса» за 2023
  год — 834 млн ₽, чистая прибыль — 119 млн ₽;
- kommersant.ru/doc/5797756 (УЖЕ был в `src`, использован при первой
  записи только для факта о ходатайстве в ФАС): ходатайства поданы
  ровно на ДВЕ компании — «ООО «Аксентис» и ООО «Фермерское хозяйство
  Пуцко»» (не на три — «МАПС» упомянут отдельно как актив, которым эти
  двое совместно владеют, не как прямая цель ходатайства).

НЕ ВНЕСЕНО и оставлено на решение человека: судьба «Фермерского
хозяйства Пуцко» — ни один проверенный источник не сообщает, состоялась
ли покупка этой части пакета Фетисовым отдельно от «Аксентиса»; раз
сделка была одним пакетным ходатайством в ФАС, а «Аксентис» точно ушёл
другому покупателю, возможно (но не подтверждено), что весь пакет
сорвался целиком. `status`/`buyer`/`title` карточки НЕ тронуты — вопрос
вынесен в «Известные проблемы» CLAUDE.md.

Запуск: python3 pipeline/fix_fetisov_aksentis_deal_fell_through.py
        python3 pipeline/fix_fetisov_aksentis_deal_fell_through.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gbf1e6917'

OLD_ECO_CONTEXT = '—'
NEW_ECO_CONTEXT = (
    'Как минимум часть пакета не состоялась: по данным более поздней '
    'публикации, ФАС согласовала заявку структуры Фетисова, но '
    '«сделка не состоялась, так как стороны не сошлись в цене». '
    '«Аксентис» позже купила другая структура — «Агроинвестпроект» '
    'Сергея Хаванова (владельца агрохолдинга АТМ), приобретя 75% за '
    'предположительно 1–1,3 млрд ₽ (вся компания оценена в 1,8–2,2 млрд '
    '₽ с учётом долга); выручка «Аксентиса» за 2023 год — 834 млн ₽, '
    'чистая прибыль — 119 млн ₽. Судьба второй части пакета — '
    '«Фермерского хозяйства Пуцко» — по проверенным источникам '
    'неизвестна.'
)

OLD_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/5797756'],
]
NEW_SRC = OLD_SRC + [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/7232873'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
