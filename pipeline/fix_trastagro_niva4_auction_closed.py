# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g5f0d5d18
(«Банк «Траст» выставил на продажу земельный актив «Трастагро-нива 4»»,
статус «Обсуждается») — тот же класс дефекта, что уже дважды находили в
этой рутине (Харьяга, Северная заря): источник карточки описывает только
ВЫСТАВЛЕНИЕ на аукцион (июнь 2023, стартовая цена 1,4 млрд ₽), а не его
исход. Здесь, в отличие от тех двух случаев, реальный исход НАЙДЕН и
подтверждён независимо реестром.

Проверено лично прямым WebFetch (Коммерсантъ,
https://www.kommersant.ru/doc/7432621): «19 декабря 2024 года... Лот
включал в себя 48 тыс. га земли при начальной стоимости более 1 млрд
руб. Единственную заявку подало АО «Рест», возглавляемое Русланом
Беретарём»; торги формально «признаны несостоявшимися из-за получения
лишь одной заявки», но по закону о торгах это не отменяет продажу
единственному заявителю по стартовой цене.

Проверено лично прямым WebFetch (audit-it.ru,
https://www.audit-it.ru/contragent/1216400010661_ooo-trastagro-niva-4):
«АО "РЕСТ" (г. Москва)» — учредитель ООО «ТрастАгро-Нива 4» с датой
записи «06.03.2025»; «06.03.2025 - БАНК "ТРАСТ" (ПАО) больше не
числится в ЕГРЮЛ учредителем» — независимое реестровое подтверждение
перехода прав.

Между объявлением 2023 года и закрытием актив выставлялся повторно
минимум трижды со снижением стартовой цены (по докладу саб-агента —
июль 2023, сентябрь 2023 без заявок, январь 2024, март 2024) — точные
дословные цитаты по этим промежуточным попыткам не добыты (источники
business-vector.info/inkazan.ru отдают 503/изображение вместо текста),
поэтому в `eco.context` идёт только КОНЕЧНЫЙ подтверждённый факт
закрытия, а не вся цепочка промежуточных объявлений.

НЕ ВКЛЮЧЕНО: связь АО «Рест» с ГАП «Ресурс»/Виктором Наурузовым —
предположение саб-агента по совпадению региона экспансии (Саратовская
область), не подтверждено дословной цитатой источника, не переносится
в данные. Судьба остального пакета «Ростагро» (ТрастАгро-Нива 1-3 и
др., проданы отдельно в декабре 2022 года структуре Романа Троценко
«Аеон Агро» за 18,7 млрд ₽) — это другая, более ранняя сделка без
собственной карточки в базе; не относится к этой карточке.

Запуск: python3 pipeline/fix_trastagro_niva4_auction_closed.py
        python3 pipeline/fix_trastagro_niva4_auction_closed.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g5f0d5d18'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Закрыта'

OLD_DATE = '2023-06-01'
NEW_DATE = '2024-12-19'

OLD_SUM = '1,4 млрд ₽'
NEW_SUM = 'более 1 млрд ₽ (по стартовой цене торгов; продано единственному заявителю)'

OLD_ECO_CONTEXT = '«Траст» выставил на продажу крупный сельскохозяйственный актив банкира Микаила Шишханова'
NEW_ECO_CONTEXT = (
    '«Траст» выставил на продажу крупный сельскохозяйственный актив '
    'банкира Микаила Шишханова. После нескольких неудачных попыток продажи '
    'со снижением стартовой цены торги состоялись 19 декабря 2024 года: '
    'подана единственная заявка, торги формально признаны '
    'несостоявшимися, но актив продан заявителю по стартовой цене — '
    'более 1 млрд ₽ (независимо подтверждено сменой учредителя ООО '
    '«ТрастАгро-Нива 4» в ЕГРЮЛ 6 марта 2025 года). Сами 48 тыс. га «Траст» '
    'получил в декабре 2021 года на банкротных торгах у ООО «Ростагро-'
    'Саратов» за 2,75 млрд ₽.'
)

NEW_BUYER_NAME = 'АО «Рест» (Руслан Беретарь)'

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/7432621'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS
    assert deal['date'] == OLD_DATE
    assert deal['sum'] == OLD_SUM
    assert deal['eco']['sum'] == OLD_SUM
    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal.get('buyer_name') is None

    new_src = deal['src'] + NEW_SRC

    print('=== status: станет ===')
    print(NEW_STATUS)
    print('\n=== date: станет ===')
    print(NEW_DATE)
    print('\n=== sum / eco.sum: станет ===')
    print(NEW_SUM)
    print('\n=== buyer_name: станет ===')
    print(NEW_BUYER_NAME)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['status'] = NEW_STATUS
        deal['date'] = NEW_DATE
        deal['sum'] = NEW_SUM
        deal['eco']['sum'] = NEW_SUM
        deal['buyer_name'] = NEW_BUYER_NAME
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
