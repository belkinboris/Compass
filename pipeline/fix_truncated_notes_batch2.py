def main(write):
    with open(PATH, encoding="utf-8") as f:
        base = json.load(f)
    by_id = {d["id"]: d for d in base["deals"]}
    for fix in FIXES:
        d = by_id[fix["id"]]
        ev = d["events"][fix["idx"]]
        assert ev["note"] == fix["old"], \
            f"{fix['id']}[{fix['idx']}].note уже другой — уже правили?"
        ev["note"] = fix["new"]
        if "source_old" in fix:
            assert ev.get("source") == fix["source_old"], \
                f"{fix['id']}[{fix['idx']}].source уже другой — уже правили?"
            ev["source"] = fix["source_new"]
        print(f"{fix['id']}[{fix['idx']}]: note восстановлен"
              + (", source переименован" if "source_old" in fix else ""))

    if write:
        with open(PATH, "w", encoding="utf-8") as f:
            json.dump(base, f, ensure_ascii=False, indent=1)
        print("\nЗАПИСАНО.")
    else:
        print("\nСухой прогон — ничего не записано. Добавьте --write.")


if __name__ == "__main__":
    main(write="--write" in sys.argv)
