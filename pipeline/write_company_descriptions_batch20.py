# -*- coding: utf-8 -*-
"""Двадцатая партия описаний профилей: чем компания занимается.

ЧТО СЛОМАНО. После девятнадцати партий настоящее описание есть у 580
профилей из 1856 (31%). На этот раз кандидатов искали не по алфавиту
списка без описания, а по числу связанных сделок среди профилей без
описания — у более «активных» профилей заметнее и цена ошибки
классификации отрасли, и польза от готового описания. Каждый проверен
по тексту его собственных сделок в базе (урок CLAUDE.md про «Акрон
Холдинг»).

Отдельная находка при чтении контекста — у ДВУХ профилей была неверная
отрасль, унаследованная не от рода занятий самой компании:

* «АО «БТС-Мост Холдинг»» стояло в «ГМК и добыча» — обе его сделки в
  базе это ПОКУПКИ (доля в золотодобывающей ЮГК, контроль в
  «Метрогипротранс»), а сам холдинг — инфраструктурно-строительная
  группа Руслана Байсарова (само имя — «мост»). Отрасль досталась от
  ЦЕЛИ одной из покупок, не от БТС-Моста. Исправлено на
  «Строительство».
* «SK Capital» стояло в «ИТ и интернет» — инвестиционная платформа
  группы ВЭБ.РФ, вкладывающая в разные компании (в т. ч. Softline,
  «Сайберус»); отрасль унаследовалась от одной из портфельных
  инвестиций, а не от рода деятельности самой платформы. Исправлено на
  «Управление активами».

Про «Mail» (`g1d6e1cf7`, две сделки 2020 года под маркой «Mail.ru
Group») — в базе уже есть отдельный, хорошо описанный профиль «VK»
(`g4e694234`, 10 сделок): Mail.ru Group Limited в 2021 году
переименована и редомицилирована в VK. Не сливаю два профиля без более
сильного основания, чем факт переименования (риск ошибки идентичности
такой же, что у «Акрон Холдинга») — вместо этого описание «Mail» прямо
называет более позднее имя, честно и без утверждения тождества данных.

ЧТО ДЕЛАЕТ. Проставляет описание в 1–2 строки 4 профилям, исправляет
отрасль у 2.

Запуск:
    python3 pipeline/write_company_descriptions_batch20.py            # сухой прогон
    python3 pipeline/write_company_descriptions_batch20.py --write    # записать
"""
import json
import re
import sys

DATA = 'static/data/deals_promoted.json'
PLACEHOLDER = re.compile(r'^\s*(описание компании пока не добавлено'
                          r'|профиль сформирован по итогам чтения)', re.I)

# id профиля -> описание. Только компании, чей род занятий общеизвестен и
# подтверждён текстом собственной сделки в базе.
DESCRIPTIONS = {
    'g839c87d5': 'Российская нефтяная компания, контролируется '
                 'Михаилом Гуцериевым.',
    'g1d6e1cf7': 'Российский интернет-холдинг под маркой Mail.ru '
                 'Group; в 2021 году переименован в VK.',
    'g27b935b9': 'Российский инфраструктурно-строительный холдинг '
                 'Руслана Байсарова.',
    'gc02549c1': 'Инвестиционная платформа группы ВЭБ.РФ, вкладывает '
                 'в доли непубличных компаний.',
}

# Профили, отрасль которых унаследована от цели/предмета одной из
# сделок, а не от рода занятий самой компании (см. докстринг). old — что
# было, для assert.
INDUSTRY_FIXES = {
    'g27b935b9': ('ГМК и добыча', 'Строительство'),
    'gc02549c1': ('ИТ и интернет', 'Управление активами'),
}


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    comps = data['companies']

    wrote, skipped = 0, []
    for cid, text in DESCRIPTIONS.items():
        c = comps.get(cid)
        assert c, 'профиля %s нет в базе' % cid
        assert 15 <= len(text) <= 220, 'описание %s вне 1–2 строк: %d' % (cid, len(text))
        old = str(c.get('desc') or '')
        if old.strip() == text:
            continue
        if old and not PLACEHOLDER.match(old):
            skipped.append((cid, c.get('name'), old[:60]))
            continue
        print('  %-12s %-34s %s' % (cid, str(c.get('name'))[:34], text[:56]))
        c['desc'] = text
        wrote += 1

    ind_fixed = 0
    for cid, (old_ind, new_ind) in INDUSTRY_FIXES.items():
        c = comps.get(cid)
        assert c, 'профиля %s нет в базе' % cid
        assert c.get('ind') == old_ind, ('отрасль %s уже другая: %r (ожидали %r)'
                                          % (cid, c.get('ind'), old_ind))
        print('  ОТРАСЛЬ  %-12s %-34s %s -> %s'
              % (cid, str(c.get('name'))[:34], old_ind, new_ind))
        c['ind'] = new_ind
        ind_fixed += 1

    print('\nОписаний записано: %d' % wrote)
    print('Отраслей исправлено: %d' % ind_fixed)
    if skipped:
        print('Пропущено (уже есть своё описание): %d' % len(skipped))
        for cid, name, old in skipped[:5]:
            print('   %s %s — %r' % (cid, name, old))

    real = sum(1 for v in comps.values()
               if (v.get('desc') or '').strip() and not PLACEHOLDER.match(str(v.get('desc'))))
    print('Всего профилей с описанием: %d из %d (%d%%)'
          % (real, len(comps), round(100 * real / len(comps))))

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return 0
    json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('Записано.')
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
