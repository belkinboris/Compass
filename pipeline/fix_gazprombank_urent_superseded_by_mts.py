# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
`gc64703e2` («Газпромбанк Лизинг инвестирует в кикшеринг Urent и
становится совладельцем», статус «Обсуждается» с марта 2023) —
находка: сделка так и не подтвердилась, вместо неё контроль над
компанией консолидировала совсем другая сторона.

Проверено лично прямым WebFetch (Интерфакс,
https://www.interfax.ru/business/940287, 15.01.2024): «доля МТС в
капитале ООО «Юрентбайк.ру» — 11,77%» до сделки, «доведя долю в
компании-владельце проекта... до 80,58%» после; оценка «Юрент» в ходе
сделки — «примерно 7-8 млрд рублей»; «Газпромбанк Лизинг» в статье НЕ
упоминается вовсе — ни среди акционеров, ни среди инвесторов.

По докладу саб-агента (не перепроверено мной лично прямым WebFetch):
ни один источник за 2024-2026 годы не называет «Газпромбанк Лизинг»
совладельцем «Юрент» ни разу — сделка, объявленная как «переговоры» в
марте 2023 года (сумма и доля были неизвестны даже источникам самой
статьи-первоисточника), судя по всему, не была закрыта: 15 января 2024
года контроль (80,58%) в компании консолидировала группа МТС отдельной
сделкой. Прямого опровержения или заявления «сделка не состоялась»
не найдено — вывод сделан по отсутствию «Газпромбанка Лизинг» во ВСЕХ
последующих раскрытиях состава акционеров.

НЕ ВНЕСЕНО в структурные поля (`buyer`/`title`/`status`) — см.
отдельную запись в CLAUDE.md, «Известные проблемы»: решение о том, как
переформулировать карточку, оставлено человеку.

Запуск: python3 pipeline/fix_gazprombank_urent_superseded_by_mts.py
        python3 pipeline/fix_gazprombank_urent_superseded_by_mts.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gc64703e2'

OLD_ECO_CONTEXT = (
    'Рыночная стоимость электросамоката Segway Ninebot, которые '
    'использует «Юрент», составляет от 75 000 до 90 000 руб., но '
    'массовая закупка «будет проходить по нижней границе диапазона», '
    'отмечает один из собеседников. Поставки самокатов в рамках сделки '
    'будут осуществляться в течение трёх лет: 35 000 шт. — в 2023 г., '
    'ещё по 25 000 — в 2024 и 2025 гг.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' По независимым данным, эта сделка так и не'
    ' закрылась: 15 января 2024 года МТС отдельной сделкой довела'
    ' свою долю в ООО «Юрентбайк.ру» с 11,77% до 80,58% (оценка'
    ' компании — 7-8 млрд ₽); «Газпромбанк Лизинг» ни в этой, ни в'
    ' последующих раскрытиях состава акционеров не упоминается вовсе.'
)

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/business/940287'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    existing_urls = {s[1] for s in deal['src']}
    add_src = [s for s in NEW_SRC if s[1] not in existing_urls]
    new_src = deal['src'] + add_src

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    if add_src:
        print('\n=== src: добавится ===')
        for s in add_src:
            print(s)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
