# -*- coding: utf-8 -*-
"""Месячная очередь, 9 сентября 2026 — дочитывание карточки `g97e1f483`
(«Группа "Ригла-Здравсити" закрыла сделку по покупке сети "Здоровый
город" в Воронежской области», добавлена в базу 8 сентября 2026).

Дельта-поиск (саб-агент + личная проверка) нашёл продавца, вторую оценку
с обоснованием и финансовые показатели предмета. Личный WebFetch
(kommersant.ru/doc/8861650) подтвердил дословно: «Эти компании ранее
принадлежали Олегу и Рите Литавриным»; вторая оценка — «Один из
источников "Ъ" на инвестрынке оценивает сделку в 100–250 млн руб.,
поскольку совокупная чистая прибыль трех приобретенных юрлиц в 2025
году была практически нулевой»; финансы — «Совокупная выручка трех
компаний в 2025 году составила 1,2 млрд руб.», прибыль ООО «Центр» —
4,3 млн ₽, ООО «Фарм-Север» — 663 тыс. ₽, у ООО «АМП» убыток 4,8 млн ₽.

Похожая сделка того же паттерна (Калининград, май 2025, 55 аптек,
~200 млн ₽ — «Ригла»/«Протек» купили сеть «Новая аптека») подтверждает
стратегию региональной консолидации, но НЕ вносится в эту карточку как
отдельный факт: это контекст для будущей отдельной карточки, если её
ещё нет в базе, а не факт ЭТОЙ сделки.

НЕ внесено: консультанты (ни один источник не назвал), прямая причина
продажи со стороны Литавриных (источники дают только контекст рынка, не
цитату владельцев), расхождение числа аптек (55 в сделке против 47/72
в исторических справках abireg.ru — не сопоставлено с достаточной
уверенностью).

Запуск:
    python3 pipeline/fix_rigla_zdorovy_gorod_seller_and_finance.py            # сухой прогон
    python3 pipeline/fix_rigla_zdorovy_gorod_seller_and_finance.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_SELLER = None

OLD_ECO_SUM = 'Стоимость актива могла составить от 370 млн до 430 млн руб. без учета обременений'
NEW_ECO_SUM = OLD_ECO_SUM + (
    '. Источник «Ъ» на инвестрынке оценивает сделку ниже — в 100–250 '
    'млн ₽, поскольку совокупная чистая прибыль трёх приобретённых '
    'юрлиц в 2025 году была практически нулевой.'
)

OLD_ECO_TARGET_FIN = '—'
NEW_ECO_TARGET_FIN = (
    'Совокупная выручка трёх купленных юрлиц в 2025 году — 1,2 млрд ₽. '
    'ООО «Центр» получило прибыль 4,3 млн ₽, ООО «Фарм-Север» — 663 '
    'тыс. ₽, ООО «АМП» — убыток 4,8 млн ₽.'
)

NEW_SRC = ['Коммерсантъ', 'https://www.kommersant.ru/doc/8861650']


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['g97e1f483']

    assert d.get('seller') == OLD_SELLER, \
        'g97e1f483 seller уже занят: %r' % (d.get('seller'),)
    assert d['eco']['sum'] == OLD_ECO_SUM, \
        'g97e1f483 eco.sum уже другой: %r' % (d['eco']['sum'],)
    assert d['eco']['target_fin'] == OLD_ECO_TARGET_FIN, \
        'g97e1f483 eco.target_fin уже другой: %r' % (d['eco']['target_fin'],)
    urls = {s[1] for s in d['src']}
    assert NEW_SRC[1] not in urls, 'источник уже добавлен'

    print('g97e1f483: seller заполнен (Олег и Рита Литаврины); eco.sum '
          'дополнен второй оценкой (100–250 млн ₽, обоснование); '
          'eco.target_fin заполнен финансовыми показателями трёх юрлиц; '
          'добавлен источник kommersant.ru')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['seller'] = 'Олег и Рита Литаврины'
    d['eco']['sum'] = NEW_ECO_SUM
    d['eco']['target_fin'] = NEW_ECO_TARGET_FIN
    d['src'].append(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
