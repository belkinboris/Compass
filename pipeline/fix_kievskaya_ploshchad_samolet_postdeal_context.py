import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gc9bc132c'

OLD_CONTEXT = (
    'Но «Самолет» в 2021–2022 г. выплачивал своим акционерам дивиденды. В '
    'прошлом году он этого не делал.'
)
CONTEXT_ADDITION = (
    ' Член совета директоров SimpleEstate Артём Цогоев объяснил мотив '
    'продажи так: «Можно было либо годами ждать отскока как минимум на '
    'уровень покупки, либо продать и забрать хоть какие-то деньги. '
    'Выбрали деньги, а не позу стратегического инвестора» (РИА '
    'Недвижимость). Финансовое положение «Самолета» после выхода '
    '«Киевской площади» продолжало ухудшаться: за 2025 год выручка выросла '
    'на 8%, до 366,8 млрд руб., EBITDA — на 24%, до 103,3 млрд руб., но '
    'компания получила чистый убыток 2,3 млрд руб. по МСФО из-за расхода '
    'от изъятия в доход государства ЖК «Квартал Марьино» по иску '
    'Генпрокуратуры (Коммерсантъ). В мае 2026 года компания допустила '
    'технический дефолт по купонам трёх выпусков облигаций: выплаты были '
    'запланированы на 4 мая, а средства поступили в депозитарий только '
    'в ночь на 5 мая (Business Gazeta).'
)
NEW_CONTEXT = OLD_CONTEXT + CONTEXT_ADDITION

NEW_SRC = [
    ['РИА Недвижимость', 'https://realty.ria.ru/20241030/samolet-1980984296.html'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8608660'],
    ['Business Gazeta', 'https://m.business-gazeta.ru/news/701575'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
