"""Приток 18.09.2026, часовой прогон 14:20 МСК — ответ на заметку владельца
№669 («Переписать под нового покупателя»). Карточка gf1608a6f стояла с
2023 года под рабочим заголовком «МТС может продать... консорциуму
финансовых инвесторов» (90-120 млрд ₽, покупатель не назван) — реальная
сделка уже была найдена и дословно описана в eco.context/events этой же
карточки: 26 июня 2026 года МТС продала 49,9% ЗПИФ «Инвестиции 18» за
21,7 млрд ₽ и сохранила контроль. Ни один источник не подтвердил продажу
внешнему консорциуму — переписываем карточку под настоящую сделку, а не
оставляем как несостоявшийся план: реальная сделка СОСТОЯЛАСЬ, просто с
другим покупателем, суммой и датой. Все значения ниже уже дословно лежали
в карточке (ComNews, 26.06.2026) — просто не были перенесены в
структурные поля title/buyer_name/sum/status/date.
"""
import json
import sys

DATA_PATH = 'static/data/deals_promoted.json'

OLD_TITLE = 'МТС может продать антенную инфраструктуру (БИК) консорциуму финансовых инвесторов'
NEW_TITLE = 'МТС продала 49,9% башенной инфраструктуры (БИК) фонду «Инвестиции 18»'


def main(write):
    data = json.load(open(DATA_PATH, encoding='utf-8'))
    card = next(d for d in data['deals'] if d['id'] == 'gf1608a6f')
    assert card['title'] == OLD_TITLE, repr(card['title'])
    assert card['date'] == '2023-11-02', repr(card['date'])
    assert card['status'] == 'Обсуждается', repr(card['status'])
    assert card['sum'] == '90–120 млрд ₽ (по оценке)', repr(card['sum'])
    assert card['buyer'] == 'g61716134', repr(card['buyer'])

    card['title'] = NEW_TITLE
    card['date'] = '2026-06-26'
    card['status'] = 'Закрыта'
    card['sum'] = '21,7 млрд ₽'
    card['buyer'] = None
    card['buyer_name'] = ('ЗПИФ «Инвестиции 18» (управляющая компания ранее принадлежала '
                          'АФК «Система», а теперь самой МТС)')
    card['eco']['sum'] = '21,7 млрд ₽'
    card['eco']['share'] = ('26 июня 2026 года МТС продала 49,9% долей БИК закрытому паевому '
                            'инвестфонду «Инвестиции 18», сохранив 50,1% и совместный контроль; '
                            'покупатель принял на себя часть долга БИК (всего около 80 млрд ₽), '
                            'а МТС получила опцион на обратный выкуп доли.')

    if write:
        json.dump(data, open(DATA_PATH, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
        print('gf1608a6f переписана под настоящую сделку 2026 года. ЗАПИСАНО.')
    else:
        print('Сухой прогон: переписал бы gf1608a6f под сделку 2026 года. Повторите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
