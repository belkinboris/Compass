import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g10adb6ac'

NEW_SELLER = 'Caterpillar Inc.'

OLD_APPR = 'Сделка одобрена Президентом РФ в ноябре 2023 года.'
NEW_APPR = (
    'Распоряжение президента РФ (27 ноября 2023 года), дословно: '
    '«разрешить совершение обществом с ограниченной ответственностью '
    '«ПСК - Новые решения» сделок по приобретению 100 процентов долей в '
    'уставных капиталах обществ с ограниченной ответственностью '
    '«Катерпиллар Тосно» и «Катерпиллар Файнэншл»» (РИА Новости).'
)

OLD_CONTEXT = (
    'Завод Caterpillar в Тосно работал с 2000 года, производя внедорожные '
    'карьерные самосвалы и гидравлические экскаваторы под брендом Cat, а '
    'также компоненты для машин и оборудования, которые компания '
    'экспортировала на свои европейские заводы. Caterpillar весной 2022 '
    'года приостановила работу завода в городе Тосно из-за СВО.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' В августе 2024 года «Тосно» и «Файнэншл» переданы в ЗПИФ «Неон», '
    'из которого Balchug Capital «вывел все денежные средства — более 20 '
    'миллиардов рублей» — «завод за целый год так и не возобновил '
    'деятельность, а сотрудники так и не вышли на работу» (Lenta.ru). '
    'Далее актив перешёл структуре, связанной с «Трансмашхолдингом» (АО '
    '«Горизонт», Александр Мигаль). 15 апреля 2026 года завод «запустили '
    'производство, сборку экскаваторов-погрузчиков» по лицензии '
    'китайского партнёра, план на 2026 год — 300 машин; бренд Cat '
    'больше не используется (Интерфакс).'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6773282'],
    ['РИА Новости', 'https://ria.ru/20231127/aktivy-1912222738.html'],
    ['Lenta.ru', 'https://lenta.ru/articles/2025/04/09/mne-tosno/'],
    ['Интерфакс', 'https://www.interfax.ru/business/1084111'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal.get('seller') is None
    assert deal['law']['appr'] == OLD_APPR
    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print(f'=== seller (новое поле): станет {NEW_SELLER!r} ===')
    print('=== law.appr: было ===')
    print(OLD_APPR)
    print('=== law.appr: станет ===')
    print(NEW_APPR)
    print('=== eco.context (новое поле): станет ===')
    print(NEW_CONTEXT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['seller'] = NEW_SELLER
        deal['law']['appr'] = NEW_APPR
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
