# -*- coding: utf-8 -*-
"""Заметка 505 (консоль, 4 сентября 2026): «Карточку обогатить этой
информацией, в дополнительной информации написать», отвечая на карточку
`gb49e3668» (Dogma выкупила две площадки ГК ПИК в Гольяново и
Очаково-Матвеевском).

Известная проблема (CLAUDE.md): по данным novostroy.ru и erzrf.ru, на
2-м Иртышском проезде в Гольяново (адрес восточной площадки) сейчас
строится «ЖК 2-й Иртышский», застройщиком назван ООО СЗ
«Л-Девелопмент» — дочерняя структура ПИК, а не Dogma. Владелец
подтвердил: добавить это наблюдение в «Дополнительную информацию»
(не менять `target`/`buyer` — источник не проверен напрямую, только
через агрегаторы недвижимости).

Запуск: python3 pipeline/fix_dogma_pik_ldevelopment_context.py [--write]
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gb49e3668'
OLD_EXTRA = (
    'Краснодарский застройщик Dogma купил у ГК ПИК два земельных '
    'участка общей площадью более 6 га. На них предусмотрено '
    'строительство жилых комплексов общей площадью 204 тыс. кв. м. '
    'Финансирование на 54,7 млрд ₽ открыл Альфа-банк, из этой суммы '
    '26,4 млрд ₽ пришлось на восточный проект в Гольяново. В компании '
    'тогда говорили, что к двум её подмосковным проектам — ЖК EVO и '
    '«Публицист» — уже в следующем году добавятся несколько проектов в '
    'Москве, а ещё ряд сделок готовился к подписанию. По итогам 2025 '
    'года выручка DOGMA выросла на 87,2%, компания впервые заняла '
    'третье место по объёму текущего строительства в России и сдала '
    'более 6 тыс. квартир.'
)
ADDITION = (
    ' По данным агрегаторов недвижимости (novostroy.ru, erzrf.ru), на '
    '2-м Иртышском проезде в Гольяново — адресе восточной площадки этой '
    'сделки — сейчас строится «ЖК 2-й Иртышский», застройщиком назван '
    'ООО СЗ «Л-Девелопмент», дочерняя структура ПИК, а не Dogma. '
    'Источник не проверен напрямую (только через агрегаторы) — не '
    'исключено, что участок площадью 3,5 га разделён на часть, '
    'проданную Dogma, и часть, которую ПИК застраивает сам.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {c['id']: c for c in data['deals']}
    card = by_id[CARD_ID]
    assert card['extra'] == OLD_EXTRA, card['extra']
    card['extra'] = OLD_EXTRA + ADDITION
    print(f'{CARD_ID}.extra: добавлена находка про Л-Девелопмент/ЖК 2-й Иртышский')

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
            f.write('\n')
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
