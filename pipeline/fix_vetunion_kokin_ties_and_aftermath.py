import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g937b94f4'

OLD_ECO_RATIONALE = (
    'Управляющий директор Peregrine Capital Дмитрий Габышев предполагает, '
    'что Дмитрий Кокин мог частично профинансировать сделку по покупке '
    'основного бизнеса «Инвитро» и выданный им заем конвертировался в '
    'долю в других структурах холдинга'
)
NEW_ECO_RATIONALE = OLD_ECO_RATIONALE + (
    '. По данным СПАРК, в финансировании сделки мог участвовать и '
    'Газпромбанк, у которого в залоге 100% головной структуры «Инвитро» '
    '(банк на запрос не ответил).'
)

OLD_ECO_CONTEXT = (
    'Изменения в структурах «Инвитро» происходят после ухода из бизнеса '
    'основателя компании Александра Островского'
)
NEW_ECO_CONTEXT = OLD_ECO_CONTEXT + (
    '. Дмитрий Кокин через ООО «Симпл» владеет 51% в «А-Телематика» '
    '(оборудование для РЖД) и является партнёром Дмитрия Афанасенко, '
    'бывшего члена совета директоров «Мостотреста» Аркадия Ротенберга, '
    'по холдингу «Телематика» — в 2015–2017 годах 45% этого холдинга '
    'принадлежали Игорю Ротенбергу; источники Коммерсанта предполагали '
    'связь новых владельцев «Инвитро» с семьёй Ротенбергов, но '
    'представитель бизнесменов это отрицал. После сделки структура '
    'владения менялась ещё раз: гендиректором Vet Union с 19 октября '
    '2023 года стал Рухая Сандро Сосоевич, а с 7 марта 2024 года '
    'единственным владельцем значится АО «Вет Юнион». Сеть продолжила '
    'расти: в августе 2024 года запустила экспресс-лаборатории в '
    'крупных городах России, в апреле 2025-го вышла на рынок Казахстана, '
    'а в 2026 году открыла первую клинику по франшизе и направление '
    'консалтинга для ветеринарного бизнеса.'
)

NEW_SRC = [
    ['РБК', 'https://companies.rbc.ru/id/5077746936053-ooo-vet-yunion/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['rationale'] == OLD_ECO_RATIONALE
    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    new_src = deal['src'] + NEW_SRC

    print('=== eco.rationale: станет ===')
    print(NEW_ECO_RATIONALE)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['rationale'] = NEW_ECO_RATIONALE
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
