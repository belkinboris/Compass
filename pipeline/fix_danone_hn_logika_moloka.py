import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g246f4b6b'

OLD_CONTEXT = (
    'С декабря 2022 года Россия обязывает иностранные компании '
    'продавать свои активы российским покупателям с дисконтом в 50% и '
    'взимает с них выходную пошлину в размере не менее 10% от суммы '
    'сделки.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' Компания дважды сменила имя: «Данон Россия» → Health & Nutrition '
    '(на время передачи) → «Логика молока» с 8 октября 2025 года '
    '(портфель брендов не изменился). 6 декабря 2024 года 100% '
    '«Вамин Татарстан» консолидировал Руслан Алисултанов, экс-министр '
    'сельского хозяйства Чечни. Финансовые показатели выросли: '
    'выручка — с ~106 млрд ₽ (2024) до 130,47 млрд ₽ (2025, +23%), '
    'чистая прибыль — с 6,2 млрд ₽ до 19,84 млрд ₽ (+220%).'
)

NEW_SRC = [
    ['expert.ru', 'https://expert.ru/news/byvshaya-dochka-danone-v-rossii-smenit-nazvanie/'],
    ['РеалноеВремя', 'https://realnoevremya.ru/news/323948-byvshie-aktivy-danone-v-rossii-pereshli-chechencam'],
    ['RuNews24', 'https://runews24.ru/business/23/07/2026/byivshie-aktivyi-danone-v-rossii-pokazali-rost-pribyili-bolee-chem-v-tri-raza-za-god'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
