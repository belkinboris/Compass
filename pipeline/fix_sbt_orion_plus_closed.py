import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g62cbdd8b'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Закрыта'

OLD_TARGET_FIN = '—'
NEW_TARGET_FIN = (
    'Выручка ООО «СК "Орион плюс"» (одна из компаний группы) за 2024 '
    'год составила 11,4 млрд руб., прибыль — 146,1 млн руб. (в 2023 '
    'году — 13,6 млрд руб. выручки, 576,3 млн руб. прибыли).'
)

OLD_EXTRA = (
    'Сделка между ООО «Стройблоктехнология» (СБТ) из Уфы и группой '
    'петербургских строительных компаний, включающей ООО «СК "Орион '
    'плюс"», ООО «Группа компаний "СМК-Инвест"», ООО «Первая евразийская '
    'концессионная компания» и другие. Получено согласие ФАС на сделку.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Сделка закрыта летом 2024 года: «Мы получили актив с заключенными '
    'контрактами, профессиональной командой, крупной материальной '
    'базой, к которому не нужно применять кризисное управление» (новый '
    'владелец, Фонтанка, 25 декабря 2024 года). Покупатель успешно '
    'встроился в рынок госзаказа Петербурга — получил контракт на '
    'капитальный ремонт набережной Обводного канала (2,5 млрд руб.) и '
    'отдельно, уже в декабре 2024 года, купил АО «Стройметалконструкция» '
    '(СМК) — вне периметра этой сделки.'
)

NEW_SRC = [
    ['Фонтанка', 'https://www.fontanka.ru/2024/07/02/73781852/'],
    ['Фонтанка', 'https://www.fontanka.ru/2024/12/25/74920775/'],
    ['DP.ru', 'https://www.dp.ru/a/2025/06/17/remont-naberezhnoj-obvodnogo'],
    ['DP.ru', 'https://www.dp.ru/a/2024/12/11/kompanija-iz-ufi-poglotila'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS
    assert deal['eco']['target_fin'] == OLD_TARGET_FIN
    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== status: станет ===')
    print(NEW_STATUS)
    print('\n=== eco.target_fin: станет ===')
    print(NEW_TARGET_FIN)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['status'] = NEW_STATUS
        deal['eco']['target_fin'] = NEW_TARGET_FIN
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
