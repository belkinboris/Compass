# -*- coding: utf-8 -*-
"""Месячная очередь, 9 сентября 2026 — дочитывание карточки `gc8fac4fb`
(«ГК "АВС-медицина" приобрела сеть частных клиник "Ниармедик"»,
добавлена в базу 8 сентября 2026).

Дельта-поиск (саб-агент + личная проверка) нашёл независимую статью
отраслевого делового издания (Медвестник) и статью Vademecum о более
раннем, отдельном шаге в истории того же актива. Личный WebFetch
подтвердил дословно:

1) Оценка суммы сделки (стороны сумму не раскрывают). medvestnik.ru:
   «Гендиректор компании Eqiva Дарья Шубина оценивает ее в 1,5 млрд
   руб.» — идёт в `eco.val` с атрибуцией, не в `sum`.

2) Причина продажи со стороны продавца. medvestnik.ru, дословная цитата
   гендиректора «Доктор Рядом Холдинг»: «В офлайн-медицине наступает
   время крупных игроков. Хорошо управлять можно только на эффекте
   масштаба.»

3) Финансовые показатели покупателя и результат сделки. medvestnik.ru:
   «Выручка клиник [АВС-медицины] за 2024 год составила 1,72 млрд
   руб.» и «повысив число медицинских учреждений в контуре компании с
   18 до 37».

4) Более ранний, отдельный шаг: АФК «Система» вышла из совладения
   «Ниармедик» ДО этой сделки. vademec.ru (19.12.2025): «Покупателем
   выступило ООО «Доктор Рядом Холдинг», которое являлось совладельцем
   клиник — также на 50%» (то есть «Доктор Рядом Холдинг» сначала
   выкупил долю АФК «Система», консолидировав 100%, и лишь затем продал
   актив целиком «АВС-медицине»); причина выхода АФК «Система» —
   «решение принято для того, чтобы реализовать непрофильный актив
   после реализации стратегического объединения и интеграции в единую
   систему медицинских активов»; выручка клиник «Ниармедик» «за прошлый
   год остановилась на отметке чуть более 2 млрд рублей (показатель
   снизился на 11% по сравнению с 2023 годом)».

Расхождение дат: medvestnik.ru и mergers.ru датируют публикацию/сделку
29 декабря 2025 года, карточка несёт дату закрытия 5 февраля 2026 —
`date` карточки НЕ меняется: оба источника вполне могут описывать
объявление/подписание, а 5 февраля 2026 — юридическое закрытие,
источника которого этот поиск не нашёл; смена даты требует отдельного
подтверждения.

НЕ внесено: юридический или финансовый консультант продавца (ни один
источник не назвал), связь покупателя с Владимиром Ворониным/ФСК
(найдено только через поисковый сниппет, не подтверждено прямым
чтением первоисточника).

Запуск:
    python3 pipeline/fix_avs_medicina_niarmedik_details.py            # сухой прогон
    python3 pipeline/fix_avs_medicina_niarmedik_details.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_ECO_VAL = '—'
NEW_ECO_VAL = (
    'Стороны сумму не раскрывают. По оценке гендиректора консалтинговой '
    'компании Eqiva Дарьи Шубиной, сделка могла составить около 1,5 '
    'млрд ₽.'
)

OLD_ECO_TARGET_FIN = '—'
NEW_ECO_TARGET_FIN = (
    'Выручка «АВС-медицины» за 2024 год — 1,72 млрд ₽. Выручка сети '
    '«Ниармедик» (12 медцентров) за 2024 год — чуть более 2 млрд ₽ '
    '(на 11% меньше, чем в 2023 году).'
)

OLD_ECO_CONTEXT = (
    'Клиники «Ниармедик» продолжат работу под брендом «АВС-медицина» и '
    'войдут в общую информационную систему сети. Продали их ООО «Доктор '
    'Рядом Холдинг» — совместное предприятие основателей бизнеса и '
    'ВЭБ.РФ — и ООО «Доктор Рядом Инвест».'
)
NEW_ECO_CONTEXT = OLD_ECO_CONTEXT + (
    ' После сделки сеть «АВС-медицины» выросла с 18 до 37 точек. Ещё в '
    'декабре 2025 года «Доктор Рядом Холдинг» выкупил у АФК «Система» её '
    '50%-ю долю в «Ниармедик», консолидировав актив перед продажей; АФК '
    '«Система» объяснила выход тем, что «непрофильный актив» реализован '
    'после интеграции медицинских активов в единую систему. Продавец '
    'объяснил решение фокусом на медтехе: «В офлайн-медицине наступает '
    'время крупных игроков. Хорошо управлять можно только на эффекте '
    'масштаба».'
)

NEW_SRC = [
    ['Медвестник', 'https://medvestnik.ru/content/news/avs-medicina-vykupila-kliniki-niarmedik.html'],
    ['Vademecum', 'https://vademec.ru/news/2025/12/19/afk-sistema-chastichno-vyshla-iz-gk-niarmedik/'],
]


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['gc8fac4fb']

    assert d['eco']['val'] == OLD_ECO_VAL, \
        'gc8fac4fb eco.val уже другой: %r' % (d['eco']['val'],)
    assert d['eco']['target_fin'] == OLD_ECO_TARGET_FIN, \
        'gc8fac4fb eco.target_fin уже другой: %r' % (d['eco']['target_fin'],)
    assert d['eco']['context'] == OLD_ECO_CONTEXT, \
        'gc8fac4fb eco.context уже другой: %r' % (d['eco']['context'],)
    urls = {s[1] for s in d['src']}
    for src in NEW_SRC:
        assert src[1] not in urls, 'источник уже добавлен: %s' % src[1]

    print('gc8fac4fb: eco.val заполнен (оценка Eqiva, ~1,5 млрд ₽); '
          'eco.target_fin заполнен (выручка АВС-медицины и Ниармедик); '
          'eco.context дополнен (рост сети 18->37, предшествующий выход '
          'АФК «Система», цитата продавца о причине); добавлены '
          'источники medvestnik.ru, vademec.ru')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['eco']['val'] = NEW_ECO_VAL
    d['eco']['target_fin'] = NEW_ECO_TARGET_FIN
    d['eco']['context'] = NEW_ECO_CONTEXT
    d['src'].extend(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
