# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g809f9155
(Лискинский маслоэкстракционный завод «Исток») — карточка год простояла
как «Не состоялась» («Вдовин... в сентябре публично заявил, что пожалел о
своем решении, и снял завод с продажи»), хотя сделка в итоге состоялась.
Проверено лично прямым WebFetch (kommersant.ru/doc/8194080, 11.11.2025,
14:04): «Воронежский предприниматель Руслан Вдовин продал масложировой
завод ООО «Исток» и транспортное ООО «Исток-логистик» в Лисках
тамбовскому бизнесмену Денису Избрехту» — тот же Избрехт, с которым, по
уже записанной в карточке цитате, «Вдовин вступил в переговоры» и с
которым «в октябре стороны принципиально договорились о сделке»: это
продолжение той же истории, а не новый претендент.

Сумма — по тому же источнику дословно «Сумма сделки не раскрывалась
сторонами»; поле `sum`/`eco.sum` не менялось (в них уже стоит независимая
оценка «6–7 млрд ₽ (по оценке)» из старого источника — она не
опровергнута и не подтверждена новым).

`status`: «Не состоялась» → «Закрыта» — «продал» есть в списке
`STATUS_WORDS['Закрыта']` review.py, но правка меняет сразу несколько
взаимосвязанных полей (title/extra/status/buyer_name), поэтому сделана
отдельным скриптом, а не через review.py (тот же приём, что уже применён
к `gf13fba9e`, торги ТПК Челябинск).

`title` и `extra` переписаны с «отказа» на состоявшуюся продажу — старый
текст «Отказ от продажи…»/«Отказ от сделки по продаже…» стал неверен по
факту, а не просто устарел.

`buyer_name` (поля не было вовсе) — заполнено именем Избрехта текстом:
профиля компании для физлица нет, `buyer` остаётся `null`, как и у
`seller` (тоже текстом, «Руслан Вдовин» — уже стояло раньше).

`law.appr` дополнен фактом о состоявшемся закрытии — старый текст
(сентябрьский отказ, октябрьская принципиальная договорённость) сохранён
как первая часть, к нему добавлено предложение о ноябрьском закрытии.

НЕ ВКЛЮЧЕНО: дата регистрации сделки/смены собственника по ЕГРЮЛ в
источнике не названа (только дата публикации статьи — 11.11.2025), поэтому
`date` карточки (2024) не менялся — год относится к первой волне
переговоров, а не к закрытию, и после чтения источника неясно, к какому
именно моменту год вообще должен быть привязан; это отдельный вопрос,
не решаемый этим скриптом. Консультанты сделки нигде не названы (проверено
тем же WebFetch: «В тексте нет упоминания консультантов»). Судьба
альтернативного претендента, ГАП «Ресурс», в новом источнике не
упоминается вовсе — формулировка `extra` ниже не утверждает, что ГАП
«Ресурс» проиграл торги, только что сделка в итоге прошла с Избрехтом.

Запуск: python3 pipeline/fix_istok_deal_actually_closed.py
        python3 pipeline/fix_istok_deal_actually_closed.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g809f9155'

OLD_STATUS = 'Не состоялась'
NEW_STATUS = 'Закрыта'

OLD_TITLE = 'Отказ от продажи Лискинского маслоэкстракционного завода «Исток»'
NEW_TITLE = 'Продажа Лискинского маслоэкстракционного завода «Исток»'

OLD_EXTRA = (
    'Отказ от сделки по продаже ООО «Исток» (производитель нерафинированного '
    'растительного масла и подсолнечного шрота). Потенциальными покупателями '
    'были Денис Избрехт и ГАП «Ресурс». Продавец — Руслан Вдовин. По '
    'информации редакции, у Вдовина возникли сложности с Избрехтом.'
)
NEW_EXTRA = (
    'ООО «Исток» (производитель нерафинированного растительного масла и '
    'подсолнечного шрота) продано Русланом Вдовиным Денису Избрехту. '
    'Публичный отказ от сделки в сентябре 2025 года не стал окончательным: '
    'стороны вернулись к переговорам, и в итоге сделка состоялась. Сумма '
    'сделки не раскрывалась.'
)

OLD_APPR = (
    'Вдовин вступил в переговоры с Избрехтом, но в сентябре публично заявил, '
    'что пожалел о своем решении, и снял завод с продажи. Несмотря на это, '
    'сделка получила одобрение ФАС, а в октябре стороны принципиально '
    'договорились о сделке.'
)
NEW_APPR = OLD_APPR + (
    ' Сделка закрылась: «Воронежский предприниматель Руслан Вдовин продал '
    'масложировой завод ООО "Исток" и транспортное ООО "Исток-логистик" в '
    'Лисках тамбовскому бизнесмену Денису Избрехту» (Коммерсантъ, '
    '11 ноября 2025 года).'
)

NEW_SRC_KOMMERSANT = ['Коммерсантъ', 'https://www.kommersant.ru/doc/8194080']

NEW_BUYER_NAME = 'Денис Избрехт'


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS
    assert deal['title'] == OLD_TITLE
    assert deal['extra'] == OLD_EXTRA
    assert deal['law']['appr'] == OLD_APPR
    assert 'buyer_name' not in deal
    assert deal['buyer'] is None

    new_src = deal['src'] + [NEW_SRC_KOMMERSANT]

    print('=== status: станет ===')
    print(NEW_STATUS)
    print('\n=== title: станет ===')
    print(NEW_TITLE)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== law.appr: станет ===')
    print(NEW_APPR)
    print('\n=== buyer_name: станет ===')
    print(NEW_BUYER_NAME)
    print('\n=== src: добавится ===')
    print(NEW_SRC_KOMMERSANT)

    if write:
        deal['status'] = NEW_STATUS
        deal['title'] = NEW_TITLE
        deal['extra'] = NEW_EXTRA
        deal['law']['appr'] = NEW_APPR
        deal['buyer_name'] = NEW_BUYER_NAME
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
