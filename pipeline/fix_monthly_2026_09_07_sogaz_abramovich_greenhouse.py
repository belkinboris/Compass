def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    sg = by_id[SG_ID]
    ab = by_id[AB_ID]
    gh = by_id[GH_ID]

    assert sg.get('status') == SG_OLD_STATUS
    assert sg['eco']['context'] == SG_OLD_CONTEXT
    assert ab.get('status') == AB_OLD_STATUS
    assert ab['eco']['context'] == AB_OLD_CONTEXT
    assert gh.get('status') == GH_OLD_STATUS
    assert gh['law']['appr'] == GH_OLD_APPR
    assert gh['eco']['target_fin'] == GH_OLD_TARGET_FIN

    print('=== c0e44fb7b: status ===', SG_NEW_STATUS)
    print('=== c0e44fb7b: eco.context ===')
    print(SG_NEW_CONTEXT)
    print()
    print('=== c59e65efb: status ===', AB_NEW_STATUS)
    print('=== c59e65efb: eco.context ===')
    print(AB_NEW_CONTEXT)
    print()
    print('=== c0f002400: status ===', GH_NEW_STATUS)
    print('=== c0f002400: law.appr ===')
    print(GH_NEW_APPR)
    print('=== c0f002400: eco.target_fin ===')
    print(GH_NEW_TARGET_FIN)

    if write:
        sg['status'] = SG_NEW_STATUS
        sg['eco']['context'] = SG_NEW_CONTEXT
        ab['status'] = AB_NEW_STATUS
        ab['eco']['context'] = AB_NEW_CONTEXT
        gh['status'] = GH_NEW_STATUS
        gh['law']['appr'] = GH_NEW_APPR
        gh['eco']['target_fin'] = GH_NEW_TARGET_FIN
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
