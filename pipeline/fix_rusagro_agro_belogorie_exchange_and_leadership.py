import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g97d9fa60'

OLD_APPR = (
    'Выход на биржу стал обязательным после предписания Федеральной '
    'антимонопольной службы. Оно было выдано по итогам сделки, в рамках '
    'которой «Русагро» приобрела 100% долей в уставном капитале «ГК '
    '«Агро-Белогорье»». Ведомство потребовало, чтобы на внутренний рынок '
    'через биржу поставлялось не менее 10% продукции.'
)
NEW_APPR = OLD_APPR + (
    ' Торги фактически начались: «С 1 июля 2025 года на Национальной '
    'товарной бирже начнутся биржевые торги свиными полутушами 2 '
    'категории», «регулярно 1 раз в неделю в объеме не менее 340 тонн '
    'соответствующего товара» (Retail.ru, 30 июня 2025 года).'
)

OLD_EXTRA = (
    'В собственности РУСАГРО остается 100% ООО «Группа компаний '
    '„Агро-Белогорье”». В мае текущего года новый владелец передал 22,5% '
    'долей в доверительное управление АО «Корпорация развития», '
    'принадлежащему Белгородской области.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Гендиректор цели сменился повторно: «Генеральным директором ООО '
    '"ГК Агро-Белогорье" с 26 января стал Николай Разуваев. Он сменил '
    'в этой должности Дмитрия Лабурцева, который руководил компанией с '
    'ноября 2024 года» (ploschadnews.ru, 29 января 2026 года).'
)

NEW_SRC = [
    ['Retail.ru', 'https://www.retail.ru/news/gk-rusagro-vyvedet-na-birzhu-svoyu-produktsiyu-po-predpisaniyu-fas-30-iyunya-2025-266337/'],
    ['ploschadnews.ru', 'https://ploschadnews.ru/agro-belogore-pereshlo-pod-rukovodstvo-partnera-ee-osnovatelya-vladimira-zotova/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['law']['appr'] == OLD_APPR
    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== law.appr: станет ===')
    print(NEW_APPR)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['law']['appr'] = NEW_APPR
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
