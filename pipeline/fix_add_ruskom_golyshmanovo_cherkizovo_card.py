# -*- coding: utf-8 -*-
"""Заметка 481 (консоль, 4 сентября 2026): «Если восходагро это и есть та
самая птицефабрика в голышманово, то одна карточка, а если это разные,
то конечно заводим отдельную карточку», отвечая на карточку `ga8cb5cab»
(«Сибирский агрохолдинг "Руском" приобрел сельхозпредприятие "Восходагро"
в Тюменской области»).

Это РАЗНЫЕ юрлица (проверено самой карточкой `ga8cb5cab`: цель — ООО
«Восходагро», зерно/молоко, `eco.target_fin` цитирует выручку именно
этого юрлица по СПАРК-Интерфакс; птицефабрика в Голышманово — отдельное
ООО «Руском», ИНН 5507085811, найдено при дочитывании месячной очереди
3 сентября 2026 — «Известные проблемы», CLAUDE.md). Владелец подтвердил:
если разные — отдельная карточка. Три источника перепроверены прямым
WebFetch в этом прогоне (t.rbc.ru, meat-expert.ru, omsk.rbc.ru) — раньше
находка держалась на докладе саб-агента без прямого чтения.

Подтверждено дословным чтением: продавец — группа «Руском» (тот же
профиль `gb1814bfc`, что уже покупатель в `ga8cb5cab` — один и тот же
холдинг Темури Латарии, здесь в роли продавца другого актива); покупатель
— АО «Куриное царство» (Липецкая область), дочерняя структура ООО «АПК
«Михайловский»», которая входит в группу «Черкизово» (профиль
`gd3bb09b3`); сделка — декабрь 2024 года, сумма не раскрыта («Сумма
декабрьской сделки не раскрывается» — РБК Тюмень); юрлицо ООО «Руском»
(Голышманово) ликвидировано присоединением к АО «Куриное царство»,
процесс завершён 5 июня 2025 года.

Запуск: python3 pipeline/fix_add_ruskom_golyshmanovo_cherkizovo_card.py [--write]
"""
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'ingest'))

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

NEW_ID = 'g61b33118'


def main(write=False):
    import promote

    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    ids = {c['id'] for c in data['deals']}
    assert NEW_ID not in ids, 'id уже занят'
    assert data['companies'].get('gb1814bfc', {}).get('name') == 'Группа «Руском»'
    assert data['companies'].get('gd3bb09b3', {}).get('name') == 'Черкизово'

    draft = {
        # Известен месяц (декабрь), но не день — база хранит только
        # YYYY-MM-DD, YYYY или "unknown" (test_dates_are_parseable),
        # поэтому день не выдумывается, а месяц уходит в eco.context.
        'date': '2024',
        'title': '«Черкизово» купило птицефабрику в Голышманово у группы «Руском»',
        'ind': 'Агро',
        'type': 'M&A',
        'status': 'Закрыта',
        'asset': 'Птицефабрика в Голышманово (Тюменская область, бренд '
                 '«Богатство Сибири. Бройлер», мощность 60 тыс. тонн мяса '
                 'в год) — юрлицо ООО «Руском», ИНН 5507085811',
        'src': [['РБК Тюмень',
                 'https://t.rbc.ru/tyumen/16/05/2025/6826f65d9a794728313f2730'],
                ['Meat-Expert.ru',
                 'https://meat-expert.ru/news/18448-kompaniia-ruskom-likvidirovana-posle-sliianiia-s-cerkizovo'],
                ['РБК Омск',
                 'https://omsk.rbc.ru/omsk/16/06/2025/684fa51c9a79470180b6e1b0']],
    }
    card = promote.to_card(draft, NEW_ID)
    card['buyer'] = 'gd3bb09b3'
    card['seller_id'] = 'gb1814bfc'
    card['eco']['context'] = (
        'Продажа произошла в декабре 2024 года, сумма сделки не '
        'раскрывается. Покупатель — АО «Куриное царство» (Липецкая '
        'область), дочерняя структура ООО «АПК «Михайловский»», которая '
        'входит в группу «Черкизово». Группа «Руском», принадлежащая '
        'омскому бизнесмену Темури Латарии, после сделки продолжила '
        'работу и строит новую птицефабрику в Омской области.'
    )
    card['law']['struct'] = (
        'Процесс реорганизации ООО «Руском» (Голышманово) начался 24 '
        'февраля 2025 года: юрлицо присоединилось к АО «Куриное царство» '
        '(Липецкая область), процесс завершён 5 июня 2025 года — по '
        'данным ЕГРЮЛ, ООО «Руском» ликвидировано.'
    )

    data['deals'].append(card)
    print(f'Добавлена карточка {NEW_ID}: {card["title"]}')

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
            f.write('\n')
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
