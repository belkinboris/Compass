import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'ge30b3d32'

OLD_ECO_CONTEXT = (
    'В том же году владельца сменили несколько страховых компаний с '
    'иностранным капиталом. Группа «Интеросс» в апреле, покупая Росбанк, '
    'приобрела СК «Сосьете Женераль Страхование» и «Сосьете Женераль '
    'Страхование жизни» — теперь это «РБ страхование» и «РБ страхование '
    'жизни». В мае швейцарская Zurich Insurance Group передала российский '
    'бизнес топ-менеджерам российской компании.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' Переименование в «Гардию» подтверждено записью в '
    'ЕГРЮЛ от 27 декабря 2022 года. Уже в апреле 2023 года в холдинговую '
    'структуру компании вошёл «Лукойл» (через «К.Н.Холдинг», совместно с '
    'ЗПИФ «Газпромбанк-Фрезия») — обслуживать страховые потребности '
    'группы на фоне закрытия западных перестраховочных рынков.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
