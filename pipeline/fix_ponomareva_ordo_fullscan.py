import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g5c2831db'

OLD_LAW_STRUCT = 'Изменения в состав участников «Ордо» внесены 8 февраля, следует из ЕГРЮЛ.'
NEW_LAW_STRUCT = (
    OLD_LAW_STRUCT + ' Хозяйство ведёт посадку виноградников в '
    'Крымском районе Краснодарского края; комментировать сделку '
    'гендиректор Иван Соловьёв отказался.'
)

OLD_ECO_CONTEXT = (
    '«Океанрыбфлот» — один из крупных добытчиков рыбы в России, его '
    'квоты на вылов оцениваются более чем в 280 тыс. тонн в год. '
    'Выручка АО «Океанрыбфлот» в 2021 году выросла на 12%, до 19,47 '
    'млрд ₽, чистая прибыль составила 5,42 млрд ₽. Валерий Пономарёв в '
    '2021 году занял пятое место в рейтинге госслужащих с самыми '
    'высокими доходами — 4,18 млрд ₽.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' Помимо «Ордо», Пономарева позже стала '
    'учредителем ещё одного, более крупного винного проекта —'
    ' «Азовские игристые» в Ейске Краснодарского края: в феврале 2024 '
    'года компания выиграла на торгах комплекс по переработке '
    'винограда и планирует винодельню мощностью 5 млн бутылок '
    'игристых вин в год — это отдельный проект, не связанный с '
    'виноградниками «Ордо».'
)

OLD_SRC = [['Коммерсантъ', 'https://www.kommersant.ru/doc/5842367']]
NEW_SRC = OLD_SRC + [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6864598'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['law']['struct'] == OLD_LAW_STRUCT
    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['law']['struct'] = NEW_LAW_STRUCT
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
