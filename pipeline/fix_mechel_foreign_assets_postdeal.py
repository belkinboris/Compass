    '«дополнительный убыток в размере 1,7 млрд рублей... от вынужденной '
    'продажи угольного трейдера в Азии» (Интерфакс). Судьба завода в '
    'Литве: несмотря на смену собственника, литовская Служба '
    'расследования финансовых преступлений установила, что изменения в '
    'управлении в 2024–2025 годах не устранили зависимость «Мечел '
    'Нямунас» от находящегося под санкциями Игоря Зюзина; 29 июля '
    '2025 года компания обанкротилась с накопленными убытками 11,8 '
    'млн евро (LRT.lt). Покупатель по-прежнему нигде не назван. '
