# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g97115d14
(Sucden купила агропредприятие в Пензенской области у турецкого
агрохолдинга) — карточка не называла ни конечного бенефициара продавца,
ни прямое юрлицо-покупателя, ни механику упаковки актива перед продажей;
`extra` было пустым полем вовсе. Проверено лично прямым WebFetch
источника карточки (АК&М) и нового источника (abireg.ru).

1) `eco.context` (новое поле) — конечный бенефициар продавца. Дословно
(abireg.ru): «Конечный бенефициар – турецкий агрохолдинг Arbel Group,
который входит в AGT Food and Ingredients (канадский переработчик
бобовых и других пищевых ингредиентов)».
https://abireg.ru/newsitem/102340/

2) `law.struct` (новое поле) — прямое юрлицо-покупатель и механика
упаковки актива. Дословно (АК&М): «ООО «Агрофирма Елецкий» контролируется
французской группой Sucden» — это прямой юридический покупатель, не сам
Sucden (`buyer` карточки остаётся профилем группы Sucden — узнаваемый
бренд в заголовке, юрлицо в law.struct, тот же принцип, что уже
применён к другим карточкам). Механика: «ООО «Агро Эко Мокшан» было
создано в январе 2024 года с заявленной сферой деятельности – покупка и
продажа собственного недвижимого имущества. Через три месяца после
регистрации учредитель, наполовину принадлежащий турецкому гражданину,
увеличил уставный капитал проекта с 10 тыс. руб. до 390 млн руб.» — это
механика упаковки актива перед продажей, а НЕ цена сделки (в `sum` не
идёт).

3) `extra` (заполнено, было пустым) — краткое резюме сделки для
карточки, где раньше не было ни одного предложения пересказа.

4) `src` — добавлен abireg.ru как второй источник.

НЕ ВКЛЮЧЕНО: сумма сделки — abireg.ru прямо пишет «финансовые параметры
которой не раскрываются», независимой оценки не нашлось; консультанты —
не упомянуты ни в одном источнике; причина продажи Arbel Group (полный
выход из РФ или точечная продажа) — источники не объясняют; согласование
ФАС — не найдено; судьба актива в 2025-2026 под Sucden — собственная
страница Sucden про российский агробизнес не называет Мокшанский
район/«Агро Эко» по имени, новых фактов развития нет.

Запуск: python3 pipeline/fix_sucden_agroeko_mokshan_beneficiary_and_structure.py
        python3 pipeline/fix_sucden_agroeko_mokshan_beneficiary_and_structure.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g97115d14'

OLD_CONTEXT = (
    'Sucden работает в России с 1991 года. В середине 1990-х она стала '
    'инвестировать в развитие свеклосахарной отрасли, купив '
    'обанкротившиеся сахарные заводы. В России компании принадлежат '
    'Добринский (Липецкая область), Каменский (Пензенская область) и '
    'Тбилисский (Краснодарский край) сахарные заводы.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' Конечный бенефициар продавца — турецкий агрохолдинг Arbel Group, '
    'который входит в AGT Food and Ingredients (канадский переработчик '
    'бобовых и других пищевых ингредиентов) (abireg.ru).'
)

NEW_STRUCT = (
    'Прямой юридический покупатель — «ООО «Агрофирма Елецкий» '
    'контролируется французской группой Sucden» (АК&М). ООО «Агро Эко '
    'Мокшан» было создано в январе 2024 года с заявленной сферой '
    'деятельности «покупка и продажа собственного недвижимого имущества»; '
    'через три месяца учредитель, наполовину принадлежащий турецкому '
    'гражданину, увеличил уставный капитал проекта с 10 тыс. руб. до '
    '390 млн руб., после чего компания была продана Sucden.'
)

OLD_EXTRA = ''
NEW_EXTRA = (
    'Sucden (через ООО «Агрофирма Елецкий») приобрела ООО «Агро Эко '
    'Мокшан» — зернохранилище и элеватор в Мокшанском районе Пензенской '
    'области — у турецкого агрохолдинга Arbel Group (AGT Food and '
    'Ingredients).'
)

NEW_SRC = [
    ['abireg.ru', 'https://abireg.ru/newsitem/102340/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    assert deal['law']['struct'] == '—'
    assert deal['extra'] == OLD_EXTRA
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== law.struct: станет ===')
    print(NEW_STRUCT)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['law']['struct'] = NEW_STRUCT
        deal['extra'] = NEW_EXTRA
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
