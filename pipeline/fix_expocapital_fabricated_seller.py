# -*- coding: utf-8 -*-
"""g4ce32808 (ExpoCapital/MC Intermark Auto) несла придуманного продавца —
найдено ночной вычиткой 40 карточек (17-18 августа 2026) и подтверждено
самостоятельно: карточка ссылается ровно на ОДИН источник
(vedomosti.ru/business/news/2023/11/14/1005757-expocapital), и в его полном
тексте (data/inbox/raw, забрано fetch_article_texts.py 17.08.2026) имени
«Алина Зиннатуллина» нет вовсе — ни как продавца, ни в любой другой роли.
Источник называет только конечного прежнего собственника (японская
Mitsubishi — это уже верно перенесено в eco.share) и действующего
гендиректора («Гендиректором по-прежнему числится Леонид Сысоев» — уже
верно перенесено в law.terms дословно).

`extra` при этом утверждал: «...у основателя и генерального директора
Алины Зиннатуллиной, которая сохранила 49% акций» — это ПРОТИВОРЕЧИТ уже
показанному на той же карточке (100% долей выкуплено, значит 49% никто не
сохранял) и не подтверждается ни единым словом источника. Имя, вероятно,
выдумано на этапе разбора статьи в черновик. Убрано; оставлены только
факты, дословно подтверждённые источником.

Заодно снят осиротевший ключ `seller_src: "text"` — он указывал на «текст
источника» как основание для поля `seller`, которого на карточке никогда не
было (сам продавец в источнике не назван), то есть ссылался в никуда.

Запуск:
    python3 pipeline/fix_expocapital_fabricated_seller.py            # сухой прогон
    python3 pipeline/fix_expocapital_fabricated_seller.py --write     # запись
"""
import json
import sys

PATH = "static/data/deals_promoted.json"
ID = "g4ce32808"

OLD_EXTRA = ('Фонд ExpoCapital (принадлежащий Игорю Киму) выкупил 100% '
             'долей российской лизинговой компании MC Intermark Auto у '
             'основателя и генерального директора Алины Зиннатуллиной, '
             'которая сохранила 49% акций. Сделка закрыта 3 ноября 2023.')
NEW_EXTRA = ('Фонд ExpoCapital (принадлежащий Игорю Киму) приобрёл 100% '
             'долей российской лизинговой компании японской Mitsubishi – '
             'MC Intermark Auto; изменения зафиксированы в ЕГРЮЛ, датой '
             'появления нового учредителя указано 3 ноября 2023 года.')


def main(write):
    with open(PATH, encoding="utf-8") as f:
        base = json.load(f)
    by_id = {d["id"]: d for d in base["deals"]}
    d = by_id.get(ID)
    assert d is not None, f"{ID} не найдена"

    assert d["extra"] == OLD_EXTRA, "extra уже другой — уже правили?"
    d["extra"] = NEW_EXTRA

    assert "seller" not in d, "seller уже появился — проверьте вручную"
    assert d.get("seller_src") == "text", "seller_src уже другой — уже правили?"
    del d["seller_src"]

    print(f"{ID}: extra (снято придуманное имя продавца «Алина "
          f"Зиннатуллина»), осиротевший seller_src удалён")

    if write:
        with open(PATH, "w", encoding="utf-8") as f:
            json.dump(base, f, ensure_ascii=False, indent=1)
        print("\nЗАПИСАНО.")
    else:
        print("\nСухой прогон — ничего не записано. Добавьте --write.")


if __name__ == "__main__":
    main(write="--write" in sys.argv)
