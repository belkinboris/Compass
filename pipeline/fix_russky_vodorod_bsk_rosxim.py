import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g2ecf6ee9'
COMPANY_ID = 'g936f9597'

OLD_LAW_APPR = (
    'Федеральный пакет АО «Башкирская содовая компания» (БСК, '
    'Стерлитамак) в размере 47% передан в доверительное управление '
    '«Русскому водороду», говорится в указе президента.'
)
NEW_LAW_APPR = (
    OLD_LAW_APPR + ' Указ «О развитии акционерного общества '
    '"Башкирская содовая компания"» подписан 13 апреля 2023 года: '
    '757 343 акции переданы без проведения конкурса на право '
    'заключения договора доверительного управления.'
)

OLD_ECO_CONTEXT = (
    'Пакет, который до сих пор остаётся в собственности Российской '
    'Федерации, передан в доверительное управление другой компании. '
    'Партнёром стал «Русский водород» — компания с нужными '
    'компетенциями именно в этой сфере.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' Гендиректор «Русского водорода» с февраля 2022 '
    'года — Эдуард Давыдов, ранее уже возглавлявший саму БСК; с '
    'сентября 2022 года компанией управляет УК «Финпартнер», '
    'принадлежащая фирме «Центр-М» Владимира Дойникова и его бывших '
    'совладельцев — Дойников ранее руководил структурой Ротенбергов '
    '«СМП-Энерго», а сами Ротенберги до 2012 года числились '
    'учредителями «Центра-М». В марте 2025 года указом президента '
    'доверительное управление прекращено, а БСК исключена из перечня '
    'стратегических предприятий; в июле 2025 года «Русский водород» '
    '(с этого момента — «Росхим») стал управляющей компанией БСК — '
    'впервые с 2002 года завод перешёл от единоличного гендиректора к '
    'корпоративному управлению.'
)

OLD_SRC = [['Интерфакс', 'https://www.interfax.ru/amp/895834']]
NEW_SRC = OLD_SRC + [
    ['Ufa1.ru', 'https://ufa1.ru/text/economics/2023/04/13/72218045/'],
    ['Интерфакс', 'https://www.interfax.ru/russia/1011730'],
    ['Интерфакс', 'https://www.interfax.ru/business/1035285'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['law']['appr'] == OLD_LAW_APPR
    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC
    assert data['companies'][COMPANY_ID]['name'] == 'Росхим'

    print('=== law.appr: станет ===')
    print(NEW_LAW_APPR)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['law']['appr'] = NEW_LAW_APPR
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
