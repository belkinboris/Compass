import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'ga06c75e2'

OLD_SRC_BAD = ['Коммерсантъ', 'https://www.kommersant.ru/doc/5987046']
NEW_SRC_GOOD = ['Коммерсантъ', 'https://www.kommersant.ru/doc/6013229']

OLD_ECO_CONTEXT = (
    'Новым владельцем стал банк «Александровский», который продолжит '
    'развивать этот бизнес под брендом «А-Капитал». «БСПБ Капитал» '
    'оказывал услуги доверительного управления, инвестиционного '
    'консультирования, формирования закрытых паевых инвестиционных '
    'фондов. По данным «Эксперт РА», на конец 2021 года компания '
    'занимала 34-е место в России по объему активов под управлением, '
    'который оценивался в 17,8 млрд рублей. В банке «Санкт-Петербург» '
    'сообщили «Коммерсанту», что сделка по продаже «БСПБ Капитал» '
    'началась еще в 2022 году.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' Причину продажи банк не уточнил; источники на '
    'рынке связывали её с санкционными рисками (в феврале 2023 года '
    'банк «Санкт-Петербург» попал в SDN-лист США). 6 ноября 2024 года '
    'банк «Александровский» перепродал управляющую компанию — новым '
    'собственником, по данным ЕГРЮЛ, стало ООО «Барристер»; цена вновь '
    'не раскрывалась. В апреле 2025 года 40% доли единственного '
    'собственника УК были распределены между шестью физлицами, включая '
    'акционера банка «Санкт-Петербург» Владимира Реутова, — аналитики '
    'отметили риск конфликта интересов.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert OLD_SRC_BAD in deal['src'], 'битой ссылки уже нет — проверьте состояние'
    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    new_src = [NEW_SRC_GOOD if s == OLD_SRC_BAD else s for s in deal['src']]

    print('=== src: станет ===')
    for s in new_src:
        print(s)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)

    if write:
        deal['src'] = new_src
        deal['eco']['context'] = NEW_ECO_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
