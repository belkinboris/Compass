import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g1c5d636d'

OLD_SHARE = '—'
NEW_SHARE = (
    'В парке ПГК более 100 тыс. вагонов; компания делит первые два места'
    ' по величине парка с подконтрольной РЖД Федеральной грузовой'
    ' компанией.'
)

OLD_TARGET_FIN = '—'
NEW_TARGET_FIN = (
    'Выручка ПГК по РСБУ за 2022 год — 105,8 млрд ₽ (+19,4%), чистая'
    ' прибыль — 38,4 млрд ₽ (в 1,7 раза больше, чем годом ранее).'
)

OLD_LAW_STRUCT = '—'
NEW_LAW_STRUCT = (
    'Покупатель — АО «Аврора Инвест», зарегистрированное 12 декабря 2022'
    ' года; гендиректор на момент сделки — Елена Чайковская. Сделку'
    ' профинансировал ВТБ; в феврале 2024 года ПГК передала в залог 66,8'
    ' тыс. вагонов балансовой стоимостью более 92 млрд ₽ для'
    ' структурирования покупки. Реальные бенефициары «Авроры Инвест» в'
    ' ЕГРЮЛ и СПАРК не раскрываются.'
)

OLD_CONTEXT = '—'
NEW_CONTEXT = (
    'Сумма сделки примерно на 20% превышает цену покупки ПГК Владимиром'
    ' Лисиным в 2011–2012 годах (175,5 млрд ₽). До объявления сделки'
    ' претендентами на покупку называли «Деметра-Холдинг», «Русагротранс»'
    ' и Алексея Тайчера — все трое опровергли своё участие в переговорах.'
    ' В декабре 2024 года ВТБ вышел из капитала «Авроры Инвест», продав'
    ' 100% компании; покупателя банк не раскрыл.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['share'] == OLD_SHARE
    assert deal['eco']['target_fin'] == OLD_TARGET_FIN
    assert deal['law']['struct'] == OLD_LAW_STRUCT
    assert deal['eco']['context'] == OLD_CONTEXT

    print('=== eco.share: станет ===')
    print(NEW_SHARE)
    print('\n=== eco.target_fin: станет ===')
    print(NEW_TARGET_FIN)
    print('\n=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)
    print('\n=== eco.context: станет ===')
    print(NEW_CONTEXT)

    if write:
        deal['eco']['share'] = NEW_SHARE
        deal['eco']['target_fin'] = NEW_TARGET_FIN
        deal['law']['struct'] = NEW_LAW_STRUCT
        deal['eco']['context'] = NEW_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
