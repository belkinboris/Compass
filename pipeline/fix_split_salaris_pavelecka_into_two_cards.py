def main(write=False):
    import promote

    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    ids = {c['id'] for c in data['deals']}
    assert NEW_ID not in ids
    assert LAUT_ID not in data['companies']

    by_id = {c['id']: c for c in data['deals']}
    card = by_id['ga3376e53']
    assert card['title'] == OLD_TITLE
    assert card['sum'] == OLD_SUM
    assert card['eco']['share'] == OLD_SHARE
    assert card['eco']['val'] == OLD_VAL
    assert card['eco']['context'] == OLD_CONTEXT
    assert card['extra'] == OLD_EXTRA

    card['title'] = NEW_TITLE_PLAZA
    card['sum'] = NEW_SUM_PLAZA
    card['eco']['sum'] = NEW_SUM_PLAZA
    card['eco']['share'] = NEW_SHARE_PLAZA
    card['eco']['val'] = NEW_VAL_PLAZA
    card['eco']['context'] = NEW_CONTEXT_PLAZA
    card['extra'] = NEW_EXTRA_PLAZA
    # статус остаётся «Обсуждается» — реальный покупатель на «Павелецкую
    # плазу» так и не нашёлся, менять нечего.

    data['companies'][LAUT_ID] = {
        'name': 'АО «Лаут»',
        'ind': 'Недвижимость',
        'desc': ('Структура, связанная (через гендиректора Владимира '
                 'Мамонова) с семьёй Александра Ракшина, основателя сети '
                 '«Мария-Ра»; в декабре 2023 года купила ТРЦ «Саларис» у '
                 'Mall Management Group.'),
        'kpi': ['Профиль', 'Автоматический'],
    }

    draft = {
        'date': '2023-12-14',
        'title': 'АО «Лаут» купило ТРЦ «Саларис» у структур Сергея Гордеева',
        'ind': 'Недвижимость',
        'type': 'M&A',
        'status': 'Закрыта',
        'sum': '24–27 млрд ₽ (по оценке)',
        'src': [['РИА Недвижимость',
                 'https://realty.ria.ru/20231214/salaris-1915710810.html'],
                ['Ведомости',
                 'https://www.vedomosti.ru/realty/articles/2023/06/26/982237-aktsioner-pik-vistavil-na-prodazhu-dva-torgovo-razvlekatelnih-tsentra']],
    }
    new_card = promote.to_card(draft, NEW_ID)
    new_card['buyer'] = LAUT_ID
    new_card['seller_id'] = 'gee230aeb'
    new_card['target'] = 'g3bae551c'
    new_card['eco']['sum'] = '24–27 млрд ₽ (по оценке)'
    new_card['eco']['share'] = (
        'Торговый центр «Саларис» общей площадью 310 000 кв. м построен '
        'при транспортно-пересадочном узле (ТПУ) «Саларьево» в 2019 году.'
    )
    new_card['eco']['val'] = (
        'Консультанты оценивали сделку в 24–27 млрд ₽, точная сумма не '
        'раскрывалась.'
    )
    new_card['eco']['context'] = (
        'Новым собственником «Салариса» стало АО «Лаут», связанное через '
        'гендиректора Владимира Мамонова с семьёй Александра Ракшина — '
        'основателя сети «Мария-Ра». Изначально центр выставлялся на '
        'продажу одним пресс-релизом вместе с ТРЦ «Павелецкая плаза» '
        '(июнь 2023 года, отдельная карточка ga3376e53) — тот новый '
        'собственник за 2,5 года так и не нашёлся.'
    )

    data['deals'].append(new_card)
    print('ga3376e53 сужена до «Павелецкой плазы»')
    print(f'Добавлена карточка {NEW_ID}: {new_card["title"]}')

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
            f.write('\n')
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
