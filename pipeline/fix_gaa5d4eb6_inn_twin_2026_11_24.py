    apply(base)
    reg_src = open(REGISTRY_PATH, encoding='utf-8').read()
    strip_registry(reg_src)
    print('%s: no_inn.buyer/seller восстановлены, легальные правки на ga609f9d0/gc19f7108 откачены, '
          'реестр ИНН очищен от двух сегодняшних строк (двойник gf5bdb983 уже держит эти ИНН)' % CID)
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return 0
    base = json.load(open(DATA, encoding='utf-8'))
    apply(base)
    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(base, f, indent=1, ensure_ascii=False)
        f.write('\n')
    reg_src = open(REGISTRY_PATH, encoding='utf-8').read()
    reg_src = strip_registry(reg_src)
    with open(REGISTRY_PATH, 'w', encoding='utf-8') as f:
        f.write(reg_src)
    print('ЗАПИСАНО.')
    return 0


