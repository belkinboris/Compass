def apply(base):
    card = next(c for c in base['deals'] if c['id'] == CID)
    notes = card.get('accepted_notes') or {}
    assert (notes.get('no_profile') or {}).get('target') == OLD_NO_PROFILE_TARGET, 'no_profile.target изменился'
    assert 'buyer' not in (notes.get('no_inn') or {}), 'no_inn.buyer уже стоит — состояние изменилось'

    comps = base['companies']
    for cid, old in OLD_DESC.items():
        assert comps[cid].get('desc') == old, 'desc %s изменился: %r' % (cid, comps[cid].get('desc'))
        comps[cid]['desc'] = NEW_DESC[cid]
        comps[cid].pop('legal_short', None)

    notes['no_inn'] = dict(notes.get('no_inn') or {})
    notes['no_inn'].update(NEW_NO_INN)
    notes['checked'] = dict(notes.get('checked') or {})
    notes['checked']['registry_owners'] = NEW_REGISTRY_OWNERS
    notes['notes'] = NEW_NOTES
    notes['searched'] = NEW_SEARCHED
    card['accepted_notes'] = notes
    return card


def _strip_registry_block(src, company_id, inn):
    pattern = re.compile(
        r"\n# Приемка карточки gaa5d4eb6 — 2026-11-24 \(pipeline/ingest/accept_card\.py\)\.\n"
        r"REGISTRY \+= \[\n"
        r"    \{\"company_id\": '%s', \"decision\": \"confirmed\", \"inn\": '%s',\n"
        r"[^\]]*?\]\n" % (re.escape(company_id), re.escape(inn)))
    new_src, n = pattern.subn('\n', src)
    assert n == 1, 'блок реестра для %s/%s не найден ровно один раз (найдено %d)' % (company_id, inn, n)
    return new_src


def strip_registry(text):
    text = _strip_registry_block(text, 'ga609f9d0', '2312321973')
    text = _strip_registry_block(text, 'gc19f7108', '7743871770')
    return text


