# -*- coding: utf-8 -*-
"""Месячная очередь качества, 11 сентября 2026 — карточка `g70e51ff1»
(«JPMorgan продал акции «Роснефти»», июль 2026) уже несла честную
пустоту о покупателе и точную цену, но не называла КОНТЕКСТ сделки —
это пятая по счёту в серии похожих продаж JPMorgan и связана с
санкциями против самой «Роснефти».

Личный WebFetch подтвердил дословно:
- Investing.com (https://ru.investing.com/news/general-news/article-3329691):
  «Уведомление депозитария от 21 июля 2026 года»; «США внесли
  «Роснефть» в санкционный список SDN в октябре 2025 года»; программа
  ADR «резолвирована ещё 14 ноября 2022 года»; «до конвертации
  охватывала 4,8% капитала «Роснефти», или около 509 млн акций».
- Smart-lab (https://smart-lab.ru/blog/news/1335449.php): «Это пятая
  российская ADR-программа, проданная банком с дисконтом после
  Сбербанка, «Магнита», МТС и НМТП» — «сделка на рыночных условиях с
  покупателем, не находящимся под санкциями, с одобрением российских
  регуляторов и разрешением OFAC»; «Депозитарий получил четыре
  дивидендных выплаты… но эти выплаты сейчас находятся на счетах типа
  «С» без доступа к ним».

Покупатель и точная сумма сделки НЕ УСТАНОВЛЕНЫ ни одним из проверенных
источников (Frank Media, Investing.com, smart-lab.ru) — это уже честно
отражено в `eco.sum`, здесь не меняется.

Запуск:
    python3 pipeline/fix_jpmorgan_rosneft_series_context.py            # сухой прогон
    python3 pipeline/fix_jpmorgan_rosneft_series_context.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

NEW_ECO_CONTEXT = (
    'Это уже пятая программа депозитарных расписок, проданная JPMorgan '
    'с дисконтом после Сбербанка, «Магнита», МТС и НМТП — во всех '
    'случаях условия одинаковы: рыночная сделка с покупателем, не '
    'находящимся под санкциями, с одобрением российских регуляторов и '
    'лицензией OFAC. Программа расписок на акции «Роснефти» охватывала '
    'около 4,8% капитала компании (примерно 509 млн акций) и была '
    'закрыта ещё в ноябре 2022 года; продажа состоялась после того, как '
    'в октябре 2025 года США внесли «Роснефть» в санкционный список '
    'SDN. Дивиденды, накопленные депозитарием за это время, остаются на '
    'счетах типа «С» без доступа к ним.'
)

NEW_SRC = [
    ['Investing.com', 'https://ru.investing.com/news/general-news/article-3329691'],
    ['Smart-lab', 'https://smart-lab.ru/blog/news/1335449.php'],
]


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['g70e51ff1']

    assert d['eco'].get('context') in (None, '—'), 'eco.context уже занят: %r' % (d['eco'].get('context'),)
    urls = {s[1] for s in d['src']}
    for src in NEW_SRC:
        assert src[1] not in urls, 'источник уже добавлен: %s' % src[1]

    print('g70e51ff1: eco.context заполнен (место в серии продаж, санкции '
          'против «Роснефти», судьба дивидендов); добавлено 2 источника')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['eco']['context'] = NEW_ECO_CONTEXT
    d['src'].extend(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
