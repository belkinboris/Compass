import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g50c555a0'

OLD_LAW_STRUCT = '—'
NEW_LAW_STRUCT = (
    'Пакет в 58,26% голосующих акций собран в несколько этапов: биржевой '
    'выкуп АО «ДМК» (30 мая — 28 июля 2023, более 11 млн акций) и '
    'одновременные добровольные предложения ООО «ДМИ» (с 29 мая) и АО '
    '«ДМФА» (с 30 мая). После консолидации АО «ДМФА» направило '
    'акционерам обязательную оферту на выкуп до 307 140 398 оставшихся '
    'акций (5 октября — 14 декабря 2023, условия для нерезидентов — см. '
    '«Условия»); программа выкупа по цене 71,5 ₽ завершилась 3 ноября '
    '2023 года.'
)

OLD_ECO_VAL = '—'
NEW_ECO_VAL = (
    'Итоговая сумма всей программы нигде не подсчитана, но один из '
    'этапов биржевого выкупа (сентябрь–октябрь 2023 года) раскрыт '
    'отдельно: компания купила 2,04 млн акций за 145,7 млн ₽.'
)

OLD_ECO_CONTEXT = '—'
NEW_ECO_CONTEXT = (
    '19 сентября 2024 года само ПАО «Детский мир» было ликвидировано, а '
    'в октябре 2024 года завершился делистинг акций с Московской биржи; '
    'операционным юрлицом сети стало ООО «ДМ».'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['law']['struct'] == OLD_LAW_STRUCT
    assert deal['eco']['val'] == OLD_ECO_VAL
    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    print('=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)
    print('\n=== eco.val: станет ===')
    print(NEW_ECO_VAL)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)

    if write:
        deal['law']['struct'] = NEW_LAW_STRUCT
        deal['eco']['val'] = NEW_ECO_VAL
        deal['eco']['context'] = NEW_ECO_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
