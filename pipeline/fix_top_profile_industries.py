# -*- coding: utf-8 -*-
"""Отрасль профиля у самых активных компаний: чужие метки -> свои.

ЧТО СЛОМАНО. Отрасль профиля когда-то выводилась из сделок, и у компаний с
широкой активностью в профиль попадала отрасль ПЕРВОЙ ПОПАВШЕЙСЯ сделки:
Сбербанк значился «Медиа» (сделки с Rambler), VK — «Банки», Ростелеком —
«ИТ и интернет», Совкомбанк — «Страхование». Метка показывается на карточке
каталога и в фильтре — владелец увидел «Сбербанк · МЕДИА» на первом же
экране каталога 6 августа.

ЧТО ДЕЛАЕТ. Правит отрасль у перечисленных ниже профилей — только у них:
это выверенный руками список из топ-25 по числу сделок, а не автоматика.
Сплошную автоматическую переразметку по сделкам мы уже мерили: у широких
холдингов «мода по сделкам» даёт ту же случайную отрасль, что и сейчас.

Запуск:
    python3 pipeline/fix_top_profile_industries.py            # сухой прогон
    python3 pipeline/fix_top_profile_industries.py --write    # записать
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

# (имя профиля, отрасль сейчас, отрасль верная, почему)
FIXES = [
    ('Сбербанк', 'Медиа', 'Банки', 'банк, а не медиахолдинг'),
    ('Ростелеком', 'ИТ и интернет', 'Телеком', 'оператор связи'),
    ('VK', 'Банки', 'ИТ и интернет', 'интернет-холдинг, а не банк'),
    ('ПАО «Совкомбанк»', 'Страхование', 'Банки', 'банк; страхование — дочерний бизнес'),
    ('АФК «Система»', 'Недвижимость', 'Холдинги', 'многопрофильный холдинг'),
    ('КИВИ', 'ИТ и интернет', 'Финтех', 'платёжный сервис'),
    ('Росатом', 'ГМК и добыча', 'Энергетика', 'атомная энергетика; добыча — часть контура'),
    ('S8 Capital', 'Автопром', 'Холдинги', 'многопрофильный холдинг (шины, лифты, медиа)'),
    ('ТилТех', 'Потребительские товары', 'Управление активами', 'венчурный фонд'),
    ('Balchug Capital', 'Машиностроение', 'Управление активами', 'инвестиционная компания'),
]


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    comps = data['companies']
    by_name = {}
    for cid, c in comps.items():
        by_name.setdefault(str(c.get('name')), cid)
    for name, old, new, why in FIXES:
        cid = by_name.get(name)
        assert cid, 'профиля «%s» нет в базе' % name
        assert comps[cid].get('ind') == old, (name, comps[cid].get('ind'), old)
        print('  %-18s %-22s -> %-20s (%s)' % (name[:18], old, new, why))
        comps[cid]['ind'] = new
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return 0
    json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('Записано: %d профилей.' % len(FIXES))
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
