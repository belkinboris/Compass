import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g4b78d957'

OLD_CONTEXT = (
    'Согласно информации на сайте «РТ-Инвест», компания была создана в '
    '2012 г. при участии «Ростеха». В госкорпорации заявили РБК, что '
    'оператор «сохраняет устойчивые позиции» в сфере обращения с '
    'отходами.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' Независимый комментатор называл иную причину передачи: «на 2 млрд '
    'рублей сейчас выставили требования к дочернему предприятию '
    '"РТ-Инвеста" в связи с вредом, нанесенным природе на тех объектах, '
    'которые подведомственны ему» (Константин Крохин, председатель '
    'Жилищного союза Москвы, BFM.ru, 19 января 2024). Первый из '
    'подмосковных заводов запущен: «Первый мусоросжигательный завод '
    'ввели в эксплуатацию в Московской области» в Воскресенске, '
    'мощностью 700 тыс. тонн мусора и 520 млн кВт·ч электричества в год '
    '(zelenograd.ru, 3 февраля 2025). Татарстанский завод, заявленный на '
    '2024 год, трижды переносился: «если финансирование будет открыто в '
    'марте-апреле, то завершить строительство и ввести его в '
    'эксплуатацию удастся только в 2027 году» — из-за роста ключевой '
    'ставки и смены технологического партнёра (KazanFirst, 26 января '
    '2025).'
)

NEW_SRC = [
    ['BFM.ru', 'https://www.bfm.ru/news/542455'],
    ['Zelenograd.ru', 'https://www.zelenograd.ru/news/57084/'],
    ['KazanFirst', 'https://kazanfirst.ru/articles/otstupat-uzhe-nelzya-musoroszhigatelnyj-zavod-v-tatarstane-planiruyut-sdat-v-2027-godu'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
