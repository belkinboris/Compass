NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6137552'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/5795838'],
    ['New Retail', 'https://new-retail.ru/novosti/retail/vladelets_tts_4daily_priznan_bankrotom'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['val'] == '—'
    assert deal['eco']['context'] == '—'

    new_src = deal['src'] + NEW_SRC

    print('=== eco.val: станет ===')
    print(NEW_ECO_VAL)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['val'] = NEW_ECO_VAL
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
