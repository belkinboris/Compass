    '«Жемчужная плаза» (94 тыс. кв. м, совместно с китайской Shanghai '
    'Industrial Investment), по которому велись переговоры о продаже. '
    'В 2022 году SRV Group понесла операционный убыток €76,4 млн при '
    'выручке €770,1 млн, а списание российских активов и ослабление '
