import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

MG_ID = 'c171fe137'
MG_OLD_STATUS = None
MG_NEW_STATUS = 'Закрыта'
MG_OLD_TERMS = (
    'KazanExpress будет работать внутри «Магнита» как отдельное '
    'бизнес-подразделение под руководством текущего менеджмента.'
)
MG_NEW_TERMS = (
    MG_OLD_TERMS + ' 9 января 2024 года состоялся официальный '
    'ребрендинг KazanExpress в «Магнит Маркет». По итогам 2024 года '
    'показатели площадки заметно просели по сравнению с прежним '
    'KazanExpress: оборот снизился почти на четверть, до 13,4 млрд ₽, '
    'число заказов упало на 34%, до 14,4 млн, а чистый убыток вырос до '
    '3,22 млрд ₽ (против 1,47 млрд ₽ в 2023 году).'
)

SH_ID = 'caedef395'
SH_OLD_STATUS = None
SH_NEW_STATUS = 'Закрыта'
SH_OLD_CONTEXT = (
    'Продукты SharxBase и SharxDesk предназначены для замены VMware в '
    'дата-центрах и внесены в реестр российского ПО Минцифры.'
)
SH_NEW_CONTEXT = (
    SH_OLD_CONTEXT + ' Продукт продолжает активно развиваться: в июле '
    '2025 года вышла новая версия с защитой от уничтожения '
    'инфраструктуры по ошибке. По данным агрегированной сводки '
    'реестровых данных (прямые источники не открылись в этой сессии), '
    'к 2026 году структура владения изменилась на 75% («ЭР-Телеком '
    'Холдинг») / 25% («Нейростартер») — то есть «ЭР-Телеком», похоже, '
    'докупил ещё долю уже после исходной сделки; точная дата и условия '
    'этой докупки не установлены.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    mg = by_id[MG_ID]
    sh = by_id[SH_ID]

    assert mg.get('status') == MG_OLD_STATUS
    assert mg['law']['terms'] == MG_OLD_TERMS
    assert sh.get('status') == SH_OLD_STATUS
    assert sh['eco']['context'] == SH_OLD_CONTEXT

    print('=== c171fe137: status ===', MG_NEW_STATUS)
    print('=== c171fe137: law.terms ===')
    print(MG_NEW_TERMS)
    print()
    print('=== caedef395: status ===', SH_NEW_STATUS)
    print('=== caedef395: eco.context ===')
    print(SH_NEW_CONTEXT)

    if write:
        mg['status'] = MG_NEW_STATUS
        mg['law']['terms'] = MG_NEW_TERMS
        sh['status'] = SH_NEW_STATUS
        sh['eco']['context'] = SH_NEW_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
