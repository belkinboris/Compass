# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка gefb52584
(Александр Удодов приобрел контроль над ООО «Трансхим», август 2024).
Дельта-поиск нашёл в ТОМ ЖЕ источнике карточки (Коммерсантъ) факты,
которые не были перенесены при первом разборе — включая финансы предмета,
уже лежавшие в тексте. Проверено лично прямым WebFetch.

1) `law.struct` (дополнение) — профиль покупателя и продавца из того же
источника: «Бывший топ-менеджер «Итеры», совладелец крупнейшего в РФ
предприятия по производству шампиньонов Александр Удодов» — «Ранее он
состоял в браке с сестрой премьер-министра Михаила Мишустина Натальей
Стениной, но в декабре 2020 года они развелись» (родство упомянуто
самим Коммерсантом как объяснение медийного интереса к сделке, а не наша
находка). Продавец: «руководитель культурного благотворительного фонда
«Артэс»» Александр Достман, контролирующий также «30% в ООО «Медцентр на
Мясницкой»».

2) `eco.context` (дополнение) — судьба завода после сделки, независимый
реестр (saby.ru, проверено лично прямым WebFetch): юрлицо действует,
владелец с 13.11.2024 — «Оптима Инвест, АО» (подтверждает закрытие),
но план на 90 тыс. тонн в год не реализован — независимых новостей о
запуске производства в 2025-2026 не нашлось, завод остаётся убыточным.

НЕ включены: сумма сделки, консультанты, мотив продажи Достмана — ни
один источник их не называет; сам он на вопросы Коммерсанта не ответил.

Запуск: python3 pipeline/fix_udodov_transhim_profile_and_finances.py
        python3 pipeline/fix_udodov_transhim_profile_and_finances.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gefb52584'

OLD_STRUCT = (
    'До передачи господину Удодову бенефициаром ООО «Трансхим» через ООО '
    '«Дезимпэкс» выступал продюсер Александр Достман'
)
STRUCT_ADDITION = (
    '. Удодов — «бывший топ-менеджер «Итеры», совладелец крупнейшего в '
    'РФ предприятия по производству шампиньонов»; «ранее он состоял в '
    'браке с сестрой премьер-министра Михаила Мишустина Натальей '
    'Стениной, но в декабре 2020 года они развелись» (Коммерсантъ). '
    'Достман — «руководитель культурного благотворительного фонда '
    '«Артэс»», контролирует также 30% в ООО «Медцентр на Мясницкой».'
)
NEW_STRUCT = OLD_STRUCT + STRUCT_ADDITION

OLD_CONTEXT = (
    'ООО «Трансхим» было создано на волне пандемии летом 2020 года. '
    'Заключенное с властями Тульской области соглашение предполагало '
    'размещение в городе Суворове производства мощностью до 90 тыс. тонн '
    'продукции в год, вложения в которое оценивались в 400 млн руб.'
)
CONTEXT_ADDITION = (
    ' Независимый реестр подтверждает закрытие сделки (владелец с '
    '13.11.2024 — АО «Оптима Инвест»), но план на 90 тыс. тонн в год не '
    'реализован — новостей о запуске производства в 2025-2026 годах не '
    'нашлось, юрлицо остаётся убыточным (saby.ru).'
)
NEW_CONTEXT = OLD_CONTEXT + CONTEXT_ADDITION

NEW_SRC = [
    ['СБИС', 'https://saby.ru/profile/7107136141-710701001'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['law']['struct'] == OLD_STRUCT
    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== law.struct: станет ===')
    print(NEW_STRUCT)
    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['law']['struct'] = NEW_STRUCT
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
