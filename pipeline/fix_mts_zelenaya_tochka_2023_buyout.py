import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g64831887'

OLD_LAW_STRUCT = (
    'В апреле 2021 года МТС исполнила первый опцион и купила 49% в 7 '
    'операторах, которые работали в 5 городах: Ставрополе, Михайловске, '
    'Невинномысске, Элисте и Тамбове.'
)
NEW_LAW_STRUCT = (
    OLD_LAW_STRUCT + ' В мае 2023 года МТС реализовала опцион по '
    'выкупу оставшихся 49% ещё в шести региональных операторах группы, '
    'в их числе ООО «Зеленая точка» (Белгород), ООО «Зеленая точка '
    'Липецк», ООО «Зеленая точка Уфа» (обслуживает также Нефтекамск и '
    'Белорецк), ООО «Зеленая точка Томск» и ООО «Зеленая точка '
    'Владивосток», — завершив консолидацию 100% группы. Совладельцами '
    'белгородского оператора были Владимир Черкашин, Александр Каверин '
    'и Дмитрий Швед, остальные компании принадлежали кипрскому офшору '
    'Clarkia Holdings Ltd.'
)

OLD_ECO_RATIONALE = None
NEW_ECO_RATIONALE = (
    'Основная цель полной консолидации «Зеленой точки» для МТС — '
    'предложить её абонентам нетелекоммуникационные сервисы компаний '
    'цифровой экосистемы. Завершение сделки означает, что около 1 млн '
    'человек в 12 городах России получают расширенный доступ к '
    'конвергентным сервисам экосистемы МТС.'
)

OLD_SRC = [['Интерфакс', 'https://www.interfax.ru/business/898681']]
NEW_SRC = OLD_SRC + [
    ['ComNews', 'https://www.comnews.ru/content/225914/2023-05-03/2023-w18/mts-vpisala-zelenuyu-tochku-krasnyy-kvadrat'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['law']['struct'] == OLD_LAW_STRUCT
    assert deal['eco'].get('rationale') == OLD_ECO_RATIONALE
    assert deal['src'] == OLD_SRC

    print('=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)
    print('\n=== eco.rationale: станет ===')
    print(NEW_ECO_RATIONALE)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['law']['struct'] = NEW_LAW_STRUCT
        deal['eco']['rationale'] = NEW_ECO_RATIONALE
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
