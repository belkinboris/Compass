import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g96b1cdaf'

OLD_ECO_CONTEXT = (
    'Enel продала все свои генерирующие мощности в России: 5,6 ГВт '
    'традиционной генерации — три крупные ГРЭС — и 300 МВт ветровой. '
    'Покупателями стали «Лукойл» и «Газпромбанк-Фрезия», структура '
    'Газпромбанка. Сумма сделки составила около 137 млн евро.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' Оферту миноритариям почти никто не принял: '
    'спустя два года у них по-прежнему оставалось 28,83% акций. Доля '
    'ЛУКОЙЛа выросла не через оферту, а через отдельную покупку 7,4% '
    'у UROC Limited (разрешение президента — декабрь 2023 года,'
    ' закрытие — январь 2024-го) — до 63,84%, а к январю 2025 года — '
    'до 65,63%. В апреле 2026 года ЭЛ5-Энерго завершила реорганизацию, '
    'присоединив АО «ВДК-энерго» и ООО «Лукойл-экоэнерго»: число '
    'станций выросло с 5 до 25, мощность — до 9,5 ГВт; доля ЛУКОЙЛа '
    'при этом не изменилась (реорганизация прошла путём конвертации '
    'акций, без денежных расчётов).'
)

OLD_SRC = [['Ведомости', 'https://www.vedomosti.ru/business/news/2023/01/09/958384-lukoil-poluchil-el5-energo']]
NEW_SRC = OLD_SRC + [
    ['Smart-lab', 'https://smart-lab.ru/blog/869008.php'],
    ['Интерфакс', 'https://www.interfax.ru/business/942089'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8195550'],
    ['Finance Mail.ru', 'https://finance.mail.ru/article/el5-energo-zavershilo-protsess-prisoedineniya-novyih-aktivov-69203657/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
