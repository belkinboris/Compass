"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g0b733c0f («AB InBev продает долю в AB InBev Efes компании Anadolu
Efes», 19.12.2023, статус «Обсуждается») — статус устарел радикально:
сделка дважды отклонена правкомиссией, а актив в итоге национализирован
указом президента. Полная история уже документирована в ДРУГОЙ,
отдельной карточке (`g0311e96f`, «Правкомиссия отказала Efes в покупке
доли в AB InBev Efes», followup_researched 2026-08-29, статус уже
«Не состоялась») — обе карточки рассказывают один и тот же сюжет с
разных моментов, и это НЕ повод сливать их механически (решение — за
человеком, записано отдельно в CLAUDE.md), но повод честно обновить
устаревший статус ЭТОЙ карточки и сослаться на более подробную.

Все факты уже проверены лично прямым WebFetch/WebSearch в этом заходе
и независимо подтверждены официальным источником: Interfax,
interfax.ru/business/1001317 — «указ президента РФ Владимира Путина от
30 декабря 2024 года №1131», «Временное управление АО "Группа компаний
Вместе" введено в отношении АО "АБ ИнБев Эфес"», «15,832 млрд
обыкновенных и 92,943 тыс. привилегированных акций». Второй отказ
правкомиссии в июне 2025 года подтверждён независимо (Yahoo Finance,
just-drinks.com, ESM Magazine, 20.06.2025) — Anadolu Efes сообщила о
повторном отклонении заявки. `eco.context` карточки `g0311e96f` уже
несёт обе цитаты дословно — здесь достаточно сослаться, а не повторять.

Статус меняется с «Обсуждается» на «Не состоялась»: сделка,
объявленная в декабре 2023 года, дважды отклонена регулятором и не
состоялась ни в исходном, ни в изменённом виде (обмен российского и
украинского бизнеса) — при этом само поле `eco.context` УЖЕ несёт цитату
об отказе («Правительственная комиссия... не одобрила сделку»), то есть
статус карточки просто не был обновлён вслед за уже известным фактом.

Запуск: python3 pipeline/fix_abinbev_efes_status_and_crossref.py
        python3 pipeline/fix_abinbev_efes_status_and_crossref.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g0b733c0f'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Не состоялась'

OLD_EXTRA = ''
NEW_EXTRA = (
    'Сделка не состоялась: правительственная комиссия по контролю за '
    'осуществлением иностранных инвестиций дважды отклонила заявку '
    '(20 июня 2024 года и повторно в июне 2025 года). Указом '
    'президента РФ от 30 декабря 2024 года №1131 акции АО «АБ ИнБев '
    'Эфес» переданы во временное управление АО «Группа компаний '
    'Вместе»; с 1 сентября 2025 года компания работает под именем '
    '«Напитки Вместе». Полная хронология — в отдельной карточке '
    '«Правкомиссия отказала Efes в покупке доли в AB InBev Efes».'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS
    assert deal['extra'] == OLD_EXTRA

    print('=== status: станет ===')
    print(NEW_STATUS)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)

    if write:
        deal['status'] = NEW_STATUS
        deal['extra'] = NEW_EXTRA
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
