# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка ga218f75c (Акульчев/
кондитерская фабрика «Колос»): дельта-поиск нашёл судьбу бренда «Руслада»
— дистрибуционного бизнеса, который в сделку НЕ вошёл и остался у
продавца Светланы Сулеймановой (это уже зафиксировано в law.struct). Три
месяца спустя обе компании бренда столкнулись с исками о банкротстве от
налоговой. Не через review.py: поле `extra` уже несёт текст о финансовом
консультанте сделки из другого источника.

Источник — читал напрямую (fetch_article_texts.py, закэширован):
sweetinfo.ru (03.06.2026), со ссылкой на картотеку арбитражного суда.
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'ga218f75c'
OLD_EXTRA = (
    'Финансовый консультант сделки — Unicorn Capital. Эксперт BGP Capital '
    'Иван Пешков дал экспертную оценку стоимости сделки.'
)
ADDITION = (
    'Бренд «Руслада» (дистрибуционный бизнес, не вошедший в сделку) три '
    'месяца спустя столкнулся с исками о банкротстве: Межрайонная '
    'инспекция ФНС №4 по Башкирии подала в Арбитражный суд Челябинской '
    'области заявления о признании банкротами ООО «Руслада» (задолженность '
    'по страховым взносам — 1,8 млн рублей, по налогу — 6,2 млн рублей, '
    'пени — 1,1 млн рублей) и ООО «Торговый дом «Руслада»» (обязательства '
    'перед бюджетом на 6 млн рублей); собственником и директором обеих '
    'компаний по-прежнему остаётся Светлана Сулейманова.'
)
NEW_EXTRA = OLD_EXTRA + ' ' + ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['extra'] == OLD_EXTRA, f"extra: неожиданное значение {deal['extra']!r}"

    print(f"{CARD_ID} extra: += судьба «Руслады» (иски о банкротстве, июнь 2026)")
    deal['extra'] = NEW_EXTRA

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
