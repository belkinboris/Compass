# -*- coding: utf-8 -*-
"""Дозакрытие класса, найденного 28 августа 2026 на карточке АСТОР/Ростелеком
(см. fix_astor_rostelecom_law_terms.py): пресс-релизная фраза-заверение
клиентам ЦЕЛИ (или самого покупателя — направление то же) не является
условием СДЕЛКИ и не должна стоять в `law.terms`.

ЗАМЕР ПО ВСЕЙ БАЗЕ (регэксп на маркеры первого лица мн. числа —
«наш\w*», «мы\s» — в law.terms/law.struct, 15 кандидатов; большинство —
ложные срабатывания: имя собственное («Наше радио», «Наш союз» — часть
названия компании/актива), журналистское «мы уже писали» (голос издания,
не стороны сделки) или настоящие условия/структура сделки с атрибуцией
(Unilever/Арнест: «важной составляющей сделки», прямо сказано; Rockwool:
инвестобязательство с именем и должностью; Альфа-банк/Европлан и
Inweasta/ППФ: описание реальной пост-сделочной структуры). Три карточки —
подтверждённые случаи того же класса, что и АСТОР, проверены живым
поиском источника на атрибуцию и содержание:

- `gdf44a92b` (SkyNet/«Фартел»): «мы продолжим оказывать услуги под
  брендом Fartel... тарифы, контакты и условия обслуживания остаются без
  изменений» — обращено к АБОНЕНТАМ приобретённого провайдера, без
  единого структурного факта сделки.
- `g37737226` (Selectel/servers.ru): «для всех клиентов... сохранятся
  условия предоставления услуг» — проверено (WebFetch пресс-релиза
  Selectel): атрибутировано Олегу Любимову, гендиректору Selectel, но
  адресовано клиентам servers.ru, а не описывает условие сделки —
  атрибуция здесь не спасает: критерий из CLAUDE.md про линзу «Юрист» —
  «кому и о чём фраза», а не «есть ли автор».
ПРОВЕРЕН И ОТКЛОНЁН как кандидат того же класса: `gbd5ad233` (Kokoc
Group/Players Team) — «мы планируем... предложили Василию Ящуку
возглавить... дивизион». WebFetch источника подтвердил атрибуцию
(Александр Шокуров, гендиректор Kokoc Group), но, в отличие от трёх
карточек выше, фраза не обращена к клиентам цели — это удержание
основателя предмета сделки в структуре покупателя (назначение на
руководство новым дивизионом), тот же класс, что уже одобрен в CLAUDE.md
для линзы «Юрист» («обязательства сохранить бренд, команду,
производство — часто единственное «условие», которое вообще раскрывают в
российских сделках», см. также «Свеза»/Mayr-Melnhof — «намерены сохранить
текущую команду»). Оставлен как есть.

Запуск: python3 pipeline/fix_law_terms_client_reassurance_batch1.py
        python3 pipeline/fix_law_terms_client_reassurance_batch1.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

FIXES = [
    ('gdf44a92b',
     'В ближайшее время мы продолжим оказывать услуги под брендом Fartel, чтобы переход был '
     'максимально удобным и прозрачным. Все действующие тарифы, контакты и условия обслуживания '
     'остаются без изменений'),
    ('g37737226',
     'Важнейшей задачей для нас является поддержка отказоустойчивости инфраструктуры наших '
     'заказчиков — для всех клиентов ООО «Единая сеть» сохранятся условия предоставления услуг и '
     'гарантии по уровню надежности сервисов'),
]


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    by_id = {c['id']: c for c in data['deals']}

    for cid, old in FIXES:
        card = by_id.get(cid)
        assert card is not None, '%r не найдена в deals_promoted.json' % cid
        assert card['law'].get('terms') == old, (
            'ожидали law.terms=%r у %s, сейчас %r — состояние изменилось'
            % (old, cid, card['law'].get('terms')))
        print('ПРАВИМ %s (%s): law.terms -> «—»' % (cid, card['title'][:60]))

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    for cid, _ in FIXES:
        by_id[cid]['law']['terms'] = '—'
    json.dump(data, open(DATA, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('Записано: %d карточек.' % len(FIXES))


if __name__ == '__main__':
    main(write='--write' in sys.argv)
