import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gcf0f7334'

OLD_CONTEXT = (
    'Петербургский холдинг «Адамант» владеет 50 предприятиями и 22 '
    'торговыми центрами. Основной бенефициар — Игорь Лейтис'
)
NEW_CONTEXT = OLD_CONTEXT + (
    '. Оба завода объединены под зонтичным брендом AIG (Argentum '
    'Innovation Group). В сентябре 2025 года на Клинском заводе '
    'запущена новая линия «Клин-1»: инвестиции 8,5 млрд ₽, мощность '
    'до 600 тонн стекла в сутки, создано 87 рабочих мест — заявленный '
    'план всей модернизации превышает 13 млрд ₽ с завершением в 2026 '
    'году. В 2025 году доли обоих заводов консолидированы на новом '
    'держателе внутри той же структуры — АО «Управляющая компания» '
    '(Санкт-Петербург), сделка одобрена ФАС в апреле 2025 года.'
)

NEW_SRC = [
    ['asninfo.ru', 'https://m.asninfo.ru/news/121016-boleye-8-mlrd-rubley-vlozhili-v-modernizatsiyu-proizvodstva-klinskiy-stekolnyy-zavod-v-podmoskovye'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/7957176'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
