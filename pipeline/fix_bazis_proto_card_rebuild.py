# -*- coding: utf-8 -*-
"""Карточка «Базис»/Proto: стороны кликабельны, тип — покупка, продавцы названы.

Замечание владельца 7 сентября 2026 по черновику в консоли: «черновик карты
сформирован очень некачественно… отмечен как инвестиция, в структуре сделки
нет ни предмета, ни продавца, зато есть инвестор «Базис», на которого нажать
нельзя… продавцы тоже видны в статье». Всё верно, и всё было в источниках,
уже стоявших у карточки, — приток их не разобрал.

Что делает скрипт.
1. Заводит два профиля компаний, которых в базе не было: «Базис» и ООО
   «Протосервисез» (бренд Proto). Пока профилей нет, покупатель и предмет
   на экране — просто текст, по нему некуда нажать.
2. Привязывает к ним стороны карточки: `buyer` → «Базис» (вместо текстового
   `buyer_name`), `target` → «Протосервисез» (вместо текстового `asset`).
3. Ставит продавцами Дениса Бескоровайного и Надежду Фердман — по
   «Ведомостям»: «До приобретения доли по 50% находилось в собственности у
   его гендиректора Дениса Бескоровайного и Надежды Фердман».
4. Меняет тип с «Инвестиция» на «M&A»: куплено 70%, то есть сменился
   контроль, а «Инвестиция» на экране читается как миноритарное вложение.

Оговорка, которую стоит держать в голове (и которая осталась в «Структуре
сделки», а не потерялась): деньги по обоим источникам пошли САМОЙ компании
(«Покупатель вложил деньги в капитал фирмы», Ведомости; «Сделка реализована
путем внесения в капитал Proto денежных средств», CNews), а у основателей
осталось 30%. Строго говоря, их доли размылись, а не были проданы, и ни один
источник не пишет, кто именно из двоих продал. Но контроль перешёл, и
называть это инвестицией с пустым продавцом — хуже: читатель не узнаёт ни
того, что компания сменила владельца, ни того, у кого она была раньше.

Имя основателя пишется как у «Ведомостей» — «Бескоровайный»; у CNews в той
же новости «Безкоровайный», и это тот случай, когда источники расходятся
между собой (см. CLAUDE.md, урок про «Флеганова»/«Ферганова»).

Запуск: python3 pipeline/fix_bazis_proto_card_rebuild.py [--write]
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / 'static' / 'data' / 'deals_promoted.json'
PENDING = ROOT / 'static' / 'data' / 'pending.json'

DEAL_ID = 'g95370469'
BAZIS_ID = 'gc30e392d'
PROTO_ID = 'g01320fb7'
BAZIS = {'name': '«Базис»', 'ind': 'ИТ и интернет',
         'desc': 'Российский разработчик инфраструктурного программного обеспечения: '
                 'серверная виртуализация и управление ИТ-инфраструктурой.',
         'kpi': ['Профиль', 'Автоматический']}
PROTO = {'name': 'ООО «Протосервисез»', 'ind': 'ИТ и интернет',
         # Описание нарочно не пересказывает заголовок сделки и строку
         # «Предмет» в посте («разработчик платформы для наблюдаемости и
         # анализа IT-систем») — иначе пост дважды подряд говорит одно и то
         # же. Здесь то, чего в сделке нет: где и с какого года компания.
         'desc': 'Московская компания, работает с 2014 года; её платформа Proto '
                 'следит за состоянием ИТ-систем и разбирает данные об их работе.',
         'kpi': ['Профиль', 'Автоматический']}
SELLER = 'Денис Бескоровайный и Надежда Фердман'
# «Структура сделки» переписана целиком, а не дополнена хвостом: первая
# версия говорила «продающей стороны в такой сделке нет» и тут же соседствовала
# с заполненным полем «Продавец» — карточка спорила сама с собой, и механизм
# был описан дважды. Итоговый текст объясняет то же самое одним куском.
STRUCT = ('Доля 70% возникла у «Базиса» вкладом в капитал: покупатель внёс в ООО '
          '«Протосервисез» деньги, поэтому доли основателей уменьшились со 100% до '
          '30%, а не были выкуплены, — объём вложений не раскрывается. До сделки '
          'уставный капитал (25 тыс. ₽) был поровну разделён между Денисом '
          'Бескоровайным и Надеждой Фердман; за ними осталось 30%. ООО '
          '«Протосервисез» войдёт в группу «Базис» как дочерняя, её финансовые '
          'результаты будут учитываться в отчётности группы.')


def main(write: bool) -> None:
    base = json.loads(BASE.read_text(encoding='utf-8'))
    pend = json.loads(PENDING.read_text(encoding='utf-8'))
    card = {c['id']: c for c in pend['cards']}[DEAL_ID]
    comps = base['companies']

    assert card['title'].startswith('«Базис» купил 70%'), 'заголовок изменился — проверьте карточку руками'
    for cid in (BAZIS_ID, PROTO_ID):
        assert cid not in comps or comps[cid]['name'] in (BAZIS['name'], PROTO['name']), \
            f'id {cid} занят чужим профилем'
    print(f'{DEAL_ID}: «{card["title"]}»')
    print(f'  профиль покупателя  {BAZIS_ID}  {BAZIS["name"]}'
          + ('  (уже есть)' if BAZIS_ID in comps else '  (заводим)'))
    print(f'  профиль предмета    {PROTO_ID}  {PROTO["name"]}'
          + ('  (уже есть)' if PROTO_ID in comps else '  (заводим)'))
    print(f'  buyer_name {card.get("buyer_name")!r} → buyer {BAZIS_ID}')
    print(f'  asset      {card.get("asset")!r} → target {PROTO_ID}')
    print(f'  seller     {card.get("seller")!r} → {SELLER!r}')
    print(f'  type       {card.get("type")!r} → \'M&A\'')
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    # Профиль перезаписывается целиком, а не только заводится: описание
    # правилось после первого прогона, и `setdefault` оставил бы старое.
    comps[BAZIS_ID] = BAZIS
    comps[PROTO_ID] = PROTO
    card['buyer'] = BAZIS_ID
    card['buyer_name'] = None
    card['target'] = PROTO_ID
    card['asset'] = None
    card['seller'] = SELLER
    card['type'] = 'M&A'
    struct = (card.get('law') or {}).get('struct') or ''
    assert struct == STRUCT or 'внесени' in struct or 'вкладом в капитал' in struct, \
        '«Структура сделки» не о вкладе в капитал — проверьте карточку руками'
    card['law']['struct'] = STRUCT
    BASE.write_text(json.dumps(base, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
    PENDING.write_text(json.dumps(pend, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
