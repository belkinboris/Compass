# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка gc2a1693a (ВТБ приобрел банк
«Открытие»): дельта-поиск нашёл, что стало со сделкой ПОСЛЕ закрытия —
уход прежней команды правления и полное завершение интеграции бренда (два
факта из двух разных источников, поэтому не через review.py — он
проверяет цитату как непрерывный кусок ОДНОГО кэшированного текста).

Источники — читал напрямую (fetch_article_texts.py, оба закэшированы):
Интерфакс (29.12.2022, business/879143) и Интерфакс (09.01.2025,
business/1002133).
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gc2a1693a'
OLD_EXTRA = (
    'Центробанк сообщил о закрытии сделки по продаже банка «Открытие» '
    'банку ВТБ. ВТБ выполнил обязательства по оплате акций в полном '
    'объеме.'
)
ADDITION = (
    '31 декабря 2022 года правление банка «Открытие» покинула прежняя '
    'команда: «31 декабря правление банка покидают Михаил Задорнов, '
    'Дмитрий Левин, Надия Черкасова, Светлана Емельянова, Наталья '
    'Смирнова, Виктор Николаев и Ирина Кремлева». 9 января 2025 года ВТБ '
    'завершил перевод отделений «Открытия» под свой бренд: «Сегодня мы '
    'завершаем один из самых масштабных проектов в области банковской '
    'инфраструктуры, его география охватывает почти 70% территории '
    'страны и представлена от Калининграда до Петропавловска-Камчатского», '
    '— заявил член правления ВТБ Руслан Еременко. Согласно данным ЕГРЮЛ, '
    'с 1 января 2025 года банк «Открытие» присоединился к БМ-банку '
    '(бывший Банк Москвы, входит в группу ВТБ) и прекратил свою '
    'деятельность.'
)
NEW_EXTRA = OLD_EXTRA + ' ' + ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['extra'] == OLD_EXTRA, f"extra: неожиданное значение {deal['extra']!r}"

    print(f"{CARD_ID} extra: += уход правления и завершение интеграции бренда")
    deal['extra'] = NEW_EXTRA

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
