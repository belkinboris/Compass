# -*- coding: utf-8 -*-
"""Месячная очередь, карточка g0748e794 («Росспиртпром»/«Башспирт»,
обсуждается): дельта-поиск нашёл, что глава Башкортостана Радий
Хабиров 12-13 августа 2026 года публично заявил, что республика
приватизацию не планирует. Это не формальное «сделка сорвалась» (нет
слова из закрытого списка STATUS_WORDS) — статус не меняем
механически, тот же класс, что уже описан в «Известных проблемах» для
БКС/«Форштадт» и Газпромбанк/«Медскан». Не через `review.py`: источник
(bashinform.ru) не образует с уже записанным текстом `eco.context»
(из другого материала, про историю самого «Росспиртпрома») непрерывный
кусок.

Источник — читал напрямую (WebFetch, дословная цитата подтверждена):
https://www.bashinform.ru/news/economy/2026-08-13/vlasti-bashkirii-opredelilis-s-prodazhey-aktivov-4661269

Запуск: python3 pipeline/fix_rosspirtprom_bashspirt_denial_context.py [--write]
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g0748e794'

OLD_CONTEXT = (
    '«Росспиртпром» создан в 2009 году на базе одноименного '
    'Федерального государственного унитарного предприятия. В его '
    'периметр входят восемь спиртовых заводов по всей стране. Весной '
    '2024 года за 8,289 млрд руб. компанию приватизировало ООО '
    '«Бизнес Альянс», принадлежащее бывшему топ-менеджеру Тройка-Д '
    'банка Владимиру Акаеву. Как следует из ЕГРЮЛ, сейчас в его '
    'собственности находится 49% в ООО «Бизнес Альянс». 51% бизнеса с '
    'июля прошлого года через ООО «Опал» принадлежит ЗПИФ «Батман», '
    'пайщики которого не раскрываются.'
)
CONTEXT_ADDITION = (
    ' 13 августа 2026 года глава Башкортостана Радий Хабиров публично '
    'заявил о судьбе «Башспирта»: «зачем продавать? Он работает, мы '
    'открыли пять лет назад новое производство, оно сильно нам '
    'помогает» — по итогам разговора издание сделало вывод, что '
    '«Башспирт» останется в собственности республики.'
)
NEW_CONTEXT = OLD_CONTEXT + CONTEXT_ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f'{CARD_ID} eco.context: += публичное заявление главы '
          f'Башкирии о том, что продавать не планируют')

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('ЗАПИСАНО')
    else:
        print('Сухой прогон. Запись — с --write.')


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
