import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gf652a925'

OLD_DATE = '2022-08-01'
NEW_DATE = '2024-02-05'

OLD_STATUS = 'Подписана'
NEW_STATUS = 'Закрыта'

OLD_EXTRA = (
    'Grundfos подписал соглашение с руководством российского '
    'подразделения о продаже двух дочерних компаний в России. Сделка '
    'позволяет новым владельцам вести независимый бизнес в России и '
    'Беларуси. Бренд Grundfos и права на интеллектуальную собственность '
    'остаются у Grundfos. Одобрение органами России, Дании и ЕС '
    'ожидалось к концу Q1 2023 года. Единовременные расходы оценены в '
    '851 млн датских крон (более $113,5 млн).'
)
NEW_EXTRA = (
    'Grundfos продал две российские «дочки» их же менеджменту: завод в '
    'Истре — указом президента от 5 февраля 2024 года разрешена продажа '
    'ООО «ИСТРАТЕХ Групп» (совладельцы — гендиректор завода Анатолий '
    'Слободинский, 60%, и Инна Маренкова, 40%); сбытовая компания — '
    'переименована в ООО «Вандйорд» с 11 июля 2024 года. Бренд Grundfos '
    'и права на интеллектуальную собственность остались у самого '
    'концерна. Единовременные расходы Grundfos на выход оценены в 851 '
    'млн датских крон (более $113,5 млн).'
)

OLD_ECO_CONTEXT = 'Сделка положит конец 23-летнему присутствию Grundfos в России.'
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' Обе части сделки закрылись в 2024 году: завод — '
    'через указ президента (5 февраля), сбытовая структура — '
    'переименованием юрлица (11 июля). Независимый источник (спор о '
    'взыскании долга между «Истратехом» и «Вандйордом») подтверждает: '
    '«обе компании до 2024 года контролировались датским холдингом '
    'Grundfos».'
)

OLD_SRC = [['СКАН-Интерфакс', 'https://web.scan-interfax.ru/app/document/view/SMI2023A::593015:10099']]
NEW_SRC = OLD_SRC + [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6493459'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8922804'],
    ['C-O-K.ru', 'https://www.c-o-k.ru/market_news/vandyord-novoe-imya-grundfos-v-rossii'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['date'] == OLD_DATE
    assert deal['status'] == OLD_STATUS
    assert deal['extra'] == OLD_EXTRA
    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== date/status: станет ===')
    print(NEW_DATE, '|', NEW_STATUS)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['date'] = NEW_DATE
        deal['status'] = NEW_STATUS
        deal['extra'] = NEW_EXTRA
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
