# -*- coding: utf-8 -*-
"""Заметка 484 (консоль, 4 сентября 2026): «Это можно рассказать в
контексте наверное, но Перепроверь конечно», отвечая на карточку
`gef939ff4» (СБК Премьер/«Донской антрацит»/«Обуховская»).

Известная проблема (CLAUDE.md) держала эти факты на докладе саб-агента
без прямого чтения («большинство прямых ссылок RBC/TASS/tadviser отдают
401/403/404»). Перепроверено прямым WebFetch в этом прогоне по трём
источникам:

- Коммерсантъ (kommersant.ru/doc/6467547) — указ президента от 25
  января 2024 года разрешил АО «Лучшее решение» купить у Fabcell
  Limited 100% акций «Донского антрацита» и «Обуховской».
- РИА Новости (ria.ru/20260331/sud-2083965374.html) — Арбитражный суд
  Москвы 31 марта 2026 года взыскал с Fabcell Limited по иску
  Сбербанка около $12,3 млн долга по кредитной линии (в т.ч. $12,1 млн
  просроченного долга).
- Коммерсантъ (kommersant.ru/doc/8710294) — торги 2 июня 2026 года по
  продаже лота (права требования Сбербанка на $400 млн, вексельные
  права на 2,75 млрд ₽ и контроль над обеими шахтами) не состоялись:
  «не было подано ни одной заявки». Организатор — «Ассет Менеджмент».

Три факта добавлены в `eco.context` одним связным текстом — это не
единая цитата (три разных источника), поэтому правка идёт этим
одноразовым скриптом, а не через review.py.

Запуск: python3 pipeline/fix_donskoy_antratsit_postdeal_verified.py [--write]
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gef939ff4'

OLD_CONTEXT = (
    'В ноябре 2021 года Сбербанк на торгах продал кипрской Valleyton '
    'Investments акции обоих предприятий и права требования по выданным '
    'им кредитам. Сумма сделки составила $230 млн, а задолженность по '
    'синдицированному кредиту, по документации к торгам, — $446,8 млн. '
    'К моменту сделки с «СБК Премьер» акции числились уже за другой '
    'кипрской структурой — Fabcell Limited; её бенефициаром в марте '
    '2022 года называли Искендера Халилова, что оспаривает его '
    'представитель. Прямой связи между Valleyton и Fabcell не '
    'установлено. Сама «СБК Премьер» раньше была структурой Сбербанка, '
    'нынешние владельцы не раскрываются.'
)

ADDITION = (
    ' 25 января 2024 года президент разрешил АО «Лучшее решение» купить '
    'у Fabcell Limited 100% акций обоих предприятий. 31 марта 2026 года '
    'Арбитражный суд Москвы по иску Сбербанка взыскал с Fabcell Limited '
    'около $12,3 млн долга по одному из договоров кредитной линии '
    '(включая $12,1 млн просроченной задолженности). 2 июня 2026 года '
    'торги по продаже лота — прав требования Сбербанка на $400 млн, '
    'вексельных прав на 2,75 млрд ₽ и контроля над «Обуховской» и '
    '«Донским антрацитом» — не состоялись: заявок не поступило.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {c['id']: c for c in data['deals']}
    card = by_id[CARD_ID]
    assert card['eco']['context'] == OLD_CONTEXT, card['eco']['context']
    card['eco']['context'] = OLD_CONTEXT + ADDITION

    known_urls = {s[1] for s in card['src'] if len(s) > 1}
    for label, url in (
        ('Коммерсантъ', 'https://www.kommersant.ru/doc/6467547'),
        ('РИА Новости', 'https://ria.ru/20260331/sud-2083965374.html'),
        ('Коммерсантъ', 'https://www.kommersant.ru/doc/8710294'),
    ):
        if url not in known_urls:
            card['src'].append([label, url])

    print(f'{CARD_ID}.eco.context: добавлены указ 2024, взыскание 2026, сорвавшиеся торги 2.06.2026')
    print(f'{CARD_ID}.src: +3 источника')

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
            f.write('\n')
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
