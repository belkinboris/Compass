import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'ga655a061'

OLD_TARGET_FIN = (
    '«Метафракс кемикалс» – один из крупнейших производителей метанола '
    'и формалина в России. В 2022 г. компания произвела 1,2 млн т '
    'метанола. По итогам 2023 г. выручка компании по РСБУ выросла на '
    '7% до 28,9 млрд рублей, чистая прибыль снизилась в 4,7 раза до '
    '2,3 млрд рублей. «Волжский оргсинтез» – крупный производитель '
    'сероуглерода и сульфата натрия. Также компания выпускает метионин, '
    'который применяется в качестве кормовой добавки для животных. '
    'Выручка предприятия по РСБУ в 2023 г. сократилась на 16% в годовом '
    'выражении до 13 млрд рублей, чистая прибыль упала на 6% до 2,7 '
    'млрд рублей.'
)
NEW_TARGET_FIN = OLD_TARGET_FIN + (
    ' Под управлением Росхима «Метафракс Кемикалс» показал: в 2024 году '
    'выручка выросла на 14,8% до 33,2 млрд руб., чистая прибыль — в 8,4 '
    'раза до 271,9 млн руб.; в 2025 году выручка составила 37,5 млрд '
    'руб., чистая прибыль — 6,1 млрд руб. (Интерфакс, ura.news).'
)

OLD_EXTRA = (
    'Сделка по приобретению деприватизированных заводов в Перми и '
    'Волгограде компанией Росхим (входит в группу Ротенбергов).'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Прежний владелец «Волжского оргсинтеза» Александр Соболевский '
    'обжаловал изъятие акций в Двенадцатом арбитражном апелляционном '
    'суде (итог не найден). Прежний владелец «Метафракс Кемикалс» '
    'Сейфеддин Рустамов — уроженец Азербайджана, живущий в США, на '
    '2023 год занимал 90-е место в списке миллиардеров Forbes; за три '
    'года до изъятия акционерам компании выплатили более 6 млрд руб. '
    'дивидендов. Росхим продолжил консолидацию отрасли: в 2025-2026 '
    'годах холдинг также договорился о покупке нефтехимического '
    'комплекса «Газпром нефтехим Салават» за 250–270 млрд руб.'
)

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/business/1010025'],
    ['ura.news', 'https://ura.news/news/1053070920'],
    ['rupec.ru', 'https://rupec.ru/news/51997/'],
    ['59.ru', 'https://59.ru/text/business/2023/08/29/72645161/'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8213287'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['target_fin'] == OLD_TARGET_FIN
    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== eco.target_fin: станет ===')
    print(NEW_TARGET_FIN)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['target_fin'] = NEW_TARGET_FIN
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
