import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g282be68a'

OLD_CONTEXT = (
    'в августе 2023 года «Форесия экологичные решения» получила '
    'заключение по 719-му постановлению правительства РФ о подтверждении '
    'локализации на «задний глушитель в сборе "Гранта"», «задний '
    'глушитель LADA 21214» (Niva), «передний глушитель LADA 21214» '
    '(Niva), а в декабре — на каталитический конвертер в сборе.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' Обе площадки уже сменили состав совладельцев. «Форесия '
    'экологичные решения» переименована в ООО «Формат Экологичные '
    'Решения» (ФЭР), и 23 августа 2024 года «АО "Русатом Химия" '
    'приобрело долю 50% в капитале» этого юрлица (atomic-energy.ru). '
    '«Форесия автомобильные решения» переименована в ООО «Авто Формат '
    'Технологии - Сиденья»; по данным реестра, «Формат Инвест» сохранил '
    'только 49% — 26% у АО «Икс Групп» и 26% у АО «Технoавто» (доля '
    '«Икс Групп» снижена с 51% 27 декабря 2024 года, tbank.ru).'
)

NEW_SRC = [
    ['atomic-energy.ru', 'https://www.atomic-energy.ru/news/2024/08/23/148708'],
    ['tbank.ru', 'https://www.tbank.ru/business/contractor/legal/1141674003569/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
