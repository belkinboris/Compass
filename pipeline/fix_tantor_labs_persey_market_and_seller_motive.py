"""Месячная очередь, 9 сентября 2026 — дочитывание карточки `gfa114edc`
(«"Тантор Лабс" купил права на СУБД "Персей"», добавлена в базу
8 сентября 2026).

Дельта-поиск (саб-агент + личная проверка) нашёл мотив продавца, место
покупателя на рынке и подтверждение, что продукт не архивируют. Личный
WebFetch подтвердил дословно:

1) Мотив продавца. secpost.ru: «по данным CNews Analytics, в 2024 году
   СУБД-направление принесло 370 млн рублей при совокупной выручке
   интегратора в 13,1 млрд рублей»; «Для «МТ-Интеграции» сделка... как
   полагает Маркин, является способом монетизировать непрофильный
   актив»; «такой формат [покупка прав, а не долей] позволяет снизить
   риски, связанные с юридическим контуром продавца» — комментарий
   M&A-юриста Анастасии Нерчинской.

2) Место «Тантор Лабс» на рынке СУБД. cnews.ru: «"Тантор Лабс" в нём
   пока не входит в топ-3 по объёмам продаж. Она на пятом месте с долей
   1,3%» — при лидерах Arenadata (8,6%), Postgres Pro (6,5%), Yandex
   B2B Tech (2,8%), DIS Group (2,7%).

3) Судьба продукта. anti-malware.ru: «Закрывать или отправлять продукт
   на склад приобретённых технологий не планируют. Развитие «Персея»
   продолжит объединённая команда внутри «Тантор Лабс»».

НЕ внесено: официальный комментарий самой «МТ-Интеграции» о причине
продажи (не нашёлся, только оценка стороннего аналитика), связь с
эпизодом «Аквариус»/2025 (ни один источник её не проводит — была бы
домыслом), консультанты сделки (не названы), итоговая сумма (обещана
только к середине осени 2026, ещё не наступила).

Запуск:
    python3 pipeline/fix_tantor_labs_persey_market_and_seller_motive.py            # сухой прогон
    python3 pipeline/fix_tantor_labs_persey_market_and_seller_motive.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_ECO_CONTEXT = (
    'Со стороны «Группы Астра» в сделке участвовала компания ООО '
    '«Тантор Лабс»'
)
NEW_ECO_CONTEXT = OLD_ECO_CONTEXT + (
    '. По данным CNews Analytics, в 2024 году СУБД-направление принесло '
    '«МТ-Интеграции» 370 млн ₽ при совокупной выручке интегратора в '
    '13,1 млрд ₽ — для продавца сделка стала способом монетизировать '
    'непрофильный актив. На рынке СУБД «Тантор Лабс» занимает пятое '
    'место с долей 1,3% (лидеры — Arenadata 8,6%, Postgres Pro 6,5%, '
    'Yandex B2B Tech 2,8%, DIS Group 2,7%).'
)

OLD_ECO_RATIONALE = (
    'Российский рынок корпоративных СУБД вступает в этап консолидации. '
    'Команд с глубоким опытом разработки таких продуктов немного, и '
    'инженерная школа становится ключевым фактором технологического '
    'лидерства.'
)
NEW_ECO_RATIONALE = OLD_ECO_RATIONALE + (
    ' Продукт закрывать не планируют — развитие «Персея» продолжит '
    'объединённая команда разработки внутри «Тантор Лабс».'
)

NEW_SRC = ['Anti-Malware.ru', 'https://www.anti-malware.ru/news/2026-08-04-111332/50892']


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['gfa114edc']

    assert d['eco']['context'] == OLD_ECO_CONTEXT, \
        'gfa114edc eco.context уже другой: %r' % (d['eco']['context'],)
    assert d['eco']['rationale'] == OLD_ECO_RATIONALE, \
        'gfa114edc eco.rationale уже другой: %r' % (d['eco']['rationale'],)
    urls = {s[1] for s in d['src']}
    assert NEW_SRC[1] not in urls, 'источник уже добавлен'

    print('gfa114edc: eco.context дополнен (мотив продавца, доля рынка '
          '«Тантор Лабс»); eco.rationale дополнен (судьба продукта); '
          'добавлен источник anti-malware.ru')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['eco']['context'] = NEW_ECO_CONTEXT
    d['eco']['rationale'] = NEW_ECO_RATIONALE
    d['src'].append(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
