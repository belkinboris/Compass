# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
`gmru-mtsbank-kdpay` (МТС Банк купил платёжный сервис KD Pay, Закрыта,
20 июля 2026) — карточка знала долю до сделки (Пономарёв 80%, Дубов
10%, Салабаев 10%), но не точный расклад ПОСЛЕ неё.

Проверено ЛИЧНО прямым WebFetch (comnews.ru/content/246503/2026-07-22/
2026-w30/1008/mts-bank-kupil-platezhnyy-servis-kd-pay): «В результате
банк стал владельцем 51% компании, Олег Пономарев сохранил 41%, а
Леонид Дубов — 8%.» Сумма сделки по-прежнему официально не раскрыта —
источник прямо подтверждает: «Стороны не раскрыли сумму сделки»,
оценка Кабакова (50–150 млн ₽) остаётся единственным числом.

НЕ ВНЕСЕНО: судьба доли Дмитрия Салабаева (10% до сделки) — источник
называет только Пономарёва и Дубова после сделки (41%+8%+51%=100%,
Салабаев в этой сумме не фигурирует вовсе), но не поясняет, вышел ли он
из капитала раньше или его доля перераспределена без объяснения — это
арифметическое расхождение с уже известным составом до сделки
зафиксировано честно, не разрешено на глаз. Новостей о фактическом
запуске/интеграции KD Pay после закрытия не нашлось ни в одном
источнике на дату этого прогона.

`buyer`/`seller`/`status`/`title` карточки НЕ тронуты.

Запуск: python3 pipeline/fix_mtsbank_kdpay_post_deal_stakes.py
        python3 pipeline/fix_mtsbank_kdpay_post_deal_stakes.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gmru-mtsbank-kdpay'

OLD_ECO_CONTEXT = (
    'Структура собственников ООО «Ритейл-Процессинг» менялась несколько '
    'раз с момента регистрации компании в 2021 году. При основании 100% '
    'компании принадлежало Олегу Пономарёву. В апреле 2022 года доля '
    'Олега Пономарёва сократилась до 80%: в капитал вошли Леонид Дубов '
    '(10%) и Дмитрий Салабаев (10%).'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' После сделки МТС Банк стал владельцем 51%, '
    'Олег Пономарёв сохранил 41%, а Леонид Дубов — 8% (сумма с долей '
    'Дмитрия Салабаева, которая до сделки была 10%, не сходится — '
    'источник его после сделки не упоминает, расхождение не '
    'разрешено).'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
