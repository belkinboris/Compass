# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка gfecb608d (Сбер купил
онлайн-школу программирования «Алгоритмика»): карточка уже несёт
нерешённое расхождение источников — `law.struct` говорит, что «банк не
выступает покупателем напрямую... но в его интересах», а `eco.context`
цитирует основателя Андрея Лобанова, утверждающего, что покупатель —
«частный инвестор». Дельта-поиск НЕ разрешил это расхождение однозначно
(ни один источник 2025-2026 годов не называет реального владельца прямо),
но нашёл косвенный факт, который стоит того, чтобы читатель его увидел:
сам Лобанов покинул пост гендиректора через два месяца после сделки, а
сменившая его глава ранее числилась именно в структуре Сбера. Подтверждено
лично прямым WebFetch.

22 ноября 2024 года гендиректором «Алгоритмики» вместо Лобанова стала
Светлана Анисимова — «на сайте «СберОбразования» в июле 2024 года»
упоминалась как «операционный директор «Алгоритмики»» (RB.RU). Это не
доказывает, что покупатель — Сбербанк (аффилированность самой Анисимовой
со СберОбразованием могла возникнуть и без прямого владения активом), но
это факт, который читатель заслуживает видеть рядом с обеими версиями
спора о личности покупателя.

Также уточнён диапазон оценок суммы сделки: «Собеседники издания оценили
сделку в от 1 до 1,5 млрд руб.» (CNews) — совпадает с уже стоящей в
карточке «~1 млрд ₽», но диапазон точнее одной цифры.

Консультантов сделки дельта-поиск не нашёл ни в одном источнике — честная
пустота, не тронуто.

Запуск: python3 pipeline/fix_algoritmika_lobanov_departure.py
        python3 pipeline/fix_algoritmika_lobanov_departure.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gfecb608d'

OLD_CONTEXT = (
    'Основатель «Алгоритмики» Андрей Лобанов подтвердил, что продал '
    'российские активы, однако сообщил, что покупателем стал не '
    'Сбербанк, а частный инвестор.'
)
CONTEXT_ADDITION = (
    ' Спор о личности покупателя дельта-поиск не разрешил, но нашёл '
    'факт, который стоит знать в его контексте: 22 ноября 2024 года, '
    'через два месяца после сделки, Лобанов покинул пост гендиректора — '
    '«Светлана Анисимова... ранее... упоминалась на сайте '
    '«СберОбразования» в июле 2024 года как операционный директор '
    '«Алгоритмики»»» (RB.RU). Диапазон оценок суммы сделки СМИ: '
    '«Собеседники издания оценили сделку в от 1 до 1,5 млрд руб.» '
    '(CNews).'
)
NEW_CONTEXT = OLD_CONTEXT + CONTEXT_ADDITION

NEW_SRC = [
    ['RB.RU', 'https://rb.ru/news/algoritmika-lobanov/'],
    ['CNews', 'https://www.cnews.ru/news/top/2024-10-22_sberbank_kupil_onlajn-shkolu'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
