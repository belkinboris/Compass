# -*- coding: utf-8 -*-
"""Недельная очередь 18.09.2026: карточка `gce803e3f` («Дом.РФ» продал на
торгах палаты Кожевенной слободы XVII века) — дельта-поиск нашёл АБН
(Агентство Бизнес Новостей) с тремя новыми фактами, которых не было в трёх
уже известных источниках (РИА Недвижимость, Агентство «Москва» x2):

  1. площадь здания — 525,7 кв. м (в карточке была только площадь участка
     аренды, 0,18 га, без площади самого памятника);
  2. стартовая цена торгов — 67,4 млн ₽ (итог — уже известные 100,5 млн ₽,
     то есть рост почти в 1,5 раза);
  3. покупатель «Бриз» связывается участниками рынка недвижимости с
     девелопером «Крост» — формулировка ОСТОРОЖНОЙ АТРИБУЦИИ издания
     («связывают», а не «принадлежит»), вносится с той же оговоркой, а не
     как установленный факт собственности; юрлицо «Бриз» отдельно
     проверено (десятки кандидатов по стране, ни один не подходит по
     профилю деятельности/дате/региону) — профиль компании-покупателя НЕ
     заводится, риск связать роль с чужим ИНН выше пользы (см. CLAUDE.md,
     «Конкретно звучащее имя компании тоже бывает однофамильцем»).

Правится ОДНОРАЗОВЫМ СКРИПТОМ, а не через `review.py`: поле `eco.context`
уже заполнено (из первого обыска), а новые факты — из ДРУГОГО источника;
дописывание проверяется ПОПРЕДЛОЖЕНЧАТО (как в `merge_duplicate_deals_
batch.py`), а не единым `flat(new) in flat(quote)` по всему полю — иначе
пришлось бы выдать за одну цитату склейку двух разных источников.

Источник: https://abn.agency/2026/09/11/v-zamoskvoreche-prodali-palaty-
kozhevennoj-slobody-xvii-veka-pochti-za-1005-mln-rublej/
(кэш: data/inbox/raw/2026-09-18-weekly-cluster1c.jsonl)

Запуск: python3 pipeline/fix_kozhevennaya_briz_krost_and_area.py [--write]
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent if (Path(__file__).parent / 'static').exists() else Path(__file__).resolve().parent
DATA = Path('/home/user/static/data/deals_promoted.json')

DEAL_ID = 'gce803e3f'

OLD_CONTEXT = (
    'Памятник архитектуры можно приспособить под ресторан, офис или другое '
    'коммерческое использование. В лот входит аренда земельного участка '
    '0,18 гектара. Палаты — старейшая сохранившаяся постройка Кожевенной '
    'слободы: изначально здание использовалось для хранения товаров и '
    'администрирования торговли, после петровских реформ стало городской '
    'таможней, а с 1983 до конца 2010-х годов в нём размещалась редакция '
    'журнала «Знание — сила».'
)

ADD_AREA = (
    'Здание площадью 525,7 кв. м.'
)
ADD_PRICE = (
    'Торги стартовали с отметки 67,4 млн рублей, однако «Бриз» предложила '
    'за объект около 100,5 млн рублей.'
)
ADD_BUYER = (
    'Компания «Бриз», которую участники рынка недвижимости связывают с '
    'девелопером «Крост».'
)

QUOTE = (
    'Компания «Бриз», которую участники рынка недвижимости связывают с '
    'девелопером «Крост», выиграла торги на покупку палат Кожевенной '
    'слободы XVII века постройки в Замоскворечье, в центре Москвы. Об '
    'этом сообщает РИА Недвижимость. Продавцом выступил «Дом.РФ», '
    'выставивший на аукцион здание площадью 525,7 кв. м — объект '
    'культурного наследия федерального значения, расположенный по '
    'адресу: Кожевническая, 19, строение 6. В лот также вошло право '
    'аренды земельного участка площадью 0,18 га. Памятник архитектуры '
    'допускается приспособить под ресторан, офис или иные коммерческие '
    'функции. Торги стартовали с отметки 67,4 млн рублей, однако «Бриз» '
    'предложила за объект около 100,5 млн рублей.'
)


def flat(s):
    return re.sub(r'[^0-9a-zа-яё]+', '', str(s or '').lower().replace('ё', 'е'))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--write', action='store_true')
    args = ap.parse_args()

    data = json.load(open(DATA, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, 'поле уже другое: %r' % deal['eco']['context']

    for add in (ADD_AREA, ADD_PRICE, ADD_BUYER):
        assert flat(add) in flat(QUOTE), 'не лежит дословно в цитате: %r' % add

    new_context = OLD_CONTEXT + ' ' + ADD_AREA + ' ' + ADD_PRICE + ' ' + ADD_BUYER
    print('НОВОЕ eco.context:')
    print(new_context)
    print()
    print('Добавлено предложений: 3 (площадь здания, стартовая цена, связь с «Крост»)')

    if args.write:
        deal['eco']['context'] = new_context
        deal.setdefault('src', [])
        urls = {s[1] for s in deal['src'] if isinstance(s, list) and len(s) > 1}
        abn_url = ('https://abn.agency/2026/09/11/v-zamoskvoreche-prodali-'
                    'palaty-kozhevennoj-slobody-xvii-veka-pochti-za-1005-'
                    'mln-rublej/')
        if abn_url not in urls:
            deal['src'].append(['АБН', abn_url])
        json.dump(data, open(DATA, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
        print('Записано.')
    else:
        print('Сухой прогон. Запись — с ключом --write.')


if __name__ == '__main__':
    main()
