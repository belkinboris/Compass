# -*- coding: utf-8 -*-
"""g772c17d9 («Связь.ON»): дочитывание по дублю из очереди притока
(data/inbox/duplicates/2026-11-23.json, черновик d90917428, источник
t.me/dealsma/7597 — тот же дайджест, что и у Frank Media/Retailer.ru,
уже в карточке, но с деталями, которых там не было).

ПОЧЕМУ ОДНОРАЗОВЫЙ СКРИПТ, А НЕ `review.py`/`resolve_duplicates.py --apply`.
Обе новые детали — дописывание к уже стоящей прозе (`eco.context`,
`eco.target_fin`), а не отдельное поле. `review.check()` для прозы требует,
чтобы ВСЕ числа итогового значения (а не только дописанного куска) лежали в
одной цитате — старые числа (10%, 250, 53, 40%) из чужого источника
(Frank Media) в цитате dealsma не лежат, и правка отказывает механически
(проверено `review.check()` напрямую — отказ «в тексте числа, которых нет в
цитатах»). Ровно случай из `docs/card_editing_scripts.md`, «Когда review.py
не подходит»: дописывание предложения к прозе — одноразовым скриптом с
`assert` на старое значение, без таблицы FIXES.

НОВЫЕ ФАКТЫ (дословно в data/inbox/raw/2026-11-23-articles.jsonl,
https://t.me/dealsma/7597):
  1. «Связь.ON» создана в 2024 году бывшими топ-менеджерами «Связного» во
     главе с Дагмарой Ивановой при участии ПСБ. Юридического правопреемства
     с обанкротившимся «Связным» у сети нет: магазины и активы прежнего
     ритейлера не передавались. — ВАЖНО: в карточке этого разграничения не
     было вовсе, риск спутать «Связь.ON» со «Связным» (разные компании).
  2. Чистый убыток 2025 года — 3,61 млрд руб. (2024 год — 703,2 млн);
     проценты к уплате — 1,67 млрд руб. (2024 год — 165 млн); кредиты и
     займы — 6,72 млрд руб.; денежные средства — 160,7 млн руб.; капитал
     отрицательный — минус 3,88 млрд руб.; обязательства по аренде — около
     2,14 млрд руб. В карточке была только выручка/коммерческие расходы/
     убыток от продаж (Frank Media этих цифр не называл).

Источники добавлены в `src`: dealsma (у кого нашлись обе детали) и
«Известия» (первоисточник самого скрытого дайджеста dealsma — в карточке
до этого была только перепечатка Frank Media/Retailer.ru).

Запуск: python3 pipeline/fix_g772c17d9_svyaznoy_dealsma_2026_11_23.py [--write]
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(ROOT, '..', 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g772c17d9'

OLD_CONTEXT = (
    'Сеть запущена в 2024 году и за два с небольшим года выросла до 250 '
    'мультицентров в 53 регионах, обзаведясь партнерствами с ПСБ, '
    'Альфа-банком, Совкомбанком и Ренессанс-банком. До сделки Ивановой '
    'принадлежало 10% компании, структурам ПСБ — почти 40%, а фонду «ГК '
    'Связь» — чуть больше половины. Управляющий партнер «ВМТ консалт» '
    'Екатерина Косарева называет причиной интереса к активу клиентскую базу, '
    'партнерские связи и дороговизну привлечения новых покупателей; Герасин '
    'добавляет, что сеть ценна не помещениями и оборудованием, а брендом, '
    'клиентской базой, IT-платформой и выстроенными партнерствами.'
)
ADD_CONTEXT = (
    'Часть менеджеров «Связь.ON», включая Иванову, ранее работала в '
    '«Связном» — крупном продавце мобильных телефонов, который позже '
    'обанкротился. Юридического правопреемства между компаниями нет: '
    'магазины и активы «Связного» новой сети не передавались.'
)
NEW_CONTEXT = OLD_CONTEXT + '\n\n' + ADD_CONTEXT

OLD_TARGET_FIN = (
    'За 2025 год компания показала выручку 2,26 млрд рублей, но '
    'коммерческие расходы составили 3,18 млрд рублей при валовой прибыли '
    'лишь 178 млн — в итоге продажи обернулись убытком в 3 млрд рублей.'
)
ADD_TARGET_FIN = (
    'Чистый убыток за 2025 год достиг 3,61 млрд рублей (в 2024 году — 703,2 '
    'млн); проценты к уплате выросли до 1,67 млрд рублей (в 2024 году — 165 '
    'млн). Кредиты и займы на конец 2025 года — 6,72 млрд рублей при 160,7 '
    'млн рублей на счетах, капитал отрицательный — минус 3,88 млрд рублей. '
    'Обязательства по аренде — около 2,14 млрд рублей.'
)
NEW_TARGET_FIN = OLD_TARGET_FIN + ' ' + ADD_TARGET_FIN

NEW_SOURCES = [
    ['Телеграм-канал: Сделки M&A', 'https://t.me/dealsma/7597'],
    ['Известия', 'https://iz.ru/2203379/valerii-kodachigov/ritejler-ehlektroniki-svyaz-on-smenil-sobstvennikov'],
]


def apply(data):
    deal = next((d for d in data['deals'] if d['id'] == DEAL_ID), None)
    assert deal is not None, '%s не найдена в deals_promoted.json' % DEAL_ID
    changed = []

    assert deal['eco']['context'] == OLD_CONTEXT, (
        'eco.context уже другой: %r' % deal['eco']['context'])
    deal['eco']['context'] = NEW_CONTEXT
    changed.append('eco.context: дописан факт об отсутствии правопреемства со «Связным»')

    assert deal['eco']['target_fin'] == OLD_TARGET_FIN, (
        'eco.target_fin уже другой: %r' % deal['eco']['target_fin'])
    deal['eco']['target_fin'] = NEW_TARGET_FIN
    changed.append('eco.target_fin: дописаны чистый убыток, проценты, долг, капитал, аренда')

    have = {s[1] for s in (deal.get('src') or []) if isinstance(s, list) and len(s) > 1}
    for label, url in NEW_SOURCES:
        if url not in have:
            deal.setdefault('src', []).append([label, url])
            changed.append('src: добавлен %s' % url)

    return changed


def main(write):
    data = json.load(open(DATA, encoding='utf-8'))
    changed = apply(data)
    for line in changed:
        print('  ' + line)
    if not write:
        print('Сухой прогон (%d изменений). Запись — с ключом --write.' % len(changed))
        return 0
    # Перечитываем файл прямо перед записью (CLAUDE.md: «deals_promoted.json
    # он перечитывает прямо перед записью»), применяем те же проверенные правки.
    data = json.load(open(DATA, encoding='utf-8'))
    apply(data)
    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')
    return 0


if __name__ == '__main__':
    sys.exit(main('--write' in sys.argv))
