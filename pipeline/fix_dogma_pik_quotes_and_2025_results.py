import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gb49e3668'

OLD_EXTRA = (
    'Сделка касается покупки краснодарским застройщиком Dogma двух '
    'земельных участков общей площадью более 6 га у российской '
    'девелоперской компании ГК ПИК. На участках предусмотрено '
    'строительство жилых комплексов общей площадью 204 тыс. кв. м. '
    'Финансирование открыто Альфа-банком на сумму 54,7 млрд руб.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Из общей суммы кредита 26,4 млрд руб. пришлось на восточный '
    'проект (Гольяново). «Уже в следующем году к двум нашим проектам, '
    'реализуемым в Подмосковье, ЖК EVO и «Публицист», добавятся '
    'несколько проектов в Москве. Еще ряд сделок находится в процессе '
    'подписания», — сообщила пресс-служба DOGMA (РБК-Кубань, 16 октября '
    '2024 года). По итогам 2025 года выручка DOGMA выросла на 87,2%, '
    'компания впервые заняла третье место по объему текущего '
    'строительства в России и сдала более 6 тыс. квартир (Коммерсантъ).'
)

NEW_SRC = [
    ['РБК-Кубань', 'https://kuban.rbc.ru/krasnodar/freenews/670f996c9a79472cd801d71f'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8440255'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
