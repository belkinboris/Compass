import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g6f678b73'

OLD_LAW_STRUCT = '—'
NEW_LAW_STRUCT = (
    'Покупатель — ООО «Самолет Плюс» (входит в группу «Самолет»); '
    'целевое юрлицо ООО «Золтор» сохранено. Продавцы — совладельцы '
    'компании Алсу Галлямова (46,2%) и Семен Сарапулов (41,8%), продавшие '
    'доли напрямую: «Фаундеры же и акционеры "Золтора" просто продали '
    'доли» (гендиректор «Самолет Плюс» Дмитрий Волков, декабрь 2023).'
)

OLD_LAW_TERMS = 'Он уточнил, что штат агентства планируется сохранить.'
NEW_LAW_TERMS = (
    OLD_LAW_TERMS + ' По факту (интервью Волкова, декабрь 2023): из 330 '
    'офисов «Золтор» на момент покупки в сеть «Самолет Плюс» за три-четыре '
    'месяца перешло более 100, и сохранена была часть команды — та, что '
    'занималась продажами и открытием точек, а не весь штат целиком.'
)

NEW_SRC = [
    ['РИА Недвижимость', 'https://realty.ria.ru/20231220/volkov-1916772075.html'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['law']['struct'] == OLD_LAW_STRUCT
    assert deal['law']['terms'] == OLD_LAW_TERMS

    existing_urls = {s[1] for s in deal['src']}
    add_src = [s for s in NEW_SRC if s[1] not in existing_urls]
    new_src = deal['src'] + add_src

    print('=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)
    print('\n=== law.terms: станет ===')
    print(NEW_LAW_TERMS)
    if add_src:
        print('\n=== src: добавится ===')
        for s in add_src:
            print(s)

    if write:
        deal['law']['struct'] = NEW_LAW_STRUCT
        deal['law']['terms'] = NEW_LAW_TERMS
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
