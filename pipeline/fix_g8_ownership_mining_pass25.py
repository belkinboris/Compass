# -*- coding: utf-8 -*-
"""G8 (PRODUCT_ROADMAP.md) — двадцать пятая партия майнинга уже собранного
текста карточек. Три уровня очереди дочитывания снова пусты (13 сентября
2026). Метод по-прежнему близок к исчерпанию (см. докстроку пасса 24) —
партия честно мала (одна запись).

Свежий замер с учётом уже занятых 177 профилей (число выросло со 133 на
момент пасса 24 — это НЕ мой метод, а параллельный аудит другой рутины
«Аудит адреса фактов», заполнивший ownership отдельно; пересчёт стартует от
факта в данных, а не от старого счётчика) дал 170 уникальных
компаний-кандидатов — почти все относятся к уже известным классам отказа.
Один прошёл проверку направления и подтверждён прямым чтением источника:

- `gb92763b6` (ООО «Энки», buyer сделки `g3e3f5e9c` — «Крост» выкупил завод
  ЖБИ в Клину у СУ-155 через «Энки»): проверено лично прямым WebFetch
  (kommersant.ru/doc/5985465) — «Энки» учредило ООО «Элемент», бенефициар
  которого — Виктор Мосин, руководящий рядом структур концерна «Крост»
  (сам концерн возглавляет Алексей Добашин). Карточка несла эту цепочку
  прозой в `extra`, но не в структурном поле.

Отклонённый в этом же проходе кандидат — `gb6bfe549` (ООО «Лойд-фиш»,
target сделки `gbb8eba27`): предложение про 99,99% в законной форме
описывает СОСТОЯНИЕ НА МОМЕНТ ЭТОЙ СДЕЛКИ (УК «Камчатка Проект», дочка
АФК «Система»), уже отражённое в `eco.share`/`law.struct` самой сделки —
но `eco.context` той же карточки говорит, что контроль над холдингом с тех
пор дважды переходил другим владельцам (Милане Керимовой через «Инсофт» в
мае 2025, затем ЗПИФ «Море Финанс» в апреле 2026, причём остаток — в
залоге). Записать в `ownership` устаревшее «на момент сделки» состояние
было бы неверно, а последнее состояние в тексте изложено не настолько
чисто (доля в залоге, не завершённая цепочка бенефициаров), чтобы
переносить его механически — честнее оставить прозу, где нюанс сохранён,
чем сжимать её в одну неполную структурную запись.

Запуск:
    python3 pipeline/fix_g8_ownership_mining_pass25.py            # сухой прогон
    python3 pipeline/fix_g8_ownership_mining_pass25.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

NEW_OWNERSHIP = {
    'gb92763b6': [{
        'name': 'ООО «Элемент» (бенефициар — Виктор Мосин, руководитель структур концерна «Крост»)',
        'id': None,
        'as_of': '2023-05',
        'source': ['Коммерсантъ', 'https://www.kommersant.ru/doc/5985465'],
    }],
}


def main(write=False):
    """Идемпотентен, как pass1-24."""
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    companies = data['companies']

    pending = {}
    for cid, entries in NEW_OWNERSHIP.items():
        assert cid in companies, 'нет такого профиля: %s' % cid
        current = companies[cid].get('ownership')
        if current:
            assert current == entries, 'ownership уже занят другим значением у %s: %r' % (cid, current)
            continue
        pending[cid] = entries

    if not pending:
        print('Все профили уже заполнены — нечего применять.')
        return

    print('Заполняю ownership: %s' % ', '.join('%s (%s)' % (cid, companies[cid]['name']) for cid in pending))

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    for cid, entries in pending.items():
        companies[cid]['ownership'] = entries

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
