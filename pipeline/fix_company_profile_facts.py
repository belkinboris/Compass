# -*- coding: utf-8 -*-
"""Два профиля компаний, где показанный факт относится не к этой компании.

ЗАЧЕМ. На карточке компании под именем стоит пара «подпись → значение». У
1819 профилей из 1872 там служебная разметка («Профиль → Автоматический»), и
это чинится в интерфейсе. Но у двух профилей стоит содержательный на вид
факт, который на самом деле про другое лицо, — а это уже данные.

  * «Яндекс» → «Направление шеринга: Артём Молчанов». Артём Молчанов —
    генеральный директор сервиса «Бери заряд!», то есть ПРЕДМЕТА сделки, а не
    «Яндекса». Родня уже записанного урока «стороной сделки бывает записан её
    предмет», только здесь предметом подписан руководитель.
  * «Росатом (Uranium One Group)» → «Литиевые проекты: Мали · Боливия ·
    Мурманская обл.». Uranium One Group — международная урановая компания
    Росатома (Казахстан, Танзания, Намибия), она же ведёт литиевый проект в
    Боливии; а Колмозерское месторождение в Мурманской области разрабатывает
    СП «Полярный литий» с «Норникелем» — это внутрироссийский контур, к
    Uranium One Group отношения не имеющий. Уточнение в скобках делало
    утверждение неверным, поэтому снимается: профиль остаётся «Росатом», и
    тогда все три проекта названы правильно.

ГРАНИЦА. Мы не переписываем факты, а снимаем ошибочную привязку: у «Яндекса»
пара удаляется целиком (кто у него отвечает за шеринг, мы не знаем и
выдумывать не будем), у «Росатома» правится только имя профиля и пояснение —
сам список проектов остаётся как есть.

Запуск:
    python3 pipeline/fix_company_profile_facts.py            # сухой прогон
    python3 pipeline/fix_company_profile_facts.py --write    # записать
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

PLAN = [
    {
        'id': 'yandex',
        'was': {'kpi': ['Направление шеринга', 'Артём Молчанов']},
        'now': {'kpi': ['Профиль', 'Редакционно подтверждён']},
        'why': 'Артём Молчанов — гендиректор «Бери заряд!», предмета сделки, а не «Яндекса»',
    },
    {
        'id': 'rosatom',
        'was': {'name': 'Росатом (Uranium One Group)',
                'kpi': ['Литиевые проекты', 'Мали · Боливия · Мурманская обл.']},
        'now': {'name': 'Росатом',
                'desc': 'Горнорудный контур госкорпорации. Литиевые проекты за рубежом ведёт '
                        'международная компания Uranium One Group (Мали, Боливия); Колмозерское '
                        'месторождение в Мурманской области разрабатывает совместное предприятие '
                        '«Полярный литий» с «Норникелем».',
                'kpi': ['Литиевые проекты', 'Мали · Боливия · Мурманская обл.']},
        'why': 'Uranium One Group — зарубежный контур, Мурманская область к нему не относится',
    },
]


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    companies = data['companies']

    for row in PLAN:
        company = companies.get(row['id'])
        assert company is not None, 'профиля %s нет в базе' % row['id']
        for field, value in row['was'].items():
            assert company.get(field) == value, \
                '%s: поле %s сейчас %r, а не %r — решение принимать заново' % (
                    row['id'], field, company.get(field), value)
        print('%s  «%s»' % (row['id'], company.get('name')))
        print('   почему: %s' % row['why'])
        for field, value in row['now'].items():
            print('   %-5s -> %s' % (field, str(value)[:96]))

    print('\nпрофилей к правке: %d' % len(PLAN))
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return 0

    for row in PLAN:
        companies[row['id']].update(row['now'])
    json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('ЗАПИСАНО в %s' % os.path.relpath(DATA, ROOT))
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
