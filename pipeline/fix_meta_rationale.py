# Предложение сообщает лишь об ОТСУТСТВИИ сведений о консультантах.
# Такое предложение выбрасываем: для консультантов есть своё поле, и там уже
# написано «публично не раскрывались».
# Требуем И отрицание, И упоминание консультанта/фирмы в том же предложении —
# иначе под правило попадали бы содержательные фразы вроде «покупатель не
# назван», которые к консультантам отношения не имеют.
NOINFO_NEG = re.compile(
    r'(?:не\s+(?:содерж\w+|указан\w*|указыв\w+|назван\w*|называ\w+|раскрыт\w*|раскрыв\w+|'
    r'приведен\w*|приводит|приводится|сообщает|упомина\w+|уточня\w+|детализир\w+|'
    r'конкретизир\w+|предоставлен\w*|упомян\w*)|отсутству\w+|'
    r'без\s+(?:указания|упоминания|раскрытия))', re.I)

# Предложение, которое сообщает только ОТКУДА взята информация: «Источник:
# пресс-служба компании», «Информация о сделке из открытых источников». Источники
# у карточки — отдельное поле, заполненное у 100% карточек, поэтому в «Цели
# сделки» такая фраза только занимает место. Отбрасываем её, но лишь когда в том
# же предложении нет ничего о самой сделке: «Источник информации о закрытой в
# июне 2024 года сделке по приобретению отеля…» содержит факты и должен остаться.
SOURCE_MARK = re.compile(
    r'(?:источник\w*\s+(?:информации|новости)|из\s+(?:\S+\s+){0,2}источник\w*|'
    r'получена?\s+из|опубликован\w*\s+в\b|telegram[- ]канал\w*|пресс-служб\w*|'
    r'цитирующ\w+|из\s+инсайдерск\w+)', re.I)
# Признаки, что предложение говорит О СДЕЛКЕ, а не только об источнике.
# Список пополнялся по факту: «Сделка: МегаФон вышел из капитала Связного,
# продав свою долю» однажды была выброшена целиком как «ссылка на источник» —
# ни «вышел», ни деепричастие «продав» в маркеры не попадали.
DEAL_SUBSTANCE = re.compile(
    r'\d|прода\w*|куп\w+|приобрет\w+|покупател\w+|продавц\w+|выкуп\w*|'
    r'дол[яи]\b|долей|акци\w+|сумма|актив\w*|капитал\w*|'
    r'вышел|вышла|вышли|вошёл|вошла|вошли|получил\w*|передал\w*|'
    r'консолидир\w*|объединил\w*|слия\w+|'
    r'завершен\w*|завершён\w*|закрыт\w*', re.I)

# «…фирм в сделке Сумма: ~1 млрд рублей» — в исходнике потерялась точка перед
# «Сумма:», и шум про консультантов слипся с цифрой в одно предложение. Раньше
# такие предложения приходилось сохранять целиком, чтобы не потерять сумму
# (см. журнал, прогон 5). Теперь разрезаем по «Сумма:» и проверяем, что та же
# сумма уже лежит в своём поле eco.sum, — тогда хвост можно отбросить вместе с
# шумом, ничего не потеряв.
SUM_SPLIT = re.compile(r'\s*(?=Сумма\s*:)', re.I)
NOINFO_OBJ = re.compile(
    r'(?:консультант\w*|консалтинг\w*|юрист\w*|юридическ\w*|фирм\w*|советник\w*|'
    r'инвестбанк\w*|инвестиционн\w*\s+(?:фирм|компани|банк)|их\s+роль|роль\s+как|'
    r'партнёр\w*|партнер\w*|консультирован\w*)', re.I)


# В предложении есть собственное содержание (цифры, сумма, доля) — выбрасывать
# его нельзя, даже если оно начинается с «в статье не указаны консультанты».
# Ловим случай, когда точка перед «Сумма:» потерялась и всё слиплось в одно
# предложение: раньше на такой карточке вместе с шумом пропадала сумма сделки.
HAS_SUBSTANCE = re.compile(r'\d|сумма\s*:|стоимост|цена\b', re.I)

# Осиротевшее придаточное про консультантов внутри предложения:
# «Переговоры между X и Y, однако не указывает, консультировала ли …» —
# после отсечения зачина у него пропадает подлежащее.
ORPHAN_CLAUSE = re.compile(
    r'[,;]\s*(?:однако|при\s+этом|но)?\s*не\s+(?:указыв\w+|указан\w*|сообщает|'
    r'уточня\w+|назван\w*|упомина\w+)[^.]*?(?:консультант\w*|консультировал\w*|'
    r'фирм\w*|юрист\w*|юридическ\w*|консалтинг\w*)[^.]*', re.I)


def is_noinfo(sentence):
    if HAS_SUBSTANCE.search(sentence):
        return False
    return bool(NOINFO_NEG.search(sentence) and NOINFO_OBJ.search(sentence))


def drop_noise_clause(sentence):
    """Убирает придаточное про отсутствие консультантов, оставляя остальное.

    Выбрасывать предложение целиком можно, только если оно всё про отсутствие
    сведений. Иначе теряются факты: «Telegram-канал dealsma публикует информацию
    о сделке продажи торгового центра «Старт» девелопером Карена Авдаляна;
    партнёры и юристы не названы» — шум только после точки с запятой, а вместе с
    ним однажды уехало и название объекта, и продавец.
    """
    parts = re.split(r'\s*;\s*', sentence)
    if len(parts) < 2:
        return sentence
    kept = [p for p in parts if not is_noinfo(p)]
    if not kept or len(kept) == len(parts):
        return sentence
    out = '; '.join(kept).strip()
    # точка могла остаться у выброшенного куска
    if not re.search(r'[.!?]$', out):
        out += '.'
    return out


def is_source_only(sentence):
    """Предложение сообщает только об источнике и ничего — о сделке."""
    return bool(SOURCE_MARK.search(sentence)) and not DEAL_SUBSTANCE.search(sentence)


# Пометки, превращающие число в оценку, а не в раскрытую сумму.
QUALIFIER = re.compile(r'оценк|эксперт|не\s+подтвержд|не\s+раскры|по\s+данным|официальн|'
                       r'предположительн|ориентировочн|порядка|около', re.I)


def sum_fully_covered(body, known_sum):
    """Текст суммы можно выбросить, только если он ничего не добавляет к eco.sum.

    Мало сверить числа: «Сумма: 100 млн руб. (по оценкам экспертов, официально
    не подтверждено)» и «100 млн руб.» в eco.sum содержат одно и то же число, но
    после очистки экспертная оценка превратилась бы на экране в раскрытую сумму.
    Поэтому требуем ещё, чтобы каждая пометка-оговорка из текста нашлась и в
    eco.sum. Правило намеренно строгое: оставить лишнюю строку не страшно,
    выдать оценку за факт — нарушение принципа «каждое число объяснимо».
    """
    if not nums(body) or not nums(body) <= nums(known_sum):
        return False
    have = {m.group(0).lower() for m in QUALIFIER.finditer(known_sum or '')}
    for m in QUALIFIER.finditer(body):
        if m.group(0).lower() not in have:
            return False
    return True


def nums(t):
    """Числа предложения без разделителей: «2,9 млрд» и «2.9 млрд» дают одно и то же."""
    return set(re.findall(r'\d+', (t or '').replace(' ', '').replace(',', '.')))


def strip_glued_sum(sentence, known_sum):
    """«<шум про консультантов> Сумма: X» -> '' если X уже лежит в eco.sum.

    Возвращает None, если правило неприменимо (тогда предложение не трогаем).
    """
    parts = SUM_SPLIT.split(sentence, maxsplit=1)
    if len(parts) != 2:
        return None
    head, tail = parts[0].strip(), parts[1].strip()
    if not head or nums(head):
        return None                      # в голове есть цифры — резать опасно
    if not (NOINFO_NEG.search(head) and NOINFO_OBJ.search(head)):
        return None                      # голова содержательная, не шум
    if not nums(tail) or not nums(tail) <= nums(known_sum):
        return None                      # сумма не подтверждается полем eco.sum
    return ''


def split_sentences(t):
    """Границей считаем точку с пробелом ПЕРЕД заглавной буквой.

    Простое деление по «точка + пробел» разрезало «Сумма: 250–300 млн руб.
    (оценка инвестбанкира, официально не раскрывается)» на две «фразы», после
    чего вторая — оговорка про оценку — выбрасывалась как шум, и оценка
    экспертов превращалась на экране в раскрытую сумму. Правило «дальше
    заглавная» ошибается в безопасную сторону: склеит два предложения, а не
    разрежет одно (тот же разделитель в fix_truncated_fields.py).
    """
    parts = re.split(r'(?<=[.!?])\s+', t)
    out = []
    for p in parts:
        p = p.strip()
        if not p:
            continue
        if out and not re.match(r'^[«"(]?[А-ЯЁA-Z]', p):
            out[-1] += ' ' + p
            continue
        out.append(p)
    return out


def strip_opener(t):
    """-> (текст без зачина, режим: False винительный, True предложный, 'clause' придаточное)"""
    m = O_TOM.match(t)
    if m:
        return t[m.end():].lstrip(), 'clause'
    m = NOM_OPENER.match(t)
    if m:
        # остаток уже в именительном — склонять не нужно
        return t[m.end():].lstrip(), 'clause'
    m = ACC_OPENER.match(t)
    if m:
        return t[m.end():].lstrip(), False
    for rx in (PREP_OPENER, PREP_OPENER2, PREP_OPENER3):
        m = rx.match(t)
        if m:
            return t[m.end():].lstrip(), True
    return t, None


def acc_to_nominative(t):
    """Винительный -> именительный.

    Для среднего и мужского неодушевлённого винительный совпадает с именительным
    («описывает приобретение X» -> «Приобретение X»), поэтому там ничего делать не
    нужно. А вот женский род расходится: «освещает регуляторную ситуацию» после
    простого отсечения давало нечитаемое «Регуляторную ситуацию». Женское
    окончание винительного правильное и регулярное: -ую/-юю у прилагательного,
    -у/-ю у существительного; их и переводим.
    """
    words = t.split()
    if not words:
        return None
    i = 0
    changed = False
    # прилагательное женского рода в винительном
    if re.match(r'^[А-Яа-яЁё]+(?:ую|юю)$', words[0].strip('.,;:')):
        w = words[0]
        core = w.rstrip('.,;:')
        tail = w[len(core):]
        words[0] = (core[:-2] + ('ая' if core.endswith('ую') else 'яя')) + tail
        i = 1
        changed = True
    if i < len(words):
        w = words[i]
        core = w.rstrip('.,;:')
        tail = w[len(core):]
        # существительное женского рода в винительном (-у/-ю), но не служебное слово
        if len(core) > 3 and re.match(r'^[А-Яа-яЁё]+[ую]$', core) and core.lower() not in ('тому', 'кому'):
            words[i] = core[:-1] + ('а' if core.endswith('у') else 'я') + tail
            changed = True
        elif changed:
            # прилагательное перевели, а существительное не опознали — не рискуем
            return None
    return ' '.join(words)


def noun_nominative(word):
    """Слово из предложного в именительный по закрытой таблице; иначе None.

    Составные слова с дефисом («M&A-сделке», «pre-IPO-сделке») разбираются по
    последней части: «сделке» есть в таблице, и приписка спереди падежа не меняет.
    """
    core = word.strip('.,;:')
    low = core.lower()
    if low in CASE:
        return CASE[low] + word[len(core):]
    if '-' in low:
        head, _, tail = low.rpartition('-')
        if tail in CASE:
            return core[:len(head) + 1] + CASE[tail] + word[len(core):]
    return None


def to_nominative(t):
    """Первое слово (и прилагательное перед ним) из предложного в именительный."""
    words = t.split()
    if not words:
        return None
    # «о закрытии сделки И ЕЁ СТОРОНАХ» — второй однородный член остаётся в
    # предложном и после конверсии первого перестаёт с ним согласовываться.
    # Такие случаи не трогаем.
    if re.search(r'\s+и\s+(?:её|его|их)?\s*\w+(?:ах|ях|ии|ах)\b', ' '.join(words[:8]), re.I):
        return None
    first = words[0].lower().strip('.,;:')

    # Несклоняемая аббревиатура латиницей — «об IPO оператора АЗС», «о M&A-сделке
    # между …». Падежа у неё нет, склонять нечего: остаток уже читается сам.
    if re.match(r'^[A-Z][A-Za-z&.-]*$', words[0].strip('.,;:')):
        return ' '.join(words)

    if first in ADJ:
        # Обычно существительное идёт сразу за прилагательным — тогда берём его и
        # дальше не смотрим. Иначе поиск «ближайшего подходящего» ломал уже
        # работавшие случаи: в «о завершённой сделке на аукционе» кандидатов
        # оказывалось два («сделке» и «аукционе»), и правило отказывалось работать.
        if len(words) > 1 and noun_nominative(words[1]) is not None:
            hits = [1]
        else:
            # Существительное не обязано стоять вплотную: «о закрытой в конце
            # июня 2024 года сделке». Ищем дальше, но только если кандидат ровно
            # один — иначе непонятно, к чему относится прилагательное.
            hits = [j for j in range(2, min(len(words), 8))
                    if noun_nominative(words[j]) is not None]
        if len(hits) != 1:
            return None
        j = hits[0]
        words[0] = ADJ[first]
        words[j] = noun_nominative(words[j])
    else:
        conv = noun_nominative(words[0])
        if conv is None:
            return None
        words[0] = conv
    return ' '.join(words)


def cap(t):
    return t[:1].upper() + t[1:] if t else t


def cleaned_or_original(original, body):
    """Зачин распознать не удалось — но шум-то мы уже сняли, его и возвращаем.

    Раньше в этой ветке возвращался исходный текст, и вместе с неузнанным
    зачином на экран возвращалась и фраза «партнёры и юристы не названы».
    """
    return cap(body) if body.strip() != original.strip() else original


def process(text, known_sum=''):
    """-> (новое значение или None для очистки, метка что сделано)"""
    t = text.strip()
    # Раньше здесь стоял выход «не мета», если текст не начинается со
    # слова-источника. Из-за него шум оставался у 78 карточек, где фраза про
    # «консультанты в статье не названы» стоит НЕ в начале, а в конце:
    # «Сделка закрыта 8 августа 2024 года. … Консультирующая роль фирм не
    # упоминается в статье.» Зачин чинится только если он мета, а вот чистка
    # предложений-пустышек нужна всему тексту, где бы они ни стояли.
    meta_start = bool(META_START.match(t))

    raw = split_sentences(t)

    # 0) отрезаем ярлык источника, приклеенный через тире, — но только если
    #    первое предложение вообще содержательное. Иначе «Источник информации —
    #    Коммерсантъ.» теряло зачин и превращалось в осиротевшее «Коммерсантъ.»,
    #    вместо того чтобы выброситься целиком как чистая ссылка на источник.
    if raw and not is_source_only(raw[0]):
        m = LABEL_PREFIX.match(raw[0])
        if m:
            raw[0] = raw[0][m.end():].lstrip()

    # 1) выкидываем предложения, которые только про отсутствие информации,
    #    только про жанр источника или только про то, откуда взята информация
    kept = []
    prev_dropped = False
    for s in raw:
        if strip_glued_sum(s, known_sum) is not None:
            prev_dropped = True
            continue
        s = drop_noise_clause(s)
        s = IN_ARTICLE.sub('', s)
        m_acc = ACCORDING.match(s)
        if m_acc:
            s = cap(s[m_acc.end():])
        if is_noinfo(s) or GENRE_ONLY.match(s) or is_source_only(s):
            prev_dropped = True
            continue
        # «Сумма: 100-150 млн руб.» и «(по оценке экспертов).» разрезаются точкой
        # после «руб.» на два «предложения». Если первое выброшено, второе —
        # осиротевший хвост в скобках, и сам по себе он бессмыслен.
        if prev_dropped and not kept and re.match(r'^[(«]?\s*[а-яё]', s):
            continue
        prev_dropped = False
        kept.append(s)
    dropped_noinfo = len(kept) < len(raw)

    if not kept:
        return None, 'очищено (нет содержания)'

    body = ' '.join(kept)

    # Осталась только фраза «Сумма: …», и та же сумма уже лежит в своём поле —
    # в «Цели сделки» это дубль, а не смысл сделки. Проверяем ДО раннего выхода
    # для не-мета текстов: иначе после снятия шума карточка оставалась с одной
    # строкой «Сумма: более 20 млн USD», дублирующей соседнее поле.
    if re.match(r'^Сумма\s*:', body, re.I) and sum_fully_covered(body, known_sum):
        return None, 'очищено (осталась только сумма, она есть в своём поле)'

    # Ничего не изменилось и зачин не мета — трогать нечего.
    # Проверяем META_START по ОЧИЩЕННОМУ тексту, а не по исходному: ярлык
    # «Коммерсантъ, консультанты не указаны — » прятал за собой настоящий
    # мета-зачин «Статья сообщает о покупке…», и тот оставался неисправленным.
    if body == t and not meta_start:
        return text, 'не мета'

    # Осталась только фраза «Сумма: …», и та же сумма уже лежит в своём поле —
    # в «Цели сделки» это дубль, а не смысл сделки. Чистим.
    # Проверяем по склеенному тексту, а не по числу предложений: «Сумма: 6 млрд
    # руб. (экспертная оценка)» распадается на два «предложения» из-за точки
    # после «руб.», и счёт по len(kept) правило не срабатывало.
    if re.match(r'^Сумма\s*:', body, re.I) and sum_fully_covered(body, known_sum):
        return None, 'очищено (осталась только сумма, она есть в своём поле)'
    # если после выброса «нет информации» первым остался не-мета текст — просто берём его
    if not META_START.match(body):
        return cap(body), 'снят шум о консультантах'

    rest, prep = strip_opener(body)
    if prep is None:
        return cleaned_or_original(text, body), 'зачин не распознан'
    if prep == 'clause':
        rest = cap(rest)
        return (rest if len(rest) >= 25 else None), 'переписано (придаточное)'
    if prep:
        conv = to_nominative(rest)
        if conv is None:
            return cleaned_or_original(text, body), 'падеж не в таблице'
        rest = conv
    else:
        conv = acc_to_nominative(rest)
        if conv is None:
            return cleaned_or_original(text, body), 'винительный не разобран'
        rest = conv
    rest = ORPHAN_CLAUSE.sub('', rest).strip(' ,;')
    # «Информационное сообщение о сделке. Умар Кремлев приобрёл …» после
    # конверсии давало обрубок-заголовок «Сделка.» перед нормальным текстом.
    # Само по себе слово «сделка» ничего не сообщает — убираем.
    rest = re.sub(r'^сделк[аи]\.\s+(?=\S)', '', rest, flags=re.I)
    rest = cap(rest)
    # если после чистки осталась совсем короткая пустышка — честнее очистить
    if len(rest) < 25:
        return None, 'очищено (осталась пустышка)'
    return rest, ('переписано (предложный)' if prep else 'переписано (винительный)') + \
        (' + снят шум' if dropped_noinfo else '')


# Поля, которые чистим. Кроме «Цели сделки» тот же мусор лежит в `extra`:
# карточка показывает его на линзе «Обзор» под заголовком «Дополнительная
# информация», причём у 678 сделок это дословная копия eco.rationale. То есть
# пользователь видел пересказ статьи даже там, где «Цель сделки» уже исправлена.
# Пустое значение у полей разное: у rationale это «—» (карточка показывает
# прочерк в списке фактов), у extra — пустая строка, иначе на экране появится
# блок «Дополнительная информация» с одним прочерком.
FIELDS = (
    ('eco.rationale', lambda d: (d.get('eco') or {}).get('rationale'),
     lambda d, v: d['eco'].__setitem__('rationale', '—' if v is None else v)),
    ('extra', lambda d: d.get('extra'),
     lambda d, v: d.__setitem__('extra', '' if v is None else v)),
)


# Осколок вырезанной фразы: в поле осталась одна скобка без чисел — «(по
# экспертным оценкам, официально не подтверждено).». Так бывало, когда
# «Сумма: 600 млн руб. (по экспертным оценкам)» разрезалась точкой после «руб.»
# на два «предложения» и выбрасывалось только первое. Само по себе такое
# уточнение ни к чему не относится и на экране выглядит обрывком.
# Требуем отсутствия цифр: если в скобках есть число, там может быть факт.
ORPHAN_PAREN = re.compile(r'^\(.{0,140}\)\.?$', re.S)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    stats = collections.Counter()
    samples = collections.defaultdict(list)
    changes = []
    for field, get, set_ in FIELDS:
        for d in data['deals']:
            old = get(d)
            if not old:
                continue
            if ORPHAN_PAREN.match(old.strip()) and not nums(old):
                stats[(field, 'очищено (осколок в скобках)')] += 1
                changes.append((d['id'], field, old, None))
                if len(samples[(field, 'очищено (осколок в скобках)')]) < 2:
                    samples[(field, 'очищено (осколок в скобках)')].append((d['id'], old, None))
                if write:
                    set_(d, None)
                continue
            # Раньше здесь стоял пропуск всего, что не начинается со
            # слова-источника. Теперь через process() проходит каждое значение:
            # мета-зачин чинится только у «мета» текстов, а предложения-пустышки
            # («консультанты в статье не названы») снимаются везде — они чаще
            # стоят в конце фразы, чем в начале.
            new, tag = process(old, (d.get('eco') or {}).get('sum') or '')
            stats[(field, tag)] += 1
            if new != old:
                changes.append((d['id'], field, old, new))
                if len(samples[(field, tag)]) < 2:
                    samples[(field, tag)].append((d['id'], old, new))
                if write:
                    set_(d, new)

    print('РЕЗУЛЬТАТ ПО КАРТОЧКАМ:')
    for (field, tag), n in stats.most_common():
        print(f'  {n:4}  {field:14} {tag}')
    print(f'\nвсего изменится: {len(changes)}')
    for (field, tag), items in samples.items():
        if tag == 'не мета':
            continue
        print(f'\n--- {field}: {tag} ---')
        for i, o, n in items:
            print(f'  {i}')
            print(f'    было:  {o[:118]}')
            print(f'    стало: {"(поле очищено)" if n is None else n[:118]}')
    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=1, ensure_ascii=False)
        print('\nЗАПИСАНО в', PATH)


if __name__ == '__main__':
    main(write='--write' in sys.argv)
