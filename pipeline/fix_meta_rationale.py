# -*- coding: utf-8 -*-
"""Бэклог A1: «Цель сделки» пересказывает статью вместо смысла сделки.

У 315 карточек поле eco.rationale начинается с канцелярского зачина —
«Статья содержит информацию о…», «Источник информирует о…». Пользователь на
экране «Цель сделки» видит пересказ того, что где-то есть статья, а не зачем
делалась сделка.

Три разных случая, и лечатся они по-разному:

1. ТЕКСТ БЕЗ СОДЕРЖАНИЯ. «Статья содержит информацию о сделке, но не указывает
   консультантов». Про цель сделки здесь нет ничего, а про консультантов уже
   написано в своём поле. По принципу «пустое поле честнее правдоподобной
   выдумки» такие поля очищаем, а не переписываем.

2. ЗАЧИН С ВИНИТЕЛЬНЫМ ПАДЕЖОМ. «Статья описывает приобретение X 61% акций» —
   после отсечения зачина остаток грамматически самостоятелен:
   «Приобретение X 61% акций».

3. ЗАЧИН С ПРЕДЛОЖНЫМ ПАДЕЖОМ. «Статья сообщает о закрытии сделки» — простое
   отсечение даёт нечитаемое «закрытии сделки», поэтому первое слово (и
   прилагательное перед ним) переводим в именительный по таблице ниже.
   Таблица намеренно закрытая: угадывать падеж по окончаниям опасно — например,
   «о доле» и «о доли» разошлись бы, — поэтому всё, чего нет в таблице, скрипт
   не трогает и показывает в отчёте как необработанное.

Запуск:
    python3 pipeline/fix_meta_rationale.py            # сухой прогон с примерами
    python3 pipeline/fix_meta_rationale.py --write    # записать
"""
import json
import re
import sys
import collections

PATH = 'static/data/deals_promoted.json'

META_START = re.compile(
    r'^(?:стать\w+|публикац\w+|материал\w*|источник\w*|заметк\w+|новост\w+|текст\w*|'
    r'в\s+стать\w+|в\s+публикац\w+|в\s+материал\w+|в\s+источник\w+)\b',
    re.I)

# Зачин, после которого идёт винительный падеж — просто отсекаем
ACC_OPENER = re.compile(
    r'^(?:стать\w+|публикац\w+|материал\w*|источник\w*|заметк\w+|новост\w+|текст\w*)\s+'
    r'(?:описывает|освещает|фиксирует|рассматривает|подтверждает|отражает|'
    r'детализирует|раскрывает|характеризует)\s+', re.I)

# Зачин с предлогом «о/об» — дальше предложный падеж, нужна конверсия
PREP_OPENER = re.compile(
    r'^(?:стать\w+|публикац\w+|материал\w*|источник\w*|заметк\w+|новост\w+|текст\w*)\s+'
    r'(?:содержит\s+информацию|сообщает|информирует|публикует\s+информацию|'
    r'представляет\s+информацию|рассказывает|повествует|говорит|уведомляет|'
    r'информации|информацию|посвящен\w*)\s+об?\s+', re.I)

# «В статье сообщается о …»
PREP_OPENER2 = re.compile(r'^в\s+стать\w+\s+(?:\S+\s+){0,2}?об?\s+', re.I)

# Предлог сразу после слова-источника, без глагола: «Публикация о проведении IPO»
PREP_OPENER3 = re.compile(
    r'^(?:стать\w+|публикац\w+|материал\w*|источник\w*|заметк\w+|новост\w+|текст\w*)\s+об?\s+',
    re.I)

# «… о том, что <целое предложение>» — предлог с придаточным: сам предлог и
# «том, что» выбрасываем целиком, остаток уже стоит в именительном и читается сам.
O_TOM = re.compile(
    r'^(?:стать\w+|публикац\w+|материал\w*|источник\w*|заметк\w+|новост\w+|текст\w*)\s+'
    r'(?:\S+\s+){0,3}?об?\s+том,\s+что\s+', re.I)

# «В статье описана сделка …», «В статье упоминаются покупатели …».
# Это пассивные обороты: подлежащее после них уже стоит в именительном падеже,
# поэтому зачин достаточно просто отсечь, ничего не склоняя. Вариант с
# придаточным («упоминается, что …») ловим той же веткой.
NOM_OPENER = re.compile(
    r'^в\s+(?:стать\w+|публикац\w+|материал\w+|источник\w+)\s+'
    r'(?:описан\w*|описывается|описываются|упомина\w+|указан\w*|указыв\w+|'
    r'сообщается|говорится|приводится|отмечается|рассматривается|анализируется|'
    r'раскрывается|фиксируется)(?:,\s+что)?\s+', re.I)

# Предложение, которое целиком описывает ЖАНР источника и ничего не сообщает о
# сделке: «Статья является новостным сообщением», «Статья — информационное сообщение».
GENRE_ONLY = re.compile(
    r'^(?:стать\w+|публикац\w+|материал\w*|источник\w*|заметк\w+|новост\w+|текст\w*)\s*'
    r'(?:—|-|является|представляет\s+собой)\s*[^.]{0,70}$', re.I)

# Предложный -> именительный. Таблица закрытая: см. docstring.
CASE = {
    'сделке': 'сделка', 'сделках': 'сделки',
    'закрытии': 'закрытие', 'завершении': 'завершение', 'приобретении': 'приобретение',
    'продаже': 'продажа', 'покупке': 'покупка', 'выкупе': 'выкуп', 'слиянии': 'слияние',
    'переговорах': 'переговоры', 'выставлении': 'выставление', 'проведении': 'проведение',
    'одобрении': 'одобрение', 'решении': 'решение', 'привлечении': 'привлечение',
    'создании': 'создание', 'подписании': 'подписание', 'намерении': 'намерение',
    'планах': 'планы', 'инвестициях': 'инвестиции', 'реорганизации': 'реорганизация',
    'ликвидации': 'ликвидация', 'размещении': 'размещение', 'консолидации': 'консолидация',
    'передаче': 'передача', 'вхождении': 'вхождение', 'выходе': 'выход',
    'реструктуризации': 'реструктуризация', 'банкротстве': 'банкротство',
    'национализации': 'национализация', 'аукционе': 'аукцион', 'торгах': 'торги',
    'смене': 'смена', 'достижении': 'достижение', 'раунде': 'раунд',
    'готовности': 'готовность', 'объявлении': 'объявление', 'возможности': 'возможность',
    'результатах': 'результаты', 'структуре': 'структура', 'находке': 'находка',
    'сотрудничестве': 'сотрудничество', 'партнёрстве': 'партнёрство',
    'намерениях': 'намерения', 'условиях': 'условия', 'итогах': 'итоги',
}
ADJ = {
    'закрытой': 'закрытая', 'завершённой': 'завершённая', 'завершенной': 'завершённая',
    'потенциальной': 'потенциальная', 'планируемой': 'планируемая', 'состоявшейся': 'состоявшаяся',
    'предстоящей': 'предстоящая', 'крупной': 'крупная', 'новой': 'новая',
    'планируемом': 'планируемое', 'возможной': 'возможная', 'несостоявшейся': 'несостоявшаяся',
}

# Предложение сообщает лишь об ОТСУТСТВИИ сведений о консультантах.
# Такое предложение выбрасываем: для консультантов есть своё поле, и там уже
# написано «публично не раскрывались».
# Требуем И отрицание, И упоминание консультанта/фирмы в том же предложении —
# иначе под правило попадали бы содержательные фразы вроде «покупатель не
# назван», которые к консультантам отношения не имеют.
NOINFO_NEG = re.compile(
    r'(?:не\s+(?:содерж\w+|указан\w*|указыв\w+|назван\w*|называ\w+|раскрыт\w*|раскрыв\w+|'
    r'приведен\w*|приводит|сообщает|упомина\w+|уточня\w+|детализир\w+|конкретизир\w+)|'
    r'без\s+(?:указания|упоминания|раскрытия))', re.I)
NOINFO_OBJ = re.compile(
    r'(?:консультант\w*|консалтинг\w*|юрист\w*|юридическ\w*|фирм\w*|советник\w*|'
    r'инвестбанк\w*|инвестиционн\w*\s+(?:фирм|компани|банк)|их\s+роль|роль\s+как)', re.I)


# В предложении есть собственное содержание (цифры, сумма, доля) — выбрасывать
# его нельзя, даже если оно начинается с «в статье не указаны консультанты».
# Ловим случай, когда точка перед «Сумма:» потерялась и всё слиплось в одно
# предложение: раньше на такой карточке вместе с шумом пропадала сумма сделки.
HAS_SUBSTANCE = re.compile(r'\d|сумма\s*:|стоимост|цена\b', re.I)

# Осиротевшее придаточное про консультантов внутри предложения:
# «Переговоры между X и Y, однако не указывает, консультировала ли …» —
# после отсечения зачина у него пропадает подлежащее.
ORPHAN_CLAUSE = re.compile(
    r'[,;]\s*(?:однако|при\s+этом|но)?\s*не\s+(?:указыв\w+|указан\w*|сообщает|'
    r'уточня\w+|назван\w*|упомина\w+)[^.]*?(?:консультант\w*|консультировал\w*|'
    r'фирм\w*|юрист\w*|юридическ\w*|консалтинг\w*)[^.]*', re.I)


def is_noinfo(sentence):
    if HAS_SUBSTANCE.search(sentence):
        return False
    return bool(NOINFO_NEG.search(sentence) and NOINFO_OBJ.search(sentence))


def split_sentences(t):
    return [s.strip() for s in re.split(r'(?<=[.!?])\s+', t) if s.strip()]


def strip_opener(t):
    """-> (текст без зачина, режим: False винительный, True предложный, 'clause' придаточное)"""
    m = O_TOM.match(t)
    if m:
        return t[m.end():].lstrip(), 'clause'
    m = NOM_OPENER.match(t)
    if m:
        # остаток уже в именительном — склонять не нужно
        return t[m.end():].lstrip(), 'clause'
    m = ACC_OPENER.match(t)
    if m:
        return t[m.end():].lstrip(), False
    for rx in (PREP_OPENER, PREP_OPENER2, PREP_OPENER3):
        m = rx.match(t)
        if m:
            return t[m.end():].lstrip(), True
    return t, None


def acc_to_nominative(t):
    """Винительный -> именительный.

    Для среднего и мужского неодушевлённого винительный совпадает с именительным
    («описывает приобретение X» -> «Приобретение X»), поэтому там ничего делать не
    нужно. А вот женский род расходится: «освещает регуляторную ситуацию» после
    простого отсечения давало нечитаемое «Регуляторную ситуацию». Женское
    окончание винительного правильное и регулярное: -ую/-юю у прилагательного,
    -у/-ю у существительного; их и переводим.
    """
    words = t.split()
    if not words:
        return None
    i = 0
    changed = False
    # прилагательное женского рода в винительном
    if re.match(r'^[А-Яа-яЁё]+(?:ую|юю)$', words[0].strip('.,;:')):
        w = words[0]
        core = w.rstrip('.,;:')
        tail = w[len(core):]
        words[0] = (core[:-2] + ('ая' if core.endswith('ую') else 'яя')) + tail
        i = 1
        changed = True
    if i < len(words):
        w = words[i]
        core = w.rstrip('.,;:')
        tail = w[len(core):]
        # существительное женского рода в винительном (-у/-ю), но не служебное слово
        if len(core) > 3 and re.match(r'^[А-Яа-яЁё]+[ую]$', core) and core.lower() not in ('тому', 'кому'):
            words[i] = core[:-1] + ('а' if core.endswith('у') else 'я') + tail
            changed = True
        elif changed:
            # прилагательное перевели, а существительное не опознали — не рискуем
            return None
    return ' '.join(words)


def to_nominative(t):
    """Первое слово (и прилагательное перед ним) из предложного в именительный."""
    words = t.split()
    if not words:
        return None
    # «о закрытии сделки И ЕЁ СТОРОНАХ» — второй однородный член остаётся в
    # предложном и после конверсии первого перестаёт с ним согласовываться.
    # Такие случаи не трогаем.
    if re.search(r'\s+и\s+(?:её|его|их)?\s*\w+(?:ах|ях|ии|ах)\b', ' '.join(words[:8]), re.I):
        return None
    first = words[0].lower().strip('.,;:')
    if first in ADJ and len(words) > 1:
        second = words[1].lower().strip('.,;:')
        if second not in CASE:
            return None
        words[0] = ADJ[first]
        words[1] = CASE[second] + words[1][len(second):]
    elif first in CASE:
        words[0] = CASE[first] + words[0][len(first):]
    else:
        return None
    return ' '.join(words)


def cap(t):
    return t[:1].upper() + t[1:] if t else t


def process(text):
    """-> (новое значение или None для очистки, метка что сделано)"""
    t = text.strip()
    if not META_START.match(t):
        return text, 'не мета'

    # 1) выкидываем предложения, которые только про отсутствие информации
    sents = split_sentences(t)
    kept = [s for s in sents if not is_noinfo(s) and not GENRE_ONLY.match(s)]
    dropped_noinfo = len(kept) < len(sents)

    if not kept:
        return None, 'очищено (нет содержания)'

    body = ' '.join(kept)
    # если после выброса «нет информации» первым остался не-мета текст — просто берём его
    if not META_START.match(body):
        return cap(body), 'снят шум о консультантах'

    rest, prep = strip_opener(body)
    if prep is None:
        return text, 'зачин не распознан'
    if prep == 'clause':
        rest = cap(rest)
        return (rest if len(rest) >= 25 else None), 'переписано (придаточное)'
    if prep:
        conv = to_nominative(rest)
        if conv is None:
            return text, 'падеж не в таблице'
        rest = conv
    else:
        conv = acc_to_nominative(rest)
        if conv is None:
            return text, 'винительный не разобран'
        rest = conv
    rest = ORPHAN_CLAUSE.sub('', rest).strip(' ,;')
    rest = cap(rest)
    # если после чистки осталась совсем короткая пустышка — честнее очистить
    if len(rest) < 25:
        return None, 'очищено (осталась пустышка)'
    return rest, ('переписано (предложный)' if prep else 'переписано (винительный)') + \
        (' + снят шум' if dropped_noinfo else '')


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    stats = collections.Counter()
    samples = collections.defaultdict(list)
    changes = []
    for d in data['deals']:
        old = (d.get('eco') or {}).get('rationale')
        if not old or not META_START.match(old.strip()):
            continue
        new, tag = process(old)
        stats[tag] += 1
        if new != old:
            changes.append((d['id'], old, new))
            if len(samples[tag]) < 3:
                samples[tag].append((d['id'], old, new))
        if write and new != old:
            if new is None:
                d['eco']['rationale'] = '—'
            else:
                d['eco']['rationale'] = new

    print('РЕЗУЛЬТАТ ПО КАРТОЧКАМ:')
    for tag, n in stats.most_common():
        print(f'  {n:4}  {tag}')
    print(f'\nвсего изменится: {len(changes)}')
    for tag, items in samples.items():
        if tag in ('не мета',):
            continue
        print(f'\n--- {tag} ---')
        for i, o, n in items:
            print(f'  {i}')
            print(f'    было:  {o[:118]}')
            print(f'    стало: {"(поле очищено)" if n is None else n[:118]}')
    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=1, ensure_ascii=False)
        print('\nЗАПИСАНО в', PATH)


if __name__ == '__main__':
    main(write='--write' in sys.argv)
