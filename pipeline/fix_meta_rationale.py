"""Бэклог A1: карточка пересказывает статью вместо смысла сделки.

Поле начинается с канцелярского зачина — «Статья содержит информацию о…»,
«Источник информирует о…», «Сообщение о проведении IPO…». Пользователь видит
пересказ того, что где-то есть статья, а не зачем делалась сделка.

Чистим ДВА поля (см. FIELDS внизу): `eco.rationale` — «Цель сделки» на линзе
«Экономист», и `extra` — «Дополнительная информация» на «Обзоре». У 678 сделок
это была дословная копия друг друга, поэтому чинить только одно бессмысленно:
пересказ статьи остался бы на той же странице под другим заголовком.

Три разных случая, и лечатся они по-разному:

1. ТЕКСТ БЕЗ СОДЕРЖАНИЯ. «Статья содержит информацию о сделке, но не указывает
   консультантов». Про цель сделки здесь нет ничего, а про консультантов уже
   написано в своём поле. По принципу «пустое поле честнее правдоподобной
   выдумки» такие поля очищаем, а не переписываем.

2. ЗАЧИН С ВИНИТЕЛЬНЫМ ПАДЕЖОМ. «Статья описывает приобретение X 61% акций» —
   после отсечения зачина остаток грамматически самостоятелен:
   «Приобретение X 61% акций».

3. ЗАЧИН С ПРЕДЛОЖНЫМ ПАДЕЖОМ. «Статья сообщает о закрытии сделки» — простое
   отсечение даёт нечитаемое «закрытии сделки», поэтому первое слово (и
   прилагательное перед ним) переводим в именительный по таблице ниже.
   Таблица намеренно закрытая: угадывать падеж по окончаниям опасно — например,
   «о доле» и «о доли» разошлись бы, — поэтому всё, чего нет в таблице, скрипт
   не трогает и показывает в отчёте как необработанное.

Запуск:
    python3 pipeline/fix_meta_rationale.py            # сухой прогон с примерами
    python3 pipeline/fix_meta_rationale.py --write    # записать
"""
