# -*- coding: utf-8 -*-
"""Месячная очередь, 8 сентября 2026 — карточка `ce4fca919» («Продажа сети
квестов «Клаустрофобия»») стояла с даты объявления о поиске покупателя
(1 августа 2024) без единого структурного поля: не было ни `status`, ни
`buyer`, ни `seller`, ни `sum`. При этом в её же собственном списке `src`
уже лежали ДВЕ ссылки, прямо описывающие ИСХОД сделки, — их никто не
дочитал (`incrussia.ru`, заголовок «Крупнейшая сеть квестов «Клаустрофобия»
перешла к конкурентам», и РБК от 15.08.2025).

Личный WebFetch каждой из трёх ссылок (обе уже стоявшие в src плюс
kommersant.ru/doc/7971462, найденный сабагентом):

- incrussia.ru: «Передача активов состоялась 1 августа [2025]»; покупатель
  — команда конкурирующей сети GrimTeam через два новых юрлица, «ООО
  «Клаустрофобия онлайн»» и «ООО «Клаустрофобия офлайн»»: 51% — инвестору
  Вадиму Змовику, 33% — Павлу Вараксину (GrimTeam), 16% — Евгению Авину
  (назначен гендиректором). Передано: товарные знаки, права аренды локаций
  с оборудованием, ПО, соцсети, домен «клаустрофобия.рф» (это поле
  `law.struct» уже верно и не меняется).
- kommersant.ru/doc/7971462: продавец — Александр Ручьев (президент ГК
  «Основа», владел с 2019 года); «в 2023 году шли переговоры о продаже
  бизнеса «МТС Энтертеймент», но стороны не сошлись по цене и сути
  сделки» — то есть ранее названные в карточке потенциальные покупатели
  (МТС Live, Яндекс) сделкой не стали.
- Точная сумма нигде не раскрыта: со слов Вараксина, «сделка была в
  пределах озвученной ранее суммы» — то есть в диапазоне экспертной
  оценки 400–500 млн ₽ (`eco.val», уже стоит в карточке, не меняется).

Профиль покупателя GrimTeam уже существует в базе (`g6eb3c726») и уже
описывает ровно этот факт («Купила в 2025 году сеть квестов
«Клаустрофобия»... за 400 млн ₽») — карточка сделки просто не была с ним
связана. `seller`/`buyer_name» не заполняются одновременно с `buyer»
(профиль есть только для покупателя).

Дата сделки: карточка датирована 2024-08-01 (объявление о поиске
покупателя) — переносится на дату реального закрытия, 2025-08-01
(«Передача активов состоялась 1 августа»), поскольку статус меняется на
«Закрыта» и дата обязана отражать закрытие, а не объявление.

Запуск:
    python3 pipeline/fix_klaustrofobia_sale_closed_grimteam.py            # сухой прогон
    python3 pipeline/fix_klaustrofobia_sale_closed_grimteam.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'
CARD_ID = 'ce4fca919'
BUYER_ID = 'g6eb3c726'

OLD_DATE = '2024-08-01'
NEW_DATE = '2025-08-01'

OLD_EXTRA = (
    'Сеть квестов «Клаустрофобия» выставлена на продажу. Среди '
    'потенциальных покупателей называют МТС Live и Яндекс: МТС Live ранее '
    'предлагала согласовать стратегию и частично войти в капитал, но '
    'продавца это не устроило.'
)
NEW_EXTRA = (
    'Сеть квестов «Клаустрофобия» перешла от прежнего владельца — '
    'президента ГК «Основа» Александра Ручьева, владевшего сетью с '
    '2019 года — команде конкурирующей сети GrimTeam: 1 августа 2025 года '
    'учреждены два юрлица, «Клаустрофобия онлайн» и «Клаустрофобия '
    'офлайн», где 51% принадлежит инвестору Вадиму Змовику, 33% — '
    'сооснователю GrimTeam Павлу Вараксину и 16% — Евгению Авину, '
    'назначенному генеральным директором. Ранее рассматривалась продажа '
    'МТС Live и Яндексу, но переговоры с МТС в итоге не привели к сделке '
    '— стороны не сошлись в цене и условиях.'
)

OLD_CONTEXT = (
    'Президент ГК «Основа» Александр Ручьев — Статья об объявлении о '
    'поиске покупателя сети квестов «Клаустрофобия». Потенциальные '
    'покупатели: МТС Live (ранее пыталась согласовать стратегию и '
    'предложить частичное вхождение в капитал, но не устроило продавца) '
    'и Яндекс.'
)
NEW_CONTEXT = (
    'Сделка обсуждалась около полугода. Точная сумма не раскрыта: по '
    'словам совладельца GrimTeam Павла Вараксина, она «в пределах '
    'озвученной ранее суммы» — оценки годичной давности в 400–500 млн ₽.'
)

OLD_SHARE = '—'
NEW_SHARE = (
    'Покупатель — два новых юрлица, ООО «Клаустрофобия онлайн» и ООО '
    '«Клаустрофобия офлайн»: по 51% у инвестора Вадима Змовика, 33% — у '
    'Павла Вараксина (GrimTeam), 16% — у Евгения Авина.'
)

NEW_SRC = ['Коммерсантъ', 'https://www.kommersant.ru/doc/7971462']


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}
    card = by_id[CARD_ID]

    assert card.get('status') is None, 'status уже занят: %r' % (card.get('status'),)
    assert card.get('buyer') is None, 'buyer уже занят: %r' % (card.get('buyer'),)
    assert card.get('seller') is None, 'seller уже занят: %r' % (card.get('seller'),)
    assert card['date'] == OLD_DATE, 'date уже другая: %r' % (card['date'],)
    assert card['extra'] == OLD_EXTRA, 'extra уже другой: %r' % (card['extra'],)
    assert card['eco']['context'] == OLD_CONTEXT, 'eco.context уже другой: %r' % (card['eco']['context'],)
    assert card['eco']['share'] == OLD_SHARE, 'eco.share уже другой: %r' % (card['eco']['share'],)
    assert not any(s == NEW_SRC for s in card['src'])

    print('status None -> "Закрыта"')
    print('buyer None -> %r (GrimTeam)' % (BUYER_ID,))
    print('seller None -> "Александр Ручьев (президент ГК «Основа»)"')
    print('date %r -> %r' % (OLD_DATE, NEW_DATE))
    print('extra: переписан под реальный исход сделки')
    print('eco.context: переписан (МТС/Яндекс были только слухами, сделка не с ними)')
    print('eco.share: добавлена структура долей GrimTeam')
    print('src: + Коммерсантъ')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    card['status'] = 'Закрыта'
    card['buyer'] = BUYER_ID
    card['seller'] = 'Александр Ручьев (президент ГК «Основа»)'
    card['date'] = NEW_DATE
    card['extra'] = NEW_EXTRA
    card['eco']['context'] = NEW_CONTEXT
    card['eco']['share'] = NEW_SHARE
    card['src'].append(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
