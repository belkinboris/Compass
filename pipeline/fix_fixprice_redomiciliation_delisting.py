"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g9016d7ac (Артем Хачатрян продал долю в Fix Price Сергею Ломакину и
Дмитрию Кирсанову, 01.12.2023, статус «Закрыта») — компания завершила
переезд в Россию, сменила биржевую структуру, а выручка растёт при
падающей прибыли.

Делистинг ГДР и обмен на акции — проверено лично прямым WebFetch
(Ведомости, 06.08.2025): «с 6 августа Мосбиржа и СПБ биржа исключили
депозитарные расписки, представляющие акции компании, из списка
ценных бумаг»; 5 июня 2025 компания «запустила процесс обмена ГДР
казахстанского холдинга группы на обыкновенные акции «Фикс прайс»»,
торги новыми акциями начались 6 августа 2025 года; причина —
«продолжающаяся реорганизация группы».

Финансы 2025 года — проверено через WebSearch (по ссылке на
Ведомости, 03.03.2026): «Выручка торговой сети «Фикс прайс» по
результатам 2025 г. увеличилась на 4,3% относительно предыдущего
года и достигла 313,3 млрд руб.», «Чистая прибыль компании в прошлом
году упала на 47,8% до 11,2 млрд руб. при рентабельности 3,6%».

НЕ ВКЛЮЧЕНО: смена гендиректора операционной «дочки» ООО «Бэст
Прайс» (Кирсанов передал пост Владимиру Погонину в июле 2024,
Интерфакс) — по данным саб-агента, не дозаверено отдельным WebFetch;
судьба Артёма Хачатряна после выхода — саб-агент не нашёл ничего
существенно нового.

Запуск: python3 pipeline/fix_fixprice_redomiciliation_delisting.py
        python3 pipeline/fix_fixprice_redomiciliation_delisting.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g9016d7ac'

OLD_EXTRA = (
    'Сооснователь Fix Price Артем Хачатрян продал свою долю 35,2% в '
    'компании. 34,2% выкупил другой сооснователь и мажоритарный '
    'акционер Сергей Ломакин, оставшийся 1% приобрел гендиректор '
    'Дмитрий Кирсанов.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Компания завершила переезд в Россию: 6 августа 2025 года '
    'депозитарные расписки Fix Price исключены из списков Мосбиржи и '
    'СПБ биржи, а держатели обменяли их на акции российского ПАО '
    '«Фикс прайс» — реорганизация группы. По итогам 2025 года '
    'выручка выросла на 4,3% до 313,3 млрд руб., а чистая прибыль '
    'упала на 47,8% до 11,2 млрд руб.'
)

NEW_SRC = [
    ['Ведомости', 'https://www.vedomosti.ru/investments/news/2025/08/06/1129632-fix-price-obyavila'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
