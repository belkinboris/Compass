def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    comps = data['companies']
    inds = set(re.search(r'const INDUSTRIES\s*=\s*\[(.*?)\]',
                         open(os.path.join(ROOT, 'static', 'index.html'), encoding='utf-8').read(),
                         re.S).group(1).replace('"', '').split(','))
    inds = {x.strip() for x in inds}

    wrote, skipped = 0, []
    for cid, text in DESCRIPTIONS.items():
        c = comps.get(cid)
        assert c, 'профиля %s нет в базе' % cid
        assert 30 <= len(text) <= 200, 'описание %s вне 1–2 строк: %d' % (cid, len(text))
        old = str(c.get('desc') or '')
        if old.strip() == text:
            continue
        if old and not PLACEHOLDER.match(old) and cid not in OVERWRITE:
            skipped.append((cid, c.get('name'), old[:60]))
            continue
        print('  %-12s %-32s %s' % (cid, str(c.get('name'))[:32], text[:60]))
        c['desc'] = text
        wrote += 1

    ind_changed = 0
    for cid, (old_ind, new_ind) in INDUSTRY_FIXES.items():
        c = comps.get(cid)
        assert c, 'профиля %s нет в базе' % cid
        assert new_ind in inds, 'отрасли %r нет в INDUSTRIES' % new_ind
        if c.get('ind') == new_ind:
            continue
        assert c.get('ind') == old_ind, (cid, c.get('ind'), old_ind)
        print('  отрасль %-12s %-28s %s -> %s' % (cid, str(c.get('name'))[:28], old_ind, new_ind))
        c['ind'] = new_ind
        ind_changed += 1

    print('\nОписаний записано: %d | отраслей исправлено: %d' % (wrote, ind_changed))
    if skipped:
        print('Пропущено (уже есть своё описание, не трогаем): %d' % len(skipped))
        for cid, name, old in skipped[:5]:
            print('   %s %s — %r' % (cid, name, old))
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return 0
    json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('Записано.')
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
