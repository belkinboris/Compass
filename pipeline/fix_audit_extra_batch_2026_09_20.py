def main(write: bool) -> int:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    cards = {d["id"]: d for d in data["deals"]}
    decided = aq.decided_by_a_reader()
    log: list = []

    for cid, quote, dst in MOVES:
        card = cards[cid]
        apply_move(card, "extra", quote, dst, write, decided, cid, log)

    poly = cards[POLYMETAL_ID]
    apply_move(poly, "extra", POLYMETAL_QUOTE, "law.struct", write, decided,
               POLYMETAL_ID, log)

    adv_card = cards[ADV_ID]
    extra = adv_card.get("extra") or ""
    adv_list = (adv_card.get("law") or {}).get("adv") or []
    if ADV_EXTRA_QUOTE not in extra:
        log.append("%s: цитата не найдена дословно — пропущено" % ADV_ID)
    elif (ADV_ID, "extra") in decided or (ADV_ID, "law.adv") in decided:
        log.append("%s: extra или law.adv решены читателем — пропущено" % ADV_ID)
    elif adv_list != [ADV_OLD_PLACEHOLDER]:
        log.append("%s: law.adv не тот плейсхолдер, что ожидали — пропущено" % ADV_ID)
    else:
        log.append("%s: extra → law.adv (заменён устаревший плейсхолдер)" % ADV_ID)
        if write:
            adv_card["law"]["adv"] = [ADV_NEW_ENTRY]
            new_extra = extra.replace(ADV_EXTRA_QUOTE, "").strip()
            import re
            new_extra = re.sub(r"\s+", " ", new_extra)
            adv_card["extra"] = new_extra if new_extra else "—"

    print("Записей: %d" % len(log))
    for line in log:
        print("   " + line)

    if not write:
        print("\n(сухой прогон; чтобы записать — --write)")
        return 0
    DATA.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    print("\nзаписано")
    return 0


if __name__ == "__main__":
    sys.exit(main("--write" in sys.argv))
