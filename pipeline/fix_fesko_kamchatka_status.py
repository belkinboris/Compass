# -*- coding: utf-8 -*-
"""Месячная очередь, 8 сентября 2026 — карточка `c4e275305` («Передача
национализированных компаний под управление группе Феско (Росатом)»,
25 сентября 2025) не несла `status` вовсе (риск UNDEFINED на экране).

Личный WebFetch выяснил хронологию из трёх источников карточки:
- portnews.ru (12.09.2025): «Распоряжениями Росимущества дочерняя
  компания Транспортной группы FESCO назначена управляющей компанией
  ряда камчатских обществ» — уже свершившийся факт, но «ООО
  "Петропавловск-Камчатский морской торговый порт" и ООО "Камчатское
  морское пароходство" в управление Группе FESCO на текущий момент не
  переданы».
- atommedia.online (20.10.2025, позже даты карточки): «получила в
  управление ООО «Петропавловск-Камчатский морской торговый порт» и ООО
  «Камчатское морское пароходство»» — оставшиеся два ключевых актива
  переданы позже.

То есть к дате публикации самого позднего источника (20 октября) процесс
завершён целиком — по конвенции базы для указов/распоряжений о передаче
управления (CanPack, Danone Россия, «Нижфарм» — все «Закрыта») статус
выставлен «Закрыта», а в `eco.context` добавлена хронологическая
оговорка про поэтапность передачи.

Запуск:
    python3 pipeline/fix_fesko_kamchatka_status.py            # сухой прогон
    python3 pipeline/fix_fesko_kamchatka_status.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'
CARD_ID = 'c4e275305'

NEW_STATUS = 'Закрыта'

OLD_CONTEXT = (
    'Более десяти национализированных компаний передано под управление '
    'ООО «Транспортная группа Феско» (входит в группу Феско и Росатом). '
    'Компании были национализированы по делу о незаконном завладении '
    'имуществом чиновниками и депутатами Камчатки.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' Передача шла поэтапно: по состоянию на 12 сентября 2025 года '
    'ключевые активы — Петропавловск-Камчатский морской торговый порт и '
    'Камчатское морское пароходство — оставались вне управления FESCO, и '
    'перешли к группе только к 20 октября 2025 года.'
)


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}
    card = by_id[CARD_ID]

    assert card.get('status') is None, 'status уже занят: %r' % (card.get('status'),)
    assert card['eco']['context'] == OLD_CONTEXT, \
        'eco.context уже другой: %r' % (card['eco']['context'],)

    print('status: None -> %r' % NEW_STATUS)
    print('eco.context: добавляется хронология поэтапной передачи')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    card['status'] = NEW_STATUS
    card['eco']['context'] = NEW_CONTEXT

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
