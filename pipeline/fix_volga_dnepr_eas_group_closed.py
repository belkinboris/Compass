import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g1caed4b7'

OLD_DATE = '2025'
NEW_DATE = '2025-12-30'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Закрыта'

OLD_SUM = 'Не раскрыта'
NEW_SUM = '$130 млн (по оценке)'

OLD_EXTRA = (
    'Бывший гендиректор аэропорта Жуковский и авиакомпании Red Wings '
    'Евгений Солодилин намерен выкупить всю грузовую группу «Волга-'
    'Днепр». В августе владельцы группы предложили государству забрать '
    'активы безвозмездно, но получили отказ Минтранса.'
)
NEW_EXTRA = (
    '30 декабря 2025 года «ЕАС Групп» Евгения Солодилина закрыла '
    'сделку: ей перешли «Волга-Днепр-Москва» (управляющая компания '
    'группы), AirBridgeCargo, «Волга-Днепр Техникс» и 67% «Атрана» '
    '(остальные 33% остались у прежних владельцев). Сделка денежная, '
    'оплачена собственными и заёмными средствами покупателя. Ранее, в '
    'августе, владельцы группы предлагали государству забрать активы '
    'безвозмездно, но получили отказ Минтранса.'
)

OLD_ECO_CONTEXT = (
    'По неофициальным данным, у покупателя «Волга-Днепра» по итогам '
    'аудита есть план реструктуризации долга компании.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' Новый владелец планирует вернуть девять Boeing '
    'лизингодателям, оставшиеся иностранные самолёты — вернуть к '
    'полётам, а арестованные за рубежом борта — в Россию.'
)

OLD_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8041497?tg'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8041497'],
]
NEW_SRC = OLD_SRC + [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8361364'],
    ['Жуковские вести', 'https://www.zhukvesti.ru/articles/detail/69548/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['date'] == OLD_DATE
    assert deal['status'] == OLD_STATUS
    assert deal['sum'] == OLD_SUM
    assert deal['eco']['sum'] == OLD_SUM
    assert deal['extra'] == OLD_EXTRA
    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== date/status/sum: станет ===')
    print(NEW_DATE, '|', NEW_STATUS, '|', NEW_SUM)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['date'] = NEW_DATE
        deal['status'] = NEW_STATUS
        deal['sum'] = NEW_SUM
        deal['eco']['sum'] = NEW_SUM
        deal['extra'] = NEW_EXTRA
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
