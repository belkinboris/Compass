NEW_SRC = [
    ['CNews', 'https://www.cnews.ru/news/top/2023-08-28_gendirektor_sozdatelya_sistem'],
    ['TAdviser', 'https://www.tadviser.ru/index.php/Компания:Группа_Борлас_(Borlas)'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['law']['terms'] == OLD_LAW_TERMS
    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== law.terms: станет ===')
    print(NEW_LAW_TERMS)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['law']['terms'] = NEW_LAW_TERMS
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
