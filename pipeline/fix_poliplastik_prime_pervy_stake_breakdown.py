# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
`gmru-prime-pervy-poliplastik` (ЗПИФ «Прайм Первый» приобрёл 14% в
группе «Полипластик», Закрыта) — заголовок называет 14%, `eco.share` —
37,7%, а прямое перемножение долей (42,31% × 55,85% ≈ 23,6%) не
совпадает ни с одним из двух чисел. На первый взгляд похоже на дефект
переноса — оказалось, что нет.

Проверено ЛИЧНО прямым WebFetch (kommersant.ru/doc/8844198, уже в
`src` как первоисточник — прочитан целиком): «14,08% в ней получил ЗПИФ
«Прайм Первый»... Компания стала владельцем 42,31% в капитале ООО
«Строительно-инжиниринговая группа предприятий» (СИГП), которому
принадлежит 55,85% группы «Полипластик». Тем самым инвестор получил
37,7% в производителе.» — то есть 14,08% это ПРЯМАЯ доля фонда в самом
«Полипластике» (её и округляет заголовок), 23,6% (42,31% от 55,85%) —
непубликуемая КОСВЕННАЯ доля через СИГП, а 37,7% — их СУММА (прямая +
косвенная), названная статьёй как итоговая. Три числа не противоречат
друг другу, просто в `eco.share` не было сказано явно, что 37,7% —
совокупная величина. Также подтверждено: «Диалог Инвестициями», где
«66,67% принадлежат Вадиму Дубовику, совладелицей выступает Елена
Маркина» — управляющая компания фонда.

- interfax.ru/interview/1112426 (интервью с председателем совета
  директоров «Полипластика» Михаилом Гориловским, 1 сентября 2026,
  проверено ЛИЧНО прямым WebFetch): на вопрос, кто такой ЗПИФ «Прайм
  Первый», ответ уклончив — «Наш партнер хорошо знаком с нефтегазовой
  отраслью»; на средства сделки: «Все средства пошли на уменьшение
  долговой нагрузки группы» — расставляет другой акцент, чем июльская
  формулировка Коммерсанта («привлечённые средства направят на
  развитие инфраструктурных проектов», уже в `law.struct`). Оба
  источника дословны и проверяемы — расхождение в акценте зафиксировано
  честно, не разрешается на глаз.

НЕ ВНЕСЕНО: личность партнёра сверх уже названного (Дубовик/Маркина) —
Гориловский сам уклонился от прямого ответа.

`buyer_name`/`status`/`title` карточки НЕ тронуты — заголовок остаётся
верным (называет прямую долю), правка только поясняет расчёт.

Запуск: python3 pipeline/fix_poliplastik_prime_pervy_stake_breakdown.py
        python3 pipeline/fix_poliplastik_prime_pervy_stake_breakdown.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gmru-prime-pervy-poliplastik'

OLD_ECO_CONTEXT = (
    'В 2024 году в капитал «Полипластика» вошли структуры Газпромбанка. '
    'Сейчас ЗПИФ «Газпромбанк-Комплексный» владеет 16,11%, а ЗПИФ '
    '«Кипарис» — 5,37%.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' Управляет фондом «Прайм Первый» УК «Диалог '
    'Инвестиции» (66,67% у Вадима Дубовика, совладелица — Елена '
    'Маркина). Названные в источнике доли не противоречат друг другу: '
    '14,08% — прямая доля фонда в самом «Полипластике» (её и округляет '
    'заголовок), а 37,7% — совокупная величина вместе с косвенной '
    'долей через СИГП. В интервью 1 сентября 2026 года председатель '
    'совета директоров Михаил Гориловский не раскрыл, кто стоит за '
    'фондом («партнёр хорошо знаком с нефтегазовой отраслью»), и '
    'сказал, что «все средства пошли на уменьшение долговой нагрузки '
    'группы» — с другим акцентом, чем июльское заявление о развитии '
    'инфраструктурных проектов.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
