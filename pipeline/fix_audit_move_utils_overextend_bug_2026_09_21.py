def main(write: bool) -> int:
    data = json.load(open(DATA, encoding="utf-8"))
    cards = {d["id"]: d for d in data["deals"]}
    log = []

    for cid, area, field, keep, restore in REPAIRS:
        card = cards[cid]
        cur = card[area][field]
        expect = keep + " " + restore
        assert cur == expect, "%s.%s.%s: не совпало\n  есть: %r\n  ждали: %r" % (
            cid, area, field, cur, expect)
        extra = card.get("extra") or ""
        new_extra = (restore + " " + extra).strip() if extra and extra not in ("—", "-") else restore
        log.append("%s: %s.%s → оставлено «%s…», в extra вернулось «%s…»"
                    % (cid, area, field, keep[:40], restore[:40]))
        if write:
            card[area][field] = keep
            card["extra"] = new_extra

    struct_card = cards[STRUCT_ID]
    cur_ctx = struct_card["eco"]["context"]
    expect_ctx = STRUCT_KEEP_CONTEXT + " " + STRUCT_RESTORE
    assert cur_ctx == expect_ctx, "g4b447867.eco.context не совпало: %r" % cur_ctx
    assert struct_card["law"]["struct"] == "—"
    log.append("g4b447867: eco.context оставлено без штампа, law.struct ← штамп проверки")
    if write:
        struct_card["eco"]["context"] = STRUCT_KEEP_CONTEXT
        struct_card["law"]["struct"] = STRUCT_RESTORE

    g39 = cards[G39_ID]
    cur_share = g39["eco"]["share"]
    expect_share = G39_SHARE_KEEP + " " + G39_FIN_RESTORE
    assert cur_share == expect_share, "g39218eec.eco.share не совпало: %r" % cur_share
    assert g39["eco"]["fin"] == "—", "g39218eec.eco.fin уже не пуст: %r" % g39["eco"]["fin"]
    log.append("g39218eec: eco.share оставлено «Куплено 100%…», eco.fin ← «Расчёт состоял…»")
    if write:
        g39["eco"]["share"] = G39_SHARE_KEEP
        g39["eco"]["fin"] = G39_FIN_RESTORE

    print("Записей: %d" % len(log))
    for line in log:
        print("   " + line)
    if not write:
        print("\n(сухой прогон; чтобы записать — --write)")
        return 0
    json.dump(data, open(DATA, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("\nзаписано")
    return 0


if __name__ == "__main__":
    sys.exit(main("--write" in sys.argv))
