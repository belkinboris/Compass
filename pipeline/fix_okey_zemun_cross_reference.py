# -*- coding: utf-8 -*-
"""Заметка 509 (консоль, 4 сентября 2026): «Две разные сделки. Делаем
вторую карточку. Но в карточках в доп информации можно указать, что в
этот же день другая сделка и ссылку», отвечая на карточку `g31136d69»
(O'Key Group S.A. продала гипермаркеты российскому менеджменту).

Вторая карточка (`g74fd5cdb», «Земун»/«Лента» получила 99% «РБФ
ритейл») уже существует — обе датированы 25.11.2025. Владелец
подтвердил: не сливать, оставить раздельно, но перекрёстно сослаться
друг на друга в «Дополнительной информации».

Запуск: python3 pipeline/fix_okey_zemun_cross_reference.py [--write]
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

OLD_EXTRA_A = ("Люксембургская O'Key Group S.A. продала бизнес гипермаркетов "
               "российскому менеджменту. В сделку вошло ООО «О'Кей» с 77 "
               "гипермаркетами, товарным знаком и логистической "
               "инфраструктурой. Менеджмент взял на себя погашение долга на "
               "45,9 млрд ₽.")
ADDITION_A = (" В тот же день, 25 ноября 2025 года, стало известно ещё об "
              "одной сделке вокруг того же актива: ООО «Земун», связанное с "
              "«Лентой», получило 99% контроля над «РБФ ритейл» — компанией, "
              "управляющей сетью «О'Кей» (этому посвящена отдельная "
              "карточка).")

OLD_EXTRA_B = ("ООО «Земун», связанное с «Лентой», получило 99% контроля "
               "над компанией «РБФ ритейл», которая управляет сетью "
               "гипермаркетов «О'кей». ФАС одобрила сделку в середине "
               "октября 2025 года. В периметр вошли магазины «О'кей», "
               "онлайн-платформа, товарные знаки и логистическая "
               "инфраструктура. Покупка 75 гипермаркетов была безденежной: "
               "«Лента» приняла на себя долговые обязательства. Сеть "
               "дискаунтеров «Да!» в соглашение не вошла и осталась у "
               "прежнего владельца сети «О'кей».")
ADDITION_B = (" В тот же день, 25 ноября 2025 года, стало известно ещё об "
              "одной сделке вокруг того же актива: O'Key Group S.A. продала "
              "бизнес гипермаркетов «О'Кей» российскому менеджменту (этому "
              "посвящена отдельная карточка).")


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {c['id']: c for c in data['deals']}

    a = by_id['g31136d69']
    assert a['extra'] == OLD_EXTRA_A, a['extra']
    a['extra'] = OLD_EXTRA_A + ADDITION_A

    b = by_id['g74fd5cdb']
    assert b['extra'] == OLD_EXTRA_B, b['extra']
    b['extra'] = OLD_EXTRA_B + ADDITION_B

    print('g31136d69 и g74fd5cdb: добавлены перекрёстные ссылки')

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
            f.write('\n')
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
