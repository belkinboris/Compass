# -*- coding: utf-8 -*-
"""Поломка, найденная при выборе карточек месячной очереди 2 сентября 2026 —
карточка g424715f8 («АФК «Система» /  РПХ «Восход»», сделка с «Морепроект»
о судьбе доли в «дочке» «Системы») несла в `law.struct` буквальные
обратные слэши перед каждой кавычкой и обрыв предложения без точки:

    'Сделка состоялась 21 июля, по ее итогам \\«дочка\\» \\«Системы\\» — АО '
    '\\«Море проект\\» сохранило за собой 77,5% РПХ \\"Восход\\'

На экране (вкладка «Юрист») это читалось буквально как обратные слэши
перед каждой кавычкой — видимый дефект, не просто некрасивый символ.

Причина — в таблице `FIXES` (pipeline/ingest/fixes/batch_agents100_r5.py,
запись `id='g424715f8', field='law.struct'`, «партия 5 агентов, раунд 5,
15.08.2026»): значение было вставлено в Python-строку как кусок JSON-
экранированного текста («\\"дочка\\"» и т. п.) БЕЗ раскодирования
экранирования сначала — то есть обратные слэши стали частью самого
значения, а не служебными символами Python. Более поздний прогон чистки
типографики (см. CLAUDE.md: «Тире — это и подпись...», механизм
`typo_flat()`) заменил внутри этого значения прямые кавычки на ёлочки
парами, но `typo_flat()` нормализует только кавычки/тире/десятичную
точку — обратные слэши он не трогает, поэтому они остались. Тот же
прогон, видимо, и обрубил конец предложения (нет ни закрывающей кавычки,
ни точки).

Проверено лично прямым WebFetch (Интерфакс, уже стоит в `src` карточки,
https://www.interfax.ru/business/912966): «Сделка состоялась 21 июля,
по ее итогам "дочка" "Системы" - АО "Море проект" сохранило за собой
77,5% РПХ "Восход".» — полное предложение с точкой, прямые кавычки в
источнике (наш стиль для прозы — ёлочки, как у соседней записи в том же
файле фиксов). Новый источник не нужен, `src` не меняется.

Проверено, что это НЕ более широкий класс: `grep` по всем
`pipeline/ingest/fixes/*.py` на `\\\\[«»"]` нашёл только эту одну запись
с реальными обратными слэшами перед кавычками внутри значения `new`/
`quote` — остальные вхождения `\\"` в файлах фиксов оказались обычным
Python-экранированием кавычки ВНУТРИ строки, ограниченной той же самой
кавычкой (корректный, не дефектный код), не escape-мусором в данных.

Запуск: python3 pipeline/fix_afk_sistema_vosход_law_struct_corruption.py
        python3 pipeline/fix_afk_sistema_vosход_law_struct_corruption.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g424715f8'

OLD_LAW_STRUCT = (
    'Сделка состоялась 21 июля, по ее итогам \\«дочка\\» \\«Системы\\» — АО '
    '\\«Море проект\\» сохранило за собой 77,5% РПХ \\"Восход\\'
)
NEW_LAW_STRUCT = (
    'Сделка состоялась 21 июля, по ее итогам «дочка» «Системы» — АО «Море '
    'проект» сохранило за собой 77,5% РПХ «Восход».'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['law']['struct'] == OLD_LAW_STRUCT, repr(deal['law']['struct'])

    print('=== law.struct: было (с обратными слэшами) ===')
    print(OLD_LAW_STRUCT)
    print('\n=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)

    if write:
        deal['law']['struct'] = NEW_LAW_STRUCT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
