"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка ge9489d60
(ГК «Полипластик» приобрела 25% видеоаналитического сервиса
QMonitoring) — карточка уже подробно проработана; найден масштаб роста
цели после сделки и расширение клиентской базы за пределы Полипластика.

Масштаб бизнеса на 2026 год — проверено лично прямым WebFetch
(sk.ru, про презентацию на Иннопром-2026): «Система видеомониторинга
стройплощадок на базе ИИ с точностью распознавания свыше 95% контролирует
более 500 объектов в рамках национальных проектов и внедрена в
Федеральном казначействе и у застройщиков из топ-10».

Финансы цели — проверено лично прямым WebFetch (audit-it.ru): выручка
ООО «Интеллектуальные стройрешения» выросла в 3,2 раза за 2025 год до
161 млн руб. (с ~50 млн руб. в 2024 году), чистая прибыль за 2025 год —
56,4 млн руб. (на 37,9% больше 2024 года).

Расширение клиентской базы за пределы Полипластика — проверено лично
прямым WebFetch (globalcio.ru, кейс застройщика ООО «Разум», ЖК «Разум
на Боевой» в Астрахани, июнь-ноябрь 2025 года): «За первый месяц
эксплуатации система автоматически зафиксировала 64 инцидента», «После
корректировки алгоритмов и проведения профилактической работы с
подрядчиками количество нарушений сократилось на 80%» — то есть
QMonitoring работает не только на площадках Полипластика, а стал
самостоятельным поставщиком технологии для рынка.

НЕ ВКЛЮЧЕНО: прямых новостей о развитии сотрудничества именно на
площадках Полипластика в 2025-2026 годах не найдено (упоминание ИИ у
Полипластика в CNews оказалось про отдельное партнёрство с Cloud.ru, не
про QMonitoring); новых раундов финансирования QMonitoring после сделки
с Полипластиком не нашлось.

Запуск: python3 pipeline/fix_polyplastic_qmonitoring_postdeal.py
        python3 pipeline/fix_polyplastic_qmonitoring_postdeal.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'ge9489d60'

OLD_EXTRA = (
    'Покупатель приобрел 25% доли в ООО «Интеллектуальные стройрешения», '
    'управляющим сервисом QMonitoring для видеоаналитики на строительных '
    'площадках. По сделке QMonitoring предоставит строительные площадки '
    'для развертывания системы видеоаналитики.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' К 2026 году сервис вырос в самостоятельного поставщика технологии: '
    'система контролирует более 500 объектов в рамках нацпроектов, '
    'внедрена в Федеральном казначействе и у застройщиков из топ-10 '
    '(sk.ru). Выручка «Интеллектуальных стройрешений» выросла в 3,2 раза '
    'за 2025 год до 161 млн руб., прибыль составила 56,4 млн руб. '
    '(audit-it.ru). Среди новых клиентов вне периметра Полипластика — '
    'застройщик «Разум» (ЖК «Разум на Боевой», Астрахань): система '
    'сократила число нарушений на 80% за первые месяцы эксплуатации '
    '(globalcio.ru).'
)

NEW_SRC = [
    ['sk.ru', 'https://sk.ru/news/skolkovo-na-innoprom-2026-pokazhet-tehnologii-kotorye-uzhe-ekonomyat-promyshlennosti-milliardy/'],
    ['audit-it.ru', 'https://www.audit-it.ru/contragent/1247700113330_ooo-intellektualnye-stroyresheniya'],
    ['globalcio.ru', 'https://globalcio.ru/projects/53782/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
