# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка `g4c3f2103`
(«Агрохолдинг «Степь» купил два сельхозпредприятия в Ставропольском
крае», закрыта, 2023) — дочитывание нашло сумму сделки (поле было
пустым) и исправило финансовые показатели предмета, ранее внесённые
неверно и с опечаткой в имени одной из компаний.

Проверено ЛИЧНО прямым WebFetch (kommersant.ru/doc/6125282):
- «За покупку этих предприятий в Грачевском районе Ставрополья,
  агрохолдинг «Степь» заплатил 2,5 млрд руб.» — сумма сделки, поле было
  «Не раскрыта». НЕ ПУТАТЬ с соседней сделкой тех же покупателя и
  структуры продавца — СП «Гвардеец» (26 тыс. га, 2,9 млрд ₽, апрель
  2023, отдельная карточка в базе отсутствует) — суммы и площади разные,
  спутать нельзя.
- «ООО СХП «Хуторок» и ООО «Сергеевское»» — правильное написание второй
  компании через «е» (в карточке и в профиле компании стояло
  «Сергиевское» — опечатка).
- «ООО СХП «Хуторок»: выручка компании составила 37,7 млн руб., а чистая
  прибыль — 17,2 млн руб.» и «ООО «Сергеевское»: выручка компании
  составила 166,9 млн руб., а чистая прибыль — 39,9 млн руб.» — в
  карточке ДО этой правки стояли другие числа (170 млн ₽ выручки
  «Сергиевское», 59 млн ₽ «Хуторок», без прибыли вовсе) — они не
  подтвердились дословным чтением того же источника, откуда была взята
  исходная запись `FIXES`, и заменяются на дословно проверенные.

Остальное — по докладу саб-агента, дословные цитаты:
- vedomosti.ru/business/articles/2023/07/27/987112-agroholding-step-kupil-
  18-000-ga-na-yuge-rossii: «Возрождение» основали в 2010 году Хаджи-
  Мурат Голаев и Арсен Салпагаров» — доли на момент сделки (50,52% и
  49,48%) уже верно стоят в поле `seller`.
- kommersant.ru/doc/5940029 (соседняя, более ранняя сделка тех же
  сторон, 2020 год): «в 2020 году «Степь» приобрела активы "Возрождения"
  (предприятия "Высоцкое" и "Чапаевское" с 28 тыс. га и молочной
  фермой)», а «Возрождение» тогда же купило у «Степи» тепличный комплекс
  «Южный» в Карачаево-Черкесии» — стороны уже обменивались активами
  раньше.

НЕ ВНЕСЕНО: (1) юридический/финансовый консультант — ноль по всем
проверенным источникам (Коммерсантъ ×3, лид «Ведомостей», заголовок
Forbes); (2) прямая причина продажи со стороны Голаева/Салпагарова — не
названа ни в одном источнике; (3) масштаб бизнеса «Возрождения» на
момент ИМЕННО этой сделки (100 тыс. га земли, прибыль 2,75 млрд ₽ за
2020 год) — цифры из рэнкинга за более ранний период, не по состоянию
на 2023 год, не вносятся во избежание путаницы времени.

Запуск: python3 pipeline/fix_step_vozrozhdenie_sum_and_financials.py
        python3 pipeline/fix_step_vozrozhdenie_sum_and_financials.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g4c3f2103'
TARGET_ID = 'g2e964da0'

OLD_SUM = 'Не раскрыта'
NEW_SUM = '2,5 млрд ₽'

OLD_ECO_SUM = 'Не раскрыта'
NEW_ECO_SUM = '2,5 млрд ₽'

OLD_ECO_TARGET_FIN = (
    'За 2022 год выручка ООО «Сергиевское» составила 170 млн ₽, ООО СХП '
    '«Хуторок» — 59 млн ₽.'
)
NEW_ECO_TARGET_FIN = (
    'За 2022 год выручка ООО «Сергеевское» составила 166,9 млн ₽, чистая '
    'прибыль — 39,9 млн ₽; у ООО СХП «Хуторок» — 37,7 млн ₽ выручки и '
    '17,2 млн ₽ чистой прибыли.'
)

OLD_ECO_CONTEXT = (
    'За первое полугодие 2023 года выручка агрохолдинга «Степь» выросла '
    'на 40,5% год к году — с 29,4 млрд ₽ до 41,3 млрд ₽.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' Стороны уже обменивались активами раньше: в 2020 '
    'году «Степь» купила у «Возрождения» «Высоцкое» и «Чапаевское» (28 '
    'тыс. га и молочная ферма), а «Возрождение» купило у «Степи» '
    'тепличный комплекс «Южный» в Карачаево-Черкесии.'
)

OLD_TARGET_NAME = 'ООО «Сергиевское» и ООО СХП «Хуторок»'
NEW_TARGET_NAME = 'ООО «Сергеевское» и ООО СХП «Хуторок»'


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)
    target = data['companies'][TARGET_ID]

    assert deal['sum'] == OLD_SUM
    assert deal['eco']['sum'] == OLD_ECO_SUM
    assert deal['eco']['target_fin'] == OLD_ECO_TARGET_FIN
    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert target['name'] == OLD_TARGET_NAME

    print('=== sum: станет ===')
    print(NEW_SUM)
    print('\n=== eco.sum: станет ===')
    print(NEW_ECO_SUM)
    print('\n=== eco.target_fin: станет ===')
    print(NEW_ECO_TARGET_FIN)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== companies[%s].name: станет ===' % TARGET_ID)
    print(NEW_TARGET_NAME)

    if write:
        deal['sum'] = NEW_SUM
        deal['eco']['sum'] = NEW_ECO_SUM
        deal['eco']['target_fin'] = NEW_ECO_TARGET_FIN
        deal['eco']['context'] = NEW_ECO_CONTEXT
        target['name'] = NEW_TARGET_NAME
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
