import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gbf0be72c'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Не состоялась'

OLD_ECO_CONTEXT = '—'
NEW_ECO_CONTEXT = (
    'Сделка с АвтоВАЗом не состоялась: весной 2023 года решение о '
    'покупателе изменилось, и «РНЛ Лизинг» в конкурентном процессе '
    '(против структур, близких к Локо-банку и Экспобанку) выиграла '
    'инвестиционная группа «Инсайт» — сделка с ней закрылась 10 августа '
    '2023 года. В ноябре 2023 года компания переименована в «Флит '
    'Автолизинг» и продолжила работу без перерыва в обслуживании '
    'клиентов.'
)

OLD_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/5887461'],
]
NEW_SRC = OLD_SRC + [
    ['Frank Media', 'https://frankmedia.ru/136125'],
    ['Флит Автолизинг', 'https://fleetautolease.ru/news/rnl-lizing-menyaet-nazvanie-na-flit-avtolizing/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS
    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== status: станет ===')
    print(NEW_STATUS)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['status'] = NEW_STATUS
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
