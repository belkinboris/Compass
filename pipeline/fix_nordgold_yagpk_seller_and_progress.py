import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g59fbdbf8'

NEW_SELLER = 'ПАО «Якутская топливно-энергетическая компания» (ЯТЭК)'

OLD_CONTEXT = (
    'ЯГПК была учреждена в 2017 году «Якутской топливно-энергетической '
    'компанией» (ЯТЭК, на тот момент входила в группу «Сумма» Зиявудина '
    'Магомедова) как оператор строительства завода по производству '
    'метанола в Якутии. Тогда предполагалось, что строительство первой '
    'очереди завода мощностью 1,75 млн т в год начнется в 2019 году. '
    'Завершение строительно-монтажных работ ожидалось в 2021 году, а '
    'первые поставки продукции — с 2022 года. Предварительная стоимость '
    'возведения первой очереди мощностью 1,75 млн т в год оценивалась '
    'чуть больше чем в $1 млрд. Впоследствии ЯТЭК, сменившая владельца, от '
    'проекта отказалась.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' Инвестиции Nordgold в разработку цинкового месторождения «Сардана» '
    '«составят 31,3 млрд руб. до 2030 г.» (Ведомости; сумма самой сделки '
    'по покупке ЯГПК не раскрывалась). В 2025–2026 годах «на Сардане '
    'продолжится экологический мониторинг и геологоразведка»: '
    '«подтвержденные Nordgold запасы, ранее заявленные предыдущими '
    'владельцами, оказались недостаточными для подготовки '
    'технико-экономического обоснования», обновлённые данные ожидаются '
    'в первом–втором квартале 2026 года (EastRussia).'
)

NEW_SRC = [
    ['EastRussia', 'https://www.eastrussia.ru/material/byulleten-eastrussia-obzor-gornodobychi-dfo-leto-2024/'],
    ['Ведомости', 'https://www.vedomosti.ru/business/articles/2024/09/13/1061945-nordgold-vlozhit-bolee-30-mlrd-v-dobichu-tsinka'],
    ['EastRussia', 'https://www.eastrussia.ru/news/nordgold-rassmatrivaet-vozmozhnost-dobychi-germaniya-na-mestorozhdenii-v-yakutii/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal.get('seller') is None
    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print(f'=== seller (новое поле): станет {NEW_SELLER!r} ===')
    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['seller'] = NEW_SELLER
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
