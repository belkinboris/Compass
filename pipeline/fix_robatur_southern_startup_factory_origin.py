import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gc7e35605'

OLD_RATIONALE = '—'
NEW_RATIONALE = (
    'Идея стартапа возникла у Александра Абатурова во время обучения в '
    'магистратуре Научно-технологического университета «Сириус»; грант '
    'Фонда содействия инновациям позволил начать разработку и '
    'тестирование первых прототипов. На трёх предприятиях, где уже '
    'установлены роботы «Робатура» для перемещения упаковок, '
    'зафиксировано сокращение затрат на фонд оплаты труда на 65% при '
    'росте объёма выпускаемой продукции. Инвестор, ООО «Южная фабрика '
    'стартапов» (зарегистрировано в декабре 2022 года), — '
    'университетская стартап-студия, среди учредителей — Южный '
    'федеральный университет и Донской государственный технический '
    'университет.'
)

NEW_SRC = [
    ['Сириус (федеральная территория)', 'https://sirius-ft.ru/tpost/kompaniya-iz-siriusa-razrabatyvaet-robota-dlya-avtomatizatsii-proizvodstv/'],
    ['Audit-it.ru', 'https://www.audit-it.ru/contragent/1226100032400_ooo-yufs'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['rationale'] == OLD_RATIONALE

    new_src = deal['src'] + NEW_SRC

    print('=== eco.rationale: станет ===')
    print(NEW_RATIONALE)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['rationale'] = NEW_RATIONALE
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
