# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g91606f1b
(«Русагро купила 50% акций НМЖК», закрыта 28 июня 2023) — не были
названы продавцы, судьба оставшихся 50% (Wilmar) и последующая
внутренняя реструктуризация масложирового бизнеса «Русагро».

Проверено лично прямым WebFetch (Интерфакс, https://www.interfax.ru/business/909101):
«Совместно с другим управляющим партнером группы Николаем Сидорком он
считается совладельцем НМЖК» — продавцы: Николай Нестеров (управляющий
партнёр, председатель совета директоров ГК «НМЖК») и Николай Сидорок
(управляющий партнёр); «с 23 июня этого года гендиректором ПКФ
"Профит", владеющей предприятиями НМЖК, стал Ян Кубинский, бывший
топ-менеджер холдинга "Солнечные продукты", часть активов которого
перешла "Русагро"».

Проверено лично прямым WebFetch (Коммерсантъ, https://www.kommersant.ru/doc/6069244):
«представители "Русагро" сообщили "Ъ", что планируют развивать бренды
НМЖК совместно с Wilmar» — сингапурская Wilmar International осталась
совладельцем оставшихся 50%, сделка её доли не касалась.

Проверено лично прямым чтением кэша (TAdviser, дозабран
`fetch_article_texts.py`, https://www.tadviser.ru/index.php/Компания:Нижегородский_масло-жировой_комбинат_(ГК_НМЖК)):
«с 5 августа 2024 года собственником АО «НМЖК» стало московское АО
«Эталон». Руководит новым владельцем Анвар Анваров, который ранее — 18
июля 2024 года — был назначен гендиректором АО «Жировой комбинат» и АО
ТД «НМЖК»» — это внутренняя реструктуризация холдинговой структуры
самой «Русагро» (консолидация её масложировых активов под «Эталоном»),
а не смена конечного контролирующего собственника.

НЕ ВКЛЮЧЕНО: точное имя второго продавца, помимо Николая Сидорка, —
более старые материалы называют «Ивана Сидорока» и «Галину Сидорок»
(предположительно родственники, семейное совладение), но дословно
проверенный Интерфакс и Агроинвестор согласованно называют именно
«Николая Сидорка» — использую подтверждённую форму, семейные
подробности не переношу. Консультанты сделки и согласование ФАС — ни
в одном источнике не названы (сумма ~21 млрд ₽ обычно требует
согласования, но подтверждения самого факта одобрения не нашлось).
Earn-out/отложенные платежи — источники не упоминают.

Запуск: python3 pipeline/fix_rusagro_nmzhk_seller_and_restructuring.py
        python3 pipeline/fix_rusagro_nmzhk_seller_and_restructuring.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g91606f1b'

OLD_EXTRA = (
    'Консультационное освещение сделки. Русагро приобрела 50% акций и '
    'контроль над группой компаний НМЖК, владеющей масложировым '
    'комбинатом в Нижнем Новгороде, маслоэкстракционными предприятиями '
    'в Урюпинске и Сорочинске, а также элеваторами.'
)
NEW_EXTRA = (
    'Русагро приобрела 50% акций и контроль над группой компаний НМЖК, '
    'владеющей масложировым комбинатом в Нижнем Новгороде, '
    'маслоэкстракционными предприятиями в Урюпинске и Сорочинске, а '
    'также элеваторами. Продавцы — управляющие партнёры группы Николай '
    'Нестеров и Николай Сидорок; сингапурская Wilmar International '
    'осталась совладельцем оставшихся 50%, «Русагро» планировала '
    'развивать бренды НМЖК совместно с ней.'
)

OLD_ECO_CONTEXT = '—'
NEW_ECO_CONTEXT = (
    'С 5 августа 2024 года собственником АО «НМЖК» стало АО «Эталон» — '
    'структура, консолидирующая масложировые активы самой «Русагро» '
    '(это внутренняя реструктуризация холдинга, а не смена конечного '
    'контролирующего собственника); возглавил «Эталон» Анвар Анваров, '
    'сменив Тимура Липатова, гендиректора ГК «Русагро».'
)

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/business/909101'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6069244'],
    ['TAdviser', 'https://www.tadviser.ru/index.php/Компания:Нижегородский_масло-жировой_комбинат_(ГК_НМЖК)'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA
    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert 'seller' not in deal

    new_src = deal['src'] + NEW_SRC

    print('=== seller: станет ===')
    print('Николай Нестеров и Николай Сидорок')
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['seller'] = 'Николай Нестеров и Николай Сидорок'
        deal['seller_src'] = 'text'
        deal['extra'] = NEW_EXTRA
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
