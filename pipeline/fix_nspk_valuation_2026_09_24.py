# -*- coding: utf-8 -*-
"""Приток 24 сентября 2026 (21:20 МСК), gmru-nspk-privatization («Банк
России готовит частичную приватизацию НСПК»): свежая оценка компании.

Коммерсантъ (тем же вечером, после форума): ЦБ в октябре объявит
потенциальным участникам оценку НСПК; регулятор ищет партнёров по
развитию платёжной инфраструктуры, а не инвесторов, ориентированных на
прибыль. Эксперты оценивают компанию в 500–700 млрд ₽ (пятипроцентный
пакет — 25–35 млрд ₽), такую сумму могут позволить себе только крупнейшие
банки, маркетплейсы и телеком-компании. Отдельно — довод, почему продажа
для ЦБ неочевидна: цифровой рубль реализуется не под эгидой НСПК, поэтому
компания не нуждается остро в привлечении сотен миллиардов рублей.

Прямым скриптом — дописывание к уже стоящему eco.val не проходит
генерик-проверку review.check() (то же ограничение, что и у других
карточек в этой сессии).

Источник: https://www.kommersant.ru/doc/8974589, прочитан целиком, кэш в
data/inbox/raw/2026-09-24-articles.jsonl. Черновик d43846694 — тот же
предмет, отпущен через raw_screen.py --enrich.

Запуск: python3 pipeline/fix_nspk_valuation_2026_09_24.py --write
"""
import argparse
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gmru-nspk-privatization'
KOMMERSANT = ['Коммерсантъ', 'https://www.kommersant.ru/doc/8974589']

OLD_VAL = (
    'Исходя из отчётности ЦБ, за 2022–2025 годы НСПК выплатила регулятору '
    'более 80 млрд ₽ дивидендов, в том числе почти 47 млрд ₽ в 2025 году. '
    'Глава правления ассоциации «Финансовые инновации» Роман Прохоров '
    'считает НСПК понятным активом, приносящим доход, и ожидает неплохого '
    'спроса на него как со стороны кредитных организаций, так и со '
    'стороны других участников рынка. 24 сентября 2026 года на '
    'Международном банковском форуме Набиуллина сообщила: «Мы считаем, '
    'что НСПК должна остаться рентабельной, самоокупаемой и позволяющей '
    'осуществлять инвестиции в проекты развития, проекты, которые важны '
    'для всего бизнеса. Но мы приняли принципиальное решение, посмотрев '
    'на ситуацию, что будем поэтапно уменьшать тарифы для банков (...), '
    'и это будет учитываться в оценке стоимости НСПК», — добавила глава '
    'ЦБ. Вместе с тем, по её словам, если в будущем рентабельность не '
    'будет позволять осуществить какие-то проекты, то может быть принято '
    'решение о повышении тарифов.'
)
QUOTE_ADD = (
    'Банк России планирует в октябре объявить потенциальным участникам '
    'приватизации Национальной системы платежных карт (НСПК) оценку '
    'компании. Регулятор видит в них партнеров по развитию платежной '
    'инфраструктуры, а не инвесторов, ориентирующихся на прибыль. '
    'Эксперты оценивают НСПК в 500–700 млрд руб., то есть пятипроцентный '
    'пакет обойдется инвесторам в 25–35 млрд руб. Заплатить такую сумму '
    'за миноритарную долю могут позволить себе только крупнейшие банки, '
    'маркетплейсы и телеком-компании. Эксперты отмечает, что для Банка '
    'России продажа выглядит неочевидной. Масштабный проект по цифровому '
    'рублю реализуется не под эгидой НСПК, следовательно, в привлечении '
    'сотен миллиардов рублей компания остро не нуждается.'
)


def main(write):
    data = json.load(open(DATA, encoding='utf-8'))
    card = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert card['eco']['val'] == OLD_VAL
    card['eco']['val'] = OLD_VAL + ' ' + QUOTE_ADD

    if KOMMERSANT[1] not in {s[1] for s in card['src'] if len(s) > 1}:
        card['src'].append(KOMMERSANT)

    if write:
        json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
        print('Записано: eco.val дополнен новой оценкой, источник добавлен.')
    else:
        print('Сухой прогон (--write, чтобы записать).')


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('--write', action='store_true')
    main(p.parse_args().write)
