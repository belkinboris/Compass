import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g60f99ba6'

OLD_ECO_CONTEXT = (
    'О покупке 7,52% голосующих ценных бумаг одной из компаний «Транснефть» '
    'сообщила в отчётности по МСФО за первое полугодие 2026 года. Сделка '
    'обошлась в 40 млрд ₽, название организации не раскрывалось. В '
    'отчётности Газпромбанка по МСФО за то же полугодие указано, что Банк '
    'России зарегистрировал дополнительный выпуск 50,6 млн акций банка. '
    'Номинальная цена одной бумаги — 450 ₽. В августе Газпромбанк увеличил '
    'уставный капитал на 4%, до 623,9 млрд ₽, как следует из раскрытия '
    'информации. Это соответствует размещению примерно 7,5% акций.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' Аналитики предлагают разные версии, зачем '
    'нефтепроводной монополии доля в банке: главный аналитик «Тринфико '
    'Private» Максим Васильев видит в этом финансовую и институциональную '
    'синергию (общие инфраструктурные проекты, расчётно-банковское '
    'обслуживание), а независимый эксперт по энергетике Кирилл Родионов '
    'связывает сделку с фискальными интересами Минфина на фоне роста '
    'дефицита федерального бюджета — до 6,46 трлн ₽ за январь–июль 2026 '
    'года против 4,62 трлн ₽ годом ранее.'
)

OLD_SRC = [
    ['Ведомости', 'https://www.vedomosti.ru/investments/news/2026/08/28/1224606-transneft-priobrela'],
    ['ПРАЙМ', 'https://1prime.ru/20260731/transneft-871940498.html'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8921107'],
]
NEW_SRC = OLD_SRC + [
    ['Mergers.ru', 'https://mergers.ru/news/Transneft-stala-akcionerom-Gazprombanka-87453'],
    ['Investing.com (со ссылкой на РБК)', 'https://ru.investing.com/news/general-news/article-3370440'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
