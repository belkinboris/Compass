"""Месячная очередь качества, 11 сентября 2026 — карточка `cd51336b7`
(«Смена бенефициарного владельца УГМК: Камилов вытеснил Махмудова и
Бокарева», март 2022) несла факт только в `extra`; структурные поля
(`law.struct`, `eco.context`) были пусты вовсе.

Личный WebFetch подтвердил дословно:
- Интерфакс (https://www.interfax.ru/business/827997): «Искандар
  Махмудов и Андрей Бокарев перестали быть контролирующими
  бенефициарами ОАО «УГМК»» — событие датировано 14 марта 2022 года;
  затронуты также АО «УК «Кузбассразрезуголь»», АО «Восточный порт»,
  АО «Ростерминалуголь».
- Коммерсантъ (https://www.kommersant.ru/doc/6095036): «Владельцем 85%
  акций УГМК вместо кипрской Selmareco Limited стал российский
  «Бизнесглобус»» (данные годового отчёта УГМК за 2022 год); «АО
  «Компания "Бизнесглобус"» действует в интересах бывшего члена совета
  директоров УГМК Андрея Бокарева».
- Газета.уз (https://www.gazeta.uz/ru/2023/09/15/sanctions/): 14
  сентября 2023 года США ввели персональные санкции против Махмудова
  и Бокарева; Камилов в списке не упомянут.
- РБК (https://www.rbc.ru/business/28/07/2025/6887ab979a7947d646454fbb):
  Андрей Козицын покинул пост гендиректора УГМК из-за санкций ЕС в
  2022 году и вернулся на эту должность 3 июля 2025 года.

Запуск:
    python3 pipeline/fix_ugmk_kamilov_ownership_structure.py            # сухой прогон
    python3 pipeline/fix_ugmk_kamilov_ownership_structure.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

NEW_LAW_STRUCT = (
    '14 марта 2022 года Искандар Махмудов и Андрей Бокарев перестали '
    'быть контролирующими бенефициарами УГМК (а также «Кузбассразрезугля», '
    '«Восточного порта» и «Ростерминалугля»). По данным годового отчёта '
    'УГМК за 2022 год, владельцем 85% акций компании вместо кипрской '
    'Selmareco Limited стал российский «Бизнесглобус» — по данным '
    'Коммерсанта, эта структура действует в интересах бывшего члена '
    'совета директоров УГМК Андрея Бокарева, при этом бенефициарным '
    'владельцем в самом отчёте указан Данияр Камилов, сын бывшего '
    'министра иностранных дел Узбекистана.'
)

NEW_ECO_CONTEXT = (
    'В июне-июле 2023 года США ввели санкции против самой УГМК и её '
    'структур, а 14 сентября 2023 года — лично против Искандара '
    'Махмудова и Андрея Бокарева; Данияр Камилов в санкционные списки '
    'не попал. Из-за санкций Евросоюза Андрей Козицын в 2022 году '
    'покинул пост гендиректора УГМК и вернулся на эту должность только '
    '3 июля 2025 года.'
)

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/business/827997'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6095036'],
    ['Газета.уз', 'https://www.gazeta.uz/ru/2023/09/15/sanctions/'],
    ['РБК', 'https://www.rbc.ru/business/28/07/2025/6887ab979a7947d646454fbb'],
]


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['cd51336b7']

    assert d.get('law', {}).get('struct') in (None, '—'), 'law.struct уже занят: %r' % (d.get('law', {}).get('struct'),)
    assert d['eco'].get('context') in (None, '—'), 'eco.context уже занят: %r' % (d['eco'].get('context'),)
    urls = {s[1] for s in d['src']}
    for src in NEW_SRC:
        assert src[1] not in urls, 'источник уже добавлен: %s' % src[1]

    print('cd51336b7: law.struct и eco.context заполнены (структура '
          'владения через «Бизнесглобус», санкции, смена гендиректора); '
          'добавлено 4 источника')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d.setdefault('law', {})['struct'] = NEW_LAW_STRUCT
    d['eco']['context'] = NEW_ECO_CONTEXT
    d['src'].extend(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
