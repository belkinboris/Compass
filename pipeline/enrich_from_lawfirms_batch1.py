# -*- coding: utf-8 -*-
"""Партия 1 разбора @LawFirms: три карточки, которым пост даёт консультанта.

ЗАЧЕМ. Замечание владельца: «дубль» — не повод пропустить пост. Из первых
15 объявлений канала 5 сделок уже были в базе с полными консультантами, но у
трёх карточек юридический консультант не назван вовсе, хотя фирма объявила о
сопровождении публично. Читатель, который видит на карточке пустое поле
«Консультанты», а в канале — имя фирмы, делает единственный возможный вывод о
качестве базы.

ЧТО ИМЕННО ЗАПИСЫВАЕТСЯ. Только имя фирмы, её роль и ссылка на объявление.
Пересказ поста в поля сделки не идёт: сумма, стороны и структура у этих трёх
карточек либо уже заполнены, либо в посте отсутствуют.

ЧТО НАМЕРЕННО НЕ ЗАПИСЫВАЕТСЯ. У «Ленты» и «О'КЕЙ» в посте стоит «142 млрд
рублей» — это ВЫРУЧКА «О'КЕЙ» за 2025 год, а не цена сделки. Разбор
предлагал её как «сумму»; ровно этот класс ошибки уже записан в CLAUDE.md
(«ВТБ продал Holiday Inn»), поэтому сумма не трогается.

ОТДЕЛЬНЫЙ СЛУЧАЙ — ЗАГЛУШКА. У карточки «Земун»/«РБФ ритейл» в поле
консультантов стояло «Стороны сделки — Не раскрывались: юридические
консультанты в публичных источниках не раскрывались». Объявление NEXTONS
доказывает обратное, поэтому строка не дополняется, а ЗАМЕНЯЕТСЯ: оставить
её рядом с именем фирмы значило бы напечатать на одной карточке утверждение
и его опровержение.

Запуск:
    python3 pipeline/enrich_from_lawfirms_batch1.py            # сухой прогон
    python3 pipeline/enrich_from_lawfirms_batch1.py --write    # записать
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

SRC_LABEL = 'РУЛЬФЫ, ИЛЬФЫ И ИНХАУСЫ (@LawFirms)'

# id карточки, роль, фирма, пояснение, адрес объявления, заменяемая заглушка,
# ожидаемые роли в поле «Консультанты» ДО правки. Последнее — проверка
# исходного состояния: если у карточки уже другой набор ролей, значит база
# изменилась с момента чтения и решение надо принимать заново, а не дописывать
# вслепую. У Ситибанка набор не пуст: Orion ведёт покупателя, продавец честно
# помечен нераскрытым, а Nextons — третья, отдельная роль (акционер покупателя).
# Пояснение — пересказ роли, а не факта сделки: всё проверяемое лежит по ссылке.
PLAN = [
    ('gmru-nordgold-chukotka',
     'Юридический консультант покупателя (Nordgold)',
     'White Square',
     'Сопровождение приобретения компании, владеющей лицензией на Чукотке. '
     'Источник: https://t.me/LawFirms/11173',
     'https://t.me/LawFirms/11173',
     None,
     []),
    ('g74fd5cdb',
     'Юридический консультант покупателя («Лента»)',
     'NEXTONS',
     'Представление интересов «Ленты» в сделке по приобретению 100% доли '
     'в ООО «РБФ-Ритейл» — операторе сети гипермаркетов «О’КЕЙ». Команду '
     'возглавлял партнёр Сергей Гюрджиан. Источник: https://t.me/LawFirms/11001',
     'https://t.me/LawFirms/11001',
     'Стороны сделки',
     ['Стороны сделки']),
    ('citibank',
     'Юридический консультант акционера покупателя («Ренессанс Капитал»)',
     'Nextons',
     'Консультирование одного из акционеров инвестиционной компании '
     '«Ренессанс Капитал» в сделке по приобретению акций Ситибанка. '
     'Источник: https://t.me/LawFirms/10545',
     'https://t.me/LawFirms/10545',
     None,
     ['Покупатель — «Ренессанс Капитал»', 'Продавец — Citigroup']),
]


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}

    for did, role, firm, note, url, drop, before in PLAN:
        deal = by_id.get(did)
        assert deal is not None, 'карточки %s нет в базе' % did
        adv = (deal.get('law') or {}).get('adv') or []
        names = ' | '.join(str(a[1]) for a in adv if len(a) > 1).lower()
        assert firm.lower() not in names, \
            '%s: %s уже записан — перепроверьте, не двойной ли это прогон' % (did, firm)
        assert [str(a[0]) for a in adv if a] == before, \
            '%s: роли в «Консультантах» другие (%r), чем при чтении (%r)' % (
                did, [str(a[0]) for a in adv if a], before)
        if drop:
            assert drop in before, '%s: заглушки «%s» нет — состояние карточки другое' % (did, drop)
        assert url not in {str(s[1]) for s in (deal.get('src') or []) if len(s) > 1}, \
            '%s: объявление уже стоит в источниках' % did

        print('%s  %s' % (did, (deal.get('title') or '')[:60]))
        if drop:
            print('    убрать заглушку: %s' % drop)
        print('    + %s — %s' % (role, firm))
        print('    + источник: %s' % url)

    print('\nкарточек к правке: %d' % len(PLAN))
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return 0

    for did, role, firm, note, url, drop, before in PLAN:
        deal = by_id[did]
        law = deal.setdefault('law', {})
        adv = [a for a in (law.get('adv') or []) if not (drop and str(a[0]) == drop)]
        adv.append([role, firm, note])
        law['adv'] = adv
        deal.setdefault('src', []).append([SRC_LABEL, url])
    json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('ЗАПИСАНО в %s' % os.path.relpath(DATA, ROOT))
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
