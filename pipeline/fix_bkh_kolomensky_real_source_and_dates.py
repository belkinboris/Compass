import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g927f3242'

OLD_SRC = [['@dealsma (Telegram)', 'https://t.me/dealsma/5799']]
NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/7460660'],
    ['Известия', 'https://iz.ru/1328299/2022-04-29/khlebokombinat-kolomenskii-kupil-rossiiskii-biznes-finskoi-fazer'],
    ['Ведомости', 'https://www.vedomosti.ru/business/news/2022/09/12/940476-fas-razreshila-kupit-pekarya'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6222071'],
]

OLD_CONTEXT = (
    'Показатели 2024:\nВыручка – 60 млрд руб. (+35% г./г.) \nОбъем '
    'продукции = 485 тыс. тонн (+13%)\nБенефициар — один из основателей '
    '«Росбилдинга», владелец девелоперской компании Sminex Алексей '
    'Тулупов.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' Даты сделок: Fazer — 29 апреля 2022 (4 фабрики, более 2 тыс. '
    'сотрудников, Известия); «Волжский пекарь» — одобрение ФАС '
    '12 сентября 2022 (Ведомости); «Дарница» — закрыта 15 сентября 2023 '
    '(Коммерсантъ, собственная страница холдинга называет октябрь 2023 '
    '— расхождение); «Пролетарец» — май 2024 по интервью (собственная '
    'страница холдинга называет июнь 2024 — расхождение). План '
    'реконструкции «Пролетарца» по данным холдинга: запуск первых линий '
    '— август 2025, полное завершение — осень 2026, мощность ~150 '
    'т/сутки.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['src'] == OLD_SRC
    assert deal['eco']['context'] == OLD_CONTEXT

    print('=== src: станет ===')
    for s in NEW_SRC:
        print(s)
    print('\n=== eco.context: станет ===')
    print(NEW_CONTEXT)

    if write:
        deal['src'] = NEW_SRC
        deal['eco']['context'] = NEW_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
