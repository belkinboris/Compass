"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
`g68a112bd` («Русатом Хэлскеа увеличил долю в Медскане до 50%», июль
2023, Закрыта) — судьба доли после сделки не прослеживалась.

Эта карточка — про историческое увеличение доли РОСАТОМА до 50% в
2023 году. Не путать с уже записанным в CLAUDE.md открытым вопросом
(карточка `g2197ed53`, «Газпромбанк может стать акционером «Медскана»)
— там неразрешённый вопрос «кто именно новый инвестор» остаётся
открытым для человека; здесь добавляется другой, подтверждённый факт:
доля Росатома с тех пор УЖЕ размылась.

Проверено ЛИЧНО прямым WebFetch (дословные цитаты):
- vedomosti.ru/business/articles/2026/06/03/1202334-u-medskana-poyavilsya-novii-investor:
  «снизила долю участия с 50 до 45%» — про Росатом; «по-прежнему
  контролирует «Медскан»» — несмотря на размытие; медгруппа «провела
  допэмиссию привилегированных акций типа А, которые приобрел один из
  финансовых инвесторов»; «по информации источника издания» им стал
  Газпромбанк (представитель компании имя не назвал — та же
  неопределённость, что уже стоит открытым вопросом у `g2197ed53`, не
  повторяется здесь ещё раз); компания «планирует IPO в сентябре 2026 г.»

НЕ ВНЕСЕНО: (1) имя нового инвестора (Газпромбанк) — источник сам
называет это неподтверждённым, вопрос уже зафиксирован отдельно в
`g2197ed53`, дублировать не стал; (2) финансовые показатели 2025 года
(выручка, убыток по МСФО) и переименование в «Росатом Технологии
здоровья» — встретились только в агрегированной выдаче поиска (zdrav.
expert), не в дословно прочитанной странице, не переносится без прямой
проверки.

Запуск: python3 pipeline/fix_rusatom_medskan_diluted_to_45.py
        python3 pipeline/fix_rusatom_medskan_diluted_to_45.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g68a112bd'

OLD_ECO_CONTEXT = (
    'Соглашение о передаче дополнительной доли подписали директор '
    '«Рустатом Хэлскеа» Игорь Обрубов и основатель АО «Медскан» Евгений '
    'Туголуков.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' Доля с тех пор размылась: к июню 2026 года '
    'Росатом снизил участие с 50 до 45% из-за новой допэмиссии '
    'привилегированных акций в пользу стороннего финансового инвестора '
    '(имя официально не раскрыто), но, по словам представителя '
    'компании, «по-прежнему контролирует «Медскан»»; IPO компании '
    'запланировано на сентябрь 2026 года.'
)

OLD_SRC = [
    ['АК&М', 'https://www.akm.ru/news/rusatom_khelskea_uvelichil_dolyu_v_medskane_do_50/'],
]
NEW_SRC = OLD_SRC + [
    ['Ведомости', 'https://www.vedomosti.ru/business/articles/2026/06/03/1202334-u-medskana-poyavilsya-novii-investor'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
