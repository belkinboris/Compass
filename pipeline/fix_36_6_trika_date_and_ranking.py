# -*- coding: utf-8 -*-
"""Карточка g91281c36 (аптечная группа «36,6» / «Трика»), ни разу не
прошедшая проверку чтением: `date` стоял "unknown", хотя оба ключевых
источника опубликованы в один день — 9 июля 2026 года (Vademecum,
17:05, ещё в настоящем времени «завершает сделку»; Коммерсантъ, 21:49,
уже в прошедшем — «выкупила»). Расхождение — обычная разница между
утренней инсайдерской публикацией и вечерним подтверждением, а не
спор о дате: используем дату публикации статьи о ЗАКРЫТИИ (Ъ).

Заодно дописывается `extra` двумя фактами о положении сторон в
квартальном рейтинге DSM Group (Коммерсантъ), которых в карточке не
было: не через review.py, а отдельным скриптом, потому что `extra` уже
не пуст, а общая проверка дословности требует, чтобы ВЕСЬ текст поля
(старый + новый) лежал в ОДНОЙ цитате.
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g91281c36'
OLD_DATE = 'unknown'
NEW_DATE = '2026-07-09'

OLD_EXTRA = (
    'В периметр сделки вошли 45 аптек (30 — в Москве и Московской области, '
    '14 — в Ярославле, 1 — в Орле) и четыре юрлица: ООО «Трика», ООО '
    '«Вега», ООО «Фармтун-6» и ООО «Фармацевтическая гильдия». По данным '
    'Vademecum, на подготовку и согласование сделки ушло более полугода, '
    'переговоры подтверждены участниками рынка. Выручка «Трика» по итогам '
    '2025 года составила 1,8 млрд руб. по оценке Ивана Пешкова '
    '(Коммерсантъ) или 2,1 млрд руб. по расчётам Аналитического центра '
    'Vademecum; сеть занимала 70-е место в рейтинге ТОП200 аптечных сетей '
    'России за 2025 год. После закрытия сделки аптеки «Трика» планируется '
    'ребрендировать под марки «36,6» или «Горздрав»; Орловская область '
    'стала новым регионом присутствия для группы.'
)
ADDITION = (
    'В рейтинге DSM Group по итогам первого квартала 2026 года «Трика» '
    'занимала 45-е место с оборотом в 0,8 млрд руб., а сама группа «36,6» '
    '— пятое место по обороту (31,3 млрд руб., +7% год к году, 5% продаж '
    'в коммерческом сегменте).'
)
NEW_EXTRA = OLD_EXTRA + ' ' + ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['date'] == OLD_DATE, f"date: неожиданное значение {deal['date']!r}"
    assert deal['extra'] == OLD_EXTRA, f"extra: неожиданное значение {deal['extra']!r}"

    print(f"{CARD_ID} date: {OLD_DATE!r} -> {NEW_DATE!r} (дата публикации "
          "статьи Ъ о закрытии сделки)")
    print(f"{CARD_ID} extra: += квартальные позиции «Трика» и «36,6» в "
          "рейтинге DSM Group")
    deal['date'] = NEW_DATE
    deal['extra'] = NEW_EXTRA

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
