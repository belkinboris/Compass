# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
`ca7a871ee` («Ростелеком запускает венчурный фонд «Консоль» объёмом
8 млрд руб.») — на дату запуска (июнь 2024) в карточке не было ни
одной портфельной сделки фонда; проверено ЛИЧНО прямым WebFetch, что
она появилась.

Проверено: comnews.ru/content/242333/2025-11-14/... — «5% долей в
капитале ООО «Базальт СПО» перешли в собственность фонда «Консоль»
1 ноября 2025 г.»; interfax.ru/business/1060758 — доля наращена «до
25% с 14,5%», изменения зарегистрированы в ЕГРЮЛ 27 ноября 2025 года.
Добавлено в `eco.context` как ПЕРВАЯ известная портфельная сделка
фонда — не переносится в `target`/`buyer` самой карточки, потому что
эта карточка описывает ЗАПУСК фонда (июнь 2024), а не конкретную
инвестицию (ноябрь 2025) — разные события, смешивать роли нельзя (тот
же принцип, что уже применён к общим объявлениям вроде «ВЭБ.РФ
выделяет ₽25 млрд на инвестиции»).

НЕ ВНЕСЕНО: утверждение comnews.ru «за пять лет существования
«Консоль» не совершила ни одной сделки» — противоречит собственному
источнику карточки (kommersant.ru/doc/6762424, июнь 2024: «Ростелеком»
ЗАПУСКАЕТ НОВЫЙ фонд «Консоль», отдельный от существующего с 2013 года
«КоммИТ Кэпитал»), проверено личным WebFetch обоих источников —
расхождение не разрешено, факт не вносится, пока не найдётся третий
источник, объясняющий его.

Запуск: python3 pipeline/fix_monthly_2026_09_07_konsol_fund_investment.py
        python3 pipeline/fix_monthly_2026_09_07_konsol_fund_investment.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

KS_ID = 'ca7a871ee'
KS_OLD_CONTEXT = (
    'Ростелеком в 2024 году запустит венчурный фонд «Консоль» объемом '
    '8 млрд руб. для инвестирования в компании, разрабатывающие '
    'платформенное и системное ПО, облачные решения, платформы ИИ и ПО '
    'для интернета вещей. Предусмотрено привлечение соинвесторов из '
    'крупного бизнеса. Планируемый размер инвестиционного чека '
    'составит 300–500 млн руб.'
)
KS_NEW_CONTEXT = (
    KS_OLD_CONTEXT + ' Первая известная портфельная сделка фонда —'
    ' 1 ноября 2025 года «Консоль» получил 5% долей разработчика ОС'
    ' Alt Linux, ООО «Базальт СПО»; к 27 ноября 2025 года долю нарастили'
    ' до 25% (с промежуточных 14,5%).'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}
    ks = by_id[KS_ID]

    assert ks['eco']['context'] == KS_OLD_CONTEXT

    print('=== ca7a871ee: eco.context ===')
    print(KS_NEW_CONTEXT)

    if write:
        ks['eco']['context'] = KS_NEW_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
