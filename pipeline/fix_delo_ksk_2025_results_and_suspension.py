# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g656645d5 (ГК «Дело» приобрела 25% плюс одну акцию «КСК» у Cargill) —
судьба терминала под 100%-контролем «Дела» после сделки не была
отражена. Проверено лично прямым WebFetch двух источников.

`eco.target_fin` (дополнено). Дословно (oleoscope.com): чистая
прибыль КСК за 2025 год по РСБУ — «10,66 млрд рублей, что на 29%
меньше, чем в 2024 году»; выручка — «12,37 млрд рублей» со снижением
«на 33,5%» (от стивидорной деятельности — «на 32%, до 12,34 млрд
рублей»). Причина падения — неурожай зерновых 2024 года.

`eco.context` (дополнено). 13 августа 2026 года ГК «Дело» приостановила
операционную деятельность терминала. Дословно (Expert.ru): «Группа
компаний "Дело" сообщила о приостановке операционной деятельности
зернового терминала КСК в Новороссийске» — решение принято «в целях
обеспечения безопасности работников и сохранности инфраструктуры» в
связи с атакой БПЛА на Новороссийск в ночь на 12 августа 2026 года.
О возобновлении работы отдельных сообщений не было на момент
обыска.

НЕ ВКЛЮЧЕНО: возможная продажа самого терминала КСК холдингу
«Деметра-Холдинг» (для финансирования выкупа доли Шишкарева у
«Росатома») — сам потенциальный покупатель эти сведения опроверг
(«Заявляем, что данные сведения не соответствуют действительности»,
mergers.ru, 25 июня 2026); неподтверждённый слух не переносится.
Судьба доли самого Сергея Шишкарева в ГК «Дело» (переход к
«Росатому») — это отдельный сюжет другой карточки (`g6a4b0a2a`,
известная проблема в CLAUDE.md), не факт об ЭТОЙ сделке 2024 года.
Сумма сделки 2024 года и финансовый консультант — по-прежнему не
найдены ни в одном источнике.

Запуск: python3 pipeline/fix_delo_ksk_2025_results_and_suspension.py
        python3 pipeline/fix_delo_ksk_2025_results_and_suspension.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g656645d5'

OLD_TARGET_FIN = (
    'зерновой терминал КСК в 2023 году отгрузил на экспорт 8,2 млн '
    'тонн зерна, что на 37% превысило показатель за предыдущий год.'
)
NEW_TARGET_FIN = OLD_TARGET_FIN + (
    ' По итогам 2025 года выручка терминала снизилась на 33,5%, до '
    '12,37 млрд руб., чистая прибыль по РСБУ — на 29%, до 10,66 млрд '
    'руб. (причина — неурожай зерновых 2024 года).'
)

OLD_CONTEXT = (
    'Дело» в 2013 году продала блокпакет в КСК Cargill — одному из '
    'основных клиентов терминала, на которого приходилось примерно '
    '20% его грузооборота. После начала боевых действий на Украине '
    'мировые зерновые трейдеры постепенно начали сворачивать бизнес в '
    'России, а в текущем сельхозсезоне они полностью прекратили '
    'экспорт зерна из страны.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' 13 августа 2026 года «Дело» приостановила операционную '
    'деятельность терминала — решение принято в целях безопасности '
    'после атаки БПЛА на Новороссийск в ночь на 12 августа (Expert.ru).'
)

NEW_SRC = [
    ['oleoscope.com', 'https://oleoscope.com/news/zernovoj-terminal-gk-delo-v-novorossijske'],
    ['Expert.ru', 'https://expert.ru/news/gk-delo-priostanovila-rabotu-zernovogo-terminala-v-novorossiyske'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['target_fin'] == OLD_TARGET_FIN
    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.target_fin: станет ===')
    print(NEW_TARGET_FIN)
    print('\n=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['target_fin'] = NEW_TARGET_FIN
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
