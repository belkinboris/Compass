# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g66bb0d00
(«Банк «Открытие» продал нефтедобывающую компанию «Харьяга»») — карточка
несла `status: "Закрыта"` и `sum: "190 млн ₽"`, хотя единственный
источник (АК&М, опубликован 25 мая 2023) описывает лишь ОБЪЯВЛЕНИЕ о
предстоящих торгах: «Торги состоятся 5 июля 2023 года», «Стартовая
стоимость лота – 190 млн руб.» — ни исхода торгов, ни победителя, ни
итоговой цены источник не называет. Это похоже на ошибку разбора при
исходном автоимпорте: стартовую цену планируемого аукциона приняли за
цену закрытой сделки, а дату аукциона — за дату закрытия.

Проверено лично прямым WebFetch (АК&М, тот же адрес, что уже стоит в
`src`): «Это информационное сообщение о начале процесса продажи, а не
отчет о его завершении» — торги ЗАПЛАНИРОВАНЫ, не проведены на момент
публикации; результата в статье нет вовсе.

Проверено лично прямым WebFetch (АК&М, https://www.akm.ru/news/bank_otkrytie_prodaet_100_dolyu_v_ustavnom_kapitale_ooo_kharyaga/,
опубликовано 24.01.2024): тот же актив (100% ООО «Харьяга» с
обязательствами перед банком) ВНОВЬ выставлен на торги — аукцион
22 февраля 2024 года, стартовая цена уже 80 млн ₽ (меньше половины
исходных 190 млн ₽).

Проверено лично прямым WebFetch (Volga.news, https://volga.news/article/679095.html,
опубликовано 13.09.2023): тот же актив выставлен на торги ЕЩЁ РАЗ,
аукцион 18 октября 2023 года — то есть между «закрытием» 5 июля 2023 и
торгами 22 февраля 2024 года стоит как минимум ОДНО промежуточное
объявление о продаже того же лота.

Проверено лично прямым WebFetch (Saby/СБИС, https://saby.ru/contragents/7715233983/770301001):
на 2 сентября 2026 года ООО «Харьяга» (ИНН 7715233983) — «в процессе
банкротства», конкурсный управляющий Волохов Роман Николаевич назначен
23 марта 2026 года; сведения об учредителях скрыты с 31 марта 2026 года.

Совокупность фактов (объявление о планируемых торгах вместо отчёта об
исходе; минимум два ПОВТОРНЫХ выставления того же актива на продажу в
последующие 7 месяцев по всё более низкой цене; банкротство самой
компании три года спустя) не доказывает механически «сделка не
состоялась» в смысле явной цитаты источника (`STATUS_WORDS` под это не
попадает), но делает утверждение «Закрыта, 190 млн ₽» недостоверным:
успешно закрытый актив не выставляют на продажу повторно. Статус
меняется на «Обсуждается» (процесс продажи документированно
продолжался и после заявленной даты закрытия), сумма — на «Не
раскрыта» (190 млн ₽ была стартовой ценой несостоявшегося аукциона, а
не уплаченной суммой).

НЕ ВКЛЮЧЕНО: точная причина, почему торги 5 июля 2023 года не привели к
продаже (отсутствие заявок, отказ покупателя от расчётов) — источники
об этом не сообщают ни разу. Личность конечного покупателя (если он
всё же появился между февралём 2024 года и банкротством 2026 года) —
не установлена, сведения об учредителях скрыты с марта 2026 года.

Запуск: python3 pipeline/fix_kharyaga_auction_never_closed.py
        python3 pipeline/fix_kharyaga_auction_never_closed.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g66bb0d00'

OLD_STATUS = 'Закрыта'
NEW_STATUS = 'Обсуждается'

OLD_SUM = '190 млн ₽'
NEW_SUM = 'Не раскрыта'

OLD_ECO_SUM = '190 млн ₽'
NEW_ECO_SUM = 'Не раскрыта'

OLD_ECO_CONTEXT = '—'
NEW_ECO_CONTEXT = (
    'Единственный источник (АК&М, 25 мая 2023) описывает лишь объявление '
    'о предстоящих торгах со стартовой ценой 190 млн ₽ — исход торгов '
    '5 июля 2023 года он не называет. Тот же актив выставлялся на '
    'продажу ещё как минимум дважды: аукцион 18 октября 2023 года '
    '(Volga.news) и аукцион 22 февраля 2024 года со стартовой ценой уже '
    '80 млн ₽ (АК&М) — повторные выставления того же лота говорят о том, '
    'что более ранние торги, включая июльские, покупателя не нашли. К '
    '2026 году сама компания «Харьяга» находится в процедуре '
    'банкротства (конкурсный управляющий назначен 23 марта 2026 года), '
    'сведения об учредителях скрыты с 31 марта 2026 года.'
)

OLD_EXTRA = (
    'Сделка размещена на торговой площадке РОСЭЛТОРГ. Банк «Открытие» '
    'продаёт 100%-ную долю в ООО «Харьяга» и обязательства перед банком. '
    'Организатор торгов — РОСЭЛТОРГ, аукцион проводится на сайте АО '
    '«Единая электронная торговая площадка». Прием заявок — до 23 июня '
    '2023 года, торги состоялись 5 июля 2023 года.'
)
NEW_EXTRA = (
    'Банк «Открытие» выставил на продажу 100%-ную долю в ООО «Харьяга» и '
    'обязательства перед банком через торговую площадку РОСЭЛТОРГ (АО '
    '«Единая электронная торговая площадка»); приём заявок на первый '
    'аукцион — до 23 июня 2023 года, сами торги были назначены на '
    '5 июля 2023 года. Источник не подтверждает исход торгов; дальнейшая '
    'судьба сделки — на вкладке «Экономист».'
)

NEW_SRC = [
    ['АК&М', 'https://www.akm.ru/news/bank_otkrytie_prodaet_100_dolyu_v_ustavnom_kapitale_ooo_kharyaga/'],
    ['Volga.news', 'https://volga.news/article/679095.html'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS
    assert deal['sum'] == OLD_SUM
    assert deal['eco']['sum'] == OLD_ECO_SUM
    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== status: станет ===')
    print(NEW_STATUS)
    print('\n=== sum: станет ===')
    print(NEW_SUM)
    print('\n=== eco.sum: станет ===')
    print(NEW_ECO_SUM)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['status'] = NEW_STATUS
        deal['sum'] = NEW_SUM
        deal['eco']['sum'] = NEW_ECO_SUM
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
