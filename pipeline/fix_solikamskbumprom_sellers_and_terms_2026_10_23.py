def apply(data):
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)
    assert deal['eco']['context'] == OLD_CONTEXT, deal['eco']['context']
    assert deal['law']['struct'] == OLD_STRUCT, deal['law']['struct']
    assert deal['eco']['val'] == OLD_VAL, deal['eco']['val']
    assert deal.get('extra') is None, deal.get('extra')
    deal['eco']['context'] = NEW_CONTEXT
    deal['law']['struct'] = NEW_STRUCT
    deal['eco']['val'] = NEW_VAL
    deal['extra'] = NEW_EXTRA
    return deal


def main(write):
    data = json.load(open(DATA, encoding='utf-8'))
    apply(data)
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return 0
    data = json.load(open(DATA, encoding='utf-8'))
    apply(data)
    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')
    return 0


if __name__ == '__main__':
    sys.exit(main('--write' in sys.argv))
