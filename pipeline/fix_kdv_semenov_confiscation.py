import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gcb309b35'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Закрыта'

OLD_EXTRA = (
    'Уведомление о намерении миноритарного акционера Игоря Семёнова '
    'продать свою долю в АО «Кондитерус Ком». Росимущество и иные '
    'миноритарии имеют преимущественное право покупки в течение двух '
    'месяцев. Арестов и залогов на акции нет.'
)
EXTRA_ADDITION = (
    'Продажа не состоялась: 1 октября 2025 года Тверской суд Москвы '
    'признал основателей холдинга Дениса и Николая Штенгеловых '
    '«экстремистским объединением» и арестовал 100% акций группы. '
    'Несмотря на это, 27 октября Семёнов уведомил о намерении продать '
    'свои 18,07% за 7,4 млрд руб. — Генпрокуратура расценила это как '
    'попытку обойти обеспечительные меры и 14 января 2026 года добилась '
    'в суде запрета его деятельности в России и обращения акций в доход '
    'государства; 29 апреля 2026 года Мосгорсуд оставил решение в силе. '
    'С 22 января 2026 года холдинг под управлением структуры '
    'Россельхозбанка «РСХБ-Финанс».'
)
NEW_EXTRA = OLD_EXTRA + ' ' + EXTRA_ADDITION

OLD_ECO_CONTEXT = '—'
NEW_ECO_CONTEXT = (
    'Капитализация холдинга KDV оценивается в 497 млрд руб., годовая '
    'прибыль — 139 млрд руб. Конфискация пакета Семёнова — часть более '
    'широкого дела: в августе 2025 года Генпрокуратура подала иск к '
    'самим Штенгеловым и их родственникам, а в октябре 2025 года суд '
    'арестовал акции и имущество всей группы компаний.'
)


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['status'] == OLD_STATUS, \
        f"status: неожиданное значение {deal['status']!r}"
    assert deal['extra'] == OLD_EXTRA, \
        f"extra: неожиданное значение {deal['extra']!r}"
    assert deal['eco']['context'] == OLD_ECO_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} status: '{OLD_STATUS}' -> '{NEW_STATUS}' "
          "(исход решён судом, не продажей)")
    print(f"{CARD_ID} extra: += реальный исход (конфискация, не продажа)")
    print(f"{CARD_ID} eco.context: += масштаб холдинга и связь с делом "
          "Штенгеловых")
    deal['status'] = NEW_STATUS
    deal['extra'] = NEW_EXTRA
    deal['eco']['context'] = NEW_ECO_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
