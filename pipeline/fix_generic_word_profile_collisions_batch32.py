# -*- coding: utf-8 -*-
"""Триадa коллизий из систематического промера (продолжение прошлого
прогона): три сделки записаны на профиль, с которым связаны только
ОБЩИМ СЛОВОМ — тот же класс, что «Парус», «Глобус», «Северный», но
найдено не чтением карточек по одной, а прогоном
`pipeline/measure_profile_name_vs_deal_titles.py` по оставшимся 31
кандидату со слабым сигналом.

1. `g685f9470` «IPO МТС Банка на Московской бирже» несла
   `target: g4cd83394` — профиль «IPO Fix Price» (сеть магазинов
   фиксированных цен, СОВСЕМ другая компания и другое IPO). Верный
   профиль «МТС Банк» уже есть в базе (`g37d577dc`, с описанием) —
   `target` просто перенаправлен, новый профиль не нужен (родня случая
   «Парус»/Ярцевский завод).

2. `g0f7d3941` «ГК «Галс Девелопмент» продала 2,7 га... компании
   Zielinski & Rozen» несла `target: gc4b2178f` — профиль «ГК «Эксперт»»
   (сеть медицинских клиник). Текст сделки прямо называет предмет:
   продажа 100% долей ООО «Эксперт недвижимость» (владелец участка на
   Старообрядческой улице) — юрлицо совпадает с профилем ТОЛЬКО словом
   «Эксперт», к клиникам отношения не имеет. Заведён новый профиль для
   этого юрлица, `target` перенаправлен.

3. `g94c9a39d` «Правительство Москвы купило бизнес-центр «Верейская
   плаза»» несла `buyer: g673a17f8` — профиль «СГ «Развитие»»
   (строительная группа, кирпичный завод «Меакир»). Текст сделки прямо
   называет покупателя: ГБУ «Развитие активов» (структура департамента
   городского имущества Москвы для управления городской недвижимостью)
   — совсем другая организация, общее только слово «Развитие». Заведён
   новый профиль, `buyer` перенаправлен.

Во всех трёх случаях id и id/имя новых профилей проверены на отсутствие
коллизии; профили-источники (`g4cd83394`, `gc4b2178f`, `g673a17f8`) не
трогаются — они остаются верными для своих ОСТАЛЬНЫХ сделок.

Запуск:
    python3 pipeline/fix_generic_word_profile_collisions_batch32.py            # сухой прогон
    python3 pipeline/fix_generic_word_profile_collisions_batch32.py --write    # записать
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

NEW_COMPANIES = {
    'g18eb978f': {
        'name': 'ООО «Эксперт недвижимость»',
        'ind': 'Недвижимость',
        'desc': 'Владелец участка 2,7 га на Старообрядческой улице в '
                'Москве (перешёл от группы ВТБ при реструктуризации '
                'долгов «Мосметростроя»); в 2023 году продан Zielinski '
                '& Rozen.',
        'kpi': ['Профиль', 'Автоматический'],
    },
    'gc1ff5c80': {
        'name': 'Компания «Развитие активов» (город Москва)',
        'ind': 'Недвижимость',
        'desc': 'Структура департамента городского имущества Москвы для '
                'управления городской недвижимостью; в 2023 году '
                'выкупила бизнес-центр «Верейская плаза».',
        'kpi': ['Профиль', 'Автоматический'],
    },
}

# сделка -> (поле, старое значение, новое значение)
ROLE_FIXES = {
    'g685f9470': ('target', 'g4cd83394', 'g37d577dc'),
    'g0f7d3941': ('target', 'gc4b2178f', 'g18eb978f'),
    'g94c9a39d': ('buyer', 'g673a17f8', 'gc1ff5c80'),
}


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    comps = data['companies']
    deals_by_id = {d['id']: d for d in data['deals']}

    for new_id, new_c in NEW_COMPANIES.items():
        assert new_id not in comps, 'id %s уже занят' % new_id
        for c in comps.values():
            assert c.get('name') != new_c['name'], 'имя %r уже занято' % new_c['name']
        print('  НОВЫЙ ПРОФИЛЬ %-12s %s' % (new_id, new_c['name']))

    assert comps['g37d577dc']['name'] == 'МТС Банк', 'профиль МТС Банк изменился'

    for cid, (field, old_val, new_val) in ROLE_FIXES.items():
        d = deals_by_id.get(cid)
        assert d, 'сделки %s нет в базе' % cid
        assert d.get(field) == old_val, ('%s.%s уже другой: %r (ожидали %r)'
                                          % (cid, field, d.get(field), old_val))
        print('  ПЕРЕНАПРАВЛЕНИЕ %s.%s: %s -> %s' % (cid, field, old_val, new_val))
        if write:
            d[field] = new_val

    if write:
        for new_id, new_c in NEW_COMPANIES.items():
            comps[new_id] = new_c

    if not write:
        print('\nСухой прогон. Запись — с ключом --write.')
        return 0

    json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('\nЗаписано.')
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
