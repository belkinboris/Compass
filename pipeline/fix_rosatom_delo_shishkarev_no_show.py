# -*- coding: utf-8 -*-
"""Росатом/«Дело»/Шишкарев (`g5eb6ff22`): 28 августа 2026 года, в саму
объявленную дату юридического завершения, «Росатом» заявил, что Сергей
Шишкарев не пришёл на сделку по выкупу его доли — прямое продолжение его
же процедурного возражения от 26 августа (уже отражённого в eco.context).

Источник — РБК (rbc.ru/business/28/08/2026/6a919b1c9a7947d0e1d8c83a),
полный текст статьи НЕДОСТУПЕН (401 Unauthorized и на прямой запрос, и на
WebFetch); цитата — дословная аннотация статьи из RSS-ленты РБК, которая и
есть единственный текст, реально попавший в приток по этому адресу.
Отдельный поиск (WebSearch по нескольким деловым изданиям — Коммерсантъ,
Ведомости, Интерфакс, ТАСС, РИА, korabel.ru, logirus.ru, tks.ru,
portnews.ru) не нашёл независимого подтверждения именно этого факта:
все альтернативные источники, найденные тем же поиском, датированы 25-27
августа и описывают только ПРЕДЫДУЩИЙ шаг истории (предупреждение
Шишкарева), а не событие самого 28 августа — статья РБК, судя по всему,
первой сообщила о развитии сюжета в эту дату, и `--mark-deep` НЕ ставится
по этой карточке в рамках этой правки (второй источник не найден и не
прочитан, честный итог попытки).

Статус карточки НЕ меняется: сам факт неявки не эквивалентен ни
подтверждению закрытия, ни его срыву — «Росатом» мог провести акцепт
оферты и без физического присутствия Шишкарева (сделка типа «русская
рулетка» это в принципе допускает), но источник этого прямо не
утверждает. «Обсуждается» остаётся честным статусом до появления факта,
однозначно называющего исход.

Запуск: python3 pipeline/fix_rosatom_delo_shishkarev_no_show.py           # проверка
        python3 pipeline/fix_rosatom_delo_shishkarev_no_show.py --write   # запись
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g5eb6ff22'
OLD_CONTEXT = (
    'Процедура «русской рулетки» запущена 17 февраля 2026 года. Шишкарев '
    'сначала намеревался выкупить долю «Росатома», но 26 июня 2026 года '
    'отказался от этого варианта, сославшись на неблагоприятную '
    'макроэкономическую конъюнктуру, после чего 6 июля 2026 года '
    '«Росатом» объявил о решении самостоятельно выкупить 51% Шишкарева; '
    'оформление сделки запущено с 1 июля, завершение ожидается до конца '
    'июля 2026 года. 25 августа 2026 года представитель «Росатома» '
    'сообщил точную дату юридического завершения: «В эту пятницу, 28 '
    'августа, юридически завершается предусмотренная корпоративным '
    'соглашением участников ГК "Дело" процедура выкупа принадлежащей '
    'С.Н. Шишкареву 51% доли в пользу госкорпорации "Росатом". '
    'Инициированный "Росатомом" механизм "русской рулетки" юридически '
    'завершится и будет нотариально удостоверен». 26 августа 2026 года '
    'Сергей Шишкарев через представителя возразил против закрытия '
    'именно 28 августа: «Вынужден констатировать, что к настоящему '
    'моменту не все условия упомянутого договора соблюдены точно, в том '
    'числе в части порядка уведомления о дате, времени и месте '
    'совершения сделки... Я не согласен на отчуждение принадлежащей мне '
    'доли и возражаю против акцепта оферты 28 августа 2026 года либо в '
    'любую иную дату без точного соблюдения условий договора». Он '
    'подчеркнул, что «речь не идет о моем отказе от исполнения '
    'договора, а касается исключительно точного и полного соблюдения '
    'процедур», и предложил направить причитающуюся ему сумму на '
    'докапитализацию самой ГК «Дело» и поддержку ветеранов СВО.'
)
ADDITION = (
    '28 августа 2026 года — в саму объявленную дату юридического '
    'завершения — «Росатом» заявил, что Сергей Шишкарев не пришёл на '
    'сделку по выкупу его доли; ранее предприниматель заявлял, что '
    'госкорпорация выполнила не все условия, прописанные в '
    'корпоративном соглашении.'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + ADDITION
NEW_SRC = ['РБК', 'https://www.rbc.ru/business/28/08/2026/6a919b1c9a7947d0e1d8c83a']


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    card = next((c for c in data['deals'] if c['id'] == CARD_ID), None)
    assert card is not None, '%r не найдена в базе' % CARD_ID
    assert card.get('eco', {}).get('context') == OLD_CONTEXT, (
        'eco.context уже другое: %r' % card.get('eco', {}).get('context'))
    assert card.get('status') == 'Обсуждается', 'статус уже другое'
    src_already_present = NEW_SRC in card.get('src', [])

    print('ДОБАВЛЕНО: %r' % ADDITION)
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return 1

    card['eco']['context'] = NEW_CONTEXT
    if not src_already_present:
        card.setdefault('src', []).append(NEW_SRC)
    json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('ЗАПИСАНО.')
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv[1:]))
