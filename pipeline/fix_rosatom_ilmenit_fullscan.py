import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g0e8d79c1'

OLD_ECO_SHARE = '—'
NEW_ECO_SHARE = (
    'ГОК «Ильменит» разрабатывает Туганское месторождение — '
    'крупнейшее в России по запасам ильменит-цирконовых песков. '
    'Комбинат производит ильменитовый, цирконовый и рутил-лейкоксеновый '
    'концентраты, а также кварцевые пески; первая очередь мощностью '
    '575 тыс. тонн песков в год введена в 2022 году.'
)

OLD_LAW_STRUCT = '—'
NEW_LAW_STRUCT = (
    'В мае 2021 года «Объединённые урановые предприятия» (дочка '
    'Росатома) при допэмиссии акций комбината приобрели 24,99% с '
    'правом увеличения доли до контрольной; в мае 2023 года Росатом '
    'выкупил оставшиеся 75% у кипрских Arfay Enterprises Limited '
    '(39,08%) и TGOK Investment Limited (35,9%), доведя долю до 100%.'
)

OLD_ECO_RATIONALE = None
NEW_ECO_RATIONALE = (
    'Покупка решает стратегическую задачу сырьевого суверенитета по '
    'ильменитовому, рутил-лейкоксеновому и циркониевому концентратам '
    '— в 2020 году Россия импортировала 99,9% титанового сырья и 85% '
    'циркониевого. Основные потребители — титановая корпорация '
    '«ВСМПО-Ависма» и ЧМЗ (входит в Росатом).'
)

OLD_ECO_TARGET_FIN = '—'
NEW_ECO_TARGET_FIN = (
    'Выручка комбината за 2022 год — 172,82 млн ₽, чистая прибыль — '
    '23,45 млн ₽; численность сотрудников — 229 человек.'
)

OLD_ECO_CONTEXT = '—'
NEW_ECO_CONTEXT = (
    'Инвестиции во вторую очередь ГОКа оцениваются в 42,4 млрд ₽ с '
    'поэтапным запуском в 2029-2031 годах — производительность '
    'вырастет более чем в 12 раз, а готовая продукция закроет 70% '
    'потребности России в ильменитовом концентрате и 100% — в '
    'цирконовом. По итогам 2025 года комбинат зафиксировал чистый '
    'убыток 3,1 млрд ₽ (в 3,8 раза больше, чем годом ранее) на фоне '
    'перестройки технологии обогащения.'
)

OLD_SRC = [
    ['ТАСС', 'https://tass.ru/ekonomika/17748115/amp'],
    ['РИА Томск', 'https://www.riatomsk.ru/article/20230515/rosatom-polnostjyu-vikupil-tomskij-gok-iljmenit/'],
]
NEW_SRC = OLD_SRC + [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/5951620'],
    ['Интерфакс', 'https://www.interfax.ru/business/985943'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['share'] == OLD_ECO_SHARE
    assert deal['law']['struct'] == OLD_LAW_STRUCT
    assert deal['eco'].get('rationale') == OLD_ECO_RATIONALE
    assert deal['eco']['target_fin'] == OLD_ECO_TARGET_FIN
    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== eco.share: станет ===')
    print(NEW_ECO_SHARE)
    print('\n=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)
    print('\n=== eco.rationale: станет ===')
    print(NEW_ECO_RATIONALE)
    print('\n=== eco.target_fin: станет ===')
    print(NEW_ECO_TARGET_FIN)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['eco']['share'] = NEW_ECO_SHARE
        deal['law']['struct'] = NEW_LAW_STRUCT
        deal['eco']['rationale'] = NEW_ECO_RATIONALE
        deal['eco']['target_fin'] = NEW_ECO_TARGET_FIN
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
