# -*- coding: utf-8 -*-
"""Карточка `cd175a614` («Продажа земли и недвижимости ООО «Бауэр
технология» ИП Руслану Прудникову») пришла без `status` вовсе, хотя
единственное заполненное поле (`law.appr`) прямо рассказывает, чем всё
закончилось: три судебные инстанции подряд «аннулировали сделку из-за
отсутствия разрешения правительственной комиссии», покупатель обязан
вернуть имущество, а продавец — возместить деньги. Сделка не просто не
завершилась — она была отменена судом задним числом. Также `extra`
заканчивается протёкшей служебной пометкой процессуальных ролей
«(Судебный спор между ООО «Бауэр технология» (истец) и ИП Руслану
Прудниковым (ответчик))» — тот же класс дефекта, что и другие протёкшие
теги этой партии, только с другой парой ролей (истец/ответчик, а не
продавец/покупатель) и с ДВУМЯ именами внутри одной пометки, поэтому не
попал под общий шаблон `strip_leaked_role_tags_2022.py`.

Почему не через review.py: единственный источник карточки (forbes.ru) в
этой сессии не отдаёт текст, дословной цитаты для STATUS_WORDS нет; сам
факт «аннулировали» и так уже дословно лежит в `law.appr` этой же
карточки — новых утверждений скрипт не добавляет, только выводит из уже
присутствующего факта правильный статус и убирает служебный шум.

Запуск: python3 pipeline/fix_bauer_technologia_status_and_tag.py
        python3 pipeline/fix_bauer_technologia_status_and_tag.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.join(os.path.dirname(ROOT), 'static', 'data', 'deals_promoted.json')

CARD_ID = 'cd175a614'
NEW_STATUS = 'Не состоялась'
TAG = (' (Судебный спор между ООО «Бауэр технология» (истец) и ИП '
       'Руслану Прудниковым (ответчик))')
OLD_EXTRA = (
    'Статья описывает судебное разбирательство. Арбитражный суд '
    'Московской области, апелляционный суд (август), кассационная '
    'инстанция Арбитражного суда Московского округа (16 октября) '
    'аннулировали сделку из-за отсутствия разрешения правительственной '
    'комиссии. Прудников должен вернуть имущество, компания возместит '
    '130 млн рублей. Сумма: 130000000 рублей.' + TAG
)
NEW_EXTRA = OLD_EXTRA[:-len(TAG)]


def main(write=False):
    data = json.load(open(BASE, encoding='utf-8'))
    card = next(d for d in data['deals'] if d['id'] == CARD_ID)
    if card.get('status') == NEW_STATUS and card['extra'] == NEW_EXTRA:
        print('УЖЕ ПРИМЕНЕНО %s' % CARD_ID)
        return
    assert 'status' not in card, '%s: status уже задан' % CARD_ID
    assert card['extra'] == OLD_EXTRA, '%s: extra уже другой' % CARD_ID
    print('ПРАВИМ  %s: status -> «%s», снята протёкшая пометка ролей' % (CARD_ID, NEW_STATUS))
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return
    card['status'] = NEW_STATUS
    card['extra'] = NEW_EXTRA
    json.dump(data, open(BASE, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
