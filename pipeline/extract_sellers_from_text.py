def norm(s):
    return re.sub(r'\s+', ' ', str(s or '')).strip()


def low(s):
    return norm(s).lower()


def texts(deal):
    eco = deal.get('eco') or {}
    return [norm(deal.get('extra')), norm(eco.get('share')), norm(eco.get('rationale')),
            norm(eco.get('context'))]


def main(write):
    data = json.load(open(PATH, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}
    comps = data['companies']
    assert not (set(TABLE) & set(SKIP)), 'карточка одновременно в таблице и в отказах'

    done = sum(1 for i, name in TABLE.items() if norm(by_id[i].get('seller')) == norm(name))
    if done == len(TABLE):
        print('Уже применено: у всех %d карточек продавец записан.' % done)
        return
    assert done == 0, 'скрипт применён частично (%d из %d)' % (done, len(TABLE))

    planned = []
    for deal_id, name in TABLE.items():
        deal = by_id.get(deal_id)
        assert deal is not None, 'нет сделки %s' % deal_id
        assert not deal.get('seller_id') and not norm(deal.get('seller')), \
            '%s: продавец уже заполнен — %r' % (deal_id, norm(deal.get('seller')))
        # Главная проверка: имя не сочинено, а взято из текста этой же карточки.
        assert any(low(name) in low(t) for t in texts(deal) if t), \
            '%s: имя продавца не найдено в тексте карточки' % deal_id
        buyer = comps.get(deal.get('buyer'), {}).get('name') if deal.get('buyer') else None
        assert not buyer or low(buyer) != low(name), \
            '%s: продавец совпал с покупателем' % deal_id
        cid = LINK.get(deal_id)
        if cid:
            profile = comps.get(cid)
            assert profile, '%s: нет профиля %s' % (deal_id, cid)
            assert low(profile['name']) in low(name), \
                '%s: название профиля не входит в имя продавца' % deal_id
            busy = [f for f in ('buyer', 'target', 'asset_id') if deal.get(f) == cid]
            if deal_id in ROLE_FIX:
                assert ROLE_FIX[deal_id] == cid and busy == ['target'], \
                    '%s: ожидали профиль продавца в поле target' % deal_id
            else:
                assert not busy, \
                    '%s: профиль уже занят ролью %s' % (deal_id, busy)
        planned.append((deal_id, name, deal))

    print('Карточек к заполнению: %d (из них связано с профилем: %d; отклонено при чтении: %d)'
          % (len(planned), len(LINK), len(SKIP)))
    for deal_id, name, deal in planned:
        print('  %s  %s' % (deal_id, name[:100]))

    if not write:
        print('\nСухой прогон. Запись — с ключом --write.')
        return

    for deal_id, name, deal in planned:
        deal['seller'] = name
        deal['seller_src'] = 'text'
        if deal_id in LINK:
            deal['seller_id'] = LINK[deal_id]
        if deal_id in ROLE_FIX:
            deal['target'] = None
            # Флаг уже понимает интерфейс: он объясняет, почему у сделки нет
            # карточки предмета (`clean_party_roles.py`, `fix_role_leaks.py`).
            deal['target_was_seller'] = True
    with open(PATH, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    filled = sum(1 for d in data['deals'] if d.get('seller_id') or norm(d.get('seller')))
    print('\nЗаписано. Продавец известен у %d карточек из %d.' % (filled, len(data['deals'])))
    linked = sum(1 for d in data['deals'] if d.get('seller_id'))
    print('Связано с профилями компаний: %d.' % linked)
    print('Исправлена роль (продавец стоял предметом сделки): %d.' % len(ROLE_FIX))


if __name__ == '__main__':
    main('--write' in sys.argv)
