import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g12370211'

OLD_SELLER = None
NEW_SELLER = 'Евгений Финкельштейн и Надежда Соловьёва'

OLD_ECO_CONTEXT = (
    'В 2018 году головная компания Тинькофф-банка TCS Group купила 40% '
    '«Кассир.ру». В феврале 2019 года доля группы снизилась до 17,5%, '
    'затем выросла до 35%, а в августе снова уменьшилась до 29,13%. В '
    'июле 2021 года TCS Group вышла из компании, вернув долю '
    'Финкельштейну.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' К октябрю 2024 года доля «АБ Холдинга» уже '
    'снизилась с 25% до 22% — появились два новых миноритария, Алексей '
    'Гиязов (2%) и Владимир Верхошинский (1%), — но Альфа-банк остался '
    'акционером «Кассир.ру».'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal.get('seller') == OLD_SELLER
    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    print('=== seller: станет ===')
    print(NEW_SELLER)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)

    if write:
        deal['seller'] = NEW_SELLER
        deal['eco']['context'] = NEW_ECO_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
