import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g4c62c047'

OLD_LAW_STRUCT = (
    'Долю в 35% продал глава группы «Ланит» Филипп Генс; Пётр Ефимов,'
    ' основатель «Информзащиты», которая также принадлежит «Ланиту»,'
    ' продал F+ tech 14%. После сделки доля Ефимова в Getmobit составляет'
    ' 41%.'
)
NEW_LAW_STRUCT = (
    OLD_LAW_STRUCT + ' Оставшиеся 10% принадлежат Марии Рукавишниковой —'
    ' основательнице и генеральному директору Getmobit.'
)

OLD_TARGET_FIN = (
    'По данным «Спарк-Интерфакс», компания «Гетмобит» зарегистрирована в'
    ' 2016 году. В 2021 году её выручка достигла 23,8 млн ₽, а убыток'
    ' составил 53,5 млн ₽.'
)
NEW_TARGET_FIN = (
    OLD_TARGET_FIN + ' По данным агрегатора (не прессы), выручка компании'
    ' впоследствии составила: 2022 год — 37,3 млн ₽, 2023 год —'
    ' 100,2 млн ₽, 2024 год — 65,7 млн ₽, 2025 год — 32,0 млн ₽; чистый'
    ' убыток — 178,3 млн ₽ в 2024 году и 164,2 млн ₽ в 2025 году.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['law']['struct'] == OLD_LAW_STRUCT
    assert deal['eco']['target_fin'] == OLD_TARGET_FIN

    print('=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)
    print('\n=== eco.target_fin: станет ===')
    print(NEW_TARGET_FIN)

    if write:
        deal['law']['struct'] = NEW_LAW_STRUCT
        deal['eco']['target_fin'] = NEW_TARGET_FIN
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
