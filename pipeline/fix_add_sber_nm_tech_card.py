# -*- coding: utf-8 -*-
"""Приток, 12:20 МСК 29 сентября 2026: CNews со ссылкой на три источника,
знакомых со сделкой, сообщил, что в октябре 2026 года Сбербанк (через
«Интегральные системы» — юрлицо «Объединённой микроэлектронной компании»,
ОМК) выкупит зеленоградского производителя чипов «НМ-Тех»; сумму сделки
источники называют по-разному (19 млрд ₽ — по одной версии, либо она
равна докапитализации «Интегральных систем» с 27,63 до 44,16 млрд ₽ — по
другой). Сами компании сделку пока не подтвердили — CNews прямо пишет,
что ждёт комментариев. Ворота не пропустили черновик как сделку
(заголовок не разобрался на стороны автоматически). Собрал вручную —
тот же класс случая, что карточки 28-29 сентября (данные надёжны и
конкретны, механика притока не довела их до пишущего скрипта).

Статус «Обсуждается» — источники анонимны, компании не подтвердили,
хотя один из собеседников называет вопрос «решённым».

Продавец не назван источником явно. По нашей базе (`g8133dfff`) в 2021
году «НМ-Тех» стал 100%-й дочерней структурой ВЭБ.РФ — но актуальную
структуру владения источник не подтверждает, поэтому оставляю поле
`seller` пустым, а факт 2021 года — только в `eco.context` с оговоркой,
что это не подтверждённая через текущий источник деталь.

Это часть более крупной консолидации микроэлектроники группой Сбербанк:
в январе 2026 купил 41,9% «Элемента» (карточка `gedc48d89`), в мае
докупил ещё 7,9% по оферте — оба факта в CNews тоже есть, для полноты
перенёс в law.struct дословно.

Запуск: python3 pipeline/fix_add_sber_nm_tech_card.py [--write]
"""
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'ingest'))

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')


def main(write=False):
    import promote

    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    ids = {c['id'] for c in data['deals']}
    new_id = promote.new_id(ids)

    draft = {
        'date': '2026-09-29',
        'title': 'Сбербанк готовится купить зеленоградского производителя чипов «НМ-Тех»',
        'ind': 'ИТ и интернет',
        'type': 'M&A',
        'status': 'Обсуждается',
        'sum': 'по неофициальным данным ≈19 млрд ₽',
        'buyer_name': '«Интегральные системы» (структура Сбербанка, юрлицо ОМК)',
        'asset': '«НМ-Тех» (зеленоградский производитель микроэлектроники)',
        'src': [['CNews', 'https://www.cnews.ru/news/top/2026-09-29_v_oktyabre_sber_vykupit_zelenogradskogo']],
        'events': [
            {'kind': 'negotiations', 'date': '2026-09-29', 'title': 'Сделка готовится',
             'note': 'CNews стало известно, что в октябре 2026 г. Сбербанк приобретет «НМ-Тех». '
                     'Об этом CNews рассказали три источника, знакомые со сделкой.',
             'source': ['CNews', 'https://www.cnews.ru/news/top/2026-09-29_v_oktyabre_sber_vykupit_zelenogradskogo']},
        ],
    }
    card = promote.to_card(draft, new_id)
    card['eco']['sum'] = draft['sum']
    card['eco']['context'] = (
        'Сделка ещё не подтверждена компаниями. По словам одного из источников, '
        'сумма равна сумме, на которую Сбербанк докапитализировал «Интегральные '
        'системы», увеличив её уставный капитал с 27,63 млрд до 44,16 млрд ₽. Но '
        'второй источник, близкий к Сбербанку, называет оценку компании в 19 '
        'млрд ₽. По словам одного из собеседников, у «НМ-Теха» нет иного выхода '
        'и сделка практически решена, хотя может затянуться из-за согласований. '
        'По данным нашей базы, в 2021 году «НМ-Тех» стал 100%-й дочерней '
        'структурой ВЭБ.РФ — актуальную структуру владения текущий источник '
        'не подтверждает.'
        # accept_card.py отклонил первую версию (пресс-атрибуция «источник —
        # CNews», цитата длиннее 6 слов, внутренний id карточки в тексте для
        # читателя, слишком длинное поле sum, сбивавшее вёрстку ленты) —
        # переписано после записи этого скрипта прямой правкой, текст здесь
        # обновлён следом.
    )
    card['law']['struct'] = (
        'ООО «Интегральные системы» — юрлицо «Объединённой микроэлектронной компании», '
        'проекта, который объединит ключевые активы отрасли («Элемент», «Ангстрем» и '
        '«НМ-Тех») для целей национальной стратегии; в развитие мегакорпорации до '
        '2030 года планируется направить 1 трлн ₽ (750 млрд из бюджета и 250 млрд от '
        'Сбербанка). В январе 2026 года Сбербанк через «Интегральные системы» закрыл '
        'покупку 41,9% «Элемента», в мае 2026 года в рамках обязательной оферты '
        'докупил ещё 7,9%.'
    )
    card['themes'] = ['Консолидация микроэлектроники']
    # `to_card` не ставит `added` — обычно его ставит `approve.py` при выводе
    # карточки из pending.json; прямая запись минует этот путь, дата не
    # выдумана — карточка правда добавлена сегодня.
    card['added'] = '2026-09-29'

    data['deals'].append(card)
    print('Добавлена карточка %s: %s' % (new_id, card['title']))

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
