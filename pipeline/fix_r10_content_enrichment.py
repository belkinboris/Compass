DATE_FIX = dict(id='c870f1e2a', old='2024', new='2024-07-11',
                 quote_day_month='11 июля 2024')


def main(argv):
    data = json.load(open(DATA, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}

    for fix in FIELD_FIXES:
        deal = by_id[fix['id']]
        parts = fix['field'].split('.')
        obj = deal
        for p in parts[:-1]:
            obj = obj.setdefault(p, {})
        current = obj.get(parts[-1])
        assert current == fix['old'], '%s.%s: поле уже другое: %r, ожидали %r' % (
            fix['id'], fix['field'], current, fix['old'])
        # У части правок `new` — это СТАРЫЙ текст поля плюс новый факт (и
        # иногда служебный хвост вроде «(Государство (Росимущество))»),
        # поэтому дословность проверяется не по всему `new`, а по тому, что
        # реально добавлено — `quote` обязана лежать внутри `new` целиком.
        # Исключение — `status`: там `new` категориальное слово («Закрыта»,
        # «Обсуждается»), а `quote` лишь ОБОСНОВЫВАЕТ его, а не совпадает
        # текстом (та же логика, что STATUS_WORDS в review.py).
        if fix['field'] != 'status':
            assert flat(fix['quote']) in flat(fix['new']), \
                '%s.%s: цитата не входит в итоговое значение' % (fix['id'], fix['field'])

    deal = by_id[DATE_FIX['id']]
    assert deal.get('date') == DATE_FIX['old'], \
        'c870f1e2a: дата уже другая: %r' % deal.get('date')
    assert re.search(r'11\s+июля', DATE_FIX['quote_day_month']), 'дата не подтверждена цитатой'

    print('Правок: %d полей + 1 дата (c870f1e2a: %r -> %r)'
          % (len(FIELD_FIXES), DATE_FIX['old'], DATE_FIX['new']))
    for fix in FIELD_FIXES:
        print('  %s.%s -> %r' % (fix['id'], fix['field'], fix['new'][:70]))

    if '--write' not in argv:
        print('\nСухой прогон. Запись — с ключом --write.')
        return 0

    for fix in FIELD_FIXES:
        deal = by_id[fix['id']]
        parts = fix['field'].split('.')
        obj = deal
        for p in parts[:-1]:
            obj = obj.setdefault(p, {})
        obj[parts[-1]] = fix['new']

    by_id[DATE_FIX['id']]['date'] = DATE_FIX['new']

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('ЗАПИСАНО.')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
