import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

# --- c8b5a234d ---
DALP_ID = 'c8b5a234d'
DALP_OLD_STRUCT = (
    'Суд согласился с надзорным ведомством: имущество получили в '
    'нарушение законодательства о противодействии коррупции.'
)
DALP_NEW_STRUCT = (
    DALP_OLD_STRUCT + ' Иск заместителя генпрокурора Игоря Ткачева был '
    'удовлетворён в отношении долей «МС-Групп» (67%), Mimoro '
    'Constructions Ltd (16,5%) и Wanester Management Limited (16,5%) — '
    'все они обращены в доход государства.'
)
DALP_OLD_CONTEXT = '—'
DALP_NEW_CONTEXT = (
    'С февраля 2025 года в компании введена процедура наблюдения '
    'сроком на 6 месяцев в связи с банкротством; решение суда об '
    'изъятии акций подлежит немедленному исполнению.'
)

# --- cc63cf578 ---
AROM_ID = 'cc63cf578'
AROM_OLD_STATUS = None
AROM_NEW_STATUS = 'Не состоялась'
AROM_OLD_CONTEXT = (
    'Собственник сети «Ароматный мир» может смениться, стороны ведут '
    'переговоры. Среди возможных покупателей называют «Севергрупп» '
    'Алексея Мордашова.'
)
AROM_NEW_CONTEXT = (
    'Стороны действительно встречались полтора года назад по поводу '
    'возможной сделки, однако, по словам источника, близкого к '
    '«Севергрупп», сейчас интереса к этому активу у компании нет и '
    'переговоров не ведется. Вместо продажи стороннему инвестору в '
    'капитале произошёл передел долей между братьями Задориными: '
    'крупнейший совладелец Павел Задорин (ранее 57,5%) и миноритарии '
    'Анна и София Задорины (по 2,5%) вышли из капитала, на апрель 2025 '
    'года 95% долей сосредоточены у Валерия Задорина. Сама компания '
    'заявляет, что её финансовое положение устойчиво и она не '
    'продаётся.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    dalp = by_id[DALP_ID]
    arom = by_id[AROM_ID]

    assert dalp['law']['struct'] == DALP_OLD_STRUCT
    assert dalp['eco']['context'] == DALP_OLD_CONTEXT
    assert arom.get('status') == AROM_OLD_STATUS
    assert arom['eco']['context'] == AROM_OLD_CONTEXT

    print('=== dalp: law.struct ===')
    print(DALP_NEW_STRUCT)
    print('=== dalp: eco.context ===')
    print(DALP_NEW_CONTEXT)
    print()
    print('=== arom: status ===', AROM_NEW_STATUS)
    print('=== arom: eco.context ===')
    print(AROM_NEW_CONTEXT)

    if write:
        dalp['law']['struct'] = DALP_NEW_STRUCT
        dalp['eco']['context'] = DALP_NEW_CONTEXT
        arom['status'] = AROM_NEW_STATUS
        arom['eco']['context'] = AROM_NEW_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
