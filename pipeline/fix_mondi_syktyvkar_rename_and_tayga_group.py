import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'ge9d2a3e6'

OLD_EXTRA = (
    'Mondi досрочно завершила продажу целлюлозно-бумажного комбината '
    'АО «Монди Сыктывкарский ЛПК» своего последнего актива в РФ. '
    'Покупатель — компания «Сезар Групп» братьев Исая и Германа '
    'Захарьяевых. Сделка закрыта, продавец получил 57 млрд рублей и '
    'располагает аккредитивом на оставшиеся 23 млрд рублей, которые '
    'будут выплачены двумя равными платежами в ноябре и декабре 2023 '
    'года.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Завод переименован в АО «Сыктывкарский ЛПК» (3 ноября 2023), '
    'материнская структура покупателя («Сезар-Инвест») — в «Тайга '
    'Групп» (май 2025). Первоначальный претендент (структура Виктора '
    'Харитонина, Augment Investments Limited, 95 млрд ₽ в 2022 году) '
    'не связан с итоговым покупателем: та сделка сорвалась независимо '
    'из-за завышенной цены и неполучения согласования, актив достался '
    '«Сезар Групп» позже. Уже под новыми владельцами СЛПК расширился: '
    'в октябре 2024 приобрёл производителя санитарно-бумажных изделий '
    '«Сыктывкар Тиссью Груп».'
)

NEW_SRC = [
    ['Forestcomplex.ru', 'https://forestcomplex.ru/cbp/mondi-slpk-pereimenovali-posle-smeny-sobstvennika/'],
    ['DP.ru', 'https://www.dp.ru/a/2022/12/19/Vlasti_RF_ne_soglasovali'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/7363283'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
