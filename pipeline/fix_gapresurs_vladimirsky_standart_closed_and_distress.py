# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка gb70b4830
(ГАП «Ресурс» приобретает «Владимирский стандарт»). Карточка стояла со
статусом «Обсуждается» с августа 2024 года: первый этап (30%) закрылся
1 августа 2024, оставшиеся 70% — «после получения согласия ФАС».

ЗАКРЫТИЕ ВТОРОГО ЭТАПА ПОДТВЕРЖДЕНО ДВУМЯ ИСТОЧНИКАМИ, оба проверены
лично прямым WebFetch:
1) Официальный годовой пресс-релиз самого покупателя (gapresurs.ru,
итоги 2024 года): «в состав Группы вошел МПК «Владимирский стандарт» с
годовым объемом производства более 60 тысяч тонн колбасных изделий,
мясных деликатесов и полуфабрикатов во Владимирской области» — первая
сторона, не спорящая сама с собой, формулирует это как полное вхождение
в группу, а не как частичное владение.
2) Независимый бизнес-блог (ermolaevv.ru) называет точную дату и долю:
«4 октября 2024 года завершилась сделка по продаже компании
"Владимирский стандарт"», права «полностью консолидированы АО "Ресурс
Фуд Проджект"», «100% долей».
Ни Коммерсантъ, ни TAdviser отдельно дату закрытия второго этапа и факт
одобрения ФАС не называют — но сочетание первоисточника-покупателя
(вхождение в группу) и независимого источника (точная дата и 100%) даёт
достаточное основание для смены статуса, в отличие от случаев, где
только один некрупный источник называет закрытие (см. класс
«Известные проблемы» в CLAUDE.md для сравнения).

ФИНАНСОВЫЙ КРИЗИС ЦЕЛИ В 2025-2026 ГОДАХ (eco.context, дополнение,
проверено лично прямым WebFetch, meat-expert.ru): «Стоимость сырья
повысилась на 35%, тары и упаковки — на 37%»; «выручка... сократилась на
5,62% в сравнении с 2024-м — до 16,18 млрд рублей», «убыток вырос почти
в 3,8 раза — до 1,14 млрд руб.», «Совокупный долг составил 9,3 млрд
рублей (+23,6% год к году)»; производство остановлено с конца июня 2026
года («в конце июня персоналу мясокомбината объявили о вынужденном
простое»). Это тот же холдинг, у которого уже задокументированы
финансовые проблемы в других карточках базы (РЗК «Ресурс»/Миллеровский
элеватор — иск о банкротстве от «Каргис», апрель 2026) — кризис
затронул и «Владимирский стандарт», не только зерновой бизнес группы.
Прямого иска о банкротстве именно этого юрлица не нашлось.

Запуск: python3 pipeline/fix_gapresurs_vladimirsky_standart_closed_and_distress.py
        python3 pipeline/fix_gapresurs_vladimirsky_standart_closed_and_distress.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gb70b4830'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Закрыта'

OLD_APPR = (
    'Сделка структурирована в два этапа: 30% компании перешли ГАП '
    '«Ресурс» 1 августа 2024 года, оставшиеся 70% будут приобретены после '
    'получения согласия ФАС.'
)
APPR_ADDITION = (
    ' Второй этап завершён: «4 октября 2024 года завершилась сделка по '
    'продаже компании "Владимирский стандарт"», права «полностью '
    'консолидированы АО "Ресурс Фуд Проджект"» (ermolaevv.ru) — тот же год '
    'подтверждает и официальный пресс-релиз ГАП «Ресурс»: «в состав Группы '
    'вошел МПК «Владимирский стандарт»».'
)
NEW_APPR = OLD_APPR + APPR_ADDITION

OLD_CONTEXT = '—'
NEW_CONTEXT = (
    'В 2025-2026 годах предприятие столкнулось с финансовым кризисом: '
    '«Стоимость сырья повысилась на 35%, тары и упаковки — на 37%», '
    '«выручка... сократилась на 5,62% в сравнении с 2024-м — до 16,18 '
    'млрд рублей», «убыток вырос почти в 3,8 раза — до 1,14 млрд руб.», '
    '«Совокупный долг составил 9,3 млрд рублей (+23,6% год к году)» — с '
    'конца июня 2026 года производство остановлено (meat-expert.ru).'
)

NEW_SRC = [
    ['ГАП «Ресурс»', 'https://www.gapresurs.ru/press-center/news/item/6777'],
    ['ermolaevv.ru', 'https://ermolaevv.ru/tpost/fnf8gbc8x1-prodana-kompaniya-vladimirskii-standart'],
    ['Мясной эксперт', 'https://meat-expert.ru/news/20478-gap-resurs-razrabatyvaet-antikrizisnuiu-programmu-dlia-vladimirskogo-standarta'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS
    assert deal['law']['appr'] == OLD_APPR
    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print(f'=== status: {OLD_STATUS!r} -> {NEW_STATUS!r} ===')
    print('=== law.appr: станет ===')
    print(NEW_APPR)
    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['status'] = NEW_STATUS
        deal['law']['appr'] = NEW_APPR
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
