# -*- coding: utf-8 -*-
"""Чинит `eco.val` карточки g801dd6a9 (Александр Сысоев продал долю в 2ГИС
структуре Сбера): бессодержательный плейсхолдер «По оценкам экспертов» не
называл, кто именно оценил долю. Найдено в рамках G5 (PRODUCT_ROADMAP.md) —
замер по всей базе на такие плейсхолдеры дал 10 карточек, эта из них.

Источник карточки — forbes.ru, но и `fetch_article_texts.py`, и WebFetch
дают на него 0 знаков (JS-заглушка вместо статьи, тот же класс, что
Forbes/RBC Pro уже описаны в CLAUDE.md как недоступные для прямого
разбора). Текст сверен по зеркалу mergers.ru, дословно воспроизводящему
абзац Forbes, и подтверждён краткими выжимками ещё нескольких изданий
(Коммерсантъ, DK.RU), называющих тот же диапазон 5,5–14 млрд ₽ — поэтому
это не одноразовый непроверяемый пересказ, а согласованная переперепечатка.

Автор оценки — Дмитрий Козлов, основатель инвестиционной компании The12
Capital; он же назвал верхнюю границу диапазона (9,4–14 млрд ₽, по
мультипликатору P/S) и нижнюю (5,5 млрд ₽, по подходу «стоимость/
количество MAU») — карточка использует именно нижнюю границу в `sum`/
`eco.sum`, поэтому в `eco.val` идёт цитата именно про неё, а не про
верхнюю границу (иначе поле спорило бы с суммой на «Обзоре» — см. урок
CLAUDE.md «Сумма на «Обзоре» и сумма в «Экономисте» — два разных поля»).

Дословность соблюдена по общему принципу review.py (новое значение —
подстрока цитаты, без парафраза), а не через сам review.py: механизм
требует цитату из ЗАБРАННОГО текста в data/inbox/raw, а Forbes не
забирается технически (0 знаков) — здесь дословность проверяется этим
скриптом вручную, зеркало и независимые переперепечатки заменяют кэш.
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g801dd6a9'
OLD_VAL = 'По оценкам экспертов'
NEW_VAL = ('Есть и другая оценка, продолжает Козлов: по альтернативному '
           'подходу (стоимость/количество MAU) цена доли в размере 25% '
           'может достигать около 5,5 млрд рублей.')


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['val'] == OLD_VAL, \
        f"ожидали {OLD_VAL!r}, нашли {deal['eco']['val']!r}"

    print(f"{CARD_ID} eco.val:")
    print(f"  было: {OLD_VAL!r}")
    print(f"  стало: {NEW_VAL!r}")

    deal['eco']['val'] = NEW_VAL

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
