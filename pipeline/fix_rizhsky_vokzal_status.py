# -*- coding: utf-8 -*-
"""У карточки `gcc677615` («Продажа РЖД здания Рижского вокзала») `status`
стоял «Не состоялась» — формально слово поддержано источником («Торги не
состоялись оба раза из-за отсутствия заявок»), но это предложение говорит о
ДВУХ ПРОШЕДШИХ аукционах, а не о судьбе продажи в целом: та же карточка (и
тот же источник, 1prime от 23 июня 2026) описывает уже НАЗНАЧЕННЫЙ третий
аукцион на 7 августа 2026 года, а `eco.rationale`/`law.appr` описывают
активно продолжающийся, одобренный правительством процесс продажи — не
завершившийся отказом. «Не состоялась» читается как «сделка не состоится» и
прямо противоречит соседним полям той же карточки, которые говорят об
активной, продолжающейся попытке продажи.

Почему не через `review.py`: словарь `STATUS_WORDS` для «Обсуждается»
(«переговор», «рассматрива», «обсужда», «изучает», «намерен», «планирует»)
не встречается дословно ни в одном закэшированном источнике карточки — все
формулировки описывают уже объявленный/назначенный аукцион («объявили
аукцион», «выставили на торги»), а не стадию переговоров или планов. Раз
дословной опоры для одного из существующих слов нет, это не перенос факта
через таблицу FIXES, а починка уже присвоенного статуса, который сам себе
противоречит внутри одной карточки — родня урока «признак дефекта — повод
прочитать, а не основание стереть», только наоборот: правило `review.py`
верно отказалось бы принять новый статус без словаря, поэтому статус
меняется отдельным скриптом с фиксацией состояния через `assert`.

Запуск: python3 pipeline/fix_rizhsky_vokzal_status.py           # проверка
        python3 pipeline/fix_rizhsky_vokzal_status.py --write   # запись
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.join(os.path.dirname(ROOT), 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gcc677615'
OLD_STATUS = 'Не состоялась'
NEW_STATUS = 'Обсуждается'


def main(write=False):
    data = json.load(open(BASE, encoding='utf-8'))
    card = next(d for d in data['deals'] if d['id'] == CARD_ID)
    if card['status'] == NEW_STATUS:
        print('УЖЕ ПРИМЕНЕНО %s' % CARD_ID)
        return
    assert card['status'] == OLD_STATUS, '%s: статус уже другой' % CARD_ID
    print('ПРАВИМ  %s status: «%s» -> «%s»' % (CARD_ID, OLD_STATUS, NEW_STATUS))
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return
    card['status'] = NEW_STATUS
    json.dump(data, open(BASE, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
