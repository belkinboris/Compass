# -*- coding: utf-8 -*-
"""Месячная очередь, карточка g27543cdc (Продажа страховой компании
ВСК): дельта-поиск нашёл более сильное опровержение, чем уже
записанное. Прежнее (ноябрь 2025) было безымянным — «ВСК не
комментирует не имеющие оснований утверждения». Новое (20 января 2026)
— именное заявление представителя именно ВЛАДЕЛЬЦА (SFI/Гуцериевы), а
не самой ВСК, и отрицает сделку целиком, включая 49%-ю долю SFI.

Не через `review.py`: новый источник (Коммерсантъ, другая статья) не
образует с уже записанным текстом `eco.context` непрерывный кусок.

Источник — читал напрямую (WebFetch, дословная цитата подтверждена):
https://www.kommersant.ru/doc/8377281

Запуск: python3 pipeline/fix_vsk_sfi_denial_context.py [--write]
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g27543cdc'

OLD_CONTEXT = (
    'ВСК не комментирует не имеющие оснований утверждения. Об этом '
    'заявил «Ведомостям» представитель страховой группы. Так в '
    'компании ответили на просьбу прокомментировать материал '
    '«Коммерсанта». Источники газеты сообщили, что собственники ВСК '
    '(51% у Сергея Цикалюка, 49% у инвестиционного холдинга SFI, '
    'принадлежащего семье Гуцериевых) рассматривают продажу компании '
    'целиком или частично. Собеседник из числа страховщиков уточнил, '
    'что для подготовки к продаже ВСК сокращает расходы. Два '
    'собеседника «Коммерсанта» из числа страховщиков допустили '
    'продажу только доли Михаила Гуцериева. Четыре источника назвали '
    'одним из претендентов на приобретение ВСК группу «Т-технологии». '
    'Еще один источник из числа банкиров добавил, что интересантом '
    'является Совкомбанк. По словам собеседников, в рамках переговоров '
    'обсуждается цена, которая определяется как мультипликатор, '
    'умноженный на EBITDA компании.'
)
CONTEXT_ADDITION = (
    ' 20 января 2026 года директор департамента по коммуникациям и '
    'связям с инвесторами «ЭсЭфАй» Антон Гольцман заявил «Ъ», что в '
    'настоящий момент холдинг не планирует «никаких сделок с ВСК» — '
    'это уже именное опровержение от представителя владельца (SFI), а '
    'не безадресный комментарий самой ВСК, и оно отрицает сделку '
    'целиком, включая 49%-ю долю SFI.'
)
NEW_CONTEXT = OLD_CONTEXT + CONTEXT_ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f'{CARD_ID} eco.context: += именное опровержение SFI '
          f'(20 января 2026)')

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal.setdefault('src', [])
        entry = ['Коммерсантъ', 'https://www.kommersant.ru/doc/8377281']
        if entry not in deal['src']:
            deal['src'].append(entry)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('ЗАПИСАНО')
    else:
        print('Сухой прогон. Запись — с --write.')


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
