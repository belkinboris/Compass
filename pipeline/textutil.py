"""Мелкие текстовые помощники, общие для поста, сводки и отчетов.

Один `plural` на пайплайн (31 октября 2026): до этого форма слова по числу
жила четырьмя копиями (`format_post`, `send_weekly_digest`, `traffic`,
`ops_status`), записанными по-разному, но с одним результатом.
`ops_status.py` сохраняет свою копию до своей правки.
"""


def plural(n, one, few, many):
    """Форма слова по числу: 1 сделка, 2 сделки, 5 сделок, 11 сделок, 21 сделка."""
    n = abs(int(n))
    if n % 10 == 1 and n % 100 != 11:
        return one
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return few
    return many
