# -*- coding: utf-8 -*-
"""Месячная очередь качества, 11 сентября 2026 — карточка `c870f1e2a»
(«Передача заводов Silgan в управление Росимущества», июль 2024)
описывала только сам указ о временном управлении; дальнейшая судьба
заводов была неизвестна.

Личный WebFetch подтвердил дословно:

1) Interfax, https://www.interfax.ru/business/1020798: «Российские
   активы Silgan Holdings перешли в управление АО "Корпорация
   развития Республики Адыгея"» с внесением изменений в ЕГРЮЛ 10
   апреля 2025 года; управление осуществляет «ООО "Энго" (Москва),
   99% долей в котором владеет "Корпорация развития Республики
   Адыгея", 1% — администрация Тахтамукайского района Адыгеи».

2) Interfax, https://www.interfax.ru/business/1051137: «фактическое
   бездействие и неучастие в операционной деятельности предприятий
   собственника - резидента недружественных стран - привело к
   приостановке производственной деятельности»; ступинский завод в
   2024 году «получил символическую выручку - 1 млн рублей при чистом
   убытке в 256,8 млн рублей», адыгейский завод «в прошлом году не
   осуществлял деятельность, поэтому финпоказатели равны нулю».

Нового операционного собственника/инвестора не найдено — заводы
остаются под управлением государственной структуры Адыгеи, работа не
возобновлена. Отдельный, более поздний указ (октябрь 2025, РБК) о
передаче ещё одного актива Silgan (склады в Ступино) в этот прогон не
включён — саб-агент не смог процитировать его дословно, требует
отдельной проверки.

Запуск:
    python3 pipeline/fix_silgan_transferred_to_adygea_idle.py            # сухой прогон
    python3 pipeline/fix_silgan_transferred_to_adygea_idle.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_ECO_CONTEXT = (
    'Предприятия выпускают круглые жестяные и алюминиевые банки общей '
    'мощностью 350 млн банок в год. Штаб-квартира Silgan Metal '
    'Packaging, основанной в 1987 году, находится в США, значительная '
    'часть активов компании — в Европе. Silgan входит в пятёрку '
    'крупнейших производителей металлической тары, включая контейнеры '
    'и консервные банки.'
)
NEW_ECO_CONTEXT = OLD_ECO_CONTEXT + (
    ' 10 апреля 2025 года управление перешло от Росимущества к АО '
    '«Корпорация развития Республики Адыгея» (через ООО «Энго», где ей '
    'принадлежит 99% долей, оставшийся 1% — у администрации '
    'Тахтамукайского района). Оба завода фактически простаивают: '
    'ступинский в 2024 году получил выручку всего 1 млн ₽ при убытке '
    '256,8 млн ₽, адыгейский деятельности не вёл вовсе.'
)

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/business/1020798'],
    ['Интерфакс', 'https://www.interfax.ru/business/1051137'],
]


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['c870f1e2a']

    assert d['eco']['context'] == OLD_ECO_CONTEXT, 'eco.context уже другой'
    urls = {s[1] for s in d['src']}
    for src in NEW_SRC:
        assert src[1] not in urls, 'источник уже добавлен: %s' % src[1]

    print('c870f1e2a: eco.context дополнен передачей управления Адыгее '
          '(апрель 2025) и простоем заводов; добавлены два источника')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['eco']['context'] = NEW_ECO_CONTEXT
    d['src'].extend(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
