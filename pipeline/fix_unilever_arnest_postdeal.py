# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка ge370e8f1 (Unilever продал
российский бизнес группе «Арнест», октябрь 2024): дельта-поиск нашёл
независимую оценку суммы от Financial Times (отличную от уже стоящей в
карточке «неофициальной» оценки 35–40 млрд ₽), инвестиционный план
покупателя и финансовые показатели бизнеса за первый год под новым
владельцем. Все цитаты подтверждены лично прямым WebFetch.

1. Financial Times оценила сделку в «около €520 млн — это примерно 55,4
   млрд рублей по курсу ЦБ на октябрь 2024 года» (Malls.ru) — идёт в
   `eco.val` рядом с уже стоящей оценкой активов Unilever, а не вместо неё:
   это оценка именно СУММЫ СДЕЛКИ от независимого издания, а не переоценка
   баланса.
2. Группа «Арнест» после закрытия объявила о планах вложить в бизнес «не
   менее 7 млрд рублей» в 2024–2026 годах — «возобновление экспорта
   продукции, инвестиции в расширение производства и маркетинг»
   (Интерфакс).
3. Финансовые показатели купленного бизнеса за 2024 год: выручка выросла
   на 15%, до 71,4 млрд руб., чистая прибыль — в 1,6 раза, до 7,2 млрд
   руб., причём сама компания объясняет рост объёмом продаж, а не ценами:
   «фактический рост цен... был ощутимо ниже страновой инфляции» (RB.ru).

Финансового консультанта сделки дельта-поиск не нашёл ни в одном
источнике — честная пустота, не тронуто. Кириллизация брендов (Dove →
«Дав» и т.п.) и цифры за 2025 год НЕ включены: единственные найденные
формулировки — пересказ поисковой выдачи без точной дословной цитаты и
подтверждённого прямого источника, а не проверенный WebFetch текст.

Запуск: python3 pipeline/fix_unilever_arnest_postdeal.py
        python3 pipeline/fix_unilever_arnest_postdeal.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'ge370e8f1'

OLD_VAL = (
    'Российские активы на конец 2022 года корпорация оценивала в 900 млн '
    'евро. Уже по итогам 2023 года доля российского бизнеса снизилась до '
    '1% от оборота и чистой прибыли группы (59,6 млрд евро и 7,1 млрд евро '
    'соответственно), а оценка стоимости активов упала до 600 млн евро.'
)
VAL_ADDITION = (
    ' По оценке Financial Times, сама сделка могла составить «около €520 '
    'млн — это примерно 55,4 млрд рублей по курсу ЦБ на октябрь 2024 '
    'года» (Malls.ru) — независимая оценка суммы, отличная от '
    'неофициальной цифры 35–40 млрд ₽.'
)
NEW_VAL = OLD_VAL + VAL_ADDITION

OLD_CONTEXT = (
    'Доля российского бизнеса по состоянию на 2022 год составляла 1,4% от '
    'оборота всего концерна Unilever и 2% от чистой прибыли (у всего '
    'концерна оборот – 60,1 млрд евро, чистая прибыль – 8,3 млрд евро).'
)
CONTEXT_ADDITION = (
    ' После закрытия сделки «Арнест» объявил о планах вложить в бизнес «не '
    'менее 7 млрд рублей» в 2024–2026 годах: «план включает в себя '
    'возобновление экспорта продукции, инвестиции в расширение '
    'производства и маркетинг» (Интерфакс). По итогам первого полного года '
    'под новым владельцем выручка бизнеса выросла на 15%, до 71,4 млрд '
    'руб., чистая прибыль — в 1,6 раза, до 7,2 млрд руб.; сама компания '
    'объясняет рост объёмом продаж, а не ценами: «фактический рост цен на '
    'реализуемую нами продукцию был ощутимо ниже страновой инфляции, что '
    'создало благоприятные условия для увеличения объема продаж в '
    'натуральном выражении» (RB.ru).'
)
NEW_CONTEXT = OLD_CONTEXT + CONTEXT_ADDITION

NEW_SRC = [
    ['Malls.ru', 'https://www.malls.ru/rus/news/byvshaya-dochka-unilever-otsenila-brendy-v-27-6-mlrd.shtml'],
    ['Интерфакс', 'https://www.interfax.ru/business/989102'],
    ['RB.ru', 'https://rb.ru/news/yunilever-rus-net/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['val'] == OLD_VAL
    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.val: станет ===')
    print(NEW_VAL)
    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['val'] = NEW_VAL
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
