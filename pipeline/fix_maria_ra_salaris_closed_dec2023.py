# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
gc660ac38 (Покупка ТРЦ «Саларис» компанией «Мария-Ра», статус
«Обсуждается» с 2024 года при собственном тексте карточки «стороны
отрицают переговоры») — сделка на самом деле закрылась ещё в декабре
2023 года, раньше даты самой карточки; продавец официально подтвердил
закрытие.

Закрытие сделки — проверено лично прямым WebFetch (РИА Недвижимость,
14.12.2023): «В Mall Management Group подтвердили РИА Недвижимость
факт закрытия сделки» (Mall Management Group — управляющая компания
торговых активов акционера ПИК Сергея Гордеева, продавца). Косвенное
подтверждение стороны покупателя — смена руководства: «у собственника
здания - АО "Лаут" - поменялся генеральный директор. Им стал Владимир
Мамонов» — тот же источник называет Мамонова руководителем нескольких
юрлиц, принадлежащих семье Александра Ракшина (основателя «Марии-Ра»).

Более ранний этап переговоров — проверено лично прямым WebFetch (РИА
Недвижимость, 28.11.2023): «Новым владельцем актива станет компания
«Первый»... принадлежит семье Александра Ракшина», на тот момент
«сделка пока не закрыта, однако «находится на продвинутой стадии»».

Оценка суммы — проверено лично прямым WebFetch (РИА Недвижимость,
14.12.2023): «Консультанты: московский ТЦ "Саларис" мог быть продан
за 24-27 млрд рублей» — укладывается в уже стоящий в карточке диапазон
21-27 млрд ₽, отдельно менять не требуется.

`status`: «Обсуждается» → «Закрыта». `date`: «2024» → «2023» — точный
день закрытия источник не называет (только дату публикации
подтверждения), поэтому в дату идёт только год, а месяц — текстом в
`extra` (тот же принцип, что уже применён к датам-заглушкам и к смене
года в других карточках). `buyer`/`seller` НЕ трогаются — формальным
покупателем по документам выступила компания «Первый» (а не «Мария-Ра»
напрямую), это семейная структура, а не сама розничная сеть; смешивать
роли не стоит без более точного установления, какое юрлицо стоит за
профилем `buyer` карточки.

Запуск: python3 pipeline/fix_maria_ra_salaris_closed_dec2023.py
        python3 pipeline/fix_maria_ra_salaris_closed_dec2023.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gc660ac38'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Закрыта'

OLD_DATE = '2024'
NEW_DATE = '2023'

OLD_EXTRA = (
    'Переговоры между владельцами сибирского ритейлера «Мария-Ра» '
    '(семья Александра Ракшина) и структурой акционера ГК ПИК Сергея '
    'Гордеева о приобретении торгово-развлекательного комплекса. '
    'Проводится процедура оценки (due diligence), стороны отрицают '
    'переговоры.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Сделка закрылась в декабре 2023 года: к 14 декабря продавец (Mall '
    'Management Group, управляет активами Сергея Гордеева) официально '
    'подтвердил закрытие; формальным покупателем по документам '
    'выступила компания «Первый», принадлежащая семье Ракшина, у '
    'собственника здания (АО «Лаут») сменился генеральный директор на '
    'Владимира Мамонова, руководящего структурами семьи.'
)

NEW_SRC = [
    ['РИА Недвижимость', 'https://realty.ria.ru/20231128/salaris-1912285399.html'],
    ['РИА Недвижимость', 'https://realty.ria.ru/20231214/salaris-1915710810.html'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS
    assert deal['date'] == OLD_DATE
    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== status: станет ===')
    print(NEW_STATUS)
    print('\n=== date: станет ===')
    print(NEW_DATE)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['status'] = NEW_STATUS
        deal['date'] = NEW_DATE
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
