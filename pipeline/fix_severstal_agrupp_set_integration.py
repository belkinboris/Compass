import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gcc054516'

OLD_CONTEXT = (
    'В январе компания, четвертая по выплавке стали в РФ, купила в '
    'России мощности по производству металлоконструкций у группы '
    'Венталл.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' В ноябре 2025 года «Северсталь» объединила дистрибуторское '
    'подразделение и «А Групп» в «Северсталь Сеть»: «В новую структуру '
    'войдет 38 филиалов и 66 складов в России и Белоруссии общей '
    'площадью более 420 тыс. кв. м» (Коммерсантъ); заявленная в 2024 '
    'году цель по объёму поставок на вторичном рынке (3 млн тонн) '
    'достигнута (пресс-релиз группы); к 2030 году компания планирует '
    'увеличить долю в сегменте малого и среднего бизнеса до 20%, или 5 '
    'млн тонн.'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8195369'],
    ['Северсталь Вместе', 'https://vmeste.severstal.com/industries/small-and-medium-enterprise-business/severstal-sozdaet-severstal-set-dlya-malogo-i-srednego-biznesa/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
