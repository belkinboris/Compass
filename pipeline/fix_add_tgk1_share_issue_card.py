"""Приток, 14:20 МСК 29 сентября 2026: ПРАЙМ со ссылкой на материалы к
собранию акционеров сообщил, что 20 октября акционеры ТГК-1 (входит в
«Газпром энергохолдинг») рассмотрят допэмиссию акций по закрытой
подписке, которая почти УДВОИТ уставный капитал компании (с 38,5 до
~74 млрд ₽). Подписчики — «Газпром энергохолдинг», МОЭК, «Газпром
энергоремонт» и «ГЭХ Развитие территорий»; новые акции могут оплачиваться
не деньгами, а акциями МОЭК и долей в уставном капитале «Петербургэнерго».
Это внутригрупповая структурная сделка (консолидация активов группы
«Газпром энергохолдинг» через встречный обмен пакетами), а не простая
покупка/продажа — ни один буквальный «покупатель»/«продавец» не подходит,
беру структуру карточки ga46c5b15 (ВТБ/АФК «Система») за образец.

Ворота не пропустили черновик (заголовок не разбирается на стороны
автоматически), а по существу здесь и нет простой пары сторон. Собрал
карточку вручную.

Статус «Обсуждается» — решение акционеров ещё не принято (голосование
20 октября), а не факт.

Источник единственный (ПРАЙМ) — честно в eco.context.

Запуск: python3 pipeline/fix_add_tgk1_share_issue_card.py [--write]
"""
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'ingest'))

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')


def main(write=False):
    import promote

    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    ids = {c['id'] for c in data['deals']}
    new_id = promote.new_id(ids)

    draft = {
        'date': '2026-09-29',
        'title': 'ТГК-1 готовит допэмиссию, которая удвоит капитал — в оплату акции МОЭК и доля в «Петербургэнерго»',
        'ind': 'Энергетика',
        'type': 'Финансирование · структурная сделка',
        'status': 'Обсуждается',
        'sum': '≈35,5 млрд ₽ (номинал допэмиссии)',
        'src': [['ПРАЙМ', 'https://1prime.ru/20260929/tgk-1-873760365.html']],
        'events': [
            {'kind': 'negotiations', 'date': '2026-09-29', 'title': 'Вынесено на собрание акционеров',
             'note': 'Акционеры ТГК-1 (входит в "Газпром энергохолдинг") 20 октября рассмотрят '
                     'допэмиссию акций по закрытой подписке, которая практически удвоит '
                     'уставный капитал компании, следует из материалов к собранию акционеров.',
             'source': ['ПРАЙМ', 'https://1prime.ru/20260929/tgk-1-873760365.html']},
        ],
    }
    card = promote.to_card(draft, new_id)
    card['eco']['sum'] = draft['sum']
    card['eco']['share'] = (
        'Выпущенные акции предлагается разместить по закрытой подписке среди '
        '«Газпром энергохолдинга», МОЭК, «Газпром энергоремонта» и «ГЭХ Развитие '
        'территорий». Дополнительные акции могут оплачиваться акциями МОЭК и долей '
        'в уставном капитале «Петербургэнерго» — то есть не деньгами, а встречными '
        'пакетами.'
    )
    card['eco']['context'] = (
        'Пока единственный источник — ПРАЙМ. Уставный капитал ТГК-1 сейчас составляет '
        '38,5 млрд ₽ (3,9 трлн обыкновенных акций номиналом 0,01 ₽); допэмиссия — ещё '
        '3,55 трлн акций той же номинальной стоимости, то есть капитал вырастет почти '
        'вдвое. Решение выносится на заочное голосование акционеров 20 октября 2026 '
        'года — сделка ещё не закрыта.'
    )
    card['themes'] = ['Консолидация активов группы']
    # `to_card` не ставит `added` — обычно его ставит `approve.py` при выводе
    # карточки из pending.json; прямая запись минует этот путь, дата не
    # выдумана — карточка правда добавлена сегодня.
    card['added'] = '2026-09-29'

    data['deals'].append(card)
    print('Добавлена карточка %s: %s' % (new_id, card['title']))

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
