"""Заголовки без голых фамилий (владелец, 9 октября 2026: «Боброва и Бикова»
без имён «выглядит очень по-газетному, по-желтушному»). Имя берётся из текста
самой карточки — там оно уже названо полностью; не угадывается.

Без ключа — сухой прогон; запись — --write (файл перечитывается перед записью).
"""
import json
import os
import sys

DATA = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'static/data/deals_promoted.json')
FIX = {
    'g5eb6ff22': ('«Росатом» завершил выкуп у Шишкарева 51% в группе компаний «Дело»',
                  '«Росатом» завершил выкуп у Сергея Шишкарева 51% в группе компаний «Дело»'),
    'g7e0c2ffb': ('Сбер приобрел Нетологию и Фоксфорд у Мордашова',
                  'Сбер приобрел Нетологию и Фоксфорд у Алексея Мордашова'),
    'gdffd613c': ('Братья Бабаевы и топ-менеджеры приобрели контрольный пакет АО «Вектор Рейл» (владельца «СГ-Транса») у Тайчера и Смыслова',
                  'Братья Бабаевы и топ-менеджеры приобрели контрольный пакет АО «Вектор Рейл» (владельца «СГ-Транса») у Алексея Тайчера и Сергея Смыслова'),
    'cd51336b7': ('Смена бенефициарного владельца УГМК: вместо Махмудова и Бокарева в отчёте указан Данияр Камилов',
                  'Смена бенефициарного владельца УГМК: вместо Искандара Махмудова и Андрея Бокарева в отчёте указан Данияр Камилов'),
}


def apply(data):
    n = 0
    for d in data['deals']:
        if d['id'] in FIX:
            old, new = FIX[d['id']]
            if d.get('title') == new:
                continue
            assert d.get('title') == old, (d['id'], d.get('title'))
            d['title'] = new
            n += 1
            print('%s: %s' % (d['id'], new))
    return n


def main(write):
    apply(json.load(open(DATA, encoding='utf-8')))
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return 0
    data = json.load(open(DATA, encoding='utf-8'))
    if apply(data):
        with open(DATA, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('Записано.')
    return 0


if __name__ == '__main__':
    sys.exit(main('--write' in sys.argv))
