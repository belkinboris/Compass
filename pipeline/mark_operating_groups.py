# -*- coding: utf-8 -*-
"""П1''' (COMPANY_FINANCE_BRIEF.md, Этап 3): проставляет `group: true` первой
партии профилей — операционным группам компаний, где дочерние юрлица
работают под брендом/управлением родителя (МТС, Яндекс, Ростелеком…), а не
инвестиционным холдингам вроде АФК «Система» (см. pipeline/
add_afk_mts_ownership_pilot.py — та же граница, только с другой стороны).

ЛИТМУС-ВОПРОС (просьба владельца 23 августа 2026): «работает ли „дочка" под
брендом/управлением родителя, или родитель просто держит долю?» Яндекс.Go,
Яндекс.Маркет — узнаваемые продукты ОДНОГО бренда, это группа. МТС, Ozon,
Сегежа под управлением АФК «Система» — разные, самостоятельные бренды со
своим менеджментом, это инвестиционный портфель, не группа.

ДВЕ ЧАСТИ СПИСКА:
  1. 16 профилей, УЖЕ являющихся целью `holding.id` хотя бы одного другого
     профиля (`link_group_membership_from_descriptions.py`, партии 1-2, плюс
     более ранние ручные записи). Это ОБЯЗАТЕЛЬНАЯ часть — правило
     целостности (test_data.py) требует `group:true` у каждой такой цели;
     без него бейдж «Группа компаний» не появится там, где уже показывается
     список участников.
  2. 5 профилей, добавленных вручную по прямому указанию владельца или как
     общеизвестные операционные группы БЕЗ единого текущего участника в
     базе (Яндекс, Росатом) — обратное правило целостности не требуется:
     группа не обязана иметь участника, чтобы быть группой (просьба
     владельца: «Яндекс… чтобы это было видно, что это группа», даже если
     сегодня в базе нет отдельной карточки Яндекс.Go).

АФК «Система» СОЗНАТЕЛЬНО НЕ В СПИСКЕ — это инвестор, у него есть
вычисляемый блок «Портфель» (обратный ownership), но не бейдж «Группа
компаний» и не список «В группу входит»: смешение этих двух ролей — именно
та путаница, которую владелец просил не допустить.

Запуск:
    python3 pipeline/mark_operating_groups.py            # сухой прогон
    python3 pipeline/mark_operating_groups.py --write
"""
import json
import sys

PATH = 'static/data/deals_promoted.json'

# (id, ожидаемое имя, почему)
GROUPS = [
    ('g00f14033', 'Ростелеком', 'цель holding у 2 профилей'),
    ('gda7d982b', 'Softline', 'цель holding у 2 профилей'),
    ('g4e694234', 'VK', 'цель holding у 2 профилей'),
    ('gf1f56e08', 'Газпромбанк', 'цель holding у 2 профилей'),
    ('g69c88bc7', 'МТС', 'цель holding у 2 профилей'),
    ('arnest', '«Арнест»', 'цель holding у 1 профиля'),
    ('g7802e51e', 'Ростех', 'цель holding у 1 профиля'),
    ('g5c8c6494', 'ЛУКОЙЛ', 'цель holding у 1 профиля'),
    ('gcafc31dc', 'ВТБ', 'цель holding у 1 профиля'),
    ('g300b9ead', 'Роснефть', 'цель holding у 1 профиля'),
    ('g896e444d', 'Вамин Татарстан', 'цель holding у 1 профиля'),
    ('ga2cfae5b', 'Альфа-Банк', 'цель holding у 1 профиля'),
    ('g28ff15bb', 'Сбербанк', 'цель holding у 1 профиля'),
    ('gc0f11fd7', 'ПАО «Газпром»', 'цель holding у 1 профиля'),
    ('sheremetyevo', 'Международный аэропорт Шереметьево (МАШ)', 'цель holding у 1 профиля'),
    ('g3a8fb04f', 'УГМК', 'цель holding у 1 профиля'),
    ('yandex', 'Яндекс', 'общеизвестная операционная группа (Яндекс.Go, Яндекс.Маркет и др. под общим брендом)'),
    ('rosatom', 'Росатом', 'госкорпорация-группа с десятками предприятий под единым управлением'),
    ('g941bdcdf', 'ИКС Холдинг', 'название прямо называет холдинг, профиль уже описан как группа ИТ-активов'),
    ('gb5bc9e57', 'Группа ИТ-компаний «Ланит» (через ООО «Л Венчурс»)', 'название прямо содержит «Группа»'),
    ('g41e65d78', 'Газпром-медиа', 'медиахолдинг с единым брендом и управлением'),
]


def main(write):
    data = json.load(open(PATH, encoding='utf-8'))
    comps = data['companies']

    for cid, name, _why in GROUPS:
        assert cid in comps, 'профиля нет в базе: %s' % cid
        assert comps[cid]['name'] == name, \
            'имя изменилось у %s: %r (ожидали %r)' % (cid, comps[cid]['name'], name)
        assert comps[cid].get('group') is not True, 'у %s уже стоит group:true' % cid

    # Правило целостности: КАЖДЫЙ профиль, на который ссылается holding.id
    # хотя бы одного другого профиля, обязан попасть в список — иначе бейдж
    # «Группа компаний» не появится там, где уже виден список участников.
    holding_targets = {c['holding']['id'] for c in comps.values()
                       if c.get('holding') and c['holding'].get('id')}
    listed = {cid for cid, _n, _w in GROUPS}
    missing = holding_targets - listed
    assert not missing, 'цели holding не попали в список group: %s' % missing

    print('Проставляем group:true — %d профилей:\n' % len(GROUPS))
    for cid, name, why in GROUPS:
        print('  %s (%s) — %s' % (name, cid, why))

    if not write:
        print('\nСухой прогон. Запись — с ключом --write.')
        return

    for cid, _name, _why in GROUPS:
        comps[cid]['group'] = True

    with open(PATH, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('\nЗаписано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
