# -*- coding: utf-8 -*-
"""Свести разнобой разметки там, где категория ЕСТЬ, а метки разные.

ЗАЧЕМ. Аудит 5 августа (по основам слов заголовка, порог «второй вариант не
меньше половины первого») нашёл два настоящих расщепления и два одиночных
промаха:
  * аптечные сети: «Фармацевтика» 6 / «Здравоохранение» 5 — у ОДНОЙ «Риглы»
    четыре сделки в одной отрасли и пятая в другой;
  * аэропорты: «Транспорт и логистика» 5 / «Порты и инфраструктура» 5;
  * заводы Ball (алюминиевые банки) лежали в «Пищепроме» — банка для напитка
    не есть напиток, это тара (тот же урок, что «упаковка для еды — не
    производство еды»);
  * подразделение Avon (косметика) лежало в «Пищепроме».

В отличие от упаковки, здесь НЕ нужна новая категория — нужна одна метка
вместо двух. Граница:
  * аптечная сеть — «Фармацевтика»: аптека продаёт лекарства; «Здравоохранение»
    остаётся клиникам, медцентрам и диагностике;
  * аэропорт как ПРЕДМЕТ сделки — «Порты и инфраструктура»: покупают объект
    инфраструктуры; авиакомпании и перевозчики остаются «Транспортом».
Остальные расщепления аудита («продал», «завод», «ВТБ», «Яндекс») — не
разнобой: отрасль ставится по предмету сделки, а покупатель бывает в любой.

Запуск:
    python3 pipeline/unify_industry_variance.py            # сухой прогон
    python3 pipeline/unify_industry_variance.py --write    # записать
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

# id -> (кусок заголовка для сверки, нынешняя отрасль, новая отрасль)
MOVE = {
    # Аптечные сети -> Фармацевтика.
    'g577a83e0': ('аптечную сеть «Аптека25.рф»', 'Здравоохранение', 'Фармацевтика'),
    'g433cfd40': ('62 аптеки «Столичных аптек»', 'Здравоохранение', 'Фармацевтика'),
    'gfa47c307': ('«Аптеки миницен»',            'Здравоохранение', 'Фармацевтика'),
    'g709c335a': ('«Аптечество» и Farmani',      'Здравоохранение', 'Фармацевтика'),
    'gf8b3e66e': ('«ЛекОптТорг',                 'Здравоохранение', 'Фармацевтика'),
    # Аэропорты -> Порты и инфраструктура.
    'g99cb85c4': ('АО «Аэропорт Оренбург»',      'Транспорт и логистика', 'Порты и инфраструктура'),
    'g9e6dec61': ('«Аэропорт Кольцово»',         'Транспорт и логистика', 'Порты и инфраструктура'),
    'g1256bf63': ('аэропорта «Березники»',       'Транспорт и логистика', 'Порты и инфраструктура'),
    'g5f662edc': ('Аэропорт Магнитогорск',       'Транспорт и логистика', 'Порты и инфраструктура'),
    'g97d0d2a2': ('аэропорт Магас',              'Транспорт и логистика', 'Порты и инфраструктура'),
    # Одиночные промахи.
    'g2dc1ba74': ('заводы Ball',                 'Пищепром и напитки', 'Производство тары'),
    'gc3ab0c7d': ('подразделение Avon',          'Пищепром и напитки', 'Потребительские товары'),
}


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    cards = {d['id']: d for d in data['deals']}
    plan, refused = [], []
    for deal_id, (title_part, was, new) in MOVE.items():
        card = cards.get(deal_id)
        if not card:
            refused.append((deal_id, 'карточки нет в базе'))
        elif card.get('ind') == new:
            continue
        elif title_part.lower() not in str(card.get('title') or '').lower():
            refused.append((deal_id, 'заголовок не совпадает: %r' % str(card.get('title'))[:56]))
        elif card.get('ind') != was:
            refused.append((deal_id, 'отрасль уже другая: %r' % card.get('ind')))
        else:
            plan.append((card, was, new))

    for card, was, new in plan:
        print('  %-11s %-22s -> %-24s %s' % (card['id'], was, new, str(card.get('title'))[:48]))
    for deal_id, why in refused:
        print('  ОТКАЗ %-11s %s' % (deal_id, why))
    if refused:
        print('Есть отказы — не пишем ничего.')
        return 1
    if not write:
        print('Сухой прогон (%d правок). Запись — с ключом --write.' % len(plan))
        return 0
    for card, was, new in plan:
        assert card['ind'] == was
        card['ind'] = new
    json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('ЗАПИСАНО: %d' % len(plan))
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
