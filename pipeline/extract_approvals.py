def is_placeholder(v):
    s = str(v or '').strip()
    return not s or bool(PLACEHOLDER.match(s))


def norm(s):
    return re.sub(r'\s+', ' ', str(s or '')).strip().lower()


def source_of(deal, field):
    return deal.get(field) if field == 'extra' else (deal.get('eco') or {}).get(field)


def main(write):
    data = json.load(open(PATH, encoding='utf-8'))
    deals = data['deals']
    by_id = {d['id']: d for d in deals}

    assert not (set(TABLE) & set(SKIP)), 'карточка одновременно в таблице и в отказах'

    done = sum(1 for i, (_, t) in TABLE.items()
               if i in by_id and norm((by_id[i].get('law') or {}).get('appr')) == norm(t))
    if done == len(TABLE):
        print('Уже применено: все %d карточек содержат нужный текст.' % done)
        return
    assert done == 0, 'скрипт применён частично (%d из %d) — данные в промежуточном состоянии' % (done, len(TABLE))

    planned = []
    for deal_id, (field, text) in TABLE.items():
        deal = by_id.get(deal_id)
        assert deal is not None, 'нет сделки %s' % deal_id
        law = deal.setdefault('law', {})
        # Затирать факт нельзя: скрипт только заполняет пустое поле.
        assert is_placeholder(law.get('appr')), \
            '%s: «Согласования» уже заполнены — %r' % (deal_id, law.get('appr'))
        raw = source_of(deal, field)
        assert not is_placeholder(raw), '%s: поле-источник %s пусто' % (deal_id, field)
        # Главная проверка: текст не сочинён, а вырезан из самой карточки.
        assert norm(text).rstrip('.') in norm(raw), \
            '%s: текст не является куском поля %s' % (deal_id, field)
        assert text.endswith(('.', '!', '?')), '%s: нет точки в конце' % deal_id
        planned.append((deal_id, field, text, law))

    print('Карточек к заполнению: %d' % len(planned))
    print('Отклонено при чтении глазами: %d' % len(SKIP))
    for deal_id, field, text, _ in planned:
        print('  %s <- %s: %s' % (deal_id, field, text[:110]))

    if not write:
        print('\nСухой прогон. Запись — с ключом --write.')
        return

    for _, _, text, law in planned:
        law['appr'] = text
    with open(PATH, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    filled = sum(1 for d in deals if not is_placeholder((d.get('law') or {}).get('appr')))
    print('\nЗаписано. «Согласования» заполнены у %d карточек из %d.' % (filled, len(deals)))


if __name__ == '__main__':
    main('--write' in sys.argv)
