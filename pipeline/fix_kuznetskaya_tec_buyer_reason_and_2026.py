# -*- coding: utf-8 -*-
"""Месячная очередь, 9 сентября 2026 — дочитывание карточки `gb0759159`
(«СГК и "Кузбассэнерго" продали 100% акций "Кузнецкой ТЭЦ"», добавлена в
базу 3 августа 2026, полностью обыскана в тот же день).

Дельта-поиск (саб-агент + личная проверка) нашёл три новых факта:

1) Покупатель, ООО «Стройтехпроект», уже владеет конкурирующей станцией
   в том же городе. Личный WebFetch (kommersant.ru/doc/4134324,
   23.10.2019) подтвердил дословно: «Компания «Стройтехпроект» принадлежит
   предпринимателю Ивану Сазыкину (100%)», «Имущественный комплекс
   Центральной ТЭЦ Новокузнецка продан кемеровской компании
   «Стройтехпроект». Цена продажи составила 335 млн руб.» — то есть
   покупатель Кузнецкой ТЭЦ ранее (в 2019 году) уже приобрёл прямого
   городского конкурента.

2) Причина продажи. Личный WebFetch (interfax.ru/business/1027067 — тот
   же источник, что уже стоит в `src` карточки, дочитан глубже) подтвердил
   дословно слова гендиректора «Кузбассэнерго» Виктора Лариошкина:
   «Отрицательный финансовый результат работы Кузнецкой ТЭЦ… связан с
   тем, что на том же берегу Новокузнецка, где находится Кузнецкая ТЭЦ,
   работает ещё одна теплостанция — Центральная ТЭЦ»; «Кузнецкая ТЭЦ в
   лучшие времена выходила в ноль… Во все остальное время, особенно с
   учётом повышения стоимости угля, роста оптовых цен, мы постепенно
   ушли в минус».

3) Продолжение сюжета в 2026 году. Личный WebFetch (142.ru, 30 января
   2026) подтвердил дословно: «03.01.2026 г. АО «Кузнецкая ТЭЦ»
   направлено письмо в Минэнерго РФ о прекращении статуса ЕТО в системе
   теплоснабжения №001» — с 1 января 2026 года новым единым
   теплоснабжающим оператором для потребителей стало ООО «ЭнергоТранзит».

Саб-агент отдельно отметил расхождение в датах между источниками (часть
изданий называет 28 апреля 2025 года, а не 22 августа 2025, как в
карточке) — это НЕ проверено прямым чтением ЕГРЮЛ в этом заходе и
сознательно НЕ вносится: смена даты сделки требует отдельного
одноразового скрипта с `assert` на исходное состояние и более твёрдого
подтверждения, чем агрегированная сводка.

Запуск:
    python3 pipeline/fix_kuznetskaya_tec_buyer_reason_and_2026.py            # сухой прогон
    python3 pipeline/fix_kuznetskaya_tec_buyer_reason_and_2026.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_ECO_RATIONALE = (
    'Продажа ТЭЦ состоялась в конце апреля. Новым владельцем стало '
    'новокузнецкое ООО «Стройтехпроект»: 95% в нём принадлежат '
    'генеральному директору Ивану Сазыкину, ещё 5% — Антону Кузнецову.'
)
NEW_ECO_RATIONALE = OLD_ECO_RATIONALE + (
    ' Причина продажи — убыточность станции: по словам гендиректора '
    '«Кузбассэнерго» Виктора Лариошкина, «отрицательный финансовый '
    'результат работы Кузнецкой ТЭЦ… связан с тем, что на том же берегу '
    'Новокузнецка… работает ещё одна теплостанция — Центральная ТЭЦ, '
    'собственники которой и приобрели Кузнецкую ТЭЦ», а рост цен на '
    'уголь и оптовых цен на электроэнергию не позволял станции выходить '
    'даже в ноль.'
)

OLD_LAW_STRUCT = (
    'Сделка включала подготовку и согласование документов, переговоры, '
    'подписание и закрытие продажи 100% акций АО «Кузнецкая ТЭЦ».'
)
NEW_LAW_STRUCT = OLD_LAW_STRUCT + (
    ' Покупатель, ООО «Стройтехпроект» Ивана Сазыкина, уже владел '
    'прямым городским конкурентом станции — имущественным комплексом '
    'Центральной ТЭЦ Новокузнецка, купленным на торгах в 2019 году за '
    '335 млн ₽.'
)

OLD_ECO_CONTEXT = (
    'АО «Кузнецкая ТЭЦ» владеет угольной тепловой электростанцией и '
    'остаётся одним из главных источников тепла для Новокузнецка — '
    'крупнейшего города Кемеровской области. Станция снабжает теплом '
    'жителей и промышленные предприятия.'
)
NEW_ECO_CONTEXT = OLD_ECO_CONTEXT + (
    ' С 1 января 2026 года АО «Кузнецкая ТЭЦ» отказалось от статуса '
    'единой теплоснабжающей организации: 3 января 2026 года станция '
    'направила соответствующее письмо в Минэнерго России, и новым '
    'оператором теплоснабжения для потребителей стало ООО '
    '«ЭнергоТранзит».'
)

NEW_SRC = ['142.ru', 'https://142.ru/gorod/novokuzneck-oplata-tepla-i-gvs-perekhodit-k-novomu-postavshiku-id6802302/']


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['gb0759159']

    assert d['eco']['rationale'] == OLD_ECO_RATIONALE, \
        'gb0759159 eco.rationale уже другой: %r' % (d['eco']['rationale'],)
    assert d['law']['struct'] == OLD_LAW_STRUCT, \
        'gb0759159 law.struct уже другой: %r' % (d['law']['struct'],)
    assert d['eco']['context'] == OLD_ECO_CONTEXT, \
        'gb0759159 eco.context уже другой: %r' % (d['eco']['context'],)
    urls = {s[1] for s in d['src']}
    assert NEW_SRC[1] not in urls, 'источник уже добавлен'

    print('gb0759159: eco.rationale дополнен (причина продажи), '
          'law.struct дополнен (покупатель — владелец конкурента), '
          'eco.context дополнен (отказ от статуса ЕТО с 2026 года); '
          'добавлен источник 142.ru')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['eco']['rationale'] = NEW_ECO_RATIONALE
    d['law']['struct'] = NEW_LAW_STRUCT
    d['eco']['context'] = NEW_ECO_CONTEXT
    d['src'].append(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
