# -*- coding: utf-8 -*-
"""Карточка ge0f7b957 («Газпромбанк вышел из капитала ГК «Эксперт», продав
миноритарную долю мажоритарным акционерам») несла 2025 год вместо 2026.

ЧТО СЛОМАНО. Поле `date` стояло «2025» (год без месяца и дня). Единственный
источник карточки — пресс-релиз gazprombank.ru, и он прямо датирует саму
сделку 2026 годом: «Москва, 25 мая 2026 года — Газпромбанк завершил сделку
по продаже принадлежащей ему миноритарной доли в группе медицинских
компаний «Эксперт» в пользу мажоритарных акционеров Группы». Дата публикации
страницы на сайте банка та же: «Газпромбанк вышел из капитала ГК «Эксперт»
25 мая, 2026». Ошибка не в дне/месяце, а в самом годе.

Год 2025 в карточке — не выдумка из ниоткуда: в том же пресс-релизе упомянута
СОСЕДНЯЯ, более ранняя сделка той же группы («продажа в мае 2025 года
18 многопрофильных клиник и трёх госпиталей «Эксперта» Группе компаний
«Мать и дитя»») — видимо, разбор источника взял год именно оттуда, а не из
абзаца про выход самого Газпромбанка. Это тот же класс дефекта, что урок
CLAUDE.md «число может относиться не к репортируемой сделке, а к
промежуточному шагу»: рядом с нужной сделкой в тексте стоит дата ДРУГОЙ
сделки, и она перетекла не в то поле.

ПОЧЕМУ НЕ ЧЕРЕЗ `review.py`. `date_is_supported()` намеренно запрещает
менять год — перенос года обязан быть отдельным, явным решением с
проверяемым источником (см. урок CLAUDE.md про g6d73538c / «Основа»/
промзона «Свиблово», и gd6b3c796 / ОСК-КМЗ), а не автоматической правкой в
общей таблице.

ПОЧЕМУ ПОЛНАЯ ДАТА. Источник называет не только год, но и точный день и
месяц («25 мая 2026 года»), дважды — в теле пресс-релиза и в дате публикации
страницы; ничего не приходится досочинять.

Запуск:
    python3 pipeline/fix_gazprombank_expert_exit_date.py            # сухой прогон
    python3 pipeline/fix_gazprombank_expert_exit_date.py --write    # записать
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'
DEAL_ID = 'ge0f7b957'
OLD_DATE = '2025'
NEW_DATE = '2026-05-25'
QUOTE = ('Москва, 25 мая 2026 года — Газпромбанк завершил сделку по продаже '
         'принадлежащей ему миноритарной доли в группе медицинских компаний '
         '«Эксперт» в пользу мажоритарных акционеров Группы — '
         'gazprombank.ru датирует страницу «25 мая, 2026»')


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}
    deal = by_id.get(DEAL_ID)
    assert deal is not None, 'нет сделки %s' % DEAL_ID
    assert deal.get('date') == OLD_DATE, \
        'дата уже другая: %r, ожидали %r' % (deal.get('date'), OLD_DATE)

    print('%s: date %r -> %r' % (DEAL_ID, OLD_DATE, NEW_DATE))
    print('  цитата: %r' % QUOTE)

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    deal['date'] = NEW_DATE
    assert deal['date'] == NEW_DATE, 'дата не записалась'

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
