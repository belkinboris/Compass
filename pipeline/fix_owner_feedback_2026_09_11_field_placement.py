# -*- coding: utf-8 -*-
"""Три карточки, где владелец нашёл дословно верную, но НЕ НА СВОЁМ МЕСТЕ
цитату — тот же класс дефекта, что уже описан в CLAUDE.md для HeadHunter/
Happy Job: `review.py` проверяет, что текст реален и процитирован точно, но
не проверяет, что он относится К ТОЙ КАТЕГОРИИ, для которой заведено поле.

**g7299791f (БКС/«Форштадт»).** `law.struct` («Как устроена сделка» на
Обзоре) нёс «В БКС заявили, что информация о сделке не соответствует
действительности» — это опровержение, а не структура сделки, и тот же факт
уже полностью раскрыт в `eco.context`. Снято; краткая версия с источником
добавлена в `extra`, чтобы опровержение было видно на главной вкладке
карточки, а не только в «Экономисте». Статус (`Обсуждается`) НЕ ТРОГАЕМ —
владелец не просил его менять, только починить размещение факта.

**g139db8c2 (S8 Capital/«МТ-Интеграция»/«Аквариус»).** `law.struct` нёс
«Сделка, возможно, будет проведена через специальную инвестиционную
структуру (SPV)» — реальная цитата sostav.ru от 22.08.2025 (проверено
прямым чтением), но написана ДО закрытия сделки как гипотеза, которую
никто и никогда не подтвердил; на закрытой сделке слово «возможно» читается
как незакрытый вопрос, который на деле просто забыли снять. Снято.
Опровержение «МТ-Интеграции» (уже раскрыто в `eco.context`) добавлено в
`extra` с источником — по прямой просьбе владельца.

**g4165ba00 (ГК «Мать и дитя»/«Инвитро»).** `law.terms` («Условия сделки»
на «Юристе») нёс «Собственники «Инвитро» при этом не ищут покупателей на
свой актив» — это не условие сделки, а более ранняя (15.07.2025), менее
информативная версия того же денай-факта, который полностью и с атрибуцией
уже стоит в `eco.context` (Курцер, 29.08.2025). Снято; отдельно в `extra`
не дублируем — там уже сказано о рассмотрении сделки, а денай подробно
рассказан в контексте. Статус (`Обсуждается`) НЕ ТРОГАЕМ.

Соответствующие записи `FIXES` (batch_digest_r1_auto.py — g7299791f/
law.struct и g4165ba00/law.terms; batch_agents100_r2.py — g139db8c2/
law.struct) закомментированы отдельно, с объяснением, до этого скрипта.

Запуск:
    python3 pipeline/fix_owner_feedback_2026_09_11_field_placement.py
    python3 pipeline/fix_owner_feedback_2026_09_11_field_placement.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(ROOT)
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

BKS_OLD_STRUCT = 'В БКС заявили, что информация о сделке не соответствует действительности.'
BKS_OLD_EXTRA = 'Strategy Partners сопровождала сделку; её роль не уточнена.'
BKS_NEW_EXTRA = (
    'БКС и банк «Форштадт» публично опровергли информацию о сделке '
    '6 октября 2025 года, в тот же день, когда о закрытии сообщил Forbes '
    '(источник: Ведомости) — опровержение с тех пор никем не оспорено, а '
    'переход контроля к БКС ни один источник не подтвердил. Strategy '
    'Partners сопровождала сделку; её роль не уточнена.'
)

AKV_OLD_STRUCT = 'Сделка, возможно, будет проведена через специальную инвестиционную структуру (SPV).'
AKV_OLD_EXTRA = (
    'Сделка по приобретению 79% акционерного капитала производителя '
    'электроники и радиоэлектронного оборудования. Покупатели — S8 '
    'Capital (холдинг Армена Саркисяна) и ГК «МТ-Интеграция». S8 Capital '
    '— активный покупатель российских активов, ранее приобретавший '
    'активы ушедших иностранцев (Continental, Bridgestone, Bosch, Otis). '
    'ГК «МТ-Интеграция» — интегратор, сосредоточившийся на интеграторском '
    'бизнесе после продажи операторского бизнеса в 2023 году.'
)
AKV_NEW_EXTRA = AKV_OLD_EXTRA + (
    ' 22 августа 2025 года, на следующий день после публикации о сделке, '
    'ГК «МТ-Интеграция» опубликовала пресс-релиз: сведения о её входе в '
    'состав акционеров «Аквариуса» назвала не соответствующими '
    'действительности (источник: CTA.ru со ссылкой на CNews) — по '
    'состоянию на 02.10.2025 обе компании по-прежнему назывались '
    'совладельцами 79%, опровержение с тех пор не подтверждено и не '
    'опровергнуто.'
)

INVITRO_OLD_TERMS = 'Собственники «Инвитро» при этом не ищут покупателей на свой актив.'


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}

    bks = by_id['g7299791f']
    assert bks['law'].get('struct') == BKS_OLD_STRUCT, (
        'g7299791f/law.struct изменился, ожидали %r, сейчас %r'
        % (BKS_OLD_STRUCT, bks['law'].get('struct')))
    assert bks.get('extra') == BKS_OLD_EXTRA, (
        'g7299791f/extra изменился, ожидали %r, сейчас %r'
        % (BKS_OLD_EXTRA, bks.get('extra')))

    akv = by_id['g139db8c2']
    assert akv['law'].get('struct') == AKV_OLD_STRUCT, (
        'g139db8c2/law.struct изменился, ожидали %r, сейчас %r'
        % (AKV_OLD_STRUCT, akv['law'].get('struct')))
    assert akv.get('extra') == AKV_OLD_EXTRA, (
        'g139db8c2/extra изменился, ожидали %r, сейчас %r'
        % (AKV_OLD_EXTRA, akv.get('extra')))

    invitro = by_id['g4165ba00']
    assert invitro['law'].get('terms') == INVITRO_OLD_TERMS, (
        'g4165ba00/law.terms изменился, ожидали %r, сейчас %r'
        % (INVITRO_OLD_TERMS, invitro['law'].get('terms')))

    print('ПРАВИМ g7299791f: law.struct -> «—» (денай не по адресу), extra '
          '-> денай с источником')
    print('ПРАВИМ g139db8c2: law.struct -> «—» (устаревшая гипотеза SPV), '
          'extra -> денай МТ-Интеграции с источником')
    print('ПРАВИМ g4165ba00: law.terms -> «—» (не условие сделки, дубль '
          'денай-факта из eco.context)')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    bks['law']['struct'] = '—'
    bks['extra'] = BKS_NEW_EXTRA

    akv['law']['struct'] = '—'
    akv['extra'] = AKV_NEW_EXTRA

    invitro['law']['terms'] = '—'

    json.dump(data, open(DATA, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
