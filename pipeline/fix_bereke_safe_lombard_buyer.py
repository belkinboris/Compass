# -*- coding: utf-8 -*-
"""g81510c02 («Игорь Ким продал казахстанскую МФО «Береке» Эдуарду Ли»)
называла покупателем ФИЗЛИЦО Эдуарда Ли — найдено ночной вычиткой 40
карточек (17-18 августа 2026) как подозрение («покупатель, возможно, должен
быть юрлицом»), подтверждено самостоятельно чтением источника целиком.

Источник (forbes.kz, дата статьи 28.03.2025 — совпадает с датой карточки)
описывает ДВЕ РАЗНЫЕ сделки одной хронологии, а не одну:

    1) 13 марта 2025: Ким продал Эдуарду Ли (экс-топ-менеджеру компании)
       98,988% ТОО «Сейф-Ломбард» — уже верно перенесено в `extra`.
    2) 28 марта 2025 (дата ЭТОЙ карточки): «Новым и одновременно "старым"
       собственником МФО "Береке" 28 марта 2025 года стало ТОО
       "Сейф-Ломбард"» — то есть саму МФО «Береке» Ким вернул компании
       «Сейф-Ломбард», а не лично Эдуарду Ли. Ли к 28 марта уже контролирует
       «Сейф-Ломбард» (сделка №1), поэтому он — конечный бенефициар, но не
       прямой юридический покупатель ИМЕННО «Береке».

Карточка склеила прямого покупателя (юрлицо) с конечным бенефициаром
(физлицо) — тот же класс дефекта, что уже описан в CLAUDE.md («Стороной
сделки может быть записан профиль совсем другой сущности»). Создан новый
профиль ТОО «Сейф-Ломбард» (юрлицо-покупатель), `buyer` карточки указывает
на него; заголовок и eco.share переписаны так, чтобы называть обе стороны
правильно, сохранив упоминание Ли как понятного читателю контекста
(«подконтрольному Эдуарду Ли»), не выдавая его за прямую сторону сделки.

Запуск:
    python3 pipeline/fix_bereke_safe_lombard_buyer.py            # сухой прогон
    python3 pipeline/fix_bereke_safe_lombard_buyer.py --write     # запись
"""
import json
import sys

PATH = "static/data/deals_promoted.json"
ID = "g81510c02"
OLD_BUYER = "gbd434171"
NEW_BUYER_ID = "gsafelombard01"

OLD_TITLE = 'Игорь Ким продал казахстанскую МФО «Береке» Эдуарду Ли'
NEW_TITLE = 'Игорь Ким передал МФО «Береке» «Сейф-Ломбарду», подконтрольному Эдуарду Ли'

NEW_COMPANY = {
    "name": "ТОО «Сейф-Ломбард»",
    "ind": "Банки",
    "desc": ("Казахстанская финансовая компания; с 13 марта 2025 года "
             "98,988% контролирует Эдуард Ли, ранее — топ-менеджер "
             "компании, выкупивший долю у Игоря Кима. 28 марта 2025 года "
             "стала собственником МФО «Береке», вернувшейся от Кима."),
    "kpi": ["Профиль", "Автоматический"],
}

NEW_ECO_SHARE = ('Новым и одновременно «старым» собственником МФО «Береке» '
                  '28 марта 2025 года стало ТОО «Сейф-Ломбард».')


def main(write):
    with open(PATH, encoding="utf-8") as f:
        base = json.load(f)
    by_id = {d["id"]: d for d in base["deals"]}
    d = by_id.get(ID)
    assert d is not None, f"{ID} не найдена"

    assert d["buyer"] == OLD_BUYER, "buyer уже другой — уже правили?"
    assert NEW_BUYER_ID not in base["companies"], "профиль уже существует"
    base["companies"][NEW_BUYER_ID] = dict(NEW_COMPANY)
    d["buyer"] = NEW_BUYER_ID

    assert d["title"] == OLD_TITLE, "title уже другой — уже правили?"
    d["title"] = NEW_TITLE

    assert d["eco"]["share"] == "—", "eco.share уже другой — уже правили?"
    d["eco"]["share"] = NEW_ECO_SHARE

    print(f"{ID}: buyer -> новый профиль «Сейф-Ломбард» ({NEW_BUYER_ID}), "
          f"title и eco.share исправлены (прямой покупатель — юрлицо, "
          f"Эдуард Ли — конечный бенефициар)")

    if write:
        with open(PATH, "w", encoding="utf-8") as f:
            json.dump(base, f, ensure_ascii=False, indent=1)
        print("\nЗАПИСАНО.")
    else:
        print("\nСухой прогон — ничего не записано. Добавьте --write.")


if __name__ == "__main__":
    main(write="--write" in sys.argv)
