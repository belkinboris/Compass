# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
gf13fba9e (ООО «Перспектива» подала заявку на аукцион по продаже
«Домодедово») — карточка застряла на моменте «подала заявку», хотя
торги давно завершены победой заявителя, договор подписан, а год сделки
был ошибочным (2024 вместо 2026). Проверено лично прямым WebFetch двух
источников.

Год сделки (2024 → 2026) — НЕ через `review.py` (смена года — отдельный
скрипт). Дословно (Коммерсантъ, 29.01.2026, 18:02): «ООО "Перспектива" —
на торгах 29 января купила аэропорт Домодедово за 66 132 908 002,5
руб.» — тот же день, что уже упомянут в источнике карточки (РИА
Новости, ria.ru/20260129/...).

`title`/`extra`/`status` — обновлены с «подала заявку»/«Обсуждается» на
факт победы и закрытия: «сообщили "Ъ" в ПСБ, который выступил
организатором торгов на площадке РТС-тендер», «К торгам не допустили
предпринимателя Евгения Рыбалкина, АО "Альма" и ООО "Аргана". В
аукционе участвовали структуры Шереметьево и аэропорта Внуково.»
Дословно (Право.ру, 09.02.2026): «"Перспектива", дочерняя структура
аэропорта Шереметьево, заключила с ПСБ договор на приобретение активов
аэропорта Домодедово» — договор подписан ровно в срок, обещанный
источником карточки («в течение пяти рабочих дней» после торгов
29 января).

`eco.sum` (заполнено, было «Не раскрыта» — расходилось с уже известным
`sum`). Та же дословная цитата Коммерсанта даёт точное число: «66 132
908 002,5 руб.» — соответствует уже стоящему округлению «66,13 млрд ₽».

`law.struct` (дополнено) и `law.terms` (дополнено) — организатор торгов
и второй допущенный участник; факт реального подписания договора.

НЕ ВКЛЮЧЕНО: юридические консультанты сделки — не найдены ни в одном из
пяти проверенных источников (Коммерсантъ, Интерфакс, Ведомости,
Право.ру, DP.ru); долговая нагрузка группы «Домодедово» (~70 млрд ₽,
Ведомости) — самостоятельный факт о финансах предмета, оставлен для
отдельной правки `eco.target_fin`, чтобы не перегружать одну правку.

Запуск: python3 pipeline/fix_domodedovo_auction_won.py
        python3 pipeline/fix_domodedovo_auction_won.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gf13fba9e'

OLD_TITLE = 'ООО «Перспектива» (дочка «Шереметьево») подала заявку на участие в аукционе по продаже «Домодедово»'
NEW_TITLE = 'ООО «Перспектива» (дочка «Шереметьево») выиграла аукцион по продаже «Домодедово»'

OLD_DATE = '2024'
NEW_DATE = '2026'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Закрыта'

OLD_EXTRA = (
    'Дочерняя структура аэропорта «Шереметьево» ООО «Перспектива» '
    'подала заявку на участие в повторном аукционе по продаже аэропорта '
    '«Домодедово». Гендиректор «Шереметьево» Михаил Василенко ранее '
    'указывал на готовность участвовать при проведении второго этапа '
    'конкурса с понижением цены. («Шереметьево» / ООО «Перспектива»)'
)
NEW_EXTRA = (
    'Дочерняя структура аэропорта «Шереметьево» ООО «Перспектива» '
    'выиграла повторный аукцион по продаже аэропорта «Домодедово», '
    'купив его за 66,13 млрд ₽. Гендиректор «Шереметьево» Михаил '
    'Василенко ранее указывал на готовность участвовать при проведении '
    'второго этапа конкурса с понижением цены. 9 февраля 2026 года '
    '«Перспектива» заключила с организатором торгов, ПСБ, договор на '
    'приобретение активов «Домодедово». («Шереметьево» / ООО '
    '«Перспектива»)'
)

OLD_ECO_SUM = 'Не раскрыта'
NEW_ECO_SUM = (
    'ООО «Перспектива» купила аэропорт Домодедово за 66 132 908 002,5 '
    'руб.'
)

OLD_STRUCT = (
    'Торги по продаже Домодедово прошли сегодня в формате голландского '
    'аукциона — с понижением стоимости. При этом минимально возможная '
    'цена составила 66,1 миллиарда рублей. Всего на участие в торгах '
    'подали пять заявок, прошли только две.'
)
NEW_STRUCT = OLD_STRUCT + (
    ' Организатором торгов выступил ПСБ на площадке РТС-тендер. К '
    'торгам не допустили предпринимателя Евгения Рыбалкина, АО «Альма» '
    'и ООО «Аргана» — в аукционе участвовали структуры Шереметьево и '
    'аэропорта Внуково.'
)

OLD_TERMS = (
    'Договор о продаже будет подписан в течение пяти рабочих дней, а '
    'передача имущества пройдет не позднее чем через 30 дней после '
    'оплаты.'
)
NEW_TERMS = OLD_TERMS + (
    ' Договор подписан 9 февраля 2026 года: «"Перспектива", дочерняя '
    'структура аэропорта Шереметьево, заключила с ПСБ договор на '
    'приобретение активов аэропорта Домодедово» (Право.ру).'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8380948'],
    ['Право.ру', 'https://pravo.ru/news/262332/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['title'] == OLD_TITLE
    assert deal['date'] == OLD_DATE
    assert deal['status'] == OLD_STATUS
    assert deal['extra'] == OLD_EXTRA
    assert deal['eco']['sum'] == OLD_ECO_SUM
    assert deal['law']['struct'] == OLD_STRUCT
    assert deal['law']['terms'] == OLD_TERMS
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== title: станет ===')
    print(NEW_TITLE)
    print('\n=== date: станет ===')
    print(NEW_DATE)
    print('\n=== status: станет ===')
    print(NEW_STATUS)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== eco.sum: станет ===')
    print(NEW_ECO_SUM)
    print('\n=== law.struct: станет ===')
    print(NEW_STRUCT)
    print('\n=== law.terms: станет ===')
    print(NEW_TERMS)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['title'] = NEW_TITLE
        deal['date'] = NEW_DATE
        deal['status'] = NEW_STATUS
        deal['extra'] = NEW_EXTRA
        deal['eco']['sum'] = NEW_ECO_SUM
        deal['law']['struct'] = NEW_STRUCT
        deal['law']['terms'] = NEW_TERMS
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
