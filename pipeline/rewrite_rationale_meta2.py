"""Бэклог A8: ручной остаток пересказа статьи в «Цели сделки».

`fix_meta_rationale.py` чинит зачины со словом-источником («Статья…»,
«Источник…») и снимает предложения-пустышки про отсутствие консультантов.
Осталось 20 карточек, где пересказ устроен иначе и правилу не поддаётся:

  * фраза начинается с глагола, а не с существительного-источника —
    «Упомянут инвестиционный консультант…», «Сообщается только, что…»,
    «Приведены факты о…»;
  * ярлык источника приклеен так, что за ним идёт ещё один мета-зачин —
    «Публичная информация) — Статья содержит публичное сообщение о…»;
  * зачин остался в винительном падеже от прошлой чистки —
    «Неудавшуюся попытку RBI продать свою долю…».

Каждый случай свой, повторов нет — расширять регулярки под единичные формы
дороже и опаснее, чем переписать руками. Формат таблицы тот же, что в
`rewrite_rationale_manual.py`: HEAD — замена зачина, FULL — полный текст,
CLEAR — очистка. Правка применяется к обоим полям, где лежит этот текст
(`eco.rationale` и `extra`), потому что у части карточек они совпадают.

Ничего не досочинено: все факты взяты из самого поля. Где источник называл
комментатора-аналитика консультантом сделки, формулировка убрана — принцип 1
запрещает выдавать комментарий в СМИ за работу консультанта.

Запуск:
    python3 pipeline/rewrite_rationale_meta2.py            # сухой прогон
    python3 pipeline/rewrite_rationale_meta2.py --write    # записать
"""
