# id -> начало исходного текста; поле очищается целиком
CLEAR = {
    # Ничего о сделке: только то, что в статье кто-то прокомментировал сделку.
    # Комментатор — не консультант, вписывать его в карточку нельзя (принцип 1).
    'gedfd4c1e': 'Упомянут инвестиционный консультант Евгений Мичурин',
}

PLACEHOLDER = re.compile(r'^(?:—|-|не\s+раскры|публично\s+не|не\s+привлекал)', re.I)
FIELDS = (
    ('eco.rationale', lambda d: (d.get('eco') or {}).get('rationale') or '',
     lambda d, v: d['eco'].__setitem__('rationale', '—' if v is None else v)),
    ('extra', lambda d: d.get('extra') or '',
     lambda d, v: d.__setitem__('extra', '' if v is None else v)),
)


def norm(s):
    return re.sub(r'\s+', ' ', s or '').strip()


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by = {d['id']: d for d in data['deals']}
    planned, errors, skipped = [], [], []

    def fields_matching(did, prefix):
        deal = by.get(did)
        if deal is None:
            errors.append(f'{did}: сделка не найдена')
            return
        hit = False
        for name, get, set_ in FIELDS:
            if get(deal).startswith(prefix):
                hit = True
                yield deal, name, get, set_
        if not hit:
            skipped.append(f'{did}: исходного текста нет ни в одном поле '
                           f'(ожидали {prefix[:52]!r})')

    for did, (old_head, new_head) in HEAD.items():
        for deal, name, get, set_ in fields_matching(did, old_head):
            cur = get(deal)
            planned.append((did, name, 'зачин', cur,
                            (new_head + cur[len(old_head):]).strip(), set_))

    for did, (prefix, new) in FULL.items():
        for deal, name, get, set_ in fields_matching(did, prefix):
            planned.append((did, name, 'целиком', get(deal), new, set_))

    for did, prefix in CLEAR.items():
        for deal, name, get, set_ in fields_matching(did, prefix):
            planned.append((did, name, 'очистка', get(deal), None, set_))

    if errors:
        print('ОШИБКИ:')
        for e in errors:
            print('  ' + e)
        print()
    if skipped:
        print(f'пропущено (правка уже применена или текст изменился): {len(skipped)}')
        for e in skipped:
            print('  ' + e)
        print()

    kinds = collections.Counter(k for _, _, k, _, _, _ in planned)
    print(f'полей к правке: {len(planned)}  {dict(kinds)}\n')
    for did, name, kind, old, new, _ in planned:
        print(f'### {did} [{name} / {kind}]')
        print(f'  было:  {old[:150]}')
        print(f'  стало: {"(поле очищено)" if new is None else new[:150]}')

    if write:
        if errors:
            print('\nЕсть ошибки — запись отменена.')
            return 1
        for did, _, _, _, new, set_ in planned:
            set_(by[did], new)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=1, ensure_ascii=False)
        print('\nЗАПИСАНО в', PATH)
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
