# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g5013525f (Росатом купил 50% доли в «Парус электро», закрыта
11.11.2023) — бизнес вырос, синергия с «Росатомом» реализовалась не
так, как предполагал эксперт на момент сделки, структура собственности
не менялась.

Проверено лично прямым WebFetch (Коммерсантъ, 29.10.2024,
https://www.kommersant.ru/doc/7265509): «Сейчас более 1200 зарядных
станций «Парус электро» заряжает транспорт в 43 регионах России»,
«Заместитель генерального директора ООО «Парус электро» Владимир
Хлебников...» — бывший гендиректор и мажоритарный совладелец до сделки
занимает пост заместителя, не первого лица.

По данным саб-агента (не дозаверено отдельным WebFetch, но источники
именные и проверяемые): выручка выросла с 5 млрд ₽ (2023) до 6,36 млрд ₽
(2024) и 6,75 млрд ₽ (2025), при этом прибыль резко просела — с 708 млн ₽
(2023) до 167 млн ₽ (2025) (list-org.com, реестровые данные). Структура
долей (РАСУ 50%, Хлебников 25%, Павлюк 25%) не менялась. Синергия с
«Росатомом» реализовалась не в виде продажи электроэнергии или
использования батарей (как предполагал эксперт на момент сделки), а в
виде интеграции продукции «Парус электро» в системы управления АЭС:
«Продукция будет комплектоваться источниками бесперебойного питания
собственного производства "Парус электро" и вычислительным
оборудованием... по конструкторской документации АО "Росатом
Автоматизированные системы управления"» (atomic-energy.ru, 22.07.2026)
— РАСУ здесь та же компания, что выступила покупателем в 2023 году.

НЕ ВКЛЮЧЕНО: доля рынка именно «Парус электро» как производителя (в
отличие от доли «Росатом Сеть зарядных станций» как оператора, 60% в
Москве по данным марта 2026) — источники эту величину не называют,
смешивать их было бы ошибкой того же класса, что «У числа на экране два
свойства: величина и множество»; совместный проект с батарейным
подразделением (ТВЭЛ/РЭНЕРА) — саб-агент нашёл только параллельные,
не пересекающиеся публикации, общего продукта не подтверждено; сумма
сделки 2023 года по-прежнему не раскрыта нигде.

Запуск: python3 pipeline/fix_rosatom_parus_elektro_growth_and_synergy.py
        python3 pipeline/fix_rosatom_parus_elektro_growth_and_synergy.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g5013525f'

OLD_EXTRA = (
    'Сделка закрыта 11 ноября 2023 г. АО «РАСУ» (отраслевой интегратор '
    'Госкорпорации «Росатом») приобрел 50% доли в ООО «Парус электро» у '
    'владельцев Владимира Хлебникова и Дениса Павлюка, каждый из которых '
    'остался с 25% компании. После сделки структура капитала: Росатом '
    '50%, Хлебников 25%, Павлюк 25%.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Бизнес вырос: выручка поднялась до 6,75 млрд ₽ (2025), но прибыль '
    'просела до 167 млн ₽ (для сравнения — 708 млн ₽ в 2023 году). '
    'Владимир Хлебников с бывшего гендиректора и мажоритарного совладельца '
    'перешёл на пост заместителя генерального директора. Структура долей '
    'не менялась. К 2026 году «Парус электро» обслуживает более 1200 '
    'зарядных станций в 43 регионах России, а синергия с «Росатомом» '
    'проявилась в поставках оборудования для систем управления АЭС по '
    'документации АО «РАСУ».'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/7265509'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
