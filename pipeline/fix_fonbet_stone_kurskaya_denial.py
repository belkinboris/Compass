# -*- coding: utf-8 -*-
"""Фонбет/Stone Курская (`g79f683bc`): карточка несла статус «Закрыта» и
заголовок, утверждающий, что «Фонбет» купил бизнес-центр, — при этом
`law.struct` УЖЕ содержал факт, который эту версию прямо опровергает:
«В «Фонбет» опровергли информацию о покупке...». Классический пример
урока «категорическое отрицание не согласовано с соседним полем той же
карточки» (REVISION_BRIEF.md, «Шаг 0», пункт 6) — отрицание было верно
записано, но не изменило ни статус, ни заголовок, ни `extra`, которые
продолжали утверждать закрытую сделку.

Полная хронология, установленная прямым чтением всех четырёх источников
карточки (даты публикации решают, что было раньше):
  1. 01.10.2025, 06:30 — Коммерсантъ со ссылкой на ТРИ анонимных
     источника на рынке недвижимости сообщил о покупке; ни девелопер
     Stone, ни сам «Фонбет» на момент публикации это не подтвердили.
  2. 01.10.2025, 07:46 — cre.ru: в Stone подтвердили, что покупателем,
     по всей видимости, станет ГРУППА ЧАСТНЫХ ИНВЕСТОРОВ (не «Фонбет»),
     переговоры на финальной стадии, имя не раскрыто.
  3. 02.10.2025 — Коммерсантъ дописал в тот же материал: управляющий
     акционер Fonbet Валентин Голованов ОФИЦИАЛЬНО ОПРОВЕРГ информацию.
  4. 02–03.10.2025 — sports.ru и повторно РИА Недвижимость передают то
     же опровержение.
  5. 12.02.2026 — рекламная статья самого Stone (Коммерсантъ) описывает
     здание как «единственное… готовое офисное здание в ЦАО, доступное
     как к покупке, так и аренде целиком» — то есть спустя 4+ месяца
     видимого подтверждения продажи КОМУ-ЛИБО по-прежнему нет.

Ни один источник не подтверждает закрытие сделки — ни с «Фонбет», ни с
«группой частных инвесторов». Правка меняет статус на «Не состоялась»
(для версии с «Фонбет», которую несла карточка), переписывает заголовок
и `extra` на честную хронологию слуха и опровержения, дополняет
`law.struct` полным текстом опровержения и версией об инвесторах,
заменяет `eco.val` дословной атрибуцией экспертных оценок. Дата смены
статуса `date_is_supported()`/`status`-проверка `review.py` для такого
масштаба правки не годится (денежный `sum` и статус меняются вместе,
источник денежной оценки — сторонний эксперт, а не подтверждение
сделки) — правка разовым скриптом, с собственными `assert` на исходное
состояние каждого поля.

Запуск: python3 pipeline/fix_fonbet_stone_kurskaya_denial.py           # проверка
        python3 pipeline/fix_fonbet_stone_kurskaya_denial.py --write   # запись
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g79f683bc'

OLD_TITLE = 'Фонбет приобрел бизнес-центр Stone Курская у девелопера Stone Hedge'
NEW_TITLE = 'Фонбет опроверг покупку бизнес-центра Stone Курская у Stone Hedge'

OLD_STATUS = 'Закрыта'
NEW_STATUS = 'Не состоялась'

OLD_SUM = '5–7 млрд ₽'
NEW_SUM = '5–7 млрд ₽ (по оценке)'

OLD_ECO_VAL = ('Консультанты оценили сделку по покупке бизнес-центра в '
               '5–7 миллиардов рублей.')
NEW_ECO_VAL = ('Заместитель коммерческого директора по вопросам '
               'развития Business Club Михаил Иоаннесянц оценивает '
               'сделку по покупке «Stone Курская» в 5–7 млрд руб., '
               'руководитель департамента по работе с офисными '
               'помещениями IBC Real Estate Екатерина Белова — в 6,5 '
               'млрд руб.')

OLD_LAW_STRUCT = ('В «Фонбет» опровергли информацию о покупке '
                   'бизнес-центра «Stone Курская» в центре Москвы.')
NEW_LAW_STRUCT = OLD_LAW_STRUCT + (
    ' «Компания «Фонбет» занимается сугубо букмекерской деятельностью и '
    'никогда не рассматривала для себя инвестиции в коммерческую '
    'недвижимость или иной род занятий… Текущий офис компании на '
    'сегодняшний день полностью удовлетворяет всем нашим потребностям», '
    '— отметил господин Голованов. Как сообщили в Stone, переговоры '
    'ведутся с группой частных инвесторов. Участие в сделке «Фонбет» в '
    'компании не подтвердили.')

OLD_EXTRA = (
    'Закрытая в 2025 году сделка покупки бизнес-центра класса А '
    'площадью 15,6 тыс. кв. м с офисными помещениями и ритейлом. Объект '
    'находится на этапе строительства, ввод в эксплуатацию запланирован '
    'на 2026 год. Фонбет планирует разместить в комплексе '
    'штаб-квартиру.')
NEW_EXTRA = (
    '1 октября 2025 года Коммерсантъ со ссылкой на три источника на '
    'рынке недвижимости сообщил, что «Фонбет» выкупил строящийся '
    'бизнес-центр класса А «Stone Курская» (15,6 тыс. кв. м, ввод в '
    'эксплуатацию запланирован на 2026 год) — на момент публикации ни '
    'девелопер Stone, ни сам «Фонбет» это не подтвердили. На следующий '
    'день управляющий акционер Fonbet Валентин Голованов официально '
    'опроверг информацию, заявив, что компания никогда не рассматривала '
    'инвестиции в коммерческую недвижимость и её текущий офис полностью '
    'удовлетворяет её потребностям. По данным Stone, переговоры о '
    'продаже здания велись с группой частных инвесторов, чьё имя не '
    'раскрывалось. По состоянию на февраль 2026 года здание '
    'по-прежнему рекламировалось девелопером как доступное к покупке '
    'целиком — независимого подтверждения закрытия сделки с кем-либо не '
    'появилось.')

NEW_SRCS = [
    ['РИА Недвижимость', 'https://realty.ria.ru/20251003/'
     'fonbet-2046224560.html'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8422162'],
]


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    card = next((c for c in data['deals'] if c['id'] == CARD_ID), None)
    assert card is not None, '%r не найдена в базе' % CARD_ID
    assert card.get('title') == OLD_TITLE, 'title изменился: %r' % card.get('title')
    assert card.get('status') == OLD_STATUS, 'status изменился: %r' % card.get('status')
    assert card.get('sum') == OLD_SUM, 'sum изменился: %r' % card.get('sum')
    assert card['eco'].get('sum') == OLD_SUM, 'eco.sum изменился: %r' % card['eco'].get('sum')
    assert card['eco'].get('val') == OLD_ECO_VAL, 'eco.val изменился: %r' % card['eco'].get('val')
    assert card['law'].get('struct') == OLD_LAW_STRUCT, (
        'law.struct изменился: %r' % card['law'].get('struct'))
    assert card.get('extra') == OLD_EXTRA, 'extra изменился: %r' % card.get('extra')
    src = card.setdefault('src', [])
    print('ЧИНИМ   %s: status «Закрыта» -> «Не состоялась» (сделка опровергнута)' % CARD_ID)
    print('ЧИНИМ   %s: title — заголовок утверждал опровергнутый факт' % CARD_ID)
    print('ПРАВИМ  %s: sum/eco.sum — пометка «(по оценке)»' % CARD_ID)
    print('ПРАВИМ  %s: eco.val — дословная атрибуция экспертных оценок' % CARD_ID)
    print('ПРАВИМ  %s: law.struct — полный текст опровержения и версия про инвесторов' % CARD_ID)
    print('ПРАВИМ  %s: extra — честная хронология слуха и опровержения' % CARD_ID)
    if write:
        card['title'] = NEW_TITLE
        card['status'] = NEW_STATUS
        card['sum'] = NEW_SUM
        card['eco']['sum'] = NEW_SUM
        card['eco']['val'] = NEW_ECO_VAL
        card['law']['struct'] = NEW_LAW_STRUCT
        card['extra'] = NEW_EXTRA
        for s in NEW_SRCS:
            if s not in src:
                src.append(s)
        json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
        print('ЗАПИСАНО')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
