# -*- coding: utf-8 -*-
"""Карточка `ga133cd89` («VK ведет переговоры о покупке Intickets.ru и доли
в «Кассир.ру»») несла заголовок и часть полей стадии переговоров (ноябрь
2023), хотя `batch_c_rev09.py` уже перевёл статус в «Закрыта» — обе сделки
реально закрылись в 2024 году, но не так, как обсуждалось.

ЧТО СЛОМАНО. Ревизия (партия batch_c_rev09, саб-агент по этой карточке)
нашла: сделка по Intickets.ru закрылась 3 мая 2024 года НЕ на 100%, а на
40% (kommersant.ru/doc/6686839); доля в «Кассир.ру» закрылась отдельно,
2 октября 2024 года, НЕ на неопределённом пакете, а на 10%
(1prime.ru/20241002/dolya-851916722.html). `review.py` уже обновил
`status`/`sum`/`eco.sum`/`extra` (поля, ранее свободные от правок фазы 1),
но `title` и `eco.share`/`eco.val` — уже занятые фазой 1
(`batch_c_2023.py`) или вообще не редактируемые через `review.py`
(`title`) — остались описывать стадию переговоров: заголовок буквально
говорит «ведет переговоры», а карточка при этом стоит «Закрыта».

ПОЧЕМУ НЕ ЧЕРЕЗ `review.py`. `title` не редактируется через `review.py`
вовсе (нет такого поля в механизме). `eco.share`/`eco.val` уже несут
записи в `batch_c_2023.py` — `test_no_duplicate_fix_for_one_field`
запрещает вторую запись на то же поле даже из другого файла. Правки
логически одна («сделка на самом деле закрылась не так, как обсуждалось,
и в двух разных датах 2024 года») — собраны в один одноразовый скрипт
с проверкой исходного состояния, тот же приём, что `fix_adamas_slh_
closing.py`.

Источники: kommersant.ru/doc/6686839 (закрытие Intickets, 40%, ~800 млн ₽),
1prime.ru/20241002/dolya-851916722.html (закрытие доли «Кассир.ру», 10%,
~500 млн ₽) — оба уже в `src` карточки после `batch_c_rev09.py`.

Запуск: без аргументов — сухой прогон, `--write` — запись.
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'
DEAL_ID = 'ga133cd89'

OLD_TITLE = 'VK ведет переговоры о покупке Intickets.ru и доли в «Кассир.ру»'
NEW_TITLE = 'VK купила 40% Intickets.ru и 10% доли в «Кассир.ру»'

OLD_SHARE = ('Intickets.ru на 100% перейдет VK, сделка должна быть закрыта '
             'до конца года. С «Кассир.ру» «еще идут переговоры»')
NEW_SHARE = ('В итоге VK закрыла две отдельные сделки: 40% ООО «Интикетс» '
             '(3 мая 2024 года) и 10% ООО «Кассир.ру — национальный '
             'билетный оператор» (2 октября 2024 года) — вместо '
             'обсуждавшихся в ноябре 2023 года 100% Intickets.ru и '
             'неопределённого пакета «Кассир.ру».')

OLD_VAL = ('По оценке собеседника “Ъ” в одной из билетных платформ, '
           'Intickets в рамках сделки может быть оценен в 1 млрд руб., а '
           '«Кассир.ру» вместе с Radario, Parter.ru и PMI — в 6 млрд руб.')
NEW_VAL = ('Это была оценка ДО сделки, на предполагаемые 100% Intickets и '
           'неопределённый пакет «Кассир.ру» с Radario, Parter.ru и PMI. '
           'Реально закрытые сделки — 40% Intickets (вся компания оценена '
           '«Ъ» в ~2 млрд ₽, сделка — ~800 млн ₽) и 10% «Кассир.ру» '
           '(~500 млн ₽) — см. `sum`/`eco.sum`.')


def main(write):
    data = json.load(open(DATA, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['title'] == OLD_TITLE, 'заголовок уже другой'
    assert deal['eco']['share'] == OLD_SHARE, 'eco.share уже другой'
    assert deal['eco']['val'] == OLD_VAL, 'eco.val уже другой'
    assert deal['status'] == 'Закрыта', ('status ожидался «Закрыта» — '
                                          'запускать после batch_c_rev09')

    print('%s: заголовок и eco.share/eco.val ещё описывали стадию '
          'переговоров при статусе «Закрыта»' % DEAL_ID)
    print('  title: %r -> %r' % (OLD_TITLE, NEW_TITLE))
    print('  eco.share обновлён на факт двух отдельных закрытий')
    print('  eco.val обновлён — старая оценка помечена как «до сделки»')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    deal['title'] = NEW_TITLE
    deal['eco']['share'] = NEW_SHARE
    deal['eco']['val'] = NEW_VAL

    assert deal['title'] == NEW_TITLE, 'заголовок не записался'

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
