# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g56e609e3
(Metsä Group продала лесопромышленные активы в Ленинградской области
группе «Вологодские лесопромышленники») — карточка держалась на
Telegram-агрегаторе (@dealsma), а не на первоисточнике. Проверено лично
прямым WebFetch трёх источников.

1) `src` (дополнено) — настоящий первоисточник, деловое СМИ. Коммерсантъ
(Санкт-Петербург), «Metsa обрубила актив в Ленобласти», 15.05.2024:
https://www.kommersant.ru/doc/6692044 — независимо подтверждает почти
все факты карточки. Дословно про дату: «учредителями обеих компаний с
8 мая 2024 года указано ООО «УК ВЛП»» — совпадает с `date` карточки.

2) `eco.val` (новое поле) — независимая оценка суммы. Дословно:
«Генеральный директор агентства «Infoline-Аналитика» Михаил Бурмистров
предполагает, что цена продажи активов могла составить до €10 млн с
учетом дисконта».

3) `eco.context` (дополнено) — юрлица предмета сделки и планы по заводу.
Дословно: «В периметр сделки вошли ООО «Мється Свирь» и ООО «Мється
Форест Подпорожье» с арендной базой, лесозаготовительными операциями и
лесопильным заводом»; план — «обеспечить возможность производства
полного цикла уже летом текущего года», препятствие — «восстановление
инженерных сетей и котельного оборудования».

4) `eco.context` (дополнено) — статус на 2025 год. Официальный блог ВЛП,
июль 2025: «Спустя ровно год оба производственных актива практически
вышли на докризисные объемы»; «С января текущего года лесопильный
передел завода работает уже в две смены, это его базовый проектный
режим».
https://vlp.eco/en/vlp-i-rukovodstvo-lenoblasti-primer-jeffektivnogo-vzaimodejstvija-biznesa-i-vlasti/

НЕ ВКЛЮЧЕНО: «Красный Север» (22.05.2024) называет ЧЕТЫРЕ юрлица в
периметре («Мється Свирь», «Мється Форест Санкт-Петербург», «Мється
Форест Подпорожье», «Мється Борд Рус»), а Коммерсантъ — только ДВА;
расхождение не разрешено, в карточку идёт только то, что подтверждает
основной источник (Коммерсантъ); консультанты сделки — не найдены ни в
одном из ~10 просмотренных источников; точная дата одобрения ФАС/
правкомиссии — везде только «одобрили сделку» без числа.

Запуск: python3 pipeline/fix_metsa_vlp_real_source_and_progress.py
        python3 pipeline/fix_metsa_vlp_real_source_and_progress.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g56e609e3'

OLD_CONTEXT = (
    'Последние 1–1,5 года лесопильный завод был законсервирован, а '
    'лесозаготовительные работы практически не проводились.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' В периметр сделки вошли ООО «Мється Свирь» и ООО «Мється Форест '
    'Подпорожье» с арендной базой, лесозаготовительными операциями и '
    'лесопильным заводом (Коммерсантъ). Планировалось «обеспечить '
    'возможность производства полного цикла уже летом текущего года» — '
    'препятствием было «восстановление инженерных сетей и котельного '
    'оборудования». По данным ВЛП на июль 2025 года, «спустя ровно год '
    'оба производственных актива практически вышли на докризисные '
    'объемы», а «с января текущего года лесопильный передел завода '
    'работает уже в две смены, это его базовый проектный режим».'
)

OLD_VAL = '—'
NEW_VAL = (
    'Независимая оценка: «Генеральный директор агентства «Infoline-'
    'Аналитика» Михаил Бурмистров предполагает, что цена продажи активов '
    'могла составить до €10 млн с учетом дисконта» (Коммерсантъ).'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6692044'],
    ['vlp.eco', 'https://vlp.eco/en/vlp-i-rukovodstvo-lenoblasti-primer-jeffektivnogo-vzaimodejstvija-biznesa-i-vlasti/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    assert deal['eco']['val'] == OLD_VAL
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== eco.val: станет ===')
    print(NEW_VAL)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['eco']['val'] = NEW_VAL
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
