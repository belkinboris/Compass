import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gf219222a'

OLD_LAW_STRUCT = '—'
NEW_LAW_STRUCT = (
    'Российский бизнес (ООО «Адаптивные технологии безопасности»,'
    ' переименован в F.A.C.C.T.) и международный (Group-IB Global'
    ' Private Ltd., Сингапур) — РАЗНЫЕ юрлица с разным составом'
    ' совладельцев: в российском Сачков сохранил 37,5% (остальное —'
    ' «Альтера Капитал» 25%, Алексей Козырев 15%, «Киберинвест» 12,5%,'
    ' Валерий Баулин 10%), а свои 37,5% в сингапурском юрлице продал'
    ' отдельно, членам высшего руководства компании (детали не'
    ' раскрывались). Управление международным бизнесом перешло к'
    ' Дмитрию Волкову.'
)

OLD_ECO_CONTEXT = (
    'До июля 2022 года 40% выручки компании приходилось на Россию, '
    '60% – на международный бизнес'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + '. В феврале 2025 года фонд «Сайберус» закрыл'
    ' сделку по покупке технологий, интеллектуальной собственности и'
    ' действующих контрактов F.A.C.C.T. — они перешли новой компании'
    ' F6, гендиректором которой стал Валерий Баулин; прежние акционеры'
    ' F.A.C.C.T., включая Сачкова, в состав совладельцев F6 не вошли.'
)

NEW_SRC = [
    ['ComNews', 'https://www.comnews.ru/content/237808/2025-02-17/2025-w08/1010/facct-perevoplotilsya-f6'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['law']['struct'] == OLD_LAW_STRUCT
    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    existing_urls = {s[1] for s in deal['src']}
    add_src = [s for s in NEW_SRC if s[1] not in existing_urls]
    new_src = deal['src'] + add_src

    print('=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    if add_src:
        print('\n=== src: добавится ===')
        for s in add_src:
            print(s)

    if write:
        deal['law']['struct'] = NEW_LAW_STRUCT
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
