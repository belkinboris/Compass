# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g5405b876 (ГК «Агама» выкупила долю Royal Greenland в ООО «Агама Роял
Гринланд», 15.12.2023, статус «Закрыта») — сам покупатель этой доли
меньше чем через полгода был продан целиком другой компании, а
юрлицо-предмет карточки позже прекратило существование через
реорганизацию.

Продажа ГК «Агама» — проверено лично прямым WebFetch (Ведомости,
31.05.2024): «Федеральная антимонопольная служба (ФАС) России
согласовала ходатайство импортера рыбы и морепродуктов «Юнифрост» о
покупке группы компаний «Агама»» — продавцы, прежние владельцы Юрий
Алашеев и Игорь Лысенков, сумма не раскрыта. Согласование ФАС
относится к ЭТОЙ более поздней, отдельной сделке (продажа всей группы
«Агама» «Юнифросту»), а не к сделке 2023 года с Royal Greenland,
которой посвящена карточка, — записано в `law.appr` с явной оговоркой,
а не в прозе `extra`, тем же приёмом, что уже применён к g87d0201c
(«Воркутауголь»/АЕОН), чтобы не создавать у `test_approval_is_not_left_in_prose`
ложное впечатление о неописанном согласовании собственной сделки
карточки.

Ликвидация юрлица-предмета — по данным саб-агента (rusprofile/
synapsenet, ЕГРЮЛ, не дозаверено отдельным WebFetch): ООО «Агама Роял
Гринланд» ликвидировано 12 февраля 2026 года путём присоединения к
ООО «Агама Истра» — внутренняя консолидация структуры группы, а не
остановка производства (площадка в Лешково продолжает работать).

НЕ ВКЛЮЧЕНО: сумма сделки с «Юнифростом», реализация плана роста
мощностей на 50% к 2025 году, показатели Royal Greenland на других
рынках после ухода из России — по данным саб-агента без прямой
дословной цитаты профильного издания, не дозаверено; продажа
мурманской фабрики группы («Рыбные мануфактуры») компании «Вирма» —
отдельный, не связанный с этой карточкой актив.

Запуск: python3 pipeline/fix_agama_sold_to_unifrost_postdeal.py
        python3 pipeline/fix_agama_sold_to_unifrost_postdeal.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g5405b876'

OLD_EXTRA = (
    'Закрытая сделка. ГК «Агама» выкупила 50% долей ООО «Агама Роял '
    'Гринланд», которые ранее принадлежали Royal Greenland. Вторые '
    '50% уже были в собственности «Агамы». Royal Greenland прекратила '
    'поставки в РФ после начала военных действий на Украине.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Меньше чем через полгода сама ГК «Агама» сменила владельца — '
    'покупателем выступил импортёр «Юнифрост» (согласование см. '
    '«Согласования» ниже). Юрлицо-предмет этой карточки, ООО «Агама '
    'Роял Гринланд», позже прекратило существование: 12 февраля 2026 '
    'года оно присоединено к ООО «Агама Истра» — внутренняя '
    'консолидация структуры группы, производство на площадке '
    'продолжается.'
)

OLD_LAW_APPR = 'Публично не сообщалось'
NEW_LAW_APPR = (
    'В мае 2024 года ФАС согласовала покупку ГК «Агама» импортёром '
    '«Юнифрост» у прежних владельцев Юрия Алашеева и Игоря Лысенкова '
    '— это согласование относится к более поздней, отдельной сделке '
    '(продажа всей группы), а не к сделке 2023 года с Royal '
    'Greenland, которой посвящена эта карточка.'
)

NEW_SRC = [
    ['Ведомости', 'https://www.vedomosti.ru/business/news/2024/05/31/1040690-fas-razreshila-prodazhu-yunifrostu-proizvoditelya'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA
    assert deal['law']['appr'] == OLD_LAW_APPR

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== law.appr: станет ===')
    print(NEW_LAW_APPR)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['law']['appr'] = NEW_LAW_APPR
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
