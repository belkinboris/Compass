import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g9876feaa'
OLD_CONTEXT = (
    'Этот предприниматель, судя по всему, занимается арендным бизнесом '
    'в Санкт-Петербурге. По крайней мере, его компании «Коломяги» '
    'принадлежат права на участок на Новоорловской улице (рядом с '
    'Суздальским озером) под строительство магазина. Правда, из '
    'протокола следует, что он действует в интересах некой Светланы '
    'Железновой. О ней ничего не известно.'
)
ADDITION = (
    'Независимо от этой версии, издание «Царьград» предполагало, что '
    '«Аквилон» мог быть приобретен в пользу башкирского застройщика '
    '«Башстройсервис» в целях выхода на подмосковный рынок — то есть '
    'вопрос о конечном бенефициаре у разных источников решается '
    'по-разному, а не просто остаётся открытым. Здание законсервировано '
    'с 2010 года из-за трещины в фундаменте.'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} eco.context: += альтернативная версия "
          "бенефициара и статус здания")
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
