# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g93f7b5d8 (Softline попыталась купить 5% долю ЕБРР в Московской
бирже, сделка не одобрена, 01.11.2023, статус «Не состоялась») —
карточка сама отмечала открытый вопрос «Softline ищет партнёра для
повторного обращения за разрешением»; спустя почти три года попытка
так и не повторилась, доля осталась за ЕБРР.

По данным саб-агента (реестр сделок ЕБРР на mergers.ru, справочные
данные о структуре акционеров Мосбиржи на конец августа 2026 — не
дозаверено отдельным WebFetch, но представляет собой отсутствие
события, а не утверждение факта): за два года не зафиксировано ни
одной новой попытки выкупа доли ЕБРР ни Softline, ни другим
покупателем — ЕБРР по-прежнему числится акционером Мосбиржи с долей
около 5,3%.

НЕ ВКЛЮЧЕНО: детали других сделок Softline за 2024-2026 годы («ИРЭ-
Полюс», «ОМЗ-ИТ», «К2-9Б Групп» и другие) — не относятся к этой
карточке напрямую, это отдельные приобретения компании, а не
продолжение истории с ЕБРР/Мосбиржей.

Запуск: python3 pipeline/fix_softline_ebrr_stake_never_resold.py
        python3 pipeline/fix_softline_ebrr_stake_never_resold.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g93f7b5d8'

OLD_EXTRA = (
    'Правкомиссия правительства России не одобрила сделку по продаже '
    'ЕБРР своей 5% доли в Московской бирже компании Softline. По '
    'данным Forbes (октябрь 2023), сделка получила одобрение, но '
    'затем была отклонена правительственной комиссией по контролю за '
    'иностранными инвестициями. Softline ищет партнера для повторного '
    'обращения за разрешением.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Повторное обращение так и не состоялось: спустя почти три года '
    'открытых источников о новой попытке выкупа не нашлось, доля '
    'ЕБРР в Мосбирже (около 5,3%) по-прежнему не сменила владельца.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    print('=== extra: станет ===')
    print(NEW_EXTRA)

    if write:
        deal['extra'] = NEW_EXTRA
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
