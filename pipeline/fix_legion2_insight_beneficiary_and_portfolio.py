import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g8fb922a6'

OLD_EXTRA = 'Консультанты оценили рыночную стоимость комплекса в 7–10 млрд руб.'
NEW_EXTRA = OLD_EXTRA + (
    ' Бенефициар «Инсайт» — Авет Миракян, бывший гендиректор холдинга '
    'SFI (контролируется Саидом Гуцериевым), покинувший пост в июле '
    '2022 года и создавший «Инсайт» с командой бывших коллег. Помимо '
    '«Легион II» «Инсайт» выкупил и другие активы ушедших западных '
    'компаний (в том числе лизинговый бизнес Siemens, переименованный '
    'в «ДельтаЛизинг»). Крупный арендатор здания — структура «Ростеха» '
    '«Технодинамика» (около 9,5 тыс. кв. м). В июле 2024 года Миракян '
    'попал под санкции Великобритании и продал свою долю в «Инсайт».'
)

NEW_SRC = [
    ['Versia.ru', 'https://versia.ru/avet-mirakyan-vyshel-iz-sovetov-direktorov-gruppy-m-video-yeldorado-i-investicionnogo-xoldinga-sfi'],
    ['CRE.ru', 'https://cre.ru/news/92234'],
    ['1Prime', 'https://1prime.ru/20241228/insayt-853928007.html'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
