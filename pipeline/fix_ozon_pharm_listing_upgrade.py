# -*- coding: utf-8 -*-
"""Месячная очередь, 9 сентября 2026 — дочитывание карточки `g09f78960`
(«"Озон Фармацевтика" завершила SPO дополнительным выпуском акций по
схеме top-up», добавлена в базу 3 августа 2026, полностью обыскана в тот
же день).

Дельта-поиск (саб-агент + личная проверка) подтвердил, что перспектива,
уже названная в карточке («открывает дорогу в Первый уровень листинга»),
сбылась — Московская биржа перевела акции в первый уровень листинга.
Личный WebFetch (interfax.ru/business/1051835) подтвердил: биржа
«приняла решение с 13 октября перевести обыкновенные акции ПАО «Озон
Фармацевтика» из раздела «второй уровень» в раздел «первый уровень»
списка ценных бумаг, допущенных к торгам» — решение принято 9 октября
2025 года, вступило в силу 13 октября 2025 года.

Включение в Индекс Мосбиржи, названное в той же фразе карточки как
перспектива, по состоянию на сентябрь 2026 года НЕ произошло (проверено
саб-агентом) — эта часть формулировки остаётся честной перспективой, а
не фактом, и не меняется.

Организатор/андеррайтер SPO по-прежнему нигде не назван (проверено
Коммерсантъ, Forbes, РБК, специализированным трекером preqveca.ru и
официальным пресс-релизом компании) — карточка права, что оставляет его
как есть.

Запуск:
    python3 pipeline/fix_ozon_pharm_listing_upgrade.py            # сухой прогон
    python3 pipeline/fix_ozon_pharm_listing_upgrade.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_ECO_RATIONALE = (
    'SPO стало первой крупной сделкой на российском рынке акционерного '
    'капитала в 2025 году и укрепило позиции ПАО «Озон Фармацевтика» '
    'среди эмитентов фармацевтического сектора. Рост доли акций в '
    'свободном обращении открывает компании дорогу в Первый уровень '
    'листинга и Индекс Московской биржи.'
)
NEW_ECO_RATIONALE = OLD_ECO_RATIONALE + (
    ' 9 октября 2025 года Московская биржа приняла решение перевести '
    'акции компании из второго уровня листинга в первый — решение '
    'вступило в силу 13 октября 2025 года; включения в Индекс Московской '
    'биржи по состоянию на сентябрь 2026 года ещё не произошло.'
)

NEW_SRC = ['Интерфакс', 'https://www.interfax.ru/business/1051835']


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['g09f78960']

    assert d['eco']['rationale'] == OLD_ECO_RATIONALE, \
        'g09f78960 eco.rationale уже другой: %r' % (d['eco']['rationale'],)
    urls = {s[1] for s in d['src']}
    assert NEW_SRC[1] not in urls, 'источник уже добавлен'

    print('g09f78960: eco.rationale дополнен (перевод в первый уровень '
          'листинга); добавлен источник interfax.ru')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['eco']['rationale'] = NEW_ECO_RATIONALE
    d['src'].append(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
