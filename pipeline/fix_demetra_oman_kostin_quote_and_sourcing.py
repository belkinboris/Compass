# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка ged59a2eb
(«Оманский инвестфонд инвестировал в Деметра-холдинг через
допэмиссию») — три отдельных дефекта, найденных при дочитывании:

1. `eco.context` нёс дословный, но ОБОРВАННЫЙ фрагмент цитаты — «Цена
   объективная, маржа приличная» — без единого слова о том, кто это
   сказал и о какой сделке. На экране это бессмысленный обрывок; в
   источнике (Новая газета Европа) это конец фразы главы ВТБ Андрея
   Костина о выходе банка из зернового бизнеса.
2. `extra` начинался словами «Канал Dealsma публикует информацию о
   сделке» — служебное упоминание внутреннего telegram-агрегатора
   попало в текст, который видит читатель (запрещено правилом «Язык
   для людей» в CLAUDE.md).
3. Факты о российских совладельцах (Marathon Group, АО «Гранум»)
   стояли в `extra` без источника в `src` — они не из уже подключённого
   Коммерсанта, а из другой статьи, которая в `src` не значилась вовсе.

Проверено лично прямым WebFetch (Новая газета Европа,
https://novayagazeta.eu/articles/2023/08/10/spetsoperatsiia-s-privlecheniem-omana):
«"Мы вышли из зернового бизнеса. У нас была доля в "Деметра-холдинге",
меньше контроля, там около 45%. Мы ее реализовали. На днях сделку
закрыли. Не могу сказать, кто покупатель, — это его право заявлять о
себе. Цена объективная, маржа приличная", — ... глава ВТБ» (Андрей
Костин); «в июле 2023 года ВТБ продал 45% "Деметра-холдинг" компании
Southern Sea Investment LLC, которая действует в интересах
инвестиционного фонда государства Оман»; «В 2020 году 27,5% акций
"Деметра-холдинг" перешли АО "Гранум", аффилированному с... Теймуразом
Боллоевым; ещё 27,5% — Marathon Group, которую связывают с... Александром
Винокуровым».

НЕ ВКЛЮЧЕНО: связь Боллоева с Владимиром Путиным и Винокурова с Сергеем
Лавровым (зять) — источник называет обе связи, но это характеристика
СВЯЗАННЫХ ЛИЦ, а не условие или сторона самой сделки с оманским фондом;
не относится к тому, что показывает карточка M&A-сделки. Размер доли
Southern Sea Investment LLC по-прежнему не раскрывается ни одним
источником.

Запуск: python3 pipeline/fix_demetra_oman_kostin_quote_and_sourcing.py
        python3 pipeline/fix_demetra_oman_kostin_quote_and_sourcing.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'ged59a2eb'

OLD_ECO_CONTEXT = 'Цена объективная, маржа приличная'
NEW_ECO_CONTEXT = (
    'Глава ВТБ Андрей Костин так прокомментировал продажу: «Мы вышли '
    'из зернового бизнеса. У нас была доля в «Деметра-холдинге», меньше '
    'контроля, там около 45%. Мы её реализовали. На днях сделку '
    'закрыли. Не могу сказать, кто покупатель, — это его право '
    'заявлять о себе. Цена объективная, маржа приличная».'
)

OLD_EXTRA = (
    'Канал Dealsma публикует информацию о сделке. Southern Sea '
    'Investment LLC (оманская компания, бенефициар государственного '
    'инвестфонда Омана) является якорным инвестором в допэмиссию '
    'Деметра-холдинга. ВТБ ранее владел 45% компании. Российские '
    'владельцы (Marathon Group, АО Гранум и другие) также участвуют в '
    'расширении доли через допэмиссию. Размер доли Southern Sea '
    'Investment LLC и точные доли других участников не раскрываются.'
)
NEW_EXTRA = (
    'Southern Sea Investment LLC (оманская компания, действующая в '
    'интересах государственного инвестфонда Омана) стала якорным '
    'инвестором в допэмиссию «Деметра-холдинга», выкупив долю ВТБ '
    '(45%). Среди российских совладельцев компании — АО «Гранум» '
    '(27,5%) и Marathon Group (27,5%), получившие свои доли ещё в '
    '2020 году. Размер доли Southern Sea Investment LLC и точные доли '
    'участников после допэмиссии не раскрываются.'
)

NEW_SRC = [
    ['Новая газета Европа', 'https://novayagazeta.eu/articles/2023/08/10/spetsoperatsiia-s-privlecheniem-omana'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
