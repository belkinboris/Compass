# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка gcef50cb7
(Моторика привлекла 900 млн руб. финансирования). Карточка не называла
инвестора вовсе — источник ворот (vc.ru) на тот момент честно писал, что
имя не раскрывается, но оно раскрылось позже, в отчётности самой
компании. Проверено лично прямым WebFetch.

1) `buyer_name` (новое поле, текстом) — годовой отчёт «Моторики» за 2024
год, дословно: «Компания привлекла 900 млн руб. от стратегического
инвестора АО УК «Первая», который специализируется на управлении
активами и предоставлении инвестиционных услуг».
Источник: https://ar2024.motorica.org/ru/performance-review/financial-review

2) `eco.context` — на что пошли деньги и как компания выросла дальше.
Тот же отчёт, дословно: «Поступления от финансирования частично были
направлены на покупку ООО «Завод специального оборудования»,
расширение производственных мощностей, развитие и выход на
международные рынки» — сделка подтверждена независимо (ComNews,
27.12.2024): «Моторика» (через «Хомо Ауктус») купила 50,1% ООО «Завод
специального оборудования» (производитель инвалидных колясок), дата по
ЕГРЮЛ — 24 декабря 2024, сумма официально не раскрыта. Дальнейший рост:
Ведомости (04.05.2026), дословно: «Консолидированная выручка группы в
прошлом году увеличилась на 70% в годовом выражении и достигла 7,1 млрд
руб.»

НЕ ВКЛЮЧЕНО: сделка ЗПИФ «Первая — прямые инвестиции» (10,16% в «Хомо
Ауктус», Коммерсантъ, 04.10.2024, оценка Dsight ~500 млн ₽) — это,
возможно, тот же процесс привлечения капитала, увиденный по частям, но
суммы (900 против ~500 млн ₽) и юрлица (ООО «Моторика» против «Хомо
Ауктус») не совпадают напрямую; сливать эти факты в один без более
явного подтверждения значило бы гадать, поэтому оставлено как отдельное
наблюдение, не перенесённое в карточку. Условия финансирования (кредит/
облигации/доля) и консультанты — не названы ни в одном источнике.

Запуск: python3 pipeline/fix_motorika_investor_and_progress.py
        python3 pipeline/fix_motorika_investor_and_progress.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gcef50cb7'

NEW_BUYER_NAME = 'АО УК «Первая»'

OLD_CONTEXT = (
    'Основанная в 2014 году «Моторика» разрабатывает и производит '
    'функциональные протезы рук для взрослых и детей. В 2016-м компания '
    'стала резидентом «Сколково», а в 2022-м — прибыльной и открыла '
    'направление нейротехнологий.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' «Поступления от финансирования частично были направлены на '
    'покупку ООО «Завод специального оборудования», расширение '
    'производственных мощностей, развитие и выход на международные '
    'рынки» (годовой отчёт «Моторики» за 2024 год) — сделка (50,1%,'
    ' производитель инвалидных колясок) подтверждена независимо '
    '(ComNews, дата по ЕГРЮЛ 24 декабря 2024, сумма не раскрыта). '
    '«Консолидированная выручка группы в прошлом году увеличилась на '
    '70% в годовом выражении и достигла 7,1 млрд руб.» (Ведомости, '
    '04.05.2026).'
)

NEW_SRC = [
    ['ar2024.motorica.org', 'https://ar2024.motorica.org/ru/performance-review/financial-review'],
    ['ComNews', 'https://www.comnews.ru/content/237026/2024-12-27/2024-w52/1010/motorika-priobrela-501-doli-ooo-zavod-specialnogo-oborudovaniya'],
    ['Ведомости', 'https://www.vedomosti.ru/investments/news/2026/05/04/1194999-pribil-motoriki'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal.get('buyer_name') is None
    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print(f'=== buyer_name (новое поле): станет {NEW_BUYER_NAME!r} ===')
    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['buyer_name'] = NEW_BUYER_NAME
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
