# -*- coding: utf-8 -*-
"""Дневная очередь (REVISION_BRIEF, первый уровень — полный обыск),
карточка gabdbe320 (Петербургский логистический холдинг «ЮСТА» приобрел
кондитерскую фабрику в Кронштадте): у покупателя ещё нет профиля компании
(«ЮСТА» стоит текстом в `buyer_name`), а `eco.context` знал только
описание предмета сделки — не самого покупателя. Дельта-поиск нашёл
масштаб бизнеса ЮСТА, подтверждено лично прямым WebFetch (career.habr.com,
собственная страница компании на HR-платформе).

«Количество торговых точек, которые мы обслуживаем: СПБ и ЛО — 2 500,
другие города СЗФО — 3 000», «Общая площадь складского хозяйства 19 800
м2», «96 грузовых автомобилей», «Более 200 тонн продукции отгружается
клиентам ежедневно».

НЕ включены (не прошли проверку дословной цитатой при личном WebFetch —
usta.group и usta-spb.ru блокируют запрос, доступны только через
поисковые сниппеты): история названия компании (по инициалам
основателей), год основания (1995 против даты регистрации юрлица 2013),
предположение об омониме «Балтийский Берег» у продавца. Консультантов
сделки, точную сумму именно этой сделки (в отличие от совместной оценки с
ТД «Аврора»), согласования и условия для линзы «Юрист» дельта-поиск не
нашёл ни в одном источнике — честная пустота.

Запуск: python3 pipeline/fix_usta_kronshtadtskaya_buyer_scale.py
        python3 pipeline/fix_usta_kronshtadtskaya_buyer_scale.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gabdbe320'

OLD_CONTEXT = (
    'Предприятие занимается выпуском зефира, пастилы, суфле, конфет и '
    'десертов. Продукция распространяется через крупные торговые сети, '
    'маркетплейсы, а также фирменные магазины в ТЦ «Гостиный двор» '
    '(Кронштадт) и здании Московского вокзала (Петербург). У компании есть '
    'свое представительство в Бишкеке (Кыргызстан). Согласно '
    'финотчетности ООО «КФ "Кронштадтская"», по итогам 2025 года фирма '
    'заработала 446 млн рублей против 374 млн в 2024-м. Чистая прибыль '
    'составила 15,3 млн рублей против 6,1 млн рублей.'
)
CONTEXT_ADDITION = (
    ' Покупатель, холдинг «ЮСТА», — петербургский дистрибьютор и '
    'логистический оператор: по собственным данным, «количество торговых '
    'точек, которые мы обслуживаем: СПБ и ЛО — 2 500, другие города СЗФО '
    '— 3 000», общая площадь складского хозяйства 19 800 м², в парке 96 '
    'грузовых автомобилей, «более 200 тонн продукции отгружается клиентам '
    'ежедневно» (career.habr.com).'
)
NEW_CONTEXT = OLD_CONTEXT + CONTEXT_ADDITION

NEW_SRC = [
    ['Habr Career', 'https://career.habr.com/companies/usta-group'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
