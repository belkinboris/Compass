import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g3679d62c'

OLD_TARGET_FIN = '—'
NEW_TARGET_FIN = (
    'Выручка АО «Аэропорт Горно-Алтайск» за 2025 год составила 2,3 '
    'млрд руб. (+32,1%), чистая прибыль — 497 млн руб. (+84,1%). 16 '
    'июля 2025 года уставный капитал вырос с 44,4 млн до 5,2 млрд руб. '
    '(audit-it.ru).'
)

OLD_EXTRA = (
    'Сбербанк консолидировал 100% акций Горно-Алтайского аэропорта '
    'путем выкупа 60% у АФК «Системы». Сумма сделки 2,4 млрд рублей '
    'согласно отчету дочерней структуры «Системы» — ООО «Система '
    'телеком активы».'
)
NEW_EXTRA = OLD_EXTRA + (
    ' В марте 2025 года аэропорт получил международный статус, общий '
    'объём инвестиций в модернизацию — 10,2 млрд руб. (7,9 млрд руб. — '
    'федеральный бюджет, 2,2 млрд руб. — частные инвестиции), '
    'прогнозируемый пассажиропоток к 2030 году — 1,3 млн человек в год '
    '(Ведомости). Рост уже виден на практике: в 2025 году аэропорт '
    'впервые в своей истории принял 500 тыс. пассажиров с начала года '
    '(tolknews.ru).'
)

NEW_SRC = [
    ['audit-it.ru', 'https://www.audit-it.ru/contragent/1050400665193_ao-aeroport-gorno-altaysk'],
    ['Ведомости', 'https://www.vedomosti.ru/strana/siberian/news/2025/07/18/1125302-mezhdunarodnogo-terminala'],
    ['tolknews.ru', 'https://tolknews.ru/respaltay/obsestvo/203349-polmilliona-passazhirov-prinyal-aeroport-gorno-altayska-s-nachala-goda'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['target_fin'] == OLD_TARGET_FIN
    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== eco.target_fin: станет ===')
    print(NEW_TARGET_FIN)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['target_fin'] = NEW_TARGET_FIN
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
