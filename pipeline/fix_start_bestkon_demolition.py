# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка g694126dd (Гинер/ТЦ «Старт»/
«Бэсткон»): дельта-поиск нашёл факт, которого в карточке нет вовсе, — судьбу
самого актива после сделки. Два независимых материала (февраль 2026 и
декабрь 2025) называют РАЗНЫЕ цифры будущего комплекса (190 тыс. м² и 43/44
этажа против 210 тыс. м² и 43/33 этажа) — записаны оба, без выбора одного.

Не через review.py: два разных источника на одно поле в одной правке —
review.py проверяет цитату как непрерывный кусок ОДНОГО кэшированного
текста, а не объединение двух.

Источники — читал напрямую (fetch_article_texts.py, оба закэшированы):
MSK1.RU (7 февраля 2026), «Москвич Mag» (17 декабря 2025).
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g694126dd'
OLD_EXTRA = 'Сделка продажи торгового центра «Старт» девелопером Карена Авдаляна.'
ADDITION = (
    'В феврале 2026 года стало известно, что на месте центра начался снос — '
    'рабочие практически полностью разобрали фасад здания, на месте '
    'построенного в 2003 году ТЦ появятся две офисные башни; сносом '
    'занимается холдинг «Бэсткон» предпринимателя Карена Авдаляна. У '
    'проекта есть два независимых описания с разными цифрами: по данным '
    'MSK1.RU (февраль 2026), будущий бизнес-центр построят на участке 1,8 '
    'га, общая площадь зданий составит 190 тысяч м², здание получит имя '
    '«Поле» и будет состоять из двух башен высотой 43 и 44 этажа, '
    'объединённых стилобатом; по данным «Москвич Mag» (декабрь 2025, '
    'архитектурная концепция бюро Apex), высота первой башни — 43 этажа, '
    'второй — 33, а общая площадь комплекса — около 210 тыс. кв. м, ввод в '
    'эксплуатацию намечен на 2029 год.'
)
NEW_EXTRA = OLD_EXTRA + ' ' + ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['extra'] == OLD_EXTRA, \
        f"extra: неожиданное значение {deal['extra']!r}"

    print(f"{CARD_ID} extra: += судьба актива (снос, две версии проекта)")
    deal['extra'] = NEW_EXTRA

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
