# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка g4ba9150f (Светогорский
ЦБК/«ЭвоКом»): обязательная проверка статуса нашла карточку, почти год
простоявшую «Обсуждается», хотя оба уже процитированных источника
(Коммерсантъ, 23.10.2025) прямо говорили о подписанном договоре и
скором закрытии. Дельта-поиск подтвердил фактическое закрытие —
Коммерсантъ от 16.11.2025 пишет о сделке в прошедшем времени
(«Ранее пакет в «ЭвоКом» получили структуры Светогорского ЦБК»), а
TAdviser прямо: «В итоге актив перешел Светогорскому ЦБК». Точная
календарная дата закрытия ни в одном источнике не названа — рынок узнал
о завершении задним числом, из статьи про ПОСЛЕДУЮЩУЮ, отдельную сделку
(«Тайга Групп» покупает долю в уже принадлежащем Светогорскому ЭвоКом) —
это самостоятельный сюжет, не апдейт данной карточки.

Не через review.py: слово «получили»/«перешел» не совпадает ни с одной
формой в словаре STATUS_WORDS (только «перешл»/«перешёл», без формы
«перешел» с обычной «е») — тот же класс молчаливого промаха, что уже
записан в CLAUDE.md про формы слов. Заодно заголовок переведён в
прошедшее время (было «приобретает», сделка завершена), extra и
eco.context приведены в соответствие.

Источники — читал напрямую (fetch_article_texts.py, закэшированы):
Коммерсантъ (kommersant.ru/doc/8210001, 16.11.2025), TAdviser (страница
компании «Эволюция комфорта»), Retail.ru (30.03.2026, о ребрендинге).
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g4ba9150f'

OLD_TITLE = 'Светогорский ЦБК приобретает ООО «ЭвоКом» (производителя Zewa и Libresse)'
NEW_TITLE = 'Светогорский ЦБК приобрёл ООО «ЭвоКом» (производителя Zewa и Libresse)'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Закрыта'

OLD_EXTRA = (
    'Договор купли-продажи подписан, смена собственника ожидается в '
    'октябре 2025 года. Покупатель получит доступ к сырью (целлюлозе) и '
    'преимущества в утилизации отходов через механизм РОП.'
)
NEW_EXTRA = (
    'Сделка закрыта: Светогорский ЦБК получил пакет в «ЭвоКом». Точная '
    'календарная дата закрытия публично не называлась — рынок узнал о '
    'завершении из более поздних публикаций. Покупатель получил доступ '
    'к сырью (целлюлозе) и преимущества в утилизации отходов через '
    'механизм РОП.'
)

OLD_CONTEXT = (
    'Среди возможных будущих владельцев компании были также структуры '
    'семьи экс-президента УГМК Искандара Махмудова и бывшего главы '
    '«Фосагро», владельца «Пикалевской соды» Максима Волкова. Источники '
    'утверждают, что в этих случаях стороны не достигли соглашения по '
    'сумме сделки.'
)
CONTEXT_ADDITION = (
    'Коммерсантъ от 16 ноября 2025 года уже пишет о сделке в прошедшем '
    'времени: «Ранее пакет в «ЭвоКом» получили структуры Светогорского '
    'ЦБК» — к этому моменту сделка была закрыта. С 30 марта 2026 года '
    '«ЭвоКом» официально переименовал Zewa в Zemma («Для нас '
    'принципиально важно было не просто сменить название, а сохранить '
    'то, за что потребители ценят Zewa», — гендиректор ООО «ЭвоКом» '
    'Артём Лебедев). В ноябре 2025 года стало известно об отдельной, '
    'ПОСЛЕДУЮЩЕЙ сделке: лесопромышленный холдинг «Тайга Групп» '
    'договорился о покупке доли (по оценке источников — не менее 50%) в '
    'уже принадлежащем Светогорскому ЦБК «ЭвоКом», планируя объединить '
    'бизнес со своим АО «Сыктывкар Тиссью Груп» (бренд Veiro); эта '
    'сделка — самостоятельный сюжет, не изменение условий данной '
    'карточки.'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + CONTEXT_ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['title'] == OLD_TITLE, f"title: неожиданное значение {deal['title']!r}"
    assert deal['status'] == OLD_STATUS, f"status: неожиданное значение {deal['status']!r}"
    assert deal['extra'] == OLD_EXTRA, f"extra: неожиданное значение {deal['extra']!r}"
    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} title: приведён в прошедшее время")
    print(f"{CARD_ID} status: Обсуждается -> Закрыта")
    print(f"{CARD_ID} extra: приведён в соответствие с закрытием сделки")
    print(f"{CARD_ID} eco.context: += подтверждение закрытия, ребрендинг, "
          f"последующая сделка Тайга Групп")
    deal['title'] = NEW_TITLE
    deal['status'] = NEW_STATUS
    deal['extra'] = NEW_EXTRA
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
