# -*- coding: utf-8 -*-
"""У карточки `gdb854428` («Сбербанк инвестиции приобрёл логистический склад
«Пивдома» в Московской области») поле `extra` утверждало «Основной арендатор
объекта — «Вкусвилл»». Обнаружено при дочитывании (REVISION_BRIEF.md,
поиск саб-агентом): ни один из пяти прочитанных источников про ЭТУ сделку
(Ведомости, RETAILER.ru, Retail.ru, CRE.ru, AKM.ru, ibcrealestate.ru) не
называет арендатора склада «Тиера»/СДМ ТК-2 вообще. «Вкусвилл» как
арендатор нашёлся только в статье про СОВСЕМ ДРУГУЮ сделку 2020 года — фонд
«Сбербанк — арендный бизнес 3» купил «PNK парк Вешки» (108 000 кв. м,
Алтуфьевское шоссе, а не Липкинское, где стоит склад «Тиера»): «Общая
площадь объекта составляет 108 000 м², арендатором выступает ритейлер
«Вкусвилл»» (sber.pro, 21.07.2020). Похоже на смешение двух разных сделок
Сбербанка со складами в районе Вешки при исходном разборе карточки.

Не через `review.py`: снимается непроверяемый факт, а не добавляется новый
— та же логика, что у скриптов снятия протёкшей пометки роли (assert на
исходное состояние вместо цитаты).

Запуск: python3 pipeline/fix_pivdom_wrong_tenant.py
        python3 pipeline/fix_pivdom_wrong_tenant.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.join(os.path.dirname(ROOT), 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gdb854428'
OLD_EXTRA = (
    'Сбербанк инвестиции приобрёл компанию СДМ ТК-2, которой принадлежит '
    'логистический комплекс площадью 82 142 кв. м на Липкинском шоссе в '
    'Московской области. Продавцом выступил ЗПИФ «Азимут-капитал». '
    'Основной арендатор объекта — «Вкусвилл». Сбербанк планирует привлечь '
    'операционного партнёра для управления проектом. (Сбербанк инвестиции '
    '(покупатель))')
NEW_EXTRA = (
    'Сбербанк инвестиции приобрёл компанию СДМ ТК-2, которой принадлежит '
    'логистический комплекс площадью 82 142 кв. м на Липкинском шоссе в '
    'Московской области. Продавцом выступил ЗПИФ «Азимут-капитал». '
    'Сбербанк планирует привлечь операционного партнёра для управления '
    'проектом. (Сбербанк инвестиции (покупатель))')


def main(write=False):
    data = json.load(open(BASE, encoding='utf-8'))
    cards = {d['id']: d for d in data['deals']}
    card = cards[CARD_ID]
    assert card['extra'] == OLD_EXTRA, 'extra уже другое'
    print('ПРАВИМ %s extra: снят непроверяемый факт про арендатора '
          '«Вкусвилл» (похоже на смешение с другой сделкой Сбербанка)' % CARD_ID)
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return
    card['extra'] = NEW_EXTRA
    json.dump(data, open(BASE, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('ЗАПИСАНО')


if __name__ == '__main__':
    main(write='--write' in sys.argv[1:])
