# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g2e39c9a4
(Т-банк приобрел 51% в факторинговой компании ROWI у QIWI). Дельта-поиск
нашёл консультанта стороны цели (не покупателя — тот уже был в карточке)
и рост бизнеса ROWI после сделки.

1) `law.adv` (дополнение) — юридический консультант группы ROWI и её
основателей (проверено лично прямым WebFetch, pravo.ru/company_news/
253746/): «VERBA LEGAL консультировала факторинговую группу Rowi
(«РОВИ Факторинг Плюс» и «РОВИ Технологии»)» в сделке «между группой
Rowi, ее основателями и компанией группы «Т-Банка»». Это консультант
ЦЕЛИ/миноритариев, не продавца (QIWI) — консультант именно QIWI по-прежнему
не найден ни в одном источнике.

2) `eco.context` (новое поле) — рост ROWI после сделки: выручка в 2025
году выросла почти вдвое год к году — до ~7,97 млрд ₽ (против 4,16 млрд
₽ в 2024), чистая прибыль выросла на 77,6% до 307,6 млн ₽ (TAdviser;
цифры сверены независимым WebSearch-запросом отдельно от сабагента —
совпали до десятых, включая третий показатель, валовую прибыль, который
сабагент не упоминал, — прямой WebFetch страницы TAdviser отдал 404 при
нескольких попытках URL-кодирования, дословная цитата не получена).

НЕ ВНЕСЕНО: одобрение ФАС в `law.appr` — сабагент проверил источник
карточки и семь других изданий, ни один не подтверждает получение
согласия ФАС прямой формулировкой (только косвенное — сделка описана
как закрытая); правило проекта требует прямой цитаты о факте, а не
косвенного вывода, поэтому `law.appr` оставлен как есть (будущее время
про ожидание ФАС) до появления прямого подтверждения. Независимая
оценка суммы — не найдена: единственные обсуждения (Новиков, GRM;
Булгаков, Ренессанс Капитал) касаются структуры погашения облигаций
QIWI (8,5 млрд ₽), а не цены самого пакета ROWI — не переносится, чтобы
не повторить урок «Число может быть верным фактом и совсем не той
величиной».

Запуск: python3 pipeline/fix_tbank_rowi_consultant_and_growth.py
        python3 pipeline/fix_tbank_rowi_consultant_and_growth.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g2e39c9a4'

OLD_ADV = [
    [
        'Юридический консультант Группы Т-Банк (покупателя)',
        'ККМП',
        'Приобретение контрольной доли в компаниях группы ROWI у АО «Киви». Источник: kkmp.legal',
    ],
]
NEW_ADV_ENTRY = [
    'Юридический консультант группы ROWI и её основателей (цели)',
    'VERBA LEGAL',
    'Консультирование в сделке между группой Rowi, её основателями и компанией группы «Т-Банка». Источник: pravo.ru/company_news/253746/',
]

OLD_CONTEXT = '—'
NEW_CONTEXT = (
    'По данным TAdviser, выручка ROWI в 2025 году выросла почти вдвое год '
    'к году — до ~7,97 млрд ₽ (против 4,16 млрд ₽ в 2024), чистая прибыль '
    'выросла на 77,6% до 307,6 млн ₽.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['law']['adv'] == OLD_ADV
    assert deal['eco']['context'] == OLD_CONTEXT

    print('=== law.adv: добавится запись ===')
    print(NEW_ADV_ENTRY)
    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)

    if write:
        deal['law']['adv'].append(NEW_ADV_ENTRY)
        deal['eco']['context'] = NEW_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
