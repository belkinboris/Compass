# -*- coding: utf-8 -*-
"""Месячная очередь, карточка gb30e66af («Бумеранг агроинвест приобрел 85%
долей производителя салатов Прованс»): дельта-поиск нашёл профиль самого
покупателя (кто он и откуда взялся — раньше не было известно вовсе) и
крупный факт после сделки: та же структура тремя месяцами позже
консолидировала рынок салатных смесей, купив ещё и «Салатерию». Не через
review.py: поле eco.context пустое («—»), но факты собраны из ТРЁХ разных
источников, а review.py принимает только одну непрерывную цитату на поле.

Источник для имени топ-менеджера «Бумеранг капитала» расходится сам с
собой: kommersant.ru/doc/8100469 (09.10.2025) называет его «Александр
Перфильев», а kommersant.ru/doc/8295554 (19.12.2025, тот же Ъ) — «Федор
Перфильев». В обеих статьях фамилия и должность (гендиректор «Бумеранг
капитала») совпадают, расходится только имя — родня уже записанного урока
«источник может расходиться сам с собой» (Флеганов/Ферганов). Разрешить
однозначно живым поиском не удалось за разумное время, поэтому имя
намеренно не называется — используется только фамилия и должность,
подтверждённые ОБОИМИ источниками.

Источники (читал напрямую, fetch_article_texts.py, закэшированы):
- kommersant.ru/doc/8100469 (структура собственников «Бумеранг агроинвест»)
- kommersant.ru/doc/8295554 (покупка «Салатерии», стратегия консолидации)
- vedomosti.ru/business/articles/2025/09/10/1138375-vlozhilis-v-proizvoditelya-salatov
  (дата основания «Бумеранг агроинвест», первая инвестиция в «Зельгрос Россия»)

Запуск: python3 pipeline/fix_boomerang_provans_buyer_profile_and_salateria.py [--write]
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gb30e66af'

OLD_CONTEXT = '—'
NEW_CONTEXT = (
    '«Бумеранг агроинвест» основано в мае 2024 г. компанией «Бумеранг '
    'капитал» экс-руководителя «Сбербанк капитала» Вагана Гаспаряна: 49% '
    'проекта контролирует сам «Бумеранг капитал», 1% — его гендиректор '
    'Перфильев, 25% — АО «Пикалевская сода» бывшего гендиректора '
    '«Фосагро» Максима Волкова, ещё 25% с сентября 2025 года — ЗПИФ '
    '«Рэвард Капитал», чьим бенефициаром на рынке считается бывший '
    'топ-менеджер ЛУКОЙЛа Александр Раппопорт. В конце 2024 г. «Бумеранг '
    'капитал» уже привлекала компания «Ароса логистика» — соинвестором '
    'для развития бизнеса ритейлера «Зельгрос Россия». 13 декабря 2025 '
    'года подконтрольное структурам фонда ООО «Прованс» получило по 100% '
    'долей в ООО «Салатерия» и СПП, прежде входивших в группу '
    '«Дмитровские овощи» Сергея Филиппова: по словам гендиректора '
    '«Бумеранг капитала» Перфильева, стратегия фонда предполагает '
    'создание крупного игрока на рынке салатных смесей для поставок в '
    'ритейл, гостиницы и заведения общепита (HoReCa), а активы «Прованса» '
    'и «Салатерии» планируется консолидировать.'
)


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} eco.context: += профиль покупателя (структура "
          f"собственников) и консолидация с «Салатерией»")
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
