# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g801dd6a9
(Александр Сысоев продал долю в 2ГИС структуре Сбера). Проверено лично
прямым WebFetch.

1) `eco.val` — атрибуция оценки Козлова была неполной (только фамилия).
mergers.ru (перепечатка Forbes), дословно: «рыночная стоимость 25% доли
компании может составлять около 9,4–14 млрд рублей, отмечает основатель
инвестиционной компании The12 Capital Дмитрий Козлов» — полное имя и
должность, и это ДРУГОЙ диапазон (9,4–14 млрд), чем уже стоявшая в поле
альтернативная оценка по MAU (5,5 млрд) — обе оценки одного и того же
аналитика, разными методами, сохранены обе.
Источник: https://mergers.ru/news/Osnovatel-2GIS-Aleksandr-Sysoev-prodal-svoyu-dolyu-i-ushel-iz-kompanii-85827

2) `date` — уточнение ВНУТРИ уже известного года (2025 -> 2025-07-28).
Тот же источник, дословно: «Стороны подписали документы о продаже
Александром Сысоевым своей доли в 2ГИС еще 28 июля, сообщили Forbes
четыре источника, близкие к предпринимателю»; «По данным СПАРК,
присоединение к юридическому лицу ООО «Дубльгис» других юридических лиц
было зафиксировано 1 августа» — дата подписания взята как более точная,
чем дата корпоративного присоединения.

3) `eco.context` (новое поле) — судьба Сысоева и структуры владения
после сделки. shoppers.media (перепечатка Forbes), дословно: «Сбер»
стал его единственным владельцем» (было 72%+3% с 2020 года, теперь
100% после выкупа доли Сысоева); «Половину этих средств он вложит в
строительство отеля «Грушевый цвет» на Алтае, а вторую часть —
инвестирует в стартапы». РАСХОЖДЕНИЕ В СУММЕ, зафиксировано честно, а не
исправлено механически: тот же источник передаёт слова самого Сысоева —
«он получил за свою долю «несколько миллиардов рублей», но менее 5 млрд
руб.» — это меньше, чем стоящая в карточке оценка «5,5 млрд ₽», но
первое лицо не называет точную цифру, а аналитические оценки (5,5 и
9,4–14 млрд) сделаны СНАРУЖИ; `sum` не меняется — оставлена как оценка
экспертов, а слова самого продавца добавлены рядом как альтернативный,
более скромный ориентир.

НЕ включены: консультанты сделки — не названы ни в одном источнике;
согласование ФАС — не найдено ни подтверждения, ни отрицания (возможное
объяснение — Сбер мог уже входить в группу лиц владельца цели с 2020
года, и повторное согласование могло не требоваться — это гипотеза, не
подтверждённая цитатой, в карточку не включена).

Запуск: python3 pipeline/fix_sysoev_2gis_sberbank_details.py
        python3 pipeline/fix_sysoev_2gis_sberbank_details.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g801dd6a9'

OLD_DATE = '2025'
NEW_DATE = '2025-07-28'

OLD_VAL = (
    'Есть и другая оценка, продолжает Козлов: по альтернативному подходу '
    '(стоимость/количество MAU) цена доли в размере 25% может достигать '
    'около 5,5 млрд рублей.'
)
NEW_VAL = (
    'Основатель инвестиционной компании The12 Capital Дмитрий Козлов: '
    '«рыночная стоимость 25% доли компании может составлять около '
    '9,4–14 млрд рублей». Есть и другая его же оценка — по альтернативному '
    'подходу (стоимость/количество MAU) цена доли в размере 25% может '
    'достигать около 5,5 млрд рублей.'
)

OLD_CONTEXT = '—'
NEW_CONTEXT = (
    'После выкупа доли Сысоева «Сбер» стал его единственным владельцем» '
    '(со 100%, было 72%+3% с 2020 года). Половину вырученных средств '
    'Сысоев «вложит в строительство отеля «Грушевый цвет» на Алтае, а '
    'вторую часть — инвестирует в стартапы» (shoppers.media). Расхождение '
    'в сумме: сам Сысоев говорит, что получил за долю «несколько '
    'миллиардов рублей», но менее 5 млрд руб.» — меньше, чем '
    'аналитические оценки (5,5 и 9,4–14 млрд ₽); точная цифра не '
    'раскрывается ни одной стороной.'
)

NEW_SRC = [
    ['mergers.ru', 'https://mergers.ru/news/Osnovatel-2GIS-Aleksandr-Sysoev-prodal-svoyu-dolyu-i-ushel-iz-kompanii-85827'],
    ['shoppers.media', 'https://shoppers.media/news/28838_osnovatel-2gis-aleksandr-sysoev-obieiasnil-svoi-uxod-iz-kompanii'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['date'] == OLD_DATE
    assert deal['eco']['val'] == OLD_VAL
    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print(f'=== date: {OLD_DATE!r} -> {NEW_DATE!r} ===')
    print('=== eco.val: станет ===')
    print(NEW_VAL)
    print('=== eco.context (новое поле): станет ===')
    print(NEW_CONTEXT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['date'] = NEW_DATE
        deal['eco']['val'] = NEW_VAL
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
