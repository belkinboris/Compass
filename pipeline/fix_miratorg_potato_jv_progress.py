# -*- coding: utf-8 -*-
"""Месячная очередь качества, 11 сентября 2026 — карточка `c15d1a169»
(«Мираторг и «Вкусно — и точка» создают СП по переработке картофеля»,
2024) описывала только подписание соглашения и запуск, намеченный на
II квартал 2025 года; ход строительства был неизвестен.

Личный WebFetch подтвердил дословно (Абирег,
https://abireg.ru/newsitem/106055): «Предприятие по глубокой
переработке и консервированию картофеля ООО «Гранд Фрайз» планируют
достроить во второй половине 2026 года. Ранее сроком окончания
реализации проекта обозначали 2025 год»; «Общая стоимость проекта
оценивается в 19,2 млрд рублей, что включает увеличение мощности до
135 тыс. тонн в год».

Запуск:
    python3 pipeline/fix_miratorg_potato_jv_progress.py            # сухой прогон
    python3 pipeline/fix_miratorg_potato_jv_progress.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_ECO_CONTEXT = (
    'Согласно статье, Мираторг, «Вкусно — и точка» и Орловская область '
    'подписали соглашение о сотрудничестве по строительству комплекса '
    'по глубокой переработке картофеля и производству картофеля фри и '
    'хашбраун во Мценском районе особой экономической зоны «Орёл». СП '
    'будет поставлять продукцию в предприятия «Вкусно — и точка» и '
    'другие сегменты HoReCa, сырьевую базу обеспечит Мираторг (250 тыс. '
    'т картофеля в год). Запуск СП намечен на II квартал 2025 года.'
)
NEW_ECO_CONTEXT = OLD_ECO_CONTEXT + (
    ' Строительство идёт со сдвигом сроков: завод («Гранд Фрайз») '
    'планируют достроить во второй половине 2026 года вместо '
    'изначально заявленного 2025-го, а общая стоимость проекта выросла '
    'до 19,2 млрд ₽ вместе с увеличением мощности до 135 тыс. т в год.'
)

NEW_SRC = ['Абирег', 'https://abireg.ru/newsitem/106055']


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['c15d1a169']

    assert d['eco']['context'] == OLD_ECO_CONTEXT, 'eco.context уже другой'
    urls = {s[1] for s in d['src']}
    assert NEW_SRC[1] not in urls, 'источник уже добавлен'

    print('c15d1a169: eco.context дополнен ходом строительства (сдвиг сроков '
          'на вторую половину 2026 года, рост стоимости до 19,2 млрд ₽)')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['eco']['context'] = NEW_ECO_CONTEXT
    d['src'].append(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
