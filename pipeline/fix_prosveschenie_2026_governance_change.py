# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка gf9932079 (ВЭБ.РФ
консолидировал 75% издателя учебников «Просвещение»): дельта-поиск нашёл
крупную волну новостей от 13 февраля 2026 года — ВЭБ.РФ становится
единоличным исполнительным органом «Просвещения», а VK — стратегическим
партнёром по edtech-направлению (три источника, поэтому не через
review.py — он проверяет цитату как непрерывный кусок ОДНОГО
кэшированного текста).

Источники — читал напрямую (fetch_article_texts.py, все закэшированы):
«Ведомости» (13.02.2026), РИА Новости (13.02.2026), Коммерсантъ
(13.02.2026).
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gf9932079'
OLD_CONTEXT = (
    '«Мы консолидировали сейчас, это совместная была работа '
    'администрации президента и правительства, 100% акций компании '
    '«Просвещение». У ВЭБа — 75%, у РФПИ — 25%»,— сказал господин '
    'Шувалов. В марте 2025 года госкорпорация, которой прежде принадлежало '
    'лишь 25% «Просвещения», увеличила свою долю в издательстве за счет '
    'выкупа 25% бизнеса, ранее принадлежавших «Сберу».'
)
ADDITION = (
    '13 февраля 2026 года стало известно о дальнейшей трансформации '
    'управления: «ВЭБ .РФ примет на себя функции единоличного '
    'исполнительного органа АО «Просвещение» (основное юрлицо группы '
    'компаний «Просвещение»)», рассказали «Ведомостям» источники, — «к '
    'управленческой команде присоединятся представители VK, а сам '
    'интернет-холдинг станет стратегическим партнером «Просвещения». '
    'Вместе партнеры займутся, в числе прочего, развитием '
    'edtech-направления». Совет директоров рекомендовал акционерам '
    'принять соответствующее решение: «Совет директоров рекомендовал '
    'акционерам принять решение о передаче полномочий единоличного '
    'исполнительного органа АО "Просвещение" ВЭБ.РФ», а куратором от '
    'госкорпорации назначен зампред Александр Тарабрин: «Зампред ВЭБ.РФ '
    'Александр Тарабрин назначен ответственным за руководство '
    'издательством «Просвещение» от лица госкорпорации. Формально '
    'должность господина Тарабрина не изменится, но все основные функции '
    'по курированию издательства лягут на него».'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} eco.context: += трансформация управления (февраль 2026)")
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
