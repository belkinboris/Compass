import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gb7a906e5'

OLD_EXTRA = ''
NEW_EXTRA = (
    'С 1 июля 2024 года детский сад на этой площадке переименован в '
    'RYBAKOV PLAYSCHOOL (перешли 85% учащихся и 99% педагогов); тогда '
    'же объявлялся план заменить с 1 сентября 2025 года школу Brookes '
    'Moscow на RYBAKOV MOSCOW. Однако 16 марта 2026 года школа Brookes '
    'на той же территории внезапно закрылась решением совета '
    'директоров Brookes Education Group, затронув около 300 учеников, '
    'многие из которых уже оплатили обучение вперёд (до 2-3,4 млн руб. '
    'в год) — источники не объясняют это расхождение между анонсом '
    'перехода 2024 года и тем, что бренд Brookes и его иностранное '
    'управление продолжали действовать вплоть до закрытия.'
)

NEW_SRC = [
    ['КП', 'https://www.kp.ru/daily/27607.5/4958038/'],
    ['DP.ru', 'https://www.dp.ru/a/2026/03/16/jelitnaja-chastnaja-shkola-v-moskve'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
