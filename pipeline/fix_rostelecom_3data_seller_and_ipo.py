# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g11d6e0bc
(Ростелеком приобрел ЦОД 3data HyperScale в Медведково у PNK Group,
август 2024). Дельта-поиск нашёл, что заголовок и поле `seller` называют
не ту сторону — сигнал уже был на самой карточке.

ПРОДАВЕЦ НАЗВАН НЕВЕРНО. Единственный источник карточки (Интерфакс,
https://www.interfax.ru/russia/976510, проверено лично прямым WebFetch)
прямо называет продавцом ФОНД, а не девелопера: «Продавцом дата-центра
выступил комбинированный ЗПИФ "Рентал ПРО" под управлением ООО УК "А
класс капитал"» — PNK Group в этой статье не упоминается вовсе. Второй
источник того же информагентства (interfax.ru/business/976641,
проверено лично) объясняет, откуда взялось имя PNK Group: «О том, что
"Ростелеком" рассматривает возможность покупки этого дата-центра у
девелопера PNK Group, в июне писал "Коммерсантъ"» — это были ИЮНЬСКИЕ
переговоры о прямой покупке у застройщика, которые пошли другим путём:
«Дата-центр... был приобретен в состав фонда "Рентал ПРО" в 2024 году за
25,8 млрд рублей с НДС» (то есть PNK Group продал объект фонду РАНЬШЕ, а
уже фонд, на закрытии, продал его «Ростелекому» за 26,28 млрд рублей).
Сигнал о настоящем продавце уже был на самой карточке: `eco.context` и
до этой правки писал «Рентал ПРО» планирует распределить часть прибыли
от сделки...» — то есть карточка знала правильного продавца в одном поле
и неправильного — в заголовке и `seller`.

Заголовок и `seller` исправлены на «ЗПИФ «Рентал ПРО»» — это не
переименование по стилю (правило «старые карточки не переименовываются»
касается смягчения формулировок, а не исправления фактической ошибки в
стороне сделки).

IPO РТК-ЦОД (`extra`, дополнение). Карточка писала про план IPO осенью
2024 года как про будущее событие; проверено лично прямым WebFetch —
IPO НЕ СОСТОЯЛОСЬ и отложено на неопределённый срок: «Мы отложили. Мы
будем ждать изменения конъюнктуры на финансовом, на фондовом рынке»
(президент «Ростелекома» Михаил Осеевский, Telesputnik, 19.11.2024); по
состоянию на май 2026 года подтверждение того же: «должно прийти своё
время, пока это время не пришло» (Коммерсантъ, 14.05.2026).

НЕ включены: точная сумма (26,3 vs 26,28 млрд ₽ — разница на уровне
округления, не меняется); консультант продавца — не назван ни в одном
источнике.

Запуск: python3 pipeline/fix_rostelecom_3data_seller_and_ipo.py
        python3 pipeline/fix_rostelecom_3data_seller_and_ipo.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g11d6e0bc'

OLD_TITLE = 'Ростелеком приобрел ЦОД 3data HyperScale в Медведково у PNK Group'
NEW_TITLE = 'Ростелеком приобрел ЦОД 3data HyperScale в Медведково у фонда «Рентал ПРО»'

OLD_SELLER = 'PNK Group'
NEW_SELLER = 'ЗПИФ «Рентал ПРО»'

OLD_EXTRA = (
    'Сделка по приобретению центра обработки данных 3data HyperScale '
    'мощностью 36 МВт с емкостью 4,8 тыс. стойко-мест. Закрыта в августе '
    '2024 г. РТК-ЦОД планирует провести IPO осенью 2024 г. (РТК-ЦОД '
    '(Ростелеком))'
)
EXTRA_ADDITION = (
    ' Продавцом выступил ЗПИФ «Рентал ПРО»: «О том, что "Ростелеком" '
    'рассматривает возможность покупки этого дата-центра у девелопера PNK '
    'Group, в июне писал "Коммерсантъ"» — но на закрытии в августе '
    'продавцом стал фонд, купивший объект у PNK Group ранее в 2024 году '
    'за 25,8 млрд рублей с НДС (Интерфакс). IPO РТК-ЦОД так и не '
    'состоялось: «Мы отложили. Мы будем ждать изменения конъюнктуры на '
    'финансовом, на фондовом рынке» (президент «Ростелекома» Михаил '
    'Осеевский, ноябрь 2024) — по состоянию на май 2026 года IPO по-прежнему '
    'не проведено.'
)
NEW_EXTRA = OLD_EXTRA + EXTRA_ADDITION

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/business/976641'],
    ['Telesputnik', 'https://telesputnik.ru/materials/money/news/rostelekom-otlozil-ipo-svoei-docki-rtk-cod'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['title'] == OLD_TITLE
    assert deal['seller'] == OLD_SELLER
    assert deal['extra'] == OLD_EXTRA
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print(f'=== title: станет ===\n{NEW_TITLE}')
    print(f'=== seller: {OLD_SELLER!r} -> {NEW_SELLER!r} ===')
    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['title'] = NEW_TITLE
        deal['seller'] = NEW_SELLER
        deal['extra'] = NEW_EXTRA
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
