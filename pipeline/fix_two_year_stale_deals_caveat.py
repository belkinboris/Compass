# -*- coding: utf-8 -*-
"""Правило владельца (заметки 474, 479, консоль, 4 сентября 2026):
«если обсуждается два года и больше новостей нет, то пусть остаётся
"обсуждается" с пояснением, что уже больше двух лет и есть вероятность,
что не состоялась».

Применено к двум карточкам, у которых `eco.context` уже нёс реестровую
находку («учредитель не сменился»), но не называл прямо вывод из
правила:

- g6ad6fe69 (холдинг «Экто»/«Премио Крамб») — источник от 29.01.2024,
  реестровый срез 04.02.2025 (больше года на момент находки, к 4 сентября
  2026 — уже больше двух с половиной лет).
- gc64703e2 (Газпромбанк Лизинг/Urent) — источник от начала 2023 года,
  находка (МТС купила «Юрентбайк.ру» отдельно) от 15.01.2024 — к
  сегодняшнему дню больше трёх лет с момента исходных переговоров.

Дополнительно для gc64703e2 заметка 479 отдельно попросила убрать
`eco.rationale` — там стояло «По неофициальным данным, "Газпромбанк
лизинг" ведёт переговоры... о вхождении в капитал» — это не цель
сделки (зачем сделка нужна сторонам), а пересказ самого факта
переговоров, который и так уже виден в заголовке и в contexts; владелец
прямо назвал это не подходящим для поля «Цель сделки».

Текст добавляемого предложения — не цитата издания, а наша собственная
редакционная оговорка, поэтому правка идёт этим одноразовым скриптом
(с assert на исходное состояние), а не через review.py (там требуется
дословная цитата источника, которой здесь нет).

Запуск: python3 pipeline/fix_two_year_stale_deals_caveat.py [--write]
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CAVEAT = (' Обсуждение тянется больше двух лет без единого подтверждения '
          '— есть вероятность, что сделка не состоялась.')

OLD_CONTEXT_EKTO = (
    'Выручка ВПТ за 2022 год — 9 млрд ₽, чистая прибыль — 1,4 млрд ₽. По '
    'данным трёх независимых реестровых агрегаторов (свежий срез ЕГРЮЛ — '
    '04.02.2025), спустя более двух лет после одобрения ФАС единственным '
    'учредителем и гендиректором ООО «Премио Крамб» остаётся Максим '
    'Ефименко — АО «Вестерн Петролеум Транспортэйшн» в истории участников '
    'не встречается вовсе.'
)

OLD_CONTEXT_URENT = (
    'Рыночная стоимость электросамоката Segway Ninebot, которыми '
    'пользуется «Юрент», — от 75 000 до 90 000 ₽, но массовая закупка '
    'должна была пройти по нижней границе диапазона. Самокаты '
    'предполагалось поставить за три года: 35 000 штук в 2023 году, ещё по '
    '25 000 в 2024 и 2025 годах. По независимым данным, сделка так и не '
    'закрылась: 15 января 2024 года МТС отдельной сделкой довела долю в '
    'ООО «Юрентбайк.ру» с 11,77% до 80,58% при оценке компании в 7–8 '
    'млрд ₽. «Газпромбанк Лизинг» ни в этом, ни в последующих раскрытиях '
    'состава акционеров не упоминается.'
)

OLD_RATIONALE_URENT = (
    'По неофициальным данным, «Газпромбанк лизинг» ведёт переговоры с '
    'кикшеринговым сервисом «Юрент» о вхождении в капитал компании.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {c['id']: c for c in data['deals']}

    ekto = by_id['g6ad6fe69']
    assert ekto['eco']['context'] == OLD_CONTEXT_EKTO, ekto['eco']['context']
    ekto['eco']['context'] = OLD_CONTEXT_EKTO + CAVEAT

    urent = by_id['gc64703e2']
    assert urent['eco']['context'] == OLD_CONTEXT_URENT, urent['eco']['context']
    urent['eco']['context'] = OLD_CONTEXT_URENT + CAVEAT
    assert urent['eco']['rationale'] == OLD_RATIONALE_URENT, urent['eco']['rationale']
    urent['eco']['rationale'] = '—'

    print('g6ad6fe69.eco.context: добавлена оговорка про 2+ года')
    print('gc64703e2.eco.context: добавлена оговорка про 2+ года')
    print('gc64703e2.eco.rationale: снято (не цель сделки, а пересказ факта переговоров)')

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
            f.write('\n')
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
