def get_field(card, field):
    obj = card
    for part in field.split('.'):
        obj = obj.get(part) if isinstance(obj, dict) else None
    return obj


def set_field(card, field, value):
    parts = field.split('.')
    obj = card
    for part in parts[:-1]:
        obj = obj.setdefault(part, {})
    obj[parts[-1]] = value


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    deals = {d['id']: d for d in data['deals']}
    changed = 0
    for cid, field, old, new, why in APPENDS:
        card = deals[cid]
        current = get_field(card, field)
        assert current == old, (
            '%s.%s изменилось с прошлого чтения: в базе %r, ожидали %r'
            % (cid, field, current, old))
        print('%s  %s.%s' % ('ПИШЕМ' if write else 'ПРАВИМ (сухой прогон)',
                              cid, field))
        print('  + %s' % why)
        if write:
            set_field(card, field, new)
            changed += 1
    if write:
        json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1,
                   ensure_ascii=False)
        print('\nЗаписано полей: %d' % changed)
    else:
        print('\nСухой прогон, правок: %d. Запись — с ключом --write.'
              % len(APPENDS))
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
