import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gdd67ffde'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Закрыта'

OLD_EXTRA = (
    'Сделка покупки ГАП «Ресурс» свиноводческого холдинга ГК «Шувалово». '
    'Получено предварительное согласие ФАС. Цель сделки — диверсификация '
    'продуктового портфеля и развитие глубокой переработки мяса, '
    'предполагается синергия с птицеводческими комплексами через обмен '
    'кормовой базой.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' По данным ЕГРЮЛ, единственный учредитель одного из активов группы '
    '— ООО «ККЗ» (Костромской комбикормовый завод) — сменился с Владимира '
    'и Нинель Коминых на структуру ГАП «Ресурс» (ООО «Мясо-Молоко '
    'Ресурс») 13 февраля 2024 года, за день до публикации о сделке — '
    'прямое подтверждение закрытия.'
)

NEW_SRC = [
    ['ЕГРЮЛ (агрегатор)', 'https://www.audit-it.ru/contragent/1104401000990_ooo-kkz'],
    ['ЕГРЮЛ (агрегатор)', 'https://www.audit-it.ru/contragent/1206100022347_ooo-myaso-moloko-resurs'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS
    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== status: станет ===')
    print(NEW_STATUS)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['status'] = NEW_STATUS
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
