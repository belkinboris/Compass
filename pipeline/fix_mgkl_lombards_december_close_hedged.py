# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g2bef2143
(ПАО «МГКЛ» приобретает две ломбардные сети в Московском регионе,
сентябрь 2024, статус «Обсуждается», заявленный срок закрытия «3–5
недель» истёк почти два года назад).

Дельта-поиск нашёл прямое подтверждение закрытия сделки М&A такого же
профиля тем же покупателем в декабре 2024 года — Interfax, 03.12.2024
(https://www.interfax.ru/business/995704, проверено лично прямым
WebFetch): «Группа "МГКЛ" приобрела 26 ломбардов и комиссионных магазинов
за 750 млн рублей, тем самым увеличив долю на ломбардном рынке Москвы и
Московской области с 11% до 14%».

ЭТО НЕ ОДНОЗНАЧНО ТА ЖЕ СДЕЛКА. Совпадают покупатель, регион, отрасль и
порядок величины (сентябрьская оценка — «две сети, ≈1 млрд ₽»;
декабрьская — «26 объектов, 750 млн ₽»), но ни один источник НЕ пишет
«та самая сделка, анонсированная в сентябре, закрылась», и ни «Ломбардия»,
ни «Народный ломбард», ни «Семерочка» (три сети-кандидата из сентябрьской
статьи) не названы ни в одном источнике о декабрьском закрытии — только
собственные бренды покупателя («Мосгорломбард», «Ресейл Маркет»).
Продавец нигде не назван. Статус НЕ меняется на «Закрыта» и предмет НЕ
привязывается к конкретным сетям — это ровно тот класс, что уже описан в
CLAUDE.md («признак дефекта — повод прочитать, а не основание стереть»/
«два похожих факта без прямой текстовой связки»), решение о слиянии
фактов оставлено человеку. Факт о декабрьском закрытии добавлен в
eco.context с явной честной оговоркой о недоказанной связи.

Запуск: python3 pipeline/fix_mgkl_lombards_december_close_hedged.py
        python3 pipeline/fix_mgkl_lombards_december_close_hedged.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g2bef2143'

OLD_CONTEXT = (
    'МГКЛ в 2024 году за счет приобретения 26 ломбардов и комиссионных '
    'магазинов в Москве и Московской области расширила розничную сеть '
    '(на 24% — до 135 отделений).'
)
CONTEXT_ADDITION = (
    ' 3 декабря 2024 года Интерфакс сообщил о закрытии похожей сделки того '
    'же покупателя: «Группа "МГКЛ" приобрела 26 ломбардов и комиссионных '
    'магазинов за 750 млн рублей, тем самым увеличив долю на ломбардном '
    'рынке Москвы и Московской области с 11% до 14%». Ни одна из трёх '
    'названных в сентябре сетей-кандидатов («Ломбардия», «Народный '
    'ломбард», «Семерочка») в декабрьских публикациях не упомянута —'
    ' связь этой декабрьской сделки именно с сентябрьским анонсом '
    'источники прямо не подтверждают.'
)
NEW_CONTEXT = OLD_CONTEXT + CONTEXT_ADDITION

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/business/995704'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
