# -*- coding: utf-8 -*-
"""ВТБ/АФК «Система»/Ozon (`ga46c5b15`): карточка уже прошла полный
дневной, недельный и месячный обыск (16 августа) — но 28 августа Frank
Media нашли в отчётности АФК «Система» подробности структуры сделки,
которых не было ни в одном из 12 уже привязанных источников: сделка —
аналог долгосрочного репо (~3 года), обеспечение включало не только
акции Ozon, но и временный залог в виде 120 млрд ₽ денежных средств
(сейчас, по словам компании, высвобожден), а гарантии группы покрыты
залогом других активов группы. Отдельно — что структура НЕ зависит от
изменения стоимости Ozon (нетипично для сделок под залог бумаг), и что
Сбербанк ранее (май 2026) вёл переговоры о получении доли АФК в Ozon в
счёт долга, но стороны не сошлись в цене — это отдельный, ранее
неизвестный несостоявшийся эпизод той же истории.

Источник — Frank Media (frankmedia.ru/302007), обычный fetch_article_texts
получил «подозрительно короткий текст (0 знаков)» (403/защита от
роботов), полный текст получен через WebFetch и сверен на месте — цитаты
дословные фрагменты того же текста.

`--mark-deep` НЕ ставится повторно: карточка это прошла 16 августа, а
сегодняшняя правка — обычное дополнение уже прочитанной карточки новым
источником, а не первичный обыск.

Запуск: python3 pipeline/fix_afk_sistema_vtb_ozon_structure_detail.py           # проверка
        python3 pipeline/fix_afk_sistema_vtb_ozon_structure_detail.py --write   # запись
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'ga46c5b15'
OLD_CONTEXT = (
    'По словам ВТБ, сделка уникальна по масштабу и сложности '
    'инвестиционных решений на российском фондовом рынке. Агентство '
    '«Эксперт РА» в день закрытия сделки (30 июня 2026) понизило рейтинг '
    'АФК «Система» с ruAA− до ruA+ с развивающимся прогнозом. Чистые '
    'финансовые обязательства корпоративного центра АФК «Система» по '
    'итогам 2025 года составляли 368,2 млрд руб.; собственные кредитные '
    'обязательства АФК перед ВТБ остались неизменными на уровне 30,5 '
    'млрд руб.'
)
ADDITION = (
    '28 августа 2026 года Frank Media со ссылкой на отчётность АФК '
    '«Система» раскрыли структуру сделки подробнее: это аналог '
    'долгосрочной операции репо сроком около трёх лет, в которой холдинг '
    'выкупил котируемые бумаги у финансового партнёра на 220 млрд '
    'рублей, а отсрочку платежа обеспечили гарантии компаний группы, '
    'покрытые залогом других активов группы; помимо этого, компания '
    'предоставила временный залог в виде 120 млрд рублей денежных '
    'средств, который, по словам АФК «Система», «был временным элементом '
    'структурной сделки, рассчитанной на три года, и на текущий момент '
    'высвобожден». В презентации к отчётности «Система» отметила, что '
    '«структура сделки не зависит от изменения стоимости активов '
    'группы» — по мнению аналитика ФГ «Финам» Дмитрия Лозового, это '
    'значит, что падение акций Ozon само по себе не требует довнесения '
    'залога. Управляющий партнёр Rassvet Capital Артём Максадов оценил '
    'экономический эффект для АФК: «Теперь компания сможет значительно '
    'сократить долговую нагрузку и сэкономить на процентных платежах '
    'порядка 35-40 млрд рублей в год». Отдельно выяснилось, что в конце '
    'мая 2026 года структуры Сбербанка вели переговоры о получении доли '
    'АФК «Система» в Ozon в счёт существующего долга, но стороны не '
    'смогли договориться о цене продажи — сделка не состоялась.'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + ADDITION
NEW_SRC = ['Frank Media', 'https://frankmedia.ru/302007']


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    card = next((c for c in data['deals'] if c['id'] == CARD_ID), None)
    assert card is not None, '%r не найдена в базе' % CARD_ID
    assert card.get('eco', {}).get('context') == OLD_CONTEXT, (
        'eco.context уже другое: %r' % card.get('eco', {}).get('context'))
    src_already_present = NEW_SRC in card.get('src', [])

    print('ДОБАВЛЕНО: %r' % ADDITION)
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return 1

    card['eco']['context'] = NEW_CONTEXT
    if not src_already_present:
        card.setdefault('src', []).append(NEW_SRC)
    json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('ЗАПИСАНО.')
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv[1:]))
