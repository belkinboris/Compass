#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Четыре обрубленных `events[].note» из класса «жёсткий лимит длины при
разборе притока» (см. CLAUDE.md, «Один и тот же обрыв на ~260 знаках»),
пропущенные предыдущей чисткой — все обнаружены тем же признаком
(`len(note) in 255..260`) по свежему замеру всей базы (Этап 14, П2).

Метод — тот же, что `fix_g21795ec9_truncated_note.py`: полный абзац найден
в кэше исходного источника (здесь — прямым чтением статьи, WebFetch), в
`new` перенесено дословное продолжение до конца обрубленного предложения
(и, где источник содержит следующее законченное предложение — как в
случае «ЮСТА»/кондитерской фабрики и Happy Job/HeadHunter — оно тоже
перенесено целиком, а не оборвано на середине новой мысли).

  * `ga525c46b` (гостиница «Амбассадор») — источник mergers.ru: адрес
    гостиницы («на улице Римского-Корсакова в Адмиралтейском районе
    Петербурга») был обрублен на предлоге «на улице…».
  * `gebead2e8` (HeadHunter/Happy Job) — источник mergers.ru: следующее
    предложение целиком о том, что даст интеграция Happy Job, было
    обрублено на «Уточняется, что…».
  * `gad66fcec` (ЗПИФ «Вим недвижимость»/склад в Кувекино) — источник
    mergers.ru: следующее предложение о дате закрытия по данным сервиса
    Asseto («21 августа») было обрублено на «По…». ВНИМАНИЕ: эта дата
    (21 августа) расходится с `date` карточки (2026-08-25) — расхождение
    НЕ разбирается этим скриптом (разные вопросы: дословность цитаты и
    точность отдельного структурного поля), оставлено как отдельная
    находка для последующего чтения.
  * `gabdbe320` (ЮСТА/кондитерская фабрика в Кронштадте) — источник
    mergers.ru: продолжение перечисления продукции и следующее
    предложение о каналах сбыта было обрублено на «конфет…».

Запуск:
    python3 pipeline/fix_events_note_260char_truncation_batch1.py            # сухой прогон
    python3 pipeline/fix_events_note_260char_truncation_batch1.py --write    # записать
"""
import json
import sys

PATH = 'static/data/deals_promoted.json'

FIXES = [
    dict(
        deal_id='ga525c46b',
        old_tail='на улице…',
        new_note=(
            'АО «Интеринвест М» под руководством управляющего гостиничной сетью Marins Hotels '
            'Павла Князева 11 августа получило 100% в ООО «РК 5–7». На балансе последней, по '
            'данным реестра средств размещения, гостиница «Амбассадор» на 251 номер (17,2 тыс. '
            'кв. м) на улице Римского-Корсакова в Адмиралтейском районе Петербурга.'
        ),
    ),
    dict(
        deal_id='gebead2e8',
        old_tail='Уточняется, что…',
        new_note=(
            'Финансовые условия соглашения стороны не разглашают. HeadHunter активно расширяет '
            'экосистему HR Tech-решений, чтобы объединить инструменты привлечения талантов, '
            'управления репутацией и развития опыта сотрудников, отмечается в пресс-релизе. '
            'Уточняется, что сделка с Happy Job позволит интегрировать в процессы аналитику '
            'внутреннего опыта и лояльности команд и сформировать набор решений для управления '
            'брендом не только на этапе привлечения кандидатов, но и на протяжении всего '
            'жизненного цикла сотрудника в компании.'
        ),
    ),
    dict(
        deal_id='gad66fcec',
        old_tail='По…',
        new_note=(
            'Закрытый паевой инвестиционный фонд «Вим недвижимость» под управлением «Вим '
            'сбережений» выкупил у входящего в ГК ПИК девелопера Parametr складской комплекс '
            'площадью 75 700 кв. м на территории промышленного парка «Кувекино» в д. Евсеево '
            'в новой Москве. По данным сервиса Asseto, сделка была закрыта 21 августа.'
        ),
    ),
    dict(
        deal_id='gabdbe320',
        old_tail='конфет…',
        new_note=(
            'Владелец ГК «ЮСТА» Станислав Бартош приобрел у предпринимателя Владислава '
            'Теплоухова 100% долей в капитале ООО «КФ "Кронштадтская"», на балансе которого '
            'числится одноименная кондитерская фабрика. Предприятие занимается выпуском '
            'зефира, пастилы, суфле, конфет и десертов. Продукция распространяется через '
            'крупные торговые сети, маркетплейсы, а также фирменные магазины в ТЦ «Гостиный '
            'двор» (Кронштадт) и здании Московского вокзала (Петербург).'
        ),
    ),
]


def main(write):
    data = json.load(open(PATH, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}

    plan = []
    for fix in FIXES:
        deal = by_id.get(fix['deal_id'])
        assert deal is not None, 'нет сделки %s' % fix['deal_id']
        target_event = None
        for ev in deal.get('events') or []:
            note = ev.get('note') or ''
            if note.endswith(fix['old_tail']) and 255 <= len(note) <= 260:
                target_event = ev
                break
        assert target_event is not None, \
            '%s: не нашли событие, обрубленное на %r' % (fix['deal_id'], fix['old_tail'])
        assert fix['new_note'].startswith(target_event['note'][:-len(fix['old_tail'])].rstrip()), \
            '%s: новый текст не продолжает старый дословно с самого начала' % fix['deal_id']
        plan.append((fix['deal_id'], target_event, fix['new_note']))

    for deal_id, ev, new_note in plan:
        print('Сделка %s: %d -> %d знаков' % (deal_id, len(ev['note']), len(new_note)))

    if not write:
        print('\nСухой прогон. Запись — с ключом --write.')
        return

    for deal_id, ev, new_note in plan:
        ev['note'] = new_note

    for deal_id, ev, new_note in plan:
        assert by_id[deal_id] is not None
        found = any((e.get('note') == new_note) for e in by_id[deal_id]['events'])
        assert found, '%s: запись не применилась' % deal_id

    with open(PATH, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('\nЗаписано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
