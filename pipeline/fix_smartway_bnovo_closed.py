import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g087764ec'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Закрыта'

OLD_EXTRA = (
    'Сделка по выкупу платформы для бронирования отелей Bnovo компанией '
    'Smartway, сервисом по организации командировок, контролируемым '
    'компанией 1С. ДКП подписан, изменения в ЕГРЮЛ пока не проведены. '
    'Продавец — Валентин Викторович Микляев.'
)
NEW_EXTRA = (
    'Сделка по выкупу платформы для бронирования отелей Bnovo компанией '
    'Smartway, сервисом по организации командировок, контролируемым '
    'компанией 1С. Продавец лично подтвердил закрытие сделки: «Я уже '
    'подписал договор о полной продаже компании и я также ушел с поста '
    'генерального директора» (Валентин Микляев, апрель 2024 года). '
    'Реестр подтверждает переход: единственный учредитель ООО «Биново» '
    'сегодня — ООО «Савади», структура владения которого совпадает с '
    'владельцами самого Smartway («1С» 51%, Елена Яремко 44,1%, '
    'Александр Коляскин 4,9%). Выручка Bnovo выросла до 514,5 млн руб. '
    'за 2025 год, но год закрыт убытком 34,9 млн руб.'
)

NEW_SRC = [
    ['svoedeloplus.ru', 'https://svoedeloplus.ru/2024/04/30/kompaniya-bnovo-smenila-vladelcza/'],
    ['РБК Компании', 'https://companies.rbc.ru/id/1177847151734-ooo-binovo/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS
    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== status: станет ===')
    print(NEW_STATUS)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['status'] = NEW_STATUS
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
