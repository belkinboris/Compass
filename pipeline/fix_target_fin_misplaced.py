def get_field(card, path):
    obj = card
    for part in path.split('.'):
        if not isinstance(obj, dict):
            return None
        obj = obj.get(part)
    return obj


def set_field(card, path, value):
    parts = path.split('.')
    obj = card
    for part in parts[:-1]:
        obj = obj.setdefault(part, {})
    obj[parts[-1]] = value


def main(argv):
    data = json.load(open(DATA, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}

    for cid, src_field, src_old, dst_field, dst_old, _dst_new in MOVES:
        current = get_field(by_id[cid], src_field)
        assert current == src_old, \
            '%s.%s: поле уже другое: %r' % (cid, src_field, str(current)[:60])
        if dst_field:
            dst_current = get_field(by_id[cid], dst_field)
            assert dst_current == dst_old, \
                '%s.%s: поле-назначение уже другое: %r' % (cid, dst_field, str(dst_current)[:60])

    print('Переносов: %d' % sum(1 for m in MOVES if m[3]))
    print('Снятий без переноса: %d' % sum(1 for m in MOVES if not m[3]))
    for cid, src_field, _o, dst_field, _do, dn in MOVES:
        if dst_field:
            print('  %s: eco.target_fin -> %s' % (cid, dst_field))
        else:
            print('  %s: eco.target_fin -> снято (штамп)' % cid)

    if '--write' not in argv:
        print('\nСухой прогон. Запись — с ключом --write.')
        return 0

    for cid, src_field, _src_old, dst_field, _dst_old, dst_new in MOVES:
        set_field(by_id[cid], src_field, '—')
        if dst_field:
            set_field(by_id[cid], dst_field, dst_new)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('ЗАПИСАНО.')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
