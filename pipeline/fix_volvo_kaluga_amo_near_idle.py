# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
geaedd22c (ГК «Промышленные инвестиции» приобрела завод Volvo в
Калуге, 01.10.2023, статус «Закрыта») — завод перезапущен под новым
брендом, но работает на малой доле исторической мощности и с
остановкой в 2025-2026 годах.

Проверено лично прямым WebFetch (Интерфакс, 01.04.2026): «В 2025 году
Ural Next собирали в Калуге до мая, затем временно приостановили»,
«С 1 апреля 2026 года на основании приказа №АМО/2603-01 от 11.03.2026
обществом возобновляется выполнение работ по серийной сборке грузовых
автомобилей».

По данным саб-агента (АиФ Калуга и 1prime.ru, 09.06.2026, не
дозаверено отдельным WebFetch): «по итогам года предприятие выпустит
порядка 1,5 тысячи грузовиков» — около 10% от досанкционной мощности
завода (15 тыс. машин в год); завод переименован в АО «АМО»
(«Автомобильное моторное общество»), выпускает модели линейки
«Урал Next» из машинокомплектов завода «Урал» в Миассе.

НЕ ВКЛЮЧЕНО: сборка беспилотников «Яндекса» на площадке — саб-агент
нашёл только видео на Rutube без текстового источника с цитатой, не
внесено; другие приобретения ГК «Промышленные инвестиции» в автопроме
— не найдено; статус карточки не меняется — это судьба актива ПОСЛЕ
сделки, а не самой сделки.

Запуск: python3 pipeline/fix_volvo_kaluga_amo_near_idle.py
        python3 pipeline/fix_volvo_kaluga_amo_near_idle.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'geaedd22c'

OLD_EXTRA = (
    'Деал касается продажи бывшего завода Volvo в Калуге группе '
    'компаний ГК «Промышленные инвестиции», связанной с миллионером '
    'Дмитрием Стрежневым. В начале сентября активы Volvo перешли под '
    'операционный контроль структур бизнесмена Игоря Кима. Завод '
    'специализируется на производстве грузовиков мощностью 15 тыс. '
    'машин в год.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Завод переименован в АО «АМО» и выпускает грузовики «Урал '
    'Next» из машинокомплектов завода «Урал». Производство '
    'останавливалось с мая 2025 по апрель 2026 года; по плану на 2026 '
    'год завод выпустит около 1,5 тыс. машин — порядка 10% от '
    'исторической мощности.'
)

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/russia/1081375'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
