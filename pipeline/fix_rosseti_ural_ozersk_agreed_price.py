# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g3bebdacf («Россети Урал» выкупила электросетевой комплекс Озерска у
ПАО «Форвард энерго», статус «Закрыта», сумма «Не раскрыта») — нашлась
цена, согласованная сторонами ДО закрытия сделки.

Проверено лично прямым WebFetch (BigPowerNews, 20.02.2023): «Цена
сделки: 250 млн рублей, в том числе НДС 20%», стороны — «ОАО «МРСК
Урала» (работает под брендом «Россети Урал»)» (покупатель) и «ПАО
«Фортум»» (продавец, будущий «Форвард энерго») — те же стороны, что и
в карточке. Дата одобрения советом директоров в источнике не названа,
только дата публикации.

`sum`/`eco.sum` НЕ меняются на эту цифру: источник датирован февралём
2023 года, за год до закрытия сделки (карточка датирует само закрытие
2024 годом) — это согласованная СТОРОНАМИ цена на момент одобрения
сделки, а не обязательно окончательная цена закрытия год спустя (родня
уже записанного урока про цену листинга, только здесь источник называет
её именно «ценой сделки», а не рыночным ожиданием продавца, — разница
тоньше, и год расхождения между согласованием и закрытием делает риск
устаревания цены реальным). Внесено в `eco.context` с честной пометкой
«согласованная в 2023 году», не в `sum`.

НЕ ВКЛЮЧЕНО: продолжение консолидации «Россети Урал» в Челябинской
области после 2024 года (Троицк, Снежинск, Трёхгорный, 2024-2025) — по
проверке лично прямым WebFetch (cheltoday.ru, 06.02.2025) это приём
МУНИЦИПАЛЬНЫХ сетей по требованию законодательства, отдельная от
«Форвард энерго» история, Озерск там не упоминается; судьба Fortum в
России (Росимущество управляет пакетом с апреля 2023, компания заявляет
о продаже активов «когда это станет возможным», BigPowerNews,
15.08.2025) — общий фон, не факт об ЭТОЙ карточке.

Запуск: python3 pipeline/fix_rosseti_ural_ozersk_agreed_price.py
        python3 pipeline/fix_rosseti_ural_ozersk_agreed_price.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g3bebdacf'

OLD_EXTRA = (
    '«Россети Урал» выкупила электросетевой комплекс Озерска, включающий '
    'подстанцию 110/6 кВ (50 МВА), 169 трансформаторных и распределительных '
    'подстанций, 477,8 км воздушных и кабельных линий электропередачи. '
    'Комплекс обеспечивает электричеством 77 тыс. жителей Озерска. С ноября '
    '2021 года объекты находились в аренде у Челябинского филиала «Россети '
    'Урал».'
)
NEW_EXTRA = OLD_EXTRA + (
    ' По данным отраслевого издания, ещё в феврале 2023 года стороны '
    'согласовали цену сделки — 250 млн руб. с НДС; окончательная сумма '
    'закрытия сделки в 2024 году публично не подтверждена.'
)

NEW_SRC = [
    ['BigPowerNews', 'https://www.bigpowernews.ru/news/document107698.phtml'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
