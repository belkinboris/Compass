"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка ge3a1be68
(Магнит купил 33% сети Самбери на Дальнем Востоке, август 2024).
Дельта-поиск нашёл реструктуризацию опциона на выкуп оставшихся долей и
рост сети в 2025-2026 годах. Проверено лично прямым WebFetch
(eastrussia.ru, 17.02.2026).

1) Фактическая цена 33% и структура опциона изменились с момента
последнего чтения: «Ретейлер приобрёл её за 9,2 млрд рублей на условиях
«отложенного возмещения»» — конкретная цифра, а не оценка (не заменяет
`sum`/`eco.sum`, которые остаются диапазоном экспертной оценки за пакет —
цифра из ОДНОГО источника без второго подтверждения, решение о замене
поля оставлено человеку). Опцион сменился с изначально описанного «право
выкупа в течение пяти лет» на конкретный пут миноритариев: «опцион-пут,
подразумевающий передачу «Магниту» 66,99% в 2028-2029 гг.», с
сокращёнными обязательствами — «"Магнит" провел реструктуризацию сделки,
сократив свои будущие финансовые обязательства до 16,2 млрд рублей».

2) Рост сети после сделки (retail.ru, 16.02.2026): «В 2025 году сеть
"Самбери" открыла 46 новых магазинов на Дальнем Востоке» — «37 таких
магазинов под вывеской «Близкий»», 8 супермаркетов «Самбери».

3) Опцион НЕ исполнен по крайней мере до сентября 2025 (retail.ru,
04.09.2025): «"Магнит" владеет 33,01% в "Самбери" с правом выкупа
оставшихся долей» — доля не выросла с даты закрытия.

НЕ включены: расхождение в имени одного из совладельцев («Ольга
Меркулова» у eastrussia.ru против «Марина Меркулова» в карточке) — не
переименовано механически, это может быть опечатка источника, требует
отдельной проверки по ЕГРЮЛ; консультант продавца — не назван ни в одном
источнике.

Запуск: python3 pipeline/fix_magnit_samberi_option_restructure.py
        python3 pipeline/fix_magnit_samberi_option_restructure.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'ge3a1be68'

OLD_CONTEXT = '—'
NEW_CONTEXT = (
    'По данным на февраль 2026 года, структура опциона на выкуп '
    'оставшейся доли изменилась: «"Магнит" провел реструктуризацию '
    'сделки, сократив свои будущие финансовые обязательства до 16,2 млрд '
    'рублей», а опцион на выкуп сформулирован как «опцион-пут, '
    'подразумевающий передачу «Магниту» 66,99% в 2028-2029 гг.» — «"Магнит" '
    'владеет 33,01% в "Самбери" с правом выкупа оставшихся долей», по '
    'состоянию на сентябрь 2025 года доля ещё не выросла (retail.ru, '
    'eastrussia.ru). Сеть продолжает расти: «в 2025 году сеть "Самбери" '
    'открыла 46 новых магазинов на Дальнем Востоке» (retail.ru).'
)

NEW_SRC = [
    ['EastRussia', 'https://www.eastrussia.ru/material/propusk-na-vostok-kak-lenta-izmenit-konkurentsiyu-v-dalnevostochnom-riteyle/'],
    ['Retail.ru', 'https://www.retail.ru/news/v-2025-godu-set-samberi-otkryla-46-novykh-magazinov-na-dalnem-vostoke-16-fevralya-2026-274529/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
