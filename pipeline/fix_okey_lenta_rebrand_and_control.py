# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка g74fd5cdb («Земун»/
«Лента» получила контроль над «РБФ ритейл»/«О'кей»): дельта-поиск нашёл
дальнейшие шаги структуры сделки и начало ребрендинга. Не через
review.py: несколько разных источников на одно поле.

Источники — читал напрямую (fetch_article_texts.py, все закэшированы):
Retail.ru (10.08.2026), Коммерсантъ (10.08.2026, doc/8876259),
kuban.bfm.ru (10.08.2026).
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g74fd5cdb'
OLD_STRUCT = (
    '25 ноября «О’кей» завершила сделку по продаже сегмента '
    'гипермаркетов менеджменту. Компания со всеми дочерними структурами '
    'перешла под управление «РБФ ритейл»'
)
ADDITION = (
    'Структура сделки прояснилась дальше: «Официально о покупке '
    'компания объявила в начале июня 2026 года, когда «Лента» получила '
    '100% в ООО «РБФ-Ритейл»» — то есть промежуточная структура «Земун» '
    'уступила место прямому владению «Ленты». «Согласно данным СПАРК, '
    'ООО «РБФ Ритейл», подконтрольное «Ленте», 10 августа 2026 года '
    'получило 99,56% в УК «О’кей»» — сама операционная компания сети '
    'перешла под контроль «РБФ Ритейл». Начался ребрендинг: «В '
    'Краснодаре работают четыре гипермаркета «О’кей», один из них уже '
    'сменил вывеску на «Гипер Ленту»», «Остальные магазины сети по всей '
    'стране планируется ребрендировать до конца 2026 года».'
)
NEW_STRUCT = OLD_STRUCT + '. ' + ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['law']['struct'] == OLD_STRUCT, \
        f"law.struct: неожиданное значение {deal['law']['struct']!r}"

    print(f"{CARD_ID} law.struct: += прямое владение «Ленты» и начало ребрендинга")
    deal['law']['struct'] = NEW_STRUCT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
