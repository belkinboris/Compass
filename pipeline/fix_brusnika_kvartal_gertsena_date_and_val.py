"""Месячная очередь, 8 сентября 2026 — карточка `cf2375bf5` (ГК
«Брусника» купила девелоперский проект «Квартал Герцена» у ГК «Самолет»)
несла дату «2025-09-30» — то же самое системное происхождение, что и у
уже исправленных `ceeb8c214`/`cc2929a95`/`c514e8712`/`cb30dbbc8`: дата
публикации рэнкинга «Ъ — Сделки года», а не дата самой сделки.

Реальная дата — 28 декабря 2024 года (СУББОТА), день, когда ГК «Самолет»
объявила о закрытии сделки. Личный WebFetch (smart-lab.ru/blog/news/
1102318.php, со ссылкой на «Ренессанс Капитал», 09.01.2025): «В субботу
(28 декабря) ГК Самолет сообщил о закрытии сделки». Независимо
подтверждено собственной страницей инвесторов «Брусники»
(ekaterinburg.brusnika.ru/investors/news/kvartal-gertzena, 15.01.2025):
«сделка состоялась в конце декабря 2024 года».

Год переносится (2025 -> 2024) — это НЕ уточнение дня внутри известного
года, а перенос в другой год, поэтому правка НЕ через `review.py`
(`date_is_supported()` его не пропускает), а отдельным одноразовым
скриптом, как и предыдущие карточки этого класса дефекта
(`fix_mini_ranking_dates_batch1/2/3.py`).

Заодно добавлена независимая оценка стоимости проекта: «Ренессанс
Капитал» оценил «Квартал Герцена» «более чем в 10 млрд руб.» (та же
статья smart-lab.ru) — сумма сделки сторонами по-прежнему не раскрыта
(источник прямо говорит, что фактическая сумма появится только в
отчётности «Самолета» по МСФО за 2024 год), поэтому `sum`/`eco.sum`
остаются «Не раскрыта», а оценка идёт в `eco.val` (поле было пустым).

Запуск:
    python3 pipeline/fix_brusnika_kvartal_gertsena_date_and_val.py            # сухой прогон
    python3 pipeline/fix_brusnika_kvartal_gertsena_date_and_val.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'
CARD_ID = 'cf2375bf5'

OLD_DATE = '2025-09-30'
NEW_DATE = '2024-12-28'

NEW_VAL = (
    '«Ренессанс Капитал» оценил стоимость проекта «Квартал Герцена» '
    'более чем в 10 млрд ₽; фактическая сумма сделки не раскрыта — '
    'стороны сообщили, что она станет известна из отчётности ГК '
    '«Самолет» по МСФО за 2024 год.'
)


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}
    card = by_id[CARD_ID]

    assert card['date'] == OLD_DATE, 'дата уже другая: %r' % (card['date'],)
    assert card['eco'].get('val') is None, \
        'eco.val уже занят: %r' % (card['eco'].get('val'),)

    print('date: %r -> %r' % (OLD_DATE, NEW_DATE))
    print('eco.val: добавляется оценка «Ренессанс Капитала»')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    card['date'] = NEW_DATE
    card['eco']['val'] = NEW_VAL

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
