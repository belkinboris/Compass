# -*- coding: utf-8 -*-
"""ПСБ/ТРК «Родник» и «Алмаз» (`gmru-psb-tpk-chelyabinsk`): почасовой приток
31 августа 2026 нашёл два черновика сырья про эту же карточку (совпадение
не по адресу источника, а по редким общим словам заголовка — «Родник»/
«Алмаз» — раздел «Известные проблемы» CLAUDE.md уже фиксировал этот же
сюжет на дату 16 августа, но сами факты в карточку тогда не легли).

Новое, дословно из двух статей 74.ru:
1) 5 августа 2026 третий по счёту аукцион (назначенный на 6 августа,
   параметры — стартовая цена 12,2 млрд ₽, задаток 2,4 млрд ₽ — это ровно
   те условия, что уже стоят в law.terms) признан несостоявшимся: заявок
   не было вовсе.
2) 7 августа 2026 объявлен новый раунд — продажа через публичное
   предложение со снижением цены до 50% (минимум 6,08 млрд ₽ при той же
   стартовой цене 12,2 млрд ₽), торги на площадке Российского аукционного
   дома назначены на 17 августа, заявки — до вечера 13 августа.

Итог четвёртого раунда (17 августа) в найденных источниках не подтверждён
— не утверждается здесь как факт.

Дописано в `law.terms` (не через review.py: обе цитаты покрывают только
новые предложения, а `check()` требует дословного совпадения ВСЕГО
значения целиком с одной цитатой — та же граница, что у уже принятых
одноразовых дополнений вроде `fix_afk_sistema_vtb_ozon_structure_detail.py`).

Запуск: python3 pipeline/fix_psb_tpk_chelyabinsk_third_auction_failed_and_new_terms.py           # проверка
        python3 pipeline/fix_psb_tpk_chelyabinsk_third_auction_failed_and_new_terms.py --write   # запись
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gmru-psb-tpk-chelyabinsk'
OLD_TERMS = (
    'Претендентам необходимо перечислить задаток в размере 2 432 879 400 '
    'руб. Прием заявок начинается 29 июля 2026 года и завершится 4 августа '
    '2026 года. Торги начнутся 6 августа 2026 года в 10:00 по московскому '
    'времени на электронной площадке АО «Российский аукционный дом»'
)
ADDITION = (
    '5 августа 2026 года аукцион признан несостоявшимся ввиду отсутствия '
    'заявок — уже третий неудачный аукцион по продаже компании «Родник». '
    '7 августа 2026 года объявлен новый раунд продажи посредством '
    'публичного предложения: стартовая стоимость та же — 12,2 млрд руб., '
    'снижение цены может составить до 50% от начальной, крайняя цена '
    'определена в 6,08 млрд руб.; торги назначены на 17 августа на '
    'электронной площадке Российского аукционного дома, заявки '
    'принимались до вечера 13 августа.'
)
NEW_TERMS = OLD_TERMS + ' ' + ADDITION
NEW_SRC = [
    ['74.ru', 'https://74.ru/text/business/2026/08/05/76572013/'],
    ['74.ru', 'https://74.ru/text/business/2026/08/07/76577105/'],
]


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    card = next((c for c in data['deals'] if c['id'] == CARD_ID), None)
    assert card is not None, '%r не найдена в базе' % CARD_ID
    assert card.get('law', {}).get('terms') == OLD_TERMS, (
        'law.terms уже другое: %r' % card.get('law', {}).get('terms'))

    print('ДОБАВЛЕНО: %r' % ADDITION)
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return 1

    card['law']['terms'] = NEW_TERMS
    src = card.setdefault('src', [])
    for s in NEW_SRC:
        if s not in src:
            src.append(s)
    json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('ЗАПИСАНО.')
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv[1:]))
