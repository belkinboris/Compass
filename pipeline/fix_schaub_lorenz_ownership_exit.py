# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g3cac5f0f (Гусейн Иманов приобрел 30% доли в Schaub Lorenz) — оба
совладельца на момент сделки (Иманов и Соколов) впоследствии вышли из
компании, а финансовые показатели резко упали. Проверено лично прямым
WebFetch двух источников.

`eco.context` (дополнено). По данным ЕГРЮЛ (tbank.ru), к моменту этого
обыска (август 2026) единственным владельцем ООО «Шмит Компани» стал
Игорь Росляков: дословно — «Доля учредителя Росляков Игорь Михайлович
в уставном капитале изменилась с 50% на 100%», «Доля учредителя Иманов
Гуламгусейн Мехди Оглы в уставном капитале изменилась с 50% на 0%».
Оба совладельца на момент сделки 2024 года (Иманов и Соколов) к этому
моменту вышли из капитала — точная дата и год этих изменений на
проверенных страницах не указаны (только день и месяц, «27 апреля»,
без года), поэтому не утверждается точнее, чем «к августу 2026».

`eco.target_fin` (дополнено). Финансовые показатели резко упали.
Дословно (saby.ru): доходы за 2024 год — «1 565.2» млн ₽, чистая
прибыль — «55.9» млн ₽; за 2025 год доходы — «897.2» млн ₽ (падение
на 42,7%), чистая прибыль — «15.9» млн ₽ — против 1,5 млрд ₽ выручки
и 125 млн ₽ прибыли в 2023 году (уже в карточке).

НЕ ВКЛЮЧЕНО: точная дата и год выхода Иманова и Соколова из капитала —
источники дают только «27 апреля» без года; судьба Соколова и Иманова
после выхода (новые активы) — не найдена ни в одном источнике; точная
сумма сделки 2024 года — по-прежнему не раскрыта.

Запуск: python3 pipeline/fix_schaub_lorenz_ownership_exit.py
        python3 pipeline/fix_schaub_lorenz_ownership_exit.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g3cac5f0f'

OLD_CONTEXT = (
    'Гуламгусейн Иманов владеет по 70% в торговых ООО «Абсолют» и ООО '
    '«Бизнес Контроль», 51% в ООО «Здоровье нации» (косметология) и '
    '70% в ООО «Смарт Дистрибьюшен» (продажа и производство бытовой '
    'техники Jackie\'s). Выручка последнего ООО в 2023 году составила '
    '339,3 млн руб., чистая прибыль 1,9 млн руб.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' К августу 2026 года оба совладельца на момент сделки 2024 года '
    'вышли из капитала: по данным ЕГРЮЛ, единственным владельцем ООО '
    '«Шмит Компани» стал Игорь Росляков — «доля учредителя Росляков '
    'Игорь Михайлович... изменилась с 50% на 100%», «доля учредителя '
    'Иманов Гуламгусейн Мехди Оглы... изменилась с 50% на 0%» '
    '(tbank.ru).'
)

OLD_TARGET_FIN = (
    'ООО «Шмит Компани» зарегистрировано в 2014 году. До конца января '
    '80% принадлежало Радмиру Соколову, 20% — Игорю Рослякову. С 31 '
    'января господину Соколову принадлежит 50%, господину Иманову — '
    '30%, доля Игоря Рослякова не изменилась. Выручка ООО в 2023 году '
    'составила 1,5 млрд руб., чистая прибыль — 125 млн руб.'
)
NEW_TARGET_FIN = OLD_TARGET_FIN + (
    ' Выручка упала до 1,57 млрд ₽ в 2024 году (прибыль 55,9 млн ₽) '
    'и до 897,2 млн ₽ в 2025 году (падение на 42,7%, прибыль 15,9 млн '
    '₽) (saby.ru).'
)

NEW_SRC = [
    ['tbank.ru', 'https://www.tbank.ru/business/contractor/legal/1167746066509/'],
    ['saby.ru', 'https://saby.ru/contragents/9701028836/772201001'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    assert deal['eco']['target_fin'] == OLD_TARGET_FIN
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== eco.target_fin: станет ===')
    print(NEW_TARGET_FIN)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['eco']['target_fin'] = NEW_TARGET_FIN
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
