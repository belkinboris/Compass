# -*- coding: utf-8 -*-
"""Почасовой приток 5 сентября 2026 (08:20) — новая карточка: совладельцы
ООО «НТЦ «Развитие»» (Роман Шаров и Константин Рябов) в начале августа
2026 года довели свою долю в ООО «МорТехПром» (корпуса пультов
управления корабельными системами, металлоконструкции для нефтегазовой
сферы) до 100% — Роман Шаров выкупил оставшиеся 40% у бывшего
гендиректора ЦКБ «Нептун» Сергея Бескровного (сам «Нептун» банкротится
с июля 2025 года, к этой сделке отношения не имеет). Это уже ВТОРАЯ
покупка долей у Бескровного тем же дуэтом: первые 60% куплены в декабре
2025 года — упомянуто как история актива в `eco.context`, отдельной
карточки для декабрьской сделки в базе нет и не заводится (слишком
давняя, чтобы быть «новой» для притока; решение об отдельной карточке —
не для этой рутины).

Источник называет только месяц закрытия («в первой половине августа»),
не день — по правилу «не сочинять день» дата ставится годом,
месяц остаётся текстом в `eco.context`.

Заголовок называет реальных людей, а не растиражированную фразу
источника («Владельцы промкластера... купили...») — по правилу «не
копировать заголовок источника дословно».

Запуск: python3 pipeline/fix_add_ntc_razvitie_mortehprom_card.py [--write]
"""
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'ingest'))

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PENDING_PATH = os.path.join(ROOT, 'static', 'data', 'pending.json')
BASE_PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

NEW_ID = 'gmortehprom2026'
MORTEHPROM_ID = 'gmortehprom'


def main(write=False):
    import promote

    with open(PENDING_PATH, encoding='utf-8') as f:
        pending = json.load(f)
    with open(BASE_PATH, encoding='utf-8') as f:
        base = json.load(f)

    ids = {c['id'] for c in base['deals']} | {c['id'] for c in pending['cards']}
    assert NEW_ID not in ids
    assert MORTEHPROM_ID not in base['companies']

    base['companies'][MORTEHPROM_ID] = {
        'name': 'ООО «МорТехПром»',
        'ind': 'Машиностроение',
        'desc': ('Петербургский производитель корпусов пультов управления '
                 'корабельными системами (алюминиевые и композитные, с '
                 'электромонтажными работами) и металлоконструкций для '
                 'нефтегазовой сферы. Основана в 2014 году.'),
        'kpi': ['Профиль', 'Автоматический'],
    }

    draft = {
        'date': '2026',
        'title': 'Роман Шаров довёл долю в «МорТехПроме» до 100%, выкупив оставшиеся 40% у Сергея Бескровного',
        'ind': 'Машиностроение',
        'type': 'M&A',
        'status': 'Закрыта',
        'src': [['«Деловой Петербург»',
                 'https://www.dp.ru/a/2026/09/04/vladelci-promklastera-v-kolpino']],
    }
    card = promote.to_card(draft, NEW_ID)
    card['seller'] = 'Сергей Бескровный'
    card['buyer_name'] = 'Роман Шаров'
    card['asset'] = 'ООО «МорТехПром»'
    card['asset_id'] = MORTEHPROM_ID
    card['eco']['share'] = (
        'ООО «МорТехПром»: корпуса пультов управления корабельными '
        'системами (алюминий, композит, электромонтаж), '
        'металлоконструкции для нефтегазовой сферы. Основана в 2014 '
        'году в Санкт-Петербурге.'
    )
    card['law']['struct'] = (
        'Владельцы «МорТехПрома» с начала августа 2026 года: Роман '
        'Шаров — 70%, Константин Рябов — 30% (оба — совладельцы ООО '
        '«НТЦ «Развитие»», где им принадлежит по 50%).'
    )
    card['eco']['context'] = (
        'Сделка закрыта в первой половине августа 2026 года. Это вторая '
        'покупка долей «МорТехПрома» у Сергея Бескровного тем же дуэтом: '
        'первые 60% куплены в декабре 2025 года. Сергей Бескровный '
        'приобрёл 50% «МорТехПрома» в марте 2023 года и довёл долю до '
        '100% в январе 2025 года; в 2023–2024 годах возглавлял '
        'петербургское ЦКБ «Нептун», которое обанкротилось летом 2025 '
        'года после срыва контракта на 2,3 млрд ₽ с ГТЛК на строительство '
        'пассажирских судов — само ЦКБ «Нептун» к этой сделке отношения '
        'не имеет. Выручка «МорТехПрома» сократилась с 18,9 млн ₽ (2024) '
        'до 9,2 млн ₽ (2025); по данным ФНС, на 1 августа 2026 года у '
        'компании 3,9 млн ₽ налоговой недоимки, операции по счетам '
        'приостановлены.'
    )

    pending['cards'].append(card)

    print(f'Добавлена карточка {NEW_ID} в pending.json: {card["title"]}')

    if write:
        with open(BASE_PATH, 'w', encoding='utf-8') as f:
            json.dump(base, f, ensure_ascii=False, indent=1)
            f.write('\n')
        with open(PENDING_PATH, 'w', encoding='utf-8') as f:
            json.dump(pending, f, ensure_ascii=False, indent=1)
            f.write('\n')
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
