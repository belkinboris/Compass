# -*- coding: utf-8 -*-
"""Чинит серьёзный дефект карточки g778efcb9 («Группа «Русские фонды»
получила контроль над отелем Baikal View на Байкале»): единственный
источник карточки — НЕ ПРО ЭТУ СДЕЛКУ.

Найдено в рамках G5 (PRODUCT_ROADMAP.md): замер на бессодержательные
плейсхолдеры `eco.val` вывел на карточку с суммой «1 млрд ₽ (по
оценке)», не подтверждённой источником. При проверке выяснилось хуже:
ссылка `https://www.kommersant.ru/doc/5747145` в `src` ведёт на статью
Коммерсанта «Инвесторы расселяются в Москве» — про покупку той же
группой «Русские фонды» 19,9% ДРУГОЙ гостиницы, «Азимут Олимпик» в
Москве, у Олимпийского комплекса. Про Baikal View, остров Ольхон или
1 млрд ₽ в этой статье нет ни слова — ссылка перепутана с другой сделкой
того же покупателя, а не просто устарела. Тот же класс дефекта, что уже
описан в CLAUDE.md («Ссылка не открывается» и родственные уроки), только
здесь ссылка технически рабочая, просто ведёт на чужую сделку.

Верный источник найден WebSearch: Коммерсантъ, «"Русские фонды" окунулись
в Байкал» (25.09.2023, kommersant.ru/doc/6236835) — заголовок и дата
совпадают с карточкой. Но и в НЁМ сумма «около 1 млрд руб.» относится к
ОТЕЛЮ ЦЕЛИКОМ («получила контроль над отелем Baikal View... стоимостью
около 1 млрд руб.»), а не к доле, которую купили «Русские фонды», — та
же цифра повторена как независимая оценка основателя Ivashkevich
Hospitality Станислава Ивашкевича («текущая стоимость отеля может
составлять около 1 млрд руб.»). Ни цена, ни оценка именно СДЕЛКИ (доли)
в источнике не названы — известен только процент, оставшийся у
миноритария (Марина Улаханова, 13,62%, что и даёт уже стоящие в `extra`
86,38% у «Русских фондов» — эта цифра источником подтверждается и не
трогается). Умножать оценку всего отеля на долю и получать
«подразумеваемую» цену сделки — самостоятельное вычисление, а не факт
из источника (тот же класс ошибки, которую эта правка и убирает) —
поэтому `sum`/`eco.sum` честно снимаются, а не заменяются расчётной
цифрой.
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g778efcb9'
OLD_SUM = '1 млрд ₽ (по оценке)'
NEW_SUM = 'Не раскрыта'
OLD_VAL = 'Экспертная оценка'
NEW_VAL = ('Стоимость всего отеля (не доли, купленной «Русскими '
           'фондами»): по данным «Коммерсанта», Baikal View оценивается '
           'около 1 млрд руб.; ту же цифру называет основатель Ivashkevich '
           'Hospitality Станислав Ивашкевич — «текущая стоимость отеля '
           'может составлять около 1 млрд руб.» Цена самой сделки '
           'источниками не раскрыта.')
OLD_SHARE = '—'
NEW_SHARE = ('Приобретены 86,38% в компаниях, владеющих отелем Baikal '
             'View (99 номеров, три звезды) на острове Ольхон; 13,62% '
             'остались у прежнего совладельца Марины Улахановой.')
OLD_SRC = ['Коммерсантъ', 'https://www.kommersant.ru/doc/5747145']
NEW_SRC = ['Коммерсантъ', 'https://www.kommersant.ru/doc/6236835']


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['sum'] == OLD_SUM, f"sum: ожидали {OLD_SUM!r}, нашли {deal['sum']!r}"
    assert deal['eco']['sum'] == OLD_SUM, \
        f"eco.sum: ожидали {OLD_SUM!r}, нашли {deal['eco']['sum']!r}"
    assert deal['eco']['val'] == OLD_VAL, \
        f"eco.val: ожидали {OLD_VAL!r}, нашли {deal['eco']['val']!r}"
    assert deal['eco']['share'] == OLD_SHARE, \
        f"eco.share: ожидали {OLD_SHARE!r}, нашли {deal['eco']['share']!r}"
    assert deal['src'] == [OLD_SRC], f"src: ожидали {[OLD_SRC]!r}, нашли {deal['src']!r}"

    print(f"{CARD_ID} sum: {OLD_SUM!r} -> {NEW_SUM!r}")
    print(f"{CARD_ID} eco.sum: {OLD_SUM!r} -> {NEW_SUM!r}")
    print(f"{CARD_ID} eco.val: {OLD_VAL!r} -> {NEW_VAL!r}")
    print(f"{CARD_ID} eco.share: {OLD_SHARE!r} -> {NEW_SHARE!r}")
    print(f"{CARD_ID} src: {OLD_SRC!r} -> {NEW_SRC!r} (заменена, не дописана — старая ссылка "
          "не про эту сделку)")

    deal['sum'] = NEW_SUM
    deal['eco']['sum'] = NEW_SUM
    deal['eco']['val'] = NEW_VAL
    deal['eco']['share'] = NEW_SHARE
    deal['src'] = [NEW_SRC]

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
