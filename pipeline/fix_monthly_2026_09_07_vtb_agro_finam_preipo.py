import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

VTB_ID = 'c7403d4db'
VTB_OLD_CONTEXT = (
    'В середине октября стало известно, что Костин попросил президента '
    'Владимира Путина дать правительству, Минфину и Генпрокуратуре '
    'поручение передать группе в управление и затем продать 13 '
    'юрлиц с сельскохозяйственными активами в Краснодарском крае. В '
    'периметр интереса ВТБ попали «Агрофирма „Дружба“», «Маяк '
    'Революции», «Лосево», «Юг-Агропром», «Агрофирма „Воздвиженская“» '
    'и другие компании, которые в мае по решению суда были переданы '
    'федеральным властям по заявлению Генпрокуратуры. Ранее их '
    'контролировала семья бывшего главы Кавказского района '
    'Краснодарского края Виталия Очкаласова. По версии следствия, '
    'активы достались ему преступным путём, а их общая стоимость '
    'оценивалась в 5,5 млрд ₽.'
)
VTB_NEW_CONTEXT = (
    VTB_OLD_CONTEXT + ' План создания холдинга не реализован — банк '
    'решил распродать сельхозактивы по отдельности; причина, по '
    'словам главы ВТБ Андрея Костина, — готовящееся с 1 апреля 2027 '
    'года регулирование ЦБ, ограничивающее вложения банков в '
    'непрофильные активы (цитату о самом решении см. в разделе '
    '«Дополнительная информация»). Общая оценочная стоимость пакета — '
    'свыше 55 млрд ₽. По крупнейшему активу, агрокомплексу '
    '«Лабинский», к сентябрю 2026 года соглашение об условиях продажи '
    'с покупателем уже заключено, закрытие ожидается до конца 2026 '
    'года; имя покупателя не раскрывается.'
)

FN_ID = 'c3c15a888'
FN_OLD_STRUCT = '—'
FN_NEW_STRUCT = (
    'Фонд запущен под названием ЗПИФ «Финам и БСФ: Новые чемпионы» — '
    'партнёром выступает инвестиционный банк BSF Partners Алексея '
    'Басова. Целевая доходность — до 40% годовых, 50% полученного '
    'дохода распределяется между пайщиками каждые шесть месяцев.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    vtb = by_id[VTB_ID]
    fn = by_id[FN_ID]

    assert vtb['eco']['context'] == VTB_OLD_CONTEXT
    assert fn['law']['struct'] == FN_OLD_STRUCT

    print('=== c7403d4db: eco.context ===')
    print(VTB_NEW_CONTEXT)
    print()
    print('=== c3c15a888: law.struct ===')
    print(FN_NEW_STRUCT)

    if write:
        vtb['eco']['context'] = VTB_NEW_CONTEXT
        fn['law']['struct'] = FN_NEW_STRUCT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
