import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g6bf4b33c'

OLD_CONTEXT = (
    'В настоящее время команда Кремлева по поручению президента РФ '
    'Владимира Путина совместно с Курчатовским институтом, Российской '
    'академией наук и другими ведущими научными организациями страны '
    'реализует проект «Большой Серпухов», который предполагает создание в '
    'Подмосковье научных центров и высокотехнологичных наукоемких отраслей '
    'промышленности. Одним из партнеров в рамках строительства Наукограда '
    'выступает «АВА».'
)
CONTEXT_ADDITION = (
    ' 29 октября 2024 года AVA Group, АО «Большой Серпухов» и '
    'правительство Московской области подписали конкретное соглашение — о '
    'создании индустриального парка «Пущино»: «Объем частных инвестиций в '
    'развитие индустриального парка превысит 4 млрд руб.», «более 90 тыс. '
    'кв. м производственных и лабораторных корпусов» и «свыше 1 тыс. '
    'рабочих мест» на участке площадью 53,8 га; «ввод в эксплуатацию... '
    'запланирован на 2026 год» (Коммерсантъ, Интерфакс).'
)
NEW_CONTEXT = OLD_CONTEXT + CONTEXT_ADDITION

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/business/989148'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/7266049'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
