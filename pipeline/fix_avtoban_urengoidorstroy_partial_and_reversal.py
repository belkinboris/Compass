import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gbd3416b4'

OLD_CONTEXT = '—'
NEW_CONTEXT = (
    'Ходатайство в ФАС было подано холдингом «Автобан» через входящую в '
    'него структуру «Ханты-Мансийскдорстрой» — «холдинг «Автобан» и '
    'входящая в него компания «Ханты-Мансийскдорстрой» обратилась в ФАС с '
    'ходатайством о покупке 100% акций подрядчика «Уренгойдорстрой»» '
    '(ura.news). Но куплен был не весь пакет: в марте 2025 года «32% акций '
    'теперь находится в собственности «Автобана», а 68% остается у '
    'директора Александра Рыскова. Но эта доля находится в залоге у '
    'банка» (ura.news). Летом 2026 года «Автобан» полностью вышел из '
    'состава учредителей — «Летом 2026 года структуры холдинга покинули '
    'состав учредителей» (ura.news) — на фоне финансовых проблем '
    'компании: 10 июля 2026 года «Уренгойдорстрой» внесли в реестр '
    'недобросовестных поставщиков, а один из кредиторов заявил о '
    'намерении добиваться его банкротства.'
)

NEW_SRC = [
    ['URA.RU', 'https://ura.news/news/1052900120'],
    ['URA.RU', 'https://ura.news/articles/1053112108'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
