# -*- coding: utf-8 -*-
"""Заметка владельца 11 сентября 2026 (id решения 604, карточка g139db8c2,
«S8 Capital и ГК «МТ-Интеграция» приобрели 79% акций «Аквариуса»»):
«оставляем, но пишем про опровержение в дополнительной информации в
основной вкладке и не забываем источник указать. почему в разделе как
устроена сделка написано "Сделка, возможно, будет проведена через
специальную инвестиционную структуру (SPV)." что значит "возможно будет
проведена"? во-первых, сделка уже была, во-вторых либо структура уже
должна была быть понятна, либо писать предположения не нужно.»

Два дефекта. (1) `law.struct` нёс голое предположение о будущем механизме
уже ЗАКРЫТОЙ сделки — снято, честная пустота. (2) Опровержение
ГК «МТ-Интеграция» уже подробно изложено в `eco.context`, но на главной
вкладке (`extra`) читатель его не видел — перенесена короткая версия факта
с указанием источника (собственный пресс-релиз компании, 22 августа
2025 года — тот же источник, что уже назван в `eco.context`).

Запуск: python3 pipeline/fix_s8_akvarius_extra_denial.py [--write]
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE_PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g139db8c2'
OLD_LAW_STRUCT = 'Сделка, возможно, будет проведена через специальную инвестиционную структуру (SPV).'
OLD_EXTRA = ('Сделка по приобретению 79% акционерного капитала производителя '
             'электроники и радиоэлектронного оборудования. Покупатели — S8 '
             'Capital (холдинг Армена Саркисяна) и ГК «МТ-Интеграция». S8 '
             'Capital — активный покупатель российских активов, ранее '
             'приобретавший активы ушедших иностранцев (Continental, '
             'Bridgestone, Bosch, Otis). ГК «МТ-Интеграция» — интегратор, '
             'сосредоточившийся на интеграторском бизнесе после продажи '
             'операторского бизнеса в 2023 году.')
NEW_EXTRA = (OLD_EXTRA + ' 22 августа 2025 года, на следующий день после '
             'первых публикаций о сделке, ГК «МТ-Интеграция» выпустила '
             'собственный пресс-релиз, в котором назвала сведения о своём '
             'вхождении в состав акционеров «Аквариуса» не соответствующими '
             'действительности; с тех пор это опровержение не подтверждено '
             'и не опровергнуто повторно.')


def main(write=False):
    with open(BASE_PATH, encoding='utf-8') as f:
        base = json.load(f)

    card = next((c for c in base['deals'] if c['id'] == CARD_ID), None)
    assert card is not None, 'карточка %s не найдена' % CARD_ID
    assert card['law']['struct'] == OLD_LAW_STRUCT, 'law.struct уже другой'
    assert card['extra'] == OLD_EXTRA, 'extra уже другой'

    card['law']['struct'] = '—'
    card['extra'] = NEW_EXTRA

    print('Правка %s: law.struct очищен, extra дополнен опровержением '
          'МТ-Интеграции.' % CARD_ID)

    if write:
        with open(BASE_PATH, 'w', encoding='utf-8') as f:
            json.dump(base, f, ensure_ascii=False, indent=1)
            f.write('\n')
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
