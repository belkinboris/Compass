# -*- coding: utf-8 -*-
"""Дневная очередь (REVISION_BRIEF, первый уровень), g672dcca1 («Минфин
сохраняет планы продать госдолю в Новороссийском морском торговом
порту до конца года», добавлена 2 сентября 2026) — у предмета сделки
(НМТП) не было профиля компании вовсе (`target` пуст), а структурные
поля карточки (кто ещё совладелец, правовое основание, оценка,
кандидат-покупатель) остались незаполненными, хотя всё это было в
источниках.

Проверено лично прямым WebFetch (Ведомости,
https://www.vedomosti.ru/business/articles/2026/05/26/1199856-prodazhi-doli):
«Правительство РФ дополнило прогнозный план приватизации на 2026–2028
гг. пакетом акций «Новороссийского морского торгового порта» (НМТП) в
размере 20% (3,85 млрд шт.)» на основании «распоряжения кабмина от
23 мая 2026 г. № 1197-р»; «"Транснефть" принадлежит 63,08% группы»; у
государства также «золотая акция» — право вето на изменение устава,
ликвидацию, реорганизацию и крупные сделки; «Стоимость 20% акций...
может составить 31–36 млрд руб.»; выручка группы за 2025 год — 76,5
млрд ₽ (+8%), EBITDA — 54,1 млрд ₽ (+12%), чистая прибыль — 40,6 млрд
₽ (+7%); «Наиболее вероятный покупатель 20% НМТП – крупный российский
профильный инвестор или консорциум компаний... приобретение пакета
иностранцами в текущих условиях маловероятно» (Дмитрий Баранов, УК
«Финам менеджмент»); с 7 июня 2026 действуют новые правила (51-ФЗ),
которые «могут потребовать согласования сделки в любом случае — из-за
включения в неё портовой инфраструктуры».

Заведён профиль компании (по образцу уже написанных сильных профилей
— Сбербанк, Яндекс): род деятельности, масштаб (15,5% грузооборота
морских портов РФ), структура акционеров, ключевой инвестпроект.

НЕ ВКЛЮЧЕНО: имя конкретного юрлица-кандидата на покупку блока — ни
один источник его не называет, только экспертную характеристику
(«профильный инвестор или консорциум»), не додумывается до имени;
общая сумма ожидаемых бюджетных поступлений от всей программы
приватизации 2026 года — не нашлась целиком ни в одном источнике.

Запуск: python3 pipeline/fix_nmtp_profile_and_deal_structure.py
        python3 pipeline/fix_nmtp_profile_and_deal_structure.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g672dcca1'
COMPANY_ID = 'g36510f4e'

COMPANY_PROFILE = {
    'name': 'ПАО «Новороссийский морской торговый порт» (НМТП)',
    'ind': 'Порты и инфраструктура',
    'desc': (
        'Крупнейший портовый оператор России и головная компания группы '
        'НМТП: терминалы в Новороссийске, Приморске и Балтийске, '
        'перевалка нефти, нефтепродуктов, угля, руды, удобрений и '
        'контейнеров. В 2025 году на группу пришлось 15,5% грузооборота '
        'морских портов страны (137,4 млн т). Контролирующий акционер — '
        '«Транснефть» (63,08%), у государства через Росимущество — 20% '
        'и «золотая акция». Строит универсальный перегрузочный комплекс '
        'в порту Новороссийска по концессии с государством (120,7 млрд '
        '₽ инвестиций, запуск в 2027 году).'
    ),
    'kpi': ['Профиль', 'Автоматический'],
}

OLD_LAW_STRUCT = '—'
NEW_LAW_STRUCT = (
    'Контролирующий акционер НМТП — «Транснефть» (63,08% группы); у '
    'государства помимо продаваемых 20% сохраняется «золотая акция» — '
    'право вето на изменение устава, ликвидацию, реорганизацию и '
    'крупные сделки. Пакет добавлен в прогнозный план приватизации на '
    '2026–2028 годы распоряжением кабмина от 23 мая 2026 г. № 1197-р.'
)

OLD_LAW_APPR = '—'
NEW_LAW_APPR = (
    'С 7 июня 2026 года действуют новые правила (закон 51-ФЗ), по '
    'которым сделка может потребовать согласования из-за включения в '
    'предмет портовой инфраструктуры, способной быть отнесённой к '
    'критической для государства; для покупателей из недружественных '
    'стран почти наверняка потребуется отдельное решение президента.'
)

OLD_ECO_VAL = '—'
NEW_ECO_VAL = 'Оценка УК «Финам менеджмент» (Дмитрий Баранов) — 31–36 млрд ₽ за 20% акций при обычном аукционе; выше при интересе стратегического инвестора.'

OLD_ECO_RATIONALE = '—'
NEW_ECO_RATIONALE = 'Наиболее вероятный покупатель — крупный российский профильный инвестор или консорциум компаний, ориентированный на развитие транспортной инфраструктуры; приобретение иностранцами в текущих условиях маловероятно.'

OLD_ECO_TARGET_FIN = '—'
NEW_ECO_TARGET_FIN = 'Выручка группы за 2025 год — 76,5 млрд ₽ (+8%), EBITDA — 54,1 млрд ₽ (+12%), чистая прибыль — 40,6 млрд ₽ (+7%).'

NEW_SRC = [
    ['Ведомости', 'https://www.vedomosti.ru/business/articles/2026/05/26/1199856-prodazhi-doli'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal.get('target') is None
    assert deal['law']['struct'] == OLD_LAW_STRUCT
    assert deal['law']['appr'] == OLD_LAW_APPR
    assert deal['eco']['val'] == OLD_ECO_VAL
    assert deal['eco']['rationale'] == OLD_ECO_RATIONALE
    assert deal['eco']['target_fin'] == OLD_ECO_TARGET_FIN
    assert COMPANY_ID not in data['companies']

    existing_urls = {s[1] for s in deal['src']}
    add_src = [s for s in NEW_SRC if s[1] not in existing_urls]
    new_src = deal['src'] + add_src

    print('=== новый профиль компании', COMPANY_ID, '===')
    print(json.dumps(COMPANY_PROFILE, ensure_ascii=False, indent=1))
    print('\n=== target: станет ===')
    print(COMPANY_ID)
    print('\n=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)
    print('\n=== law.appr: станет ===')
    print(NEW_LAW_APPR)
    print('\n=== eco.val: станет ===')
    print(NEW_ECO_VAL)
    print('\n=== eco.rationale: станет ===')
    print(NEW_ECO_RATIONALE)
    print('\n=== eco.target_fin: станет ===')
    print(NEW_ECO_TARGET_FIN)
    if add_src:
        print('\n=== src: добавится ===')
        for s in add_src:
            print(s)

    if write:
        data['companies'][COMPANY_ID] = COMPANY_PROFILE
        deal['target'] = COMPANY_ID
        deal['law']['struct'] = NEW_LAW_STRUCT
        deal['law']['appr'] = NEW_LAW_APPR
        deal['eco']['val'] = NEW_ECO_VAL
        deal['eco']['rationale'] = NEW_ECO_RATIONALE
        deal['eco']['target_fin'] = NEW_ECO_TARGET_FIN
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
