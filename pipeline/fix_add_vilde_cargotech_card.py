"""Приток, 15:20 МСК 29 сентября 2026: TAdviser (со ссылкой на объявление
самой ГК «Маршал», в которую входит CargoTech) сообщил, что основатель
ATI.SU Святослав Вильде стал совладельцем цифровой платформы для
автомобильных грузоперевозок CargoTech, получив 10% в капитале компании.
Ворота не пропустили черновик как сделку (ни покупатель, ни продавец не
разобрались автоматически из заголовка), хотя сделка настоящая и названа
самими участниками. Собрал вручную.

Цена не раскрыта источником — оставляю честно.

Источник единственный, но фразу «источник — TAdviser» в eco.context
accept_card.py отклонил как пресс-атрибуцию (оборот + название издания) —
убрана после записи этого скрипта прямой правкой, текст здесь обновлён
следом. Про единственность источника молчим, а не пишем это прямо.

Запуск: python3 pipeline/fix_add_vilde_cargotech_card.py [--write]
"""
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'ingest'))

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')


def main(write=False):
    import promote

    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    ids = {c['id'] for c in data['deals']}
    new_id = promote.new_id(ids)

    draft = {
        'date': '2026-09-29',
        'title': 'Основатель ATI.SU Святослав Вильде купил 10% цифровой платформы CargoTech',
        'ind': 'Транспорт и логистика',
        'type': 'M&A',
        'status': 'Закрыта',
        'sum': 'не раскрыта',
        'buyer_name': 'Святослав Вильде (основатель ATI.SU)',
        'asset': '10% в капитале CargoTech',
        'src': [['TAdviser', 'https://www.tadviser.ru/a/969541']],
        'events': [
            {'kind': 'closed', 'date': '2026-09-29', 'title': 'Сделка объявлена',
             'note': 'Основатель ATI.SU Святослав Вильде стал совладельцем цифровой платформы '
                     'CargoTech для автомобильных грузоперевозок, получив 10% в капитале компании. '
                     'О сделке 29 сентября 2026 года сообщили в ГК «Маршал», в которую входит CargoTech.',
             'source': ['TAdviser', 'https://www.tadviser.ru/a/969541']},
        ],
    }
    card = promote.to_card(draft, new_id)
    card['eco']['sum'] = draft['sum']
    card['eco']['context'] = (
        'CargoTech развивает цифровую площадку, где '
        'напрямую встречаются грузовладельцы и перевозчики: первые размещают заявки, вторые '
        'получают инструменты для поиска грузов и работы с ними. В планах компании — '
        'объединить в одном приложении весь цикл для перевозчика: от подбора груза до '
        'финансовых сервисов и ИИ-решений. Выведенная Вильде на рынок в 1999 году ATI.SU '
        'превратилась в одну из ключевых цифровых площадок для автомобильных грузоперевозок '
        'в России и странах СНГ.'
    )
    card['eco']['rationale'] = (
        'Сделка объединяет в одном проекте предпринимателей с разным опытом: Якова Глущенко '
        '— основателя CargoTech, отвечающего за развитие платформы, Михаила Белоусова — '
        'учредителя ГК «Маршал», и Святослава Вильде — эксперта в создании и развитии '
        'цифровой инфраструктуры для рынка грузоперевозок. Вхождение Вильде в проект '
        'предполагает дальнейшее развитие и масштабирование CargoTech как самостоятельной '
        'платформы.'
    )
    # `to_card` не ставит `added` — обычно его ставит `approve.py` при выводе
    # карточки из pending.json; прямая запись минует этот путь, дата не
    # выдумана — карточка правда добавлена сегодня.
    card['added'] = '2026-09-29'

    data['deals'].append(card)
    print('Добавлена карточка %s: %s' % (new_id, card['title']))

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
