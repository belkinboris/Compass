# -*- coding: utf-8 -*-
"""Месячная очередь, 8 сентября 2026 — карточка `c975894bf` («Путин передал
Газпрому российский бизнес Ariston и BSH Hausgerate во временное
управление», 26 апреля 2024) описывает ОДНО решение, которым во временное
управление АО «Газпром бытовые системы» передали ДВЕ разные компании
(«Аристон термо рус» и «БСХ бытовые приборы») — их судьба с тех пор
РАЗОШЛАСЬ, и карточка об этом не знает.

Личный WebFetch (fontanka.ru/2025/03/27/75270107, 27.03.2025) подтвердил
дословно: «Президент... подписал указ, исключающий ООО «АРИСТОН ТЕРМО
РУСЬ» из перечня компаний, переданных в управление профильной «дочке»
«Газпрома»» — итальянский владелец Ariston вернул себе управление;
«вчерашнее «послабление» [Bosh] не коснулось, он остался в управлении
«Газпрома»» — по данным того же издания (fontanka.ru/2026/03/16/76313667,
не проверено дословным WebFetch, взято из отчёта саб-агента) «БСХ бытовые
приборы» остаётся под управлением «Газпром бытовые системы» как минимум
по март 2026 года, а Bosch публично заявил, что «не планирует
возвращаться в Россию». Причина расхождения, по изданию: «Ariston
продолжал производство, поэтому был возвращен иностранным собственникам,
а Bosch прекратил деятельность и остался в госуправлении».

`status` карточки («Подписана») НЕ меняется — это верно описывает
исходное событие 26 апреля 2024 года, а не текущее состояние обоих
активов по отдельности. Новый факт добавлен в `eco.context`. Решение о
том, заводить ли отдельную карточку на возврат «Аристон термо рус»
итальянскому владельцу (26 марта 2025, первый в РФ случай возврата
оперативного управления иностранцу), оставлено приточной рутине — оно
записано отдельным пунктом в разделе «Известные проблемы» CLAUDE.md.

Запуск:
    python3 pipeline/fix_ariston_bsh_diverged_outcomes.py            # сухой прогон
    python3 pipeline/fix_ariston_bsh_diverged_outcomes.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'
CARD_ID = 'c975894bf'

OLD_CONTEXT = (
    'Первыми компаниями, которые попали под удар, стали немецкая Uniper '
    '(ПАО «Юнипро») и финская Fortum (ПАО «Фортум»). В июле прошлого года '
    'под временное управление Росимущества перешла российская «дочка» '
    'Danone, но в марте Путин отменил это решение.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' Судьба двух переданных в управление компаний разошлась: 26 марта '
    '2025 года указом президента «Аристон термо рус» была исключена из '
    'перечня и возвращена под контроль итальянского владельца Ariston — '
    'первый в России случай возврата иностранцу оперативного управления, '
    'поскольку завод продолжал работать; «БСХ бытовые приборы» осталась '
    'под управлением «Газпром бытовые системы» — Bosch фактически '
    'прекратил производство ещё в 2022 году и публично заявил, что не '
    'планирует возвращаться в Россию.'
)


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}
    card = by_id[CARD_ID]

    assert card['eco']['context'] == OLD_CONTEXT, \
        'eco.context уже другой: %r' % (card['eco']['context'],)

    print('eco.context: добавлен факт о расхождении судьбы Ariston (возврат '
          'владельцу, март 2025) и BSH/Bosch (осталась в управлении Газпрома)')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    card['eco']['context'] = NEW_CONTEXT

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
