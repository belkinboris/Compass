"""Продолжение fix_mini_ranking_dates_batch1.py: три из девяти оставшихся
карточек рэнкинга «Ъ — Сделки года» (`from_compact: mini`, все несли
дату публикации рэнкинга «2025-09-30» вместо даты сделки) получили
точную, дословно подтверждённую дату.

  ceeb8c214 (Газпромбанк/22% ЮГК): Ведомости, 23 декабря 2024, 17:29 —
             «Структура Газпромбанка купила у бизнесмена Струкова 22%
             «Южуралзолота»».
  cc2929a95 (Окто/Zapadnaya Gold Mining): zolteh.ru, 28 апреля 2025,
             тело статьи — «Сделка закрыта 25 апреля текущего года».
  c514e8712 (Sminex/«Инград»): irn.ru, 17 октября 2024 года — «Смайнекс
             (Sminex) закрыл сделку по приобретению компании «Инград»».

Ещё шесть карточек того же дефекта (cb30dbbc8, c19d1104d, cc80b229f,
cf2375bf5, c689eefe9, cbb6ba4c9) остаются с датой-заглушкой: источники
называют либо только месяц без точного дня («в июне—июле 2025 года» —
Коммерсантъ про c689eefe9), либо расходятся между «стало известно» и
«официально подтверждено» (moskvichmag.ru про cbb6ba4c9 — слух декабря
2024, статья апреля 2025, точной даты закрытия ни один источник не
называет), либо нужный источник недоступен для скачивания (РБК — 401).
Переносить их сейчас значило бы гадать; ждут отдельного прогона.

Карточки ceeb8c214 и c514e8712 этим переносом выходят из среза 2025 года
(переезжают в 2024); cc2929a95 остаётся в 2025, но с точным днём вместо
даты публикации рэнкинга.

ПОЧЕМУ НЕ ЧЕРЕЗ `review.py`. `date_is_supported()` намеренно запрещает
менять год — перенос года обязан быть отдельным, явным решением с
проверяемым источником.

Запуск:
    python3 pipeline/fix_mini_ranking_dates_batch2.py            # сухой прогон
    python3 pipeline/fix_mini_ranking_dates_batch2.py --write    # записать
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

FIXES = [
    dict(id='ceeb8c214', old='2025-09-30', new='2024-12-23',
         quote='Ведомости, 23 декабря 2024, 17:29: «Структура '
               'Газпромбанка купила у бизнесмена Струкова 22% '
               '«Южуралзолота»»'),
    dict(id='cc2929a95', old='2025-09-30', new='2025-04-25',
         quote='zolteh.ru, 28 апреля 2025: «Группа компаний «Западная» '
               'перешла под контроль частных инвесторов — 100% акций '
               'МКАО «Западная Голд Майнинг Лимитед» приобрела группа '
               '«ОКТО»... Сделка закрыта 25 апреля текущего года»'),
    dict(id='c514e8712', old='2025-09-30', new='2024-10-17',
         quote='irn.ru, 17 октября 2024 года: «Смайнекс (Sminex) закрыл '
               'сделку по приобретению компании «Инград»»'),
]


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}

    for fx in FIXES:
        deal = by_id.get(fx['id'])
        assert deal is not None, 'нет сделки %s' % fx['id']
        assert deal.get('date') == fx['old'], \
            '%s: дата уже другая: %r, ожидали %r' % (
                fx['id'], deal.get('date'), fx['old'])
        print('%s: date %r -> %r' % (fx['id'], fx['old'], fx['new']))
        print('  цитата: %r' % fx['quote'])

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    for fx in FIXES:
        by_id[fx['id']]['date'] = fx['new']
        assert by_id[fx['id']]['date'] == fx['new'], 'дата не записалась'

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
