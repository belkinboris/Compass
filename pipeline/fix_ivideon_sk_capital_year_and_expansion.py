# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g25db4ede (Ivideon выкупила свою долю у «Индустриального фонда» Sk
Capital) — карточка несла год 2024, хотя сделка закрылась в 2025 году
(уже была подсказка в дате самого источника CNews), а компания успела
запустить новое направление и выйти на рынки СНГ. Проверено лично
прямым WebFetch двух источников.

Год сделки (2024 → 2025) — НЕ через `review.py` (смена года — отдельный
скрипт). Дословно (CNews, 01.11.2025, 08:00): «Компания Ivideon и
венчурный фонд Индустриальный под управлением Sk Capital завершили
сделку по выкупу доли, принадлежавшей фонду с 2018 г.» — независимо
подтверждено ComNews (05.11.2025) и собственным блогом Ivideon
(11.02.2026): «в 2025 году компания выкупила долю инвестора Фонда
Индустриальный (Sk Capital)».

`eco.context` (дополнено). Дословно (блог Ivideon, 11.02.2026): «С 2025
года компания развивает решения MaaS (Management as a Service) —
продукта операционного управления на базе видео- и аудиоаналитики»,
«В 2025 году Ivideon вышли на рынки СНГ, заключив стратегические
партнерства с телеком-операторами Uztelecom в Узбекистане и
"МегаФон-Таджикистан", провайдером SkyNet в Киргизии».

НЕ ВКЛЮЧЕНО: точная сумма сделки — экспертная оценка ($10-11 млн от
Арсения Даббаха, ComNews) получена суб-агентом через пересказ, не
дословную цитату, и не перепроверена личным WebFetch — не вносится,
пока нет подтверждённой дословной цитаты; планы IPO — фраза из ComNews
о «одном из возможных сценариев» тоже не перепроверена лично в этом
прогоне; сделка Sk Capital/«Сайберус» (декабрь 2025) — это ОТДЕЛЬНАЯ,
уже задокументированная сделка со своей карточкой (`g9cb22c51`), не
переносится сюда во избежание уже дважды случавшегося класса дефекта
(«Русал»/Pioneer Aluminium, ВЭБ.РФ/Sk Capital — см. CLAUDE.md); при
желании сослаться на неё как на дальнейшую активность фонда — только
ссылкой на её собственную карточку, не копированием фактов.

Запуск: python3 pipeline/fix_ivideon_sk_capital_year_and_expansion.py
        python3 pipeline/fix_ivideon_sk_capital_year_and_expansion.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g25db4ede'

OLD_DATE = '2024'
NEW_DATE = '2025'

OLD_CONTEXT = (
    '«Фонд Индустриальный под управлением Sk Capital был создан с '
    'целью развития высокотехнологичных отраслей России через '
    'поддержку отечественных инновационных компаний и проектов. Ivideon '
    '– отличный пример эффективности работы нашей команды. Инвестиции и '
    'наша вовлеченность не только помогли компании вырасти в пять раз '
    'и превратиться из стартапа в устойчивый и прибыльный бизнес, но и '
    'позволили укрепить позиции Ivideon как лидера облачного '
    'видеонаблюдения и видеоаналитики, сохранив и усилив компетенции '
    'отечественных специалистов в этой стратегически важной области», '
    '– сказал Александр Чайкин, управляющий директор Sk Capital.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' После выхода фонда компания расширила бизнес: «С 2025 года '
    'компания развивает решения MaaS (Management as a Service) — '
    'продукта операционного управления на базе видео- и '
    'аудиоаналитики», «В 2025 году Ivideon вышли на рынки СНГ, заключив '
    'стратегические партнерства с телеком-операторами Uztelecom в '
    'Узбекистане и "МегаФон-Таджикистан", провайдером SkyNet в '
    'Киргизии» (блог Ivideon, 11 февраля 2026).'
)

NEW_SRC = [
    ['Ivideon', 'https://ru.ivideon.com/blog/vyruchka-ivideon-pereshagnula-2-mlrd-rubley-v-2025-godu/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['date'] == OLD_DATE
    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== date: станет ===')
    print(NEW_DATE)
    print('\n=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['date'] = NEW_DATE
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
