import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g1fc3fe9e'

OLD_EXTRA = (
    'Завершенная сделка по продаже 100% акционерного капитала '
    'Сибантрацита. Финансирование осуществлено ПСБ. 100% БПХ находятся '
    'в залоге у Мособлбанка (входит в структуру ПСБ).'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Покупатель переименован в «Сибкапитал» (февраль 2024); структура '
    'его владения изменилась уже через 8 дней после сделки: доля Олега '
    'Полякова сократилась с 71% до 25,5%, вошли новые совладельцы '
    'Алексей Фоменко (25,5%) и Ольга Чаплыгина (20%). 1 мая 2024 года '
    'США включили в блокирующий санкционный список «Сибантрацит» с 12 '
    'структурами и «Сибкапитал» как его владельца. Выручка группы за '
    '2023 год — 231,4 млрд ₽, чистая прибыль — 30,8 млрд ₽.'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6679813'],
    ['Интерфакс', 'https://www.interfax.ru/business/932825'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
