# -*- coding: utf-8 -*-
"""Карточка g85e07f6d (НПО «РТС»/ЦНТИ Челябинск): второе чтение нашло, что
первое предложение eco.context («построен в 1972 году, через два года в
него переехал ЦНТИ») не подтверждено ни одним из двух источников 74.ru —
первая статья говорит только, что ЦНТИ работал там «много лет», без дат
постройки/переезда. Даты снимаются, площадь и факт многолетнего занятия
здания ЦНТИ остаются.

Запуск:
    python3 pipeline/fix_g85e07f6d_eco_context_1972_2026_11_24.py            # сухой прогон
    python3 pipeline/fix_g85e07f6d_eco_context_1972_2026_11_24.py --write    # запись
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(ROOT, '..', 'static', 'data', 'deals_promoted.json')
CARD_ID = 'g85e07f6d'
OLD = ('Дом на Труда, 157 площадью 8187 кв. м построен в 1972 году, через два года в него переехал '
       'ЦНТИ. За год до продажи организацию ликвидировали, а здание поделили между судебной системой '
       'региона и федеральным агентом «Дом.РФ». На долю «Дом.РФ» пришлись помещения площадью 2488 кв. '
       'м — их и купило НПО «РТС».\n\nДо сентября 2022 года зданием владел филиал «Российского '
       'энергетического агентства» Минэнерго, после чего его передали в собственность государства.')
NEW = ('Дом на Труда, 157 площадью 8187 кв. м много лет занимал ЦНТИ. За год до продажи организацию '
       'ликвидировали, а здание поделили между судебной системой региона и федеральным агентом '
       '«Дом.РФ». На долю «Дом.РФ» пришлись помещения площадью 2488 кв. м — их и купило НПО «РТС».'
       '\n\nДо сентября 2022 года зданием владел филиал «Российского энергетического агентства» '
       'Минэнерго, после чего его передали в собственность государства.')


def apply(data):
    card = next(c for c in data['deals'] if c['id'] == CARD_ID)
    assert card['eco']['context'] == OLD, 'eco.context уже изменен кем-то другим'
    card['eco']['context'] = NEW


def main(write):
    data = json.load(open(DATA, encoding='utf-8'))
    apply(data)
    print('eco.context обновлен')
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return 0
    data = json.load(open(DATA, encoding='utf-8'))
    apply(data)
    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
        f.write('\n')
    print('ЗАПИСАНО.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main('--write' in sys.argv[1:]))
