# -*- coding: utf-8 -*-
"""«Амбер Талвис»: продавец — Росимущество, актив изъят у Юрия Шефлера.

ЧТО ЧИНИТ. Владелец 9 сентября 2026: «если ты в этой карте по талвису ещё и
продавца не можешь идентифицировать, то я буду вообще разочарован (это
следует практически из всех источников и прямо указано в источнике про сам
аукцион)». Продавца в карточке не было вовсе — плашка показывала «Продавец:
не раскрыт» у сделки, где продавец не может быть нераскрытым по устройству:
это публичные торги государственным имуществом.

САМ САЙТ ТОРГОВ ИЗ ЭТОЙ СРЕДЫ НЕ ОТКРЫВАЕТСЯ. `torgi.gov.ru` сбрасывает
соединение и через `curl`, и через WebFetch (503), и через настоящий браузер
(`ERR_CONNECTION_RESET`) — проверено тремя способами, это ограничение среды,
а не отговорка. Поэтому продавец взят из второго источника той же карточки,
где он назван прямо, — «Ведомостей» (11 августа 2026), дословно:

    «Контрольный пакет «Амбер Талвиса» перешел Росимуществу в июле 2024 г.»
    «Тамбовский районный суд удовлетворил иск Генпрокуратуры, которая
    требовала обратить в доход государства активы бизнесмена Юрия Шефлера.
    Последний, по версии ведомства, в 2022–2023 гг. направил 38 млн евро на
    поддержку вооруженных сил Украины.»

ЧТО ИЗ ЭТОГО СЛЕДУЕТ ДЛЯ КАРТОЧКИ, ПО ПУНКТАМ:
  * ПРОДАВЕЦ — Росимущество (профиль `g9fd82fee` уже есть в базе), и текст, и
    ссылка ставятся вместе: пара «`seller_id` + `seller`» не редактируется с
    одной стороны (урок CLAUDE.md — связанный `_id` перекрывает текст).
  * ПРОИСХОЖДЕНИЕ АКТИВА не было названо НИГДЕ в карточке — ровно та же дыра,
    что владелец нашёл неделей раньше на ТРК «Родник»/«Алмаз» («они остались
    от макфы, этого нигде не написано у нас»). Дописывается в `eco.context`:
    иск Генпрокуратуры, обращение в доход государства, переход пакета
    Росимуществу в июле 2024 года.
  * ТИП СДЕЛКИ стоял «M&A», хотя это продажа государственного пакета на
    публичных торгах — у удалённого дубля тип был указан верно («Продажа с
    торгов»), и при слиянии сохранился тип оставшейся карточки. Тип решает не
    только ярлык: по нему считается тема, витрина и — с сегодняшнего дня —
    инвариант «у торгов продавец назван» (`test_auction_deal_names_its_seller`).

ПРОВЕРКА ПЕРЕД ЗАПИСЬЮ: каждое число и каждое имя собственное нового текста
обязано встречаться в цитате источника, приведённой выше, — `assert` в самом
скрипте, а не обещание в комментарии.

Запуск:
    python3 pipeline/fix_amber_talvis_seller_and_origin.py           # сухой
    python3 pipeline/fix_amber_talvis_seller_and_origin.py --write
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / 'static' / 'data' / 'deals_promoted.json'

DEAL_ID = 'g63c7d1bb'
SELLER_ID = 'g9fd82fee'          # Росимущество
SELLER_NAME = 'Росимущество'

QUOTE = ('Контрольный пакет «Амбер Талвиса» перешел Росимуществу в июле 2024 г. '
         'Тамбовский районный суд удовлетворил иск Генпрокуратуры, которая '
         'требовала обратить в доход государства активы бизнесмена Юрия '
         'Шефлера. Последний, по версии ведомства, в 2022–2023 гг. направил '
         '38 млн евро на поддержку вооруженных сил Украины.')
SOURCE_URL = 'https://www.vedomosti.ru/business/articles/2026/08/11/1220271-aktiv-yuriya-sheflera'

ORIGIN_TEXT = ('Государству пакет достался по суду: Тамбовский районный суд '
               'удовлетворил иск Генпрокуратуры об обращении в доход '
               'государства активов бизнесмена Юрия Шефлера, и контрольный '
               'пакет «Амбер Талвиса» перешёл Росимуществу в июле 2024 года.')

OLD_TYPE = 'M&A'
NEW_TYPE = 'Продажа с торгов'

NUM = re.compile(r'\d[\d\s ]*(?:[.,]\d+)?')
# Имя собственное — заглавная буква НЕ в начале предложения: иначе первое
# слово фразы («Государству пакет достался…») читается как имя и роняет
# проверку на ровном месте. Тот же класс ложного срабатывания, что уже
# описан в CLAUDE.md у вычитки («1-я ювелирная сеть» как первое лицо).
NAME = re.compile(r'(?<=[а-яё,] )[А-ЯЁ][а-яё]{2,}')


def digits(text):
    return {re.sub(r'[\s ]', '', m.group(0)).rstrip('.,') for m in NUM.finditer(text)}


def main(write=False):
    data = json.loads(DATA.read_text(encoding='utf-8'))
    deal = next((d for d in data['deals'] if d['id'] == DEAL_ID), None)
    assert deal, 'карточки %s нет в базе' % DEAL_ID

    assert not deal.get('seller') and not deal.get('seller_id'), \
        'продавец уже стоит: %r / %r' % (deal.get('seller'), deal.get('seller_id'))
    assert deal.get('type') == OLD_TYPE, deal.get('type')
    assert SELLER_ID in data['companies'], 'профиля Росимущества нет'
    context = (deal.get('eco') or {}).get('context') or ''
    assert 'Шефлер' not in context and 'Генпрокурат' not in context, \
        'происхождение уже описано: %r' % context[:120]
    assert SOURCE_URL in json.dumps(deal, ensure_ascii=False), \
        'источник цитаты не привязан к карточке'

    # Ни одного числа и ни одного имени из ниоткуда: всё обязано быть в цитате.
    invented_nums = sorted(x for x in digits(ORIGIN_TEXT) if x not in digits(QUOTE))
    assert not invented_nums, 'числа не из цитаты: %s' % invented_nums
    quote_names = set(NAME.findall(QUOTE))
    invented_names = sorted(n for n in NAME.findall(ORIGIN_TEXT) if n not in quote_names)
    assert not invented_names, 'имена не из цитаты: %s' % invented_names

    print('=== %s ===' % DEAL_ID)
    print(' продавец: не назван -> %r + профиль %s' % (SELLER_NAME, SELLER_ID))
    print(' тип:      %r -> %r' % (OLD_TYPE, NEW_TYPE))
    print(' происхождение актива дописывается в «Контекст»:')
    print('   ', ORIGIN_TEXT)
    if not write:
        print('\nСухой прогон. Запись — с ключом --write.')
        return 0

    deal['seller'] = SELLER_NAME
    deal['seller_id'] = SELLER_ID
    deal['type'] = NEW_TYPE
    deal['eco']['context'] = (context.rstrip() + ' ' + ORIGIN_TEXT).strip()

    DATA.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding='utf-8')
    print('\nЗаписано.')
    return 0


if __name__ == '__main__':
    sys.exit(main('--write' in sys.argv))
