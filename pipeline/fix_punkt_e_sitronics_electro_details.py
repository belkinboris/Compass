# -*- coding: utf-8 -*-
"""Месячная очередь, 9 сентября 2026 — дочитывание карточки `g17a6fd62`
(«"Пункт Е" купило 100% "Ситроникс Электро" у группы "Ситроникс"»,
добавлена в базу 8 сентября 2026).

Дельта-поиск (саб-агент + личная проверка) нашёл три новых факта. Единственный
источник карточки — объявление юрфирмы АЛРУД (@LawFirms) без суммы и без
второго консультанта; независимые статьи Коммерсанта и ComNews дали
недостающее. Личный WebFetch подтвердил дословно:

1) Финансовый консультант покупателя. comnews.ru: «Финансовым консультантом
   Punkt E по сделке выступил инвестиционный банк Advance Capital (ООО
   "Адванс Капитал")» — АЛРУД в объявлении назван только юридическим
   консультантом, финансовый в базе не стоял вовсе.

2) Оценка стоимости сделки (сторонами сумма не раскрыта). kommersant.ru/
   doc/8603917: «Балансовую стоимость активов портфеля из 900 ЭЗС можно
   оценить в 1,4–2,9 млрд руб.»; аналитик «Эйлер — аналитические
   технологии» Йоханнес-Корнелиус Ростовский — «ориентировочная цена
   сделки могла составить 2,2–4,3 млрд руб.» Обе оценки — не факты о цене,
   а атрибутированные экспертные оценки; идут в `eco.val`, не в `sum`.

3) Дальнейший фокус Sitronics Group. comnews.ru: «В сфере
   электромобильности Sitronics Group сфокусируется на разработке и
   производстве зарядного оборудования — от индивидуальных станций до
   ультрабыстрых ЭЗС для общественного электротранспорта» — операторский
   бизнес (сеть станций, приложение, диспетчеризация, строительство
   хабов) полностью уходит «Пункт Е», а группа остаётся производителем
   оборудования.

НЕ внесено (недостаточно подтверждено дословным чтением одного документа —
саб-агент предупредил об этом сам): точные доли учредителей «Пункт Е»
(60%/40% — только в AI-сводке поиска), связь Андрея Гурленова с новой
должностью в «Пункт Е», расхождение числа станций «900» (Коммерсантъ)
против «100+575=675» (другие источники), юрлицо-учредитель «Ситроникс
Электро» (АО «Ситроникс АйТи» вместо АО «Ситроникс»).

Запуск:
    python3 pipeline/fix_punkt_e_sitronics_electro_details.py            # сухой прогон
    python3 pipeline/fix_punkt_e_sitronics_electro_details.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_ECO_VAL = '—'
NEW_ECO_VAL = (
    'Стороны сумму не раскрывают. По оценке аналитика «Эйлер — '
    'аналитические технологии» Йоханнеса-Корнелиуса Ростовского, '
    'ориентировочная цена сделки могла составить 2,2–4,3 млрд ₽; '
    'балансовая стоимость портфеля из 900 зарядных станций оценивается '
    'в 1,4–2,9 млрд ₽.'
)

OLD_ECO_CONTEXT = (
    'К покупателю перешли операторская сеть электрозарядных станций, '
    'мобильное приложение, системы мониторинга и диспетчеризации '
    'электротранспорта, а также бизнес по проектированию и строительству '
    'зарядных хабов для общественного и коммерческого транспорта. В '
    'результате сделки ООО «Пункт Е» стало крупнейшим оператором зарядной '
    'инфраструктуры в стране.'
)
NEW_ECO_CONTEXT = OLD_ECO_CONTEXT + (
    ' Sitronics Group сфокусируется на разработке и производстве зарядного '
    'оборудования — от индивидуальных станций до ультрабыстрых ЭЗС для '
    'общественного электротранспорта, сохранив это направление за собой.'
)

OLD_ADV = [
    'Юридический консультант покупателя (ООО «Пункт Е»)',
    'АЛРУД',
    'Участие во всех этапах сделки: структурирование, соглашение о '
    'намерениях, согласование и подготовка транзакционной документации. '
    'Партнёр практики корпоративного права Александр Жарский, советник '
    'Олег Ежов и команда. Источник: https://t.me/LawFirms/10817',
]
NEW_ADV_ENTRY = [
    'Финансовый консультант покупателя (ООО «Пункт Е»)',
    'Advance Capital',
    'Инвестиционный банк выступил финансовым консультантом Punkt E по '
    'сделке. Источник: ComNews.',
]

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8603917'],
    ['ComNews', 'https://www.comnews.ru/content/244847/2026-04-20/2026-w17/1008/punkt-e-priobrel-sitronics-electro'],
]


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['g17a6fd62']

    assert d['eco']['val'] == OLD_ECO_VAL, \
        'g17a6fd62 eco.val уже другой: %r' % (d['eco']['val'],)
    assert d['eco']['context'] == OLD_ECO_CONTEXT, \
        'g17a6fd62 eco.context уже другой: %r' % (d['eco']['context'],)
    assert d['law']['adv'] == [OLD_ADV], \
        'g17a6fd62 law.adv уже другой: %r' % (d['law']['adv'],)
    urls = {s[1] for s in d['src']}
    for src in NEW_SRC:
        assert src[1] not in urls, 'источник уже добавлен: %s' % src[1]

    print('g17a6fd62: eco.val заполнен (экспертные оценки 1,4–2,9 и '
          '2,2–4,3 млрд ₽ с атрибуцией); eco.context дополнен (фокус '
          'Sitronics Group на производстве оборудования); law.adv '
          'дополнен финансовым консультантом покупателя (Advance '
          'Capital); добавлены источники kommersant.ru, comnews.ru')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['eco']['val'] = NEW_ECO_VAL
    d['eco']['context'] = NEW_ECO_CONTEXT
    d['law']['adv'].append(NEW_ADV_ENTRY)
    d['src'].extend(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
