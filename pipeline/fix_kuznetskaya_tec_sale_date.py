# -*- coding: utf-8 -*-
"""Карточка gb0759159 («СГК и «Кузбассэнерго» продали 100% акций АО
«Кузнецкая ТЭЦ»») несла дату «2025-08-22» — дату публикации сообщения в
Telegram-канале @LawFirms об уже завершённом юридическом сопровождении,
а не дату самой сделки.

ЧТО СЛОМАНО. Interfax прямо пишет со ссылкой на гендиректора «Кузбассэнерго»
Виктора Лариошкина: «Сделка по продаже ТЭЦ была совершена в конце
апреля. Новым владельцем ТЭЦ стало ООО «Стройтехпроект» (Новокузнецк),
95% которого владеет его гендиректор Иван Сазыкин». То есть сделка
закрылась в конце апреля 2025 года, а карточка получила дату из более
позднего PR-сообщения консультанта (родня уже записанного урока
«обещание в тексте бота — не то же самое, что код, который его
выполняет»: PR-анонс о сделке систематически приходит с задержкой
относительно самой сделки).

ТОЧНЫЙ ДЕНЬ НЕ ПЕРЕНОСИМ. Interfax называет только «в конце апреля» —
без числа. Независимый источник с точной датой (28 апреля, по ЕГРЮЛ)
нашёлся, но отдаёт текст в повреждённой кодировке (city-n.ru) — доверять
числу без дословной проверки нельзя. Пишем то, что доказано (год не
менялся, но месяц был неверен), а не изобретаем число — тот же принцип,
что у заглушек «1 января» (`fix_placeholder_dates.py`): год и так честен,
раз он не поменялся, но раз доказанного месяца в базе формат не
предусматривает (`YYYY-MM` нигде не используется), поле сводится к
голому году.

ПОЧЕМУ НЕ ЧЕРЕЗ `review.py`. `date_is_supported()` требует дня и месяца,
названных прописью в цитате, а здесь есть только месяц без числа —
уточнение внутри года само по себе законно, но формата для него нет.

Запуск:
    python3 pipeline/fix_kuznetskaya_tec_sale_date.py            # сухой прогон
    python3 pipeline/fix_kuznetskaya_tec_sale_date.py --write    # записать
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'
DEAL_ID = 'gb0759159'
OLD_DATE = '2025-08-22'
NEW_DATE = '2025'
QUOTE = ('Interfax, 09:45, 22 мая 2025: «Сделка по продаже ТЭЦ была '
         'совершена в конце апреля. Новым владельцем ТЭЦ стало ООО '
         '«Стройтехпроект» (Новокузнецк), 95% которого владеет его '
         'гендиректор Иван Сазыкин»')


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}
    deal = by_id.get(DEAL_ID)
    assert deal is not None, 'нет сделки %s' % DEAL_ID
    assert deal.get('date') == OLD_DATE, \
        'дата уже другая: %r, ожидали %r' % (deal.get('date'), OLD_DATE)

    print('%s: date %r -> %r' % (DEAL_ID, OLD_DATE, NEW_DATE))
    print('  цитата: %r' % QUOTE)

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    deal['date'] = NEW_DATE
    assert deal['date'] == NEW_DATE, 'дата не записалась'

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
