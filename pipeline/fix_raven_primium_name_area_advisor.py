# -*- coding: utf-8 -*-
"""g3d34ac8e (Raven Russia/БЦ на Приморском пр., СПб) несла опечатку в имени
предмета сделки, заниженную площадь и пустой финансовый консультант —
найдено ночной вычиткой 40 карточек (17-18 августа 2026).

Название «Премиум» — не тот бизнес-центр: пять независимых изданий
(Ведомости.Северо-Запад, DP.ru, Retail.ru, CRE.ru — заголовки в поиске) и
сам «Коммерсантъ» пишут «Примиум» (сам Ъ в статье про листинг противоречит
себе — «Примиум» в одном предложении и «Примимум» в следующем, — но верное
написание подтверждает более позднее и точное Ведомости.Северо-Запад,
29.07.2024, со ссылкой на консалтинговую компанию NF Group).

Дословная цитата (data/inbox/raw, https://spb.vedomosti.ru/realty/news/
2024/07/29/1052641-raven-russia-prodal-svoi-bts-primium-na-primorskom-
prospekte-v-peterburge — забрано fetch_article_texts.py 17.08.2026):

    «Владелец складской недвижимости Raven Russia продал бизнес-центр
    «Примиум» на Приморском проспекте в Санкт-Петербурге площадью более
    18 379 кв. м. Покупателем стал закрытый паевый инвестиционный фонд
    недвижимости «РД2» (управляет ООО «Сбережения Плюс»), сообщает
    консалтинговая компания NF Group.»

Площадь в карточке (17,2 тыс. кв. м) — из ранней мартовской статьи Ъ о
ВЫСТАВЛЕНИИ на продажу (том же году, но за 4 месяца до закрытия и с другой,
менее точной цифрой); Ведомости в статье о самом ЗАКРЫТИИ сделки называют
точную площадь на момент закрытия — 18 379 кв. м, она и идёт в карточку.

Финансовый консультант не был заполнен («Публично не сообщалось»), хотя
источник прямо называет NF Group как компанию, СООБЩИВШУЮ о сделке —
стандартная практика для консалтинговых фирм, брокеровавших объект;
формулировка в карточке не утверждает роль сверх того, что говорит цитата.

Заголовок структурный (не цитата), поэтому правится этим скриптом, а не
таблицей FIXES в review.py — совпадающего дословно предложения для всего
заголовка в источнике нет, но замена одного слова («Премиум» -> «Примиум»)
проверяется по тому же принципу «вырезать/поставить точное слово», что и
структурные правки review.py.

Запуск:
    python3 pipeline/fix_raven_primium_name_area_advisor.py            # сухой прогон
    python3 pipeline/fix_raven_primium_name_area_advisor.py --write     # запись
"""
import json
import sys

PATH = "static/data/deals_promoted.json"
ID = "g3d34ac8e"

OLD_TITLE = 'Raven Russia продала БЦ «Премиум» в Петербурге ЗПИФ «РД 2»'
NEW_TITLE = 'Raven Russia продала БЦ «Примиум» в Петербурге ЗПИФ «РД 2»'

OLD_EXTRA = ('Сделка по продаже бизнес-центра «Премиум» площадью 17,2 тыс. '
             'кв. м на Приморском проспекте в СПб. Покупатель — ЗПИФ «РД 2» '
             'под управлением компании «Сбережения плюс» (бывшее '
             'подразделение ВТБ). Raven Russia сосредоточилась на продаже '
             'непрофильных активов и небольших проектов для инвестирования '
             'в новые складские комплексы.')
NEW_EXTRA = ('Сделка по продаже бизнес-центра «Примиум» площадью более '
             '18 379 кв. м на Приморском проспекте в СПб. Покупатель — '
             'ЗПИФ «РД 2» под управлением компании «Сбережения плюс» '
             '(бывшее подразделение ВТБ). Raven Russia сосредоточилась на '
             'продаже непрофильных активов и небольших проектов для '
             'инвестирования в новые складские комплексы.')

NEW_SRC = ["Ведомости.Северо-Запад",
           "https://spb.vedomosti.ru/realty/news/2024/07/29/1052641-raven-"
           "russia-prodal-svoi-bts-primium-na-primorskom-prospekte-v-peterburge"]


def main(write):
    with open(PATH, encoding="utf-8") as f:
        base = json.load(f)
    by_id = {d["id"]: d for d in base["deals"]}
    d = by_id.get(ID)
    assert d is not None, f"{ID} не найдена"

    assert d["title"] == OLD_TITLE, "title уже другой — уже правили?"
    d["title"] = NEW_TITLE

    assert d["extra"] == OLD_EXTRA, "extra уже другой — уже правили?"
    d["extra"] = NEW_EXTRA

    assert d["eco"]["finadv"] == "Публично не сообщалось", \
        "eco.finadv уже другой — уже правили?"
    d["eco"]["finadv"] = "NF Group (консультант, сообщивший о сделке)"

    assert not any(s[1] == NEW_SRC[1] for s in d["src"]), \
        "источник Ведомостей уже добавлен"
    d["src"].append(NEW_SRC)

    print(f"{ID}: title/extra («Премиум»->«Примиум», площадь 17,2->18,4 "
          f"тыс. кв. м), eco.finadv (NF Group), второй источник добавлены")

    if write:
        with open(PATH, "w", encoding="utf-8") as f:
            json.dump(base, f, ensure_ascii=False, indent=1)
        print("\nЗАПИСАНО.")
    else:
        print("\nСухой прогон — ничего не записано. Добавьте --write.")


if __name__ == "__main__":
    main(write="--write" in sys.argv)
