# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка g1437f510 (Тольятти
Инвест/«Джей Ви Системз»): `law.struct` называл совладельцев покупателя
(Илья Пронин 90%, Ольга Гудкова 10%), но не их реальную связь. Дельта
нашла: оба совладельца — выходцы из группы «ЭФКО» (Пронин возглавляет
её научно-образовательный центр «Бирюч», Гудкова была совладельцем
масложирового комбината «ЭФКО» «Евдаково»).

Не через review.py: `law.struct` уже не пуст, а общая проверка
дословности требует, чтобы ВСЁ значение поля (старый текст + новый)
лежало в ОДНОЙ цитате — старый текст собран из нескольких источников,
новый — дословно из отдельной статьи (tlt.ru).
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g1437f510'
OLD_STRUCT = (
    'ООО «Тольятти Инвест» образовано в 2023 году. Руководителем '
    'является Илья Пронин, который также является учредителем '
    'компании с долей 90%, 10% принадлежат Ольге Гудковой.'
)
ADDITION = (
    'Пронин возглавляет учрежденный группой «ЭФКО» научно-'
    'образовательный центр «Бирюч», расположенный в Белгородской '
    'области, а также являлся единоличным владельцем ЗАО «ИЦ '
    '«Бирюч», которое с конца марта ликвидируется. Гудкова до 2019 '
    'года была совладельцем 40% долей ООО «Евдаково» — масложирового '
    'комбината «ЭФКО» в Воронежской области.'
)
NEW_STRUCT = OLD_STRUCT + ' ' + ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['law']['struct'] == OLD_STRUCT, \
        f"law.struct: неожиданное значение {deal['law']['struct']!r}"

    print(f"{CARD_ID} law.struct: += связь совладельцев покупателя с "
          "группой «ЭФКО»")
    deal['law']['struct'] = NEW_STRUCT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
