"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка gdb4b1cbf
(Роснано, Russia Partners и Baring Vostok вышли из Новомета) — карточка
уже подробно проработана; найдены статус выполнения условий сделки,
смена руководства, ухудшение финансов и новый судебный иск.

Редомициляция — условие сделки НЕ выполнено полностью на сентябрь 2024
года — проверено лично прямым WebFetch (Коммерсантъ,
kommersant.ru/doc/7162546): «На данный момент закрыты не все
обязательства покупателя» (подтверждено «Роснано»), «6 сентября была
создана международная компания ООО (МКООО) «Новомет»» в Калининграде —
только первый шаг смены юрисдикции, а не её завершение.

Смена гендиректора — проверено лично прямым WebFetch (Коммерсантъ,
kommersant.ru/doc/6715059): бывший гендиректор «Новомет-Пермь» Максим
Перельман уступил пост Илье Тихонову (по состоянию на 18 мая 2026 года
Тихонов остаётся гендиректором, по данным checko.ru).

Финансы предприятия за 2025 год — проверено лично прямым WebFetch
(Коммерсантъ, kommersant.ru/doc/8570732): «Выручка компании составила
17,27 млрд руб., что выше показателя предыдущего года на 9,8% (15,72
млрд руб.)», но «Прошлый год общество закончило с убытком в размере
2,72 млрд руб. В 2024-м «Новомет-Пермь» демонстрировал прибыль 2,59
млрд руб.» — прибыль сменилась убытком при росте выручки; «Краткосрочные
обязательства компании выросли на 25% — до 23 млрд руб.».

Новый судебный иск — проверено лично прямым WebFetch (Коммерсантъ,
kommersant.ru/doc/7403624): прокуратура Пермского края (по инициативе
«Роснано») оспаривает договоры на поставку бурового оборудования,
заключённые в 2015-2020 годах, с семью иностранными компаниями —
«Исковое заявление... было зарегистрировано в Арбитражном суде
Пермского края 24 декабря» 2024 года; исход дела на момент этого
прогона не установлен.

НЕ ВКЛЮЧЕНО: продажа непрофильного актива ОКБ БН за 5 млрд руб. (конец
2024 года) — это отдельный, не структурный для ЭТОЙ карточки актив
предприятия; выполнение условия о плане развития до 2028 года,
представленном комиссии при президенте РФ по ТЭК, — ни подтверждения,
ни опровержения не найдено ни в одном источнике.

Запуск: python3 pipeline/fix_novomet_postdeal_lawsuit_and_losses.py
        python3 pipeline/fix_novomet_postdeal_lawsuit_and_losses.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gdb4b1cbf'

OLD_EXTRA = (
    'Выход инвесторов Роснано (30,76%), Russia Partners и Baring '
    'Vostok (суммарно 19,34%) из акционерного капитала АО «Новомет-'
    'Пермь». Покупателем выступили структуры, близкие к Максиму '
    'Перельману и промышленной группе «Конар». Инвесторы входили в '
    'капитал с 2011 года; попытки продажи в 2016 году (Halliburton, '
    'РФПИ и Saudi Aramco) не реализовались.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Условие сделки о редомициляции выполнено не полностью: на '
    'сентябрь 2024 года «Роснано» подтверждало, что закрыты не все '
    'обязательства покупателя, хотя первый шаг — регистрация МКООО '
    '«Новомет» в Калининграде — уже сделан. Гендиректор Максим '
    'Перельман уступил пост Илье Тихонову. В 2025 году показатели '
    'ухудшились: выручка выросла на 9,8% до 17,27 млрд руб., но '
    'прибыль (2,59 млрд руб. в 2024 году) сменилась убытком 2,72 млрд '
    'руб., краткосрочные обязательства выросли на 25% до 23 млрд руб. '
    'В декабре 2024 года прокуратура Пермского края по инициативе '
    '«Роснано» подала иск об оспаривании договоров на поставку '
    'бурового оборудования 2015-2020 годов с семью иностранными '
    'компаниями (Коммерсантъ) — исход дела не установлен.'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/7162546'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6715059'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8570732'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/7403624'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
