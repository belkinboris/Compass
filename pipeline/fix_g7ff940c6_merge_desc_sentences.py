import json

PATH = "static/data/deals_promoted.json"
OLD = "Московская финансовая компания предпринимателя Дмитрия Матвеенко. Юрлицо — ООО «Макрон-СТ»."
NEW = "Московская финансовая компания предпринимателя Дмитрия Матвеенко; юрлицо — ООО «Макрон-СТ»."


def main():
    data = json.load(open(PATH, encoding="utf-8"))
    comp = data["companies"]["g7ff940c6"]
    assert comp["desc"] == OLD, "описание уже другое: %r" % comp["desc"]
    comp["desc"] = NEW
    json.dump(data, open(PATH, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("поправлено: g7ff940c6.desc")


if __name__ == "__main__":
    main()
