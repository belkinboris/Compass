"""Чинит склейку в `post_override` карточки `g2f22b1dc` (Росатом/«Аккую»).

Что сломано: с 1 сентября 2026 (коммит `6f6f115`, правка через реплай в
консоли) строка «Предмет» несла «до 49% в проекте АЭС «Аккую» (Турция)»
в Турции (первый энергоблок) — единым пакетом...» — механическая склейка
поля `asset` («…«Аккую» (Турция)») и продолжения `eco.share` («в Турции
(первый энергоблок)…») без удаления повтора: Турция названа дважды
подряд, и после «(Турция)» висит осиротевшая закрывающая кавычка »,
которой не было пары. Это не редакторское решение по существу (обе
части — правда, просто одна поверх другой), а обычная склейка без
дедупликации — правится вырезанием, а не пересказом.

Дефект был виден `send_telegram.py`'s ручной проверке текста при КАЖДОМ
почасовом прогоне публикации с 1 сентября (пост честно НЕ отправлялся,
`--skip g2f22b1dc`), но ни разу не попадал ни в один канал, видимый
владельцу: `ops_status.py` считает только posted/edited/applied/soon/
unread/held, а «пост придержан из-за брака в тексте» в эту разметку не
входит. Три с лишним дня карточка молча ждала, пока кто-то её откроет
руками — правка нужна была ещё 1 сентября.

Правка — только вырезание повтора и осиротевшей кавычки, ни одного
нового слова: `флет(new)` обязан лечь подстрокой на `флет(old)` минус
вырезанный кусок, проверено `assert` ниже.

Запуск: без аргументов — сухой прогон; `--write` — запись.
"""
import json
import sys

PATH = "static/data/deals_promoted.json"
DEAL_ID = "g2f22b1dc"

BROKEN = (
    "Предмет: до 49% в проекте АЭС «Аккую» (Турция)» в Турции "
    "(первый энергоблок) — единым пакетом либо несколькими компаниями."
)
FIXED = (
    "Предмет: до 49% в проекте АЭС «Аккую» в Турции "
    "(первый энергоблок) — единым пакетом либо несколькими компаниями."
)


def main():
    write = "--write" in sys.argv
    with open(PATH, encoding="utf-8") as f:
        data = json.load(f)

    deals = data["deals"]
    deal = next(d for d in deals if d["id"] == DEAL_ID) if isinstance(deals, list) else deals[DEAL_ID]

    override = deal.get("post_override") or ""
    assert BROKEN in override, "сломанной строки нет — карточку уже поправили или текст другой"

    new_override = override.replace(BROKEN, FIXED)
    # Проверка на себе: правка не добавляет ничего, кроме удаления повтора.
    assert new_override != override
    assert "(Турция)»" not in new_override
    assert override.replace(
        "«Аккую» (Турция)» в Турции", "«Аккую» в Турции"
    ) == new_override

    print("До:", repr(override[:200]))
    print("После:", repr(new_override[:200]))

    if write:
        deal["post_override"] = new_override
        with open(PATH, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            f.write("\n")
        print("Записано.")
    else:
        print("Сухой прогон — ничего не записано. Для записи: --write")


if __name__ == "__main__":
    main()
