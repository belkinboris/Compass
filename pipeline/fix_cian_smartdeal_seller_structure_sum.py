import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g4ac0a0a7'

NEW_SELLER = (
    'Алексей Макаров и Валерий Попандопуло (совладельцы поровну с 2021 '
    'года; до этого единственным владельцем компании была её гендиректор '
    'Наталья Соловьёва)'
)

OLD_LAW_STRUCT = '—'
NEW_LAW_STRUCT = (
    'Прямой покупатель по документам 2022 года — ООО «Айриэлтор», '
    'дочерняя структура «Циан». Конечная материнская компания группы, '
    'Cian PLC, зарегистрирована в Ларнаке (Кипр) — из-за иностранного '
    'конечного собственника группы-покупателя сделка потребовала '
    'одобрения правительственной комиссии по контролю за иностранными '
    'инвестициями, а не потому, что сам SmartDeal был структурирован '
    'через офшор.'
)

OLD_SUM = 'Не раскрыта'
NEW_SUM = '754 млн ₽ (плюс до 478 млн ₽ условного возмещения)'

OLD_ECO_SUM = 'Не раскрыта'
NEW_ECO_SUM = NEW_SUM

OLD_ECO_VAL = '—'
NEW_ECO_VAL = (
    'По данным CNews со ссылкой на документы компании: из выплаченных '
    '754 млн ₽ — 640 млн ₽ отложенного возмещения и 114 млн ₽ условного; '
    'сверх этого предусмотрено дополнительное условное возмещение до '
    '478 млн ₽, то есть вся сумма сделки может достичь 1 млрд ₽.'
)

OLD_ECO_CONTEXT = (
    'CEO SmartDeal Алексей Макаров перешел на работу в «Циан» на пост '
    'директора направления «Транзакционный бизнес» в департаменте '
    'управления продуктами'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + '. SmartDeal (ООО «Практика Успеха») — резидент '
    'инновационного центра «Сколково».'
)

NEW_SRC = [
    ['CNews', 'https://www.cnews.ru/news/top/2025-05-15_tsian_zaplatit_do_milliarda'],
    ['CNews', 'https://www.cnews.ru/news/line/2022-01-24_tsian_zaklyuchil_predvaritelnoe'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert 'seller' not in deal
    assert deal['law']['struct'] == OLD_LAW_STRUCT
    assert deal['sum'] == OLD_SUM
    assert deal['eco']['sum'] == OLD_ECO_SUM
    assert deal['eco']['val'] == OLD_ECO_VAL
    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    existing_urls = {s[1] for s in deal['src']}
    add_src = [s for s in NEW_SRC if s[1] not in existing_urls]
    new_src = deal['src'] + add_src

    print('=== seller: станет ===')
    print(NEW_SELLER)
    print('\n=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)
    print('\n=== sum / eco.sum: станет ===')
    print(NEW_SUM)
    print('\n=== eco.val: станет ===')
    print(NEW_ECO_VAL)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    if add_src:
        print('\n=== src: добавится ===')
        for s in add_src:
            print(s)

    if write:
        deal['seller'] = NEW_SELLER
        deal['law']['struct'] = NEW_LAW_STRUCT
        deal['sum'] = NEW_SUM
        deal['eco']['sum'] = NEW_ECO_SUM
        deal['eco']['val'] = NEW_ECO_VAL
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
