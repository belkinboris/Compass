# -*- coding: utf-8 -*-
"""Вычитка готового поста ПЕРЕД отправкой: механические признаки корявости.

ЗАЧЕМ. Пост канала собирается из полей карточки, поэтому наследует все её
дефекты — и показывает их публично. 9 августа владелец прислал четыре живых
поста подряд с одной и той же ошибкой: «Предмет: Дальневосточного банка»,
«производственную базу», «производителе картошки для чипсов Lay's». Причина
была в разборе (падеж глагола заголовка), но заметил её ЧИТАТЕЛЬ, а не
пайплайн: между сборкой поста и его отправкой не стояло ни одной проверки.

ГРАНИЦА. Это НЕ проверка смысла и не замена чтению — здесь нет ни модели, ни
сети, ни токенов. Проверяются только механические признаки, каждый из которых
уже разу приводил к публичной ошибке: падеж вместо именительного, слово
«undefined» на экране, родовое описание вместо имени стороны, заглушка,
показанная как факт, пустая карточка без единого факта. Всё это ловится
регуляркой и стоит миллисекунды.

ЧТО ДЕЛАТЬ С НАХОДКОЙ. Пост с находкой НЕ отправляется молча: он уходит в
консоль основателей на решение (там и так живёт очередь модерации). Молчаливая
публикация «как есть» — ровно то поведение, из-за которого дефект и дошёл до
читателя.

Запуск:
    python3 pipeline/publish/check_post.py       # самопроверка правил
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, 'pipeline', 'ingest'))

# Косвенный падеж там, где должен стоять именительный. Смотрим ТОЛЬКО на
# строку «Предмет:» — у сторон падеж бывает законным («Семья бизнесмена
# Говора»), а предмет обязан называться так, как он называется.
#
# Косвенный падеж проверяется у ПЕРВОГО слова, а не у любого из первых трёх.
# Разрешённые два слова впереди ловили родительный падеж определения при
# главном слове в именительном: «здание Рижского вокзала», «платформа
# персонализированных добавок». Пока строка «Предмет» печаталась только с
# новизной к заголовку, таких было мало; с 24 сентября 2026 она стоит в
# каждом посте, и замер по всей базе показал 67 срабатываний, почти все
# ложные, против 5 у правила «первое слово». Обе настоящие находки 9 августа
# («Дальневосточного банка», «производственную базу») начинаются с
# косвенного слова и ловятся по-прежнему.
OBLIQUE_TAIL = re.compile(
    r'^[а-яё]+(?:ого|его|ому|ему|ыми|ими|ую|юю|ых|их|ов|ев|ам|ям)\b', re.I)

PLACEHOLDER = re.compile(r'^(?:—|-|не\s+раскрыт[аоы]?|не\s+определена|'
                         r'публично\s+не\s+сообщалось|не\s+привлекался)$', re.I)

# Найдено владельцем 25 августа (Pridex/Multispace, ge283bafc): «Покупатель:
# В периметр сделки вошли четыре объекта…» — целое предложение-описание
# вместо имени стороны, и is_generic_description() его не поймал (он ищет
# родовое слово типа «Группа»/«Компания» в НАЧАЛЕ значения, а тут в начале
# стоит обычный предлог). Признак другой: имя почти никогда не начинается с
# предлога/союза И не заканчивается точкой — сочетание обоих специфично для
# «сюда затесалось целое предложение», проверено на всей базе (1436 строк
# Продавец/Покупатель по всем сделкам, 0 ложных срабатываний) — само по
# себе НАЧАЛО с предлога у имён иногда бывает («У Мамы»), поэтому одного
# признака мало, нужны оба сразу.
SENTENCE_NOT_A_NAME = re.compile(
    r'^(?:в|во|на|по|для|после|до|при|согласно|из|за|с|со|через|между|среди|'
    r'против|ради|у|под|над|перед)\s', re.I)


def check(text):
    """Список причин, по которым пост нельзя публиковать молча. Пусто — можно."""
    problems = []
    if not text or not text.strip():
        return ['пост пуст']

    if re.search(r'\bundefined\b|\bnull\b|\bNaN\b', text):
        problems.append('на экране служебное слово (undefined/null/NaN)')

    for line in text.splitlines():
        line = re.sub(r'<[^>]+>', '', line).strip()
        m = re.match(r'^(Предмет|Продавец|Покупатель|Сумма|Статус|Отрасль):\s*(.+)$', line)
        if not m:
            continue
        field, value = m.group(1), m.group(2).strip()
        # «не раскрыт» у стороны — не заглушка, а решение владельца от
        # 24 сентября 2026: покупатель, продавец и предмет стоят в каждом посте,
        # неизвестная сторона называется так же, как на плашке карточки сайта.
        # Прочерк и прочие заглушки по-прежнему означают, что в пост утекло
        # пустое поле карточки.
        if PLACEHOLDER.match(value) and not (
                field in ('Предмет', 'Продавец', 'Покупатель') and value == 'не раскрыт'):
            problems.append('«%s» показан заглушкой «%s» — такую строку не выводят вовсе'
                            % (field, value))
        if field == 'Предмет' and OBLIQUE_TAIL.match(value):
            problems.append('«Предмет: %s» — косвенный падеж вместо именительного'
                            % value[:40])
        if field in ('Продавец', 'Покупатель'):
            # Имя стороны, только НЕ деталь через тире («Покупатель: X — суть») —
            # деталь законно бывает целым предложением, имя перед тире — нет.
            name_part = value.split(' — ', 1)[0].strip()
            if SENTENCE_NOT_A_NAME.match(name_part) and name_part.endswith('.'):
                problems.append('«%s: %s» — похоже на предложение-описание, а не имя стороны'
                                % (field, name_part[:60]))
            try:
                from draft import is_generic_description
            except ImportError:
                continue
            if is_generic_description(value):
                problems.append('«%s: %s» — родовое описание вместо имени'
                                % (field, value[:40]))

    body = re.sub(r'<[^>]+>', '', text)
    # ЭТАП 9: формула поста больше не гарантирует строку стороны — если она
    # дословно повторяет заголовок, её теперь не печатают вовсе (правильное
    # поведение, не дефект). «Статус» добавлен в проверку по той же причине:
    # это факт о ходе сделки («закрыта», «обсуждается»), а не категория-
    # ярлык, — честно короткий пост (как «Алор брокер» после чистки, у
    # которого от старых полей остались только Статус и Отрасль) не должен
    # ловиться тем же правилом, что и правда пустой пост. «Отрасль» одна,
    # без статуса и без единой стороны/суммы, в проверку не засчитывается —
    # это ближе к ярлыку, чем к новости.
    if not re.search(r'(Предмет|Продавец|Покупатель|Сумма|Статус):', body):
        problems.append('в посте нет ни одной стороны, суммы и статуса — читателю нечего узнать')
    return problems


def check_digest(text):
    """Вычитка МЕСЯЧНОЙ СВОДКИ. Отдельная от `check()` не по прихоти: та
    проверяет пост про ОДНУ сделку и требует хотя бы одну строку «Предмет/
    Покупатель/Сумма/Статус» — у сводки таких строк нет по устройству, и
    общая проверка браковала бы каждую («в посте нет ни одной стороны»).
    Здесь свои признаки того, что публиковать нельзя: служебное слово на
    экране, ни одной ссылки на сделку (значит, месяц собрался пустым и
    сводка ни о чём) и потерянная оговорка о неполноте — без неё число
    «столько-то сделок за месяц» перескажут как статистику всего рынка."""
    problems = []
    if not text or not text.strip():
        return ['сводка пуста']
    if re.search(r'\bundefined\b|\bnull\b|\bNaN\b', text):
        problems.append('на экране служебное слово (undefined/null/NaN)')
    if '/#/deal/' not in text:
        problems.append('в сводке нет ни одной сделки — рассказывать не о чем')
    if 'публично доступн' not in text:
        problems.append('потеряна оговорка о том, что мы собираем только публично доступные сделки')
    return problems


def _self_check():
    """Правила проверяются на себе — иначе они молча пропустят то же самое."""
    bad = ('<b>МКБ завершил присоединение</b>\n\n'
           'Предмет: Дальневосточного банка\nПокупатель: МКБ\n\nСтатус: Закрыта')
    assert any('косвенный падеж' in p for p in check(bad)), 'падеж не пойман'

    good = ('<b>МКБ завершил присоединение</b>\n\n'
            'Предмет: Дальневосточный банк\nПокупатель: МКБ\n\nСтатус: Закрыта')
    assert not check(good), check(good)

    # Законные значения, которые правило трогать НЕ должно: имя во множественном
    # числе и предмет, начинающийся с прилагательного в именительном.
    for value in ('Предмет: права на СУБД «Персей»',
                  'Предмет: производственная база',
                  'Предмет: московский фармритейлер «Диалог»',
                  'Предмет: 96% акций Челябинского завода'):
        post = '<b>Заголовок</b>\n\n%s\nПокупатель: МКБ' % value
        assert not check(post), (value, check(post))

    assert any('undefined' in p for p in check('<b>X</b>\n\nСтатус: undefined\nСумма: 1 млрд ₽'))
    assert any('заглушкой' in p for p in check('<b>X</b>\n\nПредмет: —\nСумма: 1 млрд ₽'))
    assert any('нечего узнать' in p for p in check('<b>Просто заголовок</b>\n\nОтрасль: Банки'))

    # Найдено владельцем 25 августа (Pridex/Multispace) — целое предложение
    # вместо имени стороны, is_generic_description() его не ловит (нет
    # родового слова в начале).
    sentence_bug = ('<b>X</b>\n\nПокупатель: В периметр сделки вошли четыре объекта '
                    'общей площадью 18,2 тысячи квадратных метров в Москве.')
    assert any('предложение-описание' in p for p in check(sentence_bug))
    # Деталь через тире законно бывает целым предложением — проверяем только
    # часть ДО тире, а не всю строку целиком.
    with_detail = ('<b>X</b>\n\nПокупатель: «Ромашка» — В 2024 году компания '
                  'вышла на рынок Санкт-Петербурга.')
    assert not check(with_detail), check(with_detail)
    print('Самопроверка правил вычитки поста пройдена.')

    # Сводка месяца проверяется своими правилами: у неё нет строк «Предмет/
    # Покупатель», и общая проверка забраковала бы любую.
    digest = ('📊 <b>Рынок в августе</b>\n\n1. <a href="https://x/#/deal/g1">Сделка</a> — 1 млрд ₽\n'
              'Мы собираем только сделки, информация о которых публично доступна.')
    assert not check_digest(digest), check_digest(digest)
    assert check(digest), 'общая проверка не должна признавать сводку постом о сделке'
    assert any('ни одной сделки' in p for p in check_digest('Просто текст, информация публично доступна.'))
    assert any('оговорка' in p for p in check_digest('<a href="https://x/#/deal/g1">Сделка</a>'))


if __name__ == '__main__':
    _self_check()
