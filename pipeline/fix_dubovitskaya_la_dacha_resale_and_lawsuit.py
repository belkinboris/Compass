import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gb31c796f'

OLD_ECO_CONTEXT = (
    'Весной 2022 года администрация Лиманского района Астраханской '
    'области подала в Арбитражный суд Москвы иск к ООО «Ла дача '
    'Астрахань» по поводу прав на участок земли площадью 2,5 га под '
    'гостевым домом, поскольку он находится на землях особо охраняемых '
    'территорий'
)
NEW_ECO_CONTEXT = OLD_ECO_CONTEXT + (
    '. 27 июля 2022 года администрация отозвала иск, и суд прекратил '
    'производство по делу.'
)

OLD_EXTRA = (
    'Сделка закрыта. Покупатель — Наталия Дубовицкая (супруга '
    'экс-помощника президента РФ В. Суркова), совладелица ООО «Бюро '
    'Дрим» и ООО «Бюро СПБ», владелица ООО «Ветрадиология». Продавец — '
    'Елена Полетаева, владевшая компанией менее двух недель (с '
    '11 сентября 2023 года). Предыдущие владельцы: кипрский офшор '
    'Woorlon Holdings Limited, Станислав Подольский, Digitdrive '
    'Limited.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Актив перепродан уже через три недели: с 11 октября 2023 года '
    'владельцем «Ла дача Астрахань» стало ООО «Птицефабрика '
    '«Акашевская»» — этой компанией через «Марфининвест» владеет Мария '
    'Лисицина, которая, по мнению рынка, представляет интересы семьи '
    'экс-губернатора Краснодарского края Александра Ткачева. Эксперт '
    '(Ivashkevich Hospitality) оценивал рыночную стоимость объекта в '
    '1 млрд ₽; источники отмечали, что продавец, скорее всего, не вышел '
    'на прибыль от этой цепочки перепродаж. Это отдельная сделка, для '
    'которой пока нет своей карточки в базе.'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6281365'],
    ['РИА Недвижимость', 'https://realty.ria.ru/20231017/villa-1903249316.html'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
