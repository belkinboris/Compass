import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gac36eece'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Закрыта'

OLD_DATE = '2022-12-01'
NEW_DATE = '2022-12-27'

OLD_ECO_CONTEXT = (
    'О переходе KDL в ГК «Медскан», где 25% принадлежат структуре '
    '«Росатома», стало известно в конце октября.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' Сумма сделки сторонами не раскрыта: гендиректор '
    '«Infoline-аналитики» Михаил Бурмистров оценивал KDL в 15 млрд ₽, '
    'источник, близкий к одной из сторон, — в 19–20 млрд ₽. В 2023 '
    'году «Сбербанк Инвестиции» вошли в капитал головной «Медскан Лаб» '
    '(49% за 2,75 млрд ₽, позже сократив долю до 39%), а в октябре 2025 '
    'года «Медскан» выкупил эту долю обратно за 4,767 млрд ₽ — по '
    'словам компании, «для завершения приобретения сети KDL и снижения '
    'долговой нагрузки перед планируемым выходом на IPO».'
)

OLD_SRC = [['Forbes', 'https://www.forbes.ru/biznes/480480-medicinskij-holding-medskan-kupit-set-laboratorij-kdl']]
NEW_SRC = OLD_SRC + [
    ['Ведомости', 'https://www.vedomosti.ru/business/articles/2022/12/28/957441-gruppa-medskan'],
    ['Vademecum', 'https://vademec.ru/news/2025/10/28/v-medskane-nazvali-prichinu-sdelki-po-vykhodu-struktury-sberbanka-iz-kholdingovoy-kompanii-gruppy-kd/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS
    assert deal['date'] == OLD_DATE
    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== status: станет ===')
    print(NEW_STATUS)
    print('\n=== date: станет ===')
    print(NEW_DATE)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['status'] = NEW_STATUS
        deal['date'] = NEW_DATE
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
