# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g25448b74 (Магнит купил маркетплейс KazanExpress, 19.10.2023, статус
«Закрыта») — проект прошёл полный цикл от ребрендинга до фактического
сворачивания модели маркетплейса менее чем через три года.

Ребрендинг — по данным саб-агента (Forbes, 15.04.2024, не дозаверено
отдельным WebFetch): «"Магнит" начал перевод маркетплейса KazanExpress
под бренд "Магнит Маркет"» — имя KazanExpress не сохранилось.

Сворачивание модели — проверено лично прямым WebFetch (Ведомости,
29.07.2026): «Магнит маркет» отказывается от стратегии универсального
маркетплейса и переходит на модель «расширенной полки»; «с 6 сентября
маркетплейс приостановит работу основной витрины на сайте и в
приложении для покупателей»; доля среди мультикатегорийных
маркетплейсов — «менее 1%» при ёмкости сегмента 9,75 трлн руб.;
выручка 2025 года — 5,1 млрд руб.

НЕ ВКЛЮЧЕНО: точные убытки по годам (саб-агент нашёл 2024 — «более 3
млрд руб.», 2025 — 4,9 млрд руб., рост на 51,9%) и падение в рейтинге
маркетплейсов (57-е место в 2024 году против 39-го в 2023-м, когда
это ещё был KazanExpress) — из вторичных изданий (oborot.ru), не
дозаверено отдельным WebFetch; уход руководителя проекта и закрытие
ПВЗ в отдельных регионах — детали, не меняющие сути находки.

Запуск: python3 pipeline/fix_magnit_market_shutdown_2026.py
        python3 pipeline/fix_magnit_market_shutdown_2026.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g25448b74'

OLD_EXTRA = (
    'Сделка по покупке маркетплейса KazanExpress. Магнит намерен '
    'запустить на его базе собственный маркетплейс «Магнит Маркет», '
    'увеличив географию и число пунктов выдачи за счет открытия ПВЗ '
    'в магазинах сети, а также развивая товарные категории и '
    'привлекая новых продавцов.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Планы не оправдались: маркетплейс переименован в «Магнит '
    'Маркет» в 2024 году, но доля среди мультикатегорийных '
    'маркетплейсов осталась «менее 1%» при выручке 5,1 млрд руб. за '
    '2025 год. 29 июля 2026 года «Магнит» объявил отказ от модели '
    'универсального маркетплейса — с 6 сентября 2026 года витрина '
    'сторонних продавцов останавливается, проект превращается в '
    '«расширенную полку» доставки сети.'
)

NEW_SRC = [
    ['Ведомости', 'https://www.vedomosti.ru/business/articles/2026/07/29/1217412-magnit-market-obyavil'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
