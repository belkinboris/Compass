# -*- coding: utf-8 -*-
"""ВТБ/агрохолдинг «Покровский» (`g2668950b`): 28 августа 2026 года первый
зампред ВТБ Дмитрий Пьянов сообщил, что соглашение об условиях с покупателем
«Лабинского» уже подписано и банк ожидает закрытия сделки до конца года —
шаг заметно конкретнее апрельского заявления Костина о намерении продать
(уже отражённого в eco.context). Покупатель по имени не назван.

Цитата не лежит в тексте старых источников (Коммерсантъ/Ведомости.Юг от
апреля) — тот же приём, что и в прежних правках этого поля: старое значение
сохраняется, дописывается новое предложение со ссылкой на источник.

Статус карточки НЕ меняется: подписано соглашение об УСЛОВИЯХ с покупателем,
а не сама сделка купли-продажи — «Закрыта» уже стоит за сделку ВТБ/
Росимущество 2024 года (предмет карточки), а не за будущую перепродажу
«Лабинского» — это отдельная сделка (пока в базе не заведена своей
карточкой, решение о создании новой карточки — отдельный шаг, не этот).

Запуск: python3 pipeline/fix_vtb_pokrovsky_agreement_signed_context.py           # проверка
        python3 pipeline/fix_vtb_pokrovsky_agreement_signed_context.py --write   # запись
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g2668950b'
OLD_CONTEXT = (
    'До 2023 года основным владельцем «Покровского» являлись бывший '
    'инспектор аппарата полномочного представителя президента РФ в ЮФО '
    'Андрей Коровайко и его партнер по бизнесу Аркадий Чебанов. В октябре '
    '2023 года Лабинский городской суд удовлетворил требование '
    'Генеральной прокуратуры РФ о передаче активов «Покровского» в '
    'ведение Росимущества в связи с обвинениями в коррупции в адрес '
    'Коровайко и Чебанова. По данным суда, Коровайко несколько лет '
    'использовал служебное положение для захвата чужих бизнесов и '
    'создания своих, в чем также участвовали судьи Арбитражного суда '
    'Ростовской области. ВТБ не намерен развивать актив внутри группы: '
    'в апреле 2026 года глава банка Андрей Костин объявил о решении '
    'продать сельскохозяйственные активы — «У нас есть '
    'сельскохозяйственные [активы], но я принял решение их продать. '
    'Будем только в городе работать», уточнив про предстоящий конкурс по '
    '«Лабинскому»: «Да, у нас там конкурс будет, там много желающих». '
    'Причина — новое регулирование ЦБ с 1 апреля 2027 года, ограничивающее '
    'вложения банков в непрофильные активы. По данным «Коммерсанта», '
    'общая оценочная стоимость сельскохозяйственного портфеля ВТБ '
    'превышает 55 млрд руб., реализовать активы банк рассчитывает к 2027 '
    'году; вероятные претенденты — «Агрокомплекс им. Н. И. Ткачева» и '
    'структуры предпринимателя Али Узденова, а также агрохолдинг '
    '«Просторы».'
)
ADDITION = (
    '28 августа 2026 года первый зампред ВТБ Дмитрий Пьянов сообщил: «До '
    'конца года ожидаем сделку по продаже активов "Лабинского"», добавив, '
    'что соглашение об условиях с покупателем уже подписано.'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + ADDITION
NEW_SRC = ['ПРАЙМ', 'https://1prime.ru/20260828/vtb-872759641.html']


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    card = next((c for c in data['deals'] if c['id'] == CARD_ID), None)
    assert card is not None, '%r не найдена в базе' % CARD_ID
    assert card.get('eco', {}).get('context') == OLD_CONTEXT, (
        'eco.context уже другое: %r' % card.get('eco', {}).get('context'))
    src_already_present = NEW_SRC in card.get('src', [])

    print('ДОБАВЛЕНО: %r' % ADDITION)
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return 1

    card['eco']['context'] = NEW_CONTEXT
    if not src_already_present:
        card.setdefault('src', []).append(NEW_SRC)
    json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('ЗАПИСАНО.')
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv[1:]))
