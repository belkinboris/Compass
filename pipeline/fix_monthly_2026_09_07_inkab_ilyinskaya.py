import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

INKAB_ID = 'inkab-ipo'
INKAB_OLD_CONTEXT = (
    'Основной акционер Александр Смильгевич обязался не сокращать '
    'долю 5 лет и поддерживать дивиденды не менее 50% чистой прибыли '
    'по МСФО. Около 65% объёма собрано ещё на этапе премаркетинга. '
    'С 29.06.2026 акции INCB входят в индекс IPO Мосбиржи.'
)
INKAB_NEW_CONTEXT = (
    INKAB_OLD_CONTEXT + ' После размещения по 100 ₽ акции достигли '
    'исторического максимума 101,08 ₽ (25 июня), но к 17 июля упали до '
    'минимума 58,16 ₽. Совет директоров утвердил стратегию на '
    '2026–2027 годы: целевая выручка на 2026 год — не менее 7,5 млрд ₽, '
    'чистая прибыль — 1,3 млрд ₽; на 2027 год — 11,9 млрд ₽ и 2,4 млрд '
    '₽ соответственно. По итогам первого полугодия 2026 года выручка '
    'снизилась на 16% год к году, до 2116,4 млн ₽, зато чистая прибыль '
    'вышла на исторический максимум — 298,4 млн ₽, EBITDA выросла на '
    '57%, а чистый долг сократился с 3,76 до 1,72 млрд ₽ (отношение '
    'чистый долг/EBITDA — 1,3× против 3,65× на конец 2025 года).'
)

MID_ID = 'mid-ilyinskaya'
MID_OLD_CONTEXT = (
    'Доли продавцов — ТОО «Emdeu Medline» (92,11%) и ООО «Раф-Мед» '
    '(7,88%) — находились в залоге у Сбербанка. Финансовый директор '
    'группы Ия Лукьянова повысила прогноз роста выручки на 2026 год до '
    '24–25%.'
)
MID_NEW_CONTEXT = (
    MID_OLD_CONTEXT + ' По итогам первого полугодия 2026 года выручка '
    'группы «Мать и дитя» выросла на 28,8% год к году, до 24 809 млн ₽ '
    '— рост связан прежде всего с динамикой амбулаторного и '
    'стационарного направлений, в том числе за счёт присоединившейся '
    'ранее сети «Эксперт»; вклад именно Ильинской больницы отдельно не '
    'выделен — сделка закрылась 24 июня, ближе к концу отчётного '
    'периода.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    inkab = by_id[INKAB_ID]
    mid = by_id[MID_ID]

    assert inkab['eco']['context'] == INKAB_OLD_CONTEXT
    assert mid['eco']['context'] == MID_OLD_CONTEXT

    print('=== inkab-ipo: eco.context ===')
    print(INKAB_NEW_CONTEXT)
    print()
    print('=== mid-ilyinskaya: eco.context ===')
    print(MID_NEW_CONTEXT)

    if write:
        inkab['eco']['context'] = INKAB_NEW_CONTEXT
        mid['eco']['context'] = MID_NEW_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
