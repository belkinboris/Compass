# -*- coding: utf-8 -*-
"""Месячная очередь качества, 11 сентября 2026 — карточка `cf6de2938`
(«Раздел активов Яндекса между российской и международной
структурами») несла НЕВЕРНУЮ сумму сделки: «$70–80 млн» — это, по
статье-источнику (Коммерсантъ), сумма, обсуждавшаяся в правкомиссии
как компенсация Yandex N.V. НА РАННЕМ этапе переговоров, а не итоговая
цена сделки. Реальное закрытие произошло в два этапа, финальная оценка
— 475 млрд ₽ (≈$5,2 млрд), и сделка полностью закрыта.

Личный WebFetch подтвердил дословно:

1) Interfax, https://www.interfax.ru/business/944509:
   «Yandex N.V., головная компания "Яндекса", договорилась о продаже
   российского бизнеса за 475 млрд рублей консорциуму частных
   инвесторов»; «продавец получит эквивалент как минимум 230 млрд
   рублей в китайских юанях и до 176 млн акций класса "А" Yandex
   N.V.»; состав консорциума — «структуры "ЛУКОЙЛа", экс-зампреда
   "Газпрома" Александра Рязанова, основателя LETA Capital Александра
   Чачавы и гендиректора "Инфинитума" Павла Прасса».

2) Ведомости, 15 июля 2024,
   https://www.vedomosti.ru/investments/news/2024/07/15/1050031-yandex-nv:
   «Утром 15 июля новый владелец "Яндекса" – ЗПИФ "Консорциум.
   Первый" – сообщил о завершении всех расчетов по биржевому и
   внебиржевому обмену и выкупу акций Yandex N.V.»; «Yandex N.V.
   закрыла сделку по продаже бизнеса "Яндекса" и полностью вышла из
   состава акционеров группы»; «До конца июля компания сменит
   название и перестанет использовать бренды "Яндекса"».

Старая сумма ($70–80 млн) и её контекст (обсуждение в правкомиссии,
критика Аркадия Воложа) не удаляются — они остаются в `eco.context`
как исторический этап переговоров, но дополнены итоговым исходом, а
`sum`/`eco.sum`/`eco.val` переписаны на подтверждённую итоговую цену,
чтобы верхнеуровневое поле не вводило в заблуждение о размере сделки.
`status` меняется на «Закрыта» (сделка подтверждена завершённой),
`date` уточняется до дня закрытия (год уже стоял верно), `buyer_name`
— ЗПИФ «Консорциум.Первый» (у фонда нет отдельного профиля компании).

Запуск:
    python3 pipeline/fix_yandex_split_closed_2024.py            # сухой прогон
    python3 pipeline/fix_yandex_split_closed_2024.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_SUM = '$70–80 млн (сниженная сумма, ранее $250 млн)'
NEW_SUM = '475 млрд ₽ (≈$5,2 млрд)'

OLD_ECO_SUM = '$70–80 млн'
NEW_ECO_SUM = NEW_SUM

OLD_ECO_VAL = '$70–80 млн (сниженная сумма, ранее $250 млн)'
NEW_ECO_VAL = (
    'Итоговая оценка бизнеса — 475 млрд ₽ (≈$5,2 млрд). Yandex N.V. '
    'получила не менее 230 млрд ₽ эквивалентом в китайских юанях и до '
    '176 млн акций класса «А» Yandex N.V.'
)

OLD_ECO_CONTEXT = (
    'Сообщение о переговорах в профильной правкомиссии по условиям '
    'разделения активов Яндекса. По информации, сумма, которая должна '
    'была отойти нидерландской Yandex N.V., снизилась с $250 млн до '
    '$70–80 млн вследствие критики военных действий сооснователем '
    'Аркадием Волож.'
)
NEW_ECO_CONTEXT = OLD_ECO_CONTEXT + (
    ' Сделка закрылась в два этапа и завершилась полностью 15 июля '
    '2024 года: ЗПИФ «Консорциум.Первый» (менеджмент «Яндекса», '
    'структуры «Лукойла», Александра Чачавы, Павла Прасса и Александра '
    'Рязанова) выкупил российский бизнес у Yandex N.V., которая '
    'полностью вышла из состава акционеров и до конца июля 2024 года '
    'сменила название на Nebius Group.'
)

OLD_DATE = '2024'
NEW_DATE = '2024-07-15'


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['cf6de2938']

    assert d['sum'] == OLD_SUM, 'sum уже другое: %r' % (d['sum'],)
    assert d['eco']['sum'] == OLD_ECO_SUM, 'eco.sum уже другое: %r' % (d['eco']['sum'],)
    assert d['eco']['val'] == OLD_ECO_VAL, 'eco.val уже другое: %r' % (d['eco']['val'],)
    assert d['eco']['context'] == OLD_ECO_CONTEXT, 'eco.context уже другой'
    assert d.get('status') is None, 'status уже занят: %r' % (d.get('status'),)
    assert d.get('buyer_name') is None, 'buyer_name уже занят: %r' % (d.get('buyer_name'),)
    assert d['date'] == OLD_DATE, 'date уже другая: %r' % (d['date'],)

    print('cf6de2938: sum/eco.sum/eco.val исправлены на подтверждённую итоговую '
          'цену (475 млрд ₽), status -> Закрыта, date уточнена до 2024-07-15, '
          'buyer_name -> ЗПИФ «Консорциум.Первый», eco.context дополнен исходом')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['sum'] = NEW_SUM
    d['eco']['sum'] = NEW_ECO_SUM
    d['eco']['val'] = NEW_ECO_VAL
    d['eco']['context'] = NEW_ECO_CONTEXT
    d['status'] = 'Закрыта'
    d['date'] = NEW_DATE
    d['buyer_name'] = 'ЗПИФ «Консорциум.Первый»'
    d['src'].append(['Ведомости', 'https://www.vedomosti.ru/investments/news/2024/07/15/1050031-yandex-nv'])

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
