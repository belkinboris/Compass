# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g1e2b16c3 (S8 Capital приобрела шинный завод Bridgestone в России,
декабрь 2023, статус «Закрыта») — завод перезапущен под новым брендом,
а весь шинный холдинг S8 Capital позже продан целиком «Севергрупп»
Алексея Мордашова.

Ребрендинг — проверено через WebSearch со ссылкой на Коммерсантъ
(08.07.2024): завод в Ульяновске возобновил работу в ноябре 2024 года
под брендом Gislaved; по данным саб-агента (Автостат, 20.03.2026, не
дозаверено отдельным WebFetch) — за 2025 год произведено 1,2 млн шин
по плану, освоено 148 типоразмеров в двух брендах (Gislaved и
Cordiant).

Продажа всего холдинга — проверено лично прямым WebFetch (Коммерсантъ,
02.10.2024, doc/7198179): покупатель — «Севергрупп» Алексея
Мордашова, продавец — холдинг S8 Capital, «Сделка была одобрена
антимонопольными органами», право собственности получено 1 октября
2024 года; в периметр вошли бренды Cordiant, Tunga, Torero, Gislaved,
Cordiant Professional, Tyrex и производства «Метеор Авто», «Метеор
Термо», «Метеор Тех» (около 8 тыс. сотрудников). Согласование ФАС
относится к ЭТОЙ более поздней сделке (продажа всего холдина
«Севергрупп»), а не к сделке 2023 года с S8 Capital, которой посвящена
карточка, — записано в `law.appr` с явной оговоркой, тем же приёмом,
что уже применён к «Воркутауглю»/АЕОН и «Агама»/«Юнифрост».

НЕ ВКЛЮЧЕНО: сумма сделки с «Севергрупп» не раскрыта ни в одном
источнике; доля рынка объединённого «Кордианта» (13% легковых шин РФ
в 2025 году) и цель по выручке 50 млрд руб. к концу 2026 — по данным
саб-агента (rupec.ru), не дозаверено отдельным WebFetch; покупка S8
Capital активов Huntsman (январь 2024, завод полиуретана в Обнинске)
— отдельная, не связанная с шинным дивизионом сделка, в карточку не
добавляется.

Запуск: python3 pipeline/fix_s8_bridgestone_gislaved_resold_severgroup.py
        python3 pipeline/fix_s8_bridgestone_gislaved_resold_severgroup.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g1e2b16c3'

OLD_EXTRA = (
    'Сделка закрыта в декабре 2023 года. S8 Capital (холдинг Армена '
    'Саркисяна) приобрела завод Bridgestone в Ульяновске. Торговые '
    'марки и бренд Bridgestone новому собственнику не передаются. Это '
    'третье приобретение шинного дивизиона S8 Capital после сделок с '
    'Continental (май 2023, завод в Калуге) и «Кордиант» (май 2023, '
    'три предприятия в Омске и Ярославле).'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Завод возобновил работу в ноябре 2024 года под брендом '
    'Gislaved. Весь шинный холдинг S8 Capital (Continental, '
    '«Кордиант», Bridgestone/Gislaved) продан целиком «Севергрупп» '
    'Алексея Мордашова — та получила право собственности 1 октября '
    '2024 года (согласование — см. «Согласования» ниже).'
)

OLD_LAW_APPR = 'Публично не сообщалось'
NEW_LAW_APPR = (
    'Продажу всего шинного холдинга S8 Capital (включая бывший завод '
    'Bridgestone) компании «Севергрупп» Алексея Мордашова одобрили '
    'антимонопольные органы — сделка закрыта 1 октября 2024 года. Это '
    'согласование относится к более поздней, отдельной сделке '
    '(продажа всего холдинга), а не к покупке завода S8 Capital в '
    '2023 году, которой посвящена эта карточка.'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/7198179'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA
    assert deal['law']['appr'] == OLD_LAW_APPR

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== law.appr: станет ===')
    print(NEW_LAW_APPR)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['law']['appr'] = NEW_LAW_APPR
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
