# -*- coding: utf-8 -*-
"""Две карточки — настоящие реорганизации (ст. 57-58 ГК РФ), но не несли
type="Реорганизация": проверка по всей базе (17 августа 2026) искала слова
«присоединение/слияние/разделение/выделение/реорганизация» вне уже
размеченного g998e5eb5 (МКБ/Дальневосточный банк) и нашла 129 упоминаний,
из которых 127 — шум («подразделение» содержит «разделение» подстрокой,
«слияния и поглощений» — идиома рынка, «трансформация»/«реорганизация
направления» — обычная деловая перестройка, а не смена юрлица).

Настоящих две:

- c3e0b0e8f: «Присоединение ООО «Глобус» к АО «Авиакомпания «Сибирь»»
  (реорганизация)» — заголовок и `extra` прямо называют присоединение,
  решение единственного акционера, регистрацию в ЕГРЮЛ. Была без единой
  структурной стороны (buyer/target/asset все пусты) и типом «M&A».
- cfeca52ce: «Детский мир завершил реорганизацию с выделением дочерней
  компании ООО ДМ» — `eco.share`/`extra` прямо называют форму (выделение).
  Была типом «Продажа с торгов» — вероятно, из-за того, что в той же
  новости описан ещё и выкуп акций у несогласных акционеров, но ПРЕДМЕТ
  карточки (заголовок, первое предложение) — сама реорганизация, а не
  аукцион.

Для выделения понадобилась НОВАЯ пара ролей: при присоединении сторона
прекращает существование в пользу правопреемника, а при выделении
ИСХОДНОЕ общество, наоборот, сохраняется (ГК РФ и ст. 19 ФЗ «Об АО» прямо
говорят «без прекращения последнего») — паре «правопреемник/присоединяемое
общество» здесь неоткуда взяться. Термины проверены (WebSearch, 17 августа
2026): «присоединяемое общество» — соответствует ст. 17 ФЗ «Об АО»,
«выделяемое общество» — самой сути определения в ст. 19. Слово
«сливающееся общество», которое звучало правдоподобно, в законе НЕ
встречается: там «общество, участвующее в слиянии» — компактный термин не
вводим. Раз в базе нет ни одной карточки-слияния и ни одной
карточки-разделения, `static/index.html` для этих форм подстраховочно
использует ту же пару, что для присоединения (сторона тоже прекращает
существование), а `reorg_form` пока умеет только "выделение" (см.
REORG_ROLES в static/index.html) — расширять по факту появления настоящей
карточки, а не заранее.

Запуск:
    python3 pipeline/fix_reorg_misclassified.py           # сухой прогон
    python3 pipeline/fix_reorg_misclassified.py --write    # запись
"""
import json
import sys

PATH = "static/data/deals_promoted.json"

FIXES = [
    dict(
        id="c3e0b0e8f",
        assert_type="M&A",
        set=dict(
            type="Реорганизация",
            buyer_name="АО «Авиакомпания «Сибирь»»",
            asset="ООО «Глобус»",
        ),
        why="присоединение ООО «Глобус» к АО «Авиакомпания «Сибирь»» — "
            "заголовок и extra прямо называют реорганизацию и присоединение, "
            "структурных полей не было вовсе (M&A по умолчанию генератора).",
    ),
    dict(
        id="cfeca52ce",
        assert_type="Продажа с торгов",
        set=dict(
            type="Реорганизация",
            reorg_form="выделение",
            buyer="g47bca1da",     # ПАО «Детский мир» — профиль уже есть
            asset="ООО ДМ",
        ),
        why="выделение 100% дочерней операционной компании ООО ДМ — заголовок "
            "и eco.share прямо называют форму; тип «Продажа с торгов» относился "
            "к соседнему сюжету (выкуп акций у несогласных), а не к самой "
            "реорганизации, которой посвящена карточка.",
    ),
]


def main(write):
    with open(PATH, encoding="utf-8") as f:
        base = json.load(f)
    by_id = {d["id"]: d for d in base["deals"]}

    for fix in FIXES:
        d = by_id.get(fix["id"])
        assert d is not None, f"карточка {fix['id']} не найдена"
        assert d.get("type") == fix["assert_type"], (
            f"{fix['id']}: ожидали type={fix['assert_type']!r}, "
            f"а стоит {d.get('type')!r} — уже правили?")
        print(f"{fix['id']}: type {d.get('type')!r} -> "
              f"{fix['set']['type']!r}  ({fix['why']})")
        for k, v in fix["set"].items():
            print(f"   {k}: {d.get(k)!r} -> {v!r}")
            d[k] = v

    if write:
        with open(PATH, "w", encoding="utf-8") as f:
            json.dump(base, f, ensure_ascii=False, indent=1)
        print(f"\nЗАПИСАНО: {len(FIXES)} карточек переклассифицированы.")
    else:
        print("\nСухой прогон — ничего не записано. Добавьте --write.")


if __name__ == "__main__":
    main(write="--write" in sys.argv)
