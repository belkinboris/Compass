# -*- coding: utf-8 -*-
"""Предмет сделки — не компания: убрать объекты из каталога «Компании».

ЗАЧЕМ. 22 сентября 2026 владелец открыл в каталоге профиль «проект добычи
золота Быстринско-Ширинское»: «Это не компания. Это убрать надо. Остаться в
компаниях могут быть только те которые компании. Ооошки аошки фонды зпифы но
точно не дома и не проекты.»

ПОЧЕМУ НЕ УДАЛЕНИЕ. Такие профили — ПРЕДМЕТ реальных сделок: по ним стоит
`target`/`asset_id` карточки, с них ведёт плашка сторон, на них считается
история сделок. Удаление сломало бы карточки и увело читателя в никуда.
Поэтому профиль остаётся, а из КАТАЛОГА уходит: признак `asset: true` читает
клиент (`companyRows`, подсказки поиска, счётчики) и не показывает такой
профиль в списке компаний. Ссылка с карточки сделки по-прежнему открывается,
и на странице честно написано, что это объект, а не компания.

КАК ОТБИРАЛИ. Чтение всех 2028 профилей (имя, отрасль, описание, а при
сомнении — карточка сделки). Правило, по которому решали:
  • родовое имя физического объекта (БЦ/ТРЦ/ТЦ, здание, отель, склад,
    участок, логопарк, месторождение, проект, лицензия, бренд, доля,
    портфель, «завод <иностранный бренд> в <городе>») — объект;
  • имя совпадает с именем юрлица (включая завод со СВОИМ именем) или это
    физлицо — компания;
  • лот из нескольких ЮРЛИЦ — компания, лот из нескольких ОБЪЕКТОВ — объект;
  • сомнение — компания.
Цена ошибки несимметрична: спрятать живую компанию хуже, чем оставить в
каталоге лишнюю строку, — поэтому сомнение всегда в пользу компании.

ЧТО НАШЛОСЬ ПО ДОРОГЕ (одно слово в имени ничего не решает):
  • «Зингер» выглядит арендой Дома Зингера, а куплено 100% акций ЗАО «Зингер»;
  • «Курорт «Архыз»» — на вид канатные дороги, в карточке 100% акций АО «УК
    «Архыз»»;
  • завод «Электропульт», завод «Транскат», «Завод специального оборудования»
    — юрлица со своими именами; а завод Volvo в Калуге, завод Takeda в
    Ярославле и заводы Bosch в Энгельсе — переданная недвижимость и
    оборудование;
  • «Ingka Centres (портфель ТЦ «Мега»)» по имени портфель, а по базе —
    ПРОДАВЕЦ в трёх сделках, то есть шведская компания.

ПРИЗНАК ЛЕЖИТ ОТДЕЛЬНЫМ ПОЛЕМ, А НЕ ВЫВОДИТСЯ ИЗ РЕЕСТРА ФНС. Проверено
счётом: из 257 прочитанных профилей реестр расходится с чтением у 47 — у 25
объектов там стоит подтверждённый ИНН (это SPV, владеющие зданием), а у 22
компаний ИНН просто не нашли. Реестр отвечает на вопрос «есть ли у этого
имени юрлицо», а каталог — на вопрос «компания это или объект»; это разные
вопросы.

    python3 pipeline/mark_catalog_assets_2026_09_22.py
    python3 pipeline/mark_catalog_assets_2026_09_22.py --write
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "static" / "data" / "deals_promoted.json"
ANSWERS = ROOT / "data" / "inbox" / "catalog" / "assets_2026_09_22.json"


def main(write: bool) -> int:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    comp = data["companies"]
    rows = json.loads(ANSWERS.read_text(encoding="utf-8"))

    sides = set()
    for deal in data["deals"]:
        for field in ("buyer", "seller_id"):
            if deal.get(field):
                sides.add(deal[field])

    mark, refuse, already = [], [], 0
    for row in rows:
        if row.get("verdict") != "asset":
            continue
        cid = row["id"]
        profile = comp.get(cid)
        if profile is None:
            refuse.append((cid, row.get("name"), "профиля нет в базе"))
            continue
        # ЖИВУЮ СТОРОНУ СДЕЛКИ НЕ ПРЯЧЕМ НИКОГДА. Покупатель или продавец —
        # по определению участник рынка, каким бы ни было его имя: профиль
        # «Ingka Centres (портфель ТЦ «Мега»)» назван портфелем, а стоит
        # продавцом в трёх сделках.
        if cid in sides:
            refuse.append((cid, row.get("name"), "профиль стоит покупателем или продавцом"))
            continue
        if profile.get("asset"):
            already += 1
            continue
        mark.append((cid, row.get("name")))
        if write:
            profile["asset"] = True

    for cid, name, why in refuse:
        print("   ОТКАЗ  %s %-46s %s" % (cid, str(name)[:46], why))
    print("Убрать из каталога: %d" % len(mark))
    if already:
        print("Уже помечено раньше: %d" % already)
    for cid, name in mark[:12]:
        print("   %s %s" % (cid, str(name)[:70]))
    if len(mark) > 12:
        print("   … и ещё %d" % (len(mark) - 12))
    if not write:
        print("\n(сухой прогон; чтобы записать — --write)")
        return 0
    if mark:
        DATA.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        print("\nзаписано")
    return 0


if __name__ == "__main__":
    sys.exit(main("--write" in sys.argv))
