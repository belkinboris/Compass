"""Приток, 14:20 МСК 30 сентября 2026: ПРАЙМ сообщил, что Роснедра
выставили на торги участок Кипчакский — месторождение марганцевых руд в
Челябинской области (Кизильский район), начальная цена 172,578 млн ₽,
лицензия на 25 лет. Заявки до 30 октября, торги 17 ноября. Ворота не
пропустили черновик автоматически. Собрал вручную, тот же класс случая,
что карточки с недвижимостью на торгах.

Саб-агент независимого подтверждения САМОГО тендера не нашёл (единственный
источник — ПРАЙМ), но нашёл дословный фон о стратегической причине:
Счётная палата ещё в 2021 году отмечала зависимость России от импорта
марганца, а после 2022 года Евросоюз запретил поставки марганцевой руды в
Россию (theins.ru). Это фон, не подтверждение самого тендера — источник
по тендеру остаётся единственный, `--mark-read`, не `--mark-deep`.

Запуск: python3 pipeline/fix_add_rosnedra_manganese_card.py [--write]
"""
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'ingest'))

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')


def main(write=False):
    import promote

    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    ids = {c['id'] for c in data['deals']}
    new_id = promote.new_id(ids)

    draft = {
        'date': '2026-09-30',
        'title': 'Роснедра выставили на торги участок марганцевых руд в Челябинской области',
        'ind': 'ГМК и добыча',
        'type': 'Продажа с торгов',
        'status': 'Обсуждается',
        'sum': '172,578 млн ₽',
        'seller': 'Роснедра',
        'asset': 'лицензия на участок Кипчакский — месторождение марганцевых руд в Кизильском районе Челябинской области (25 лет, площадь 4,23 км²)',
        'src': [['ПРАЙМ', 'https://1prime.ru/20260930/rosnedra-873803090.html']],
        'events': [
            {'kind': 'negotiations', 'date': '2026-09-30', 'title': 'Торги объявлены',
             'note': 'Заявки принимаются до 30 октября, торги назначены на 17 ноября 2026 года.',
             'source': ['ПРАЙМ', 'https://1prime.ru/20260930/rosnedra-873803090.html']},
        ],
    }
    card = promote.to_card(draft, new_id)
    card['eco']['sum'] = draft['sum']
    card['eco']['context'] = (
        'Прогнозные ресурсы окисленных марганцевых руд по категории Р1 (при бортовом '
        'содержании марганца 10%) оценены в 11,2 млн тонн со средним содержанием '
        'марганца 15,67% — так сказано в приложении к приказу Уралнедра. Развитие '
        'марганцевых месторождений — часть более широкой задачи: Счётная палата ещё в '
        '2021 году отмечала зависимость экономики России от импорта марганца, хрома, '
        'титана и лития, а после 2022 года Евросоюз запретил поставки марганцевой руды '
        'в Россию. Кипчакский участок много меньше крупнейшего в стране '
        'Больше-Токмакского месторождения (запасы свыше 1,7 млрд тонн, в его операторе '
        'весной 2026 года АО «Флагман» купило долю почти в 17% — отдельная сделка, не '
        'эта).'
    )
    card['themes'] = ['Продажа с торгов']
    card['added'] = '2026-09-30'

    data['deals'].append(card)
    print('Добавлена карточка %s: %s' % (new_id, card['title']))

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
