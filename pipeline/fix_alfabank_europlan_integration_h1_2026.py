# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка g78986e22 (Альфа-банк/
«Европлан»): дельта-поиск нашёл конкретику по интеграции «Альфамобиля» в
«Европлан» (карточка знала только о планах, не о структуре) и первые
публичные финансовые показатели «Европлана» за первое полугодие 2026 года
под новым владельцем — оба факта из источников, отличных от уже
использованных в соответствующих полях, поэтому не через review.py.

Источники — читал напрямую (fetch_article_texts.py, оба закэшированы):
smart-lab.ru (интеграция, без даты публикации в тексте, но материал об
уже принятых кадровых решениях) и smart-lab.ru (финрезультаты за I
полугодие 2026 года).
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g78986e22'

OLD_STRUCT = (
    'Было принято решение о поэтапной интеграции «Альфамобиля» '
    '(розничное подразделение «Альфа-Лизинга») и «Европлана». «Мы '
    'де-факто дали возможность контролировать поток генерации стока '
    '«Европлану». Соответственно, в течение ближайшего года произойдет '
    'интеграция, но не за счет юридического присоединения, а за счет '
    'амортизации старого портфеля «Альфамобиля». Новый розничный '
    'лизинговый бизнес будет расти на балансе «Европлана». В свою '
    'очередь другая наша компания — «Альфа-Лизинг» — сосредоточится на '
    'корпоративном лизинге.'
)
STRUCT_ADDITION = (
    'Позже стали известны детали объединения: региональные офисы '
    '«Альфамобиля» станут обособленными подразделениями в сети '
    '«Европлана», пересечение клиентских баз — всего около 10%, '
    'должность гендиректора «Альфамобиля» займёт Анатолий Аминов, а '
    'юридическое объединение компаний пока не планируется.'
)
NEW_STRUCT = OLD_STRUCT + ' ' + STRUCT_ADDITION

OLD_TARGET_FIN = (
    'Чистая прибыль ЛК «Европлан» по МСФО за 2024 год составила 14,9 '
    'млрд руб. Чистая прибыль без учёта единовременного эффекта от '
    'увеличения ставки налога на прибыль — 17,2 млрд руб. Чистая прибыль '
    'Европлана по МСФО за первое полугодие 2025 года упала на 78% до 19 '
    'млрд руб. по сравнению с годом ранее'
)
TARGET_FIN_ADDITION = (
    'За первое полугодие 2026 года, уже под контролем Альфа-банка, '
    '«Европлан» отчитался о чистой прибыли 4,3 млрд руб. (+129% по '
    'сравнению с первым полугодием 2025 года) при лизинговом портфеле '
    '139,5 млрд руб. (-17% с начала 2026 года).'
)
NEW_TARGET_FIN = OLD_TARGET_FIN + ' ' + TARGET_FIN_ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['law']['struct'] == OLD_STRUCT, \
        f"law.struct: неожиданное значение {deal['law']['struct']!r}"
    assert deal['eco']['target_fin'] == OLD_TARGET_FIN, \
        f"eco.target_fin: неожиданное значение {deal['eco']['target_fin']!r}"

    print(f"{CARD_ID} law.struct: += детали интеграции «Альфамобиля»")
    print(f"{CARD_ID} eco.target_fin: += финрезультаты за I полугодие 2026")
    deal['law']['struct'] = NEW_STRUCT
    deal['eco']['target_fin'] = NEW_TARGET_FIN

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
