# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
`g9be8d398» («VK покупает сеть школ английского языка Ufirst (бывшая
English First)», статус «Согласование получено») — поле `extra`
отстало от остальной карточки: оно всё ещё говорит «Сделка в статусе
переговоров... Подано ходатайство в ФАС», хотя `law.appr` этой же
карточки уже год как знает, что ФАС одобрила сделку. Также не была
заполнена структура покупателя (`law.struct`).

Проверено лично прямым WebFetch:
- Право.ру, https://pravo.ru/fas15/news/250742/, 28.12.2023: «Ведомство
  зарегистрировало ходатайство «Учи.Ру Плюс» 20 ноября» [2023], одобрено
  28 декабря 2023 года; комментарий экс-директора и совладелицы
  «Рашмор» Елены Мухаметзяновой — «Все произошло поступательно и
  логично, а для клиента абсолютно безболезненно».
- Коммерсантъ, https://www.kommersant.ru/doc/6396193: «ООО «Учи.Ру
  Плюс» принадлежит ООО «Учи.Ру», 73,68% которого у ООО «Компания ВК»,
  еще 26,31% — МКОО «ВК образовательные технологии»» — то есть прямой
  покупатель по документам ФАС не сам VK, а «Учи.Ру Плюс», хотя
  конечный контролирующий холдинг — VK на 100% (через две свои
  структуры).

НЕ ИЗМЕНЕНО: статус остаётся «Согласование получено» — саб-агент не
нашёл ни одного источника (2024-2026), подтверждающего фактическое
закрытие/передачу доли; менять на «Закрыта» было бы недоказанной
правкой. Расхождение источников по составу совладельцев продавца
(«Рашмор») уже найдено и сознательно оставлено предыдущим прогоном
(`batch_e_rev02.py`) — не трогаю повторно.

Запуск: python3 pipeline/fix_vk_ufirst_extra_and_structure.py
        python3 pipeline/fix_vk_ufirst_extra_and_structure.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g9be8d398'

OLD_EXTRA = (
    'Сделка в статусе переговоров. VK ведёт переговоры о покупке 100% '
    'доли в уставном капитале ООО «Рашмор», в структуру которого '
    'входит онлайн-школа Ufirst. Подано ходатайство в ФАС. Интеграция '
    'позволит развить техническую сторону компании и получить учебные '
    'наработки.'
)
NEW_EXTRA = (
    'ФАС одобрила ходатайство «Учи.Ру Плюс» (дочерней структуры VK) о '
    'приобретении 100% доли в уставном капитале ООО «Рашмор», в '
    'структуру которого входит онлайн-школа Ufirst — решение принято '
    '28 декабря 2023 года. Интеграция позволит развить техническую '
    'сторону компании и получить учебные наработки.'
)

OLD_LAW_STRUCT = '—'
NEW_LAW_STRUCT = (
    'Прямой покупатель по документам ФАС — ООО «Учи.Ру Плюс», '
    'принадлежащее ООО «Учи.Ру» (73,68% — у ООО «Компания ВК», ещё '
    '26,31% — у МКОО «ВК образовательные технологии»), то есть '
    'конечный контролирующий холдинг — VK.'
)

NEW_SRC = [
    ['Право.ру', 'https://pravo.ru/fas15/news/250742/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA
    assert deal['law']['struct'] == OLD_LAW_STRUCT

    existing_urls = {s[1] for s in deal['src']}
    add_src = [s for s in NEW_SRC if s[1] not in existing_urls]
    new_src = deal['src'] + add_src

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)
    if add_src:
        print('\n=== src: добавится ===')
        for s in add_src:
            print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['law']['struct'] = NEW_LAW_STRUCT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
