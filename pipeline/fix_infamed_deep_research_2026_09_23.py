# -*- coding: utf-8 -*-
"""Приток 23 сентября 2026, карточка gd8faa2c4 (Инфамед/«Мирамистин»):
доп. поиск источников (шаг 9а) нашёл юридическое основание спора
(нотариальный договор, «двойная продажа доли»), хронологию апелляций
вплоть до Верховного суда и — важно для честности карточки — встречную
версию стороны Хугаевой/Николаева (обвинение Хейфицев в мошенничестве
через адвоката Рубена Маркарьяна). Без второй версии карточка выглядела
бы так, будто решение суда 23 сентября окончательно закрывает вопрос,
хотя обе стороны подали кассационные жалобы в Верховный суд, которые ещё
не рассмотрены. Прямая правка (не review.py FIXES) — карточка построена
скриптом напрямую, дополнение расширяет уже записанные вручную поля.

Запуск: python3 pipeline/fix_infamed_deep_research_2026_09_23.py --write
"""
import argparse
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PENDING = os.path.join(ROOT, 'static', 'data', 'pending.json')

CARD_ID = 'gd8faa2c4'

NEW_SOURCES = [
    ['Vademecum', 'https://vademec.ru/news/2025/07/22/sud-zapretil-benefitsiaru-infameda-izmenyat-status-regudostovereniy-na-miramistin-i-okomistin/'],
    ['ПРАЙМ', 'https://1prime.ru/20260910/infamed-873202946.html'],
    ['ПРАЙМ', 'https://1prime.ru/20260915/eks-gendirektor-873314968.html'],
]

LAW_TERMS = (
    'В обоснование заявления о принятии обеспечительных мер Хейфиц сослалась на то, '
    'что ответчиками совершаются действия, «явно противоречащие закону и заключенному '
    'в нотариальном порядке договору» с истцом. В частности, она обращает внимание на '
    'двойную продажу доли в ООО «Инфамед».'
)

LAW_APPR_ADDITION = (
    ' Кассационная жалоба Николаева на решения нижестоящих судов (признавших законным '
    'декабрьский договор с Хейфиц) поступила в Верховный суд 11 сентября 2026 года, '
    'решений по ней пока не принято. Отдельно кассационную жалобу с просьбой отменить '
    'обеспечительные меры (запрет Николаеву распоряжаться долей 99,9% и правами на '
    'сами препараты) 4 сентября 2026 года подал сам «Инфамед» — тоже пока не '
    'рассмотрена.'
)

DISPUTE_VERSION = (
    'Версия стороны Хугаевой/Николаева (по словам представлявшего их интересы адвоката '
    'Рубена Маркарьяна): чета Хейфиц убедила Хугаеву заключить фиктивный договор о '
    'продаже её 50%-ной доли за 7,525 млн руб. — менее 1% от реальной стоимости '
    'половины бизнеса, оценённой более чем в 1 млрд руб.; параллельно от имени Павла '
    'Хейфица был заключён предварительный договор о продаже уже 100% доли за 2 млрд '
    'руб. (цена, близкая к рыночной) — как утверждается, для переговоров с реальным '
    'инвестором. В правоохранительные органы с обеих сторон подавались заявления о '
    'мошенничестве. Дело рассматривается в закрытом режиме, судебные акты не '
    'публикуются — независимо подтвердить ни одну из версий сторонним источником не '
    'удалось.'
)


def main(write):
    data = json.load(open(PENDING, encoding='utf-8'))
    card = next(c for c in data['cards'] if c['id'] == CARD_ID)
    assert card['law']['terms'] == '—'
    assert card['extra'].startswith('В ЕГРЮЛ собственником')
    existing_urls = {s[1] for s in card['src']}
    for src in NEW_SOURCES:
        assert src[1] not in existing_urls
        card['src'].append(src)
    card['law']['terms'] = LAW_TERMS
    card['law']['appr'] = (card['law'].get('appr') or '—')
    if card['law']['appr'] == '—':
        card['law']['appr'] = LAW_APPR_ADDITION.strip()
    else:
        card['law']['appr'] += LAW_APPR_ADDITION
    card['extra'] = card['extra'] + ' ' + DISPUTE_VERSION
    if write:
        json.dump(data, open(PENDING, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
        print('Записано: юридическое основание, хронология апелляций и встречная версия добавлены.')
    else:
        print('Сухой прогон (--write, чтобы записать).')


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('--write', action='store_true')
    main(p.parse_args().write)
