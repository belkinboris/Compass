# -*- coding: utf-8 -*-
"""Месячная очередь, карточка g4165ba00 («Мать и дитя» рассматривает
приобретение «Инвитро»): дельта-поиск нашёл прямое публичное
опровержение стороной-покупателем спустя полтора месяца после статьи
Ведомостей, по которой карточка собиралась, — статус с тех пор ни разу
не пересматривался. Не через `review.py`: добавляемый текст собран из
ДВУХ источников (smart-lab.ru/ТАСС и rb.ru), а дословная проверка
`review.py` требует непрерывный кусок ОДНОГО источника.

Статус карточки НЕ меняется механически на «Не состоялась»: цитата
Курцера — отрицание самого ФАКТА переговоров («не было никаких
переговоров»), а не одно из слов из закрытого списка `STATUS_WORDS`
(«не состоял», «отказал», «прекращен», «отменен», «не будет», «отозв»).
Родня уже записанных случаев БКС/«Форштадт» и Газпромбанк/«Медскан» —
запись в «Известные проблемы» CLAUDE.md, решение по статусу и составу
сторон оставлено человеку.

Источники — читал напрямую (fetch_article_texts.py, закэшированы):
https://smart-lab.ru/blog/news/1198480.php (перепечатка ТАСС, 29.08.2025)
https://rb.ru/news/invitro-analiz-2025/ (15.07.2025)

Запуск: python3 pipeline/fix_mat_i_ditya_invitro_denial_context.py [--write]
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g4165ba00'

OLD_CONTEXT = (
    'В 2023 году основатель и владелец «Инвитро» Александр Островский '
    'продал сеть предпринимателю Роману Мирончику.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' «Инвитро» принадлежит Роману Мирончику, партнёром называют Алексея '
    'Крапивина, чьи интересы связывают с Аркадием Ротенбергом. Если '
    'сделка состоится, это будет второе крупное объединение после '
    'сделки «Медскан» и KDL. 29 августа 2025 года гендиректор «Мать и '
    'дитя» Марк Курцер публично опроверг сами переговоры: «Начну с '
    'публикации. Для нас это было открытием. Мы не планировали и у нас '
    'не было никаких переговоров с собственниками «Инвитро»», — сказав, '
    'что компания сотрудничает с «Инвитро» только в части диагностики, '
    '«но не более того». С этой даты тема в прессе не всплывала.'
)


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f'{CARD_ID} eco.context: += публичное опровержение переговоров '
          f'(Курцер, 29.08.2025) и структура собственности «Инвитро»')

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('ЗАПИСАНО')
    else:
        print('Сухой прогон. Запись — с --write.')


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
