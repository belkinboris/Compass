WORD = re.compile(r"[\w%,.№-]+", re.U)
DIRT = re.compile(r'\d+[,.]?\d*\s*%|\bдолей\b|\bакций\b|оставшиеся|^\s*доля\b', re.I)


def norm(s):
    return re.sub(r'\s+', ' ', str(s or '')).strip()


def bare(w):
    return w.strip('«»"(),.;:%').lower()


def same_word(a, b):
    a, b = bare(a), bare(b)
    if not a or not b:
        return False
    if a == b:
        return True
    n = min(len(a), len(b))
    i = 0
    while i < n and a[i] == b[i]:
        i += 1
    return i >= max(3, int(0.6 * n))


def fits(result, source):
    """Результат выводится из старого названия: подстрокой или с точностью до окончаний."""
    if norm(result).lower() in norm(source).lower():
        return True
    rw, sw = WORD.findall(result), WORD.findall(source)
    return any(all(same_word(a, b) for a, b in zip(rw, sw[i:i + len(rw)]))
               for i in range(len(sw) - len(rw) + 1))


def main(write):
    data = json.load(open(PATH, encoding='utf-8'))
    comps = data['companies']
    assert not (set(TABLE) & set(SKIP)), 'профиль одновременно в таблице и в отказах'

    plan, done = [], []
    for cid, new in TABLE.items():
        c = comps.get(cid)
        assert c is not None, 'нет профиля %s' % cid
        old = norm(c.get('name'))
        if old == new:
            done.append(cid)
            continue
        assert DIRT.search(old), '%s: в названии нет доли — правка не нужна (%r)' % (cid, old)
        assert fits(new, old), '%s: новое название не выводится из старого\n  %r -> %r' % (cid, old, new)
        assert not DIRT.search(new), '%s: в новом названии осталась доля' % cid
        plan.append((cid, old, new, c))

    assert len(plan) + len(done) == len(TABLE), 'часть профилей изменилась вне скрипта'
    if not plan:
        print('Уже применено: все %d названий вычищены.' % len(TABLE))
        return

    print('Профилей к правке: %d (не чинятся, оставлены как есть: %d)' % (len(plan), len(SKIP)))
    for cid, old, new, _ in plan:
        print('  %s  %s\n     -> %s' % (cid, old[:70], new))
    if not write:
        print('\nСухой прогон. Запись — с ключом --write.')
        return
    for _, _, new, c in plan:
        c['name'] = new
    with open(PATH, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    left = sum(1 for c in comps.values() if DIRT.search(norm(c.get('name'))))
    print('\nЗаписано: %d названий. Осталось с долей в названии: %d (все — лоты из нескольких юрлиц).' % (len(plan), left))


if __name__ == '__main__':
    main('--write' in sys.argv)
