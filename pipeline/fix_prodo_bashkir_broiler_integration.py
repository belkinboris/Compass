import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gmru-prodo-star-nafta-broiler'

OLD_ECO_CONTEXT = (
    '«Башкирский бройлер» — репродуктор второго ряда: он закупает '
    'молодых кур от родительского стада и производит финальный гибрид '
    'мясной породы для птицефабрик. Как объясняет представитель АО '
    '«Птицефабрика Челябинская» Сергей Гладыщук, рентабельность в '
    'таком бизнесе часто невысокая.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' К концу августа 2026 года «Продо» начала '
    'интеграцию актива: около 300 сотрудников проходят обучение и '
    'адаптацию к стандартам агрохолдинга под кураторством экспертов '
    '«Уфимского мясоконсервного комбината», планируется открыть около '
    '50 новых вакансий, выстроена логистика поставок инкубационного '
    'яйца на птицефабрики группы в Омской, Калужской и Тюменской '
    'областях. Аналитик ИК «Финам» Ярослав Кабаков оценил сделку в '
    '4,5–5 млрд ₽ (с учётом долга около 3 млрд ₽), что согласуется с '
    'независимой оценкой собственного капитала актива в 1,4–2 млрд ₽.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
