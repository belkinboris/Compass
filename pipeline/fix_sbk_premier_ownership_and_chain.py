import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gef939ff4'

OLD_ECO_CONTEXT = (
    'В ноябре 2021 года Сбербанк на торгах продал кипрской Valleyton '
    'Investments акции обоих предприятий, а также права требования по '
    'выданным им кредитам. Сумма сделки составила $230 млн, при этом в '
    'документации к торгам сказано, что задолженность по синдицированному '
    'кредиту составляла $446,8 млн'
)
NEW_ECO_CONTEXT = (
    'В ноябре 2021 года Сбербанк на торгах продал кипрской Valleyton '
    'Investments акции обоих предприятий, а также права требования по '
    'выданным им кредитам. Сумма сделки составила $230 млн, при этом в '
    'документации к торгам сказано, что задолженность по синдицированному '
    'кредиту составляла $446,8 млн. К моменту сделки с «СБК Премьер» '
    'акции числились уже за другой кипрской структурой, Fabcell Limited '
    '(бенефициаром которой в марте 2022 года был назван Искендер '
    'Халилов, что оспаривает его представитель) — прямая связь между '
    'Valleyton и Fabcell источниками не устанавливается. Сама «СБК '
    'Премьер» ранее была структурой Сбербанка; нынешние владельцы не '
    'раскрываются.'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/5783847'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    new_src = deal['src'] + NEW_SRC

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
