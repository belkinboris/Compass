# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
`g6007df5d` («Брусника» выкупает половину проекта Level Group на
Перовском шоссе в Москве», статус «Обсуждается», 2023-07-03) — статус
не менялся почти три года при том, что участок реально застраивается.

Проверено (по докладу саб-агента, дословные цитаты и прямые находки):
- novostroy.ru/buildings/izdanie/ и msk.novostroy.su/buildings/izdanie/:
  на участке по адресу Перовское шоссе, 21 (Нижегородский район, ЮВАО
  Москвы — тот самый адрес завода «Станкоагрегат», который Level Group
  продавала «Бруснике») с апреля 2024 года строится ЖК «Издание»
  застройщиком «Брусника. Москва»: пять корпусов 15–29 этажей, продажи
  открыты, на момент проверки продано около 72% лотов, стадия —
  котлован/монолит, сдача — III квартал 2027 года.
- Согласованная площадь застройки уточнилась до 2,3 га (61 816 кв. м,
  из них 52 705 кв. м — жильё) — более точная цифра по сравнению с
  предварительной оценкой анонса 2023 года («около 4 га», «около 198
  тыс. кв. м»), типичная для перехода от предварительной договорённости
  к финальным проектным параметрам после закрытия.
- Ни один источник не сообщил о срыве сделки — только последовательное
  движение к её результату (тендер на подготовку площадки, старт
  продаж, ход строительства).

Тот же класс решения, что уже применялся в базе к другим карточкам с
сильными косвенными подтверждениями без единой дословной цитаты со
словом «закрыта» (см. CLAUDE.md, класс «признак дефекта — повод
прочитать», и прецедент `fix_fm_logistic_central_properties_closed.py`).

НЕ ВНЕСЕНО: (1) точная дата закрытия и финальная (не оценочная) сумма
сделки — ни один источник их не называет, оценка Nikoliers (3–3,5 млрд
₽) в `sum` карточки остаётся единственной цифрой; (2) юридический/
финансовый консультант — ноль по всем проверенным источникам, включая
сам Коммерсантъ; (3) условия сделки (эскроу, отлагательные условия) —
источник карточки прямо говорит, что стороны не комментируют параметры
до закрытия, и позже их нигде не раскрыли.

Запуск: python3 pipeline/fix_brusnika_levelgroup_closed.py
        python3 pipeline/fix_brusnika_levelgroup_closed.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g6007df5d'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Закрыта'

OLD_ECO_CONTEXT = (
    'По данным информсистемы «Наш.Дом.РФ», Level Group сейчас строит '
    '510 тыс. кв. м — восьмое место в топ-10 девелоперов Москвы по '
    'объёму строительства.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' С апреля 2024 года «Брусника» строит на этом '
    'участке жилой комплекс «Издание» — пять корпусов высотой 15–29 '
    'этажей, согласованная площадь застройки уточнилась до 2,3 га '
    '(61 816 кв. м, из них 52 705 кв. м жильё). На момент проверки '
    'продано около 72% лотов, сдача запланирована на III квартал 2027 '
    'года.'
)

OLD_SRC = [['Коммерсантъ', 'https://www.kommersant.ru/doc/6082030']]
NEW_SRC = OLD_SRC + [
    ['Novostroy.ru', 'https://www.novostroy.ru/buildings/izdanie/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS
    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== status: станет ===')
    print(NEW_STATUS)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['status'] = NEW_STATUS
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
