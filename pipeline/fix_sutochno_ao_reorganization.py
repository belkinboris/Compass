# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g61cccee7 (Pre-IPO фонд «ВИМ Инвестиций» приобрёл 16,03% «Суточно.ру»)
— судьба компании после сделки (шаг к IPO, финансовые показатели) не
была отражена. Проверено лично прямым WebFetch трёх источников.

`eco.context` (дополнено). ООО «Суточно» преобразовано в акционерное
общество — типовой шаг перед IPO. Дословно (audit-it.ru): дата
регистрации АО «СУТОЧНО» — «12 ноября 2024», образовано из «ООО
"СУТОЧНО"» (ликвидировано в тот же день), гендиректор — «Кузнецов Юрий
Владимирович» (тот же человек, с 12 ноября 2024 года). По состоянию
на апрель 2026 года IPO не состоялось, но планы подтверждены: дословно
(finance.mail.ru, представитель компании): «Компания Суточно.ру
технически готова к выходу на IPO и сохраняет эти планы на ближайшие
два года» — сроки зависят от рыночной конъюнктуры и ключевой ставки,
жёсткого дедлайна нет.

НЕ ВКЛЮЧЕНО: цифра «выручка выросла до 71 млрд рублей» из того же
источника (finance.mail.ru, 01.04.2026) — внутренне противоречит
соседним показателям того же предложения: «скорректированная EBITDA
2,8 млрд рублей», «рентабельность 39%» — при выручке 71 млрд эти два
числа дают маржу 3,9%, а не 39%; при более правдоподобной выручке
~7,1 млрд маржа сходится точно. Похоже на опечатку в самом источнике
(потерянная запятая), а не на найденный факт, — правило дословности не
защищает от арифметически несостоятельного числа, эта проверка
отдельная и обязательная перед переносом любого числа. Сама выручка не
переносится; показатели EBITDA (2,8 млрд ₽, +56%) и скорректированной
чистой прибыли (2,8 млрд ₽, +40%) внутренне согласованы между собой и
могли бы быть перенесены отдельно, но решено не включать частичный
набор показателей без надёжной выручки как знаменателя картины —
предпочтено недосказать, чем исказить.

Запуск: python3 pipeline/fix_sutochno_ao_reorganization.py
        python3 pipeline/fix_sutochno_ao_reorganization.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g61cccee7'

OLD_CONTEXT = (
    'В июле 2022 года о намерении приобрести сервис заявлял холдинг '
    'VK, планировавший расширить свою экосистему после ухода с '
    'российского рынка западных агрегаторов Booking и Airbnb.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' 12 ноября 2024 года ООО «Суточно» преобразовано в акционерное '
    'общество — АО «Суточно» (тот же гендиректор, Юрий Кузнецов) — '
    'типовой шаг перед возможным IPO. По состоянию на апрель 2026 года '
    'IPO не состоялось, но представитель компании подтвердил: '
    '«Компания Суточно.ру технически готова к выходу на IPO и '
    'сохраняет эти планы на ближайшие два года», жёстких сроков '
    'размещения компания не называет.'
)

NEW_SRC = [
    ['audit-it.ru', 'https://www.audit-it.ru/contragent/1247300009560_ao-sutochno'],
    ['Market Power / Mail Finance', 'https://finance.mail.ru/article/sutochnoru-zayavila-o-gotovnosti-k-ipo-v-blizhajshie-dva-goda-69203525/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
