import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gdffd613c'

OLD_ECO_CONTEXT = (
    'По итогам 2021 года доля «СГ-Транса» в перевозках СУГ по сети ОАО РЖД '
    'составляла 64%, говорится в проспекте выпуска облигаций. Парк '
    'насчитывал 31 тыс. единиц, в том числе 24,6 тыс. цистерн для СУГ (из '
    'них 4,2 тыс. — в паритетном СП с СИБУРом НХТК), 6,7 тыс. '
    'танк-контейнеров и 4,5 тыс. фитинговых платформ.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' Купленный в этой сделке пакет позже изъят '
    'государством: 23 апреля 2025 года суд по иску Генпрокуратуры '
    'обратил в доход РФ 100% «Вектор Рейл» вместе с «СГ-Транс» и '
    '«Химинвесттранс» — с Салмана Бабаева (бывшего вице-президента РЖД), '
    'его сыновей Тимура и Руслана Бабаевых и Алексея Тайчера взыскано '
    'солидарно 30,1 млрд ₽, а всего по делу изъято 12 компаний на около '
    '242 млрд ₽; 27 августа 2025 года апелляция решение оставила в силе. '
    'С марта 2026 года ПСБ выставил 100% «Вектор Рейл» на электронный '
    'аукцион со стартовой ценой 20,3 млрд ₽.'
)

OLD_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6147405'],
]
NEW_SRC = OLD_SRC + [
    ['Интерфакс', 'https://www.interfax.ru/russia/1022453'],
    ['Право.ru', 'https://pravo.ru/news/260153/'],
    ['Эксперт', 'https://expert.ru/transport/vagony-vyezzhayut-v-rynok/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
