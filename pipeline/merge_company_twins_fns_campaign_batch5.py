#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Семь профилей-близнецов, найденные волной 2 самопроверки ИНН вебом
(28 августа 2026, `pipeline/fns_registry.py`) — тот же класс, что уже
чинили `merge_company_twins_fns_campaign*.py`.

Все семь — одно и то же юридическое лицо в разное время (переименование,
перепродажа, ребрендинг), не два профиля одной сделки:

  * «Русский водород» / «Росхим» — ребрендинг того же производителя.
  * Urent / «ЮрентБайк.ру» (МТС Юрент) — сервис кикшеринга сменил
    юрлицо/бренд после сделки с Газпромбанк Лизингом.
  * логопарк «Трилоджи парк Томилино» / ООО «Томилино парк» — тот же
    объект под разными названиями на разных карточках.
  * завод Volkswagen в Калуге / «Фольксваген Груп Рус» — завод и
    материнская операционная компания резолвятся в тот же ИНН.
  * Lanit Ventures / «Группа ИТ-компаний «Ланит»» — инвестподразделение
    группы записано отдельным профилем.
  * «Топ-менеджмент… Faurecia и группа «Автокомпонент»» / «Формат Инвест» —
    более ранний (2023, предварительные переговоры, кандидат в покупатели
    ещё не определён окончательно) и более поздний (2024, уже названное
    юрлицо) этапы одной истории; проверено читением обеих карточек
    (`g8de46135`, `g282be68a`) — предмет карточек РАЗНЫЙ (весь российский
    периметр Faurecia против двух конкретных площадок в Тольятти), поэтому
    сами КАРТОЧКИ СДЕЛОК не сливаются, сливается только профиль покупателя.
  * «Кораблик» / ООО «Кораблик-Р» — операционное юрлицо сети детских
    товаров под двумя профилями. ВАЖНО: до этого слияния отдельным
    скриптом (`fix_zuev_korablik_detsky_mir_target.py`) снята НЕВЕРНАЯ
    ссылка `target` карточки `g22000f22` на профиль «Кораблик» — там
    предметом сделки был пакет акций «Детского мира», а «Кораблик» в
    заголовке — лишь пояснение, кто такой покупатель Алексей Зуев. Без
    этой предварительной правки слияние перенесло бы чужую роль на
    профиль «Кораблик-Р».

ПРОВЕРЕНО ПЕРЕД СЛИЯНИЕМ: ни одна пара не описывает одну и ту же сделку
дважды, роли не пересекаются.

НЕ ВКЛЮЧЕНА восьмая находка той же волны — «ООО «АЛД Автомотив»» /
«ALD Automotive Russia»: обе карточки резолвятся в один ИНН 7725514969, но
это НЕ переименование во времени — они стоят target/seller_id ОДНОЙ И ТОЙ
ЖЕ сделки (`g2d653619`, «ALD Automotive продала лизинговую компанию в
России структурам Игоря Кима»): «АЛД Автомотив» — российское юрлицо-цель,
«ALD Automotive Russia» — по всей видимости placeholder для иностранного
продавца (Société Générale), которому по ошибке присвоили ИНН российской
цели. Тот же класс, что уже документирован для Guess/ГЕСС СИАЙЭС и
San Gally Park/EKE — механическое слияние запрещено ассертом ниже, вопрос
оставлен человеку.

КАК ВЫБИРАЛСЯ ОСТАЮЩИЙСЯ ПРОФИЛЬ — тот же порядок: больше ролей — меньше
переписывать; при равенстве — тот, что уже несёт `confirmed` в реестре ФНС.

ЗАПИСИ РЕЕСТРА ФНС ПОСЛЕ СЛИЯНИЯ — снимаются ОТДЕЛЬНОЙ правкой того же
`pipeline/fns_registry.py` (не этим скриптом), как и в прошлые разы.

Запуск:
    python3 pipeline/fix_zuev_korablik_detsky_mir_target.py --write   # СНАЧАЛА
    python3 pipeline/merge_company_twins_fns_campaign_batch5.py            # сухой прогон
    python3 pipeline/merge_company_twins_fns_campaign_batch5.py --write    # записать
"""
import json
import sys

PATH = 'static/data/deals_promoted.json'
REFS = ('buyer', 'seller_id', 'target', 'asset_id')

# (остаётся, удаляется, ожидаемые имена, почему так)
MERGE = [
    ('g936f9597', 'g4e9a741e', ('Росхим', 'Русский водород'),
     'у «Росхим» 6 ролей против 1, и он уже несёт подтверждённый ИНН'),
    ('g30d7fdce', 'g81e02f80', ('ООО «ЮрентБайк.ру» (МТС Юрент)', 'Urent'),
     'у «ЮрентБайк.ру» 2 роли против 1, и он уже несёт подтверждённый ИНН'),
    ('g39d6172a', 'g1fe52112', ('ООО «Томилино парк»', 'логопарк «Трилоджи парк Томилино»'),
     'ролей поровну (1/1); остаётся профиль с уже подтверждённым в реестре ФНС ИНН'),
    ('g26aba682', 'g382b3875', ('Фольксваген Груп Рус', 'завод Volkswagen в Калуге'),
     'ролей поровну (1/1); остаётся профиль с уже подтверждённым в реестре ФНС ИНН'),
    ('gb5bc9e57', 'g18b06ad5', ('Группа ИТ-компаний «Ланит» (через ООО «Л Венчурс»)', 'Lanit Ventures'),
     'у «Ланит» 2 роли против 1, и он уже несёт подтверждённый ИНН'),
    ('g14d905f4', 'ga605d471',
     ('Формат Инвест', 'Топ-менеджмент российского подразделения Faurecia и группа «Автокомпонент»'),
     'у «Формат Инвест» 2 роли против 1, и он уже несёт подтверждённый ИНН (более поздний, '
     'уже названный этап той же истории)'),
    ('geaeb1582', 'gd2431ed3', ('ООО «Кораблик-Р»', 'Кораблик'),
     'после снятия неверной ссылки g22000f22 (см. fix_zuev_korablik_detsky_mir_target.py) '
     'у «Кораблик» ролей не осталось; «Кораблик-Р» несёт единственную настоящую роль'),
]


def main(write):
    data = json.load(open(PATH, encoding='utf-8'))
    comps, deals, keys = data['companies'], data['deals'], data['match_keys']

    for keep, drop, names, _why in MERGE:
        assert keep in comps and drop in comps, 'профиля нет: %s / %s' % (keep, drop)
        assert (comps[keep]['name'], comps[drop]['name']) == names, \
            'имена изменились: %r против %r' % ((comps[keep]['name'], comps[drop]['name']), names)
        both = [d['id'] for d in deals
                if {d.get(f) for f in REFS} >= {keep, drop}]
        assert not both, 'сделка ссылается на оба профиля сразу: %s' % both

    moved = 0
    plan = []
    for keep, drop, names, why in MERGE:
        n = sum(1 for d in deals for f in REFS if d.get(f) == drop)
        aliases = [a for a in (keys.get(drop) or []) if a not in (keys.get(keep) or [])]
        plan.append((keep, drop, names, why, n, aliases))
        moved += n

    print('СЛИЯНИЕ ПРОФИЛЕЙ-БЛИЗНЕЦОВ (волна 2 самопроверки ИНН): %d пар, переезжает %d ролей\n'
          % (len(MERGE), moved))
    for keep, drop, names, why, n, aliases in plan:
        print('  «%s» <- «%s»' % (names[0], names[1]))
        print('      %s -> %s | ролей переезжает: %d | псевдонимов добавится: %d %s'
              % (drop, keep, n, len(aliases), aliases or ''))
        print('      почему: %s' % why)

    if not write:
        print('\nСухой прогон. Запись — с ключом --write.')
        return

    было = len(comps)
    for keep, drop, _names, _why, _n, aliases in plan:
        for d in deals:
            for f in REFS:
                if d.get(f) == drop:
                    d[f] = keep
        if aliases:
            keys[keep] = (keys.get(keep) or []) + aliases
        keys.pop(drop, None)
        comps.pop(drop)
        data.setdefault('merged_companies', {})[drop] = keep

    assert len(comps) == было - len(MERGE), 'удалилось не столько профилей, сколько пар'
    for d in deals:
        refs = [d.get(f) for f in REFS if d.get(f)]
        assert len(refs) == len(set(refs)), 'после слияния компания заняла две роли: %s' % d['id']
    with open(PATH, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('\nЗаписано. Профилей: %d (было %d). Переставлено ролей: %d.'
          % (len(comps), было, moved))


if __name__ == '__main__':
    main('--write' in sys.argv)
