import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g1664083c'
BUYER_ID = 'g05adfbe5'

OLD_TITLE = 'ВТБ продал торговый центр «Весна» на Новом Арбате ЗПИФ «СВ»'
NEW_TITLE = 'ВТБ продал торговый центр «Весна» на Новом Арбате ЗПИФ «СР»'

OLD_EXTRA = (
    'Consul Group сообщила о закрытии сделки по продаже ТЦ «Весна» на '
    'Новом Арбате банком ВТБ. Покупателем выступил ЗПИФ «СВ» от '
    'управляющей компании «КСП Капитал». Конечный бенефициар покупателя '
    'не установлен.'
)
NEW_EXTRA = (
    'Consul Group сообщила о закрытии сделки по продаже ТЦ «Весна» на '
    'Новом Арбате банком ВТБ. Покупателем выступил ЗПИФ «СР» от '
    'управляющей компании «КСП Капитал». По данным Ведомостей, фонд '
    'связан с совладельцем сети ЦОД Key Point Group; второй источник это '
    'не подтверждает.'
)

OLD_DATE = '2024'
NEW_DATE = '2026'

OLD_SRC = [['@dealsma (Telegram)', 'https://t.me/dealsma/7043']]
NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8624356'],
    ['Ведомости', 'https://www.vedomosti.ru/realty/articles/2026/04/28/1193494-vtb-nashel-pokupatelya-na-torgovii-tsentr-vesna'],
]

OLD_CONTEXT = (
    'Сам актив ранее принадлежал бывшему президенту Банка Москвы Андрею '
    'Бородину. Кто стоит за покупателем «Весны», точно неизвестно. '
    'Основным претендентом на ТЦ консультанты называли арендатора центра '
    '— компанию Bosco di Ciliegi Михаила Куснировича. При этом «КСП '
    'Капитал» управляет активами многих уважаемых людей, например, главы '
    'ВЭБа Игоря Шувалова.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' По данным Ведомостей (28 апреля 2026), «его новым собственником '
    'стал фонд, связанный с совладельцем сети центров обработки данных '
    'Key Point Group» — второй независимый источник (Коммерсантъ) этого '
    'не подтверждает.'
)

OLD_BUYER_NAME = 'ЗПИФ «СВ»'
NEW_BUYER_NAME = 'ЗПИФ «СР»'
OLD_BUYER_DESC = (
    'Фонд под управлением «КСП Капитал»; в 2024 году купил у ВТБ '
    'торговый центр «Весна» на Новом Арбате, конечный бенефициар не '
    'установлен.'
)
NEW_BUYER_DESC = (
    'Фонд под управлением «КСП Капитал»; в 2026 году купил у ВТБ '
    'торговый центр «Весна» на Новом Арбате. По данным одного источника '
    '(Ведомости), связан с совладельцем сети ЦОД Key Point Group — '
    'второй источник это не подтверждает.'
)


OLD_MATCH_KEY = 'зпиф св'
NEW_MATCH_KEY = 'зпиф ср'


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)
    buyer = data['companies'][BUYER_ID]

    assert deal['title'] == OLD_TITLE
    assert deal['extra'] == OLD_EXTRA
    assert deal['date'] == OLD_DATE
    assert deal['src'] == OLD_SRC
    assert deal['eco']['context'] == OLD_CONTEXT
    assert buyer['name'] == OLD_BUYER_NAME
    assert buyer['desc'] == OLD_BUYER_DESC
    assert data['match_keys'].get(BUYER_ID) == [OLD_MATCH_KEY]

    print('=== title: станет ===')
    print(NEW_TITLE)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== date: станет ===')
    print(NEW_DATE)
    print('\n=== src: станет ===')
    for s in NEW_SRC:
        print(s)
    print('\n=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== companies[g05adfbe5].name: станет ===')
    print(NEW_BUYER_NAME)
    print('\n=== companies[g05adfbe5].desc: станет ===')
    print(NEW_BUYER_DESC)
    print('\n=== match_keys[g05adfbe5]: станет ===')
    print([NEW_MATCH_KEY])

    if write:
        deal['title'] = NEW_TITLE
        deal['extra'] = NEW_EXTRA
        deal['date'] = NEW_DATE
        deal['src'] = NEW_SRC
        deal['eco']['context'] = NEW_CONTEXT
        buyer['name'] = NEW_BUYER_NAME
        buyer['desc'] = NEW_BUYER_DESC
        data['match_keys'][BUYER_ID] = [NEW_MATCH_KEY]
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
