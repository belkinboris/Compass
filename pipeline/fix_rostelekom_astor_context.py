"""Месячная очередь (REVISION_BRIEF), карточка gadcc1f58 (Ростелеком/
АСТОР): дельта-поиск (официальный пресс-релиз Ростелекома) дал масштаб
и независимость продукта АСТОР от иностранного ПО, а также структурную
принадлежность сделки кластеру «X.Технологии». Не через review.py:
старое значение eco.context — короткая фраза из другого источника
(Интерфакс), не образует непрерывный кусок с этой цитатой.

Источник — читал напрямую (fetch_article_texts.py, закэширован):
Ростелеком (company.rt.ru/press/news/d474717/), уже добавлен в src.
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gadcc1f58'

OLD_CONTEXT = (
    'С 2000 г. команда «Астор» реализовала более 750 проектов, в том '
    'числе для ретейлеров России и СНГ'
)
ADDITION = (
    'АСТОР — российский разработчик ERP и других комплексных систем с '
    'применением ИИ для автоматизации управления ретейл-бизнесом; в '
    'ТОП-100 российских торговых сетей входят 17 ретейлеров, '
    'использующих решения АСТОР. АСТОР использует свободно '
    'распространяемые ОС и СУБД, что обеспечивает независимость '
    'торговых предприятий от внешних факторов воздействия, таких как '
    'санкционная политика других государств и изменение политики '
    'лицензирования зарубежного программного обеспечения. Сделка '
    'проведена в рамках «X.Технологии» — кластера развития цифрового '
    'бизнеса «Ростелекома», основная задача которого — поиск новых '
    'точек роста за счёт инвестиций, M&A и партнёрств.'
)
NEW_CONTEXT = OLD_CONTEXT + '. ' + ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} eco.context: += масштаб продукта, независимость от "
          f"иностранного ПО, структура кластера X.Технологии")
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
