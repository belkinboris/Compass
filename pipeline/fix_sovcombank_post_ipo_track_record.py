# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка g4e3b91d7 (IPO
Совкомбанка): дельта-поиск дополняет только что заполненный eco.fin
показателями активов/капитала (та же статья РИА Новости, другой абзац —
не подряд с уже внесённой цитатой, поэтому не через review.py) и
дописывает в eco.context дивидендную историю банка как публичной
компании — двух выплат до этого дня в карточке не было вовсе.

Источники: РИА Новости (итоги 2024 года по МСФО), Ведомости (первая
выплата, май 2025) и Коммерсантъ (дивиденды за 2025 год, 2 июля 2026,
там же — итоговая прибыль банка за 2025 год, 53 млрд руб., что снимает
расхождение с другими, менее надёжными источниками, называвшими 35
млрд). Все три читал напрямую.
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g4e3b91d7'

OLD_FIN = (
    'Выручка Совкомбанка в 2024 году выросла в два раза и составила 722 '
    'миллиарда рублей по сравнению с 395 миллиардами рублей в 2023 году, '
    'чистая прибыль составила 77 миллиардов рублей, свидетельствуют '
    'объявленные банком финансовые результаты по МСФО за прошлый год.'
)
FIN_ADDITION = (
    'Активы банка увеличились на 27% год к году и составили 4 триллиона '
    'рублей на 31 декабря 2024 года. Капитал вырос на 31% год к году, '
    'достигнув 390 миллиардов рублей. Рентабельность капитала (ROE) '
    'составила 26%.'
)
NEW_FIN = OLD_FIN + ' ' + FIN_ADDITION

OLD_CONTEXT = (
    'Доля физических лиц в размещении составила порядка 65%, '
    'институциональных инвесторов – около 35 % от всего объема '
    'размещения.'
)
CONTEXT_ADDITION = (
    'Как публичная компания банк дважды выплачивал дивиденды: 0,35 руб. '
    'на акцию по итогам 2024 года (первый этап, май 2025 года — 10% '
    'чистой прибыли по МСФО за 2024 год) и 0,35 руб. на акцию по итогам '
    '2025 года (7,86 млрд руб., или 14,72% от чистой прибыли по МСФО за '
    '2025 год, которая составила 53 млрд руб.).'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + CONTEXT_ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['fin'] == OLD_FIN, \
        f"eco.fin: неожиданное значение {deal['eco']['fin']!r}"
    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} eco.fin: += активы/капитал/ROE за 2024 год")
    print(f"{CARD_ID} eco.context: += дивидендная история банка как "
          "публичной компании")
    deal['eco']['fin'] = NEW_FIN
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
