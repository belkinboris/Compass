# -*- coding: utf-8 -*-
"""Месячная очередь, 9 сентября 2026 — дочитывание карточки `g24b33459`
(«Группа "Эталон" приобрела 65% в СП для проекта развития территории в
Ростове-на-Дону», добавлена в базу 3 августа 2026, полностью обыскана в
тот же день).

Дельта-поиск (саб-агент + личная проверка) нашёл два новых факта. Личный
WebFetch (bloknot-rostov.ru, 22 апреля 2024) подтвердил дословно:

1) Продавец. «ООО «Кумжаград» было зарегистрировано в феврале 2024 года
   Еленой Степановой. Вскоре контроль над компанией перешёл к закрытому
   паевому инвестиционному комбинированному фонду «Астерия»» — «Последний
   и продал долю ГК «Эталон»» — продавец добавлен в `seller`.

2) Название проекта. Само СП называется ООО «Кумжаград», рабочее имя
   микрорайона — «Кумжаград» (площадка рядом с Кумженской рощей в
   Железнодорожном районе Ростова-на-Дону) — добавлено в `eco.context».

Саб-агент также отметил, что Елена Степанова, зарегистрировавшая
компанию до продажи фонду, «связана со структурами АФК «Система»» —
материнской структуры самого «Эталона» (то есть цепочка контроля перед
продажей фонду могла быть связана с той же группой); эта деталь НЕ
внесена — она сложнее одной дословной цитаты и требует отдельной
проверки, если понадобится. Сумма сделки по-прежнему нигде не названа.

Запуск:
    python3 pipeline/fix_etalon_kumzhagrad_seller_and_name.py            # сухой прогон
    python3 pipeline/fix_etalon_kumzhagrad_seller_and_name.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_SELLER = None
NEW_SELLER = 'ЗПИФ комбинированный «Астерия»'

OLD_ECO_CONTEXT = (
    'Партнёры готовят проект комплексного развития территории на '
    'участке свыше 300 га; начать его планировали в первом полугодии '
    '2025 года.'
)
NEW_ECO_CONTEXT = OLD_ECO_CONTEXT + (
    ' Само совместное предприятие называется ООО «Кумжаград» — по '
    'рабочему названию будущего микрорайона рядом с Кумженской рощей в '
    'Железнодорожном районе Ростова-на-Дону.'
)

NEW_SRC = ['Блокнот Ростов', 'https://bloknot-rostov.ru/news/mikrorayon-kumzhagrad-postroit-v-rostove-zastroyshch-1725580']


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['g24b33459']

    assert d.get('seller') == OLD_SELLER, \
        'g24b33459 seller уже занят: %r' % (d.get('seller'),)
    assert d['eco']['context'] == OLD_ECO_CONTEXT, \
        'g24b33459 eco.context уже другой: %r' % (d['eco']['context'],)
    urls = {s[1] for s in d['src']}
    assert NEW_SRC[1] not in urls, 'источник уже добавлен'

    print('g24b33459: seller None -> "ЗПИФ комбинированный «Астерия»"; '
          'eco.context дополнен (название проекта «Кумжаград»); добавлен '
          'источник bloknot-rostov.ru')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['seller'] = NEW_SELLER
    d['eco']['context'] = NEW_ECO_CONTEXT
    d['src'].append(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
