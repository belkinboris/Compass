# -*- coding: utf-8 -*-
"""Двенадцатая партия описаний профилей: чем компания занимается.

ЧТО СЛОМАНО. После одиннадцати партий настоящее описание есть у 500
профилей из 1872 (27%). Кандидатов этой партии искали по узнаваемости
имени, а не по рангу участия в сделках (см. батчи 8–11) — каждый проверен
по тексту его собственной сделки в базе. Пять узнаваемых имён намеренно
отложены — Trinity Group, Enel Russia, AIG (российская страховая
компания), Doka (российские активы), Fedilco Group Limited: либо не
нашлось ни одной связанной сделки в базе (нечем подтвердить, что профиль —
именно та компания, о которой думаешь — урок CLAUDE.md про «Акрон
Холдинг»), либо род занятий по самой сделке недостаточно ясен, чтобы не
гадать (Fedilco — покупатель МТС Армении, но что это за компания обычно —
из текста карточки не следует).

Заодно одно исправление отрасли, найденное при чтении контекста сделки:
Zebra Toys стояла в «Ритейл», хотя собственная сделка называет её
«производителем игрушек» — исправлено на «Потребительские товары».

ЧТО ДЕЛАЕТ. Проставляет описание в 1–2 строки 17 профилям, исправляет
отрасль у 1.

Запуск:
    python3 pipeline/write_company_descriptions_batch12.py            # сухой прогон
    python3 pipeline/write_company_descriptions_batch12.py --write    # записать
"""
import json
import re
import sys

DATA = 'static/data/deals_promoted.json'
PLACEHOLDER = re.compile(r'^\s*(описание компании пока не добавлено'
                          r'|профиль сформирован по итогам чтения)', re.I)

# id профиля -> описание. Только компании, чей род занятий общеизвестен.
DESCRIPTIONS = {
    'g107770ca': 'Российский оператор мобильной связи, входит в группу '
                 '«Ростелеком» (бренд Т2).',
    'g34fb06d5': 'Российская алюминиевая компания, один из крупнейших '
                 'производителей алюминия в мире.',
    'g04328d0f': 'Российский ювелирный холдинг: производство и розничная '
                 'сеть.',
    'gf7f00f75': 'Немецкий производитель отопительного и климатического '
                 'оборудования.',
    'g4f542f90': 'Российский производитель кофе спешелти-обжарки.',
    'gc56ae3fb': 'Российский производитель игрушек.',
    'g6cdf8d75': 'Международный оператор мобильной связи и eSIM для '
                 'корпоративных клиентов.',
    'g67e0c7f9': 'Американское подразделение Трубной металлургической '
                 'компании (ТМК), производитель труб для нефтегазовой '
                 'отрасли.',
    'gff185389': 'Немецкий производитель строительных материалов '
                 '(газобетон).',
    'gb362986b': 'Российский производитель бытовой техники под немецким '
                 'брендом Schaub Lorenz.',
    'g4f3ea67e': 'Международный холдинг кибербезопасности Group-IB, '
                 'выделенный из российского бизнеса компании.',
    'g41dae07f': 'Американская инвестиционная компания (фонд прямых '
                 'инвестиций).',
    'g68bdaf04': 'Страховое подразделение французской банковской группы '
                 'BNP Paribas.',
    'ge6af02f6': 'Российская компания генетических исследований '
                 '(ДНК-тестирование).',
    'ga070e8d2': 'Один из крупнейших фондов прямых инвестиций, работавших '
                 'на российском рынке.',
    'g511b219e': 'Российский производитель сухих строительных смесей и '
                 'клеёв.',
    'ge828c124': 'Шведская группа — производитель матрасов и товаров для '
                 'сна, ранее владела российским брендом «Аскона».',
}

# Профили, отрасль которых унаследована от одной сделки и не отражает
# основной бизнес компании (см. докстринг). old — что было, для assert.
INDUSTRY_FIXES = {
    'gc56ae3fb': ('Ритейл', 'Потребительские товары'),
}

# Профили, которым описание не ставится в этой партии: неизвестно, что
# именно они обозначают, или падежная/предметная форма имени.
UNCLEAR = {}


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    comps = data['companies']

    wrote, skipped = 0, []
    for cid, text in DESCRIPTIONS.items():
        c = comps.get(cid)
        assert c, 'профиля %s нет в базе' % cid
        assert 15 <= len(text) <= 220, 'описание %s вне 1–2 строк: %d' % (cid, len(text))
        assert cid not in UNCLEAR, 'профиль %s помечен неясным — описание ставить нельзя' % cid
        old = str(c.get('desc') or '')
        if old.strip() == text:
            continue
        # Своё описание не перетираем: прошлые партии и ручные правки старше этой.
        if old and not PLACEHOLDER.match(old):
            skipped.append((cid, c.get('name'), old[:60]))
            continue
        print('  %-12s %-34s %s' % (cid, str(c.get('name'))[:34], text[:56]))
        c['desc'] = text
        wrote += 1

    ind_fixed = 0
    for cid, (old_ind, new_ind) in INDUSTRY_FIXES.items():
        c = comps.get(cid)
        assert c, 'профиля %s нет в базе' % cid
        assert c.get('ind') == old_ind, ('отрасль %s уже другая: %r (ожидали %r)'
                                          % (cid, c.get('ind'), old_ind))
        print('  ОТРАСЛЬ  %-12s %-34s %s -> %s'
              % (cid, str(c.get('name'))[:34], old_ind, new_ind))
        c['ind'] = new_ind
        ind_fixed += 1

    print('\nОписаний записано: %d' % wrote)
    print('Отраслей исправлено: %d' % ind_fixed)
    if skipped:
        print('Пропущено (уже есть своё описание): %d' % len(skipped))
        for cid, name, old in skipped[:5]:
            print('   %s %s — %r' % (cid, name, old))
    print('Оставлено без описания намеренно: %d профилей (см. UNCLEAR)' % len(UNCLEAR))

    real = sum(1 for v in comps.values()
               if (v.get('desc') or '').strip() and not PLACEHOLDER.match(str(v.get('desc'))))
    print('Всего профилей с описанием: %d из %d (%d%%)'
          % (real, len(comps), round(100 * real / len(comps))))

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return 0
    json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('Записано.')
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
