# -*- coding: utf-8 -*-
"""Приток, 08:20 МСК 30 сентября 2026: «Деловой Петербург» сообщил, что
здание на Большой Конюшенной ул., 11 (памятник федерального значения «Дом
Капеллы», ~1,2 тыс. м²) перешло в начале сентября 2026 в долевую
собственность структур бизнесмена Муссы Экзекова: ООО «Гранд Конюшенная»
(3/6 долей) и ООО «Коннэкт» (2/6 долей, независимо подтверждено через
SPARK-Interfax — ИНН 7801239650, владелец Экзеков Мусса Хабалевич), плюс
физлицо (1/6 доли). Ворота не пропустили черновик как сделку (заголовок
не разобрался на стороны автоматически: заметка Росреестра, а не прямая
формула «купил у»). Собрал вручную, тот же класс случая, что карточки
Боброва и «Великоленского» 29 сентября.

Продавец не раскрыт (физлицо, Росреестр не публикует имена с 2023 года).
Статья предполагает, что им мог быть Борис Григорьевич Авсаджанашвили,
основатель сети «Бабочка» (в тексте dp.ru — неточно «Бойгар», но
независимый источник sobaka.ru называет полное отчество «Борис
Григорьевич», что как раз совпадает с инициалами «Б.Г.» из разрешения на
ремонт фасада 2021 года) — но это совпадение инициалов, не подтверждённый
факт, дословно так и подано в источнике. В карточку — как версия в
eco.context, не как поле `seller`.

Цена 450-500 млн ₽ — оценка стороннего эксперта (IBC Real Estate), не
раскрытая сумма сделки — в `sum` с пометкой, чтобы не выдать оценку за факт.

Корроборация (субагент, 30 сентября): другие издания историю не подхватили
(на дату поиска это эксклюзив dp.ru); официальных комментариев сторон нет;
название ООО «Гранд Конюшенная» не нашлось ни в одном публичном реестре
(агрегаторы блокировали проверку) — подтверждается только самой статьёй.

Запуск: python3 pipeline/fix_add_ekzekov_konyushennaya_card.py [--write]
"""
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'ingest'))

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')


def main(write=False):
    import promote

    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    ids = {c['id'] for c in data['deals']}
    new_id = promote.new_id(ids)

    draft = {
        'date': '2026-09-30',
        'title': 'Бизнесмен Мусса Экзеков купил историческое здание в центре Петербурга',
        'ind': 'Недвижимость',
        'type': 'M&A',
        'status': 'Закрыта',
        'sum': '≈450–500 млн ₽ (по оценке)',
        'buyer_name': 'ООО «Гранд Конюшенная» и ООО «Коннэкт» (структуры Муссы Экзекова)',
        'asset': 'здание на Большой Конюшенной ул., 11 в Петербурге («Дом Капеллы», ~1,2 тыс. м²)',
        'src': [['Деловой Петербург', 'https://www.dp.ru/a/2026/09/30/vladelec-trc-grand-kanon']],
        'events': [
            {'kind': 'closed', 'date': '2026-09-30', 'title': 'Сделка завершена',
             'note': 'По данным Росреестра, здание в начале сентября 2026 года перешло '
                     'в долевую собственность структур Муссы Экзекова и физлица.',
             'source': ['Деловой Петербург', 'https://www.dp.ru/a/2026/09/30/vladelec-trc-grand-kanon']},
        ],
    }
    card = promote.to_card(draft, new_id)
    card['eco']['sum'] = draft['sum']
    card['eco']['context'] = (
        'Здание — памятник федерального значения «Дом Капеллы» конца XIX века '
        '(архитектор Леонтий Бенуа), часть квартала «Дворы Капеллы» рядом с '
        'Певческой капеллой на набережной Мойки. Продавец не раскрыт: это физлицо, '
        'а Росреестр с 2023 года не публикует имена таких собственников по общим '
        'запросам. Источник предполагает, что им мог быть Борис Григорьевич '
        'Авсаджанашвили, основатель петербургской сети магазинов одежды «Бабочка» — '
        'в разрешении на ремонт фасада здания 2021 года заказчиком указан «ИП '
        'Авсаджанашвили Б.Г.», инициалы совпадают. Но это совпадение, а не '
        'подтверждённый факт: сама статья и независимая проверка не нашли прямого '
        'подтверждения личности продавца. Сумма — не раскрытая сторонами цена, а '
        'оценка независимого эксперта (IBC Real Estate), допускающего использование '
        'здания под апарт-отель, мини-гостиницу или офисы с ретейлом на первом '
        'этаже — это его прогноз, а не объявленные планы покупателя. Комментариев '
        'от сторон сделки нет.'
    )
    card['law']['struct'] = (
        'Здание перешло в долевую собственность: ООО «Гранд Конюшенная» — 3/6 долей, '
        'ООО «Коннэкт» — 2/6 долей, физическое лицо — 1/6 доли. ООО «Коннэкт» '
        '(ИНН 7801239650) принадлежит Муссе Хабалевичу Экзекову — независимо '
        'подтверждено по данным SPARK-Interfax. ООО «Гранд Конюшенная» связано с ним '
        'через совместное владение с «Коннэкт», по данным «Контур.Фокус», на которые '
        'ссылается источник; отдельно в открытых реестрах компания не найдена.'
    )
    card['themes'] = ['Недвижимость']
    # `to_card` не ставит `added` — обычно его ставит `approve.py` при выводе
    # карточки из pending.json; прямая запись минует этот путь, дата не
    # выдумана — карточка правда добавлена сегодня.
    card['added'] = '2026-09-30'

    data['deals'].append(card)
    print('Добавлена карточка %s: %s' % (new_id, card['title']))

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
