import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g32905903'

OLD_CONTEXT = (
    'ОАО «Тверская фармацевтическая фабрика» зарегистрировано в 1994 году. '
    'Уставный капитал составляет 106,7 тыс. рублей. Основной вид '
    'деятельности компании – производство лекарственных препаратов для '
    'медицинского применения. Генеральным директором является Ирина '
    'Нечаева. Учредители – государство и ООО «Спаркл». Правопредшественники '
    '– ЗАО «Лайс» и ЗАО ИК «Прогресс-инвест».'
)
CONTEXT_ADDITION = (
    ' После сделки фабрика вошла в региональный инвестпроект: «21 октября '
    'на заседании Бюджетной комиссии Тверской области было принято решение '
    'о поддержке этого проекта. Фабрика получит льготный заем по программе '
    '«Проекты обрабатывающей промышленности» от регионального Фонда '
    'развития промышленности... мощность производства планируется нарастить '
    'с 10 до 12-15 миллионов единиц продукции в год» (vladmiva.ru). На '
    'ПМЭФ-2026 (3 июня) губернатор Виталий Королев и председатель совета '
    'директоров фабрики Владимир Чуев (он же основатель и гендиректор '
    '«ВладМиВы») подписали соглашение об инвестициях 500 млн ₽, 30+ новых '
    'рабочих мест и регистрации новых наружных препаратов для снятия боли '
    'в мышцах, суставах и при травмах (tverlife.ru).'
)
NEW_CONTEXT = OLD_CONTEXT + CONTEXT_ADDITION

NEW_SRC = [
    ['ВладМиВа', 'https://vladmiva.ru/events/vladmiva-investiruet-v-istoricheskoe-farmatsevticheskoe-proizvodstvo-tveri/'],
    ['Тверская жизнь', 'https://tverlife.ru/sobytija/tverskaja-oblast-uvelichit-vypusk-dostupnyh-lekarstv/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
