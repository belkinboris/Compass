import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g5de426be'

OLD_DATE = '2023-04-26'
NEW_DATE = '2021'

OLD_LAW_STRUCT = '—'
NEW_LAW_STRUCT = (
    'Прежний владелец Бекхан Агаев купил «Нобель Ойл» в 2020 году у '
    'Григория Гуревича, гонконгской Oriental Patron Financial Group и '
    'China Investment Corporation. Операторские услуги «Нобель Ойл» '
    'оказывает «Нефтиса», принадлежавшая на тот момент её основателю '
    'Михаилу Гуцериеву.'
)

OLD_LAW_TERMS = '—'
NEW_LAW_TERMS = (
    'Представитель Искендера Халилова заявил, что бизнесмен не '
    'владеет «Нобель Ойл» «в интересах третьих лиц».'
)

OLD_ECO_CONTEXT = (
    'Новый собственник «Нобель Ойл» Искендер Халилов — российско-'
    'азербайджанский бизнесмен. В 2000-х годах он занимал пост '
    'вице-президента «Славнефти», которую тогда возглавлял Гуцериев. '
    'Оба бизнесмена были также совладельцами Кузбасской топливной '
    'компании (КТК), которая ведёт добычу угля в Кемеровской области.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' 1 июля 2023 года на месторождении в Коми '
    'произошёл разлив нефтесодержащей жидкости в реку Колва; в марте '
    '2024 года суд утвердил мировое соглашение — компания выплатила '
    '25,4 млн ₽ и обязалась рекультивировать земли. В сентябре 2025 '
    'года двум сотрудникам «Нобель Ойл» предъявлено обвинение в '
    'сокрытии информации об этой аварии — ущерб в 209 млн ₽ компания '
    'возместила полностью.'
)

OLD_SRC = [['Коммерсантъ', 'https://www.kommersant.ru/doc/5953701']]
NEW_SRC = OLD_SRC + [
    ['Усинск Online', 'https://usinsk.online/news/kompaniya-nobel-ojl-vyplatit-25-4-mln-rublej-v-techenie-goda'],
    ['БНК', 'https://bnkomi.ru/data/news/190195'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['date'] == OLD_DATE
    assert deal['law']['struct'] == OLD_LAW_STRUCT
    assert deal['law']['terms'] == OLD_LAW_TERMS
    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== date: станет ===')
    print(NEW_DATE)
    print('\n=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)
    print('\n=== law.terms: станет ===')
    print(NEW_LAW_TERMS)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['date'] = NEW_DATE
        deal['law']['struct'] = NEW_LAW_STRUCT
        deal['law']['terms'] = NEW_LAW_TERMS
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
