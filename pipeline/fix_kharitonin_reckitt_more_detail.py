# -*- coding: utf-8 -*-
"""Заметка 511 (консоль, 4 сентября 2026): «Нужны подробности чтобы
принять решение», отвечая на карточку `ge361bfa8» (структуры Виктора
Харитонина рассматривают приобретение российского бизнеса Reckitt).

Перепроверено прямым чтением (incrussia.ru): интерес Харитонина был не
к производственным мощностям, а к брендам и дистрибуции ВСЕГО
российского портфеля Reckitt (статья не разделяет фармсегмент —
Нурофен, Стрепсилс — и бытовую химию — Durex, Vanish, Tiret, Calgon,
уже проданную «Арнесту»); Reckitt не готова передавать права на
международные товарные знаки и рассчитывает продать актив «за большую
цену». Инвестбанкир Иван Пешков оценивал весь портфель в 30-40 млрд ₽
с учётом долга, но реальная цена могла быть выше из-за 9+ млрд ₽ на
счетах компании и отсутствия кредитной задолженности. Официальных
заявлений о статусе переговоров нет — открытым остаётся вопрос, была
ли претензия Харитонина именно на фармсегмент (тот, что НЕ ушёл
«Арнесту») или на весь портфель целиком.

Запуск: python3 pipeline/fix_kharitonin_reckitt_more_detail.py [--write]
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'ge361bfa8'
OLD_CONTEXT = (
    'По мнению Астафьева, переговоры о продаже фармацевтических '
    'активов Reckitt структурам основателя «Фармстандарта» Виктора '
    'Харитонина мог сорвать отказ компании передать российским '
    'покупателям права на глобальные бренды. 24 июля 2026 года Reckitt '
    'Benckiser договорилась о продаже российского подразделения '
    'бытовой химии не структурам Харитонина, а группе «Арнест»; '
    'закрытие этой сделки ожидается во второй половине 2026 года. Ни '
    'Харитонин, ни «Фармстандарт» в сообщениях об этой сделке не '
    'упоминаются.'
)
ADDITION = (
    ' Интерес Харитонина был не к производственным мощностям, а к '
    'брендам и дистрибуции: источник, знакомый с переговорами, называл '
    'причиной то, что «Reckitt не готова передавать новому собственнику '
    'права на международные товарные знаки и рассчитывает продать '
    'актив "за большую цену"». Речь шла о всём российском портфеле '
    'Reckitt в целом (без явного разделения на фармсегмент — Нурофен, '
    'Стрепсилс — и бытовую химию, ушедшую «Арнесту»); инвестбанкир Иван '
    'Пешков оценивал портфель в 30–40 млрд ₽ с учётом долга, отмечая, '
    'что реальная цена могла быть выше из-за 9+ млрд ₽ на счетах '
    'компании и отсутствия кредитной задолженности. Официальных '
    'заявлений о статусе переговоров не было ни разу.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {c['id']: c for c in data['deals']}
    card = by_id[CARD_ID]
    assert card['eco']['context'] == OLD_CONTEXT, card['eco']['context']
    card['eco']['context'] = OLD_CONTEXT + ADDITION

    known_urls = {s[1] for s in card['src'] if len(s) > 1}
    url = 'https://incrussia.ru/news/rossijskie-aktivy-reckitt-mogut-perejti-vladeltsu-farmstandarta/'
    if url not in known_urls:
        card['src'].append(['Inc. Russia', url])

    print(f'{CARD_ID}.eco.context: добавлены подробности (incrussia.ru)')

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
            f.write('\n')
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
