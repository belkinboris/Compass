import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g7d996243'

OLD_CONTEXT = (
    'В 2023 году группа Russ провела ряд крупных поглощений на рынке'
    ' наружной рекламы. В июле 2023 года она объявила о покупке своего'
    ' главного конкурента — второго номера в отрасли компании Gallery.'
)
NEW_CONTEXT = (
    OLD_CONTEXT + ' По итогам 2023 года доля Russ на рынке наружной'
    ' рекламы составила 43% (выручка группы — 38,3 млрд ₽); консолидация'
    ' продолжилась и дальше — по отраслевым измерениям (только'
    ' стандартные форматы в 50 крупнейших городах), к 2025 году доля'
    ' выросла до 78,5%. Само юрлицо АО «Постер» прекратило существование'
    ' 25 марта 2024 года, присоединившись к другой компании.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
