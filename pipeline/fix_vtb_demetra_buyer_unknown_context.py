# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
`ga7232033` («ВТБ продает 45% в «Деметра-Холдинг»», закрыта, 2023) —
карточка стояла закрытой при полностью пустом `buyer`/`buyer_name`:
дочитывание подтвердило, что это честная пустота, а не недосмотр —
прямого покупателя пакета ВТБ не назвал НИ ОДИН источник, включая
самого главу ВТБ Андрея Костина («Не могу сказать, кто покупатель, —
это его право заявлять о себе»).

Проверено (по докладу саб-агента, дословные цитаты; оба источника
карточки прочитаны полностью):
- kommersant.ru/doc/6096656 и vedomosti.ru/business/articles/2023/07/
  10/984636-u-zernotreidera-demetra-holding-poyavitsya-investor-iz-
  omana: «Southern Sea Investment LLC — не прямой покупатель, а
  якорный инвестор — один из покупателей допэмиссии, которую проводит
  зерновой холдинг»; «Какую долю получит оманская компания, не
  уточняется»; «сумма сделки также не раскрывается». То есть оманский
  инвестор ВОШЁЛ в капитал холдинга ЧЕРЕЗ ОТДЕЛЬНУЮ допэмиссию, а не
  купив пакет ВТБ напрямую, — важное разграничение, чтобы не
  приписать ему роль прямого покупателя.
- agroinvestor.ru/companies/news/40448-vtb-prodast-svoyu-dolyu-v-
  demetra-kholding/ (источник карточки): «в феврале прошлого года ВТБ
  в результате допэмиссии снизил долю в «Деметра-Холдинг» с 50% плюс
  одна акция до 45%» — ЭТО ОТДЕЛЬНОЕ, БОЛЕЕ РАННЕЕ событие (февраль
  2022 года), не механизм самой продажи 2023 года; уже стоящая в
  карточке фраза про допэмиссию (`law.struct`) рискует читаться как
  описание сделки-продажи 2023 года, хотя источник говорит именно про
  более раннее размытие.
- interfax.ru/business/915704 (10 августа 2023): «Marathon Group
  владела 10,57% долей холдинга через ООО «СПН»»; «Сделка была
  денежной, и Marathon Group зафиксировал прибыль от инвестиций в
  «Деметра-Холдинг»» — параллельный выход ещё одного акционера в тот
  же период, покупатель тоже не назван.

НЕ ВНЕСЕНО: (1) имя прямого покупателя 45% ВТБ — не установлено ни
одним из проверенных источников, поле `buyer`/`buyer_name` остаётся
честной пустотой, а не ошибкой; (2) сумма сделки — нигде не раскрыта,
только оценочное «цена объективная, маржа приличная» (Костин), уже
не вносится повторно; (3) точная доля, полученная Southern Sea
Investment, и её связь (если есть) с конечной структурой владения
холдинга — источники прямо говорят, что доля не уточняется;
(4) статус компании «в процессе реорганизации с 14.05.2024» — известен
только по агрегатору (rusprofile), не подтверждён прямым чтением
реестра, не вносится.

Запуск: python3 pipeline/fix_vtb_demetra_buyer_unknown_context.py
        python3 pipeline/fix_vtb_demetra_buyer_unknown_context.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'ga7232033'

OLD_LAW_STRUCT = (
    'Есть и тактическая задача: при экспорте зерна компания с '
    'арабскими совладельцами, как предполагается, столкнётся с '
    'меньшими санкционными препятствиями. Долю планируется продать '
    'через дополнительную эмиссию — она позволит российским '
    'собственникам сохранить ведущую роль в управлении стратегическими '
    'активами «Деметра-холдинга».'
)
NEW_LAW_STRUCT = (
    OLD_LAW_STRUCT + ' Доля ВТБ уже снижалась с контрольной (50% плюс '
    'одна акция) до 45% ещё в феврале 2022 года в результате более '
    'ранней допэмиссии — это отдельное от продажи 2023 года событие.'
)

OLD_ECO_CONTEXT = (
    'По словам Костина, покупатели уже найдены, причём среди них '
    'могут быть не только российские. Претендентов на пакет акций '
    'холдинга глава ВТБ не назвал, уточнив лишь, что они будут из '
    'дружественных стран.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' Прямого покупателя пакета ВТБ ни один источник '
    'так и не назвал — сам Костин сказал: «Не могу сказать, кто '
    'покупатель, — это его право заявлять о себе». В июле 2023 года '
    'анкерным инвестором ОТДЕЛЬНОЙ допэмиссии холдинга стала оманская '
    'Southern Sea Investment LLC — по уточнению источников, это не '
    'прямой покупатель доли ВТБ, а один из покупателей допэмиссии, '
    'доля и сумма не раскрывались. В том же месяце из капитала вышла '
    'и Marathon Group Александра Винокурова (около 10,57% через ООО '
    '«СПН»), тоже не раскрыв покупателя.'
)

OLD_SRC = [
    ['Агроинвестор', 'https://www.agroinvestor.ru/companies/news/40448-vtb-prodast-svoyu-dolyu-v-demetra-kholding/'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6085072'],
]
NEW_SRC = OLD_SRC + [
    ['Ведомости', 'https://www.vedomosti.ru/business/articles/2023/07/10/984636-u-zernotreidera-demetra-holding-poyavitsya-investor-iz-omana'],
    ['Интерфакс', 'https://www.interfax.ru/business/915704'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['law']['struct'] == OLD_LAW_STRUCT
    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['law']['struct'] = NEW_LAW_STRUCT
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
