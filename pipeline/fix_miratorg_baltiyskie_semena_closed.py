# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g1964bb40 («Мираторг» покупает производителя семенного картофеля
«Балтийские семена») — статус «Обсуждается» держался больше двух лет
после получения разрешения Правкомиссии («ожидается закрытие»), хотя
сделка реально закрыта и актив уже интегрирован. Проверено лично
прямым WebFetch двух независимых регистрационных источников.

`status`/`date` (изменены). Дословно (saby.ru, ЕГРЮЛ-данные): «Мираторг-
Брянск, ООО» «С 24.04.24 является владельцем» ООО «Балтийские семена»
— значит, сделка закрыта не позже конца апреля 2024 года, через
полтора месяца после разрешения Правкомиссии (март 2024). `date`
меняется на дату этой записи ЕГРЮЛ (перенос внутри того же года —
допустимая уточняющая правка, не смена года).

`eco.context` (дополнено). К 2025 году «Балтийские семена» как
отдельное юрлицо перестали существовать — актив полностью поглощён
структурой «Мираторга». Дословно (saby.ru): статус компании —
«Деятельность прекращена» с датой «4 августа 2025 г.» в результате
«Прекращение деятельности юридического лица путем реорганизации в
форме присоединения». Дословно (audit-it.ru, независимо, тот же
факт): «Правопреемник: ООО "МИРАТОРГ-КАЛИНИНГРАД" (ИНН:
1043902828430)» — то есть актив консолидирован в существующую
калининградскую структуру холдинга, а не оставлен отдельным юрлицом.

`law.appr` (уточнено) — было «В марте 2024 получено разрешение
Правкомиссии, ожидается закрытие» (будущее время на уже закрытой
сделке, тот же класс правки, что уже применялся к другим карточкам).

НЕ ВКЛЮЧЕНО: сумма сделки — ни один источник её не называет,
«Мираторг» от комментариев отказался (Коммерсантъ, уже в карточке).
Прямые страницы rusprofile.ru/list-org дали 403 при попытке открыть —
использованы альтернативные регистрационные агрегаторы (saby.ru,
audit-it.ru), которые дали тот же факт независимо друг от друга.

Запуск: python3 pipeline/fix_miratorg_baltiyskie_semena_closed.py
        python3 pipeline/fix_miratorg_baltiyskie_semena_closed.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g1964bb40'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Закрыта'
OLD_DATE = '2024-03-01'
NEW_DATE = '2024-04-24'

OLD_CONTEXT = (
    'В ассортименте «Балтийских семян» были сорта для производства '
    'чипсов и картофеля фри, сообщало в 2022 году правительство '
    'Калининградской области.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' По данным ЕГРЮЛ, с 24 апреля 2024 года владельцем ООО '
    '«Балтийские семена» стало ООО «Мираторг-Брянск». К 2025 году '
    'компания как отдельное юрлицо прекратила существование: с 4 '
    'августа 2025 года деятельность прекращена путём реорганизации в '
    'форме присоединения к ООО «Мираторг-Калининград» — актив '
    'консолидирован в уже действующей калининградской структуре '
    'холдинга.'
)

OLD_APPR = 'В марте 2024 получено разрешение Правкомиссии, ожидается закрытие.'
NEW_APPR = (
    'В марте 2024 получено разрешение Правкомиссии. Сделка закрыта: по '
    'данным ЕГРЮЛ, с 24 апреля 2024 года владельцем ООО «Балтийские '
    'семена» стало ООО «Мираторг-Брянск».'
)

NEW_SRC = [
    ['saby.ru', 'https://saby.ru/contragents/3906900736/390601001'],
    ['audit-it.ru', 'https://www.audit-it.ru/contragent/1153926000084_ooo-baltiyskie-semena'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS, deal['status']
    assert deal['date'] == OLD_DATE, deal['date']
    assert deal['eco']['context'] == OLD_CONTEXT
    assert deal['law']['appr'] == OLD_APPR, deal['law']['appr']
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== status: было / станет ===')
    print(OLD_STATUS, '->', NEW_STATUS)
    print('=== date: было / станет ===')
    print(OLD_DATE, '->', NEW_DATE)
    print('\n=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== law.appr: станет ===')
    print(NEW_APPR)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['status'] = NEW_STATUS
        deal['date'] = NEW_DATE
        deal['eco']['context'] = NEW_CONTEXT
        deal['law']['appr'] = NEW_APPR
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
