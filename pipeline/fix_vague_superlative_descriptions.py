# -*- coding: utf-8 -*-
"""Снять превосходную степень без измерения — не все превосходные степени.

ЗАЧЕМ. Профессиональные базы (Crunchbase, PitchBook) прямо советуют не писать
«лучший», «ведущий», «самый» без конкретики — это маркетинговый штамп, а не
факт. Первая реакция на этот совет — вычистить каждое слово вроде «крупнейший»
из описаний профилей. Это была бы ОШИБКА: замер по базе (7 августа) нашёл 18
профилей со словом «крупнейший»/«ведущий», и 17 из них — не штамп, а
общеизвестный, проверяемый факт с указанием МЕРЫ: «Крупнейший банк России»
(Сбербанк — по активам, общеизвестно), «крупнейший в стране банк сельхозземель
по площади» (Био-Тон — мера названа в самом тексте), «Крупнейший частный банк
России» (Альфа-Банк — уточнено «частный», иначе конфликтовало бы со
Сбербанком). Это ровно то, что и профессиональная база показала бы: масштаб —
полезная информация, когда его можно проверить.

Настоящий штамп нашёлся один: «Ведущий российский разработчик промышленных
роботов» (Технорэд) — «ведущий» без меры и без сравнения. Он не говорит,
ведущий по чему: по выручке, по числу проектов, по узнаваемости. Заменён на
описание рода занятий без непроверяемого ранга.

УРОК ШИРЕ ЭТОГО СКРИПТА: признак «есть превосходная степень» — повод
прочитать конкретное предложение, а не правило для автоматической чистки.
Родня уже записанного урока «признак дефекта — повод прочитать, а не
основание стереть».

Запуск:
    python3 pipeline/fix_vague_superlative_descriptions.py            # сухой прогон
    python3 pipeline/fix_vague_superlative_descriptions.py --write    # записать
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

FIXES = {
    'technored': (
        'Ведущий российский разработчик промышленных роботов.',
        'Российский разработчик промышленных роботов для автоматизации '
        'производства.',
    ),
}


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    comps = data['companies']

    changed = 0
    for cid, (old, new) in FIXES.items():
        c = comps.get(cid)
        assert c, 'профиля %s нет в базе' % cid
        cur = str(c.get('desc') or '')
        if cur == new:
            continue
        assert cur == old, 'у %s описание уже другое: %r' % (cid, cur)
        print('  %-12s %s\n  %-12s -> %s' % (cid, old, '', new))
        c['desc'] = new
        changed += 1

    print('\nИсправлено описаний: %d' % changed)
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return 0
    json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('Записано.')
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
