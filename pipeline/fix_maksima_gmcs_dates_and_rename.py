# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g3a25a36c
(«ГК «Максима» приобрела 60% IT-интегратора GMCS», закрыта июль 2023) —
дата в `law.struct» была неточной («в сентябре» вместо 31 июля), не был
назван бенефициар конечного покупателя и переименование самой ГК
«Максима» в ГК «МТ-Интеграция» — ту же группу, что уже фигурирует в
базе в саге вокруг «Аквариуса»/S8 Capital.

Проверено лично прямым WebFetch (ComNews, https://www.comnews.ru/content/229281/2023-10-06/2023-w40/1007/gk-maksima-kupila-byvshiy-oskolok-maykor):
«ЗПИКФ "Контрада-Спутник" продал 65% долей в ООО "Джи-Эм-Си-Эс Верэкс"
компании "МТ-Интеграция"» — 7 июля 2023 года; «"МТ-Интеграция"
перепродала 60% уставного капитала GMCS АО "Инвестмир"» — 31 июля
2023 года, то есть держание МТ-Интеграцией длилось 24 дня, а не до
сентября, как было в карточке; АО «Инвестмир» принадлежит Сергею
Асланяну, «председателю совета директоров ГК "Максима"»; «Екатерина
Воропаева (президент GMCS) нарастила долю в ней до 29%», «11%
находятся в руках у» Ильи Дрозмана (исполнительный директор).

Проверено лично прямым WebFetch (Ведомости, https://www.vedomosti.ru/technology/news/2025/08/22/1133615-maksima-ne-voidet):
«Информация о входе ГК "МТ-Интеграция" (ранее ГК "Максима") в состав
акционеров группы компаний "Аквариус" не соответствует действительности»
— то есть ГК «Максима», покупатель в этой карточке, была впоследствии
переименована в ГК «МТ-Интеграция» и это та же группа, которая уже
описана в «Известных проблемах» CLAUDE.md как публично отрицавшая
участие в сделке с «Аквариусом» (карточка `g139db8c2`) — не совпадение
имён, а прямое продолжение той же компании.

НЕ ВКЛЮЧЕНО: альтернативная (более высокая) оценка суммы сделки от
самих «Ведомостей» (до 4,5 млрд ₽, без названного эксперта, статья
почти вся под пейволлом) — уже стоящая оценка Максима Кутузова (1-1,5
млрд ₽) именует эксперта и метод рассуждения, вторая цифра источника
не называет обоснования вовсе; более ранняя история владения GMCS
(2005-2018, до Совкомбанка) и точные финансовые показатели самой GMCS
за 2021-2025 годы — сабагент отметил расхождение методик подсчёта
между источниками (ФНС/ComNews против TAdviser дают разные цифры за
один и тот же год), переносить без разрешения расхождения не стал.
Консультанты сделки — не названы ни в одном источнике.

Запуск: python3 pipeline/fix_maksima_gmcs_dates_and_rename.py
        python3 pipeline/fix_maksima_gmcs_dates_and_rename.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g3a25a36c'

OLD_LAW_STRUCT = (
    'В июле 2023 г. 65% доля в GMCS перешла к ООО «МТ-Интеграция», '
    'входящей в состав группы компаний «Максима». В сентябре эта доля '
    'перешла к другой структуре ГК «Максима» — АО «Инвестмир».'
)
NEW_LAW_STRUCT = (
    '7 июля 2023 года ЗПИКФ «Контрада-Спутник» продал 65% долей в ООО '
    '«Джи-Эм-Си-Эс Верэкс» компании «МТ-Интеграция», входящей в состав '
    'группы компаний «Максима». Уже 31 июля 2023 года «МТ-Интеграция» '
    'перепродала 60% уставного капитала GMCS АО «Инвестмир» — структуре '
    'Сергея Асланяна, председателя совета директоров ГК «Максима» '
    '(держание «МТ-Интеграцией» продлилось 24 дня). Оставшиеся доли: '
    '29% у президента GMCS Екатерины Воропаевой, 11% — у исполнительного '
    'директора Ильи Дрозмана.'
)

OLD_ECO_CONTEXT = (
    'В 2018 г. Совкомбанк установил косвенный контроль над GMCS. Это '
    'произошло путем покупки 100% доли в «Джи-Эм-Си-Эс Менеджмент». Как '
    'писало издание TAdviser, сумма сделки составила 500 млн руб. При '
    'этом еще весной 2022 г. «Джи-Эм-Си-Эс менеджмент» продал свою долю '
    'в GMCS («Джи-Эм-Си-Эс Верэкс») Вячеславу Кузьмичеву, который '
    'перепродал ее управляющей компании «Контрдата Капитал»'
)
NEW_ECO_CONTEXT = OLD_ECO_CONTEXT + (
    '. ГК «Максима» позже переименована в ГК «МТ-Интеграция» — это та '
    'же группа, что в 2025 году публично отрицала своё участие в '
    'приобретении акций «Аквариуса»: «Информация о входе ГК '
    '«МТ-Интеграция» (ранее ГК «Максима») в состав акционеров группы '
    'компаний «Аквариус» не соответствует действительности».'
)

NEW_SRC = [
    ['ComNews', 'https://www.comnews.ru/content/229281/2023-10-06/2023-w40/1007/gk-maksima-kupila-byvshiy-oskolok-maykor'],
    ['Ведомости', 'https://www.vedomosti.ru/technology/news/2025/08/22/1133615-maksima-ne-voidet'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['law']['struct'] == OLD_LAW_STRUCT
    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    new_src = deal['src'] + NEW_SRC

    print('=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['law']['struct'] = NEW_LAW_STRUCT
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
