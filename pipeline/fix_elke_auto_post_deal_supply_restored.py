# -*- coding: utf-8 -*-
"""Месячная очередь качества, 11 сентября 2026 — карточка `g7f6d55a9`
(«Семья бизнесмена Говора приобрела частную сеть АЗС Elke Auto в
Томске», август 2026) не рассказывала, что случилось с сетью ПОСЛЕ
сделки: причина продажи (топливный кризис июня 2026) была в карточке,
а восстановление поставок и работы заправок — нет. Новый, более
поздний источник (РИА Томск, 3 сентября) добавляет именно это.

Личный WebFetch подтвердил дословно (https://www.riatomsk.ru/article/
20260903/novii-vladelets-rasshiril-set-elke-avto-v-tomske-do-7-azs,
3 сентября 2026, 20:27):
- «Топливо на АЗС поставляется с Кемеровского НПЗ с 27 июля в полном
  объеме и в полном ассортименте, включая АИ-92, АИ-95 и дизельное
  топливо. Объем реализации составляет 180 "кубов" в сутки».
- «"Элке Авто" открыла еще одну АЗС – на улице Елизаровых, 85. Таким
  образом, в Томске работают уже семь заправочных станций компании».
- «Ожидается, что до конца ноября заработают все 11 АЗС "Элке Авто"».

ВАЖНО, что НЕ внесено. (1) Спор о бенефициаре управляющей компании
(«Инрусинвест» / Скурыгин против Говор) уже найден и сознательно
оставлен нерешённым партией `batch_deep_2026_r8.py` от 18 августа —
эта правка его не трогает и не пытается разрешить. (2) Число «11 АЗС»
в новом источнике расходится с «12 АЗС» в уже стоящем в карточке
`eco.share` (из более раннего источника, riatomsk.ru от 6 августа) —
это не наша ошибка, а расхождение источников между собой: число из
нового источника взято в кавычки как прямая цитата собственника, а не
как наше утверждение, и старое число в `eco.share` не тронуто. (3) Ещё
один и тот же URL (riatomsk.ru/.../elke-avto-prodazha-kemerovo-tomsk,
источник 6 августа) при повторном WebFetch дал ПРОТИВОРЕЧИВЫЕ
пересказы в разных попытках (один раз «6 из 12 станций», другой раз
«вся сеть из 11 станций куплена целиком») — итог нестабилен, доверия
не заслуживает, и уже стоящий в карточке текст (проверенный раньше,
через `review.py`, дословной цитатой) не переписывается на основании
такого пересказа.

Запуск:
    python3 pipeline/fix_elke_auto_post_deal_supply_restored.py            # сухой прогон
    python3 pipeline/fix_elke_auto_post_deal_supply_restored.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_ECO_RATIONALE = (
    'Сеть одной из первых в регионе столкнулась с нестабильностью '
    'поставок бензина в июне 2026 года и была вынуждена приостановить '
    'работу заправок. Позднее часть АЗС снова заработала, но заметно '
    'подняла цены на топливо.'
)

NEW_ECO_RATIONALE = OLD_ECO_RATIONALE + (
    ' С 27 июля поставки топлива с Кемеровского НПЗ восстановлены в '
    'полном объёме и ассортименте (АИ-92, АИ-95, дизельное топливо) — '
    '180 «кубов» в сутки; к началу сентября работало семь заправок, и, '
    'по словам собственника, до конца ноября должны заработать «все 11 '
    'АЗС „Элке Авто"».'
)

NEW_SRC = ['РИА Томск', 'https://www.riatomsk.ru/article/20260903/novii-vladelets-rasshiril-set-elke-avto-v-tomske-do-7-azs']


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['g7f6d55a9']

    assert d['eco'].get('rationale') == OLD_ECO_RATIONALE, 'eco.rationale изменился: %r' % (d['eco'].get('rationale'),)
    urls = {s[1] for s in d['src']}
    assert NEW_SRC[1] not in urls, 'источник уже добавлен'

    print('g7f6d55a9: eco.rationale дополнен (восстановление поставок '
          'топлива с 27 июля, семь заправок к сентябрю, план восстановить '
          'всю сеть к ноябрю); добавлен источник')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['eco']['rationale'] = NEW_ECO_RATIONALE
    d['src'].append(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
