import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g5301e77e'

OLD_LAW_STRUCT = '—'
NEW_LAW_STRUCT = (
    'В июле 2023 года ульяновское АО «Хемпель» переименовано в АО '
    '«Литум. Ульяновск» — новый владелец, ГК «Литум», уже владел '
    'похожим активом: в августе 2022 года купил и переименовал в ООО '
    '«Литум» лакокрасочный завод норвежской Jotun в Ленинградской '
    'области. На момент публикаций (август–сентябрь 2023 года) в ЕГРЮЛ '
    'формально всё ещё был указан прежний владелец, датская «Хемпель '
    'А/С», хотя управление заводом уже перешло к «Литуму».'
)

OLD_ECO_CONTEXT = '—'
NEW_ECO_CONTEXT = (
    'Покупателем стала ГК «Литум», работающая в той же сфере; цену '
    'сделки стороны не разглашали независимо от Hempel. По словам '
    'гендиректора ГК «Литум» Андрея Дружинина, завод в Ульяновске, как '
    'и раньше, продолжит выпускать лакокрасочные покрытия для '
    'строительной, судостроительной, энергетической и нефтегазовой '
    'отраслей.'
)

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/business/918738'],
    ['73online.ru', 'https://73online.ru/r/ekaterinburgskiy_biznesmen_perezapuskaet_rabotu_ulyanovskogo_zavoda_hempel-124689'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['buyer'] is None
    assert 'buyer_name' not in deal
    assert deal['law']['struct'] == OLD_LAW_STRUCT
    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    new_src = deal['src'] + NEW_SRC

    print('=== buyer_name: станет ===')
    print('ГК «Литум»')
    print('\n=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['buyer_name'] = 'ГК «Литум»'
        deal['law']['struct'] = NEW_LAW_STRUCT
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
