# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
`ge8f111a2` («Тимур Бекмамбетов продал российское ООО "Базелевс" Лале
Рустамовой и Тимуру Асадову», 2022-12-22, Закрыта) — `law.struct`
самой карточки говорит «Сделка ещё структурируется и будет завершена в
течение нескольких месяцев», что противоречит статусу «Закрыта» на ту
же дату; дальнейшая судьба предмета не прослеживалась.

Проверено ЛИЧНО прямым WebFetch (дословные цитаты)
ko.ru/articles/timur-bekmambetov-vyshel-iz-rossiyskogo-biznesa (второй,
независимый источник о той же сделке, от того же дня):
- «Стоимость сделки не раскрывается, но известно, что она прошла на
  рыночных условиях»;
- «сделку закрыли за счёт средств, вырученных за весь 2022 год» (слова
  Рустамовой) — то есть, в отличие от RBC (уже в `src`), этот источник
  описывает сделку как уже профинансированную и закрытую в 2022 году,
  а не как продолжающую структурироваться.

Источники расходятся между собой в степени завершённости на 22 декабря
2022 года (родня уже записанного в CLAUDE.md урока «Источник может
расходиться сам с собой») — статус `status` не менялся: оба источника
согласны, что сделка состоялась, расходятся только в формулировке
«уже закрыта» vs «структурируется ещё несколько месяцев». Точная дата
фактического закрытия НЕ названа ни в одном из девяти проверенных
источников (включая ko.ru, sostav.ru, interfax.ru — RBC, основной
источник карточки, недоступен прямым WebFetch, 401).

НЕ ВНЕСЕНО: (1) точная дата закрытия — не найдена нигде; (2) более
ранняя передача 100% доли Рустамовой в марте 2022 года (до публично
анонсированной сделки 50/50 с Асадовым) — только через WebSearch-
пересказ Википедии, требует отдельной проверки WebFetch прежде чем
переносить в структурные поля; (3) финансовые показатели «Базелевс»
2024-2025 годов и партнёрство с «Национальной Медиа Группой» — только
через WebSearch-пересказ реестровых агрегаторов и вторичных изданий,
не проверено дословно; (4) судьба Тимура Бекмамбетова после продажи —
контекст о человеке, не о самой сделке, не вносится в структурные
поля; (5) официальная сумма сделки — не раскрывалась ни тогда, ни
позже, только экспертные оценки (300-500 млн ₽ по разным источникам,
не проверены дословно).

Запуск: python3 pipeline/fix_bazelevs_postdeal.py
        python3 pipeline/fix_bazelevs_postdeal.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'ge8f111a2'

OLD_ECO_CONTEXT = (
    'По словам Рустамовой, продажу Bazelevs в России готовили за '
    'несколько лет до начала спецоперации.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' Официальная сумма не раскрывалась нигде — '
    '«стоимость сделки не раскрывается, но известно, что она прошла на '
    'рыночных условиях» (Рустамова); по её же словам, «сделку закрыли '
    'за счёт средств, вырученных за весь 2022 год» — то есть, в отличие '
    'от формулировки «сделка ещё структурируется» из другого источника '
    'того же дня, сама Рустамова описывает её как уже профинансированную '
    'к концу 2022 года. Точная дата фактического закрытия не названа ни '
    'в одном источнике.'
)

OLD_SRC = [['РБК', 'https://www.rbc.ru/technology_and_media/22/12/2022/63a3455b9a794727166d9d1c?from=from_main_3']]
NEW_SRC = OLD_SRC + [['Компания', 'http://www.ko.ru/articles/timur-bekmambetov-vyshel-iz-rossiyskogo-biznesa/']]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
