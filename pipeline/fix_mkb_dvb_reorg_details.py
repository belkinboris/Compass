# -*- coding: utf-8 -*-
"""Месячная очередь качества, 11 сентября 2026 — карточка `g998e5eb5`
(«МКБ завершил присоединение Дальневосточного банка», реорганизация,
август 2026) держалась на одной статье Коммерсанта и не называла ни
условий конвертации акций, ни судьбы юрлица ДВБ после присоединения.
`law.terms` был пуст.

Личный WebFetch подтвердил дословно:
- Finance.mail.ru
  (https://finance.mail.ru/article/sliyanie-v-tsifrah-69206895/, 29 апреля
  2026): «Одна обыкновенная и привилегированная акция ДВБ конвертируется
  в 141,3 обыкновенной акции МКБ»; «Планируется разместить 1,475 млрд
  обыкновенных акций МКБ»; «получат право требовать выкупа принадлежащих
  им акций МКБ по цене 10,35 ₽ за акцию».
- Abn.agency
  (https://abn.agency/2026/06/22/dalnevostochnyj-bank-prekratit-deyatelnost-posle-prisoedineniya-k-mkb/,
  22 июня 2026): «после завершения процедуры деятельность АО
  «Дальневосточный банк» будет прекращена»; «Правопреемником всех его
  прав и обязанностей станет ПАО «Московский кредитный банк»».

Согласование ЦБ (консультанты — не найдены ни в одном источнике): реестр
Банка России по МКБ показывает согласование новой редакции устава
23.07.2026 (зарегистрировано 01.08.2026) — предшествует дате закрытия
(3 августа) и на момент публикации Коммерсанта в самой статье не
называлось; сама запись реестра не датирована отдельной публикацией и не
даёт дословной цитаты для law.appr — оставлено как есть (честная пустота
надёжнее непроверяемой парафразы записи реестра).

Запуск:
    python3 pipeline/fix_mkb_dvb_reorg_details.py            # сухой прогон
    python3 pipeline/fix_mkb_dvb_reorg_details.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_LAW_TERMS = '—'
NEW_LAW_TERMS = (
    'Планируется разместить 1,475 млрд обыкновенных акций МКБ. Одна '
    'обыкновенная и привилегированная акция ДВБ конвертируется в 141,3 '
    'обыкновенной акции МКБ. Акционеры, которые проголосуют против или '
    'не примут участия в голосовании по вопросу реорганизации, получат '
    'право требовать выкупа принадлежащих им акций МКБ по цене 10,35 ₽ '
    'за акцию.'
)

OLD_LAW_STRUCT = (
    'Акции ДВБ конвертировали в акции Московского кредитного банка. Ради '
    'этого МКБ объявил допэмиссию, которая увеличила его капитал на 4,4%.'
)

NEW_LAW_STRUCT = OLD_LAW_STRUCT + (
    ' После завершения процедуры деятельность АО «Дальневосточный банк» '
    'прекращается, правопреемником всех его прав и обязанностей '
    'становится МКБ.'
)

NEW_SRC = [
    ['Finance.mail.ru', 'https://finance.mail.ru/article/sliyanie-v-tsifrah-69206895/'],
    ['Abn.agency', 'https://abn.agency/2026/06/22/dalnevostochnyj-bank-prekratit-deyatelnost-posle-prisoedineniya-k-mkb/'],
]


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['g998e5eb5']

    assert d['law'].get('terms') == OLD_LAW_TERMS, 'law.terms уже занят: %r' % (d['law'].get('terms'),)
    assert d['law'].get('struct') == OLD_LAW_STRUCT, 'law.struct изменился: %r' % (d['law'].get('struct'),)
    urls = {s[1] for s in d['src']}
    for src in NEW_SRC:
        assert src[1] not in urls, 'источник уже добавлен: %s' % src[1]

    print('g998e5eb5: law.terms заполнен (курс конвертации акций, цена '
          'выкупа для несогласных); law.struct дополнен (прекращение '
          'юрлица ДВБ, правопреемство МКБ); добавлено 2 источника')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['law']['terms'] = NEW_LAW_TERMS
    d['law']['struct'] = NEW_LAW_STRUCT
    d['src'].extend(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
