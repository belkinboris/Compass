# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g2075a46d
(Balchug Capital получил 17% в девелопере Malltech). Дельта-поиск нашёл
признаки того, что дата сделки стоит с ошибкой на год, и опечатку в имени
основателя фонда.

ДАТА. Карточка несёт «2024-08-08», а единственный источник
(vedomosti.ru, проверено лично прямым WebFetch,
https://www.vedomosti.ru/realty/articles/2025/09/03/1136115-...) —
статья ОПУБЛИКОВАНА 3 сентября 2025 года и говорит: «Сделку закрыли 8
августа» — год явно не назван в этом предложении, НО статья описывает
это как недавнее событие (репортаж по факту получения выписки из
кипрского реестра), а следующий абзац того же материала называет точную
дату последующего события — «20 августа в совет директоров Malltech
вошли...» — тем же летом, за две недели до публикации. Публикация в
сентябре 2025 о событии «8 августа» без указания года достоверно значит
август 2025-го, а не годом раньше: в русской деловой прессе дата без года
всегда означает текущий/недавний год относительно даты публикации,
второй такой сделки (тот же покупатель, тот же процент, тот же продавец)
в источниках не встречается. Меняет ГОД, а не день/месяц — по правилу
CLAUDE.md («review.py не умеет переносить сделку в другой год») это не
проходит через таблицу FIXES, поэтому отдельный скрипт с assert на
исходное значение.

ИМЯ. Карточка несёт «Давида Аморяна» — источник (та же статья,
проверено лично) называет его «Давидом Амаряном» (David Amaryan,
бывший сотрудник «Тройки Диалог»). Опечатка на одну букву, но имя
человека должно быть точным.

ДОПОЛНЕНО (eco.context, новое поле — было «—»): состав нового совета
директоров («20 августа в совет директоров Malltech вошли сотрудники
Balchug Capital Сурен Багдасарян, Александр Хачатурян и Ашхе Танян, а
гендиректор девелопера Ярослав Халявин и его управляющий директор Кирилл
Степанов — покинули совет») и версия консультанта о происхождении доли,
процитированная с явной атрибуцией как ПРЕДПОЛОЖЕНИЕ, а не факт:
«Balchug Capital мог получить долю через покупку российского
подразделения Goldman Sachs — «Голдман сакс банк», полагает один из его
партнеров».

НЕ включены: доля Goldman Sachs в самом Malltech в 2018 году (28%) — эта
деталь всплыла в сводке сабагента, но при личной проверке WebFetch
именно в этой статье её не нашлось; консультанты сделки, точная причина
продажи Bardsley/Суздальцевым — не нашлись ни в одном источнике.
Цифра «59,24% контроля к концу 2025 года», которую WebSearch-сводка
настойчиво выдавала за факт, отклонена — прямая проверка retail.ru
показала, что такой доли в документе нет вовсе (похоже на галлюцинацию
модели-суммаризатора).

Запуск: python3 pipeline/fix_balchug_malltech_date_and_name.py
        python3 pipeline/fix_balchug_malltech_date_and_name.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g2075a46d'

OLD_DATE = '2024-08-08'
NEW_DATE = '2025-08-08'

OLD_EXTRA = (
    '8 августа Balchug Capital стал прямым владельцем 17% Malltech '
    'согласно реестру юридических лиц Кипра. В совет директоров компании '
    'вошли топ-менеджеры армянского инвестфонда Давида Аморяна. '
    'Предполагается, что косвенно фонду принадлежит около 74% компании '
    'через сейшельские офшоры. Возможно, доля получена после приобретения '
    'российского бизнеса Goldman Sachs.'
)
NEW_EXTRA = OLD_EXTRA.replace('Давида Аморяна', 'Давида Амаряна')
assert NEW_EXTRA != OLD_EXTRA

OLD_CONTEXT = (
    'Malltech была создана в 2004 году Росевробанком (впоследствии стал '
    'частью Совкомбанка) и до 2016 года носила название '
    '«Росевродевелопмент».'
)
CONTEXT_ADDITION = (
    ' 20 августа 2025 года в совет директоров Malltech вошли сотрудники '
    'Balchug Capital — «Сурен Багдасарян, Александр Хачатурян и Ашхе '
    'Танян», а гендиректор девелопера Ярослав Халявин и его управляющий '
    'директор Кирилл Степанов совет покинули. Происхождение доли до конца '
    'не выяснено: «Balchug Capital мог получить долю через покупку '
    'российского подразделения Goldman Sachs — «Голдман сакс банк», '
    'полагает один из его партнеров» (Ведомости) — это версия одного из '
    'партнёров фонда, а не подтверждённый факт.'
)
NEW_CONTEXT = OLD_CONTEXT + CONTEXT_ADDITION

NEW_SRC_LABEL_ONLY_CHECK = None  # источник уже стоит в src (та же статья)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['date'] == OLD_DATE
    assert deal['extra'] == OLD_EXTRA
    assert deal['eco']['context'] == OLD_CONTEXT

    print(f'=== date: {OLD_DATE!r} -> {NEW_DATE!r} ===')
    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)

    if write:
        deal['date'] = NEW_DATE
        deal['extra'] = NEW_EXTRA
        deal['eco']['context'] = NEW_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
