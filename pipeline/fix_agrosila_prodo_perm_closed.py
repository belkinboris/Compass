import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g0c19cd78'

# Текущее состояние диска (после первого, ошибочного захода этого же
# скрипта): status уже «Закрыта», eco.context уже несёт факт закрытия,
# но ВМЕСТЕ с упоминанием ФАС, которое нужно перенести в law.appr.
CURRENT_ECO_CONTEXT = (
    'Годом ранее покупкой пермского предприятия, кроме «Агросилы», '
    'интересовались агрохолдинг «Комос групп» из Удмуртии, '
    'агропромышленный холдинг «Дороничи» из Кировской области и группа '
    'агропредприятий «Ресурс» из Ставропольского края. Но в августе в ГК '
    '«Продо» заявили, что продавать предприятие не планируют. Сделка всё '
    'же закрылась: 4 апреля 2023 года «Агросила» сообщила о завершении '
    'покупки 100% акций АО «Продо Птицефабрика Пермская», а 11 апреля '
    '2023 года её задним числом одобрила ФАС, не увидев угрозы '
    'конкуренции на рынке мяса птицы.'
)
NEW_ECO_CONTEXT = (
    'Годом ранее покупкой пермского предприятия, кроме «Агросилы», '
    'интересовались агрохолдинг «Комос групп» из Удмуртии, '
    'агропромышленный холдинг «Дороничи» из Кировской области и группа '
    'агропредприятий «Ресурс» из Ставропольского края. Но в августе в ГК '
    '«Продо» заявили, что продавать предприятие не планируют. Сделка всё '
    'же закрылась: 4 апреля 2023 года «Агросила» сообщила о завершении '
    'покупки 100% акций АО «Продо Птицефабрика Пермская».'
)

OLD_LAW_APPR = 'Публично не сообщалось'
NEW_LAW_APPR = (
    'ФАС одобрила сделку 11 апреля 2023 года — уже после сообщения о её '
    'закрытии, — не увидев угрозы конкуренции на рынке мяса '
    'сельскохозяйственной птицы.'
)

CURRENT_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/5841450'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/5914007'],
    ['NewsKo', 'https://www.newsko.ru/news/nk-7639279.html'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == 'Закрыта'
    assert deal['eco']['context'] == CURRENT_ECO_CONTEXT
    assert deal['law']['appr'] == OLD_LAW_APPR
    assert deal['src'] == CURRENT_SRC

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== law.appr: станет ===')
    print(NEW_LAW_APPR)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['law']['appr'] = NEW_LAW_APPR
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
