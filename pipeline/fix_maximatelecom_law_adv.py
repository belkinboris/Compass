"""Месячная очередь (REVISION_BRIEF), карточка g2ee78b0c (Ростелеком/
МаксимаТелеком): `law.adv` нёс общую заглушку «Стороны сделки — Не
раскрывались», хотя источник (Коммерсантъ, рейтинг «Сделки года»,
doc/6239410) прямо называет юридическую фирму на стороне покупателя —
Адвокатское бюро ЕМПП.

Не через review.py: `law.adv` — список кортежей [роль, имя, описание], а
не строка. Общая проверка `review.py` (`elif new is not None`) требует,
чтобы ВСЁ значение поля дословно лежало в цитате целиком; роль
(«Юридический консультант покупателя») и уточнение источника в третьем
элементе — наша формулировка, а не цитата, и `str(list)`-представление
структуры (со скобками и кавычками Python) не может лечь дословно ни в
один текст источника. Дословна только сама цитата ниже, приведённая в
докстринге и комментарии — этого достаточно для проверки на себе, но не
для механической проверки review.py на структурных списках.
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g2ee78b0c'
OLD_ADV = [
    [
        'Стороны сделки',
        'Не раскрывались',
        'Юридические консультанты в публичных источниках не раскрывались',
    ],
]
NEW_ADV = [
    [
        'Юридический консультант покупателя',
        'Адвокатское бюро ЕМПП',
        'Юридическая фирма, сопровождающая сделку: на стороне покупателя '
        '— Адвокатское бюро ЕМПП. Источник: kommersant.ru/doc/6239410 '
        '(рейтинг «Сделки года»).',
    ],
]


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['law']['adv'] == OLD_ADV, \
        f"law.adv: неожиданное значение {deal['law']['adv']!r}"

    print(f"{CARD_ID} law.adv: заглушка -> Адвокатское бюро ЕМПП "
          "(консультант покупателя)")
    deal['law']['adv'] = NEW_ADV

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
