SELLER_FIX = ("ektos", "Composite System Ltd (Британские Виргинские острова)")

# Qiwi: рассрочка и залог уже названы в `extra` — переносим ровно эти два
# предложения в пустое `eco.fin`, остальной текст `extra` не трогаем.
QIWI_ID = "g0fadc207"
QIWI_SENTENCES = [
    "Оплата предусмотрена в рассрочку: первый транш — 11,875 млрд ₽ в "
    "течение 4 месяцев, остаток — четырьмя равными долями начиная с Q4 2024.",
    "В обеспечение выплат 100% акций покупателя (Fusion Factor) заложены "
    "в пользу Qiwi plc.",
]


def main(write: bool) -> int:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    cards = {d["id"]: d for d in data["deals"]}
    applied = []

    for cid, sa, sf, quote, da, df in MOVES:
        card = cards[cid]
        src = card.get(sa) if sa != "top" else card
        cur = (src or {}).get(sf) if sa != "top" else card.get(sf)
        assert cur and quote in cur, "%s.%s: текст не найден дословно" % (cid, sf)
        dst = card.setdefault(da, {}) if da != "top" else card
        old_dst = dst.get(df)
        new_dst = quote if not old_dst or old_dst in ("—", "-", "") else (old_dst + " " + quote)
        applied.append((cid, sa + "." + sf, da + "." + df, quote[:60]))
        if write:
            dst[df] = new_dst
            remainder = cur.replace(quote, "").strip()
            src[sf] = remainder if remainder else "—"

    ektos = cards[SELLER_FIX[0]]
    assert ektos.get("seller") is None, "у ЭКТОСа уже есть продавец"
    fin = (ektos.get("eco") or {}).get("fin") or ""
    assert "Composite System Ltd" in fin
    applied.append((SELLER_FIX[0], "eco.fin", "seller", SELLER_FIX[1]))
    if write:
        ektos["seller"] = SELLER_FIX[1]
        ektos["eco"]["fin"] = "—"

    qiwi = cards[QIWI_ID]
    extra = qiwi.get("extra") or ""
    for s in QIWI_SENTENCES:
        assert s in extra, "Qiwi: предложение не найдено дословно"
    assert (qiwi.get("eco") or {}).get("fin") in ("—", "-", "", None)
    applied.append((QIWI_ID, "extra", "eco.fin", "рассрочка + залог"))
    if write:
        new_extra = extra
        for s in QIWI_SENTENCES:
            new_extra = new_extra.replace(s, "").strip()
        import re
        new_extra = re.sub(r"\s+", " ", new_extra)
        qiwi["extra"] = new_extra
        qiwi["eco"]["fin"] = " ".join(QIWI_SENTENCES)

    print("Перенесено: %d" % len(applied))
    for cid, src, dst, snippet in applied:
        print("   %-24s %s → %s   «%s…»" % (cid, src, dst, snippet))

    if not write:
        print("\n(сухой прогон; чтобы записать — --write)")
        return 0
    DATA.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    print("\nзаписано")
    return 0


if __name__ == "__main__":
    sys.exit(main("--write" in sys.argv))
