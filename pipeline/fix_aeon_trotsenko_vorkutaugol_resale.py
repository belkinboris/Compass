import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g87d0201c'

OLD_EXTRA = ''
NEW_EXTRA = (
    '«Воркутауголь» перепродан дальше — АО «Маяк» (связано с кузбасской '
    'группой «Каракан Инвест») приобрело 85% ООО Группа «Русская '
    'энергия», которой принадлежит угольная компания (согласование — '
    'см. «Согласования» ниже). Второй крупный проект, доставшийся '
    'структурам Александра Орехова, — Сырадасайское месторождение на '
    'Таймыре («Северная Звезда») — заморожен с июля 2025 года '
    '(стоимость 58,1 млрд руб., причины — финансовые сложности '
    'инвестора и земельный спор), возобновление планируется не раньше '
    'июля 2028 года. Химические активы, которые Троценко не продал в '
    'этой сделке, — это 60% ГК «Азот»: позже они оказались у того же '
    'Александра Орехова, который довёл долю до 100% (см. отдельную '
    'карточку о выходе Михаила Федяева из «Азота»).'
)

OLD_LAW_APPR = 'Публично не сообщалось'
NEW_LAW_APPR = (
    '18 марта 2026 года ФАС одобрила перепродажу «Воркутаугля» другому '
    'покупателю (АО «Маяк», связано с группой «Каракан Инвест») — это '
    'согласование относится к более поздней, отдельной сделке на том '
    'же активе, а не к продаже 2023 года, которой посвящена эта '
    'карточка.'
)

NEW_SRC = [
    ['bnkomi.ru', 'https://www.bnkomi.ru/data/news/196746/'],
    ['ngs24.ru', 'https://ngs24.ru/text/economics/2026/07/15/76534358/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA
    assert deal['law']['appr'] == OLD_LAW_APPR

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== law.appr: станет ===')
    print(NEW_LAW_APPR)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['law']['appr'] = NEW_LAW_APPR
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
