"""Приток, 12:20 МСК 30 сентября 2026: РИА Недвижимость сообщила, что
«Дом.РФ» выставил на конкурс главный корпус бывшего Ижевского оружейного
завода (памятник федерального значения, проезд Дерябина, 2/3) —
стартовая цена 50,79 млн ₽, заявки до 26 октября, конкурс 30 октября.
Победитель обязан реставрировать здание за 7 лет, доступно льготное
финансирование (9% или 6% под гостиницу). Ворота не пропустили черновик
автоматически. Собрал вручную.

Саб-агент нашёл содержательную корроборацию за пределами самой статьи:
realty.rbc.ru (28 марта 2025) — это часть программы «Дом.РФ» по поручению
Путина: к 2030 году восстановить 1000 объектов культурного наследия,
весной 2025 на аукцион готовили уже 44 памятника; susanin.news (27 ноября
2025) — передача здания в управление «Дом.РФ» ещё в ноябре 2025, с
комментарием главы правительства Удмуртии Романа Ефимова (пересказан не
дословно — цитата длиннее 6 слов). `--mark-deep`, не `--mark-read`:
реально нашли и прочитали источники сверх привязанного.

Здание — «Дом.РФ» уже есть в базе как профиль компании (`gb2b066c3`).

Запуск: python3 pipeline/fix_add_izhevsk_arms_factory_card.py [--write]
"""
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'ingest'))

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')


def main(write=False):
    import promote

    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    ids = {c['id'] for c in data['deals']}
    new_id = promote.new_id(ids)

    draft = {
        'date': '2026-09-30',
        'title': '«Дом.РФ» выставил на конкурс здание Ижевского оружейного завода',
        'ind': 'Недвижимость',
        'type': 'Продажа с торгов',
        'status': 'Обсуждается',
        'sum': '50,79 млн ₽',
        'seller': '«Дом.РФ»',
        'asset': 'главный корпус бывшего Ижевского оружейного завода (объект культурного наследия федерального значения, 21,1 тыс. м², участок 0,94 га)',
        'src': [['РИА Недвижимость', 'https://realty.ria.ru/20260930/izhevsk-2121177636.html']],
        'events': [
            {'kind': 'negotiations', 'date': '2026-09-30', 'title': 'Конкурс объявлен',
             'note': 'Заявки на конкурс принимаются до 26 октября, сам конкурс — 30 октября 2026 года.',
             'source': ['РИА Недвижимость', 'https://realty.ria.ru/20260930/izhevsk-2121177636.html']},
        ],
    }
    card = promote.to_card(draft, new_id)
    card['seller_id'] = 'gb2b066c3'
    card['eco']['sum'] = draft['sum']
    card['eco']['context'] = (
        'Здание — визитная карточка Ижевска, вокруг него формировался город; расположено '
        'на берегу Ижевского пруда. Победитель конкурса обязан за семь лет провести '
        'реставрацию и сохранение здания; для этого доступно льготное финансирование — '
        '9% годовых, или 6%, если объект приспособят под гостиницу. Это часть более '
        'широкой программы «Дом.РФ»: по поручению Владимира Путина до 2030 года в России '
        'должна быть восстановлена тысяча объектов культурного наследия, весной 2025 '
        'года институт готовил к аукциону 44 памятника истории и культуры в 29 регионах '
        'страны. Само здание передали в управление «Дом.РФ» ещё в ноябре 2025 года — '
        'по словам главы правительства Удмуртии Романа Ефимова, инвестор обязан '
        'полностью сохранить исторический облик, а строить рядом новые капитальные '
        'здания запретит закон.'
    )
    card['law']['struct'] = (
        'Здание не используется с 1990-х годов, статус объекта культурного наследия '
        'федерального значения присвоен в 1995 году. Концепция редевелопмента для '
        'будущего инвестора уже подготовлена — её разработал победитель всероссийского '
        'конкурса, прошедшего в 2024 году.'
    )
    card['themes'] = ['Продажа с торгов', 'Недвижимость']
    card['added'] = '2026-09-30'

    data['deals'].append(card)
    print('Добавлена карточка %s: %s' % (new_id, card['title']))

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
