# -*- coding: utf-8 -*-
"""15 августа 2026: три карточки из партии дочитывания тонких карточек несли
не просто неточный день, а НЕВЕРНЫЙ ГОД — событие целиком перепутано с
соседним годом того же многолетнего сюжета. Тот же класс, что
`fix_osnova_sviblovo_date.py`/`fix_nordline_arctic_sum_misattribution.py`, и
по той же причине не через `review.py` (`date_is_supported()` намеренно не
даёт менять год через обычную таблицу FIXES — перенос года есть утверждение
нового, а не уточнение известного).

  c1aa8b20d (Fesco/Петропавловск-Камчатский порт). Карточка стояла с
    заглушкой «2022» — годом общей волны конфискаций после начала военных
    действий. Настоящее событие («Fesco получила в управление порт») —
    2025 год: национализация по иску Генпрокуратуры (коррупционное дело,
    а не санкционное) прошла в мае 2025-го (Ленинский райсуд Владивостока),
    передача 38 камчатских активов началась в сентябре 2025-го, а именно
    порт и пароходство Fesco получила 20 октября 2025 года (Ведомости).
    Статус/стороны не трогаем (административная передача в управление, а
    не купля-продажа — тот же класс карточек, что ce56cdefd/Silgan, там
    статус и стороны тоже не проставлялись).

  ce6b8c447 (Carlsberg/«Балтика»). Карточка стояла с заглушкой «2022» — а
    претензия и требование компенсации, которым посвящена карточка,
    целиком относятся к 2023 году: указ о временном управлении — 16 июня
    2023, расторжение рамочного соглашения с «Арнестом» — конец августа
    2023, уведомления о споре по трём международным соглашениям —
    середина октября 2023, сама статья с суммой претензии (71 млрд руб.) —
    8 ноября 2023 (dp.ru, перепечатка Интерфакса; forbes.ru — источник
    карточки — недоступен в этой сессии, но текст идентичен). Здесь, в
    отличие от Fesco, есть реальные стороны несостоявшейся сделки —
    заполняем seller/target/buyer_name и статус «Не состоялась»
    (соглашение расторгнуто), чего раньше не было вовсе.

  c9bad29b7 (Ingka/Газпромбанк, ТЦ «Мега»). Год не менялся (2023), но
    карточка датой и статусом описывала САМОЕ НАЧАЛО переговоров
    (17.02.2023, «Обсуждается») — а сделка тем временем закрылась:
    Газпромбанк выкупил все 14 ТЦ «Мега» 28 сентября 2023 года (Ведомости).
    Статус и eco.share правятся отдельно через `review.py`
    (`fixes/batch_d_n07.py`, тот же источник vedomosti.ru уже добавлен в
    src); здесь — дата, заголовок, покупатель и оценка суммы, для которых
    в FIXES-таблице подходящей записи не было вовсе.

Профили сторон (Газпромбанк, Ingka Centres, Carlsberg Group, «Балтика»)
уже есть в базе — проверено перед записью, создавать не нужно. Для
«Арнеста» отдельного профиля материнской группы нет (только «Арнест
Юнирусь» — другое юрлицо той же группы, не факт что то же самое), поэтому
несостоявшийся покупатель «Балтики» записан текстом в `buyer_name`, а не
ссылкой на профиль.

Запуск:
    python3 pipeline/fix_r10_major_date_corrections.py            # сухой прогон
    python3 pipeline/fix_r10_major_date_corrections.py --write    # запись
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')


def main(argv):
    data = json.load(open(DATA, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}

    # --- c1aa8b20d: Fesco / Петропавловск-Камчатский порт --------------
    fesco = by_id['c1aa8b20d']
    assert fesco.get('date') == '2022', 'c1aa8b20d: дата уже другая: %r' % fesco.get('date')
    assert fesco.get('eco') == {}, 'c1aa8b20d: eco уже не пуст: %r' % fesco.get('eco')

    # --- ce6b8c447: Carlsberg / «Балтика» -------------------------------
    carlsberg = by_id['ce6b8c447']
    assert carlsberg.get('date') == '2022', 'ce6b8c447: дата уже другая: %r' % carlsberg.get('date')
    assert carlsberg.get('title') == 'Carlsberg требует компенсацию за срыв продажи «Балтики» России'
    for field in ('seller', 'target', 'buyer_name', 'status'):
        assert carlsberg.get(field) is None, 'ce6b8c447: %s уже не пусто: %r' % (field, carlsberg.get(field))

    # --- c9bad29b7: Ingka / Газпромбанк, ТЦ «Мега» ----------------------
    ingka = by_id['c9bad29b7']
    assert ingka.get('date') == '2023-02-17', 'c9bad29b7: дата уже другая: %r' % ingka.get('date')
    assert ingka.get('title') == ('Ingka ищет покупателя на портфель недвижимости в России '
                                   '(торговые центры «Мега» и объекты IKEA)')
    for field in ('seller', 'target', 'buyer', 'sum'):
        assert ingka.get(field) is None, 'c9bad29b7: %s уже не пусто: %r' % (field, ingka.get(field))

    print('c1aa8b20d: date 2022 -> 2025-10-20; + eco.context/eco.val/law.appr')
    print('ce6b8c447: date 2022 -> 2023-11-08; title/seller/target/buyer_name/status/eco.*/law.*')
    print('c9bad29b7: date 2023-02-17 -> 2023-09-28; title/seller/buyer/sum')

    if '--write' not in argv:
        print('\nСухой прогон. Запись — с ключом --write.')
        return 0

    # === c1aa8b20d ===
    fesco['date'] = '2025-10-20'
    fesco['eco'] = {
        'context': ('Процесс передачи управления начался в сентябре 2025 года, когда FESCO '
                    'получила первую партию предприятий, принадлежащих Росимуществу на '
                    'территории Камчатского края. Как передает «Интерфакс», общее количество '
                    'камчатских активов, переданных транспортной группе, достигло 38 компаний.'),
        'val': ('Капитализация активов транспортного узла в порту Петропавловска-Камчатского '
                'составляет ₽16,7 млрд по данным иска (по оценке)'),
    }
    fesco['law'] = {
        'appr': ('Петропавловск-Камчатский морской торговый порт национализирован по '
                 'решению Ленинского районного суда Владивостока, принятого в мае 2025 года. '
                 'Суд удовлетворил иск Генеральной прокуратуры России о конфискации '
                 'имущества, полученного в нарушение законодательства о противодействии '
                 'коррупции.'),
    }

    # === ce6b8c447 ===
    carlsberg['date'] = '2023-11-08'
    carlsberg['title'] = 'Carlsberg требует у России компенсацию за срыв продажи «Балтики»'
    carlsberg['seller'] = 'carlsberg'          # Carlsberg Group
    carlsberg['target'] = 'baltika'            # Пивоваренная компания «Балтика»
    carlsberg['buyer_name'] = 'группа «Арнест»'
    carlsberg['status'] = 'Не состоялась'
    carlsberg['eco'] = {
        'rationale': ('Carlsberg Group минувшим летом планировала продать активы в России, за '
                      '«Балтику» датчане планировали получить около 71 млрд рублей, '
                      'утверждают источники Интерфакса. По их словам, как и в случае с '
                      'Heineken, покупателем «Балтики» должна была выступить группа '
                      '«Арнест».'),
        'context': ('Carlsberg направил властям письмо, в котором классифицировал действия РФ '
                    'как нарушения обязательств по двустороннему инвестиционному соглашению. '
                    'В Минфине не нашли оснований для компенсации убытков датчанам.'),
    }
    carlsberg['law'] = {
        'appr': ('16 июня 2023 года президент России Владимир Путин подписал указ о передаче '
                 'пивоваренного гиганта во временное управление Росимущества.'),
        'struct': ('Рамочное соглашение со структурами «Арнеста», поясняют собеседники '
                   'агентства, было расторгнуто в связи с введением в «Балтике» режима '
                   'временного управления со стороны Росимущества.'),
        'terms': ('В середине октября Carlsberg направил в Кабмин официальные «уведомления о '
                  'споре» по трём международным соглашениям. Датская компания предложила '
                  'урегулировать спор в ближайшее полугодие, начиная с 13 октября, в '
                  'противном случае датчане пригрозили международным судом.'),
    }

    # === c9bad29b7 ===
    ingka['date'] = '2023-09-28'
    ingka['title'] = 'Газпромбанк выкупил у Ingka все торговые центры «Мега» в России'
    ingka['seller'] = 'g088c1281'   # Ingka Centres (портфель ТЦ «Мега»)
    ingka['buyer'] = 'gf1f56e08'    # Газпромбанк
    ingka['sum'] = '$2 млрд (по оценке)'
    ingka.setdefault('eco', {})['val'] = (
        'Сумма сделки в текущих условиях и с учетом дисконтов вряд ли превысила $2 млрд '
        '(193 млрд руб. по текущему курсу), полагает генеральный директор '
        '«Infoline-аналитики» Михаил Бурмистров (по оценке; сама сделка сумму не '
        'раскрывала)')

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('ЗАПИСАНО.')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
