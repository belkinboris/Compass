# -*- coding: utf-8 -*-
"""Месячная очередь качества, 11 сентября 2026 — карточка `g35357328`
(«ВТБ продал московский отель Holiday Inn в Сокольниках», июль 2026)
уже несла описание здания и оценку суммы, но не называла ИСТОРИЮ
происхождения актива и то, что это ПОСЛЕДНИЙ гостиничный объект ВТБ.

Личный WebFetch подтвердил дословно:
- Investing.ru (https://ru.investing.com/news/general-news/article-3320645,
  со ссылкой на РБК): «ВТБ стал владельцем Holiday Inn в результате
  присоединения к нему Банка Москвы, к которому актив перешел, в свою
  очередь, от дочерней компании «Лизингбизнес-сервис». В 2001 году она
  приобрела здание гостиницы и право долгосрочной аренды земельного
  участка под ней, заплатив за это порядка $20 млн... Еще около $70 млн
  компания вложила в завершение строительства отеля и в его оснащение».
- Newkuban.ru (https://newkuban.ru/news/260791385/): «"Банк Москвы"
  через свою "дочку" "Лизингбизнес-сервис" приобрел на торгах
  недостроенное здание отеля (готовность составляла 90%)».
- Коммерсантъ (https://www.kommersant.ru/doc/8846212): «Гостиница была
  последним гостиничным активом банка»; «После этой сделки банк продал
  все гостиничные объекты».

Покупатель НЕ УСТАНОВЛЕН ни одним из проверенных источников (все
называют его только описательно — «группа профессиональных инвесторов
в высокотехнологичные активы») — это честная пустота, не заполняется.

Запуск:
    python3 pipeline/fix_vtb_holiday_inn_ownership_history.py            # сухой прогон
    python3 pipeline/fix_vtb_holiday_inn_ownership_history.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_ECO_CONTEXT = (
    'Отель под управлением гостиничного оператора Holiday Inn открылся '
    'в Сокольниках в 2006 году. Его общая площадь оценивается в 45,5 '
    'тыс. кв. м, в отеле 523 номера площадью от 25 до 78 кв. м.'
)

NEW_ECO_CONTEXT = OLD_ECO_CONTEXT + (
    ' Здание отеля в 2001 году приобрела «дочка» Банка Москвы '
    '«Лизингбизнес-сервис» — на торгах, при готовности 90%, заплатив за '
    'сам объект около $20 млн и ещё около $70 млн вложив в завершение '
    'строительства и оснащение; после присоединения Банка Москвы к ВТБ '
    'актив перешёл банку. Эта сделка — последний гостиничный объект в '
    'портфеле ВТБ: после неё банк полностью вышел из гостиничного '
    'бизнеса.'
)

NEW_SRC = [
    ['Investing.ru', 'https://ru.investing.com/news/general-news/article-3320645'],
    ['Newkuban.ru', 'https://newkuban.ru/news/260791385/'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8846212'],
]


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['g35357328']

    assert d['eco'].get('context') == OLD_ECO_CONTEXT, 'eco.context изменился: %r' % (d['eco'].get('context'),)
    urls = {s[1] for s in d['src']}
    for src in NEW_SRC:
        assert src[1] not in urls, 'источник уже добавлен: %s' % src[1]

    print('g35357328: eco.context дополнен (история актива с 2001 года, '
          'полный выход ВТБ из гостиничного бизнеса); добавлено 3 источника')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['eco']['context'] = NEW_ECO_CONTEXT
    d['src'].extend(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
