import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g68500c4a'

OLD_ECO_TARGET_FIN = '—'
NEW_ECO_TARGET_FIN = (
    'На момент сделки (интервью председателя совета директоров Михаила '
    'Лифшица, 30.03.2023): портфель заказов — около 90 млрд ₽, выручка '
    'за 2022 год выросла примерно на 30% до 12,5 млрд ₽, прибыль — 1,1 '
    'млрд ₽.'
)

OLD_ECO_CONTEXT = (
    'До 2018 года «Ренова» владела долей в 80% акций УТЗ. Тогда в '
    'апреле ГК и Вексельберг попали под американские санкции, а в '
    'сентябре компания снизила свою долю в уставном капитале завода до '
    '49%. Лифшиц стал держателем 20% акций, 16% получил Евгений Белов, '
    '15% — ООО «Легаси Медиа»'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + '. Меньше чем через год после этой сделки завод '
    'перешёл к следующему владельцу: в июле 2023 года «Мосэлектрощит» и '
    'связанный с ним Ковровский электротехнический завод передали 100% '
    'ООО «УТЗ Актив» в залог структуре «Интер РАО» (ООО «Актив-Энергия»), '
    'а в марте 2024 года «Интер РАО» обратила залог в собственность и '
    'завершила приобретение УТЗ.'
)

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/business/912088'],
    ['Интерфакс', 'https://www.interfax.ru/business/952888'],
    ['Mergers.ru', 'https://mergers.ru/news/Inter-RAO-zakryla-sdelku-po-pokupke-Uralskogo-turbinnogo-zavoda-83097'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['target_fin'] == OLD_ECO_TARGET_FIN
    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    existing_urls = {s[1] for s in deal['src']}
    add_src = [s for s in NEW_SRC if s[1] not in existing_urls]
    new_src = deal['src'] + add_src

    print('=== eco.target_fin: станет ===')
    print(NEW_ECO_TARGET_FIN)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    if add_src:
        print('\n=== src: добавится ===')
        for s in add_src:
            print(s)

    if write:
        deal['eco']['target_fin'] = NEW_ECO_TARGET_FIN
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
