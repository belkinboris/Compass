import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g1f098415'

OLD_LAW_STRUCT = '—'
NEW_LAW_STRUCT = (
    'Покупателем формально выступило АО «Аквалайф ресурс» (Троицк '
    'Московской области, зарегистрировано в 2015 году), принадлежащее '
    'ООО «Технологии управления» — структуре, которая имеет 11,11% в '
    'ООО «УК «Черноголовка»». Ранее воронежским заводом владела '
    'люксембургская Kellogg Lux VI S.a.r.l.'
)

OLD_LAW_TERMS = '—'
NEW_LAW_TERMS = (
    'По данным Telegram-канала Baza (не подтверждено сторонами '
    'официально), права на поставку Pringles в Россию в сделку не '
    'вошли — «Черноголовка» планирует выпускать чипсы по собственной '
    'рецептуре.'
)

OLD_EXTRA = (
    'Сделка по продаже российского бизнеса Kellogg Company (ООО '
    '«Келлогг Рус», управляющего тремя заводами в Воронеже, Пскове и '
    'Вязьме) компании ГК «Черноголовка». Закрыта 13 июля 2023 года.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Компания продолжила выпускать сухие завтраки марки Extra и '
    'бренды Dinosaurs, Unicorn и Choco Zavr; с 20 сентября 2023 года '
    'ООО «Келлогг Рус» переименовано в ООО «Любятово». На всех трёх '
    'заводах работало 1780 человек (данные пресс-службы на середину '
    'июля 2023 года). Финансовые показатели после сделки выросли: '
    'выручка «Любятово» — 7,84 млрд ₽ (2023) → 10,54 млрд ₽ (2024, +34%) '
    '→ 13,2 млрд ₽ (2025, +25%); чистая прибыль — 262,77 млн ₽ (2023) → '
    '496,19 млн ₽ (2024) → 846,8 млн ₽ (2025). На воронежском заводе '
    'работают четыре производственные линии, выпускается 50 наименований '
    'продукции.'
)

NEW_SRC = [
    ['Abireg', 'https://abireg.ru/newsitem/98414/'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6108718'],
    ['TAdviser', 'https://www.tadviser.ru/index.php/Компания:Келлогг_Рус_(Kellogg_Rus)'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8712117'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['law']['struct'] == OLD_LAW_STRUCT
    assert deal['law']['terms'] == OLD_LAW_TERMS
    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)
    print('\n=== law.terms: станет ===')
    print(NEW_LAW_TERMS)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['law']['struct'] = NEW_LAW_STRUCT
        deal['law']['terms'] = NEW_LAW_TERMS
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
