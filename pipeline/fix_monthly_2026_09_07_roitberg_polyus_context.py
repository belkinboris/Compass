import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

RB_ID = 'c672707b3'
RB_OLD_CONTEXT = (
    'Среди нынешних акционеров — МФК IFC, входящая в состав Всемирного '
    'банка. Инвестора пока ищут.'
)
RB_NEW_CONTEXT = (
    RB_OLD_CONTEXT + ' Позже компания рассматривала и другой путь '
    'привлечения капитала: по данным на апрель 2026 года, первичное '
    'размещение акций (IPO) АО «Медицина» могло состояться осенью 2026 '
    'года на Московской бирже, но окончательное решение ещё не принято '
    '— это отдельный, более поздний сюжет о капитале компании, а не '
    'судьба именно этой сделки.'
)

PL_ID = 'c5e3a4754'
PL_NEW_CONTEXT = (
    'Прямых подтверждений ни закрытия, ни срыва сделки не нашлось. '
    'Косвенный сигнал: в декабре 2024 года «Полюс» объявил о '
    'строительстве СОБСТВЕННОЙ обогатительной фабрики на Сухом Логе '
    '(первая линия — 2028 год, общие капзатраты — $6 млрд) вместо '
    'использования готовых мощностей поблизости, о которых шла речь '
    'в 2023 году.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    rb = by_id[RB_ID]
    pl = by_id[PL_ID]

    assert rb['eco']['context'] == RB_OLD_CONTEXT
    assert pl['eco'].get('context') is None

    print('=== c672707b3: eco.context ===')
    print(RB_NEW_CONTEXT)
    print()
    print('=== c5e3a4754: eco.context ===')
    print(PL_NEW_CONTEXT)

    if write:
        rb['eco']['context'] = RB_NEW_CONTEXT
        pl['eco']['context'] = PL_NEW_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
