# -*- coding: utf-8 -*-
"""Приток 18.09.2026, часовой прогон 11:20 МСК — `enrich.py --write` вернул
на карточку g5599430f (CPF/«Новомясово») сумму «2,05 млрд ₽», которую этот
же прогон вчера (часовой прогон 08:20 МСК) сознательно снял: это не цена
сделки, а уставный капитал вновь созданного SPV «Новомясово», совпавший по
величине с ценой в заголовке TAdviser (см.
pipeline/ingest/fixes/batch_2026_09_18_hourly_run.py, запись про поле
`sum`). enrich.py не умеет отличать «поле никогда не проверяли» от «поле
проверили и подтвердили пустым» — то же самое TAdviser-объявление снова
попало в сегодняшнюю ленту и снова совпало с пустым `sum`.

Заодно вскрылось, что вчерашняя правка сняла ЧИСЛО ИЗ ПОЛЯ, но не тронула
ТОТ ЖЕ НОМЕР, буквально скопированный в заголовок карточки из заголовка
источника («...за 2,05 млрд рублей»): заголовок и поле — разные места,
и снятие одного не снимает другое (родня уже записанного класса «Сумма на
«Обзоре» и сумма в «Экономисте» — два разных поля»). Заголовок укорочен
до части, не содержащей неверной суммы.

Постоянного способа запретить enrich.py повторно предлагать это поле пока
нет — architectural gap, отмечен в PRODUCT_ROADMAP.md для будущей осознанной
правки. Пока источник продолжает попадаться в ленте, снимать эту находку
придётся руками при каждом повторе.
"""
import json
import sys

DATA_PATH = 'static/data/deals_promoted.json'

OLD_TITLE = 'Таиландская CPF купила российского производителя свинины «Новомясово» за 2,05 млрд рублей'
NEW_TITLE = 'Таиландская CPF купила российского производителя свинины «Новомясово»'


def main(write):
    data = json.load(open(DATA_PATH, encoding='utf-8'))
    deals = data['deals'] if isinstance(data, dict) else data
    target = [d for d in deals if d.get('id') == 'g5599430f']
    assert len(target) == 1, target
    card = target[0]
    assert card['sum'] == '2,05 млрд ₽', repr(card['sum'])
    assert card['title'] == OLD_TITLE, repr(card['title'])
    card['sum'] = None
    card['title'] = NEW_TITLE

    if write:
        json.dump(data, open(DATA_PATH, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
        print('Сумма и заголовок g5599430f очищены от неверной цифры. ЗАПИСАНО.')
    else:
        print('Сухой прогон: снял бы сумму и поправил заголовок g5599430f. Повторите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
