# -*- coding: utf-8 -*-
"""Семнадцатая партия описаний профилей: чем компания занимается.

ЧТО СЛОМАНО. После шестнадцати партий настоящее описание есть у 557
профилей из 1871 (30%). Кандидатов этой партии искали по узнаваемости
имени среди профилей БЕЗ описания — как и раньше, каждый проверен по
тексту его собственной сделки в базе, прежде чем писать описание (урок
CLAUDE.md про «Акрон Холдинг»). Узнаваемые имена без единой связанной
сделки в базе (Evraz, Cofix, Enel Russia, Leoni AG — их id не встретился
ни в одном поле ни одной сделки) отложены намеренно: нечем подтвердить,
что профиль — именно та компания, о которой думаешь.

ЧТО ДЕЛАЕТ. Проставляет описание в 1–2 строки 11 профилям, исправляет
отрасль у 1.

Отдельная находка при чтении контекста: `g39cb6128` («RBI / российский
Райффайзенбанк») стоял в отрасли «Строительство» — банковская группа
Raiffeisen Bank International получила отрасль своей ЕДИНСТВЕННОЙ сделки
в базе, а сделка эта — про отказ RBI от выкупа доли в австрийской
СТРОИТЕЛЬНОЙ компании Strabag SE (актив сделки, а не сама компания).
Тот же класс дефекта, что «Сбербанк значился „Медиа"» — отрасль профиля
унаследована от предмета сделки, а не от рода занятий самой компании.
Исправлено на «Банки».

Запуск:
    python3 pipeline/write_company_descriptions_batch17.py            # сухой прогон
    python3 pipeline/write_company_descriptions_batch17.py --write    # записать
"""
import json
import re
import sys

DATA = 'static/data/deals_promoted.json'
PLACEHOLDER = re.compile(r'^\s*(описание компании пока не добавлено'
                          r'|профиль сформирован по итогам чтения)', re.I)

# id профиля -> описание. Только компании, чей род занятий общеизвестен и
# подтверждён текстом собственной сделки в базе.
DESCRIPTIONS = {
    'g14d93e1d': 'Российский бизнес Binance — крупнейшей в мире '
                 'криптовалютной биржи; в 2023 году продан площадке '
                 'CommEX, которая не смогла исполнить обязательства по '
                 'сделке.',
    'gdf918dd1': 'Американский банк, обслуживал состоятельных клиентов; '
                 'в мае 2023 года обанкротился и был приобретён JPMorgan '
                 'Chase.',
    'g2cc9c0cd': 'Американская компания по добыче урана, акции '
                 'торгуются на бирже NYSE American.',
    'ge02f6db2': 'Итальянская группа, один из крупнейших в Европе '
                 'производителей и переработчиков стали.',
    'gca76a828': 'Российский разработчик облачных решений для '
                 'видеонаблюдения.',
    'gbe2e52e2': 'Российский разработчик платформ для создания '
                 'чат-ботов и голосовых ассистентов на основе ИИ.',
    'g27010a1f': 'Российский сервис доставки готовых рационов питания.',
    'g4cd13d77': 'Российский туристический интернет-портал; в ноябре '
                 '2025 года товарный знак и домен куплены сервисом '
                 'Tutu.ru.',
    'g11360101': 'Российский сервис для приёма онлайн-платежей и '
                 'продажи курсов и цифровых продуктов.',
    'g5e679df1': 'Российский бизнес финского производителя '
                 'лесозаготовительной техники Ponsse; в 2023 году '
                 'продан компании «Бизон» из Хабаровска.',
    'g631ec584': 'Американская нефтесервисная компания, один из '
                 'крупнейших мировых поставщиков оборудования и услуг '
                 'для нефтегазовой отрасли.',
}

DESCRIPTIONS['g39cb6128'] = ('Австрийская банковская группа Raiffeisen '
                              'Bank International, материнская компания '
                              'российского Райффайзенбанка.')

# Профили, отрасль которых унаследована от предмета единственной сделки
# и не отражает основной бизнес компании (см. докстринг). old — что
# было, для assert.
INDUSTRY_FIXES = {
    'g39cb6128': ('Строительство', 'Банки'),
}

# Профили, которым описание не ставится в этой партии: неизвестно, что
# именно они обозначают, или падежная/предметная форма имени.
UNCLEAR = {}


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    comps = data['companies']

    wrote, skipped = 0, []
    for cid, text in DESCRIPTIONS.items():
        c = comps.get(cid)
        assert c, 'профиля %s нет в базе' % cid
        assert 15 <= len(text) <= 220, 'описание %s вне 1–2 строк: %d' % (cid, len(text))
        assert cid not in UNCLEAR, 'профиль %s помечен неясным — описание ставить нельзя' % cid
        old = str(c.get('desc') or '')
        if old.strip() == text:
            continue
        # Своё описание не перетираем: прошлые партии и ручные правки старше этой.
        if old and not PLACEHOLDER.match(old):
            skipped.append((cid, c.get('name'), old[:60]))
            continue
        print('  %-12s %-34s %s' % (cid, str(c.get('name'))[:34], text[:56]))
        c['desc'] = text
        wrote += 1

    ind_fixed = 0
    for cid, (old_ind, new_ind) in INDUSTRY_FIXES.items():
        c = comps.get(cid)
        assert c, 'профиля %s нет в базе' % cid
        assert c.get('ind') == old_ind, ('отрасль %s уже другая: %r (ожидали %r)'
                                          % (cid, c.get('ind'), old_ind))
        print('  ОТРАСЛЬ  %-12s %-34s %s -> %s'
              % (cid, str(c.get('name'))[:34], old_ind, new_ind))
        c['ind'] = new_ind
        ind_fixed += 1

    print('\nОписаний записано: %d' % wrote)
    print('Отраслей исправлено: %d' % ind_fixed)
    if skipped:
        print('Пропущено (уже есть своё описание): %d' % len(skipped))
        for cid, name, old in skipped[:5]:
            print('   %s %s — %r' % (cid, name, old))
    print('Оставлено без описания намеренно: %d профилей (см. UNCLEAR)' % len(UNCLEAR))

    real = sum(1 for v in comps.values()
               if (v.get('desc') or '').strip() and not PLACEHOLDER.match(str(v.get('desc'))))
    print('Всего профилей с описанием: %d из %d (%d%%)'
          % (real, len(comps), round(100 * real / len(comps))))

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return 0
    json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('Записано.')
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
