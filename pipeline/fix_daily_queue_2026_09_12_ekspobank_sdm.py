import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_ECO_CONTEXT = (
    'По данным «СПАРК-Интерфакса», до сделки Экспобанку принадлежало '
    '23,5% акций, по её итогам доля выросла до 86%.'
)

NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' Экспобанк выкупил 15% СДМ-банка у ЕБРР в ноябре '
    '2018 года и увеличил пакет до 23,57% в январе 2021-го; крупнейшим '
    'акционером СДМ-банка после этого и до конца 2021 года, по данным '
    'телеграм-канала MarketOverview, оставался Анатолий Ландеман. Кто '
    'именно продал контрольный пакет сейчас, источники не называют.'
)

NEW_ECO_VAL = (
    'Аналитик IPM Consulting Анастасия Владимирова оценивала справедливый '
    'диапазон для пакета в 0,8–1,0 P/BV, то есть 6–8,5 млрд ₽ без учёта '
    'премии за контроль (по оценке).'
)

NEW_ECO_TARGET_FIN = (
    'На 1 июля 2026 года у СДМ-банка: капитал 11,7 млрд ₽, активы '
    '116,4 млрд ₽.'
)

NEW_ECO_FIN = (
    'У Экспобанка на август 2026 года: активы 345,6 млрд ₽, чистая '
    'прибыль за 7 месяцев 2026 года — 5,3 млрд ₽.'
)

NEW_ECO_RATIONALE = (
    'По заявлению пресс-службы Экспобанка, сделка соответствует стратегии '
    'развития банка, одним из приоритетов которой является расширение '
    'клиентской платформы; клиентам СДМ-банка станут доступны сервисы по '
    'сопровождению внешнеэкономической деятельности, сложным сделкам, а '
    'также услуги категорий Premium и Private Banking.'
)

NEW_LAW_APPR = 'Сделка получила согласование ФАС и Банка России.'

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8953009'],
    ['finance.mail.ru', 'https://finance.mail.ru/article/'
                        'ekspobank-zakryil-sdelku-po-pokupke-kontrolnogo-'
                        'paketa-aktsij-sdm-banka-69227381/'],
]


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}
    d = by_id['gbeb0dfe8']

    assert d['eco']['context'] == OLD_ECO_CONTEXT, 'eco.context уже другое: %r' % (d['eco']['context'],)
    assert d['eco']['val'] == '—', 'eco.val уже занято: %r' % (d['eco']['val'],)
    assert d['eco']['target_fin'] == '—', 'eco.target_fin уже занято: %r' % (d['eco']['target_fin'],)
    assert d['eco']['fin'] == '—', 'eco.fin уже занято: %r' % (d['eco']['fin'],)
    assert d['eco']['rationale'] == '—', 'eco.rationale уже занято: %r' % (d['eco']['rationale'],)
    assert d['law']['appr'] == '—', 'law.appr уже занято: %r' % (d['law']['appr'],)
    urls = {s[1] for s in d['src']}
    for name, url in NEW_SRC:
        assert url not in urls, 'источник уже добавлен: %s' % url

    print('gbeb0dfe8: заполняю law.appr (согласование ФАС и ЦБ), eco.val '
          '(оценка IPM Consulting), расширяю eco.context (история '
          'владения), заполняю eco.target_fin, eco.fin, eco.rationale, '
          'добавляю 2 источника (Коммерсантъ, finance.mail.ru)')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['eco']['context'] = NEW_ECO_CONTEXT
    d['eco']['val'] = NEW_ECO_VAL
    d['eco']['target_fin'] = NEW_ECO_TARGET_FIN
    d['eco']['fin'] = NEW_ECO_FIN
    d['eco']['rationale'] = NEW_ECO_RATIONALE
    d['law']['appr'] = NEW_LAW_APPR
    d['src'].extend(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
