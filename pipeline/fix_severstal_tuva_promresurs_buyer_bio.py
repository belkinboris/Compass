# -*- coding: utf-8 -*-
"""Недельная очередь качества, 11 сентября 2026 — дочитывание карточки
`ge0cc0dfe` («Северсталь» продала угольный актив в Туве новосибирской
компании», закрыта 27 августа 2026, дочитана 4 сентября).

Дельта-поиск (саб-агент + личная проверка WebFetch) нашёл биографию
покупателя (ООО «Промресурс», Сергей Дьяконов) и финансовые показатели
самого «Промресурса» — карточка знала только сферу деятельности
(«оптовая торговля твёрдым топливом»).

Личный WebFetch подтвердил дословно (mergers.ru,
https://mergers.ru/news/Novosibirskaya-kompaniya-Promresurs-priobrela-ugolnye-aktivy-v-Tuve-87495):

1) «Ранее он управлял угольными шахтами в Киселевске и Прокопьевске
   Кемеровской области.»
2) «Дьяконов также владеет 55% долей в челябинской компании-
   разработчике программного обеспечения «Логистик Систем Рус».»
3) «Выручка ООО «Промресурс» по итогам 2025 года выручка составила
   8,24 млрд руб., однако компания получила убыток в размере
   791,1 млн руб.»

НЕ внесено: сумма сделки «Северсталь»/«Улугхемуголь» (по-прежнему
нигде не раскрыта, включая эту и все проверенные более поздние
публикации); планы «Промресурса» по интеграции актива (источники
называют только техническую деталь про соседний участок «Межегейуголь»
— приостановку разработки Восточного участка, не относящуюся к предмету
ЭТОЙ карточки); прямая аффилиация Дьяконова с другими игроками угольного
рынка (источник называет только прежний управленческий опыт, не текущее
участие в чужих активах).

Запуск:
    python3 pipeline/fix_severstal_tuva_promresurs_buyer_bio.py            # сухой прогон
    python3 pipeline/fix_severstal_tuva_promresurs_buyer_bio.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_ECO_CONTEXT = (
    '«Улугхемуголь» (100%) — бывший угольный актив «Северстали», '
    'единственный оставшийся у компании после продажи «Воркутаугля» в '
    '2022 году. Ему принадлежит лицензия на участок «Западный» '
    'Улуг-Хемского угольного бассейна: запасы C1 — 250,5 млн т, '
    'C2 — 246,2 млн т.'
)
NEW_ECO_CONTEXT = OLD_ECO_CONTEXT + (
    ' Покупатель, Сергей Дьяконов, ранее управлял угольными шахтами в '
    'Киселевске и Прокопьевске Кемеровской области и владеет 55% '
    'долей в челябинской компании-разработчике программного '
    'обеспечения «Логистик Систем Рус». Выручка ООО «Промресурс» по '
    'итогам 2025 года составила 8,24 млрд ₽, компания получила убыток '
    'в размере 791,1 млн ₽.'
)

NEW_SRC = ['mergers.ru',
           'https://mergers.ru/news/Novosibirskaya-kompaniya-Promresurs-priobrela-ugolnye-aktivy-v-Tuve-87495']


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['ge0cc0dfe']

    assert d['eco']['context'] == OLD_ECO_CONTEXT, \
        'ge0cc0dfe eco.context уже другой: %r' % (d['eco']['context'],)
    urls = {s[1] for s in d['src']}
    assert NEW_SRC[1] not in urls, 'источник уже добавлен: %s' % NEW_SRC[1]

    print('ge0cc0dfe: eco.context дополнен (биография Сергея Дьяконова, '
          'финансы ООО «Промресурс» за 2025 год); добавлен источник '
          'mergers.ru')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['eco']['context'] = NEW_ECO_CONTEXT
    d['src'].append(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
