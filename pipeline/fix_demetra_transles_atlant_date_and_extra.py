import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g3c230c8f'

OLD_DATE = '2024-06-24'
NEW_DATE = '2025'

OLD_EXTRA = 'Представлена информация о структуре сделки и финансовых показателях сторон.'
NEW_EXTRA = (
    'Обе сделки реализуются в рамках стратегии развития группы '
    '«Трансфин-М» (этой лизинговой компании принадлежит «Атлант»): «Мы '
    'укрепляем позиции в сегментах полувагонов и крытых вагонов, – '
    'пояснил он. – Это позволит улучшить сервис и качество оказываемых '
    'услуг для клиентов-грузовладельцев, повысить их транспортную '
    'безопасность, выстроить эффективное управление вагонами совместно с '
    'РЖД» (Ведомости).'
)

OLD_APPR = 'Сделка получила одобрение Федеральной антимонопольной службы.'
NEW_APPR = (
    '«Приобретение операторских компаний было согласовано с ФАС, говорит '
    'источник, близкий к одной из сторон сделки» (Ведомости) — атрибуция '
    'источника сохранена как есть, это не заявление самого ФАС.'
)

NEW_SRC = []


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['date'] == OLD_DATE
    assert deal['extra'] == OLD_EXTRA
    assert deal['law']['appr'] == OLD_APPR

    print(f'=== date: {OLD_DATE!r} -> {NEW_DATE!r} ===')
    print('=== extra: было ===')
    print(OLD_EXTRA)
    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('=== law.appr: было ===')
    print(OLD_APPR)
    print('=== law.appr: станет ===')
    print(NEW_APPR)

    if write:
        deal['date'] = NEW_DATE
        deal['extra'] = NEW_EXTRA
        deal['law']['appr'] = NEW_APPR
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
