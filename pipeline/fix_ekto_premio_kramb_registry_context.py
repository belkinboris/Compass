import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g6ad6fe69'

OLD_CONTEXT = 'Выручка ВПТ за 2022 год — 9 млрд ₽, чистая прибыль — 1,4 млрд ₽.'
NEW_CONTEXT = (
    OLD_CONTEXT + ' По данным трёх независимых реестровых агрегаторов'
    ' (свежий срез ЕГРЮЛ — 04.02.2025), спустя более двух лет после'
    ' одобрения ФАС единственным учредителем и гендиректором ООО «Премио'
    ' Крамб» остаётся Максим Ефименко — АО «Вестерн Петролеум'
    ' Транспортэйшн» в истории участников не встречается вовсе.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
