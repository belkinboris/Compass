import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'ge9b4ba4d'

OLD_ECO_CONTEXT = (
    'Мидова имела отношение и к другим структурам этой группы: до '
    '2015 года она руководила Мелкооптовым рынком тамбовского '
    'хладокомбината, собственник которого сейчас — Артур Карданов.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' Сеть сменила собственника ещё несколько раз: '
    'в 2025 году контроль перешёл к другой структуре, а 13 января 2026 '
    'года 25 магазинов сети (263 тыс. кв. м) купила «Лента» — у '
    'структур, по-прежнему подконтрольных группе «Синдика». Сумма не '
    'раскрыта; полную стоимость бизнеса источники оценивали около '
    '6 млрд ₽, но с учётом убыточности актива реальная цена могла быть '
    'ниже.'
)

OLD_SRC = [['Ведомости', 'https://www.vedomosti.ru/business/articles/2023/01/09/958271-u-obi-v-tretii-raz-smenilis-sobstvenniki']]
NEW_SRC = OLD_SRC + [['Коммерсантъ', 'https://www.kommersant.ru/doc/8340567']]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
