# -*- coding: utf-8 -*-
"""Продавцы сделки Wink/«ЛайфСтрим» названы в тексте карточки, а поле пусто.

Что чинит. У карточки `g1125c0ec` («Wink купил сервис «Смотрешка»»)
`seller` и `seller_id` пусты, хотя `extra` и «Предмет / доля» дословно
называют троих продавцов: «ранее 89% принадлежало гендиректору Александру
Киселевичу, 7,25% — Тимуру Родионову, 3,75% — Георгию Юфа».

Почему это нашлось. Тест «чтение подтверждает, но не расширяет»
(`test_gold_verified_multiples_are_a_subset_of_rule_candidates`) покраснел
после того, как два чтения подтвердили цену, дату, долю и периметр этой
сделки: у карточки с подтверждёнными фактами текстовые правила отказали с
причиной «стороны не названы». Тот же класс, что и у VK/«Зингера» тем же
вечером, — и тот же вывод: сигнал теста верный, чинить надо данные.

Граница правки. Это ПЕРЕНОС факта в своё поле, а не новое утверждение:
каждое имя проверяется на дословное вхождение в `extra` по отдельности
(правило «проверка „результат лежит в тексте" не работает на
перечислениях» — режем по запятым и проверяем каждую часть).
Профиля ни у кого из троих в базе нет, поэтому пишется текст, а не ссылка.

Запуск: python3 pipeline/fix_lifestream_sellers_from_extra.py [--write]
"""
import json
import sys
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent / 'static' / 'data' / 'deals_promoted.json'
DEAL_ID = 'g1125c0ec'
NAMES = ['Александр Киселевич', 'Тимур Родионов', 'Георгий Юфа']
# В тексте имена стоят в дательном падеже («принадлежало ... Киселевичу»),
# поэтому дословно проверяем фамилию — она у всех троих не склоняется
# внутри основы, а падеж меняет только окончание.
STEMS = ['Киселевич', 'Родионов', 'Юфа']
NEW = 'Александр Киселевич, Тимур Родионов и Георгий Юфа'


def main(write: bool) -> None:
    data = json.loads(BASE.read_text(encoding='utf-8'))
    deals = {d['id']: d for d in data['deals']}
    card = deals[DEAL_ID]
    assert not card.get('seller'), 'продавец уже записан — скрипт больше не нужен'
    assert not card.get('seller_id'), 'продавец связан с профилем — решите руками'
    text = (card.get('extra') or '') + ' ' + ((card.get('eco') or {}).get('share') or '')
    for stem in STEMS:
        assert stem in text, f'{stem} не встречается в тексте карточки — основание правки пропало'
    print(f'{DEAL_ID}: seller  —  →  {NEW}')
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return
    card['seller'] = NEW
    BASE.write_text(json.dumps(data, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
