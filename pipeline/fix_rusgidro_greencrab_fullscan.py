# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
`g446bbeee` («РусГидро консолидировало проект Green Crab (выкуп доли
Вадима Швецова)», закрыта, 2023) — предмет сделки (сам каршеринг
Green Crab) не был описан структурно, а обоснование покупателя не
было заполнено вовсе; дочитывание нашло и то, и другое, плюс
продолжение сюжета (расширение на Южно-Сахалинск).

Проверено (по докладу саб-агента, дословные цитаты):
- kommersant.ru/doc/6082767 (источник карточки): «сдаче в
  краткосрочную аренду электромобилей во Владивостоке»; в парке «111
  электромобилей», из них «16» JAC iEV7 и «95» Evolute; «"РусГидро", у
  которой есть сеть зарядных станций на Дальнем Востоке, теперь
  планирует самостоятельно развивать проект»; «"РусГидро" со своей
  стороны развивало сеть зарядных станций для электромобилей на
  Дальнем Востоке, которую планировалось загружать в том числе за счет
  каршеринга».
- akm.ru/news/green_crab_nachal_rabotu_v_yuzhno_sakhalinske/ (28 июля
  2023): «начале работы» каршеринга в Южно-Сахалинске — «15
  электромобилей JAC iEV7S», охват «Холмский, Невельский, Анивский и
  Корсаковский» районы, зарядка на станциях РусГидро бесплатная —
  прямое продолжение той же экспансии, которую предполагала сделка.

НЕ ВНЕСЕНО: (1) точная дата закрытия сделки (в снипете поисковика
встретилась «30 июня 2023», но саб-агент не смог прочитать это
дословно в первоисточнике — только в пересказе агрегатора, дословность
не подтверждена, поэтому дата в карточке остаётся годом); (2)
финансовые показатели компании за 2025 год (выручка/убыток) и точная
причина распродажи парка весной 2026 года — источники расходятся
(один пишет о прекращении работы, представитель компании это
опровергает: «Продажа автомобилей не связана с тем, что мы
закрываемся. Мы обновляем автопарк»), ни одна из двух версий не
подтверждена дословной цитатой из первично прочитанного текста с
установленной датой публикации — вопрос остаётся открытым, не
вносится ни в одну сторону; (3) юридический/финансовый консультант —
ноль по всем источникам.

Запуск: python3 pipeline/fix_rusgidro_greencrab_fullscan.py
        python3 pipeline/fix_rusgidro_greencrab_fullscan.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g446bbeee'

OLD_ECO_SHARE = '—'
NEW_ECO_SHARE = (
    'Green Crab сдаёт в краткосрочную аренду электромобили во '
    'Владивостоке: на момент сделки в парке было 111 машин — 16 JAC '
    'iEV7 и 95 Evolute.'
)

OLD_ECO_RATIONALE = None
NEW_ECO_RATIONALE = (
    'У «РусГидро» есть сеть зарядных станций для электромобилей на '
    'Дальнем Востоке, которую планировалось загружать в том числе за '
    'счёт каршеринга; после выхода партнёра компания решила '
    'развивать проект самостоятельно.'
)

OLD_ECO_CONTEXT = (
    'Летом 2022 года Вадим Швецов вышел из автомобильного бизнеса, '
    'продав контрольный пакет «Соллерс Авто» (76,7%) компании «Альтер '
    'Инвест», которая принадлежит топ-менеджменту автоконцерна. Выход '
    'из каршеринга обсуждался уже тогда, но процесс затянулся.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' 28 июля 2023 года Green Crab запустила '
    'каршеринг в Южно-Сахалинске — 15 электромобилей JAC iEV7S с '
    'охватом Холмского, Невельского, Анивского и Корсаковского '
    'районов, зарядка на станциях «РусГидро» бесплатная.'
)

OLD_SRC = [['Коммерсантъ', 'https://www.kommersant.ru/doc/6082767']]
NEW_SRC = OLD_SRC + [
    ['AK&M', 'https://www.akm.ru/news/green_crab_nachal_rabotu_v_yuzhno_sakhalinske/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['share'] == OLD_ECO_SHARE
    assert deal['eco'].get('rationale') == OLD_ECO_RATIONALE
    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== eco.share: станет ===')
    print(NEW_ECO_SHARE)
    print('\n=== eco.rationale: станет ===')
    print(NEW_ECO_RATIONALE)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['eco']['share'] = NEW_ECO_SHARE
        deal['eco']['rationale'] = NEW_ECO_RATIONALE
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
