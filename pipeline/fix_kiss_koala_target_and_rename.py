import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g3c56d235'
COMPANY_ID = 'g63a953b7'

OLD_SELLER = None
OLD_SELLER_ID = 'g63a953b7'
OLD_TARGET = None
NEW_SELLER = 'Sony Music Group'
NEW_SELLER_ID = None
NEW_TARGET = 'g63a953b7'

OLD_COMPANY_NAME = 'Кисс Коала'
NEW_COMPANY_NAME = 'Коала Мьюзик'

OLD_COMPANY_DESC = 'Российский каталог Sony Music, приобретён ООО «Мерит».'
NEW_COMPANY_DESC = (
    'Российский музыкальный лейбл, бывший каталог Sony Music в России '
    '(до 2022 года — ООО «Сони Мьюзик Энтертейнмент»). В сентябре 2022 '
    'года переименован в «Кисс Коала» и в декабре того же года куплен '
    'ООО «Мерит», структурой бывших менеджеров Warner Music Russia; в '
    'сентябре 2023 года переименован в «Коала Мьюзик» — под этим '
    'именем работает и сейчас, выпуская российских артистов (Денис '
    'Мацуев, Сергей Лазарев и другие).'
)

OLD_ECO_CONTEXT = (
    'В марте 2022 года Warner Music и Sony Music Group приостановили '
    'работу в России. Российское подразделение Warner Music продолжало '
    'заключать контракты. Sony Music Group отозвала у «Сони Мьюзик '
    'Энтертейнмент», которую позже переименовали в «Кисс Коала», '
    'зарубежные каталоги, но российский передала ей.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' В сентябре 2023 года «Кисс Коала» ещё раз '
    'переименована — в «Коала Мьюзик»; выручка выросла до 1,9 млрд ₽ '
    'в 2025 году (+34%), хотя прибыль снизилась почти вдвое, до 233 '
    'млн ₽. В 2024-2025 годах у лейбла был публичный спор с певицей '
    'Бьянкой: суд обязал выплатить недополученные по контракту роялти, '
    'а затем певица потребовала досрочно расторгнуть контракт.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)
    company = data['companies'][COMPANY_ID]

    assert deal.get('seller') == OLD_SELLER
    assert deal.get('seller_id') == OLD_SELLER_ID
    assert deal.get('target') == OLD_TARGET
    assert company['name'] == OLD_COMPANY_NAME
    assert company['desc'] == OLD_COMPANY_DESC
    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    print('=== deal.seller/seller_id/target: станут ===')
    print(NEW_SELLER, NEW_SELLER_ID, NEW_TARGET)
    print('\n=== company.name: станет ===')
    print(NEW_COMPANY_NAME)
    print('\n=== company.desc: станет ===')
    print(NEW_COMPANY_DESC)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)

    if write:
        deal['seller'] = NEW_SELLER
        deal['seller_id'] = NEW_SELLER_ID
        deal['target'] = NEW_TARGET
        company['name'] = NEW_COMPANY_NAME
        company['desc'] = NEW_COMPANY_DESC
        deal['eco']['context'] = NEW_ECO_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
