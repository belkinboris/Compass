import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_DATE = '2024'

OLD_ECO_CONTEXT_SAMOLET = (
    'Согласно письму генерального директора Анны Акиньшиной в адрес '
    'премьер-министра Мишустина, компания предлагает государству '
    'блокирующий и более пакеты акций для участия в управлении с '
    'правом обратного выкупа по новой цене, а также готова обеспечить '
    'дополнительное внешнее финансирование до 10 млрд руб.'
)
NEW_ECO_CONTEXT_SAMOLET = OLD_ECO_CONTEXT_SAMOLET + (
    ' 19 февраля 2026 года правительство отказало в отдельной части '
    'просьбы — прямом льготном кредите на 50 млрд ₽: «Правительство не '
    'намерено предоставлять девелоперу «Самолет» прямые субсидии»; '
    'вместо этого рассматривается возврат застройщику национализированного '
    'жилого комплекса «Квартал Марьино». Судьба предложения об обмене '
    'пакетом акций отдельно не прокомментирована.'
)

OLD_SRC_VEB = ["@dealsma (Telegram)", "http://%D0%92%D0%AD%D0%91.%D0%A0%D0%A4/"]
NEW_SRC_VEB = ["Коммерсантъ", "https://www.kommersant.ru/doc/8438720"]


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    veb = by_id['cacdb5edc']
    samolet = by_id['c4534c6d1']
    mts = by_id['c56a6cc5f']

    assert veb['date'] == OLD_DATE, 'cacdb5edc date уже другая: %r' % (veb['date'],)
    assert veb.get('status') is None, 'cacdb5edc status уже занят: %r' % (veb.get('status'),)
    assert OLD_SRC_VEB in veb['src'], 'cacdb5edc src не содержит ожидаемую запись'
    assert samolet['date'] == OLD_DATE, 'c4534c6d1 date уже другая: %r' % (samolet['date'],)
    assert samolet.get('status') is None, 'c4534c6d1 status уже занят: %r' % (samolet.get('status'),)
    assert samolet['eco']['context'] == OLD_ECO_CONTEXT_SAMOLET, \
        'c4534c6d1 eco.context уже другой: %r' % (samolet['eco']['context'],)
    assert mts['date'] == OLD_DATE, 'c56a6cc5f date уже другая: %r' % (mts['date'],)
    assert mts.get('status') is None, 'c56a6cc5f status уже занят: %r' % (mts.get('status'),)

    print('cacdb5edc: date %r -> "2026-02-13"; status None -> "Закрыта"; '
          'источник заменён на kommersant.ru/doc/8438720' % (OLD_DATE,))
    print('c4534c6d1: date %r -> "2026-02-04"; status None -> "Обсуждается"; '
          'eco.context дополнен (отказ в кредите 19.02.2026)' % (OLD_DATE,))
    print('c56a6cc5f: date %r -> "2026-02-05"; status None -> "Обсуждается"' % (OLD_DATE,))

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    veb['date'] = '2026-02-13'
    veb['status'] = 'Закрыта'
    veb['src'] = [NEW_SRC_VEB if s == OLD_SRC_VEB else s for s in veb['src']]

    samolet['date'] = '2026-02-04'
    samolet['status'] = 'Обсуждается'
    samolet['eco']['context'] = NEW_ECO_CONTEXT_SAMOLET

    mts['date'] = '2026-02-05'
    mts['status'] = 'Обсуждается'

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
