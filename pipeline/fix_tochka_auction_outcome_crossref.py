# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g75a6ee1c
(«Росбанк и другие банки участвуют в аукционе по покупке «Точки»»,
статус «Обсуждается», 10 июля 2023) — это анонс аукциона, а не его
исход; исход уже полноценно описан ОТДЕЛЬНОЙ, уже прочитанной карточкой
`gcd2b0954» («Продажа банком «Траст» 90,01% акций АО «Точка»
консорциуму инвесторов во главе с «Интерросом»», закрыта 25.08.2023,
41,5 млрд ₽) — задваивать те же факты здесь не нужно, добавлена только
короткая перекрёстная ссылка.

Проверено лично прямым WebFetch (Коммерсантъ, https://www.kommersant.ru/doc/6183613):
«Банк непрофильных активов «Траст» закрыл сделку по продаже 90% АО
«Точка» за 41,5 млрд руб.» (25 августа 2023 года) — покупателем
выступил не банк-участник аукциона (ни Росбанк, ни Альфа-банк, ни
Филёв), а сам менеджмент «Точки» через кипрскую «Каталитик пипл»,
реализовавший преимущественное право выкупа и собравший консорциум
инвесторов с участием группы «Интеррос».

Запуск: python3 pipeline/fix_tochka_auction_outcome_crossref.py
        python3 pipeline/fix_tochka_auction_outcome_crossref.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g75a6ee1c'

OLD_EXTRA = (
    'Банк непрофильных активов «Траст» (АО Национальный банк «Траст»), '
    'организующий аукцион — Банк непрофильных активов «Траст» организует '
    'английский аукцион на повышение по продаже финансовой компании '
    '«Точка». На аукцион заявились семь интересантов, включая '
    'Альфа-банк, Росбанк и Владислава Филева. Аукцион планировался на '
    '10 июля.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Итог: ни один из банков-участников аукцион не выиграл — '
    'преимущественным правом выкупа воспользовался сам менеджмент '
    '«Точки», собравший консорциум инвесторов с участием группы '
    '«Интеррос»; сделка на 90,01% акций закрыта 25 августа 2023 года за '
    '41,5 млрд ₽ (см. карточку «Продажа банком «Траст» 90,01% акций АО '
    '«Точка» консорциуму инвесторов во главе с «Интерросом»»).'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6183613'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
