# -*- coding: utf-8 -*-
"""Карточка Шереметьево/Домодедово называла банкротством то, что им не было.

ЧТО СЛОМАНО. `domodedovo-aukcion` несла в четырёх местах слово «банкротство»
(`law.struct`, `law.terms`, `extra` — «Процедура несостоятельности
(банкротства)», `eco.rationale` — «после банкротства Домодедово»), хотя её
же собственное поле `law.appr` дословно описывает СОВСЕМ ДРУГУЮ процедуру:
«Арбитражный суд Московской области... удовлетворил требование Генпрокуратуры
изъять в доход государства 100% долей... ООО «ДМЕ Холдинг»». Это гражданский
иск об обращении имущества в доход государства (национализация), а не
несостоятельность — два разных основания, и это противоречие уже стояло в
CLAUDE.md как открытый вопрос («источники расходятся... требует отдельного
решения человека»).

ПРОВЕРЕНО ЖИВЫМ ПОИСКОМ (17-18 августа 2026). Ни один найденный источник не
называет ни ДМЕ Холдинг, ни аэропорт формально банкротом:
  - РИА/Interfax/Ведомости/Право.ру (январь 2026, про сам аукцион): актив
    вернулся государству по решению суда июня 2025 года, дальше его продают
    на аукционе на понижение — это ПРИВАТИЗАЦИЯ государственного имущества,
    а не банкротная распродажа.
  - РБК (24 июля 2025, гендиректор МАШ Иванов): «банкротства мы не
    допустим» — руководство прямо ГОВОРИТ, что дело не дошло до банкротства,
    несмотря на долг ~70 млрд ₽; ведутся переговоры с кредиторами о
    реструктуризации, а не конкурсное производство.
  - rusbankrot.ru (отраслевой ресурс о банкротствах): «Домодедово... на
    грани: долги 70 млрд... но банкротства не будет» — и тот же источник
    подтверждает, что активы «переданы в доход государства по решению суда
    в июне 2025 года», а не через процедуру несостоятельности.

Итог: два реальных, но РАЗНЫХ события — (1) национализация ДМЕ Холдинг по
иску Генпрокуратуры (июнь 2025, уже верно описана в `law.appr`) и
(2) приватизационная продажа полученного государством актива с молотка
(январь 2026, голландский аукцион). Ни одно из двух не было банкротством;
слово «банкротство» в четырёх полях — не то же самое, что «плохое
финансовое состояние компании» (это было правдой и осталось в
`eco.target_fin`) — это конкретный правовой термин, и он здесь неверен.

ПОЧЕМУ НЕ ЧЕРЕЗ review.py. Правка не добавляет новый факт по цитате из
источника карточки, а снимает терминологическую ошибку, подтверждённую
внешними источниками, которых не было в `src` карточки на момент правки, —
`review.py` для такой правки не подходит (она проверяет дословное
совпадение с УЖЕ ПРИВЯЗАННЫМ источником, а не верность юридической
квалификации). Правка внесена одноразовым скриптом с `assert` на исходное
значение, как и другие правки этого класса (`fix_nordline_arctic_sum_
misattribution.py`, `fix_osnova_sviblovo_date.py`).

ЗАПУСК:
    python3 pipeline/fix_domodedovo_bankruptcy_misclassification.py            # сухой прогон
    python3 pipeline/fix_domodedovo_bankruptcy_misclassification.py --write    # запись
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'domodedovo-aukcion'

OLD_STRUCT = ('Продажа имущественного комплекса через процедуру публичного '
              'предложения в рамках банкротства; договор купли-продажи — в '
              'течение 5 рабочих дней с даты подведения итогов, передача '
              'имущества — не позднее 30 календарных дней после оплаты')
NEW_STRUCT = ('Продажа имущественного комплекса как государственного '
              'имущества (актив обращён в доход государства по решению суда '
              'в июне 2025 года — это национализация по иску Генпрокуратуры, '
              'не банкротство) через процедуру публичного предложения на '
              'понижение цены; договор купли-продажи — в течение 5 рабочих '
              'дней с даты подведения итогов, передача имущества — не '
              'позднее 30 календарных дней после оплаты')

OLD_TERMS = ('Классический кейс продажи актива в банкротстве через '
             'понижающийся аукцион — цена ушла ниже долговой нагрузки '
             'объекта, итоговая стоимость определилась не рыночной оценкой, '
             'а правилами голландского аукциона')
NEW_TERMS = ('Продажа государственного имущества через понижающийся '
             '(голландский) аукцион — не банкротная процедура: актив вернулся '
             'государству по гражданскому иску Генпрокуратуры, а не через '
             'несостоятельность. Итоговая цена ушла ниже долговой нагрузки '
             'объекта — её определили не рыночной оценкой, а правилами '
             'аукциона')

OLD_EXTRA = 'Процедура несостоятельности (банкротства); торги на электронной площадке РТС-Тендер'
NEW_EXTRA = ('Продажа государственного имущества (не банкротство: актив '
             'обращён в доход государства по иску Генпрокуратуры в июне '
             '2025 года), торги на электронной площадке РТС-Тендер')

OLD_RATIONALE = 'Консолидация двух из трёх московских аэропортов под контролем Шереметьево после банкротства Домодедово'
NEW_RATIONALE = ('Консолидация двух из трёх московских аэропортов под '
                  'контролем Шереметьево после того, как государство изъяло '
                  'Домодедово у прежнего владельца и продало его на '
                  'приватизационных торгах')


def main(argv):
    data = json.load(open(DATA, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['law']['struct'] == OLD_STRUCT, 'law.struct уже другой: %r' % deal['law']['struct']
    assert deal['law']['terms'] == OLD_TERMS, 'law.terms уже другой: %r' % deal['law']['terms']
    assert deal['extra'] == OLD_EXTRA, 'extra уже другой: %r' % deal['extra']
    assert deal['eco']['rationale'] == OLD_RATIONALE, 'eco.rationale уже другой: %r' % deal['eco']['rationale']

    print('ПРАВИМ %s: снимаем слово «банкротство» из четырёх полей' % DEAL_ID)
    print('  причина: актив вернулся государству гражданским иском '
          'Генпрокуратуры (национализация), а продан был на приватизационных '
          'торгах — ни то, ни другое не банкротство; проверено живым '
          'поиском по независимым источникам (РИА, Interfax, Ведомости, '
          'Право.ру, РБК, rusbankrot.ru)')

    if '--write' not in argv:
        print('\nСухой прогон. Запись — с ключом --write.')
        return 0

    deal['law']['struct'] = NEW_STRUCT
    deal['law']['terms'] = NEW_TERMS
    deal['extra'] = NEW_EXTRA
    deal['eco']['rationale'] = NEW_RATIONALE

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write('\n')

    print('Записано.')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
