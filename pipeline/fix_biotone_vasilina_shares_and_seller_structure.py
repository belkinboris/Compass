import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gd84abf3e'

OLD_EXTRA = (
    'Сделка закрыта 14 мая 2024 года. Холдинг «Био-тон» приобрел 100% '
    'акций ООО «Серноводский элеватор» (элеватор на 100+ тыс. тонн зерна '
    'в Сергиевском районе Самарской области) и 99,2% акций ООО '
    'Агрокомплекс «Конезавод «Самарский»» (разведение лошадей и '
    'выращивание растений на ~7 тыс. га земли).'
)
NEW_EXTRA = (
    'Сделка закрыта 14 мая 2024 года. Холдинг «Био-тон» приобрел 99,19% '
    'акций ООО «Серноводский элеватор» (элеватор на 100+ тыс. тонн зерна '
    'в Сергиевском районе Самарской области) и 100% акций ООО '
    'Агрокомплекс «Конезавод «Самарский»» (разведение лошадей и '
    'выращивание растений на ~7 тыс. га земли).'
)

OLD_TARGET_FIN = (
    'Серноводский элеватор за 2023 год получил выручку в размере 121 '
    'млн руб., чистая прибыль составила 17 млн руб. ООО Агрокомплекс '
    '«Конезавод «Самарский» был приобретен у сооснователя — Виктора '
    'Димитрова. Выручка конезавода за 2023 год составила 2,1 млрд руб., '
    'чистая прибыль 102 млн руб.»'
)
NEW_TARGET_FIN = (
    'Серноводский элеватор за 2023 год получил выручку в размере 121 '
    'млн руб., чистая прибыль составила 17 млн руб. ООО Агрокомплекс '
    '«Конезавод «Самарский» был приобретен у сооснователя — Виктора '
    'Димитрова. Выручка конезавода за 2023 год составила 2,1 млрд руб., '
    'чистая прибыль 102 млн руб.'
)

NEW_STRUCT = (
    'Доли ООО «Серноводский элеватор» были выкуплены у ООО '
    '«Большечерниговский комбикормовый завод» (77,76%) и у двух '
    'физических лиц (21,43%); доля в ООО Агрокомплекс «Конезавод '
    '«Самарский»» (100%) выкуплена у сооснователя Виктора Димитрова '
    '(АК&М).'
)

NEW_CONTEXT = (
    'Продажа — часть более широкой распродажи активов группой '
    'Димитриева в 2024 году: «В 2024 году группа Димитриева пошла по '
    'пути распродажи активов. «Василина» продала одну из крупнейших '
    'своих компаний — «Агрокомплекс «Конезавод «Самарский» и связанный '
    'с ним элеватор» (oboz.info). Конкретная причина продажи источником '
    'не названа.'
)

NEW_SRC = [
    ['oboz.info', 'https://oboz.info/nazvany-100-samyh-bogatyh-vladeltsev-agrobiznesa-v-samarskoj-oblasti/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA
    assert deal['eco']['target_fin'] == OLD_TARGET_FIN
    assert deal['law']['struct'] == '—'
    assert deal['eco']['context'] == '—'
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== eco.target_fin: станет ===')
    print(NEW_TARGET_FIN)
    print('\n=== law.struct: станет ===')
    print(NEW_STRUCT)
    print('\n=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['eco']['target_fin'] = NEW_TARGET_FIN
        deal['law']['struct'] = NEW_STRUCT
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
