import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g0410fde2'

OLD_ECO_CONTEXT = (
    'АО «Медскан» создано в июле 2020 года и контролирует около тридцати '
    'компаний медицинской специализации. На конец 2022 года владельцами '
    'являлись Евгений Туголуков (74,99%) и «Русатом Хэлскеа» (25,01%), '
    'входящее в группу компаний «Росатом». «Русатом Хэлскеа» вошел в '
    'капитал АО «Медскан в феврале 2022 года, выкупив дополнительную '
    'эмиссию на сумму 2,49 млрд руб.»'
)
NEW_ECO_CONTEXT = (
    'АО «Медскан» создано в июле 2020 года и контролирует около тридцати '
    'компаний медицинской специализации. На конец 2022 года владельцами '
    'являлись Евгений Туголуков (74,99%) и «Русатом Хэлскеа» (25,01%), '
    'входящее в группу компаний «Росатом». «Русатом Хэлскеа» вошел в '
    'капитал АО «Медскан в феврале 2022 года, выкупив дополнительную '
    'эмиссию на сумму 2,49 млрд руб.» Уже через два месяца после сделки '
    'пакет «Сбербанк Инвестиции» в «Медскан Лаб» сократился с 49% до '
    '39% — 10% вернулись Евгению Туголукову. Сделка изначально включала '
    'пут-опцион «Сбербанк Инвестиции», учитывавшийся в отчётности '
    '«Медскана» как долговое обязательство; 24 октября 2025 года '
    '«Сбербанк Инвестиции» полностью вышли из капитала за 4,767 млрд ₽ — '
    'операция была связана с завершением приобретения сети KDL и '
    'снижением долговой нагрузки «Медскана» перед планируемым IPO.'
)

NEW_SRC = [
    ['Frank Media', 'https://frankmedia.ru/226165'],
    ['Vademecum', 'https://vademec.ru/news/2025/10/28/v-medskane-nazvali-prichinu-sdelki-po-vykhodu-struktury-sberbanka-iz-kholdingovoy-kompanii-gruppy-kd/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    existing_urls = {s[1] for s in deal['src']}
    add_src = [s for s in NEW_SRC if s[1] not in existing_urls]
    new_src = deal['src'] + add_src

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    if add_src:
        print('\n=== src: добавится ===')
        for s in add_src:
            print(s)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
