import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'geac3f614'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Закрыта'

OLD_DATE = '2024-04-08'
NEW_DATE = '2024-04-09'

OLD_EXTRA = (
    'Продажа долей в ООО «Городской супермаркет» (бренд «Азбука вкуса») '
    'совладельцами Invest AG и основателями Evraz миллиардерами '
    'Александром Абрамовым и Александром Фроловым компании АО «Бавэро '
    'групп». Статус сделки — в процессе закрытия. Бенефициары покупателя '
    'в ЕГРЮЛ не раскрываются.'
)
NEW_EXTRA = (
    'Продажа долей в ООО «Городской супермаркет» (бренд «Азбука вкуса») '
    'совладельцами Invest AG и основателями Evraz миллиардерами '
    'Александром Абрамовым и Александром Фроловым компании АО «Бавэро '
    'групп», закрыта 9 апреля 2024 года. В ту же волну вышел и Millhouse '
    'Романа Абрамовича (39,6% долей). Бенефициары покупателя в ЕГРЮЛ не '
    'раскрываются. Уже менее чем через год контроль над сетью перешёл '
    'дальше: в мае 2025 года «Магнит» приобрёл более 81% «Азбуки вкуса» '
    'за 29,65 млрд руб., а в июле 2025 года нарастил долю до 84,05% '
    '(Коммерсантъ) — отдельная, более поздняя сделка.'
)

NEW_SRC = [
    ['BFM.ru', 'https://www.bfm.ru/news/547868'],
    ['Ведомости', 'https://www.vedomosti.ru/business/news/2024/04/08/1030596-partneri-abramovicha-vishli'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8292624'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS
    assert deal['date'] == OLD_DATE
    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== status: станет ===')
    print(NEW_STATUS)
    print('\n=== date: станет ===')
    print(NEW_DATE)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['status'] = NEW_STATUS
        deal['date'] = NEW_DATE
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
