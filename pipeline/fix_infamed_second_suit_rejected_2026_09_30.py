# -*- coding: utf-8 -*-
"""Качество, 30 сентября 2026 (ежедневный прогон 21:37 МСК) — недельная
очередь дочитывания (второй уровень), карточка `gd8faa2c4` (Инфамед/
Хугаева/Хейфиц). Саб-агент нашёл движение ПОСЛЕ даты обыска (23 сентября):
30 сентября тот же суд (Арбитражный суд Московской области) отклонил ВТОРОЙ,
самостоятельный иск Хугаевой к Хейфиц — не тот, что уже описан в карточке
(там Хугаева оспаривала законность декабрьского 2024 года договора как
притворную сделку, а карточка про сентябрьский спор с Николаевым).

Это НОВОЕ судебное событие в той же затяжной тяжбе, не правка уже
записанных полей: добавлено отдельной записью в `events[]`, а не через
FIXES-таблицу `review.py` (там нет механизма добавления новых событий,
только правки уже существующих скалярных полей).

Запуск:
    python3 pipeline/fix_infamed_second_suit_rejected_2026_09_30.py            # сухой прогон
    python3 pipeline/fix_infamed_second_suit_rejected_2026_09_30.py --write    # запись
"""
import json
import sys

DATA_PATH = 'static/data/deals_promoted.json'

NEW_EVENT = {
    'kind': 'court',
    'date': '2026-09-30',
    'title': 'Суд отклонил второй иск Хугаевой',
    'note': ('Арбитражный суд Московской области отклонил ВТОРОЙ (поданный в '
             'марте 2025 года) иск Ирины Хугаевой к Оксане Хейфиц — Хугаева '
             'требовала признать притворной сделкой договор от 28 декабря '
             '2024 года о продаже Хейфиц 50%-ной доли в «Инфамеде», считая, '
             'что он маскировал агентский договор. Суд счёл это недоказанным: '
             'покупатель полностью уплатил продавцу указанную в договоре '
             'сумму — чуть более 7,5 млн ₽, а стороны при нотариальном '
             'заключении договора дали друг другу заверения, что «настоящий '
             'договор не является ни мнимой, ни притворной сделкой». Решение '
             'пока не вступило в силу.'),
    'source': ['ПРАЙМ', 'https://1prime.ru/20260930/sud-873808561.html'],
}


def main(write):
    data = json.load(open(DATA_PATH, encoding='utf-8'))
    deals = data['deals'] if isinstance(data, dict) else data
    target = [d for d in deals if d.get('id') == 'gd8faa2c4']
    assert len(target) == 1, target
    card = target[0]
    assert len(card['events']) == 1, card['events']
    assert not any(e.get('source', [None, None])[1] == NEW_EVENT['source'][1]
                   for e in card['events'])
    card['events'].append(NEW_EVENT)

    if write:
        json.dump(data, open(DATA_PATH, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
        print('Событие 30.09.2026 (отклонён второй иск Хугаевой) добавлено в gd8faa2c4. ЗАПИСАНО.')
    else:
        print('Сухой прогон: добавил бы новое событие в events[] карточки gd8faa2c4. Повторите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
