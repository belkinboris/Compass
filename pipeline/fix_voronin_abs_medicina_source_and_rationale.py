# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g3b91745f
(Владимир Воронин (ФСК) приобрел 10% акций АВС-Медицина) — единственный
источник карточки был Telegram-агрегатором (@dealsma), причины сделки не
названо, дальнейшая судьба покупателя не отслежена.

Настоящий первоисточник — проверено лично прямым WebFetch (Коммерсантъ,
6 ноября 2024 года, kommersant.ru/doc/7282828). Он ПОДТВЕРЖДАЕТ уже
стоящую в карточке структуру сделки (10% в ООО «АВС-Медицина» + доли в
других структурах, а не полный выход Кайбелова — версия саб-агента о
«полном выходе» не подтвердилась при прямой проверке источника, поэтому
структурные поля не меняются) и добавляет причину раздела бизнеса:
«Олег Кайбелов объяснил, что разошелся с партнером относительно видения
развития компании и системы управления» — этого не было ни в одном поле
карточки, добавлено в новое поле `eco.rationale` (у карточки его не было
вовсе).

Дальнейшая судьба покупателя — проверено лично прямым WebFetch
(Коммерсантъ, апрель 2026 года, kommersant.ru/doc/8569255): «Владимир
Воронин 1 апреля увеличил долю в ООО «Врач на дом» с 80% до 100%», выкупив
доли двух других партнёров («Из бизнеса вышли Анатолий Макеев и Игорь
Школьников, которым принадлежало по 10%»); «Сделка прошла на рыночных
условиях» (Артём Мелихов, гендиректор АВС-Медицины). «Врач на дом» —
структура, которую развивает АВС-Медицина (та же группа, что и в этой
карточке), поэтому факт добавлен в `extra` как продолжение консолидации
бизнеса тем же покупателем, а не как отдельная сделка с этой карточкой.

`src` дополнен обоими материалами Коммерсанта (Telegram-агрегатор
остаётся первой записью — правило: `src` аддитивно, ссылка не убирается).

НЕ ВКЛЮЧЕНО: точная сумма сделки (в карточке уже стоит оценка ДМГ,
160–180 млн ₽ — подтверждена тем же источником дословно, не расходится);
состав «других структур», доли в которых также перешли Воронину, —
Коммерсантъ называет их обобщённо, поимённого списка юрлиц нет ни в одном
источнике.

Запуск: python3 pipeline/fix_voronin_abs_medicina_source_and_rationale.py
        python3 pipeline/fix_voronin_abs_medicina_source_and_rationale.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g3b91745f'

OLD_SRC = [['@dealsma (Telegram)', 'https://t.me/dealsma/5485']]
NEW_SRC = OLD_SRC + [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/7282828'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8569255'],
]

NEW_RATIONALE = (
    'Олег Кайбелов объяснил, что разошелся с партнером относительно '
    'видения развития компании и системы управления (Коммерсантъ, '
    '6 ноября 2024 года).'
)

OLD_EXTRA = (
    'Владимир Воронин, владелец ФСК, приобрел 10% акционерного капитала '
    'ООО «АВС-Медицина» и долю в других структурах группы у сооснователя '
    'Олега Кайбелова. Сеть АВС-Медицина включает 14 клиник в Москве, '
    'Подмосковье и Калуге с выручкой 1,36 млрд руб. в 2023 году.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Воронин продолжил консолидацию бизнеса: 1 апреля 2026 года он '
    'довёл долю в ООО «Врач на дом» (структуре, которую развивает '
    'АВС-Медицина) с 80% до 100%, выкупив доли двух других партнёров — '
    '«из бизнеса вышли Анатолий Макеев и Игорь Школьников, которым '
    'принадлежало по 10%». «Сделка прошла на рыночных условиях» (Артём '
    'Мелихов, гендиректор АВС-Медицины, Коммерсантъ, апрель 2026 года).'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['src'] == OLD_SRC
    assert 'rationale' not in deal['eco']
    assert deal['extra'] == OLD_EXTRA

    print('=== src: станет ===')
    for s in NEW_SRC:
        print(s)
    print('\n=== eco.rationale: новое поле ===')
    print(NEW_RATIONALE)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)

    if write:
        deal['src'] = NEW_SRC
        deal['eco']['rationale'] = NEW_RATIONALE
        deal['extra'] = NEW_EXTRA
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
