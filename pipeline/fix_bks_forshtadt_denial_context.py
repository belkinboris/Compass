# -*- coding: utf-8 -*-
"""Месячная очередь, карточка g7299791f («Финансовая группа БКС купила банк
«Форштадт»»): дельта-поиск нашёл серьёзное, НЕ разрешённое до конца
противоречие между статусом карточки («Закрыта») и последующими фактами.

Хронология: Forbes 06.10.2025 сообщил о закрытой сделке. В ТОТ ЖЕ день
БКС и «Форштадт» опровергли информацию (Ведомости, fomag.ru — цитата
опровержения уже дословно лежит в law.struct карточки: «"Данная
информация не соответствует действительности", – ответили "Ведомостям"
в БКС»). Ни один источник за прошедшие почти 10 месяцев это опровержение
не опроверг в свою очередь. Живой поиск (WebSearch/WebFetch, проверено
напрямую) нашёл два независимых факта ПОСЛЕ опровержения:

1. «Эксперт РА» 28.01.2026, подтверждая рейтинг банка, отметило
   существенные изменения в руководстве и совете директоров — то есть
   реальная перестройка в банке произошла, но рейтинговое агентство НЕ
   называет БКС и не подтверждает смену собственника.
2. Агрегатор topbanki.ru на срез 27.07.2026 называет ТЕХ ЖЕ трёх именных
   владельцев банка (Левин 50%, Екавян 43%, Черный 6,82%), что и до
   истории с БКС, — БКС среди собственников не значится.

Это НЕ доказывает окончательно, что сделка не состоялась (агрегатор —
не первичный реестр ЦБ/ЕГРЮЛ, доступ к которым в этой сессии закрыт),
но веско ставит под сомнение статус «Закрыта». Ни один источник не несёт
слова, дословно подтверждающего один из статусов STATUS_WORDS
(review.py) — ни «Закрыта», ни «Не состоялась», ни «Обсуждается» — само
опровержение и отсутствие изменений в реестре не являются механически
проверяемой цитатой. Поэтому статус НЕ меняется этим скриптом: это
решение записано отдельно в PRODUCT_ROADMAP.md («Известные проблемы»)
для человека. Задача этого скрипта — только зафиксировать в самой
карточке (eco.context) обе стороны картины, дословно и с источниками,
чтобы читатель видел контекст сомнения, а не только исходное «Закрыта».

Источники (читал напрямую, fetch_article_texts.py, закэшированы):
raexpert.ru/releases/2026/jan28b, topbanki.ru/bank/forshtadt/.

Запуск: python3 pipeline/fix_bks_forshtadt_denial_context.py [--write]
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g7299791f'

OLD_CONTEXT = (
    'Основными совладельцами банка значились ООО «Энергоинвест» (50%), '
    'бенефициаром которого является Сергей Левин, Арам Екавян (43,08%) и '
    'Сергей Черный (6,81%), возглавляющий крупного производителя соли ООО '
    '«Руссоль».'
)
CONTEXT_ADDITION = (
    'Рейтинговое агентство «Эксперт РА» 28 января 2026 года, подтвердив '
    'банку рейтинг ruBB+ со сменой прогноза на «развивающийся», отметило '
    'существенные изменения в руководстве Банка, включая обновление '
    'топ-менеджмента и состава совета директоров, но не назвало БКС и не '
    'подтвердило смену собственника. По данным агрегатора topbanki.ru на '
    '27 июля 2026 года структура именных владельцев банка не изменилась: '
    '50% — Сергей Левин, 43% — Арам Екавян, 6,82% — Сергей Черный; БКС '
    'среди собственников не значится. Опровержение БКС и «Форштадта» от '
    '6 октября 2025 года с тех пор ничем не было опровергнуто ни одним '
    'источником.'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + CONTEXT_ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} eco.context: += рейтинг «Эксперт РА» о перестройке "
          f"руководства + срез реестра собственников 27.07.2026 (БКС не "
          f"значится) — статус «Закрыта» под сомнением, решение за "
          f"человеком (см. PRODUCT_ROADMAP.md)")
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
