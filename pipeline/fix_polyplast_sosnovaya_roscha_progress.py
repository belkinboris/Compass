import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gc5eb971c'

OLD_CONTEXT = (
    'До 1992 года санаторий входил в систему здравниц высшего '
    'руководства страны. С 1992 по 2006 год санаторием владело ПО '
    '«Нижневартовскнефтегаз».'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' В 2025-2026 годах комплекс реконструируется с расширением на '
    'территорию бывшего санатория «Марат»: «На реализацию проекта '
    'заложено свыше 12 млрд рублей», «Номерной фонд превысит 190 '
    'номеров», объединённый комплекс получит имя «Сосновая Роща 4*»; '
    'восстановлены канатная дорога и парк «Можжевеловая роща» (1,7 га) — '
    'председатель совета директоров АО «Полипласт» Александр '
    'Шамсутдинов лично представлял объекты в июне 2026. По данным ЕГРЮЛ, '
    '11 ноября 2025 года учредителем ООО «Санаторий «Сосновая Роща»» '
    'вместо «Полипласт Новомосковск» стало ООО «Молодечно» — связь этой '
    'структуры с группой «Полипласт» в открытых источниках не '
    'установлена.'
)

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/pressreleases/1096706'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8740857'],
    ['audit-it.ru', 'https://www.audit-it.ru/contragent/1149102128328_ooo-sanatoriy-sosnovaya-roshcha'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
