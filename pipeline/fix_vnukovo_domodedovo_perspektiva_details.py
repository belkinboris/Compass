# -*- coding: utf-8 -*-
"""Месячная очередь качества, 11 сентября 2026 — карточка `g94268c8d`
(«„Внуково" приобрело 25,01% в контролирующей „Домодедово" компании»,
август 2026) не называла ни консультаций с ФАС, ни хода структурной
реорганизации самого «Домодедово» после сделки — оба факта прозвучали в
статьях, вышедших ПОЗЖЕ первой публикации карточки. `law.appr` был пуст.

Личный WebFetch подтвердил дословно:
- Интерфакс (https://www.interfax.ru/business/1104636, 21 июля 2026,
  18:13), Виталий Ванцев, глава совета директоров «Внуково»: «Прежде чем
  войти в сделку, мы провели консультации с ФАС. Получили от нее
  представления, которые предполагают, что мы не будем повышать тарифы
  более чем на 7% в год».
- Интерфакс (https://www.interfax.ru/business/1108047, 7 августа 2026,
  12:53): «вместо 26 „разрозненных" компаний группы было сформировано
  семь»; «определено количество сотрудников, которые будут работать в
  „Домодедово" — 6,8 тысячи человек».

Формального решения ФАС/правкомиссии (одобрение или отказ) ни один из
проверенных источников не называет — только факт консультаций и
принятые «Внуково» тарифные обязательства; это записано как есть, без
подмены на «одобрено». Более поздних новостей о едином билете,
брендинге или судьбе Дмитрия Каменщика (после отказа Верховного суда
10 марта 2026) не нашлось — сумма и мотивы сторон в карточке уже полны.

Запуск:
    python3 pipeline/fix_vnukovo_domodedovo_perspektiva_details.py            # сухой прогон
    python3 pipeline/fix_vnukovo_domodedovo_perspektiva_details.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_LAW_APPR = '—'
NEW_LAW_APPR = (
    'Перед сделкой «Внуково» провело консультации с ФАС и получило от '
    'неё представления, ограничивающие рост тарифов «Домодедово» не '
    'более чем на 7% в год — формального решения ФАС или правкомиссии '
    'об одобрении сделки источники не называют.'
)

OLD_LAW_STRUCT = (
    'АО «Международный аэропорт Внуково» подало заявление о принятии в '
    'состав участников ООО «Перспектива» и внесло в её уставный капитал '
    '16,5 млрд рублей, получив долю 25,01%.'
)

NEW_LAW_STRUCT = OLD_LAW_STRUCT + (
    ' После сделки структуру группы реорганизовали: вместо 26 отдельных '
    'юрлиц сформировано семь, штат «Домодедово» определён в 6,8 тыс. '
    'человек.'
)

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/business/1104636'],
    ['Интерфакс', 'https://www.interfax.ru/business/1108047'],
]


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['g94268c8d']

    assert d['law'].get('appr') == OLD_LAW_APPR, 'law.appr уже занят: %r' % (d['law'].get('appr'),)
    assert d['law'].get('struct') == OLD_LAW_STRUCT, 'law.struct изменился: %r' % (d['law'].get('struct'),)
    urls = {s[1] for s in d['src']}
    for src in NEW_SRC:
        assert src[1] not in urls, 'источник уже добавлен: %s' % src[1]

    print('g94268c8d: law.appr заполнен (консультации с ФАС, тарифное '
          'ограничение 7% в год); law.struct дополнен (реорганизация '
          '26 юрлиц в 7, штат 6,8 тыс.); добавлено 2 источника')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['law']['appr'] = NEW_LAW_APPR
    d['law']['struct'] = NEW_LAW_STRUCT
    d['src'].extend(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
