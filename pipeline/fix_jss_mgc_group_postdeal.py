import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gf845980e'

OLD_TARGET_FIN = (
    'Российское подразделение — ООО «Джойсон Сейфти Системс Рус» — '
    'управляет заводом в Ульяновске. В 2023 году выручка местной '
    'компании выросла на 86,4%, до 3,88 млрд руб., чистая прибыль '
    'увеличилась в 2,4 раза, до 547,7 млн руб. Как сказано в отчетности '
    'общества, около 38% продаж пришлось на ремни, 31% — на рули, 26,6% '
    '— на подушки безопасности.'
)
NEW_TARGET_FIN = OLD_TARGET_FIN + (
    ' Рост продолжился под новым владельцем: в 2024 году выручка выросла '
    'на 40% до 5,4 млрд руб., валовая прибыль — на 26% до 1 млрд руб., '
    'чистая прибыль — на 14,6% до 627,9 млн руб. Структура выручки '
    'изменилась: треть (1,7 млрд руб.) пришлась на подушки безопасности, '
    'столько же — на рули, на ремни — лишь 193,9 млн руб. (было 38% в '
    '2023 году), также появились торговля (1,4 млрд руб.) и выполнение '
    'работ (361,5 млн руб.) (profinansy.ru).'
)

OLD_EXTRA = (
    'Продажа 100% долей ООО «Джойсон Сейфти Системс Рус» (завод в '
    'Ульяновске, производство ремней, рулей, подушек безопасности). '
    'Получено согласие ФАС.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Покупатель MGC Group («Эм Джи Си Груп») создан на базе '
    'консолидированных активов канадской Magna в России; гендиректор '
    'Павел Середа ранее возглавлял Горьковский автозавод. В конце '
    '2025 года холдинг продолжил консолидацию: приобрёл у испанской '
    'Grupo Antolin предприятия по выпуску элементов интерьера в '
    'Ленинградской области и Поволжье (Интерфакс).'
)

NEW_SRC = [
    ['profinansy.ru', 'https://lenta.profinansy.ru/news/3741389'],
    ['Интерфакс', 'https://www.interfax.ru/business/1000148'],
    ['Интерфакс', 'https://www.interfax.ru/business/1092800'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['target_fin'] == OLD_TARGET_FIN
    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== eco.target_fin: станет ===')
    print(NEW_TARGET_FIN)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['target_fin'] = NEW_TARGET_FIN
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
