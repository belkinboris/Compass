# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
`g1fa32c96` («ОМК приобрела Оскольский завод металлургического
машиностроения», декабрь 2023, Закрыта) — финансовая судьба завода
после перехода к ОМК и планы расширения не прослеживались.

Проверено ЛИЧНО прямым WebFetch (дословные цитаты):
- kommersant.ru/doc/7624454 (итоги 2024 года): «Завод завершил 2024 год
  с чистым убытком в 420,8 млн руб., что в 5,4 раза больше, чем в
  2023-м (77,4 млн руб.)»; выручка «с 1,8 млрд до 2,2 млрд руб.» (+22%);
  «ОЗММ перешел под контроль ОМК в конце 2023 года»; гендиректор Сергей
  Косулин занимает должность по настоящее время;
- fonar.tv/news/2026/07/28/omk-otkazalas-ot-stroitelstva-zavoda-za-42-milliarda-v-starom-oskole:
  завод бесшовных нержавеющих труб в Старом Осколе (стоимость выросла с
  34,6 до 42,2 млрд ₽) — «работы сейчас не ведутся», формального отказа
  в правительство область не поступало; названные ОМК причины —
  «охлаждение экономики» России, экспортные ограничения, высокая
  ключевая ставка, а также собственные убытки ОЗММ.

НЕ ВНЕСЕНО: (1) точная дата перехода прав (день/месяц) в дополнение к
уже стоящему в карточке «12 декабря» — interfax.ru/business/940315
подтверждает сумму (604 545,4 тыс. ₽, та же оценка, что уже стоит в
`eco.val`), но не называет более точной даты, чем уже известная; (2)
расхождение оценок стоимости проекта труб (35 млрд у «Ъ» против 42,2
млрд у fonar.tv) не разрешено — это, по всей видимости, рост сметы со
временем, а не спор источников, но отдельно не проверялось; (3) фраза
fonar.tv про «убыток 2 млрд рублей в прошлом году» у ОЗММ не совпадает
с цифрой Коммерсанта (420,8 млн ₽ за 2024 год) — расхождение оставлено
как есть, не подгонялось под удобную цифру.

Запуск: python3 pipeline/fix_omk_ozmm_2024_financials_and_stalled_expansion.py
        python3 pipeline/fix_omk_ozmm_2024_financials_and_stalled_expansion.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g1fa32c96'

OLD_ECO_CONTEXT = '—'
NEW_ECO_CONTEXT = (
    'По итогам 2024 года завод показал выручку 2,2 млрд ₽ (рост на 22% '
    'к 1,8 млрд ₽ годом ранее), но чистый убыток вырос в 5,4 раза — до '
    '420,8 млн ₽ (77,4 млн ₽ в 2023 году). Гендиректор от ОМК Сергей '
    'Косулин по-прежнему занимает должность. Соседний проект ОМК — '
    'завод бесшовных нержавеющих труб в Старом Осколе стоимостью '
    '34,6–42,2 млрд ₽ — по состоянию на июль 2026 года не строится: '
    'формального отказа компания в региональные власти не подавала, но '
    'работы не ведутся; среди названных причин — охлаждение экономики, '
    'экспортные ограничения, высокая ключевая ставка и собственные '
    'убытки завода.'
)

OLD_SRC = [
    ['Абирег', 'https://abireg.ru/newsitem/100861/'],
]
NEW_SRC = OLD_SRC + [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/7624454'],
    ['Interfax', 'https://www.interfax.ru/business/940315'],
    ['Fonar.tv', 'https://fonar.tv/news/2026/07/28/omk-otkazalas-ot-stroitelstva-zavoda-za-42-milliarda-v-starom-oskole'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
