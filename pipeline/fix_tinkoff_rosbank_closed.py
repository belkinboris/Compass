import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g3d9af03c'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Закрыта'
OLD_DATE = '2024-03-14'
NEW_DATE = '2025-01-01'

OLD_VAL = (
    'Росбанк в рамках сделки по интеграции в «ТКС Холдинг» может быть '
    'оценен с мультипликатором в 0,9–1,1 капитала. На такую оценку '
    'рассчитывает совет директоров «ТКС Холдинга», исходя из рыночных '
    'бенчмарков.'
)
NEW_VAL = OLD_VAL + (
    ' По факту закрытия сделки председатель совета директоров ТКС '
    'Холдинга Алексей Малиновский заявил: «фактический мультипликатор '
    'приобретения Росбанка составил 0,8 его общего капитала» — ниже '
    'предварительной оценки.'
)

OLD_CONTEXT = (
    'Основными акционерами Росбанка являются компания «Интеррос» '
    'Владимира Потанина (45%) и созданный им благотворительный фонд '
    '(47,5%). Еще 7,5% находятся на балансе компании «Русфинанс» '
    '(принадлежит Росбанку) в рамках мотивационной программы '
    'сотрудников банка.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' 15-16 августа 2024 года «ТКС Холдинг» получил контроль над '
    '99,4062% акций Росбанка. «Интеррос», оплатив долю в допэмиссии '
    'ТКС Холдинга акциями Росбанка, нарастил свою долю в головной '
    'компании с 35,1% до 41,4%, став крупнейшим неконтролирующим '
    'акционером. С 1 января 2025 года Росбанк официально стал частью '
    'Т-Банка, завершив присоединение в качестве филиала и утратив '
    'собственную лицензию — при этом, по словам представителя Т-Банка, '
    '«для них будут сохранены бренды L\'Hermitage и Росбанк» в '
    'сегментах private banking и работы с крупным и средним бизнесом.'
)

OLD_APPR = 'Публично не сообщалось'
NEW_APPR = (
    '25 декабря 2024 года Банк России зарегистрировал дополнительный '
    'выпуск акций Т-Банка, размещаемых в рамках конвертации в акции '
    'присоединяемого Росбанка (Интерфакс).'
)

NEW_SRC = [
    ['РИА Новости', 'https://ria.ru/20240816/holding-1966709868.html'],
    ['РИА Новости', 'https://ria.ru/20250101/banki-1992228779.html'],
    ['RB.RU', 'https://rb.ru/news/interros-tcs-41/'],
    ['Ведомости', 'https://www.vedomosti.ru/finance/articles/2024/09/11/1061618-rosbank-stanet-filialom-t-banka'],
    ['Интерфакс', 'https://www.interfax.ru/business/1003324'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS, deal['status']
    assert deal['date'] == OLD_DATE, deal['date']
    assert deal['eco']['val'] == OLD_VAL
    assert deal['eco']['context'] == OLD_CONTEXT
    assert deal['law']['appr'] == OLD_APPR, deal['law']['appr']
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== status: было / станет ===')
    print(OLD_STATUS, '->', NEW_STATUS)
    print('=== date: было / станет ===')
    print(OLD_DATE, '->', NEW_DATE)
    print('\n=== eco.val: станет ===')
    print(NEW_VAL)
    print('\n=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== law.appr: станет ===')
    print(NEW_APPR)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['status'] = NEW_STATUS
        deal['date'] = NEW_DATE
        deal['eco']['val'] = NEW_VAL
        deal['eco']['context'] = NEW_CONTEXT
        deal['law']['appr'] = NEW_APPR
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
