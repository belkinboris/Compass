# -*- coding: utf-8 -*-
"""Два поля `eco.val` несли один и тот же текст оценки ДВАЖДЫ подряд:
сначала как обычное предложение, потом снова — в скобках, с числом впереди
(«…не раскрывается; 250–350 млн ₽ (…не раскрывается)»). Похоже на след более
ранней правки, дописавшей отформатированную версию значения и не убравшей
исходную.

Почему не через `review.py`: механизм таблицы `FIXES` требует, чтобы новое
значение дословно лежало в цитате ИЗ ИСТОЧНИКА. Здесь чинится не перенос
факта из статьи, а внутренняя порча уже существующего значения базы — сама
формулировка («оценка Dsight, официально не раскрывается…») не встречается
в кэше источника слово в слово, это старый аналитический пересказ, а не
цитата. Резать его тем не менее можно: он не добавляет нового факта, только
убирает самоповтор, и вторая половина (та, что в скобках) буквально
содержится в исходном значении — проверено `assert`.

Запуск: python3 pipeline/dedupe_eco_val_self_repeat.py           # проверка
        python3 pipeline/dedupe_eco_val_self_repeat.py --write   # запись
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.join(os.path.dirname(ROOT), 'static', 'data', 'deals_promoted.json')

FIXES = {
    'g7e81d8e7': (
        'Оценка Dsight, официально не раскрывается; возможен дисконт ввиду '
        'падения выручки на 34,7% в 2025 году; 250–350 млн ₽ (оценка Dsight, '
        'официально не раскрывается; возможен дисконт ввиду падения выручки '
        'на 34,7% в 2025 году)',
        '250–350 млн ₽ (оценка Dsight, официально не раскрывается; возможен '
        'дисконт ввиду падения выручки на 34,7% в 2025 году)',
    ),
    'g2777a4b6': (
        'Оценка сооснователя «МойОфис» Дмитрия Комиссарова, приводимая '
        '«Ведомостями»; vc.ru указывает диапазон 80–100 млн руб. со ссылкой на '
        'экспертов; официально сумма не раскрывается; около 100 млн ₽ (оценка '
        'сооснователя «МойОфис» Дмитрия Комиссарова, приводимая «Ведомостями»; '
        'vc.ru указывает диапазон 80–100 млн ₽ со ссылкой на экспертов; '
        'официально сумма не раскрывается)',
        'около 100 млн ₽ (оценка сооснователя «МойОфис» Дмитрия Комиссарова, '
        'приводимая «Ведомостями»; vc.ru указывает диапазон 80–100 млн ₽ со '
        'ссылкой на экспертов; официально сумма не раскрывается)',
    ),
}


def main(write=False):
    data = json.load(open(BASE, encoding='utf-8'))
    cards = {d['id']: d for d in data['deals']}
    for cid, (old, new) in FIXES.items():
        card = cards[cid]
        assert card['eco']['val'] == old, '%s: значение уже другое' % cid
        assert new in old, '%s: новое значение — не часть старого' % cid
        print('ПРАВИМ  %s eco.val: снят самоповтор' % cid)
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return
    for cid, (_old, new) in FIXES.items():
        cards[cid]['eco']['val'] = new
    json.dump(data, open(BASE, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
