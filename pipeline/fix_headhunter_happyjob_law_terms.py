# -*- coding: utf-8 -*-
"""«HeadHunter приобрел 51% компании Happy Job» (`gebead2e8`) — `law.terms`
несло дословную, но НЕ ПОДХОДЯЩУЮ по смыслу цитату: «Стандарты, методика,
контроль качества, бенчмаркинг и порядок присуждения сертификатов
«Отличное место для работы» останутся неизменными и будут соответствовать
мировым практикам.»

Это не условие СДЕЛКИ (не индемнити, не заверение, не earn-out, не
обязательство сохранить бренд/команду/производство — та категория, для
которой поле вообще заведено), а фраза-заверение из пресс-релиза,
адресованная клиентам сертификации Happy Job («ваш сертификат остаётся
действительным») — про то, как продолжает работать ПРОДУКТ цели, а не про
то, на каких условиях HeadHunter его купил. review.py дословность значения
проверил верно (цитата реальна, взята из TAdviser) — но дословность не
означает уместность: поле `law.terms` для условий сделки, а не для описания
продукта цели.

Docstring FIXES-записи (`batch_2026_08_19.py`) сам подтверждает, что
согласований, консультантов и договорных условий не нашлось НИ В ОДНОМ из
девяти прочитанных источников — то есть настоящего материала для линзы
«Юрист» у этой карточки нет вовсе, и честное пустое состояние (вкладка не
рендерится, см. правило 18 августа) точнее, чем это единственное
подтянутое за уши предложение.

Карточка изначально стояла в `static/data/pending.json` (очередь на
решение); пока эта правка готовилась, владелец одобрил её кнопкой в
Telegram, и она уже промоутнута рутиной публикации в
`static/data/deals_promoted.json` — правка нацелена туда, а не в pending.

Запуск: python3 pipeline/fix_headhunter_happyjob_law_terms.py           # проверка
        python3 pipeline/fix_headhunter_happyjob_law_terms.py --write   # запись
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gebead2e8'
OLD_TERMS = ('Стандарты, методика, контроль качества, бенчмаркинг и порядок '
             'присуждения сертификатов «Отличное место для работы» останутся '
             'неизменными и будут соответствовать мировым практикам.')


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    card = next((c for c in data['deals'] if c['id'] == CARD_ID), None)
    assert card is not None, '%r не найдена в deals_promoted.json' % CARD_ID
    assert card['law'].get('terms') == OLD_TERMS, (
        'ожидали law.terms=%r, сейчас %r — состояние изменилось'
        % (OLD_TERMS, card['law'].get('terms')))

    print('ПРАВИМ %s: law.terms -> «—» (нет настоящих условий сделки ни в одном '
          'из девяти источников — честная пустота вместо продуктовой фразы)' % CARD_ID)
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    card['law']['terms'] = '—'
    json.dump(data, open(DATA, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
