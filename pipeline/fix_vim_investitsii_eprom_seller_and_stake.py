# -*- coding: utf-8 -*-
"""Месячная очередь, 9 сентября 2026 — дочитывание карточки `gd3769bb9`
(«"ВИМ Инвестиции" приобрели долю в производителе зарядных станций
"E-ПРОМ"», добавлена в базу 8 сентября 2026).

Дельта-поиск (саб-агент + личная проверка) нашёл два новых факта.

1) Размер купленной доли уже был известен из пресс-релиза Advance Capital
   (финансовый консультант продавца), но не перенесён в `eco.share`:
   «...эксклюзивным финансовым консультантом Е-ПРОМ в сделке по продаже
   49,99% долей фонду «ВИМ Инвестиции»» (advancecapital.ru, уже в `src`).

2) Продавец. Личный WebFetch (audit-it.ru/contragent/1241600045939_ooo-e-prom)
   подтвердил дословно раздел «Учредители»: единственными участниками
   ООО «Е-ПРОМ» (ИНН 1673007192) названы «Валиев Булат Халимович» (с
   02.10.2024) и «ЗАКРЫТЫЙ ПАЕВОЙ ИНВЕСТИЦИОННЫЙ КОМБИНИРОВАННЫЙ ФОНД
   «ФОНД ПРЕ-АЙПИО 2»» (с 29.07.2025, — это и есть покупатель по этой
   карточке). Осторожность: это данные реестрового АГРЕГАТОРА, не прямая
   выписка ЕГРЮЛ, и точный процент долей на странице скрыт — имя продавца
   внесено в `eco.context` с честной атрибуцией источнику, а не в
   структурное поле `seller` (тот же класс осторожности, что уже применён
   к другим карточкам этого раздела: реестровый агрегатор весом, но не
   заменяет прямую выписку).

Также добавлен независимый источник — Ведомости (23.09.2025), личный
WebFetch подтвердил: «Фонд Pre-IPO 2 под управлением АО «ВИМ инвестиции»
приобрел долю в капитале компании Е-ПРОМ» — статья не называет ни
продавца, ни размер доли, но это первое подтверждение сделки независимым
деловым СМИ, а не только объявлением юрфирмы и пресс-релизом консультанта.

НЕ внесено: юридический консультант продавца (ни один источник не назвал),
планы IPO компании (название фонда — намёк, не факт).

Запуск:
    python3 pipeline/fix_vim_investitsii_eprom_seller_and_stake.py            # сухой прогон
    python3 pipeline/fix_vim_investitsii_eprom_seller_and_stake.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_ECO_SHARE = 'Куплена доля в компании «E-ПРОМ», её размер не назван.'
NEW_ECO_SHARE = (
    'Фонд купил 49,99% долей в уставном капитале компании «E-ПРОМ» — эту '
    'цифру называет финансовый консультант продавца, Advance Capital.'
)

OLD_ECO_CONTEXT = (
    '«E-ПРОМ» — один из лидеров рынка производства зарядных станций для '
    'электромобилей: поставила более 1400 быстрых электрозарядных станций '
    'в 42 региона России, продукция входит в реестр промышленной '
    'продукции Минпромторга.'
)
NEW_ECO_CONTEXT = OLD_ECO_CONTEXT + (
    ' По данным ЕГРЮЛ (реестровый агрегатор audit-it.ru), единственным '
    'учредителем ООО «Е-ПРОМ» до входа фонда был Булат Валиев.'
)

NEW_SRC = ['Ведомости', 'https://www.vedomosti.ru/investments/news/2025/09/23/1141325-vim-e-prom']


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['gd3769bb9']

    assert d['eco']['share'] == OLD_ECO_SHARE, \
        'gd3769bb9 eco.share уже другой: %r' % (d['eco']['share'],)
    assert d['eco']['context'] == OLD_ECO_CONTEXT, \
        'gd3769bb9 eco.context уже другой: %r' % (d['eco']['context'],)
    urls = {s[1] for s in d['src']}
    assert NEW_SRC[1] not in urls, 'источник уже добавлен'

    print('gd3769bb9: eco.share дополнен (доля 49,99%); eco.context '
          'дополнен (продавец по данным ЕГРЮЛ — Булат Валиев); добавлен '
          'источник vedomosti.ru')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['eco']['share'] = NEW_ECO_SHARE
    d['eco']['context'] = NEW_ECO_CONTEXT
    d['src'].append(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
