# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка g6fe7016f («Ростелеком»/
ОМП/«Аврора»): три находки дельта-поиска.

1. `law.struct` нёс снимок СЕРЕДИНЫ сделки («Ростелеком пока владеет
   75%») — источник карточки писал это на момент публикации, до
   закрытия. Хабр (5 октября 2023) подтверждает: сделка закрылась,
   3 октября 2023 года «Ростелеком» официально стал владельцем 99,9%.
   Это не дополнение, а замена устаревшего факта верным.
2. `law.terms` уже нёс противоречие: со слов источника Ъ Березкин
   «должен был» сохранить 0,1% для доли от выручки, но «источник
   утверждает, что бизнесмен вышел из актива полностью». Итоговая доля
   «Ростелекома» — 99,9%, А НЕ 100% (тот же Хабр) — то есть 0,1% в
   юрлице у кого-то остались, что напрямую опровергает анонимное
   утверждение о полном выходе. Дописано разрешение противоречия.
3. `eco.context` не знал о судьбе проекта дальше 2019 года (списание
   убытков) — Коммерсантъ (2025) сообщает о новом продукте на той же
   ОС, «Аврора ТВ».

Источники: Хабр (два материала, сентябрь-октябрь 2023) и Коммерсантъ
(doc/8671023, 2025) — все читал напрямую. Не через review.py: замена
устаревшего факта (не дословная правка «пустое -> заполненное») и
объединение источников для law.terms/eco.context.
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g6fe7016f'

OLD_STRUCT = (
    'По данным «Контур.Фокуса», «Ростелеком» пока владеет 75% юрлица, '
    '25% у ООО «Открытая мобильная платформа — центр разработки», '
    'связанного с Григорием Березкиным.'
)
NEW_STRUCT = (
    'Сделка закрыта: по данным на 3 октября 2023 года, «Ростелеком» '
    'официально стал владельцем 99,9% разработчика ОС «Аврора» — '
    'выкуп оставшихся 25% доли ООО «Открытая мобильная платформа — '
    'центр разработки», связанного с Григорием Березкиным, завершён.'
)

OLD_TERMS = (
    'У Григория Березкина должно было остаться 0,1% для получения доли '
    'от выручки с проектов на ОС «Аврора» в течение 20 лет. Но источник '
    'издания утверждает, что бизнесмен вышел из актива полностью.'
)
TERMS_ADDITION = (
    'Итоговая доля «Ростелекома» после закрытия сделки составила 99,9%, '
    'а не 100% (Хабр, 5 октября 2023) — то есть 0,1% в юрлице '
    'действительно сохранились за третьей стороной, что расходится с '
    'утверждением анонимного источника о полном выходе Березкина.'
)
NEW_TERMS = OLD_TERMS + ' ' + TERMS_ADDITION

OLD_CONTEXT = (
    'В 2015 году Григорий Березкин стал основным владельцем Jolla, '
    'финского разработчика операционной системы Sailfish, созданного '
    'экс-сотрудниками Nokia. В 2016 году для адаптации ОС к российскому '
    'рынку была создана ОМП. В 2018 году «Ростелеком» выкупил 75% за '
    '3,3 млрд руб., а Sailfish переименовали в «Аврору». По итогам 2019 '
    'года оператор списал на убытки 2,3 млрд руб. инвестиций в проект.'
)
CONTEXT_ADDITION = (
    'В 2025 году «Ростелеком» объявил о запуске производства умных '
    'телевизоров на базе операционной системы «Аврора ТВ»: первая '
    'партия может составить 150–200 тыс. устройств до конца 2026 года, '
    'основным заказчиком ожидается госсектор, в планах компании — '
    'занять до 30% рынка смарт-ТВ в перспективе трёх лет.'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + CONTEXT_ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['law']['struct'] == OLD_STRUCT, \
        f"law.struct: неожиданное значение {deal['law']['struct']!r}"
    assert deal['law']['terms'] == OLD_TERMS, \
        f"law.terms: неожиданное значение {deal['law']['terms']!r}"
    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} law.struct: замена устаревшего снимка (75%) на "
          "закрытие сделки (99,9%, 3 октября 2023)")
    print(f"{CARD_ID} law.terms: += разрешение противоречия про 0,1% "
          "Березкина")
    print(f"{CARD_ID} eco.context: += запуск «Аврора ТВ» (2025)")
    deal['law']['struct'] = NEW_STRUCT
    deal['law']['terms'] = NEW_TERMS
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
