import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gcdd1b337'

OLD_BUYER_NAME = None
NEW_BUYER_NAME = 'Олег Малис (через собственные структуры)'

OLD_ECO_CONTEXT = (
    'Ранее к ретейлеру подали многомиллиардные иски, и сейчас компания '
    'находится в предбанкротном состоянии.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' Покупателем позже уверенно назывались структуры '
    'Олега Малиса — совладельца сети через кипрскую DTS Retail LTD '
    '(69,25% в «Сети Связной»). Предбанкротное состояние обернулось '
    'реальным банкротством: 12 декабря 2023 года суд признал ООО «Сеть '
    'Связной» банкротом по искам на 18 млрд ₽. В ноябре 2025 года суд '
    'утвердил мировое соглашение, простив кредиторам около 45 млрд ₽ '
    'долга; на конец 2025 года выручка сети — нулевая, чистые активы '
    'отрицательны (минус 22 млрд ₽). 8 мая 2026 года на торгах '
    'конкурсной массы 5,6% в «Сети Связной» и контрольный пакет DTS '
    'Retail купил Сергей Фролов, бывший вице-президент ВЭБ.РФ и '
    'топ-менеджер «Ростелекома».'
)

OLD_SRC = [['РБК', 'https://www.rbc.ru/technology_and_media/05/12/2022/638b11529a79473003a808d1?fbclid=IwAR2H82xR5lbhGspPNlz4ny5E0MDgd35Vy9UygQL_lH8PVrBPMLePYdwq8EM']]
NEW_SRC = OLD_SRC + [
    ['Ведомости', 'https://www.vedomosti.ru/technology/articles/2022/12/06/953870-pokupatelem-doli-megafona-v-svyaznom-mog-vistupit-malis'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6395924'],
    ['CNews', 'https://www.cnews.ru/news/top/2026-05-08_dolyu_v_razorivshejsya_seti'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal.get('buyer_name') == OLD_BUYER_NAME
    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== buyer_name: станет ===')
    print(NEW_BUYER_NAME)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['buyer_name'] = NEW_BUYER_NAME
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
