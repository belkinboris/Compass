# -*- coding: utf-8 -*-
"""Карточка g99be4c1d («Ponsse продала российский бизнес компании «Бизон»»)
несла 2025 год вместо 2023.

ЧТО СЛОМАНО. Поле `date` стояло «2025-09-25». Источник — статья 47news с
заголовком «Теперь точно всё. Финский производитель техники для
лесозаготовки Ponsse покинул Горелово и Тихвин», датированная «15:00
26.09.2023», и текст называет тот же день сделки прямо: «как стало известно
47news, 25 сентября финский производитель лесозаготовительных машин Ponsse
Pls завершил сделку по продаже своего российского бизнеса». Совпадение дня и
месяца (25 сентября) с ошибочным годом карточки — ровно тот класс дефекта,
что уже описан в CLAUDE.md («Дата новости — не дата сделки»): разбор притока
взял день и месяц верно, а год приписал год притока/повторного забора статьи
вместо года самого события.

ПОЧЕМУ НЕ ЧЕРЕЗ `review.py`. `date_is_supported()` намеренно запрещает менять
год — перенос года обязан быть отдельным, явным решением с проверяемым
источником, а не автоматической правкой в общей таблице (см. урок про
g6d73538c / «Основа»/промзона «Свиблово»).

ПОЧЕМУ ПОЛНАЯ ДАТА, А НЕ ТОЛЬКО ГОД. В отличие от «Основы», источник называет
не только год, но и точный день и месяц («25 сентября», подтверждено датой
публикации статьи «26.09.2023» — на следующий день после закрытия сделки).
Ничего не приходится досочинять.

Запуск:
    python3 pipeline/fix_ponsse_bizon_date.py            # сухой прогон
    python3 pipeline/fix_ponsse_bizon_date.py --write    # записать
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'
DEAL_ID = 'g99be4c1d'
OLD_DATE = '2025-09-25'
NEW_DATE = '2023-09-25'
QUOTE = ('как стало известно 47news, 25 сентября финский производитель '
         'лесозаготовительных машин Ponsse Pls завершил сделку по продаже '
         'своего российского бизнеса — статья 47news датирована 26.09.2023')


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}
    deal = by_id.get(DEAL_ID)
    assert deal is not None, 'нет сделки %s' % DEAL_ID
    assert deal.get('date') == OLD_DATE, \
        'дата уже другая: %r, ожидали %r' % (deal.get('date'), OLD_DATE)

    print('%s: date %r -> %r' % (DEAL_ID, OLD_DATE, NEW_DATE))
    print('  цитата: %r' % QUOTE)

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    deal['date'] = NEW_DATE
    assert deal['date'] == NEW_DATE, 'дата не записалась'

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
