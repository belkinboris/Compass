def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    changes = []
    for did, old in FIXES.items():
        eco = by_id[did].setdefault('eco', {})
        actual = eco.get('val')
        assert actual == old, f'{did}.eco.val: ожидали {old!r}, нашли {actual!r}'
        changes.append((did, old))
        if write:
            eco['val'] = '—'

    print(f'правок: {len(changes)}')
    for did, old in changes[:15]:
        print(f'  {did}: {old!r} -> \'—\'')
    if len(changes) > 15:
        print(f'  ...и ещё {len(changes) - 15}')

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=1, ensure_ascii=False)
        print('\nЗАПИСАНО в', PATH)
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
