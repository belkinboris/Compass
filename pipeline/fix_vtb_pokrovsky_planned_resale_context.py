# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка g2668950b (ВТБ приобрела
агрохолдинг «Покровский» у Росимущества, декабрь 2024): дельта-поиск нашёл,
что ВТБ не намерен развивать актив внутри группы, а готовит его продажу —
глава ВТБ Андрей Костин в апреле 2026 года публично объявил решение продать
сельскохозяйственные активы («Будем только в городе работать»), назвал
предстоящий конкурс по агрокомплексу «Лабинский» (управляет «Покровским») и
причину — новое регулирование ЦБ с 1 апреля 2027 года, ограничивающее вложения
банков в непрофильные активы. «Коммерсантъ» (тем же месяцем) даёт оценку
портфеля (>55 млрд ₽), срок продажи (к 2027 году) и вероятных претендентов.
Не через review.py: цитаты из НОВЫХ источников (south.vedomosti.ru,
kommersant.ru) в поле, уже содержащем текст из другого источника (история
национализации до сделки ВТБ).

Запуск: python3 pipeline/fix_vtb_pokrovsky_planned_resale_context.py
        python3 pipeline/fix_vtb_pokrovsky_planned_resale_context.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g2668950b'

OLD_CONTEXT = (
    'До 2023 года основным владельцем «Покровского» являлись бывший '
    'инспектор аппарата полномочного представителя президента РФ в ЮФО '
    'Андрей Коровайко и его партнер по бизнесу Аркадий Чебанов. В октябре '
    '2023 года Лабинский городской суд удовлетворил требование Генеральной '
    'прокуратуры РФ о передаче активов «Покровского» в ведение Росимущества '
    'в связи с обвинениями в коррупции в адрес Коровайко и Чебанова. По '
    'данным суда, Коровайко несколько лет использовал служебное положение '
    'для захвата чужих бизнесов и создания своих, в чем также участвовали '
    'судьи Арбитражного суда Ростовской области.'
)
CONTEXT_ADDITION = (
    ' ВТБ не намерен развивать актив внутри группы: в апреле 2026 года глава '
    'банка Андрей Костин объявил о решении продать сельскохозяйственные '
    'активы — «У нас есть сельскохозяйственные [активы], но я принял '
    'решение их продать. Будем только в городе работать», уточнив про '
    'предстоящий конкурс по «Лабинскому»: «Да, у нас там конкурс будет, там '
    'много желающих». Причина — новое регулирование ЦБ с 1 апреля 2027 '
    'года, ограничивающее вложения банков в непрофильные активы. По данным '
    '«Коммерсанта», общая оценочная стоимость сельскохозяйственного '
    'портфеля ВТБ превышает 55 млрд руб., реализовать активы банк '
    'рассчитывает к 2027 году; вероятные претенденты — «Агрокомплекс им. '
    'Н. И. Ткачева» и структуры предпринимателя Али Узденова, а также '
    'агрохолдинг «Просторы».'
)
NEW_CONTEXT = OLD_CONTEXT + CONTEXT_ADDITION

NEW_SRC = [
    ['Ведомости.Юг', 'https://south.vedomosti.ru/south/news/2026/04/08/1188854-vtb'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8572213'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
