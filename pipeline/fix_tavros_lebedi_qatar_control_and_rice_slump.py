import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'ga5b0724c'

OLD_EXTRA = (
    'Сделка закрыта 27 октября 2023. Покупатель — лица, связанные с '
    'агрохолдингом Таврос (управляющий партнер AVG Capital Partners '
    'Рустем Миргалимов владеет более 80% холдинга). Продавец — ООО '
    '«Форум» (Алексей Говоринов). Инвестиционный банкир Илья Шумов '
    'отметил, что сделка была частично в форме cash-in, деньги '
    'направлены на развитие ГК «Лебеди».'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Контроль над самим «Тавросом» сменился: 25 октября 2024 года '
    'катарская Green Way LLC стала владельцем 80% УК «Таврос», доля '
    'Миргалимова размылась до 0,99% (доля структур Альфа-Капитала, '
    '19,01%, не изменилась). Продавец Александр Шиянов вышел из состава '
    'учредителей «Лебедей» в августе 2024 года. Рынок риса обвалился по '
    'ценам из-за перепроизводства при запрете экспорта риса-сырца: цена '
    'снизилась более чем вдвое (2024→2025), выручка «Лебедей» упала с '
    '1,45 до 1,1 млрд ₽, «Лебеди-Агро» устойчиво убыточна.'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/7267002'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
