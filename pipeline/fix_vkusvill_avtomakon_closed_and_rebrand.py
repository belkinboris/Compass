# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g499c5c6c
(«Вкусвилл» приобретает 100% долей в IT-компаниях ГК «Автомакон») —
карточка несла статус «Закрыта», но `extra` внутри неё же противоречил
статусу («Статус: оценка компании, переговоры»). Проверено лично прямым
WebFetch:

Закрытие (Интерфакс, 18.07.2025, interfax.ru/business/1036853):
«Сделка по приобретению ООО "Автомакон", ООО "Даталаб", ООО "Фулстек"
закрыта 17 июля.» Та же статья: «Параметры сделки не уточняются» — сумма
по-прежнему не раскрыта фактически, в базе остаются только экспертные
оценки (уже стояли раньше).

Ребрендинг (ComNews, 23.09.2025, comnews.ru/digital-economy/content/
241396/2025-09-23/2025-w39/1012/vkusvill-pereimenoval-it-dochku-
avtomakon-tekhvill): «"ВкусВилл" проводит ребрендинг своей
технологической "дочки" — компании "Автомакон". Новое название —
"ТехВилл"» и «В ближайшее время к "ТехВиллу" присоединятся ООО
"ДатаЛаб" и ООО "Фулстек"».

`extra` переписан («переговоры» → закрыта). `eco.context` дополнен фактом
ребрендинга — старое значение (непрофильные активы «Вкусвилла») сохранено
как первая часть.

НЕ ВКЛЮЧЕНО: точная сумма сделки (источники по-прежнему называют только
диапазон экспертных оценок, уже отражённый в `eco.val`); консультанты
сделки — ни в одном из проверенных источников (Интерфакс, ComNews ×2,
Oborot.ru) не названы; судьба основателей «Автомакон» (Зезюлин, Чирков)
после сделки — не упомянута ни в одном источнике.

Запуск: python3 pipeline/fix_vkusvill_avtomakon_closed_and_rebrand.py
        python3 pipeline/fix_vkusvill_avtomakon_closed_and_rebrand.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g499c5c6c'

OLD_EXTRA = (
    'Покупатель — сеть «Вкусвилл» приобретает 100% долей в ООО '
    '«Автомакон», «ДатаЛаб», «Фулстек» для получения контроля над '
    'IT-инфраструктурой и синергии разработки. Статус: оценка компании, '
    'переговоры.'
)
NEW_EXTRA = (
    'Покупатель — сеть «Вкусвилл» приобрёл 100% долей в ООО «Автомакон», '
    '«ДатаЛаб», «Фулстек» для получения контроля над IT-инфраструктурой '
    'и синергии разработки. Сделка закрыта 17 июля 2025 года; параметры '
    'сделки не уточнялись.'
)

OLD_CONTEXT = (
    'Помимо поглощенных компаний ГК «Автомакон» у «Вкусвилла» есть и '
    'другой непрофильный бизнес. В 2023 году ритейлер выкупил сеть кафе '
    '«Андерсон» (см. «Ъ» от 20 ноября 2023 года), в 2024 году приобрел '
    'сервис корпоративного питания «Обед.ру». Также у Андрея Кривенко '
    'совместно с партнерами есть фонд «ТилТех», который инвестировал в '
    'бренд Noun, сеть «Клиники Фомина», производителя матрасов Blue '
    'Sleep, производителя и продавца мебели и товаров для дома Divan.ru '
    'и др.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' Позже «Вкусвилл» провёл ребрендинг купленного актива: «"ВкусВилл" '
    'проводит ребрендинг своей технологической "дочки" — компании '
    '"Автомакон". Новое название — "ТехВилл"», к которому «в ближайшее '
    'время... присоединятся ООО "ДатаЛаб" и ООО "Фулстек"» (ComNews, '
    '23 сентября 2025 года).'
)

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/business/1036853'],
    ['ComNews', 'https://www.comnews.ru/digital-economy/content/241396/2025-09-23/2025-w39/1012/vkusvill-pereimenoval-it-dochku-avtomakon-tekhvill'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA
    assert deal['eco']['context'] == OLD_CONTEXT

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
