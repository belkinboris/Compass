import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'cc16fce80'

OLD_TITLE = 'Государство планирует продать золотодобывающую компанию ЮГК'
NEW_TITLE = 'Росимущество продало золотодобывающую компанию ЮГК структуре Руслана Байсарова'

OLD_DATE = '2024-07-15'
NEW_DATE = '2026-06-19'
DATE_QUOTE = ('Победителем аукциона стала компания «БТС-Мост холдинг» Руслана Байсарова. '
              'Стоимость покупки активов по результатам торгов составила 93,2 млрд руб. '
              '... На фоне новости о продаже акции ЮГК на Мосбирже 19 июня упали более чем на 5%.')

FIELDS = {
    'type': ('M&A', 'Продажа с торгов'),
    'status': (None, 'Закрыта'),
    'sum': (None, '93,2 млрд ₽'),
    'target': (None, 'g2c0e743d'),   # Южуралзолото Группа Компаний
    'seller': (None, 'g9fd82fee'),   # Росимущество
    'buyer': (None, 'g27b935b9'),    # АО «БТС-Мост Холдинг»
}

ECO_FIELDS = {
    'share': (None,
              '67,2% акций ПАО «Южуралзолото Группа Компаний» (ЮГК) и доли связанных '
              'структур, ранее конфискованные у бывшего основного владельца Константина '
              'Струкова'),
    'val': (None,
            '162,2 млрд ₽ (по оценке Росимущества) — стартовая цена аукциона; доля '
            'государства (67,2%) оценивалась в 140,4 млрд ₽'),
    'rationale': (None,
                  '«Мы заинтересованы в том, чтобы те объекты, бизнес в первую очередь, '
                  'объекты, которые есть у государства, чтобы они работали дальше, так '
                  'сказать, и нашли своего собственника нового», — заявил министр финансов '
                  'Антон Силуанов о судьбе конфискованного пакета (16 июля 2025 года)'),
    'context': (None,
                '11 июля 2025 года Советский районный суд Челябинска удовлетворил иск '
                'Генпрокуратуры об обращении в доход государства активов, связанных с '
                'бывшим основным владельцем ЮГК Константином Струковым; 15 июля 2025 года '
                'Росимущество officially стало учредителем компании. Аукцион по продаже '
                '67,2% акций в голландском формате не состоялся трижды подряд (18 мая — не '
                'было заявок, 26 мая — единственную заявку отклонили за неполный пакет '
                'документов, 10 июня — единственный претендент не внёс задаток), прежде чем '
                '19 июня 2026 года торги выиграла «БТС-Мост Холдинг». 7 июля 2026 года '
                'компанию переименовали в группу «БТС-Золото», её главой стал Олег Ширяев.'),
}


def _fix_typo(text):
    return text.replace(' officially ', ' официально ')


def main(argv):
    data = json.load(open(DATA, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}
    deal = by_id.get(DEAL_ID)
    assert deal is not None, 'нет сделки %s' % DEAL_ID

    assert deal.get('title') == OLD_TITLE, 'заголовок уже другой: %r' % deal.get('title')
    assert deal.get('date') == OLD_DATE, 'дата уже другая: %r' % deal.get('date')
    for field, (old, _new) in FIELDS.items():
        assert deal.get(field) == old, '%s уже другое: %r' % (field, deal.get(field))
    eco = deal.get('eco') or {}
    for field, (old, _new) in ECO_FIELDS.items():
        assert eco.get(field) == old, 'eco.%s уже другое: %r' % (field, eco.get(field))
    assert deal.get('law', {}).get('struct') == (
        'В середине июня «БТС-Мост Холдинг» купила на торгах 67,2% акций ЮГК и доли '
        'связанных структур за 93,16 млрд руб.'), 'law.struct изменился — проверьте вручную'
    assert len(deal.get('src') or []) == 3, 'число источников изменилось — проверьте вручную'

    print('%s: сделка ЮГК/«БТС-Мост Холдинг» — дописываем закрытие торгов' % DEAL_ID)
    print('  title -> %r' % NEW_TITLE)
    print('  date  %r -> %r  (цитата: %r)' % (OLD_DATE, NEW_DATE, DATE_QUOTE))
    for field, (_old, new) in FIELDS.items():
        print('  %s -> %r' % (field, new))
    for field, (_old, new) in ECO_FIELDS.items():
        print('  eco.%s -> %r' % (field, _fix_typo(new)[:80] + '…'))

    if '--write' not in argv:
        print('\nСухой прогон. Запись — с ключом --write.')
        return 0

    deal['title'] = NEW_TITLE
    deal['date'] = NEW_DATE
    for field, (_old, new) in FIELDS.items():
        deal[field] = new
    deal.setdefault('eco', {})
    for field, (_old, new) in ECO_FIELDS.items():
        deal['eco'][field] = _fix_typo(new)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('ЗАПИСАНО.')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
