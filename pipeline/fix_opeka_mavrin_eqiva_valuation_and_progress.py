# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка gfe21a083
(Акционеры «Валента Фарм» продали 49,99% «Опеки» основателю Алексею
Маврину). Уже стоявшая оценка суммы не несла имени оценщика — правило
CLAUDE.md («Сумма пишется одним способом... оно в «Оценке и дисконте»)
требует атрибуции именно там. Проверено лично прямым WebFetch.

1) `eco.val` — атрибуция оценки. Коммерсантъ, дословно: «Гендиректор
аналитической компании Eqiva Дарья Шубина оценивает 50% в «Опеке» в
700–800 млн руб.»
Источник: https://www.kommersant.ru/doc/7266558 (уже в src)

2) `eco.context` (новое поле) — три факта из того же источника:
- Причина продажи: «Опека» рассчитывала открыть 40 пансионатов в
  горизонте пяти лет... Но в итоге сети за пять лет удалось запустить
  только семь объектов» — темп роста не оправдал ожиданий инвесторов
  2019 года.
- Кедровский о судьбе вырученных денег: «средства от продажи долей в
  «Опека-групп» «успешно реинвестированы в другие проекты» в РФ».
- Контекст исходной инвестиции: «Акционеры «Валенты Фарм» в июле 2019
  года инвестировали в бизнес «Опеки» 700 млн руб.... Доли Олега
  Кедровского (ему принадлежало 31,24%), Дмитрия Шульженко и Святослава
  Петрушко (по 9,37%)».
- Судьба «Опеки» после сделки (sgc-opeca.ru, пресс-релиз самой компании,
  дословно): «Выручка ГК выросла на 21% год к году, показатель EBITDA
  увеличился на 27,5%»; «открытие нового пансионата «Отрадное»...» и
  «договор на управление пансионатом «Цветы» на 250 мест» (2025 год).

НЕ включены: консультанты сделки — не найдены ни в одном источнике;
залог доли Маврина в Сбербанке (найден в ЕГРЮЛ) — источник не подтверждает
связь именно с финансированием ЭТОЙ сделки, а не более старых отношений с
банком, писать в law.struct как обеспечение кредита на покупку нельзя без
прямого подтверждения.

Запуск: python3 pipeline/fix_opeka_mavrin_eqiva_valuation_and_progress.py
        python3 pipeline/fix_opeka_mavrin_eqiva_valuation_and_progress.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gfe21a083'

OLD_VAL = 'Экспертная оценка; 700–800 млн ₽ (по оценке)'
NEW_VAL = (
    'Гендиректор аналитической компании Eqiva Дарья Шубина оценивает 50% '
    'в «Опеке» в 700–800 млн руб.'
)

OLD_CONTEXT = '—'
NEW_CONTEXT = (
    '«Опека» рассчитывала открыть 40 пансионатов в горизонте пяти лет... '
    'Но в итоге сети за пять лет удалось запустить только семь объектов» '
    '— темп роста не оправдал ожиданий инвесторов 2019 года. Олег '
    'Кедровский говорит, что средства от продажи долей «успешно '
    'реинвестированы в другие проекты» в РФ. Исходная инвестиция: '
    '«Акционеры «Валенты Фарм» в июле 2019 года инвестировали в бизнес '
    '«Опеки» 700 млн руб.», доли Кедровского, Шульженко и Петрушко тогда '
    'составляли 31,24% и по 9,37% (Коммерсантъ). По данным самой '
    'компании, в 2025 году «выручка ГК выросла на 21% год к году, '
    'показатель EBITDA увеличился на 27,5%», открыт новый пансионат '
    '«Отрадное» в Ленинградской области, подписан договор на управление '
    'пансионатом «Цветы» на 250 мест (sgc-opeca.ru).'
)

NEW_SRC = [
    ['sgc-opeca.ru', 'https://sgc-opeca.ru/msk/news/itogi-2025/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['val'] == OLD_VAL
    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.val: было ===')
    print(OLD_VAL)
    print('=== eco.val: станет ===')
    print(NEW_VAL)
    print('=== eco.context (новое поле): станет ===')
    print(NEW_CONTEXT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['val'] = NEW_VAL
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
