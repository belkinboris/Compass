import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g5d9d8e6c'

OLD_ECO_CONTEXT = (
    '«Открытию» принадлежало 34,2% капитала группы, или 13,7% голосов. '
    'Покупатель пакета акций неизвестен.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' Сумма (8,85 млрд ₽) — оценка Коммерсанта, а не '
    'согласованная сторонами цена; покупатель не назван нигде, включая '
    'источники вплоть до 2026 года. Дальнейшая судьба Qiwi: 21 февраля '
    '2024 года Банк России отозвал лицензию у КИВИ Банка из-за '
    'высокорисковых расчётов между физлицами и теневым бизнесом; '
    'позже, уже отдельной сделкой, весь российский бизнес компании '
    'купила гонконгская структура бывшего гендиректора, а сам холдинг '
    'переименован в NanduQ и покинул NASDAQ.'
)

OLD_SRC = [
    ['Forbes', 'https://www.forbes.ru/biznes/484951-bank-otkrytie-vysel-iz-kapitala-qiwi'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/5826320'],
]
NEW_SRC = OLD_SRC + [['Банк России', 'https://www.cbr.ru/press/pr/?file=638441030839855571BANK_SECTOR.htm']]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
