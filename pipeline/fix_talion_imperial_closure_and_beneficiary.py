import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'geb8edd5c'

OLD_CONTEXT = (
    'По данным Российского аукционного дома, сделка стала одной из '
    'крупнейших на Северо-Западе в сегменте коммерческой недвижимости '
    'в 2025 году.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' Отель фактически прекратил работу: «Пятизвёздочный "Талион" '
    'прекратил свою операционную деятельность», «со временем объект '
    'официально сменит название на "Сенатор"», «Управлением объектом '
    'занимается команда холдинга "Империя"» (Fontanka.ru, 1 декабря '
    '2025).'
)

OLD_STRUCT = '—'
NEW_STRUCT = (
    'Конечный бенефициар холдинга «Империя» — Андрей Фоменко: «В 2001 '
    'году холдинг Андрея Фоменко "Империя" открыл в Санкт-Петербурге '
    'первый бизнес-центр "Сенатор"», «По состоянию на 2015 год, сеть '
    'бизнес-центров "Сенатор" состояла из 26 объектов общей площадью '
    '310 000 квадратных метров» (Wikipedia).'
)

NEW_SRC = [
    ['Fontanka.ru', 'https://www.fontanka.ru/2025/12/01/76148905/'],
    ['Wikipedia', 'https://ru.wikipedia.org/wiki/Фоменко,_Андрей_Николаевич'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    assert deal['law']['struct'] == OLD_STRUCT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== law.struct: станет ===')
    print(NEW_STRUCT)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['law']['struct'] = NEW_STRUCT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
