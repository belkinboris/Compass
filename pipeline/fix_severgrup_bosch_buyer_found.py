# -*- coding: utf-8 -*-
"""Месячная очередь, карточка gd4645195 («Севергрупп»/завод
электроинструментов, бывший Bosch): заголовок и `extra` до сих пор
говорят «продаёт... в поиске покупателя» и называют ГК «Интерскол»
заинтересованной стороной — хотя `buyer_name` карточки уже верно несёт
«ООО «Интернет проекты»» (структура Softline/Волотовской), а статус
стоит «Закрыта». Дельта-поиск нашёл: сама ГК «Интерскол» публично
опровергла интерес («в самом "Интерсколе" РБК сообщили, что покупку
завода в Энгельсе не рассматривают») — упоминание в `extra` не просто
устарело, а прямо опровергнуто. Источник сделки (mergers.ru) уже в
`src` карточки.

Не через `review.py`: это ЗАМЕНА уже написанного, вводящего в
заблуждение текста (заголовок и половина `extra`), а не дополнение
пустого поля — `review.py` рассчитан на дословный перенос в пустое
или частично заполненное поле, а не на переписывание вводного текста.

Источник — читал напрямую (WebFetch, дословная цитата подтверждена):
https://mergers.ru/news/Severgrupp-Mordashova-prodala-OOO-Jengels-Jelektroinstrumenty-byvshij-zavod-Bosch-85439

Запуск: python3 pipeline/fix_severgrup_bosch_buyer_found.py [--write]
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gd4645195'

OLD_TITLE = ('«Севергрупп» продает завод электроинструментов (бывший '
             'Bosch) в поиске покупателя')
NEW_TITLE = ('«Севергрупп» продала завод электроинструментов (бывший '
             'Bosch) структуре Softline')

OLD_EXTRA = (
    'Выставление на продажу 100% долей ООО «Энгельс '
    'Электроинструменты» холдингом «Севергрупп». Активность по поиску '
    'покупателя. ГК «Интерскол» заинтересована в приобретении.'
)
NEW_EXTRA = (
    'Продажа 100% долей ООО «Энгельс Электроинструменты» холдингом '
    '«Севергрупп». Покупателем выступило ООО «Интернет проекты» — '
    'структура, связанная со Softline (99% принадлежит вице-'
    'президенту по инвестициям Softline Елене Волотовской, 1% — ООО '
    '«Аталайя»). ГК «Интерскол», ранее называвшаяся заинтересованной '
    'стороной, публично опровергла эту информацию: в компании РБК '
    'сообщили, что покупку завода в Энгельсе не рассматривают.'
)


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['title'] == OLD_TITLE, \
        f"title: неожиданное значение {deal['title']!r}"
    assert deal['extra'] == OLD_EXTRA, \
        f"extra: неожиданное значение {deal['extra']!r}"

    print(f'{CARD_ID} title: покупатель найден, сделка закрыта')
    print(f'{CARD_ID} extra: реальный покупатель + опровержение '
          f'«Интерскола»')

    if write:
        deal['title'] = NEW_TITLE
        deal['extra'] = NEW_EXTRA
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('ЗАПИСАНО')
    else:
        print('Сухой прогон. Запись — с --write.')


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
