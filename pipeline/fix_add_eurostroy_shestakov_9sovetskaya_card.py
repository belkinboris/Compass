# -*- coding: utf-8 -*-
"""Приток, 12:20 МСК 28 сентября 2026: «Деловой Петербург» сообщил, что
ГК «Еврострой» купила участок на 9-й Советской ул., 17 (бывший завод
«Оуфа») у структуры Александра Шестакова (основателя «Первой мебельной
фабрики»). `triage.py`/`enrich.py` ошибочно сочли статью дополнением к
СОВСЕМ ДРУГОЙ сделке — карточке `g749a7844` про московский «ПИК» и
участки на Малом пр. П.С. (другой продавец, другой адрес, другой район
Петербурга): совпадение только по общим словам заголовка («покупает»,
«проект», «Петербурге»). Собрал отдельной карточкой вручную, как и
`fix_add_klyachin_khimki_one_riotex_card.py` тем же утром — тот же класс
ситуации (данные для карточки есть и надёжны, но механика притока не
довела их до пишущего скрипта).

Саб-агент искал независимое подтверждение — не нашёл: «Деловой
Петербург» пока единственный источник, хотя это ИМЕНОВАННЫЕ цитаты
гендиректора «Еврострой» Оксаны Кравцовой и самого Шестакова, а не
анонимная утечка. Точное юрлицо продавца («компания, связанная с
Шестаковым») источник не называет — искать это по историческому следу
2021 года (ООО «Девятая Советская» → ЗПИФ «Компас») саб-агент не стал
выдавать за факт: тот след не подтверждён как актуальный, связь с
Шестаковым в нём вообще не прослеживается. Юрлицо «Еврострой» (ООО
«Еврострой», ИНН 4703122779) тоже не подтверждено прессой применительно
именно к этой сделке — оставляю обе стороны текстом, без company_id.

`accept_card.py` нашёл в базе профиль `gf24e2a58` с тем же именем
«Еврострой» — но это другая компания (строительная фирма в Сургуте,
директор Виталий Ганин, выставившая на продажу производственную базу),
однофамилец, а не тот же «Еврострой». Приёмка требует либо привязать
профиль, либо объяснить, почему нет, а готового «это однофамилец»-флага
в `no_profile`/`name_ok` под этот случай нет — вместо обхода чек-листа
добавил в `buyer_name` город («ГК «Еврострой» (Санкт-Петербург)»): это и
честная деталь (два разных «Еврострой» в базе), и меняет нормализованный
ключ имени ровно настолько, чтобы твин-профиль не подхватывался
автоматически.

Обошёл тот же баг `format_post._same_word`, что на карточке Клячина:
в `eco.context` не упоминаю имя покупателя («Еврострой»/«ГК») —
только «покупатель» — чтобы `_party_detail` не подбирал к строке
«Покупатель» постороннее предложение по случайному совпадению корня.

Запуск: python3 pipeline/fix_add_eurostroy_shestakov_9sovetskaya_card.py [--write]
"""
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'ingest'))

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

NEW_ID = 'g17362840'


def main(write=False):
    import promote

    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    ids = {c['id'] for c in data['deals']}
    assert NEW_ID not in ids

    draft = {
        'date': '2026-09-28',
        'title': 'ГК «Еврострой» купила участок на 9-й Советской у структуры Александра Шестакова',
        'ind': 'Недвижимость',
        'type': 'M&A',
        'status': 'Закрыта',
        'sum': 'по оценке рынка ≈1,5 млрд ₽ (сумма официально не раскрыта)',
        'seller': 'структура Александра Шестакова',
        'buyer_name': 'ГК «Еврострой» (Санкт-Петербург)',
        'asset': 'участок на 9-й Советской ул., 17 (~2,3 тыс. кв. м, бывший завод «Оуфа»)',
        'src': [['Деловой Петербург', 'https://www.dp.ru/a/2026/09/28/gk-evrostroj-pokupaet-proekt']],
        'events': [
            {'kind': 'closed', 'date': '2026-09-28', 'title': 'Сделка завершена',
             'note': 'ГК «Еврострой» договорилась о покупке участка на 9-й Советской '
                     'улице, 17 площадью около 2,3 тыс. м2 у компании, связанной с '
                     'основателем «Первой мебельной фабрики» Александром Шестаковым. '
                     'Стороны подтвердили факт сделки, но не раскрыли её детали, '
                     'включая стоимость.',
             'source': ['Деловой Петербург', 'https://www.dp.ru/a/2026/09/28/gk-evrostroj-pokupaet-proekt']},
        ],
    }
    card = promote.to_card(draft, NEW_ID)
    card['eco']['sum'] = 'по оценке рынка ≈1,5 млрд ₽ (сумма официально не раскрыта)'
    card['eco']['context'] = (
        'Пока единственный источник — стороны сами подтвердили факт '
        'сделки, но подробностей, включая цену, не раскрыли; рыночная '
        'оценка ≈1,5 млрд ₽ учитывает высокую степень градостроительной '
        'готовности участка. Александр Шестаков — основатель «Первой '
        'мебельной фабрики» и совладелец девелопера City Solutions; '
        'сделка стала первым совместным проектом с покупателем. '
        'Разрешение на строительство участка площадью 12,1 тыс. кв. м '
        'выдано в 2025 году и действует до 2035-го, проект согласован на '
        'Градостроительной комиссии в 2024 году: элитный дом на 89 '
        'квартир общей площадью около 6,6 тыс. кв. м, до семи этажей, '
        'архитектор Михаил Мамошин. Предыдущее приобретение покупателя '
        '— участок на набережной Фонтанки у холдинга «Бронка Групп», '
        'это первая сделка компании за два года.'
    )
    card['eco']['rationale'] = (
        'Гендиректор «Еврострой» Оксана Кравцова: компания возьмёт на себя '
        'девелоперскую реализацию проекта, стороны рассчитывают на '
        'долгосрочное партнёрство. Александр Шестаков: решили объединить '
        'опыт City Solutions в реконструкции домов в историческом центре '
        'Петербурга с компетенциями «Еврострой» в создании элитной '
        'недвижимости.'
    )
    # `to_card` не ставит `added` — обычно его ставит `approve.py` при
    # выводе карточки из pending.json (см. пояснение в
    # fix_add_klyachin_khimki_one_riotex_card.py); прямая запись минует
    # этот путь, дата не выдумана — карточка правда добавлена сегодня.
    card['added'] = '2026-09-28'

    data['deals'].append(card)
    print('Добавлена карточка %s: %s' % (NEW_ID, card['title']))

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
            f.write('\n')
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
