# -*- coding: utf-8 -*-
"""Месячная очередь качества, 11 сентября 2026 — карточка `cb1991390`
(«Передача четырёх национализированных компаний под управление АО
«Росхим»», 1 ноября 2023) описывала только сам факт передачи В
УПРАВЛЕНИЕ; дальнейшая судьба актива была неизвестна.

Личный WebFetch подтвердил дословно (Интерфакс,
https://www.interfax.ru/business/986061): «В состав лота входят
принадлежащие в настоящее время Росимуществу 100% ООО «Радамант»
(Москва, владелец ООО «Дальнегорский ГОК»), ООО «ФинИнвест» (Москва,
бывший владелец «Радаманта»), ООО «Горно-химическая компания «Бор» и
ООО НПП «Силика»»; «лот продан по начальной цене - 2 млрд 233,5 млн
рублей»; «"Росхим" стал единственным участником аукциона»; «Новый
собственник компаний должен будет ... в течение двух лет ...
осуществить модернизацию и расширение действующего производства
боросодержащей продукции до 100 тыс. тонн в год».

То, что в ноябре 2023 года передавалось «Росхиму» ПОД УПРАВЛЕНИЕ, в
октябре 2024 года было им же ВЫКУПЛЕНО у государства на аукционе —
временное управление стало собственностью. `status` не был заполнен
вовсе, ставится «Закрыта».

Запуск:
    python3 pipeline/fix_roskhim_four_companies_auction_purchase.py            # сухой прогон
    python3 pipeline/fix_roskhim_four_companies_auction_purchase.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

NEW_LAW_STRUCT = (
    'В октябре 2024 года «Росхим» выкупил тот же пакет (ООО «Радамант», '
    'ООО «ФинИнвест», ООО «Горно-химическая компания «Бор»», ООО НПП '
    '«Силика») у Росимущества на аукционе — единственный участник, '
    'стартовая цена лота 2 млрд 233,5 млн ₽. Покупатель обязался '
    'модернизировать и расширить производство боропродукции до 100 тыс. '
    'т в год в течение двух лет.'
)

NEW_SRC = ['Интерфакс', 'https://www.interfax.ru/business/986061']


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['cb1991390']

    assert 'struct' not in d.get('law', {}), 'law.struct уже занят: %r' % (d['law'].get('struct'),)
    assert d.get('status') is None, 'status уже занят: %r' % (d.get('status'),)
    urls = {s[1] for s in d['src']}
    assert NEW_SRC[1] not in urls, 'источник уже добавлен'

    print('cb1991390: law.struct заполнен (выкуп «Росхимом» на торгах, '
          'октябрь 2024), status -> Закрыта, добавлен источник')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['law']['struct'] = NEW_LAW_STRUCT
    d['status'] = 'Закрыта'
    d['src'].append(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
