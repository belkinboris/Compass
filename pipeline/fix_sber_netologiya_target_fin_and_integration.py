import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g7e0c2ffb'

OLD_TARGET_FIN = '—'
NEW_TARGET_FIN = (
    'В 2023 году «Нетология» заработала 3,1 млрд руб. (+6,9% к 2022 '
    'году), «Фоксфорд» — 4,4 млрд руб. (+52%). Во втором квартале '
    '2024 года «Фоксфорд» занимал 7-е место по выручке среди EdTech-'
    'компаний России (1,2 млрд руб.), «Нетология» — 14-е (630 млн руб.), '
    'по данным рейтинга Smart Ranking (edtechs.ru, CNews).'
)

OLD_EXTRA = (
    'Сбер закрыл сделку по приобретению образовательных активов '
    'Нетология-групп (Нетология и Фоксфорд), объединяющих школы '
    'дополнительного профессионального образования и онлайн-школу для '
    'школьников. Продавец — TalentTech (структура Северстали), '
    'контролирующая образовательные активы. Это первая значительная M&A '
    'сделка Сбера в edtech-сегменте.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Оба бренда сохранены и встроены в продуктовую линейку Сбера, а не '
    'слиты и не переименованы: в августе 2025 года «Сбербанк и '
    '«Нетология» заключили соглашение о сотрудничестве с Финансовым '
    'университетом при Правительстве России, Московским авиационным '
    'институтом и Уральским федеральным университетом» для подготовки '
    'ИТ-специалистов (CNews, 29 августа 2025 года), а в июле 2026 года '
    'курсы «Фоксфорда» стали доступны держателям детской СберКарты '
    '(kgd.ru, 23 июля 2026 года).'
)

NEW_SRC = [
    ['edtechs.ru', 'https://edtechs.ru/analitika-i-intervyu/sber-pokupaet-obrazovatelnye-aktivy-alekseya-mordashova-netologiyu-i-foksford/'],
    ['CNews', 'https://www.cnews.ru/news/top/2024-10-17_odni_iz_liderov_na_rynke'],
    ['CNews', 'https://www.cnews.ru/news/line/2025-08-29_sberbanknetologiya_i_krupnye'],
    ['kgd.ru', 'https://kgd.ru/news/biz/item/118338-detskaya-sberkarta-otkryvaet-dostup-k-onlajn-kursam-foksforda'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['target_fin'] == OLD_TARGET_FIN
    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== eco.target_fin: станет ===')
    print(NEW_TARGET_FIN)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['target_fin'] = NEW_TARGET_FIN
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
