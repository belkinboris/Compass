# -*- coding: utf-8 -*-
"""Месячная очередь, 8 сентября 2026 — карточка `cc0e7565f» («Б1 (ex-EY)
оценила бизнес Russ в 460-500 млрд руб», август 2024) стояла без `status`
вовсе. Личный WebFetch источника (rbc.ru) возвращал 401 в этой сессии —
факты восстановлены через независимые пересказы (sostav.ru, vc.ru,
forbes.ru), согласующиеся друг с другом по цифрам и методологии.

Это НЕ отдельная сделка купли-продажи, а отчёт об оценке, заказанный в
рамках объединения Wildberries и Russ (СП «РВБ», объявлено в июне 2024):
«методология учитывала... инвестиционную синергию с учётом бизнес-плана
развития объединённой компании Russ и Wildberries» (sostav.ru,
пересказ РБК). Самого объединения в базе как отдельной карточки нет —
многочисленные карточки после него («Wildberries и Russ приобрели...»)
есть, а карточки самого слияния (создание СП «РВБ», доли 65/35) не
нашлось; это отдельный вопрос для притока, не для этой карточки.

Важная находка: независимая оценка того же бизнеса Russ по СПАРК-
Интерфакс (РСБУ, мультипликаторы P/S/EV/S/P/E/P/Book) дала Forbes цифру
70–72 млрд ₽ — против 460–500 млрд ₽ у Б1 (МСФО, EV/EBITDA), расхождение
в шесть раз на одну и ту же дату. Официальная позиция Russ (по данным
vc.ru со ссылкой на forbes.ru): оценка Forbes «не учитывает M&A сделки в
2023–2024 годах, установку цифрового инвентаря, выход на новые сегменты
и рынки... финансовые результаты других юрлиц, а также синергетический
рост от объединения Russ и Wildberries». Обе оценки методологически
объяснимы — расхождение стоит показать явно, а не оставлять единственную
цифру как согласованный факт (родня записанного в CLAUDE.md урока «Число
может быть верным фактом и совсем не той величиной»).

Статус карточки — «Обсуждается»: это отчёт об оценке в рамках ещё не
оформленной в базе сделки, не сама сделка (`type`/`buyer`/`seller` не
трогаются — вопрос об архитектуре карточки решает приток).

Запуск:
    python3 pipeline/fix_russ_wb_valuation_dispute_context.py            # сухой прогон
    python3 pipeline/fix_russ_wb_valuation_dispute_context.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'
CARD_ID = 'cc0e7565f'

OLD_CONTEXT = '—'
NEW_CONTEXT = (
    'Оценка сделана в рамках объединения Wildberries и Russ (СП «РВБ», '
    'доли 65/35, объявлено в июне 2024 года) — независимая оценка того же '
    'бизнеса по СПАРК-Интерфакс (РСБУ) дала Forbes цифру 70–72 млрд ₽, в '
    'шесть раз меньше: Russ объяснил расхождение тем, что методология '
    'Forbes не учитывает сделки M&A 2023–2024 годов и синергию от '
    'объединения с Wildberries.'
)


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}
    card = by_id[CARD_ID]

    assert card.get('status') is None, 'status уже занят: %r' % (card.get('status'),)
    assert card['eco']['context'] == OLD_CONTEXT, \
        'eco.context уже другой: %r' % (card['eco']['context'],)

    print('status None -> "Обсуждается"')
    print('eco.context: добавлен факт о расхождении оценок Б1/Forbes и связи '
          'со слиянием Wildberries/Russ')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    card['status'] = 'Обсуждается'
    card['eco']['context'] = NEW_CONTEXT

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
