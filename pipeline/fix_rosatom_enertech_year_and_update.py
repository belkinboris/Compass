# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
`g3fdf0220` («Росатом консолидировал 49% южнокорейского производителя
батарей Enertech International») несла НЕВЕРНЫЙ ГОД: `date` стоял
«2023», хотя по источнику самой карточки сделка (доведение доли
«Рэнеры» с 49,16% до 98,32%, то есть фактическое поглощение, а не
«консолидация 49%», как звучит заголовок) закрылась в 2022 году —
статья 2023 года лишь АНАЛИЗИРУЕТ уже закрытую сделку годом позже.

Проверено (по докладу саб-агента, дословные цитаты; источник карточки
kommersant.ru/doc/5985451 перепрочитан полностью):
- «Стороны закрыли сделку в 2022 году»; «"Рэнера" увеличила долю с
  49,16% до 98,32%, полностью выкупив пакет, принадлежащий TVG Saehan
  Holdings Limited»; «Госкорпорация еще в 2021 году купила 49% у
  холдинга Ener1 Бориса Зингаревича, а в 2022 году — у него же ещё
  49%».
- kommersant.ru/doc/6553260 (март 2024): Южная Корея запретила
  поставки литий-ионных аккумуляторов для электротранспорта в РФ
  (следуя 12-му пакету санкций ЕС) — «Основной южнокорейский
  поставщик литий-ионных аккумуляторов в Россию — компания Enertech,
  которая отправляет батареи для «Рэнеры»»; объём поставок 2023 года
  — не менее 1,5 млрд ₽.
- neftegaz.ru/news/Oborudovanie/909892 (15.12.2025): технический пуск
  первой гигафабрики «Рэнеры» в опытно-промышленную эксплуатацию
  состоялся в Немане Калининградской области — позже изначально
  заявленной осени 2025 года; серийное производство запланировано на
  лето 2026 года, выход на полную мощность (24/7) — к 2027 году.

Год сделки МЕНЯЕТСЯ одноразовым скриптом с `assert` на исходное
состояние — тот же класс правки, что уже применялся в базе для других
карточек с неверным годом (см. CLAUDE.md, «review.py не умеет
переносить сделку в другой год — и не должен»), это НЕ задача
`review.py`/таблицы FIXES.

НЕ ВНЕСЕНО: (1) сумма сделки 2022 года и консультанты — ноль по всем
проверенным источникам; (2) финансовые показатели «Рэнера-Энертек» за
2023-2025 годы — получены только через агрегированный пересказ
поисковика (rusprofile/РБК компании дали 403/401 при прямом чтении),
не вносятся без подтверждения дословной цитатой; (3) дал ли Сеул
исключение для дальнейших поставок после запрета марта 2024 года —
источники высказывают только предположение аналитиков, не факт;
(4) заголовок карточки («консолидировал 49%») формально неточен
(реальный переход — с 49,16% до 98,32%), но заголовки старых карточек
по принятому правилу не переименовываются — уточнение внесено в
`law.struct`.

Запуск: python3 pipeline/fix_rosatom_enertech_year_and_update.py
        python3 pipeline/fix_rosatom_enertech_year_and_update.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g3fdf0220'

OLD_DATE = '2023'
NEW_DATE = '2022'

OLD_LAW_STRUCT = (
    'Изначально «Рэнера» вошла в капитал Enertech в 2021 году, '
    'выкупив 49,16% у TVG SEI Holdings Limited, которая также входит '
    'в Ener1. Госкорпорации нужна технология производства батарей для '
    'запуска гигафабрики в Калининградской области. Первая сделка '
    'дальнейшего выкупа долей не оговаривала.'
)
NEW_LAW_STRUCT = (
    OLD_LAW_STRUCT + ' В 2022 году «Рэнера» довела долю с 49,16% до '
    '98,32%, полностью выкупив пакет TVG Saehan Holdings Limited '
    '(тоже структура Ener1) — то есть речь о фактическом поглощении, '
    'а не о доведении до 49%.'
)

OLD_ECO_CONTEXT = (
    'Технология NMC (литий-никель-марганец-кобальт-оксидные '
    'аккумуляторы), которую развивает Enertech, лучше всего подходит '
    'для электротранспорта, говорит Игорь Чаусов из АНО «Центр '
    '„Энерджинет“». По его мнению, решение «Росатома» купить '
    'технологию можно только приветствовать: литий-ионные '
    'аккумуляторы в больших количествах нужны России уже сейчас, а на '
    'создание собственной технологии ушло бы в лучшем случае три-'
    'четыре года.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' В марте 2024 года Южная Корея запретила '
    'поставки литий-ионных аккумуляторов для электротранспорта в '
    'Россию — Enertech был основным южнокорейским поставщиком таких '
    'батарей для «Рэнеры» (не менее 1,5 млрд ₽ поставок в 2023 году). '
    'Технический пуск калининградской гигафабрики в опытно-'
    'промышленную эксплуатацию состоялся 15 декабря 2025 года — '
    'позже заявленной осени 2025 года; серийное производство '
    'запланировано на лето 2026 года.'
)

OLD_SRC = [['Коммерсантъ', 'https://www.kommersant.ru/doc/5985451']]
NEW_SRC = OLD_SRC + [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6553260'],
    ['Нефтегаз.ру', 'https://neftegaz.ru/news/Oborudovanie/909892-po-grafiku-rosatom-zapustil-v-ope-pervuyu-gigafabriku-v-rossii/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['date'] == OLD_DATE
    assert deal['law']['struct'] == OLD_LAW_STRUCT
    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== date: станет ===')
    print(NEW_DATE)
    print('\n=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['date'] = NEW_DATE
        deal['law']['struct'] = NEW_LAW_STRUCT
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
