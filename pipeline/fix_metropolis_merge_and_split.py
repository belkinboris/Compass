import hashlib
import json
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(ROOT, '..', 'static', 'data', 'deals_promoted.json')

TRC_MALL_ID = 'g8ffdf4ac'
FAILED_2022_ID = 'g56342584'
REAL_CLOSE_ID = 'gd75ae46f'
MGMT_CHANGE_ID = 'c08c9f11e'
BC_OFFICE_DEAL_ID = 'gac4491d6'

NEW_BC_PROFILE_NAME = 'Бизнес-центр «Метрополис»'
NEW_BC_PROFILE_ID = 'g' + hashlib.sha1(NEW_BC_PROFILE_NAME.encode('utf-8')).hexdigest()[:8]

MILESTONE_2022 = {
    'kind': 'cancelled',
    'date': '2022',
    'title': 'Первый покупатель — «М Холдинг Лтд» (Capital Partners) — сделку не закрыл',
    'note': ('«М Холдинг Лтд», структура казахстанской Capital Partners, договорилась '
             'о покупке ТЦ «Метрополис» у совладельцев Morgan Stanley и Hines за '
             'ожидаемые $1,5 млрд. Сделку одобрили ФАС (декабрь 2022) и '
             'Правительственная комиссия по контролю за иностранными инвестициями, '
             'но по неизвестным причинам она не была закрыта. Реальным покупателем '
             'позже стал Balchug Capital — см. дату этой карточки.'),
    'source': ['CRE.ru', 'https://www.cre.ru/news/89539'],
}

MILESTONE_2026 = {
    'kind': 'announced',
    'date': '2026-02-03',
    'title': 'Управляющей организацией балансодержателя стала «ТПС недвижимость»',
    'note': ('Управляющей организацией ООО «Кубик» и АО «М-Холдинг» — юрлиц, на '
             'балансе которых числится ТРЦ «Метрополис», — стала «ТПС недвижимость» '
             '(та же компания, что с июля 2024 года управляет самим торговым '
             'центром). Ведомости со ссылкой на опрошенных экспертов пишут, что '
             'переход управления на уровень балансодержателя МОЖЕТ говорить о '
             'завершении сделки по приобретению комплекса, но ни Balchug Capital, '
             'ни «ТПС недвижимость» это не подтвердили, а прямой связи «АО '
             '«М-Холдинг»» с Balchug Capital источник не устанавливает.'),
    'source': ['Ведомости',
               'https://www.vedomosti.ru/realty/articles/2026/02/05/1174133-u-torgovo-razvlekatelnogo-kompleksa-metropolis-vozmozhno-smenilsya-sobstvennik'],
}

IRN_SOURCE = ['IRN.ru', 'https://www.irn.ru/news/157285-vedomosti-tps-nedvizhimost-vzyala-v-upravlenie.html']

NEW_BC_PROFILE = {
    'name': NEW_BC_PROFILE_NAME,
    'ind': 'Недвижимость',
    'desc': ('Офисный комплекс класса «А» из трёх корпусов (110 000 м²) на '
             'Ленинградском шоссе, рядом со станцией метро «Войковская» — часть '
             'комплекса «Метрополис», отдельная от одноимённого торгово-развлекательного '
             'центра (разные здания, разные собственники).'),
    'kpi': ['Профиль', 'Автоматический'],
}


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    deals = {d['id']: d for d in data['deals']}
    companies = data['companies']

    # Проверка исходного состояния — падаем, если данные уже другие.
    assert FAILED_2022_ID in deals, 'сорвавшаяся сделка 2022 уже отсутствует'
    assert REAL_CLOSE_ID in deals, 'реальное закрытие уже отсутствует'
    assert MGMT_CHANGE_ID in deals, 'карточка смены управления уже отсутствует'
    assert BC_OFFICE_DEAL_ID in deals, 'сделка по бизнес-центру уже отсутствует'
    real = deals[REAL_CLOSE_ID]
    assert real.get('target') == TRC_MALL_ID
    assert not real.get('events'), 'у реальной карточки уже есть events — план устарел'
    bc_deal = deals[BC_OFFICE_DEAL_ID]
    assert bc_deal.get('target') == TRC_MALL_ID, 'бизнес-центр уже не ссылается на профиль ТРЦ'
    assert NEW_BC_PROFILE_ID not in companies, 'профиль бизнес-центра уже существует'
    assert data.get('merged', {}).get(FAILED_2022_ID) is None
    assert data.get('merged', {}).get(MGMT_CHANGE_ID) is None
    for cid in (FAILED_2022_ID, MGMT_CHANGE_ID):
        assert not (data.get('telegram_posts') or {}).get(cid), \
            '%s несёт пост в канал — просто удалить карточку нельзя' % cid

    print('План:')
    print('  %s (2022, сорвалась) -> веха в %s' % (FAILED_2022_ID, REAL_CLOSE_ID))
    print('  %s (2026, смена управления) -> веха в %s' % (MGMT_CHANGE_ID, REAL_CLOSE_ID))
    print('  %s (бизнес-центр): target %s -> новый профиль %s (%r)'
          % (BC_OFFICE_DEAL_ID, TRC_MALL_ID, NEW_BC_PROFILE_ID, NEW_BC_PROFILE_NAME))

    if not write:
        print('\n(сухой прогон, для записи — --write)')
        return

    # 1) Веха о сорвавшейся сделке 2022 года.
    real['events'] = [MILESTONE_2022, MILESTONE_2026]

    # 2) Источник IRN.ru — корроборирующая ссылка на факт смены управления,
    #    ранее была только у сливаемой карточки c08c9f11e.
    if IRN_SOURCE not in real['src']:
        real['src'].append(IRN_SOURCE)
    if MILESTONE_2026['source'] not in real['src']:
        real['src'].append(MILESTONE_2026['source'])

    # 3) Слияние: карточки уходят из `deals`, редирект — в `merged`.
    data['deals'] = [d for d in data['deals']
                      if d['id'] not in (FAILED_2022_ID, MGMT_CHANGE_ID)]
    data.setdefault('merged', {})
    data['merged'][FAILED_2022_ID] = REAL_CLOSE_ID
    data['merged'][MGMT_CHANGE_ID] = REAL_CLOSE_ID

    # 4) Бизнес-центр — отдельное здание, отдельный профиль.
    companies[NEW_BC_PROFILE_ID] = NEW_BC_PROFILE
    bc_deal['target'] = NEW_BC_PROFILE_ID

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
        f.write('\n')
    print('\nЗаписано.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
