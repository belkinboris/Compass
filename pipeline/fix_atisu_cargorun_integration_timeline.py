# -*- coding: utf-8 -*-
"""Месячная очередь, 9 сентября 2026 — дочитывание карточки `gc5951fac`
(«Владельцы логистической платформы ATI.SU купили 25% разработчика
сервиса CARGO.RUN», добавлена в базу 8 сентября 2026).

Дельта-поиск (саб-агент + личная проверка) нашёл конкретику плана
интеграции продуктов, о которой карточка говорила только в общих словах
(«партнёрство должно объединить поиск заказов... с планированием и
контролем рейсов»). Личный WebFetch (cnews.ru, тот же источник, что уже
стоял в `src`) подтвердил дословно: «Первую версию интеграции выпустят в
ноябре 2026 г.»; «Перевозчики смогут переносить в Cargo.Run Start данные
о заказах, найденных на ATI.SU»; «Новые возможности войдут в действующие
тарифы Cargo.Run Start»; «ATI.SU и Cargo.Run также подготовят совместный
образовательный курс для перевозчиков... посвятят... практическим
способам эффективнее работать на рынке автомобильных грузоперевозок».

НЕ внесено: параллельная, более ранняя (2023 год) инвестиция Святослава
Вильде в ГК «Трак Радар» — это отдельная сделка с другим предметом, не
относящаяся к этой карточке; сумма сделки и консультанты — ни один
источник не назвал.

Запуск:
    python3 pipeline/fix_atisu_cargorun_integration_timeline.py            # сухой прогон
    python3 pipeline/fix_atisu_cargorun_integration_timeline.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_ECO_RATIONALE = (
    'Партнёрство должно объединить поиск заказов на ATI.SU с '
    'планированием и контролем рейсов в продукте CARGO.RUN Start. '
    'Основатель CARGO.RUN Тимур Каримов объясняет: сейчас перевозчики '
    'вручную переносят заказы в свои системы учёта, отдельно ищут '
    'следующую загрузку и обновляют статус свободного транспорта. '
    'Интеграция автоматизирует эти шаги, ускоряет планирование и сводит '
    'к минимуму рутинные операции.'
)
NEW_ECO_RATIONALE = OLD_ECO_RATIONALE + (
    ' Первую версию интеграции планируют выпустить в ноябре 2026 года: '
    'перевозчики смогут переносить в CARGO.RUN Start данные о заказах, '
    'найденных на ATI.SU, — новые возможности войдут в действующие '
    'тарифы. Компании также готовят совместный образовательный курс о '
    'том, как эффективнее работать на рынке грузоперевозок.'
)


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['gc5951fac']

    assert d['eco']['rationale'] == OLD_ECO_RATIONALE, \
        'gc5951fac eco.rationale уже другой: %r' % (d['eco']['rationale'],)

    print('gc5951fac: eco.rationale дополнен сроками и деталями '
          'интеграции (ноябрь 2026, перенос заказов, тарифы, курс)')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['eco']['rationale'] = NEW_ECO_RATIONALE

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
