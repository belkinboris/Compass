# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g39218eec
(Softline купила разработчика ПО для охраны труда Visitech) — карточка
несла структуру владения ДО сделки (Миланов/фонд/«Гиперион»/сотрудники),
но не показывала, что выход продавцов состоялся не одномоментно.
Проверено лично прямым WebFetch https://www.audit-it.ru/contragent/1156501002206_ooo-vizitek
(ЕГРЮЛ-хронология Visitech, audit-it.ru).

`eco.context` (дополнено) — двухэтапный выход. Дословно: «Новый учредитель
– ООО "СЛ СОФТ"» и одновременно «Миланов Рустам Николов больше не
числится в ЕГРЮЛ учредителем» и «ООО "УК ДАЛЬНЕВОСТОЧНЫЙ ФОНД ВЫСОКИХ
ТЕХНОЛОГИЙ" больше не числится в ЕГРЮЛ учредителем» — запись от
24.05.2024 (дата карточки); «ООО "ГИПЕРИОН" больше не числится в ЕГРЮЛ
учредителем» — отдельной записью от 08.11.2024, на 5,5 месяцев позже.

`seller` НЕ заполняется структурно: это не один продавец, а минимум три
стороны (Миланов лично, Дальневосточный фонд, «Гиперион» — тоже доля
Миланова, 22,9%, но выведенная позже отдельным юрлицом) в двух разных
юридических закрытиях — механически свести к одному имени значило бы
выбрать его произвольно (родня уроку CLAUDE.md про лот из нескольких
юрлиц: у сделки один предмет, но несколько сторон, которые нельзя
слить в одно поле).

НЕ ВКЛЮЧЕНО: цитата гендиректора Visitech Ангелины Зиминой при закрытии
(«Благодаря слиянию мы получим значительные ресурсы... интеграция с
комплементарными решениями SL Soft позволит...») — это реассюранс-фраза
для клиентов о будущем продукта, а не условие сделки (тот же класс, что
уже снят в law.terms HeadHunter/Happy Job, см. CLAUDE.md) — в `law.terms`
не переносится; обновление продукта («Электронный наряд-допуск», май
2025) — не структурный факт о сделке, не первостепенно для карточки M&A;
консультанты и согласование ФАС — не найдены ни в одном источнике (сумма
162 млн ₽ ниже порогов уведомления); финансовые показатели Visitech за
2024-2025 год — не раскрывались публично нигде.

Запуск: python3 pipeline/fix_visitech_seller_exit_timeline.py
        python3 pipeline/fix_visitech_seller_exit_timeline.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g39218eec'

OLD_CONTEXT = (
    'Основным владельцем компании, по текущим данным, является ее '
    'бывший гендиректор Рустам Миланов (10,97% прямого владения и еще '
    '22,9% через ООО «Гиперион»), 18,18% принадлежат Дальневосточному '
    'фонду высоких технологий (создан «Роснано», ВЭБ.РФ и РВК), '
    'оставшиеся доли в ООО «Визитек» и «Гиперион» распределены между '
    'сотрудниками и частными инвесторами.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' По данным ЕГРЮЛ, выход продавцов прошёл в два этапа: 24 мая 2024 '
    'года (дата сделки) новым учредителем стало ООО «СЛ Софт», а Рустам '
    'Миланов и Дальневосточный фонд высоких технологий вышли из состава '
    'учредителей; ООО «Гиперион» (та же доля Миланова, 22,9%) вышло '
    'отдельной записью 8 ноября 2024 года, на 5,5 месяцев позже.'
)

NEW_SRC = [
    ['audit-it.ru', 'https://www.audit-it.ru/contragent/1156501002206_ooo-vizitek'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
