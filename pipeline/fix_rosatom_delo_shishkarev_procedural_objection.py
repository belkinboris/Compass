# -*- coding: utf-8 -*-
"""Росатом/«Дело»/Шишкарев (`g5eb6ff22`): 26 августа 2026 года, за два дня до
объявленной даты юридического завершения (28 августа), Сергей Шишкарев через
представителя публично возразил против принятия оферты именно в этот день —
не отказываясь от сделки как таковой, а настаивая на точном соблюдении всех
процедур (порядок уведомления о дате, времени и месте сделки). Отдельно
предложил направить сумму выкупа на докапитализацию самой ГК «Дело» и
поддержку ветеранов СВО вместо выплаты себе.

Цитата не лежит в тексте старых источников (РИА Новости, 25 августа) — та же
ситуация, что и с прошлой правкой того же поля (28aug_closing_date): старое
значение сохраняется, к нему дописывается новое предложение со ссылкой на
источник (Коммерсантъ, 26 августа).

Статус карточки НЕ меняется: Шишкарев прямо говорит «речь не идет о моем
отказе от исполнения договора» — это процедурный спор о дате/порядке, а не
отказ от сделки и не её закрытие; «Обсуждается» остаётся честным статусом.

Запуск: python3 pipeline/fix_rosatom_delo_shishkarev_procedural_objection.py           # проверка
        python3 pipeline/fix_rosatom_delo_shishkarev_procedural_objection.py --write   # запись
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g5eb6ff22'
OLD_CONTEXT = (
    'Процедура «русской рулетки» запущена 17 февраля 2026 года. Шишкарев '
    'сначала намеревался выкупить долю «Росатома», но 26 июня 2026 года '
    'отказался от этого варианта, сославшись на неблагоприятную '
    'макроэкономическую конъюнктуру, после чего 6 июля 2026 года «Росатом» '
    'объявил о решении самостоятельно выкупить 51% Шишкарева; оформление '
    'сделки запущено с 1 июля, завершение ожидается до конца июля 2026 '
    'года. 25 августа 2026 года представитель «Росатома» сообщил точную '
    'дату юридического завершения: «В эту пятницу, 28 августа, юридически '
    'завершается предусмотренная корпоративным соглашением участников ГК '
    '"Дело" процедура выкупа принадлежащей С.Н. Шишкареву 51% доли в '
    'пользу госкорпорации "Росатом". Инициированный "Росатомом" механизм '
    '"русской рулетки" юридически завершится и будет нотариально '
    'удостоверен».'
)
ADDITION = (
    '26 августа 2026 года Сергей Шишкарев через представителя возразил '
    'против закрытия именно 28 августа: «Вынужден констатировать, что к '
    'настоящему моменту не все условия упомянутого договора соблюдены '
    'точно, в том числе в части порядка уведомления о дате, времени и '
    'месте совершения сделки... Я не согласен на отчуждение принадлежащей '
    'мне доли и возражаю против акцепта оферты 28 августа 2026 года либо в '
    'любую иную дату без точного соблюдения условий договора». Он '
    'подчеркнул, что «речь не идет о моем отказе от исполнения договора, а '
    'касается исключительно точного и полного соблюдения процедур», и '
    'предложил направить причитающуюся ему сумму на докапитализацию '
    'самой ГК «Дело» и поддержку ветеранов СВО.'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + ADDITION
NEW_SRC = ['Коммерсантъ', 'https://www.kommersant.ru/doc/8909086']


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    card = next((c for c in data['deals'] if c['id'] == CARD_ID), None)
    assert card is not None, '%r не найдена в базе' % CARD_ID
    assert card.get('eco', {}).get('context') == OLD_CONTEXT, (
        'eco.context уже другое: %r' % card.get('eco', {}).get('context'))
    assert card.get('status') == 'Обсуждается', 'статус уже другое'
    src_already_present = NEW_SRC in card.get('src', [])

    print('ДОБАВЛЕНО: %r' % ADDITION)
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return 1

    card['eco']['context'] = NEW_CONTEXT
    if not src_already_present:
        card.setdefault('src', []).append(NEW_SRC)
    json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('ЗАПИСАНО.')
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv[1:]))
