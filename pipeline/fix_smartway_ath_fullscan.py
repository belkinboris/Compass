import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g8e71c525'

OLD_ECO_RATIONALE = (
    'По словам основателя и гендиректора Smartway Максима Яремко, '
    'ATH последние 11 лет остаётся эксклюзивным представителем AMEX '
    '— крупнейшей в мире компании по организации командировок и '
    'управлению корпоративными расходами.'
)
NEW_ECO_RATIONALE = (
    OLD_ECO_RATIONALE + ' Управляющий директор ATH Филипп Лукьяненко: '
    '«Присоединение к группе Smartway — логичный шаг для продолжения '
    'развития нашей компании».'
)

OLD_ECO_CONTEXT = (
    'По данным «СПАРК-Интерфакса», ещё 44,10% Smartway владеет '
    'гендиректор компании Максим Олегович Яремко, а оставшиеся 4,9% '
    '— у Александра Владимировича Коляскина.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' Остальные 51% Smartway принадлежат '
    'IT-холдингу «1С». ATH работает на рынке с 1992 года: с 2012 года '
    '— эксклюзивный представитель American Express Global Business '
    'Travel в России, в 2017 году приобрела 95% BTM, в 2019 году '
    'присоединила российское представительство Hogg Robinson Group. '
    'По данным реестровых агрегаторов, после сделки выручка ATH резко '
    'снизилась (2023 год — убыток 3,8 млн ₽, 2024 год — выручка 8,8 '
    'млн ₽) — бизнес и клиенты фактически перешли к Smartway; к 2026 '
    'году компания находится в процессе ликвидации.'
)

OLD_SRC = [['Коммерсантъ', 'https://www.kommersant.ru/amp/6014872']]
NEW_SRC = OLD_SRC + [
    ['Inc. Russia', 'https://incrussia.ru/news/smartway-kupil-atn/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['rationale'] == OLD_ECO_RATIONALE
    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== eco.rationale: станет ===')
    print(NEW_ECO_RATIONALE)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['eco']['rationale'] = NEW_ECO_RATIONALE
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
