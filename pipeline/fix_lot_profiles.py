# -*- coding: utf-8 -*-
"""Бэклог A19: одиннадцать «профилей компаний» — на деле лоты из нескольких юрлиц.

ЧТО СЛОМАНО. В справочнике компаний лежат записи «ООО «Датана» и 49% ООО
«Датабриз»», «долей ООО «Бион», ООО «Химфармкомплект», ООО «Фарминтеллект»»,
«долей в пяти юрлицах сети гипермаркетов OBI». Это не компания, а состав сделки,
попавший в каталог: такая запись открывается как профиль, считается в «1846
компаний» и показывается в плашке сторон вместе с процентами из заголовка.

ПОЧЕМУ ИХ НЕ ПОЧИНИЛИ В ПРОГОНЕ 37. Тогда чистили названия вырезанием и решили,
что резать нельзя: останется первое юрлицо, а сделка была про все. Замер был
верным, вывод — нет. Резать нужно не до одного имени, а только доли и предлоги:
«ООО «Датана» и 49% ООО «Датабриз»» -> «ООО «Датана» и ООО «Датабриз»». Все имена
остаются на месте, уходит только то, чему в названии не место.

ЧТО СДЕЛАНО.
  * 11 названий вычищены. Разрешено вырезать (доли, «долей», «оставшиеся»,
    предлоги) и поправить падеж; проверка та же, что в прогонах 34 и 37:
    результат обязан ложиться на старое название слово в слово с точностью до
    окончаний. Кавычки нормализуются — это типографика, а не новый факт.
  * У 9 записей выставлен признак `lot`. Профиль остаётся один (у сделки одно
    поле «предмет»), но интерфейс теперь прямо говорит: это не одна компания, а
    несколько юрлиц, проданных одним лотом. Две записи из одиннадцати признак не
    получают: «права требования к АО «РоузХилл» и опцион на 50% акций» — это
    компания «РоузХилл», а что именно продали, написано в карточке сделки;
    «проекте Баксы» — один проект, а не лот.

ЧЕГО НЕ ДЕЛАЕМ. Не разбиваем лот на отдельные профили: у сделки одно поле
«предмет», и при разбиении пришлось бы выбрать одно юрлицо из трёх — то есть
потерять часть сделки. Признак честнее.

Запуск:
    python3 pipeline/fix_lot_profiles.py            # сухой прогон
    python3 pipeline/fix_lot_profiles.py --write    # записать
"""
import json
import re
import sys

PATH = 'static/data/deals_promoted.json'

# id профиля -> (новое название, лот ли это)
TABLE = {
    'gf3f11590': ('«Транслес» и «Грузовая компания»', True),
    'g91948881': ('ООО «Серноводский элеватор» и Агрокомплекс «Конезавод «Самарский»»', True),
    'ge9d8842b': ('Rubis Holdings Limited и Jullianita Limited', True),
    'g6f7fd542': ('Компании, владеющие отелем Baikal View', True),
    'geca16a9c': ('ООО «Вет Юнион», «Проактив Информ», «Раритас Тера»', True),
    'gdfe819ae': ('ООО «Датана» и ООО «Датабриз»', True),
    'g71505e18': ('Пять юрлиц сети гипермаркетов OBI', True),
    'g7bc6e441': ('ООО «Бион», ООО «Химфармкомплект», ООО «Фарминтеллект»', True),
    'g6db4ded9': ('ООО «ЭкоПродукт» и ООО «Агропромышленная компания «Кумир»»', True),
    # не лоты: одна компания и один проект
    'g5eb71006': ('АО «РоузХилл»', False),
    'gf6825669': ('Проект «Баксы»', False),
}

DIRT = re.compile(r'\d+[,.]?\d*\s*%|\bдолей\b|\bакций\b|оставшиеся|^\s*доля\b', re.I)
WORD = re.compile(r"[\w%,.№-]+", re.U)

# Окончания, на которые слову позволено разойтись с оригиналом, когда общего
# начала меньше трёх знаков. Список закрытый: «пяти» -> «Пять» так проходит,
# а «Вера» -> «Вета» (окончания «ра»/«та») — нет.
ENDINGS = {'', 'ь', 'и', 'ы', 'а', 'я', 'ю', 'е', 'у', 'ти', 'ть', 'ей', 'ой', 'ам', 'ах', 'ов'}


def norm(s):
    return re.sub(r'\s+', ' ', str(s or '')).strip()


def bare(w):
    return w.strip('«»"(),.;:%').lower()


def same_word(a, b):
    a, b = bare(a), bare(b)
    if not a or not b:
        return False
    if a == b:
        return True
    n = min(len(a), len(b))
    i = 0
    while i < n and a[i] == b[i]:
        i += 1
    if i >= max(3, int(0.6 * n)):
        return True
    # Короткие слова порог в три знака не проходят даже в родных формах:
    # у «Пять»/«пяти» общего начала два знака. Ослабляем ровно для них —
    # оба слова короткие, начало совпадает, а разошлись только окончания.
    return (i >= 2 and max(len(a), len(b)) <= 5
            and a[i:] in ENDINGS and b[i:] in ENDINGS)


def words(s):
    """Слова без пунктуации: одинокая запятая не слово и совпасть ни с чем не может."""
    return [w for w in WORD.findall(s) if bare(w)]


def fits_words(result, source):
    """Каждое слово результата встречается в старом названии (в том же порядке)."""
    rw, sw = words(result), words(source)
    i = 0
    for word in rw:
        while i < len(sw) and not same_word(word, sw[i]):
            i += 1
        if i >= len(sw):
            return False
        i += 1
    return True


# Правило проверяется на себе: чужое имя на старое название лечь не должно,
# а падежные формы — должны.
assert same_word('Пять', 'пяти') and same_word('Агрокомплекс', 'Агрокомплекса')
assert not same_word('Вера', 'Вета') and not same_word('Иван', 'Игорь')
assert fits_words('ООО «Вет Юнион», «Проактив Информ»',
                  'ООО «Вет Юнион», 74,9% «Проактив Информ», 76% «Раритас Тера»')
assert not fits_words('ООО «Иван Петров»',
                      'ООО «Вет Юнион», 74,9% «Проактив Информ», 76% «Раритас Тера»')


def main(write):
    data = json.load(open(PATH, encoding='utf-8'))
    comps = data['companies']

    plan, done = [], []
    for cid, (new, is_lot) in TABLE.items():
        c = comps.get(cid)
        assert c is not None, 'нет профиля %s' % cid
        old = norm(c.get('name'))
        if old == new and bool(c.get('lot')) == is_lot:
            done.append(cid)
            continue
        assert DIRT.search(old), '%s: в названии нечего чистить (%r)' % (cid, old)
        assert fits_words(new, old), '%s: новое название не выводится из старого\n  %r -> %r' % (cid, old, new)
        assert not DIRT.search(new), '%s: в новом названии осталась доля' % cid
        plan.append((cid, old, new, is_lot, c))

    assert len(plan) + len(done) == len(TABLE), 'часть профилей изменилась вне скрипта'
    if not plan:
        print('Уже применено: все %d записей приведены в порядок.' % len(TABLE))
        return

    print('Профилей к правке: %d (из них помечаются лотом: %d)'
          % (len(plan), sum(1 for p in plan if p[3])))
    for cid, old, new, is_lot, _ in plan:
        print('  %s%s\n     было:  %s\n     стало: %s' % (cid, ' [лот]' if is_lot else '', old, new))
    if not write:
        print('\nСухой прогон. Запись — с ключом --write.')
        return
    for cid, _, new, is_lot, c in plan:
        c['name'] = new
        if is_lot:
            c['lot'] = True
        else:
            c.pop('lot', None)
    with open(PATH, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    left = sum(1 for c in comps.values() if DIRT.search(norm(c.get('name'))))
    print('\nЗаписано. Профилей с долей в названии осталось: %d.' % left)


if __name__ == '__main__':
    main('--write' in sys.argv)
