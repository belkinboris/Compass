# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень): gmru-darkin-
vladmorribport («Сергей Дарькин закрыл сделку по выкупу доли
«Владморрыбпорта»»).

Расхождение суммы (18,7 vs 17–17,5 млрд ₽), записанное в «Известных
проблемах» как нерешённое, разобрано личным WebFetch. Механизм: 18,7
млрд ₽ — это заранее одобренный акционерами в апреле ПОТОЛОК
кредитования (см. `law.struct`: «заём... в сумме не более 18,7 млрд
руб.»), а фактически раскрытая через портал раскрытия корпоративной
информации цена сделки — 17,5 млрд ₽, подтверждена НЕЗАВИСИМО двумя
источниками:
- korabel.ru (24.06.2026, личный WebFetch): «выкупило 47% акций
  ОАО «Владивостокский морской рыбный порт» (ВМРП) у предпринимателя
  Александра Евдокимова» за «17,5 млрд рублей», со ссылкой (через
  KONKURENT.RU) на «данные портала раскрытия корпоративной информации»;
- primamedia.ru (11.06.2026, по сводке саб-агента): договор денежного
  займа между ВМРП и «Геотэкс» — на ту же сумму, 17,5 млрд рублей.
Родня уже записанного класса дефекта («Число из подзаголовка о выкупе
бизнеса может быть суммой ЗАЙМА на его финансирование, а не ценой
актива») — только здесь ОБА числа связаны с займом (одно — одобренный
лимит, другое — фактически предоставленная и раскрытая через портал
сумма), и вторая цифра точнее первой, а не относится к другому активу.

Побочный факт того же дочитывания — личный WebFetch primamedia.ru
(05.08.2026): обязательная оферта миноритариям по 2 809,40 ₽ за акцию
получила от Банка России предписание о несоответствии законодательству
(«Скорее всего, речь идёт о чисто технических моментах») — это отдельная
процедура ПОСЛЕ консолидации 99,76%, самой сделки по 47% не касается.

Запуск: python3 pipeline/fix_monthly_2026_09_07_vladmorribport_sum.py
        python3 pipeline/fix_monthly_2026_09_07_vladmorribport_sum.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gmru-darkin-vladmorribport'
OLD_SUM = '18,7 млрд ₽'
NEW_SUM = '17,5 млрд ₽'

OLD_CONTEXT = (
    'Теперь «ГЕОТЭКСУ» принадлежит 99,76% капитала стивидорной компании, '
    'пишет InfraNews со ссылкой на данные ЕГРЮЛ.'
)
NEW_CONTEXT = (
    OLD_CONTEXT + ' Раскрытая через портал раскрытия корпоративной '
    'информации цена сделки — 17,5 млрд ₽; это меньше одобренного '
    'акционерами в апреле кредитного лимита (не более 18,7 млрд ₽), под '
    'который ВТБ профинансировал покупку. В августе 2026 года '
    'обязательная оферта миноритариям (2 809,40 ₽ за акцию) получила от '
    'Банка России предписание о технических несоответствиях '
    'законодательству — самой сделки по 47% это не касается.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}
    deal = by_id[DEAL_ID]

    assert deal['sum'] == OLD_SUM
    assert deal['eco']['sum'] == OLD_SUM
    assert deal['eco']['context'] == OLD_CONTEXT

    print('=== sum / eco.sum ===')
    print(NEW_SUM)
    print()
    print('=== eco.context ===')
    print(NEW_CONTEXT)

    if write:
        deal['sum'] = NEW_SUM
        deal['eco']['sum'] = NEW_SUM
        deal['eco']['context'] = NEW_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
