# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g1ce3ddfc
(IDS Borjomi Russia продала завод «Чистозерье» ООО «Торговый дом
Усть-Каменский»/Евгению Громчакову) — оценка сделки стояла без атрибуции,
а причина продажи не была раскрыта вовсе, хотя источник (Коммерсантъ,
единственная ссылка карточки) прямо называет и эксперта, и версию причины.
Проверено лично прямым WebFetch https://www.kommersant.ru/doc/6822105.

`buyer_name`/`law.struct` НЕ трогаются: Коммерсантъ прямо пишет «IDS Borjomi
Russia продала новосибирскому бизнесмену Евгению Громчакову ООО «Карачинская
звезда»» — buyer_name как имя физлица уже верно называет прямую сторону по
собственным словам источника, а law.struct уже дословно несёт структуру
владения (99% Громчаков/1% Голодов через ООО «Торговый дом Усть-Каменский»).
Это НЕ случай «прямой юридический покупатель против бенефициара» (родня
g81510c02) — там источник называл юрлицо, здесь источник прямо называет
физлицо покупателем.

1) `eco.val` — атрибуция оценки. Дословно: «Независимый эксперт Алена
Кондратьева поясняет, что «Карачинская звезда» выпускает воду «Чистозерье».
Именно права на бренд, вместе с производственными мощностями, по ее словам,
были реализованы... Стоимость сделки могла составить 60–65 млн руб., считает
эксперт.» Кондратьева — единственный названный эксперт в тексте, оценка идёт
следующим предложением без другого имени между ними — атрибуция обоснована.

2) `eco.rationale` (новое поле, ранее отсутствовало) — версия причины
продажи, с явной пометкой мнения эксперта, не факта:
  - Кондратьева: «В портфеле IDS Borjomi есть более сильные марки, например
    «Святой источник», возможно, решено сфокусироваться на них».
  - Алексей Воинов, директор «Аква-Вайт»: «на рынке Новосибирской области у
    «Карачинской звезды» есть сильный конкурент — «Карачинский источник»,
    это могло стать поводом для решения о продаже».
Обе версии — гипотезы аналитиков рынка, не заявления самой IDS Borjomi или
покупателя (компания и покупатель причину публично не комментировали) —
оставлены как атрибутированные мнения, не как установленный факт.

НЕ ВКЛЮЧЕНО: авторская фраза самого Коммерсанта («продиктована стремлением
IDS Borjomi Russia сфокусироваться на федеральных брендах, уйдя от
конкуренции с региональными игроками») — это пересказ редакции, а не прямая
цитата спикера, и она пересказывает те же две версии экспертов, а не несёт
третий отдельный факт.

Запуск: python3 pipeline/fix_ids_borjomi_chistozerye_valuation_and_rationale.py
        python3 pipeline/fix_ids_borjomi_chistozerye_valuation_and_rationale.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g1ce3ddfc'

OLD_VAL = 'По оценке экспертов; 60–65 млн ₽ (по оценке)'
NEW_VAL = (
    'По оценке независимого эксперта Алены Кондратьевой; 60–65 млн ₽ '
    '(по оценке)'
)

NEW_RATIONALE = (
    'Причина продажи публично не раскрывалась ни IDS Borjomi Russia, ни '
    'покупателем. По мнению независимого эксперта Алены Кондратьевой, '
    '«в портфеле IDS Borjomi есть более сильные марки, например «Святой '
    'источник», возможно, решено сфокусироваться на них». Алексей Воинов, '
    'директор «Аква-Вайт», указывает на другую возможную причину: «на рынке '
    'Новосибирской области у «Карачинской звезды» есть сильный конкурент — '
    '«Карачинский источник», это могло стать поводом для решения о продаже».'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['val'] == OLD_VAL
    assert 'rationale' not in deal['eco'], 'eco.rationale уже существует'

    print(f'=== eco.val: {OLD_VAL!r} -> {NEW_VAL!r} ===')
    print('=== eco.rationale (новое поле): станет ===')
    print(NEW_RATIONALE)

    if write:
        deal['eco']['val'] = NEW_VAL
        deal['eco']['rationale'] = NEW_RATIONALE
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
