# -*- coding: utf-8 -*-
"""Месячная очередь, карточка gf019cd92 (Станислав Карабут/бизнес-парк
«Арма»): дельта-поиск нашёл, что случилось с активом ПОСЛЕ этой
сделки — актив прошёл ещё две смены владельца в течение года и
вернулся к исходному собственнику, Рустему Терегулову (группа
«Большой город»), у которого его в 2022 году забрал АО «Ю-Крафт» —
именно эта, более ранняя смена, уже описана в поле `eco.share`. Не
через `review.py`: источники (Коммерсантъ, РИА Недвижимость) не
образуют с уже записанным текстом `eco.share` непрерывный кусок.

Источники — читал напрямую (WebFetch, дословные цитаты подтверждены):
https://www.kommersant.ru/doc/8691575
https://realty.ria.ru/20260528/arma-2095213540.html

Запуск: python3 pipeline/fix_arma_returned_to_teregulov_context.py [--write]
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gf019cd92'

OLD_SHARE = (
    'Исходно «Арма» принадлежала компании «Большой город» Рустема '
    'Терегулова, но более двух лет назад он передал объект новому '
    'владельцу (см. «Ъ» от 10 июня 2022 года). Тогда собственником '
    'стало АО «Ю-Крафт» под управлением Владислава Цыгана, который '
    'также руководил АО «Спецтехника» экс-акционера «Еврохима» '
    'Дмитрия Стрежнева, чье состояние в 2021 году Forbes оценивал в '
    '$750 млн.'
)
SHARE_ADDITION = (
    ' Уже в августе 2025 года доли в компании перешли МКООО '
    '«Креэйшнз», а затем — МКООО «Панорама», которое стало владельцем '
    '100% долей в ООО «АЗ «Арма»». МКООО «Панорама» контролирует '
    'Рустем Терегулов через девелоперскую группу «Большой город» — '
    'то есть бизнес-квартал «Арма» вернулся первоначальному '
    'владельцу. Два источника «Ъ» считают, что смена владельца, '
    'скорее всего, носит формальный характер; партнёр NF Group '
    'Марина Малахатько предполагает, что речь идёт о внутренней '
    'реструктуризации владения активом.'
)
NEW_SHARE = OLD_SHARE + SHARE_ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['share'] == OLD_SHARE, \
        f"eco.share: неожиданное значение {deal['eco']['share']!r}"

    print(f'{CARD_ID} eco.share: += возврат актива Терегулову через '
          f'год после этой сделки')

    if write:
        deal['eco']['share'] = NEW_SHARE
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('ЗАПИСАНО')
    else:
        print('Сухой прогон. Запись — с --write.')


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
