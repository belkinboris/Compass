# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g093489b0
(Росатом ведет переговоры о покупке дизайн-центра микроэлектроники
«Модуль») — карточка стоит «Обсуждается» с мая 2024 года; REVISION_BRIEF.md
прямо требует для незакрытых сделок обязательную проверку статуса как
самого вредного класса устаревания. Проверено лично прямым WebFetch.

Ни закрытия, ни срыва сделки НЕ НАЙДЕНО ни в одном источнике 2024-2026 —
но нашёлся косвенный сигнал, что НТЦ «Модуль» действует как самостоятельное
юрлицо: Минпромторг оштрафовал компанию напрямую в июне 2026 года, без
единого упоминания Росатома или НПО КИС. Дословно (CNews, 26.06.2026):
«Минпромторг оштрафовал АО НТЦ «Модуль» на 290,1 млн руб. за нарушение
сроков разработки радиационно-стойкого процессора» — «второй этап
задержан на 10 дней (штраф 4,95 млн руб.), третий этап просрочен на 288
дней (штраф 285,18 млн руб.)».
https://www.cnews.ru/news/top/2026-06-26_minpromtorg_oshtrafoval_ntts

Это НЕ доказательство срыва переговоров (сделка никогда официально не
подтверждалась ни одной стороной, а форма АО не раскрывает состав
акционеров в открытых реестрах ЕГРЮЛ — переход контроля таким путём не
проверить) — компания могла быть оштрафована и уже будучи частью
периметра Росатома. `status` НЕ меняется: ни «Закрыта», ни «Не
состоялась» не подтверждены явно (родня уже записанным случаям
«заявленные сроки закрытия прошли без подтверждения — статусы намеренно
НЕ изменены»).

НЕ ВКЛЮЧЕНО: независимая оценка суммы, консультанты, согласование ФАС —
не найдены ни в одном источнике; интервью гендиректора Адамова (январь
2026, журнал «Национальная оборона») о планах компании до 2027 года без
упоминания сделки — не первостепенный факт для карточки M&A, штраф
показывает то же самое (компания действует самостоятельно) более
конкретно и проверяемо.

Запуск: python3 pipeline/fix_ntc_modul_status_check.py
        python3 pipeline/fix_ntc_modul_status_check.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g093489b0'

OLD_CONTEXT = (
    'Размер долга один из источников «Ведомостей» оценил в 100 млн руб. '
    '«Я предполагаю, что у центра накопились долги перед заказчиками», '
    '— подтвердил другой собеседник издания, так что «Росатому» он '
    'может достаться по низкой цене.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' По состоянию на 26 июня 2026 года подтверждений закрытия или '
    'срыва переговоров не найдено: Минпромторг оштрафовал АО НТЦ '
    '«Модуль» на 290,1 млн руб. за нарушение сроков разработки '
    'радиационно-стойкого процессора напрямую, без единого упоминания '
    'Росатома или НПО КИС в связи со штрафом (CNews).'
)

NEW_SRC = [
    ['CNews', 'https://www.cnews.ru/news/top/2026-06-26_minpromtorg_oshtrafoval_ntts'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    assert deal['status'] == 'Обсуждается'
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
