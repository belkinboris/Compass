# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g8b512496 (Сергей Галицкий приобрел маслозавод «Южный полюс» в
Кропоткине, 28.12.2023, статус «Закрыта») — покупатель (ООО «СПП
«Юг»») спустя пять месяцев сам сменил структуру владения: Галицкий
сократил долю, у завода появились новые совладельцы.

Проверено лично прямым WebFetch (Коммерсантъ, 28.06.2024,
doc/6792638): «Подконтрольное Сергею Галицкому АО «Объединенный
капитал» в середине мая сократило с 75% до 40% долю в ООО СПП «Юг»» —
25% получил Аслан Шхачемуков, 10% — Арам Фундукян, 25% сохранил за
собой Владимир Хашиг (гендиректор СПП «Юг» и одновременно ФК
«Краснодар»).

НЕ ВКЛЮЧЕНО: финансовые показатели СПП «Юг»/«Южного полюса» за
2024-2025 годы — по данным саб-агента только из агрегаторов (СПАРК/
Saby/list-org), без дословной журналистской цитаты, и сами цифры
расходятся между двумя разными юрлицами группы (СПП «Юг» — убыток с
2024 года; «Южный полюс» как отдельное юрлицо — по другим агрегаторам
прибыльно) — точность обеих цифр не дозаверена; новых приобретений в
агробизнесе Галицкого за 2024-2026 годы саб-агент не нашёл; винный
бизнес «Галицкий & Галицкий»/«Русский терруар» — отдельный, не
связанный с этим заводом актив (источники о нём вдобавок расходятся
в цифрах прибыли), в карточку о заводе не добавляется.

Запуск: python3 pipeline/fix_galitsky_yuzhny_polyus_ownership_split.py
        python3 pipeline/fix_galitsky_yuzhny_polyus_ownership_split.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g8b512496'

OLD_EXTRA = (
    'Приобретение 100% долей ООО «Южный полюс» — маслозавода в '
    'Кропоткине, выпускающего растительное масло под брендом '
    '«Краснодарское отборное». Мощность переработки до 100 тыс. тонн '
    'сырья в год.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' В середине мая 2024 года структура владения покупателя '
    'изменилась: подконтрольное Галицкому АО «Объединенный капитал» '
    'сократило долю в ООО СПП «Юг» с 75% до 40%, 25% получил Аслан '
    'Шхачемуков, 10% — Арам Фундукян, 25% сохранил Владимир Хашиг.'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6792638'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
