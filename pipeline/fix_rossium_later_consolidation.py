# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка g703c4f62 (Авдеев/
Судариков, «Россиум»): дельта-поиск нашёл более поздний, самостоятельный
шаг консолидации контроля — через год после сделки Авдеева, в октябре
2025 года, доля в самом «Россиуме» перешла от промежуточной холдинговой
структуры к конечному бенефициару. Авдеев в этом более позднем событии
не упоминается вовсе — это продолжение истории уже НОВОГО владельца, а
не часть исходной сделки.

Источник: AK&M (2 октября 2025) — читал напрямую.
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g703c4f62'
OLD_CONTEXT = (
    '«Уверен, что под его руководством Концерн «Россиум» продолжит '
    'успешное развитие и достигнет новых высот. Для меня же пришло '
    'время сосредоточиться на моих близких, в первую очередь детях, и '
    'других важных аспектах моей жизни вне рамок бизнеса»,— сообщил '
    'господин Авдеев.'
)
ADDITION = (
    '2 октября 2025 года «Россиум» и связанная с ним холдинговая '
    'компания «Доминанта» сменили владельца ещё раз: 93,14% в '
    'концерне «Россиум» перешли от «Доминанты» к АО «Инвестиционная '
    'компания «Регион»», а 90% самой «Доминанты» отошли бенефициару '
    '«Региона» Сергею Сударикову — то есть окончательная консолидация '
    'контроля растянулась почти на год после ухода Авдеева.'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} eco.context: += более поздняя консолидация "
          "контроля (октябрь 2025)")
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
