import json
import sys

DATA = 'static/data/deals_promoted.json'

NEW_ECO_CONTEXT = (
    '14 мая и 3 июня 2025 года «Росатом» заложил весь полученный пакет '
    '(92,5% акций ДВМП, двумя равными траншами по 46,26%) — суммы '
    'займов и держатели залога не раскрываются, эксперты называют '
    'причиной потребность в средствах на инвестпрограмму и развитие '
    'перевозок по Севморпути. В апреле 2026 года ФАС согласовала '
    'создание совместного предприятия «Росатома» с дубайским портовым '
    'оператором DP World: 92,5% акций ДВМП вносятся в ООО «Глобальная '
    'логистика», «Росатом» получает 51%, DP World выкупает 49% за '
    'денежный вклад. В августе 2026 года сделку одобрила '
    'правительственная комиссия по контролю за иностранными '
    'инвестициями, акции ДВМП на Московской бирже в тот день выросли '
    'на 18,1%.'
)

NEW_SRC = [
    ['Ведомости', 'https://www.vedomosti.ru/business/articles/2025/11/28/1158848-rosatom-zalozhil-prinadlezhaschie-emu-aktsii-fesco'],
    ['Ведомости', 'https://www.vedomosti.ru/investments/news/2026/04/07/1188440-aktsii-virosli'],
    ['atomic-energy.ru', 'https://www.atomic-energy.ru/news/2026/08/20/167918'],
]


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['c6b59f911']

    assert d['eco'].get('context') is None, 'eco.context уже занят: %r' % (d['eco'].get('context'),)
    urls = {s[1] for s in d['src']}
    for src in NEW_SRC:
        assert src[1] not in urls, 'источник уже добавлен: %s' % src[1]

    print('c6b59f911: eco.context заполнен (залог 92,5% акций, СП с DP '
          'World, одобрение правкомиссии); добавлены три источника')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['eco']['context'] = NEW_ECO_CONTEXT
    d['src'].extend(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
