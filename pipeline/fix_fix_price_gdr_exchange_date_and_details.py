# -*- coding: utf-8 -*-
"""Месячная очередь, 9 сентября 2026 — дочитывание карточки `gec757ede»
(«Публичный обмен ГДР Fix Price Group PLC на акции "Фикс Прайс"»,
добавлена в базу 8 сентября 2026).

Дельта-поиск (саб-агент + личная проверка) нашёл, что ДАТА в карточке
(22 октября 2025 года) не соответствует ни одному реальному этапу сделки.
Личным WebFetch подтверждена вся хронология:

- Начало обмена — 5 июня 2025 (expert.ru, уже стоял в `src`: «Торговая
  сеть Fix Price запустила процесс обмена... Сбор заявок пройдет с
  5 июня по 4 июля»).
- Итоги обмена и первый день торгов акциями ПАО «Фикс Прайс» на Мосбирже
  — 20 августа 2025 года (media.fix-price.com, официальный пресс-релиз):
  «было обменено 104,2 млн ГДР на 16,5 млрд акций ПАО «Фикс Прайс»»,
  «около 16,5% уставного капитала ПАО «Фикс Прайс»», обмен проведён
  «через RTS» (Retail Technologies & Solutions Limited, дочерняя
  структура группы).
- Дата 22 октября 2025 года ни в одном источнике не встретилась —
  похоже на ошибку исходного разбора. Дата закрытия исправлена на
  20 августа 2025 (день, когда обмен официально завершён и подведены
  итоги) — смена месяца и дня внутри того же года, без утверждения
  нового года.

Дополнительно, личный WebFetch (kommersant.ru/doc/8764989, 25.06.2026)
подтвердил дословно финансовые результаты компании за полный 2025 год:
«выручка Fix Price выросла на 4,3% по сравнению с 2024 годом — до
313,3 млрд руб.»; «чистая прибыль, напротив, упала на 49,5% — до
11,2 млрд руб.»; «Акционеры... одобрили решение совета директоров о
невыплате дивидендов по итогам 2025 года».

НЕ внесено (саб-агент честно пометил как непроверенное дословным
чтением, часть страниц отдавала 401/капчу): программы buyback (два
этапа, 2025-2026), обратный сплит акций 1000:1, техническая конвертация
«хвоста» ГДР в июне 2026 — каждое требует отдельной проверки прямым
чтением первоисточника, прежде чем вносить в карточку.

Запуск:
    python3 pipeline/fix_fix_price_gdr_exchange_date_and_details.py            # сухой прогон
    python3 pipeline/fix_fix_price_gdr_exchange_date_and_details.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_DATE = '2025-10-22'
NEW_DATE = '2025-08-20'

OLD_ECO_CONTEXT = '—'
NEW_ECO_CONTEXT = (
    'Итоги обмена подведены 20 августа 2025 года: обменено 104,2 млн ГДР '
    'на 16,5 млрд акций ПАО «Фикс Прайс» (около 16,5% уставного '
    'капитала) через дочернюю структуру группы Retail Technologies & '
    'Solutions Limited (RTS). Держатели ГДР, не участвовавшие в обмене, '
    'сохранили право собственности на расписки, но лишились доступа к '
    'организованным торгам на Московской бирже и СПБ Бирже; листинг ГДР '
    'сохраняется на казахстанской Astana International Exchange.'
)

OLD_TARGET_FIN = (
    'Выручка материнской компании FIX PRICE GROUP PLC за первое '
    'полугодие выросла до 154,5 млрд р (+4,1% год к году), открыто 299 '
    'новых магазинов (+4,2% с начала года), сопоставимые продажи выросли '
    'на 0,9%, трафик сопоставимых магазинов (LFL) снизился на 3,4%, '
    'чистая прибыль упала до 6,2 млрд р.'
)
NEW_TARGET_FIN = OLD_TARGET_FIN + (
    ' За весь 2025 год выручка выросла на 4,3% год к году, до 313,3 '
    'млрд ₽, а чистая прибыль упала на 49,5%, до 11,2 млрд ₽; акционеры '
    'одобрили невыплату дивидендов по итогам 2025 года.'
)

NEW_SRC = ['Коммерсантъ', 'https://www.kommersant.ru/doc/8764989']


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['gec757ede']

    assert d.get('date') == OLD_DATE, \
        'gec757ede date уже другой: %r' % (d.get('date'),)
    assert d['eco']['context'] == OLD_ECO_CONTEXT, \
        'gec757ede eco.context уже другой: %r' % (d['eco']['context'],)
    assert d['eco']['target_fin'] == OLD_TARGET_FIN, \
        'gec757ede eco.target_fin уже другой: %r' % (d['eco']['target_fin'],)
    urls = {s[1] for s in d['src']}
    assert NEW_SRC[1] not in urls, 'источник уже добавлен'

    print('gec757ede: date "2025-10-22" -> "2025-08-20" (реальная дата '
          'подведения итогов обмена); eco.context заполнен (объём '
          'обмена, RTS, судьба неучаствовавших держателей ГДР); '
          'eco.target_fin дополнен финансовыми результатами 2025 года; '
          'добавлен источник kommersant.ru')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['date'] = NEW_DATE
    d['eco']['context'] = NEW_ECO_CONTEXT
    d['eco']['target_fin'] = NEW_TARGET_FIN
    d['src'].append(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
