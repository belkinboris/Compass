# -*- coding: utf-8 -*-
"""Две карточки несли не тот год: g98a85532 («1С может войти в капитал ПАО
«Группа Астра» на 10-20%») — «2025» вместо 2026, g7e470153 («Суточно.ру»
привлекло инвестиции pre-IPO фондов ВИМ Инвестиции») — «2025» вместо 2024.

g98a85532. CNews прямо датирует материал 19 марта 2026 года («2026-03-19»
в самом адресе статьи) и пишет, что «Астра» начала рассматривать
привлечение стратегического инвестора в январе 2026 года — переговоры
целиком лежат в 2026 году, источник карточки (Forbes) описывает тот же
эпизод. Год-заглушка компактного импорта поставила не тот год.

g7e470153. Источник карточки (РБК, 09.01.2025) сообщает о ПЛАНАХ
основателя провести IPO в 2025 году — это не дата самой сделки. Сама
сделка (покупка 16,03% компании Фондом пре-айпио 2 под управлением ВИМ
Инвестиции) состоялась в МАРТЕ 2024 года — независимо подтверждено
investfunds.ru (публикация 14 октября 2024, «Дата покупки доли: Март 2024
года») и Forbes. Классический случай «дата публикации статьи — не дата
сделки» (см. CLAUDE.md): карточка получила год статьи о ПОСЛЕДУЮЩИХ планах,
а не год самой сделки, которую эта же карточка описывает. Точный день не
назван ни одним источником, поэтому пишем только год — родня уже принятого
решения по 238 карточкам с датой-заглушкой «1 января» (пишем то, что
доказано, не сочиняем день).

ПОЧЕМУ НЕ ЧЕРЕЗ `review.py`. `date_is_supported()` намеренно запрещает
менять год — перенос года обязан быть отдельным, явным решением с
проверяемым источником, а не автоматической правкой в общей таблице.

Обе карточки выходят из среза 2025 года.

Запуск:
    python3 pipeline/fix_1c_astra_and_sutochno_years.py            # сухой прогон
    python3 pipeline/fix_1c_astra_and_sutochno_years.py --write    # записать
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

FIXES = [
    dict(id='g98a85532', old='2025', new='2026-03-19',
         quote='CNews, адрес статьи датирован 2026-03-19; «Астра» начала '
               'рассматривать привлечение стратегического инвестора в '
               'январе 2026 года'),
    dict(id='g7e470153', old='2025', new='2024',
         quote='investfunds.ru, публикация 14 октября 2024: «Дата покупки '
               'доли: Март 2024 года»; РБК от 09.01.2025 сообщает не о '
               'сделке, а о планах основателя провести IPO в 2025 году'),
]


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}

    for fx in FIXES:
        deal = by_id.get(fx['id'])
        assert deal is not None, 'нет сделки %s' % fx['id']
        assert deal.get('date') == fx['old'], \
            '%s: дата уже другая: %r, ожидали %r' % (
                fx['id'], deal.get('date'), fx['old'])
        print('%s: date %r -> %r' % (fx['id'], fx['old'], fx['new']))
        print('  цитата: %r' % fx['quote'])

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    for fx in FIXES:
        by_id[fx['id']]['date'] = fx['new']
        assert by_id[fx['id']]['date'] == fx['new'], 'дата не записалась'

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
