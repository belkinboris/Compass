def inn_is_valid(inn: str) -> bool:
    """Контрольное число ИНН по официальному алгоритму ФНС — 10 знаков для
    юрлиц, 12 для ИП/физлиц. Нужна для защиты от опечатки при переносе числа
    из результата поиска в реестр вручную."""
    if not inn or not inn.isdigit():
        return False
    digits = [int(c) for c in inn]
    if len(inn) == 10:
        weights = (2, 4, 10, 3, 5, 9, 4, 6, 8)
        control = sum(w * d for w, d in zip(weights, digits)) % 11 % 10
        return control == digits[9]
    if len(inn) == 12:
        weights1 = (7, 2, 4, 10, 3, 5, 9, 4, 6, 8)
        weights2 = (3, 7, 2, 4, 10, 3, 5, 9, 4, 6, 8)
        control1 = sum(w * d for w, d in zip(weights1, digits)) % 11 % 10
        control2 = sum(w * d for w, d in zip(weights2, digits)) % 11 % 10
        return control1 == digits[10] and control2 == digits[11]
    return False


