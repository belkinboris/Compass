import json
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__)).rsplit(os.sep, 1)[0]
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')
DEAL = 'g20d4cc38'

NEW_STRUCT = (
    'Правительство США через Международную финансовую корпорацию '
    'развития (DFC) может получить около 15% в структуре, которая будет '
    'создана в рамках сделки по приобретению международных активов '
    '"ЛУКОЙЛа". При этом американская сторона не будет вносить денежные '
    'средства на первоначальном этапе. Группе инвесторов, возглавляемой '
    'американским миллиардером Тоддом Боули, может достаться '
    'миноритарная доля, а более половины совокупного капитала новой '
    'структуры будет принадлежать инвесторам с Ближнего Востока. Среди '
    'потенциальных участников сделки - структуры, связанные с правящей '
    'семьей Абу-Даби, а также два миллиардера сирийского происхождения '
    'из Катара, являющиеся деловыми партнерами Джареда Кушнера - зятя '
    'президента США, и Иванки Трамп - дочери президента. Структура '
    'сделки предусматривает, что США через Боули и правительство будут '
    'контролировать большинство мест в совете директоров создаваемой '
    'компании. Высокопоставленный представитель американской '
    'администрации заявил, что сделка предусматривает "значительный '
    'авансовый платеж и долю США в прибыли", и будет способствовать '
    'укреплению американского "энергетического доминирования" и '
    'продолжит действовать после завершения нынешнего президентского '
    'срока. Группа Боули намерена приобрести у нероссийских владельцев '
    'акции "ЛУКОЙЛа" номинальной стоимостью около $10 млрд, при этом '
    'покупка будет осуществляться со значительным дисконтом.'
)


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))   # перечитано прямо перед записью
    deal = next(d for d in data['deals'] if d['id'] == DEAL)
    assert deal['law']['struct'] == '—', deal['law']['struct']
    deal['law']['struct'] = NEW_STRUCT
    print('law.struct записан: консорциум Боули/Ближний Восток, доля США через DFC')
    if not write:
        print('\nСухой прогон. Запись — с ключом --write.')
        return 0
    json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('записано')
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
