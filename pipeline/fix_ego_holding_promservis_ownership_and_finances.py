import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g6f88ab01'

OLD_ECO_RATIONALE = (
    '«Мы собираемся развивать там одно из важнейших направлений '
    'бизнеса, связанное с подводной техникой. В этих южных по отношению '
    'к нам городах — Волгограде, Таганроге и некоторых других — '
    'исторически развивалась гидроакустика. Это очень востребованная '
    'тема, интересная нам и, уверен, нашему заказчику. Мы давно '
    'работаем с этим направлением, раньше в основном с зарубежными '
    'партнёрами, а теперь развиваем своё», — говорит глава МНС'
)
NEW_ECO_RATIONALE = (
    '«Мы собираемся развивать там одно из важнейших направлений '
    'бизнеса, связанное с подводной техникой. В этих южных по отношению '
    'к нам городах — Волгограде, Таганроге и некоторых других — '
    'исторически развивалась гидроакустика. Это очень востребованная '
    'тема, интересная нам и, уверен, нашему заказчику. Мы давно '
    'работаем с этим направлением, раньше в основном с зарубежными '
    'партнёрами, а теперь развиваем своё», — говорит гендиректор МНС '
    'Константин Смирнов'
)

OLD_ECO_CONTEXT = (
    'Промсервис» стал третьей «дочкой» «Морских навигационных систем» '
    '(МНС). Две другие — ООО «Бизнес–гарант» и ООО «МНС–энерго» — как и '
    'материнская компания, располагаются в Петербурге'
)
NEW_ECO_CONTEXT = OLD_ECO_CONTEXT + (
    '. Ранее на производственно-складском комплексе работал цех '
    'металлоконструкций. По данным ЕГРЮЛ, МНС стало владельцем ещё '
    '27 июня 2023 года — раньше даты публикации новости; гендиректором '
    'ООО «Промсервис» с 12 июля 2023 года назначен Дмитрий Орехов.'
)

OLD_ECO_TARGET_FIN = (
    'Волгоградская компания специализируется на управлении нежилой '
    'недвижимостью и является микропредприятием с упрощённой системой '
    'налогообложения и выручкой за 2022 год 0,2 млн рублей'
)
NEW_ECO_TARGET_FIN = OLD_ECO_TARGET_FIN + (
    '. После сделки выручка выросла, но осталась на уровне единиц '
    'миллионов рублей: 2,03 млн ₽ (2023), 4,79 млн ₽ (2024), 4,86 млн ₽ '
    '(2025); прибыль колеблется около нуля (от −192 до +68 тыс ₽) — '
    'ни один источник не сообщает о фактическом запуске производства '
    'гидроакустики на этой площадке.'
)

NEW_SRC = [
    ['СБИС', 'https://saby.ru/profile/3443065404-344301001'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['rationale'] == OLD_ECO_RATIONALE
    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['eco']['target_fin'] == OLD_ECO_TARGET_FIN

    new_src = deal['src'] + NEW_SRC

    print('=== eco.rationale: станет ===')
    print(NEW_ECO_RATIONALE)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== eco.target_fin: станет ===')
    print(NEW_ECO_TARGET_FIN)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['rationale'] = NEW_ECO_RATIONALE
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['eco']['target_fin'] = NEW_ECO_TARGET_FIN
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
