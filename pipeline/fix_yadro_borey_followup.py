NEW_SRCS = [
    ['Интерфакс', 'https://www.interfax.ru/business/1006209'],
    ['РБК Компании', 'https://companies.rbc.ru/id/'
     '5177746194577-ooo-konstruktorskoe-byuro-borej/'],
    ['CNews', 'https://www.cnews.ru/news/line/'
     '2026-07-24_yadro_predstavila_kompleksnoe'],
]


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    card = next((c for c in data['deals'] if c['id'] == CARD_ID), None)
    assert card is not None, '%r не найдена в базе' % CARD_ID
    assert card['eco'].get('rationale') == OLD_RATIONALE, (
        'eco.rationale изменился с ожидаемого: %r' % card['eco'].get('rationale'))
    assert card['eco'].get('target_fin') == OLD_TARGET_FIN, (
        'eco.target_fin изменился с ожидаемого: %r' % card['eco'].get('target_fin'))
    assert card['eco'].get('context') == OLD_CONTEXT, (
        'eco.context изменился с ожидаемого: %r' % card['eco'].get('context'))
    src = card.setdefault('src', [])
    print('ПРАВИМ  %s: eco.rationale — обоснование Павла Егорова (Yadro)' % CARD_ID)
    print('ПРАВИМ  %s: eco.target_fin — финансы предмета за 2024 год' % CARD_ID)
    print('ПРАВИМ  %s: eco.context — продукт BOREY «Посейдон» (июль 2026)' % CARD_ID)
    if write:
        card['eco']['rationale'] = NEW_RATIONALE
        card['eco']['target_fin'] = NEW_TARGET_FIN
        card['eco']['context'] = NEW_CONTEXT
        for s in NEW_SRCS:
            if s not in src:
                src.append(s)
        json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
        print('ЗАПИСАНО')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
