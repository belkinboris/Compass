def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    comps = data['companies']

    changed = 0
    for cid, text in SHORTER.items():
        c = comps.get(cid)
        assert c, 'профиля %s нет в базе' % cid
        assert cid not in KEEP, 'профиль %s помечен как несокращаемый' % cid
        assert len(text) <= LIMIT, 'сокращение %s длиннее предела: %d' % (cid, len(text))
        old = str(c.get('desc') or '')
        if old == text:
            continue
        assert old, 'у %s не было описания — сокращать нечего' % cid
        assert len(old) > len(text), 'у %s «сокращение» не короче исходного' % cid
        print('  %-12s %-26s %d -> %d зн.' % (cid, str(c.get('name'))[:26], len(old), len(text)))
        c['desc'] = text
        changed += 1

    print('\nСокращено описаний: %d' % changed)
    print('Оставлено длинными намеренно: %d (факты о сделке, см. KEEP)' % len(KEEP))
    over = [(k, len(v['desc'])) for k, v in comps.items()
            if v.get('desc') and len(v['desc']) > LIMIT and k not in KEEP]
    print('Длиннее предела и не в KEEP: %d' % len(over))
    for k, n in over[:10]:
        print('   %s %s — %d зн.' % (k, comps[k].get('name'), n))

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return 0
    json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('Записано.')
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
