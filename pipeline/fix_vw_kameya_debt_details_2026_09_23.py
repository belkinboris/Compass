# -*- coding: utf-8 -*-
"""Приток 23 сентября 2026, карточка gd1130c05 (Volkswagen/«Арт-Финанс»):
сырьё-дополнение (@dealsma, t.me/dealsma/7411, пересказ статьи Коммерсанта
doc/8972260 — того же источника, что уже привязан к карточке) раскрывает
механику претензии «Камеи», которой в `extra` ещё не было: как «Камея»
получила требование, попытку Volkswagen оспорить цессию и смену
конкурсного управляющего. Прямая правка (не через review.py FIXES) —
`extra` уже собран прошлым прогоном как связный текст из ДРУГОЙ версии
той же статьи, и переписывать его целиком под одну дословную цитату
нельзя технически (правка добавляет факт из НОВОГО текста поверх уже
записанного, не переиначивая старое) — тот же приём, что и раньше в этой
сессии для событий-заметок.

Запуск: python3 pipeline/fix_vw_kameya_debt_details_2026_09_23.py --write
"""
import argparse
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gd1130c05'

OLD_TAIL = (
    'а Винокурова отдельно — продажи структуры дистрибутора Scania (БВГ) и '
    'выплаты «Порше Руссланд» дивидендов в 4 млрд руб. иностранным '
    'участникам; цель оспаривания — вернуть активы в конкурсную массу '
    'Volkswagen AG для банкротных торгов (Коммерсантъ, 22 сентября 2026).'
)

ADDITION = (
    ' Механика требования «Камеи»: АО «Камея», созданное 10 января 2025 '
    'года с капиталом 10 тыс. руб., купило у НАЗ (ранее ГАЗ) право '
    'требования к Volkswagen AG на 16,9 млрд руб. за 120 млн руб. — эту '
    'сумму суд взыскал с Volkswagen в июле 2024 года за прекращение '
    'сотрудничества по производству Volkswagen и Skoda в Нижнем Новгороде '
    'и поставок двигателей; решение прошло апелляцию, кассацию и '
    'Верховный суд. Volkswagen пытался оспорить цессию, ссылаясь на '
    'возможную аффилированность НАЗ и «Камеи», но суды эти доводы не '
    'поддержали. В реестр требований позже добавились 1,59 млрд руб. '
    'индексации и около 8,29 млрд руб. процентов по ст. 395 ГК РФ — итого '
    'около 26,8 млрд руб. Первым конкурсным управляющим Volkswagen AG стал '
    'Андрей Столяров, в июле 2026 года его сменила Наталья Винокурова '
    '(Коммерсантъ, 23 сентября 2026, со ссылкой на t.me/dealsma/7411).'
)


def main(write):
    data = json.load(open(DATA, encoding='utf-8'))
    card = next(d for d in data['deals'] if d['id'] == CARD_ID)
    assert card['extra'].endswith(OLD_TAIL), 'extra уже не тот, что ожидали'
    assert ADDITION not in card['extra'], 'уже дописано'
    card['extra'] = card['extra'] + ADDITION
    if write:
        json.dump(data, open(DATA, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
        print('Записано: extra дополнен механикой требования «Камеи».')
    else:
        print('Сухой прогон (--write, чтобы записать).')


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('--write', action='store_true')
    main(p.parse_args().write)
