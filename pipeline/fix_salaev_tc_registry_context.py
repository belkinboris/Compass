import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g6b737511'

OLD_CONTEXT = (
    'Она приобрела этот ТЦ в 2021 году у ООО «НЭК Гатчина», ликвидированного'
    ' в 2022-м. Оба комплекса находятся в залоге у Сбербанка.'
)
NEW_CONTEXT = (
    OLD_CONTEXT + ' По данным реестровых агрегаторов, по состоянию на 2026'
    ' год оба объекта остаются у тех же собственников — Александр и Диана'
    ' Салаевы (ООО «Универсам «Диана»») и Елена Штабинская (ООО «ЛЕОН+»),'
    ' доли по-прежнему в залоге. Елена Штабинская вышла из числа участников'
    ' «Универсам «Диана»» 27 декабря 2024 года, сохранив владение только'
    ' гатчинским комплексом.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
