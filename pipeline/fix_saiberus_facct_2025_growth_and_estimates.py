import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g4feb42fc'

OLD_VAL = (
    'Стоимость всех приобретенных активов в Softline Venture Partners и '
    'инвесткомпании Kama Flow оценивают в 5 млрд руб., а срок окупаемости — '
    'в пять-шесть лет. В ГК «Финам» сделку оценивают в 2,5 млрд руб. '
    'Главный аналитик «Регблока» Анна Авакимян считает, что сумма сделки '
    'составляет 2,2–3,2 млрд руб.'
)
VAL_ADDITION = (
    ' Аналитик ФГ «Финам» Леонид Делицын оценил сумму сделки в 4 млрд руб., '
    'а инвестиционный стратег УК «АриКапитал» Сергей Суверов — в 4–5 млрд '
    'руб.'
)
NEW_VAL = OLD_VAL + VAL_ADDITION

OLD_CONTEXT = (
    'Группа (российское юрлицо — ООО «Ф.А.К.К.Т.») была образована в 2023 '
    'году после продажи бизнеса Group-IB в России местному руководству. При '
    'этом основной акционер Group-IB Илья Сачков остался одним из '
    'владельцев компании. Фонд «Сайберус» инвестирует в решения в сфере '
    'ИБ. Он создан в 2022 г. основным владельцем Positive Technologies '
    'Юрием Максимовым. Фондом владеют участники рынка (государство, '
    'корпорации, граждане), указано на его сайте.'
)
CONTEXT_ADDITION = (
    ' Через полтора года под управлением «Сайберуса» компания '
    '(переименована в F6) по итогам 2025 года показала выручку 3,88 млрд '
    'руб. и чистый убыток 689 млн руб. — убыток связан с погашением '
    'акционерных займов на покупку активов, полностью выплаченных весной '
    '2026 года; компания готовится к IPO/DPO. В декабре 2025 года '
    'структура ВЭБ.РФ Sk Capital вложила 5 млрд руб. в сам фонд «Сайберус» '
    'на развитие через M&A и поддержку экспорта ИБ-решений. Илья Сачков '
    'получил дивиденды в размере 1,537 млрд руб. на фоне сделки — выплата '
    'произведена из накопленной прибыли компаний, переданных «Сайберусу» '
    '(источник не устанавливает прямую причинно-следственную связь с ценой '
    'сделки).'
)
NEW_CONTEXT = OLD_CONTEXT + CONTEXT_ADDITION

NEW_SRC = [
    ['VC.ru', 'https://vc.ru/services/3086530'],
    ['SecurityLab.ru', 'https://www.securitylab.ru/news/567318.php'],
    ['CNews', 'https://www.cnews.ru/news/top/2026-05-06_otbyvayushchij_srok_osnovatel'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['val'] == OLD_VAL
    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.val: станет ===')
    print(NEW_VAL)
    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['val'] = NEW_VAL
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
