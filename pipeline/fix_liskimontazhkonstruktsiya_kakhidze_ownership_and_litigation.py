    'горсуд, апрель 2026) и «Союзметаллсервиса» (577,2 млн ₽, арбитраж '
    'Москвы), само предприятие судится с контрагентом на 72,5 млн ₽ '
    '(июнь 2026); управляющая организация завода, АО «УК «АК Капитал»» '
    '(приняла управление в мае 2025 года после ухода Цивилева), в августе '
    '2026 столкнулась с заявлением о банкротстве от налоговой службы '
    'из-за долга 27,73 млн ₽.'
