# -*- coding: utf-8 -*-
"""«Ростелеком приобрел 51% в разработчике цифровых решений для ритейла
АСТОР» (`gadcc1f58`) — `law.terms` несло дословную, но НЕ подходящую по
смыслу цитату: «Наше сотрудничество с «Ростелекомом» станет мощным
драйвером для дальнейшего технологического развития нашей компании.
Объединяя усилия с лидером рынка цифровых решений, мы сможем реализовать
самые смелые проекты и предложить нашим клиентам принципиально новые
возможности для автоматизации и оптимизации рабочих процессов.»

Тот же класс, что уже чинился у HeadHunter/Happy Job
(fix_headhunter_happyjob_law_terms.py): это не условие СДЕЛКИ (не
индемнити, не заверение, не earn-out, не обязательство сохранить бренд/
команду), а фраза-заверение от лица АСТОР, адресованная ЕГО собственным
клиентам («предложить нашим клиентам новые возможности») — про то, как
продолжит работать продукт цели, а не на каких условиях её купили.
Партнёр (владелец, чат «M&A Faces», 27 августа) заметил дополнительно:
цитата стоит БЕЗ атрибуции — ни в `law.terms`, ни в источниках карточки
не сказано, кто именно это сказал; текст не совпадает ни с цитатой
Дмитрия Рейдмана в `eco.rationale` (та атрибутирована и остаётся), ни с
чем-либо ещё на карточке — это осиротевшее предложение без указания
автора и не по адресу поля.

`law.struct` (данные ЕГРЮЛ о владении 51%) — НЕ трогается, это настоящий
факт сделки; линза «Юрист» остаётся жить на нём одном.

Запуск: python3 pipeline/fix_astor_rostelecom_law_terms.py           # проверка
        python3 pipeline/fix_astor_rostelecom_law_terms.py --write   # запись
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gadcc1f58'
OLD_TERMS = ('Наше сотрудничество с «Ростелекомом» станет мощным драйвером для '
             'дальнейшего технологического развития нашей компании. Объединяя '
             'усилия с лидером рынка цифровых решений, мы сможем реализовать '
             'самые смелые проекты и предложить нашим клиентам принципиально '
             'новые возможности для автоматизации и оптимизации рабочих процессов.')


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    card = next((c for c in data['deals'] if c['id'] == CARD_ID), None)
    assert card is not None, '%r не найдена в deals_promoted.json' % CARD_ID
    assert card['law'].get('terms') == OLD_TERMS, (
        'ожидали law.terms=%r, сейчас %r — состояние изменилось'
        % (OLD_TERMS, card['law'].get('terms')))

    print('ПРАВИМ %s: law.terms -> «—» (пресс-релизная фраза-заверение АСТОР '
          'своим клиентам, без атрибуции и не про условия сделки)' % CARD_ID)
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    card['law']['terms'] = '—'
    json.dump(data, open(DATA, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
