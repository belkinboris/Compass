# -*- coding: utf-8 -*-
"""Классификация строк формы 101 ЦБ (`Data101FNewXML`) на актив/пассив.

ЧЕТВЁРТЫЙ ЧЕРНОВИК, 23 августа 2026 — метод переписан целиком, старая
таблица `ACCOUNT_TYPES` (300+ строк ручных догадок по каждому счёту первого
порядка) УДАЛЕНА и заменена прямым чтением полей самого ответа. Не
подключать к сайту, пока не решён вопрос про gross/net ниже (см. последний
абзац) — это уже не вопрос покрытия (оно теперь ~100%), а вопрос того, ЧТО
именно показывать пользователю.

ГЛАВНАЯ НАХОДКА. Три предыдущих черновика (18-22 августа) угадывали
актив/пассив каждого счёта ПО ТЕКСТУ Положения 809-П — медленно, счёт за
счётом, с риском ошибки на каждом (счёт 706 сначала приняли за капитал,
хотя это счёт-транзит; 101/103/104 придуманы «по названию», которых в
действующем плане счетов нет вовсе). Всё это время сам ответ
`Data101FNewXML` УЖЕ НЁС нужную разметку — просто под именами полей, не
объяснёнными нигде в WSDL (там сырой XML без описания структуры строки).
Официальный формат этой же формы (0409101) для ДРУГОГО, старого канала
раздачи (пакетные DBF-файлы) документирован тут:
https://www.cbr.ru/vfs/credit/formats/101-20181201.PDF — поля совпадают
дословно с тем, что отдаёт SOAP (`numsc`≈`NUM_SC`, `ap`≈`A_P`, `vitg`≈VITG,
`iitg`≈IITG, `priz`≈PRIZ), просто в нижнем регистре и без пары полей самого
DBF-заголовка (`pln` — отдельное поле в SOAP-ответе, в DBF-файле «глава»
зашита в имя файла, а не в строку). Прямая цитата документа:

  A_P  символьный 1  Признак счета: 1 – счет активный; 2 – счет пассивный

То есть КАЖДАЯ строка ответа УЖЕ говорит, на какой стороне баланса она
стоит — гадать по 809-П больше не нужно вовсе, только читать `ap`.

ВТОРАЯ НАХОДКА, СТОЛЬ ЖЕ ВАЖНАЯ. Поле `pln` — не декоративное, это «глава
Плана счетов», и в ответе `Data101FNewXML` реально встречаются ВСЕ пять:
А — балансовые счета (то, что действительно составляет актив/пассив банка);
Б — счета доверительного управления; В — ВНЕБАЛАНСОВЫЕ счета; Г — срочные
операции (производные); Д — счета депо. Три прежних черновика (18-22
августа) читали ответ БЕЗ фильтра по `pln` вовсе — то есть суммировали
вместе балансовые счета банка (реальные активы) с гарантиями/поручительствами
на внебалансовых счетах (В, у Сбербанка 444 млрд ₽ на 2026-07-01) и с
производными (Г, 49 млрд ₽) — эти суммы к «Активам» из независимой сверки
(TAdviser, МСФО) не имеют отношения вовсе, это справочные/забалансовые
величины. Плюс строка `numsc == "ITGAP"` — это КОНТРОЛЬНЫЙ ИТОГ по главе
(проверочная сумма, а не счёт) и тоже не должна попадать в сумму.
Обнаружено не чтением закона, а прямым сравнением сырых строк ответа
(`pln` встречается со значениями А/Б/В/Г/Д, `numsc` — с буквенным «ITGAP»)
— тот же класс урока, что уже записан в CLAUDE.md про поле `A_P`: раньше
искали смысл в законе, хотя он был прямо в данных.

ЧТО ОСТАЁТСЯ ИСКЛЮЧЁННЫМ ВРУЧНУЮ, А НЕ ПО `ap`. Даже среди `pln == "А"`
есть счета, чей `ap`-остаток — не остаток на конец периода, а валовый
оборот внутреннего клиринга (см. прежние находки, они не отменены этой
правкой, только перенесены сюда без таблицы): 303 «Внутрибанковские
требования и обязательства» (у Сбербанка 309,8 трлн ₽ — больше всех активов
банка, механизм клиринга между подразделениями), 706 «Финансовый результат
текущего года» (809-П п.7.1: счёт, через который проходят ВСЕ доходы и
расходы года, не чистая прибыль — 145,4 трлн ₽ у Сбербанка), 612 «Выбытие и
реализация» (809-П п.6.23: «Счета без указания признака счёта» — транзитный
механизм, дословно из закона), 616 «Вспомогательные счета» (по названию и
назначению — учёт выбытия срочных сделок и товарных запасов, тоже
технический). Эти четыре счёта ПРОВЕРЕНЫ ПРЯМОЙ ЦИТАТОЙ закона (703/612) или
масштабом относительно независимой сверки (303/706) в прежних черновиках —
находка про `ap`/`pln` их не отменяет, они остаются `EXCLUDED`.

ЖИВАЯ ПРОВЕРКА 23 АВГУСТА (после этой правки, `pipeline/cbr_fetch_bank_summary.py`,
все три банка, 2026-07-01): АКТИВ (сумма всех `pln=="А"`, `ap=="1"`, кроме
исключённых) против независимой сверки — Сбербанк 111% (73,61 / 66,09 трлн
₽), ВТБ 103% (39,23 / 38,0 трлн ₽), Альфа-Банк 108% (15,49 / 14,27 трлн ₽).
Покрытие теперь фактически 100% строк `pln=="А"` (никаких «неклассифицировано»
не остаётся — каждая строка это либо `ap`, либо в списке `TRANSIT_ACCOUNTS`).
Сумма АКТИВ и сумма ПАССИВ при этом сходятся почти точно (Сбербанк 73,61 /
72,62 — расхождение 1,4%, ожидаемо для двойной записи), что подтверждает
метод: если бы `ap` был перепутан массово, стороны разошлись бы сильнее.

ПОЧЕМУ ВСЁ РАВНО НЕ 100% — И ЭТО УЖЕ НЕ БАГ, А ВОПРОС GROSS VS NET.
Устойчивый перебор 103-111% у ВСЕХ трёх банков (не у одного — не шум
выборки) сохранился и после этой правки, то есть причина не в фильтрации.
Гипотеза, не проверенная построчно, но логически согласованная с двойной
записью: наша сумма — это ВАЛОВЫЙ (gross) итог по дебетовой стороне,
а независимая сверка (TAdviser/МСФО) — это ЧИСТЫЙ (net) показатель «Активы»,
как его публикует сам банк. Публичная отчётность показывает кредиты ЗА
ВЫЧЕТОМ резерва на возможные потери ОДНОЙ строкой, а не гросс-кредит и
гросс-резерв раздельно — резервы (например, счёт 329 у раздела «Кредиты
и депозиты, размещённые в банках», 1,96 трлн ₽ у Сбербанка, `ap=="2"`)
по двойной записи ложатся в НАШ пассивный итог, а по экономическому смыслу
должны УМЕНЬШАТЬ актив, а не увеличивать капитал+обязательства. То же,
вероятно, верно для части объёма счёта 474 «Расчёты по отдельным операциям
и корректировки» (2,8/2,3 трлн ₽ у Сбербанка почти поровну на обеих
сторонах — похоже на тот же класс, что уже исключённые 303/612/616, но
не проверено прямой цитатой закона для КАЖДОГО подсчёта). Отличить
«резерв, уменьшающий актив» от «настоящее обязательство» (вклады
клиентов, выпущенные облигации) по одному только `ap` нельзя — оба
пассивны по разметке источника; разница в экономическом СМЫСЛЕ счёта, а
не в его стороне баланса, и это снова требует читать закон, только
прицельно — не по всем счетам подряд, а по счетам-кандидатам на «резерв».
СЛЕДУЮЩИЙ ШАГ ПЕРЕД ПОДКЛЮЧЕНИЕМ К САЙТУ: пройти по счетам, чей `ap=="2"`
остаток при этом называется «резерв»/«переоценка, уменьшающая» в 809-П
(329, часть 45.x/47.x, часть 474/502/504), и решить — вычитать их из
актива отдельно, или показывать пользователю ВАЛОВУЮ, чуть завышенную
цифру с честной пометкой «расчёт по данным ЦБ, оценка, может отличаться
от отчётности банка на 5-10%».
"""
from __future__ import annotations

ASSET = "asset"
CAPITAL_LIABILITY = "capital_liability"
EXCLUDED = "excluded"     # off-balance/производные/депо главы плана счетов ИЛИ счёт внутреннего оборота
UNKNOWN = "unknown"       # ap не «1» и не «2» — не должно происходить, но не гадаем

# Счета первого порядка (без учёта суффикса «.N» агрегата), чей остаток —
# валовый оборот внутреннего клиринга/транзита, а не остаток на конец
# периода. Проверены прямой цитатой 809-П (612) или масштабом относительно
# независимой сверки (303, 706, 145 трлн ₽ и 309,8 трлн ₽ у одного только
# Сбербанка — больше всех активов банка). 616 — по названию и однотипному
# назначению с 612 (учёт выбытия), отдельной цитаты не нашлось, но оба
# счёта стоят рядом в 809-П под одним заголовком «Выбытие и реализация».
TRANSIT_ACCOUNTS: set[str] = {"303", "706", "612", "616"}

BALANCE_SHEET_CHAPTER = "А"  # `pln`: балансовые счета. Б/В/Г/Д — не баланс банка, см. докстроку.


def classify_row(pln: str, numsc: str, ap: str) -> tuple[str, str]:
    """(тип, причина) для ОДНОЙ строки ответа `Data101FNewXML`. В отличие от
    прежних версий этого модуля, не нужен номер счёта для поиска в таблице —
    `ap` уже говорит, актив это или пассив (см. докстроку модуля,
    официальный формат формы 0409101). Нужны только: (1) фильтр по `pln`,
    чтобы не считать внебалансовые/производные/депо счета частью баланса,
    (2) список счетов-транзитов, чей остаток вообще не остаток."""
    if numsc == "ITGAP":
        return EXCLUDED, "контрольный итог по главе — не счёт"
    if pln != BALANCE_SHEET_CHAPTER:
        return EXCLUDED, f"глава плана счетов «{pln}», не балансовые счета (см. докстроку)"
    base = numsc.split(".")[0].strip()
    if base in TRANSIT_ACCOUNTS:
        return EXCLUDED, "счёт внутреннего оборота/транзита — остаток не является суммой на конец периода"
    if ap == "1":
        return ASSET, "поле A_P источника = 1 (счёт активный, официальный формат формы 0409101)"
    if ap == "2":
        return CAPITAL_LIABILITY, "поле A_P источника = 2 (счёт пассивный, официальный формат формы 0409101)"
    return UNKNOWN, f"неожиданное значение A_P: {ap!r}"
