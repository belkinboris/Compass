def classify(numsc: str) -> tuple[str, str, str]:
    """(тип, уверенность, причина) для счёта. Хвост «.N» (например «32.1»)
    отбрасывается ДО ТОЧКИ для поиска в таблице — сам хвост (0/1/2 после
    точки) не расшифрован (см. докстроку модуля про двузначные классы), но
    когда ВСЯ группа счетов под этим префиксом однородна по знаку (как «20»
    и «45»/«47» — подтверждено по 809-П), уверенность записи в таблице
    может быть high и для таких кодов; low ставится только там, где сама
    природа префикса под вопросом."""
    key = numsc.split(".")[0].strip()
    return ACCOUNT_TYPES.get(key, (UNKNOWN, "none", "счёт не встречался при построении таблицы 18 августа 2026"))
