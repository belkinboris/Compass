# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
`gmru-geotek-bashneftegeofizika` («Геотек» и «Башнефтегеофизика»
объединяют нефтесервисные активы, Обсуждается, 28 июля 2026) — проверка,
не появилось ли новостей о ходе или закрытии месяц спустя.

Проверено ЛИЧНО прямым WebFetch:
- vedomosti.ru/business/articles/2026/07/28/1216898-bashneftegeofizika-
  pokupaet-konkurenta (заголовок статьи, в открытой части, за paywall
  дальше не читается): «По словам источника «Ведомостей», знакомого со
  сторонами процесса, сейчас они находятся на завершающем этапе
  осуществления всех корпоративных процедур, необходимых для закрытия
  сделки.» — единственное найденное упоминание стадии сделки; сам
  заголовок статьи описывает её как ПОКУПКУ «Башнефтегеофизикой»
  конкурента, а не как равноправное объединение, — из открытого текста
  не следует, какая формулировка точнее.
- interfax.ru/business/1106008 (проверено повторно): подтверждает уже
  известные факты, ничего нового; банк-сопровождающий по-прежнему не
  назван ни одним изданием (проверены также kommersant.ru/doc/8846265,
  1prime.ru/20260728/geotekshij-871813182.html, пресс-релиз самого
  «Геотека», AKM).

НЕ ВНЕСЕНО: корпоративный конфликт в руководстве «Башнефтегеофизики»
(Явдат/Рустем Адиевы, с конца 2024 года) — предшествует объявлению
сделки и ни одним источником прямо с ней не увязан, добавлять как
контекст этой сделки было бы домыслом.

`status`/`buyer`/`seller`/`title` карточки НЕ тронуты — сделка на дату
прогона не закрыта, банк и структура по-прежнему не раскрыты нигде.

Запуск: python3 pipeline/fix_geotek_bashneftegeofizika_progress.py
        python3 pipeline/fix_geotek_bashneftegeofizika_progress.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gmru-geotek-bashneftegeofizika'

OLD_ECO_CONTEXT = (
    '«Геотек» (прежнее название — «Геотек Сейсморазведка») создан в '
    '2009 году, работает в Западной и Восточной Сибири, в '
    'Тимано-Печорской и Волго-Уральской провинциях, а также в '
    'Казахстане, Узбекистане и других странах. В 2025 году его выручка '
    'выросла на 15% — до 6,3 млрд ₽. Раньше холдинг принадлежал ЗПИФ '
    'из структуры группы Газпромбанка, но по последним раскрытым '
    'сведениям на конец 2025 года контроль перешёл к АО «РНИ Холдинг». '
    'Его руководитель Михаил Вахрушев возглавляет и несколько дочерних '
    'структур научно-производственного холдинга «ВМП». АО '
    '«Башнефтегеофизика» (БНГФ) — нефтесервисная компания с головным '
    'офисом в Уфе, её история связана с нефтяной промышленностью '
    'Башкортостана с 1932 года. Она входит в число крупнейших '
    'российских производителей нефтегазового оборудования и имеет '
    'статус системообразующего предприятия ТЭК. Выручка БНГФ в 2025 '
    'году выросла на 45% — до 37,3 млрд ₽. По неофициальным данным, '
    'сделку поддерживает и финансово сопровождает крупный российский '
    'банк; как он называется, не раскрывается.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' По данным источника «Ведомостей», знакомого со '
    'сторонами (та же дата, 28 июля 2026 года), стороны находятся «на '
    'завершающем этапе осуществления всех корпоративных процедур, '
    'необходимых для закрытия сделки» — при этом само издание в '
    'заголовке материала называет сделку покупкой «Башнефтегеофизикой» '
    'конкурента, а не равноправным объединением; какая формулировка '
    'точнее, источники не разрешают. Название банка по-прежнему нигде '
    'не раскрыто.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
