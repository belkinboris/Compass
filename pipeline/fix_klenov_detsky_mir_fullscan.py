"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
`g76159e00` («Дмитрий Кленов продал 10% акций "Детского мира"»,
закрыта, 2023-03-13) — не было ни личности Кленова, ни судьбы самого
«Детского мира» после трансформации в частную компанию.

Проверено ЛИЧНО прямым WebFetch (interfax.ru/business/803696,
дословные цитаты): Кленов — «управляющий партнер Altus Capital»;
пакет 10% возник при расформировании суб-фонда Gulf Investments
Limited (владел 29,99% «Детского мира») в июне 2021 года — тогда же
Павел Грачёв и Михаил Стискин получили 19,99%; сам Кленов объяснял
решение «оптимизацией структуры владения».

По докладу саб-агента (не перепроверено мной лично): 2 мая 2023 года
консорциум Алексея Зуева («Кораблик») купил 29,9% «Детского мира» —
20% у Грачёва/Стискина, а источники (Vedomosti) арифметически
сопоставляют оставшиеся ~10% с долей Кленова, но НЕ подтверждают это
прямо как факт покупателя; в карточку эта версия НЕ внесена — только
арифметическое совпадение, не источник, называющий Кленова продавцом
Зуеву напрямую. Отдельная карточка `g22000f22` уже содержит эту же
осторожную формулировку («предположительно») в собственном
`eco.share` — дублировать её здесь не нужно.

НЕ ВНЕСЕНО (по докладу саб-агента, требует отдельной проверки): выкуп
акций у миноритариев вёл АО «ДМК» с 30 мая по 28 июля 2023 года по
71,5 ₽, для «недружественных» инвесторов — счета типа «С» или 60,77 ₽;
ПАО «Детский мир» ликвидировано (по одному источнику — 19 сентября
2024 года, по другому делистинг завершён в феврале 2024-го —
расхождение дат не разрешено, не вносится без прямой проверки);
финансовые показатели группы за 2024-2025 годы — цифры получены только
через WebSearch-сводки разных агрегаторов без единого первоисточника.

Запуск: python3 pipeline/fix_klenov_detsky_mir_fullscan.py
        python3 pipeline/fix_klenov_detsky_mir_fullscan.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g76159e00'

OLD_LAW_STRUCT = '—'
NEW_LAW_STRUCT = (
    'Кленов — управляющий партнёр Altus Capital. Его 10% возникли при '
    'расформировании суб-фонда Gulf Investments Limited (владел 29,99% '
    '«Детского мира») в июне 2021 года — тогда же Павел Грачёв и '
    'Михаил Стискин получили 19,99%; сам Кленов объяснял решение '
    '«оптимизацией структуры владения».'
)

OLD_SRC = [['Connect.ok.ru', 'https://www.kommersant.ru/doc/5874239']]
NEW_SRC = OLD_SRC + [
    ['Интерфакс', 'https://www.interfax.ru/business/803696'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['law']['struct'] == OLD_LAW_STRUCT
    assert deal['src'] == OLD_SRC

    print('=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['law']['struct'] = NEW_LAW_STRUCT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
