import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g6be1ac50'

OLD_EXTRA = (
    'Сделка закрыта 6 сентября 2023. НЛМК продал 100% долей в '
    'компаниях ООО «НЛМК-Калуга» (электрометаллургический завод '
    'мощностью 1,5 млн тонн стали и 0,9 млн тонн проката в год), ООО '
    '«Вторчермет НЛМК» и АО «НЛМК-Урал» (мощности 2 млн тонн в год) '
    'Промышленно-металлургическому холдингу. Доля НЛМК на рынке '
    'арматуры составляла 18%.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Заводы переименованы в «Промсорт-Урал» (31 октября 2023) и '
    '«Промсорт-Калуга». Уже 9 октября 2023 ФАС возбудила дело против '
    '«Промсорта» за рост цен на арматуру на 25% за два месяца — итог '
    'дела не раскрыт. Группа быстро выросла: по итогам II полугодия '
    '2025 заняла первое место в общероссийском рейтинге производителей '
    'сортового проката, произвела за год 3,8 млн тонн (+14%). В августе '
    '2026 ФАС начала новую проверку роста цен на арматуру (+30-49% с '
    'начала года), назвав «Промсорт» доминирующим игроком рынка.'
)

NEW_SRC = [
    ['Ревда-инфо', 'https://www.revda-info.ru/2023/11/10/nlmk-ural-pereimenovan-v-promsort-ural-lisin-prodal-sortovoj-divizion-na-urale-i-v-kaluge/'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6266451'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
