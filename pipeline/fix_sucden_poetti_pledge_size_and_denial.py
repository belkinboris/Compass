# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
`gmru-sucden-poetti` (Французская Sucden может получить контроль над
бизнесом производителя кофе Poetti, Обсуждается, 15 июля 2026) — уже
известно, что часть сделки — залог доли, но точный размер доли и
официальное опровержение перехода контроля в карточке не названы.

Проверено ЛИЧНО прямым WebFetch:
- retail.ru/news/sdelka-poetti-i-sucden-ne-yavlyaetsya-skrytoy-peredachey-
  aktivov-16-iyulya-2026-279949/: «в залог передана миноритарная часть
  доли в уставном капитале общества в размере 35%»; «Договор не
  является скрытой покупкой и не влечет переход контроля над ООО
  «МилФудс» к ООО «Сдс»... Сделка также не предусматривает изменений в
  текущей структуре управления ООО «МилФудс»».
- kommersant.ru/doc/8815172 (уже в `src`, повторно прочитан целиком):
  подтверждает дату (июнь 2026) и назначение залога (обеспечение
  товарного кредита на закупку кофе), но называет залогодержателем
  ООО «Агросервис» (структуру Sucden) — БЕЗ конкретного размера доли;
  «В Sucden говорят, что планов входить в уставный капитал «Милфудс»
  нет.»

НЕ РАЗРЕШЕНО: источники расходятся, КАКАЯ именно структура Sucden
держит залог — kommersant.ru (и уже стоящий в карточке `law.struct`)
называет ООО «Агросервис», а retail.ru — ООО «Сдс» (то же имя, что уже
стоит в `buyer_name` карточки). Возможно, это два разных юрлица группы
Sucden в цепочке, возможно — расхождение одного из изданий; выбирать
одно на глаз не стал, расхождение зафиксировано честно.

`buyer_name`/`status`/`title` карточки НЕ тронуты — по заявлению обеих
сторон переход контроля не состоялся, залог — не покупка.

Запуск: python3 pipeline/fix_sucden_poetti_pledge_size_and_denial.py
        python3 pipeline/fix_sucden_poetti_pledge_size_and_denial.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gmru-sucden-poetti'

OLD_ECO_CONTEXT = (
    'ООО «Милфудс» существует с 2008 года. В 2022 году компания '
    'выкупила российские активы финского производителя кофе Paulig. На '
    'его мощностях в Твери запустили линейку Poetti. Викас Сои ранее '
    'был главой российской Milagro Beverage Company (бренды кофе '
    'Milagro, D’Arte, Belagio). Активы этой компании, вероятно, вошли в '
    'периметр «Милфудс». Сейчас ей принадлежат права на официальный '
    'сайт и бренд Milagro.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' В залог передана не вся доля, а её миноритарная '
    'часть — 35%. Обе стороны прямо опровергли переход контроля: '
    '«Договор не является скрытой покупкой и не влечёт переход контроля '
    'над ООО «МилФудс»... сделка также не предусматривает изменений в '
    'текущей структуре управления ООО «МилФудс»». Источники расходятся, '
    'какая именно структура Sucden держит залог — «Агросервис» или '
    '«Сдс»; расхождение не разрешено.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
