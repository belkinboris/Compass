#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Профиль компании обрублен на середине названия.

ЧТО СЛОМАНО. `companies[id].name` — это то, что показывается в плашке
сторон, в каталоге и в поиске: если оно обрублено, дефект виден на каждой
карточке с участием этой компании. У 9 профилей название обрывается на
незакрытой «» или (): «Санаторий «Россиянка», «Разрез «Степановский»,
«ООО «Агентская компания «Гамбит»» без второй закрывающей ёлочки.

ОТКУДА ВЗЯЛОСЬ. Профили собирались из заголовков сделок и текста `extra»,
где то же название стоит целиком, — обрыв случился при переносе в отдельное
поле `name`.

ГРАНИЦА ПРАВКИ. Для 6 названий восстановление механическое: не хватает ровно
одной закрывающей «этажки» — либо простой (Санаторий «Россиянка»), либо
второй при вложенности (ООО «Агентская компания «Гамбит»»). Для трёх имён с
незакрытой скобкой — правка ручная, с проверкой источника:
  * `g8d10285c` — «Элма групп» (учредитель — концерн «Прамо»)»: фраза перед
    обрывом уже полная, не хватает одной «)».
  * `g0b9343f2` — Augment Investments Limited (МКОО, подконтрольное Виктору
    Харитонину…): в `extra` сделки g4e5d24db эта же компания названа короче —
    «Augment Investments Limited» — а «МКОО» (форма компании) в g703d5597
    стоит без остального уточнения. Restoring до «(МКОО)» — это то, что
    доказуемо принадлежит названию, а не пересказ чужого предложения о
    бенефициаре.
  * `gfe4e2358` — «ООО «Арт-Финанс» (зарегистрировано в феврале 2023 г»:
    остаток фразы не встречается ни в одной карточке с этой компанией — там
    название даётся как «ООО «Арт-Финанс»» и «ООО «Арт-Финанс» (структура
    дилерского холдинга «Авилон»)», без даты регистрации. Досочинять дату
    нельзя, поэтому обрубленное уточнение снимается целиком, а не дописывается
    догадкой.

Запуск:
    python3 pipeline/fix_company_names.py            # сухой прогон
    python3 pipeline/fix_company_names.py --write    # записать
"""
import json
import sys

PATH = 'static/data/deals_promoted.json'

# company_id -> (было, стало)
FIXES = {
    'g893ef7bc': ('Санаторий «Россиянка', 'Санаторий «Россиянка»'),
    'g23e8efa9': ('Разрез «Степановский', 'Разрез «Степановский»'),
    'g23a1df20': ('УК «Белая скала', 'УК «Белая скала»'),
    'g64d451b5': ('ООО «Агентская компания «Гамбит»', 'ООО «Агентская компания «Гамбит»»'),
    'g5e535262': ('АО «Киностудия «Союзмультфильм»', 'АО «Киностудия «Союзмультфильм»»'),
    'ge02c264d': ('ООО «МПК «Тосненский»', 'ООО «МПК «Тосненский»»'),
    'g8d10285c': ('«Элма групп» (учредитель — концерн «Прамо»', '«Элма групп» (учредитель — концерн «Прамо»)'),
    'g0b9343f2': ('Augment Investments Limited (МКОО', 'Augment Investments Limited (МКОО)'),
    'gfe4e2358': ('ООО «Арт-Финанс» (зарегистрировано в феврале 2023 г', 'ООО «Арт-Финанс»'),
}


def main(write):
    data = json.load(open(PATH, encoding='utf-8'))
    companies = data['companies']

    plan = []
    for cid, (old, new) in FIXES.items():
        c = companies.get(cid)
        assert c is not None, 'нет компании %s' % cid
        assert c.get('name') == old, '%s: имя не совпадает дословно: %r' % (cid, c.get('name'))
        plan.append((cid, old, new))

    print('Обрубленных названий компаний: %d' % len(plan))
    for cid, old, new in plan:
        print('  %-12s %r -> %r' % (cid, old, new))

    if not write:
        print('\nСухой прогон. Запись — с ключом --write.')
        return

    for cid, old, new in plan:
        companies[cid]['name'] = new
    for cid, old, new in plan:
        assert companies[cid]['name'] == new, '%s: не записалось' % cid

    with open(PATH, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('\nЗаписано: %d названий.' % len(plan))


if __name__ == '__main__':
    main('--write' in sys.argv)
