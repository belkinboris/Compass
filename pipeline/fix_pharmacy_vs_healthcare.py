# -*- coding: utf-8 -*-
"""Аптечные сети лежали в двух отраслях сразу. Плюс два профиля не о том.

ВОПРОС ВЛАДЕЛЬЦА (19 сентября 2026): «А почему "Апрель" — фармацевтика, а
"Аптеки миницен" и "Новая аптека" — здравоохранение? В чём разница? Если её
нет, надо везде поправить.»

ЗАМЕР. Разницы нет. Аптечные сети стояли в обеих отраслях: десяток в
«Фармацевтике» («Апрель», «Нео-Фарм», «36,6», «Трика», «Аптечные традиции»,
«Трик Фарма», «На здоровье», «Фармакон», «Фарм») и шесть в
«Здравоохранении». При этом САМИ СДЕЛКИ про аптеки уже все до одной
отнесены к «Фармацевтике» (20 из 20) — то есть разъехались только профили,
и разъехались они в меньшую сторону.

ПРАВИЛО, по которому разводим впредь:
  * «Фармацевтика» — всё про лекарства: производство, субстанции,
    дистрибуция и аптечные сети (розница лекарств).
  * «Здравоохранение» — медицинские услуги и техника: клиники,
    лаборатории, телемедицина, протезы, медоборудование, уход.

CVS Health намеренно ОСТАЁТСЯ в «Здравоохранении»: по собственному
описанию это «сеть аптек И поставщик медицинских услуг и страхования» —
не аптечная сеть, а разносторонняя медицинская компания.

ДВА ПРОФИЛЯ НЕ О ТОМ — найдены тем же замером, чинятся заодно:
  * «Свеза» — «один из крупнейших в мире производителей берёзовой фанеры» —
    стояла в «Фармацевтике». Отрасль явно приехала от предмета её
    единственной сделки («Центр фармацевтической упаковки»), а не от неё
    самой. Правильная отрасль — «Лесопром».
  * «Опека» — описана как «Российская аптечная сеть», хотя текст её же
    карточки говорит прямо: «продали 49,99% акций сети домов престарелых
    "Опека"» (источники: Коммерсантъ 7266558, Vademecum от 31.10.2024), и
    профиль Алексея Маврина в нашей базе называет его «основателем сети
    домов престарелых "Опека"». Это уход за пожилыми, а не аптеки: правим
    и описание, и отрасль профиля, и отрасль самой сделки.

Запуск: python3 pipeline/fix_pharmacy_vs_healthcare.py --write
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "static" / "data" / "deals_promoted.json"

# Аптечные сети, стоявшие в «Здравоохранении».
TO_PHARMA = {
    "g7313d9af": "Ригла",
    "g1beaf092": "ЛекОптТорг",
    "g9decc157": "аптечная сеть «Аптека25.рф»",
    "g92995d45": "АО «Столичные аптеки»",
    "gd3564a89": "«Аптеки миницен» и «Новая аптека»",
    "g1d06106b": "«Аптечество» и Farmani",
}
SVEZA = "g59be6698"
OPEKA = "gce18ed36"
OPEKA_DESC_OLD = "Российская аптечная сеть."
OPEKA_DESC_NEW = ("Сеть домов престарелых (пансионатов для пожилых); в 2024 году её "
                  "основатель Алексей Маврин выкупил 49,99% у акционеров «Валента Фарм».")


def main(write: bool) -> int:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    companies, deals = data["companies"], data["deals"]

    for cid, name in TO_PHARMA.items():
        c = companies[cid]
        assert c["name"] == name, "%s: ожидали «%s», в базе «%s»" % (cid, name, c["name"])
        assert c["ind"] == "Здравоохранение", "%s: отрасль уже «%s»" % (cid, c["ind"])
        c["ind"] = "Фармацевтика"
        print("  %-34s Здравоохранение → Фармацевтика" % name)

    sveza = companies[SVEZA]
    assert sveza["ind"] == "Фармацевтика" and "фанер" in sveza["desc"]
    sveza["ind"] = "Лесопром"
    print("  %-34s Фармацевтика → Лесопром" % sveza["name"])

    opeka = companies[OPEKA]
    assert opeka["desc"] == OPEKA_DESC_OLD, "описание «Опеки» уже другое"
    assert opeka["ind"] == "Фармацевтика"
    opeka["desc"], opeka["ind"] = OPEKA_DESC_NEW, "Здравоохранение"
    print("  %-34s Фармацевтика → Здравоохранение (+ описание)" % opeka["name"])

    hit = [d for d in deals if "Опеки" in (d.get("title") or "")]
    assert len(hit) == 1, "ожидали одну сделку про «Опеку», нашли %d" % len(hit)
    deal = hit[0]
    assert deal["ind"] == "Фармацевтика"
    deal["ind"] = "Здравоохранение"
    if isinstance(deal.get("industries"), list):
        deal["industries"] = ["Здравоохранение" if x == "Фармацевтика" else x
                              for x in deal["industries"]]
    print("  сделка «%s…» → Здравоохранение" % deal["title"][:46])

    # Проверка на себе: аптечных сетей в «Здравоохранении» больше остаться не
    # должно — кроме CVS Health, о котором сказано в докстроке.
    left = [c["name"] for c in companies.values()
            if c.get("ind") == "Здравоохранение"
            and "аптек" in (c.get("name", "") + c.get("desc", "")).lower()]
    assert left == ["CVS Health"], "в «Здравоохранении» остались аптеки: %s" % left

    if not write:
        print("\n(сухой прогон; чтобы записать — --write)")
        return 0
    # indent=1 и без завершающего перевода строки — как файл лежит в git.
    json.dump(data, DATA.open("w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("\nзаписано")
    return 0


if __name__ == "__main__":
    sys.exit(main("--write" in sys.argv))
