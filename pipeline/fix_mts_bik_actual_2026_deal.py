import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gf1608a6f'

OLD_CONTEXT = (
    'МТС выделила башенные активы в ООО «Башенная инфраструктурная'
    ' компания» в сентябре 2021 года; в портфеле около 23 тыс.'
    ' антенно-мачтовых сооружений (АМС). Продать актив планировали в'
    ' первой половине 2022 года, но из-за неопределённости на рынке'
    ' после начала военной операции на Украине переговоры отложили.'
)
NEW_CONTEXT = (
    OLD_CONTEXT + ' Ни один источник не подтвердил продажу внешнему'
    ' консорциуму. Вместо этого 26 июня 2026 года МТС продала 49,9%'
    ' долей БИК закрытому паевому инвестфонду «Инвестиции 18» за'
    ' 21,7 млрд ₽, сохранив 50,1% и совместный контроль; покупатель'
    ' принял на себя часть долга БИК (всего около 80 млрд ₽), а МТС'
    ' получила опцион на обратный выкуп доли. Управляющая фондом'
    ' компания — бывшая структура самой МТС/АФК «Система».'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
