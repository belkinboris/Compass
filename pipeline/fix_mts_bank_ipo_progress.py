# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g465977ce
(МТС Банк провел IPO и привлек ₽11,5 млрд) — судьба акций и бизнеса
после IPO не была отражена вовсе: за два с лишним года случилось резкое
падение котировок, отдельное SPO и рост финансовых показателей.
Проверено лично прямым WebFetch четырёх источников.

1) `eco.context` (дополнено) — динамика акций. Дословно (investfunds.ru,
29.08.2026): текущая цена «909.50 RUB», диапазон размещения IPO — «от
2 350 рублей до 2 500 рублей за акцию» — падение примерно на 63-64% от
цены размещения.

2) `eco.context` (дополнено) — SPO в июле 2025 года, отдельное от
истечения lock-up событие (новый капитал, а не продажа акций МТС или
других держателей). Дословно (Интерфакс): «Цена размещения в рамках SPO
МТС-банка составит 1380,5 руб./АО», «объем привлечения составил 4 млрд
руб.», «В рамках SPO банк размещает 2 млн 897 тыс 574 акций», «уставный
капитал банка увеличится на 8,4%».

3) `eco.target_fin` (дополнено) — финансовые показатели 2024-2025.
Дословно (Интерфакс, 2024): «Чистая прибыль МТС-банка по МСФО за 2024
год сократилась на 1% и составила 12,4 млрд рублей», «Кредитный
портфель банка... вырос на 10,9%... до 385,8 млрд рублей», «Капитал
банка по МСФО за 2024 год вырос на 47,4%, до 112,4 млрд рублей».
Дословно (bosfera.ru, 2025): «Чистая прибыль МТС Банка по МСФО за 2025
год составила 14,4 млрд рублей, что на 16,7% больше»; «Активы банка
увеличились на 25%, до 754,5 млрд рублей», «капитал составил 126,3
млрд рублей».

НЕ ВКЛЮЧЕНО: юридический консультант IPO — суб-агент нашёл кандидата
(LECAP) по индексу поисковика, но прямой WebFetch страницы (и двух
альтернативных страниц того же сайта) трижды подряд отдал 404 — цитата
не подтверждена личным чтением, в карточку не идёт; организаторы/
букраннеры IPO — не найдены ни в одном открытом источнике; независимая
оценка после SPO — не нашлась.

Запуск: python3 pipeline/fix_mts_bank_ipo_progress.py
        python3 pipeline/fix_mts_bank_ipo_progress.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g465977ce'

OLD_CONTEXT = 'спрос превысил объем предложения примерно в 15 раз по верхней границе ценового диапазона'
NEW_CONTEXT = OLD_CONTEXT + (
    '. По состоянию на 29 августа 2026 года акции торгуются заметно '
    'ниже цены размещения: текущая цена «909.50 RUB» против диапазона '
    'IPO «от 2 350 рублей до 2 500 рублей за акцию» (investfunds.ru) — '
    'падение примерно на 63-64%. В июле 2025 года банк провёл отдельное '
    'SPO: «Цена размещения в рамках SPO МТС-банка составит 1380,5 '
    'руб./АО», «объем привлечения составил 4 млрд руб.», «уставный '
    'капитал банка увеличится на 8,4%» (Интерфакс) — это новый капитал, '
    'а не продажа акций мажоритарным акционером.'
)

OLD_TARGET_FIN = '—'
NEW_TARGET_FIN = (
    'По МСФО за 2024 год: «Чистая прибыль МТС-банка... сократилась на '
    '1% и составила 12,4 млрд рублей», кредитный портфель вырос на '
    '10,9% до 385,8 млрд руб., капитал вырос на 47,4% до 112,4 млрд '
    'руб. (Интерфакс). За 2025 год: чистая прибыль «составила 14,4 млрд '
    'рублей, что на 16,7% больше», активы выросли на 25% до 754,5 млрд '
    'руб., капитал — 126,3 млрд руб. (bosfera.ru).'
)

NEW_SRC = [
    ['investfunds.ru', 'https://investfunds.ru/stocks/MTS-Bank/'],
    ['Интерфакс', 'https://www.interfax.ru/business/1036041'],
    ['Интерфакс', 'https://www.interfax.ru/business/1012031'],
    ['bosfera.ru', 'https://bosfera.ru/press-release/chistaya-pribyl-mts-banka-po-msfo-za-2025-god-prevysila-14-mlrd-rubley'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    assert deal['eco']['target_fin'] == OLD_TARGET_FIN
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== eco.target_fin: станет ===')
    print(NEW_TARGET_FIN)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['eco']['target_fin'] = NEW_TARGET_FIN
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
