import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'geb645292'

OLD_CONTEXT = (
    'АО «ЦК» также владеет 100% долей компании ExpoMobility (ООО '
    '«Экспомобилити»), занимающейся операционной арендой автомобилей. '
    'Прежнее название этой компании – ALD Automotive, ее активы структура '
    'Кима приобрела весной 2023 года у группы Societe Generale. Структуры '
    'Кима в прошлом году аккумулировали целый ряд активов, связанных с '
    'финансовым бизнесом представительств работавших в РФ иностранных '
    'концернов. В частности, «дочки» производителя сельхозтехники CNH '
    'Industrial (ныне – ООО «ИФС Лизинг» и ООО «ИФС Капитал»), японской '
    'Mitsubishi (MC Intermark Auto, ООО «МСИА»), шведской Volvo (ООО '
    '«Стоков Финансовые Услуги»).'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' 25 февраля 2025 года консолидация дошла до банка: «Бизнесмен получил '
    '45% долей в банке напрямую и еще 55% – через контролируемую им '
    'компанию "Экспомобилити"», а «разрешение президента РФ на продажу '
    'российской банковской "дочки" германский автоконцерн Volkswagen '
    'получил 31 декабря 2024 года» — по итогам 2024 года «Фольксваген банк '
    'Рус» занимал 135-е место в рэнкинге «Интерфакс-100» с активами 24 '
    'млрд ₽ и капиталом 23,6 млрд ₽ (Интерфакс, 26 февраля 2025). '
    'Купленная факторинговая «дочка» (ООО «Фольксваген Финансовые Услуги '
    'Рус») переименована в ООО «Экспофинанс» и ликвидирована 21 октября '
    '2024 года (данные ЕГРЮЛ).'
)

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/business/1010853'],
    ['РБК Компании', 'https://companies.rbc.ru/id/1077762019499-ooo-folksvagen-finansovyie-uslugi-rus/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
