# -*- coding: utf-8 -*-
"""Побочная находка при собственной проверке правки (карточка
g91606f1b, «Русагро купила 50% акций НМЖК»): второе предложение в
`extra` («Продавцы — управляющие партнёры группы Николай Нестеров и
Николай Сидорок; сингапурская Wilmar International осталась
совладельцем...») исчезало с экрана целиком, хотя нёс единственный
новый факт (Wilmar остаётся совладельцем оставшихся 50%).

Причина — в самом алгоритме `extraHtml()`: поле `seller` короткое («Николай
Нестеров и Николай Сидорок» — после фильтра стоп-слов ровно три
значащих слова), и когда все три слова встречаются в предложении
`extra` целиком (даже если рядом с ними десяток других, действительно
новых слов), отношение «общих слов» к МЕНЬШЕМУ множеству (то есть к
самому `seller`) даёт 100% — предложение засчитывается дублем
целиком. Это не тот же случай, что уже чинили для `eco.val` («Порог
схожести без нижней абсолютной планки...», common>=3 введён именно от
этого) — здесь `common` и есть 3, порог формально пройден, но
источник совпадения — короткое ИМЯ, а не короткая ФРАЗА-ЗАГЛУШКА;
абсолютный минимум не спасает, когда сам эталон короче минимума.

Правку самого `extraHtml()` в этом прогоне не делаю — это общий для
всей базы алгоритм, и менять его стоит с прогоном по всем карточкам,
где есть короткие `seller`/`buyer_name`, а не мимоходом. Обошёл для
ЭТОЙ карточки: убрал повтор имён продавцов из предложения с фактом о
Wilmar — сами имена уже показаны отдельно, в поле `seller`.

Запуск: python3 pipeline/fix_nmzhk_extra_dedup_seller_overlap.py
        python3 pipeline/fix_nmzhk_extra_dedup_seller_overlap.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g91606f1b'

OLD_EXTRA = (
    'Русагро приобрела 50% акций и контроль над группой компаний НМЖК, '
    'владеющей масложировым комбинатом в Нижнем Новгороде, '
    'маслоэкстракционными предприятиями в Урюпинске и Сорочинске, а '
    'также элеваторами. Продавцы — управляющие партнёры группы Николай '
    'Нестеров и Николай Сидорок; сингапурская Wilmar International '
    'осталась совладельцем оставшихся 50%, «Русагро» планировала '
    'развивать бренды НМЖК совместно с ней.'
)
NEW_EXTRA = (
    'Русагро приобрела 50% акций и контроль над группой компаний НМЖК, '
    'владеющей масложировым комбинатом в Нижнем Новгороде, '
    'маслоэкстракционными предприятиями в Урюпинске и Сорочинске, а '
    'также элеваторами. Сингапурская Wilmar International осталась '
    'совладельцем оставшихся 50% — «Русагро» планировала развивать '
    'бренды НМЖК совместно с ней.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    print('=== extra: станет ===')
    print(NEW_EXTRA)

    if write:
        deal['extra'] = NEW_EXTRA
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
