# -*- coding: utf-8 -*-
"""Восход — юридический консультант покупателя в сделке Т-Технологии / Авто.ру.

ЧТО СЛОМАНО. У карточки `g59380a3e` был записан только консультант ПРОДАВЦА
(Asari Legal со стороны «Яндекса»), а сторона покупателя стояла пустой. Факт
нашёлся у владельца: канал «РУЛЬФЫ, ИЛЬФЫ И ИНХАУСЫ» (@LawFirms) опубликовал
сообщение самой фирмы о сопровождении сделки.

ПОЧЕМУ ПРОПУСТИЛИ — две независимые причины, обе устранены отдельно:
  1. Канала @LawFirms не было в реестре источников (`sources.json`), то есть
     мы его вообще не читали. Добавлен и проверен `fetch.py --verify`.
  2. Даже если бы читали — `enrich.py` не умеет предлагать консультантов
     вовсе: среди его правок есть источник, сумма, стороны, статус, заголовок
     и этап, а поля `law.adv` среди них нет. Это отдельная задача: наивное
     правило («консультант», «советник») замерено на 133 живых постах шести
     юридических каналов и дало 11 срабатываний, из которых ВЕРНЫХ НОЛЬ —
     в этих каналах «советник» это должность сотрудника, а «консультант» —
     слово из рейтингов (пойман мастер-класс по арбитражу и пост про
     космонавтов). В базу такое правило пускать нельзя.

ОТКУДА ФАКТ. https://t.me/LawFirms/10680 — сообщение фирмы: «Юридическая
фирма «Восход» сообщает о сопровождении командой корпоративной практики
сделки по приобретению … «Т-Технологии» 100% группы компаний Авто.ру у
«Яндекса»… Со стороны «Восхода» сделку на стороне покупателя сопровождали…».
Сторона названа в самом сообщении дословно («на стороне покупателя»), поэтому
роль не выводится догадкой. Проверяемые факты сообщения (сумма 35 млрд ₽,
подписание 18 марта, 100% группы компаний) совпадают с уже записанными в
карточке — источник о ТОЙ ЖЕ сделке, а не о похожей.

ЧЕГО НЕ ДЕЛАЕМ. Не переписываем существующую запись про Asari Legal (это
консультант другой стороны, обе верны) и не добавляем имена юристов из
сообщения: в карточке хранится фирма, а не состав команды.

Запуск:
    python3 pipeline/add_voskhod_avtoru_advisor.py            # сухой прогон
    python3 pipeline/add_voskhod_avtoru_advisor.py --write    # записать
"""
import json
import sys

PATH = 'static/data/deals_promoted.json'
DEAL_ID = 'g59380a3e'
POST = 'https://t.me/LawFirms/10680'

ROLE = 'Юридический консультант покупателя (Т-Технологии)'
FIRM = 'Восход'
NOTE = ('Сопровождение командой корпоративной практики сделки по приобретению '
        '«Т-Технологии» 100% группы компаний Авто.ру у «Яндекса»; со стороны '
        '«Восхода» сделку сопровождали на стороне покупателя. Источник: ' + POST)
SRC_ENTRY = ['РУЛЬФЫ, ИЛЬФЫ И ИНХАУСЫ (@LawFirms)', POST]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    adv = deal.setdefault('law', {}).setdefault('adv', [])
    # Проверки исходного состояния: если данные уже другие, падаем, а не портим.
    assert any('Asari' in str(a[1]) for a in adv if len(a) > 1), \
        'ожидали найти Asari Legal — карточка изменилась, перепроверьте'
    assert not any(FIRM.lower() in str(a[1]).lower() for a in adv if len(a) > 1), \
        'Восход уже записан — повторный прогон не нужен'
    # Факт обязан подтверждаться сделкой, а не просто быть правдоподобным:
    # сумма из сообщения фирмы совпадает с суммой карточки.
    assert '35 млрд' in str(deal.get('sum')), 'сумма карточки разошлась с сообщением фирмы'

    src = deal.setdefault('src', [])
    src_new = not any(len(s) > 1 and s[1] == POST for s in src)

    print('карточка: %s — %s' % (DEAL_ID, deal.get('title')))
    print('было консультантов: %d' % len(adv))
    for a in adv:
        print('   • %s — %s' % (a[0], a[1]))
    print('добавляем: %s — %s' % (ROLE, FIRM))
    print('источник в src: %s' % ('добавляем' if src_new else 'уже есть'))

    if write:
        adv.append([ROLE, FIRM, NOTE])
        if src_new:
            src.append(SRC_ENTRY)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=1, ensure_ascii=False)
        print('\nЗАПИСАНО в', PATH)
    else:
        print('\nСухой прогон. Запись — с ключом --write.')
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
