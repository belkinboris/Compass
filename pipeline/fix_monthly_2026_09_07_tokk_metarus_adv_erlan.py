import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

TOKK_OLD_TARGET_FIN = '—'
TOKK_NEW_TARGET_FIN = (
    'АО «Метарус Курганинск» — предмет сделки: выручка за 2025 год — '
    '48,9 млн ₽ против 703,4 млн ₽ в 2024-м, убыток 641,7 млн ₽ против '
    'прибыли 204 млн ₽ годом ранее.'
)

ADV_OLD_CONTEXT = (
    'Сделка прошла на фоне корпоративного конфликта с основателем '
    'группы Дмитрием Коробковым, который оспаривал продажу своей доли '
    '2023 года. В апреле 2026 года суд первой инстанции признал '
    '«Эрлан» недобросовестным приобретателем, но в июне 2026 года '
    'апелляция отменила это решение.'
)
ADV_NEW_CONTEXT = (
    'Сделка прошла на фоне корпоративного конфликта с основателем '
    'группы Дмитрием Коробковым, который оспаривал продажу своей доли '
    '2023 года. В апреле 2026 года суд первой инстанции признал '
    '«Эрлан» недобросовестным приобретателем, но 30 июня 2026 года '
    'Девятый арбитражный апелляционный суд отменил это решение и '
    'оставил контрольные доли структурам Кирилла Коробейникова и '
    'Павла Сидорова; представитель Коробкова заявил о планах '
    'обжаловать решение, срок подачи кассационной жалобы — до 10 '
    'сентября 2026 года.'
)

ADV_OLD_TARGET_FIN = '—'
ADV_NEW_TARGET_FIN = (
    'В 2025 году группа АДВ заняла пятое место в рейтинге Sostav.ru по '
    'объёму медиазакупок с биллингом 48,4 млрд ₽ без НДС.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    tokk = by_id['tokk-metarus']
    adv = by_id['adv-erlan']

    assert tokk['eco']['target_fin'] == TOKK_OLD_TARGET_FIN
    assert adv['eco']['context'] == ADV_OLD_CONTEXT
    assert adv['eco']['target_fin'] == ADV_OLD_TARGET_FIN

    print('=== tokk-metarus: eco.target_fin ===')
    print(TOKK_NEW_TARGET_FIN)
    print()
    print('=== adv-erlan: eco.context ===')
    print(ADV_NEW_CONTEXT)
    print()
    print('=== adv-erlan: eco.target_fin ===')
    print(ADV_NEW_TARGET_FIN)

    if write:
        tokk['eco']['target_fin'] = TOKK_NEW_TARGET_FIN
        adv['eco']['context'] = ADV_NEW_CONTEXT
        adv['eco']['target_fin'] = ADV_NEW_TARGET_FIN
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
