def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}
    for did in list(ADD) + list(EXCLUDE):
        assert did in by_id, 'нет карточки %s' % did
    assert not (set(ADD) & set(EXCLUDE)), 'id и в ADD, и в EXCLUDE'
    added, already = [], []
    for did, why in ADD.items():
        d = by_id[did]
        have = d.get('themes') or []
        if THEME in have:
            already.append(did)
            continue
        d['themes'] = have + [THEME]
        added.append((did, d['title'][:80], why))
    for a in added:
        print(' + %s | %s\n     %s' % a)
    total = sum(1 for d in data['deals'] if THEME in (d.get('themes') or []))
    print('добавлено: %d; уже стояло: %d; всего с темой: %d; отклонено после чтения: %d'
          % (len(added), len(already), total, len(EXCLUDE)))
    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=1, ensure_ascii=False)
        print('ЗАПИСАНО в', PATH)
    else:
        print('Сухой прогон. Применение — с ключом --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
