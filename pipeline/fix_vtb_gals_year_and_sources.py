import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g92476095'

OLD_DATE = '2024'
NEW_DATE = '2026'

OLD_SRC = [['@dealsma (Telegram)', 'https://t.me/dealsma/7148']]
NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8710438'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8741733'],
    ['Галс-Девелопмент (пресс-центр)', 'https://hals-development.ru/presscenter/news/1369636'],
]

OLD_CONTEXT = (
    'ВТБ стал основным владельцем «Галс-Девелопмента» в 2009 году, когда '
    'приобрел контрольный пакет (51,24%) девелопера у АФК «Система».'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' После продажи компания заявила о планах развития: «Новым '
    'собственником ГК "Галс-Девелопмент" стала группа профессиональных '
    'инвесторов в высокотехнологичные проекты», «Компания продолжит '
    'работать как системный и инновационный девелопер... планируем '
    'наращивать портфель проектов и продолжим внедрять цифровые '
    'инновации на наших стройплощадках» (пресс-центр «Галс-Девелопмент», '
    '19 июня 2026).'
)

OLD_VAL = (
    'Покупатель- некая группа инвесторов, которая заплатила за актив в '
    'два раза больше, чем обсуждали на рынке.'
)
NEW_VAL = OLD_VAL + (
    ' Ранее, до закрытия, назывались другие кандидаты: «одним из '
    'претендентов на покупку является "Страна Девелопмент"», «интерес к '
    'покупке "Галса" также проявляла девелоперская Sezar Group» '
    '(Коммерсантъ, 28 апреля 2026) — ни один не подтверждён как '
    'финальный покупатель.'
)

NEW_SRC_FOR_VAL = ['Коммерсантъ', 'https://www.kommersant.ru/doc/8625350']


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['date'] == OLD_DATE
    assert deal['src'] == OLD_SRC
    assert deal['eco']['context'] == OLD_CONTEXT
    assert deal['eco']['val'] == OLD_VAL

    print('=== date: станет ===')
    print(NEW_DATE)
    print('\n=== src: станет ===')
    for s in NEW_SRC + [NEW_SRC_FOR_VAL]:
        print(s)
    print('\n=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== eco.val: станет ===')
    print(NEW_VAL)

    if write:
        deal['date'] = NEW_DATE
        deal['src'] = NEW_SRC + [NEW_SRC_FOR_VAL]
        deal['eco']['context'] = NEW_CONTEXT
        deal['eco']['val'] = NEW_VAL
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
