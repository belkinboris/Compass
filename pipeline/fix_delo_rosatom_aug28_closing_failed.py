"""`g6a4b0a2a` (Росатом/Шишкарев/ГК «Дело») — дополнение к `eco.context`,
уже занятому текстом из прежних источников. Интерфакс (3 сентября 2026,
ВЭФ-2026, https://www.interfax.ru/russia/1112881) сообщает новый,
конкретный факт, которого в карточке не было: назначенное на 28 августа
закрытие сделки («русская рулетка») НЕ СОСТОЯЛОСЬ — «ни Сергей Шишкарев,
ни его представители на закрытие сделки не явились». Это разрешает
несколько дней висевшего в сыром притоке множества дублирующих друг
друга заметок («Росатом» завершит процедуру выкупа 51% в ГК «Дело»
28 августа», ««Росатом» 28 августа планирует выкупить 51% ГК «Дело» за
77 млрд рублей») — они были про ПЛАН, а не про исход, и исход теперь
известен: попытка сорвалась, а не завершилась.

Дополнение — не через review.py (поле уже занято, дословная цитата
покрывает только новую часть, а не старое+новое целиком — тот же приём,
что и у Самолёт/Сабанеева, `fix_samolet_sabaneeva_prosecutor_check.py`).

Запуск: python3 pipeline/fix_delo_rosatom_aug28_closing_failed.py           # проверка
        python3 pipeline/fix_delo_rosatom_aug28_closing_failed.py --write   # запись
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g6a4b0a2a'
OLD_CONTEXT = (
    'В ближайшие дни истекает срок, установленный корпоративным договором с '
    'Госкорпорацией "Росатом" для выкупа мною их доли… Выкупать пакет не буду '
    'После отказа Шишкарева право выкупа перешло к «Росатому»: по словам главы '
    'госкорпорации Алексея Лихачёва, «Корпоративное решение о том, что мы '
    'покупаем, принято» — то есть «Росатом» выкупает долю самого Шишкарева, а '
    'не наоборот. На начало июля 2026 года оформление сделки продолжалось и '
    'могло «продлиться до конца месяца». Меморандум о взаимопонимании с '
    '«Ростехом» по созданию СП (пакет 49% оценивался в 74 млрд ₽), '
    'заключённый Шишкаревым в апреле 2026 года, из-за его отказа не состоялся.'
)
ADDITION = (
    'Назначенное на 28 августа 2026 года закрытие сделки не состоялось: '
    'стороны должны были в этот день подписать и нотариально удостоверить '
    'все необходимые документы по переводу доли Шишкарева в ООО УК «Дело» в '
    'пользу «Росатома», но, по сообщению госкорпорации, «ни Сергей Шишкарев, '
    'ни его представители на закрытие сделки не явились». Шишкарев заявил, '
    'что требует точного соблюдения условий договора и не согласен с '
    'акцептом оферты без этого, а также предложил «Росатому» направить '
    'причитающуюся ему по сделке сумму на докапитализацию самой компании. '
    'Лихачёв на ВЭФ-2026 (3 сентября) сказал, что группа «Дело» '
    'перекредитована и «сейчас находится в сложном положении», а «Росатому» '
    'предстоят переговоры с банками о реструктуризации задолженности '
    'компании.'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + ADDITION


def _find_card(data):
    for c in data.get('deals', []):
        if c['id'] == CARD_ID:
            return c
    return None


def main(write=False):
    data = json.load(open(BASE, encoding='utf-8'))
    card = _find_card(data)
    assert card is not None, '%r не найдена в базе' % CARD_ID
    assert card.get('eco', {}).get('context') == OLD_CONTEXT, (
        'eco.context уже другое: %r' % card.get('eco', {}).get('context'))

    print('ДОБАВЛЕНО: %r' % ADDITION)
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return 1

    card['eco']['context'] = NEW_CONTEXT
    json.dump(data, open(BASE, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('ЗАПИСАНО в %r.' % BASE)
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv[1:]))
