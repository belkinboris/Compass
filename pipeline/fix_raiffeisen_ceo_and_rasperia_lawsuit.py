# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка g1b5e8ab8 (Raiffeisen
Bank International попытался продать долю в российском бизнесе):
дельта-поиск нашёл два крупных развития истории ПОСЛЕ провалившейся в
октябре 2025 попытки продажи — смену CEO (Йохан Штробль, лично веший
переговоры, покидает пост) и рекордный иск RBI к Rasperia на 3,15 млрд
евро в Вене, поданный в рамках стратегии извлечения ценности из
российского бизнеса. Статус карточки не меняется («Не состоялась»
по-прежнему верно описывает конкретную попытку октября 2025) — это
дополнение контекста, а не новый исход той же сделки. Не через
review.py: старое значение eco.context — про «Турецкий поток», другая
тема статьи, не образует непрерывный кусок с этими цитатами.

Источники — читал напрямую (fetch_article_texts.py, закэшированы):
EQS-News (17.12.2025, объявление о смене CEO) и Vindobona (09.08.2026,
об иске к Rasperia).
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g1b5e8ab8'

OLD_CONTEXT = (
    'Raiffeisen проводит платежи по газопроводу «Турецкий поток» — '
    'единственному оставшемуся у России маршруту поставок газа в '
    'Европу после того, как остальные были перекрыты, рассказали '
    'собеседники. За первые восемь месяцев этого года по «Турецкому '
    'потоку» через Турцию в европейские страны, включая Болгарию и '
    'Венгрию, было поставлено около 11,5 млрд куб. м газа. По средним '
    'рыночным ценам этот газ стоил примерно $3,8 млрд, что делает его '
    'существенной частью российского газового экспорта.'
)
ADDITION = (
    '17 декабря 2025 года наблюдательный совет RBI назначил Михаэля '
    'Хёллерера преемником Йохана Штробля (лично вёл провалившиеся '
    'переговоры о продаже) на посту CEO с 1 июля 2026 года — Штробль '
    'решил не добиваться продления своего мандата, который истекает в '
    'феврале 2027 года. В августе 2026 года RBI и его российская '
    'дочерняя структура АО «Райффайзенбанк» подали в венский суд иск на '
    '3,15 млрд евро к российской Rasperia Trading Limited, впервые в '
    'мире применив статью 11a 14-го пакета санкций ЕС — предметом '
    'взыскания выступают 28,5 млн акций STRABAG SE, замороженные на '
    'счёте Rasperia в Австрии, вместе с накопленными дивидендами и '
    'выплатами от снижения капитала STRABAG. Российский суд наложил на '
    'RBI всемирный запрет на судебные разбирательства по этому делу, но '
    'прямо исключил из-под запрета разбирательство в Австрии; в начале '
    'августа 2026 года Rasperia отозвала оставшиеся иски в России. '
    'Разбирательство в Вене может занять около полугода, расходы RBI по '
    'делу оцениваются до 150 млн евро за 2026 год.'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} eco.context: += смена CEO, иск к Rasperia на 3,15 млрд евро")
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
