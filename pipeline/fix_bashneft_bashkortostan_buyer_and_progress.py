import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gbbc6c73e'

OLD_BUYER_NAME = 'Рим Хакимов'
NEW_BUYER_NAME = 'ООО «Аврора» (управляет ГК «Президент Отель»)'

OLD_CONTEXT = 'ООО ГК «Башкортостан» зарегистрировано в июле 2002 года в Уфе.'
NEW_CONTEXT = OLD_CONTEXT + (
    ' Переход собственности занял два шага: с 24 июня 2024 года новым '
    'владельцем 100% стал Рим Хакимов, «связанный с олигархом Дамиром '
    'Мугиновым», а с 3 июля 2024 года — ООО «Аврора», «0,2% в которой '
    'принадлежит дочери Мугинова Зарине» (Хакимов владел 10 дней, '
    'конечный бенефициар — семья Мугиновых). Причина продажи: актив был '
    'убыточным — «в 2017–2020 годах уходил в минус на 63–93 миллиона '
    'рублей в год» (УФА1.ру); Башнефть официально сделку не '
    'комментировала.'
)

NEW_SRC = [
    ['РБК Уфа', 'https://ufa.rbc.ru/ufa/10/07/2024/668e493f9a79472efab0810b'],
    ['УФА1.ру', 'https://ufa1.ru/text/gorod/2024/08/03/73909862/'],
    ['Prufy.ru', 'https://prufy.ru/news/society/170045-gostinitsa_bashkiriya_poluchila_pyat_zvezd_zasluzhenno_/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal.get('buyer') is None
    assert deal.get('buyer_name') == OLD_BUYER_NAME
    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print(f'=== buyer_name (новое поле): станет {NEW_BUYER_NAME!r} ===')
    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['buyer_name'] = NEW_BUYER_NAME
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
