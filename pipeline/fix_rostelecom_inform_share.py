# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
`g200c00b5` («Ростелеком купил оставшиеся 49,9% акций ООО «Информ» у
ЛУКОЙЛа», закрыта, 2023-05-03) — карточка полна структурными полями
(law.struct/appr, eco.val/rationale/target_fin/context), но не отвечала
на самый простой вопрос: чем вообще занимается «Информ». Источник
карточки (Интерфакс) этого не описывает вовсе.

Проверено ЛИЧНО прямым WebFetch (дословные цитаты, rtk-inform.ru —
собственный сайт компании):
- «предприятие Группы «Ростелеком» в области интеграции IT-решений для
  предприятий топливно-энергетического комплекса»;
- «53 региона нефтедобычи и нефтепереработки объединены
  инфраструктурой, обслуживаемой Информом»;
- «Компания была основана в 1993 г.» и работает «30 лет на рынке связи
  для топливно-энергетического комплекса»;
- «специализированный оператор Группы «Ростелеком»» для заказчиков ТЭК.

НЕ ВНЕСЕНО: (1) финансовые показатели за 2023-2025 годы — саб-агент
нашёл их только через агрегатор saby.ru, и они расходятся с уже
стоящими в карточке цифрами за 2022 год из независимого источника
(СПАРК-Интерфакс через саму статью) на другую методику подсчёта;
использовать без прямой проверки по ГИР БО или отчётности нельзя;
(2) точная дата подписания договора (известен только день публикации
пресс-релиза, 3 мая 2023 — уже стоит в `date`); (3) консультанты и
независимая оценка — ноль по всем источникам, включая пресс-релизы
Ростелекома и ЛУКОЙЛа; (4) утверждение TAdviser о том, что «Информ» —
головная ИТ-организация ЛУКОЙЛа с 2004 года — страница дала 404 при
прямом чтении, не подтверждено дословно.

Запуск: python3 pipeline/fix_rostelecom_inform_share.py
        python3 pipeline/fix_rostelecom_inform_share.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g200c00b5'

OLD_ECO_SHARE = '—'
NEW_ECO_SHARE = (
    '«Информ» — специализированный оператор группы «Ростелеком» для '
    'топливно-энергетического комплекса: оказывает телекоммуникационные '
    'и ИТ-услуги предприятиям в 53 регионах нефтедобычи и '
    'нефтепереработки. Компания основана в 1993 году и работает на '
    'рынке связи для ТЭК более 30 лет.'
)

OLD_SRC = [['Интерфакс', 'https://www.interfax.ru/amp/898857']]
NEW_SRC = OLD_SRC + [
    ['«Информ» (сайт компании)', 'https://rtk-inform.ru/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['share'] == OLD_ECO_SHARE
    assert deal['src'] == OLD_SRC

    print('=== eco.share: станет ===')
    print(NEW_ECO_SHARE)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['eco']['share'] = NEW_ECO_SHARE
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
