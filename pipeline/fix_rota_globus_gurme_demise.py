import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g92f41a2d'

OLD_ECO_CONTEXT = (
    'Сеть гастрономов премиум-класса «Глобус Гурмэ» существует с 2005 '
    'года. Её основали Лев Хасис — в 2006–2011 годах CEO X5 Group '
    '(«Пятёрочка», «Перекрёсток»), бывший зампред Сбербанка — и '
    'владелец ресторанного холдинга Novikov Group Аркадий Новиков. В '
    '2007 году Новиков продал свою долю структуре Льва Хасиса и '
    'Евгения Бернштама. В 2019 году Хасис вышел из бизнеса и передал '
    'пакет менеджменту, а годом позже «Глобус Гурмэ» перешёл под '
    'контроль Аркадия Новикова и основателя Pinskiy&Co Антона '
    'Пинского.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' Сеть де-факто прекратила существование к 2025 '
    'году. 22 июля 2023 года в ТЦ «Времена года» на Кутузовском '
    'проспекте прорвало трубу с горячей водой — погибли четыре '
    'сотрудницы гипермаркета «Глобус Гурмэ», пострадали около 70 '
    'человек. В августе 2024 года и «Синдика», и «Рота» вышли из '
    'капитала операционной компании сети, передав контроль Яне '
    'Черниковой (55%) и Илье Меерсону (45%); с начала 2024 года суд '
    'удовлетворил свыше 50 исков поставщиков на сумму более 70 млн ₽.'
)

OLD_SRC = [['Коммерсантъ', 'https://www.kommersant.ru/doc/5796344']]
NEW_SRC = OLD_SRC + [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6122580'],
    ['New Retail', 'https://new-retail.ru/novosti/retail/postavshchiki_globus_gurme_podali_isk_o_bankrotstve_byvshey_operatsionnoy_kompanii_seti/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
