# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g401b169a
(СДС-Холдинг продаёт 75% АО НПК «Алтаймаш» группе «Талтэк», статус
«Обсуждается» с 23 января 2024 года при собственном тексте карточки
«сделка либо закрыта, либо глобально согласована») — найден независимый
источник того же дня, использующий слово «закрыта», и косвенный сигнал
2025 года о продолжающейся реорганизации; прямого, более позднего
подтверждения не нашлось, `status` НЕ меняется.

Независимое подтверждение (того же дня, что и уже известный источник) —
проверено лично прямым WebFetch (РЖД-Партнер, 23.01.2024, 14:37):
«Статус сделки: Закрыта. Сделку подтвердили РЖД-Партнеру сразу несколько
независимых друг от друга участников рынка, в том числе и лицо, близкое
к АО «Алтайвагон»» — но там же прямо оговорено: «Согласно неофициальной
информации, новым владельцем стала группа компаний «ТАЛТЭК»» — то есть
и этот источник называет сведения неофициальными, официального
подтверждения сторон как не было, так и нет.

Смена гендиректора «Алтаймаша» — по данным агрегаторов ЕГРЮЛ (checko.ru,
upfox.ru, проверено лично прямым WebSearch/WebFetch, без прямой цитаты
СМИ): Александр Мирошник указан гендиректором в более раннем состоянии
реестра, Наталья Михель — с мая 2025 года. Само по себе не доказывает
смену КОНЕЧНОГО собственника (гендиректор мог смениться и без выхода
СДС), но добавлено как факт продолжающейся реорганизации управления.

НЕ ВКЛЮЧЕНО: финальная сумма сделки (публичной цифры по-прежнему нет,
только оценка 15-23 млрд руб.); приговор Михаилу Федяеву по делу
«Листвяжной» (25 марта 2025, три с половиной года условно) — ни один
источник не связывает его напрямую с этой сделкой, это отдельный
уголовный сюжет, не факт о карточке. `status` НЕ меняется: ни один из
найденных источников (в том числе новый) не даёт официального
подтверждения — только повторяющиеся неофициальные сведения и косвенный
кадровый сигнал. Записано в CLAUDE.md как известная проблема:
расхождение между текстом карточки и статусом держится больше двух лет
и заслуживает решения человека.

Запуск: python3 pipeline/fix_sds_altaimash_taltek_postdeal_signals.py
        python3 pipeline/fix_sds_altaimash_taltek_postdeal_signals.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g401b169a'

OLD_EXTRA = (
    'Сделка между СДС-Холдинг (продавец) и группой «Талтэк» (покупатель). '
    'Продается 75% в АО НПК «Алтаймаш», которая владеет 100% ООО '
    '«Алтайвагон». По информации источников, сделка либо закрыта, либо '
    'глобально согласована с обсуждением отдельных условий.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Независимый источник того же дня (РЖД-Партнер) также называет '
    'сделку закрытой со ссылкой на нескольких участников рынка, но '
    'прямо оговаривает, что сведения неофициальные. По данным '
    'агрегаторов ЕГРЮЛ, гендиректор «Алтаймаша» сменился на Наталью '
    'Михель к маю 2025 года — косвенный сигнал продолжающейся '
    'реорганизации управления, не прямое подтверждение смены '
    'собственника.'
)

NEW_SRC = [
    ['РЖД-Партнер', 'https://www.rzd-partner.ru/zhd-transport/news/altayvagon-prodan/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
