# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка g8348fea5 (ЗАО «Глобус»/
«Сибирский Молл»/«Новая высота»/ВЭБ.РФ): дельта-поиск нашёл судьбу актива
после сделки — владелец объявил о планах снести ТРЦ и построить на его
месте многофункциональный комплекс, а через несколько дней публично
опроверг слухи о сносе. Оба события — часть одной истории и не противоречат
друг другу по существу (сам он говорит, что его слова о студенческих
эскизных идеях исказили), но карточка не знала ни о планах, ни об
опровержении.

Проверка на 2026 год (в рамках того же дельта-поиска): признаков начала
стройки/сноса не нашлось — проект остаётся на стадии планирования из-за
договорных обязательств с действующими арендаторами (часть уже перенесена
в текст ниже — 2032 год).

Не через review.py: три разных источника на одно поле в одной правке.

Источники — читал напрямую (fetch_article_texts.py, все закэшированы):
Коммерсантъ-Сибирь (19.09.2024, doc/7167855), nsknews.info (интервью
Бойко), Mail/BFM.RU-Новосибирск (23.09.2024).
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g8348fea5'
OLD_EXTRA = (
    'Завершённая сделка на аукционе. ЗАО «Глобус» (владелец отеля Grand '
    'Autograph в Новосибирске) приобрело два объекта недвижимости: '
    'торгово-развлекательный комплекс «Сибирский Молл» (64 527 кв.м) и '
    'бизнес-центр «Новая высота» (33 620 кв.м). Продавец — госкорпорация '
    'ВЭБ.РФ.'
)
ADDITION = (
    'В сентябре 2024 года владелец ЗАО «Глобус» девелопер Александр Бойко '
    'заявил, что здание ТРЦ будет снесено, а на его месте построят '
    'многофункциональный центр: «Проект усложняется тем, что сначала мы '
    'должны построить новые площади, перенести все торговые точки туда, а '
    'потом сносить действующее здание». Площадь нового комплекса может '
    'составить более 700 тыс. кв. м, в том числе 250 тыс. кв. м жилья, '
    'проект рассчитан минимум на семь лет — большинство договоров с '
    'арендаторами не дают собственникам возможности ничего делать до 2032 '
    'года: «Думаю, что через три года будем выходить на площадку», — сказал '
    'Бойко. Через несколько дней он публично опроверг слухи о сносе, '
    'заявив об искажении своих слов в СМИ; поводом послужило подписание '
    'соглашения между TS Group и НГУАДИ о создании совместной лаборатории, '
    'и, по его словам, речь шла о перспективе, весьма отдалённой во '
    'времени. По состоянию на август 2026 года признаков начала стройки '
    'или сноса не появилось.'
)
NEW_EXTRA = OLD_EXTRA + ' ' + ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['extra'] == OLD_EXTRA, \
        f"extra: неожиданное значение {deal['extra']!r}"

    print(f"{CARD_ID} extra: += планы сноса и их опровержение (2024)")
    deal['extra'] = NEW_EXTRA

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
