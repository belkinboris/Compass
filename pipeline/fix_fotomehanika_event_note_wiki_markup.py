"""Приток 18.09.2026, часовой прогон 09:20 МСК: enrich.py дописал карточке
g9edfa8d8 («Корпорация робототехники»/«Фотомеханика») новый этап (закрытие
сделки) из RSS-выдержки TAdviser — и скопировал её ДОСЛОВНО, вместе со
служебной вики-разметкой самого TAdviser: заголовок статьи-инфобокса
(«История   2026: ...») и внутреннюю ссылку на карточку компании в формате
«Компания:Корпорация Робототехники (Корпорация роботов)» вместо обычного
имени. Предложение к тому же обрывается на полуслове («...новые модели
конвейерного, сортировочного...») — RSS отдал только начало абзаца.

Тот же класс дефекта, что уже чинился вчера для «Новомясово»
(fix_novomyasovo_event_note.py) и записан в CLAUDE.md («обратная кавычка в
комментарии» и «`\\x00`» — родня по духу: сырьё стороннего сайта протекает
на экран без очистки). Факты не меняются, только снимается служебная
разметка и обрывок последнего, неполного предложения.
"""
import json
import sys

DEALS_PATH = 'static/data/deals_promoted.json'

OLD_NOTE = (
    'История 2026: «Корпорация робототехники» купила «Фотомеханика» «Компания:Корпорация '
    'Робототехники (Корпорация роботов)» приобрела 51% доли в ГК «Фотомеханика», которая '
    'занимается производством складских роботов и систем автоматизации. В периметр сделки '
    'вошли…'
)

NEW_NOTE = (
    '«Корпорация Робототехники» приобрела 51% доли в ГК «Фотомеханика», которая занимается '
    'производством складских роботов и систем автоматизации. В периметр сделки вошли '
    'несколько компаний группы, формирующих единый производственный и R&D-контур. Об этом '
    'в «Корпорации Робототехники» сообщили TAdviser 16 сентября 2026 года.'
)


def main(write):
    data = json.load(open(DEALS_PATH, encoding='utf-8'))
    deals = data['deals'] if isinstance(data, dict) else data
    target = [d for d in deals if d.get('id') == 'g9edfa8d8']
    assert len(target) == 1, target
    card = target[0]
    events = card.get('events') or []
    hit = [e for e in events if e.get('source') and e['source'][1] == 'https://www.tadviser.ru/a/966930']
    assert len(hit) == 1, hit
    assert hit[0]['note'] == OLD_NOTE, repr(hit[0]['note'])
    hit[0]['note'] = NEW_NOTE

    if write:
        json.dump(data, open(DEALS_PATH, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
        print('Событие g9edfa8d8 очищено от вики-разметки TAdviser. ЗАПИСАНО.')
    else:
        print('Сухой прогон: очистил бы событие g9edfa8d8. Повторите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
