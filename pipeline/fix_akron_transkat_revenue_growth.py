import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g6daa6446'

NEW_EXTRA = (
    'Выручка завода выросла в разы: с ≈2,8 млрд ₽ (2024) до 10,9 млрд ₽ '
    '(2025, рост в 4 раза), прибыль за 2025 год — 43,5 млн ₽. Структура '
    'собственности не менялась.'
)

NEW_SRC = [
    ['Audit-it.ru', 'https://www.audit-it.ru/contragent/1027808750947_ao-transkat'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal.get('extra') in (None, '')

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
