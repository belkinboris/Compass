# -*- coding: utf-8 -*-
"""Четыре профиля-близнеца, найденные волной 1 самопроверки ИНН вебом
(28 августа 2026, `pipeline/fns_registry.py`) — тот же класс, что уже
чинили `merge_company_twins_fns_campaign*.py`.

В ОТЛИЧИЕ от прошлых партий, три из четырёх пар здесь — не «два профиля
одной и той же сделки», а ОДНО И ТО ЖЕ ЮРЛИЦО В РАЗНОЕ ВРЕМЯ (компанию
купили, переименовали, потом перепродали снова — тот же класс, что уже
задокументирован в CLAUDE.md для Yadro/переименований и для «Аскона»/
Ковров): проверено, что это НЕ случай «Ультиматек»/«Экспанта» (там
профили держали РАЗНЫЕ юрлица, дочка выделена позже) — здесь ИНН у обеих
карточек пары один и тот же, то есть юридическое лицо непрерывно то же
самое, просто сменило имя и/или собственника между сделками:

  * «Кама» (Атом) / АО «Кама» (проект электромобиля «Атом») — один и тот
    же разработчик, две РАЗНЫЕ сделки (ПСБ купил 16,9% в 2026 году,
    Росатом/Рэнера — раньше, в 2024).
  * «Башенная инфраструктурная компания» / БИК (bik) — один и тот же
    башенный оператор МТС, две сделки в разное время (обсуждение продажи
    в 2023 году, закрытая продажа доли фонду в 2026-м).
  * ООО «Эссити» / «ЭвоКом» — одно и то же производство (Zewa, Libresse):
    Игорь Шилов купил российский бизнес Essity в 2023 году, к 2025-му
    компанию переименовали в «ЭвоКом», и её перепродали Светогорскому
    ЦБК — тот же ИНН на обеих карточках.
  * «Рестораны KFC в России» (сеть AmRest, 215 точек) / ООО «Юнирест»
    (Rostic's) — AmRest продал сеть «Смарт сервис» в 2023 году; тот же
    операционный субъект под новым именем («Юнирест») позже купил ещё
    97 ресторанов KFC и продал долю инвестору.

ПРОВЕРЕНО ПЕРЕД СЛИЯНИЕМ: ни одна пара не описывает одну и ту же сделку
дважды (даты и контрагенты разные на каждой карточке), роли не
пересекаются — переносится роль, а не факты одной карточки поверх
другой.

НЕ ВКЛЮЧЕНА пятая находка той же волны — «Guess (российский бизнес)» /
«ГЕСС СИАЙЭС»: обе карточки резолвятся в один ИНН 7729482411, но это НЕ
простое переименование во времени — они стоят buyer/target ОДНОЙ И ТОЙ ЖЕ
сделки (g7b2a78bf), то есть, похоже, спутана роль (Guess как покупатель —
видимо, должен быть иностранным юрлицом без ИНН, а не тем же профилем,
что и цель). Механическое слияние здесь запрещено самим ассертом ниже
(«сделка ссылается на оба профиля сразу») и не должно быть — вопрос
оставлен человеку, см. журнал.

КАК ВЫБИРАЛСЯ ОСТАЮЩИЙСЯ ПРОФИЛЬ — тот же порядок: больше ролей — меньше
переписывать; при равенстве — тот, что уже несёт `confirmed` в реестре
ФНС (не терять готовую синхронизацию).

ЗАПИСИ РЕЕСТРА ФНС ПОСЛЕ СЛИЯНИЯ — снимаются ОТДЕЛЬНОЙ правкой того же
`pipeline/fns_registry.py` (не этим скриптом), как и в прошлый раз.

Запуск:
    python3 pipeline/merge_company_twins_fns_campaign_batch4.py            # сухой прогон
    python3 pipeline/merge_company_twins_fns_campaign_batch4.py --write    # записать
"""
import json
import sys

PATH = 'static/data/deals_promoted.json'
REFS = ('buyer', 'seller_id', 'target', 'asset_id')

# (остаётся, удаляется, ожидаемые имена, почему так)
MERGE = [
    ('g0993ebfa', 'kama_atom', ('АО «Кама» (проект электромобиля «Атом»)', '«Кама» (Атом)'),
     'ролей поровну (1/1); остаётся профиль с уже подтверждённым в реестре ФНС ИНН'),
    ('bik', 'g349e0a05', ('Башенная инфраструктурная компания (БИК)', 'ООО «Башенная инфраструктурная компания»'),
     'ролей поровну (1/1); остаётся профиль с уже подтверждённым в реестре ФНС ИНН'),
    ('g2cceb6b7', 'g153264e5', ('ЭвоКом', 'ООО «Эссити»'),
     'ролей поровну (1/1); остаётся профиль с уже подтверждённым в реестре ФНС ИНН (текущее имя компании)'),
    ('gf15f54d1', 'gb88bde7d', ('ООО «Юнирест» (Rostic\'s)', 'Рестораны KFC в России (сеть AmRest, 215 точек)'),
     'у «Юнирест» 2 роли против 1, и он уже несёт подтверждённый ИНН'),
]


def main(write):
    data = json.load(open(PATH, encoding='utf-8'))
    comps, deals, keys = data['companies'], data['deals'], data['match_keys']

    for keep, drop, names, _why in MERGE:
        assert keep in comps and drop in comps, 'профиля нет: %s / %s' % (keep, drop)
        assert (comps[keep]['name'], comps[drop]['name']) == names, \
            'имена изменились: %r против %r' % ((comps[keep]['name'], comps[drop]['name']), names)
        both = [d['id'] for d in deals
                if {d.get(f) for f in REFS} >= {keep, drop}]
        assert not both, 'сделка ссылается на оба профиля сразу: %s' % both

    moved = 0
    plan = []
    for keep, drop, names, why in MERGE:
        n = sum(1 for d in deals for f in REFS if d.get(f) == drop)
        aliases = [a for a in (keys.get(drop) or []) if a not in (keys.get(keep) or [])]
        plan.append((keep, drop, names, why, n, aliases))
        moved += n

    print('СЛИЯНИЕ ПРОФИЛЕЙ-БЛИЗНЕЦОВ (волна 1 самопроверки ИНН): %d пар, переезжает %d ролей\n'
          % (len(MERGE), moved))
    for keep, drop, names, why, n, aliases in plan:
        print('  «%s» <- «%s»' % (names[0], names[1]))
        print('      %s -> %s | ролей переезжает: %d | псевдонимов добавится: %d %s'
              % (drop, keep, n, len(aliases), aliases or ''))
        print('      почему: %s' % why)

    if not write:
        print('\nСухой прогон. Запись — с ключом --write.')
        return

    было = len(comps)
    for keep, drop, _names, _why, _n, aliases in plan:
        for d in deals:
            for f in REFS:
                if d.get(f) == drop:
                    d[f] = keep
        if aliases:
            keys[keep] = (keys.get(keep) or []) + aliases
        keys.pop(drop, None)
        comps.pop(drop)
        data.setdefault('merged_companies', {})[drop] = keep

    assert len(comps) == было - len(MERGE), 'удалилось не столько профилей, сколько пар'
    for d in deals:
        refs = [d.get(f) for f in REFS if d.get(f)]
        assert len(refs) == len(set(refs)), 'после слияния компания заняла две роли: %s' % d['id']
    with open(PATH, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('\nЗаписано. Профилей: %d (было %d). Переставлено ролей: %d.'
          % (len(comps), было, moved))


if __name__ == '__main__':
    main('--write' in sys.argv)
