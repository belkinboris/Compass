import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

RWB_ID = 'gmru-vtb-otkrytie-office-rwb'
RWB_OLD_CONTEXT = (
    'До интеграции «Открытия» в группу ВТБ здесь находился головной офис '
    'банка, а после покупки «Открытия» объект перешёл под контроль ВТБ. '
    'Весной появились сведения о переговорах RWB с ВТБ о покупке актива, '
    'но в самой RWB тогда настаивали, что речь идёт только о возможной '
    'аренде. 7 августа в ВТБ подтвердили, что дочерний БМ-банк завершил '
    'сделку по продаже.'
)
RWB_NEW_CONTEXT = (
    RWB_OLD_CONTEXT + ' Договор купли-продажи заключён в июне 2026 года, '
    'а собственник здания сменился 4 августа 2026 года; сумму сделки и '
    'покупателя стороны не раскрыли.'
)

BZ_ID = 'berizaryad'
BZ_OLD_RATIONALE = (
    'Интеграция в экосистему Яндекс Go; «Яндекс» планирует вложить ещё '
    '2 млрд ₽ и вырастить сеть с 40 до 100 тыс. станций к концу 2026 года.'
)
BZ_NEW_RATIONALE = (
    BZ_OLD_RATIONALE + ' По итогам первого года интеграции (март 2026) '
    'сеть выросла на 60% и превысила 60 тыс. станций, число пользователей '
    'увеличилось в 1,5 раза и превысило 7 млн человек; инвестиции с '
    'момента интеграции превысят 2 млрд ₽ к концу 2026 года.'
)

BZ_OLD_STRUCT = (
    'Приобретение 100% акций АО «Заряд!»: поэтапный выкуп акций pre-IPO '
    'инвесторов через брокера, выкуп у учредителей и финансовых '
    'инвесторов. Основатель Кирилл Кулаков стал советником по интеграции.'
)
BZ_NEW_STRUCT = (
    BZ_OLD_STRUCT + ' Операционное направление возглавил операционный '
    'директор «Яндекс Go» Артём Молчанов.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    rwb = by_id[RWB_ID]
    bz = by_id[BZ_ID]

    assert rwb['eco']['context'] == RWB_OLD_CONTEXT
    assert bz['eco']['rationale'] == BZ_OLD_RATIONALE
    assert bz['law']['struct'] == BZ_OLD_STRUCT

    print('=== gmru-vtb-otkrytie-office-rwb: eco.context ===')
    print(RWB_NEW_CONTEXT)
    print()
    print('=== berizaryad: eco.rationale ===')
    print(BZ_NEW_RATIONALE)
    print()
    print('=== berizaryad: law.struct ===')
    print(BZ_NEW_STRUCT)

    if write:
        rwb['eco']['context'] = RWB_NEW_CONTEXT
        bz['eco']['rationale'] = BZ_NEW_RATIONALE
        bz['law']['struct'] = BZ_NEW_STRUCT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
