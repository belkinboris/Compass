import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g36386bcf'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Не состоялась'

OLD_ECO_CONTEXT = '—'
NEW_ECO_CONTEXT = (
    'Эта конкретная схема (продажа 51% инвесторам за $4 млрд, Yandex '
    'N.V. сохраняет 49% и получает лицензии на 4 зарубежных проекта '
    'плюс выплату $300-400 млн) не реализовалась: в итоге Yandex N.V. '
    'полностью вышла из капитала российского бизнеса (0%, а не 49%), '
    'сохранив прямое владение теми же четырьмя направлениями (Nebius, '
    'Toloka, Avride, TripleTen) уже не как миноритарий, а без всякой '
    'доли в российской компании. Сделка закрылась в июле 2024 года за '
    '475 млрд ₽ консорциумом «Консорциум.Первый» — отдельная карточка '
    '«Приобретение консорциумом инвесторов (ЗПИФ «Консорциум.Первый»)…».'
)

NEW_SRC = [
    ['Ведомости', 'https://www.vedomosti.ru/business/articles/2024/02/05/1018392-yandex-nv-zaklyuchila'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS
    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    existing_urls = {s[1] for s in deal['src']}
    add_src = [s for s in NEW_SRC if s[1] not in existing_urls]
    new_src = deal['src'] + add_src

    print('=== status: станет ===')
    print(NEW_STATUS)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    if add_src:
        print('\n=== src: добавится ===')
        for s in add_src:
            print(s)

    if write:
        deal['status'] = NEW_STATUS
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
