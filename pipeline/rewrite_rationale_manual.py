# Один и тот же текст лежит в двух полях: `eco.rationale` («Цель сделки» на
# линзе «Экономист») и `extra` («Дополнительная информация» на «Обзоре»).
# У всех 42 ручных карточек это была дословная копия, поэтому правку применяем
# к обоим — иначе исправленная «Цель сделки» соседствовала бы на той же
# странице с неисправленным пересказом статьи.
# Пустое значение у полей разное: rationale показывается прочерком, а пустой
# extra просто не рендерится, поэтому там пустая строка.
FIELDS = (
    ('eco.rationale', lambda d: (d.get('eco') or {}).get('rationale') or '',
     lambda d, v: d['eco'].__setitem__('rationale', '—' if v is None else v)),
    ('extra', lambda d: d.get('extra') or '',
     lambda d, v: d.__setitem__('extra', '' if v is None else v)),
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by = {d['id']: d for d in data['deals']}

    changes, errors, skipped = [], [], []

    def each(did, old_prefix):
        """Поля карточки, которые начинаются с ожидаемого исходного текста."""
        d = by.get(did)
        if d is None:
            errors.append(f'{did}: сделка не найдена')
            return
        hit = False
        for name, get, set_ in FIELDS:
            if get(d).startswith(old_prefix):
                hit = True
                yield d, name, get, set_
        if not hit:
            # Не ошибка, а норма при повторном прогоне: правка уже применена и
            # исходного зачина в базе больше нет. Блокировать запись из-за этого
            # нельзя — иначе в таблицу нельзя было бы дописать новую карточку.
            # Но в отчёт пропуск попадает: так видно и опечатку в зачине.
            skipped.append(f'{did}: исходного текста нет ни в одном поле '
                           f'(ожидали {old_prefix[:52]!r})')

    for did, (old_head, new_head) in HEAD.items():
        for d, name, get, set_ in each(did, old_head):
            cur = get(d)
            changes.append((did, name, 'зачин', cur,
                            (new_head + cur[len(old_head):]).strip(), set_))

    for did, (old_prefix, new) in FULL.items():
        for d, name, get, set_ in each(did, old_prefix):
            changes.append((did, name, 'целиком', get(d), new, set_))

    for did, old_prefix in CLEAR.items():
        for d, name, get, set_ in each(did, old_prefix):
            cur = get(d)
            # страховка: чистим поле только когда сумма действительно есть
            # отдельно — иначе вместе с шумом уедет единственное число
            if 'Сумма:' in cur and not ((d.get('eco') or {}).get('sum') or '').strip():
                errors.append(f'{did}/{name}: в тексте есть сумма, а eco.sum пуст — не чищу')
                continue
            changes.append((did, name, 'очистка', cur, None, set_))

    if errors:
        print('ОШИБКИ:')
        for e in errors:
            print('  ' + e)
        print()
    if skipped:
        print(f'пропущено (правка уже применена или текст изменился): {len(skipped)}')
        for e in skipped:
            print('  ' + e)
        print()

    kinds = collections.Counter(c[2] for c in changes)
    fields = collections.Counter(c[1] for c in changes)
    print(f'полей к правке: {len(changes)}  по видам: {dict(kinds)}  по полям: {dict(fields)}\n')
    for did, name, kind, old, new, _ in changes:
        print(f'### {did} [{name} / {kind}]')
        print(f'  было:  {old[:150]}')
        print(f'  стало: {"(поле очищено)" if new is None else new[:150]}')

    if write:
        if errors:
            print('\nЕсть ошибки — записывать нельзя, поправьте таблицу.')
            return 1
        for did, _, _, _, new, set_ in changes:
            set_(by[did], new)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=1, ensure_ascii=False)
        print('\nЗАПИСАНО в', PATH)
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
