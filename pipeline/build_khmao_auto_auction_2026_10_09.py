# -*- coding: utf-8 -*-
"""Приток 11:20 МСК 9 октября 2026: в ХМАО провалился аукцион по продаже
группы из 8 автосалонных ООО (Сургут, Нижневартовск: «ЗапСибАвто»,
«Автоуниверсал», «Автоуниверсал-Элит», «Автоуниверсал-Моторс»,
«Автоуниверсал-Статус», «Автоуниверсал-Премиум», «АвтоМакс-Сервис»,
«Юнимоторс») — заявок не поступило. Активы ранее связаны с Алексеем
Бобровым (совладелец «Корпорации СТС»), сейчас у Росимущества — тот же
класс сюжета, что и провал/повторные торги по агрохолдингу (g5b4e85aa),
но другой лот той же национализации. Ворота не распознали сделку
автоматически («не установлен предмет сделки»). Собрано вручную тем же
путём, что build_tc_skazka_2026_10_09.py.

Запуск: python3 pipeline/build_khmao_auto_auction_2026_10_09.py [--write]
"""
import json
import sys

sys.path.insert(0, 'pipeline/ingest')
import promote  # noqa: E402

PENDING = 'static/data/pending.json'
URL = 'https://ura.news/news/1053134766'

DRAFT = {
    'draft_id': 'd-khmao-auto-2026-10-09',
    'title': 'Аукцион по продаже бывших автосалонов совладельца «Корпорации СТС» в ХМАО не состоялся',
    'date': '2026-10-09',
    'src': [['URA.RU', URL]],
    'sum': '868 млн ₽',
    'type': 'Продажа с торгов',
    'status': 'Не состоялась',
    'events': [
        {'kind': 'cancelled', 'date': '2026-10-09', 'title': 'Аукцион признан несостоявшимся',
         'note': 'В Югре не состоялись торги по продаже группы из восьми автомобильных компаний '
                 '(Сургут, Нижневартовск) — заявок на аукцион не поступило, следует из протокола '
                 'на портале ГИС «Торги».',
         'source': ['URA.RU', URL]},
    ],
    'buyer_name': None,
    'asset': '100% долей в восьми автосалонных компаниях в Сургуте и Нижневартовске',
    'seller': 'Росимущество',
    'parsed_parties': {'buyer': None,
                        'asset': '100% долей в восьми автосалонных компаниях в Сургуте и Нижневартовске',
                        'seller': 'Росимущество'},
    'ind': 'Авто',
    'needs_review': True,
}


def main(write):
    pending = json.load(open(PENDING, encoding='utf-8'))
    existing = {c['id'] for c in pending['cards']}
    deal_id = promote.new_id(existing)
    card = promote.to_card(DRAFT, deal_id)
    card['eco']['sum'] = (
        'Начальная цена лота — 868 млн ₽, задаток для участия — свыше 173,5 млн ₽.'
    )
    card['eco']['share'] = (
        '100% уставного капитала восьми ООО: «ЗапСибАвто», «Автоуниверсал», '
        '«Автоуниверсал-Элит», «Автоуниверсал-Моторс», «Автоуниверсал-Статус», '
        '«Автоуниверсал-Премиум», «АвтоМакс-Сервис», «Юнимоторс».'
    )
    card['eco']['context'] = (
        'Автосалоны ранее были связаны с Алексеем Бобровым, совладельцем «Корпорации СТС»; '
        'сейчас активы принадлежат Росимуществу. Та же национализация, что и у '
        'агрохолдинга Боброва и Бикова (g5b4e85aa), — другой лот того же дела.'
    )
    card['themes'] = ['Национализация / иск Генпрокуратуры', 'Продажа с торгов']
    card['pending_since'] = '2026-10-09T11:20:00+00:00'
    if not write:
        print('Сухой прогон. Карточка была бы: %s' % deal_id)
        print(json.dumps(card, ensure_ascii=False, indent=2))
        return
    pending['cards'].append(card)
    with open(PENDING, 'w', encoding='utf-8') as f:
        json.dump(pending, f, ensure_ascii=False, indent=1)
        f.write('\n')
    print('Записано: %s добавлена в pending.json' % deal_id)


if __name__ == '__main__':
    main('--write' in sys.argv)
