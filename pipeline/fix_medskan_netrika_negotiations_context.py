# -*- coding: utf-8 -*-
"""Месячная очередь, карточка g630c3361 (ГК «Медскан»/«Нетрика Медицина»,
статус «Обсуждается»): проверка статуса — обязательный шаг для
незакрытых сделок. Дельта-поиск подтвердил, что переговоры продолжаются
спустя четыре месяца после статьи, на которой держится карточка:
член совета директоров «Медскана» лично сказал в интервью 30.01.2026,
что стороны «ведём переговоры о вхождении компании в наш контур».
Более поздних публикаций (после января 2026) о закрытии, срыве или
смене собственника «Нетрики Медицина» не нашлось на 24.08.2026 — статус
«Обсуждается» остаётся верным, менять его нет оснований.

Отдельно — мотив сделки со стороны «Медскана»: компания готовится к IPO
(осень 2026 года, по заявлению её же финансового директора) — карточка
уже несёт тему «IPO / SPO», но не саму цитату о ходе подготовки.

Источники — читал напрямую (fetch_article_texts.py, закэшированы):
https://www.vedomosti.ru/health/medicine_future/characters/2026/01/30/1173011-meditsinskogo-rinka
https://www.kommersant.ru/doc/8549598

Запуск: python3 pipeline/fix_medskan_netrika_negotiations_context.py [--write]
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g630c3361'

OLD_CONTEXT = (
    'Нетрика Медицина» образована в 2006 году. Основатели компании — '
    'Артем Мошков и Алексей Ильин. Им принадлежит 37,8% и 7,2% '
    'соответственно. Еще 50% у ООО «ТМ Цифровые решения», 5% — у '
    'управляющего партнера Дениса Чумакова.'
)
CONTEXT_ADDITION = (
    'Переговоры продолжались как минимум до конца января 2026 года: '
    '«Сейчас мы ведем переговоры о вхождении компании в наш контур, что '
    'позволит более эффективно реализовать планы по запуску проекта», — '
    'говорил 30 января 2026 года член совета директоров «Медскана» '
    'Евгений Абакумов. Мотив со стороны «Медскана» — подготовка к IPO: '
    'финансовый директор компании Илья Никольский заявлял, что компания '
    '«целится в осеннее окно» и на 80% готова организационно, с '
    'размещением через механизм cash-in на сентябрь 2026 года.'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + CONTEXT_ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} eco.context: += подтверждение продолжающихся "
          f"переговоров (30.01.2026) и мотив IPO «Медскана» — статус "
          f"«Обсуждается» остаётся верным")
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
