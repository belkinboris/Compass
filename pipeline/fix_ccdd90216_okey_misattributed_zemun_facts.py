# -*- coding: utf-8 -*-
"""Карточка `ccdd90216` («Менеджмент выкупает часть бизнеса гипермаркетов
«О'Кей» у O'Key Group») несла факты ДВУХ ДРУГИХ, более поздних сделок той же
саги, приписанные ей ошибочно партией `batch_e_rev01.py` (запись «ccdd90216»
в докстроке той партии).

Найдено 11 сентября 2026 при дочитывании раздела «Известные проблемы»
CLAUDE.md: правка `status` из партии 3 (см. `fix_known_issues_2026_09_11_
batch3.py`, пункт 2) вернула статус на «Обсуждается», но не тронула
`law.appr`/`eco.context`/`src` — а тест `test_review_table_is_applied_and_
not_pending` упал именно на записи `status`, потому что она в таблице FIXES
утверждает «Закрыта» с цитатой из статьи Эксперта о ЗАВЕРШЕНИИ сделки.

Разбор показал: цитата Эксперта («O'Key Group завершила сделку... менедж-
менту») и цитата про ФАС/«Земун» («14 октября ФАС... согласовала... покупку
ООО «Земун» 99%... «РБФ Ритейл»») — это факты ДВУХ ДРУГИХ карточек той же
саги, а не этой:
  - закрытие сделки (Эксперт, «завершила») датировано 25 ноября 2025 года —
    это событие уже описано отдельной карточкой `g31136d69` (дата 2025-11-25,
    статус «Закрыта», те же стороны);
  - согласование ФАС покупки «Земуном» 99% «РБФ Ритейл» — это СОВСЕМ ДРУГАЯ
    сделка (Земун входит в капитал РБФ Ритейл, а не РБФ Ритейл покупает
    бизнес у O'Key Group), уже верно описанная карточкой `g74fd5cdb`
    (buyer=ga64461ca «Земун», тот же текст согласования дословно).
  - `eco.context` того же прогона («компания получит 99,56%... установит
    косвенный контроль») — по собственной пометке `why` записи описывает
    именно косвенный контроль ЧЕРЕЗ «Земун» и «РБФ Ритейл», то есть тоже
    факт чужой сделки, а не условия прямой продажи бизнеса менеджменту.

Собственное поле `law.adv` карточки `ccdd90216` всё это время честно несло
«статус: подписан основной договор (сделка не закрыта)» — внутреннее
противоречие с `status`/`law.appr`/`eco.context`, которое и выдало ошибку.

Правка: `law.appr` и `eco.context` возвращены в пустое состояние (факт не
теряется — он уже верно стоит на `g74fd5cdb`), источник Эксперта (о
завершении сделки, событие которой описывает `g31136d69`) убран из `src`.
Запись `status` уже поправлена прошлым скриптом. Соответствующие четыре
записи таблицы FIXES в `batch_e_rev01.py` сняты — оставлять их означало бы
утверждать, что эта карточка подтверждает факты, которых в её собственных
источниках нет.

Запуск: сухой прогон без аргументов, запись — `--write`.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "static" / "data" / "deals_promoted.json"

LAW_APPR = ("14 октября ФАС России согласовала покупку ООО «Земун» 99% "
            "уставного капитала холдинговой компании ООО «РБФ Ритейл», "
            "которая принадлежит менеджерам сети гипермаркетов «О’Кей».")
ECO_CONTEXT = ("Покупатель получит 99,56% уставного капитала холдинга "
               "ООО «О’кей» и после закрытия сделки будет косвенно "
               "контролировать всю сеть розничных гипермаркетов.")
EXPERT_SRC = ["Эксперт", "https://expert.ru/news/vladelets-seti-gipermarketov-"
              "o-key-prodal-biznes-menedzhmentu/"]


def main(write=False):
    data = json.loads(DATA.read_text(encoding="utf-8"))
    deals = {d["id"]: d for d in data["deals"]}
    d = deals["ccdd90216"]

    assert d.get("status") == "Обсуждается", "ожидался статус, уже исправленный batch3"
    assert (d.get("law") or {}).get("appr") == LAW_APPR, "law.appr не совпадает с ожидаемым"
    assert (d.get("eco") or {}).get("context") == ECO_CONTEXT, "eco.context не совпадает с ожидаемым"
    assert EXPERT_SRC in (d.get("src") or []), "источник Эксперта не найден в src"

    d["law"]["appr"] = ""
    d["eco"]["context"] = ""
    d["src"] = [s for s in d["src"] if s != EXPERT_SRC]

    print("ccdd90216: law.appr и eco.context очищены (факты чужих сделок — "
          "Земун/РБФ Ритейл и закрытие 2025 года), источник Эксперта снят "
          "из src (его факт о завершении — событие g31136d69, не этой карточки)")

    if write:
        DATA.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        print("Записано.")
    else:
        print("Сухой прогон. --write для записи.")


if __name__ == "__main__":
    main("--write" in sys.argv)
