# -*- coding: utf-8 -*-
"""Описания профилей, написанные «после сделки …», — про событие, а не про компанию.

Владелец 2 сентября 2026 на посте о продаже госпакета Шереметьево: в строке
«Предмет» стояло «Крупнейший аэропорт России; после сделки контролирует также
активы аэропорта Домодедово» — и «после сделки» читалось как «после продажи
госпакета», хотя фраза была написана в профиле после ДРУГОЙ сделки (покупки
Домодедово на аукционе в январе 2026). Описание профиля попадает в посты и на
страницы про ЛЮБУЮ сделку компании, поэтому в нём нельзя ссылаться на «сделку»
без имени — только на факт с датой. Замер по всем профилям: таких три (ещё два
профиля Expobank/Adriatic говорят «после продажи латвийского и чешского
банков» — это указание времени, не проблема). Урок CLAUDE.md «Описание,
которое описывает событие, — не описание компании» — тот же класс.

Запуск:
    python3 pipeline/fix_event_relative_company_descriptions.py          # сухой прогон
    python3 pipeline/fix_event_relative_company_descriptions.py --write
"""
import json
import sys

PATH = 'static/data/deals_promoted.json'

FIXES = {
    'sheremetyevo': (
        'Крупнейший аэропорт России; после сделки контролирует также активы аэропорта Домодедово.',
        'Крупнейший аэропорт России; с 2026 года контролирует также аэропорт Домодедово.',
    ),
    'citibank': (
        'Бывшая российская «дочка» Citigroup, крупнейший кастодиан в России. После сделки переименован в АО «РенКап Банк».',
        'Бывшая российская «дочка» Citigroup, крупнейший кастодиан в России; с 2026 года — АО «РенКап Банк».',
    ),
    'hugoboss': (
        'Российская «дочка» немецкого производителя одежды премиум-сегмента. 19 магазинов на конец 2022 года. После сделки юрлицо переименовано в «Линк Фэшн».',
        'Российская «дочка» немецкого производителя одежды премиум-сегмента; 19 магазинов на конец 2022 года. Юрлицо переименовано в «Линк Фэшн».',
    ),
}


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    for cid, (old, new) in FIXES.items():
        co = data['companies'][cid]
        assert co.get('desc') == old, (cid, co.get('desc'))
        co['desc'] = new
        print(f'{cid}: {co["name"]}\n  - {old}\n  + {new}')
    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=1, ensure_ascii=False)
        print('ЗАПИСАНО в', PATH)


if __name__ == '__main__':
    main(write='--write' in sys.argv)
