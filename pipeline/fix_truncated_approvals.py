def norm(s):
    return re.sub(r'\s+', ' ', str(s or '')).strip()


def looks_broken(value):
    """Тот же признак обрыва, по которому собрана таблица."""
    v = norm(value)
    return bool(v) and (bool(TRAIL.search(v)) or bool(LOWER_START.match(v)))


def sources(deal):
    eco = deal.get('eco') or {}
    return [norm(deal.get('law', {}).get('appr')), norm(deal.get('extra')),
            norm(eco.get('rationale')), norm(eco.get('context'))]


def main(write):
    data = json.load(open(PATH, encoding='utf-8'))
    deals = data['deals']
    by_id = {d['id']: d for d in deals}

    done = sum(1 for i, t in TABLE.items()
               if i in by_id and norm((by_id[i].get('law') or {}).get('appr')) == norm(t))
    if done == len(TABLE):
        print('Уже применено: все %d значений в исправленном виде.' % done)
        return
    assert done == 0, 'скрипт применён частично (%d из %d)' % (done, len(TABLE))

    planned = []
    for deal_id, text in TABLE.items():
        deal = by_id.get(deal_id)
        assert deal is not None, 'нет сделки %s' % deal_id
        law = deal.setdefault('law', {})
        cur = norm(law.get('appr'))
        assert looks_broken(cur), '%s: значение не выглядит обрывком — %r' % (deal_id, cur[:80])
        body = norm(text).rstrip('.').lower()
        assert any(body in s.lower() for s in sources(deal) if s), \
            '%s: текст не является куском исходного' % deal_id
        assert not TRAIL.search(text) and not LOWER_START.match(text), \
            '%s: результат сам выглядит обрывком' % deal_id
        planned.append((deal_id, cur, text, law))

    print('Значений к починке: %d' % len(planned))
    for deal_id, cur, text, _ in planned:
        print('  %s\n    было:  %s\n    стало: %s' % (deal_id, cur[:100], text[:100]))

    if not write:
        print('\nСухой прогон. Запись — с ключом --write.')
        return

    for _, _, text, law in planned:
        law['appr'] = text
    with open(PATH, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    left = [d['id'] for d in deals if looks_broken((d.get('law') or {}).get('appr'))]
    print('\nЗаписано. Обрывков в «Согласованиях» осталось: %d' % len(left))


if __name__ == '__main__':
    main('--write' in sys.argv)
