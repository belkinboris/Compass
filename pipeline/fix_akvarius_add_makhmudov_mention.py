# -*- coding: utf-8 -*-
"""Заметка 512 (консоль, 4 сентября 2026): «Если закрыта сделка с S8,
то карточку с S8 дополнить информацией, что шли переговоры с другим
таким-то покупателем», отвечая на карточку `g26608f96» (Искандер
Махмудов покупает контроль в ГК «Аквариус»).

`g139db8c2» (S8 Capital/«МТ-Интеграция», статус «Закрыта») уже
существует и не упоминает Махмудова. Условие выполнено (сделка с S8
закрыта) — дополняю.

Запуск: python3 pipeline/fix_akvarius_add_makhmudov_mention.py [--write]
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g139db8c2'
OLD_CONTEXT = (
    'Структура владения и руководство АО «Группа Аквариус» скрыты в '
    'ЕГРЮЛ. В ноябре 2024 года «Сберинвест», входящий в блок '
    'корпоративно-инвестиционного бизнеса Сбербанка, получил 12% в '
    'капитале «Аквариуса», а затем приобрёл ещё 12%, доведя пакет до '
    '24%. До сделки крупные доли «Аквариуса», помимо «Сберинвеста», '
    'принадлежали Алексею Калинину и президенту группы Владимиру '
    'Степанову через АО «А-Холдинг». 22 августа 2025 года, на следующий '
    'день после публикации о сделке, ГК «МТ-Интеграция» выпустила '
    'пресс-релиз, в котором назвала сведения о своём входе в состав '
    'акционеров «Аквариуса» не соответствующими действительности. По '
    'состоянию на 02.10.2025 обе компании по-прежнему назывались '
    'совладельцами 79%, а ключевые посты в «Аквариусе» заняли '
    'представители S8 Capital; опровержение «МТ-Интеграции» с тех пор '
    'не подтверждено и не опровергнуто. После сделки доля «Сберинвеста» '
    'указывается как 21%, расхождение с 24% до сделки не объяснено. В '
    'сентябре 2025 года S8 Capital выделил «Аквариусу» экстренные 5 '
    'млрд ₽ на зарплаты и урегулирование судебных исков; по оценке '
    'экспертов, этой суммы хватит только до конца 2025 года.'
)
ADDITION = (
    ' До того, как о сделке с S8 Capital стало известно, CNews называл '
    'потенциальным покупателем контроля в «Аквариусе» структуры '
    'Искандера Владимировича Махмудова (отдельная карточка g26608f96) '
    '— эта версия впоследствии не подтвердилась, реальным покупателем '
    'выступил S8 Capital.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {c['id']: c for c in data['deals']}
    card = by_id[CARD_ID]
    assert card['eco']['context'] == OLD_CONTEXT, card['eco']['context']
    card['eco']['context'] = OLD_CONTEXT + ADDITION
    print(f'{CARD_ID}.eco.context: добавлено упоминание Махмудова как несостоявшейся версии')

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
            f.write('\n')
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
