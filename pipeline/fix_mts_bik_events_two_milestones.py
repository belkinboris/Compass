# -*- coding: utf-8 -*-
"""Заметка 469 (консоль, 4 сентября 2026): «Давай сделаем текущую
карточку с обсуждением как первую веху, а новую инфу как основную
последнюю веху, но можно дописать в первой вехе оговорку о том, что мы
не уверены, что именно в продолжении этих обсуждений была закрыта
сделка», отвечая на карточку `gf1608a6f» (МТС/БИК).

`eco.context` карточки уже нёс оба факта прозой (первоначальные
переговоры о продаже консорциуму 2021–2022 годов и реальную сделку —
26 июня 2026 года МТС продала 49,9% долей БИК фонду «Инвестиции 18» за
21,7 млрд ₽), но текстом одним абзацем, без структуры «Ход сделки».
Этот скрипт добавляет `events[]` — список поле, недоступное для
`review.py`/FIXES — с двумя записями:

1. Первая веха — переговоры 2021–2022 годов с внешним консорциумом
   (`kind='negotiations'`), с честной оговоркой, что ни один источник
   не подтвердил, что именно эти переговоры привели к сделке 2026 года.
2. Вторая, основная веха — закрытая продажа 49,9% долей БИК фонду
   «Инвестиции 18» 26 июня 2026 года (`kind='closed'`).

Статус карточки НЕ меняется (остаётся «Обсуждается» — первоначальный,
более широкий сюжет о продаже внешнему консорциуму формально не
подтверждён и не опровергнут; закрытая продажа 49,9% фонду — отдельный,
подтверждённый факт, для него достаточно события `kind='closed'`, без
`--milestone`/канала: факт уже был в базе с 3 сентября 2026, не новый
для этого прогона).

Запуск: python3 pipeline/fix_mts_bik_events_two_milestones.py [--write]
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gf1608a6f'

NEW_EVENTS = [
    {
        'kind': 'negotiations',
        'date': '2022',
        'title': 'Переговоры о продаже консорциуму',
        'note': ('МТС выделила башенные активы в ООО «Башенная '
                 'инфраструктурная компания» в сентябре 2021 года и '
                 'планировала продать актив внешнему консорциуму '
                 'финансовых инвесторов в первой половине 2022 года, но '
                 'из-за неопределённости на рынке переговоры отложили. Ни '
                 'один источник не подтвердил, что именно эти переговоры '
                 'привели к сделке 2026 года, описанной ниже, — это '
                 'разные по составу и структуре сделки.'),
        'source': ['Коммерсантъ', 'https://www.kommersant.ru/doc/6312433'],
    },
    {
        'kind': 'closed',
        'date': '2026-06-26',
        'title': 'Продажа 49,9% долей БИК фонду «Инвестиции 18»',
        'note': ('26 июня 2026 года МТС продала 49,9% долей БИК закрытому '
                 'паевому инвестфонду «Инвестиции 18» за 21,7 млрд ₽, '
                 'сохранив 50,1% и совместный контроль; покупатель принял '
                 'на себя часть долга БИК (всего около 80 млрд ₽), а МТС '
                 'получила опцион на обратный выкуп доли. Управляющая '
                 'фондом компания — бывшая структура самой МТС/АФК '
                 '«Система».'),
        'source': ['ComNews',
                   'https://www.comnews.ru/content/246037/2026-06-26/2026-w26/1010/mts-perelozhila-bashni-karmana-karman'],
    },
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {c['id']: c for c in data['deals']}
    card = by_id[CARD_ID]
    assert not card.get('events'), card.get('events')

    card['events'] = NEW_EVENTS
    print(f'{CARD_ID}: добавлены две записи events[] (переговоры 2022 -> продажа 26.06.2026)')

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
            f.write('\n')
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
