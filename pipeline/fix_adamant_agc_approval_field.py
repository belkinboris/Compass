# -*- coding: utf-8 -*-
"""Исправление находки pytest (test_approval_is_not_left_in_prose) сразу
после записи `pipeline/fix_adamant_agc_glass_aig_rebrand.py` в том же
заходе — карточка gcf0f7334 (холдинг «Адамант» купил два стекольных
завода AGC). Факт согласования ФАС остался в прозе `eco.context»
одновременно с пустым (заглушка «Публично не сообщалось») `law.appr` —
ровно тот класс дефекта, что уже описан в CLAUDE.md («признак `упомянут
госорган + слово разрешения`... её место — law.appr, а не соседнее
поле»). Правило шире одной карточки: если фраза называет госорган и
решение, её место — `law.appr`.

`law.appr` (заполнено) — перенесён факт согласования ФАС.
`eco.context` (сокращено) — из последнего предложения убрана часть про
согласование ФАС; факт о смене держателя долей остался.

Запуск: python3 pipeline/fix_adamant_agc_approval_field.py
        python3 pipeline/fix_adamant_agc_approval_field.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gcf0f7334'

OLD_CONTEXT = (
    'Петербургский холдинг «Адамант» владеет 50 предприятиями и 22 '
    'торговыми центрами. Основной бенефициар — Игорь Лейтис. Оба '
    'завода объединены под зонтичным брендом AIG (Argentum Innovation '
    'Group). В сентябре 2025 года на Клинском заводе запущена новая '
    'линия «Клин-1»: инвестиции 8,5 млрд ₽, мощность до 600 тонн '
    'стекла в сутки, создано 87 рабочих мест — заявленный план всей '
    'модернизации превышает 13 млрд ₽ с завершением в 2026 году. В '
    '2025 году доли обоих заводов консолидированы на новом держателе '
    'внутри той же структуры — АО «Управляющая компания» (Санкт-'
    'Петербург), сделка одобрена ФАС в апреле 2025 года.'
)
NEW_CONTEXT = (
    'Петербургский холдинг «Адамант» владеет 50 предприятиями и 22 '
    'торговыми центрами. Основной бенефициар — Игорь Лейтис. Оба '
    'завода объединены под зонтичным брендом AIG (Argentum Innovation '
    'Group). В сентябре 2025 года на Клинском заводе запущена новая '
    'линия «Клин-1»: инвестиции 8,5 млрд ₽, мощность до 600 тонн '
    'стекла в сутки, создано 87 рабочих мест — заявленный план всей '
    'модернизации превышает 13 млрд ₽ с завершением в 2026 году. В '
    '2025 году доли обоих заводов консолидированы на новом держателе '
    'внутри той же структуры — АО «Управляющая компания» (Санкт-'
    'Петербург).'
)

OLD_APPR = 'Публично не сообщалось'
NEW_APPR = (
    'В апреле 2025 года Федеральная антимонопольная служба '
    'удовлетворила ходатайства АО «Управляющая компания» о покупке '
    'долей обоих заводов у структур той же группы.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    assert deal['law']['appr'] == OLD_APPR, deal['law']['appr']

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== law.appr: станет ===')
    print(NEW_APPR)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['law']['appr'] = NEW_APPR
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
