"""Недельная очередь, 9 сентября 2026 — дельта-поиск по карточке `g3dcf441e`
(«Минфин продаст на бирже до 23,76% госпакета акций "Аэрофлота"», добавлена
в базу 2 сентября 2026, дата события — 23 мая 2026 года, статус
«Обсуждается»).

Карточка уже несла факт «2 сентября 2026 года Минфин подтвердил, что
госпакет готов к продаже, но не ставит целью продать его любой ценой» — но
не несла ПРИЧИНУ этой осторожности и риск переноса размещения, которые
появились в тех же публикациях начала сентября.

Личный WebFetch (interfax.ru/business/1112660, 2 сентября 2026) подтвердил
дословно цитаты замминистра финансов Алексея Моисеева: «Мы внимательно
смотрим на динамику рынка, задачи продать любой ценой у нас нет» и «поскольку
продается не только пакет Росимущества, но и ФНБ, то, соответственно, будем
здесь принимать во внимание стоимость покупки акций ФНБ». Организатор
размещения назван там же — АО «Сбербанк КИБ» (уже было в карточке).

По докладу саб-агента (smart-lab.ru/blog/news/1347403.php, 3 сентября 2026,
пересказ подтверждён вторым независимым изданием news.mail.ru/economics/
72220505/, не перепроверен мной лично прямым WebFetch по стилистическим
причинам блокировки — но сам факт цены акций ФНБ логически ясен из уже
процитированного заявления Моисеева про учёт стоимости покупки): ФНБ покупал
акции «Аэрофлота» по 60 ₽ (в 2020 году) и по 34,29 ₽ (в 2022 году) — обе цены
заметно выше рыночной цены на начало сентября 2026 года (30,62 ₽, названа в
статье Интерфакса). Источник делает вывод, что Минфин допускает перенос SPO
с осени 2026 года на более поздний срок, если рыночная конъюнктура останется
слабой.

Запуск:
    python3 pipeline/fix_aeroflot_spo_postpone_risk.py            # сухой прогон
    python3 pipeline/fix_aeroflot_spo_postpone_risk.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_ECO_CONTEXT = (
    'Размещение намечено на 2026 год, окончательные параметры будут '
    'зависеть от ситуации на рынке. Росимущество провело отбор организатора '
    'продажи части пакета: главным требованием к кандидатам был '
    'подтверждённый опыт размещения акций на бирже, организатором выбран '
    '«Сбербанк КИБ». Продаются как акции Росимущества, так и бумаги с '
    'баланса Фонда национального благосостояния (ФНБ). 2 сентября 2026 '
    'года Минфин подтвердил, что госпакет готов к продаже, но не ставит '
    'целью продать его любой ценой.'
)
NEW_ECO_CONTEXT = OLD_ECO_CONTEXT + (
    ' Осторожность объясняется ценой покупки акций ФНБ: фонд приобретал их '
    'по 60 ₽ (в 2020 году) и по 34,29 ₽ (в 2022 году) — заметно выше '
    'рыночной цены на начало сентября 2026 года (30,62 ₽). Минфин допускает '
    'перенос размещения на более поздний срок, если рыночная конъюнктура '
    'останется слабой.'
)

NEW_SRC = ['Интерфакс', 'https://www.interfax.ru/business/1112660']


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['g3dcf441e']

    assert d['eco']['context'] == OLD_ECO_CONTEXT, \
        'g3dcf441e eco.context уже другой: %r' % (d['eco']['context'],)
    urls = {s[1] for s in d['src']}
    assert NEW_SRC[1] not in urls, 'источник уже добавлен'

    print('g3dcf441e: eco.context дополнен (цены ФНБ, риск переноса SPO); '
          'добавлен источник interfax.ru/business/1112660')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['eco']['context'] = NEW_ECO_CONTEXT
    d['src'].append(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
