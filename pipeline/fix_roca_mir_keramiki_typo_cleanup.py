"""Месячная очередь (REVISION_BRIEF), карточка gbb9adb9d (Roca Group/
«Мир керамики»): `eco.target_fin` нёс дословную, но испорченную типографику
исходного источника — телеграм-канала @dealsma (уже стоит в `src`,
проверено прямым чтением кэша: "Финансовые показатели 202:\nВыручка – 3,6
млрд руб. (минус 8,8 г./г.)\nEBTIDA – 300 млн руб. (оценочной)").

ВАЖНО: проверено — это НЕ выдумка и не ошибка нашего разбора. Абирег
(второй источник в `src`) действительно не содержит этих цифр (проверено
прямым WebFetch), но телеграм-пост @dealsma содержит их дословно, включая
опечатки самого канала. «202:» — обрубленный год: соседний абзац того же
поста (про «Акватон РУС») даёт «Финансовые показатели 2023:» для того же
отчётного периода — год восстанавливается однозначно из структуры самого
поста, а не домысливается. «EBTIDA» — опечатка канала вместо EBITDA (та
же аббревиатура правильно написана чуть ниже в том же посте, в абзаце
про Roca Group: «EBITDA - €18 млн»). Пропущенный знак процента у «минус
8,8 г./г.» — та же самая строка у «Акватон РУС» несёт «+9% г./г.» с
процентом, только строка «Рока Рус» его потеряла.

Не через review.py: очищенный текст перестаёт быть побайтовой копией
источника (это и есть цель правки — убрать опечатки), поэтому дословная
проверка `review.py` неприменима к этому классу правки.
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gbb9adb9d'
OLD_TARGET_FIN = (
    'ООО «Рока Рус» — производитель санкерамики управляет заводом в '
    'Ленобласти. Финансовые показатели 202: Выручка – 3,6 млрд руб. '
    '(минус 8,8 г./г.) EBTIDA – 300 млн руб. (оценочной) ООО «АКВАТОН '
    'РУС» — осуществляет полный цикл производства мебели для ванных '
    'комнат, начиная с разработки дизайна моделей и заканчивая их '
    'сборкой. На двух заводах «Акватон», расположенных в 100 км к '
    'востоку от Москвы в поселке Давыдово Орехово-Зуевского района, '
    'работает более 500 человек. Финансовые показатели 2023: Выручка – '
    '1,8 млрд руб. (+9% г./г.) EBTIDA – 150 млн руб.'
)
NEW_TARGET_FIN = (
    'ООО «Рока Рус» — производитель санкерамики управляет заводом в '
    'Ленобласти. Финансовые показатели 2023: выручка – 3,6 млрд руб. '
    '(-8,8% г./г.), EBITDA – 300 млн руб. (оценочно). ООО «АКВАТОН '
    'РУС» — осуществляет полный цикл производства мебели для ванных '
    'комнат, начиная с разработки дизайна моделей и заканчивая их '
    'сборкой. На двух заводах «Акватон», расположенных в 100 км к '
    'востоку от Москвы в поселке Давыдово Орехово-Зуевского района, '
    'работает более 500 человек. Финансовые показатели 2023: выручка – '
    '1,8 млрд руб. (+9% г./г.), EBITDA – 150 млн руб.'
)


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['target_fin'] == OLD_TARGET_FIN, \
        f"eco.target_fin: неожиданное значение {deal['eco']['target_fin']!r}"

    print(f"{CARD_ID} eco.target_fin: очищены опечатки источника "
          "(«202:» -> «2023:», EBTIDA -> EBITDA, восстановлен знак %)")
    deal['eco']['target_fin'] = NEW_TARGET_FIN

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
