import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g65557c4a'

OLD_LAW_STRUCT = '—'
NEW_LAW_STRUCT = (
    'С 24 января 2024 года функции единоличного исполнительного органа'
    ' завода переданы управляющей организации — АО «Росхим», которое'
    ' также выступает единственным учредителем, владеющим 100% уставного'
    ' капитала. «Росхим» (до августа 2023 года — «Русский водород») на'
    ' 100% принадлежит ЗПИФ «Квинта»; гендиректор холдинга с 2022 года —'
    ' Эдуард Давыдов.'
)

OLD_CONTEXT = (
    'В марте прошлого года суд вернул государству акции «Кучуксульфата»,'
    ' приватизированного в 1991 году, изъяв их у кипрской Kapok'
    ' Investments Limited и нескольких физических лиц. Прокуратура'
    ' сочла, что эти собственники владели акциями незаконно, и указала'
    ' на нарушения в процедуре приватизации, из-за которых государство'
    ' не уведомили о сделках.'
)
NEW_CONTEXT = (
    OLD_CONTEXT + ' «Росхим» управляет и другими химическими активами —'
    ' «Башкирской содовой компанией», Стерлитамакским нефтехимическим'
    ' заводом, Крымским содовым заводом и заводом аминокислот'
    ' «Донбиотех».'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['law']['struct'] == OLD_LAW_STRUCT
    assert deal['eco']['context'] == OLD_CONTEXT

    print('=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)
    print('\n=== eco.context: станет ===')
    print(NEW_CONTEXT)

    if write:
        deal['law']['struct'] = NEW_LAW_STRUCT
        deal['eco']['context'] = NEW_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
