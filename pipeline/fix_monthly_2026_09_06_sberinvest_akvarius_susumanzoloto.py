def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    sber = by_id[SBER_ID]
    akv = by_id[AKV_ID]
    susu = by_id[SUSU_ID]

    assert sber['date'] == SBER_OLD_DATE
    assert sber['eco'].get('rationale') is None
    assert sber['eco'].get('context') is None
    assert akv.get('seller') == AKV_OLD_SELLER
    assert akv.get('asset') == AKV_OLD_ASSET
    assert susu['eco']['share'] == SUSU_OLD_SHARE
    assert susu['eco']['rationale'] == SUSU_OLD_RATIONALE

    print('=== sber: date ===', SBER_NEW_DATE)
    print('=== sber: eco.rationale ===')
    print(SBER_NEW_RATIONALE)
    print('=== sber: eco.context ===')
    print(SBER_NEW_CONTEXT)
    print()
    print('=== akv: seller ===', AKV_NEW_SELLER)
    print('=== akv: asset ===')
    print(AKV_NEW_ASSET)
    print()
    print('=== susu: eco.share ===')
    print(SUSU_NEW_SHARE)
    print('=== susu: eco.rationale ===')
    print(SUSU_NEW_RATIONALE)

    if write:
        sber['date'] = SBER_NEW_DATE
        sber['eco']['rationale'] = SBER_NEW_RATIONALE
        sber['eco']['context'] = SBER_NEW_CONTEXT
        akv['seller'] = AKV_NEW_SELLER
        akv['asset'] = AKV_NEW_ASSET
        susu['eco']['share'] = SUSU_NEW_SHARE
        susu['eco']['rationale'] = SUSU_NEW_RATIONALE
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
