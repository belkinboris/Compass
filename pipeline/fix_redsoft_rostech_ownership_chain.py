# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка g71bd68cf (АО «Цифровой
вектор»/«Ред Софт»): дельта-поиск нашёл ТРЕТИЙ, самый значимый шаг в
цепочке передач той же 30%-й доли, которого в карточке не было вовсе —
9 июня 2025 года доля ушла от технической компании-прокладки «Цифровая
Система» к АО «РТ-Ред», дочерней структуре госкорпорации «Ростех».
Карточка уже честно фиксировала первую передачу (декабрь 2024 -> апрель
2025), но не знала о второй (апрель -> июнь 2025), о которой писали
десятки изданий.

Источники: CNews (данные ЕГРЮЛ, сумма сделки, номинал доли) и Anti-
Malware.ru (принадлежность «Ростеху», цель партнёрства) — оба читал
напрямую. Не через review.py: два источника в одном поле.
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g71bd68cf'
OLD_STRUCT = (
    'Как обнаружил TAdviser, в конце апреля 2025 года у ООО «Ред Софт» '
    'появился новый соучредитель — АО «Цифровая Система». Он получил '
    'долю 30% в уставном капитале компании, ранее принадлежавшую АО '
    '«Цифровой Вектор». АО «Цифровая Система» было образовано недавно, '
    'в конце февраля 2025 года, АО «Цифровой Вектор» — в ноябре '
    '2024-го. У обеих этих компаний один и тот же гендиректор — Артур '
    'Деев.'
)
ADDITION = (
    'По данным ЕГРЮЛ, 9 июня 2025 г. эти же 30% перешли в собственность '
    'АО «РТ-Ред» — дочерней структуры госкорпорации «Ростех». Сумма '
    'сделки не раскрывается. Партнёрство направлено на совместное '
    'развитие экосистемы решений «РЕД СОФТ», создание корпоративных '
    'программных продуктов и программно-аппаратных комплексов.'
)
NEW_STRUCT = OLD_STRUCT + ' ' + ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['law']['struct'] == OLD_STRUCT, \
        f"law.struct: неожиданное значение {deal['law']['struct']!r}"

    print(f"{CARD_ID} law.struct: += продажа той же доли «Ростеху» "
          "(июнь 2025 года) — третий и главный шаг цепочки")
    deal['law']['struct'] = NEW_STRUCT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
