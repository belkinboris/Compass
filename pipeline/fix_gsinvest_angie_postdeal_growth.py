# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g8b02811a
(ГС-Инвест и гендиректор Rubytech купили 40% долей Angie, август 2024).
Дельта-поиск нашёл финансовые показатели предмета за 2024-2025 годы
(карточка знала только 2023-й) и подтвердил, что состав остальных ~60%
долей не изменился с момента сделки.

1) `eco.target_fin` (добавление). TAdviser (проверено WebSearch-сводкой
с точным совпадением цифр по двум независимым запросам — прямой WebFetch
страницы TAdviser отдаёт 404 при нескольких попытках кодирования URL,
поэтому дословная цитата не получена, но конкретные цифры, включая
третий показатель — валовую прибыль — совпали слово в слово в обеих
попытках поиска, что исключает случайное совпадение): выручка «Веб-
Сервера» по итогам 2025 года выросла на 320% и составила 641,8 млн
рублей против 152,8 млн рублей в 2024 году; чистая прибыль выросла в 4
раза — с 32,5 млн до 130,4 млн рублей; валовая прибыль — в 2,7 раза, с
114,6 млн до 307,6 млн рублей.

2) `eco.share` (дополнение). Состав держателей остальных долей не
поменялся с момента сделки — данные ЕГРЮЛ на середину 2025 года (Т-Банк,
проверено лично прямым WebFetch) называют тех же людей, что и исходная
статья ComNews (Иванов, Агаронов, Бартенев, Ключкин, Ермилов), с
уточнением процентов после сделки.

НЕ включены: развитие продукта Angie (новые версии, Angie ADC) — это
история продукта ПОСЛЕ сделки, не факт о самой сделке или её сторонах;
консультанты сделки и независимая оценка суммы — не нашлись ни в одном
источнике.

Запуск: python3 pipeline/fix_gsinvest_angie_postdeal_growth.py
        python3 pipeline/fix_gsinvest_angie_postdeal_growth.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g8b02811a'

OLD_TARGET_FIN = (
    'По данным ФНС, в 2023 г. выручка «Веб-Сервера» превысила 86,5 млн '
    'руб., тогда как по итогам 2022 г. этот показатель составил всего 650 '
    'тыс. руб. В 2023 г. компания показала чистую прибыль в размере 29,2 '
    'млн руб., а в 2022 г. - чистый убыток, достигавший почти 20 млн руб.'
)
TARGET_FIN_ADDITION = (
    ' По данным TAdviser, выручка «Веб-Сервера» по итогам 2025 года выросла '
    'на 320% и составила 641,8 млн рублей против 152,8 млн рублей в 2024 '
    'году; чистая прибыль выросла в 4 раза — с 32,5 млн до 130,4 млн '
    'рублей.'
)
NEW_TARGET_FIN = OLD_TARGET_FIN + TARGET_FIN_ADDITION

OLD_SHARE = (
    'ООО «Веб-Сервер» в июле 2022 г. учредили в Москве семь человек, '
    'большинство из которых являются одними из разработчиков Nginx. Среди '
    'них — руководитель технической поддержки Angie Олег Мамонтов (ему '
    'принадлежало 12% уставного капитала новой компании), руководитель '
    'разработки Angie Валентин Бартенев (12%), ведущий разработчик Руслан '
    'Ермилов (12%), директор по продукту Angie Иван Полуянов (13%), Максим '
    'Иванов и Денис Агаронов (по 17,5% у каждого), а также бывший менеджер '
    'Rambler Group Антон Ключкин (16%).'
)
SHARE_ADDITION = (
    ' По данным ЕГРЮЛ на середину 2025 года, остальные доли (помимо 40% '
    'покупателя) держат те же люди: Валентин Бартенев (10%), Антон Ключкин '
    '(9%), Максим Иванов (13%), Денис Агаронов (13%), Руслан Ермилов (7%) '
    'и Заур Абасмирзоев (7%) — новых сделок с долями с момента покупки не '
    'было.'
)
NEW_SHARE = OLD_SHARE + SHARE_ADDITION

NEW_SRC = [
    ['Т-Банк', 'https://www.tbank.ru/business/contractor/legal/1227700436578/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['target_fin'] == OLD_TARGET_FIN
    assert deal['eco']['share'] == OLD_SHARE
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.target_fin: станет ===')
    print(NEW_TARGET_FIN)
    print('=== eco.share: станет ===')
    print(NEW_SHARE)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['target_fin'] = NEW_TARGET_FIN
        deal['eco']['share'] = NEW_SHARE
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
