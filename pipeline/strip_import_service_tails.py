# -*- coding: utf-8 -*-
"""Служебные хвосты компактного импорта, которые видит читатель.

НАЙДЕНО вычиткой 15 случайных карточек (просьба владельца 15 августа 2026:
«вычитай на русский язык, на повторы, на грамматику»). В четырёх карточках
из пятнадцати прозаический абзац обрывался служебной пометкой разбора:

    «…вырученные средства направлены на выплату дивидендов акционерам.
     Сумма: 6,35 млрд рублей (инвестиции ГПБ Лизинг). (АО «Газпромбанк
     лизинг» (инвестор/покупатель доли))»

Ни «Сумма: …», ни «(X (роль))» не предложения — это внутренняя разметка
партий компактного импорта, оставшаяся в тексте, который показывается на
экране. Читатель видит абзац, заканчивающийся висящей скобкой.

ДВА КЛАССА, ОБА СНИМАЮТСЯ ТОЛЬКО ТАМ, ГДЕ НИЧЕГО НЕ ТЕРЯЕТСЯ.

1. «Сумма: …» в конце `extra`/`eco.rationale`. Снимается ТОЛЬКО если все
   числа хвоста уже стоят в `sum` или `eco.val` этой же карточки — то есть
   хвост дословно ничего не добавляет (633 поля). У 152 полей хвост несёт
   ЧИСЛА, которых в полях суммы нет («Enterprise Value оценивается в
   5,8 млрд руб.», «из которых 7,7 млрд руб. — долг»), и ещё у 14 карточка
   вообще без `sum`, — эти НЕ ТРОГАЮТСЯ: признак дефекта не основание
   стереть факт (CLAUDE.md), их надо разносить по полям чтением.

2. «(X (роль))» в конце любого текстового поля. Снимается ТОЛЬКО если во
   ВСЕХ вложенных скобках стоят одни ролевые слова («(инвестор)»,
   «(покупатель)», «(эмитент)») — тогда хвост не сообщает ничего сверх
   полей `buyer`/`seller`/`target` карточки (72 поля). Хвосты, где внутри
   есть содержание («(Ростелеком (через дочернюю компанию ООО «Коммит
   Кэпитал»))», «(Покупатель: ООО «РВБ» (совместная компания Russ и
   Wildberries))») — 183 поля — НЕ ТРОГАЮТСЯ по той же причине.

ПОЧЕМУ ШИРЕ, ЧЕМ `strip_leaked_role_tags_all.py`. Тот прогон (234 карточки)
искал закрытый список ролей «продавец|покупатель|цель|таргет|конечный
бенефициар|сторона продавца|сторона покупателя» — и не видел «(инвестор)»,
«(инвесторы)», «(эмитент)», «(инвестор/покупатель доли)», «(привлечение
инвестиций)». Ровно тот же класс урока, что уже записан в CLAUDE.md про
`продавц\\w*`, не совпадающий со словом «Продавец»: правило молчит, а замер
выглядит законченным. Здесь список ролей задан основами и покрывает падежи
и составные формы.

ПОЧЕМУ НЕ ЧЕРЕЗ `review.py`. Снимается НАША СОБСТВЕННАЯ разметка, а не
текст источника; цитаты для этого не существует в природе. Текст ДО хвоста
не меняется ни на символ — это проверяется `assert` на каждом поле.

Запуск:
    python3 pipeline/strip_import_service_tails.py            # сухой прогон
    python3 pipeline/strip_import_service_tails.py --write    # запись
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

ECO_FIELDS = ('rationale', 'context', 'share', 'val', 'target_fin', 'fin', 'sum', 'finadv')
LAW_FIELDS = ('struct', 'appr', 'terms')

# «Сумма: …» до конца строки, начинающаяся с новой фразы (после точки) или
# с начала поля. Хвост забирается целиком — он всегда последний.
SUM_TAIL = re.compile(r'(?:^|(?<=[.!?])\s+)Сумма:\s*(.*)$', re.S)

# Хвост в скобках в самом конце поля, ВНУТРИ которого есть ещё скобки.
NESTED_TAIL = re.compile(r'\s*\(([^()]*(?:\([^()]*\)[^()]*)*)\)\s*$')

# Внутренняя скобка, состоящая ТОЛЬКО из ролевых слов.
ROLE_ONLY = re.compile(
    r'^(?:инвестор|покупател|продавец|продавц|получател|эмитент|цель|таргет|сторон|'
    r'привлечение|заемщик|заёмщик|кредитор|арендатор|девелопер|застройщик|'
    r'организатор|оператор|управляющ|бенефициар|акционер|учредител|участник)'
    r'[а-яё/ -]*$', re.I)

NUM = re.compile(r'\d+(?:[.,]\d+)?')

EXPECTED_SUM_TAILS = 633
EXPECTED_ROLE_TAILS = 72


def numbers(s):
    return set(NUM.findall(str(s or '')))


def sum_tail_is_redundant(deal, tail):
    """Хвост «Сумма: …» ничего не добавляет: все его числа уже в полях суммы."""
    if not deal.get('sum'):
        return False
    known = numbers(deal.get('sum')) | numbers((deal.get('eco') or {}).get('val'))
    tail_numbers = numbers(tail)
    return bool(tail_numbers) and tail_numbers <= known


def role_tail_is_pure(inner):
    """Во всех вложенных скобках — только ролевые слова, содержания нет."""
    subs = re.findall(r'\(([^()]*)\)', inner)
    return bool(subs) and all(ROLE_ONLY.match(s.strip()) for s in subs)


def clean(deal, field, value):
    """Вернуть очищенное значение или None, если чистить нечего.

    ПОРЯДОК ВАЖЕН, и это не стилистика. `SUM_TAIL` жадный (`.*$` с `re.S`) —
    он забирает всё до конца строки, включая ролевой хвост, стоящий ПОСЛЕ
    суммы. Первая версия снимала сумму первой и вместе с ней уносила
    «богатый» хвост, который правило специально обещало не трогать: у
    g68975b9d так ушло бы «(Продавец Артем Соколов (финансовый консультант
    Aspring Capital))» — имя консультанта. Там оно уцелело только потому,
    что уже стояло в `eco.finadv`, то есть по случайности, а не по правилу.
    Поэтому: сначала снимаем ЧИСТЫЙ ролевой хвост, а сумму — только если
    после неё не осталось неснятого хвоста в скобках."""
    out = value

    m = NESTED_TAIL.search(out)
    if m and '(' in m.group(1) and role_tail_is_pure(m.group(1)):
        out = out[:m.start()].rstrip()

    rest = NESTED_TAIL.search(out)
    rich_tail_left = bool(rest and '(' in rest.group(1))
    m = SUM_TAIL.search(out)
    if (m and not rich_tail_left and field in ('extra', 'eco.rationale')
            and sum_tail_is_redundant(deal, m.group(1))):
        out = out[:m.start()].rstrip()

    return out if out != value else None


def _self_check():
    """Правило проверено на себе: что снимается, а что нет."""
    card = {'sum': '6,35 млрд ₽', 'eco': {}}
    # чистый дубль суммы — снимается
    v = 'Компания купила актив. Сумма: 6,35 млрд рублей.'
    assert clean(card, 'extra', v) == 'Компания купила актив.'
    # сумма с ЧУЖИМ числом — не снимается
    v2 = 'Компания купила актив. Сумма: 6,35 млрд рублей; EV — 12 млрд руб.'
    assert clean(card, 'extra', v2) is None, 'хвост с новым числом снимать нельзя'
    # чистая ролевая пометка — снимается
    v3 = 'Компания купила актив. (ERA Capital (инвестор))'
    assert clean(card, 'extra', v3) == 'Компания купила актив.'
    # ролевая пометка С СОДЕРЖАНИЕМ — не снимается
    v4 = 'Компания купила актив. (Ростелеком (через дочернюю компанию ООО «Коммит Кэпитал»))'
    assert clean(card, 'extra', v4) is None, 'хвост с содержанием снимать нельзя'
    # обычная скобка в конце фразы — не трогается
    v5 = 'Актив продан по стартовой цене (торги признаны несостоявшимися).'
    assert clean(card, 'extra', v5) is None, 'обычная скобка — не разметка'
    # «Сумма:» в середине предложения (не после точки) — не трогается
    v6 = 'В отчёте указана Сумма: без расшифровки'
    assert clean({'sum': None, 'eco': {}}, 'extra', v6) is None
    # ГЛАВНАЯ ЗАЩИТА: сумма + «богатый» ролевой хвост после неё. Сумму
    # снимать нельзя — жадная регулярка унесла бы имя консультанта.
    v7 = ('Актив продан. Сумма: 6,35 млрд рублей. '
          '(Продавец Иванов (финансовый консультант Aspring Capital))')
    assert clean(card, 'extra', v7) is None, \
        'сумму нельзя снимать, пока за ней стоит неснятый хвост с содержанием'
    # А если хвост ЧИСТО ролевой — снимаются оба, и порядок это позволяет.
    v8 = 'Актив продан. Сумма: 6,35 млрд рублей. (ERA Capital (инвестор))'
    assert clean(card, 'extra', v8) == 'Актив продан.'


def main(argv):
    _self_check()
    data = json.load(open(DATA, encoding='utf-8'))

    todo = []
    for d in data['deals']:
        pairs = [('extra', d.get('extra'))]
        pairs += [('eco.' + k, (d.get('eco') or {}).get(k)) for k in ECO_FIELDS]
        pairs += [('law.' + k, (d.get('law') or {}).get(k)) for k in LAW_FIELDS]
        for field, value in pairs:
            if not isinstance(value, str) or not value:
                continue
            new = clean(d, field, value)
            if new is not None:
                assert value.startswith(new), \
                    '%s.%s: чистка изменила текст, а не только сняла хвост' % (d['id'], field)
                todo.append((d['id'], field, value, new))

    sums = [t for t in todo if 'Сумма:' in t[2][len(t[3]):]]
    roles = [t for t in todo if t[2][len(t[3]):].rstrip().endswith(')')]
    emptied = [t for t in todo if not t[3]]
    print('Полей к чистке: %d (у %d карточек)' % (len(todo), len({t[0] for t in todo})))
    print('  из них со снятым «Сумма: …»: %d' % len(sums))
    print('  из них со снятой ролевой пометкой: %d' % len(roles))
    print('  поле состояло ЦЕЛИКОМ из хвоста и удаляется: %d' % len(emptied))
    for cid, field, old, new in emptied:
        print('    УДАЛЯЕМ %s %s: %r' % (cid, field, old[:70]))
    for cid, field, old, new in todo[:8]:
        print('  %s %-14s снято: %r' % (cid, field, old[len(new):][:70]))

    if '--write' not in argv:
        print('\nСухой прогон. Запись — с ключом --write.')
        return 0

    by_id = {d['id']: d for d in data['deals']}
    for cid, field, _old, new in todo:
        deal = by_id[cid]
        group, _, key = field.partition('.')
        if not new:
            # Поле состояло ЦЕЛИКОМ из служебного хвоста — значит, оно и не
            # было заполнено: сумма уже стоит в `sum`/`eco.val`. Пустая
            # строка на экране выглядела бы как «мы это поле заполнили»,
            # поэтому поле удаляется, а не обнуляется.
            (deal if field == 'extra' else deal[group]).pop(key or 'extra', None)
        elif field == 'extra':
            deal['extra'] = new
        else:
            deal[group][key] = new

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('ЗАПИСАНО: %d полей.' % len(todo))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
