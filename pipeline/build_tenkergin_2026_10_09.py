"""Приток 16:20 МСК 9 октября 2026: Роснедра повторно выставили на аукцион
оловянно-вольфрамовое месторождение Тенкергин (Чукотка) — весной 2026 года
аукцион уже проходил со стартовым платежом 110,091 млн ₽, сейчас цена
выросла в ~7,12 раза до 783,331 млн ₽ (ПРАЙМ, со ссылкой на ГИС «Торги»).
В тексте источника есть явно мусорная вторая цифра «5,418 млрд ₽» —
не сходится с арифметикой роста (110,091 × 7,12 ≈ 783,8, что совпадает с
первой цифрой) и похожа на утечку рекламного блока в кэш статьи
(docs/intake_run.md, прецедент Сбербанк/Summit Towers) — не вношу её в
карточку. Ворота не распознали сделку (нет явного «X продаёт Y» в
заголовке). Роснедра — госорган, профиль не заводим (прецедент g51fa80ce,
«Голдрупп»).

Запуск: python3 pipeline/build_tenkergin_2026_10_09.py [--write]
"""
import json
import sys

sys.path.insert(0, 'pipeline/ingest')
import promote  # noqa: E402

PENDING = 'static/data/pending.json'
URL = 'https://1prime.ru/20261009/rosnedra-874114704.html'

DRAFT = {
    'draft_id': 'd-tenkergin-2026-10-09',
    'title': 'Роснедра повторно выставили на аукцион месторождение Тенкергин на Чукотке',
    'date': '2026-10-09',
    'src': [['ПРАЙМ', URL]],
    'sum': '783,331 млн ₽',
    'type': 'Продажа с торгов',
    'status': 'Обсуждается',
    'events': [],
    'buyer_name': None,
    'asset': 'право геологического изучения и добычи на оловянно-вольфрамовом месторождении Тенкергин',
    'seller': 'Роснедра',
    'parsed_parties': {'buyer': None,
                        'asset': 'право геологического изучения и добычи на оловянно-вольфрамовом месторождении Тенкергин',
                        'seller': 'Роснедра'},
    'ind': 'ГМК и добыча',
    'needs_review': True,
}


def main(write):
    pending = json.load(open(PENDING, encoding='utf-8'))
    existing = {c['id'] for c in pending['cards']}
    deal_id = promote.new_id(existing)
    card = promote.to_card(DRAFT, deal_id)
    card['eco']['sum'] = '783,331 млн ₽'
    card['eco']['share'] = (
        'Срок лицензии — четверть века, участок занимает 1,8 кв. км в Чукотском '
        'автономном округе. Запасы триоксида вольфрама: категория C1 — 3843 т, C2 — '
        '3147 т, ресурсы P1 — 5827 т. Запасы рудного олова: C1 — 97 т, C2 — 58 т, '
        'ресурсы P1 — 106 т.'
    )
    card['eco']['context'] = (
        'Заявки принимают до 5 ноября, сами торги назначены на 23 ноября. Весной 2026 '
        'года аукцион по тому же участку уже проходил со стартовым платежом 110,091 млн '
        '₽ — нынешняя цена выросла в ~7,12 раза, задаток источник не называет.'
    )
    card['themes'] = ['Продажа с торгов']
    card['pending_since'] = '2026-10-09T16:20:00+00:00'
    if not write:
        print('Сухой прогон. Карточка была бы: %s' % deal_id)
        print(json.dumps(card, ensure_ascii=False, indent=2))
        return
    pending['cards'].append(card)
    with open(PENDING, 'w', encoding='utf-8') as f:
        json.dump(pending, f, ensure_ascii=False, indent=1)
        f.write('\n')
    print('Записано: %s добавлена в pending.json' % deal_id)


if __name__ == '__main__':
    main('--write' in sys.argv)
