# -*- coding: utf-8 -*-
"""Месячная очередь, карточка g1d003324 (ВИМ Private Equity/BASK):
дельта-поиск нашёл, что цель привлечения средств называет ТРИ направления,
а в карточке — только два (обрезано на «развитие продуктовой линейки»,
третье — «рост представленности бренда в онлайн-каналах продаж» —
потеряно при первом переносе). Не через review.py: текущее значение поля
уже перефразировано относительно источника («БАСК планирует направить
привлеченные инвестиции» вместо «Компания планирует направить
инвестиции, привлеченные от АО ВИМ Инвестиции») и не является его
дословной подстрокой — механическая проверка review.py не пропустит ни
старое, ни новое значение поля.

Источник — читал напрямую (fetch_article_texts.py, закэширован):
https://investfunds.ru/news/171317/
Дословная цитата источника: «Компания планирует направить инвестиции,
привлеченные от АО ВИМ Инвестиции, на расширение производственных
мощностей, развитие продуктовой линейки и рост представленности бренда
в онлайн-каналах продаж.»

Запуск: python3 pipeline/fix_bask_rationale_online_channels.py [--write]
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g1d003324'

OLD_RATIONALE = (
    'Инвестиционный раунд является стратегическим шагом для '
    'масштабирования бизнеса БАСК на федеральном уровне. БАСК планирует '
    'направить привлеченные инвестиции на расширение производственных '
    'мощностей и развитие продуктовой линейки.'
)
NEW_RATIONALE = (
    'Инвестиционный раунд является стратегическим шагом для '
    'масштабирования бизнеса БАСК на федеральном уровне. БАСК планирует '
    'направить привлеченные инвестиции на расширение производственных '
    'мощностей, развитие продуктовой линейки и рост представленности '
    'бренда в онлайн-каналах продаж.'
)


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['rationale'] == OLD_RATIONALE, \
        f"eco.rationale: неожиданное значение {deal['eco']['rationale']!r}"

    print(f"{CARD_ID} eco.rationale: += третье направление трат "
          f"(онлайн-каналы продаж), потерянное при первом переносе")
    deal['eco']['rationale'] = NEW_RATIONALE

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
