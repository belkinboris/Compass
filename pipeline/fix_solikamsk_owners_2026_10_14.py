"""«Соликамскбумпром» (g002710cf), опубликована: владелец 14 октября 2026 —
«написано у нас плохо, как будто они сами свои акции продают; проверь в
интернете, кто продаёт». Продавца пакета не называет ни один источник; это
продажа уже выпущенных акций их владельцами (о допэмиссии не пишет никто).
Владельцы — по Ъ 26.03.2026 (doc/8535065) и Ъ-Прикамье/mail.ru (июнь 2026):
вдова Баранова 24,3%, ООО «Сопапэкс» (наследники Баранова и Дмитрий Кепп)
около четверти, «СБП-Инвест» (дочка комбината) около 22%, «Калиостро
Капитал» Вадима Логофета 5,21% (Ъ 04.08.2026). Заголовок — от лица покупателя; продавец
остаётся пустым (роль в источниках никому не названа). Пост в канале
поправит рутина публикации (правка не будит подписчиков). Без ключа — сухо."""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
B = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')
ID = 'g002710cf'
OLD_TITLE = '«Соликамскбумпром» сообщил о соглашении о намерениях передать 83,3% акций «Юнь Чоу»'
NEW_TITLE = 'Китайская «Юнь Чоу» намерена купить 83,3% «Соликамскбумпрома»'
OLD_SHARE = ('83,3% акций АО «Соликамскбумпром» — контрольный пакет одного из крупнейших в стране '
             'производителей газетной бумаги.')
NEW_STRUCT_HEAD = 'Кто из акционеров продаёт свои акции, не называется. '
OWNERS = (' Своих владельцев комбинат официально не раскрывает. По данным на март 2026 года, '
          '24,3% акций было у вдовы Виктора Баранова Татьяны, около 25% — у ООО «Сопапэкс», которым '
          'владеют наследники Баранова и Дмитрий Кепп, около 22% — у «СБП-Инвест», дочерней '
          'компании самого комбината; ещё 5,21% принадлежит ООО «Калиостро Капитал» Вадима Логофета.')
NEW_SRC = [['Коммерсантъ', 'https://www.kommersant.ru/doc/8535065'],
           ['Коммерсантъ', 'https://www.kommersant.ru/doc/8861083']]
raw = open(B, encoding='utf-8').read()
base = json.loads(raw)
c = next(d for d in base['deals'] if d['id'] == ID)
assert c['title'] == OLD_TITLE, c['title']
assert c['eco']['share'] == OLD_SHARE, c['eco']['share']
assert not c['law']['struct'].startswith(NEW_STRUCT_HEAD)
assert 'Своих владельцев комбинат' not in c['eco']['context']
c['title'] = NEW_TITLE
c['law']['struct'] = NEW_STRUCT_HEAD + c['law']['struct']
c['eco']['context'] = c['eco']['context'].rstrip() + OWNERS
have = {s[1] for s in c.get('src') or [] if len(s) > 1}
for s in NEW_SRC:
    if s[1] not in have:
        c['src'].append(s)
print(ID, '→', NEW_TITLE)
if '--write' in sys.argv:
    open(B, 'w', encoding='utf-8').write(json.dumps(base, ensure_ascii=False, indent=1) + ('\n' if raw.endswith('\n') else ''))
    print('записано')
