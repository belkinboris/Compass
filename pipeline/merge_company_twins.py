# -*- coding: utf-8 -*-
"""Бэклог A22: одна компания записана двумя профилями.

ЧТО СЛОМАНО. «Альфа-Банк» и «Alfa-Bank» — две карточки компании, и сделки
поделены между ними: у одной четыре, у другой одна. На экране это врёт трижды:
«Сделок в базе» на профиле показывает половину, каталог показывает одну
компанию дважды, а поиск по имени находит то один профиль, то другой — в
зависимости от того, как пользователь написал: латиницей или кириллицей.

ЗАМЕР. Ключ «имя без организационной формы, без пунктуации, с транслитерацией
в латиницу и сглаживанием c/k, ph/f, y/i, ё/е, удвоенных букв» даёт **15 пар
профилей** (30 записей из 1846), на которых висит **32 роли в сделках**. Прежний
ключ из прогона 50 (простая таблица букв) находил 11 пар: «Balchug Capital» и
«Балчуг Капитал» он не видел из-за c против k, «Polymetal» и «Полиметалл» — из-за
y против и. Проверка «компаний-тёзок 0», стоявшая в роадмапе, ловила только
посимвольное совпадение и не видела класса вовсе.

ЧТО СЛИТО (12 пар). Одна компания, два написания:
латиница/кириллица («Alfa-Bank»/«Альфа-Банк», «Avito»/«Авито»,
«Balchug Capital»/«Балчуг Капитал», «Glorax»/«Глоракс», «MTS AI»/«МТС AI»,
«Группа Arenadata»/«Группа Аренадата», «Reg.ru»/«Рег.ру»), ё/е («Артем
Чайка»/«Артём Чайка», «Объединенная чайная компания»/«Объединённая», «ГК
«Самолет»»/«ПАО ГК «Самолёт»»), дефис/пробел («МТС-банк»/«МТС Банк») и одна
пара точных тёзок — «Уральский турбинный завод» дважды (завод продавали дважды:
«Ренова» — «Мосэлектрощиту» в 2023-м, затем «Интер РАО» в 2024-м; это один
завод и две сделки, а не два завода).

ЧТО НЕ СЛИТО И ПОЧЕМУ (3 пары). Похожие имена — не всегда одна компания:
иностранный владелец и его российское юрлицо носят одно имя, но в сделке стоят
по РАЗНЫЕ стороны, и слияние сделало бы продавца предметом собственной сделки.
  * «Essity» (продавец российского бизнеса) и ООО «Эссити» (сам этот бизнес);
  * «Fortum» (финский владелец) и «Фортум» (ПАО «Фортум», российские активы,
    которые списывались и деконсолидировались);
  * «Polymetal» (Polymetal International plc) и «Полиметалл» (АО «Полиметалл»,
    российский актив, проданный «Мангазее» в 2024-м).
Это ровно тот случай, о котором предупреждал бэклог: пары читаются глазами.

КАК ВЫБИРАЛСЯ ОСТАЮЩИЙСЯ ПРОФИЛЬ. (1) У кого больше ролей в сделках — тот и
остаётся: меньше ссылок переписывать, меньше риска. (2) При равенстве —
кириллическое написание: продукт русскоязычный. (3) Отдельно оговорено в
таблице, если у профиля-победителя неверная отрасль: у «МТС-банка» стояло
«Страхование» (отрасль купленной страховой), у «Alfa-Bank» — «E-commerce»
(отрасль купленной платформы), поэтому там остаётся профиль с верной отраслью.
Имена профилей НЕ переписываются: оба написания взяты из наших же источников,
и выдумывать «правильное» третье мы не будем.

ЧТО ОСТАЁТСЯ ОТ УДАЛЁННОГО ПРОФИЛЯ. Его адрес: `merged_companies` в базе хранит
пару «id дубля -> id оставшегося», и `#/companies/<id дубля>` открывает
оставшийся профиль. Так же, как `merged` для слитых карточек сделок (прогон 50).

ЧТО ПРОВЕРЯЕТСЯ ПЕРЕД ЗАПИСЬЮ. Оба профиля на месте и названы так, как в
таблице; ни одна сделка не ссылается на оба сразу (иначе после слияния компания
заняла бы в сделке две роли); число профилей уменьшается ровно на число пар;
псевдонимы обоих профилей сохраняются — иначе сопоставление притока перестанет
узнавать одно из написаний.

Запуск:
    python3 pipeline/merge_company_twins.py            # сухой прогон
    python3 pipeline/merge_company_twins.py --write    # записать
"""
import json
import sys

PATH = 'static/data/deals_promoted.json'
REFS = ('buyer', 'seller_id', 'target', 'asset_id')

# (остаётся, удаляется, ожидаемые имена, почему так)
MERGE = [
    ('ga2cfae5b', 'ge5be0c9f', ('Альфа-Банк', 'Alfa-Bank'),
     'у «Альфа-Банка» 4 роли против 1, и отрасль верна («Банки» против «E-commerce» — '
     'это отрасль купленной платформы Flocktory)'),
    ('g1eff47f6', 'g33d494f5', ('Авито', 'Avito'), 'у «Авито» 4 роли против 2'),
    ('gf7340794', 'g7e126b37', ('Balchug Capital', 'Балчуг Капитал'),
     'у «Balchug Capital» 6 ролей против 1'),
    ('g12111389', 'g2657ae61', ('ГК «Самолет»', 'ПАО ГК «Самолёт»'),
     'у «ГК «Самолет»» 6 ролей против 1'),
    ('gbef46925', 'gb5e89156', ('Артём Чайка', 'Артем Чайка'),
     'ролей поровну; остаётся написание через «ё» — это одно и то же лицо, обе сделки про 3S Group'),
    ('g545a6a28', 'g9a82cb81', ('Глоракс', 'Glorax'), 'ролей поровну; остаётся кириллица'),
    ('g49b227e3', 'g37490eb2', ('Группа Аренадата', 'Группа Arenadata'),
     'ролей поровну; остаётся кириллица'),
    ('g28add31b', 'g87d49ce2', ('МТС AI', 'MTS AI'), 'ролей поровну; остаётся кириллица'),
    ('g37d577dc', 'g3c2d2c87', ('МТС Банк', 'МТС-банк'),
     'ролей поровну; остаётся профиль с верной отраслью («Банки» против «Страхование» — '
     'это отрасль купленной страховой компании)'),
    ('gb191a9be', 'geac55d57', ('Объединённая чайная компания', 'Объединенная чайная компания'),
     'ролей поровну; остаётся написание через «ё»'),
    ('g4f9e4c87', 'g254ebc08', ('Reg.ru', 'Рег.ру'),
     'ролей поровну; остаётся написание бренда, как он пишет себя сам'),
    ('g87315c72', 'g51a98759', ('Уральский турбинный завод', 'Уральский турбинный завод'),
     'точные тёзки: один завод, проданный дважды («Ренова» -> «Мосэлектрощит» в 2023-м, '
     'затем «Интер РАО» в 2024-м)'),
]

# Пары, которые ключ считает одинаковыми, а читатель — нет.
SKIP = {
    ('ga48b2459', 'g153264e5'): 'Essity (продавец) и ООО «Эссити» (проданный российский бизнес)',
    ('g4b33b0cd', 'g189ee2cd'): 'Fortum (финский владелец) и ПАО «Фортум» (российские активы)',
    ('g90b3b906', 'g4058df30'): 'Polymetal International plc и АО «Полиметалл» (российский актив)',
}


def main(write):
    data = json.load(open(PATH, encoding='utf-8'))
    comps, deals, keys = data['companies'], data['deals'], data['match_keys']

    for keep, drop, names, _why in MERGE:
        assert keep in comps and drop in comps, 'профиля нет: %s / %s' % (keep, drop)
        assert (comps[keep]['name'], comps[drop]['name']) == names, \
            'имена изменились: %r против %r' % ((comps[keep]['name'], comps[drop]['name']), names)
        both = [d['id'] for d in deals
                if {d.get(f) for f in REFS} >= {keep, drop}]
        assert not both, 'сделка ссылается на оба профиля сразу: %s' % both
    for pair in SKIP:
        assert all(x in comps for x in pair), 'пара из SKIP уже слита: %s' % (pair,)

    moved = 0
    plan = []
    for keep, drop, names, why in MERGE:
        n = sum(1 for d in deals for f in REFS if d.get(f) == drop)
        aliases = [a for a in (keys.get(drop) or []) if a not in (keys.get(keep) or [])]
        plan.append((keep, drop, names, why, n, aliases))
        moved += n

    print('СЛИЯНИЕ ПРОФИЛЕЙ-БЛИЗНЕЦОВ: %d пар, переезжает %d ролей\n' % (len(MERGE), moved))
    for keep, drop, names, why, n, aliases in plan:
        print('  «%s» <- «%s»' % (names[0], names[1]))
        print('      %s -> %s | ролей переезжает: %d | псевдонимов добавится: %d %s'
              % (drop, keep, n, len(aliases), aliases or ''))
        print('      почему: %s' % why)
    print('\nНЕ СЛИТО (похожее имя — не одна компания):')
    for (a, b), why in SKIP.items():
        print('  %s / %s — %s' % (a, b, why))

    if not write:
        print('\nСухой прогон. Запись — с ключом --write.')
        return

    было = len(comps)
    for keep, drop, _names, _why, _n, aliases in plan:
        for d in deals:
            for f in REFS:
                if d.get(f) == drop:
                    d[f] = keep
        if aliases:
            keys[keep] = (keys.get(keep) or []) + aliases
        keys.pop(drop, None)
        comps.pop(drop)
        data.setdefault('merged_companies', {})[drop] = keep

    assert len(comps) == было - len(MERGE), 'удалилось не столько профилей, сколько пар'
    for d in deals:
        refs = [d.get(f) for f in REFS if d.get(f)]
        assert len(refs) == len(set(refs)), 'после слияния компания заняла две роли: %s' % d['id']
    with open(PATH, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('\nЗаписано. Профилей: %d (было %d). Переставлено ролей: %d.'
          % (len(comps), было, moved))


if __name__ == '__main__':
    main('--write' in sys.argv)
