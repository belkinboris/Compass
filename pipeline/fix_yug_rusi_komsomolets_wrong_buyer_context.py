import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g5607637d'

OLD_ECO_CONTEXT = (
    '«Юг Руси» — один из основных производителей и экспортеров '
    'растительных масел в России. Объединяет девять маслозаводов, '
    'крупнейший из которых находится в Ростове-на-Дону. В сезоне '
    '2021/22 года «Юг Руси» обеспечивал 12% выпуска сырого '
    'подсолнечного масла и 28% бутилированного, сказано в отчете '
    'группы «Русагро»'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + '. По независимым данным, сделка закрылась НЕ с '
    '«Югом Руси»: 25 августа 2023 года «Комсомолец» купила структура '
    'фонда прямых инвестиций «Сигнет Инвестиции» (ООО «АПК» → ГК '
    '«Иррико» → ЗПИФ «Сигнет — инвестиции 1»), продавцами выступили '
    'Валерий и Иван Нагели (100% акций); цена не раскрывалась.'
)

NEW_SRC = [
    ['Agroinvestor', 'https://www.agroinvestor.ru/companies/news/40889-zabaykalskiy-plemzavod-komsomolets-smenil-vladeltsa/'],
    ['Chita.ru', 'https://www.chita.ru/text/business/2023/08/25/72638576/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    existing_urls = {s[1] for s in deal['src']}
    add_src = [s for s in NEW_SRC if s[1] not in existing_urls]
    new_src = deal['src'] + add_src

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    if add_src:
        print('\n=== src: добавится ===')
        for s in add_src:
            print(s)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
