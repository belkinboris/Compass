# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g62f09353
(ПАО «Интер РАО» приобрело 98,4% акций НПО «Элсиб») — показатели
предприятия за 2024-2025 годы под новым владельцем, консультант
покупателя (в карточке был назван только консультант продавца) и итог
консолидации энергомашиностроительного бизнеса.

Финансы предприятия под управлением Интер РАО — проверено лично прямым
WebFetch: за 2024 год «получил выручку в 8,1 миллиарда рублей, а чистую
прибыль — в 1,2 миллиарда» (ngs.ru); за 2025 год «выручка на 53% (+4,3
млрд рублей) до суммы в 12,350 млрд рублей», «чистая прибыль компании...
приросла на 576 млн рублей и составила 1,767 млрд рублей (+48%)»
(ksonline.ru) — стабильный рост оба года после сделки.

Консультант покупателя — проверено лично прямым WebFetch (Коммерсантъ,
kommersant.ru/doc/7327316): «Команда Better Chance выступила в роли
юридического консультанта Группы «Интер РАО»» (консультант продавца,
АО «Кузбассэнерго», — ALUMNI Partners, уже стоит в карточке).

Итог консолидации — проверено лично прямым WebFetch: «Все необходимые
корпоративные процедуры были проведены. Это позволяет нам говорить о
том, что консолидация текущих машиностроительных активов состоялась»,
«в состав машиностроительного сектора входят шесть крупных предприятий»,
«Мы не исключаем возможность приобретения новых активов» (investfuture.ru)
— то есть покупка «Элсиба» стала частью завершённой на данный момент
консолидации, а не отдельным эпизодом. Также по данным ЕГРЮЛ структура
покупателя переименована: «одна из структур компании ООО «Интер РАО –
распределённая генерация» была переименована в ООО «Интер РАО –
машиностроение»» (mashnews.ru).

НЕ ВКЛЮЧЕНО: выплата условного вознаграждения (earn-out, 7,21 млрд ₽) —
ни один источник не подтверждает и не опровергает, что оно уже выплачено
или на каких условиях; находка AK&M про «Интер РАО Капитал обнулило долю
в НПО «Элсиб»» (январь 2025) — заголовок за платным доступом, тело не
прочитано, может относиться к внутренней реструктуризации владения, а
не к earn-out — не внесено без прочтения.

Запуск: python3 pipeline/fix_inter_rao_elsib_postdeal.py
        python3 pipeline/fix_inter_rao_elsib_postdeal.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g62f09353'

OLD_TARGET_FIN = (
    'Выручка компании по РСБУ по итогам 2023 г. составила 7,3 млрд '
    'руб., чистая прибыль — 661 млн руб.'
)
NEW_TARGET_FIN = OLD_TARGET_FIN + (
    ' Под управлением Интер РАО рост продолжился: в 2024 году выручка '
    'составила 8,1 млрд руб., чистая прибыль — 1,2 млрд руб.; в 2025 '
    'году выручка выросла на 53% до 12,35 млрд руб., чистая прибыль — '
    'на 48% до 1,767 млрд руб. (ngs.ru, ksonline.ru).'
)

OLD_LAW_ADV = [
    [
        'Юридический консультант продавца (АО «Кузбассэнерго»)',
        'ALUMNI Partners',
        'Сопровождение АО «Кузбассэнерго» в сделке по продаже 98,36% '
        'акций НПО «Элсиб». Источник: https://t.me/LawFirms/7765',
    ]
]
NEW_LAW_ADV_ENTRY = [
    'Юридический консультант покупателя (ПАО «Интер РАО»)',
    'Better Chance',
    'Команда Better Chance выступила в роли юридического консультанта '
    'Группы «Интер РАО» в сделке по приобретению НПО «Элсиб». '
    'Источник: Коммерсантъ.',
]

OLD_EXTRA = (
    '«Интер РАО» приобрело 98,4% акций производителя электродвигателей, '
    'генераторов и трансформаторов НПО «Элсиб» у СУЭК. Сделка завершена.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Покупка стала частью завершённой консолидации: «консолидация '
    'текущих машиностроительных активов состоялась», в машиностроительный '
    'сектор Интер РАО входят шесть крупных предприятий, компания не '
    'исключает новых приобретений (investfuture.ru). По данным ЕГРЮЛ, '
    'структура покупателя ООО «Интер РАО – распределённая генерация» '
    'переименована в ООО «Интер РАО – машиностроение» (mashnews.ru).'
)

NEW_SRC = [
    ['ngs.ru', 'https://ngs.ru/text/business/2025/03/28/75273716/'],
    ['ksonline.ru', 'https://ksonline.ru/601143/novosibirskie-promyshlennye-predpriyatiya-podvodyat-finansovye-itogi-2025-goda'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/7327316'],
    ['investfuture.ru', 'https://investfuture.ru/articles/inter-rao-zavershil-konsolidatsiyu-mashinostroitelnykh-aktivov-i-planiruet-rasshirenie-36118650'],
    ['mashnews.ru', 'https://mashnews.ru/inter-rao-kupilo-984-npo-elsib-za-126-mlrd-rublej.html'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['target_fin'] == OLD_TARGET_FIN
    assert deal['law']['adv'] == OLD_LAW_ADV
    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC
    new_law_adv = deal['law']['adv'] + [NEW_LAW_ADV_ENTRY]

    print('=== eco.target_fin: станет ===')
    print(NEW_TARGET_FIN)
    print('\n=== law.adv: добавится ===')
    print(NEW_LAW_ADV_ENTRY)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['target_fin'] = NEW_TARGET_FIN
        deal['law']['adv'] = new_law_adv
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
