import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gdc72cc35'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Закрыта'

OLD_TITLE = 'Inweasta покупает ООО «ППФ Страхование жизни» у группы PPF'
NEW_TITLE = 'Inweasta купила ООО «ППФ Страхование жизни» у группы PPF'

OLD_EXTRA = ''
NEW_EXTRA = (
    'Сделка закрыта в ноябре 2024 года (Интерфакс, 31 марта 2025 года). '
    'В тот же день компания объявила о ребрендинге: «Компания "PPF '
    'Страхование жизни" объявила о смене юридического названия на ООО '
    'СК "Эверия Лайф", страховщик продолжит работу на рынке под новым '
    'брендом Everia Life». По итогам 2024 года премия в агентском '
    'канале выросла на 10%, продажи долгосрочных договоров — на 11%, '
    'выплаты клиентам — на 17% (АСН-новости, 31 марта 2025 года).'
)

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/business/1017380'],
    ['АСН-новости', 'https://www.asn-news.ru/news/89165'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS
    assert deal['title'] == OLD_TITLE
    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== status: станет ===')
    print(NEW_STATUS)
    print('\n=== title: станет ===')
    print(NEW_TITLE)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['status'] = NEW_STATUS
        deal['title'] = NEW_TITLE
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
