import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g9f76fe60'

NEW_EXTRA = (
    'Павел Тё вышел из этой структуры: 29 июля 2025 подконтрольное ему '
    'ООО «Велна» покинуло состав учредителей «СМ» — теперь 90% долей '
    '«СМ» у Максима Буре, 10% — у Ольги Шатровой. Источник не уточняет, '
    'осталась ли доля РЧФ у «СМ» под новыми владельцами или перешла кому-'
    'то ещё. Финансы фабрики за это время ухудшились: выручка за 2024 '
    'год — 743,1 млн ₽ (−22,1% год к году), чистая прибыль — 118,5 млн ₽ '
    '(−33,5%).'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/7923870'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal.get('extra') in (None, '')

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
