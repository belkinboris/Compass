#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Тот же обрыв, что чинит `fix_truncated_fields.py`, но с другого края.

ЧТО СЛОМАНО. `fix_truncated_fields.py` (A6) ловит обрыв, когда в значении
БОЛЬШЕ открывающих скобок/кавычек, чем закрывающих, — потерян ХВОСТ
предложения. Здесь наоборот: значение начинается словом, а не знаком, но при
этом внутри него ЗАКРЫВАЮЩИХ «»/`)` больше, чем открывающих, — значит, начало
предложения потеряно, а конец остался. На экране это видно так: «Показатели
таргета» начинается с «Фокус», выручка Solar Security за 2016 год составила
361 млн руб.» — независимое слово «Фокус» ничего не значит без потерянного
«По данным «Контур.Фокус», …».

ПОЧЕМУ A6 ЭТО НЕ ЛОВИТ. Его признак обрыва — `^\s*[)»,;:.]` (значение НАЧИНАЕТСЯ
со знака) или перекос «открывающих больше». У этого дефекта потерянный кусок
был в НАЧАЛЕ, поэтому оставшийся текст начинается с буквы, а перекос
противоположный — закрывающих больше, чем открывающих. Признаки не
пересекаются, поэтому нужен отдельный, а не правка существующего.

КАК ЧИНИМ. Полный текст по-прежнему в `extra`. Используем ту же функцию
восстановления `recover()` из `fix_truncated_fields.py`: она ищет обрывок в
`extra`, определяет предложение целиком (включая случаи, где обрывок начинается
СЕРЕДИНОЙ предложения) и дотягивает по признакам обрыва. Ничего не досочиняем.

Запуск:
    python3 pipeline/fix_truncated_field_heads.py            # сухой прогон
    python3 pipeline/fix_truncated_field_heads.py --write    # записать
"""
import json
import sys

from pipeline.fix_truncated_fields import norm, recover, PATH, FIELDS, PLACEHOLDER

# Ручные решения для двух случаев, которые механика не берёт.
OVERRIDE = {
    # `split_sentences()` режет предложение на аббревиатуре организационной
    # формы перед именем с заглавной («…(Invintel B.V. Алексея Мордашова…»):
    # следующее слово выглядит началом нового предложения, хотя это одна
    # фраза. Из-за разреза найденный фрагмент совпадает с «предложением»
    # целиком, recover() не видит прироста и возвращает None. Текст ниже
    # дословно взят из extra этой же карточки.
    ('gf9ceefb9', 'eco', 'share'):
        '12 февраля 2020 года ВТБ и консорциум инвесторов (Invintel B.V. '
        'Алексея Мордашова — 40%, банк «Россия» — 10%) подписали юридически '
        'обязывающие соглашения о продаже «Ростелекому» 55% ООО «Т2 РТК '
        'Холдинг»; расчёты и переход прав собственности завершились 16 марта '
        '2020 года.',
    # Источник этих сумм не дублирован в extra (это отдельная оценочная
    # заметка, не факт из основного текста), поэтому потерянное начало
    # восстановить нечем. Досочинять его — значит выдать догадку за факт;
    # честнее снять осиротевшую закрывающую скобку, которой не на что закрыться.
    ('g1992e9cc', 'eco', 'val'):
        '11,8 млрд ₽ (по данным Ведомостей и ТАСС); округлённо ~12 млрд ₽ '
        'фигурирует в РБК и ряде других источников',
    ('ga0db1bef', 'eco', 'val'):
        '65 млн € (по заявлению на момент анонса); по словам Колесникова в '
        '2023 г., фактические инвестиции 2019–2020 гг. составили не менее '
        '100 млн €',
}


def head_cut(s):
    """Перекос в обратную сторону: закрывающих «»/) больше, чем открывающих —
    начало значения потеряно, а не конец."""
    return (s.count('»') - s.count('«') > 0) or (s.count(')') - s.count('(') > 0)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)

    changes, misses = [], []
    for d in data['deals']:
        extra = norm(d.get('extra'))
        for grp in FIELDS:
            block = d.get(grp) or {}
            for key, val in list(block.items()):
                if not isinstance(val, str):
                    continue
                cur = norm(val)
                if not cur or PLACEHOLDER.match(cur):
                    continue
                if not head_cut(cur):
                    continue
                ov = OVERRIDE.get((d['id'], grp, key))
                if ov is not None:
                    # Ручное решение обязано либо содержать обрывок целиком
                    # (нашли потерянное начало), либо отличаться от него ровно
                    # снятой последней осиротевшей скобкой — не больше.
                    assert cur in ov or ov == cur[:-1], \
                        '%s.%s: ручная правка меняет больше, чем обрыв' % (d['id'], key)
                rec = recover(extra, cur) if ov is None else ov
                if rec is None:
                    misses.append((d['id'], f'{grp}.{key}', cur))
                    continue
                changes.append((d['id'], f'{grp}.{key}', cur, rec))
                if write:
                    block[key] = rec

    print('Обрывов начала значения (закрывающих больше открывающих): %d' % (len(changes) + len(misses)))
    for did, field, old, new in changes:
        print('  %s [%s]' % (did, field))
        print('    было:  %s' % old[:130])
        print('    стало: %s' % new[:170])
    if misses:
        print('\nНЕ ВОССТАНОВЛЕНЫ (обрывок не нашёлся в extra целиком):')
        for did, field, cur in misses:
            print('  %s [%s]: %s' % (did, field, cur[:110]))

    if not write:
        print('\nСухой прогон. Запись — с ключом --write.')
        return
    with open(PATH, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('\nЗаписано: %d полей.' % len(changes))


if __name__ == '__main__':
    main(write='--write' in sys.argv)
