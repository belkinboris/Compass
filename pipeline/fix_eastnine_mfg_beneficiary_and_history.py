import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gb9fdfce4'

OLD_LAW_STRUCT = (
    'Сделка пройдёт в два этапа. Сначала кипрская I.G.M. Manufactrust Ltd '
    'сооснователя MFG Дэвида Келлермана выкупает доли в ритейлере у '
    'шведских Eastnine AG и MFG Intressenter, а также у иностранных '
    'миноритариев с небольшими пакетами и увеличивает свою долю в '
    'компании примерно с 34% до 82%. Затем весь этот пакет у I.G.M. '
    'Manufactrust покупает российское юрлицо Gem Capital.'
)
NEW_LAW_STRUCT = (
    OLD_LAW_STRUCT + ' За Gem Capital (ООО «ГЕМ Инвест») стоит бывший '
    'топ-менеджер «Газпрома» Анатолий Палий; вскоре после сделки «ГЕМ '
    'Инвест» разделило контроль над MFG с фондом Kismet Capital Group '
    'Ивана Таврина, создав с ним совместное предприятие на паритетных '
    'началах (50 на 50).'
)

OLD_ECO_CONTEXT = (
    'В марте 2022 года Eastnine, владевшая около 36% MFG, отменила '
    'планировавшееся IPO ритейлера на фоне потрясений на российском '
    'финансовом рынке, а в октябре договорилась с АФК «Система» — эта '
    'договорённость исполнена не была.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' По той сделке АФК «Система» в октябре 2022 года '
    'подписала обязывающее соглашение о покупке 47,7% MFG за 15,8 млрд '
    '₽, но не смогла её закрыть: сооснователь Дэвид Келлерман и '
    'гендиректор Михаил Уржумцев не согласились продавать свои доли, и '
    'собрать контрольный пакет не вышло.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['law']['struct'] == OLD_LAW_STRUCT
    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    print('=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)

    if write:
        deal['law']['struct'] = NEW_LAW_STRUCT
        deal['eco']['context'] = NEW_ECO_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
