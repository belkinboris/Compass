import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'ge571a54e'

OLD_CONTEXT = (
    'После продажи актива в Армении у МТС остался в СНГ еще один дочерний '
    'оператор связи — «МТС Беларусь» (49%). В 2016 году МТС продала '
    'узбекского оператора Universal Mobile Systems, а в 2019 году МТС '
    'вышла из «ВФ Украина».'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' Первая заявка на продажу была отклонена: «Комиссия по регулированию '
    'общественных услуг Армении (КРОУ) не разрешила... МТС продать свою '
    '"дочку" в Армении», сославшись на право не разрешать сделку, если она '
    '«угрожает национальной безопасности или государственным интересам» '
    '(CNews, 11 апреля 2023). Повторная заявка была одобрена, и сделка '
    'закрылась 24 января 2024 года. 25 марта 2024 года компания сменила '
    'юридическое название на Viva Armenia. 7 июля 2026 года Fedilco Group '
    'Limited (бренд «Вива Армения») сама выступила покупателем: «купила у '
    '"Ростелекома" 100% акций дочернего армянского телеком-оператора '
    'GNC-Alfa» — «сумма сделки неизвестна», цель — «формирование '
    'полноценной конвергентной платформы, объединяющей мобильную связь, '
    'фиксированный интернет, телевидение... в единую экосистему» '
    '(Коммерсантъ).'
)

NEW_SRC = [
    ['CNews', 'https://www.cnews.ru/news/top/2023-04-11_mts_ne_smogla_ujti_iz_armenii'],
    ['Telecompaper', 'https://www.telecompaper.com/news/viva-mts-changes-corporate-name-to-viva-armenia--1495550'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8797894'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
