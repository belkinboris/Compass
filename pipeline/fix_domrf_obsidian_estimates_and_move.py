# -*- coding: utf-8 -*-
"""Месячная очередь, 9 сентября 2026 — дочитывание карточки `gdfce7e3d`
(«"Дом.РФ" приобрел бизнес-центр "Обсидиан" на Ходынском поле»,
добавлена в базу 8 сентября 2026, обыскана в тот же день).

Дельта-поиск (саб-агент + личная проверка) нашёл две новые независимые
оценки стоимости сделки и подтверждение состоявшегося переезда. Личный
WebFetch подтвердил дословно:

1) marketpower.pro: «рыночная стоимость актива составляет 4,3–4,7 млрд
   ₽» (Александр Богданов, исполнительный директор Remain — почти
   совпадает с нижней границей уже стоявшей оценки Commonwealth
   Partnership); «объект в 5,3 млрд ₽, допуская возможность скидки»
   (Ксения Харкевич, руководитель офисного департамента Invest7).

2) vedomosti.ru: «В этот раз представитель Business Club данную
   транзакцию подтвердил» и «в Дом.РФ сообщили, что он уже переехал в
   новый офис» — переезд, который в карточке был описан будущим
   временем («скоро придётся освободить»), к августу 2026 года
   состоялся.

НЕ внесено (саб-агент честно пометил как непроверенное или не тот класс
уверенности): консультанты сделки (ни один источник не назвал), точная
дата и условия переезда Т-Банка в «Искра-парк» (взято через пересказ
поиска, не через прямой WebFetch), предположение, что здание — новостройка
без предыдущих владельцев (логический вывод, а не факт из источника).

Запуск:
    python3 pipeline/fix_domrf_obsidian_estimates_and_move.py            # сухой прогон
    python3 pipeline/fix_domrf_obsidian_estimates_and_move.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_ECO_VAL = (
    'По оценке старшего директора департамента оценки и консалтинга '
    'Commonwealth Partnership Антона Калистратова, в начале года '
    '«Обсидиан» выставляли примерно за 4,8 млрд ₽ без учёта НДС. С '
    'учётом возможного торга Дом.РФ мог заплатить за объект 4,3–4,8 '
    'млрд ₽.'
)
NEW_ECO_VAL = OLD_ECO_VAL + (
    ' Другие оценки экспертов рынка недвижимости: исполнительный '
    'директор Remain Александр Богданов — 4,3–4,7 млрд ₽; руководитель '
    'офисного департамента Invest7 Ксения Харкевич — 5,3 млрд ₽ '
    '(с возможной скидкой).'
)

OLD_ECO_RATIONALE = (
    'Головной офис «Дом.РФ» в бизнес-центре «Военторг» на Воздвиженке '
    'занимает 5,4 тыс. кв. м. Ещё 6,4 тыс. кв. м госкорпорация снимает в '
    'субаренду у Business Club в бизнес-центре «Искра-парк», но эти '
    'площади скоро придётся освободить: их планирует занять Т-Банк.'
)
NEW_ECO_RATIONALE = OLD_ECO_RATIONALE + (
    ' К августу 2026 года «Дом.РФ» подтвердил, что уже переехал в новый '
    'офис.'
)

NEW_SRC = ['MarketPower', 'https://marketpower.pro/publications/dom-rf-dogovorilsia-o-pokupke-biznes-tsentra-obsidian']


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['gdfce7e3d']

    assert d['eco']['val'] == OLD_ECO_VAL, \
        'gdfce7e3d eco.val уже другой: %r' % (d['eco']['val'],)
    assert d['eco']['rationale'] == OLD_ECO_RATIONALE, \
        'gdfce7e3d eco.rationale уже другой: %r' % (d['eco']['rationale'],)
    urls = {s[1] for s in d['src']}
    assert NEW_SRC[1] not in urls, 'источник уже добавлен'

    print('gdfce7e3d: eco.val дополнен двумя независимыми оценками '
          '(Remain 4,3–4,7 млрд ₽, Invest7 5,3 млрд ₽); eco.rationale '
          'дополнен подтверждением состоявшегося переезда; добавлен '
          'источник marketpower.pro')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['eco']['val'] = NEW_ECO_VAL
    d['eco']['rationale'] = NEW_ECO_RATIONALE
    d['src'].append(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
