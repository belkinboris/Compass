import json
import sys

DATA_PATH = 'static/data/pending.json'


def main(write):
    data = json.load(open(DATA_PATH, encoding='utf-8'))
    cards = data['cards']
    target = [c for c in cards if c['id'] == 'ga3fc7ce4']
    assert len(target) == 1, target
    assert target[0]['title'] == 'Украина продает имущество в Харькове по заниженной цене, заявил Ганчев'

    data['cards'] = [c for c in cards if c['id'] != 'ga3fc7ce4']

    if write:
        json.dump(data, open(DATA_PATH, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
        print('ga3fc7ce4 удалена из предпросмотра (не сделка). ЗАПИСАНО.')
    else:
        print('Сухой прогон: удалил бы ga3fc7ce4 из предпросмотра. Повторите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
