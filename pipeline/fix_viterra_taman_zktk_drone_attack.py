import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'ga13c3ea7'

OLD_EXTRA = (
    'Сделка между Viterra (продавец) и Ильей Косыхом (покупатель), '
    'собственником экспортера зерна «Доставка морем». Другая 50% '
    'комплекса принадлежит ООО «Деметра-холдинг».'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Терминал прошёл через резкий обвал перевалки в 2025 году (−56,8%, '
    'до 2,42 млн тонн) из-за снижения государственной экспортной квоты, '
    'начал модернизацию причалов (цель — рост мощности до 8 млн тонн в '
    'год) и восстановил объёмы в первой половине 2026 года — а 30 июля '
    '2026 пострадал от атаки БПЛА и не может осуществлять деятельность '
    'из-за повреждений. Структура собственности (50% «Деметра-холдинг») '
    'не менялась.'
)

NEW_SRC = [
    ['Ведомости', 'https://www.vedomosti.ru/business/articles/2026/07/30/1217719-zernovoi-terminal'],
    ['PortNews', 'https://portnews.ru/news/388203/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
