# -*- coding: utf-8 -*-
"""«РусГазДобыча»/«Гидроиндустрия» (g38bdff94): пост печатал «Покупатель:
«Гидромаш МСК» (Артём Молчанов) — «РусГазДобыча» получила право купить
активы ГМС...» — чужая фраза о ПРОДАВЦЕ пришла в строку покупателя. Причина
тот же класс, что и у gafde5488 (архив `routines/publication.md`, шаг 6/7/12):
`buyer` без профиля (только `buyer_name`), деталь берётся из `eco.context`
— а там первым предложением стояло то, что рассказывает о «РусГазДобыче»,
а не о покупателе; второе предложение («О самом переходе... к «Гидромаш
МСК» узнали из ЕГРЮЛ») — про покупателя, но не первое по порядку.
Переставил предложения местами: после перестановки деталь у «Покупателя»
не печатается вовсе (оба предложения не прошли порог «новизны» для детали)
— честная неполнота вместо чужого факта.

Без ключа — сухой прогон, запись по --write.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

OLD = ('«РусГазДобыча» получила право купить активы ГМС, включая '
       '«Гидромашсервис», спустя год после того, как эти компании перешли '
       'под временное управление по указу президента (конец 2024 года). '
       'О самом переходе 49% «Гидроиндустрии» к «Гидромаш МСК» узнали из '
       'данных ЕГРЮЛ.')
NEW = ('О самом переходе 49% «Гидроиндустрии» к «Гидромаш МСК» узнали из '
       'данных ЕГРЮЛ. «РусГазДобыча» получила право купить активы ГМС, '
       'включая «Гидромашсервис», спустя год после того, как эти компании '
       'перешли под временное управление по указу президента '
       '(конец 2024 года).')


def main():
    write = '--write' in sys.argv
    data = json.load(open(DATA, encoding='utf-8'))
    card = next(d for d in data['deals'] if d['id'] == 'g38bdff94')
    assert card['eco']['context'] == OLD, card['eco']['context']
    card['eco']['context'] = NEW
    print('g38bdff94: eco.context sentences reordered')
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return 0
    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
        f.write('\n')
    print('записано')
    return 0


if __name__ == '__main__':
    sys.exit(main())
