import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g91ef0733'

OLD_STATUS = 'Подписана'
NEW_STATUS = 'Закрыта'

OLD_LAW_STRUCT = (
    'В конце 2022 года 51% в «Полиматика Рус» перешёл к ОФД '
    '«Сотфлайн», одной из компаний, связанных с группой Softline. У '
    'Воротынцева осталось 29%, у Беловой — 16%, у Куликовского — 4%. '
    'Германович вышел из капитала компании.'
)
NEW_LAW_STRUCT = (
    OLD_LAW_STRUCT + ' Осенью 2023 года доля перешла внутри группы к '
    '«СЛ Софт», и Softline консолидировал 100% «Полиматика.рус»; новым '
    'гендиректором стал топ-менеджер Softline Геннадий Сашин. В начале '
    '2026 года Softline продал 49% структуре «Ростелекома» — «БФТ-'
    'Холдингу» — за 230 млн ₽, сохранив 51%, но передав операционный '
    'контроль и право назначать гендиректора партнёру.'
)

OLD_ECO_TARGET_FIN = (
    'Продукты Polymatica внедрены в госсекторе, ритейле, энергетике, '
    'банках и телекоме, ими пользуются более 30 000 человек.'
)
NEW_ECO_TARGET_FIN = (
    OLD_ECO_TARGET_FIN + ' Выручка «Полиматика.рус» составила 343 млн '
    '₽ в 2023 году (чистая прибыль 9,7 млн ₽), выросла до 431 млн ₽ в '
    '2024-м (прибыль 125 млн ₽), но в 2025 году упала до 256 млн ₽ с '
    'чистым убытком 311 млн ₽.'
)

OLD_SRC = [
    ['ComNews', 'https://www.comnews.ru/content/223657/2022-12-22/2022-w51/gk-softline-priobrela-mazhoritarnuyu-dolyu-kompanii-polymatica'],
    ['CNews', 'https://www.cnews.ru/news/top/2024-10-30_softline_sobral_100_rossijskogo'],
]
NEW_SRC = OLD_SRC + [['CNews', 'https://www.cnews.ru/news/top/2026-04-06_softline_za_230_millionov_pereprodal']]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS
    assert deal['law']['struct'] == OLD_LAW_STRUCT
    assert deal['eco']['target_fin'] == OLD_ECO_TARGET_FIN
    assert deal['src'] == OLD_SRC

    print('=== status: станет ===')
    print(NEW_STATUS)
    print('\n=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)
    print('\n=== eco.target_fin: станет ===')
    print(NEW_ECO_TARGET_FIN)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['status'] = NEW_STATUS
        deal['law']['struct'] = NEW_LAW_STRUCT
        deal['eco']['target_fin'] = NEW_ECO_TARGET_FIN
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
