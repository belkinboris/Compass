import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g934ee51b'
OLD_CONTEXT = (
    'Фонд Balchug Capital, принадлежащий армянскому предпринимателю '
    'Давиду Амаряну, завершил сделку по приобретению российских активов '
    'американской компании Caterpillar. Среди переданных активов '
    'находятся завод по производству спецтехники в Тосно (Ленинградская '
    'область) и лизинговая компания в Москве. Сделка была официально '
    'завершена 14 июня 2024 года.'
)
NEW_CONTEXT = (
    'Фонд Balchug Capital, принадлежащий армянскому предпринимателю '
    'Давиду Амаряну, завершил сделку по приобретению российских активов '
    'американской компании Caterpillar — четырёх структур: «Катерпиллар '
    'Евразия», «Солар Турбинс СиАйЭс» (сервис газотурбинного '
    'оборудования), «Катерпиллар Дистрибьюшн Интернейшнл» и '
    '«Электро-Мотив Локомотив Текнолоджис» (поставщик энергетических '
    'установок, а также структура, управляющая складом в Химках площадью '
    '17,5 тыс. кв. м). Это НЕ включает завод по производству спецтехники '
    'в Тосно (Ленинградская область): он с апреля 2025 года принадлежит '
    'другому владельцу, Александру Мигалю (через АО «Горизонт»), и '
    'упоминание завода в этой карточке ранее было ошибкой — смешением с '
    'параллельной, отдельной распродажей активов Caterpillar в России. '
    'ВС РФ признал 23 июля 2026 года законным решение правительственной '
    'комиссии, одобрившей продажу этих четырёх структур Balchug Capital: '
    'иск об оспаривании подала ООО «Соммарива» Андрея Черномырдина, '
    'которая сама хотела приобрести эти активы. Основатель Balchug '
    'Capital Давид Амарян заявил, что фонд выстроил новые цепочки '
    'поставок и работает над обновлением линейки техники, продавать '
    'активы не планирует, но не исключает привлечения партнёра.'
)


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} eco.context: исправлена ошибка (не завод в Тосно) + иск/ВС")
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
