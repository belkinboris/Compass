# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g889e051d
(АФК «Система» передала контроль над рыбопромышленным холдингом
«Восход» Милане Керимовой) — искали дальнейшую судьбу актива и личность
нового владельца.

Проверено лично прямым WebFetch. Версия номинального держателя
(shoppers.media, 5 мая 2025, https://shoppers.media/news/22249_afk-
sistema-prodala-rybopromyslennyi-xolding-vosxod): «Ранее Керимова не
была известна на рыбопромышленном рынке», «Не исключено, что она может
действовать в интересах АФК "Система", говорят три источника газеты».

Холдинг сменил владельца ПОВТОРНО (Коммерсантъ, 03.06.2026,
kommersant.ru/doc/8710295): «Владельцем 33% в ООО "РПХ "Восход"" в
апреле 2026 года стал ЗПИФ "Море Финанс" под управлением АО
"Инновационная компания НЗ"... 67% оставшихся на балансе этой структуры
долей в РПХ "Восход" перешли в залог ИК НЗ» — то есть Керимова/«Инсофт»
не продали контроль целиком, а разделили: 33% ушло новому держателю,
67% осталось у неё в залоге у того же держателя. `buyer`/`seller`
карточки НЕ переписаны: это отдельный, более поздний структурный шаг
(родня уже записанных карточек «Известные проблемы» о многоступенчатых
сделках — Федяев/Азот, Шишкарев/Дело), а не смена сторон ЭТОЙ сделки
(АФК «Система» → Керимова).

Та же статья даёт свежие финансы: «Выручка ООО "РПХ "Восход"" в 2025
году составила 228 млн руб., увеличившись год к году почти в два раза.
Чистый убыток сократился с 195,7 млн до 88,6 млн руб.», «Их совокупная
выручка в 2025 году достигла 4,38 млрд руб., снизившись год к году на
25,7%» — добавлено в `eco.target_fin`.

НЕ ВКЛЮЧЕНО: возможная связь Керимовой с Сулейманом Керимовым — ни
один проверенный источник её не подтверждает и не опровергает прямой
цитатой (это была бы собственная догадка, а не перенесённый факт).
Точная сумма ни одной из двух сделок по-прежнему не раскрыта, только
оценки (11–15 млрд ₽ и 12–14 млрд ₽ — тот же порядок, что уже стоял).
Результаты путины 2025/2026 годов отдельно не публиковались.

Запуск: python3 pipeline/fix_afk_sistema_voskhod_second_transfer.py
        python3 pipeline/fix_afk_sistema_voskhod_second_transfer.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g889e051d'

OLD_CONTEXT = (
    'АФК «Система» в 2021 году начала приобретать рыбопромышленные '
    'активы на Камчатке, вошедшие затем в РПХ «Восход». В ноябре 2023 '
    'года сообщалось, что 22,5% холдинга получило АО «Краунинвест» '
    'Ольги Зачиняевой. Но затем эта структура вышла из состава '
    'учредителей.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' «Ранее Керимова не была известна на рыбопромышленном рынке» — '
    '«Не исключено, что она может действовать в интересах АФК '
    '"Система", говорят три источника газеты» (shoppers.media, 5 мая '
    '2025 года). Холдинг сменил владельца повторно: «Владельцем 33% в '
    'ООО "РПХ "Восход"" в апреле 2026 года стал ЗПИФ "Море Финанс" под '
    'управлением АО "Инновационная компания НЗ"... 67% оставшихся на '
    'балансе этой структуры долей в РПХ "Восход" перешли в залог ИК НЗ» '
    '(Коммерсантъ, 3 июня 2026 года).'
)

OLD_TARGET_FIN = (
    'В 2024 году выручка предприятия составила 115,7 млн руб., чистый '
    'убыток — 195,7 млн руб. Совокупный оборот четырех подконтрольных '
    'ей структур (ООО «УК "Камчатка Проект"», «Викта», «Лойд Авто» и '
    '«Лойд Фиш») составил 4,85 млрд руб., сократившись за год на '
    '27,4%. В то же время РПХ «Восход» считается на рынке одним из '
    'крупнейших российских добытчиков тихоокеанского лосося. Основные '
    'активы компании находятся на Камчатке: 30 рыболовных участков, 6 '
    'заводов и более 35 кораблей. Эти мощности позволяют выпускать в '
    'год более 24 тыс. тонн готовой продукции, красной рыбы и икры.'
)
NEW_TARGET_FIN = OLD_TARGET_FIN + (
    ' В 2025 году выручка ООО «РПХ "Восход"» составила 228 млн руб., '
    'увеличившись почти в два раза; чистый убыток сократился с 195,7 '
    'млн до 88,6 млн руб. Совокупная выручка подконтрольных структур в '
    '2025 году — 4,38 млрд руб., снизившись на 25,7% (Коммерсантъ, '
    '3 июня 2026 года).'
)

NEW_SRC = [
    ['shoppers.media', 'https://shoppers.media/news/22249_afk-sistema-prodala-rybopromyslennyi-xolding-vosxod'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8710295'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    assert deal['eco']['target_fin'] == OLD_TARGET_FIN

    new_src = deal['src'] + NEW_SRC

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== eco.target_fin: станет ===')
    print(NEW_TARGET_FIN)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['eco']['target_fin'] = NEW_TARGET_FIN
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
