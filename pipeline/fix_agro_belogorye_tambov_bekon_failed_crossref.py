# -*- coding: utf-8 -*-
"""Месячная очередь качества, 11 сентября 2026 — карточка `cc399efaf`
(«Объединение животноводческих активов «Агро-Белогорья» и «Тамбовского
Бекона»», август 2023) описывает СОРВАННОЕ закрытие: «Владимир Зотов и
Лариса Ковалёва перестали выходить на связь и не явились на закрытие
сделки». Исход уже известен базе и полностью описан в двух других
карточках — сюжет с «Тамбовским Беконом» дальше не продолжился, вместо
этого «Русагро» через суд и последующий выкуп получила контроль над
самим «Агро-Белогорьем»:
  `g81a766ac` (27 сентября 2024, доля увеличена с 22,5% до 47,5% по
  решению суда) и `g97d9fa60` (13 ноября 2024, «Русагро» получила
  полный контроль, 77,5% за 31 млрд ₽).

Личный WebFetch подтвердил дословно
(meatinfo.ru, https://meatinfo.ru/news/rusagro-priobrela-775-gruppi-kompaniy-agro-484108):
«Компания РУСАГРО завершила сделку по покупке 77,5% акций группы
компаний «Агро-Белогорье» за сумму в 31 миллиард рублей»; «После
договоренности об объединении бизнеса ранее, бывшие совладельцы вышли
из сделки, что привело к нескольким судебным процессам».

`status` карточки не был заполнен вовсе — объединение с «Тамбовским
Беконом» в том виде, в каком его описывает карточка, не состоялось,
ставится «Не состоялась»; в `eco.context` добавлена короткая
фраза-мост к реальному исходу, без пересказа деталей (они уже в двух
других карточках).

Запуск:
    python3 pipeline/fix_agro_belogorye_tambov_bekon_failed_crossref.py            # сухой прогон
    python3 pipeline/fix_agro_belogorye_tambov_bekon_failed_crossref.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_ECO_CONTEXT = (
    'На последнем этапе оставалось лишь подписать согласованные '
    'документы, но Владимир Зотов и Лариса Ковалёва перестали выходить '
    'на связь и не явились на закрытие сделки.'
)
NEW_ECO_CONTEXT = OLD_ECO_CONTEXT + (
    ' Объединение с «Тамбовским Беконом» в этом виде не состоялось: '
    'вместо него «Русагро» через суд и последующий выкуп получила '
    'полный контроль над самим «Агро-Белогорьем» — 77,5% акций за '
    '31 млрд ₽, сделка закрыта в ноябре 2024 года.'
)


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['cc399efaf']

    assert d['eco']['context'] == OLD_ECO_CONTEXT, 'eco.context уже другой'
    assert d.get('status') is None, 'status уже занят: %r' % (d.get('status'),)

    print('cc399efaf: status -> Не состоялась, eco.context дополнен '
          'кросс-ссылкой на реальный исход (g81a766ac, g97d9fa60)')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['eco']['context'] = NEW_ECO_CONTEXT
    d['status'] = 'Не состоялась'

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
