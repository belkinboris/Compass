# -*- coding: utf-8 -*-
"""gafde5488 (Сбербанк/«НМ-Тех»): новый этап по ЕГРЮЛ — без смены статуса.

30 октября 2026 «Ведомости» (со ссылкой на источники, не на подтверждение
сторон) написали, что «НМ-тех» вошел в периметр «Интегральных систем»:
19 октября 2026 обе компании синхронно увеличили уставный капитал
(«НМ-тех» — с 288,4 млрд до 398,8 млрд руб.), в тот же день в ЕГРЮЛ
появились сведения о двух новых участниках «НМ-теха» (имена не раскрыты), а
7 октября — запись о корпоративном договоре, ограничивающем отчуждение
долей. Заголовок статьи сам хедж («возможно, перешел») — вывод построен на
анонимных источниках и косвенной выписке ЕГРЮЛ, а не на подтверждении
Сбербанка, ВЭБ.РФ или самого «НМ-теха»; независимого подтверждения другими
изданиями найти не удалось (WebSearch, 30 октября 2026).

ПОЧЕМУ СТАТУС НЕ ТРОГАЕМ. Слово «перешел» механически входит в
STATUS_WORDS['Закрыта'] (review.py) — и `enrich.py` на одном заголовке
поднял бы статус до «Закрыта» не глядя на «возможно» и на то, что источники
анонимны. Это ровно тот случай, для которого в рутине есть дочитывание
человеком: карточка остается «Обсуждается», а новый этап записывается как
`negotiations` (не входит в `POSTWORTHY_MILESTONE_KINDS` — отдельного поста
в канал это не вызывает, и это сознательное решение, не недосмотр).

Это ОБОГАЩЕНИЕ уже описанной сделки, а не новая карточка: `promote.py`
придержал черновик d50566545 с тем же заголовком как «на решение» (не
установлен предмет механически), но стороны — те же самые, что у gafde5488
(покупатель «Интегральные системы»/ga71b47eb, предмет «НМ-Тех»/gff89c3d4)."""
import json

PATH = "static/data/deals_promoted.json"
URL = "https://www.vedomosti.ru/technology/articles/2026/10/30/1241368-nm-teh-pereshel-pod-kontrol"


def main():
    data = json.load(open(PATH, encoding="utf-8"))
    card = next(d for d in data["deals"] if d["id"] == "gafde5488")
    assert not any(e.get("date") == "2026-10-30" for e in card.get("events") or []), \
        "событие от 30 октября уже есть — повторный запуск не нужен"
    event = {
        "kind": "negotiations",
        "date": "2026-10-30",
        "title": "Косвенные признаки смены контроля",
        "note": ("«Ведомости» со ссылкой на анонимные источники написали, что «НМ-тех» "
                 "вошел в периметр «Интегральных систем»: 19 октября 2026 года уставный "
                 "капитал «НМ-теха» увеличился с 288,4 млрд до 398,8 млрд руб., в тот же "
                 "день в ЕГРЮЛ внесены сведения о двух новых участниках «НМ-теха» без "
                 "раскрытия имен, а 7 октября — запись о корпоративном договоре, "
                 "ограничивающем отчуждение долей; по данным издания, «Интегральные "
                 "системы» нарастили капитал на ту же сумму. Само издание называет "
                 "переход контроля предположением — ни Сбербанк, ни ВЭБ.РФ, ни «НМ-тех» "
                 "эту сделку публично не подтверждали."),
        "source": ["Ведомости", URL],
    }
    card.setdefault("events", []).append(event)
    if not has_source(card, URL):
        card["src"].append(["Ведомости", URL])
    json.dump(data, open(PATH, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("Событие добавлено: gafde5488, 2026-10-30, kind=negotiations (статус не менялся).")


def has_source(card, url):
    return any(len(s) > 1 and s[1] == url for s in card.get("src") or [])


if __name__ == "__main__":
    main()
