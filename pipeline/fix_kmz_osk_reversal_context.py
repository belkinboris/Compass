# -*- coding: utf-8 -*-
"""Месячная очередь, карточка g5dc6cb47 (ОСК приобрела Кингисеппский
машиностроительный завод у семьи Даниленко, июль 2025): дельта-поиск
нашёл, что сделка имеет продолжение, которого карточка не знала вовсе —
в январе 2026 года ОСК вышла из капитала КМЗ, вернув 99,9% доли ООО
«Назия» прежней владелице, Татьяне Даниленко (родственнице основателя
КМЗ Михаила Даниленко); при этом её доля осталась в залоге у ОСК.

Это НЕ повод менять статус карточки на «Не состоялась» — сама сделка
(июль 2025) закрылась и была реальной, статус «Закрыта» относится
именно к НЕЙ. Возврат доли полгода спустя — отдельное, более позднее
событие, того же рода, что уже зафиксированная в других карточках этой
сессии дальнейшая судьба актива (ср. Сбер/«Еаптека» → RWB/Wildberries).
Обе стороны рассказали о выходе без взаимных претензий: сам Михаил
Даниленко называет полгода сотрудничества «эффективными» и говорит, что
похожие проекты впредь можно делать без вхождения ОСК в капитал; в ОСК
при этом, по данным Фонтанки, «так и не смогли пояснить», зачем
корпорации нужно было покупать актив на такое короткое время. За время
владения ОСК на заводе резко обострился и без того существовавший
кризис с зарплатой (долг вырос до ~300 млн ₽, к ноябрю ОСК выделила
500 млн ₽ на расчёт с сотрудниками за август–сентябрь).

Не через review.py: поле eco.context уже несёт содержание, новые факты
из нескольких источников не образуют с ним непрерывный кусок текста.

Источники — читал напрямую (fetch_article_texts.py, закэшированы):
https://www.fontanka.ru/2026/01/14/76215445/
https://www.fontanka.ru/2025/11/09/76111870/

Запуск: python3 pipeline/fix_kmz_osk_reversal_context.py [--write]
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g5dc6cb47'

OLD_CONTEXT = 'По данным сервиса «Контур.Фокус», 100% КМЗ принадлежат ООО «Назия».'
CONTEXT_ADDITION = (
    'В январе 2026 года, по данным ЕГРЮЛ, произошли обратные изменения: '
    '99,9% доли ООО «Назия» были возвращены от ОСК прежней владелице, '
    'Татьяне Даниленко (родственнице основателя КМЗ Михаила Даниленко), '
    'при этом её доля осталась в залоге у ОСК. Сам Михаил Даниленко '
    'назвал полгода сотрудничества «эффективными» и заявил, что похожие '
    'проекты впредь можно делать «без вхождения в наш капитал». По '
    'данным «Фонтанки», в ОСК так и не смогли пояснить, зачем корпорации '
    'нужно было покупать актив на такое короткое время. За время '
    'владения ОСК на заводе обострился кризис с зарплатой — долг перед '
    'сотрудниками вырос до ~300 млн ₽, и в конце ноября 2025 года ОСК '
    'выделила заводу 500 млн ₽ на расчёт с сотрудниками за '
    'август–сентябрь.'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + CONTEXT_ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} eco.context: += возврат доли ОСК Даниленко (январь "
          f"2026) и кризис с зарплатой в период владения ОСК")
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
