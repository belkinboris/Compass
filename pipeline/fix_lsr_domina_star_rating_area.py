# -*- coding: utf-8 -*-
"""Разовая правка g7bbe19c2 (ЛСР/Domina Пулково): звёздность и площадь.

ЧТО СЛОМАНО. `eco.share` называл отель «4-звёздочным» площадью «56 тыс. кв. м».
Оба числа неверны — три независимых источника (Интерфакс/smart-lab.ru,
TAdviser со ссылкой на РБК Петербург, dp.ru) согласно называют отель
ПЯТИЗВЁЗДОЧНЫМ площадью ~43,75–43,8 тыс. кв. м:
  - smart-lab.ru (Интерфакс, 07.05.2026): «Группа ЛСР приобрела 100% долей
    ООО «Пулково Скай», владеющего пятизвездочным отелем «Domina Пулково»
    на 253 номера в Санкт-Петербурге».
  - TAdviser (со ссылкой на РБК Петербург): «Группа ЛСР... приобрела
    пятизвездочный гостиничный комплекс «Domina Пулково»... общая площадь
    комплекса — 43,8 тыс. кв. м».
  - dp.ru (29.04.2026, Евгений Войтенков): «Общая площадь комплекса
    "Domina Пулково" — 43,75 тыс. м2».

ПОЧЕМУ НЕ ЧЕРЕЗ review.py. Число номеров/апартаментов/нежилых помещений в
текущем тексте УЖЕ верно (253/470/83 — подтверждено теми же источниками),
неверны только звёздность и площадь. Но review.py требует, чтобы ВСЁ поле
целиком дословно лежало в ОДНОЙ цитате источника, а полная фраза карточки
(две компании-владельца + звёздность + площадь + номера + дата ЕГРЮЛ)
собрана из нескольких статей — ни в одной нет всех фактов одним куском.
Правка точечная (замена двух чисел/слов в уже верном по структуре
предложении), а не перенос нового факта, поэтому делается прямой заменой
с `assert` на исходный текст, а не таблицей `FIXES`.

Запуск:
    python3 pipeline/fix_lsr_domina_star_rating_area.py            # сухой прогон
    python3 pipeline/fix_lsr_domina_star_rating_area.py --write    # запись
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(ROOT)
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

OLD = ('Группа ЛСР приобрела 100% долей ООО «Пулково Скай» и ООО «УК Статус», '
       'владеющих гостиничным комплексом Domina Пулково в Санкт-Петербурге — '
       '4-звёздочным отелем площадью 56 тыс. кв. м с 253 номерами, 470 '
       'апартаментами и 83 нежилыми помещениями. Договор подписан 27 апреля '
       '2026 года, изменения внесены в ЕГРЮЛ 7 мая 2026 года.')

NEW = ('Группа ЛСР приобрела 100% долей ООО «Пулково Скай» и ООО «УК Статус», '
       'владеющих гостиничным комплексом Domina Пулково в Санкт-Петербурге — '
       '5-звёздочным отелем площадью 43,75 тыс. кв. м с 253 номерами, 470 '
       'апартаментами и 83 нежилыми помещениями. Договор подписан 27 апреля '
       '2026 года, изменения внесены в ЕГРЮЛ 7 мая 2026 года.')


def main(argv):
    data = json.load(open(DATA, encoding='utf-8'))
    card = next(d for d in data['deals'] if d['id'] == 'g7bbe19c2')

    assert card['eco']['share'] == OLD, 'исходный текст eco.share уже другой'

    print('БЫЛО:', repr(card['eco']['share']))
    print('СТАНЕТ:', repr(NEW))

    if '--write' not in argv:
        print('\nСухой прогон. Запись — с ключом --write.')
        return 0

    card['eco']['share'] = NEW
    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('ЗАПИСАНО.')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
