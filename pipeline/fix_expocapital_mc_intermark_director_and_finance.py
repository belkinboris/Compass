import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g4ce32808'

OLD_EXTRA = (
    'Фонд ExpoCapital (принадлежащий Игорю Киму) приобрёл 100% долей '
    'российской лизинговой компании японской Mitsubishi – MC Intermark '
    'Auto; изменения зафиксированы в ЕГРЮЛ, датой появления нового '
    'учредителя указано 3 ноября 2023 года.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Гендиректор сменился: Леонид Сысоев покинул пост 16 октября 2025 '
    'года, новый директор — Алексей Дигай. Бизнес растёт: выручка за '
    '2025 год — 2,94 млрд ₽ (+18,8%), чистая прибыль — 183,7 млн ₽ '
    '(+69,6%). По рейтингу «Эксперт РА» на начало 2025 года компания '
    'занимает 63-е место среди лизинговых компаний по общему портфелю '
    'и 10-е — по портфелю оперативного лизинга.'
)

OLD_LAW_TERMS = 'Гендиректором по-прежнему числится Леонид Сысоев.'
NEW_LAW_TERMS = (
    'Леонид Сысоев покинул пост гендиректора 16 октября 2025 года; новый '
    'директор — Алексей Дигай.'
)

NEW_SRC = [
    ['Vbankcenter.ru', 'https://vbankcenter.ru/contragent/1077762679631'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA
    assert deal['law']['terms'] == OLD_LAW_TERMS

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== law.terms: станет ===')
    print(NEW_LAW_TERMS)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['law']['terms'] = NEW_LAW_TERMS
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
