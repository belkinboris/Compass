# -*- coding: utf-8 -*-
"""`g6743f902` (АО «Трамплин Холдинг» купил 51% ООО «Мальт Систем») —
владелец 11 сентября 2026: в опубликованном посте «в предмете написан
неправильный падеж «дизайн-центра»».

Текст `eco.share` — «51% ООО «Мальт Систем» — дизайн-центра микроэлектроники
с архитектурой Malt-C...» — родительный падеж «дизайн-центра» здесь
скопирован из ЗАГОЛОВКА («купил 51% дизайн-центра «Мальт Систем»»), где он
верен (управляется глаголом «купил»). В `eco.share` то же слово стоит БЕЗ
управляющего глагола — это самостоятельная подпись предмета сделки под
надписью «Предмет:», и она обязана читаться в именительном падеже: «51% ООО
«Мальт Систем» — дизайн-центр микроэлектроники...» (родня уже записанного в
CLAUDE.md правила про падеж предмета, вырезанного подстрокой из заголовка —
здесь тот же дефект, но текст не вырезан автоматически, а переписан
читателем-агентом приёмки и унаследовал падеж источника). Заголовок (`title`)
не трогаем — там «дизайн-центра» правильно.

Проверено по всей базе: `[»"]\\s*—\\s*дизайн-центра\\b` (закрывающая кавычка
или прямая, потом тире, потом слово) — совпадение только здесь.

Запуск:
    python3 pipeline/fix_tramplin_maltsystem_asset_case.py
    python3 pipeline/fix_tramplin_maltsystem_asset_case.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(ROOT)
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g6743f902'

OLD_SHARE = ('51% ООО «Мальт Систем» — дизайн-центра микроэлектроники с '
             'архитектурой Malt-C для потоковой обработки сетевого трафика '
             'и криптопреобразований.')
NEW_SHARE = ('51% ООО «Мальт Систем» — дизайн-центр микроэлектроники с '
             'архитектурой Malt-C для потоковой обработки сетевого трафика '
             'и криптопреобразований.')


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    deal = next((d for d in data['deals'] if d['id'] == DEAL_ID), None)
    assert deal is not None, '%r не найдена' % DEAL_ID
    assert deal['eco'].get('share') == OLD_SHARE, (
        'eco.share изменился, ожидали %r, сейчас %r' % (OLD_SHARE, deal['eco'].get('share')))

    print('ПРАВИМ %r: eco.share — «дизайн-центра» -> «дизайн-центр» '
          '(именительный, самостоятельная подпись предмета без управляющего '
          'глагола)' % DEAL_ID)

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    deal['eco']['share'] = NEW_SHARE

    json.dump(data, open(DATA, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
