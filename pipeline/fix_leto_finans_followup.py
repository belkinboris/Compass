# -*- coding: utf-8 -*-
"""«Лето Финанс»/«МедТехСервис» (`gc991514e`): месячный дообыск нашёл две
вещи — одну содержательную, одну исправляющую дефект.

ИСПРАВЛЕНИЕ ДЕФЕКТА. `extra` нёс скобку «(связанная с Артемом Чайкой
через управляющую компанию УК «Дальний Восток»)» — утверждение о реальном
публичном человеке. Единственный источник карточки (Интерфакс,
interfax.ru/business/945677) этого не говорит вовсе: он прямо называет
владельцем «Лето Финанс» Анастасию Романову (это уже верно записано в
`eco.context`), а УК «Дальний Восток» упоминает только как управляющую
компанию ДВУХ ДРУГИХ фирм Романовой («Недра М», «Палладиум») — про Чайку
там ни слова. Прямой WebFetch того же URL и два независимых WebSearch-а
21 августа не нашли НИ ОДНОГО источника, подтверждающего связь Чайки с
«Лето Финанс». Это тот же класс дефекта, что уже чинился для Sokolov/
Антона Пака (`fix_sokolov_field_contamination.py`) — заявление, дословно
не выводимое из своего источника, — только здесь скобка была вписана
рядом с верным фактом, а не подменила его. Убираем непроверяемую скобку,
не трогая остальной текст.

НОВЫЙ ФАКТ. Финансовые показатели завода за 2024–2025 годы и январская
консолидация доли Петра Железнякова — из Vademecum, источник, не
процитированный в карточке раньше. `eco.target_fin` и `law.struct` уже
заняты — дословно объединить с цитатой из другого источника `review.py`
не может, правка разовым скриптом.

Запуск: python3 pipeline/fix_leto_finans_followup.py           # проверка
        python3 pipeline/fix_leto_finans_followup.py --write   # запись
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gc991514e'

OLD_EXTRA = (
    'Закрытие сделки: ООО «Лето Финанс» (связанная с Артемом Чайкой через '
    'управляющую компанию УК «Дальний Восток») приобрела 50% в иркутском '
    'ООО «МедТехСервис», производителе тест-полосок для глюкометров и '
    'самих глюкометров. Продавцами выступили Сергей Дьяченко (17%), '
    'Федор Железняков (17%) и Петр Железняков (16%).')
NEW_EXTRA = (
    'Закрытие сделки: ООО «Лето Финанс» приобрела 50% в иркутском ООО '
    '«МедТехСервис», производителе тест-полосок для глюкометров и самих '
    'глюкометров. Продавцами выступили Сергей Дьяченко (17%), Федор '
    'Железняков (17%) и Петр Железняков (16%).')

OLD_TARGET_FIN = (
    '«МедТехСервис» в конце 2018 года при финансовой поддержке КРИО ввел '
    'в эксплуатацию в Иркутске завод по производству тест-полосок для '
    'глюкометров, его стоимость оценивалась в 373 млн рублей. Линия для '
    'производства тест-полосок была поставлена и смонтирована '
    'южнокорейской компанией B-Bio. Мощность производства составила до 3 '
    'млн упаковок тест-полосок в год. Первые поставки завод начал в '
    'августе 2019 года.')
NEW_TARGET_FIN = OLD_TARGET_FIN + (
    ' По данным СПАРК-Интерфакс, выручка завода в 2024 году составила '
    '1,057 млрд рублей, чистая прибыль – 82,3 млн рублей.')

OLD_STRUCT = (
    'При этом, согласно заключенным договорам, «Лето Финанс» передало '
    'недавно полученные доли в залог Железняковым и Дьяченко, которые '
    'владеют оставшимися 50% в «МедТехСервисе».')
NEW_STRUCT = OLD_STRUCT + (
    ' В январе 2025 года Петр Железняков консолидировал долю до 50%, при '
    'этом передал ее в залог Сергею Дьяченко.')

NEW_SRC = ['Vademecum', 'https://vademec.ru/news/2025/08/28/'
           'upravlentsev-irkutskogo-medtekhservisa-zapodozrili-v-'
           'khishchenii-65-mln-rubley/']


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    card = next((c for c in data['deals'] if c['id'] == CARD_ID), None)
    assert card is not None, '%r не найдена в базе' % CARD_ID
    assert card.get('extra') == OLD_EXTRA, (
        'extra изменился с ожидаемого: %r' % card.get('extra'))
    assert card['eco'].get('target_fin') == OLD_TARGET_FIN, (
        'eco.target_fin изменился с ожидаемого: %r' % card['eco'].get('target_fin'))
    assert card['law'].get('struct') == OLD_STRUCT, (
        'law.struct изменился с ожидаемого: %r' % card['law'].get('struct'))
    src = card.setdefault('src', [])
    print('ЧИНИМ   %s: extra — снята непроверяемая скобка про Артёма Чайку' % CARD_ID)
    print('ПРАВИМ  %s: eco.target_fin — финансы завода за 2024 год' % CARD_ID)
    print('ПРАВИМ  %s: law.struct — консолидация доли Железнякова (январь 2025)' % CARD_ID)
    if write:
        card['extra'] = NEW_EXTRA
        card['eco']['target_fin'] = NEW_TARGET_FIN
        card['law']['struct'] = NEW_STRUCT
        if NEW_SRC not in src:
            src.append(NEW_SRC)
        json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
        print('ЗАПИСАНО')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
