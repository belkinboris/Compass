import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gda61c5b8'
OLD_CONTEXT = (
    'Торги назначены на 21 мая, заявки принимаются до 8 мая. Цена '
    'актива составляет 280,8 млрд руб.'
)
ADDITION = (
    'Торги не состоялись: «к установленному извещением и документацией '
    'о торгах сроку окончания подачи заявок на участие в торговой '
    'процедуре… не подано ни одной заявки на участие в торгах, в связи с '
    'чем процедура проведения торгов не состоялась». Начальная цена была '
    'установлена на уровне 280,8 млрд руб. Эксперты объясняют провал '
    'ценой: руководитель направления офисной недвижимости IBC Real '
    'Estate Николай Горюнов считает, что «дисконт в 30% мог бы '
    'простимулировать интерес инвесторов», директор департамента офисной '
    'недвижимости NF Group Марина Малахатько называет ориентиром «дисконт '
    'на уровне около 25%». Инвестбанкир Арик Шабанов формулирует общий '
    'вывод: «Инвестору важна не разница между ценами покупки и продажи, а '
    'экономика самого актива» и «Несостоявшийся аукцион показывает, что '
    'инвесторы не готовы автоматически принимать заявленную цену».'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} eco.context: += провал майских торгов и мнения экспертов")
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
