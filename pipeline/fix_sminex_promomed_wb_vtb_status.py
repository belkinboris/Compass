import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_VAL_SMINEX = (
    'Партнёр NF Group Станислав Бибик считает цену рыночной. '
    'Управляющий партнёр Alto Real Estate Fund Наталия Тишендорф '
    'согласна с этим, но оговаривается: актив привлекателен для '
    'инвесторов только при условии, что здание в хорошем состоянии и '
    'не обременено долгом. Руководитель департамента рынков капитала и '
    'инвестиций IBC Real Estate Микаэл Казарян добавляет, что офисы в '
    'Хамовниках стоят до 300 000 ₽ за 1 кв. м, то есть за бизнес-центр '
    'на территории «Московского шёлка» можно выручить около 5,5 млрд ₽.'
)
NEW_VAL_SMINEX = OLD_VAL_SMINEX + (
    ' Сделка закрылась в 2024 году — покупателем стал энергохолдинг '
    '«Интер РАО» (сообщено в декабре 2024 года), точная цена не '
    'раскрыта: 4,8 млрд ₽ — это апрельская запрошенная цена, независимые '
    'источники оценивают саму сделку в диапазоне 4,2–5 млрд ₽.'
)

OLD_DATE_PROMOMED = '2024'
NEW_DATE_PROMOMED = '2026-04-30'


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    wb = by_id['c51d0bb64']
    sminex = by_id['ce4180b68']
    promomed = by_id['c7996afb5']

    assert wb.get('status') is None, 'c51d0bb64 status уже занят: %r' % (wb.get('status'),)
    assert sminex.get('status') is None, 'ce4180b68 status уже занят: %r' % (sminex.get('status'),)
    assert sminex['eco']['val'] == OLD_VAL_SMINEX, \
        'ce4180b68 eco.val уже другой: %r' % (sminex['eco']['val'],)
    assert promomed['date'] == OLD_DATE_PROMOMED, \
        'c7996afb5 date уже другая: %r' % (promomed['date'],)
    assert promomed.get('status') is None, 'c7996afb5 status уже занят: %r' % (promomed.get('status'),)

    print('c51d0bb64: status None -> "Обсуждается"')
    print('ce4180b68: status None -> "Закрыта"; eco.val дополнен (покупатель '
          '«Интер РАО», цена не раскрыта)')
    print('c7996afb5: date %r -> %r (ошибка года); status None -> "Закрыта"' %
          (OLD_DATE_PROMOMED, NEW_DATE_PROMOMED))

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    wb['status'] = 'Обсуждается'
    sminex['status'] = 'Закрыта'
    sminex['eco']['val'] = NEW_VAL_SMINEX
    promomed['date'] = NEW_DATE_PROMOMED
    promomed['status'] = 'Закрыта'

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
