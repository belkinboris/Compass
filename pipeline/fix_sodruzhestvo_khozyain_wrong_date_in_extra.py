# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g55a86137
(«ГК «Содружество» приобрела ООО «Хозяин» в Красноярском крае») — поле
`extra` несло «Сделка закрыта в июле 2023», хотя `date` карточки — «2024»,
а `eco.context` уже верно говорит «в январе 2024 года» — внутреннее
противоречие в самой карточке.

Проверено лично прямым WebFetch (Коммерсантъ, https://www.kommersant.ru/doc/6564254
— тот же источник, что уже стоит в `src`, опубликован 15.03.2024):
«Входящее в ГК «Содружество» ООО «Содружество-Сибирь» в январе стало
владельцем переработчика зерна и масличных ООО «Хозяин» в Ачинске
Красноярского края» — слово «июль»/«2023» в статье не встречается
вообще, «в январе» здесь означает январь 2024 года (статья от марта
2024-го). Также подтверждено: «"Содружество" может наращивать
переработку этой культуры в регионе в первую очередь для экспорта в
Китай» — эта цель (Китай) раньше не была перенесена в карточку.

«Июль 2023» — реальная дата, но из ДРУГОГО, более раннего события в
истории того же юрлица: по данным реестровых агрегаторов (ЕГРЮЛ, не
дословная цитата Коммерсанта, поэтому не переносится как факт этой
сделки), в июле 2023 года прежний владелец ООО «Хозяин» Владимир Шестак
вышел из состава учредителей в пользу промежуточных структур — событие,
не имеющее отношения к ГК «Содружество», которая приобрела компанию
только полгода спустя, в январе 2024 года. Похоже, кто-то из прежних
правщиков нашёл в реестре дату этого промежуточного шага и по ошибке
приписал её сделке с «Содружеством» — родня уже записанного в CLAUDE.md
класса «число из чужого абзаца/чужого события».

НЕ ВКЛЮЧЕНО: личность продавца (промежуточные держатели «Транссервис»/
«Регионагро» по данным реестровых агрегаторов) и финансовые показатели
после сделки — это уже не из основного источника (Коммерсанта), а из
вторичных реестровых агрегаторов, которые к тому же расходятся в
точных суммах между собой; переносить без прямого дословного
подтверждения не стал.

Запуск: python3 pipeline/fix_sodruzhestvo_khozyain_wrong_date_in_extra.py
        python3 pipeline/fix_sodruzhestvo_khozyain_wrong_date_in_extra.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g55a86137'

OLD_EXTRA = (
    'Сделка закрыта в июле 2023. ГК «Содружество» (один из основных '
    'переработчиков соевых бобов и рапса в России) приобрела 100% долей '
    'ООО «Хозяин» — переработчика зерна и масличных культур в '
    'Красноярском крае с мощностью более 10 тыс. тонн муки в год.'
)
NEW_EXTRA = (
    'Сделка закрыта в январе 2024 года — точный день реестр не '
    'называет. ГК «Содружество» (один из основных переработчиков соевых '
    'бобов и рапса в России) приобрела 100% долей ООО «Хозяин» — '
    'переработчика зерна и масличных культур в Красноярском крае с '
    'мощностью более 10 тыс. тонн муки в год.'
)

OLD_ECO_RATIONALE = (
    'Источник «Ъ» на рынке отмечает, что «Хозяин» может быть интересен '
    '«Содружеству» как стартовая площадка для развития переработки '
    'рапса в регионе'
)
NEW_ECO_RATIONALE = OLD_ECO_RATIONALE + (
    ' — в первую очередь для экспорта в Китай.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA
    assert deal['eco']['rationale'] == OLD_ECO_RATIONALE

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== eco.rationale: станет ===')
    print(NEW_ECO_RATIONALE)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['eco']['rationale'] = NEW_ECO_RATIONALE
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
