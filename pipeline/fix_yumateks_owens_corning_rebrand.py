import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gf5101b05'

OLD_ECO_CONTEXT = (
    'Завод стекловолокна работает в Гусь-Хрустальном Владимирской '
    'области, завод теплоизоляции из каменной ваты — в Тверской области.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' Белорусский актив оказался не заводом, а '
    'небольшой сбытовой компанией «Оуэнс Корнинг Бел» в Минске (около '
    'пяти сотрудников) — сейчас она называется «Юматекс Бел». Оба '
    'российских завода тоже сменили бренд: изоляция из каменной ваты '
    'теперь продаётся под маркой «Юматекс Термо» вместо Parok, а завод '
    'стекловолокна называется «Росатом Стекловолокно» — в декабре 2025 '
    'года на его площадке открылся исследовательский центр по разработке '
    'стекловолокна и композитов.'
)

OLD_SRC = [['ПРАЙМ', 'https://1prime.ru/business/20221206/839071691.html']]
NEW_SRC = OLD_SRC + [
    ['Sputnik Беларусь', 'https://sputnik.by/20221212/aktivy-amerikanskoy-owens-corning-v-belarusi-pereshli-k-rosatomu-1070018605.html'],
    ['Атомная энергия 2.0', 'https://www.atomic-energy.ru/news/2025/12/19/162037'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
