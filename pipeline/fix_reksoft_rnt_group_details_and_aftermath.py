import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g9445a221'

OLD_LAW_STRUCT = (
    'В объем работы юристов входили: проведение юридической проверки, '
    'составление документации (право России и Гонконга) по сделке, '
    'поддержка файлинга в Правительственную комиссии и ФАС России, а '
    'также тесное взаимодействие с финансовой и коммерческой командой и '
    'представителями продавца'
)
NEW_LAW_STRUCT = OLD_LAW_STRUCT + (
    '. По данным ЕГРЮЛ, приобретённый актив находился в залоге у EPAM '
    'Systems Inc.; в «Рексофте» пояснили, что это технический нюанс '
    'сделки и залог будет снят после завершения расчётов. Даты закрытия '
    'расходятся у сторон: по ЕГРЮЛ сделка состоялась 2 августа 2023 '
    'года, тогда как сама EPAM Systems сообщала о завершении продажи '
    'российского бизнеса 26 июля.'
)

OLD_ECO_VAL = (
    'Стоимость сделки (руб./$): не раскрывается (согласно открытым '
    'источникам — $101,5–152,2 млн)'
)
NEW_ECO_VAL = OLD_ECO_VAL + (
    '; аналитик s20 Capital Андрей Шарлай оценивал стоимость компании '
    'классическими методами в 10–15 млрд ₽, но с оговоркой, что из-за '
    'сокращения активов и штата и желания собственников продать актив '
    'быстро фактическая сумма могла быть на порядок меньше'
)

OLD_ECO_CONTEXT = (
    '«Рексофт» (Reksoft) — один из ведущих российских разработчиков '
    'цифровых решений для таких сфер как банки и финансы, госсектор, '
    'ритейл, транспорт, логистика, IT, телеком, медиа, гостиничный '
    'бизнес. По данным на август 2022 года 20% ООО принадлежит '
    'структуре «Интерроса» Владимира Потанина'
)
NEW_ECO_CONTEXT = OLD_ECO_CONTEXT + (
    '. Эта доля — остаток от продажи: в апреле 2022 года сооснователь '
    '«Рексофта» Александр Егоров продал «Интерросу» 40% компании (сумму '
    'стороны не раскрыли, эксперты оценивали долю в 2–3 млрд ₽). EPAM '
    'планировала отразить от продажи убыток около $18,4 млн, включая '
    'накопленный убыток от курсовых разниц, — это бухгалтерский убыток '
    'продавца, а не цена сделки. После закрытия выручка группы '
    '«Рексофт» выросла: 3,35 млрд ₽ и 1500 сотрудников в 2023 году, '
    '6,77 млрд ₽ в 2024-м, 7,35 млрд ₽ в 2025-м. По словам гендиректора '
    'Александра Егорова, ключевым событием 2024 года стало завершение '
    'интеграции команд, влившихся в «Рексофт» в 2022–2023 годах, включая '
    'RNT Group, — отдельный бренд RNT Group после этого в новостях '
    'компании не встречается.'
)

NEW_SRC = [
    ['РБК', 'https://companies.rbc.ru/news/BWDIhOxXMt/itogi-2024-goda-reksoft-vyiruchka-udvaivaetsya-vtoroj-god-podryad/'],
    ['Рексофт', 'https://www.reksoft.com/news/reksoft-summed-up-the-results-of-2025/'],
    ['Roem.ru', 'https://roem.ru/04-08-2023/300268/rossijskij-biznes-epam/'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/5318257'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['law']['struct'] == OLD_LAW_STRUCT
    assert deal['eco']['val'] == OLD_ECO_VAL
    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    new_src = deal['src'] + NEW_SRC

    print('=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)
    print('\n=== eco.val: станет ===')
    print(NEW_ECO_VAL)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['law']['struct'] = NEW_LAW_STRUCT
        deal['eco']['val'] = NEW_ECO_VAL
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
