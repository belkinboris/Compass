# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g2b6c37c1
(ГК «Солар»/«Ростелеком» приобрела 28,57% Secure-T) — единственный
источник карточки оказался статьёй о СОВСЕМ ДРУГОЙ сделке.

Проверено лично прямым WebFetch. Ссылка `https://www.cnews.ru/news/top/
2020-08-31_rostelekom_pokupaet_polovinu` (слаг несёт дату 2020-08-31 —
на четыре года раньше даты карточки, 2024-03-28) при прямом чтении
оказалась статьёй о покупке «Ростелекомом» 49% «Элвис-Плюс» в 2020 году:
ни слова о Secure-T, «Секьюр-Ти», ГК «Солар» или «Солар-ПТ» в тексте нет.
Тот же класс дефекта, что уже описан в CLAUDE.md («источник — то, что
подтверждает факт, а не то, как о нём узнали» / «домен без пути») —
здесь ссылка не голый домен, а рабочая статья, просто не про эту сделку.

Настоящий источник найден WebSearch и проверен прямым WebFetch —
Интерфакс (https://www.interfax.ru/business/953431) подтверждает
ВСЕ факты карточки дословно: долю 28,57%, дату регистрации 28 марта,
основателей Харитона Никишкина (44,64%) и Сергея Шахова (26,79%),
контекст инвестпрограммы на 22 млрд рублей и формулировку «третья
M&A-сделка» после «Элвис-Плюс» и «НТБ», финансовые показатели «Секьюр-
Ти» за 2023 год (выручка 54,7 млн ₽, чистая прибыль 33,8 млн ₽). Сами
факты карточки, таким образом, не выдуманы — только ссылка была не той
статьёй.

НЕ ВКЛЮЧЕНО: рост доли «Солар» с 28,57% до контрольных 51% (Никишкин и
Шахов якобы размылись до 24,5% каждый, май 2024 года) — правдоподобный
следующий шаг (в `extra` карточки уже описан опцион на 23%, который при
реализации довёл бы долю до контрольной), найден через WebSearch
(TAdviser: «"Солар" стал владельцем 51% разработчика решений в сфере
киберграмотности Secure-T»), но прямой WebFetch статьи TAdviser вернул
404 четырьмя отдельными попытками (два прямых захода на URL, попытка
через RB.RU данные Никишкина — доли не называет вовсе, и повторный заход
на TAdviser). Единственный фактически прочитанный источник по теме
(anti-malware.ru, 2024-04-01) подтверждает только исходные 28,57% и
прямо пишет «Величина и доля не объявлены» про опцион — рост до 51% им
не подтверждён. Без дословного прочтения основного источника факт не
записывается — только замена неверной ссылки.

Запуск: python3 pipeline/fix_secure_t_wrong_source.py
        python3 pipeline/fix_secure_t_wrong_source.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g2b6c37c1'

OLD_SRC = [
    ['CNews', 'https://www.cnews.ru/news/top/2020-08-31_rostelekom_pokupaet_polovinu'],
]
NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/business/953431'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['src'] == OLD_SRC, deal['src']

    print('=== src: было ===')
    print(OLD_SRC)
    print('=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
