# -*- coding: utf-8 -*-
"""Снимает недостоверную сумму сделки у карточки gc10da566 («Деметра-холдинг
приобрел элеватор ООО «Наш Союз» в Орловской области»).

Найдено в рамках G5 (PRODUCT_ROADMAP.md): замер на бессодержательные
плейсхолдеры eco.val дал 10 карточек, из которых у трёх сумма не
подтверждается их же единственным источником вообще. Здесь — именно
такой случай: единственный источник (poleinvest.ru, кэш уже на диске,
`fetch_article_texts.py`) описывает элеватор и планы модернизации, но НЕ
СОДЕРЖИТ ни одной цифры про деньги — ни цены, ни оценки, ни слова
«стоимость». Проверено дважды: чтением кэша и отдельным WebSearch
(«Наш Союз» Верховье Орловская сумма сделки) — ни dholding.ru (офиц.
пресс-релиз покупателя), ни agroinvestor.ru, ни другие найденные
материалы не называют сумму этой сделки.

ВАЖНО — ловушка, в которую чуть не попал этот же прогон: WebSearch по
теме сначала выдал похожую с виду статью glavagronom.ru «Деметра-холдинг
стал владельцем ещё одного элеватора» с фразой «сумма которой не
разглашается» — но при прямой проверке кэша выяснилось, что эта статья
ПРО ДРУГУЮ СДЕЛКУ: покупку «Дишнинского элеватора» (тоже в Орловской
области, но другое юрлицо, ноябрь 2022 года), а не «Наш Союз» (октябрь
2024). Использовать её цитату здесь было бы тем же классом ошибки, что
уже найден в этом же прогоне на карточке g778efcb9 (источник не про ту
сделку) — поэтому она НЕ используется, и сумма снимается как честно
неподтверждённая, а не заменяется чужой цитатой.

`extra` этой же карточки называет выручку предприятия за 2023 год
(«1 млрд руб.») — похоже, именно она стала основой ошибочно
подтянутой цены сделки («до 1,2 млрд ₽»); это ещё один самостоятельный
признак того, что число — не цена сделки, а величина другого порядка,
перенесённая не в то поле.

Заодно снимается `eco.val` («По оценке экспертов») — раз самой оценки
нет ни в одном источнике, поле не может утверждать, что она есть.
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gc10da566'
OLD_SUM = 'до 1,2 млрд ₽ (по оценке)'
NEW_SUM = 'Не раскрыта'
OLD_VAL = 'По оценке экспертов'
NEW_VAL = '—'


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['sum'] == OLD_SUM, f"sum: ожидали {OLD_SUM!r}, нашли {deal['sum']!r}"
    assert deal['eco']['sum'] == OLD_SUM, \
        f"eco.sum: ожидали {OLD_SUM!r}, нашли {deal['eco']['sum']!r}"
    assert deal['eco']['val'] == OLD_VAL, \
        f"eco.val: ожидали {OLD_VAL!r}, нашли {deal['eco']['val']!r}"

    print(f"{CARD_ID} sum: {OLD_SUM!r} -> {NEW_SUM!r}")
    print(f"{CARD_ID} eco.sum: {OLD_SUM!r} -> {NEW_SUM!r}")
    print(f"{CARD_ID} eco.val: {OLD_VAL!r} -> {NEW_VAL!r}")

    deal['sum'] = NEW_SUM
    deal['eco']['sum'] = NEW_SUM
    deal['eco']['val'] = NEW_VAL

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
