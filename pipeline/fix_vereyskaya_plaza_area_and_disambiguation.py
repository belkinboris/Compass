# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
`g94c9a39d` («Правительство Москвы купило бизнес-центр «Верейская
плаза»», закрыта 10.01.2023) — не заполнены площадь предмета и есть
риск спутать эту сделку с ДРУГОЙ, более ранней покупкой городом
здания в том же квартале.

Проверено лично прямым WebFetch, РИА Недвижимость,
https://realty.ria.ru/20230131/biznes-tsentr-1848582178.html,
31.01.2023: «Общая площадь бизнес-центра... составляет 26,6 тысячи
квадратных метров, арендная площадь — около 20 тысяч квадратных
метров»; «Компания «Развитие активов» планировала заплатить за этот
актив 3,94 миллиарда рублей»; «правительство города купило бизнес-центр
на Верейской улице для размещения своих структур, каких именно – они
не назвали» (со ссылкой на неназванных экспертов рынка недвижимости —
честная неопределённость, а не наша недоработка).

ВАЖНАЯ РАЗВЯЗКА: в том же квартале (Верейская ул., 29) город раньше
покупал ДРУГОЕ здание — 4-ю очередь (строение 34), под суды (Второй
кассационный и Первый апелляционный) — это отдельная, более ранняя
история (Ведомости, 2019 год), не относящаяся к этой карточке
(строение 154, 1-я очередь). Дописано явно, чтобы читатель не спутал
две разные сделки одного квартала.

НЕ ВКЛЮЧЕНО: конкретное городское ведомство-новосёл — источники прямо
говорят, что эксперты его не назвали; причина продажи со стороны Plaza
Development в 2022 году и финансовое состояние компании на тот момент
— не нашлось; согласования (Мосгордума/конкурс) и консультанты сделки
— не нашлось нигде; список арендаторов с брокерского сайта — не
использован, актуальность после смены собственника не подтверждена.

Запуск: python3 pipeline/fix_vereyskaya_plaza_area_and_disambiguation.py
        python3 pipeline/fix_vereyskaya_plaza_area_and_disambiguation.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g94c9a39d'

OLD_ECO_SHARE = '—'
NEW_ECO_SHARE = (
    'Общая площадь бизнес-центра (1-я очередь, Верейская ул., 29, '
    'стр. 154) — 26,6 тыс. кв. м, арендная площадь — около 20 тыс. '
    'кв. м.'
)

OLD_ECO_CONTEXT = '—'
NEW_ECO_CONTEXT = (
    'Это отдельная сделка от более ранней покупки городом другого '
    'здания того же квартала (4-я очередь, стр. 34) — с 2019 года оно '
    'используется под суды (Второй кассационный и Первый '
    'апелляционный). Точное городское ведомство, которое разместится '
    'в новом здании, эксперты рынка недвижимости не назвали.'
)

NEW_SRC = [
    ['РИА Недвижимость', 'https://realty.ria.ru/20230131/biznes-tsentr-1848582178.html'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['share'] == OLD_ECO_SHARE
    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    existing_urls = {s[1] for s in deal['src']}
    add_src = [s for s in NEW_SRC if s[1] not in existing_urls]
    new_src = deal['src'] + add_src

    print('=== eco.share: станет ===')
    print(NEW_ECO_SHARE)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    if add_src:
        print('\n=== src: добавится ===')
        for s in add_src:
            print(s)

    if write:
        deal['eco']['share'] = NEW_ECO_SHARE
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
