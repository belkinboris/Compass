NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8860619'],
    ['Mail.ru Финансы', 'https://finance.mail.ru/article/investitsiyam-podobrali-taru-69220624/'],
    ['ЛКП', 'https://lkpconsult.ru/services/soprovozhdenie-sdelok-m-a/soprovozhdenie-kupli-prodazhi-biznesa/'],
]


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['gbf6f6432']

    assert d['eco']['target_fin'] == OLD_ECO_TARGET_FIN, \
        'gbf6f6432 eco.target_fin уже другой: %r' % (d['eco']['target_fin'],)
    assert d['law']['adv'] == OLD_LAW_ADV, \
        'gbf6f6432 law.adv уже занят: %r' % (d['law']['adv'],)
    assert d['law']['struct'] == OLD_LAW_STRUCT, \
        'gbf6f6432 law.struct уже другой: %r' % (d['law']['struct'],)
    assert d['eco']['context'] == OLD_ECO_CONTEXT, \
        'gbf6f6432 eco.context уже другой: %r' % (d['eco']['context'],)
    urls = {s[1] for s in d['src']}
    for src in NEW_SRC:
        assert src[1] not in urls, 'источник уже добавлен: %s' % src[1]

    print('gbf6f6432: eco.target_fin заполнен (финансы «Полекс Урала» за '
          '2025 год); law.adv заполнен (ЛКП — юрист покупателя); law.struct '
          'заполнен (структура сделки, второй совладелец Гомиашвили); '
          'eco.context дополнен (именные мнения экспертов); добавлены '
          'источники kommersant.ru/doc/8860619, finance.mail.ru, '
          'lkpconsult.ru')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['eco']['target_fin'] = NEW_ECO_TARGET_FIN
    d['law']['adv'] = NEW_LAW_ADV
    d['law']['struct'] = NEW_LAW_STRUCT
    d['eco']['context'] = NEW_ECO_CONTEXT
    d['src'].extend(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
