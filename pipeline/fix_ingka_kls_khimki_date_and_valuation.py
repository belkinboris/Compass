# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g21ef1542
(Ingka Centres продала штаб-квартиру в Химках компании КЛС-Химки) —
дата была перепутана на год, а `law.appr` выдавало предположение
консультанта за подтверждённый факт. Проверено лично прямым WebFetch.

ДАТА. Карточка несла «2024-06-21» — источник (Ведомости) сам датирован
31 июля 2023 года и говорит: «21 июня новым владельцем 100% долей в
компании ООО «Химки бизнес-парк» стала фирма «КЛС-Химки»» — год в
предложении не назван, но следует из даты публикации: 2023, а не 2024.
Независимо подтверждено Retail.ru той же датой. Перенос в другой год не
проходит через `review.py`, поэтому отдельный скрипт.

ДОБАВЛЕНО/ИСПРАВЛЕНО:
1) `law.appr` — было утверждением «Сделка одобрена правительственной
комиссией» как факт, хотя источник передаёт это лишь ПРЕДПОЛОЖЕНИЕМ
консультанта о механизме скидки, а не сообщением о состоявшемся
одобрении. Ведомости, дословно: «эта цена могла снизиться вдвое после
одобрения сделки правительственной комиссией» — переформулировано, чтобы
не выдавать гипотезу за факт.
2) `eco.val` — добавлена вторая независимая оценка. Ведомости/Retail.ru,
дословно (партнёр «Ricci | Офисы» Дмитрий Жидков): «в 150 000 руб. за
квадратный метр, то есть 6,3 млрд руб. за весь объект» — заметно выше
оценки Платова (4-4,2 млрд ₽) и запрашиваемой цены (~4 млрд ₽), обе
оценки сохранены, диапазон не приводится к одной цифре.
3) `eco.context` — дополнено: цель покупки КЛС-Химки изданию выяснить не
удалось («С какой целью «КЛС-Химки» приобрела офисный комплекс…
изданию узнать не удалось»).

НЕ ВКЛЮЧЕНО: судьба бизнес-парка в 2025-2026 — официальный сайт всё ещё
несёт брендинг Ingka Centres, что подозрительно похоже на неактуальную
страницу, а не на надёжное подтверждение владения; ни один независимый
источник не сообщает о переименовании или новых арендаторах — честная
пустота, а не находка. Финальная цена сделки не раскрыта ни одним
источником, `sum` не меняется. Консультанты сделки не найдены.

Запуск: python3 pipeline/fix_ingka_kls_khimki_date_and_valuation.py
        python3 pipeline/fix_ingka_kls_khimki_date_and_valuation.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g21ef1542'

OLD_DATE = '2024-06-21'
NEW_DATE = '2023-06-21'

OLD_APPR = 'Сделка одобрена правительственной комиссией.'
NEW_APPR = (
    'Прямого подтверждения одобрения не найдено: источник (Ведомости) '
    'передаёт лишь предположение консультанта о механизме — «эта цена '
    'могла снизиться вдвое после одобрения сделки правительственной '
    'комиссией» — это гипотеза о типичной скидке, а не сообщение о '
    'состоявшемся одобрении.'
)

OLD_VAL = (
    'Рыночную стоимость комплекса директор департамента рынков капитала '
    'Nikoliers Денис Платов оценивает в 4–4,2 млрд руб.'
)
NEW_VAL = OLD_VAL + (
    ' Партнёр «Ricci | Офисы» Дмитрий Жидков оценивает иначе: «в 150 000 '
    'руб. за квадратный метр, то есть 6,3 млрд руб. за весь объект» — '
    'заметно выше и запрашиваемой цены, и оценки Платова.'
)

OLD_CONTEXT = (
    '«Химки бизнес-парк» был построен еще в 2007–2008 гг. В отношении '
    'земли под данным активом долгое время проходило судебное '
    'разбирательство между дочерней компанией шведской группы и '
    'коллективным сельскохозяйственным предприятием «Химки», владельцем '
    'которого называли миллиардера Александра Клячина. Впрочем, '
    'впоследствии суд подтвердил права шведов на эту площадку.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' «С какой целью «КЛС-Химки» приобрела офисный комплекс… изданию '
    'узнать не удалось» (Ведомости).'
)

NEW_SRC = [
    ['Retail.ru', 'https://www.retail.ru/news/vladelets-magazinov-ikea-i-tsentrov-mega-prodal-rossiyskuyu-shtab-kvartiru/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['date'] == OLD_DATE
    assert deal['law']['appr'] == OLD_APPR
    assert deal['eco']['val'] == OLD_VAL
    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print(f'=== date: {OLD_DATE!r} -> {NEW_DATE!r} ===')
    print('=== law.appr: было ===')
    print(OLD_APPR)
    print('=== law.appr: станет ===')
    print(NEW_APPR)
    print('=== eco.val: станет ===')
    print(NEW_VAL)
    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['date'] = NEW_DATE
        deal['law']['appr'] = NEW_APPR
        deal['eco']['val'] = NEW_VAL
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
