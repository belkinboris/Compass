# -*- coding: utf-8 -*-
"""Приток, 16:20 МСК 30 сентября 2026: РИА Недвижимость сообщила, что
«Дом.РФ» выставил на конкурс усадьбу Бестужевых-Рюминых XVIII века в
Чеховском районе Московской области (село Молоди) — тот же день и тот же
пул конкурсов «Дом.РФ», что усадьба в Карауле (`g5aabf462`) и Ижевский
оружейный завод (`gea799efc`). Начальная цена 2,72 млн ₽, заявки до
9 ноября, конкурс 13 ноября.

ВАЖНО: enrich.py по ошибке сначала слил источник этого лота в карточку
Караула (`g5aabf462`) — по слабому совпадению заголовков («Дом.РФ»
выставил на торги усадьбу...»), хотя предметы разные. Ошибку откатил
прямой правкой (см. запись в KNOWN_ISSUES.md), для Бестужевых-Рюминых
собрал отдельную карточку — этим скриптом.

Саб-агент независимого подтверждения самого конкурса не нашёл, но нашёл
важное уточнение к детали про Пастернака: по данным azbyka.ru (страница
о храме Воскресения Христова в Молодях), к 1913 году усадьбой владел уже
А. И. Бородин (последний владелец, назван и в тексте РИА), а дачу у него
снимала семья художника Леонида Осиповича Пастернака (отца Бориса
Пастернака) — не просто «семья Бориса Пастернака», и не только летом 1913
года, а в 1913–1916 годах. Источник также независимо подтверждает всю
цепочку владельцев усадьбы, дословно совпадающую с текстом РИА. Это
дополнение — `--mark-deep`, реально нашли и прочитали источник сверх
привязанного.

Запуск: python3 pipeline/fix_add_domrf_bestuzhev_ryumin_card.py [--write]
"""
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'ingest'))

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')


def main(write=False):
    import promote

    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    ids = {c['id'] for c in data['deals']}
    new_id = promote.new_id(ids)

    draft = {
        'date': '2026-09-30',
        'title': '«Дом.РФ» выставил на конкурс усадьбу Бестужевых-Рюминых в Подмосковье',
        'ind': 'Недвижимость',
        'type': 'Продажа с торгов',
        'status': 'Обсуждается',
        'sum': '2,72 млн ₽',
        'seller': '«Дом.РФ»',
        'asset': 'усадьба Бестужевых-Рюминых в селе Молоди (Чеховский район, Московская область): главный дом 755 м² и флигель 333,6 м²',
        'src': [['РИА Недвижимость', 'https://realty.ria.ru/20260930/usadba-2121240206.html'],
                ['azbyka.ru', 'https://azbyka.ru/palomnik/Храм_Воскресения_Христова_(Молоди)']],
        'events': [
            {'kind': 'negotiations', 'date': '2026-09-30', 'title': 'Конкурс объявлен',
             'note': 'Заявки на конкурс принимаются до 9 ноября, сам конкурс — 13 ноября 2026 года.',
             'source': ['РИА Недвижимость', 'https://realty.ria.ru/20260930/usadba-2121240206.html']},
        ],
    }
    card = promote.to_card(draft, new_id)
    card['seller_id'] = 'gb2b066c3'
    card['eco']['sum'] = draft['sum']
    card['eco']['context'] = (
        'Усадебный ансамбль восходит к 1699 году, когда Пётр I пожаловал земли Фёдору '
        'Головину — при нём заложена основа усадьбы и построена каменная Воскресенская '
        'церковь; позже усадьбой владели Домашневы, Салтыковы, Кротковы, Бестужевы и '
        'промышленник Бородин — эта цепочка владельцев подтверждается независимо. В '
        'пресс-релизе «Дом.РФ» сказано, что летом 1913 года здесь жила семья Бориса '
        'Пастернака; по более точным данным, к тому времени усадьбой уже владел Бородин, '
        'а дачу у него в 1913–1916 годах снимала семья художника Леонида Пастернака, '
        'отца Бориса. Лот предлагается использовать в коммерческих целях, например под '
        'загородный отель; победитель конкурса обязан провести реставрацию и сохранение '
        'здания.'
    )
    card['themes'] = ['Продажа с торгов', 'Недвижимость']
    card['added'] = '2026-09-30'

    data['deals'].append(card)
    print('Добавлена карточка %s: %s' % (new_id, card['title']))

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
