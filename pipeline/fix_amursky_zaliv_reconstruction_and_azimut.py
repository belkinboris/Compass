import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gfeb4e569'

OLD_CONTEXT = (
    'En+ Group проявляет большой интерес к сфере гостеприимства '
    'Владивостока. По информации «Ведомостей», структура Дерипаски хочет '
    'стать главным игроком на этом рынке, считая его недооцененным. '
    'Напомним, в 2019-м «Парк-отель Бурдугуз» за 3,7 млрд руб. приобрел '
    'два владивостокских долгостроя – отели «Хаятт». Сейчас в них открыты '
    'Vladivostok Grand Hotel & SPA и RODINA.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' В сентябре 2025 года стало известно о планах реконструкции: '
    '«Реконструкцию гостиницы планируется начать в 2025 году и закончить '
    'в 2028-м», объём инвестиций — 7,285 млрд рублей (РБК: «инвестирует '
    '7,3 млрд руб.»), класс отеля повысится с трёх до четырёх звёзд, '
    'номерной фонд вырастет с 289 до 302 номеров (68 повышенной '
    'комфортности), появятся SPA, четыре ресторана и конференц-зал; '
    'комплекс получит новое название «LEGENDA Амурский залив». '
    'Инвестор — «Компания «Азимут Владивосток» в статусе резидента '
    'свободного порта», подписавшая соглашение с Корпорацией развития '
    'Дальнего Востока и Арктики (КРДВ); по данным РБК, «Азимут '
    'Владивосток» — юрлицо-держатель именно этого комплекса, выкупленное '
    '«Парк-отелем Бурдугуз» (структуры En+ Group) в рамках той же сделки.'
)

NEW_SRC = [
    ['newsvl.ru', 'https://www.newsvl.ru/eef/2025/09/07/233791/'],
    ['РБК (Приморье)', 'https://prim.rbc.ru/prim/10/09/2025/68c0f8279a79475ee39be890'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
