# -*- coding: utf-8 -*-
"""Заметка 516 (консоль, 4 сентября 2026): «Обсуждается, и в описании
сказать что есть источник где говорят что закрыта, но что официально
опровергают. Тот же подход с двумя годами как выше», отвечая на
карточку `g7299791f» («Финансовая группа БКС купила банк «Форштадт»»).

Владелец решил статус: не «Закрыта» (единственный источник о закрытии
опровергнут самими сторонами в тот же день), а «Обсуждается». Оговорка
про срок — не буквально «два года» (объявление было в октябре 2025
года, меньше года назад), а тот же ПОДХОД: явно назвать, что вопрос
висит без движения продолжительное время и опровержение с тех пор
никем не оспорено.

Запуск: python3 pipeline/fix_bks_forshtadt_status_and_caveat.py [--write]
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g7299791f'
OLD_TITLE = 'Финансовая группа БКС купила банк «Форштадт»'
NEW_TITLE = 'Финансовая группа БКС могла купить банк «Форштадт»'
OLD_STATUS = 'Закрыта'
OLD_CONTEXT = (
    'Основными совладельцами банка значились ООО «Энергоинвест» (50%), '
    'бенефициаром которого является Сергей Левин, Арам Екавян (43,08%) '
    'и Сергей Черный (6,81%), возглавляющий крупного производителя соли '
    'ООО «Руссоль». Рейтинговое агентство «Эксперт РА» 28 января 2026 '
    'года подтвердило банку рейтинг ruBB+ со сменой прогноза на '
    '«развивающийся» и отметило существенные изменения в руководстве '
    'банка, включая обновление топ-менеджмента и состава совета '
    'директоров, но не назвало БКС и не подтвердило смену собственника. '
    'По данным открытого агрегатора банковских сведений на 27 июля '
    '2026 года структура именных владельцев банка не изменилась: 50% — '
    'Сергей Левин, 43% — Арам Екавян, 6,82% — Сергей Черный; БКС среди '
    'собственников не значится. Опровержение БКС и «Форштадта» от 6 '
    'октября 2025 года с тех пор никем не оспорено.'
)
ADDITION = (
    ' Единственный источник, назвавший сделку закрытой (Forbes, 6 '
    'октября 2025 года), был в тот же день опровергнут обеими '
    'сторонами; ни один источник с тех пор не подтвердил переход '
    'контроля к БКС. Вопрос висит без движения почти год — статус '
    'оставлен «Обсуждается», а не «Закрыта».'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {c['id']: c for c in data['deals']}
    card = by_id[CARD_ID]
    assert card['title'] == OLD_TITLE, card['title']
    assert card['status'] == OLD_STATUS, card['status']
    assert card['eco']['context'] == OLD_CONTEXT, card['eco']['context']

    card['title'] = NEW_TITLE
    card['status'] = 'Обсуждается'
    card['eco']['context'] = OLD_CONTEXT + ADDITION

    print(f'{CARD_ID}: статус -> Обсуждается, заголовок и контекст переписаны')

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
            f.write('\n')
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
