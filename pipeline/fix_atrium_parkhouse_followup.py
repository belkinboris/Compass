NEW_SRCS = [
    ['Блокнот Анапа', 'https://bloknotanapa.ru/news/'
     'vladeltsy-krasnoy-ploshchadi-v-anape-prikupili-eshch'],
]


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    card = next((c for c in data['deals'] if c['id'] == CARD_ID), None)
    assert card is not None, '%r не найдена в базе' % CARD_ID
    assert card['law'].get('appr') == OLD_APPR, (
        'law.appr изменился с ожидаемого: %r' % card['law'].get('appr'))
    assert card['law'].get('adv') == OLD_ADV, (
        'law.adv изменился с ожидаемого: %r' % card['law'].get('adv'))
    assert card['eco'].get('context') == OLD_CONTEXT, (
        'eco.context изменился с ожидаемого: %r' % card['eco'].get('context'))
    src = card.setdefault('src', [])
    print('ПРАВИМ  %s: law.appr — согласование правкомиссии (перевод)' % CARD_ID)
    print('ПРАВИМ  %s: law.adv — добавлен юрконсультант покупателя Denuo' % CARD_ID)
    print('ПРАВИМ  %s: eco.context — расхождение суммы и профиль покупателя' % CARD_ID)
    if write:
        card['law']['appr'] = NEW_APPR
        card['law']['adv'] = NEW_ADV
        card['eco']['context'] = NEW_CONTEXT
        for s in NEW_SRCS:
            if s not in src:
                src.append(s)
        json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
        print('ЗАПИСАНО')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
