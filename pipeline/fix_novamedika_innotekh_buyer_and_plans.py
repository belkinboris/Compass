# -*- coding: utf-8 -*-
"""Месячная очередь, 9 сентября 2026 — дочитывание карточки `gad241bb3`
(«Производственная площадка "Новамедика Иннотех" продана с торгов
структурой "Роснано"», добавлена в базу 3 августа 2026, полностью
обыскана в тот же день).

Дельта-поиск (саб-агент + личная проверка) нашёл два новых факта сверх
уже известного:

1) Покупатель, АО «Синмедекс», — юрлицо, зарегистрированное незадолго до
   торгов. Личный WebFetch (1cont.ru, справочник по ОГРН 1257700299427)
   подтвердил дословно: дата регистрации «04 июля 2025» (за месяц до
   объявления торгов Роснано в августе), уставный капитал «100,0 тыс ₽»,
   заявленный вид деятельности «21.20 Производство лекарственных
   препаратов и материалов, применяемых в медицинских целях»,
   генеральный директор «СОЛОДУХА НИКОЛАЙ ГЕННАДЬЕВИЧ». Собственной
   публичной истории или продукции у компании до сделки не найдено —
   похоже на структуру, созданную специально под приобретение актива;
   учредители не раскрываются.

2) Планы нового владельца на площадку. Личный WebFetch (rusnano.com,
   пресс-релиз от 20 октября 2025) подтвердил дословно: «Ключевыми
   задачами нового владельца «Новамедика Иннотех» станут модернизация и
   дальнейшее развитие контрактного производства, а также расширение
   сотрудничества с партнерами из числа фармацевтических производителей.»

Саб-агент также нашёл в агрегированном поиске неподтверждаемую
формулировку о «запуске производства в III квартале 2026» — она НЕ
вносится: прямым чтением первоисточников не подтвердилась.

Итоговая сумма сделки и финансовый консультант по-прежнему нигде не
названы (проверено пятью независимыми источниками) — карточка права,
что оставляет их как есть.

Запуск:
    python3 pipeline/fix_novamedika_innotekh_buyer_and_plans.py            # сухой прогон
    python3 pipeline/fix_novamedika_innotekh_buyer_and_plans.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_ECO_CONTEXT = (
    'Владелец ещё в августе объявил торги по продаже 100% этой фирмы, но '
    'заявка на участие поступила лишь одна — по данным электронной '
    'торговой площадки. Стартовая цена составляла 720 млн ₽.'
)
NEW_ECO_CONTEXT = OLD_ECO_CONTEXT + (
    ' АО «Синмедекс» зарегистрировано незадолго до торгов, 4 июля 2025 '
    'года, с уставным капиталом 100 тыс. ₽ и заявленным видом '
    'деятельности «производство лекарственных препаратов и материалов, '
    'применяемых в медицинских целях» — собственной публичной истории у '
    'компании до сделки не было. По сообщению Роснано, ключевыми '
    'задачами нового владельца станут модернизация и дальнейшее развитие '
    'контрактного производства, а также расширение сотрудничества с '
    'партнёрами из числа фармацевтических производителей.'
)

NEW_SRC = ['РОСНАНО', 'https://www.rusnano.com/news/20251020-gruppa-rosnano-prodala-novamedika-innotekh-strategicheskomu-investoru/']


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['gad241bb3']

    assert d['eco']['context'] == OLD_ECO_CONTEXT, \
        'gad241bb3 eco.context уже другой: %r' % (d['eco']['context'],)
    urls = {s[1] for s in d['src']}
    assert NEW_SRC[1] not in urls, 'источник уже добавлен'

    print('gad241bb3: eco.context дополнен (регистрация «Синмедекс», '
          'планы нового владельца); добавлен источник rusnano.com')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['eco']['context'] = NEW_ECO_CONTEXT
    d['src'].append(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
