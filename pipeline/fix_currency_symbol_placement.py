# -*- coding: utf-8 -*-
"""Валюта не на своём месте: ₽ должен идти ПОСЛЕ числа, $ и € — ПЕРЕД.

ЧТО СЛОМАНО. Соглашение о записи суммы (см. CLAUDE.md, «Сумма пишется одним
способом») требует: `₽` после числа («5 млрд ₽»), `$`/`€` перед числом
(«$150 млн»). У 9 карточек (в основном IPO 2023–2024 года и две сделки за
символическую сумму в евро) знак стоит наоборот — «₽5 млрд», «1 €». Разбор,
подмешивавший эти карточки, писал сумму по-своему и через
`pipeline/normalize_sum.py` не проходил (его регулярка не ловит рубль ПЕРЕД
числом — она ищет валюту после числа или перед $/€, не ₽). Правка точечная,
без общей регулярки: `normalize_sum.py` — сложный, общий движок с известной
отдельной проблемой (склеивает знак со следующим словом при пометке источника,
«$по данным» без пробела); трогать его ради 9 карточек рискованнее, чем
переписать 9 строк явно.

ЧТО ДЕЛАЕМ. Меняем `sum`/`eco.sum` (и `eco.val` у `g64eb0e04`, где та же
строка продублирована) на форму со значком на верном месте — только порядок
цифр и символа, число и текст вокруг не меняются.

Запуск:
    python3 pipeline/fix_currency_symbol_placement.py            # сухой прогон
    python3 pipeline/fix_currency_symbol_placement.py --write    # записать
"""
import json
import sys

PATH = 'static/data/deals_promoted.json'

# id -> {поле: (было, стало)}
FIXES = {
    'g9cb22c51': {'sum': ('₽5 млрд', '5 млрд ₽'), 'eco.sum': ('₽5 млрд', '5 млрд ₽')},
    'g6ba5f232': {'sum': ('₽15 млрд', '15 млрд ₽'), 'eco.sum': ('₽15 млрд', '15 млрд ₽')},
    'g00a0318e': {
        'sum': ('₽3,5 млрд (привлечено), капитализация ₽23,5 млрд',
                '3,5 млрд ₽ (привлечено), капитализация 23,5 млрд ₽'),
        'eco.sum': ('₽3,5 млрд (привлечено), капитализация ₽23,5 млрд',
                    '3,5 млрд ₽ (привлечено), капитализация 23,5 млрд ₽'),
    },
    'g3ed36abe': {'sum': ('₽12,5–13,1 млрд', '12,5–13,1 млрд ₽'),
                  'eco.sum': ('₽12,5–13,1 млрд', '12,5–13,1 млрд ₽')},
    'g6a453b19': {'sum': ('₽600 млн', '600 млн ₽'), 'eco.sum': ('₽600 млн', '600 млн ₽')},
    'g465977ce': {'sum': ('₽11,5 млрд', '11,5 млрд ₽'), 'eco.sum': ('₽11,5 млрд', '11,5 млрд ₽')},
    'g139d522a': {'sum': ('₽5 млрд', '5 млрд ₽'), 'eco.sum': ('₽5 млрд', '5 млрд ₽')},
    'ga2e9c5b1': {'sum': ('1 €', '€1'), 'eco.sum': ('1 €', '€1')},
    'g64eb0e04': {
        'sum': ('1 € + 100 млн € (погашение внутрикорпоративной задолженности)',
                '€1 + €100 млн (погашение внутрикорпоративной задолженности)'),
        'eco.val': ('1 € + 100 млн € (погашение внутрикорпоративной задолженности)',
                    '€1 + €100 млн (погашение внутрикорпоративной задолженности)'),
    },
}


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    changes = []
    for did, fields in FIXES.items():
        d = by_id[did]
        for field, (old, new) in fields.items():
            if field.startswith('eco.'):
                key = field.split('.', 1)[1]
                obj = d.setdefault('eco', {})
            else:
                key, obj = field, d
            actual = obj.get(key)
            assert actual == old, f'{did}.{field}: ожидали {old!r}, нашли {actual!r}'
            changes.append((did, field, old, new))
            if write:
                obj[key] = new

    print(f'правок: {len(changes)}')
    for did, field, old, new in changes:
        print(f'  {did} [{field}]: {old!r} -> {new!r}')

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=1, ensure_ascii=False)
        print('\nЗАПИСАНО в', PATH)
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
