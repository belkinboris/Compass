def main(write=False):
    import promote

    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    ids = {c['id'] for c in data['deals']}
    assert NEW_ID not in ids
    assert NEW_ID not in data.get('merged', {})

    existing = next(c for c in data['deals'] if c['id'] == EXISTING_ID)
    assert existing['seller'] == OLD_SELLER
    assert existing['date'] == OLD_DATE
    assert existing['extra'] == OLD_EXTRA

    existing['title'] = NEW_TITLE
    existing['date'] = '2025-10-01'
    existing['seller'] = 'ООО «Инвест Трейд» (Сергей Феськов)'
    existing.pop('seller_src', None)
    existing['eco']['context'] = NEW_CONTEXT
    existing['extra'] = (
        'Покупатель — «Агрокомплекс им. Н. И. Ткачева», компания экс-главы '
        'Минсельхоза Александра Ткачева. Продавец — ООО «Инвест Трейд» '
        '(бенефициар Сергей Феськов). Сделка закрыта в октябре 2025 года.'
    )

    draft = {
        'date': '2025-02-07',
        'title': ('«Приосколье» перешло от Геннадия Бобрицкого к «Инвест-трейду» '
                   'Сергея Феськова'),
        'ind': 'Агро',
        'type': 'M&A',
        'status': 'Закрыта',
        'sum': 'Не раскрыта',
        'src': [['Коммерсантъ', 'https://www.kommersant.ru/doc/7496153']],
    }
    new_card = promote.to_card(draft, NEW_ID)
    new_card['target'] = 'g66d6e4ea'
    new_card['seller'] = 'Геннадий Бобрицкий'
    new_card['seller_src'] = 'text'
    new_card['buyer_name'] = 'ООО «Инвест-трейд» (Сергей Феськов)'
    new_card['asset'] = ('структуры группы «Приосколье» — АО «Приосколье», ЗАО '
                          '«Новооскольский комбикормовый завод», АО «Краснояружская '
                          'зерновая компания» и другие')
    new_card['eco']['rationale'] = BOBRITSKY_RATIONALE
    new_card['eco']['context'] = BOBRITSKY_CONTEXT

    data['deals'].append(new_card)

    print(f'{EXISTING_ID}: переписана на «Инвест Трейд»/Феськов и октябрь 2025')
    print(f'Добавлена карточка {NEW_ID}: {new_card["title"]}')

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
            f.write('\n')
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
