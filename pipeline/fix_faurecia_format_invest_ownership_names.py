# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка `g8de46135`
(«Продажа активов Faurecia в России российским топ-менеджерам», закрыта,
2023) — дочитывание назвало, кто именно получил доли после выхода
Горина, и уточнило юридический предмет сделки.

Проверено (по докладу саб-агента, дословные цитаты):
- interfax.ru/business/940387: «Татьяна Громова (35%) и операционный
  директор Faurecia в России Оливье Гриненберже (35%). Еще по 7,5% – у
  Николая Афанасьева, Марины Давыденко, Евгении Бурцевой и Ильи Панина.»
  — Коммерсантъ (уже в карточке) называл только формулу «по 7,5%», без
  имён; Интерфакс — независимый источник — называет всех четверых.
- kommersant.ru/doc/6454433: «Компании «Форесия автомобильные решения» и
  «Форесия экологичные решения»… перешли в собственность компании
  «Формат Инвест»»; interfax.ru/business/940387 подтверждает организационно-
  правовую форму покупателя — «ООО "Формат Инвест"»; a-kt.ru называет и
  третье юрлицо цели — «АО «Форесия Интериор Тольятти»».

НЕ ВНЕСЕНО: (1) юридический/финансовый консультант — ноль по всем
проверенным источникам (обе статьи Ъ, Интерфакс, TAdviser, mashnews.ru,
abreview.ru, drom.ru, a-kt.ru); (2) согласование правкомиссии по контролю
за иностранными инвестициями — ни один источник не упоминает его
применительно именно к этой сделке; (3) точная (не оценочная) сумма
сделки — нигде не раскрыта, включая более поздние источники; (4)
переименование заводов в «Автокомпонент Формат Тольятти» — факт остался
неподтверждённым дословной цитатой: прямое чтение a-kt.ru и news.drom.ru
не дало чистой цитаты о переименовании (drom.ru отдал в основном
комментарии пользователей, не редакционный текст).

Запуск: python3 pipeline/fix_faurecia_format_invest_ownership_names.py
        python3 pipeline/fix_faurecia_format_invest_ownership_names.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g8de46135'

OLD_LAW_STRUCT = (
    'В сентябре Горин вышел из компании, а остальные совладельцы, кроме '
    'Татьяны Громовой и Оливье Гриненберже, получили по 7,5%. Оливье '
    'Гриненберже в 2023 году получил российский паспорт.'
)
NEW_LAW_STRUCT = (
    OLD_LAW_STRUCT + ' По данным Интерфакса, эти 7,5% получили Николай '
    'Афанасьев, Марина Давыденко, Евгения Бурцева и Илья Панин. '
    'Предметом сделки выступили три юрлица — ООО «Форесия Экологичные '
    'решения», ООО «Форесия Автомобильные решения» и АО «Форесия '
    'Интериор Тольятти» — они перешли образованному топ-менеджерами ООО '
    '«Формат Инвест».'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['law']['struct'] == OLD_LAW_STRUCT

    print('=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)

    if write:
        deal['law']['struct'] = NEW_LAW_STRUCT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
