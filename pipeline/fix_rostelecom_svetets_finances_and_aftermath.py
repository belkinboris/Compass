import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gfc7d8f5f'

OLD_ECO_TARGET_FIN = '—'
NEW_ECO_TARGET_FIN = (
    'Выручка ООО «Фирма «Светец»» за 2024 год — 612,1 млн ₽, чистая '
    'прибыль — 205,9 млн ₽ (по данным РБК-Компании); показатели растут '
    'год к году после сделки.'
)

OLD_ECO_CONTEXT = (
    'На момент публикации (март 2023 года) в пресс-службе «Ростелекома» '
    'уточнили ТАСС, что сделка не закрыта: «традиционно незавершенные '
    'сделки не комментируют». Переход долей зафиксирован в ЕГРЮЛ 14 '
    'марта 2023 года. На сайте разработчика «Светец» говорится, что '
    'компания уже 30 лет предлагает клиентам широкий спектр решений для '
    'организации и развития бизнеса; реализовано свыше 500 проектов на '
    'территории России и в странах СНГ.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' «Светец» задолго до сделки уже поставлял '
    '«Ростелекому» ПО для собственных продуктов — в мае 2022 года '
    'обеспечил подключение внешних номеров к «Виртуальной АТС» '
    '«Ростелекома»; покупка формализовала уже существовавшую '
    'зависимость, а не открыла новый рынок. После сделки компания '
    'сохранила бренд и операционную самостоятельность: в марте 2025 '
    'года «Светец» совместно с «Ростелекомом» и CraftTalk выпустил '
    'цифровую HRM-платформу на базе ИИ.'
)

NEW_SRC = [
    ['CNews', 'https://www.cnews.ru/news/line/2022-05-11_svetets_obespechil_funktsiyu'],
    ['CNews', 'https://www.cnews.ru/news/line/2025-03-05_tsifrovaya_hrm-platforma_rostelekom'],
    ['РБК-Компании', 'https://companies.rbc.ru/id/1025007115253-ooo-firma-svetets/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['target_fin'] == OLD_ECO_TARGET_FIN
    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    existing_urls = {s[1] for s in deal['src']}
    add_src = [s for s in NEW_SRC if s[1] not in existing_urls]
    new_src = deal['src'] + add_src

    print('=== eco.target_fin: станет ===')
    print(NEW_ECO_TARGET_FIN)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    if add_src:
        print('\n=== src: добавится ===')
        for s in add_src:
            print(s)

    if write:
        deal['eco']['target_fin'] = NEW_ECO_TARGET_FIN
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
