import json
import sys

DATA = 'static/data/deals_promoted.json'

NEW_OWNERSHIP = {
    'g745308a7': [{
        'name': 'Сергей Асланян',
        'id': None,
        'as_of': '2024',
        'source': ['Коммерсантъ', 'https://www.kommersant.ru/doc/5912279'],
    }],
    'gb75289f9': [{
        'name': 'Захар Смушкин и Борис Зингаревич (через ООО «Илим Глобал Тимбер Рус»)',
        'id': None,
        'share': '50%',
        'as_of': '2023-09',
        'source': ['РБК', 'https://www.rbc.ru/business/18/09/2023/65084b569a7947f2bcfc477f'],
    }],
    'g0dcec2ce': [{
        'name': 'МеталлСервис',
        'id': None,
        'as_of': '2024-08',
        'source': ['Интерфакс', 'https://www.interfax.ru/business/965664'],
    }],
}


def main(write=False):
    """Идемпотентен, как pass1-7."""
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    companies = data['companies']

    pending = {}
    for cid, entries in NEW_OWNERSHIP.items():
        assert cid in companies, 'нет такого профиля: %s' % cid
        current = companies[cid].get('ownership')
        if current:
            assert current == entries, 'ownership уже занят другим значением у %s: %r' % (cid, current)
            continue
        pending[cid] = entries

    if not pending:
        print('Все профили уже заполнены — нечего применять.')
        return

    print('Заполняю ownership: %s' % ', '.join('%s (%s)' % (cid, companies[cid]['name']) for cid in pending))

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    for cid, entries in pending.items():
        companies[cid]['ownership'] = entries

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
