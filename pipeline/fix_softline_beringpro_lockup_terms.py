# -*- coding: utf-8 -*-
"""Месячная очередь качества, 11 сентября 2026 — карточка `g15386e04`
(«Softline потратил 340 миллионов на покупку бывшего консалтингового
подразделения KPMG») уже прошла точечную правку 2 сентября
(`batch_g15386e04.py`, после жалобы владельца на нестыковку сумм) — там
из статьи CNews перенесена верная сумма (340 млн ₽), доля, продавцы,
финансы предмета, гудвил и история бренда. `law.terms` при этом
оставался пуст: ни один из тогда прочитанных источников не называл
УСЛОВИЯ выплаты, только сам факт погашения задолженности (уже стоит в
`law.struct`: «13 млн ₽ деньгами и 100 млн ₽ акциями»).

Личный WebFetch подтвердил дословно (Интерфакс, 2 октября 2025, 19:28,
https://www.interfax.ru/business/1050562): «Предусмотрен 6-месячный
Lock-up по этим акциям с поэтапным высвобождением 1/6 пакета
ежемесячно».

ВАЖНО, что НЕ внесено. Тот же Интерфакс называет оценку компании «около
700 млн рублей» через мультипликатор «около 4х EV/EBITDA» — эта цифра
уже была найдена РАНЕЕ (в той же партии 2 сентября) и ЯВНО ОТКЛОНЕНА:
докстрока `batch_g15386e04.py` прямо говорит, что первоисточник (CNews,
с презентацией Softline) «сам разбирает и опровергает... цифру (700 млн
руб. у «Интерфакса»)» как основанную на неверном мультипликаторе, и
называет 340 млн ₽ единственной полной суммой сделки. Эта правка её не
воскрешает — берётся только условие lock-up, которое не зависит от
спорной оценки и арифметически согласуется с уже подтверждённой
структурой (100 млн ₽ акциями — это ≈90% от 113 млн ₽ краткосрочного
вознаграждения продавцам, ровно та пропорция, что называет тот же
абзац Интерфакса).

Запуск:
    python3 pipeline/fix_softline_beringpro_lockup_terms.py            # сухой прогон
    python3 pipeline/fix_softline_beringpro_lockup_terms.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_LAW_TERMS = '—'
NEW_LAW_TERMS = (
    'Акции «Софтлайна», которыми частично выплачено вознаграждение '
    'продавцам, переданы с условием lock-up на 6 месяцев с поэтапным '
    'высвобождением 1/6 пакета ежемесячно.'
)

NEW_SRC = ['Интерфакс', 'https://www.interfax.ru/business/1050562']


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['g15386e04']

    assert d['law'].get('terms') == OLD_LAW_TERMS, 'law.terms уже занят: %r' % (d['law'].get('terms'),)
    urls = {s[1] for s in d['src']}
    assert NEW_SRC[1] not in urls, 'источник уже добавлен'

    print('g15386e04: law.terms заполнен (lock-up на акции «Софтлайна», '
          '6 месяцев, поэтапное высвобождение 1/6 в месяц); добавлен '
          'источник (без спорной оценки 700 млн ₽ — она уже отклонена '
          'ранее)')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['law']['terms'] = NEW_LAW_TERMS
    d['src'].append(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
