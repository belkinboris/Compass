def main(write=False):
    data = json.load(open(BASE, encoding='utf-8'))
    cards = {d['id']: d for d in data['deals']}
    todo_dates, todo_tags = {}, {}

    for cid, (old, new) in DATES.items():
        card = cards[cid]
        if card['date'] == new:
            print('УЖЕ ПРИМЕНЕНО %s (дата)' % cid)
            continue
        assert card['date'] == old, '%s: дата уже другая (%r)' % (cid, card['date'])
        todo_dates[cid] = new
        print('ПРАВИМ  %s date: «%s» -> «%s»' % (cid, old, new))

    for cid, field, old_full, tag in TAG_FIXES:
        card = cards[cid]
        new_full = old_full[:-len(tag)]
        current = card['eco']['rationale'] if field == 'eco.rationale' else card[field]
        if current == new_full:
            print('УЖЕ ПРИМЕНЕНО %s %s (пометка)' % (cid, field))
            continue
        assert current == old_full, '%s %s: значение уже другое' % (cid, field)
        todo_tags[(cid, field)] = new_full
        print('ПРАВИМ  %s %s: снята протёкшая пометка роли' % (cid, field))

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return
    for cid, new in todo_dates.items():
        cards[cid]['date'] = new
    for (cid, field), new_full in todo_tags.items():
        if field == 'eco.rationale':
            cards[cid]['eco']['rationale'] = new_full
        else:
            cards[cid][field] = new_full
    if todo_dates or todo_tags:
        json.dump(data, open(BASE, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
