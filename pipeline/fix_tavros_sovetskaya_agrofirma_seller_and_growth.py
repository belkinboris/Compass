import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gcef66398'

OLD_EXTRA = ''
NEW_EXTRA = (
    'Продавец — Алексей Барамзин, прежний владелец «Советской '
    'агрофирмы» (связаться с ним для комментария не удалось). По '
    'информации «Тавроса», привлечённые от продажи 19,01% агрохолдинга '
    'Альфа-банку средства планируется направить на инновационные и '
    'логистические проекты — в банке подчеркнули, что «сделка не '
    'связана с кредитованием и имеет автономный характер, отвечающий '
    'интересам обеих сторон».'
)

OLD_ECO_CONTEXT = (
    'Более 80% ООО «УК \"Таврос\"» владеет управляющий партнер AVG '
    'Capital Partners Рустем Миргалимов, 19,01% агрохолдинга этим летом '
    'получил Альфа-банк'
)
NEW_ECO_CONTEXT = OLD_ECO_CONTEXT + (
    '. После покупки «Таврос» планировал вложиться в строительство '
    'комбикормового завода для обеспечения поголовья собственными '
    'кормами — план реализован: инвестиции в модернизацию составили '
    '2,3–2,4 млрд ₽ (два корпуса для промышленного стада на 145 тыс. '
    'голов каждый, корпус для ремонтного молодняка на 150 тыс. голов, '
    'комбикормовый завод мощностью 80 тыс. т в год). Производство яиц '
    'выросло с 261 млн штук (2023, план на 2024 год — 290 млн) до '
    'рекордных 297 млн штук в 2024 году (+12%). В 2022 году связанная с '
    '«Тавросом» компания «Управление агроактивами» уже покупала у '
    '«Черкизово» птицефабрику «Башкирская» (750 млн яиц в год, 2 млрд '
    '₽) — эта сделка входит в ту же линию расширения холдинга в '
    'яичном сегменте.'
)

NEW_SRC = [
    ['Агроинвестор', 'https://www.agroinvestor.ru/investments/news/43191-sovetskaya-agrofirma-vlozhit-v-modernizatsiyu-2-4-mlrd-rubley/'],
    ['zzr.ru', 'https://zzr.ru/news/sovetskaya-agrofirma-naraschivaet-proizvodstvo-yayca'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6070243'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA
    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
