NEW_SELLER = 'Михаил Несветайло'


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}
    deal = by_id.get(DEAL_ID)
    assert deal is not None, 'нет сделки %s' % DEAL_ID

    for k, v in OLD.items():
        assert deal.get(k) == v, 'поле %s уже другое: %r, ожидали %r' % (k, deal.get(k), v)
    for k, v in OLD_ECO.items():
        assert deal.get('eco', {}).get(k) == v, \
            'eco.%s уже другое: %r' % (k, deal.get('eco', {}).get(k))
    for k, v in OLD_LAW.items():
        assert deal.get('law', {}).get(k) == v, \
            'law.%s уже другое: %r' % (k, deal.get('law', {}).get(k))
    assert deal.get('eco', {}).get('rationale') == OLD_RATIONALE, \
        'eco.rationale уже другое: %r' % deal.get('eco', {}).get('rationale')
    assert 'seller' not in deal, 'seller уже заполнен: %r' % deal.get('seller')

    print('%s: сделка закрылась 28.01.2026, не в декабре 2025' % DEAL_ID)
    print('  date: %r -> %r' % (OLD['date'], NEW['date']))
    print('  status: %r -> %r' % (OLD['status'], NEW['status']))
    print('  sum/eco.sum: %r -> %r' % (OLD['sum'], NEW['sum']))
    print('  seller (новое поле): %r' % NEW_SELLER)
    print('  law.struct дополнен структурой SLH Group')
    print('  eco.rationale дополнен мотивом обособления через офшор')
    print('  eco.share заполнен периметром сделки')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    deal['date'] = NEW['date']
    deal['status'] = NEW['status']
    deal['sum'] = NEW['sum']
    deal['eco']['sum'] = NEW_ECO['sum']
    deal['eco']['val'] = NEW_ECO['val']
    deal['eco']['share'] = NEW_ECO['share']
    deal['eco']['rationale'] = NEW_RATIONALE
    deal['law']['struct'] = NEW_LAW['struct']
    deal['seller'] = NEW_SELLER
    deal['seller_src'] = 'text'
    deal['src'] = (deal.get('src') or []) + [
        ['Коммерсантъ', 'https://www.kommersant.ru/doc/8380020'],
        ['Sostav', 'https://www.sostav.ru/publication/vladeltsy-miuz-diamonds-kupili-adamas-81320.html'],
        ['Компания', 'https://ko.ru/articles/zolotaya-sdelka-set-adamas-prodali-strukture-milliardera-levaeva/'],
    ]

    assert deal['date'] == NEW['date'], 'дата не записалась'
    assert deal['status'] == NEW['status'], 'статус не записался'

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
