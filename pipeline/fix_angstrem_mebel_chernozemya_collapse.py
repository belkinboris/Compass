# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка gad4a5636
(«Ангстрем» покупает «Мебель Черноземья») — статус «Обсуждается» держится
с июля 2024 года; деловая пресса о самой сделке молчит полностью, но
финансовая отчётность цели показывает резкий обвал.

Судьба сделки — проверено лично: ни один материал позже 26 июля
2024 года не подтверждает и не опровергает закрытие или срыв именно
ЭТОЙ сделки. `status` НЕ меняется — обвал показателей цели МОЖЕТ быть
следствием интеграции с «Ангстремом» (сокращение параллельной розницы
после покупки), а может быть признаком того, что бизнес разваливается
независимо от переговоров, — источники это не разрешают, а прямой доступ
к ЕГРЮЛ (кто сейчас учредитель) недоступен в этой сессии (403 на
rusprofile.ru, list-org.com).

Финансовый обвал цели — проверено лично прямым WebFetch (audit-it.ru):
выручка ООО «ХК «Мебель Черноземья»» упала с 351,7 млн руб. (2023) до
~144,8 млн руб. (2024) и до 29,8 млн руб. (2025, падение на 79,4% год к
году); прибыль обвалилась на 98,6% год к году до 385 тыс. руб.;
численность сотрудников упала со 104 человек (2024) до 12 (2025).
Компания «находится в процессе реорганизации в форме выделения» с 19 мая
2026 года.

НЕ ВКЛЮЧЕНО: отзывы покупателей на Яндекс.Картах о закрытии магазинов —
анекдотический источник, не дотягивает до стандарта дословной цитаты
издания, принятого в базе; состав учредителей юрлица после сделки (есть
ли среди них «Ангстрем» или структуры Чернушкина) — не удалось проверить
напрямую (ЕГРЮЛ-агрегаторы вернули 403).

Запуск: python3 pipeline/fix_angstrem_mebel_chernozemya_collapse.py
        python3 pipeline/fix_angstrem_mebel_chernozemya_collapse.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gad4a5636'

OLD_TARGET_FIN = (
    'Выручка основного юрлица — ООО «ХК "Мебель Черноземья"» — в 2022 '
    'году сократилась почти вдвое, до 330 млн руб., в 2023 году выросла '
    'всего на 6,5%, до 351,7 млн руб. при чистом убытке 670 тыс. руб.'
)
NEW_TARGET_FIN = OLD_TARGET_FIN + (
    ' В 2024-2025 годах — резкий обвал: выручка упала до ~144,8 млн '
    'руб. (2024), затем до 29,8 млн руб. (2025, -79,4% год к году), '
    'прибыль сократилась на 98,6% до 385 тыс. руб.; численность '
    'сотрудников упала со 104 человек (2024) до 12 (2025) (audit-it.ru).'
)

OLD_CONTEXT = '—'
NEW_CONTEXT = (
    'Ни возобновления переговоров, ни закрытия, ни срыва сделки '
    'публично не сообщалось. При этом финансовые показатели цели резко '
    'ухудшились (см. «Финансы предмета»), а сама компания с 19 мая '
    '2026 года находится в процессе реорганизации в форме выделения '
    '(audit-it.ru) — само по себе это не подтверждает и не опровергает '
    'исход сделки: может быть следствием интеграции с покупателем, а '
    'может — признаком того, что бизнес цели разваливается независимо '
    'от переговоров.'
)

NEW_SRC = [
    ['audit-it.ru', 'https://www.audit-it.ru/contragent/1153668017030_ooo-khk-mebel-chernozemya'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['target_fin'] == OLD_TARGET_FIN
    assert deal['eco']['context'] == OLD_CONTEXT

    new_src = deal['src'] + NEW_SRC

    print('=== eco.target_fin: станет ===')
    print(NEW_TARGET_FIN)
    print('\n=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['target_fin'] = NEW_TARGET_FIN
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
