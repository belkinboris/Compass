# -*- coding: utf-8 -*-
"""Карточка g2f22b1dc («Росатом рассматривает продажу до 49% в проекте АЭС
«Аккую» внешним инвесторам») — новый черновик g47093838 («Путин заявил о
готовности турецких компаний выкупить долю в АЭС «Аккую»», РБК/Интерфакс,
28 октября 2026) оказался тем же сюжетом, а не отдельной сделкой: в карточке
уже есть то же самое («Лихачев 21 апреля 2026 года говорил, что с рядом
турецких компаний начато предметное обсуждение») — новость 28 октября лишь
добавляет публичное подтверждение Путина и уточнение про финансирование.
docs/duplicates.md, исход `enrich`: черновик не становится отдельной
карточкой, факт переносится в существующую. review.py не годится здесь по
той же причине, что в docs/card_editing.md «Когда review.py не подходит»:
на диске нет кэша статей ни этой, ни старой карточки (контейнер рутины
пуст), а единственная новая PROSE_WRITTEN запись без братьев по id не
пройдёт сверку `prose_gate.known_texts()`. Источник — Интерфакс
(https://www.interfax.ru/business/1125517): «Там полностью наше
финансирование, все $25 млрд. Это 100% российские инвестиции»; «...сейчас
внутри Турции нашлись компании, которые хотят тоже быть участниками этого
процесса»; «Мы это только приветствуем».

Черновик g47093838 выкинут отдельно (pipeline/ingest/drop_pending.py,
дубль).

Без --write — сухой прогон.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / 'static' / 'data' / 'deals_promoted.json'
ID = 'g2f22b1dc'

OLD_EXTRA = ('Заявление Росатома впервые прозвучало 7 августа 2026 года. Глава Росатома '
             'Алексей Лихачев 21 апреля 2026 года говорил, что с рядом турецких компаний '
             'начато предметное обсуждение параметров участия в уставном капитале. '
             'Параллельно готовится выпуск облигаций «Атомэнергопрома» в китайских юанях '
             'и исламских облигаций (сукук) для финансирования АЭС «Аккую». По данным '
             'Минэнерго Турции на январь 2026 года, готовность первого энергоблока '
             'станции составляет 95%.')
NEW_EXTRA = (OLD_EXTRA + ' 28 октября 2026 года президент Владимир Путин публично '
             'подтвердил интерес турецких компаний к проекту и назвал это «приветствуем», '
             'уточнив, что строительство АЭС «Аккую» на 100% финансируется Россией '
             '(всего $25 млрд).')


def main(write):
    data = json.loads(DATA.read_text(encoding='utf-8'))
    card = next(c for c in data['deals'] if c['id'] == ID)
    assert card['extra'] == OLD_EXTRA, card['extra']
    print('%s: extra дополнен фактом от 28 октября 2026.' % ID)

    if not write:
        print('Сухой прогон. Применение — с ключом --write.')
        return 0

    data = json.loads(DATA.read_text(encoding='utf-8'))
    card = next(c for c in data['deals'] if c['id'] == ID)
    assert card['extra'] == OLD_EXTRA, card['extra']
    card['extra'] = NEW_EXTRA
    card.setdefault('src', [])
    if not any(u[1] == 'https://www.interfax.ru/business/1125517' for u in card['src'] if len(u) > 1):
        card['src'].append(['Интерфакс', 'https://www.interfax.ru/business/1125517'])
    DATA.write_text(json.dumps(data, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
    print('Сделано.')
    return 0


if __name__ == '__main__':
    sys.exit(main('--write' in sys.argv))
