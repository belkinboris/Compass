# -*- coding: utf-8 -*-
"""Приток 24 сентября 2026, карточка gb7ea4703 («Лента»/«Мария-Ра»):
откат преждевременного статуса «Закрыта».

ЧТО ПРОИЗОШЛО. enrich.py 24 сентября механически подхватил новую статью
«Делового Петербурга» (заголовок «"Лента" купила крупнейшую сибирскую
торговую сеть "Мария-Ра"», прошедшее время) и по слову «купила» поменял
статус карточки на «Закрыта» и заголовок — тоже в прошедшее время,
добавив событие kind=closed с пустой заметкой.

ПРОВЕРКА ЧТЕНИЕМ (шаг 9а, доп. поиск). Сама статья ДП внутри честно
пишет: сделку подтвердил лишь рыночный консультант, официально ни
покупатель («не комментируют рыночные слухи»), ни продавец не
подтверждали. Доп. поиск (WebSearch, 24 сентября) не нашёл НИ ОДНОГО
независимого подтверждения с момента появления новости 18–21 сентября:
retail.ru и amic.ru пересказывают тот же «Банкфакс», Толк прямо пишет
«сделка... закрыта или находится на заключительной стадии, однако в
компании "Лента" это не подтверждали», у Коммерсанта/Ведомостей/РБК/
Интерфакса своих публикаций с независимым источником нет, пресс-релиза
«Ленты», решения ФАС или записи в реестре сделок не нашлось.

ЧТО СДЕЛАНО. Статус и заголовок возвращены к настоящему времени (тому
же виду, что уже был установлен предыдущим чтением этой карточки —
см. post_preview). Событие kind=closed снято: оно не описывает новый
факт сверх уже записанного kind=negotiations, только более позднюю
статью с тем же непроверенным утверждением. Genuinely новые факты из
статьи ДП — заявление Ракшина о непереговорах уже устарело и не
внесено, а вот беneficiар «Ленты» (Мордашов), история поглощений
«Ленты» и собственная отчётность головной «Мария-Ра» за 2025 год — не
были в карточке раньше, добавлены. Честная оговорка о неподтверждении
(источник — «Толк») добавлена в law.appr рядом с уже стоявшим там
упоминанием ФАС.

Запуск: python3 pipeline/fix_lenta_maria_ra_premature_close_2026_09_24.py --write
"""
import argparse
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gb7ea4703'

OLD_TITLE = '«Лента» купила крупнейшую сибирскую торговую сеть «Мария-Ра»'
NEW_TITLE = '«Лента» покупает сеть «Мария-Ра»'

OLD_STATUS = 'Закрыта'
NEW_STATUS = 'Обсуждается'

OLD_TARGET_FIN = (
    'Основной операционной компанией торговой сети сегодня является ООО "Розница К-1". '
    'По данным "Контур.Фокус", выручка компании в прошлом году приблизилась к 128 '
    'миллиардам рублей, а чистая прибыль составила 2,7 миллиарда рублей.'
)
ADD_TARGET_FIN = (
    ' Головная "Мария-Ра" за 2025 год показала выручку 9,41 млрд рублей (−8,5%) и '
    'чистую прибыль 4,76 млрд рублей (−13%).'
)

OLD_APPR = 'В частности, участникам сделки, скорее всего, придётся дождаться одобрения Федеральной антимонопольной службы.'
ADD_APPR = (
    ' Сделку подтвердил Shopper\'s консультант, работающий с ретейлом: договорённость '
    'была ещё в мае, а последние месяцы шло согласование, в том числе в ФАС. В '
    'пресс-службе "Ленты" заявили, что "не комментируют рыночные слухи". Предварительно, '
    'сделка по продаже барнаульской сети закрыта или находится на заключительной '
    'стадии, однако в компании "Лента" это не подтверждали.'
)

OLD_EXTRA = (
    'По данным "Контур.Фокус", Александр Ракшин сейчас является соучредителем 41 '
    'компании с общей балансовой оценкой активов в 86 миллиардов рублей, 38 из них '
    'имеют своим основным видом деятельности именно управление недвижимостью. В '
    'прошлом году эти компании показали совокупную чистую прибыль в 13 миллиардов '
    'рублей, но на розничную торговлю (ООО "Розница К-1" — основное юрлицо сети) '
    'приходится только 2,7 миллиарда рублей.'
)
ADD_EXTRA = (
    ' Группа "Лента", бенефициаром которой является миллиардер Алексей Мордашов, за '
    'последние годы провела несколько крупных сделок: в 2023-м приобрела "Монетку", '
    'в 2024-м — "Улыбку радуги", в 2025-м — челябинскую "Молнию", в 2026-м — сеть '
    'гипермаркетов "О\'Кей".'
)


def main(write):
    data = json.load(open(DATA, encoding='utf-8'))
    card = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert card['title'] == OLD_TITLE
    card['title'] = NEW_TITLE

    assert card['status'] == OLD_STATUS
    card['status'] = NEW_STATUS

    events = card['events']
    assert events[0]['kind'] == 'closed' and events[0]['note'] == ''
    del events[0]

    assert card['eco']['target_fin'] == OLD_TARGET_FIN
    card['eco']['target_fin'] = OLD_TARGET_FIN + ADD_TARGET_FIN

    assert card['law']['appr'] == OLD_APPR
    card['law']['appr'] = OLD_APPR + ADD_APPR

    assert card['extra'] == OLD_EXTRA
    card['extra'] = OLD_EXTRA + ADD_EXTRA

    for label, url in (
        ('Retail.ru', 'https://www.retail.ru/news/lenta-priobrela-torgovuyu-set-mariya-ra-23-sentyabrya-2026-282462/'),
        ('Толк', 'https://tolknews.ru/obsestvo/225757-pravda-li-rukovodstvo-mariya-ra-podtverdilo-prodazhu-seti-kompanii-lenta'),
    ):
        if not any(s[1] == url for s in card['src']):
            card['src'].append([label, url])

    if write:
        json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
        print('Записано: статус и заголовок откачены, событие closed снято, факты дописаны.')
    else:
        print('Сухой прогон (--write, чтобы записать).')


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('--write', action='store_true')
    main(p.parse_args().write)
