# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
gf8b3e66e («36,6» купила петербургскую сеть «ЛекОптТорг & Родник
Здоровья», закрыта 1 октября 2023) — бренды сохранены, «36,6»
продолжила консолидацию рынка Петербурга, компания растёт.

Проверено лично прямым WebFetch (Фармвестник,
https://pharmvestnik.ru/content/news/Vyruchka-aptechnoi-seti-36-6-uvelichilas-na-29-6.html):
«Общая выручка компании выросла на 29,6%... и составила 97,0 млрд
руб.» (2024 год), «Абсолютное значение EBITDA составило 6,7 млрд руб.
при уровне рентабельности 7,7%», «число точек группы выросло на 18,7%
год к году и составило 2554 аптеки».

По данным саб-агента (Vademec.ru, не дозаверено отдельным WebFetch):
бренды «ЛекОптТорг» и «Родник здоровья» сохранены, не переименованы в
«36,6»; в декабре 2024 «36,6» купила ещё одну петербургскую сеть —
«Аптека для бережливых» (158 точек), закрепившись в Петербурге и
Ленобласти; по данным на 2025 год «36,6» занимает 10,3% рынка
Петербурга (3-е место в городе, после «Эрика&МЗ» 25,9% и «Неофарм»
15,3%); за 2025 год выручка компании выросла ещё на 21% до 117,4
млрд ₽, число аптек — до 2753.

НЕ ВКЛЮЧЕНО: официальная сумма сделки задним числом — по-прежнему не
раскрыта нигде, гендиректор компании прямо отказался называть сумму и
формат сделки в 2023 году; точное число аптек под каждым из двух
брендов по отдельности сегодня — источники дают только суммарные
цифры по всей группе «36,6», не по конкретному петербургскому активу.

Запуск: python3 pipeline/fix_36_6_lekopttorg_consolidation_and_growth.py
        python3 pipeline/fix_36_6_lekopttorg_consolidation_and_growth.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gf8b3e66e'

OLD_EXTRA = (
    'Сделка по приобретению 100% акционерного капитала ГК «ЛекОптТорг» '
    'и «Родник здоровья». Покупатель — ПАО «Аптечная сеть 36,6», '
    'продавцы — Назим Рамазанов и Анна Рубайло. К ПАО перешло 12 юрлиц '
    'объединённой сети.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Бренды «ЛекОптТорг» и «Родник здоровья» сохранены. «36,6» '
    'продолжила консолидацию рынка Петербурга: в декабре 2024 купила '
    'ещё одну местную сеть, «Аптека для бережливых» (158 точек), заняв '
    'к 2025 году 10,3% рынка города (3-е место). Группа растёт: '
    'выручка за 2024 год — 97 млрд ₽ (+29,6%), за 2025 год — 117,4 '
    'млрд ₽ (+21%), число аптек выросло до 2753.'
)

NEW_SRC = [
    ['Фармвестник', 'https://pharmvestnik.ru/content/news/Vyruchka-aptechnoi-seti-36-6-uvelichilas-na-29-6.html'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
