"""Месячная очередь 18.09.2026: карточка `gebead2e8` (HeadHunter/Happy Job) —
ПОВТОРНОЕ появление того же класса дефекта, что уже правился
`pipeline/fix_headhunter_happyjob_law_terms.py` (18 августа 2026): `law.terms`
снова несло дословную, но НЕ ПОДХОДЯЩУЮ по смыслу цитату — на этот раз:

  «Создатели платформы Happy Job, а также команда методологов, консультантов,
  разработчиков и дизайнеров во главе с основателем компании Алексеем
  Клочковым продолжат развивать продуктовую линейку и улучшать качество
  платформы, обмениваясь опытом с HeadHunter.»

Личная проверка первоисточника (happy-job.ru/news/happy-job-stanovitsya-
chastyu-ekosistemy-headhunter/, тот же адрес уже стоит в `src`) подтвердила:
это авторский абзац пресс-релиза САМОЙ Happy Job, адресованный ЕЁ
пользователям/клиентам («команда никуда не уходит, продукт продолжит
развиваться») — а не описание условия, на котором HeadHunter согласился на
покупку 51%. Во всём тексте статьи нет ни слова «опцион», «earn-out»,
«индемнити», «согласование», «структура сделки», «неконкуренция» — то есть
настоящего юридического материала для линзы «Юрист» по-прежнему нет ни в
одном из проверенных источников (Mergers.ru, TAdviser, Абирег, РБК Компании,
happy-job.ru). Дословность цитаты `review.py`/чтение не нарушала (фраза
реальна) — но уместность в поле `law.terms` нарушена ровно тем же способом,
что и в первый раз: поле для условий СДЕЛКИ, а не для описания судьбы
ПРОДУКТА цели.

Урок: правило от 18 августа («вкладка без данных не рендерится вовсе»)
защищает экран, но не мешает более позднему проходу дочитывания СНОВА
подтянуть похожую по форме, но чужую по смыслу фразу в то же поле — того же
класса, что уже описан в CLAUDE.md («Дословная цитата в НЕ СВОЁМ поле»).
Признак для будущих проверок: фраза о том, что «команда/продукт продолжит
работать/развиваться» — это адресовано клиентам цели, а не покупателю.

Запуск: python3 pipeline/fix_headhunter_happyjob_law_terms_2.py           # проверка
        python3 pipeline/fix_headhunter_happyjob_law_terms_2.py --write   # запись
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gebead2e8'
OLD_TERMS = ('Создатели платформы Happy Job, а также команда методологов, '
             'консультантов, разработчиков и дизайнеров во главе с '
             'основателем компании Алексеем Клочковым продолжат развивать '
             'продуктовую линейку и улучшать качество платформы, обмениваясь '
             'опытом с HeadHunter.')


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    card = next((c for c in data['deals'] if c['id'] == CARD_ID), None)
    assert card is not None, '%r не найдена в deals_promoted.json' % CARD_ID
    assert card['law'].get('terms') == OLD_TERMS, (
        'ожидали law.terms=%r, сейчас %r — состояние изменилось'
        % (OLD_TERMS, card['law'].get('terms')))

    print('ПРАВИМ %s: law.terms -> «—» (снова клиентская фраза-заверение '
          'вместо условия сделки; настоящих условий нет ни в одном источнике)'
          % CARD_ID)
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    card['law']['terms'] = '—'
    json.dump(data, open(DATA, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
