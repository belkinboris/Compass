import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g3b67afa3'

OLD_TARGET_FIN = '—'
NEW_TARGET_FIN = (
    'Выручка ПАО «М.Видео» по итогам 2024 года увеличилась на 4% до '
    '451,6 млрд руб., чистый убыток вырос в 3 раза до 20,1 млрд руб., '
    'EBITDA снизилась на 9,8% до 37,7 млрд руб. (Интерфакс).'
)

OLD_EXTRA = (
    'В результате выкупа акций топ-менеджментом компании (management '
    'buy-out) гендиректор ПАО «М.Видео» Билан Ужахов стал мажоритарным '
    'акционером группы «М.Видео - Эльдорадо». Он косвенно владеет '
    '53,633% акций через компанию МКООО «Эрикария», которая владеет 50% '
    'ПАО напрямую. Сделка следует за договоренностью апреля 2022 года о '
    'продаже акций от Саида Гуцериева российским предпринимателям.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Ужахов дважды передавал операционное управление, оставаясь '
    'контролирующим акционером: с 21 февраля 2025 года гендиректором '
    'стал Феликс Либ, а с марта 2026 года — Владислав Бакальчук (Либ '
    'занял пост председателя совета директоров). В 2025-2026 годах '
    'компания провела докапитализацию на 30 млрд руб. через допэмиссию '
    'в пользу «Кэпиталгард», SFI и связанных структур. В январе-марте '
    '2025 года велись переговоры о продаже сети Промсвязьбанку (оценка '
    'бизнеса — 300 млрд руб.), но продажа не состоялась — вместо неё '
    'прошла докапитализация (Интерфакс, Ведомости).'
)

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/business/1023612'],
    ['Интерфакс', 'https://www.interfax.ru/business/1009694'],
    ['Интерфакс', 'https://www.interfax.ru/business/1077658'],
    ['Ведомости', 'https://www.vedomosti.ru/investments/news/2026/08/13/1220924-dopemissiyu-mvideo'],
    ['Интерфакс', 'https://www.interfax.ru/business/1004958'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['target_fin'] == OLD_TARGET_FIN
    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== eco.target_fin: станет ===')
    print(NEW_TARGET_FIN)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['target_fin'] = NEW_TARGET_FIN
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
