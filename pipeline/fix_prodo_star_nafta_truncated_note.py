# -*- coding: utf-8 -*-
"""events[0].note карточки gmru-prodo-star-nafta-broiler (Продо/«Башкирский
бройлер», выкуп у «Стар Нафта») обрублен на середине слова — обрывался на
«...«Башк». Тот же класс дефекта, что уже чинили у g21795ec9 (ALMI Partner):
жёсткий лимит длины где-то в разборе притока, срабатывающий и на середине
слова (см. CLAUDE.md, «Один и тот же обрыв на ~260 знаках»).

Полный текст восстановлен по источнику (mergers.ru, data/inbox/raw, забрано
fetch_article_texts.py 17.08.2026) — та же статья слово в слово повторяется
в источнике дважды (второй раз — с атрибуцией «отмечает "Коммерсантъ"» и
дополнительными абзацами про сами компании), недостающий хвост взят из
первого повторения, продолжающего ровно с точки обрыва.

Восстановленный хвост («Башкирский бройлер» занимается выпуском
инкубационного яйца...) дословно совпадает с `eco.share` этой же карточки —
это не новая находка, а тот же факт, что уже показан на экране под другой
подписью. Значит в базе он лишний дважды, но в `events[0].note` он — часть
цельной цитаты о СОБЫТИИ (закрытии сделки), которую нельзя обрывать
посередине ради обхода дублирования (см. урок «Пропуск предложения
ПОСЕРЕДИНЕ цитаты рвёт дословность»): сохраняем текст целиком, а решает,
показывать ли повтор на экране, `noteIsNovel()` в static/index.html —
он и так спрячет этот блок как чистый повтор, ровно как и для
agrostroy-zemlya.

Запуск:
    python3 pipeline/fix_prodo_star_nafta_truncated_note.py            # сухой прогон
    python3 pipeline/fix_prodo_star_nafta_truncated_note.py --write     # запись
"""
import json
import sys

PATH = "static/data/deals_promoted.json"
ID = "gmru-prodo-star-nafta-broiler"

OLD = ('Условия сделки стороны не привели. Инвестиционный директор BGP '
       'Capital Юрий Левицкий говорит, что стоимость бизнеса «Башкирского '
       'бройлера» 1,4–2 млрд руб., но долг — 3 млрд руб. Экономика сделки '
       'определяется принимаемыми обязательствами, констатирует он. «Башк')
NEW = ('Условия сделки стороны не привели. Инвестиционный директор BGP '
       'Capital Юрий Левицкий говорит, что стоимость бизнеса «Башкирского '
       'бройлера» 1,4–2 млрд руб., но долг — 3 млрд руб. Экономика сделки '
       'определяется принимаемыми обязательствами, констатирует он. '
       '«Башкирский бройлер» занимается выпуском инкубационного яйца в '
       'Альшеевском районе Башкирии. Его валовый сбор 46 млн штук в год, '
       'в перспективе значение вырастет до 72 млн.')


def main(write):
    with open(PATH, encoding="utf-8") as f:
        base = json.load(f)
    by_id = {d["id"]: d for d in base["deals"]}
    d = by_id[ID]
    assert d["events"][0]["note"] == OLD, "events[0].note уже другой — уже правили?"
    d["events"][0]["note"] = NEW
    print(f"{ID}: events[0].note восстановлен (был обрублен на «Башк»)")

    if write:
        with open(PATH, "w", encoding="utf-8") as f:
            json.dump(base, f, ensure_ascii=False, indent=1)
        print("\nЗАПИСАНО.")
    else:
        print("\nСухой прогон — ничего не записано. Добавьте --write.")


if __name__ == "__main__":
    main(write="--write" in sys.argv)
