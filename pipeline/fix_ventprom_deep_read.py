# -*- coding: utf-8 -*-
"""Дочитывание карточки `gb98fcce5` (Артёмовский машиностроительный завод
«Вентпром», национализация 17 августа 2026 года) — суточный уровень очереди
дочитывания (`REVISION_BRIEF.md`), первое чтение после появления карточки
12 сентября 2026 (сама национализация состоялась 17 августа, приток завёл
карточку позже). Единственным источником карточки был mergers.ru; полный
разбор WebFetch по трём независимым изданиям дал факты, которых там не было.

Что добавлено, с проверкой каждой цитаты дословным чтением страницы (не по
пересказу):

1. `buyer` — JustMedia (03.09.2026): «сейчас единственным акционером
   предприятия является Российская Федерация в лице свердловского ТУ
   Росимущества». Профиль «Росимущество» (`g9fd82fee`) уже есть в базе.

2. `law.struct` — JustMedia: решение касалось не только самого завода, но и
   «ряда аффилированных с ним фирм»; veved.ru называет одну из них —
   ООО «Вентпром-Инжиниринг», привлечённую в процесс третьим лицом.

3. `law.appr` дополнен: дата подачи иска (veved.ru — «в начале мая 2026
   года»), основание для признания владельцев экстремистским объединением
   (денежный перевод гражданину Украины, проживание Горшкова за пределами
   России с 2023 года) и то, что решение подлежит немедленному исполнению
   несмотря на возможность обжалования (судья Елена Мосягина). Отдельно —
   ВАЖНАЯ ОГОВОРКА источника: сам Интерфакс называет ответчика Олега
   Горшкова «полным тёзкой одного из предыдущих собственников предприятия»
   — то есть это может быть НЕ тот же человек, что владел 27,9% акций в
   2018 году (уже стоит в `eco.context`). Оговорка добавлена дословно, чтобы
   не создать у читателя впечатление, что это точно одно и то же лицо, —
   сама карточка этого не утверждает, но два поля рядом легко читаются как
   единая история одного человека.

4. `eco.context` дополнен заявлением компании о продолжении деятельности
   (JustMedia): гендиректор Павел Вяткин остаётся единственным руководителем,
   кадровых решений со стороны ТУ Росимущества пока не было.

Источники добавлены в `src`: JustMedia, veved.ru, Интерфакс (все три
процитированы дословно при чтении, не по пересказу саб-агента).

Запуск:
    python3 pipeline/fix_ventprom_deep_read.py            # сухой прогон
    python3 pipeline/fix_ventprom_deep_read.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'
CID = 'gb98fcce5'

OLD_LAW_STRUCT = '—'
NEW_LAW_STRUCT = (
    'Решение касалось не только самого завода: Ленинский районный суд '
    'обратил в доход государства и ряд аффилированных с «Вентпромом» фирм. '
    'Одна из них — ООО «Вентпром-Инжиниринг», привлечённая в процесс '
    'третьим лицом.'
)

OLD_LAW_APPR = (
    'Акции перешли в доход государства решением Ленинского районного суда '
    'Екатеринбурга от 17 августа 2026 года по делу «о запрете деятельности '
    'общественных объединений» — истцом выступал заместитель прокурора '
    'Свердловской области, по делу вынесено более 20 исполнительных листов, '
    'среди ответчиков — Олег Горшков и другие лица.'
)
NEW_LAW_APPR = (
    'Акции перешли в доход государства решением Ленинского районного суда '
    'Екатеринбурга от 17 августа 2026 года по делу «о запрете деятельности '
    'общественных объединений» — истцом выступал заместитель прокурора '
    'Свердловской области, иск подан в начале мая 2026 года, по делу '
    'вынесено более 20 исполнительных листов, среди ответчиков — Олег '
    'Горшков (возможно, его полный тёзка, а не тот же человек, что владел '
    'заводом в 2018 году) и другие лица. Основанием для признания владельцев '
    'экстремистским объединением стал денежный перевод гражданину Украины и '
    'то, что Горшков с 2023 года живёт за пределами России. Судья Елена '
    'Мосягина постановила, что решение подлежит немедленному исполнению, '
    'хотя оно ещё может быть обжаловано.'
)

OLD_ECO_CONTEXT = (
    'Прежний совладелец — Олег Горшков, которому на март 2018 года '
    'принадлежало 27,9% акций.'
)
NEW_ECO_CONTEXT = (
    'Прежний совладелец — Олег Горшков, которому на март 2018 года '
    'принадлежало 27,9% акций. Сам завод заявил, что продолжает обычную '
    'хозяйственную деятельность: гендиректор Павел Вяткин остаётся '
    'единственным руководителем, кадровых решений со стороны '
    'территориального управления Росимущества пока не было.'
)

NEW_SOURCES = [
    ['JustMedia', 'https://www.justmedia.ru/news/economy/sud-natsionaliziroval-artemovskiy-zavod-ventprom-primeniv-novuyu-skhemu'],
    ['veved.ru', 'https://veved.ru/eburg/press/politika-txt/214348-vladelcev-krupnejshego-v-rossii-proizvoditelja-promyshlennyh-ventiljatorov-priznali-jekstremistskim-obedineniem.html'],
    ['Интерфакс', 'https://www.interfax.ru/business/1112931'],
]

NEW_BUYER_ID = 'g9fd82fee'  # Росимущество


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    deals = {d['id']: d for d in data['deals']}
    companies = data['companies']
    card = deals[CID]

    assert companies[NEW_BUYER_ID]['name'] == 'Росимущество'

    already_applied = (card.get('buyer') == NEW_BUYER_ID
                        and card['law']['struct'] == NEW_LAW_STRUCT
                        and card['law']['appr'] == NEW_LAW_APPR
                        and card['eco']['context'] == NEW_ECO_CONTEXT)
    if already_applied:
        print('Уже применено — нечего делать (скрипт идемпотентен).')
        return

    assert card.get('buyer') is None, 'buyer уже занят: %r' % card.get('buyer')
    assert card['law']['struct'] == OLD_LAW_STRUCT
    assert card['law']['appr'] == OLD_LAW_APPR
    assert card['eco']['context'] == OLD_ECO_CONTEXT
    existing_urls = {u for _, u in card['src']}
    to_add = [pair for pair in NEW_SOURCES if pair[1] not in existing_urls]

    print('Правки для %s (%s):' % (CID, card['title']))
    print('  buyer -> %s (%s)' % (NEW_BUYER_ID, companies[NEW_BUYER_ID]['name']))
    print('  law.struct: %r -> %r' % (OLD_LAW_STRUCT, NEW_LAW_STRUCT))
    print('  law.appr: дополнено датой иска, основанием, оговоркой о тёзке')
    print('  eco.context: дополнено заявлением компании о продолжении работы')
    print('  src: +%d адресов' % len(to_add))

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    card['buyer'] = NEW_BUYER_ID
    card['law']['struct'] = NEW_LAW_STRUCT
    card['law']['appr'] = NEW_LAW_APPR
    card['eco']['context'] = NEW_ECO_CONTEXT
    card['src'].extend(to_add)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
