# -*- coding: utf-8 -*-
"""Месячная очередь, 9 сентября 2026 — дочитывание карточки `g97a481d8`
(«ВК приобрела 100% РНКО "Деньги.Мэйл.Ру" у P.J.V. Digital Forces LTD»,
добавлена в базу 3 августа 2026, полностью обыскана в тот же день).

Дельта-поиск (саб-агент + личная проверка) нашёл, что дата в карточке
(15 февраля 2024) — НЕ дата сделки, а, судя по всему, дата, close к
дате ПЕРЕИМЕНОВАНИЯ РНКО (см. ниже). Реальная сделка закрылась намного
раньше. Личный WebFetch подтвердил дословно:

1) Дата. Указ президента, разрешающий сделку, — от 17 февраля 2023 года
   (kommersant.ru/doc/5838786). Сама сделка закрыта, по Sostav.ru
   (07.03.2023, публикация на следующий день после события): «Сделка
   была закрыта 6 марта» [2023 года]. Это на ГОД раньше даты, стоявшей в
   карточке, — год меняется, поэтому правка идёт отдельным скриптом с
   `assert`, а не через `review.py`.

2) Сумма. Тот же источник: «Доля «Компании ВК» в РНКО оценивается в
   90 млн руб.»

3) Природа сделки — внутригрупповая передача, а не покупка у
   независимого продавца. Тот же источник: «кипрской P.J.V. Digital
   Forces LTD, входящей в международный материнский холдинг VK Company
   Limited» — то есть продавец сам был структурой группы ВК; сделка —
   перевод актива из кипрского контура в российское юрлицо, а не
   приобретение у третьей стороны.

4) Дальнейшая судьба РНКО. Личный WebFetch (profbanking.com,
   22 февраля 2024) подтвердил дословно: «Расчётная небанковская
   кредитная организация «Деньги.Мэйл.Ру» переименована в… «ВК
   Платёжные решения»» — вероятно, именно эта публикация 2024 года и
   была ошибочно принята источником @LawFirms/составителем карточки за
   дату сделки.

Запуск:
    python3 pipeline/fix_vk_dengi_mail_ru_date_and_details.py            # сухой прогон
    python3 pipeline/fix_vk_dengi_mail_ru_date_and_details.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_DATE = '2024-02-15'
NEW_DATE = '2023-03-06'

OLD_SUM = 'Не раскрыта'
NEW_SUM = '90 млн ₽ (по оценке)'

OLD_ECO_CONTEXT = (
    'В октябре 2022 года правительство РФ запретило сделки с долями в 45 '
    'кредитных организациях, принадлежащих лицам из «недружественных '
    'стран», — в этот список входила и РНКО «Деньги.Мэйл.Ру». Точная '
    'дата сделки в объявлении юридической фирмы не названа.'
)
NEW_ECO_CONTEXT = (
    'В октябре 2022 года правительство РФ запретило сделки с долями в 45 '
    'кредитных организациях, принадлежащих лицам из «недружественных '
    'стран», — в этот список входила и РНКО «Деньги.Мэйл.Ру». Указ '
    'президента, разрешающий эту сделку, подписан 17 февраля 2023 года, '
    'сделка закрыта 6 марта 2023 года. Продавец, кипрская P.J.V. Digital '
    'Forces LTD, сама входила в международный материнский холдинг VK '
    'Company Limited — то есть сделка была переводом актива внутри '
    'группы ВК, а не покупкой у независимой стороны. В феврале 2024 года '
    'РНКО «Деньги.Мэйл.Ру» переименована в РНКО «ВК Платёжные решения».'
)

OLD_ECO_SUM = 'Не раскрыта'
NEW_ECO_SUM = '90 млн ₽ (по оценке)'

NEW_SRC = [
    ['Sostav.ru', 'https://www.sostav.ru/publication/vk-59320.html'],
    ['Профбанкинг', 'https://www.profbanking.com/only-news/4784-vk-payment-solutions'],
]


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['g97a481d8']

    assert d.get('date') == OLD_DATE, \
        'g97a481d8 date уже другой: %r' % (d.get('date'),)
    assert d.get('sum') == OLD_SUM, \
        'g97a481d8 sum уже занят: %r' % (d.get('sum'),)
    assert d['eco']['context'] == OLD_ECO_CONTEXT, \
        'g97a481d8 eco.context уже другой: %r' % (d['eco']['context'],)
    assert d['eco']['sum'] == OLD_ECO_SUM, \
        'g97a481d8 eco.sum уже другой: %r' % (d['eco']['sum'],)
    urls = {s[1] for s in d['src']}
    for src in NEW_SRC:
        assert src[1] not in urls, 'источник уже добавлен: %s' % src[1]

    print('g97a481d8: date "2024-02-15" -> "2023-03-06"; sum/eco.sum '
          '-> "90 млн ₽ (по оценке)"; eco.context дополнен (указ, '
          'внутригрупповая природа, переименование в 2024); добавлены '
          'источники sostav.ru, profbanking.com')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['date'] = NEW_DATE
    d['sum'] = NEW_SUM
    d['eco']['sum'] = NEW_ECO_SUM
    d['eco']['context'] = NEW_ECO_CONTEXT
    d['src'].extend(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
