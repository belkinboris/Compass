import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g623cf943'

OLD_SELLER = None
NEW_SELLER = 'Николас Хендерсон-Стюарт и кипрская «B.P.G. European Baby Food»'

OLD_EXTRA = (
    'Сделка закрыта в 2023 году. Покупателем выступила компания «Экто»'
    ' Юсуфа Алекперова, сына акционера ЛУКОЙЛа Вагита Алекперова.'
    ' Бенефициары продавца не раскрыты. В капитал компании вложено'
    ' 2,3 млрд ₽.'
)
NEW_EXTRA = (
    'Сделка закрыта в апреле 2023 года. Покупателем выступила компания'
    ' «Экто» Юсуфа Алекперова, сына акционера ЛУКОЙЛа Вагита Алекперова.'
    ' Продавцы 49% — британец Николас Хендерсон-Стюарт и кипрская'
    ' «B.P.G. European Baby Food»; остальные 51% принадлежат россиянину'
    ' Андрею Курочкину, который ранее был исполнительным директором'
    ' «Белфуд Продакшн» и продавцом не был. В капитал компании вложено'
    ' 2,3 млрд ₽.'
)

OLD_CONTEXT = (
    'Среди других активов компании — железнодорожный оператор «Вестерн'
    ' Петролеум Транспортейшн», доли в нефтесервисной компании «ВэллТех»'
    ' и автодилере «Лукавто», а также бренд энергетических напитков'
    ' Plan B, который продаётся на АЗС «Лукойла».'
)
NEW_CONTEXT = (
    OLD_CONTEXT + ' «Белфуд Продакшн» начал работу в агрогородке Новка'
    ' Витебского района в марте 2016 года на площадях обанкротившегося'
    ' Витебского плодоовощного комбината.'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6616866'],
    ['Белрынок', 'https://belmarket.by/news/72ca35a8-ac85-40c1-b719-8f4df1485df3'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal.get('seller') == OLD_SELLER
    assert deal['extra'] == OLD_EXTRA
    assert deal['eco']['context'] == OLD_CONTEXT

    existing_urls = {s[1] for s in deal['src']}
    add_src = [s for s in NEW_SRC if s[1] not in existing_urls]
    new_src = deal['src'] + add_src

    print('=== seller: станет ===')
    print(NEW_SELLER)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== eco.context: станет ===')
    print(NEW_CONTEXT)
    if add_src:
        print('\n=== src: добавится ===')
        for s in add_src:
            print(s)

    if write:
        deal['seller'] = NEW_SELLER
        deal['extra'] = NEW_EXTRA
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
