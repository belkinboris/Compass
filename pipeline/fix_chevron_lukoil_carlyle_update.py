# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка g84fd8194 (Chevron
рассматривает приобретение зарубежных активов Лукойла): обязательная
проверка статуса — родственная карточка про IHC/ЛУКОЙЛ (g75920ee3) уже
дописана в прошлой партии тем же фактом, здесь его нужно отразить со
стороны Chevron. 29 января 2026 года ЛУКОЙЛ заключил предварительное,
неэксклюзивное соглашение НЕ С CHEVRON, а с фондом Carlyle — но Chevron
не вышел из борьбы: как минимум до начала февраля 2026 года продолжал
претендовать на портфель параллельно с Carlyle. Отдельно, независимо от
этого спора, Chevron ведёт СВОЙ собственный трек — переговоры напрямую
с правительством Ирака об управлении месторождением Западная Курна-2
(национализированным Ираком после ухода ЛУКОЙЛа из-за санкций) — это
НЕ конкуренция за портфель LUKOIL International GmbH, а отдельное,
самостоятельное соглашение. Казахстанские активы (Тенгиз, Карачаганак)
также не входят в периметр спора Chevron/Carlyle — они остаются у
ЛУКОЙЛа независимо от исхода сделки.

Статус «Обсуждается» остаётся верным: сделка с Carlyle всё ещё не
закрыта на 21 августа 2026 года (лицензия OFAC продлена до 19 сентября).

Не через review.py: несколько разных источников на одно поле, каждый
со своей частью истории.

Источники — читал напрямую (fetch_article_texts.py, все закэшированы):
Коммерсантъ (24.07.2026, doc/8844173), forbes.kz (06.02.2026),
nationalbusiness.kz (06.02.2026), Zawya (11.03.2026), The Moscow Times
(21.08.2026).
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g84fd8194'
OLD_CONTEXT = (
    'Среди других потенциальных покупателей зарубежных активов '
    '«Лукойла» — американский инвестиционный фонд Carlyle, компании из '
    'Румынии и Казахстана. Швейцарский трейдер Gunvor также выражал '
    'готовность приобрести активы, но позже отозвал предложение из-за '
    'отказа Минфина США выдать необходимую лицензию.'
)
ADDITION = (
    '29 января 2026 года ЛУКОЙЛ заключил предварительное соглашение НЕ '
    'С CHEVRON, а с фондом Carlyle: «В январе ЛУКОЙЛ достиг '
    'предварительного соглашения о продаже Lukoil International GmbH с '
    'американским инвестиционным фондом Carlyle. Сделку должен '
    'одобрить американский Минфин». Однако Chevron не вышел из борьбы: '
    '«Как минимум два потенциальных покупателя, включая Chevron, '
    'по-прежнему претендуют на приобретение зарубежных активов '
    '"Лукойла"», и среди других претендентов также назван «консорциум с '
    'участием Quantum Energy Partners и инвестиционного банка Xtellus '
    'Partners». Параллельно и независимо от этого спора Chevron ведёт '
    'собственные переговоры с правительством Ирака об управлении '
    'национализированным месторождением Западная Курна-2: «Iraq\'s '
    'cabinet has approved the final terms and conditions of the '
    'framework agreement signed between the Ministry of Oil... and '
    'U.S.-based Chevron Corporation for the management and operation of '
    'the West Qurna 2 oil field» — это отдельное соглашение с Ираком, а '
    'не часть спора за портфель ЛУКОЙЛа. По состоянию на 21 августа 2026 '
    'года сделка ЛУКОЙЛа с Carlyle всё ещё не закрыта: «Вашингтон '
    'продлил до 19 сентября 2026 года генеральную лицензию, разрешающую '
    'вести переговоры о продаже зарубежных активов российской '
    'нефтекомпании Лукойл».'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} eco.context: += соглашение ЛУКОЙЛа с Carlyle, отдельный трек Chevron/Ирак")
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
