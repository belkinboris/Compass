"""Недельная очередь (REVISION_BRIEF), карточка ga525c46b («Союз Маринс
Групп» выкупила гостиницу «Амбассадор»): недельный дельта-поиск нашёл
профиль покупателя (не был известен вовсе, кроме бренда Marins Hotels)
и историю владения предметом до сделки — многолетний корпоративный
конфликт совладельцев, уголовное дело и банкротство одного из них,
объясняющие, почему объект продавался семь лет. Не через review.py:
старые значения eco.context/law.struct — из уже процитированного
Коммерсанта, но по разным абзацам статьи, не образуют непрерывный
кусок с новыми цитатами (для law.struct — из другого источника, dp.ru).

Источники — читал напрямую (fetch_article_texts.py, закэшированы):
Коммерсантъ (kommersant.ru/doc/8890090, уже в src) и dp.ru (2021,
исторический материал о корпоративном конфликте).
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'ga525c46b'

OLD_CONTEXT = (
    'В целом инвесторы стали осторожнее относиться к инвестициям в '
    'гостиничный сегмент из-за длительных сроков окупаемости, высокой '
    'стоимости заемного финансирования и охлаждения экономики, говорит '
    'Екатерина Андреева. По данным NF Group, в январе—июне 2026 года '
    'средний уровень загрузки отелей в Петербурге снизился на 2,4 '
    'процентного пункта, до 60%. Средний тариф показал сдержанный рост '
    '— только на 2% за год, до 10,6 тыс. руб. в сутки.'
)
CONTEXT_ADDITION = (
    '«Союз Маринс Групп» создана Александром Куликовым, погибшим в '
    '2016 году; сейчас её конечные бенефициары не раскрываются. '
    'Компания занимается производством фильмов (сериал «Морпехи», '
    'фильм «Вий»), а также управляет коммерческой недвижимостью, '
    'например бизнес-центром «Нагатинский» (70 тыс. кв. м) в Москве — '
    'гостиничный бизнес под брендом Marins Hotels является отдельным '
    'направлением, сейчас в портфеле 12 отелей в городах России. '
    'Согласно СПАРК, в 2025 году выручка ООО УК «Союз Маринс Групп» '
    'выросла на 19%, до 841,5 млн руб., чистая прибыль составила 10,8 '
    'млн руб. До перехода прав собственниками ООО «РК 5–7» в равных '
    'долях выступали соучредители компании «Петербургские отели» '
    'Бексолт Давлатов и Виктор Прокопцов. Директор департамента '
    'инвестиций и рынков капитала Bright Rich | CORFAC International '
    'Екатерина Андреева не исключает, что прежние собственники могли '
    'продать объект, рассчитывая сконцентрироваться на другом бизнесе. '
    'История долгих поисков покупателя связана с корпоративным '
    'конфликтом: в 2021 году гостиницу выставляла на продажу управляющая '
    'компания W8 за 3,5 млрд руб., указав владельцами ООО «Отель '
    'Амбассадор» Александра Терентьева (62,6%) и Виктора Прокопцова '
    '(37,4%), находившихся в состоянии конфликта с 2016 года; в феврале '
    '2021 года Терентьев был осуждён на 6 лет лишения свободы за '
    'покушение на мошенничество, а в сентябре 2020 года признан '
    'банкротом с обязательствами свыше 3,6 млрд руб.'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + CONTEXT_ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} eco.context: += профиль покупателя, история владения предметом "
          f"(конфликт, банкротство, первоначальный листинг 2021 года)")
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
