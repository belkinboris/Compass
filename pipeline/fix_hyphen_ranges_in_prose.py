# -*- coding: utf-8 -*-
"""Каталог вычитки, класс C3: диапазоны дефисом в прозе — 162 поля.

Прошлый круг («дефис в диапазонах сумм», 138 полей) чинил только `sum` и
`eco.sum`; та же болезнь осталась в прозе — `eco.val`, `eco.context`,
`extra` и других полях, где число тоже пишется через голый дефис вместо
короткого тире: «13-15 лет», «100-160 тыс. руб.», «2023-2024 году».
В базе уже 540+ случаев такого же диапазона с ПРАВИЛЬНЫМ тире (например,
«200–550 млн», «2028–2030») — это не новое правило, а распространение
уже принятой в базе типографики на поля, которые предыдущий круг не тронул.

РЕГУЛЯРКА ЗАЩИЩЕНА С ОБЕИХ СТОРОН, чтобы не задеть НЕ-диапазоны:
  * ISO-дату («2021-07-28») — вторая группа дефис-цифры сразу после первой
    ломает границу с обеих сторон, ни один из двух дефисов не совпадает;
  * код/артикул («K2-9b») — если перед первым числом или после второго
    стоит буква без пробела (часть одного «слова»), совпадение не считается;
  * суффикс множественного числа («1990-2000-х») — то же самое: дефис перед
    «х» не отделён от цифры, граница не совпадает.

ДВА ИСКЛЮЧЕНИЯ, НАЙДЕННЫЕ ЧТЕНИЕМ, А НЕ ПРАВИЛОМ (регулярка их не отличит):
  * gf5c8e14e — «номеров 8-800» — российский префикс бесплатной линии,
    не диапазон значений.
  * gc8a29a42 — «ул. Смоленской, 31-33» — номер дома, у таких в русской
    типографике дефис остаётся дефисом (не тире), это другой класс.

ТРИ ТОЧЕЧНЫХ СЛУЧАЯ, ПОПАВШИЕСЯ ПО ПУТИ (не диапазон сам по себе, а факт,
стоящий не в том поле или не в том написании — тот же класс уроков, что и
основная правка «Сумма: …» из начала этой сессии):
  * g6822cbf4 (extra) — хвост «Сумма: 7.5-10 млрд руб (экспертная оценка,
    официально не раскрыто)» после имени консультанта; `sum`/`eco.sum`
    уже несут ту же оценку в верном написании («7,5–10 млрд ₽ (по
    оценке)») — хвост убирается целиком, это дубль, а не новый факт.
  * cc0e7565f (extra, eco.context, eco.val, sum, eco.sum) — единственное
    место, где вообще стоит оценка стоимости, было целиком служебной
    строкой «Сумма: 460-500 млрд руб (5,9 млрд USD). (Russ (оцениваемая
    компания))» в eco.context; факт перенесён в sum/eco.sum/eco.val по
    образцу уже принятого в базе шаблона «Оценка экспертов; N–M млрд ₽
    (по оценке)» (см. g020432e9); служебный тег «(Russ (оцениваемая
    компания))» — утечка ключа сопоставления компании в текст, снят из
    extra и eco.context (класс «служебный id источника доезжает до
    экрана» из CLAUDE.md).
  * g81163284 — `eco.sum` уже верно написан («$25–50 млн (по оценке)»,
    доллар перед числом, короткое тире, пробел перед скобкой), а `sum` и
    `eco.val` остались в старом написании («25-50 млн $(по оценке)» —
    доллар после числа, дефис, без пробела); оба приведены к уже верному
    соседнему полю той же карточки, а не к новому решению.

Запуск:
    python3 pipeline/fix_hyphen_ranges_in_prose.py            # сухой прогон
    python3 pipeline/fix_hyphen_ranges_in_prose.py --write    # запись
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

ECO_FIELDS = ('rationale', 'context', 'share', 'val', 'target_fin', 'fin', 'finadv')
LAW_FIELDS = ('struct', 'appr', 'terms')

RANGE = re.compile(r'(?<![\w./-])(\d+(?:[.,]\d+)?)-(\d+(?:[.,]\d+)?)(?![\w./-])')

EXCLUDE_LITERAL = {
    ('gf5c8e14e', 'eco.rationale'): '8-800',
    ('gc8a29a42', 'extra'): '31-33',
}

SETS = [
    ('g6822cbf4', 'extra',
     'Финансовый консультант сделки со стороны продавца — Aspring Capital '
     'Сумма: 7.5-10 млрд руб (экспертная оценка, официально не раскрыто).',
     'Финансовый консультант сделки со стороны продавца — Aspring Capital.'),

    ('cc0e7565f', 'extra',
     'Б1 (ex-EY) провела аудит и оценку бизнеса оператора наружной рекламы '
     'Russ. Использовалась методология сравнительной оценки на основе '
     'мультипликаторов EV/EBITDA с анализом аналогичных компаний '
     '(JCDecaux, Stroer, Lamar, Outfront). Оценка не включает долю Russ в '
     'совместном предприятии РВБ с Wildberries. (Russ (оцениваемая '
     'компания))',
     'Б1 (ex-EY) провела аудит и оценку бизнеса оператора наружной рекламы '
     'Russ. Использовалась методология сравнительной оценки на основе '
     'мультипликаторов EV/EBITDA с анализом аналогичных компаний '
     '(JCDecaux, Stroer, Lamar, Outfront). Оценка не включает долю Russ в '
     'совместном предприятии РВБ с Wildberries.'),
    ('cc0e7565f', 'eco.context',
     'Сумма: 460-500 млрд руб (5,9 млрд USD). (Russ (оцениваемая компания))',
     '—'),
    ('cc0e7565f', 'eco.val',
     'Б1 (ex-EY) провела аудит и оценку бизнеса оператора наружной рекламы '
     'Russ.',
     'Оценка экспертов; 460–500 млрд ₽ (5,9 млрд $, по оценке).'),
    ('cc0e7565f', 'sum', None, '460–500 млрд ₽ (по оценке)'),
    ('cc0e7565f', 'eco.sum', '—', '460–500 млрд ₽ (по оценке)'),

    ('g81163284', 'sum',
     '25–50 млн $(по оценке)', '$25–50 млн (по оценке)'),
    ('g81163284', 'eco.val',
     'Оценки экспертов; 25-50 млн $(по оценке)',
     'Оценки экспертов; $25–50 млн (по оценке)'),
]


def fix_range(text):
    return RANGE.sub(r'\1–\2', text)


def _self_check():
    assert fix_range('на горизонте 9-12 месяцев.') == 'на горизонте 9–12 месяцев.'
    assert fix_range('в 2023-2024 году уже закрыл') == 'в 2023–2024 году уже закрыл'
    assert fix_range('доля 3,5-4%. По словам') == 'доля 3,5–4%. По словам'
    assert fix_range('оценка $1,1-1,3 млрд (по оценке)') == 'оценка $1,1–1,3 млрд (по оценке)'
    # ISO-дата — не трогать ни один из двух дефисов
    assert fix_range('Дата сделки в черновике (2021-07-28) неточна') == \
        'Дата сделки в черновике (2021-07-28) неточна'
    # код/артикул — буква вплотную к цифре ломает границу
    assert fix_range('приобрел 51%-ную долю К2-9b (компании') == \
        'приобрел 51%-ную долю К2-9b (компании'
    # суффикс «-х» — дефис перед буквой не отделён
    assert fix_range('работал в 1990-2000-х годах') == 'работал в 1990-2000-х годах'
    # телефонный префикс и номер дома — исключены точечно, не регуляркой:
    # сама регулярка их бы тронула (проверяем, что защита EXCLUDE_LITERAL
    # в main() действительно нужна, а не полагается на то, что regex сам
    # промолчит на этих случаях)
    assert fix_range('номеров 8-800) в рамках') == 'номеров 8–800) в рамках'
    assert fix_range('Смоленской, 31-33 в Соломенском') == \
        'Смоленской, 31–33 в Соломенском'


def get_field(card, path):
    obj = card
    for part in path.split('.'):
        if not isinstance(obj, dict):
            return None
        obj = obj.get(part)
    return obj


def set_field(card, path, value):
    parts = path.split('.')
    obj = card
    for part in parts[:-1]:
        obj = obj.setdefault(part, {})
    obj[parts[-1]] = value


def main(argv):
    _self_check()
    data = json.load(open(DATA, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}

    special_fields = {(cid, field) for cid, field, _old, _new in SETS}

    plan = []
    for deal in data['deals']:
        pairs = [('extra', deal.get('extra'))]
        pairs += [('eco.' + k, (deal.get('eco') or {}).get(k)) for k in ECO_FIELDS]
        pairs += [('law.' + k, (deal.get('law') or {}).get(k)) for k in LAW_FIELDS]
        for field, value in pairs:
            if not isinstance(value, str) or not value:
                continue
            if (deal['id'], field) in special_fields:
                continue  # чинится точечно в SETS, не общим правилом
            excl = EXCLUDE_LITERAL.get((deal['id'], field))
            new = fix_range(value)
            if excl and excl in value:
                # вернуть точечно защищённый диапазон обратно к дефису
                new = new.replace(fix_range(excl), excl)
            if new != value:
                plan.append((deal, field, value, new))

    for cid, field, old, _new in SETS:
        current = get_field(by_id[cid], field)
        assert current == old, \
            '%s.%s: поле уже другое: %r, ожидали %r' % (cid, field, str(current)[:60], str(old)[:60])

    print('Диапазонов в прозе (regex): %d полей' % len(plan))
    for deal, field, old, new in plan[:8]:
        print('  %s %-16s %r -> %r' % (deal['id'], field, old[:40], new[:44]))
    print('Точечных правок: %d' % len(SETS))
    for cid, field, old, new in SETS:
        print('  %s %-12s %r -> %r' % (cid, field, str(old)[:50], str(new)[:50]))

    if '--write' not in argv:
        print('\nСухой прогон. Запись — с ключом --write.')
        return 0

    for deal, field, _old, new in plan:
        set_field(deal, field, new)
    for cid, field, _old, new in SETS:
        set_field(by_id[cid], field, new)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('ЗАПИСАНО.')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
