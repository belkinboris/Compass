"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g3db7d882 (РумелкоАгро приобрел 80% долей агрохозяйства ООО «Кашин
луг», 27.11.2023, статус «Закрыта») — тот же холдинг продолжил
консолидацию молочно-животноводческих активов, а структуры того же
бенефициара (Владимира Лисина) отдельно купили крупный актив в
пищепроме — источники расходятся, тот ли это холдинг.

Никольское — проверено лично прямым WebFetch (Интерфакс, 17.01.2024):
«с 12 января этого года холдингу принадлежит 100% ООО «Никольское»»
— тот же холдинг «Румелко», предыдущие владельцы — частные лица,
компания занимается КРС и производством молока (тот же профиль, что
и «Кашин луг»).

АО «Прогресс» (бренды «Фрутоняня», «Малышам», «Липецкий бювет») —
проверено лично прямым WebFetch (Fontanka.ru, 30.09.2024): «Связанные
с основателем... НЛМК Владимиром Лисиным структуры купили липецкого
производителя детского питания — АО «Прогресс»» — но ТОТ ЖЕ автор
явно называет «Румелко» ОТДЕЛЬНЫМ проектом Лисина («Еще один проект
Лисина в сельском хозяйстве — московская компания «Румелко», которая
производит корма для животных»), то есть это не то же самое
юрлицо/холдинг, что купил «Кашин луг» и «Никольское», а другой актив
того же бенефициара — источники (Fontanka против Monocle.ru)
расходятся в том, консолидируются ли активы в одну группу.

НЕ ВКЛЮЧЕНО: показатели «Кашина луга» за 2024-2025 годы и решение
проблемы неиспользуемых 211,1 га — саб-агент не нашёл новых данных;
сумма сделки с «Прогрессом» — источники называют её нераскрытой,
оценки расходятся (около 70 млрд ₽ — не дозаверено отдельным
WebFetch); розничная сеть «Румелкоагро-молоко» (2025) — не относится
к этой карточке напрямую.

Запуск: python3 pipeline/fix_rumelko_nikolskoye_and_fruttonyanya_context.py
        python3 pipeline/fix_rumelko_nikolskoye_and_fruttonyanya_context.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g3db7d882'

OLD_EXTRA = (
    'Сделка закрыта 27 ноября 2023. Покупатель — РумелкоАгро (группа '
    'компаний Владимира Лисина, специализирующаяся на молочном '
    'животноводстве и растениеводстве). Продавцы — физические лица. '
    'Приобретены 80% долей ООО «Кашин луг» в Тверской области. '
    'Целевой объект — агрохозяйство с финансовыми показателями 2022: '
    'выручка 73,2 млн руб., чистая прибыль 15 млн руб.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Тот же холдинг продолжил консолидацию: с 12 января 2024 года '
    'ему принадлежит 100% ООО «Никольское» — ещё одного молочно-'
    'животноводческого хозяйства, тоже выкупленного у частных лиц. '
    'Отдельно структуры того же бенефициара, Владимира Лисина, купили '
    'в 2024 году крупного производителя детского питания АО '
    '«Прогресс» (бренды «Фрутоняня», «Малышам») — источники '
    'расходятся в том, тот ли это холдинг «Румелко»: Fontanka.ru '
    'называет «Румелко» отдельным, не связанным с этой покупкой '
    'проектом.'
)

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/business/940562'],
    ['Fontanka.ru', 'https://www.fontanka.ru/2024/09/30/74154179/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
