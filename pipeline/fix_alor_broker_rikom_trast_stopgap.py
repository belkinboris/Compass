# -*- coding: utf-8 -*-
"""Недельная очередь (REVISION_BRIEF, второй уровень), карточка
g6bf41023 («Алор брокер» купил неназванную брокерскую компанию) —
первая узкая дельта поверх полного обыска (25.08.2026): найден
провалившийся промежуточный шаг ДО покупки. Проверено лично прямым
WebFetch.

`eco.context` (дополнено). Дословно (abn.agency, 30.06.2026, 09:58):
«"Алор брокер" сообщил клиентам о передаче функций по учету и хранению
ценных бумаг стратегическому партнеру компании — ИК "Риком-Траст"» —
решение объяснялось «для обеспечения непрерывности торговых операций
клиентов на фондовом рынке». Судя по тому, что карточка сама же
говорит о недоступности торгов на фондовом рынке клиентам ПОСЛЕ этого
июньского шага, партнёрство с «Риком-Траст» не решило проблему доступа
— и уже 24 августа «Алор» купил отдельного брокера с той же целью
(восстановление депозитарной лицензии). Хронология: 26 июня — отзыв
лицензии ЦБ; 30 июня — временная передача учёта «Риком-Траст»; 24
августа — покупка нового брокера.

НЕ ВКЛЮЧЕНО: реестровые данные ЦБ РФ (cbr.ru/finorg) о статусе лицензии
— это структурированные данные реестра, а не текст статьи, не
процитированы дословно, используются только как косвенное, не
записываемое в карточку подтверждение; название купленной компании,
восстановление лицензии, сумма сделки, консультанты — по-прежнему не
раскрыты ни одним источником, несмотря на разные углы поиска.

Запуск: python3 pipeline/fix_alor_broker_rikom_trast_stopgap.py
        python3 pipeline/fix_alor_broker_rikom_trast_stopgap.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g6bf41023'

OLD_CONTEXT = (
    'На фоне кризиса в группе сменился генеральный директор. Пост '
    'принял Александр Лужбин, уже руководивший структурой с 2011 по '
    '2015 год. Эксперты считают назначение логичным антикризисным шагом '
    'для усиления контроля рисков и быстрого восстановления всей '
    'инфраструктуры. 26 июня 2026 года ЦБ аннулировал депозитарную '
    'лицензию «Алора» из-за того, что брокер, по словам регулятора, не '
    'соблюдал антисанкционное законодательство — три указа президента '
    '(№95, №138 и №840), запрещающих схемы, по которым российские '
    'инвесторы покупали со скидкой активы у иностранцев, чтобы продать '
    'дороже в России. Сейчас «Алор» сосредоточен на сопровождении '
    'клиентов и переводе их активов к другим брокерам: торги на '
    'фондовом рынке клиентам недоступны, однако можно торговать на '
    'срочном и валютном рынках, а компания продолжает обслуживать '
    'институциональных инвесторов. В «Алоре» заявили, что планируют '
    'восстановить возможность торговли на фондовом рынке, но как '
    'именно — не уточнили.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' Между отзывом лицензии и покупкой брокера был промежуточный шаг: '
    '«"Алор брокер" сообщил клиентам о передаче функций по учету и '
    'хранению ценных бумаг стратегическому партнеру компании — ИК '
    '"Риком-Траст"» для «обеспечения непрерывности торговых операций '
    'клиентов на фондовом рынке» (abn.agency, 30 июня 2026) — судя по '
    'тому, что торги остаются недоступны, эта мера не решила проблему.'
)

NEW_SRC = ['abn.agency', 'https://abn.agency/2026/06/30/alor-broker-perevodit-uchet-aktivov-klientov-v-depozitarij-ik-rikom-trast/']


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    assert not any(s[1] == NEW_SRC[1] for s in deal['src']), 'источник уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src добавится ===')
    print(NEW_SRC)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].append(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
