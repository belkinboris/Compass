# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), партия 22: две карточки pre-IPO
2024 года (ГК «Цифровые привычки», Ultimate Education), уже прошедшие
полный обыск и недельную дельту.

gaa7602e7 («Цифровые привычки»): дозаполнены финансы за 2025 год
(рост выручки во многом за счёт закрытых M&A-сделок) и статус движения
к IPO — акционеры одобрили преобразование в ПАО, план подтверждён на
конец 2027 года.

g6a453b19 (Ultimate Education): карточка называла раунд «₽600 млн» —
это была заявленная ЦЕЛЬ (РБК, октябрь 2024, до закрытия книги заявок);
итоговый закрытый результат — 565 млн ₽, «что соответствует заявленным
ранее ожиданиям компании» (Ведомости, 11 декабря 2024, статья о
закрытии раунда). Правится `sum`/`eco.sum` на фактический результат.
Дополнительно дописана смена гендиректора (май 2025).

Не через review.py: во всех случаях либо меняется УЖЕ не пустое поле
на текст из ДРУГОГО источника (одна цитата не может покрыть старый и
новый текст разом), либо сумма меняется на другое число (дословность
не разрешает подмену числа без буквального совпадения).
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')


def extend(deal, path, old, addition):
    obj = deal
    for part in path[:-1]:
        obj = obj[part]
    key = path[-1]
    assert obj[key] == old, f"{deal['id']} {'.'.join(path)}: неожиданное значение {obj[key]!r}"
    obj[key] = old + ' ' + addition


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}

    # --- ГК «Цифровые привычки» ---
    d = by_id['gaa7602e7']
    extend(d, ['eco', 'fin'],
           'выручка группы по итогам 2024 г. удвоилась по сравнению с '
           'аналогичным периодом прошлого года и достигла 1,5 млрд руб. '
           '(+97%), а чистая прибыль составила 565 млн руб., что более '
           'чем в два раза превышает результат 2023 г. (+240%).',
           'По итогам 2025 года выручка выросла на 41,4% до 2,1 млрд '
           'руб. — как за счёт органического роста, так и вследствие '
           'закрытия сразу четырёх M&A-сделок; OIBDA выросла на 85% до '
           '1,3 млрд руб. с маржой в 59%, чистая прибыль — на 89% до '
           '1,1 млрд руб. с рентабельностью 53,8% (Т-Инвестиции).')
    extend(d, ['eco', 'context'],
           'Акции будет размещать АО «Цифровые привычки», являющееся '
           'холдинговой компанией. В состав группы входят '
           'лицензированные ИТ-компании — «Цифровые привычки», '
           '«Финейтив» и «Платформа КИН». По информации “Ъ”, 100% '
           'группы принадлежит ИТ-предпринимателю Александру '
           'Елизарьеву.',
           'В июне 2026 года акционеры группы одобрили преобразование '
           'компании из АО в ПАО и подтвердили намерение провести IPO '
           'до конца 2027 года (Абирег).')

    # --- Ultimate Education ---
    d = by_id['g6a453b19']
    OLD_SUM = '600 млн ₽'
    NEW_SUM = '565 млн ₽'
    assert d['sum'] == OLD_SUM, f"sum: неожиданное значение {d['sum']!r}"
    assert d['eco']['sum'] == OLD_SUM, f"eco.sum: неожиданное значение {d['eco']['sum']!r}"
    d['sum'] = NEW_SUM
    d['eco']['sum'] = NEW_SUM
    extend(d, ['eco', 'context'],
           'Холдинг Ultimate Education объединяет тематические онлайн-'
           'школы Psyhomedia, XYZ School, Bang Bang Education и Moscow '
           'Digital School.',
           'В мае 2025 года со-СЕО холдинга назначены Владимир Синицын '
           'и Анна Тимофеева, а прежний гендиректор Павел Мосейкин '
           'перешёл в совет директоров и занялся стратегическим '
           'развитием компании (EdTechs.ru).')

    print('gaa7602e7: eco.fin += итоги 2025 года (в т.ч. M&A); '
          'eco.context += преобразование в ПАО, план IPO на 2027 год')
    print(f"g6a453b19 sum/eco.sum: {OLD_SUM!r} -> {NEW_SUM!r} "
          "(заявленная цель 600 млн ₽ — итоговый закрытый результат "
          "565 млн ₽, Ведомости)")
    print('g6a453b19: eco.context += смена гендиректора (май 2025)')

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
