def hint(card):
    """Какой конструкцией писать заголовок этой карточки (для находки приемки)."""
    return HINTS.get((card.get('type'), phase(card.get('status'))), 'см. pipeline/title_standard.py, RULES')


def verb_ok(card, title=None):
    """True, если в заголовке глагол стандарта для типа и статуса карточки; None — стандарта нет."""
    rx = VERBS.get((card.get('type'), phase(card.get('status'))))
    if not rx:
        return None
    return bool(re.search(r'(?<![А-Яа-яЁё])' + rx + r'(?![А-Яа-яЁё])', title or card.get('title') or '', re.I))


def render(base):
    by = {d['id']: d for d in base['deals']}
    lines = ['Третья редакция по вашим замечаниям: род глагола («Инсайт Лизинг» купил), вход в капитал без названной доли — «купил долю» / «может купить акции», а не «проинвестировал».', '', RULES, '', '10 примеров (было → стало):']
    for i, (cid, new) in enumerate(EXAMPLES, 1):
        d = by[cid]
        assert verb_ok(d, new) in (True, None), (cid, new)
        lines.append('%d. %s\n→ %s\nhttps://projectcompass.ru/#/deal/%s' % (i, d['title'], new, cid))
    lines.append('')
    lines.append('Одобрите или поправьте ответом здесь. После одобрения новые карточки сразу пишутся по стандарту — приемка не пропустит заголовок без глагола стандарта, — а старые переписываются в вычитке вместе с остальными полями.')
    return '\n'.join(lines)


def main(argv):
    base = json.load(open(DATA, encoding='utf-8'))
    text = render(base)
    print(text)
    if '--console' in argv:
        sys.path.insert(0, os.path.join(ROOT, 'pipeline'))
        sys.path.insert(0, os.path.join(ROOT, 'pipeline', 'ingest'))
        import httpx
        import console_topics
        from send_drafts import send_one
        token = os.environ.get('TELEGRAM_BOT_TOKEN', '')
        thread = console_topics.thread_id('admin')
        with httpx.Client(timeout=20) as client:
            ok = all(send_one(client, token, chat, text, None, thread) for chat in console_topics.console_chats())
        print('Отправлено в консоль' if ok else 'НЕ ДОШЛО')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
