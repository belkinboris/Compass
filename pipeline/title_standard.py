ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CLOSED, SIGNED, TALKS, FAILED = 'closed', 'signed', 'talks', 'failed'


def phase(status):
    s = str(status or '')
    if s.startswith('Закрыт'):
        return CLOSED
    if s.startswith(('Подписан', 'Согласование')):
        return SIGNED
    if s.startswith('Не состоял'):
        return FAILED
    return TALKS


# Разрешенные глаголы (основы) по типу и статусу.
VERBS = {
    ('M&A', CLOSED): r'купил[аио]?',
    ('M&A', SIGNED): r'покупа(?:ет|ют)',
    # Продажа без покупателя (владелец одобрил 6 ноября 2026): «Y выставлен на продажу [за N ₽]».
    ('M&A', TALKS): r'(?:мо(?:жет|гут) купить|собира(?:ется|ются) купить|выставлен[аоы]? на продажу)',
    ('M&A', FAILED): r'отказал(?:ся|ась|ось|ись) от покупки',
    # Инвестиция: доля известна — «купил N%» (Артем и владелец, 6 ноября 2026: доля —
    # главное в такой новости, а покупка доли за деньги в капитал — экономически покупка).
    # Доля не названа — все равно покупка: «купил долю / акции» (владелец, 6 ноября 2026:
    # «если нет четкого процента, это автоматически не значит, что это инвестиция, лучше
    # все равно писать «может купить акции»»). «Проинвестировал» — только деньги в проект,
    # без доли в компании. Кредит и заем — не инвестиция.
    ('Инвестиция', CLOSED): r'(?:купил[аио]? (?:\d|дол[а-я]*|акци[а-я]*)|проинвестировал[аи]? в проект)',
    ('Инвестиция', SIGNED): r'(?:покупа(?:ет|ют) (?:\d|дол[а-я]*|акци[а-я]*)|инвестиру(?:ет|ют) в проект)',
    ('Инвестиция', TALKS): r'(?:(?:мо(?:жет|гут)|собира(?:ется|ются)) купить (?:\d|дол[а-я]*|акци[а-я]*))',
    ('Продажа с торгов', CLOSED): r'купил[аио]? на торгах',
    ('Продажа с торгов', TALKS): r'(?:выставил[аио]?|выставлен[аоы]?) на торги',
    ('Временное управление', CLOSED): r'переданы? во временное управление',
    # Передача в управление по решению собственника (владелец, 6 ноября 2026):
    # «X передана в управление Y»; до передачи — «X передадут в управление Y».
    ('Передача в управление', CLOSED): r'передан[аоы]? в управление',
    ('Передача в управление', SIGNED): r'(?:передадут|переда(?:ет|ют)) в управление',
    ('Передача в управление', TALKS): r'(?:мо(?:жет|гут) передать|собира(?:ется|ются) передать|передадут) в управление',
}

RULES = """Стандарт заголовка карточки, третья редакция (на сайте). Пост в канале остается свободным — для него отдельная строка.

Покупка: закрыта — «X купил [N%] Y [у Z]»; подписана или на согласовании — «X покупает…»; обсуждается — «X может купить…» (слухи) или «X собирается купить…» (объявили стороны); сорвалась — «X отказался от покупки Y».
Вход в капитал: доля известна — «X купил N% Y»; доля не названа — «X купил долю в Y» / «X может купить акции Y». «Проинвестировал» — только деньги в проект без доли в компании. Кредит и заем — не инвестиция.
Торги: «X купил на торгах Y» / «Z выставил на торги Y». Продажа без покупателя: «Y выставлен на продажу [за N ₽]».
Временное управление по указу: «Активы X переданы во временное управление Y». Передача управления собственником: «X передана в управление Y».
Изъятие: «Активы X обращены в доход государства».
IPO и СП: «X провел IPO на Мосбирже» / «X и Y создали СП».
Род глагола: название, которое само — русское слово своего рода, согласуется с ним («Роснефть» купила, «Лента» купила, «Аэрофлот» купил); название без рода (бренд, аббревиатура, латиница, составное вроде «Инсайт Лизинг») — мужской род («Инсайт Лизинг» купил); перед названием слово рода — по нему («компания X купила», «АО X купило»); множественное — «совладельцы», «акционеры».
Имена — узнаваемые (бренд, а не юрлицо), одна мысль, без второй части через тире."""

