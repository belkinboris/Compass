"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
gb5e69c73 (Сбербанк продал торговые комплексы «Сибирские городки»
фирме «Онлайн финанс», статус «Закрыта» с 2023 года) — нашлась судьба
одного из 13 объектов сети и финансовое состояние холдинга.

Закрытие одного из объектов — проверено лично прямым WebFetch
(НГС42.ру, 12.04.2024): ТЦ на ул. Зорге, 17 в Новокузнецке (22 тыс.
кв. м) выставлен на продажу «для разбора» за 16 млн руб., на тот
момент ещё работал («на 12 апреля открыто около 40 торговых точек»).
Проверено лично прямым WebFetch (НГС42.ру, 11.05.2025): «Пожалуй, самым
крупным ТЦ, которого не стало в городе за последнее время, стал
«Сибирский городок»… Его сначала закрыли, затем распродали по частям.»

Финансы холдинга — по данным саб-агента (ФНС/агрегаторы saby.ru и
checko.ru, две независимые сверки совпали): ООО «Сибирские Городки»
(материнская структура) в 2024 году ушла в убыток 294,5 млн руб. после
прибыльного 2023 года (93,3 млн руб. чистой прибыли при выручке
1,1 млрд руб.) — эта цифра НЕ проверена лично прямым WebFetch в этом
прогоне (агрегаторская сверка через ФНС, не первичный документ), внесена
с оговоркой.

НЕ ВКЛЮЧЕНО: судьба остальных 12 объектов сети (проверен и подтверждён
только новокузнецкий); девелопер «Мера» — банкротства не нашлось,
компания действует, но со сдвигом сроков по не связанному с этой
сделкой проекту («Дом на Арочной», НГС42.ру, 18.05.2026) — отдельная
история, в карточку не переносится.

Запуск: python3 pipeline/fix_sberbank_sibirskie_gorodki_postdeal.py
        python3 pipeline/fix_sberbank_sibirskie_gorodki_postdeal.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gb5e69c73'

OLD_EXTRA = (
    'Сбербанк реализовал продажу 13 торговых комплексов «Сибирские '
    'городки» фирме «Онлайн финанс», связанной с кемеровским '
    'девелопером «Мера». Согласно данным «СПАРК-Интерфакс», сделка '
    'связана с рынком жилищной недвижимости.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Один из 13 объектов — ТЦ на ул. Зорге в Новокузнецке (22 тыс. '
    'кв. м) — впоследствии закрыт и распродан по частям (НГС42.ру). По '
    'данным агрегаторов ФНС, материнская структура сети в 2024 году '
    'ушла в убыток 294,5 млн руб. после прибыльного 2023 года (93,3 '
    'млн руб. чистой прибыли).'
)

NEW_SRC = [
    ['НГС42.ру', 'https://ngs42.ru/text/business/2024/04/12/73454639/'],
    ['НГС42.ру', 'https://ngs42.ru/text/gorod/2025/05/11/75428498/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
