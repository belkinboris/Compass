def main(write: bool) -> int:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    cards = {d["id"]: d for d in data["deals"]}
    applied = []

    for cid, src_path, quote, dst_path in MOVES:
        card = cards[cid]
        cur = get(card, src_path)
        assert cur and quote in cur, "%s.%s: текст не найден дословно" % (cid, src_path)
        old_dst = get(card, dst_path)
        new_dst = quote if not old_dst or old_dst in ("—", "-", "") else (old_dst + " " + quote)
        applied.append((cid, src_path, dst_path, quote[:55]))
        if write:
            remainder = cur.replace(quote, "").strip()
            remainder = re.sub(r"\s+", " ", remainder)
            set_(card, src_path, remainder if remainder else "—")
            set_(card, dst_path, new_dst)

    print("Перенесено кусков: %d" % len(applied))
    for cid, s, d, snippet in applied:
        print("   %-14s %-14s → %-15s «%s…»" % (cid, s, d, snippet))

    if not write:
        print("\n(сухой прогон; чтобы записать — --write)")
        return 0
    DATA.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    print("\nзаписано")
    return 0


if __name__ == "__main__":
    sys.exit(main("--write" in sys.argv))
