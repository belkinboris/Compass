def get(card, path):
    if path == "extra":
        return card.get("extra")
    a, b = path.split(".")
    return (card.get(a) or {}).get(b)


def set_(card, path, value):
    if path == "extra":
        card["extra"] = value
        return
    a, b = path.split(".")
    card.setdefault(a, {})[b] = value


