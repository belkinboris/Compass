import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g6e46ac10'

OLD_EXTRA = (
    'Продажа компании Трансфин-М (лизинговая компания с операционным '
    'лизингом вагонов и парком техники). Официальная сумма не '
    'раскрывается. Покупателем выступили ЗПИФ Инвестсервис (70%, '
    'управление УК Аурум Инвестмент) и ЗПИФ Талер (30%, управление ООО '
    'Тетис Кэпитал). Предполагаемыми конечными бенефициарами являются '
    'гендиректор Максим Анищенков, члены совета директоров Александр '
    'Голанд и Иван Благодатских, имевшие преимущественное право '
    'выкупа.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' В июне 2024 года, уже после продажи компании, Алексей Тайчер был '
    'задержан по возвращении из-за границы. 20 апреля 2026 года суд '
    'приговорил его к 11 годам колонии общего режима, штрафу 2 млн '
    'руб. и запрету занимать должности в коммерческих организациях на '
    'два года десять месяцев — за мошенничество на сумму свыше 1,16 '
    'млрд руб. Дело касается операций «Трансфин-М» 2017 года (за семь '
    'лет до продажи компании) и не связано с условиями самой сделки.'
)

NEW_SRC = [
    ['Fontanka.ru', 'https://www.fontanka.ru/2026/04/01/76343591/'],
    ['Сберометр', 'https://www.sberometer.ru/rvn/213049/eks-vladelec-transfin-m-aleksey-taycher-prigovoren-k-11-godam-kolonii-za-hischenie-pochti-1-2-mlrd'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
