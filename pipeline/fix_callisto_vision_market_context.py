# -*- coding: utf-8 -*-
"""Месячная очередь, 9 сентября 2026 — дочитывание карточки `g13d60ebc`
(«Kama Flow инвестировала 700 млн ₽ в разработчика систем маркировки
Callisto Vision», добавлена в базу 3 августа 2026, полностью обыскана в
тот же день).

Дельта-поиск (саб-агент + личная проверка) не нашёл новых структурных
фактов о самой сделке (доля, финансовый консультант, дальнейшая судьба —
всё по-прежнему не раскрыто ни в одном источнике), но нашёл рыночный
контекст: ComNews в аналитическом обзоре венчурного рынка за I полугодие
2026 года называет эту сделку в числе крупнейших раундов на сжимающемся
рынке (падение инвестиций в ИТ-стартапы на 62% год к году, капитал
уходит в промышленные технологии и M&A). Личный WebFetch (comnews.ru,
07.09.2026) подтвердил дословно: «Callisto Vision (промышленная
маркировка и прослеживаемость) - $9,1 млн, инвестор Kama Flow.»

Саб-агент также нашёл неподтверждаемые сведения об основателях компании
(противоречие между источниками относительно текущей должности одного из
предполагаемых основателей) — сознательно НЕ внесены: недостаточно
доказательств для записи через дословную цитату.

Запуск:
    python3 pipeline/fix_callisto_vision_market_context.py            # сухой прогон
    python3 pipeline/fix_callisto_vision_market_context.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_ECO_CONTEXT = (
    'Callisto Vision — российский разработчик систем маркировки и '
    'контроля качества продукции. Они работают более чем на 150 '
    'высокоскоростных линиях; проекты выполнены в российских регионах, '
    'Узбекистане и Саудовской Аравии. За 2025 год на оборудовании и ПО '
    'компании промаркировано свыше 6 млрд единиц потребительской '
    'продукции в пищевой, фармацевтической и других отраслях.'
)
NEW_ECO_CONTEXT = OLD_ECO_CONTEXT + (
    ' По оценке отраслевого обзора венчурного рынка (ComNews, сентябрь '
    '2026), эта сделка вошла в число крупнейших венчурных раундов первого '
    'полугодия 2026 года — на фоне падения инвестиций в ИТ-стартапы на '
    '62% год к году капитал на российском рынке смещается в промышленные '
    'технологии и M&A.'
)

NEW_SRC = ['ComNews', 'https://www.comnews.ru/content/247242/2026-09-07/2026-w37/1008/rossiyskiy-venchur-szhalsya-do-293-mln-dengi-ukhodyat-promyshlennye-tekhnologii-i-ma']


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['g13d60ebc']

    assert d['eco']['context'] == OLD_ECO_CONTEXT, \
        'g13d60ebc eco.context уже другой: %r' % (d['eco']['context'],)
    urls = {s[1] for s in d['src']}
    assert NEW_SRC[1] not in urls, 'источник уже добавлен'

    print('g13d60ebc: eco.context дополнен (место сделки среди крупнейших '
          'венчурных раундов I полугодия 2026); добавлен источник comnews.ru')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['eco']['context'] = NEW_ECO_CONTEXT
    d['src'].append(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
