# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g61e63e94
(«Агрокомплекс Ткачева» закрыл покупку молочного завода PepsiCo на
Кубани) — карточка держалась на Telegram-агрегаторе (@dealsma), а не на
первоисточнике. Проверено лично прямым WebFetch двух источников.

1) `src` (дополнено) — настоящие первоисточники. Интерфакс, 29.05.2024,
https://www.interfax.ru/business/962844 — независимо подтверждает
сделку целиком: «"Агрокомплекс им. Н.И.Ткачева"... закрыл сделку по
покупке молочного завода в Тимашевском районе Краснодарского края,
ранее принадлежавшего компании "Вимм-Билль-Данн"» (станица Медведовская
— в составе Тимашевского района, расхождения с картой района нет).
Коммерсантъ (2026), https://www.kommersant.ru/doc/7909448 — подтверждает
работу завода как минимум в 2026 году.

2) `eco.context` (дополнено) — сумма сделки подтверждена нераскрытой
независимо («точную дату покупки актива, а также его стоимость в
компании не уточнили»); инвестиции в модернизацию и новые цеха.
Дословно (Интерфакс): «агрохолдинг уже вложил в модернизацию завода
233,5 млн рублей, запустив в промышленную эксплуатацию цех по
производству майонеза мощностью до 54 тонн продукции в сутки»; «Этим
летом на предприятии заработают еще два цеха: производство плавленых
сыров мощностью 6 тонн в сутки, а также творога и творожных изделий
мощностью 10 тонн в сутки».

3) `eco.context` (дополнено) — завод продолжает работать. Дословно
(Коммерсантъ, 2026): «Молочную продукцию выпускают три завода: «Молоко»
и «Сыры Кубани» в станице Выселки, а также Медведовский молочный завод
в станице Медведовской».

`date` НЕ меняется на 29.05.2024: это дата публикации статьи Интерфакса
о закрытой сделке, а не подтверждённая дата самого закрытия — сам
источник прямо пишет, что точная дата не уточнена (родня уроку CLAUDE.md
«Дата публикации статьи — не дата сделки»).

НЕ ВКЛЮЧЕНО: независимая оценка суммы — ни один источник её не называет
и не оценивает; консультанты — не найдены ни в одном из проверенных
источников (Интерфакс, Ъ, milknews.ru, kuban24.ru, Forbes); согласование
ФАС — не упоминается ни в одном источнике.

Запуск: python3 pipeline/fix_agrokompleks_tkacheva_pepsico_real_source.py
        python3 pipeline/fix_agrokompleks_tkacheva_pepsico_real_source.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g61e63e94'

OLD_CONTEXT = (
    'Объем выпуска молочной продукции ВБД за прошлый год снизился на '
    '8,7%, до 940,7 тыс. тонн, выручка компании выросла до 117,17 млрд '
    'руб. против 107,79 млрд руб. годом ранее.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' Сумма сделки не раскрыта независимо: «точную дату покупки актива, '
    'а также его стоимость в компании не уточнили» (Интерфакс). '
    'Агрохолдинг «вложил в модернизацию завода 233,5 млн рублей, '
    'запустив в промышленную эксплуатацию цех по производству майонеза '
    'мощностью до 54 тонн продукции в сутки»; летом 2024 запущены цеха '
    'плавленых сыров (6 тонн в сутки) и творога (10 тонн в сутки). По '
    'данным Коммерсанта (2026), завод продолжает работать: «Молочную '
    'продукцию выпускают три завода: «Молоко» и «Сыры Кубани» в станице '
    'Выселки, а также Медведовский молочный завод в станице '
    'Медведовской».'
)

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/business/962844'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/7909448'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
