import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gf0ce42ac'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Закрыта'

OLD_CONTEXT = (
    'в 2024 году «Азот Инвест» начислил Федяеву 3,571 млрд рублей '
    'дивидендов, выплатил — 3,058 млрд рублей. Рыбальченко было '
    'начислено 48 тысяч рублей дивидендов.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' Ещё до закрытия сделки Федяев передал долю сестре: «Собственником '
    '100% АО "Азот Инвест"... стала Светлана Рыбальченко» (Коммерсантъ, '
    '14 марта 2025) — юрист связывал это с опасением санкций (партнёр '
    'Федяева Роман Троценко уже под санкциями ЕС и Британии). Сделка '
    'закрылась 28 мая 2026 года иначе, чем предполагалось: «Александр '
    'Орехов... увеличил долю в... ГК "Азот" с 60% до 100%», «Из капитала '
    'ГК "Азот" вышла... Светлана Рыбальченко, владевшая 40%» — Орехов и '
    'Троценко ранее были совладельцами ИК «АЕОН» (Коммерсантъ, 28 мая '
    '2026).'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/7566990'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8693027'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS
    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== status: станет ===')
    print(NEW_STATUS)
    print('\n=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['status'] = NEW_STATUS
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
