# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка gc9a9d929
(Luding Group приобрела бренд «Полугар») — карточка уже фиксировала
планы управляющего директора Luding Group Гарегина Шахмеликяна
запустить новые линейки под маркой; искали, реализованы ли они.

Реализованы дважды, проверено лично прямым WebFetch. Водка (Коммерсантъ,
30.06.2025): «Luding Group запускает производство водки в суперпремиаль-
ном сегменте под маркой "Полугар"», крепость «38,5%», цена «около 1,3
тыс. руб. за 0,5 л.». Крафтовая серия (strongweek.ru, 12.03.2026): «В
конце марта на российский рынок выходит новая коллекция "Полугар
Премиум Крафт", приуроченная к 15-летию современной истории бренда.
Серия включает три крафтовых напитка неизменной для "Полугара" крепости
38,5%». В обеих новостях Илья Родионов (продавец бренда) сохраняет роль
— представлен как «наследник и производитель "Полугара"» — соответствует
изначальному плану «продолжить сотрудничество с господином Родионовым».

`eco.context` дополнен фактом о реализации плана.

НЕ ВКЛЮЧЕНО: конкретные цифры роста продаж за 2025-2026 годы (заявленная
цель 250-300% за три года) — ни в одном источнике не нашлось отчёта о
фактическом росте, план остаётся только планом. Структурная роль
Родионова в Luding Group (доля в капитале, должность) — источники
называют только производственную/творческую роль, не структурную;
не домысливаем. Другие M&A-сделки Luding Group в алкогольном сегменте
— не найдено, упомянутые бренды (Tchaikovsky, Lockwood, «Айвазовский»)
уже существовали у компании, не новые приобретения.

Запуск: python3 pipeline/fix_luding_polugar_new_lines_launched.py
        python3 pipeline/fix_luding_polugar_new_lines_launched.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gc9a9d929'

OLD_CONTEXT = (
    'Luding Group с 2022 года являлась эксклюзивным дистрибутором '
    '«Полугара». Компания намерена продолжить сотрудничество с '
    'господином Родионовым, заявил управляющий директор Luding Group '
    'Гарегин Шахмеликян. В планах Luding Group — нарастить продажи '
    '«Полугара» в ближайшие три года на 250–300%, а также запустить '
    'новые линейки под этой маркой, добавил господин Шахмеликян.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' План реализован: «Luding Group запускает производство водки в '
    'суперпремиальном сегменте под маркой "Полугар"» крепостью 38,5% '
    'по цене около 1,3 тыс. руб. за 0,5 л (Коммерсантъ, 30 июня 2025 '
    'года), а к 15-летию бренда вышла «новая коллекция "Полугар Премиум '
    'Крафт"» из трёх напитков той же крепости (strongweek.ru, 12 марта '
    '2026 года). Илья Родионов сохраняет роль — представлен как '
    '«наследник и производитель "Полугара"».'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/7851711'],
    ['strongweek.ru', 'https://strongweek.ru/novosti/5333-polugar-predstavlyaet-novuyu-premialnuyu-seriyu-kraftovykh-napitkov'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT

    new_src = deal['src'] + NEW_SRC

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
