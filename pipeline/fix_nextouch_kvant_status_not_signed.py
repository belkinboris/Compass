# -*- coding: utf-8 -*-
"""Месячная очередь качества, 11 сентября 2026 — карточка `g0431fc51`
(«NexTouch объявила о покупке обанкротившегося производителя телевизоров
«Квант»», август 2026) несла статус «Подписана» — это была правка
`review.py` от 9 августа 2026 года по правилу «слово «объявил» есть в
широком словаре для статуса «Подписана»».

ПОЧЕМУ ЭТО ОШИБКА. Заголовок карточки дословно означает лишь намерение
(«объявила о покупке»), а не факт подписания договора — правило
сработало на слове, а не на смысле, тот же класс дефекта, что уже
записан в CLAUDE.md для других слов-триггеров статуса. Личный WebFetch
подтвердил дословно на трёх разных датах (5 августа, 3 и 4 сентября
2026 года — то есть месяц спустя после объявления статус всё ещё не
изменился):
- BFM (https://www.bfm.ru/amp/news/614316): «Ведется работа по
  приобретению этого актива»; «Сделка будет закрыта через шесть —
  максимум восемь месяцев».
- Abireg, 3 сентября (https://abireg.ru/newsitem/117050/): «...в начале
  августа компания заявила о намерении приобрести активы группы».
- Abireg, 4 сентября (https://abireg.ru/newsitem/117108/): «Активы
  «Кванта» намеревался приобрести производитель интерактивного
  оборудования NexTouch».

Ни один источник (включая самый свежий, месяц спустя) не говорит о
подписанном договоре — везде «намерена/намеревался/ведётся работа».
Статус возвращается к «Обсуждается» — исходному значению до ошибочной
правки. Заодно добавлены новые факты о процедуре банкротства предмета
(появившиеся уже после объявления намерения).

Запуск:
    python3 pipeline/fix_nextouch_kvant_status_not_signed.py            # сухой прогон
    python3 pipeline/fix_nextouch_kvant_status_not_signed.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_STATUS = 'Подписана'
NEW_STATUS = 'Обсуждается'

OLD_ECO_CONTEXT = 'Первоначальная стоимость предприятия оценивалась в 3 млрд ₽ без учёта долгов.'

NEW_ECO_CONTEXT = OLD_ECO_CONTEXT + (
    ' 3 августа 2026 года арбитражный суд Москвы признал ООО «Квант» '
    'несостоятельным и ввёл конкурсное производство сроком на шесть '
    'месяцев, до 3 февраля 2027 года; в реестр кредиторов вошли '
    'требования 24 кредиторов на 763,4 млн ₽, ФНС заявила о намерении '
    'включить ещё 154,4 млн ₽. NexTouch заявляет, что сделка будет '
    'закрыта через шесть — максимум восемь месяцев с момента объявления.'
)

NEW_SRC = [
    ['BFM', 'https://www.bfm.ru/amp/news/614316'],
    ['Abireg', 'https://abireg.ru/newsitem/117050/'],
    ['Abireg', 'https://abireg.ru/newsitem/117108/'],
]


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['g0431fc51']

    assert d.get('status') == OLD_STATUS, 'статус уже другой: %r' % (d.get('status'),)
    assert d['eco'].get('context') == OLD_ECO_CONTEXT, 'eco.context изменился: %r' % (d['eco'].get('context'),)
    urls = {s[1] for s in d['src']}
    for src in NEW_SRC:
        assert src[1] not in urls, 'источник уже добавлен: %s' % src[1]

    print('g0431fc51: status %r -> %r (не подтверждено подписание, только '
          'намерение); eco.context дополнен (банкротство, кредиторы); '
          'добавлено 3 источника' % (OLD_STATUS, NEW_STATUS))

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['status'] = NEW_STATUS
    d['eco']['context'] = NEW_ECO_CONTEXT
    d['src'].extend(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
