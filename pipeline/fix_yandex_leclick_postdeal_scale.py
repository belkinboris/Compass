import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'ge7072ad5'

OLD_CONTEXT = (
    'В марте 2023 года LeClick купил конкурентное решение — SmartReserve. '
    'Оно было частью платформы для ресторанов R_keeper, которая принадлежала '
    'VK до февраля 2023 года — тогда она продала её обратно основателям. '
    'Сумму сделки не раскрывали.'
)
CONTEXT_ADDITION = (
    ' Основатель и гендиректор LeClick Анастасия Люстина перешла в Яндекс '
    'вместе со всей командой: «Будем заниматься всё тем же — развитием '
    'бронирования и автоматизации, но уже изнутри. Объединим ресурсы» '
    '(habr.com). В декабре 2024 года «Яндекс Еда» запустила функцию '
    'онлайн-бронирования столиков на основе SmartReserve — пилот охватывал '
    'более 1 000 ресторанов в Москве и Санкт-Петербурге, до 31 января 2025 '
    'года подключение было бесплатным (restoranoved.ru). На июль 2026 года '
    'к SmartReserve подключено более четырёх тысяч ресторанов, сервис '
    'ежемесячно обрабатывает свыше миллиона броней, им пользуются более пяти '
    'тысяч хостес (iznanka.news). На базе актива Яндекс выпустил ИИ-хостес, '
    'принимающую и оформляющую входящие звонки-брони: в 99% случаев '
    'виртуальный агент успешно отвечает на запрос, а число бронирований в '
    'ресторанах «Мясо&Рыба» выросло на 22%, у сети «СИДР Групп» — на 23% '
    '(rb.ru).'
)
NEW_CONTEXT = OLD_CONTEXT + CONTEXT_ADDITION

NEW_SRC = [
    ['Ресторановед', 'https://restoranoved.ru/articles/news/yandex-eda-zapustila-onlayn-bronirovanie-stolikov/'],
    ['Habr', 'https://habr.com/ru/news/848184/'],
    ['iznanka.news', 'https://iznanka.news/articles/Poslednee/YAndeks-Eda-posadila-II-na-restorannyy-telefon.html'],
    ['RB.RU', 'https://rb.ru/news/yandeks-sozdal-ii-hostes-dlya-restoranov-nejroset-uspeshno-obrabatyvaet-99-zaprosov-na-bronirovanie/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
