# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка gb101d54d (ВТБ приобрел
Первую грузовую компанию, сентябрь 2024): структурное поле `seller` было
пустым у одной из крупнейших M&A-сделок 2024 года (более 200 млрд ₽) —
дельта-поиск нашёл продавца и, что важнее, судьбу актива ПОСЛЕ сделки:
сам ВТБ владел ПГК меньше четырёх месяцев и уже вышел из капитала. Все
цитаты подтверждены лично прямым WebFetch.

1. Продавец — АО «Аврора Инвест»: «В ноябре 2023 г. ПГК у структур
   владельца НЛМК Владимира Лисина выкупило АО "Аврора Инвест"»
   (Интерфакс) — то есть прямым продавцом ВТБ было АО «Аврора Инвест»,
   которое само купило ПГК у структур Лисина годом раньше. Независимая
   оценка: «Источники оценивали сумму сделки примерно в 220 млрд руб.,
   некоторые оценки были выше» — при этом по данным собственной
   отчётности «Аврора Инвест» на покупку ПГК у Лисина потратила 243 млрд
   рублей.
2. Судьба актива: 16 декабря 2024 года, то есть менее чем через четыре
   месяца после покупки, «Банк ВТБ вышел из капитала АО "Аврора Инвест",
   владеющей Первой грузовой компанией: 100% компании... продано с
   хорошей прибылью для банка. Сделка закрыта. Покупателя банк не
   раскрывает» (AKM). Новый гендиректор назначен в апреле 2025 года —
   Алексей Винников, ранее возглавлявший оператора «Атлант» (Интерфакс).
   Финансовые показатели ПГК за 2025 год: выручка упала на 9%, до 123,7
   млрд руб., чистая прибыль по МСФО — в 9 раз, до 4,6 млрд руб., при
   общем долге 207,4 млрд руб. — и почти вся годовая прибыль (4,5 из 4,6
   млрд руб.) направлена на дивиденды (Т-Банк Инвестиции).

Личность покупателя декабря 2024 года НЕ установлена ни одним проверенным
источником вплоть до мая 2026 года — предположение о «отце и сыновьях
Бабаевых» встретилось только в комментариях к посту (не в основном
тексте, не подтверждено первоисточником) и в карточку не идёт: слишком
похоже на путаницу с составом инвесторов сделки 2023 года (Тимур и Руслан
Бабаевы уже упоминались как совладельцы «Вектор Рейл», связанного с
покупателями ПГК от Лисина), а не на факт о сделке декабря 2024 года.
Консультантов сделки ВТБ/«Аврора Инвест» не нашли ни в одном источнике.

Запуск: python3 pipeline/fix_vtb_pgk_seller_and_postdeal.py
        python3 pipeline/fix_vtb_pgk_seller_and_postdeal.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gb101d54d'

OLD_SELLER = None
NEW_SELLER = 'АО «Аврора Инвест»'

OLD_CONTEXT = (
    'ПГК была создана в 2007 году, затем выделена из состава ОАО РЖД в '
    'рамках реформы. В 2011 году 75% минус две акции приобрела структура '
    'Владимира Лисина за 125,5 млрд руб. В 2012 году, выкупив у ОАО РЖД '
    'оставшийся пакет за 50 млрд руб., холдинг господина Лисина '
    'консолидировал 100% оператора.'
)
CONTEXT_ADDITION = (
    ' В ноябре 2023 года «ПГК у структур владельца НЛМК Владимира Лисина '
    'выкупило АО "Аврора Инвест"» — по данным собственной отчётности этой '
    'компании, на покупку было потрачено 243 млрд рублей; независимая '
    'оценка источников рынка — «примерно в 220 млрд руб., некоторые '
    'оценки были выше» (Интерфакс). Владение ВТБ оказалось коротким: уже '
    '16 декабря 2024 года, менее чем через четыре месяца, «Банк ВТБ вышел '
    'из капитала АО "Аврора Инвест"... 100% компании... продано с хорошей '
    'прибылью для банка. Покупателя банк не раскрывает» (AKM) — личность '
    'нового собственника оставалась неизвестной публично как минимум до '
    'мая 2026 года. В апреле 2025 года новым гендиректором ПГК назначен '
    'Алексей Винников, ранее возглавлявший оператора «Атлант» (Интерфакс). '
    'За 2025 год выручка компании упала на 9%, до 123,7 млрд руб., чистая '
    'прибыль по МСФО — в 9 раз, до 4,6 млрд руб., при общем долге 207,4 '
    'млрд руб.; почти вся годовая прибыль (4,5 из 4,6 млрд руб.) '
    'направлена на дивиденды (Т-Банк Инвестиции).'
)
NEW_CONTEXT = OLD_CONTEXT + CONTEXT_ADDITION

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/Eef2024/979610'],
    ['AKM', 'https://www.akm.ru/news/vtb_prodal_kompaniyu_avrora_invest/'],
    ['Интерфакс', 'https://www.interfax.ru/business/1023301'],
    ['Т-Банк Инвестиции', 'https://www.tbank.ru/invest/social/profile/Bonds_PnL/11b2589c-df31-4328-ac05-3bce4f2a02b7/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal.get('seller') == OLD_SELLER
    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== seller: станет ===')
    print(NEW_SELLER)
    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['seller'] = NEW_SELLER
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
