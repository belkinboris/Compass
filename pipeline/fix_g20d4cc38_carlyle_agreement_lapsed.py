# -*- coding: utf-8 -*-
"""Карточка `g20d4cc38` (ЛУКОЙЛ продаёт LUKOIL International GmbH компании
Carlyle) — `eco.context` дополнен: январское соглашение с Carlyle утратило
силу (не получило одобрение OFAC к концу июня), но OFAC отдельно продлило
лицензию на переговоры до 22 октября. Append, не замена поля целиком —
`review.py` не годится (его проверка дословности требует, чтобы ВСЁ поле
лежало в цитате, а здесь цитата — только новый абзац), тот же приём, что
`fix_gd937c845_otp_loan_portfolio.py`. Статус не меняем: истёкший срок
конкретного соглашения и продление лицензии на переговоры — не прямое
заявление стороны о срыве сделки (`docs/card_status_dates.md`).

Источник: https://www.vedomosti.ru/business/news/2026/10/08/1235427-soglashenie-prodazhe

    python3 pipeline/fix_g20d4cc38_carlyle_agreement_lapsed.py           # показать
    python3 pipeline/fix_g20d4cc38_carlyle_agreement_lapsed.py --write  # записать
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__)).rsplit(os.sep, 1)[0]
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')
DEAL = 'g20d4cc38'

OLD_CONTEXT = (
    'О состоявшейся продаже 29 января 2026 года сообщил телеграм-канал '
    '«РУЛЬФЫ, ИЛЬФЫ И ИНХАУСЫ»: ЛУКОЙЛ продал зарубежные активы, которыми '
    'владела LUKOIL International GmbH, американской инвестиционной '
    'компании Carlyle. Активы в Республике Казахстан в сделку не входят и '
    'остаются у группы «ЛУКОЙЛ». Дата взята по дню этого сообщения — дату '
    'подписания договора источник не называет; прежняя дата, 1 января '
    '2022 года, была поставлена условно. На сентябрь 2026 года сделка '
    'по-прежнему не закрыта: Минфин США продлевает лицензию на '
    'ПЕРЕГОВОРЫ о продаже (не на закрытие) уже несколько раз — последний '
    'срок истекает 19 сентября 2026 года. 22 октября 2025 года США ввели '
    'санкции против самого ЛУКОЙЛа, и после истечения месячного '
    'льготного периода (21 ноября 2025 года) компания потеряла '
    'операционный контроль над LIG и полностью списала инвестицию в неё '
    '— убыток от обесценения составил 1,66 трлн ₽. Оценки стоимости '
    'актива расходятся: $3–4 млрд по одному аналитику против рыночных '
    '$12–15 млрд без учёта казахстанских активов по оценке ФГ «Финам».'
)

ADDED = (
    'Соглашение «Лукойла» о продаже активов международного Lukoil '
    'International GmbH (LIG) американскому инвестиционному фонду Carlyle '
    'утратило силу. Это следует из отчетности LIG, обратил внимание '
    '«Финмаркет». Оно истекло в конце июня, поскольку не получило '
    'одобрение Управление по контролю за иностранными активами (OFAC) '
    'минфина США. При этом в сентябре сообщалось, что OFAC продлило до '
    '22 октября лицензию, которая разрешает ведение переговоров и '
    'вступление в условные соглашения с «Лукойлом» для продажи Lukoil '
    'International GmbH.'
)


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))   # перечитано прямо перед записью
    deal = next(d for d in data['deals'] if d['id'] == DEAL)
    assert deal['eco']['context'] == OLD_CONTEXT, deal['eco']['context']
    deal['eco']['context'] = OLD_CONTEXT + ' ' + ADDED
    print('eco.context дополнен: январское соглашение с Carlyle утратило силу, '
          'лицензия на переговоры продлена до 22 октября')
    if not write:
        print('\nСухой прогон. Запись — с ключом --write.')
        return 0
    json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('записано')
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
