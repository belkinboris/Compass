import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g1d73eef1'

OLD_ECO_CONTEXT = '—'
NEW_ECO_CONTEXT = (
    'В 2026 году у актива случился крупный, но временный разворот: 15 '
    'июня Генпрокуратура добилась ареста ключевых заводов ЕПК (Саратов, '
    'Волжский, Самара и связанных структур), рассчитывая обратить их в '
    'доход государства. 10 июля Лефортовский суд Москвы отказался принять '
    'иск к рассмотрению — по формальным нарушениям антикоррупционного '
    'законодательства при его подаче — и арест сняли; за две недели до '
    'решения за основателя ЕПК публично заступился режиссёр Никита '
    'Михалков.'
)

OLD_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/5886717'],
]
NEW_SRC = OLD_SRC + [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8763172'],
    ['The Moscow Times', 'https://ru.themoscowtimes.com/2026/07/10/mihalkova-a200489'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
