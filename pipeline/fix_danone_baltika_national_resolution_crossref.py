# -*- coding: utf-8 -*-
"""Месячная очередь качества, 11 сентября 2026 — дочитывание двух
карточек о начале национализации Danone и «Балтики» (июль 2023,
weekly_researched 10 августа 2026): `c51777ade` (назначение Якуба
Закриева гендиректором «Данон Россия») и `c374fc2ca` (указ №520 —
передача долей Danone и «Балтики» во временное управление
Росимущества).

Дельта-поиск установил: обе истории закончились продажей, и обе уже
ПОЛНОСТЬЮ описаны в базе отдельными карточками — `g96da922c» (Danone
продала бизнес «Вамин Р», закрыто в мае 2024, включая переименования
в Health & Nutrition и затем «Логика молока») и `baltika` (Carlsberg
продал «Балтику» через MBO «ВГ Инвест», закрыто 2 декабря 2024).
Полные суммы, структуры и источники этих сделок НЕ переносятся сюда
повторно — они уже есть в тех карточках; здесь фиксируется только
факт, что временное управление, с которого начинались ЭТИ две
карточки, закончилось.

Личный WebFetch подтвердил дословно (Интерфакс, 6 декабря 2024,
https://www.interfax.ru/business/996240): «16 июля 2023 года Путин
подписал указ, согласно которому принадлежащие Carlsberg активы были
переданы в управление Росимуществу»; «Объявление о сделке
[«Балтики»] последовало сразу за публикацией указа президента... от
2 декабря, который вывел активы Carlsberg в России из-под временного
госуправления». Этот же указ (по данным Коммерсанта, 3 декабря 2024,
https://www.kommersant.ru/doc/7345382) вывел из-под временного
управления и долю в Danone — подтверждено тем, что сделка по Danone
закрылась уже в мае 2024 года (после отмены указа № 520 в этой части
президентом 13 марта 2024 года, по данным Ведомостей — уже отражено
в `g96da922c`).

Запуск:
    python3 pipeline/fix_danone_baltika_national_resolution_crossref.py            # сухой прогон
    python3 pipeline/fix_danone_baltika_national_resolution_crossref.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_C51777ADE_CONTEXT = (
    'Статья описывает национализацию российского подразделения '
    'Danone. По словам источников, Danone из 40 претендентов отобрала '
    'трех покупателей; в результате гендиректором «Данон Россия» был '
    'назначен Якуб Закриев, племянник Рамзана Кадырова и заместитель '
    'председателя правительства Чечни. Danone намеревалась списать '
    'стоимость активов на сумму до 1 млрд евро.'
)
NEW_C51777ADE_CONTEXT = OLD_C51777ADE_CONTEXT + (
    ' Национализация закончилась продажей: в мае 2024 года Danone '
    'закрыла сделку с ООО «Вамин Р» за 17,7 млрд ₽; компания дважды '
    'сменила имя — сначала на Health & Nutrition, затем, с 8 октября '
    '2025 года, на «Логика молока».'
)

OLD_C374FC2CA_CONTEXT = '—'
NEW_C374FC2CA_CONTEXT = (
    'Временное управление Росимущества снято указом президента от '
    '2 декабря 2024 года. Доля в Danone продана ещё в мае 2024 года '
    'структуре «Вамин Р» за 17,7 млрд ₽; доля в «Балтике» — российскому '
    'менеджменту через ООО «ВГ Инвест» (сделка закрыта также в декабре '
    '2024 года).'
)

NEW_SRC = ['Интерфакс', 'https://www.interfax.ru/business/996240']


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d1 = by_id['c51777ade']
    d2 = by_id['c374fc2ca']

    assert d1['eco']['context'] == OLD_C51777ADE_CONTEXT, \
        'c51777ade eco.context уже другой: %r' % (d1['eco']['context'],)
    assert d2['eco']['context'] == OLD_C374FC2CA_CONTEXT, \
        'c374fc2ca eco.context уже другой: %r' % (d2['eco']['context'],)
    urls1 = {s[1] for s in d1['src']}
    urls2 = {s[1] for s in d2['src']}
    assert NEW_SRC[1] not in urls2, 'источник уже добавлен в c374fc2ca: %s' % NEW_SRC[1]

    print('c51777ade: eco.context дополнен (национализация закончилась '
          'продажей «Вамин Р», переименования — факт уже полностью '
          'описан в карточке g96da922c, здесь только итог)')
    print('c374fc2ca: eco.context заполнен (временное управление снято '
          'указом от 2 декабря 2024 года; обе доли проданы — Danone и '
          '«Балтика», подробности в g96da922c и baltika); добавлен '
          'источник interfax.ru')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d1['eco']['context'] = NEW_C51777ADE_CONTEXT
    d2['eco']['context'] = NEW_C374FC2CA_CONTEXT
    d2['src'].append(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
