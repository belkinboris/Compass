def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    akzo = by_id[AKZO_ID]
    pevek = by_id[PEVEK_ID]

    assert akzo['law']['struct'] == AKZO_OLD_LAW_STRUCT
    assert pevek['law']['struct'] == PEVEK_OLD_LAW_STRUCT

    print('=== akzo: law.struct ===')
    print(AKZO_NEW_LAW_STRUCT)
    print()
    print('=== pevek: law.struct ===')
    print(PEVEK_NEW_LAW_STRUCT)

    if write:
        akzo['law']['struct'] = AKZO_NEW_LAW_STRUCT
        pevek['law']['struct'] = PEVEK_NEW_LAW_STRUCT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
