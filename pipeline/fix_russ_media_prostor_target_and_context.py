# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка g707633b2 (ГК Russ
приобрела оператора наружной рекламы «Медиа Простор»): дельта-поиск нашёл
пробел в предмете сделки — `eco.share` был прочерком, а единственное
предложение о географии в `eco.context` описывало НЕ «Медиа Простор»
(предмет покупки), а СОБСТВЕННЫЙ, уже существовавший инвентарь Russ в
Москве. Сам первоисточник карточки (Sostav.ru) чётко разделяет эти два
факта в соседних предложениях — при первом переносе в карточку они,
похоже, слились в один. Проверено лично прямым WebFetch того же
первоисточника.

Дословно: «компания «Медиа Простор», которая управляет рекламными
размещениями на 490 остановочных павильонах городского общественного
транспорта Санкт-Петербурга» — а уже ОТДЕЛЬНО «ГК также является
эксклюзивным оператором рекламных конструкций на остановках общественного
транспорта в Москве» (это про саму ГК Russ, уже стоит в `eco.context` и
не трогается). «Медиа Простор» — петербургский актив, а не московский.

Заодно дописан контекст: сделка — не изолированный эпизод, а часть
задокументированной серии региональных покупок операторов наружки Russ в
2024 году (та же группа уже была замечена в прошлых заходах очереди на
покупке «Эфир Транзит» и «Барсрекарт» в казанском метро) — TAdviser
перечисляет минимум 6-7 таких покупок за год.

Не через review.py: `eco.share` заполняется впервые (не расширение
существующего значения), а факт о серии сделок — сведение нескольких
источников.

Запуск: python3 pipeline/fix_russ_media_prostor_target_and_context.py
        python3 pipeline/fix_russ_media_prostor_target_and_context.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g707633b2'

OLD_SHARE = '—'
NEW_SHARE = (
    '«Медиа Простор» управляет рекламными размещениями на 490 '
    'остановочных павильонах городского общественного транспорта '
    'Санкт-Петербурга — сделка увеличила долю инвентаря Russ на '
    'автобусных остановках города до более чем 80% (Sostav.ru).'
)

OLD_CONTEXT = (
    'ГК также является эксклюзивным оператором рекламных конструкций на '
    'остановках общественного транспорта в Москве. Кроме того, ее '
    'инвентарь присутствует в Московской области и еще в 12 городах по '
    'всей России.'
)
CONTEXT_ADDITION = (
    ' Покупка «Медиа Простор» — не изолированный эпизод: та же группа в '
    '2024 году провела не менее 6-7 региональных покупок операторов '
    'наружной рекламы («Мост» в Нижнем Новгороде, «Урал Стрит»,'
    ' «Инфо-Ю», «Профимаркет», сочинская «Партия» и другие), включая уже '
    'известные карточке «Эфир Транзит» и «Барсрекарт» в казанском метро '
    '(TAdviser).'
)
NEW_CONTEXT = OLD_CONTEXT + CONTEXT_ADDITION

NEW_SRC = [
    ['TAdviser', 'https://www.tadviser.ru/index.php/Компания:Russ_(Русс_Аутдор_ранее_Russ_Outdoor)'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['share'] == OLD_SHARE
    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.share: станет ===')
    print(NEW_SHARE)
    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['share'] = NEW_SHARE
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
