import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g6168731b'

OLD_ECO_CONTEXT = (
    'Ещё в марте 2022 года Heineken объявила о прекращении инвестиций и '
    'экспорта в РФ, а также производства, продажи и рекламы своего '
    'бренда в России. В том же месяце компания сообщила, что передаст '
    'бизнес в стране новому владельцу. Уйти из России Heineken обещала '
    'в первой половине 2023 года, но признавала, что продажа затянулась '
    'из-за изменений в российском законодательстве.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' В декабре 2023 года юрлицо переименовано в '
    '«Объединённые пивоварни — холдинг»: по словам основателя '
    '«Арнеста» Алексея Сагала, смена названия была одним из условий '
    'сделки с Heineken. 23 октября 2025 года компания сменила имя во '
    'второй раз — на «Пивоварни Бочкарев» (публичные коммуникации под '
    'новым брендом — с 1 ноября 2025 года). Выручка выросла до 48,45 '
    'млрд ₽ в 2024 году (+18,73%), чистая прибыль составила 2,48 млрд '
    '₽. В октябре 2025 года «Сбербанк инвестиции» получили 9,1% '
    'компании при допэмиссии (аналитики оценивают вложение в 1,3–2 '
    'млрд ₽) — Сбербанк остаётся основным кредитором «Пивоварен '
    'Бочкарев», контроль сохранил основной бенефициар, ООО «АУР '
    'инвест» Алексея Сагала.'
)

OLD_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/amp/5941014'],
    ['Ведомости', 'https://www.vedomosti.ru/business/articles/2023/08/25/991930-heineken-prodala-rossiiskii-biznes'],
    ['Интерфакс', 'https://www.interfax.ru/business/917760'],
]
NEW_SRC = OLD_SRC + [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6379867'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8160444'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8161535'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
