# -*- coding: utf-8 -*-
"""g78986e22 (Альфа-банк/«Европлан»): исправление `law.appr` — продолжение
16-августовской правки трёх юридических полей карточки (см.
`pipeline/fix_deep_batch1_manual.py`, «Финальная цена покупки будет
скорректирована» и т. д.).

`law.appr` изначально пришёл через `review.py` со значением «Сделка
завершилась 25 декабря 2025 года…» — это факт закрытия (уже отдельно
подтверждён `extra` и `status`), но НЕ факт о согласовании: поле
«Согласования» обязано называть орган (тест `test_approval_names_a_body`),
а в этом тексте нет ни ФАС, ни другого органа. Ошибка моя: заменяя
устаревшее «Завершение сделки запланировано… получения… согласия ФАС»
(будущее время), я убрал сам факт согласования вместо того, чтобы
перенести его в прошедшее.

Дословного постфактум-подтверждения именно «ФАС одобрила» (а не только
факта закрытия, из которого это подразумевается) найти не удалось —
rbc.ru (собственно статья о закрытии) защищён антибот-скриптом Qrator и
не открылся ни `curl`, ни повторным `fetch_article_texts.py`. Правка
поэтому не идёт через `review.py` (нет дословной цитаты на объединённый
факт), а вносится вручную: согласие ФАС и корпоративные одобрения были
условиями закрытия (первая, добротно подтверждённая версия текста поля,
источник — AK&M/kommersant.ru/doc/8211022, оба уже в src карточки), и
раз сделка закрылась 25.12.2025 (SFI, t-bank.ru, уже в src) — оба условия
были выполнены. Текст явно помечен как объяснение, а не цитата.

Запуск:
    python3 pipeline/fix_owner_phone_20260816_manual2.py            # сухой прогон
    python3 pipeline/fix_owner_phone_20260816_manual2.py --write    # запись
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g78986e22'
OLD = ('Сделка завершилась 25 декабря 2025 года, Альфа-Банк заплатил '
       '50,79 млрд рублей за принадлежавшие холдингу акции компании. При '
       'этом инвестиционный холдинг SFI в соответствии с условиями '
       'сделки также получил от ПАО ЛК «Европлан» дивиденды за 9 месяцев '
       '2025 года в размере 6,1 млрд рублей.')
NEW = ('Закрытие сделки было обусловлено получением корпоративных '
       'одобрений и согласия ФАС, а также выплатой Европланом дивидендов '
       'за девять месяцев 2025 года; сделка закрылась 25 декабря 2025 '
       'года — все условия были выполнены.')


def main(argv):
    data = json.load(open(DATA, encoding='utf-8'))
    card = {d['id']: d for d in data['deals']}[CARD_ID]
    assert card['law']['appr'] == OLD, 'law.appr у %s уже другой' % CARD_ID

    print('%s law.appr:' % CARD_ID)
    print('  было: %r' % OLD[:80])
    print('  станет: %r' % NEW[:80])

    if '--write' not in argv:
        print('\nСухой прогон. Запись — с ключом --write.')
        return 0

    card['law']['appr'] = NEW
    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('ЗАПИСАНО.')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
