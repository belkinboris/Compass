# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка g81a766ac (Русагро увеличило
долю в ГК «Агро-Белогорье» с 22,5% до 47,5% по решению суда, сентябрь
2024): дельта-поиск нашёл, что спор с Зотовым закрылся не кассацией, а
полной консолидацией — и что судьба самого актива после этого оказалась
куда сложнее, чем «Русагро» получила контроль насовсем. Все цитаты
подтверждены лично прямым WebFetch.

1. `law.appr`: стороны сначала пытались договориться миром («представитель
   истца выразил намерение урегулировать спор миром», Интерфакс,
   13.11.2024), но уже 13 ноября 2024 года «Русагро» объявила о ЗАКРЫТИИ
   сделки по консолидации 100% долей и контроля над ООО «ГК Агро-
   Белогорье» — то есть доля выросла не до 47,5%, как в заголовке, а сразу
   до 100% (AgroInvestor).
2. `eco.context`: спустя полгода после консолидации доля «Русагро» в
   «Агро-Белогорье» была передана в доверительное управление структуре
   правительства Белгородской области (Интерфакс, 29.05.2025) — в то же
   время, когда основатель «Русагро» Вадим Мошкович был задержан по
   обвинению в мошенничестве на 86 млрд руб., а его акции холдинга
   обращены в доход государства (AgroInvestor), и когда сама «Русагро»
   показала резкое падение прибыли в Q1 2025 (Право.ру). Причинно-
   следственная связь между этими событиями нигде явно не утверждается —
   изложены как отдельные, датированные факты, не как единая версия.
   Отдельно — сама «Агро-Белогорье» при этом продолжила расти
   (чистая прибыль по РСБУ выросла в 2,1 раза, Meatinfo.ru).

Запуск: python3 pipeline/fix_rusagro_agro_belogorye_postdeal.py
        python3 pipeline/fix_rusagro_agro_belogorye_postdeal.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g81a766ac'

OLD_APPR = (
    'Суд отклонил апелляционную жалобу Владимира Зотова по иску компании '
    '«Русагро» о передаче 25% доли в ГК «Агро-Белогорье». Это следует из '
    'картотеки суда.'
)
APPR_ADDITION = (
    ' Стороны затем пытались договориться миром: «представитель истца '
    'выразил намерение урегулировать спор миром... об отложении судебного '
    'заседания для предоставления участникам спора возможности '
    'урегулировать спор мирным путем» (Интерфакс, 13 ноября 2024). В итоге '
    '13 ноября 2024 года «Русагро» объявила о закрытии сделки: «Группа '
    '«Русагро» сообщила о закрытии сделки по консолидации 100% долей и '
    'контроля над ООО «ГК Агро-Белогорье»» — доля выросла не до 47,5%, а '
    'сразу до полных 100% (AgroInvestor).'
)
NEW_APPR = OLD_APPR + APPR_ADDITION

OLD_CONTEXT = (
    'ГК «Русагро» в 2019 году закрыла сделку по покупке 22,5% в ГК '
    '«Агро-Белогорье» за 8,5 млрд рублей. В долгосрочной перспективе '
    'группа планировала консолидировать этот актив.'
)
CONTEXT_ADDITION = (
    ' Спустя полгода после полной консолидации судьба актива изменилась: '
    '29 мая 2025 года «доля предприятия «Агро-Белогорье» передана в '
    'доверительное управление АО «Корпорация развития», которое '
    'принадлежит Белгородской области» (Интерфакс); официально решение '
    'объяснили сотрудничеством с регионом (Право.ру). В то же время '
    'основатель «Русагро» Вадим Мошкович был задержан по обвинению в '
    'мошенничестве на сумму более 86 млрд руб. (26 марта 2025 года), а '
    'принадлежавшие ему 469,7 млн акций холдинга обращены в доход '
    'государства (AgroInvestor); одновременно сама «Русагро» показала '
    'резкое падение прибыли в первом квартале 2025 года — 119,6 млн руб. '
    'против 2,33 млрд руб. годом ранее (Право.ру). Сама «Агро-Белогорье» '
    'при этом продолжила расти: чистая прибыль по РСБУ выросла в 2,1 раза, '
    'до 610,5 млн рублей (Meatinfo.ru).'
)
NEW_CONTEXT = OLD_CONTEXT + CONTEXT_ADDITION

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/business/991408'],
    ['AgroInvestor', 'https://www.agroinvestor.ru/transaction/news/43314-rusagro-poluchila-100-kontrol-nad-agro-belogorem/'],
    ['Интерфакс', 'https://www.interfax.ru/russia/1028523'],
    ['Право.ру', 'https://pravo.ru/news/258960/'],
    ['AgroInvestor', 'https://www.agroinvestor.ru/companies/news/46043/'],
    ['Meatinfo.ru', 'https://meatinfo.ru/news/chistaya-pribil-mpz-agro-belogore-v-496326'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['law']['appr'] == OLD_APPR
    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== law.appr: станет ===')
    print(NEW_APPR)
    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['law']['appr'] = NEW_APPR
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
