# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка g343154dd (Кредит Европа
банк/Икано-банк): два независимых дефекта, найденных при дельта-дочитывании.

1. `extra` нёс «Сделка закрыта 1 марта 2022 года» — неверный ГОД. Оба уже
   известных источника (Коммерсантъ, doc/5844677, и Интерфакс,
   business/889368) датированы 2 марта 2023 года и говорят «Кредит Европа
   банк стал собственником Икано банка 1 марта» — день и месяц верны,
   год должен быть 2023 (поле `date` карточки, «2023-03-01», уже верное
   и никогда не менялось). IKEA объявила уход из России в 2022-м, но
   регуляторное одобрение (26 января 2023) и закрытие сделки состоялись
   позже, в 2023 году, — типовая путаница «событие в истории актива vs
   дата этой сделки».

2. `eco.context` заканчивался на дате публикации новости о закрытии.
   Дельта нашла дальнейшую судьбу банка (после исходного обыска):
   переименование в «Фибабанк» (май 2023) и присоединение к покупателю
   (14 июля 2023, банк прекратил существование) — «что было дальше».

Не через review.py: `extra` — не структурная цитата, а компиляция,
исправление ОДНОГО символа (года) внутри неё не проходит требование
дословности целиком; `eco.context` уже не пуст, и дословность требует
цитаты на ВСЁ значение (старое из Интерфакса + новое из banks-finance.ru
— разные источники, разом дословно нигде не лежат).
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g343154dd'

OLD_EXTRA = (
    'Сделка по приобретению 50% долей ООО «Икано-банк» (входит в Группу '
    'Икеи). Банк занимает 208-е место по активам (4,8 млрд руб.) и '
    'предоставляет кредиты покупателям магазинов IKEA и МЕГА. Сделка '
    'закрыта 1 марта 2022 года.'
)
NEW_EXTRA = (
    'Сделка по приобретению 50% долей ООО «Икано-банк» (входит в Группу '
    'Икеи). Банк занимает 208-е место по активам (4,8 млрд руб.) и '
    'предоставляет кредиты покупателям магазинов IKEA и МЕГА. Сделка '
    'закрыта 1 марта 2023 года.'
)

OLD_CONTEXT = (
    'Москва. 2 марта. INTERFAX.RU - Кредит Европа банк закрыл сделку по '
    'покупке российской банковской «дочки» шведской группы IKEA, '
    'которая покинула рынок РФ в связи с событиями на Украине.'
)
ADDITION = (
    'В мае 2023 года банк объявил, что меняет название «Икано Банк» на '
    '«Фибабанк». 14 июля 2023 года прекратил деятельность и влился в '
    '«Кредит Европа Банк».'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['extra'] == OLD_EXTRA, \
        f"extra: неожиданное значение {deal['extra']!r}"
    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} extra: год закрытия 2022 -> 2023 (опечатка, "
          "оба источника датированы 2 марта 2023)")
    print(f"{CARD_ID} eco.context: += переименование в «Фибабанк» и "
          "присоединение к покупателю (июль 2023)")
    deal['extra'] = NEW_EXTRA
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
