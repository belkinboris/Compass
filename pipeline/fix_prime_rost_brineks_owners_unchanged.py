import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gd3f012e4'

OLD_EXTRA = (
    'Сделка получила согласие ФАС. Продавцы — Ренат и Рустем '
    'Бадретдиновы (по 50% каждый в ООО ГК «БРИНЭКС»). Покупатель — АО '
    '«Прайм рост» (создана в конце 2023 года, конечный бенефициар '
    'неизвестен).'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Официального подтверждения или опровержения самой сделки в '
    'прессе так и не появилось. Но с 4 февраля 2026 года пост '
    'гендиректора «Бринэкса» лично занял один из совладельцев, сменив '
    'наёмного управляющего, а с марта 2026 года гендиректором ключевого '
    'юрлица сети «Колеса Даром» стал второй совладелец — оба вернулись к '
    'операционному руководству спустя два года после объявленной '
    'продажи 100% бизнеса. Выручка сети за 2024 год выросла на 20% до '
    '36,8 млрд руб.'
)

NEW_SRC = [
    ['audit-it.ru', 'https://www.audit-it.ru/contragent/1221600021356_ooo-gk-brineks'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
