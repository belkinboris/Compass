# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g4b447867
(Нео-Фарм выкупила 98 аптек сетей Социалочка.рф и Аптечные традиции в
Курской области). Проверено лично прямым WebFetch и прямым запросом.

1) `eco.rationale` (новое поле) — причина продажи. sozvezdie.ru/
vademec.ru, дословно: «Конъюнктура такова, что строить разветвленную
сеть в нескольких крупных городах стало крайне трудоемко и
ресурсозатратно». Фармвестник, дословно: «Два «черных лебедя» друг за
другом — это уже был перебор» (пандемия и политика поставщиков);
«Вариантов было немного — привлечение финансового партнера или решение
проблем за счет внутренних ресурсов, продажи части бизнеса».
Источники: https://pharmvestnik.ru/content/news/Dmitrii-Ruckoi-prodal-aptechnuu-set.html

2) `extra` — уточнение по брендам: «Социалочка.рф» и «Аптечные традиции»
— два РАЗНЫХ бренда одного собственника, а не синонимы. Коммерсантъ,
дословно: Руцкой планировал развивать «Социалочка.рф» отдельно в
Ульяновской области, но «впоследствии отказался от этой идеи» — бренды
объединены под одним владельцем и проданы одним лотом.

3) `law.struct` (новое поле) — судьба сети после сделки, факт найден
прямым запросом (не журналистской цитатой): домен socialochka.ru
отвечает кодом 301 и перенаправляет на «https://stolichki.ru/apteki/
kursk?from=socialochka.ru» (проверено лично, curl -I, 29 августа 2026)
— бывшая сеть интегрирована в бренд «Столички» самого Нео-Фарма, а не
сохранена отдельно.

НЕ включены: сумма сделки — все три источника (Коммерсантъ, Vademecum,
Фармвестник) сходятся дословно: «Сумму сделки стороны не раскрывают»;
единственное найденное число (оценка Николая Беспалова «55–70 млрд
руб.») относится к оценке ВСЕЙ группы «Неофарм»/«Столички» из статьи
2022 года о передаче прав в ЗПИФ «Здравинвест» — не к этой сделке (родня
уроку CLAUDE.md «Разбор источника доверяет числу из чужого абзаца»);
консультанты — не найдены ни в одном источнике.

Запуск: python3 pipeline/fix_neofarm_apteki_traditsii_kursk_details.py
        python3 pipeline/fix_neofarm_apteki_traditsii_kursk_details.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g4b447867'

NEW_RATIONALE = (
    '«Конъюнктура такова, что строить разветвленную сеть в нескольких '
    'крупных городах стало крайне трудоемко и ресурсозатратно» '
    '(sozvezdie.ru/vademec.ru). «Два «черных лебедя» друг за другом — '
    'это уже был перебор» (пандемия и политика поставщиков): «Вариантов '
    'было немного — привлечение финансового партнера или решение проблем '
    'за счет внутренних ресурсов, продажи части бизнеса» (Фармвестник).'
)

OLD_EXTRA = (
    'Сделка по приобретению ООО «Нео-фарм» всех 98 аптек в Курской '
    'области у ГК «Аптечные традиции». Сделка закрыта. Нео-Фарм управляет '
    'сетями «Неофарм» и «Столички», занимает 6-е место в рейтинге '
    'Vademecum с выручкой свыше 75,3 млрд рублей и пулом в 1 244 аптеки. '
    'Продавец — ГК «Аптечные традиции» (владелец Дмитрий Руцкой), '
    'занимавшая 47-е место в рейтинге с выручкой 3,4 млрд рублей. Права '
    'ООО «Нео-фарм» принадлежат ЗПИФ «Здравинвест».'
)
NEW_EXTRA = OLD_EXTRA + (
    ' «Социалочка.рф» и «Аптечные традиции» — два разных бренда одного '
    'владельца: Руцкой планировал развивать «Социалочку.рф» отдельно в '
    'Ульяновской области, но «впоследствии отказался от этой идеи» '
    '(Коммерсантъ) — оба бренда проданы одним лотом.'
)

NEW_STRUCT = (
    'Домен socialochka.ru отвечает кодом 301 и перенаправляет на '
    '«https://stolichki.ru/apteki/kursk?from=socialochka.ru» (проверено '
    'лично, 29 августа 2026) — бывшая сеть интегрирована в собственный '
    'бренд Нео-Фарма «Столички», а не сохранена отдельно.'
)

NEW_SRC = [
    ['Фармвестник', 'https://pharmvestnik.ru/content/news/Dmitrii-Ruckoi-prodal-aptechnuu-set.html'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert not deal['eco'].get('rationale')
    assert deal['extra'] == OLD_EXTRA
    assert deal['law']['struct'] == '—'
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.rationale (новое поле): станет ===')
    print(NEW_RATIONALE)
    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('=== law.struct (новое поле): станет ===')
    print(NEW_STRUCT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['rationale'] = NEW_RATIONALE
        deal['extra'] = NEW_EXTRA
        deal['law']['struct'] = NEW_STRUCT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
