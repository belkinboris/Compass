# -*- coding: utf-8 -*-
"""Приток 24 сентября 2026 (15:20 МСК), gmru-nspk-privatization («Банк
России готовит частичную приватизацию НСПК»): дополнение eco.val.

На том же Международном банковском форуме (24 сентября) Набиуллина
сообщила, что ЦБ будет поэтапно снижать тарифы НСПК для банков и учтёт
это при оценке компании перед продажей — деталь методики оценки, которой
в карточке ещё не было (структурные условия продажи — контроль ЦБ
>50%+1 и лимит 5% на одного покупателя — уже были записаны в law.terms
и law.struct с 9 августа).

Черновик того же дня («ЦБ продаёт МИР», smart-lab.ru, g035ebc5f) поднял
эти же три структурных факта как будто новые — саб-агент рутины проверил
их по первоисточникам (Коммерсантъ, Ведомости, Интерфакс, 1prime) и
подтвердил все четыре, но три из них уже в базе; черновик отпущен через
accept_card.py как дубль, не отдельная сделка.

Прямым скриптом — дописывание к уже стоящему тексту eco.val не проходит
генерик-проверку review.check() (то же ограничение, что и для
gb7ea4703/g17fc21d6/gmru-nspk-privatization.eco.context/g2daf32fe).

Источник: https://www.interfax.ru/russia/1118184 (уже привязан к
карточке), прочитан целиком, кэш в data/inbox/raw/2026-09-24-articles.jsonl.

Запуск: python3 pipeline/fix_nspk_tariffs_2026_09_24.py --write
"""
import argparse
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gmru-nspk-privatization'

OLD_VAL = (
    'Исходя из отчётности ЦБ, за 2022–2025 годы НСПК выплатила регулятору '
    'более 80 млрд ₽ дивидендов, в том числе почти 47 млрд ₽ в 2025 году. '
    'Глава правления ассоциации «Финансовые инновации» Роман Прохоров '
    'считает НСПК понятным активом, приносящим доход, и ожидает неплохого '
    'спроса на него как со стороны кредитных организаций, так и со '
    'стороны других участников рынка.'
)
QUOTE_ADD = (
    '24 сентября 2026 года на Международном банковском форуме Набиуллина '
    'сообщила: «Мы считаем, что НСПК должна остаться рентабельной, '
    'самоокупаемой и позволяющей осуществлять инвестиции в проекты '
    'развития, проекты, которые важны для всего бизнеса. Но мы приняли '
    'принципиальное решение, посмотрев на ситуацию, что будем поэтапно '
    'уменьшать тарифы для банков (...), и это будет учитываться в оценке '
    'стоимости НСПК», — добавила глава ЦБ. Вместе с тем, по её словам, '
    'если в будущем рентабельность не будет позволять осуществить '
    'какие-то проекты, то может быть принято решение о повышении тарифов.'
)


def main(write):
    data = json.load(open(DATA, encoding='utf-8'))
    card = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert card['eco']['val'] == OLD_VAL
    card['eco']['val'] = OLD_VAL + ' ' + QUOTE_ADD

    if write:
        json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
        print('Записано: eco.val дополнен деталью о снижении тарифов.')
    else:
        print('Сухой прогон (--write, чтобы записать).')


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('--write', action='store_true')
    main(p.parse_args().write)
