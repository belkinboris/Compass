"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
gc92ba4cb («Логистика и точка» приобретает российский бизнес Havi,
26.12.2022, статус «Закрыта») — бизнес вырос и начал диверсификацию за
пределы обслуживания только «Вкусно — и точка».

Проверено лично прямым WebFetch (gorodn.ru, 24.04.2025): «Федеральная
сеть быстрого питания «Вкусно и точка» достроила мультитемпературный
распределительный центр в Аксайском районе Ростовской области»,
«Площадь центра — 8,2 тыс. кв. м. Он рассчитан на 8 тыс. паллетомест»,
«Московское ООО «Рулог» вложило в проект более 1 млрд руб.», «обе
компании через АО «Логистика и точка» связаны с предпринимателем из
Кемеровской области Александром Говором», «Сообщается также, что
центр может оказывать логистические услуги сторонним клиентам».

НЕ ВКЛЮЧЕНО: финансовые показатели ООО «Рулог» за 2024 год (выручка
105,21 млрд ₽, +15% к 2023) — по данным саб-агента из РБК Компании/
бухотчётности, без дословной цитаты, не дозаверено отдельным
WebFetch; судьба HAVI Global на других рынках (продажи подразделений
в Сингапуре, Японии, Тайване, странах Балтии) — не относится к
российскому активу, которому посвящена карточка.

Запуск: python3 pipeline/fix_havi_logistika_i_tochka_growth.py
        python3 pipeline/fix_havi_logistika_i_tochka_growth.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gc92ba4cb'

OLD_EXTRA = (
    'ФАС получила ходатайство о приобретении. Компания «Логистика и '
    'точка» (владелец Александра Говора) покупает 100% российских '
    'активов Havi Россия (ООО «Рулог»). Сделка включает 14 '
    'распределительных центров и трудовые места для свыше 1,2 тысячи '
    'сотрудников. Завершение зависит от согласования ФАС.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' 24 апреля 2025 года под Ростовом открыт новый '
    'мультитемпературный распределительный центр (8,2 тыс. кв. м, '
    '8 тыс. паллетомест, вложено свыше 1 млрд руб.) — бизнес не '
    'просто продолжает работать, но и расширяется, а центр может '
    'оказывать логистические услуги сторонним клиентам, не только '
    '«Вкусно — и точка».'
)

NEW_SRC = [
    ['gorodn.ru', 'https://gorodn.ru/razdel/novosti_kompaniy/investproekty/set-_vkusno-i-tochka_-otkryla-pod-rostovom-logisticheskiy-tsentr-za-1-mlrd-rub/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
