import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gb83b2a3f'

OLD_EXTRA = (
    'Завершение сделки по приобретению ГК «Мать и дитя» (MD Medical) '
    'четырёх медицинских клиник: 100% ООО МЦ «Биологическая медицина» '
    '(ЛДЦ Биомедицина, Антирефлюкс-Сургут) в Сургуте и 100% ООО '
    '«Оздоровительный центр «Вира»» в Нефтеюганске. Финансирование '
    'осуществлено за счёт собственных средств группы.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Группа продолжила инвестировать в регион: в 2025 году открыла в '
    'Сургуте отдельную новую клинику репродуктивного здоровья (163 '
    'млн ₽ инвестиций). По всей стране группа сильно расширилась через '
    'M&A — крупнейшая сделка: покупка сети «Эксперт» (18 клиник и 3 '
    'госпиталя в 13 городах) за 8,5 млрд ₽ в мае 2025 года. Выручка всей '
    'группы за 2025 год выросла на 31,2% до 43,5 млрд ₽, чистая прибыль '
    '— на 8,5% до 11 млрд ₽, группа объединяет 90 медучреждений в 35 '
    'регионах.'
)

NEW_SRC = [
    ['Vademecum', 'https://www.vademec.ru/news/2025/09/09/mat-i-ditya-za-163-mln-rubley-otkryla-tsentr-eko-v-surgute/'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/7738477'],
    ['МД Медикал Груп', 'https://www.mcclinics.ru/media/news/financial-results-2025/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
