# -*- coding: utf-8 -*-
"""ge386fb20 («Магнит»/«Колос Кубани») несла придуманную договорную
структуру — найдено ночной вычиткой 40 карточек (17-18 августа 2026) и
подтверждено самостоятельно: все 6 доступных источников карточки
(kommersant.ru/doc/8476725, doc/8477794, south.vedomosti.ru, kubnews.ru,
smart-lab.ru, mergers.ru) говорят ОДНО И ТО ЖЕ — «Магнит» сумму не раскрыл,
инвестдиректор BGP Capital Юрий Левицкий оценивает рыночную стоимость садов
в 1–1,3 млрд руб., но «с учётом долга компании» цена могла составить
1,8 млрд руб. Это МЕТОД ОЦЕНКИ (долг учтён при расчёте стоимости), а не
условие сделки. Ни в одном источнике нет ни слова про «реструктуризацию
долга», «отложенные (рассроченные) платежи» или урожайность 2026-2028 —
`eco.fin`/`law.terms` карточки досочинили несуществующую earn-out-структуру
поверх честной оценочной методики.

Заодно: `sum`/`eco.sum` несли «1,8 млрд ₽» как факт, хотя источники прямо
говорят — сумма не раскрыта, это чужая оценка (нужна пометка «(по оценке)»,
см. правило проекта про сумму сделки). И `eco.share`/профиль компании
(`gf4207471`) называли «Колос Кубани» «крупнейшим производителем голубики
в России» — источник (Ъ, doc/8476725) называет ЕГО в топ-5 ПО ПЛОЩАДИ, не
единственным крупнейшим: «Руководитель проекта «Ягодная академия» Ирина
Козий включает «Колос Кубани» в топ-5 крупнейших по площади выращивания
голубики хозяйств в России».

`eco.fin`/`law.terms` возвращены к честному прочерку: единственный реальный
факт этих полей (инвестиции до 1,4 млрд ₽ в модернизацию) уже стоит в
`eco.context`/`extra` — досочинённую часть переносить некуда, потому что её
не было в источниках вовсе.

Запуск:
    python3 pipeline/fix_kolos_kubani_fabricated_debt_terms.py            # сухой прогон
    python3 pipeline/fix_kolos_kubani_fabricated_debt_terms.py --write     # запись
"""
import json
import sys

PATH = "static/data/deals_promoted.json"
ID = "ge386fb20"
COMPANY_ID = "gf4207471"

FABRICATED_FIN = (
    "Сделка предусматривает реструктуризацию долга компании на 1,8 млрд "
    "руб. и отложенные платежи, привязанные к выходу хозяйства на "
    "плановую урожайность в 2026–2028 годах; дополнительно «Магнит» "
    "планирует инвестировать до 1,4 млрд руб. в модернизацию производства."
)
FABRICATED_TERMS = (
    "Отложенные (рассроченные) платежи по сделке привязаны к достижению "
    "хозяйством плановой урожайности в 2026–2028 годах; предусмотрена "
    "реструктуризация долга компании на 1,8 млрд руб."
)
OLD_SHARE = (
    "Приобретение хозяйства ООО «Колос Кубани» (крупнейший производитель "
    "голубики в России; продавец — Денис Таран) — 262 га земли в Крымском "
    "районе Краснодарского края, из которых 155 га плодоносящих садов: "
    "73 га под голубику и 82 га под яблони."
)
NEW_SHARE = (
    "Приобретение хозяйства ООО «Колос Кубани» (одно из пяти крупнейших "
    "по площади выращивания голубики хозяйств России, по оценке "
    "руководителя проекта «Ягодная академия» Ирины Козий; продавец — "
    "Денис Таран) — 262 га земли в Крымском районе Краснодарского края, "
    "из которых 155 га плодоносящих садов: 73 га под голубику и 82 га "
    "под яблони."
)


def main(write):
    with open(PATH, encoding="utf-8") as f:
        base = json.load(f)
    by_id = {d["id"]: d for d in base["deals"]}
    d = by_id.get(ID)
    assert d is not None, f"{ID} не найдена"

    assert d["sum"] == "1,8 млрд ₽", "sum уже другой — уже правили?"
    d["sum"] = "1,8 млрд ₽ (по оценке)"
    assert d["eco"]["sum"] == "1,8 млрд ₽", "eco.sum уже другой — уже правили?"
    d["eco"]["sum"] = "1,8 млрд ₽ (по оценке)"

    assert d["eco"]["fin"] == FABRICATED_FIN, "eco.fin уже другой — уже правили?"
    d["eco"]["fin"] = "—"

    assert d["law"]["terms"] == FABRICATED_TERMS, "law.terms уже другой — уже правили?"
    d["law"]["terms"] = "—"

    assert d["eco"]["share"] == OLD_SHARE, "eco.share уже другой — уже правили?"
    d["eco"]["share"] = NEW_SHARE

    company = base["companies"].get(COMPANY_ID)
    assert company is not None, f"компания {COMPANY_ID} не найдена"
    assert company["desc"] == "Крупнейший производитель голубики в России (Краснодарский край).", \
        "описание компании уже другое — уже правили?"
    company["desc"] = (
        "Одно из пяти крупнейших по площади выращивания голубики хозяйств "
        "России (Краснодарский край)."
    )

    print("ge386fb20: sum, eco.sum, eco.fin, law.terms, eco.share исправлены")
    print("gf4207471 (профиль): описание исправлено")

    if write:
        with open(PATH, "w", encoding="utf-8") as f:
            json.dump(base, f, ensure_ascii=False, indent=1)
        print("\nЗАПИСАНО.")
    else:
        print("\nСухой прогон — ничего не записано. Добавьте --write.")


if __name__ == "__main__":
    main(write="--write" in sys.argv)
