import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g65d042bc'

OLD_LAW_STRUCT = (
    'В рамках взыскания банком с компании 1,19 млрд руб. арбитражный суд '
    'Камчатского края 9 августа произвел замену истца на «Восточный '
    'актив». Заявление о правопреемстве конкурсного кредитора в деле о '
    'банкротстве «Сокры» суд рассмотрит 21 августа'
)
NEW_LAW_STRUCT = OLD_LAW_STRUCT + (
    '. 4 декабря 2023 года суд признал «Сокру» банкротом и ввёл '
    'конкурсное производство на 6 месяцев; прежние учредители — Андрей '
    'Обедин (51%), Сергей Андреев (44%) и ООО «Сбербанк Инвестиции» (5%). '
    'По данным СПАРК-Интерфакс, спустя годы после сделки «Восточный '
    'актив» так и не стал совладельцем завода — Обедин и Андреев '
    'по-прежнему числятся учредителями, «Восточный актив» остаётся лишь '
    'держателем выкупленных прав требования к должнику.'
)

OLD_ECO_CONTEXT = (
    'Компания принадлежит Евгению Свистуле, и в этом году она стала '
    'владельцем ООО «Витязь Авто», которое управляет лососевым заводом '
    'и участком для вылова нерки на Камчатке'
)
NEW_ECO_CONTEXT = OLD_ECO_CONTEXT + (
    '. Выручка «Сокры» упала с 1,39 млрд ₽ (2021) до 1,13 млрд ₽ (2022), '
    'чистая прибыль — с 425 до 90 млн ₽. «Сокра» подала встречный иск к '
    'Сбербанку на 3,44 млрд ₽ за приостановку финансирования, из-за '
    'которой были сорваны три контракта на строительство судов и '
    'потеряны инвестквоты (недополученная прибыль оценена заводом в '
    '2,97 млрд ₽); Андрей Обедин через представителя называл попытку '
    'банкротства «искусственной», направленной на смену собственника.'
)

NEW_SRC = [
    ['ПроБанкротство', 'https://probankrotstvo.ru/news/sud-priznal-bankrotom-kamcatskii-rybzavod-sokra-iz-za-dolga-17-mlrd-rublei-3942'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6187045'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['law']['struct'] == OLD_LAW_STRUCT
    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    new_src = deal['src'] + NEW_SRC

    print('=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['law']['struct'] = NEW_LAW_STRUCT
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
