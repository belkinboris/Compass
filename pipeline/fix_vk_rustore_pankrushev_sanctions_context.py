import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_ECO_CONTEXT = (
    'Дмитрий Панкрушев возглавляет ООО «Много приложений» — компанию, '
    'которую VK привлекал к разработке RuStore.'
)
NEW_ECO_CONTEXT = OLD_ECO_CONTEXT + (
    ' В июле 2026 года Евросоюз ввёл санкции против холдинга VK из-за '
    'мессенджера, который в ЕС считают шпионским ПО; по мнению '
    'гендиректора ИК «Инициатива» Алексея Гориславца, решение о продаже '
    'RuStore, вероятно, связано с попыткой вывести платформу из-под '
    'санкционных рисков. Он же оценивает стоимость актива в 2 млрд ₽ — '
    'сторонами сумма не раскрывается. По данным ЕГРЮЛ, с 15 июля 2026 '
    'года новым владельцем ООО «Много приложений» (компании-разработчика '
    'RuStore) значится Дмитрий Панкрушев, хотя точная дата закрытия '
    'сделки по самому RuStore публично не подтверждена.'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8816553'],
    ['CNews', 'https://www.cnews.ru/news/top/2026-07-16_rustore_prodan_s_potrohamivk'],
]


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['g1a626d5b']

    assert d['eco']['context'] == OLD_ECO_CONTEXT, \
        'g1a626d5b eco.context уже другой: %r' % (d['eco']['context'],)
    urls = {s[1] for s in d['src']}
    for src in NEW_SRC:
        assert src[1] not in urls, 'источник уже добавлен: %s' % src[1]

    print('g1a626d5b: eco.context дополнен (санкционный фон ЕС, оценка '
          '2 млрд ₽, признак смены владельца по ЕГРЮЛ с 15 июля — '
          'статус НЕ меняется); добавлены источники kommersant.ru, '
          'cnews.ru')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['eco']['context'] = NEW_ECO_CONTEXT
    d['src'].extend(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
