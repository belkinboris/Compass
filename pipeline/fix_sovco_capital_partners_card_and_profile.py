#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Карточка «Совко Капитал Партнерс» / Совкомбанк (gcbf6e44b, очередь
предпросмотра): стороны кликабельны, предмет назван, текст — человеческий,
первоисточник — на месте.

ЧТО БЫЛО (владелец, 11 сентября 2026, по карточке в консоли): покупатель
«Совко капитал партнерс» — текстом, без профиля («непонятно, что за
компания»); предмета нет вовсе, хотя очевидно, что это акции Совкомбанка,
и Совкомбанк должен быть кликабельным; в «Структуре» — дословная фраза
Ведомостей «Книгу заявок в основном закрыли семь институциональных
инвесторов…», из которой не понять, что произошло; в источниках только
Ведомости, хотя они сами ссылаются на пресс-релиз Совкомбанка, где формат
сделки назван прямо.

ЧТО ДЕЛАЕТ.
1. Заводит профиль МКАО «Совко Капитал Партнерс» — холдинговой компании
   основных акционеров Совкомбанка. Описание — по Интерфаксу от 3 сентября
   2021 года (регистрация в Калининградском САР в порядке редомициляции из
   Люксембурга; «принадлежит группе российских бизнесменов, включая
   основателей банка, ключевых членов руководства и наблюдательного совета
   банка, но не находится под контролем какого-либо конечного
   собственника») и Ведомостям от 9 сентября 2026 года (57,7% до сделки).
   ИНН 3906406196 / ОГРН 1213900011280 — по cbonds.ru; в реестр ФНС
   вносится отдельной записью (pipeline/fns_registry.py).
2. Покупатель карточки — ссылка на этот профиль; предмет — профиль ПАО
   «Совкомбанк» (gb7e1e33a), текстом «акции Совкомбанка». У профиля
   Совкомбанка проставляется `holding` на «Совко Капитал Партнерс» —
   бейдж «Входит в группу» в обе стороны, как у Tele2/Ростелеком.
3. «Как устроена сделка», «Контекст» и «Финансы покупаемой компании»
   переписаны по-человечески по двум источникам. Факты те же, что в
   таблице FIXES (`pipeline/ingest/fixes/fix_sovko_capital_sovcombank.py`):
   числа, имена и валюты не менялись — только формулировка. Записи таблицы
   помечаются впитанными через `proofread_absorbed` — тот же штамп, что
   ставит вычитка (см. CLAUDE.md, «Владелец видит карточку в консоли
   РАНЬШЕ, чем её вычитывают»).
4. В источники добавляется пресс-релиз Совкомбанка. Адрес взят из ссылки
   в самой статье Ведомостей (не из выдачи поиска); сайт sovcombank.ru
   автоматическому чтению отвечает 503 (та же защита от роботов, что у
   rbc.ru — 401/403), человеку страница открывается, владелец её читал.
   Дословная формулировка релиза подтверждена перепечаткой АБН
   (abn.agency, 9 сентября 2026, 18:15): «Пакет акций ПАО «Совкомбанк»
   был продан в ходе ускоренного формирования книги заявок вне биржевого
   стакана».
5. Статус — «Закрыта»: релиз и Ведомости говорят о состоявшемся
   размещении («был продан», «разместили»), не о планах. Заголовок
   переписан: «за счет акционера» читателю ничего не говорило.

Запуск: python3 pipeline/fix_sovco_capital_partners_card_and_profile.py [--write]
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')
PENDING = os.path.join(ROOT, 'static', 'data', 'pending.json')
sys.path.insert(0, os.path.join(ROOT, 'pipeline', 'ingest'))
from review import fix_fingerprint  # noqa: E402

DEAL = 'gcbf6e44b'
SOVCO = 'gsovcocp'
SOVCOMBANK = 'gb7e1e33a'

PRESS_RELEASE = ['Совкомбанк',
                 'https://sovcombank.ru/articles/novosti-kompanii/'
                 'paket-aktsii-sovkombanka-razmeschen-sredi-institutsionalnih-investorov']

OLD_STRUCT = ('Книгу заявок в основном закрыли семь институциональных инвесторов, а '
              '«Совко капитал партнерс» участвовал в размещении и увеличил свою долю. '
              'Цену размещения и другие параметры стороны пока не раскрывают, добавили '
              'в Совкомбанке.')
OLD_CONTEXT = ('До сделки «Совко капитал партнерс» принадлежало 57,7% Совкомбанка. Доля '
               'собственных выкупленных акций составляла 0,4%. Еще 17,3% находились в '
               'свободном обращении на рынке. Остальные, как указано на сайте банка, не '
               'находятся в свободном обращении.')
OLD_FIN = ('Чистая прибыль ПАО «Совкомбанк» по МФСО за первые шесть месяцев выросла '
           'в 2,6 раза год к году и достигла отметки в 45,3 млрд руб. Чистый '
           'процентный доход банк нарастил на 70,4% до 124,7 млрд руб. Чистая '
           'процентная маржа (NIM) увеличилась до 7,2% с 4,5% годом ранее. '
           'Рентабельность капитала (ROE) достигла 21,1%, показав рост в 9,9 п. п.')

NEW_TITLE = ('«Совко Капитал Партнерс» увеличил долю в Совкомбанке, выкупив часть '
             'пакета одного из акционеров')
NEW_STRUCT = ('Пакет акций Совкомбанка продан в формате ускоренного формирования книги '
              'заявок (accelerated bookbuilding) вне биржевого стакана. Большую часть '
              'выкупили семь институциональных инвесторов; «Совко Капитал Партнерс» тоже '
              'участвовал в размещении и увеличил свою долю. Сам банк стороной сделки не '
              'был и собственные акции не продавал. Цену и размер пакета стороны не '
              'раскрыли.')
NEW_CONTEXT = ('До сделки «Совко Капитал Партнерс» принадлежало 57,7% акций Совкомбанка, '
               '0,4% банк держал как выкупленные собственные акции, 17,3% находились в '
               'свободном обращении; остальные акции в свободном обращении не находятся.')
NEW_FIN = ('За первое полугодие 2026 года чистая прибыль Совкомбанка по МСФО выросла в '
           '2,6 раза, до 45,3 млрд ₽, чистый процентный доход — на 70,4%, до 124,7 млрд ₽. '
           'Чистая процентная маржа — 7,2% против 4,5% годом ранее, рентабельность '
           'капитала — 21,1%.')
NEW_SHARE = 'Акции Совкомбанка. Размер пакета стороны не раскрыли.'

PROFILE = {
    'name': '«Совко Капитал Партнерс»',
    'ind': 'Холдинги',
    # Бейдж «Группа компаний»: на профиль ссылается `holding` Совкомбанка, и
    # тест `test_holding_target_is_always_flagged_as_group` требует этого
    # признака у любой цели `holding` (запись в CLAUDE.md «группа vs фонд»).
    'group': True,
    # Первое предложение — короткое и о главном: именно его берёт пост канала
    # в пояснение к покупателю (`_party_detail` выбирает предложение по
    # длине и новизне, и длинное первое предложение уступило бы место
    # «люксембургской S.a r.l.» — проверено сухим рендером поста).
    'desc': ('Холдинговая компания основных акционеров Совкомбанка. Принадлежит группе '
             'российских бизнесменов, включая основателей банка и ключевых руководителей, '
             'без единого контролирующего владельца; зарегистрирована в Калининградском '
             'САР (МКАО), до сентября 2021 года — люксембургская Sovco Capital Partners '
             'S.a r.l.'),
    'kpi': [],
}
MATCH_KEYS = ['совко капитал партнерс', 'sovco capital partners']


def main(write=False):
    with open(BASE, encoding='utf-8') as f:
        base = json.load(f)
    with open(PENDING, encoding='utf-8') as f:
        pending = json.load(f)
    card = next(c for c in pending['cards'] if c['id'] == DEAL)

    # Проверки исходного состояния — если данные уже другие, падаем, а не портим.
    assert SOVCO not in base['companies'], 'профиль уже заведён'
    assert base['companies'][SOVCOMBANK]['name'] == 'ПАО «Совкомбанк»'
    assert not base['companies'][SOVCOMBANK].get('holding'), 'у Совкомбанка уже есть группа'
    assert card.get('buyer_name') == '«Совко капитал партнерс»' and not card.get('buyer')
    assert not card.get('target') and not card.get('asset_id') and not card.get('asset')
    assert card['law']['struct'] == OLD_STRUCT
    assert card['eco']['context'] == OLD_CONTEXT
    assert card['eco']['target_fin'] == OLD_FIN
    assert card['eco']['share'] == '—'
    assert card['status'] == 'Обсуждается'
    assert len(card['src']) == 1 and 'vedomosti.ru' in card['src'][0][1]

    base['companies'][SOVCO] = PROFILE
    base.setdefault('match_keys', {})[SOVCO] = MATCH_KEYS
    base['companies'][SOVCOMBANK]['holding'] = {
        'id': SOVCO, 'confidence': 'disclosed',
        'source': ['Интерфакс', 'https://www.interfax.ru/business/788471'],
    }

    card['title'] = NEW_TITLE
    card['buyer'] = SOVCO
    card.pop('buyer_name')
    card['target'] = SOVCOMBANK
    card['asset'] = 'акции Совкомбанка'
    card['eco']['share'] = NEW_SHARE
    card['status'] = 'Закрыта'
    card['src'].append(PRESS_RELEASE)
    absorbed = card.setdefault('proofread_absorbed', {})
    for field, old, new in (('law.struct', OLD_STRUCT, NEW_STRUCT),
                            ('eco.context', OLD_CONTEXT, NEW_CONTEXT),
                            ('eco.target_fin', OLD_FIN, NEW_FIN)):
        section, key = field.split('.')
        card[section][key] = new
        absorbed.setdefault(field, []).append(fix_fingerprint(old))

    print('Профиль:', SOVCO, PROFILE['name'])
    print('Карточка:', card['title'])
    print('  buyer', card['buyer'], '| target', card['target'], '| asset', card['asset'])
    print('  status', card['status'], '| src', [s[0] for s in card['src']])
    print('  struct:', card['law']['struct'])
    if not write:
        print('(сухой прогон, для записи — --write)')
        return
    for path, data in ((BASE, base), (PENDING, pending)):
        with open(path, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=1, ensure_ascii=False)
            f.write('\n')
    print('Записано.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
