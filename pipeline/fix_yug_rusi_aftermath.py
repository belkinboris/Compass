# -*- coding: utf-8 -*-
"""Агрокомплекс Ткачева/«Юг Руси» (`gba72051d`): месячный дообыск нашёл
комментарии независимых аналитиков рынка растительных масел в момент
сделки (Андрей Сизов, Дмитрий Рылько — Коммерсантъ) и подробную судьбу
обеих сторон ПОСЛЕ закрытия: Сергей Кислов покинул Россию и в декабре
2024 года передал остававшиеся у него активы (не входившие в проданный
периметр) полному тёзке отца, Василию Кислову; сам холдинг «Юг Руси» к
2025 году оказался в глубоком кризисе — чистый убыток МЭЗ «Юг Руси» в
2025 году составил 4,1 млрд ₽ против прибыли 4,757 млрд ₽ годом ранее,
выручка упала на 30,8%, три маслозавода выставлены на продажу за 6
млрд ₽. Источники другие, чем уже занятые поля `eco.rationale` и
`eco.context` — слияние разовым скриптом.

НЕ ВКЛЮЧЕНО НАМЕРЕННО: сюжет 2026 года о национализации ростовского
ипподрома и хлебозавода «Юг Руси» с участием Сергея Кислова (иск
Генпрокуратуры, суд удовлетворил в апреле 2026) — по данным источников
это отдельные активы, выделенные из холдинга ДО сделки 2023 года и не
входившие в проданный масложировой бизнес; сам саб-агент отметил
расходящуюся хронологию передачи этих активов между источниками. Это
судьба Кислова как физлица и других его активов, а не судьба ПРЕДМЕТА
этой сделки — не путать, не переносить без отдельной проверки.

Запуск: python3 pipeline/fix_yug_rusi_aftermath.py           # проверка
        python3 pipeline/fix_yug_rusi_aftermath.py --write   # запись
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gba72051d'

OLD_RATIONALE = (
    'Если внутреннему рынку масла постоянно грозит ограничительное '
    'регулирование, то внешний дает прямой доступ к незерновой '
    'валютной выручке, отмечает The Bell.')
NEW_RATIONALE = OLD_RATIONALE + (
    ' «Рентабельность маслозаводов остается отличной, производство '
    'масла идет рекордными темпами с учетом хорошего предложения '
    'сырья из-за заградительных пошлин на вывоз подсолнечника», — '
    'отмечал Андрей Сизов (Совэкон). Заводы «"Юга Руси" могут быть уже '
    'не самыми новыми, но отличаются удачным расположением», добавляя '
    'привлекательности за счёт портовой инфраструктуры для экспортной '
    'программы, — говорил Дмитрий Рылько (ИКАР).')

OLD_CONTEXT = (
    'По данным ЕГРЮЛ, Музафаров стал 30 августа гендиректором головных '
    'структур группы ООО «МЭЗ Юг Руси» и ООО «Юг Руси». На посту главы '
    '«Юга Руси» он сменил Дмитрия Кислова, сына основателя и владельца '
    'группы Сергея Кислова.')
NEW_CONTEXT = OLD_CONTEXT + (
    ' Основатель «Юга Руси» Сергей Кислов после продажи активов покинул '
    'Россию; в декабре 2024 года он передал остававшиеся у него в '
    'России компании (не входившие в проданный периметр — фабрику '
    '«Донская гофротара», «Хлебозавод Юг Руси», санаторий «Ольгинка») '
    'Василию Васильевичу Кислову, полному тёзке отца предпринимателя. '
    'Ключевые предприятия холдинга завершили 2025 год с убытком: МЭЗ '
    '«Юг Руси» получил 4,1 млрд рублей чистого убытка против 4,757 '
    'млрд рублей чистой прибыли годом ранее, выручка снизилась на '
    '30,8%, до 53,3 млрд рублей. В декабре 2025 года холдинг выставил '
    'на продажу три маслозавода в Белгородской и Воронежской областях '
    '(Валуйский, Чернянский, Аннинский) за 6 млрд рублей суммарно, '
    'объяснив это лишь тем, что «совет директоров просто решил '
    'продать».')

NEW_SRCS = [
    ['Интерфакс', 'https://www.interfax.ru/business/1082333'],
    ['Ведомости', 'https://www.vedomosti.ru/strana/central/news/2025/'
     '12/02/1159925-maslozavoda-chernozeme'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6196897'],
    ['Блокнот Ростов', 'https://bloknot-rostov.ru/news/'
     'yug-rusi-prodali-tkachevu-levyy-bereg-dona-zastroya-1688216'],
    ['161.RU', 'https://161.ru/text/business/2024/12/26/74926805'],
]


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    card = next((c for c in data['deals'] if c['id'] == CARD_ID), None)
    assert card is not None, '%r не найдена в базе' % CARD_ID
    assert card['eco'].get('rationale') == OLD_RATIONALE, (
        'eco.rationale изменился с ожидаемого: %r' % card['eco'].get('rationale'))
    assert card['eco'].get('context') == OLD_CONTEXT, (
        'eco.context изменился с ожидаемого: %r' % card['eco'].get('context'))
    src = card.setdefault('src', [])
    print('ПРАВИМ  %s: eco.rationale — комментарии Сизова и Рылько' % CARD_ID)
    print('ПРАВИМ  %s: eco.context — судьба Кислова и кризис холдинга в 2025 году' % CARD_ID)
    if write:
        card['eco']['rationale'] = NEW_RATIONALE
        card['eco']['context'] = NEW_CONTEXT
        for s in NEW_SRCS:
            if s not in src:
                src.append(s)
        json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
        print('ЗАПИСАНО')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
