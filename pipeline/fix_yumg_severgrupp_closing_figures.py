import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gcfae418d'

OLD_EXTRA = (
    'Холдинговая компания ЮМГ размещает 32,8 млн акций по цене 766,2 '
    'руб. за акцию в пользу «Севергрупп». В оплату «Севергрупп» '
    'передает 100% долей клиник «Ава-Петер» (Скандинавия). После сделки '
    '«Севергрупп» может получить до 26,7% ЮМГ. Переход долей подлежит '
    'одобрению ФАС. (Холдинг ЮМГ (ЕМС и «Семейный доктор») / '
    '«Севергрупп»)'
)
NEW_EXTRA = (
    'Сделка закрыта: холдинговая компания ЮМГ выпустила 23,85 млн акций '
    'по цене 766,2 руб. за акцию в пользу «Севергрупп» (первоначально '
    'объявленный объём в 32,8 млн акций уменьшился — часть акционеров '
    'воспользовалась преимущественным правом выкупа дополнительных '
    'акций). В оплату «Севергрупп» передала 100% долей клиник '
    '«Ава-Петер» (Скандинавия). В результате «Севергрупп» получила '
    '20,9% ЮМГ (вместо ранее анонсированных «до 26,7%»). Сделка '
    'одобрена ФАС. (Холдинг ЮМГ (ЕМС и «Семейный доктор») / '
    '«Севергрупп»)'
)

OLD_CONTEXT = '—'
NEW_CONTEXT = (
    'EMC заняла четвёртое место в рейтинге крупнейших российских '
    'частных многопрофильных клиник по итогам 2025 года, по версии '
    'отраслевого издания Vademecum («Скандинавия» — на седьмой '
    'позиции). Выручка группы увеличилась на 14,1% в евро, до €289,5 '
    'млн, в рублях — на 9,8%, до 27,3 млрд руб. EMC начнёт '
    'консолидировать «Скандинавию» в финансовой отчётности с июля 2026 '
    'года.'
)


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['extra'] == OLD_EXTRA, f"extra: неожиданное значение {deal['extra']!r}"
    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} extra: план (32,8 млн акций, до 26,7%) заменён на итог "
          f"закрытия (23,85 млн акций, 20,9%)")
    print(f"{CARD_ID} eco.context: += положение EMC на рынке после объединения")
    deal['extra'] = NEW_EXTRA
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
