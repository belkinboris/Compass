# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
`g81b7b7e6» («UCL Holding (Владимир Лисин) продала Окскую судоверфь
Александру Иванову», закрыта 08.12.2023) — покупатель назван только
по имени и одной прежней должности, без биографии.

Проверено лично прямым WebFetch, Коммерсантъ,
https://www.kommersant.ru/doc/3151794, 2016: «Бенефициарами
«Совфрахта», по данным самой компании, являются глава совета
директоров ПАО «Совфрахт» Александр Иванов и председатель правления
Дмитрий Пурим»; «компании группы, обеспечивающие транспортные и
логистические услуги в Крыму, попали в санкционный список США» —
то есть у группы «Совфрахт», совладельцем которой был Иванов, уже был
опыт санкционного давления до того, как источники стали связывать
санкционные риски с продажей верфи Лисина.

Побочно найдено саб-агентом (Коммерсантъ, doc/2967076, не
перепроверено мной лично прямым WebFetch в этом прогоне): Иванов
родился в 1979 году, окончил Московскую государственную академию
водного транспорта, с 2001 года работал в «Совфрахте», с января 2010
года — председатель совета директоров.

НЕ ВКЛЮЧЕНО: точные данные об источнике денег на покупку верфи и о том,
вышел ли Иванов из капитала «Совфрахта» перед этой сделкой — источники
такого не раскрывают; активность верфи в 2024-2025 годах (портфель
заказов, смена гендиректора на Олега Сасина) — саб-агент нашёл это на
korabel.ru, но точный URL статьи не сохранил, а прямой WebFetch по
восстановленному адресу дал 404 — не вношу без личной проверки;
согласование ФАС/правкомиссии и консультанты сделки — ни один источник
их не называет.

Запуск: python3 pipeline/fix_okskaya_sudoverf_buyer_bio.py
        python3 pipeline/fix_okskaya_sudoverf_buyer_bio.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g81b7b7e6'

OLD_EXTRA = (
    'Сделка включала продажу 100% акций АО «Окская судоверфь» от АО '
    '«Волга-флот» (входит в UCL Holding Владимира Лисина) покупателю '
    'Александру Иванову (бывший акционер «Совфрахт»). ДКП заключен в '
    '2022 году, расчеты завершены в 2023 году.'
)
NEW_EXTRA = (
    OLD_EXTRA + ' Иванов был не рядовым акционером, а главой совета '
    'директоров «Совфрахта» и его совладельцем (вместе с '
    'предправления Дмитрием Пуримом); группа «Совфрахт» уже имела опыт '
    'санкционного давления — в 2016 году её крымские логистические '
    'компании попали в санкционный список США.'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/3151794'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    existing_urls = {s[1] for s in deal['src']}
    add_src = [s for s in NEW_SRC if s[1] not in existing_urls]
    new_src = deal['src'] + add_src

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    if add_src:
        print('\n=== src: добавится ===')
        for s in add_src:
            print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
