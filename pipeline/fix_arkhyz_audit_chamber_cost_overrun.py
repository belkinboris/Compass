# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
`g2f572b66` («"Горные вершины" выиграли конкурс на приобретение
курорта "Архыз"», закрыта 01.03.2023) — исходная сделка уже подробно
описана; дочитывание нашло значимое развитие 2026 года.

Проверено лично прямым WebFetch:
- Коммерсантъ, https://www.kommersant.ru/doc/8551887: «Счетная палата
  выявила удвоение стоимости строительства горнолыжного курорта
  "Архыз" в Карачаево-Черкесии — с 15,4 млрд до 31,2 млрд руб. за
  год.»; письмо главы Счетной палаты Бориса Ковальчука премьер-
  министру Михаилу Мишустину датировано 30 марта 2026 года;
  концессионер просит «грант в 15,3 млрд руб. и субсидии на 12,3 млрд
  руб.»; «компания "Горные вершины"... ранее оплатила четверть
  стоимости проекта — 6 млрд руб. еще в 2024 году».

Замечено, но НЕ разрешается самим скриптом: источники расходятся в
дате оплаты первых 6 млрд ₽ (25% пакета) — Коммерсантъ 2023 года при
описании самой сделки говорил о платеже в течение нескольких месяцев
после подписания (март-июнь 2023), а Коммерсантъ 2026 года (при
описании находки Счётной палаты) называет 2024 год. Обе даты приведены
дословно, расхождение не сглаживается.

НЕ ВНЕСЕНО: цитаты депутата Госдумы Дмитрия Тортева (Rambler/Travel) —
это политическая критика, а не факт о сделке; framing «концессионное
соглашение» вместо «договор купли-продажи акций» из непроверенных
WebSearch-сниппетов о субсидиях 2026 года — не подтверждено прямым
чтением первоисточника, могло быть неточным пересказом.

Запуск: python3 pipeline/fix_arkhyz_audit_chamber_cost_overrun.py
        python3 pipeline/fix_arkhyz_audit_chamber_cost_overrun.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g2f572b66'

OLD_ECO_CONTEXT = (
    'Скок, по открытым данным, — совладелец нескольких компаний в '
    'сфере курортной недвижимости Сочи. Ему принадлежит краснодарское '
    'ООО «Юг-бизнеспартнер» (выручка 13,7 млрд ₽ в 2021 году), которое '
    'владеет курортным комплексом в Имеретинской низменности рядом с '
    'олимпийскими объектами — «Сочи-парк», туристической деревней '
    '«Мандроги» в Ленинградской области (юрлицо — ООО «Мандроги»), '
    'Крымским винным заводом и форелеводческим хозяйством в '
    'Краснодарском крае.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' В марте 2026 года Счётная палата (письмо главы'
    ' ведомства Бориса Ковальчука премьер-министру Михаилу Мишустину'
    ' от 30 марта 2026 года) выявила удвоение стоимости строительства'
    ' курорта за год — с 15,4 млрд до 31,2 млрд ₽. Концессионер просит'
    ' у государства грант в 15,3 млрд ₽ и субсидии на 12,3 млрд ₽; сам'
    ' он ранее оплатил четверть стоимости проекта — 6 млрд ₽ (источники'
    ' расходятся в годе платежа: 2023 или 2024).'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8551887'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    existing_urls = {s[1] for s in deal['src']}
    add_src = [s for s in NEW_SRC if s[1] not in existing_urls]
    new_src = deal['src'] + add_src

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    if add_src:
        print('\n=== src: добавится ===')
        for s in add_src:
            print(s)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
