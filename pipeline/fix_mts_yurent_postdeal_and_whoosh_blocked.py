import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'ga95746a3'

OLD_EXTRA = (
    'Консультант по структурированию сделки. МТС увеличил долю в ООО '
    '«Юрентбайк» (сервис поминутной аренды электросамокатов) с 11,77% '
    'до 79,77%, став контрольным акционером. После сделки 11,03% '
    'осталось у VEB Ventures, 9,2% у Ольги Стефанюк.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' В январе 2025 года «ВЭБ Венчурс» вышла из капитала («плановый '
    'выход, связанный с завершением инвестиционной фазы»), передав '
    '10,49% профильному ЗПИФ; доля МТС выросла до 79,09%. В 2025 году '
    'оборот платформы вырос на 23,7% до 15,5 млрд руб. В феврале 2026 '
    'года ФАС заблокировала возможное объединение «Юрента» с конкурентом '
    'Whoosh, усмотрев риск ограничения конкуренции на рынке кикшеринга — '
    'Whoosh отозвал ходатайство.'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/7477359'],
    ['Ведомости', 'https://www.vedomosti.ru/business/news/2026/02/10/1175317-whoosh-otozval'],
    ['RB.ru', 'https://rb.ru/news/oborot-kiksheringa-yurent-vyros-do-155-mlrd-v-2025-godu-na-samokatah-stali-ezdit-na-267-chashe/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
