"""Приток 22 сентября 2026: карточка gd1130c05 (продажа российского бизнеса
Volkswagen Group «Арт-Финанс»/«Авилон», 2023) уже держит в `extra` собранный
построчно рассказ о сделке (в т.ч. более раннюю тяжбу с ГАЗ). Новая
тяжба — кредитор и конкурсный управляющий Volkswagen AG оспаривают
действительность этой и смежных сделок 2023 года (Коммерсантъ,
doc/8972260) — того же рода факт, appendится тем же способом (одноразовый
скрипт с assert, не через review.py: цитата одна, а поле уже собрано из
нескольких источников построчно, и review.py требует, чтобы ВСЁ значение
поля лежало дословно в одной цитате — здесь это невозможно физически).

Дословная цитата источника (сверена вручную с data/inbox/raw/
2026-09-22-articles.jsonl, url kommersant.ru/doc/8972260):
"АО «Камея», выкупившее долг Volkswagen AG перед автозаводом НАЗ (ранее
ГАЗ), оспаривает сделки по продаже российских активов немецкого
автоконцерна, следует из картотеки арбитражных дел. В сентябре «Камея»
подала заявления о признании недействительными и применения последствий
недействительности сделок по продаже автозавода в Калуге (сегодня АГР) и
дистрибутора грузовиков MAN (сегодня МТБР). Конкурсный управляющий
Volkswagen AG Наталья Винокурова одновременно подала заявление о признании
недействительной сделки по продаже структуры дистрибутора Scania (сегодня
БВГ). Наталья Винокурова сообщила "Ъ", что также оспаривается выплата
«Порше Руссланд» дивидендов в размере 4 млрд руб. в пользу иностранных
участников."

Запуск: python3 pipeline/ingest/fixes/append_vw_kaluga_dispute_2026_09_22.py --write
"""
import argparse
import json
import sys

DATA = 'static/data/deals_promoted.json'
CARD_ID = 'gd1130c05'

OLD_EXTRA = (
    'Сделка закрыта 18 мая 2023 года; регистрация перехода права '
    'собственности на доли ООО «Фольксваген Груп Рус» завершена 22 мая '
    '2023 года. В периметр сделки вошли российское представительство ООО '
    '«Фольксваген Груп Рус», автозавод в Калуге мощностью 225 тыс. '
    'автомобилей в год (около 4 000 сотрудников), импортёрская структура '
    '(дистрибуция и послепродажное обслуживание брендов VW, Audi, Skoda, '
    'Bentley, Lamborghini, Ducati), склад запчастей в Чехове, а также ООО '
    '«Фольксваген Компоненты и Сервис», ООО «Скания Лизинг», ООО «Скания '
    'Финанс» и ООО «Скания Страхование». Покупатель — ООО «Арт-Финанс» '
    '(зарегистрировано в феврале 2023 года; единственный владелец и '
    'гендиректор — Андрей Павлович, президент группы «Авилон»). Сделку '
    'одобрила Правительственная комиссия по контролю за осуществлением '
    'иностранных инвестиций; завод продан без права обратного выкупа. По '
    'данным отчётности Volkswagen за первое полугодие 2023 года, '
    'деконсолидация российских активов привела к убытку 0,4 млрд € по '
    'итогам финансового года. На начало 2022 года аналитики оценивали '
    'стоимость бизнеса VW в России не менее чем в $1,5 млрд, то есть '
    'сделка прошла с очень большим дисконтом. После закрытия сделки ООО '
    '«Фольксваген Груп Рус» переименовано в AGR Automotive Group (ООО '
    '«АГР»); параллельно «Авилон» вёл переговоры с китайским Chery о '
    'возобновлении производства на калужском заводе. Закрытию '
    'предшествовало судебное противодействие ГАЗ, который добился '
    'временного ареста активов VW в России по искам на 15,6 млрд и '
    '28,4 млрд ₽, однако суд снял обеспечительные меры.'
)

ADDITION = (
    ' В сентябре 2026 года кредитор Volkswagen AG (АО «Камея», '
    'выкупившее долг Volkswagen AG перед автозаводом НАЗ, ранее ГАЗ) и '
    'конкурсный управляющий Volkswagen AG Наталья Винокурова оспаривают в '
    'арбитраже действительность продажи калужского автозавода (АГР) и '
    'дистрибутора MAN (МТБР), а Винокурова отдельно — продажи структуры '
    'дистрибутора Scania (БВГ) и выплаты «Порше Руссланд» дивидендов в '
    '4 млрд руб. иностранным участникам; цель оспаривания — вернуть активы '
    'в конкурсную массу Volkswagen AG для банкротных торгов (Коммерсантъ, '
    '22 сентября 2026).'
)

NEW_EXTRA = OLD_EXTRA + ADDITION

NEW_SRC = ['Коммерсантъ', 'https://www.kommersant.ru/doc/8972260']


def main(write):
    data = json.load(open(DATA, encoding='utf-8'))
    card = next(d for d in data['deals'] if d['id'] == CARD_ID)
    assert card.get('extra') == OLD_EXTRA, 'extra изменился с момента написания правки'
    assert NEW_SRC not in card.get('src', []), 'источник уже привязан'
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return
    card['extra'] = NEW_EXTRA
    card.setdefault('src', []).append(NEW_SRC)
    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
        f.write('\n')
    print('Записано: %s — extra дополнен, источник добавлен.' % CARD_ID)


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('--write', action='store_true')
    args = p.parse_args()
    main(args.write)
