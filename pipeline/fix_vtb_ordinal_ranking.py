# -*- coding: utf-8 -*-
"""Убрать порядковое место на рынке из описания ВТБ.

Замечание Ксюши (19 сентября 2026): оценочные описания компаний стоит
убирать — «второй по величине банк» может устареть или задеть. Пример её
собственный, и он точный: место в рейтинге зависит от того, по какому
показателю считать (активы, капитал, прибыль, число клиентов), меняется от
года к году, и никто у нас за ним не следит. Написав его один раз, мы
обещаем читателю актуальность, которой не обеспечиваем.

ЗАМЕР ПЕРЕД ПРАВКОЙ (та же дата, вся база — 2029 профилей). Порядковое
место названо ровно у трёх профилей, и чинить нужно ОДИН:
  * ВТБ (`gcafc31dc`) — «Второй по величине банк страны». Чистый рейтинг
    без меры: по чему второй, не сказано. Это и правим.
  * Pilkington/STiS (`g3117f856`) — «второе крупное приобретение стекольных
    активов после Guardian Industries в 2022 году». Это не место на рынке,
    а порядковый номер покупки в истории покупателя: факт, который не
    устаревает. Не трогаем.
  * «Колос Кубани» (`gf4207471`) — «одно из пяти крупнейших по площади
    выращивания голубики хозяйств России». Мера названа прямо (площадь
    выращивания голубики), и это ровно тот случай, который CLAUDE.md
    разбирает как «превосходная степень с проверяемой мерой — полезный
    факт, а не штамп». Не трогаем.

ЧТО ОСТАЁТСЯ У ВТБ. Вторая половина фразы — перечисление того, чем банк
занимается, и она не оценочная. Ничего нового не дописываем: из фразы
вырезается только рейтинговая часть, остаток остаётся дословным.

Запуск:
    python3 pipeline/fix_vtb_ordinal_ranking.py          # сухой прогон
    python3 pipeline/fix_vtb_ordinal_ranking.py --write  # записать
"""
import json
import sys
from pathlib import Path

DATA = Path(__file__).resolve().parents[1] / "static" / "data" / "deals_promoted.json"
COMPANY_ID = "gcafc31dc"
OLD = "Второй по величине банк страны — корпоративное и розничное финансирование, инвестиционный бизнес."
NEW = "Универсальный банк: корпоративное и розничное финансирование, инвестиционный бизнес."


def main(write: bool) -> None:
    raw = DATA.read_text(encoding="utf-8")
    data = json.loads(raw)
    card = data["companies"][COMPANY_ID]
    if card.get("desc") == NEW:
        print("Уже исправлено.")
        return
    assert card.get("desc") == OLD, "описание ВТБ не в ожидаемом состоянии: %r" % card.get("desc")
    card["desc"] = NEW
    print("было:  %s\nстало: %s" % (OLD, NEW))
    if not write:
        print("\nСухой прогон. Записать: --write")
        return
    DATA.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    print("\nЗаписано.")


if __name__ == "__main__":
    main("--write" in sys.argv)
