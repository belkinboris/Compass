import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

COMPANY_ID = 'ggeometria'
COMPANY = {
    'name': 'ООО «Геометрия»',
    'ind': 'Недвижимость',
    'desc': (
        'Петербургский застройщик элитной недвижимости; зарегистрирован '
        '5 мая 2026 года, единственный владелец — Александр Кравцов, сын '
        'основателей ГК «Еврострой». До этого Кравцов был совладельцем '
        '(45%) ООО «Физика Девелопмент», откуда вышел в день регистрации '
        '«Геометрии». Готовые проекты — апарт-отель VIDI на Синопской '
        'набережной (сдан в 2024) и клубный дом Talento в историческом '
        'центре (сдача в 2026).'
    ),
    'kpi': ['Профиль', 'Автоматический'],
}
COMPANY_KEYS = ['ооо геометрия', 'геометрия']

DEALS = ['g749a7844', 'gbdefd889']
OLD_BUYER_NAME = '«Геометрия»'


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)

    assert COMPANY_ID not in data['companies']
    for did in DEALS:
        deal = next(d for d in data['deals'] if d['id'] == did)
        assert deal.get('buyer') is None
        assert deal.get('buyer_name') == OLD_BUYER_NAME

    print('=== новый профиль компании ===')
    print(COMPANY_ID, COMPANY)
    print('\n=== match_keys ===')
    print(COMPANY_ID, COMPANY_KEYS)
    for did in DEALS:
        print(f'\n=== {did}: buyer -> {COMPANY_ID}, buyer_name -> None ===')

    if write:
        data['companies'][COMPANY_ID] = COMPANY
        data['match_keys'][COMPANY_ID] = COMPANY_KEYS
        for did in DEALS:
            deal = next(d for d in data['deals'] if d['id'] == did)
            deal['buyer'] = COMPANY_ID
            deal['buyer_name'] = None
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
