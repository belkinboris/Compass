def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['law']['struct'] == OLD_STRUCT, \
        f"law.struct: неожиданное значение {deal['law']['struct']!r}"
    assert deal['eco']['target_fin'] == OLD_TARGET_FIN, \
        f"eco.target_fin: неожиданное значение {deal['eco']['target_fin']!r}"
    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} law.struct: += прямой юридический покупатель "
          "(АО «Энергия Инноваций»)")
    deal['law']['struct'] = NEW_STRUCT

    print(f"{CARD_ID} eco.target_fin: += финансовые показатели завода "
          "2022-2025")
    deal['eco']['target_fin'] = NEW_TARGET_FIN

    print(f"{CARD_ID} eco.context: += поставка для БРЕСТ-ОД-300 "
          "(декабрь 2025)")
    deal['eco']['context'] = NEW_CONTEXT

    src_urls = [s[1] for s in deal.get('src', [])]
    for name, url in [
        ('saby.ru', 'https://saby.ru/profile/4001005954-400101001'),
        ('EnergyLand.info', 'https://energyland.info/news-show--electro-277760'),
    ]:
        if url not in src_urls:
            deal['src'].append([name, url])
            print(f"{CARD_ID} src: += {name}")

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
