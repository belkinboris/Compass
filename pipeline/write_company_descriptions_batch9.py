# -*- coding: utf-8 -*-
"""Девятая партия описаний профилей: чем компания занимается.

ЧТО СЛОМАНО. После восьми партий настоящее описание есть у 444 профилей
из 1873 (24%). Хвост без описания — 1430 профилей, и та же картина, что в
партии 8: имена людей, сломанные падежные формы («Лентой», «Газпромом»,
«РуссНефти», «Еврохима»), метки раундов («Pre-seed», «Раунд A») и
фрагменты формулировки сделки в поле имени («Приобретение Qiwi»,
«Инвестиции Дмитрия Потапова»). Кандидатов этой партии искали по
узнаваемости имени, а не по рангу участия — те же основания, что в
партии 8.

ЧТО ДЕЛАЕТ. Проставляет описание в 1–2 строки 16 профилям.

ПОБОЧНАЯ НАХОДКА: ЕЩЁ ДВА ПРОФИЛЯ С НЕВЕРНОЙ ОТРАСЛЬЮ (тот же класс, что
в партии 8 — «Отрасль профиля — не отрасль первой попавшейся сделки»):
  - `gff44d7b7` «ВСМПО-Ависма» стоял «Энергетика» — унаследовано от сделки
    «"Русал" приобрёл 4,35% акций "РусГидро" у дочки "ВСМПО-Ависма"»,
    отрасль которой определена по ПРЕДМЕТУ сделки (акции энергокомпании
    РусГидро), а не по самой ВСМПО-Ависме. У профиля есть и вторая сделка
    (Arconic/«Промышленные инвестиции»), верно размеченная «ГМК и
    добыча» — по ней и исправлено.
  - `g761804d9` «Segezha Packaging» стоял «Пищепром и напитки», хотя
    единственная сделка профиля («Segezha Group продала… Segezha
    Packaging») размечена «Производство тары» — профиль просто не
    подхватил отрасль своей же сделки. Исправлено на «Производство тары».
Обе правки проверены по тексту заголовков сделок самого профиля.

Запуск:
    python3 pipeline/write_company_descriptions_batch9.py            # сухой прогон
    python3 pipeline/write_company_descriptions_batch9.py --write    # записать
"""
import json
import re
import sys

DATA = 'static/data/deals_promoted.json'
PLACEHOLDER = re.compile(r'^\s*(описание компании пока не добавлено'
                          r'|профиль сформирован по итогам чтения)', re.I)

# id профиля -> описание. Только компании, чей род занятий общеизвестен.
DESCRIPTIONS = {
    'gf283ed52': 'Канадский производитель автокомпонентов, один из '
                 'крупнейших в мире.',
    'gff44d7b7': 'Крупнейший в мире производитель титана и титановой '
                 'продукции.',
    'g5d0db23a': 'Один из крупнейших российских ритейлеров, управляет '
                 'сетями «Пятёрочка» и «Перекрёсток».',
    'ga39d16dd': 'Один из крупнейших производителей угля в России.',
    'g41dfb596': 'Государственная корпорация, инвестирующая в '
                 'нанотехнологии и высокотехнологичные проекты.',
    'g72e3b46f': 'Крупнейший в мире производитель никеля и палладия.',
    'g447a35a0': 'Один из крупнейших российских производителей '
                 'лекарственных препаратов.',
    'g842a7fd2': 'Крупная российская сеть магазинов парфюмерии и '
                 'косметики.',
    'ga577cb9a': 'Британская розничная группа, владеет сетями товаров '
                 'для дома и ремонта, включая B&Q и Castorama.',
    'gcb2a725b': 'Международный трейдер нефти и нефтепродуктов.',
    'g6c95bc9a': 'Российская угледобывающая компания.',
    'g230e3a6d': 'Российская группа брендов одежды, включает befree, '
                 'Zarina и Love Republic.',
    'gc904414e': 'Крупный российский оператор железнодорожных грузовых '
                 'перевозок, «дочка» РЖД.',
    'g74eaf526': 'Британская золотодобывающая компания, вела добычу в '
                 'Амурской области.',
    'g761804d9': 'Европейский производитель бумажной упаковки, ранее '
                 'принадлежал Segezha Group.',
    'g789a84a2': 'Алжирский оператор мобильной связи.',
}

# Профили, отрасль которых унаследована от одной сделки и не отражает
# основной бизнес компании (см. докстринг). old — что было, для assert.
INDUSTRY_FIXES = {
    'gff44d7b7': ('Энергетика', 'ГМК и добыча'),
    'g761804d9': ('Пищепром и напитки', 'Производство тары'),
}

# Профили, которым описание не ставится в этой партии: неизвестно, что
# именно они обозначают, или падежная/предметная форма имени.
UNCLEAR = {}


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    comps = data['companies']

    wrote, skipped = 0, []
    for cid, text in DESCRIPTIONS.items():
        c = comps.get(cid)
        assert c, 'профиля %s нет в базе' % cid
        assert 15 <= len(text) <= 220, 'описание %s вне 1–2 строк: %d' % (cid, len(text))
        assert cid not in UNCLEAR, 'профиль %s помечен неясным — описание ставить нельзя' % cid
        old = str(c.get('desc') or '')
        if old.strip() == text:
            continue
        # Своё описание не перетираем: прошлые партии и ручные правки старше этой.
        if old and not PLACEHOLDER.match(old):
            skipped.append((cid, c.get('name'), old[:60]))
            continue
        print('  %-12s %-34s %s' % (cid, str(c.get('name'))[:34], text[:56]))
        c['desc'] = text
        wrote += 1

    ind_fixed = 0
    for cid, (old_ind, new_ind) in INDUSTRY_FIXES.items():
        c = comps.get(cid)
        assert c, 'профиля %s нет в базе' % cid
        assert c.get('ind') == old_ind, ('отрасль %s уже другая: %r (ожидали %r)'
                                          % (cid, c.get('ind'), old_ind))
        print('  ОТРАСЛЬ  %-12s %-34s %s -> %s'
              % (cid, str(c.get('name'))[:34], old_ind, new_ind))
        c['ind'] = new_ind
        ind_fixed += 1

    print('\nОписаний записано: %d' % wrote)
    print('Отраслей исправлено: %d' % ind_fixed)
    if skipped:
        print('Пропущено (уже есть своё описание): %d' % len(skipped))
        for cid, name, old in skipped[:5]:
            print('   %s %s — %r' % (cid, name, old))
    print('Оставлено без описания намеренно: %d профилей (см. UNCLEAR)' % len(UNCLEAR))

    real = sum(1 for v in comps.values()
               if (v.get('desc') or '').strip() and not PLACEHOLDER.match(str(v.get('desc'))))
    print('Всего профилей с описанием: %d из %d (%d%%)'
          % (real, len(comps), round(100 * real / len(comps))))

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return 0
    json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('Записано.')
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
