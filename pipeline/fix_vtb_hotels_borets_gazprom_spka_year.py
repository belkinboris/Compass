import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_DATE = '2024'

OLD_ECO_CONTEXT_BORETS = (
    'Генпрокуратура мотивировала иск тем, что компании выпускают '
    'оборудование, используемое при добыче более 80% нефти в России, а '
    'владение ими иностранцами нарушает законодательство. Кроме того, в '
    '2024 году зафиксирован вывод финансовых активов за границу более чем '
    'на 2 млрд ₽.'
)
NEW_ECO_CONTEXT_BORETS = OLD_ECO_CONTEXT_BORETS + (
    ' 25 июня 2025 года Тринадцатый арбитражный апелляционный суд отказал '
    'бывшим собственникам холдинга «Борец» в удовлетворении апелляционной '
    'жалобы на решение первой инстанции об обращении группы в собственность '
    'государства — решение вступило в силу.'
)

OLD_ECO_CONTEXT_SPKA = (
    'Предприятие введено в эксплуатацию в прошлом году, участие Роскосмоса '
    'может обеспечить производство спутников для федеральных проектов. '
    'Основной вопрос — финансирование сделки. (Газпром (потенциальный '
    'продавец))'
)
NEW_ECO_CONTEXT_SPKA = OLD_ECO_CONTEXT_SPKA + (
    ' Изначальный план изменился: по данным на 26 мая 2026 года, «Газпром» '
    'планирует продать «Газпром СПКА» (вместе с Центром управления '
    'полётами) до конца 2026 года не напрямую «Роскосмосу», а структуре '
    '«Новый старт», создаваемой для консолидации спутникостроительных '
    'активов, — «Роскосмос» в этой схеме куратор, не прямой покупатель '
    'доли. Сделка на эту дату ещё не закрыта.'
)


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    vtb_hotels = by_id['c45ad6ae9']
    borets = by_id['c382b7c7d']
    spka = by_id['c07bedf76']

    assert vtb_hotels['date'] == OLD_DATE, 'c45ad6ae9 date уже другая: %r' % (vtb_hotels['date'],)
    assert vtb_hotels.get('status') is None, 'c45ad6ae9 status уже занят: %r' % (vtb_hotels.get('status'),)
    assert borets['date'] == OLD_DATE, 'c382b7c7d date уже другая: %r' % (borets['date'],)
    assert borets.get('status') is None, 'c382b7c7d status уже занят: %r' % (borets.get('status'),)
    assert borets['eco']['context'] == OLD_ECO_CONTEXT_BORETS, \
        'c382b7c7d eco.context уже другой: %r' % (borets['eco']['context'],)
    assert spka['date'] == OLD_DATE, 'c07bedf76 date уже другая: %r' % (spka['date'],)
    assert spka.get('status') is None, 'c07bedf76 status уже занят: %r' % (spka.get('status'),)
    assert spka['eco']['context'] == OLD_ECO_CONTEXT_SPKA, \
        'c07bedf76 eco.context уже другой: %r' % (spka['eco']['context'],)

    print('c45ad6ae9: date %r -> "2025-08-08"; status None -> "Закрыта"' % (OLD_DATE,))
    print('c382b7c7d: date %r -> "2025-03-27"; status None -> "Закрыта"; '
          'eco.context дополнен (апелляция 25.06.2025)' % (OLD_DATE,))
    print('c07bedf76: date %r -> "2025-03-03"; status None -> "Обсуждается"; '
          'eco.context дополнен (продолжение — «Новый старт», не Роскосмос)' % (OLD_DATE,))

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    vtb_hotels['date'] = '2025-08-08'
    vtb_hotels['status'] = 'Закрыта'

    borets['date'] = '2025-03-27'
    borets['status'] = 'Закрыта'
    borets['eco']['context'] = NEW_ECO_CONTEXT_BORETS

    spka['date'] = '2025-03-03'
    spka['status'] = 'Обсуждается'
    spka['eco']['context'] = NEW_ECO_CONTEXT_SPKA

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
