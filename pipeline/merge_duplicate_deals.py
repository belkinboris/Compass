# -*- coding: utf-8 -*-
"""Бэклог E7: две карточки об одной сделке — и роль, перепутанная в соседней.

ЧТО СЛОМАНО. В базе лежали две карточки об одном и том же выходе Volkswagen из
России: «Продажа Volkswagen Group российского бизнеса … компании «Арт-Финанс»
(группа «Авилон»)» (18 мая 2023) и «Продажа российских активов Volkswagen Group
дилерскому холдингу «Авилон» (ООО «Арт-Финанс»)» (22 мая 2023). Одна сумма
(€125 млн), один покупатель, один периметр — разные только даты подписания и
регистрации. Юрист, ищущий эту сделку, находил две записи и не мог понять, чем
они отличаются; счётчики базы считали её дважды.

КАК НАЙДЕНО И ЧТО ПОКАЗАЛО ЧТЕНИЕ. Замер `match.py --measure`: 37 карточек из
1333 находят ЧУЖУЮ карточку базы — это 19 уникальных пар. Прочитаны все 19.
  * НАСТОЯЩИЙ ДУБЛЬ — один (Volkswagen). Его чинит этот скрипт.
  * 18 пар — РАЗНЫЕ сделки, склеенные общими словами. Класс виден невооружённым
    глазом: «иностранец уходит из России» пишется одними и теми же словами —
    «продала российский бизнес/активы менеджменту». Так склеились Whirlpool и
    Arconic, Mondi и Amcor, CNH и Henkel, Viessmann и Qiwi, Faurecia и Knauf,
    O'Key и Roca. Второй такой класс — раунды: «X привлёк $N млн в раунде
    Series …» (BestDoctor и ElectroNeek, hotellab и BestDoctor, Welldone и
    «Перфобур»). Третий — недвижимость: «продал торгово-развлекательный
    комплекс …» (пять пар).

ЧТО ЭТО ЗНАЧИТ ДЛЯ ПРИТОКА (и почему правило не стали ужесточать здесь).
Слабый сигнал «три общих слова заголовка» ошибается не случайно, а системно на
целых классах сделок. Именно поэтому `enrich.py` по такому совпадению в базу не
пишет (прогон 49). Сузить сам сигнал — отдельная задача с замером полноты: STOP
придётся пополнять словами «российск», «активы», «менеджмент», «раунде», а
каждое такое слово снижает и полноту тоже.

ЛОВУШКА, НА КОТОРУЮ ЗДЕСЬ УЖЕ НАСТУПИЛИ. Правило «общее название в кавычках +
одна и та же сумма + 45 дней» кажется признаком дубля, но по базе даёт 5 пар, из
которых верна одна. Причина: название в кавычках — часто не предмет, а
ПРОДАВЕЦ, и банк «Траст», продающий десятки активов, совпадает сам с собой
(«продал пакет акций «РуссНефти» за 1,4 млрд ₽» и «выставил на продажу
земельный актив за 1,4 млрд ₽»). Признак дубля — ДВА общих названия в кавычках
при одной сумме; на нём в базе ровно одна пара, и после этого скрипта — ни
одной. Это закреплено тестом `test_no_duplicate_deal_cards`.

ВТОРОЙ ДЕФЕКТ, НАЙДЕННЫЙ ТЕМ ЖЕ ЧТЕНИЕМ. В карточке «Приобретение ЗАО «Балчуг
Капитал» пакетов акций российских ПАО у Goldman Sachs International» предметом
сделки стоял сам «Балчуг Капитал» — то есть покупатель, а поле покупателя было
пустым. Это седьмая карточка известного класса A21 (первые шесть исправлены в
прогоне 45 скриптом `fix_buyer_in_target.py`); класс, как и было записано,
находится чтением, а не правилом.

ЧТО ОСТАЁТСЯ ОТ УДАЛЁННОЙ КАРТОЧКИ. Её адрес: `merged` в базе хранит пару
«id дубля -> id оставшейся сделки», и `#/deal/<id дубля>` открывает ту сделку,
которая осталась. Иначе ссылка из закладок или из чужого письма молча
показывала бы общую ленту.

ЧТО ПРОВЕРЯЕТСЯ ПЕРЕД ЗАПИСЬЮ. Обе карточки должны быть на месте и в том
состоянии, которое описано в таблице (иначе скрипт падает, а не портит данные);
переносимый факт обязан дословно лежать в тексте карточки-дубля; после слияния
у сделки не должно остаться двух ролей у одной компании, а число карточек
обязано уменьшиться ровно на одну.

Запуск:
    python3 pipeline/merge_duplicate_deals.py            # сухой прогон
    python3 pipeline/merge_duplicate_deals.py --write    # записать
"""
import json
import sys

PATH = 'static/data/deals_promoted.json'

# Пара «оставляем -> удаляем». Оставлена карточка с ВЕРНЫМИ ролями: у неё
# покупатель — «Арт-Финанс», предмет — «Фольксваген Груп Рус». У дубля предметом
# стоял «Авилон», то есть группа покупателя, а покупатель был пуст.
KEEP, DROP = 'gd1130c05', 'ge6588382'

# Факты, которых у остающейся карточки нет, а у дубля есть. Каждый обязан
# дословно лежать в дубле — это проверяется assert'ом ниже.
APPR_WAS = 'Сделка одобрена Правительственной комиссией по контролю за осуществлением иностранных инвестиций.'
APPR_NEW = 'Разрешение правительственной подкомиссии по контролю за иностранными инвестициями датировано 17 апреля 2023 года.'
EXTRA_ADD = ('Закрытию предшествовало судебное противодействие со стороны ГАЗ, который добился '
             'временного ареста активов VW в России по искам на 15,6 млрд и 28,4 млрд руб., '
             'однако суд снял обеспечительные меры.')

# Седьмая карточка класса «предметом стоит покупатель» (см. fix_buyer_in_target.py).
ROLE_FIX = {
    'g81d69138': {'target_to_buyer': 'g7e126b37',
                  'asset': 'миноритарные пакеты акций девяти российских компаний'},
}

# Пары, прочитанные и признанные РАЗНЫМИ сделками. Список нужен, чтобы
# следующий прогон не перечитывал их заново и не «чинил» верные записи.
NOT_DUPLICATES = {
    ('gd82d7839', 'geb1cfe85'): 'BestDoctor и ElectroNeek — разные раунды разных компаний',
    ('g00e9c766', 'gd82d7839'): 'hotellab.io и BestDoctor — разные раунды',
    ('g7623613c', 'gd48766d5'): 'Welldone и «Перфобур» — разные раунды',
    ('g1059432d', 'g5b337455'): 'Whirlpool и Arconic — разные выходы из России',
    ('g3c46e216', 'gb68699cf'): 'Mondi и Amcor — оба продали по три завода упаковки, но это разные сделки',
    ('g09d132ef', 'g7c8f9112'): 'Softline Venture Partners: Workclass и HR Rocket — две инвестиции',
    ('g256dd345', 'g4face480'): '«Таврос» купил птицефабрику, «Черкизово» — «Здоровую ферму»; общее только «Траст»',
    ('g8348fea5', 'g9876feaa'): '«Сибирский Молл» и ТРЦ «Аквилон» — разные объекты',
    ('gb7363fed', 'ge6b63fd9'): 'отель SO и ТЦ «Невский центр» — разные объекты',
    ('g36386bcf', 'gf219222a'): 'раздел «Яндекса» и разделение Group-IB — разные компании',
    ('g531446fe', 'g6f4a071a'): 'CNH Industrial и Henkel — разные выходы',
    ('g4612b667', 'ga13c3ea7'): 'Viterra: терминал в Ростове-на-Дону и 50% ЗТКТ в Тамани — разные активы',
    ('g04efcb3a', 'g0fadc207'): 'Viessmann и Qiwi — разные выходы',
    ('gc660ac38', 'gc96f0c6b'): 'ТРЦ «Саларис» и ТРЦ Columbus — разные объекты',
    ('g1664083c', 'g3e3f233c'): 'ТЦ «Весна» и бизнес-центр на Арбате — разные объекты',
    ('g282be68a', 'g4cac8db4'): 'Faurecia и Knauf — разные выходы',
    ('g31136d69', 'gbb9adb9d'): "O'Key и Roca — разные выходы",
    ('g81d69138', 'gaa82c6f6'): ('«Балчуг Капитал» дважды покупал у Goldman Sachs, но разное: '
                                 'пакеты акций девяти ПАО и 100% ООО «Голдман Сакс Банк»'),
}


def norm(s):
    return ' '.join(str(s or '').split())


def main(write):
    data = json.load(open(PATH, encoding='utf-8'))
    deals, comps = data['deals'], data['companies']
    by_id = {d['id']: d for d in deals}

    keep, drop = by_id.get(KEEP), by_id.get(DROP)
    assert keep and drop, 'карточек пары нет в базе — состояние изменилось, скрипт остановлен'
    assert norm(keep.get('sum')) == norm(drop.get('sum')) == '125 млн €', \
        'суммы пары изменились — это уже не та пара, которую читали'
    assert norm((keep.get('law') or {}).get('appr')) == APPR_WAS, 'согласование уже правили'
    # Точка в конце — не часть факта: в сплошном тексте дубля та же фраза стоит
    # перед точкой с запятой («…17 апреля 2023 года; цена сделки…»), поэтому
    # сравнение со сплошным текстом ведётся без завершающей точки.
    assert APPR_NEW == norm((drop.get('law') or {}).get('appr')), \
        'согласование дубля изменилось — переносить нечего'
    assert APPR_NEW.rstrip('.') in norm(drop.get('extra')), \
        'дата разрешения не лежит в тексте дубля дословно'
    assert EXTRA_ADD in norm(drop.get('extra')), 'факт о ГАЗ не лежит в дубле дословно'
    assert EXTRA_ADD not in norm(keep.get('extra')), 'факт о ГАЗ уже перенесён'

    keep_urls = {str(s[1]) for s in (keep.get('src') or []) if len(s) > 1}
    new_src = [s for s in (drop.get('src') or []) if len(s) > 1 and str(s[1]) not in keep_urls]

    print('СЛИЯНИЕ ДУБЛЯ')
    print('  оставляем %s  %s' % (KEEP, str(keep['title'])[:80]))
    print('  удаляем   %s  %s' % (DROP, str(drop['title'])[:80]))
    print('  переносим источников: %d' % len(new_src))
    for label, url in new_src:
        print('      %-28s %s' % (str(label)[:28], url))
    print('  согласования: дата разрешения (17 апреля 2023) — её у остающейся карточки нет')
    print('  дополнительно: арест активов по искам ГАЗ — факта у остающейся карточки нет')

    fixed = []
    for deal_id, plan in ROLE_FIX.items():
        card = by_id.get(deal_id)
        assert card, '%s: карточки нет' % deal_id
        assert card.get('target') == plan['target_to_buyer'], \
            '%s: предметом стоит уже не %s' % (deal_id, plan['target_to_buyer'])
        assert not card.get('buyer') and not card.get('buyer_name'), \
            '%s: покупатель уже заполнен' % deal_id
        text = json.dumps(card, ensure_ascii=False)
        assert plan['asset'] in text, '%s: названия предмета нет в тексте карточки' % deal_id
        assert plan['target_to_buyer'] != card.get('seller_id'), \
            '%s: одна компания оказалась бы в двух ролях' % deal_id
        fixed.append((deal_id, card, plan))

    print('\nРОЛИ: предметом стоял покупатель')
    for deal_id, card, plan in fixed:
        print('  %s  %s' % (deal_id, str(card['title'])[:80]))
        print('      покупатель <- %s (%s); предмет текстом: %s'
              % (plan['target_to_buyer'], comps[plan['target_to_buyer']]['name'], plan['asset']))

    print('\nПрочитано пар: %d. Дубль: 1. Разные сделки: %d.'
          % (len(NOT_DUPLICATES) + 1, len(NOT_DUPLICATES)))

    if not write:
        print('\nСухой прогон. Запись — с ключом --write.')
        return

    keep.setdefault('src', []).extend(new_src)
    keep['law']['appr'] = APPR_NEW
    keep['extra'] = norm(keep.get('extra')) + ' ' + EXTRA_ADD
    was = len(deals)
    data['deals'] = [d for d in deals if d['id'] != DROP]
    assert len(data['deals']) == was - 1, 'удалилась не одна карточка'
    # Ссылка на дубль могла остаться в закладках или в чужом письме. Молча
    # показывать вместо неё общую ленту нечестно, поэтому адрес слитой карточки
    # ведёт на оставшуюся сделку: интерфейс читает эту карту (`MERGED`).
    data.setdefault('merged', {})[DROP] = KEEP

    for deal_id, card, plan in fixed:
        card['buyer'] = plan['target_to_buyer']
        card['target'] = None
        card['asset'] = plan['asset']

    with open(PATH, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('\nЗаписано. Карточек в базе: %d (было %d).' % (len(data['deals']), was))


if __name__ == '__main__':
    main('--write' in sys.argv)
