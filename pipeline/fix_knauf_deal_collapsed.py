# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g4cac8db4 (Knauf продает российский бизнес по производству
стройматериалов местному менеджменту) — статус «Обсуждается» держался
два с половиной года, хотя сама сделка, о которой написана карточка,
СОРВАЛАСЬ. Проверено лично прямым WebFetch двух источников.

`status` (изменено: «Обсуждается» → «Не состоялась»). Дословно
(Коммерсантъ, 08.10.2025): «Производителя стройматериалов Knauf не
захотели покупать. О срыве сделки сообщили в пресс-службе компании» —
это прямое заявление самой компании о провале, а не слух или молчание
(в отличие от уже описанных в CLAUDE.md случаев БКС/«Форштадт» и
«Мать и дитя»/«Инвитро», где сторона либо не подтверждала, либо
отрицала сам факт переговоров — здесь компания прямо подтверждает,
что переговоры БЫЛИ и провалились). Имя покупателя и цену компания
решила не раскрывать даже постфактум.

`law.appr` (исправлено — было «Он рассчитывает, что правкомиссия
одобрит сделку в этом месяце», прогноз двухлетней давности, который
не сбылся). Дословно (Expert.ru, 08.10.2025): «Интенсивные обсуждения
последних месяцев... не привели к достижению соглашения. К сожалению,
компания, участвовавшая в переговорах, прекратила переговоры» —
покупатель вышел из переговоров, а не Knauf отказался продавать.

`eco.context` (заполнено, было «—»). Дословно (Expert.ru): бизнес
«работает под управлением местного руководства отдельно от других
структур группы»; «группа Knauf не получает прибыль от своего бизнеса
в РФ». Опцион на обратный выкуп в течение двух лет (уже в `law.terms`)
не был использован — использовать было нечего, сама продажа не
состоялась.

НЕ ВКЛЮЧЕНО: версия о связи срыва с расследованиями Der Spiegel/
Danwatch о поставках Knauf-Rotband для военных объектов (май 2025) —
источник (theins.press) не является предметом сделки M&A и не
подтверждён нейтральной деловой прессой напрямую как причина срыва
именно ЭТИХ переговоров (Коммерсантъ и Expert.ru называют цену и
техническую несовместимость софта как более вероятные причины); имя
покупателя/менеджмента — по-прежнему нигде не раскрыто.

Запуск: python3 pipeline/fix_knauf_deal_collapsed.py
        python3 pipeline/fix_knauf_deal_collapsed.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g4cac8db4'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Не состоялась'

OLD_APPR = 'Он рассчитывает, что правкомиссия одобрит сделку в этом месяце.'
NEW_APPR = (
    'В марте 2024 года руководитель рассчитывал на одобрение '
    'правкомиссии «в этом месяце», но соглашение не было достигнуто: '
    '8 октября 2025 года Knauf сообщила, что покупатель вышел из '
    'переговоров.'
)

OLD_CONTEXT = '—'
NEW_CONTEXT = (
    'Российский бизнес работает «под управлением местного руководства '
    'отдельно от других структур группы», группа Knauf «не получает '
    'прибыль от своего бизнеса в РФ» (Expert.ru). Опцион на обратный '
    'выкуп в течение двух лет (см. «Условия») не был использован — '
    'сама продажа не состоялась.'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8100266'],
    ['Expert.ru', 'https://expert.ru/news/knauf-ne-smogla-prodat-svoy-biznes-v-rossii/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS, deal['status']
    assert deal['law']['appr'] == OLD_APPR, deal['law']['appr']
    assert deal['eco']['context'] == OLD_CONTEXT, deal['eco']['context']
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== status: было / станет ===')
    print(OLD_STATUS, '->', NEW_STATUS)
    print('\n=== law.appr: станет ===')
    print(NEW_APPR)
    print('\n=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['status'] = NEW_STATUS
        deal['law']['appr'] = NEW_APPR
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
