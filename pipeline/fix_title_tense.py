"""Заголовок карточки противоречит статусу сделки (плюс один заголовок не о сделке).

ЧТО СЛОМАНО. Заголовки собраны из новостных: «X5 Group покупает…», «Selectel
купила…». Само по себе разное время — не ошибка, если оно совпадает со
статусом: сделка идет — настоящее, сделка закрыта — прошедшее. Но у части
карточек время и статус противоречат друг другу: «покупает» при статусе
«Закрыта» и «купила» при статусе «Обсуждается». Читатель верит заголовку, а
плашка статуса говорит обратное.

ЗАМЕР (прогон 35). Из 1333 карточек время глагола видно у 1006: прошедшее у
764, настоящее у 172, остальные — назывные («Продажа…», «IPO…»). Соответствие
статусу:
    741  прошедшее · Закрыта      — верно
    106  настоящее · Обсуждается  — верно
     46  настоящее · Закрыта      — ПРОТИВОРЕЧИЕ
     24  прошедшее · Обсуждается  — ПРОТИВОРЕЧИЕ
Итого 70 карточек, каждая прочитана.

КУДА ПРАВИМ. В обе стороны правим ЗАГОЛОВОК, а не статус: статус выставлялся по
тексту карточки и подтверждается им («сделка закрыта 29 января 2024 года»,
«подано ходатайство в ФАС»), а заголовок — это заголовок новости на момент
объявления.

ГРАНИЦА ПРАВКИ. Меняется ровно одно слово — глагол. Скрипт разбивает старый и
новый заголовок на слова и падает, если отличается что-то кроме одной позиции,
или если новое слово не из таблицы форм. Так правка не может незаметно
поменять сумму, долю или название стороны.

Запуск:
    python3 pipeline/fix_title_tense.py            # сухой прогон
    python3 pipeline/fix_title_tense.py --write    # записать
"""
