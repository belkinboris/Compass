# Заголовок не о сделке, а о том, кто ее сопровождал: «ККМП консультировала
# группу «Казахмыс» по сделке предоплатного финансирования…». Так выглядел бы
# заголовок пресс-релиза юрфирмы, но карточка — о сделке, а консультант у нее
# уже записан в «Юридических консультантах». Новый заголовок собран из слов
# самой карточки: поле «Предмет / доля» говорит «предоплатное финансирование
# (prepayment facility) на сумму до USD 1,5 млрд, предоставленное Mercuria
# Energy Group группе «Казахмыс»». Скрипт проверяет, что каждое значимое слово
# нового заголовка встречается в тексте этой карточки.
TITLE_REWRITE = {
    'g15bee2cf': 'Предоплатное финансирование Mercuria Energy Group группе «Казахмыс» '
                 'на $1,5 млрд',
}

PRESENT = re.compile(
    r'\b(покупает|покупают|приобретает|приобретают|продает|продает|продают|'
    r'инвестирует|привлекает|привлекают|выкупает|получает|консолидирует)\b', re.I)
PAST = re.compile(
    r'\b(купил|купила|купило|купили|приобрел|приобрел|приобрела|приобрело|приобрели|'
    r'продал|продала|продало|продали|инвестировал|инвестировала|инвестировало|'
    r'инвестировали|привлек|привлек|привлекла|привлекли|выкупил|выкупила|выкупили|'
    r'получил|получила|получили|консолидировал|консолидировала)\b', re.I)


def norm(s):
    return re.sub(r'\s+', ' ', str(s or '')).strip()


def swap(title, rx, new_word):
    """Заменяем ровно одно слово — первое совпадение глагола."""
    return rx.sub(lambda m: new_word, title, count=1)


def one_word_changed(old, new):
    ow, nw = old.split(' '), new.split(' ')
    if len(ow) != len(nw):
        return None
    diff = [(a, b) for a, b in zip(ow, nw) if a != b]
    return diff[0] if len(diff) == 1 else None


def main(write):
    data = json.load(open(PATH, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}

    plan, done = [], []
    for table, rx, direction in ((TO_PAST, PRESENT, 'наст.->прош.'),
                                 (TO_PRESENT, PAST, 'прош.->наст.')):
        for deal_id, word in table.items():
            deal = by_id.get(deal_id)
            assert deal is not None, 'нет сделки %s' % deal_id
            old = norm(deal['title'])
            if direction == 'наст.->прош.':
                assert norm(deal.get('status')) == 'Закрыта', \
                    '%s: статус уже не «Закрыта»' % deal_id
            else:
                assert norm(deal.get('status')) != 'Закрыта', \
                    '%s: статус уже «Закрыта» — правка не нужна' % deal_id
            new = swap(old, rx, word)
            if new == old:
                done.append(deal_id)   # уже применено
                continue
            changed = one_word_changed(old, new)
            assert changed, '%s: изменилось не одно слово' % deal_id
            was, now = changed
            key = was.lower().strip('.,;:')
            if direction == 'наст.->прош.':
                assert now.lower() in FORMS.get(key, set()), \
                    '%s: %r -> %r нет в таблице форм' % (deal_id, was, now)
            else:
                assert was.lower() in FORMS.get(now.lower(), set()), \
                    '%s: %r -> %r нет в таблице форм' % (deal_id, was, now)
            plan.append((deal_id, direction, old, new, deal))

    for deal_id, title in TITLE_REWRITE.items():
        deal = by_id.get(deal_id)
        assert deal is not None, 'нет сделки %s' % deal_id
        old = norm(deal['title'])
        if old == title:
            done.append(deal_id)
            continue
        pool = ' '.join([old, norm(deal.get('extra')), norm((deal.get('eco') or {}).get('share')),
                         norm(deal.get('sum'))]).lower()
        for word in re.findall(r'[\w$,.]{4,}', title.lower()):
            assert word.strip('«»,.') in pool, \
                '%s: слова %r нет в тексте карточки' % (deal_id, word)
        plan.append((deal_id, 'заголовок не о сделке', old, title, deal))

    total = len(TO_PAST) + len(TO_PRESENT) + len(TITLE_REWRITE)
    assert len(plan) + len(done) == total, \
        'часть заголовков изменилась вне скрипта (%d + %d ≠ %d)' % (len(plan), len(done), total)
    if not plan:
        print('Уже применено: все %d заголовков согласованы со статусом.' % total)
        return
    if done:
        print('Уже было применено раньше: %d' % len(done))

    print('Заголовков к правке: %d' % len(plan))
    for deal_id, direction, old, new, _ in plan:
        print('  %s [%s]\n     было:  %s\n     стало: %s' % (deal_id, direction, old[:95], new[:95]))

    if not write:
        print('\nСухой прогон. Запись — с ключом --write.')
        return
    for _, _, _, new, deal in plan:
        deal['title'] = new
    with open(PATH, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('\nЗаписано: %d заголовков.' % len(plan))


if __name__ == '__main__':
    main('--write' in sys.argv)
