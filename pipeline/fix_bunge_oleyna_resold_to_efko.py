import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g80138f49'

OLD_EXTRA = (
    'Агротрейдер Bunge продал бизнес в России и бренд подсолнечного '
    'масла «Олейна» Карену Ванецяну за «полцены» менее года назад до '
    'момента публикации.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' В 2025 году Ванецян и структуры Exoil Group полностью вышли из '
    'этого актива: в апреле «Эфко продукты питания» получила 31,4% в '
    'ООО «Агроинвест» (владеет заводом и брендами «Олейна»/Ideal), а к '
    '27 августа 2025 года по данным ЕГРЮЛ довела долю до 100%.'
)

NEW_SRC = [
    ['Agroinvestor.ru', 'https://www.agroinvestor.ru/companies/news/39902-novyy-vladelets-oleyny-rasskazal-o-podrobnostyakh-sdelki-s-bunge/'],
    ['Ведомости', 'https://www.vedomosti.ru/business/articles/2025/04/16/1104612-gruppa-efko-stala-sovladeltsem-proizvoditelya-masla-oleina'],
    ['Интерфакс', 'https://www.interfax.ru/business/1044618'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
