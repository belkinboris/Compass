# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка `gb0c3ddbf`
(«Группа «Черкизово» приобрела 15 тыс. га сельхозземли в Белгородской
области у агрохолдинга «Бенталь»», закрыта, 2023) — дочитывание не
подтвердило сумму сделки, стоявшую в карточке, и нашло, кто именно
продавец.

Проверено лично прямым WebFetch (kommersant.ru/doc/6311121):
- «Продавцом выступило ООО «Бенталь»», «учредитель ООО «Бенталь» (с
  августа 2022 года) — Виталий Лушников».
- «ООО «Бенталь»… продал группе 11 тыс. га, находившиеся в собственности,
  и уступил права аренды еще на 4 тыс. га» (уже верно стоит в `extra`).
- Сумма сделки НИГДЕ не подтверждена: статья прямо говорит, что компания
  её не раскрыла, а называет только НЕЗАВИСИМУЮ ЭКСПЕРТНУЮ ОЦЕНКУ —
  «предлагаемая цена гектара сельхозземли в Белгородской области сейчас
  доходит до 170 тыс. руб.», «в среднем в Черноземье цена предложения
  составляет от 60 тыс. руб. за гектар» — отсюда вывод самой статьи
  (через саб-агента, независимо подтверждено тем же прочтением): «только
  приобретенная в собственность земля могла стоить «Черкизову» от 650 млн
  руб. и выше». Это оценка ТОЛЬКО за 11 тыс. га в собственности — БЕЗ
  учёта прав аренды на 4 тыс. га и двух растениеводческих баз, то есть
  заведомо неполная величина. Стоявший в карточке диапазон «1,3–1,5 млрд
  ₽» этой статьёй не подтверждается и не встретился ни в одном из
  проверенных источников (Коммерсантъ, Агроинвестор, agroinvestor.ru) —
  источник этой цифры установить не удалось (похоже на неверный разбор на
  этапе автоматического импорта). Тот же класс ошибки, что уже описан в
  CLAUDE.md («Число может быть верным фактом и совсем не той величиной»):
  сумма заменяется на честное «Не раскрыта», оценка — на `eco.val` с явной
  оговоркой о её неполноте.
- Учредитель продавца, Виталий Лушников, — «бывший топ-менеджер «Белой
  птицы»» (обанкротившийся агрохолдинг) — фон, помогающий понять, кто
  продавец.
- По данным audit-it.ru (через саб-агента, WebSearch-сводка): в 2024 году
  контроль над ООО «Бенталь» перешёл к ООО «Овербест Рус» — Лушников
  вышел из состава учредителей.

НЕ ВНЕСЕНО: (1) официальная реакция самого «Бенталь» на сделку — не
найдена ни у одного источника; (2) согласование ФАС/правкомиссии — не
упоминается нигде; (3) юридический/финансовый консультант — не найден;
(4) структура нового владельца «Бенталь» после 2024 года (в т.ч.
предполагаемая гонконгская Overbest Limited) — источник (bel.ru) не
удалось прочитать напрямую (отдал заглушку вместо текста), факт остался
непроверенным цитатой и не вносится.

Запуск: python3 pipeline/fix_cherkizovo_bental_sum_and_seller.py
        python3 pipeline/fix_cherkizovo_bental_sum_and_seller.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gb0c3ddbf'

OLD_SELLER = None
NEW_SELLER = 'ООО «Бенталь»'

OLD_SUM = '1,3–1,5 млрд ₽'
NEW_SUM = 'Не раскрыта'

OLD_ECO_SUM = '1,3–1,5 млрд ₽'
NEW_ECO_SUM = 'Не раскрыта'

OLD_ECO_VAL = '—'
NEW_ECO_VAL = (
    'Компания сумму не раскрыла. По независимой оценке, исходя из '
    'рыночных цен на землю в Белгородской области (от 60 до 170 тыс. ₽ за '
    'гектар), только 11 тыс. га земли в собственности могли стоить от 650 '
    'млн ₽ и выше — без учёта прав аренды на ещё 4 тыс. га и двух '
    'растениеводческих баз.'
)

OLD_ECO_CONTEXT = '—'
NEW_ECO_CONTEXT = (
    'Учредитель продавца, ООО «Бенталь», — Виталий Лушников, бывший '
    'топ-менеджер обанкротившегося агрохолдинга «Белая птица». В 2024 '
    'году контроль над «Бенталь» перешёл к ООО «Овербест Рус», Лушников '
    'вышел из состава учредителей.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal.get('seller') == OLD_SELLER
    assert deal['sum'] == OLD_SUM
    assert deal['eco']['sum'] == OLD_ECO_SUM
    assert deal['eco']['val'] == OLD_ECO_VAL
    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    print('=== seller: станет ===')
    print(NEW_SELLER)
    print('\n=== sum: станет ===')
    print(NEW_SUM)
    print('\n=== eco.sum: станет ===')
    print(NEW_ECO_SUM)
    print('\n=== eco.val: станет ===')
    print(NEW_ECO_VAL)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)

    if write:
        deal['seller'] = NEW_SELLER
        deal['sum'] = NEW_SUM
        deal['eco']['sum'] = NEW_ECO_SUM
        deal['eco']['val'] = NEW_ECO_VAL
        deal['eco']['context'] = NEW_ECO_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
