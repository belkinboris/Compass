# -*- coding: utf-8 -*-
"""Продолжение fix_mini_ranking_dates_batch1/2/3.py: две карточки того же
класса дефекта — дата публикации рэнкинга «Ъ — Сделки года»
(«2025-09-30») вместо даты сделки.

`cbb6ba4c9` (Альфа-банк вошёл в капитал АО «Пушкинский»/«КАРО ФИЛЬМ
Севастопольский», группа «Каро Фильм») — точная дата НАШЛАСЬ: личный
WebFetch (realty.ria.ru/20250418/alfa-bank-2011968109.html, публикация
18.04.2025, 09:15) подтверждает материал именно об этой сделке («Альфа-
банк вошел в капитал АО "Пушкинский" и ООО "Каро Фильм Севастопольский"»)
— перенос дня/месяца внутри уже известного года (2025 -> 2025).

`c689eefe9` («Т-Девелопмент»/Т-Банк купил комплекс гостиницы «Турист») —
ТОЧНЫЙ день по-прежнему не найден (это уже отмечено в
fix_mini_ranking_dates_batch1.py как источник, называющий только период):
личный WebFetch (kommersant.ru/doc/7940155, 03.08.2025) подтверждает
формулировку «В июне—июле 2025 года эти юрлица… перешли ООО
«Т-Девелопмент»» — источник прямо говорит, что известен только диапазон
из ДВУХ месяцев, а не один месяц или день. Взять один из двух месяцев на
угад значило бы выдумать точность, которой нет источник не даёт (родня
правила «дата-заглушка хуже пустой даты», но здесь неизвестен даже
единственный месяц — сильнее случая Осново/Свиблово, где был известен
хотя бы месяц). Поэтому дата сведена к ОДНОМУ ГОДУ («2025», без месяца и
дня — тот же приём, что и в `fix_placeholder_dates.py`), а диапазон
месяцев дописан текстом в `eco.context`.

Запуск:
    python3 pipeline/fix_mini_ranking_dates_batch4.py            # сухой прогон
    python3 pipeline/fix_mini_ranking_dates_batch4.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

DATE_FIXES = [
    dict(id='cbb6ba4c9', old='2025-09-30', new='2025-04-18',
         quote='РИА Недвижимость, 18.04.2025, 09:15: «Альфа-банк вошел '
               'в капитал АО "Пушкинский" и ООО "Каро Фильм '
               'Севастопольский" с целью запуска некоммерческого '
               'культурного проекта»'),
    dict(id='c689eefe9', old='2025-09-30', new='2025',
         quote='Коммерсантъ, 03.08.2025: «В июне—июле 2025 года эти '
               'юрлица… перешли ООО «Т-Девелопмент»» — точный месяц не '
               'назван, известен только двухмесячный диапазон'),
]

CONTEXT_CARD_ID = 'c689eefe9'
OLD_CONTEXT = (
    'Гостиницу «Турист» на Сельскохозяйственной улице на севере Москвы '
    'структура Т-Банка купила под общежитие. По оценке экспертов, '
    'переоборудование этой недвижимости может стоить от 1 до 3 '
    'миллиардов рублей.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' Точная дата закрытия не названа: Коммерсантъ пишет, что переход '
    'юрлиц к «Т-Девелопменту» произошёл «в июне—июле 2025 года».'
)


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}

    for fx in DATE_FIXES:
        deal = by_id.get(fx['id'])
        assert deal is not None, 'нет сделки %s' % fx['id']
        assert deal.get('date') == fx['old'], \
            '%s: дата уже другая: %r, ожидали %r' % (
                fx['id'], deal.get('date'), fx['old'])
        print('%s: date %r -> %r' % (fx['id'], fx['old'], fx['new']))
        print('  цитата: %r' % fx['quote'])

    ctx_card = by_id[CONTEXT_CARD_ID]
    assert ctx_card['eco']['context'] == OLD_CONTEXT, \
        'eco.context уже другой: %r' % (ctx_card['eco']['context'],)
    print('%s: eco.context — добавляется пояснение о диапазоне месяцев' %
          CONTEXT_CARD_ID)

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    for fx in DATE_FIXES:
        by_id[fx['id']]['date'] = fx['new']
        assert by_id[fx['id']]['date'] == fx['new'], 'дата не записалась'

    ctx_card['eco']['context'] = NEW_CONTEXT

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
