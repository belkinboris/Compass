# -*- coding: utf-8 -*-
"""Приток, 16:20 МСК 28 сентября 2026 — указ о передаче российских активов
Metro Cash & Carry во временное управление АО «УК Торг РУС» (РИА Новости,
URA.RU, оба — вечер 28 сентября). Тот же класс события, что уже есть в
`pending.json` карточкой `g64462179` (указ от 17 сентября про Nestlé, FM
Logistic, «Ашан» и «Лемана ПРО» — управляющий там другой, «Л.Е.В.
Менеджмент»), но ПРОМОУТ ОШИБОЧНО СОЧЁЛ СЕГОДНЯШНИЙ УКАЗ ДУБЛЕМ ТОГО (общие
слова заголовка «активы»/«передал»/«временное»/«управление» — совпадение
формы, не содержания): другой управляющий, другая дата указа, другая
компания. Без вмешательства настоящее отдельное событие тихо пропало бы
дубль-фильтром, не дойдя даже до очереди сомнительного сырья.

Саб-агент искал подробности — источники пока предельно тонкие: ни номера
указа, ни юрлица Metro в России, ни данных о «УК Торг РУС» (поиск по ЕГРЮЛ-
реестрам не нашёл ни одной подходящей записи) ни один найденный источник не
называет. Карточка сделана по тому же принципу, что и указ про Nestlé
(`kind='custody'`, без seller/buyer_name) — только с честно пустыми полями
там, где источники действительно молчат, а не с придуманными подробностями.

Запуск: python3 pipeline/fix_add_metro_cash_carry_custody_card.py [--write]
"""
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'ingest'))

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

NEW_ID = 'ga142d8e0'


def main(write=False):
    import promote

    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    ids = {c['id'] for c in data['deals']}
    assert NEW_ID not in ids

    draft = {
        'date': '2026-09-28',
        'title': 'Активы Metro Cash & Carry в России переданы во временное управление «УК Торг РУС»',
        'ind': 'Ритейл',
        'type': 'M&A',
        'status': 'Закрыта',
        'asset': 'российские активы сети Metro Cash & Carry',
        'src': [['РИА Новости', 'https://ria.ru/20260928/metro--2120739862.html'],
                ['URA.RU', 'https://ura.news/news/1053131533']],
        'events': [
            {'kind': 'closed', 'date': '2026-09-28', 'title': 'Указ подписан',
             'note': 'Активы немецкой торговой сети Metro в России переданы во временное '
                     'управление АО «УК Торг РУС» — указ президента.',
             'source': ['РИА Новости', 'https://ria.ru/20260928/metro--2120739862.html']},
        ],
    }
    card = promote.to_card(draft, NEW_ID)
    card['kind'] = 'custody'
    card['law']['struct'] = (
        'Президент России передал во временное управление АО «УК Торг '
        'РУС» российские активы немецкой торговой сети Metro Cash & '
        'Carry. Ни номер и дату указа, ни то, какие именно юрлица он '
        'затрагивает, источники на момент записи не называют — только '
        'сам факт передачи.'
    )
    card['eco']['context'] = (
        'Источники предельно короткие («молния», без подробностей). Кто '
        'стоит за АО «УК Торг РУС», источники не говорят; поиск по '
        'открытым реестрам (СПАРК, Контур.Фокус) не нашёл ни одной '
        'подходящей записи с этим названием — возможно, недавно '
        'созданное юрлицо, но это предположение, не факт. Похожий указ '
        '17 сентября 2026 года передал во временное управление другой '
        'структуре («Л.Е.В. Менеджмент») активы Nestlé, FM Logistic, '
        '«Ашана» и «Леманы ПРО» — это отдельное решение, не то же самое.'
    )
    card['added'] = '2026-09-28'

    data['deals'].append(card)
    print('Добавлена карточка %s: %s' % (NEW_ID, card['title']))

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
            f.write('\n')
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
