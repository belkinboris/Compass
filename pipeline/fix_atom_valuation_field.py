# -*- coding: utf-8 -*-
"""ПСБ/«Атом» (`gcaa03820`): подразумеваемая оценка всего бизнеса «Камы»
(58,9 млрд ₽) была вписана третьим предложением в `law.struct` — а это
поле на экране подписано «Структура», не «Оценка и дисконт». Тот же
класс промаха, что аудит нашёл у М.видео днём раньше (`pipeline/
fix_mvideo_control_denial_field.py`) — дословно, релевантно, но не в
своей полке; сработал ровно вопросник «Шаг 0» из REVISION_BRIEF.md
(«каждое заполненное поле отвечает подписи на экране, а не имени поля»),
добавленный по итогам того самого аудита.

Правильная полка для оценки — `eco.val` («Оценка и дисконт»), но она уже
занята комментарием аналитика Беспалова про риск ликвидности при запуске
продаж — из другого источника, дословно смешать в одну цитату для
`review.py` нельзя. Обе мысли ложатся на одну и ту же тему (что означает
допэмиссия для стоимости бизнеса), поэтому объединяем вторым абзацем
внутри `eco.val`, а `law.struct` возвращаем к двум предложениям о
механике сделки (cash-in доп-эмиссия).

Запуск: python3 pipeline/fix_atom_valuation_field.py           # проверка
        python3 pipeline/fix_atom_valuation_field.py --write   # запись
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gcaa03820'

OLD_STRUCT = (
    'ПСБ приобрел 16,98% акций производителя электромобилей «Атом» АО '
    '«Кама» за 9 999 613 000 руб., сообщили в банке. Директор '
    'департамента инвестиционных и сложных финансовых сделок ПСБ '
    'Никита Душкин уточнил «Ъ», что пакет выкуплен в рамках '
    'дополнительной эмиссии за денежные средства. Таким образом, весь '
    'бизнес «Камы» в рамках сделки мог оцениваться в 58,9 млрд руб.')
NEW_STRUCT = (
    'ПСБ приобрел 16,98% акций производителя электромобилей «Атом» АО '
    '«Кама» за 9 999 613 000 руб., сообщили в банке. Директор '
    'департамента инвестиционных и сложных финансовых сделок ПСБ '
    'Никита Душкин уточнил «Ъ», что пакет выкуплен в рамках '
    'дополнительной эмиссии за денежные средства.')

OLD_VAL = (
    '«Атом» только запускает продажи, поэтому на начальном этапе '
    'поступление денежных средств от реализации автомобилей может '
    'оказаться ограниченным, отмечает аналитик «Эйлер Аналитические '
    'технологии» Владимир Беспалов. Продажа пакета акций, считает '
    'эксперт, позволит финансировать деятельность за счет '
    'акционерного капитала без увеличения долговой нагрузки, что '
    'должно способствовать снижению кредитных рисков. Кроме того, '
    'привлечение системно значимого банка в качестве партнера должно '
    'положительно сказаться и на реализации проекта в дальнейшем, '
    'добавляет он.')
NEW_VAL = OLD_VAL + (
    ' Таким образом, весь бизнес «Камы» в рамках сделки мог '
    'оцениваться в 58,9 млрд руб.')


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    card = next((c for c in data['deals'] if c['id'] == CARD_ID), None)
    assert card is not None, '%r не найдена в базе' % CARD_ID
    assert card['law'].get('struct') == OLD_STRUCT, (
        'law.struct изменился с ожидаемого: %r' % card['law'].get('struct'))
    assert card['eco'].get('val') == OLD_VAL, (
        'eco.val изменился с ожидаемого: %r' % card['eco'].get('val'))
    print('ПРАВИМ  %s: law.struct — снимаем оценку (не «Структура»)' % CARD_ID)
    print('ПРАВИМ  %s: eco.val — добавляем оценку вторым предложением' % CARD_ID)
    if write:
        card['law']['struct'] = NEW_STRUCT
        card['eco']['val'] = NEW_VAL
        json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
        print('ЗАПИСАНО')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
