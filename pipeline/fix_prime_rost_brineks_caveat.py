# -*- coding: utf-8 -*-
"""Заметка 503 (консоль, 4 сентября 2026): «Тот же подход с "обсуждается"
и отметкой про больше 2х лет, как выше делали», отвечая на карточку
`gd3f012e4» (АО «Прайм рост»/ГК «БРИНЭКС»).

Тот же текст-оговорка, что уже добавлен `g6ad6fe69`/`gc64703e2` этим
прогоном (заметки 474/479) — редакционная синтеза, не цитата источника,
поэтому одноразовый скрипт, а не review.py.

Запуск: python3 pipeline/fix_prime_rost_brineks_caveat.py [--write]
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gd3f012e4'
OLD_EXTRA = (
    'Продавцы — Ренат и Рустем Бадретдиновы, у каждого по 50% в ООО ГК '
    '«БРИНЭКС». Покупатель — АО «Прайм рост», созданное в конце 2023 '
    'года; его конечный бенефициар неизвестен. Ни подтверждения, ни '
    'опровержения сделки публично так и не появилось. При этом с 4 '
    'февраля 2026 года пост гендиректора «Бринэкса» занял один из '
    'совладельцев, сменив наёмного управляющего, а с марта 2026 года '
    'гендиректором ключевого юрлица сети «Колеса Даром» стал второй '
    'совладелец: оба вернулись к операционному руководству спустя два '
    'года после объявленной продажи 100% бизнеса. Выручка сети за 2024 '
    'год выросла на 20%, до 36,8 млрд ₽.'
)
CAVEAT = (' Обсуждение тянется больше двух лет без единого подтверждения '
          '— есть вероятность, что сделка не состоялась.')


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {c['id']: c for c in data['deals']}
    card = by_id[CARD_ID]
    assert card['extra'] == OLD_EXTRA, card['extra']
    card['extra'] = OLD_EXTRA + CAVEAT
    print(f'{CARD_ID}.extra: добавлена оговорка про 2+ года')

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
            f.write('\n')
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
