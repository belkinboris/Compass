# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g50571ec8
(Росхим приостановил покупку Камтэкс-Химпрома) — статус «Обсуждается»
держится с сентября 2024 года; проверено, не возобновились ли
переговоры, и обновлены показатели самой компании.

Судьба сделки — проверено лично: ни один материал позже 24 сентября
2024 года о самой сделке (возобновление, срыв, новый покупатель) не
найден. `status` НЕ меняется — тишина не равна ни возобновлению, ни
срыву (тот же класс осторожности, что уже применён к другим спорным
статусам в базе).

Финансы компании за 2024-2025 годы — проверено лично прямым WebFetch:
за 2024 год «выручка предприятия выросла с 5,6 млрд руб. до 6 млрд
руб.», «чистая прибыль общества в 2024 году составила 503,5 млн руб.»
(Коммерсантъ, kommersant.ru/doc/7624523) — компания продолжила расти
самостоятельно уже ПОСЛЕ приостановки сделки. За 2025 год —
разворот: «Выручка АО за год сократилась на 20% с 6 млрд руб. — до 4,9
млрд руб.» и «АО получило чистый убыток по РСБУ в размере 461,5 млн
руб.» (Коммерсантъ, kommersant.ru/doc/8604637), причина — «отсутствие
поставок сырья (ортоксилола) для производства готовой продукции в
четвертом квартале 2025 года», что, в свою очередь, связано с
«дефицитом нефтеперерабатывающих мощностей... следствием внеплановых
остановок после падения на заводы обломков БПЛА» — то есть убыток НЕ
связан со сделкой/Росхимом, а с внешним сбоем поставок сырья.

НЕ ВКЛЮЧЕНО: вложения в модернизацию оборудования (о которой шла речь
как о причине паузы) — прямых подтверждений не нашлось; продажа заводом
непрофильного санатория-профилактория (42 млн ₽, ООО СЗ
«Петрокоминвест») — не относится к предмету этой сделки.

Запуск: python3 pipeline/fix_roskhim_kamteks_khimprom_postpause_fin.py
        python3 pipeline/fix_roskhim_kamteks_khimprom_postpause_fin.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g50571ec8'

OLD_TARGET_FIN = (
    'Чистая прибыль общества в 2023 году составила 690,7 млн руб., '
    'выручка — 5,5 млрд руб.'
)
NEW_TARGET_FIN = OLD_TARGET_FIN + (
    ' В 2024 году выручка выросла до 6 млрд руб., чистая прибыль '
    'составила 503,5 млн руб. В 2025 году — разворот: выручка '
    'сократилась на 20% до 4,9 млрд руб., компания получила чистый '
    'убыток 461,5 млн руб. (Коммерсантъ).'
)

OLD_EXTRA = (
    'Сделка по приобретению 100% акционерного капитала АО «Камтэкс-'
    'Химпром» находится на паузе. Причина приостановки: производственное '
    'оборудование устаревшее (установлено в 1980-х годах, последняя '
    'реконструкция в начале 1990-х), требуются существенные инвестиции '
    'в модернизацию при растущих объемах производства.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Возобновления переговоров, срыва сделки или нового покупателя '
    'публично не сообщалось. Убыток компании за 2025 год вызван внешней '
    'причиной, не связанной со сделкой: «Основной причиной снижения '
    'выручки и получения убытка стало отсутствие поставок сырья '
    '(ортоксилола) для производства готовой продукции в четвертом '
    'квартале 2025 года» из-за дефицита нефтеперерабатывающих мощностей '
    'после ударов БПЛА по заводам (Коммерсантъ, 19 апреля 2026 года).'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/7624523'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8604637'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['target_fin'] == OLD_TARGET_FIN
    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== eco.target_fin: станет ===')
    print(NEW_TARGET_FIN)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['target_fin'] = NEW_TARGET_FIN
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
