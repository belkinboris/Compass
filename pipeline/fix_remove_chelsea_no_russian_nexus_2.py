# -*- coding: utf-8 -*-
"""Карточка g862ad338 «Тодд Бёли продал свою долю в «Челси»» прошла ворота
притока 18.09.2026 (часовой прогон 09:20 МСК) ошибочно — ВТОРОЙ РАЗ ПОДРЯД
за два дня, и по родственной, но не идентичной причине: 17 сентября ворота
приняли за признак упоминание Романа Абрамовича (исторический контекст, не
сторона сделки); сегодня признаком стало само слово «Челси» — транслитерация
имени иностранного футбольного клуба кириллицей, которую russian_evidence()
читает как «имя собственное кириллицей», то есть как потенциальное имя
российской компании или человека.

Источник (Коммерсантъ) описывает сделку целиком между иностранными
сторонами: миллиардеры-финансисты Тодд Бёли и Марк Уолтер продали свою долю
в лондонском футбольном клубе «Челси» инвестиционной компании Clearlake
Capital Group (которая тем самым стала единственным владельцем). Ни продавцы,
ни покупатель, ни сам клуб к российскому рынку отношения не имеют — честный
«нероссийский контур без российского элемента» (CLAUDE.md), который мы не
публикуем.

Оба случая подряд — сигнал, что дело не в одной находке, а в самом классе:
кириллическая транслитерация иностранного бренда/клуба/имени неотличима
для эвристики от настоящего русского имени. Обобщённое правило-регулярка
сюда не пишется этим скриптом намеренно (см. CLAUDE.md: обобщение в код —
отдельная осознанная правка со своим замером по всей базе, не разовая
догадка в конце часового прогона) — просто фиксируем повтор в журнале и
снимаем карточку тем же способом, что и вчера.

Карточка ещё не отправлена в консоль (send_drafts не запускался после
promote.py) — снимаем из pending.json, а не через модерацию.

Запуск: python3 pipeline/fix_remove_chelsea_no_russian_nexus_2.py [--write]
"""
import json
import sys

PENDING_PATH = 'static/data/pending.json'


def main(write):
    data = json.load(open(PENDING_PATH, encoding='utf-8'))
    cards = data['cards']
    before = len(cards)
    target = [c for c in cards if c['id'] == 'g862ad338']
    assert len(target) == 1, target
    assert target[0]['title'] == 'Тодд Бёли продал свою долю в «Челси»'
    assert not target[0].get('draft_sent'), 'карточка уже отправлена в консоль — снимать нельзя этим скриптом'
    data['cards'] = [c for c in cards if c['id'] != 'g862ad338']
    assert len(data['cards']) == before - 1

    if write:
        json.dump(data, open(PENDING_PATH, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
        print('Снято: g862ad338. ЗАПИСАНО.')
    else:
        print('Сухой прогон: снял бы g862ad338. Повторите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
