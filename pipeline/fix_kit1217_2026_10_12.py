"""«КИТ1217» / «Игроник» (g9354e001): карточка и пост вместо масштаба
компании пересказывали слова основателя — «медиасуверенность», что значат
цифры в названии — и «выручка выросла в шесть раз» без базы. Владелец и
Артем 12 октября 2026: «Пипко — ноунейм, непонятно, как это релевантно»;
«пост с малоизвестной компанией должен содержать цифры». Абсолютной выручки
нет ни в одном источнике (РБК, Lenta, ABN, «Элитный трейдер», Mail),
поэтому вперед — то, что есть в рублях: 48,8 млрд рекламных бюджетов,
место в рейтинге, клиенты. Без --write — сухой прогон."""
import json, sys
DATA = 'static/data/deals_promoted.json'
ID = 'g9354e001'

NEW = {
    'target_fin': (
        'У «Игроника» под управлением 48,8 млрд рублей рекламных бюджетов: это четвертое '
        'место среди медиагрупп России в рейтинге АКАР и Sostav за 2025 год. '
        'Среди клиентов «Игроника» — Альфа-Банк, «Ростелеком», X5 и Ozon. '
        'По данным ABN Agency (другие источники этих цифр не приводят), прогноз EBITDA '
        '«Игроника» на 2026 год — около 2,7 млрд рублей, а инвестконсультанты оценивают '
        'бизнес более чем в 15 млрд рублей. Выручку в рублях компания не раскрывает.'),
    'rationale': (
        'Размещение не скорое: горизонт — от полугода до полутора лет, практическая '
        'подготовка начнется в 2027 году, основная площадка — Мосбиржа. '
        'Если IPO состоится, «КИТ1217» станет первой публичной компанией на российском '
        'рекламном рынке.'),
    'context': (
        'В «КИТ1217» войдет «Игроник», у холдинга будет совет директоров. '
        'По данным ABN Agency, деньги от размещения планируют направить на покупку '
        'других игроков рекламного рынка; контроль над холдингом основатель хочет '
        'оставить за своей семьей.'),
}
OLD_START = {'target_fin': 'За четыре года бизнес увеличил выручку в шесть раз',
             'rationale': 'За термином «медиасуверенность»',
             'context': 'Имя «КИТ1217» для будущего холдинга придумало агентство «Депо»'}
# повторный запуск после первой записи 12 октября: сверять и с ее текстом
SECOND = {'target_fin': '«Игроник» — четвертая по величине медиагруппа России',
          'rationale': 'Размещение не скорое', 'context': 'В «КИТ1217» войдет «Игроник»'}

def apply(data):
    card = next(x for x in data['deals'] if x['id'] == ID)
    for k, v in NEW.items():
        assert card['eco'][k].startswith((OLD_START[k], SECOND[k])), (k, card['eco'][k][:80])
        print(f'{k}:\n  было: {card["eco"][k]}\n  стало: {v}\n')
        card['eco'][k] = v

write = '--write' in sys.argv
apply(json.load(open(DATA, encoding='utf-8')))
if write:
    data = json.load(open(DATA, encoding='utf-8'))          # перечитать перед записью
    apply(data)
    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
        f.write('\n')
    print('записано')
