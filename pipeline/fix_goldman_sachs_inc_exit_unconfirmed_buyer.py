# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
`g404d96eb` («Goldman Sachs продал 3,75% акций ИНК-Капитал менеджменту
ИНК», 2022, Закрыта) — единственная ссылка в `src` не подтверждает
премису карточки вовсе, а сам факт продажи МЕНЕДЖМЕНТУ нигде официально
не подтверждён.

НАЙДЕНО, НЕ ПОЧИНЕНО ЦЕЛИКОМ — решение по `buyer`/`title` за человеком,
запись добавлена в «Известные проблемы» CLAUDE.md.

Проверено ЛИЧНО прямым WebFetch (дословные цитаты):
- neftegaz.ru/news/companies/254704-... (ЕДИНСТВЕННЫЙ источник в `src`
  карточки) — это статья от 27 августа 2013 года про ВХОД Goldman Sachs
  в капитал (покупка доли у ЕБРР), а не про выход 2022 года: «В
  результате сделки, заключенной между Европейским Банком Реконструкции
  и Развития и Goldman Sachs, доля владения ЕБРР уменьшилась до 4,4%, а
  доля Goldman Sachs составила 3,75%». Слово «менеджмент» не
  встречается вовсе, о продаже/выходе не сказано ни слова — источник
  подтверждает противоположную по направлению сделку;
- interfax.ru/business/910063 (реальный источник факта, использованный
  в `eco.context`, но так и не добавленный в `src`) — «В отчетном
  периоде из состава акционеров компании вышел миноритарный акционер
  Goldman Sachs International»; «в прошлом году обсуждался вариант
  выкупа доли Goldman Sachs НА БАЛАНС ООО "ИНК" за сумму около $150
  млн»; «Информации о том, какой сценарий в итоге был реализован, у
  источника агентства нет, официально сведения о переговорах сторон не
  подтверждались» — то есть ни покупатель, ни механизм выкупа
  официально не названы НИ ОДНИМ источником.

Отдельно проверено (WebSearch, не дословным чтением конкретной статьи):
структура владения ИНК-Капитал действительно включает ООО «Приор» —
контролирующего акционера с долей 91,85%, где Николаю Буйнову
принадлежит 67,58%, а гендиректору ИНК Марине Седых — 11% (forbes.ru,
2018 год, о более раннем выкупе ЕБРР). Это делает версию «Приор»
СТРУКТУРНО правдоподобной (выходящую долю логично забирает уже
контролирующий акционер), но не превращает её в подтверждённый факт —
Forbes-статья описывает более раннюю сделку и не подтверждает именно
покупку доли Goldman Sachs в 2022 году.

Внесено: в `eco.context` добавлена честная неопределённость (обсуждался
выкуп на баланс ИНК, итоговый сценарий официально не подтверждён);
`src` дополнен реальной статьёй о выходе (interfax.ru), которая была
использована для факта в `eco.context`, но не была в списке источников.
`buyer`/`title`/`extra` (с конкретным именем «Приор»/Буйнов) НЕ
изменены — решение оставлено человеку.

Запуск: python3 pipeline/fix_goldman_sachs_inc_exit_unconfirmed_buyer.py
        python3 pipeline/fix_goldman_sachs_inc_exit_unconfirmed_buyer.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g404d96eb'

OLD_ECO_CONTEXT = 'Goldman Sachs International был акционером компании с 2013 года.'
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' По данным источника «Интерфакса» (статья от 4 '
    'июля 2023 года), в 2022 году обсуждался вариант выкупа доли '
    'Goldman Sachs на баланс самого ООО «ИНК» за сумму около $150 млн, '
    'но какой сценарий в итоге был реализован и кто стал покупателем — '
    'официально сторонами не подтверждено ни разу.'
)

OLD_SRC = [
    ['Нефтегаз.ру', 'https://neftegaz.ru/news/companies/254704-goldman-sachs-poluchil-dolyu-v-irkutskoy-neftyanoy-kompanii/'],
]
NEW_SRC = OLD_SRC + [
    ['Интерфакс', 'https://www.interfax.ru/business/910063'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
