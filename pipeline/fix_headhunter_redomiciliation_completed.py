# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
gb1b7478f (HeadHunter выкупает акции и ADS кипрской материнской
компании, 01.10.2023, статус «Обсуждается») — редомициляция полностью
завершена ещё в 2024 году, карточка год простояла со статусом
«Обсуждается» на уже закрытой истории.

Проверено лично прямым WebFetch (CNews, 27.09.2024): «Московская
биржа начала торги акциями МКПАО... «Хэдхантер»», «Предложением
воспользовались владельцы 6,2 млн акций (12,5% от общего числа)
HeadHunter», «В результате теперь доля МКПАО «Хэдхантер» в HeadHunter
составила 85.7%».

По данным саб-агента (не дозаверено отдельным WebFetch, но
хронологически согласовано и предшествует уже проверенному факту):
27 марта 2024 акционеры одобрили редомициляцию на годовом собрании;
27 ноября 2024 завершена госрегистрация кипрской стороны как МКАО
«Хэдхантер Груп ПИЭЛСИ» — формальное завершение переезда; в декабре
2024 одобрены спецдивиденды 907 руб./акция (40 млрд руб. всего) «в
связи с редомициляцией».

Статус меняется с «Обсуждается» на «Закрыта»: сделка (обмен акций
кипрской материнской компании на акции российской МКАО) фактически
состоялась и завершена.

НЕ ВКЛЮЧЕНО: судьба доли Kismet Capital Group/Ивана Таврина после
санкций США (декабрь 2023) — саб-агент прямо отметил, что не нашёл
прямого источника, продал ли Таврин долю или она просто перестала
раскрываться публично; это открытый вопрос, а не факт, в карточку не
вносится; финансовые показатели HeadHunter за 2024-2025 годы (МСФО)
— по данным саб-агента (Ведомости, Коммерсантъ), не дозаверены
отдельным WebFetch в этом заходе.

Запуск: python3 pipeline/fix_headhunter_redomiciliation_completed.py
        python3 pipeline/fix_headhunter_redomiciliation_completed.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gb1b7478f'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Закрыта'

OLD_EXTRA = (
    'Российская компания МКАО «Хэдхантер» (зарегистрирована в '
    'октябре 2023) предложила держателям обыкновенных акций и ADS '
    'кипрской HeadHunter Group PLC выкупить их бумаги по цене 910,5 '
    'руб./акция (819,45 руб. с учётом 10% налога на выход). Выкуп '
    'предусмотрен в объёме 14,64 млн акций (28,9%) при неодобрении '
    'изменений устава или 26,68 млн акций (52,7%) при одобрении. '
    'Предложение адресовано иностранным инвесторам в связи с '
    'делистингом с NASDAQ и необходимостью обеспечить контроль '
    'российскими резидентами.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Редомициляция завершена: 27 марта 2024 года акционеры одобрили '
    'переезд, 26 сентября 2024 года начались торги МКПАО «Хэдхантер» '
    'на Мосбирже — офертой воспользовались держатели 12,5% акций, '
    'доля МКПАО в кипрской структуре достигла 85,7%. 27 ноября 2024 '
    'года завершена госрегистрация кипрской стороны, а в декабре '
    '2024 года одобрены спецдивиденды 907 руб./акция «в связи с '
    'редомициляцией».'
)

NEW_SRC = [
    ['CNews', 'https://www.cnews.ru/news/top/2024-09-27_headhunter_vernulsya_na_birzhukompaniya'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS
    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== status: станет ===')
    print(NEW_STATUS)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['status'] = NEW_STATUS
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
