# -*- coding: utf-8 -*-
"""Две карточки несли `date`=«2022» — год относился к более РАННЕМУ этапу
той же истории, а не к событию, которое описывает сама карточка:

- g68a112bd («Русатом Хэлскеа увеличил долю в Медскане до 50%»): в 2022
  году Росатом стал акционером «Медскана», выкупив только 25,001% — это
  уже отражено в собственном тексте карточки («приобретено в феврале
  2022 года»). Но ЗАГОЛОВОК и содержание карточки — про УВЕЛИЧЕНИЕ доли
  до 50%, а этот шаг источник (AK&M) прямо датирует: «AK&M 20 июля 2023
  16:18 ... выкупил дополнительную эмиссию акций АО «Медскан», увеличив
  свою долю в капитале группы компаний до 50%».
- gff984390 («Траст» продал Тимано-Печорскую газовую компанию»):
  источник (AK&M) датирован 4 июля 2023 года; независимая проверка живым
  поиском подтверждает точную дату закрытия — 30 июня 2023 года, а
  покупатель ООО «Верде Дженерейшн Инжиниринг» зарегистрирован 15 мая
  2023 года (то же самое уже сказано в eco.rationale карточки — «созданное
  15 мая текущего года», просто «текущий год» относился не к 2022-му).
  Заодно снята протёкшая служебная пометка сторон «(Банк непрофильных
  активов «Траст» (продавец, проводил аукцион))».

Почему не через review.py: перенос в другой год не поддержан
`date_is_supported()` намеренно (см. прецедент
`fix_osnova_sviblovo_date.py`); для gff984390 факт о 30 июня подтверждён
живым поиском, а не дословным кэшем притока.

Запуск: python3 pipeline/fix_medskan_trast_dates.py
        python3 pipeline/fix_medskan_trast_dates.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.join(os.path.dirname(ROOT), 'static', 'data', 'deals_promoted.json')

TAG = ' (Банк непрофильных активов «Траст» (продавец, проводил аукцион))'
OLD_TRAST_RATIONALE = (
    'Банк «Траст» закрыл сделку по продаже Тимано-Печорской газовой '
    'компании и прав требования к ней путём прямой продажи. Покупателем '
    'выступило ООО «Верде Дженерейшн Инжиниринг», созданное 15 мая '
    'текущего года совладельцами Андреем Зозулей, Кириллом Ратниковым и '
    'Ириной Сметлевой. Сумма: 1 млрд руб.' + TAG
)
NEW_TRAST_RATIONALE = OLD_TRAST_RATIONALE[:-len(TAG)]


def main(write=False):
    data = json.load(open(BASE, encoding='utf-8'))
    cards = {d['id']: d for d in data['deals']}

    medskan = cards['g68a112bd']
    trast = cards['gff984390']

    done = (medskan['date'] == '2023-07-20' and trast['date'] == '2023-06-30'
            and trast['eco']['rationale'] == NEW_TRAST_RATIONALE)
    if done:
        print('УЖЕ ПРИМЕНЕНО')
        return

    assert medskan['date'] == '2022', 'g68a112bd: дата уже другая'
    assert trast['date'] == '2022', 'gff984390: дата уже другая'
    assert trast['eco']['rationale'] == OLD_TRAST_RATIONALE, 'gff984390: rationale уже другой'

    print('ПРАВИМ  g68a112bd date: «2022» -> «2023-07-20»')
    print('ПРАВИМ  gff984390 date: «2022» -> «2023-06-30», снята протёкшая пометка')
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return
    medskan['date'] = '2023-07-20'
    trast['date'] = '2023-06-30'
    trast['eco']['rationale'] = NEW_TRAST_RATIONALE
    json.dump(data, open(BASE, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
