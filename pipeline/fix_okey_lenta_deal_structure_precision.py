# -*- coding: utf-8 -*-
"""Продолжение fix_okey_lenta_rebrand_and_control.py (та же карточка,
g74fd5cdb): перечитав kuban.bfm.ru внимательнее, нашёл более точные
детали — сделка была БЕЗДЕНЕЖНОЙ (принятие долга), затрагивала все 75
гипермаркетов, а сеть дискаунтеров «Да!» в неё НЕ входила. Это важно:
финансовые показатели «О'Кей групп» за I полугодие 2026 года
(выручка +10,4%, прибыль +17,3%), которые нашлись в параллельном
поиске, оказались показателями ИМЕННО сети «Да!» — оставшейся у
прежнего владельца после его переезда в РФ (издание в мае 2026 сообщало
о переименовании прежнего владельца в «Группу Да»), а не гипермаркетов
под «Лентой». В карточку эти цифры НЕ внесены — они описывают не тот
бизнес.

Источник — читал напрямую (fetch_article_texts.py, закэширован):
kuban.bfm.ru (10.08.2026).
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g74fd5cdb'
OLD_EXTRA = (
    'ООО «Земун» (связанная с «Лентой») получила 99% контроля над '
    'компанией «РБФ ритейл», которая управляет сетью гипермаркетов '
    '«О\'кей». ФАС одобрила сделку в середине октября 2025 года. В '
    'периметр входят магазины «О\'кей», онлайн-платформа, товарные знаки '
    'и логистическая инфраструктура.'
)
ADDITION = (
    'Уточнение по структуре: «Сделка по приобретению 75 гипермаркетов '
    'была безденежной: «Лента» приняла на себя долговые обязательства. '
    'Сеть дискаунтеров «Да!» в соглашение не вошла» — она осталась у '
    'прежнего владельца сети «О\'кей».'
)
NEW_EXTRA = OLD_EXTRA + ' ' + ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['extra'] == OLD_EXTRA, f"extra: неожиданное значение {deal['extra']!r}"

    print(f"{CARD_ID} extra: += сделка безденежная (принятие долга), «Да!» не входит")
    deal['extra'] = NEW_EXTRA

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
