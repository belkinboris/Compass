import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gb7363fed'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Не состоялась'

OLD_CONTEXT = (
    'До этого владельцем отеля SO было ООО «Форум» Алексея Говорунова,'
    ' сына бывшего вице-губернатора Санкт-Петербурга Александра'
    ' Говорунова.'
)
NEW_CONTEXT = (
    OLD_CONTEXT + ' Финансовый управляющий Говорунова (признан банкротом'
    ' в апреле 2026 года; «Форум» — в ноябре 2025 года) оспорил сделку,'
    ' настаивая, что актив выбыл по цене существенно ниже рыночной'
    ' накануне банкротства. 10 августа 2026 года Тринадцатый арбитражный'
    ' апелляционный суд отменил сделку — здание возвращается «Форуму», с'
    ' АО «Вознесенский проспект» взыскана госпошлина в пользу бюджета.'
    ' Решение ещё может быть обжаловано в кассации в течение месяца;'
    ' если оно устоит, ожидается продажа отеля на банкротных торгах.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS
    assert deal['eco']['context'] == OLD_CONTEXT

    print('=== status: станет ===')
    print(NEW_STATUS)
    print('\n=== eco.context: станет ===')
    print(NEW_CONTEXT)

    if write:
        deal['status'] = NEW_STATUS
        deal['eco']['context'] = NEW_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
