# -*- coding: utf-8 -*-
"""Месячная очередь, карточка g9da487d4 (Банк «Санкт-Петербург»/
«Агентская компания «Гамбит»»): дельта-поиск нашёл, что карточка несёт
НЕВЕРНЫЙ ГОД. Единственный источник карточки (dp.ru) сам датирован
20 мая 2026 года и приводит полные годовые финансовые показатели
«Гамбита» ЗА 2025 ГОД — такие цифры физически не могут быть известны в
апреле 2025 года. Два независимых источника (smart-lab.ru/Frank Media,
abn.agency), оба датированы 17-20 апреля 2026 года, подтверждают: смена
собственника зарегистрирована в ЕГРЮЛ 17 апреля 2026 года, а не 2025.

Заодно поймана путаница в `extra`: «Агентская компания «Гамбит»»
работает как СТРАХОВОЙ АГЕНТ (продаёт чужие полисы), а не как
страховая компания (не несёт страховых обязательств сама) — extra
ошибочно называл её «страховой компанией».

`review.py` намеренно не умеет переносить сделку в другой год (см.
`date_is_supported()`) — это не недоработка, а осознанная граница:
смена года слишком похожа на «утверждение нового», чтобы идти через
таблицу FIXES. Правится отдельным скриптом со своим `assert`.

Источники — читал напрямую (WebFetch, дословные цитаты подтверждены):
https://www.dp.ru/a/2026/05/20/bank-sankt-peterburg-kupil (уже в src)
https://smart-lab.ru/blog/news/1293336.php
https://abn.agency/2026/04/20/bank-sankt-peterburg-kupil-70-strahovogo-agenta-gambit/

Запуск: python3 pipeline/fix_bank_spb_gambit_year_and_entity_type.py [--write]
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g9da487d4'

OLD_DATE = '2025-04-01'
NEW_DATE = '2026-04-01'

OLD_EXTRA = (
    'Банк «Санкт-Петербург» приобрел 70% долей страховой компании. '
    'Оставшиеся 30% остаются у ГД компании Прейс Веры Владимировны. '
    'Сделка закрыта в апреле-мае 2025 года. Цель — расширение '
    'присутствия на рынке страховых услуг, усиление кросс-продаж и '
    'увеличение комиссионных доходов.'
)
NEW_EXTRA = (
    'Банк «Санкт-Петербург» приобрел 70% долей страхового агента '
    '(компания продаёт чужие страховые полисы, а не выступает '
    'страховщиком сама) — они перешли от Юлии Арсентьевой, владевшей '
    '99,99% компании. Оставшиеся 30% в мае 2026 года перешли '
    'генеральному директору компании Вере Прейс (ранее ей не '
    'принадлежали). Сделка закрыта в апреле-мае 2026 года. Цель — '
    'расширение присутствия на рынке страховых услуг, усиление '
    'кросс-продаж и увеличение комиссионных доходов.'
)


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['date'] == OLD_DATE, \
        f"date: неожиданное значение {deal['date']!r}"
    assert deal['extra'] == OLD_EXTRA, \
        f"extra: неожиданное значение {deal['extra']!r}"

    print(f'{CARD_ID} date: {OLD_DATE!r} -> {NEW_DATE!r}')
    print(f'{CARD_ID} extra: страховая компания -> страховой агент, '
          f'2025 -> 2026 в дате закрытия')

    if write:
        deal['date'] = NEW_DATE
        deal['extra'] = NEW_EXTRA
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('ЗАПИСАНО')
    else:
        print('Сухой прогон. Запись — с --write.')


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
