# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g97a4c417
(Технониколь приобрела завод по переработке пластика в Твери, сентябрь
2024). Дельта-поиск нашёл собственный пресс-релиз «Технониколь» (зеркало
polyprofi.ru — на tn.ru WebFetch отдаёт 403; текст на зеркале сверен лично
прямым WebFetch и совпадает дословно) с двумя фактами точнее, чем уже
стоящие в карточке обобщения.

1) `eco.context` сейчас знает только суммарную мощность («до 30 тыс. тонн в
год»), не различая продукты. Пресс-релиз ТН разбивает её на два вида
переработки: «ежегодно завод будет производить до 30 тысяч тонн ПЭТ-флекса
и до 10 тысяч тонн гранулята из ПНД» — это НЕ противоречие уже стоящему
факту (там же названы «три линии по переработке ПЭТ-бутылок в хлопья, две
линии по рециклингу отходов ПЭТ в регранулят и линию по производству
упаковочной ПЭТ-ленты» — то есть 30 тыс. тонн уже относилось только к ПЭТ),
а уточнение: к прежним 30 тыс. тонн ПЭТ добавляется отдельная линия ПНД на
10 тыс. тонн, которой в карточке не было вовсе.

2) Сроки интеграции актива, которых в карточке не было: «интеграция в
структуру «Технониколь» начнется в сентябре 2024 года и закончится в
2025 году».

НЕ включено: личность и владельцы продавца «ГК EcoPartners» (сабагент нашёл
состав группы на b-soc.ru и имена сооснователей через WebSearch-агрегацию,
но НЕ смог получить дословную цитату прямым чтением страницы Forbes с
именами — по стандарту дословности этого проекта такое не пишется без
личной проверки; это задача для отдельного прохода, не для этого); точная
сумма сделки — независимого числа не нашлось, все источники повторяют уже
стоящую в карточке оценку InfoLine «1,5–1,6 млрд ₽» или пишут «сумма
сделки не раскрывается» (сам пресс-релиз ТН); консультанты — не названы ни
в одном источнике.

Запуск: python3 pipeline/fix_technonikol_tver_zavod_capacity_and_integration.py
        python3 pipeline/fix_technonikol_tver_zavod_capacity_and_integration.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g97a4c417'

OLD_CONTEXT = (
    'С момента запуска в сентябре 2023 года завод переработал более 5,3 тыс. '
    'тонн вторичного сырья, планируется нарастить мощность до 30 тыс. тонн в '
    'год, инвестировав 700 млн руб.'
)
CONTEXT_ADDITION = (
    ' По данным пресс-релиза «Технониколь», ежегодно завод будет производить '
    'до 30 тысяч тонн ПЭТ-флекса и до 10 тысяч тонн гранулята из ПНД; '
    'интеграция в структуру «Технониколь» началась в сентябре 2024 года и '
    'завершится в 2025 году.'
)
NEW_CONTEXT = OLD_CONTEXT + CONTEXT_ADDITION

NEW_SRC = [
    ['Полипрофи (пресс-релиз ТехноНИКОЛЬ)', 'https://polyprofi.ru/news/tekhnonikol_priobrela_zavod_v_tveri.html'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
