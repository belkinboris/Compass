# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g5512a325
(Supplement Group выкупила 80% ООО «Здоровая планета», бренд Jump) —
показатели ПОКУПАТЕЛЯ (`eco.fin`) стояли прочерком, а его дальнейшая
консолидация рынка после этой сделки не отслежена.

Финансы и мощности покупателя на момент сделки — проверено лично прямым
WebFetch (Коммерсантъ, kommersant.ru/doc/7231710): «Выручка компании в
прошлом году составила 264,2 млн руб., увеличившись в пять с половиной
раз год к году. Чистая прибыль выросла почти в четыре раза, до 85,1 млн
руб.», «У группы 680 кв. м производственных площадей, намечено открытие
кластера на 6 тыс. кв. м. Текущая мощность — 250 тыс. банок в месяц.» —
это ОБЪЯСНЯЕТ мотив сделки (уже стоящий в `eco.rationale`) конкретными
цифрами: небольшой, но растущий производитель расширяет ассортимент
через покупку смежного бренда, а не поглощает конкурента с рынка.

Дальнейшая судьба покупателя — проверено лично прямым WebFetch
(Коммерсантъ, kommersant.ru/doc/8443530, 20 февраля 2026 года): «В
контур производителя входят ООО «Сапплемент Групп», ООО «Эвейк Групп» и
ООО «Здоровая планета», зарегистрированные в Курске», «По итогам 2025
года выручка компании составила 1,4 млрд руб.», «Бизнес контролируется
Павлом Мамаевым и Виктором Липиным» — то есть «Здоровая планета» за
полтора года стала частью более широкого контура (три юрлица), а не
осталась изолированной покупкой; в феврале 2026 года «АО «Сапплемент
Капитал»... собирается приобрести курского производителя этикеток
«Лейблпак»» — консолидация продолжается, но уже вне сегмента БАД/
спортпита. Добавлено в `extra` как продолжение истории покупателя.

НЕ ВКЛЮЧЕНО: ребрендинг/интеграция бренда Jump — сайт jump.bio по-прежнему
подписан «ООО «Здоровая планета»», Supplement Group как владелец нигде
не упомянут, найти публичного объявления об интеграции не удалось —
честный пустой результат по этому углу. Выкуп Supplement Group оставшихся
20% у фонда «Экспонента» — по данным ЕГРЮЛ на 31.08.2026 доля не
изменилась (80/20). Юридические консультанты сделки — по-прежнему нигде
не названы.

Запуск: python3 pipeline/fix_supplement_group_buyer_fin_and_further_ma.py
        python3 pipeline/fix_supplement_group_buyer_fin_and_further_ma.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g5512a325'

OLD_FIN = '—'
NEW_FIN = (
    'Выручка Supplement Group (покупателя) в 2023 году составила 264,2 '
    'млн руб., увеличившись в пять с половиной раз год к году. Чистая '
    'прибыль выросла почти в четыре раза, до 85,1 млн руб. У группы '
    '680 кв. м производственных площадей и мощность 250 тыс. банок в '
    'месяц, намечено открытие кластера на 6 тыс. кв. м (Коммерсантъ).'
)

OLD_EXTRA = (
    'Сделка по приобретению Supplement Group 80% долей ООО «Здоровая '
    'планета», производителя фитнес-десертов под брендом Jump '
    '(протеиновые батончики, печенье и другие продукты). Оставшиеся 20% '
    'остались у инвестфонда «Экспонента».'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Покупатель продолжил консолидацию: к 2026 году в его контур входят '
    'ООО «Сапплемент Групп», ООО «Эвейк Групп» и ООО «Здоровая планета» '
    '(зарегистрированы в Курске), выручка группы за 2025 год составила '
    '1,4 млрд руб., бизнес контролируется Павлом Мамаевым и Виктором '
    'Липиным; в феврале 2026 года структура группы («АО «Сапплемент '
    'Капитал»») договорилась о покупке курского производителя этикеток '
    '«Лейблпак» — уже вне сегмента БАД/спортпита (Коммерсантъ, '
    '20 февраля 2026 года).'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/7231710'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8443530'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['fin'] == OLD_FIN
    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== eco.fin: станет ===')
    print(NEW_FIN)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['fin'] = NEW_FIN
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
