# g5f662edc: источник уже стоит в src (74.ru), само слово «Росимущество» в
# карточке не встречалось — цитата найдена WebFetch 13 сентября 2026 и
# дописывается в eco.context, чтобы факт остался проверяемым по карточке,
# а не только по этому скрипту.
G5F_ADDITION = (
    ' По поручению Росимущества торги проводил Российский аукционный дом '
    'в рамках федерального плана приватизации на 2020–2022 годы.'
)


def main(write):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    comps = data['companies']
    by_id = {d['id']: d for d in data['deals']}

    for cid, seller_text, seller_id, field, substr in ENTRIES:
        card = by_id[cid]
        assert card.get('seller') is None, (cid, 'seller уже задан:', card.get('seller'))
        assert not card.get('seller_id'), (cid, 'seller_id уже привязан')
        if field is not None:
            if isinstance(field, tuple):
                val = (card.get(field[0]) or {}).get(field[1]) or ''
            else:
                val = card.get(field) or ''
            assert substr in val, (cid, field, 'цитата не найдена:', substr[:60])
        if seller_id is not None:
            assert seller_id in comps, (cid, 'профиль продавца не существует:', seller_id)

    # g5f662edc: докладываем цитату, подтверждающую Росимущество, в саму карточку
    card = by_id['g5f662edc']
    old_context = card['eco']['context']
    assert card['eco']['context'] is not None and 'Росимущество' not in old_context
    assert G5F_ADDITION.strip() not in old_context

    for cid, seller_text, seller_id, field, substr in ENTRIES:
        card = by_id[cid]
        card['seller'] = seller_text
        if seller_id:
            card['seller_id'] = seller_id
        print('%s: seller = %r%s' % (cid, seller_text, (' -> %s' % seller_id) if seller_id else ''))

    card = by_id['g5f662edc']
    card['eco']['context'] = old_context + G5F_ADDITION
    card['src'] = card['src']  # источник (74.ru) уже был в src — не дублируем
    print('g5f662edc: eco.context дополнен цитатой о Росимуществе (источник уже в src)')

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
            f.write('\n')
        print('Записано.')
    else:
        print('Сухой прогон — для записи передайте --write')


if __name__ == '__main__':
    import sys
