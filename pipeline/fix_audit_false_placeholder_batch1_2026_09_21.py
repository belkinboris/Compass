def main(write: bool) -> int:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    cards = {d["id"]: d for d in data["deals"]}
    decided = aq.decided_by_a_reader()
    log: list = []
    applied = 0
    skipped = 0

    for cid, src, quote, dst in MOVES:
        if cid not in cards:
            log.append("%s: карточки нет — пропущено" % cid)
            skipped += 1
            continue
        ok = apply_move(cards[cid], src, quote, dst, write, decided, cid, log)
        applied += int(ok)
        skipped += int(not ok)

    # g547ff4b8: ручной разбор предложения через точку с запятой.
    cid = "g547ff4b8"
    card = cards.get(cid)
    if card is not None:
        full = get_field(card, "eco.context") or ""
        needle = ("Юридическим консультантом G.O.I. Energy выступила BonelliErede, финансовым — "
                  "Ernst & Young; сама G.O.I. Energy — подразделение кипрского фонда Argus New Energy "
                  "Fund, её инвесторы контролируют израильскую BAZAN GROUP.")
        if needle in full and (cid, "eco.context") not in decided \
           and (cid, "law.adv") not in decided and (cid, "eco.finadv") not in decided:
            keep = "Сама G.O.I. Energy — подразделение кипрского фонда Argus New Energy Fund, её инвесторы контролируют израильскую BAZAN GROUP."
            log.append("%s: eco.context → law.adv («Юридическим консультантом… BonelliErede»)" % cid)
            log.append("%s: eco.context → eco.finadv («финансовым… Ernst & Young»)" % cid)
            applied += 2
            if write:
                new_ctx = full.replace(needle, keep).strip()
                new_ctx = re.sub(r"\s+", " ", new_ctx)
                set_field(card, "eco.context", new_ctx)
                set_field(card, "law.adv", "Юридическим консультантом G.O.I. Energy выступила BonelliErede.")
                set_field(card, "eco.finadv", "Финансовым консультантом G.O.I. Energy выступил Ernst & Young.")
        else:
            log.append("%s: ожидаемый фрагмент eco.context не найден или поля решены читателем — пропущено" % cid)
            skipped += 1

    done_path = ROOT / "pipeline" / "audit_queue_done.json"
    done = json.loads(done_path.read_text(encoding="utf-8")) if done_path.exists() else {}
    for k, note in STALE_KEYS.items():
        if write:
            done[k] = note
        log.append("%s: отмечена done без переноса — %s" % (k, note))

    print("Применено: %d, пропущено: %d" % (applied, skipped))
    for line in log:
        print("   " + line)

    if not write:
        print("\n(сухой прогон; чтобы записать — --write)")
        return 0
    DATA.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    done_path.write_text(json.dumps(done, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print("\nзаписано")
    return 0


if __name__ == "__main__":
    sys.exit(main("--write" in sys.argv))
