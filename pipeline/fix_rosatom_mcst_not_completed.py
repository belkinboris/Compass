import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'ge6f87428'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Не состоялась'

OLD_ECO_CONTEXT = (
    'НПО «Критические информационные системы» (НПО КИС, структура '
    '«Росатома») приобретает 100% акций АО МЦСТ. По неофициальным '
    'данным, сделка была безденежной.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' Стороны не договорились: сделка так и не '
    'состоялась. Вместо перехода к Росатому в сентябре 2024 года '
    'Минпромторг ввёл на МЦСТ внешнее управление — из-за срыва '
    'гособоронзаказа, управляющей организацией назначен НПЦ «Элвис»; '
    'право собственности при этом не переходит. В январе 2026 года '
    'сменился гендиректор — Александра Кима, руководившего компанией с '
    'момента основания в 1992 году, сменил представитель «Элвиса» '
    'Андрей Пименов, но контрольная доля, по данным Коммерсанта, '
    'по-прежнему у Кима.'
)

OLD_SRC = [['Коммерсантъ', 'https://www.kommersant.ru/doc/5813229']]
NEW_SRC = OLD_SRC + [
    ['Habr', 'https://habr.com/ru/news/846946/'],
    ['1Rre.ru', 'https://www1.ru/news/2026/02/12/u-razrabotcika-processorov-elbrus-smenilsia-gendirektor-posle-sluxov-o-sryve-srokov-gosoboronzakaza.html'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS
    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== status: станет ===')
    print(NEW_STATUS)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['status'] = NEW_STATUS
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
