import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g09446477'

OLD_EXTRA = (
    'Инвестор — ОАО «АБ ХОЛДИНГ» (головная структура Альфа-банка) '
    'приобрела 32% в ООО «Мозен». Сделка закрыта 4 октября 2023 года. '
    'Партнёрами сервиса также выступают Модульбанк, Тинькофф банк и '
    'банк «Точка». (Альфа-банк (АБ Холдинг))'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Доля «АБ Холдинга» с тех пор выросла до контрольной — 50% (доля '
    'Семибратова снизилась до 43%, появились новые миноритарии-физлица). '
    'Интеграция с продуктами Альфа-Банка реализована: льготная комиссия '
    'для таксопарков, овердрафт до 10 млн ₽, кэшбэк водителям. Бизнес '
    'растёт: выручка за 2025 год — 356 млн ₽ (+31,3%), прибыль — 16,1 '
    'млн ₽ (+102,1%).'
)

NEW_SRC = [
    ['Т-Банк', 'https://www.tbank.ru/business/contractor/legal/1197847252580/'],
    ['Audit-it.ru', 'https://www.audit-it.ru/contragent/1197847252580_ooo-mozen'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
