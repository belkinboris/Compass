# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g1d76aeb5 (Multispace может выкупить бизнес-центр Stone Курская у
девелопера Stone, статус «Обсуждается») — переговоры с Multispace 2023
года ни к чему не привели, здание в 2025 году продано неизвестному
покупателю, и один названный кандидат публично опроверг сделку.

Проверено лично прямым WebFetch (Коммерсантъ, 01.10.2025, doc/8079485):
заголовок «"Фонбет" приобрел бизнес-центр "Stone Курская"», «букмекер
выкупил строящийся бизнес-центр "Stone Курская" площадью 15,6 тыс.
кв. м оценочно за 5-7 млрд руб.» — источники Ъ назвали покупателем
именно «Фонбет». В тот же день «Фонбет» опроверг это — проверено через
прямую цитату в поисковой выдаче Forbes.ru (сам Forbes отдаёт WebFetch
только неразбираемую анимацию, поэтому цитата взята из независимо
процитированного пересказа): управляющий акционер Валентин Голованов
заявил, что компания «занимается сугубо букмекерской деятельностью и
никогда не рассматривала для себя инвестиции в коммерческую
недвижимость», нынешний офис «полностью удовлетворяет все её
потребности».

Multispace к этому зданию отношения не имеет — проверено по данным
саб-агента (CRE.ru): в 2026 году компания открывает новую площадку в
ДРУГОМ здании (БЦ Dubinin'Sky, девелопер «Галс-Девелопмент»), то есть
переговоры 2023 года со Stone для неё закрыты без результата.

Текущее состояние здания — проверено лично прямым WebFetch
(Коммерсантъ, 12.02.2026, doc/8422162): «Управляющая компания STONE
Office приступила к управлению бизнес-центром класса Prime STONE
Курская» — конкретный владелец или крупный арендатор по-прежнему не
назван ни в одном источнике.

`status`/`buyer` НЕ меняются: ни один источник не подтверждает
конкретную сторону сделки (кандидат «Фонбет» публично опровергнут, а не
просто не подтверждён).

Запуск: python3 pipeline/fix_stone_kurskaya_fonbet_denial_and_status.py
        python3 pipeline/fix_stone_kurskaya_fonbet_denial_and_status.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g1d76aeb5'

OLD_EXTRA = (
    'Переговоры между девелопером Stone и сетью гибких офисов '
    'Multispace о возможном приобретении бизнес-центра «Stone '
    'Курская». Рассматриваются два варианта: выкупка объекта или '
    'аренда площадей.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' В октябре 2025 года источники Коммерсанта назвали покупателем '
    'здания букмекерскую компанию «Фонбет» — та же в тот же день '
    'официально опровергла сделку («никогда не рассматривала для себя '
    'инвестиции в коммерческую недвижимость»). С февраля 2026 года '
    'зданием управляет собственная УК STONE Office, конкретный '
    'владелец или крупный арендатор по-прежнему не назван ни в одном '
    'источнике. Multispace к этому зданию отношения не имеет — в 2026 '
    'году открывает офис в другом бизнес-центре.'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8079485'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8422162'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
