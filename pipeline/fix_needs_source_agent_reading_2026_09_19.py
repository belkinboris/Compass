def set_path(obj, path, value):
    parts = path.split('.')
    for p in parts[:-1]:
        obj = obj.setdefault(p, {})
    obj[parts[-1]] = value


def get_path(obj, path):
    for p in path.split('.'):
        if not isinstance(obj, dict):
            return None
        obj = obj.get(p)
    return obj


