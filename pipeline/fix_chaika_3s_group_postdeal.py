import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gdd85a5b9'

OLD_EXTRA = (
    'Артем Чайка приобрел 50% доли в девелопере 3S Group у основателя '
    'ульяновского застройщика «Премьера» Руслана Сеюкова, увеличив свой '
    'пакет до 99%. Оставшийся 1% принадлежит Александру Китаеву. Сеюков '
    'остается совладельцем входящей в группу компании «Три эс проперти '
    'девелопмент» и будет заниматься строительством апарт-комплекса в '
    'рамках ТПУ «Савеловская».'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Под единоличным контролем Чайки компания получила новый крупный '
    'проект: многофункциональный комплекс площадью 68 тыс. кв. м у метро '
    '«Кленовый бульвар» (изначально планировался ТЦ на 18 тыс. кв. м) '
    '(developmentmedia.ru). Выручка ООО «Три ЭС ГРУП» за 2024 год выросла '
    'до 247,2 млн руб., чистая прибыль — до 159,1 млн руб. (РБК Компании). '
    'В феврале 2025 года Великобритания ввела санкции против Артёма '
    'Чайки как главы «Нерудной компании Бердяуш» — другого его бизнеса, '
    'не связанного с 3S Group (Ведомости).'
)

NEW_SRC = [
    ['developmentmedia.ru', 'https://developmentmedia.ru/2026/04/28/syn-byvshego-genprokurora-chajki-postroit-mnogofunktsionalnyj-kompleks-v-moskve/'],
    ['РБК Компании', 'https://companies.rbc.ru/id/5177746233066-ooo-obschestvo-s-ogranichennoj-otvetstvennostyu-tri-es-grup/'],
    ['Ведомости', 'https://www.vedomosti.ru/politics/news/2025/02/14/1092190-velikobritaniya-vvela-sanktsii'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
