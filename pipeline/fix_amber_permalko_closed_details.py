import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g8ac1b593'
BUYER_ID = 'g831f105a'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Закрыта'

OLD_ECO_RATIONALE = None
NEW_ECO_RATIONALE = (
    'По мнению аналитика Анны Буйлаковой, как европейская компания с '
    'выходом на глобальные рынки, Amber Beverage Group могла решить '
    'выйти из российского бизнеса из-за его «токсичности» — сама '
    'компания причину продажи не комментировала.'
)

OLD_ECO_TARGET_FIN = (
    'Завод выпускает свыше 1,8 млн декалитров алкоголя в год. Выручка '
    'в 2022 году — 2,5 млрд ₽, чистая прибыль — 102,9 млн ₽.'
)
NEW_ECO_TARGET_FIN = (
    OLD_ECO_TARGET_FIN + ' Выручка за 2023 год — 2,6 млрд ₽; по итогам '
    '2025 года — 3,5 млрд ₽ при чистой прибыли 43,65 млн ₽.'
)

OLD_ECO_CONTEXT = (
    'Выручка компании в 2022 году — 805,6 млн ₽, чистая прибыль — '
    '53,5 млн ₽. Единственный учредитель ООО «АлкоВорлд» — '
    'предприниматель Александр Глусь.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' В марте 2024 года гендиректором завода стал '
    'Андрей Семериков; 9 июля 2024 года завод вернул историческое '
    'название — АО «Пермалко» (юрлицо, ОГРН и ИНН не изменились); с 25 '
    'августа 2026 года руководство возглавил Алексей Гулевич, ранее '
    'глава «Руст Россия».'
)

OLD_SRC = [['Коммерсантъ', 'https://www.kommersant.ru/doc/6068596']]
NEW_SRC = OLD_SRC + [
    ['Коммерсантъ (Пермь)', 'https://www.kommersant.ru/doc/6594457'],
    ['KP.RU (Пермь)', 'https://perm.kp.ru/online/news/5894384'],
    ['Business Class', 'https://www.business-class.su/news/2026/08/30/na-zavode-permalko-novym-direktorom-naznachen-aleksei-gulevich'],
]

OLD_COMPANY_DESC = (
    'Компания из Петрозаводска (учредитель Александр Глусь), '
    'управляет ЛВЗ «Петровский»; в 2023 году покупала 92,6% АО «Амбер '
    'Пермалко» у латвийской Amber Beverage Group.'
)
NEW_COMPANY_DESC = (
    'Компания из Петрозаводска (учредитель Александр Глусь, бывший '
    'совладелец украинского алкогольного холдинга Nemiroff), управляет '
    'ЛВЗ «Петровский»; в 2023 году купила 92,6% АО «Амбер Пермалко» '
    '(с июля 2024 года — снова АО «Пермалко») у латвийской Amber '
    'Beverage Group.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)
    company = data['companies'][BUYER_ID]

    assert deal['status'] == OLD_STATUS
    assert deal['eco'].get('rationale') == OLD_ECO_RATIONALE
    assert deal['eco']['target_fin'] == OLD_ECO_TARGET_FIN
    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC
    assert company['desc'] == OLD_COMPANY_DESC

    print('=== status: станет ===')
    print(NEW_STATUS)
    print('\n=== eco.rationale: станет ===')
    print(NEW_ECO_RATIONALE)
    print('\n=== eco.target_fin: станет ===')
    print(NEW_ECO_TARGET_FIN)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)
    print('\n=== company.desc: станет ===')
    print(NEW_COMPANY_DESC)

    if write:
        deal['status'] = NEW_STATUS
        deal['eco']['rationale'] = NEW_ECO_RATIONALE
        deal['eco']['target_fin'] = NEW_ECO_TARGET_FIN
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        company['desc'] = NEW_COMPANY_DESC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
