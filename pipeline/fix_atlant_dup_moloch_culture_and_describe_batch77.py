def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    comps = data['companies']
    mk = data['match_keys']
    mc = data['merged_companies']
    deals = data['deals']

    # --- дубль «Атлант» ---
    assert DUP_ID in comps, 'дубля %s уже нет' % DUP_ID
    assert comps[DUP_ID]['name'] == 'Атлант', 'имя дубля изменилось'
    assert LIVE_ID in comps and comps[LIVE_ID]['name'] == 'ж/д оператор «Атлант»'
    assert DUP_ID not in mc

    dd = [d for d in deals if d['id'] in DUP_DEALS]
    assert len(dd) == 2
    for d in dd:
        assert d.get('buyer') == DUP_ID, '%s: buyer уже не дубль' % d['id']
        print('ПЕРЕСТАНОВКА buyer  %s: %s -> %s' % (d['id'], DUP_ID, LIVE_ID))
    print('УДАЛЕНИЕ ДУБЛЯ       %s ("Атлант") -> merged_companies[%s]=%s'
          % (DUP_ID, DUP_ID, LIVE_ID))
    if write:
        for d in dd:
            d['buyer'] = LIVE_ID
        del comps[DUP_ID]
        mc[DUP_ID] = LIVE_ID
        del mk[DUP_ID]
        if 'атлант' not in mk[LIVE_ID]:
            mk[LIVE_ID].append('атлант')

    # --- переименование «Молочной культуры» ---
    for cid, (old, new) in RENAMES.items():
        assert comps[cid]['name'] == old, 'профиля %s уже переименован' % cid
        existing_names = {c.get('name') for c in comps.values()}
        assert new not in existing_names, 'имя %r уже занято' % new
        print('ПЕРЕИМЕНОВАНИЕ  %-12s %r -> %r' % (cid, old, new))
        if write:
            comps[cid]['name'] = new
            mk[cid] = NEW_ALIASES[cid]

    # --- обычные описания ---
    wrote, skipped = 0, []
    for cid, text in DESCRIPTIONS.items():
        c = comps.get(cid)
        assert c, 'профиля %s нет в базе' % cid
        assert 15 <= len(text) <= 220, 'описание %s вне 1–2 строк: %d' % (cid, len(text))
        old = str(c.get('desc') or '')
        if old.strip() == text:
            continue
        if old and not PLACEHOLDER.match(old):
            skipped.append((cid, c.get('name'), old[:60]))
            continue
        print('  ОПИСАНИЕ %-12s %-40s %s' % (cid, str(c.get('name'))[:40], text[:50]))
        if write:
            c['desc'] = text
        wrote += 1

    print('\nОписаний записано: %d' % wrote)
    if skipped:
        print('Пропущено (уже есть своё описание): %d' % len(skipped))
        for cid, name, old in skipped[:5]:
            print('   %s %s — %r' % (cid, name, old))

    real = sum(1 for v in comps.values()
               if (v.get('desc') or '').strip() and not PLACEHOLDER.match(str(v.get('desc'))))
    print('Всего профилей с описанием: %d из %d (%d%%)'
          % (real, len(comps), round(100 * real / len(comps))))

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return 0
    json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('Записано.')
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
