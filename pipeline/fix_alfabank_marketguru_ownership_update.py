"""Месячная очередь (REVISION_BRIEF), карточка g61eca68c (Альфа-Банк/
MarketGuru): `eco.context` называл долю миноритария «Нина Гральник
(4,1%)» — это цифра сентября 2025 года (источник abn.agency, момент самой
сделки). Более поздний независимый источник (vc.ru, 26 марта 2026, со
ссылкой на данные Rusprofile) даёт другие, более полные цифры: «Нине
Гральник принадлежит 12,3%... Дмитрий Сизон владеет 7,6%» — в сумме с 80%
Альфа-Банка это даёт 99,9% (полностью учтённый капитал), тогда как старая
пара «80% + 4,1%» оставляла 15,9% неучтёнными. Это не опечатка, а более
поздний и более полный снимок реестра — доли миноритариев могли
измениться за полгода, или исходная цифра 4,1% была неполной. Правка не
через review.py: она опирается на СРАВНЕНИЕ ДВУХ источников из разных
периодов, а не на дословную цитату одного, и заменяет устаревшее число, а
не добавляет факт к пустому полю.
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g61eca68c'
OLD_CONTEXT = (
    'Незадолго до этого из состава учредителей «Маркетгуру» выбыл '
    'значившийся в составе участников общества с мая 2023 года '
    'бизнесмен Максим Гральник, ранее выступавший в СМИ, как основатель '
    'проекта. Кроме Альфа-банка в составе учредителей компании остаются '
    'Нина Гральник (4,1%), а также руководитель «Маркетгуру» Дмитрий '
    'Сизон, ранее занимавшийся бизнесом по производству строительных '
    'металлоконструкций.'
)
NEW_CONTEXT = (
    'Незадолго до этого из состава учредителей «Маркетгуру» выбыл '
    'значившийся в составе участников общества с мая 2023 года '
    'бизнесмен Максим Гральник, ранее выступавший в СМИ, как основатель '
    'проекта. Кроме Альфа-банка в составе учредителей компании остаются '
    'Нина Гральник и руководитель «Маркетгуру» Дмитрий Сизон, ранее '
    'занимавшийся бизнесом по производству строительных '
    'металлоконструкций. По данным Rusprofile на март 2026 года, Нине '
    'Гральник принадлежит 12,3% долей, Дмитрию Сизону — 7,6%.'
)


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} eco.context: устаревшая доля миноритария (4,1%, "
          "сентябрь 2025) заменена на более полный снимок Rusprofile "
          "(12,3%/7,6%, март 2026)")
    deal['eco']['context'] = NEW_CONTEXT

    src_urls = [s[1] for s in deal.get('src', [])]
    new_src = ['vc.ru', 'https://vc.ru/id4994551/2814483-alfa-bank-kupil-'
               'platformu-marketguru']
    if new_src[1] not in src_urls:
        deal['src'].append(new_src)
        print(f"{CARD_ID} src: += vc.ru (источник более полного снимка "
              "долей)")

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
