import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_CONTEXT_USZ = (
    'Завод запущен в 2015 году, в него вложили 4,5 млрд ₽; он выпускает '
    'токарные и фрезерные станки с ЧПУ. После того как DMG MORI объявила '
    'о сворачивании работы в России, завод остановили.'
)
NEW_CONTEXT_USZ = OLD_CONTEXT_USZ + (
    ' К октябрю 2024 года завод возобновил работу под временным '
    'управлением Росимущества — на 2025 год планировался выпуск 250 '
    'станков с ЧПУ.'
)

OLD_CONTEXT_FRII = (
    'Каждый из проектов может получить от 30 млн до 200 млн ₽. Среди '
    'финансируемых компаний — SalesAI (контроль качества звонков с '
    'помощью ИИ), Stylebox (онлайн-подбор одежды) и ServiceGuru '
    '(платформа мобильного обучения для МСБ).'
)
NEW_CONTEXT_FRII = OLD_CONTEXT_FRII + (
    ' План исполнен иначе, чем объявляли: за весь 2024 год ФРИИ вложил '
    '50 млн ₽ всего в пять стартапов (вместо 15 и «до 3 млрд ₽»); нужное '
    'число компаний (15) набралось только по итогам 2025 года, а '
    'совокупная сумма (свыше 0,5 млрд ₽) осталась в шесть раз меньше '
    'первоначально заявленной.'
)

OLD_DATE_WB = '2024'
NEW_DATE_WB = '2026-06-15'
OLD_CONTEXT_WB = (
    'Wildberries & Russ ведет переговоры об участии в проекте создания '
    'национальной платформы, реализуемом РЖД и FESCO (входит в контур '
    '«Росатома»). Платформа будет цифровым окном для грузоотправителей и '
    'объединит участников транспортно-логистического рынка.'
)
NEW_CONTEXT_WB = OLD_CONTEXT_WB + (
    ' В тот же день FESCO публично опровергла переговоры: «не ведет '
    'переговоры с Объединенной компанией Wildberries и Russ о вхождении '
    'в состав каких-либо совместных предприятий». Юрлицо платформы,'
    ' ООО «ЦТЛП Лотус», зарегистрированное 10 июля 2026 года, Wildberries '
    'среди учредителей не называет — ими стали ООО «Цифровая логистика», '
    'ПАО «ДВМП» и ГК «Астрал».'
)


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    usz = by_id['cbb730efc']
    frii = by_id['cdbb80afb']
    wb = by_id['c06611bae']

    assert usz['eco']['context'] == OLD_CONTEXT_USZ, \
        'cbb730efc eco.context уже другой: %r' % (usz['eco']['context'],)
    assert frii.get('status') is None, 'cdbb80afb status уже занят: %r' % (frii.get('status'),)
    assert frii['eco']['context'] == OLD_CONTEXT_FRII, \
        'cdbb80afb eco.context уже другой: %r' % (frii['eco']['context'],)
    assert wb['date'] == OLD_DATE_WB, 'c06611bae date уже другая: %r' % (wb['date'],)
    assert wb.get('status') is None, 'c06611bae status уже занят: %r' % (wb.get('status'),)
    assert wb['eco']['context'] == OLD_CONTEXT_WB, \
        'c06611bae eco.context уже другой: %r' % (wb['eco']['context'],)

    print('cbb730efc: eco.context дополнен (завод возобновил работу к '
          'октябрю 2024)')
    print('cdbb80afb: status None -> "Закрыта"; eco.context дополнен '
          '(план исполнен иначе — медленнее и меньше объявленного)')
    print('c06611bae: date %r -> %r (ошибка года, не дня)' % (OLD_DATE_WB, NEW_DATE_WB))
    print('c06611bae: status None -> "Не состоялась" (FESCO опровергла, '
          'реальное юрлицо без Wildberries)')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    usz['eco']['context'] = NEW_CONTEXT_USZ
    frii['status'] = 'Закрыта'
    frii['eco']['context'] = NEW_CONTEXT_FRII
    wb['date'] = NEW_DATE_WB
    wb['status'] = 'Не состоялась'
    wb['eco']['context'] = NEW_CONTEXT_WB

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
