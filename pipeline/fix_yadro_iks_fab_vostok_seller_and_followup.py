# -*- coding: utf-8 -*-
"""Месячная очередь качества, 11 сентября 2026 — карточка `g80f18d3d`
(«Владелец Yadro купил склад на границе с Китаем», июль 2026) уже
называла покупателя (профиль «ИКС Холдинг») и площадку, но не называла
ПРОДАВЦА (прежнего единственного владельца юрлица-цели) и не знала о
КРУПНОМ ПРОДОЛЖЕНИИ сюжета: в сентябре 2026 года на той же площадке
объявлено строительство двух заводов на 35+ млрд ₽.

Личный WebFetch подтвердил дословно:
- CNews, 28 июля 2026 (уже в `src` карточки,
  https://www.cnews.ru/news/top/2026-07-28_samyj_krupnyj_proizvoditel):
  «„ИКС Холдинг" в июле 2026 г. приобрела компанию ООО „Икс Фаб Восток"»;
  «С момента основания (декабрь 2025 г.) и по июль 2026 г. юрлицо
  принадлежало нынешнему гендиректору компании Адаму Китариеву».
- CNews, 3 сентября 2026
  (https://www.cnews.ru/news/top/2026-09-03_iks_holding_investiruet_1):
  «"ИКС Холдинг" направит свыше 35 млрд руб. на создание производственного
  комплекса из двух предприятий по выпуску сложных полупроводников» на той
  же площадке — выпуск СВЧ-микросхем и фотоэлектрических преобразователей,
  площадь свыше 35 тыс. кв. м, 500 рабочих мест, запуск к 2030 году.

Сумма самой сделки (покупки юрлица) ни в одном источнике не названа —
честная пустота, не заполняется.

Запуск:
    python3 pipeline/fix_yadro_iks_fab_vostok_seller_and_followup.py            # сухой прогон
    python3 pipeline/fix_yadro_iks_fab_vostok_seller_and_followup.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

NEW_SELLER = 'Адам Китариев'

OLD_ASSET = 'склад на границе с Китаем'
NEW_ASSET = (
    'ООО «Икс Фаб Восток» — владельца площадки бывшего домостроительного '
    'комбината в особой экономической зоне «Надеждинская», Приморский '
    'край, около 30 км от границы с КНР'
)

OLD_ECO_CONTEXT = '—'
NEW_ECO_CONTEXT = (
    'В сентябре 2026 года «ИКС Холдинг» объявил о строительстве на той же '
    'площадке производственного комплекса из двух заводов по выпуску '
    'сложных полупроводников (СВЧ-микросхемы и фотоэлектрические '
    'преобразователи) стоимостью свыше 35 млрд ₽, площадью более 35 тыс. '
    'кв. м и на 500 рабочих мест — запуск планируется к 2030 году. '
    'Юрлицо-цель этой сделки, ООО «Икс Фаб Восток», возглавил тот же Адам '
    'Китариев, ранее её единственный владелец.'
)

NEW_SRC = [
    'CNews',
    'https://www.cnews.ru/news/top/2026-09-03_iks_holding_investiruet_1',
]


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['g80f18d3d']

    assert d.get('seller') is None, 'seller уже занят: %r' % (d.get('seller'),)
    assert d.get('asset') == OLD_ASSET, 'asset изменился: %r' % (d.get('asset'),)
    assert d['eco'].get('context') == OLD_ECO_CONTEXT, 'eco.context уже занят: %r' % (d['eco'].get('context'),)
    urls = {s[1] for s in d['src']}
    assert NEW_SRC[1] not in urls, 'источник уже добавлен'

    print('g80f18d3d: seller заполнен (Адам Китариев); asset уточнён '
          '(ООО «Икс Фаб Восток» вместо общей фразы «склад»); eco.context '
          'заполнен (сентябрьское продолжение — 35 млрд ₽, два завода); '
          'добавлен источник')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['seller'] = NEW_SELLER
    d['asset'] = NEW_ASSET
    d['eco']['context'] = NEW_ECO_CONTEXT
    d['src'].append(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
