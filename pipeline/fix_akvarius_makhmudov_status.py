"""Известная проблема (CLAUDE.md, 11 сентября 2026): за 1,5 года ни один
источник не подтвердил Искандера Махмудова стороной покупателя «Аквариуса»
(g26608f96) — а публично названный основатель реального покупателя, S8
Capital, оказался ДРУГИМ человеком. Sostav.ru (22.08.2025, дата финальной
сделки): «Инвестиционный холдинг S8 Capital Армена Саркисяна» — Махмудов в
этой и всех проверенных публикациях о финальной сделке не упоминается.
Тот же класс, что уже применён к `gc64703e2` (Газпромбанк Лизинг/Urent) в
этом прогоне: 3+ независимых снимка молчания плюс публично названная,
отличная от предполагаемой сторона.

Запуск: сухой прогон без аргументов, запись — `--write`.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "static" / "data" / "deals_promoted.json"


def main(write=False):
    data = json.loads(DATA.read_text(encoding="utf-8"))
    deals = {d["id"]: d for d in data["deals"]}
    d = deals["g26608f96"]
    assert d["status"] == "Обсуждается", "статус уже другой"
    d["status"] = "Не состоялась"
    d["eco"]["context"] += (
        " Основатель реального покупателя, S8 Capital, публично назван: "
        "«Инвестиционный холдинг S8 Capital Армена Саркисяна» (Sostav.ru, "
        "22.08.2025) — Махмудов ни в этой, ни в других публикациях о "
        "финальной сделке не фигурирует."
    )
    print("g26608f96: status Обсуждается → Не состоялась "
          "(реальный покупатель — S8 Capital/Саркисян, не Махмудов)")
    if write:
        DATA.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        print("Записано.")
    else:
        print("Сухой прогон. --write для записи.")


if __name__ == "__main__":
    main("--write" in sys.argv)
