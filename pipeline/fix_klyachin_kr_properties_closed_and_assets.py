# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
gf3c5069f (Александр Клячин выкупает активы KR Properties у
Росимущества) — карточка держала статус «Обсуждается», хотя к этому
времени в базе УЖЕ есть две карточки об ОТДЕЛЬНЫХ, более поздних
перепродажах конкретных объектов из этого же пакета (БЦ «Домино» —
ЗПИФ «Церера», БЦ «Салют» — ЗПИФ «Союз-инвест»), что структурно
подразумевает закрытие исходной сделки.

Проверено лично прямым WebFetch. Коммерсантъ (29.12.2025,
kommersant.ru/doc/8335380): «В этом году господин Клячин в
партнерстве со Сбербанком выкупил объекты девелоперской компании» —
прошедшее время подтверждает закрытие («выкупил» — в списке
`STATUS_WORDS['Закрыта']`). НТВ (05.03.2025, ntv.ru/novosti/2884517,
со ссылкой на Микаэла Казаряна, IBC Real Estate): «рыночная стоимость
активов составляет примерно 70–80 млрд руб.» — экспертная оценка
масштаба пакета (не цена сделки).

`status`: «Обсуждается» → «Закрыта». `eco.val` заполнен экспертной
оценкой (стоял прочерком). `eco.context` дополнен полным списком
активов пакета сверх уже известных «Домино»/«Салюта»: жилые проекты
«Мюр & Мерилиз» и Kuznetsky Most 12 by Lalique, деловые кварталы
«Красная Роза», «Рассвет», «Даниловская мануфактура», БЦ «Авиатор» и
«Вернадский», доля в ресторане «Савва» при отеле «Метрополь», особняк
на Смоленском бульваре (Ведомости/Коммерсантъ, март 2025).

НЕ ВКЛЮЧЕНО (сознательно, чтобы не разрастить карточку до хроники
всех последующих сделок): дальнейшие перепродажи отдельных объектов —
торги по «Юг Девелопмент»/«Даниловской мануфактуре» (выиграло АО
«Управление активами» за 12,3 млрд ₽, 22.12.2025), проект «Малая
Грузинская, 3.6» (продан October Group, закрыт 24.12.2025), обратный
выкуп отеля Azimut на Тульской (11.08.2026) — каждая из них либо уже
имеет собственную карточку, либо не подтверждена достаточно, чтобы
заводить новую своим ходом (не работа рутины «качество» — это решение
притока). Точный процент доли Сбербанка в «КР плюс» (49%/51% через
ООО «Грос», по мартовским данным ЕГРЮЛ) не внесён: более поздний
источник (Коммерсантъ, 29.12.2025) называет владение Сбербанка без
процента, а утверждения о том, что Клячин выкупил долю Сбербанка и
стал единоличным владельцем, встретились только на источниках низкого
качества (repost.news, sledst.org, rumafia.io — с признаками
недостоверности, включая несуществующие названия объектов) и не
использованы. Точная сумма сделки по-прежнему не раскрыта нигде.

Запуск: python3 pipeline/fix_klyachin_kr_properties_closed_and_assets.py
        python3 pipeline/fix_klyachin_kr_properties_closed_and_assets.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gf3c5069f'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Закрыта'

OLD_CONTEXT = (
    'Владелец гостиничной сети Azimut Hotels Александр Клячин '
    'договорился о выкупе у государства активов, которые ранее '
    'принадлежали его девелоперской компании KR Properties. Об этом '
    '«Ведомостям» рассказали один из знакомых бизнесмена и собеседник, '
    'знакомый с обсуждением этой сделки. По словам первого источника '
    '«Ведомостей», договоренности были достигнуты на уровне '
    'Министерства финансов, хотя данные объекты находятся на балансе '
    'созданной Росимуществом компании «Управление недвижимостью».'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' Сделка закрылась: «В этом году господин Клячин в партнерстве со '
    'Сбербанком выкупил объекты девелоперской компании» (Коммерсантъ, '
    '29 декабря 2025 года). В пакет, помимо уже известных БЦ «Домино» и '
    '«Салют», входят жилые проекты «Мюр & Мерилиз» и Kuznetsky Most 12 '
    'by Lalique, деловые кварталы «Красная Роза», «Рассвет», '
    '«Даниловская мануфактура», бизнес-центры «Авиатор» и «Вернадский», '
    'доля в ресторане «Савва» при отеле «Метрополь», особняк на '
    'Смоленском бульваре.'
)

OLD_VAL = '—'
NEW_VAL = (
    'По оценке Микаэла Казаряна (IBC Real Estate), «рыночная стоимость '
    'активов составляет примерно 70–80 млрд руб.» (НТВ, 5 марта 2025 '
    'года).'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8335380'],
    ['НТВ', 'https://www.ntv.ru/novosti/2884517'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS
    assert deal['eco']['context'] == OLD_CONTEXT
    assert deal['eco']['val'] == OLD_VAL

    new_src = deal['src'] + NEW_SRC

    print('=== status: станет ===')
    print(NEW_STATUS)
    print('\n=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== eco.val: станет ===')
    print(NEW_VAL)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['status'] = NEW_STATUS
        deal['eco']['context'] = NEW_CONTEXT
        deal['eco']['val'] = NEW_VAL
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
