# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка g5da91c40 (EMC приобрёл
75% сети «Семейный доктор»): дельта-поиск нашёл, что произошло с
предметом сделки ПОСЛЕ закрытия — новый флагманский центр (2 млрд руб.
инвестиций), выросшая сеть (16 -> 17 поликлиник) и историю выручки. Не
через review.py: старое значение eco.context (про премиальный сегмент
EMC) — из другого источника, не образует непрерывный кусок с новой
цитатой.

Источник — читал напрямую (fetch_article_texts.py, закэширован):
Ведомости (08.06.2026), уже добавлен в src.
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g5da91c40'

OLD_CONTEXT = (
    'ЕМЦ долгое время работал на премиальный сегмент и ориентировался '
    'на экспатов. После их массового отъезда в 2022 году органический '
    'рост остановился, а в реальном выражении началось снижение.'
)
ADDITION = (
    'В июне 2026 года «Семейный доктор» открыл в Москве флагманский '
    'Центр медицины площадью 17 000 кв. м — инвестиции в проект '
    'составили 2 млрд руб., из них 40% направлено на покупку '
    'медицинского оборудования; ожидаемый срок окупаемости — около трёх '
    'лет после выхода на стабильную загрузку. «При выходе на проектную '
    'мощность вклад Центра медицины «Семейного доктора» может составить '
    'до 30% совокупной выручки всей сети», — сообщила генеральный '
    'директор сети Юлия Графова. Выручка «Семейного доктора» в 2024 '
    'году составила 7,9 млрд руб. (11-е место в рейтинге Forbes среди '
    'медицинских компаний по выручке); в EMC ожидали, что в 2025 году '
    'выручка сети составит 9,3 млрд руб. К середине 2026 года сеть '
    'выросла до 17 поликлиник (было 16 на момент сделки).'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} eco.context: += развитие сети после сделки (новый центр, выручка)")
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
