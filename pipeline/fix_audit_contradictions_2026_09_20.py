# -*- coding: utf-8 -*-
"""Поля одной карточки спорят друг с другом — разбор трёх случаев.

Класс CONTRADICTION из аудита 13 сентября 2026. Каждая правка сделана по
тому, что УЖЕ написано в самой карточке: ни одного нового утверждения о
сделке здесь не появляется — убирается или смягчается фраза, которая
противоречит соседнему полю.

1. «Ростех» продаёт штаб-квартиру «Швабе» (ge957fc7b). «Контекст»
   заканчивался фразой «О новых попытках продать актив официально не
   объявляли», а в соседнем поле стоит: «Торги назначены на 25 сентября
   2026 года». Фраза устарела в момент появления карточки — убрана.

2. Freedom и Bilim Group (g18a6d375). Заголовок утверждал полную покупку
   компании, а поле суммы — обратное: «Размер доли, стоимость и структура
   сделки не раскрываются. Поэтому говорить о полном поглощении Bilim
   Group или покупке контрольного пакета пока нельзя». Заголовок смягчён
   до доли. Само поле суммы не трогаем: его текст поставлен чтением с
   цитатой из источника, и спорить с прочитанным скрипт не должен — то,
   что эта фраза стоит не в своём поле, остаётся в очереди чтения
   отдельной находкой (класс FIELD_MISPLACED).

3. Офис «Открытия» у ВТБ (gmru-vtb-otkrytie-office-rwb) — РАЗОБРАН И
   ОСТАВЛЕН КАК ЕСТЬ. «Контекст» говорит «сумму сделки и покупателя
   стороны не раскрыли», а карточка называет покупателем RWB. Это похоже
   на противоречие, но обе фразы верны: официально покупателя не называли,
   имя известно из публикаций, на которые карточка ссылается. Переписать
   «не раскрыли стороны» в «не назвал ВТБ» я попробовал и откатил: кто
   именно молчал, в карточке не сказано, а весь этот абзац поставлен
   чтением с цитатой — значит, и менять его должно чтение, а не скрипт.

Общий урок этого прогона: машинная правка не спорит с тем, что уже
прочитано человеком. Поля из таблицы FIXES (review.py) скрипты не трогают.

    python3 pipeline/fix_audit_contradictions_2026_09_20.py
    python3 pipeline/fix_audit_contradictions_2026_09_20.py --write
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "static" / "data" / "deals_promoted.json"

DROP = " О новых попытках продать актив официально не объявляли."
OLD_TITLE = "Freedom купил казахстанскую ИТ-компанию Bilim Group"
NEW_TITLE = "Freedom купил долю в казахстанской ИТ-компании Bilim Group"


def main(write: bool) -> int:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    cards = {d["id"]: d for d in data["deals"]}

    a = cards["ge957fc7b"]
    ctx = a["eco"]["context"]
    assert DROP.strip() in ctx, "фраза уже убрана"
    assert "25 сентября 2026" in (a["law"] or {}).get("struct", ""), "торги больше не назначены"
    new_ctx = ctx.replace(DROP, "").replace(DROP.strip(), "").strip()

    c = cards["g18a6d375"]
    assert c["title"] == OLD_TITLE, c["title"]
    assert "говорить о полном поглощении" in (c["eco"].get("sum") or ""), \
        "поле суммы изменилось — перечитать карточку"

    print("ge957fc7b  «Контекст»: убрана фраза, которой противоречит соседнее поле")
    print("   было: …%s" % ctx[-120:])
    print("   стало: …%s" % new_ctx[-120:])
    print("g18a6d375  заголовок: «%s» → «%s»" % (OLD_TITLE, NEW_TITLE))
    print("gmru-vtb-otkrytie-office-rwb  оставлено как есть: противоречия нет, "
          "см. пояснение в начале файла")

    if not write:
        print("\n(сухой прогон; чтобы записать — --write)")
        return 0
    a["eco"]["context"] = new_ctx
    c["title"] = NEW_TITLE
    DATA.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    print("\nзаписано")
    return 0


if __name__ == "__main__":
    sys.exit(main("--write" in sys.argv))
