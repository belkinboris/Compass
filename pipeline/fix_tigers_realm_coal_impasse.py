# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g3375c312
(Tigers Realm Coal продаёт угольные активы на Чукотке Марку Бузуку,
статус «Обсуждается» с апреля 2024 года) — сделка не просто затянулась,
а зашла в тупик; условия ухудшились по сравнению с исходным объявлением.

Источники — англоязычные (австралийская TIG отчитывается перед ASX),
дословная русская цитата невозможна; факты переданы точным пересказом
с указанием источника, проверено лично прямым WebFetch каждого.

Тупик в переговорах — проверено лично прямым WebFetch (TipRanks, 29 июля
2025 года): сделку разбили на две части, одна часть одобрена
спецкомиссией, но требует пересмотренного договора купли-продажи
из-за сниженной цены продажи и выросшего налога на выход; покупатель не
подписал изменённый договор, что привело к тупику; компания
рассматривает альтернативные варианты выхода из российских активов.

Статус на январь 2026 года (самый свежий найденный) — проверено лично
прямым WebFetch (gem.wiki, со ссылкой на отчёты TIG перед ASX): сделка с
«АПМ-Инвест» по-прежнему не завершена, одобрение президента России —
единственное оставшееся условие — всё ещё не получено.

Судьба продавца — по данным независимого поиска (не проверено прямым
WebFetch первоисточника): TIG делистингуется с Австралийской биржи (ASX)
с 2 марта 2026 года за непредоставление отчётности более двух лет —
это отдельная история, не прямое следствие исхода сделки с Бузуком;
один из акционеров TIG связан с РФПИ, находящимся под санкциями
Австралии/США/Великобритании/Канады.

`status` НЕ меняется на «Не состоялась» — ни один источник не
использует слово из закрытого списка, а официального отказа от сделки
не было; ситуация — открытый тупик, а не подтверждённый срыв.

НЕ ВКЛЮЧЕНО: точная судьба добычи на месторождениях — «Берингпромуголь»
продолжает добычу независимо от исхода сделки (788 тыс. тонн за первое
полугодие 2025 года, nedradv.ru), но это операционный, не структурный
факт; данные ЕГРЮЛ (audit-it.ru) по-прежнему называют учредителем
кипрскую «Росмиро Инвестментс Лимитед» — актуальность снимка не
подтверждена, не переносится как окончательное состояние.

Запуск: python3 pipeline/fix_tigers_realm_coal_impasse.py
        python3 pipeline/fix_tigers_realm_coal_impasse.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g3375c312'

OLD_EXTRA = (
    'Объявление австралийской Tigers Realm Coal о продаже угольных '
    'активов в России (ООО «Берингпромуголь», ООО «Порт угольный» и '
    'других активов) предпринимателю Марку Бузуку через компанию '
    '«АПМ-Инвест». Сделка требует одобрения акционеров TIG, ФАС и '
    'президента России.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' К 2025 году переговоры зашли в тупик: по данным отчётности TIG '
    '(TipRanks, 29 июля 2025 года), сделку разбили на две части, цену '
    'продажи снизили, налог на выход вырос, а Бузук не подписал '
    'пересмотренный договор — компания рассматривает альтернативные '
    'варианты выхода из российских активов. На январь 2026 года '
    '(gem.wiki, со ссылкой на отчёты TIG) единственным оставшимся '
    'условием по-прежнему называется одобрение президента России, '
    'которое так и не получено. Сама TIG к марту 2026 года '
    'делистингуется с Австралийской биржи за непредоставление '
    'отчётности более двух лет — отдельная от исхода сделки история.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    print('=== extra: станет ===')
    print(NEW_EXTRA)

    if write:
        deal['extra'] = NEW_EXTRA
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
