import json
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(ROOT)
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'rosatom-mali'

OLD_CONTEXT = ('Совместная добыча в регионе Сикасо идет с марта 2023 года. В июле '
               '2024-го Минпром Мали передал разрешение на добычу на месторождении '
               'Бугула компании Moketi Mining SARL, которая входит в Uranium One '
               'Group. Геологоразведка по отчету за 2025-й предварительно '
               'подтвердила потенциал участка')

NEW_CONTEXT = OLD_CONTEXT + (
    '. Гендиректор Росатома Алексей Лихачев говорит, что госкорпорация купила '
    'местную малийскую компанию для этого проекта и ведет изыскания: первый '
    'этап разведки увеличил запасы месторождения вдвое, более чем до 400 '
    'тысяч тонн литиевого концентрата. Ранее сообщалось, что строительство '
    'горно-обогатительного комбината в Мали может начаться в 2028 году.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, 'поле уже другое — правку надо пересмотреть'

    print('=== eco.context: было ===')
    print(OLD_CONTEXT)
    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
