import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g31546fef'

OLD_DATE = '2024'
NEW_DATE = '2025'

OLD_CONTEXT = (
    'Продавец — компания «КР Плюс» (принадлежит Сбербанку и владельцу '
    'Azimut Hotels Александру Клячину). Сумма сделки- 12,3 млрд, что '
    'меньше суммы долга по этому объекту (16,7 млрд руб.).'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' Гендиректор АО «Управление активами» — Кирилл Демченко, который '
    'также владеет ООО «Кэпитал перформ» (РИА Недвижимость).'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8312031'],
    ['РИА Недвижимость', 'https://realty.ria.ru/20251222/upravlenie-2063754003.html'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['date'] == OLD_DATE
    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== date: станет ===')
    print(NEW_DATE)
    print('\n=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['date'] = NEW_DATE
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
