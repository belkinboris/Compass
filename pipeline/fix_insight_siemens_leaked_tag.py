# -*- coding: utf-8 -*-
"""У карточки `g62698716` («Инвестиционная группа «Инсайт» приобрела ООО ЛК
«Сименс Финанс» у Siemens AG») `eco.rationale` заканчивается протёкшей
служебной пометкой стороны — тем же классом дефекта, что уже чинили
`pipeline/strip_leaked_role_tags_2022.py` (20 карточек), только с другим
порядком слов: «(Покупатель: Инвестиционная группа «Инсайт» (Авета
Миракяна))» вместо «(Имя (роль))» — сюда не попала под старый шаблон, ищущий
роль ПОСЛЕ имени, а не метку «Покупатель:» ПЕРЕД именем. Единственная
карточка 2022/2026 годов с этим порядком (проверено регуляркой по всей базе
в границах моего среза).

Почему не через review.py: снимается служебный шум, а не новый факт;
текст, предшествующий пометке, не меняется ни на символ.

Запуск: python3 pipeline/fix_insight_siemens_leaked_tag.py
        python3 pipeline/fix_insight_siemens_leaked_tag.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.join(os.path.dirname(ROOT), 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g62698716'
OLD_RATIONALE = (
    'Сделка структурирована с привлечением финансирования через размещение '
    'облигаций: ГК «Инсайт» разместила 27.09.2022 пятилетние облигации на 53 '
    'млрд рублей (организатор размещения — БКС), затем 29 сентября 2022 '
    'выкупила 100% долей ООО ЛК «Сименс Финанс». 31 октября 2022 ГК «Инсайт» '
    'выкупила обратно облигации на 24,7 млрд рублей, предположительно за '
    'счет кредита под залог активов приобретённой компании. Сумма: '
    'несколько млрд рублей (сумма сделки не указана точно; облигации '
    'размещены на 53 млрд рублей). (Покупатель: Инвестиционная группа '
    '«Инсайт» (Авета Миракяна))'
)
NEW_RATIONALE = (
    'Сделка структурирована с привлечением финансирования через размещение '
    'облигаций: ГК «Инсайт» разместила 27.09.2022 пятилетние облигации на 53 '
    'млрд рублей (организатор размещения — БКС), затем 29 сентября 2022 '
    'выкупила 100% долей ООО ЛК «Сименс Финанс». 31 октября 2022 ГК «Инсайт» '
    'выкупила обратно облигации на 24,7 млрд рублей, предположительно за '
    'счет кредита под залог активов приобретённой компании. Сумма: '
    'несколько млрд рублей (сумма сделки не указана точно; облигации '
    'размещены на 53 млрд рублей).'
)


def main(write=False):
    data = json.load(open(BASE, encoding='utf-8'))
    card = next(d for d in data['deals'] if d['id'] == CARD_ID)
    if card['eco']['rationale'] == NEW_RATIONALE:
        print('УЖЕ ПРИМЕНЕНО %s' % CARD_ID)
        return
    assert card['eco']['rationale'] == OLD_RATIONALE, '%s: значение уже другое' % CARD_ID
    print('ПРАВИМ  %s eco.rationale: снята протёкшая пометка стороны' % CARD_ID)
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return
    card['eco']['rationale'] = NEW_RATIONALE
    json.dump(data, open(BASE, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
