import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gbb1c889d'

OLD_CONTEXT = (
    'Кайрат Итемгенов входит в список Forbes богатейших бизнесменов'
    ' Казахстана. Ему принадлежит Aqniet Group, управляющая одной из'
    ' крупнейших аптечных сетей в Казахстане Europharma и сетью аптек в'
    ' регионах Arzan Pharm. Также он владеет отелями Movenpick и Pana в'
    ' Москве, гостиничным комплексом Жетысу в Алматы, где представлены'
    ' бренды Novotel Living и Ibis, а также крупным подрядчиком,'
    ' работающим в энергетической сфере — KBI Energy. В логистической'
    ' отрасли у него есть компания Satti Logistics, занимающаяся'
    ' доставкой грузов автотранспортом.'
)
NEW_CONTEXT = (
    OLD_CONTEXT + ' Редомициляция Globaltrans в Абу-Даби официально'
    ' завершена 26 февраля 2024 года, лицензия регулятора (Abu Dhabi'
    ' Global Market) получена 15 марта 2024 года. К началу февраля 2024'
    ' года доля структур Итемгенова достигла 26,69% (позже —'
    ' до 32,12% после завершения дополнительных сделок).'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
