import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gfcfba8c9'

OLD_STRUCT = (
    'Сама транзакция уже закрыта, утверждают двое собеседников '
    '«Ведомостей». Еще один уточняет, что в собственность покупателя '
    'пока перешел лишь объект в Ярославле, а оформление сургутского '
    'комплекса он ожидает лишь к лету.'
)
NEW_STRUCT = OLD_STRUCT + (
    ' 18 марта 2026 года, через 12 дней после публикации, собственник '
    'сургутского объекта опроверг сделку: «руководитель акционерного '
    'общества "Риалрен"... заявил, что информация о продаже местного '
    'центра, озвученная ранее газетой "Ведомости", не соответствует '
    'действительности», «Какие-либо сделки, направленные на отчуждение '
    'Торгового центра, не заключались» (СургутИнформ-ТВ).'
)

OLD_CONTEXT = '—'
NEW_CONTEXT = (
    'Консультантом сделки выступила CORE.XP: «В CORE.XP, выступавшей '
    'консультантом данной сделки, от комментариев отказались» '
    '(Ведомости).'
)

NEW_SRC = ['СургутИнформ-ТВ', 'https://sitv.ru/arhiv/news/sdelki-ne-zaklyuchalis-sobstvennik-aury-oproverg-informacziyu-o-prodazhe-tcz/']


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['law']['struct'] == OLD_STRUCT
    assert deal['eco']['context'] == OLD_CONTEXT
    assert not any(s[1] == NEW_SRC[1] for s in deal['src']), 'источник уже в src'

    print('=== law.struct: станет ===')
    print(NEW_STRUCT)
    print('\n=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src добавится ===')
    print(NEW_SRC)

    if write:
        deal['law']['struct'] = NEW_STRUCT
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].append(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
