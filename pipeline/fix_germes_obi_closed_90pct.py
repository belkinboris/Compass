# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка ga1935680
(Компания «Гермес» приобретает 65% в российском бизнесе сети OBI) —
карточка держала статус «Обсуждается» (только одобрение ФАС), хотя
сделка закрылась, а версия о связи «Гермеса» с «Севергрупп» (со ссылкой
на отраслевое издание Shopper's) с тех пор подтвердилась несколькими
независимыми СМИ.

Проверено лично прямым WebFetch (interfax.ru/business/1036100,
14.07.2025, 14:17): «ООО "Гермес" закрыло сделку по приобретению 65% в
трех юрлицах сети строительных гипермаркетов OBI», «В результате доля
"Гермеса" в компаниях увеличилась до 90%», «Остальные 10% в юрлицах
принадлежат АО "Аллонж", которое СМИ связывают со структурами ХК
"Синдика"».

`status`: «Обсуждается» → «Закрыта». `title` переписан с настоящего
времени («приобретает») на завершённое действие. `eco.val` заполнен
экспертной оценкой всего бизнеса OBI (стоял прочерком). `law.appr`
дополнен фактом закрытия.

НЕ ВКЛЮЧЕНО (сознательно, чтобы не задваивать уже заведённые карточки):
дальнейшая консолидация актива под «Севергрупп» (покупка у «Синдики»,
апрель 2025 — закрыта январь 2026) уже описана отдельной карточкой
`gcdd2b6de` («Севергрупп выкупил сеть магазинов OBI у Синдики»,
`buyer`/`seller` уже проставлены, включая явную фразу «актив перешёл
группе "Лента" через ООО "Гермес"» — тот же «Гермес», что и в этой
карточке); переход бизнеса к «Ленте» и ребрендинг в «Дом Лента» — тоже
отдельная карточка `g02eed099` («Группа Лента приобрела активы сети OBI
Россия»). Обе уже несут подробности (структуру сделки, стратегию
«Ленты», ребрендинг) — переносить их сюда значило бы показывать один и
тот же факт под тремя разными подписями. Эта карточка остаётся про свой
собственный, более ранний и узкий шаг: закрытие покупки 65% (общая доля
«Гермеса» выросла до 90%).

Запуск: python3 pipeline/fix_germes_obi_closed_90pct.py
        python3 pipeline/fix_germes_obi_closed_90pct.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'ga1935680'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Закрыта'

OLD_TITLE = 'Компания «Гермес» приобретает 65% в российском бизнесе сети OBI'
NEW_TITLE = 'Компания «Гермес» закрыла сделку по приобретению 65% в российском бизнесе сети OBI'

OLD_CONTEXT = (
    'ООО «Гермес» было зарегистрировано в марте этого года в '
    'Санкт-Петербурге, его единственный владелец — некий Владимир '
    'Захватошин, о котором практически ничего не известно. В апреле '
    '«Гермес» уже приобрел по 25% трех юрлиц, которые управляют '
    'магазинами OBI в России. Отраслевое издание Shopper\'s тогда '
    'сообщало, что долю в OBI купили структуры, связанные с '
    '«Севергрупп» Алексея Мордашова. Дальнейшим развитием OBI может '
    'заняться подконтрольная «Севергрупп» сеть «Лента».'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' Сделка закрылась: «ООО "Гермес" закрыло сделку по приобретению '
    '65% в трех юрлицах сети строительных гипермаркетов OBI», «В '
    'результате доля "Гермеса" в компаниях увеличилась до 90%. '
    'Остальные 10%... принадлежат АО "Аллонж", которое СМИ связывают со '
    'структурами ХК "Синдика"» (Интерфакс, 14 июля 2025 года). Связь '
    '«Гермеса» с «Севергрупп» с тех пор подтвердили и другие СМИ.'
)

OLD_VAL = '—'
NEW_VAL = (
    'По оценке гендиректора Infoline-Аналитики Ивана Федякова, весь '
    'бизнес OBI в России может стоить до 5 млрд ₽ (dp.ru, 14 июля 2025 '
    'года).'
)

OLD_APPR = 'ФАС одобрила сделку по продаже контрольной доли OBI.'
NEW_APPR = OLD_APPR + (
    ' Сделка закрылась 14 июля 2025 года (Интерфакс).'
)

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/business/1036100'],
    ['dp.ru', 'https://www.dp.ru/a/2025/07/14/germes-priobrjol-65-dolej'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS
    assert deal['title'] == OLD_TITLE
    assert deal['eco']['context'] == OLD_CONTEXT
    assert deal['eco']['val'] == OLD_VAL
    assert deal['law']['appr'] == OLD_APPR

    new_src = deal['src'] + NEW_SRC

    print('=== status: станет ===')
    print(NEW_STATUS)
    print('\n=== title: станет ===')
    print(NEW_TITLE)
    print('\n=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== eco.val: станет ===')
    print(NEW_VAL)
    print('\n=== law.appr: станет ===')
    print(NEW_APPR)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['status'] = NEW_STATUS
        deal['title'] = NEW_TITLE
        deal['eco']['context'] = NEW_CONTEXT
        deal['eco']['val'] = NEW_VAL
        deal['law']['appr'] = NEW_APPR
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
