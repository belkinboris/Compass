import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'ga28b511a'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Закрыта'

OLD_DATE = '2024'
NEW_DATE = '2023-09-29'

OLD_EXTRA = (
    'Сделка по приобретению винодельческого предприятия «Вина '
    'Лефкадии» в Саук-Дере Краснодарского края. Покупатель — ООО '
    '«Терруары Саук-Дере», подконтрольное собственнику винодельни '
    '«Мысхако» Алексею Сидюкову. Продавец — семья Михаила Николаева. В '
    'сделку входит около 300 га земли и госколлекция вин СССР. Статус '
    'сделки: в процессе закрытия.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Сделка закрылась 29 сентября 2023 года (смена учредителя по '
    'ЕГРЮЛ); семья Николаева сохранила другую винодельню — «Лефкадию» '
    'в селе Молдаванское. В апреле 2025 года завод переименован в '
    '«Винодельню Саук-Дере», но показатели ухудшились: выручка упала '
    'на 69% до 10,8 млн руб. за 2025 год, штат сократился с 11 до 6 '
    'человек; обещанные 200 рабочих мест и 3 млрд руб. инвестиций '
    'публично не подтверждены. В апреле 2026 года суд по иску '
    'Генпрокуратуры изъял в доход государства весь бизнес Алексея '
    'Сидюкова (62,5 млрд руб., в том числе винодельни «Саук-Дере», '
    '«Раевское» и «Мысхако») — купленный этой сделкой актив теперь '
    'принадлежит государству.'
)

NEW_SRC = [
    ['Коммерсантъ Краснодар', 'https://www.kommersant.ru/doc/6184599'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6934176'],
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8727295'],
    ['Audit-it.ru', 'https://www.audit-it.ru/contragent/1052320814897_ooo-vina-lefkadii'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS
    assert deal['date'] == OLD_DATE
    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== status: станет ===')
    print(NEW_STATUS)
    print('\n=== date: станет ===')
    print(NEW_DATE)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['status'] = NEW_STATUS
        deal['date'] = NEW_DATE
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
