# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), три карточки.
Все факты проверены ЛИЧНО прямым WebFetch.

1) ksk (ГК «Дело»/Cargill, зерновой терминал КСК): личный WebFetch
   kommersant.ru/doc/8878930 (13.08.2026) — ГК «Дело» приостановила
   операционную деятельность терминала в ночь на 12 августа 2026 года
   после массированной атаки украинских беспилотников на Краснодарский
   край, повредившей инфраструктуру («Мера принята ради безопасности
   работников и инфраструктуры»); подтверждения возобновления работы на
   дату этого прогона (7 сентября 2026) не нашлось. Юридический
   консультант Cargill и официальная сумма сделки по-прежнему нигде не
   названы — не вносится (честная неопределённость остаётся).

2) mercedes («Автодом»/российские активы Mercedes-Benz, завод в
   Есипово): личный WebFetch lenta.ru/news/2024/05/27/new-brand/
   (27.05.2024) — «Автодом» объявил о планах выпускать на заводе
   автомобили под собственным брендом (позже зарегистрирован как
   Maxeed), инвестиции могут достичь 10 млрд ₽, в перспективе — до
   восьми моделей. Более поздние (2025-2026) сведения о ходе выпуска
   противоречивы и не подтверждены дословной цитатой (сайты 403/401,
   неподтверждённые упоминания Exeed) — не вносятся, честная
   неопределённость остаётся; юридический консультант продавца
   (Mercedes-Benz) по-прежнему не найден.

3) technored (ГК «Вартон»/«Технорэд»): личный WebFetch comnews.ru
   (11.07.2025) — примиряет уже стоявший в карточке факт (основатель
   Артём Лукин: «Вартон» не владеет контрольным пакетом, выкуп 49%,
   подтверждено ЕГРЮЛ) с исходным планом фонда «Сколково» (поэтапное
   доведение до 51%) — оба факта из одного источника, противоречия нет:
   49% — статус на сегодня, 51% — недостигнутая цель плана. Тот же
   источник называет выручку ООО «Технорэд» за 2024 год — 640 млн ₽
   (поле eco.target_fin было пустым). Личный WebFetch kommersant.ru/
   doc/7872900 (10.07.2025) — общий объём инвестиций в партнёрство до
   2030 года — около 6,5 млрд ₽, сроки возможного IPO — 2028–2030 годы.

Запуск: python3 pipeline/fix_monthly_2026_09_07_ksk_mercedes_technored.py
        python3 pipeline/fix_monthly_2026_09_07_ksk_mercedes_technored.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

KSK_OLD_CONTEXT = (
    'Cargill с сезона 2023/24 прекратил экспорт российского зерна и '
    'пересматривал портфель. За трейдером в РФ остались перерабатывающие '
    'активы'
)
KSK_NEW_CONTEXT = (
    KSK_OLD_CONTEXT + '. В ночь на 12 августа 2026 года массированная '
    'атака украинских беспилотников на Краснодарский край повредила '
    'инфраструктуру терминала, и «Дело» приостановило его операционную '
    'деятельность ради безопасности работников и инфраструктуры; '
    'подтверждения возобновления работы пока нет.'
)

MERC_OLD_CONTEXT = (
    'Mercedes объявил об уходе в октябре 2022 года. На покупку '
    '«Мерседес-Бенц Банк Рус» потребовалось отдельное разрешение '
    'президента, полученное в феврале 2023 года.'
)
MERC_NEW_CONTEXT = (
    MERC_OLD_CONTEXT + ' В мае 2024 года «Автодом» объявил о планах '
    'выпускать на заводе в Есипово автомобили под собственным брендом '
    '(позже зарегистрирован как Maxeed): инвестиции могут достичь '
    '10 млрд ₽, в перспективе компания рассчитывает вывести на рынок до '
    'восьми моделей.'
)

TR_OLD_CONTEXT = (
    'Technored совместно с «Астрой» за пять лет планирует выпустить не '
    'менее 25 тыс. роботов и робототехнических комплексов, а также '
    'провести IPO.'
)
TR_NEW_CONTEXT = (
    TR_OLD_CONTEXT + ' Общий объём инвестиций в партнёрство до 2030 '
    'года может составить около 6,5 млрд ₽; выйти на IPO стороны '
    'рассчитывают в 2028–2030 годах. Первоначальный план предусматривал '
    'поэтапное доведение доли «Вартона» до 51%, но по состоянию на июль '
    '2025 года, по данным ЕГРЮЛ, «Вартон» владеет 49,02% без '
    'контрольного пакета.'
)

TR_OLD_TARGET_FIN = '—'
TR_NEW_TARGET_FIN = 'Выручка ООО «Технорэд» за 2024 год — 640 млн ₽.'


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    ksk = by_id['ksk']
    merc = by_id['mercedes']
    tr = by_id['technored']

    assert ksk['eco']['context'] == KSK_OLD_CONTEXT
    assert merc['eco']['context'] == MERC_OLD_CONTEXT
    assert tr['eco']['context'] == TR_OLD_CONTEXT
    assert tr['eco']['target_fin'] == TR_OLD_TARGET_FIN

    print('=== ksk: eco.context ===')
    print(KSK_NEW_CONTEXT)
    print()
    print('=== mercedes: eco.context ===')
    print(MERC_NEW_CONTEXT)
    print()
    print('=== technored: eco.context ===')
    print(TR_NEW_CONTEXT)
    print()
    print('=== technored: eco.target_fin ===')
    print(TR_NEW_TARGET_FIN)

    if write:
        ksk['eco']['context'] = KSK_NEW_CONTEXT
        merc['eco']['context'] = MERC_NEW_CONTEXT
        tr['eco']['context'] = TR_NEW_CONTEXT
        tr['eco']['target_fin'] = TR_NEW_TARGET_FIN
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
