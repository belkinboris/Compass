import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

PEK_ID = 'cdcc6f67f'
PEK_OLD_CONTEXT = (
    'Источник информации указывает на переговоры между логистическими '
    'операторами и российскими страховыми компаниями. ПЭК рассматривает '
    'приобретение страховой компании с лицензией без существенного '
    'бизнеса. «Деловые линии» изучают различные страховые компании, '
    'включая СК «Абсолют Страхование», однако компания информацию не '
    'подтвердила.'
)
PEK_NEW_CONTEXT = (
    PEK_OLD_CONTEXT + ' Обе истории закончились без сделки для этих '
    'логистических операторов. Переговоры ПЭК декабря 2025 года не '
    'состоялись — совладелец компании подтвердил, что конкретных '
    'решений не принималось. СК «Абсолют Страхование» ушла другому '
    'покупателю: 26 июня 2026 года 100% страховщика перешли к ОАО '
    '«ЦАНЦ», «Деловые линии» среди сторон этой сделки не упоминаются.'
)

WB_ID = 'c0bc92892'
WB_OLD_CONTEXT = (
    'Статья описывает активный поиск Wildberries подходящего объекта '
    'для покупки. Ряд компаний уже предложен к рассмотрению.'
)
WB_NEW_CONTEXT = (
    WB_OLD_CONTEXT + ' Закрытия именно этой сделки (0,5–1 млрд ₽) нигде '
    'не подтверждено. Более поздний и гораздо более крупный сюжет — '
    'переговоры о покупке «Росгосстраха» у ВТБ (оценка около 50 млрд ₽)'
    ' — публично опровергнут обеими сторонами в июне 2026 года: глава '
    'ВТБ Андрей Костин заявил, что РВБ «не входит в число претендентов '
    'на покупку «Росгосстраха»». Страховые сервисы платформы к 2026 '
    'году запущены через партнёрства с существующими страховщиками '
    '(страхование от атак БПЛА, «СберСтрахование» для продавцов), а не '
    'через покупку лицензии.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    pek = by_id[PEK_ID]
    wb = by_id[WB_ID]

    assert pek['eco']['context'] == PEK_OLD_CONTEXT
    assert wb['eco']['context'] == WB_OLD_CONTEXT

    print('=== cdcc6f67f: eco.context ===')
    print(PEK_NEW_CONTEXT)
    print()
    print('=== c0bc92892: eco.context ===')
    print(WB_NEW_CONTEXT)

    if write:
        pek['eco']['context'] = PEK_NEW_CONTEXT
        wb['eco']['context'] = WB_NEW_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
