"""Дочитывание раздела «Известные проблемы» CLAUDE.md, партия 3 (11 сентября 2026).

Что чинит и почему. Владелец попросил пройтись по всем карточкам, отправленным
на решение создателей с доп. вопросами, и найти ответы самостоятельно —
прямым чтением источников. Ниже — правки, для которых нашлось однозначное
подтверждение (не судьба, а факт).

1. `gad633118` (Приобретение СП «Каталитик Пипл» 25% Selectel) — `buyer` и
   `target` перепутаны местами: `target` указывал на профиль ПОКУПАТЕЛЯ
   («Каталитик Пипл»), а `buyer` был пуст. Источник карточки (CNews,
   cnews.ru/news/top/2025-12-29_nezavisimyj_it-provajder, уже в `src`):
   «"Каталитик Пипл" купила 25% в фирме Selectel» — Каталитик Пипл
   однозначно покупатель, Selectel — предмет (профиль `gd4a7c612`,
   «ООО «Селектел»», уже существует и не был задействован).

2. `ccdd90216` («Менеджмент выкупает часть бизнеса гипермаркетов «О'Кей»»)
   — `status` стоял «Закрыта» на дате РЕШЕНИЯ СОВЕТА ДИРЕКТОРОВ, а не
   закрытия. Собственный источник карточки (Интерфакс,
   interfax.ru/business/1000764, 26.12.2024) прямо пишет: «информация о
   подписании основного договора и закрытии сделки не приводится» —
   решение принято, сделка не закрыта. Это первая, более ранняя стадия
   той же саги, что и `g31136d69` (закрытие 25.11.2025) — отдельная
   карточка сохранена (у неё дата решения совета директоров, а не
   закрытия), но статус приведён в соответствие с её же источником.

3. `g4cb8fc20` («Росатом интересуется... «Техсервис»») — статус
   «Обсуждается» → «Не состоялась»: интерес «Росатома» (Эльконский ГМК)
   упоминается ровно в одной статье 2022 года про due diligence и больше
   НИ РАЗУ ни в одном источнике за три года; актив в итоге продан
   совсем другому покупателю (Ростех → «ИГ Геоинвест», октябрь 2025,
   карточка `gadb5b474`, уже в базе, с другим продавцом и структурой).

4. `g017cd5b4` («АФК «Система» инвестирует в «Моторику»») — статус
   «Обсуждается» → «Не состоялась»: за три с лишним года НИ ОДИН из
   четырёх независимых каналов (ЕГРЮЛ на дату публикации, годовой отчёт
   компании за 2025 год, вход Газпромбанка в декабре 2024, раунд
   ЗПИФ УК «Первая» на 900 млн ₽ в июне 2024) не называет АФК «Система»
   ни инвестором, ни акционером — при этом компания продолжает
   привлекать капитал от НАЗВАННЫХ других сторон, то есть переговоры
   2023 года закрытием не завершились.

Запуск: сухой прогон без аргументов, запись — `--write`. Проверки
исходного состояния — `assert` перед каждой правкой.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "static" / "data" / "deals_promoted.json"


def main(write=False):
    data = json.loads(DATA.read_text(encoding="utf-8"))
    deals = {d["id"]: d for d in data["deals"]}
    changes = []

    # 1. gad633118 — buyer/target swap
    d = deals["gad633118"]
    assert d.get("target") == "g62dd02d2" and not d.get("buyer"), \
        "gad633118: ожидались target=g62dd02d2, buyer пуст"
    assert "gd4a7c612" in data["companies"], "профиль ООО «Селектел» не найден"
    d["buyer"] = "g62dd02d2"
    d["target"] = "gd4a7c612"
    changes.append("gad633118: buyer/target возвращены на свои места "
                    "(Каталитик Пипл — покупатель, Селектел — предмет)")

    # 2. ccdd90216 — status
    d = deals["ccdd90216"]
    assert d.get("status") == "Закрыта", "ccdd90216: ожидался статус «Закрыта»"
    d["status"] = "Обсуждается"
    changes.append("ccdd90216: status Закрыта → Обсуждается "
                    "(дата — решение совета директоров, не закрытие)")

    # 3. g4cb8fc20 — status
    d = deals["g4cb8fc20"]
    assert d.get("status") == "Обсуждается", "g4cb8fc20: ожидался статус «Обсуждается»"
    d["status"] = "Не состоялась"
    changes.append("g4cb8fc20: status Обсуждается → Не состоялась "
                    "(интерес не подтверждён за три года, актив продан другому)")

    # 4. g017cd5b4 — status
    d = deals["g017cd5b4"]
    assert d.get("status") == "Обсуждается", "g017cd5b4: ожидался статус «Обсуждается»"
    d["status"] = "Не состоялась"
    changes.append("g017cd5b4: status Обсуждается → Не состоялась "
                    "(четыре независимых канала за три года не находят АФК «Система»)")

    # 5. g9f76fe60 — уже поставленный в карточке открытый вопрос теперь
    #    закрыт: доля осталась у «СМ», новых бенефициаров зовут по имени.
    d = deals["g9f76fe60"]
    old_frag = "Осталась ли доля РЧФ у «СМ» под новыми владельцами или перешла к кому-то ещё, публично не раскрывалось."
    assert old_frag in (d.get("extra") or ""), "g9f76fe60: ожидаемая фраза не найдена в extra"
    new_frag = ("По данным ЕГРЮЛ на 2026 год, доля осталась у «СМ»: 25% в РЧФ "
                "по-прежнему принадлежит этой компании, не переоформлены.")
    d["extra"] = d["extra"].replace(old_frag, new_frag)
    changes.append("g9f76fe60: extra — закрыт открытый вопрос о судьбе доли "
                    "(осталась у «СМ», список её долей на 2026 год: Буре 84%, "
                    "Шатрова 10%, «Магнето» 6%)")

    print("\n".join(changes))
    if write:
        DATA.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        print("Записано.")
    else:
        print("Сухой прогон. --write для записи.")


if __name__ == "__main__":
    main("--write" in sys.argv)
