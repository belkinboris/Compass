# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень): mts-bik («МТС
продала 49,9% башенной компании БИК фонду "Инвестиции 18"»). Личный
WebFetch smart-lab.ru (07.07.2026 и 01.09.2026).

Две другие карточки захода — `selectel-itmo` (СП Selectel/ИТМО по
AI-агентам) и `absolut-strah` (ЦАНЦ/«Абсолют Страхование») — честный
пустой результат: у первой единственный найденный кандидат (дата
регистрации ООО «ЭМС» как 100%-й структуры Selectel до объявления доли
ИТМО) не подтверждён личным WebFetch надёжным адресом с датой — не
вносится; у второй находка (подтверждение рейтинга «Эксперт РА» от
30 марта 2026) целиком относится к периоду ДО закрытия сделки и
дублирует уже стоящие в `eco.target_fin` показатели (премии, активы,
капитал, рейтинг) — не даёт ничего нового по существу. Обе карточки
только помечены `--mark-followup`, без записи в JSON.

Находка по mts-bik — независимый аналитический разбор, а не
установленный факт, поэтому вносится с явной атрибуцией мнению
конкретного автора, а не как утверждение:
1) smart-lab.ru/blog/1325414.php (07.07.2026): «Раньше УК
   «Доверительная» носила название «Система Капитал» (кому
   принадлежала — понятно из названия)» — управляющая компания
   покупателя ранее была связана с АФК «Система» (материнской
   структурой МТС); тот же автор предполагает, что доля передана
   временно ради разгрузки баланса, с расчётом на обратный выкуп с
   премией.
2) smart-lab.ru/blog/1346490.php (01.09.2026): разбор отчёта МТС за
   2 квартал 2026 года — без разового дохода от продажи доли БИК P/E
   был бы около 7,14 против отчётных 3,51; при этом чистый долг группы
   вырос на 31% кв/кв (492,5 → 645,2 млрд ₽) — то есть вырученные
   деньги не пошли на снижение долга напрямую.

Запуск: python3 pipeline/fix_monthly_2026_09_07_mts_bik_analysis.py
        python3 pipeline/fix_monthly_2026_09_07_mts_bik_analysis.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'mts-bik'
OLD_CONTEXT = (
    'Взаимные опционы: у МТС — право выкупить проданную долю обратно '
    'при наступлении определённых обстоятельств'
)
NEW_CONTEXT = (
    OLD_CONTEXT + '. Независимый разбор на smart-lab.ru обращает '
    'внимание, что управляющая компания покупателя, «Доверительная», '
    'ранее называлась «Система Капитал» и была связана с АФК '
    '«Система» — материнской структурой МТС; по мнению автора разбора, '
    'доля могла быть передана временно ради разгрузки баланса МТС, с '
    'расчётом на использование опциона обратного выкупа с премией. Тот '
    'же источник отмечает, что без разового дохода от продажи доли P/E '
    'МТС за 2 квартал 2026 года составил бы около 7,14 против отчётных '
    '3,51, а чистый долг группы за квартал вырос на 31% (492,5 → 645,2 '
    'млрд ₽).'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}
    deal = by_id[DEAL_ID]

    assert deal['eco']['context'] == OLD_CONTEXT

    print('=== mts-bik: eco.context ===')
    print(NEW_CONTEXT)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
