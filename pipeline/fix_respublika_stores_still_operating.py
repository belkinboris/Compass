# -*- coding: utf-8 -*-
"""Месячная очередь качества, 11 сентября 2026 — карточка `c6eb3063c`
(«Продажа бренда и сайта книжной сети «Республика» в рамках
банкротства», 24 июля 2023) описывала только продажу товарных знаков
Дмитрию Алиеву; что стало с самой сетью магазинов дальше — было
неизвестно.

Личный WebFetch подтвердил дословно (Retail.ru, 6 августа 2026,
https://www.retail.ru/news/knizhnaya-set-respublika-smenila-sobstvennika-6-avgusta-2026-280712/):
«В настоящее время все действующие девять магазинов «Республики»
находятся в Москве»; «По итогам 2025 года выручка ООО «Пролайф»
сократилась на 20% — до 711,7 млн руб., а чистый убыток почти
удвоился, достигнув 94,3 млн руб.»; «Владельцем компании «Интел-руал»
(контролирует сеть «Республика» через ООО «Пролайф») стало ООО
«Индекс», которое принадлежит АО «Концерн производительных сил»».

Магазины под брендом продолжают работать — сеть не куплена «только
ради актива». Прямой связи между покупкой Алиевым товарных знаков и
операционной компанией «ПроЛайф» источник не устанавливает — это
зафиксировано честно, без досочинённой связки.

Запуск:
    python3 pipeline/fix_respublika_stores_still_operating.py            # сухой прогон
    python3 pipeline/fix_respublika_stores_still_operating.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

NEW_ECO_VAL = (
    'Магазины сети продолжают работать под брендом «Республика» — на '
    'август 2026 года девять точек в Москве. У компании, управляющей '
    'сетью (ООО «Интел-руал»/«Пролайф»), в 2026 году сменился владелец '
    '— им стало ООО «Индекс» (АО «Концерн производительных сил»); '
    'выручка «Пролайфа» за 2025 год — 711,7 млн ₽, убыток — 94,3 млн ₽. '
    'Прямая связь этой компании с покупкой товарных знаков Алиевым в '
    'открытых источниках не установлена.'
)

NEW_SRC = ['Retail.ru', 'https://www.retail.ru/news/knizhnaya-set-respublika-smenila-sobstvennika-6-avgusta-2026-280712/']


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['c6eb3063c']

    assert d['eco'].get('val') in (None, '—'), 'eco.val уже занят: %r' % (d['eco'].get('val'),)
    urls = {s[1] for s in d['src']}
    assert NEW_SRC[1] not in urls, 'источник уже добавлен'

    print('c6eb3063c: eco.val заполнен (сеть продолжает работать, смена '
          'владельца управляющей компании в 2026 году); добавлен источник')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['eco']['val'] = NEW_ECO_VAL
    d['src'].append(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
