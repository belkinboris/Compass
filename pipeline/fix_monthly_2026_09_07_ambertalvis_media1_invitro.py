def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    at = by_id[AT_ID]
    m1 = by_id[M1_ID]
    inv = by_id[INV_ID]

    assert at['date'] == AT_OLD_DATE
    assert at.get('status') == AT_OLD_STATUS
    assert at['eco']['share'] == AT_OLD_SHARE
    assert at['eco']['context'] == AT_OLD_CONTEXT
    assert m1['eco']['val'] == M1_OLD_VAL
    assert inv['eco']['context'] == INV_OLD_CONTEXT

    print('=== at: date ===', AT_NEW_DATE)
    print('=== at: status ===', AT_NEW_STATUS)
    print('=== at: eco.share ===')
    print(AT_NEW_SHARE)
    print('=== at: eco.context ===')
    print(AT_NEW_CONTEXT)
    print()
    print('=== m1: eco.val ===')
    print(M1_NEW_VAL)
    print()
    print('=== inv: eco.context ===')
    print(INV_NEW_CONTEXT)

    if write:
        at['date'] = AT_NEW_DATE
        at['status'] = AT_NEW_STATUS
        at['eco']['share'] = AT_NEW_SHARE
        at['eco']['context'] = AT_NEW_CONTEXT
        m1['eco']['val'] = M1_NEW_VAL
        inv['eco']['context'] = INV_NEW_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
