import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_CONTEXT_ANTIPOV = (
    'Активы бизнесмена Юрия Антипова, включая Челябинский '
    'электрометаллургический комбинат, передаются «Ростеху». Решение '
    'суда об обращении активов в госсобственность принято в феврале.'
)
NEW_CONTEXT_ANTIPOV = OLD_CONTEXT_ANTIPOV + (
    ' Спустя почти два года план не исполнен: по данным ЕГРЮЛ на '
    '20 февраля 2026 года предприятие по-прежнему принадлежит '
    'напрямую Российской Федерации (Росимуществу), передачи «Ростеху» '
    'и продажи 75% частному инвестору не произошло. Новым генеральным '
    'директором с 19 февраля 2026 года назначен Вячеслав Попков — '
    'бывший топ-менеджер Трубной металлургической компании (ТМК), '
    'структуры которой СМИ в 2024 году называли вероятным частным '
    'инвестором.'
)

OLD_CONTEXT_MOEX = (
    'По неофициальным данным, биржа интересовалась покупкой одного '
    'бутикового брокера, но тот отказался от продажи.'
)
NEW_CONTEXT_MOEX = OLD_CONTEXT_MOEX + (
    ' По закону «Об организованных торгах» биржа не вправе совмещать '
    'организацию торгов с брокерской, дилерской и депозитарной '
    'деятельностью — но прямого запрета на владение такой компанией '
    'нет, что и открывает бирже путь к покупке.'
)


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    antipov = by_id['c1d2ba2c0']
    moex = by_id['c90380a10']
    mts = by_id['c6a6cb6ee']

    assert antipov.get('status') is None, 'c1d2ba2c0 status уже занят: %r' % (antipov.get('status'),)
    assert antipov['eco']['context'] == OLD_CONTEXT_ANTIPOV, \
        'c1d2ba2c0 eco.context уже другой: %r' % (antipov['eco']['context'],)
    assert moex['eco']['context'] == OLD_CONTEXT_MOEX, \
        'c90380a10 eco.context уже другой: %r' % (moex['eco']['context'],)
    assert mts.get('status') is None, 'c6a6cb6ee status уже занят: %r' % (mts.get('status'),)

    print('c1d2ba2c0: status None -> "Обсуждается"; eco.context дополнен '
          '(национализация состоялась, но передачи «Ростеху» и продажи '
          '75% не произошло)')
    print('c90380a10: eco.context дополнен (правовое основание интереса '
          'биржи к владению брокером)')
    print('c6a6cb6ee: status None -> "Обсуждается" (программа анонсирована, '
          'исход не подтверждён)')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    antipov['status'] = 'Обсуждается'
    antipov['eco']['context'] = NEW_CONTEXT_ANTIPOV
    moex['eco']['context'] = NEW_CONTEXT_MOEX
    mts['status'] = 'Обсуждается'

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
