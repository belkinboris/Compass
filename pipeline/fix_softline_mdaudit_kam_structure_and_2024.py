# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка gaa0ca672
(ГК Softline приобрела контроль в «МД Аудит») — сделка была раскрыта
структурно неточно: карточка держала «МД Аудит» напрямую предметом
сделки, хотя Softline купил долю в её ВЛАДЕЛЬЦЕ (армянском ООО «Кам»), а
не в самой целевой компании; финансы предмета не обновлены за 2024 год.
Проверено лично прямым WebFetch https://www.cnews.ru/news/top/2025-03-13_softline_potratit_bolshe_300_mln
(CNews, 13.03.2025).

1) `eco.val` (дополнено) — структура сделки. Дословно: ««МД Аудит» и ее
владелец армянское ООО «Кам» были приобретены за краткосрочное
вознаграждение в размере 94 млн руб. и долгосрочное условное
вознаграждение в размере 69 млн руб.» Softline получил 75% долю в этих
компаниях; «Вся компания оценена в 217 млн руб.» — это оценка САМОГО
«Кам» (владельца), а не только «МД Аудит».

2) `eco.target_fin` (дополнено) — отчётность «МД Аудит» за 2024 год.
Дословно: «В 2024 г. выручка «МД Аудит» составила 173,4 млн руб., чистая
прибыль - 70,1 млн руб.» — рост под контролем Softline (2023: 128,7/60
млн → 2024: 173,4/70,1 млн).

3) `extra` (дополнено) — судьба заявленной «серии M&A-сделок для ритейл-
платформы». Дословно: сделки Softline (МД Аудит и параллельная сделка с
«Визитек», март 2025) «не преподносятся как связанная серия... одна – для
промышленности, вторая – для ритейла» — на март 2025 заявленная в июне
2024 ритейл-серия пока состоит только из самой «МД Аудит», второй
сделки для того же кластера не нашлось.

НЕ ВКЛЮЧЕНО: имя физического или юридического лица, продавшего долю в
ООО «Кам», — ни Ведомости (2024), ни CNews (2025) его не называют; CNews
лишь пишет, что с 2020 года компания «неоднократно меняла владельцев»
(кипрские и американские структуры) — недостаточно для структурного поля
`seller`, оставлено текстом в уже существующем `eco.context`.
Консультанты и согласование ФАС — не найдены ни в одном источнике.

Запуск: python3 pipeline/fix_softline_mdaudit_kam_structure_and_2024.py
        python3 pipeline/fix_softline_mdaudit_kam_structure_and_2024.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gaa0ca672'

OLD_VAL = (
    '163 млн рублей (94 млн краткосрочное отложенное возмещение + 69 млн '
    'долгосрочное условное вознаграждение).'
)
NEW_VAL = OLD_VAL + (
    ' Softline получил 75% долю не в самой «МД Аудит», а в её владельце — '
    'армянском ООО «Кам»; вся компания «Кам» оценена в 217 млн ₽ (CNews).'
)

OLD_TARGET_FIN = (
    'Выручка «МД Аудит» в 2023 г. достигла 128,7 млн руб. при чистой '
    'прибыли 60 млн руб.'
)
NEW_TARGET_FIN = OLD_TARGET_FIN + (
    ' В 2024 году, уже под контролем Softline, выручка «МД Аудит» выросла '
    'до 173,4 млн руб., чистая прибыль — до 70,1 млн руб. (CNews).'
)

OLD_EXTRA = (
    'Сделка по приобретению контрольной доли в облачном сервисе для '
    'управления стандартами и бизнес-процессами. ГК Softline выступает '
    'покупателем через дочернюю компанию SL Soft. Первая из планируемой '
    'серии M&A-сделок для создания единой платформы автоматизации '
    'бизнес-процессов в ритейле.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' По состоянию на март 2025 года вторая сделка того же ритейл-кластера '
    'не нашлась: параллельная сделка Softline с «Визитек» (охрана труда, '
    'март 2025) — из другого направления, «не преподносятся как связанная '
    'серия... одна – для промышленности, вторая – для ритейла» (CNews).'
)

NEW_SRC = [
    ['CNews', 'https://www.cnews.ru/news/top/2025-03-13_softline_potratit_bolshe_300_mln'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['val'] == OLD_VAL
    assert deal['eco']['target_fin'] == OLD_TARGET_FIN
    assert deal['extra'] == OLD_EXTRA
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.val: станет ===')
    print(NEW_VAL)
    print('\n=== eco.target_fin: станет ===')
    print(NEW_TARGET_FIN)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['val'] = NEW_VAL
        deal['eco']['target_fin'] = NEW_TARGET_FIN
        deal['extra'] = NEW_EXTRA
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
