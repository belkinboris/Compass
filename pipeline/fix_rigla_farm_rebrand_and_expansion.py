# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g5e21a38a («"Ригла" приобрела приморскую аптечную сеть "Фарм"»,
закрыта 2023) — не были перенесены даты сделки, условия для
сотрудников, судьба бренда после интеграции и продолжение экспансии
«Риглы» в Приморье.

Проверено лично прямым WebFetch (Коммерсантъ, тот же адрес, что уже
стоит в `src` карточки, https://www.kommersant.ru/doc/6161765):
«новые аптеки будут работать под брендом «Здравсити Аптека»».

Проверено лично прямым WebFetch (UssurMedia,
https://ussurmedia.ru/news/1565366/, цитата Юрия Шандры): «договор
стороны подписали 8 августа, а 15 августа сделка была завершена»,
«Все 150 человек, которые сейчас работают в аптеках и офисе, сохранят
свои рабочие места. Формат аптеки, цены останутся прежними».

Проверено лично прямым WebFetch (РБК Приморье,
https://prim.rbc.ru/prim/16/09/2025/68c8d6f29a794773fcf8349e):
«Юрлицо было ликвидировано путем реорганизации в форме присоединения
и теперь работает под вывеской «Здравсити Аптека»»; в сентябре 2025
года «Ригла» поглотила ещё три приморские аптечные компании (ООО
«Аптека25.рф», ООО «Фарма Лайф», ООО «Аванти Фарма»).

НЕ ВКЛЮЧЕНО: точная дата ликвидации юрлица «Фарм» — встретилась только
в реестровом сниппете поисковой выдачи (не в дословно прочитанной
статье), не переношу без цитаты; отдельное согласование ФАС именно по
этой сделке — не найдено (все найденные одобрения ФАС относятся к
другим, более поздним и более крупным сделкам «Риглы» на Дальнем
Востоке); судьба остальных активов Юрия Шандры («Центроптика»,
«Медфарм», «ОптикФарм») — не нашлось журналистского материала;
юридический консультант сделки — не назван нигде.

Запуск: python3 pipeline/fix_rigla_farm_rebrand_and_expansion.py
        python3 pipeline/fix_rigla_farm_rebrand_and_expansion.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g5e21a38a'

OLD_LAW_STRUCT = (
    'По данным СПАРК-Интерфакс, 15 августа «Ригла» стала владельцем '
    '99,99% в ООО «Фарм», а оставшиеся 0,01% перешли АО «Протек»'
)
NEW_LAW_STRUCT = OLD_LAW_STRUCT + (
    '. Договор стороны подписали 8 августа, сделка завершена 15 августа. '
    'Юрлицо «Фарм» позднее ликвидировано путём реорганизации '
    'присоединением к «Ригле» и теперь работает под вывеской «Здравсити '
    'Аптека».'
)

OLD_LAW_TERMS = '—'
NEW_LAW_TERMS = (
    'По словам продавца Юрия Шандры, все 150 сотрудников аптек и офиса '
    'сохранили рабочие места, формат аптек и цены остались прежними.'
)

OLD_ECO_CONTEXT = (
    'Сеть «Фарм», основанная в 1994 году, принадлежала семье бывшего '
    'депутата городской Думы Уссурийска Юрия Шандры. Согласно данным '
    'СПАРК-Интерфакс, он также владеет уссурийским салоном '
    '«Центроптика», а также обладает долей в многопрофильном медцентре '
    '«Медфарм» и салоне «ОптикФарм»'
)
NEW_ECO_CONTEXT = OLD_ECO_CONTEXT + (
    '. В сентябре 2025 года «Ригла» продолжила экспансию в Приморье, '
    'поглотив ещё три местные аптечные компании (ООО «Аптека25.рф», ООО '
    '«Фарма Лайф», ООО «Аванти Фарма»).'
)

NEW_SRC = [
    ['UssurMedia', 'https://ussurmedia.ru/news/1565366/'],
    ['РБК Приморье', 'https://prim.rbc.ru/prim/16/09/2025/68c8d6f29a794773fcf8349e'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['law']['struct'] == OLD_LAW_STRUCT
    assert deal['law']['terms'] == OLD_LAW_TERMS
    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    new_src = deal['src'] + NEW_SRC

    print('=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)
    print('\n=== law.terms: станет ===')
    print(NEW_LAW_TERMS)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['law']['struct'] = NEW_LAW_STRUCT
        deal['law']['terms'] = NEW_LAW_TERMS
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
