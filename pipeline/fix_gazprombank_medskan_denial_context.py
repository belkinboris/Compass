# -*- coding: utf-8 -*-
"""Месячная очередь, карточка g2197ed53 («Газпромбанк может стать
акционером сети медицинских центров «Медскан»», статус «Обсуждается»):
проверка статуса незакрытой сделки — обязательный шаг. Картина оказалась
сложнее простого «переговоры продолжаются» или «переговоры сорвались».

Хронология: 16 декабря 2025 года сам основатель «Медскана» Евгений
Туголуков на прямой вопрос ведущего радио РБК, не про Газпромбанк ли
речь о новых pre-IPO инвесторах, ответил «Нет, не про это» — то есть
публично не подтвердил именно эту версию (назвав вместо неё безымянных
«серьёзных институциональных инвесторов»). При этом 3 июня 2026 года
«Ведомости» сообщили, что «Медскан» провёл допэмиссию привилегированных
акций типа А в пользу «одного из финансовых инвесторов» — представитель
компании имя не назвал, а анонимный источник издания (топ-менеджер
финансовой структуры) утверждает, что покупателем стал именно
Газпромбанк; «Росатом» при этом заявляет, что по-прежнему контролирует
«Медскан».

Ни сама компания, ни Газпромбанк публично сделку не подтвердили ни в
одну, ни в другую сторону. Статус НЕ меняется этим прогоном: слово
«приобрел» из цитаты Ведомостей формально входит в список STATUS_WORDS
для «Закрыта» в review.py, но приписывать закрытие ИМЕННО Газпромбанку
(как называет карточка) при прямом отсутствии подтверждения и with
публичным несогласием источника было бы недобросовестной точностью —
родня уже задокументированного случая БКС/«Форштадт» (24 августа 2026).
Обе стороны картины сведены в eco.context, вопрос — в CLAUDE.md
(«Известные проблемы») для решения человеком.

Источники — читал напрямую (fetch_article_texts.py, закэшированы):
https://www.kommersant.ru/doc/8293582 (16.12.2025)
https://www.vedomosti.ru/business/articles/2026/06/03/1202334-u-medskana-poyavilsya-novii-investor (03.06.2026)

Запуск: python3 pipeline/fix_gazprombank_medskan_denial_context.py [--write]
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g2197ed53'

OLD_CONTEXT = (
    'Сейчас 50% в этом обществе принадлежит структуре «Росатома», а '
    'остальное – основателю Евгению Туголукову. Размер доли, которую '
    'может приобрести Газпромбанк, и кто выступает продавцом, не '
    'раскрывается.'
)
CONTEXT_ADDITION = (
    '16 декабря 2025 года сам Туголуков на прямой вопрос о Газпромбанке '
    'ответил «Нет, не про это», назвав вместо этого безымянных «серьёзных '
    'институциональных инвесторов» в pre-IPO раунде. При этом 3 июня 2026 '
    'года «Ведомости» сообщили, что компания провела допэмиссию '
    'привилегированных акций типа А в пользу «одного из финансовых '
    'инвесторов» — представитель «Медскана» имя не назвал, а анонимный '
    'источник издания называет покупателем именно Газпромбанк; «Росатом» '
    'заявляет, что по-прежнему контролирует «Медскан». Ни сама компания, '
    'ни Газпромбанк сделку публично не подтвердили.'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + CONTEXT_ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} eco.context: += публичное опровержение Туголукова "
          f"(16.12.2025) + сообщение о допэмиссии без названного "
          f"покупателя (03.06.2026) — статус остаётся «Обсуждается», "
          f"вопрос записан в CLAUDE.md")
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
