# -*- coding: utf-8 -*-
"""Карточка c51d0bb64 («Партнерство Wildberries и ВТБ по развитию WB Банка»):
новый этап 30 октября 2026 года — черновик d16904700 («ВТБ и RWB активно
финализируют подготовку сделки по покупке доли в WB-банке», data/inbox/hold/
2026-10-30.json, источник ПРАЙМ) оказался не новой сделкой, а продолжением
этой самой: тот же покупатель (ВТБ), тот же продавец/партнер (RWB =
Wildberries & Russ), тот же предмет (5% WB Банка с опционом на увеличение
доли), то же финансирование допэмиссией. Ворота придержали черновик с
ЕДИНСТВЕННОЙ причиной «не установлен предмет сделки» — разбор заголовка не
увидел сторон, и near_duplicate() с пустыми buyer/asset/seller черновика
дубль не нашел (тот же класс дефекта, что docs/duplicates.md описывает для
d50566545/«НМ-Тех», 30 октября 2026). Правило оттуда — не собирать новую
карточку, а применить исход, как при `new_stage` у resolve_duplicates.py:
дописать events[] дословной цитатой, статус не трогать (цитата не
подтверждает ни закрытие, ни срыв, а «обсуждается» уже стоит).

НОВОЕ В СТАТЬЕ 30 октября (сверх уже записанного 24 и 29 сентября): названы
точные параметры допэмиссии (до 49% акций, цена размещения 87 ₽ за акцию,
доля государства после SPO выше 50%) и причина очередной задержки — не
пересмотр условий, а юридическое оформление договора купли-продажи с рядом
взаимных гарантий. Пьянов явно говорит, что ВТБ исходит из того, что сделка
будет закрыта.

Прямым скриптом, а не review.py FIXES, — тем же приемом, что
pipeline/fix_nspk_vtb_wbbank_2026_09_24.py: generic-проверка `check()`
требует, чтобы ВЕСЬ новый текст поля eco.context лежал в цитате целиком, а
не только дописанный кусок, и добавление events[] дотированные пути
review.py не поддерживает.

Источник прочитан целиком, кэш — data/inbox/raw/2026-10-30-articles.jsonl
(https://1prime.ru/20261030/vtb-874800478.html). Корроборация: WebSearch
подтвердил ту же хронологию переносов (август → сентябрь → октябрь) и те же
условия сделки (5% WB Банка, опцион на увеличение, без контроля) в более
ранних публикациях (expert.ru, The Moscow Times, investfuture.ru,
retail.ru) — расхождений с уже записанным в карточке не нашлось. РБК
(https://www.rbc.ru/finances/30/10/2026/6ae35383e8a83604a8226ab1, черновик
d45427839 того же дня) описывает тот же звонок Пьянова, но отдает статью
только авторизованным читателям — не забран, для карточки использован
ПРАЙМ.

Запуск:
    python3 pipeline/fix_vtb_wb_bank_october_30_finalizing.py            # сухой
    python3 pipeline/fix_vtb_wb_bank_october_30_finalizing.py --write    # записать
"""
import argparse
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')
STATE = os.path.join(ROOT, 'data', 'inbox', 'moderation_state.json')

DEAL_ID = 'c51d0bb64'
DRAFT_ID = 'd16904700'
DRAFT_TITLE = 'ВТБ и RWB активно финализируют подготовку сделки по покупке доли в WB-банке'

PRIME = ['ПРАЙМ', 'https://1prime.ru/20261030/vtb-874800478.html']

OLD_CONTEXT = (
    '28 августа 2026 года первый зампред ВТБ Дмитрий Пьянов сообщил, что покупка '
    'миноритарной доли в WB-банке и финтех-активах перенесена на сентябрь, но параметры '
    'допэмиссии под нее принципиально не пересматривались: банк не форсирует сделку, '
    'понимая, что управленческие и человеческие ресурсы партнера заняты последствиями '
    'чрезвычайных событий. 31 августа 2026 года он уточнил, что допэмиссия пройдет в '
    'прежних диапазонах 300–400 млрд рублей, ближе к нижней границе, а участие розничных '
    'инвесторов будет скромным из-за разрыва в цене акций. Под вход в WB Банк ВТБ проводит '
    'допэмиссию около 500 млрд ₽ — это объем размещения акций самого банка, а не цена '
    'партнерства; стоимость доли не раскрыта. 24 сентября 2026 года глава ВТБ Андрей '
    'Костин сообщил о новом переносе: «Да, она (допэмиссия — ИФ) перенеслась, но она '
    'будет», — сказал он, отвечая на вопрос, перенеслось ли SPO на октябрь. 29 сентября '
    '2026 года Пьянов уточнил: параметры SPO (цена, объем, якорные инвесторы) не меняются, '
    'а сделку с RWB банк рассчитывает закрыть «ближе к концу октября».'
)
CONTEXT_ADD = (
    '30 октября 2026 года Пьянов сообщил, что стороны активно готовят договор '
    'купли-продажи доли в WB Банке и у них остается немного открытых вопросов — в '
    'основном по взаимным гарантиям в самом договоре, и именно его юридическое оформление, '
    'а не пересмотр условий сделки, стало причиной новой задержки; по его словам, ВТБ '
    'исходит из того, что сделка будет закрыта. Он также назвал точные параметры '
    'допэмиссии: до 49% акций ВТБ по цене размещения 87 рублей за акцию, при этом доля '
    'государства в банке после SPO останется выше 50%.'
)

EVENT = {
    'kind': 'negotiations',
    'date': '2026-10-30',
    'title': 'Договор о покупке доли в WB Банке пока не подписан — стороны согласовывают гарантии',
    'note': ('"У сторон остается небольшое количество вопросов для финализации сделки, '
             'которые нужно урегулировать и оформить юридически. Обычно этот процесс '
             'занимает продолжительное время. Сейчас стороны активно финализируют договор '
             'купли-продажи, этот договор имеет ряд взаимных гарантий, так что основной '
             'причиной отсрочки является договоротворчество", - пояснил Пьянов.'),
    'source': PRIME,
}


def main(write):
    data = json.load(open(DATA, encoding='utf-8'))
    card = next(d for d in data['deals'] if d['id'] == DEAL_ID)
    assert card['eco']['context'] == OLD_CONTEXT, 'eco.context карточки уже другой — перечитайте'
    assert len(card.get('events') or []) == 2, 'events[] карточки устроен иначе — перечитайте'
    assert card['events'][-1]['date'] == '2026-09-29', 'последнее событие уже другое — перечитайте'

    card['eco']['context'] = OLD_CONTEXT + ' ' + CONTEXT_ADD
    if PRIME[1] not in {s[1] for s in card['src'] if len(s) > 1}:
        card['src'].append(PRIME)
    card['events'].append(EVENT)

    state = json.load(open(STATE, encoding='utf-8')) if os.path.exists(STATE) else \
        {'decided_raw': {}, 'sent_raw': []}
    import re
    raw_key = lambda t: re.sub(r'[^\wа-яё]+', '', str(t or ''), flags=re.I).lower()
    state.setdefault('decided_raw', {})[DRAFT_ID] = 'enrich:%s' % DEAL_ID
    state.setdefault('raw_titles', {})[raw_key(DRAFT_TITLE)] = 'enrich:%s' % DEAL_ID

    print('%s: eco.context дополнен (этап 30 октября — финализация договора, параметры SPO)' % DEAL_ID)
    print('%s: events[] += %r' % (DEAL_ID, EVENT['title']))
    print('%s: src += %s' % (DEAL_ID, PRIME))
    print('moderation_state: %s -> enrich:%s (черновик не вернется как «новая» сделка)' % (DRAFT_ID, DEAL_ID))

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return 0

    json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    json.dump(state, open(STATE, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('Записано.')
    return 0


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('--write', action='store_true')
    main(p.parse_args().write)
