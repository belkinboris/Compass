SOURCE = ['Известия', 'https://iz.ru/2172226/denis-kuznetcov/kak-auchan-ne-uspel-realizovat-rossijskij-biznes']


def main(write):
    data = json.load(open(DATA, encoding='utf-8'))
    card = next(d for d in data['deals'] if d['id'] == CARD_ID)
    companies = data['companies']
    assert BUYER_ID in companies, 'профиль покупателя должен существовать'

    assert card.get('buyer') is None
    card['buyer'] = BUYER_ID

    assert card['eco']['context'] == OLD_ECO_CONTEXT
    card['eco']['context'] = OLD_ECO_CONTEXT + ' ' + QUOTE_HISTORY

    assert card['law']['struct'] == '—'
    card['law']['struct'] = QUOTE_LAW_MECHANISM

    assert not card.get('events')
    card['events'] = [{
        'kind': 'cancelled',
        'date': '2026-09-24',
        'title': MILESTONE_TITLE,
        'note': QUOTE_MILESTONE,
        'source': SOURCE,
    }]

    if write:
        json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
        print('Записано: buyer, eco.context, law.struct, events[cancelled].')
    else:
        print('Сухой прогон (--write, чтобы записать).')


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('--write', action='store_true')
    main(p.parse_args().write)
