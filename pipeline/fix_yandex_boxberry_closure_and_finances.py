import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g46c6e23f'

OLD_TARGET_FIN = (
    'Boxberry работает с 2010 года, развивая сервис доставки для '
    'интернет-магазинов и частных лиц. На сайте компании говорится, что '
    'у нее более 4 тыс. отделений и 640 городов присутствия. '
    'Логистическая сеть «Яндекса» насчитывает свыше 14 тыс. ПВЗ и более '
    '60 сортировочных центров.'
)
NEW_TARGET_FIN = OLD_TARGET_FIN + (
    ' Выручка «Боксберри Софт» в 2024 году выросла на 1,7% год к году, '
    'до 2,3 млрд руб., чистый убыток составил 197 млн руб. (Коммерсантъ, '
    '16 апреля 2025 года).'
)

OLD_CONTEXT = '—'
NEW_CONTEXT = (
    'Спустя четыре месяца после сделки бренд Boxberry прекратил '
    'существование: «Оператор логистических услуг Boxberry 28 августа '
    '2025 г. официально уведомили партнеров о полном прекращении '
    'деятельности своей сети пунктов выдачи заказов по всей России с '
    '1 октября» (CNews, 28 августа 2025 года) — точки перешли под бренд '
    '«Яндекс Доставки». «Пункты выдачи заказов "Яндекса" и сервис '
    '"Яндекс Доставка" появятся еще более чем в 20 регионах в разных '
    'частях страны» (Коммерсантъ, 16 апреля 2025 года).'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/7659049'],
    ['CNews', 'https://www.cnews.ru/news/top/2025-08-28_odin_iz_starejshih_servisov'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['target_fin'] == OLD_TARGET_FIN
    assert deal['eco']['context'] == OLD_CONTEXT

    new_src = deal['src'] + NEW_SRC

    print('=== eco.target_fin: станет ===')
    print(NEW_TARGET_FIN)
    print('\n=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['target_fin'] = NEW_TARGET_FIN
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
