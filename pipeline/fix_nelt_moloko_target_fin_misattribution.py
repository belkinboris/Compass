# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка gd66af0f7 (Nelt приобрёл
25% в «Moloko Group»/«Гранд Премьер»): дельта-поиск нашёл, что
eco.target_fin («Финансы предмета») на самом деле нёс финансовые
показатели ПОКУПАТЕЛЯ (Nelt), а не предмета сделки (Moloko Group) —
прочтение оригинала Коммерсанта подтверждает: рост выручки на 36,25% и
прибыли на 64,47% в тексте относятся к абзацу про Nelt («Nelt создана в
1995 году... Согласно СПАРК, по итогу 2024 года выручка компании
увеличилась на 36,25%...»), а не к Moloko Group, чья совокупная выручка
за тот же год, наоборот, СОКРАТИЛАСЬ на 3,7% до 1,22 млрд руб. Тот же
класс дефекта, что уже записан в CLAUDE.md («Число может быть верным
фактом и совсем не той величиной»), только здесь спутаны не метрики, а
стороны сделки. Не через review.py: это замена ошибочного значения на
верное (правило дословности проверяет реальность цитаты, а не то, к
какой стороне она относится).

Заодно: неверная выручка убрана из «Финансов предмета» и не потеряна —
перенесена в eco.context как справка о покупателе (бенефициар, история
компании), вместе с двумя мнениями экспертов из того же абзаца
источника, которых в карточке не было; и поправлена доля «РСХБ-Финанс»
в extra (0,75% -> точные 0,76% по тексту источника).

Источник — тот же, что уже стоит в src (kommersant.ru/doc/8139874),
перечитан напрямую (fetch_article_texts.py, закэширован).
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gd66af0f7'

OLD_TARGET_FIN = (
    'Выручка компании увеличилась на 36,25%, до 8,48 млрд руб., чистая '
    'прибыль — на 64,47%, до 83,71 млн руб.'
)
NEW_TARGET_FIN = (
    'Согласно СПАРК, совокупная выручка всех компаний холдинга Moloko '
    'Group по итогам 2024 года сократилась примерно на 3,7% и составила '
    '1,22 млрд руб. (приведённые ранее в карточке рост выручки на 36,25% '
    'до 8,48 млрд руб. и прибыли на 64,47% до 83,71 млн руб. относятся к '
    'покупателю Nelt, а не к предмету сделки — см. «Контекст»).'
)

OLD_CONTEXT = (
    'Рынок молочной продукции в России остается слабо консолидированным '
    '— 50 крупнейших игроков обеспечивают лишь половину общего объема '
    'производства.'
)
ADDITION = (
    'Покупатель, Nelt, создан в 1995 году; долгое время поставлял '
    'продукты питания иностранных брендов (Hochland Exquisa, Zott, '
    'Meggle), с 2020 года выпускает собственную молочную, мясную и '
    'кондитерскую продукцию под марками Venn’s, Marcelo Dolce, Lavka, '
    'Schönfeld, тогда же открыл площадку для выпуска сыров; бенефициар '
    'бизнеса — Кирилл Сычев. Согласно СПАРК, по итогам 2024 года выручка '
    'Nelt выросла на 36,25%, до 8,48 млрд руб., чистая прибыль — на '
    '64,47%, до 83,71 млн руб. По мнению Андрея Кучерова, уровень '
    'концентрации рынка относительно высокий, но далёк от монопольного, '
    'так как всё ещё широк круг региональных игроков; по прогнозу '
    'гендиректора «Союзмолоко» Артёма Белова, дальнейшее развитие '
    'молочной индустрии будет происходить не столько за счёт поглощений '
    'небольших компаний крупными игроками, сколько через укрупнение '
    'бизнеса.'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + ADDITION

OLD_EXTRA = (
    'Nelt, дистрибутор молочной продукции, приобрел 25% долей ГК '
    '«Moloko Group», которой принадлежит производство сыров под '
    'брендом «Гранд Премьер» в Калужской области. Продавец Илья Рагозин '
    'сохранил 74,24% капитала, «РСХБ-Финанс» остался с пакетом 0,75%.'
)
NEW_EXTRA = OLD_EXTRA.replace('0,75%', '0,76%')


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['target_fin'] == OLD_TARGET_FIN, \
        f"eco.target_fin: неожиданное значение {deal['eco']['target_fin']!r}"
    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"
    assert deal['extra'] == OLD_EXTRA, f"extra: неожиданное значение {deal['extra']!r}"

    print(f"{CARD_ID} eco.target_fin: заменено — было ошибочно финансами покупателя")
    print(f"{CARD_ID} eco.context: += справка о покупателе, два мнения экспертов")
    print(f"{CARD_ID} extra: доля РСХБ-Финанс 0,75% -> 0,76% (точность по источнику)")
    deal['eco']['target_fin'] = NEW_TARGET_FIN
    deal['eco']['context'] = NEW_CONTEXT
    deal['extra'] = NEW_EXTRA

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
