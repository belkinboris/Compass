# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), партия 21: карточка gb21ab6d1
(IPO «Алкогольная группа Кристалл», февраль 2024) уже прошла полный
обыск и недельную дельту. Дельта-поиск нашёл дальнейшую судьбу —
одно из самых слабых IPO 2024 года на Мосбирже: акция потеряла порядка
80% стоимости от цены размещения, обещанные во время IPO дивиденды
начались (0,05 руб./акция за 2024 год) и уже прекратились (за 2025 год
компания зафиксировала убыток по МСФО и отменила выплаты).

Не через review.py: `eco.context` уже не пуст (стратегия развития до
2026 года), а новые факты — из трёх разных, более поздних источников.
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gb21ab6d1'
OLD_CONTEXT = (
    'Привлеченные средства компания направит на реализацию стратегии '
    'развития до 2026 года, которая предусматривает кратный рост '
    'объемов производства и логистических мощностей, запуск новых '
    'продуктов в сегменте ЛВИ. При этом компания не планирует '
    'выплачивать дивиденды до 2-й половины 2025 года и будет '
    'использовать доходы для финансирования роста бизнеса.'
)
ADDITION = (
    'Акция оказалась одной из самых слабых среди российских IPO 2024 '
    'года: на 22 августа 2026 года она торговалась по 1,9 ₽ против '
    'цены размещения 9,5 ₽ — падение около 80%. Обещанные дивиденды '
    'начались: за 2024 год акционеры утвердили выплату 0,05 руб. на '
    'акцию (Интерфакс, 23 июня 2025) — но уже прекратились: за 2025 '
    'год компания показала по МСФО выручку 4,92 млрд ₽ (+37,6% год к '
    'году) и чистый убыток 12,8 млн ₽ (против прибыли 104 млн ₽ годом '
    'ранее, Smart-Lab), и акционеры утвердили невыплату дивидендов, '
    'направив часть добавочного капитала (2,8 млрд ₽) на погашение '
    'убытка (Коммерсантъ, 1 июля 2026).'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} eco.context: += обвал акции (~80% от цены IPO), "
          "старт и отмена дивидендов, убыток за 2025 год")
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
