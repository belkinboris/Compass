# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка gc9461b5c (Сбербанк
Инвестиции вышли из капитала «Медскан Лаб»): дельта-поиск (Vademecum,
28.10.2025) нашёл несколько фактов сверх уже известного, каждый из
разных предложений источника — не через review.py, потому что
существующий eco.context не является дословной цитатой (перефразирован
ещё до введения строгой дословности) и не образует непрерывный кусок с
новыми находками.

Четыре добавления:
1. Прямая атрибуция намерения о конвертации доли — не просто «по данным
   Forbes», а конкретное заявление основателя ГК «Медскан» Евгения
   Туголукова в июне 2025 года.
2. Другие претенденты на пакет (Газпромбанк, Виктор Харитонин) — были
   названы СМИ до сделки со Сбербанком.
3. Расхождение источников по оценке входа 2023 года записано БЕЗ
   принудительного примирения (см. CLAUDE.md, «Два независимых факта»):
   Vademecum называет иную цифру и формулировку, чем первичная заметка
   АКМ от июня 2023 года, уже стоявшая в карточке.
4. История и масштаб сети KDL на момент сделки 2025 года.

Источники — читал напрямую (fetch_article_texts.py, закэшированы):
Vademecum (28.10.2025) и AK&M (05.06.2023, отдельная более старая заметка
о входе в капитал, не та, что уже стоит в src карточки).
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gc9461b5c'

OLD_CONTEXT = (
    'По данным Forbes, стороны обсуждали возможность конвертации пакета '
    'в акции головной структуры — АО «Медскан», однако эти планы, судя '
    'по всему, реализованы не были.'
)
ADDITION = (
    'Основатель ГК «Медскан» Евгений Туголуков в июне 2025 года '
    'рассказал о намерении конвертировать долю банковского игрока из '
    'KDL в головную компанию — этот план реализован не был. Покупкой '
    'доли, по данным СМИ, интересовались также «Газпромбанк» и владелец '
    '«Фармстандарта» Виктор Харитонин. Оценка входа Сбербанк Инвестиций '
    'в 2023 году расходится между источниками: Vademecum называет '
    'приобретение 49% за 2,75 млрд рублей, тогда как АК&M в июне 2023 '
    'года сообщал о вкладе в уставный капитал «Медскан Лаб» в размере '
    '2,49 млрд рублей за ту же долю — что именно измеряет каждая цифра, '
    'из текстов однозначно не следует. Сеть KDL, включающая 13 '
    'лабораторий и более 490 медицинских офисов в 40 городах России, '
    'перешла под управление «Медскан Лаб» в декабре 2022 года после '
    'выкупа у фонда UFG Private Equity.'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} eco.context: += прямая атрибуция, другие претенденты, "
          f"расхождение оценки 2023, история KDL")
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
