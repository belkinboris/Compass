# -*- coding: utf-8 -*-
"""Качество, 8 октября 2026 — три правки мимо таблицы FIXES: факт из НОВОГО
источника дописывается/заменяет поле, уже заполненное ДРУГИМ источником
(routines/quality.md: «факт из другого источника в цитату той же записи не
дописать — отдельным скриптом, который дополняет поле, а не заменяет»).

1. `ga4d82b1c` (Danone/«Вамин Р») — `law.struct` описывал структуру на
   май 2024 (владельцы «Вамин Татарстан» 99% + Алисултанов 1%). Это уже
   НЕ ТЕКУЩИЙ факт: 6 декабря 2024 Алисултанов стал единственным (100%)
   владельцем ООО «Юнимилк» (бывший «Вамин Татарстан») — Интерфакс,
   новый источник сверх текущего `src`. Поле заменяется целиком (не
   дополняется), т.к. старая структура больше не действует.

2. `gb2bed44c` (ЛСР/«Геометрия») — `eco.share` знал только площадь
   участка; «Деловой Петербург» (новый источник) называет адрес
   (Ремесленная, 17) и план по квартирографии (477 → 350 квартир) —
   дописано.

3. `g61b33118` (Черкизово/«Руском») — `law.appr` знал только факт
   одобрения ФАС; ПРАЙМ (новый источник) называет условие предписания
   (вывод 10% продукции на биржу в течение 4 лет) — дописано.

Запуск:
    python3 pipeline/fix_2026_10_08_ownership_changes.py            # сухой прогон
    python3 pipeline/fix_2026_10_08_ownership_changes.py --write    # запись
"""
import json
import sys

sys.path.insert(0, '.')
from pipeline.ingest.review import fix_fingerprint

DATA_PATH = 'static/data/deals_promoted.json'

# --- 1. ga4d82b1c ---------------------------------------------------------
OLD_STRUCT_1 = (
    'ООО "Вамин Р" было зарегистрировано 25 сентября 2023 года. Его '
    'владельцами являются "Вамин Татарстан" (99%) и Руслан Алисултанов '
    '(1%). Бенефициар - Минтимер Мингазов.'
)
NEW_STRUCT_1 = (
    'Руслан Алисултанов стал владельцем ООО "Юнимилк" (бывшее '
    '"Вамин-Татарстан"), которое контролирует (через "Вамин-Р") компанию '
    '"Эйч энд Эн" (объединяет бывшие активы Danone в России). '
    'Соответствующие изменения отражены в ЕГРЮЛ 6 декабря 2024 года. '
    'Ранее ему принадлежал 1% компании.'
)
NEW_SRC_1 = ['Интерфакс', 'https://www.interfax.ru/business/996657']

# --- 2. gb2bed44c ----------------------------------------------------------
OLD_SHARE_2 = (
    'Участок на Петровском острове, продаваемая площадь — 30,7 тыс. кв. м.'
)
ADD_SHARE_2 = (
    ' Речь идёт об участке на Ремесленной улице, 17. Действующее '
    'разрешение предусматривает 477 квартир, однако «Геометрия» '
    'намерена сократить квартирографию примерно до 350 резиденций за '
    'счёт объединения части лотов.'
)
NEW_SRC_2 = ['Деловой Петербург', 'https://www.dp.ru/a/2026/08/03/gruppa-lsr-prodala-vtoruju']

# --- 3. g61b33118 ----------------------------------------------------------
OLD_APPR_3 = 'Сделка получила одобрение Федеральной антимонопольной службы.'
ADD_APPR_3 = (
    ' Согласно предписанию, группа «Черкизово» с середины 2025 года '
    'обязана поэтапно в течение четырёх лет вывести на биржу не менее '
    '10% от общего объёма реализуемой ею продукции на внутреннем рынке.'
)
NEW_SRC_3 = ['ПРАЙМ', 'https://1prime.ru/20241210/fas--853462241.html']


def main(write):
    data = json.load(open(DATA_PATH, encoding='utf-8'))
    deals = data['deals'] if isinstance(data, dict) else data
    by_id = {d['id']: d for d in deals}

    c1 = by_id['ga4d82b1c']
    assert c1['law']['struct'] == OLD_STRUCT_1, c1['law']['struct']
    assert NEW_SRC_1 not in (c1.get('src') or [])

    c2 = by_id['gb2bed44c']
    assert c2['eco']['share'] == OLD_SHARE_2, c2['eco']['share']
    assert NEW_SRC_2 not in (c2.get('src') or [])

    c3 = by_id['g61b33118']
    assert c3['law']['appr'] == OLD_APPR_3, c3['law']['appr']
    assert NEW_SRC_3 not in (c3.get('src') or [])

    c1['law']['struct'] = NEW_STRUCT_1
    c1.setdefault('src', []).append(NEW_SRC_1)
    absorbed1 = c1.setdefault('proofread_absorbed', {})
    fp1 = fix_fingerprint(OLD_STRUCT_1)
    absorbed1.setdefault('law.struct', [])
    if fp1 not in absorbed1['law.struct']:
        absorbed1['law.struct'].append(fp1)

    c2['eco']['share'] = OLD_SHARE_2 + ADD_SHARE_2
    c2.setdefault('src', []).append(NEW_SRC_2)

    c3['law']['appr'] = OLD_APPR_3 + ADD_APPR_3
    c3.setdefault('src', []).append(NEW_SRC_3)

    if write:
        json.dump(data, open(DATA_PATH, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
        print('ga4d82b1c: law.struct заменён (структура сменилась 06.12.2024), src дополнен.')
        print('gb2bed44c: eco.share дополнен (адрес, план по квартирографии), src дополнен.')
        print('g61b33118: law.appr дополнен (условие предписания ФАС), src дополнен. ЗАПИСАНО.')
    else:
        print('Сухой прогон: применил бы три правки выше. Повторите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
