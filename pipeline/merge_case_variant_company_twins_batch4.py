# -*- coding: utf-8 -*-
"""Шесть падежных близнецов, найденных леммой, а не именительным падежом —
четвёртая волна.

ЧТО СЛОМАНО. Прошлые волны ловили близнецов приведением головы
словосочетания к именительному падежу (`casing.py`) — метод слеп к
однословным именам-организациям (Газпром, Мираторг…), и его расширили
прямым поиском по стеблю известного бренда. Тот способ тоже требует
заранее знать, какой бренд искать. В этот раз — сплошной прогон ПО
ЛЕММЕ: каждое слово имени профиля приводится к начальной форме через
pymorphy3, и профили группируются по совпадению набора лемм. Метод шире
(не требует единственного слова и не требует, чтобы голова стояла
первой), но и шумнее — даёт много ложных совпадений там, где разные
компании называются похожими родовыми словами («Приобретение X» для
разных X, «российские активы Y» для разных Y, дочерние бренды МТС). Из
20 групп сплошного прогона шесть — настоящие падежные близнецы, у
остальных лемма совпала случайно (разные компании, общее родовое слово).

* «Группа «ВИС»» (`g40ce292b`, именительный, без сделки) / «Группы «ВИС»»
  (`gf17d6223`, родительный, сделка IPO) — инфраструктурный холдинг.
* «Группа АЗТ» (`g489c4c35`, именительный, отрасль «Здравоохранение») /
  «Группы АЗТ» (`g4353a82e`, родительный, отрасль «Фармацевтика», сделка
  «Герофарм приобрёл 49%») — ЗАОДНО отрасль была разной у двух половин
  одного профиля; сама сделка (`ind: "Фармацевтика"`, предмет —
  производство лекарств полного цикла) подтверждает «Фармацевтику».
* «Рязанская чаеразвесочная фабрика» / «Рязанской чаеразвесочной
  фабрики» — тот же рисунок, что «Окуловская бумажная фабрика» и
  «Богдановичский комбикормовый завод»: профиль вырезан из заголовка
  сделки без приведения к начальной форме.
* «Первая грузовая компания» (`gdd278a7f`, именительный, с описанием,
  сделка ВТБ 2024) / «Первой грузовой компании» (`g66c9c6cb`,
  родительный, сделка Лисин→«Аврора Инвест» 2023) — у ОБОИХ была своя
  сделка, крупнейший российский ж/д оператор годами жил двумя профилями.
* «Сахалинская энергия» / «Сахалинской энергии» — у ОБОИХ ни одной
  сделки в базе (профили-сироты, см. известную проблему «157 профилей
  без единой сделки»); слиты по грамматике имени, не по контексту
  сделки — но это не гадательная идентификация: два профиля отличаются
  ровно окончанием одного и того же слова, третьего толкования нет.
* «Яндекс» (`yandex`, именительный, с описанием, ~20 сделок) / «Яндексе»
  (`g48dc66d8`, предложный падеж) — тоже профиль-сирота без единой
  сделки, слит в основной профиль Яндекса тем же способом.

Перед записью для каждого дубля с сделками проверено: id встречается в
JSON только в перечисленных здесь сделках. Для профилей-сирот (нет ни
одной сделки) это условие вырождается в «список сделок пуст» — тоже
проверено явно.

Запуск:
    python3 pipeline/merge_case_variant_company_twins_batch4.py            # сухой прогон
    python3 pipeline/merge_case_variant_company_twins_batch4.py --write    # записать
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

# (dup_id, survivor_id, [deal_ids], ожидаемое имя дубля, ожидаемое имя выжившего)
CLUSTERS = [
    ('gf17d6223', 'g40ce292b', ['gb3211ae8'], 'Группы «ВИС»', 'Группа «ВИС»'),
    ('g4353a82e', 'g489c4c35', ['gca3a8810'], 'Группы АЗТ', 'Группа АЗТ'),
    ('g5cad6f30', 'g8ee31e1c', ['g9f76fe60'],
     'Рязанской чаеразвесочной фабрики', 'Рязанская чаеразвесочная фабрика'),
    ('g66c9c6cb', 'gdd278a7f', ['g1c5d636d'], 'Первой грузовой компании', 'Первая грузовая компания'),
    ('gac336deb', 'g21a1f3ce', [], 'Сахалинской энергии', 'Сахалинская энергия'),
    ('g48dc66d8', 'yandex', [], 'Яндексе', 'Яндекс'),
]

# Отрасль выжившего профиля «Группа АЗТ» унаследовала её от заголовка
# сделки-дубля, а не от собственной сделки — сделка подтверждает
# «Фармацевтику» прямым текстом (производство лекарств полного цикла).
INDUSTRY_FIXES = {
    'g489c4c35': ('Здравоохранение', 'Фармацевтика'),
}


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    companies = data['companies']
    deals = data['deals']

    for dup_id, survivor_id, deal_ids, dup_name, survivor_name in CLUSTERS:
        assert companies[dup_id]['name'] == dup_name, 'дубль %s уже не тот' % dup_id
        assert companies[survivor_id]['name'] == survivor_name, 'выживший %s уже не тот' % survivor_id

        full_text_refs = sorted(d['id'] for d in deals if dup_id in json.dumps(d, ensure_ascii=False))
        assert full_text_refs == sorted(deal_ids), (
            'дубль %s встречается не только в учтённых сделках: %r' % (dup_id, full_text_refs))

        print('СЛИВАЕМ  %s -> %s (%s)' % (dup_id, survivor_id, survivor_name))
        if deal_ids:
            print('ПЕРЕНАПРАВЛЯЕМ  сделки', deal_ids)

        if not write:
            continue

        for d in deals:
            if d.get('id') in deal_ids:
                if d.get('target') == dup_id:
                    d['target'] = survivor_id
                if d.get('buyer') == dup_id:
                    d['buyer'] = survivor_id
                if d.get('seller_id') == dup_id:
                    d['seller_id'] = survivor_id
                if d.get('asset_id') == dup_id:
                    d['asset_id'] = survivor_id

        survivor_aliases = set(data['match_keys'].get(survivor_id, []))
        survivor_aliases.update(data['match_keys'].pop(dup_id, []))
        data['match_keys'][survivor_id] = sorted(survivor_aliases)

        data.setdefault('merged_companies', {})[dup_id] = survivor_id
        del companies[dup_id]

    for cid, (old_ind, new_ind) in INDUSTRY_FIXES.items():
        c = companies.get(cid)
        assert c, 'профиля %s нет в базе' % cid
        assert c.get('ind') == old_ind, ('отрасль %s уже другая: %r (ожидали %r)'
                                          % (cid, c.get('ind'), old_ind))
        print('ОТРАСЛЬ  %s: %s -> %s' % (cid, old_ind, new_ind))
        if write:
            c['ind'] = new_ind

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return 0

    json.dump(data, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('Записано.')
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
