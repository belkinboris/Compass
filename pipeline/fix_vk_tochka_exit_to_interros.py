# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g46cc9712 (VK приобрела 25% акций банка «Точка», 15.11.2023, статус
«Закрыта») — связка VK+«Точка» прожила чуть больше двух лет: VK
полностью вышла из капитала, контроль переходит к структурам
Владимира Потанина и «Т-Технологиям».

Проверено лично прямым WebFetch (ComNews, 17.04.2026): «16 апреля
2026 г. ООО "ВК" (VK) закрыло сделку по продаже 25% доли в АО
"Точка". Покупателем выступил холдинг "Интеррос"... Сумма сделки
составила не менее 21,2 млрд руб.» — из цены следует оценка всей
«Точки» в 84,8 млрд руб. (рост с 46,5 млрд руб. на момент покупки VK
в 2023 году).

По данным саб-агента (Коммерсантъ, doc/8399615, не проверено
дополнительно прямым WebFetch): «Т-Технологии» намерены
консолидировать 100% «Точки» через закрытую допэмиссию, завершение
ближе к IV кварталу 2026 года; активы банка по МСФО на середину 2025
года — 310 млрд руб., капитал 26,8 млрд руб., чистая прибыль 6,1 млрд
руб.

НЕ ВКЛЮЧЕНО: точные показатели капитала/прибыли за 2025 год (взяты
только из отчёта саб-агента, не дозаверены отдельным WebFetch) — эти
факты честнее оставить для отдельного дочитывания, если карточка
«Т-Технологии»/«Точка» будет заведена; продуктовая синергия с
экосистемой VK — саб-агент не нашёл ни одного подтверждения за
2024-2026 годы, только факт владения долей и её продажи, поэтому в
карточку не добавляется вовсе.

Решение для человека записано отдельно в CLAUDE.md («Известные
проблемы»): стоит ли заводить отдельную карточку на консолидацию
«Т-Технологиями» 100% «Точки» — сюжет вышел за рамки исходной сделки
VK, но новую карточку создаёт только приток, не эта рутина.

Запуск: python3 pipeline/fix_vk_tochka_exit_to_interros.py
        python3 pipeline/fix_vk_tochka_exit_to_interros.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g46cc9712'

OLD_EXTRA = (
    'Завершённая сделка: VK приобрела 25% акций АО «Точка» в 4 '
    'квартале 2023 года. В консорциум инвесторов также вошла компания '
    '1С. Операционный контроль остаётся у менеджмента, ни один '
    'акционер не владеет контрольным пакетом.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' 16 апреля 2026 года VK закрыла сделку по продаже этой доли '
    'холдингу «Интеррос» Владимира Потанина — не менее чем за 21,2 '
    'млрд руб. (оценка всей «Точки» выросла до 84,8 млрд руб. против '
    '46,5 млрд руб. на момент покупки VK). Контроль над банком '
    'переходит к «Т-Технологиям», которые намерены консолидировать '
    '100% через допэмиссию к концу 2026 года — связка VK и «Точки» '
    'больше не действует.'
)

NEW_SRC = [
    ['ComNews', 'https://www.comnews.ru/content/244816/2026-04-17/2026-w16/1008/vk-postavila-banku-tochku-interros-teper-u-rulya'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
