# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g94dcc5cc («Газпром может приобрести до 40% автопроизводителя Aurus»,
статус год простоял «Обсуждается» на дату 30 октября 2023) — сделка
закрылась летом 2025 года, но в другой форме и с другим составом
продавцов, чем предполагала карточка.

Проверено лично прямым WebFetch (Коммерсантъ, https://www.kommersant.ru/doc/8211090,
уже была вторым источником в карточке — Ведомости, но эта же новость
дана Коммерсантом подробнее): «Дочерняя структура «Газпрома» компания
«Газпром Тех» приобрела контрольный 51% пакет российского
автопроизводителя Aurus», «в состав приобретенной доли вошла часть
пакета госинститута ФГУП НАМИ (владело 63,5% Aurus), а также пакет,
ранее принадлежавший арабском фонду Tawazun (36%), а затем российской
компании «Дедал»», «ее сумма оценивается в 12-13 млрд руб.».

Это НЕ та сделка, что описывал заголовок 2023 года: тогда речь шла
только о доле «до 40%» напрямую у ФГУП «НАМИ»; по факту купленный
пакет — 51% (контрольный), собранный из ЧАСТИ доли НАМИ и ВСЕЙ доли,
которая с 2019 года принадлежала арабскому фонду Tawazun, а в декабре
2024 перешла российской компании «Дедал» (бенефициар не установлен).
`eco.share`/`eco.context` карточки описывают версию 2023 года и НЕ
переписаны этим скриптом — это уже применённые записи таблицы `FIXES`,
трогать их значило бы затирать историю обсуждения; полная и верная
картина дана в `extra`. `status`/`sum`/`eco.sum` — незатронутые ранее
поля, обновлены на подтверждённый факт закрытия.

НЕ ВКЛЮЧЕНО: точная дата закрытия (источники называют только «летом
2025 г.»); бенефициар компании «Дедал»; итоговая доля ФГУП «НАМИ» после
сделки (источники называют только долю ДО, 63,5%, не после). Две
отдельные, не задокументированные в базе сделки (вход Tawazun в 2019
году и переход его доли к «Дедалу» в декабре 2024) записаны в CLAUDE.md,
«Известные проблемы» — решение, заводить ли для них карточки, за
приточной рутиной.

Запуск: python3 pipeline/fix_gazprom_aurus_deal_closed.py
        python3 pipeline/fix_gazprom_aurus_deal_closed.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g94dcc5cc'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Закрыта'

OLD_SUM = 'Не раскрыта'
NEW_SUM = '12–13 млрд ₽ (по оценке)'

OLD_EXTRA = (
    'Возможность входа Газпрома в капитал ООО Аурус путем денежной '
    'инвестиции. Газпром может получить до 40% компании от крупнейшего '
    'акционера ФГУП НАМИ (подведомственного Минпромторгу). Инвестиции '
    'необходимы Aurus для развития проекта производства люксовых '
    'автомобилей. (информация о возможной сделке между Газпромом и ФГУП '
    'НАМИ)'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Сделка закрылась летом 2025 года в другой форме: «Газпром Тех» '
    '(дочерняя структура «Газпрома») приобрела не «до 40%», а контрольный '
    'пакет 51%, собранный из части доли ФГУП «НАМИ» и всей доли, которая '
    'с 2019 года принадлежала арабскому фонду Tawazun (тот вложил в Aurus '
    '110 млн евро), а в декабре 2024 перешла российской компании «Дедал» '
    '(бенефициар не установлен). Сумма сделки оценивается в 12–13 млрд ₽.'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8211090'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS
    assert deal['sum'] == OLD_SUM
    assert deal['eco']['sum'] == OLD_SUM
    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== status: станет ===')
    print(NEW_STATUS)
    print('\n=== sum / eco.sum: станет ===')
    print(NEW_SUM)
    print('\n=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['status'] = NEW_STATUS
        deal['sum'] = NEW_SUM
        deal['eco']['sum'] = NEW_SUM
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
