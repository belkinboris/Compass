# -*- coding: utf-8 -*-
"""Карточка `ge283bafc` («Pridex продал сеть сервисных офисов Multispace
группе частных инвесторов») вышла в канал с «Покупатель: В периметр сделки
вошли четыре объекта…» — владелец нашёл это сам 25 августа 2026.

`asset` нёс «сеть сервисных офисов Multispace группе частных инвесторов» —
хвост заголовка вырезан ЦЕЛИКОМ, включая дательный падеж покупателя
(«группе… инвесторов»), а не только сам предмет. Источник (РИА
Недвижимость) называет продавца и продукт раздельно: «Компания Pridex
продала сеть гибких офисов Multispace» — предмет заканчивается на
«Multispace», дальше в заголовке уже другая сторона. Чинится вырезанием.

`buyer`/`buyer_name` СОЗНАТЕЛЬНО не заполняются: источник называет
покупателя только родовым описанием — «Новым владельцем Multispace стала
группа профессиональных частных инвесторов», без единого имени. Это тот
же класс, что уже отклоняет `is_generic_description()` в `draft.py`
(«Группа инвесторов» — проверенный истинный пример в его докстроке): в
отличие от «Cats.vc и группа российских инвесторов» (там ЕСТЬ конкретное
имя рядом с родовым словом), здесь после «группа» нет ни одного
собственного имени. Записать это как `buyer_name` значило бы выдать
анонимное описание за структурную сторону сделки. Факт «новый владелец —
консорциум частных инвесторов» остаётся там, где он уже дословно лежит, —
в `eco.rationale`; он не обязан попасть в короткий пост, если строка
«Зачем» выберет другое предложение.

Отдельный, более общий баг был в самом `format_post.render()` (Этап 9):
без имени стороны строка «Покупатель» бралась из ОДНОЙ детали
(`eco.context`) — читатель видел «Покупатель: В периметр сделки вошли
четыре объекта…», предложение вообще не о покупателе. Починено отдельно,
в том же коммите: строка «Покупатель» больше не печатается без имени
стороны — а раз у ЭТОЙ карточки имени нет и не будет (см. выше), пост о
ней теперь просто не несёт строки «Покупатель» вовсе, что честнее
выдумывания структурного поля из родового описания.

Запуск: python3 pipeline/fix_pridex_multispace_buyer_and_asset.py           # проверка
        python3 pipeline/fix_pridex_multispace_buyer_and_asset.py --write   # запись
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
BASE = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'ge283bafc'
OLD_ASSET = 'сеть сервисных офисов Multispace группе частных инвесторов'
NEW_ASSET = 'сеть сервисных офисов Multispace'


def main(write=False):
    data = json.load(open(BASE, encoding='utf-8'))
    deals = {d['id']: d for d in data['deals']}

    assert DEAL_ID in deals, 'карточки %r больше нет — состояние изменилось' % DEAL_ID
    deal = deals[DEAL_ID]
    assert deal.get('asset') == OLD_ASSET, (
        'ожидался asset=%r, сейчас %r — состояние изменилось' % (OLD_ASSET, deal.get('asset')))

    print('ПРАВИМ %s:' % DEAL_ID)
    print('  asset: %r -> %r' % (OLD_ASSET, NEW_ASSET))
    print('  (buyer/buyer_name НЕ заполняются — источник называет покупателя')
    print('   только родовым описанием, без имени; см. докстринг)')
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    deal['asset'] = NEW_ASSET
    deal.pop('buyer_name', None)  # откат прежней попытки этого же прогона

    json.dump(data, open(BASE, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
