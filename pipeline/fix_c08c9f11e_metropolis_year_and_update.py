# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
`c08c9f11e` (ТПС недвижимость / ТРЦ «Метрополис»).

НАЙДЕНА И ИСПРАВЛЕНА ФАКТИЧЕСКАЯ ОШИБКА В ДАТЕ (год) — не через
`review.py` (он не умеет переносить сделку в другой год, см. CLAUDE.md),
а этим одноразовым скриптом. Личный WebFetch (vedomosti.ru/realty/
articles/2026/02/05/1174133, дата публикации статьи — 5 февраля 2026
года) прямо называет дату события: «3 февраля 2026 года» «ТПС
недвижимость» стала управляющей организацией для АО «М-Холдинг» (через
ООО «Кубик» владеет ТЦ «Метрополис»). Карточка несла дату «2025-02-03»
— на год раньше реального события. Источник карточки irn.ru (проверено
личным WebFetch) описывает ДРУГОЕ, более раннее событие того же
процесса — оперативное (не юридическое) управление самим объектом,
дата публикации той статьи — 10 июля 2024 года, точная дата события в
ней не названа.

Дополнительно личным WebFetch (RIA Недвижимость,
realty.ria.ru/20260205/metropolis-2072377358.html, 5 февраля 2026)
подтверждён более сильный сигнал: смена управляющей компании перешла с
уровня самого ОБЪЕКТА (июль 2024) на уровень ЮРЛИЦА-БАЛАНСОДЕРЖАТЕЛЯ
(февраль 2026) — эксперт: «тот факт, что юридическое лицо —
балансодержатель актива — перешло под управление «ТПС Недвижимости»,
может свидетельствовать о завершении сделки по приобретению ТЦ
«Метрополис»». При этом ни Balchug Capital, ни «ТПС недвижимость» не
ответили на запросы изданий — реальные бенефициары по-прежнему не
названы, и это остаётся мнением экспертов, а не подтверждённым фактом.
`buyer`/`seller` карточки НЕ меняются — вопрос собственника остаётся
открытым, дополнен только `eco.context`.

Запуск: python3 pipeline/fix_c08c9f11e_metropolis_year_and_update.py
        python3 pipeline/fix_c08c9f11e_metropolis_year_and_update.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'c08c9f11e'
OLD_DATE = '2025-02-03'
NEW_DATE = '2026-02-03'

OLD_CONTEXT = (
    '«ТПС недвижимость» владеет торговыми центрами «Океания», «Хорошо» '
    'и Columbus. Она принадлежала трастам семей миллиардеров Александра '
    'Пономаренко и Александра Скоробогатько, а также дочери Аркадия '
    'Ротенберга Лилии. Текущие собственники не раскрываются.'
)
NEW_CONTEXT = (
    OLD_CONTEXT + ' Смена управляющей компании прошла в два этапа: в '
    'июле 2024 года «ТПС недвижимость» взяла в оперативное управление '
    'сам торговый центр, а с 3 февраля 2026 года стала управляющей '
    'организацией уже для юрлица-балансодержателя, АО «М-Холдинг». По '
    'мнению опрошенных экспертов, переход управления на уровень '
    'балансодержателя может говорить о завершении сделки по покупке '
    'комплекса — но ни Balchug Capital, ни «ТПС недвижимость» не '
    'ответили на запросы изданий, и реальный собственник по-прежнему '
    'не назван.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}
    card = by_id[CARD_ID]

    assert card['date'] == OLD_DATE
    assert card['eco']['context'] == OLD_CONTEXT

    print('=== date ===', OLD_DATE, '->', NEW_DATE)
    print('=== eco.context ===')
    print(NEW_CONTEXT)

    if write:
        card['date'] = NEW_DATE
        card['eco']['context'] = NEW_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
