# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g8f1fab29 (Русал купил 30% акций китайской HWNM, 23.10.2023, статус
«Закрыта») — дата в карточке была датой ОБЪЯВЛЕНИЯ, а фактическое
закрытие произошло позже, и итоговая цена оказалась выше объявленной.

Проверено лично прямым WebFetch (Ведомости, 29.08.2024): «UC Rusal
получила права на владение приобретенной долей в HWNM в апреле 2024
г.» — то есть закрытие состоялось почти через полгода после
объявления сделки в октябре 2023 года.

Итоговая цена — проверено лично прямым WebFetch (AKM, 21.03.2025):
«Первоначально выплаченное вознаграждение составило $264 млн и было
впоследствии скорректировано до $316 млн в соответствии с
соответствующими условиями соглашения о покупке акций» — на $52 млн
больше первоначально объявленных $267 млн (расхождение с карточкой,
где стоит $267 млн, — видимо, ранняя оценка до первой выплаты).

НЕ ВКЛЮЧЕНО: изменение доли «Русала» в HWNM — саб-агент не нашёл
подтверждений (осталась 30%); объёмы поставок глинозёма именно с
этого завода — саб-агент нашёл только агрегированный по всей компании
рост производства глинозёма на 25,3% за 2024 год, не привязанный
отдельно к HWNM; сделка по индийской Pioneer Aluminium (март 2025) —
это ДРУГАЯ, отдельная сделка с собственной карточкой в базе
(`ga58eb450`), не относится к HWNM.

Запуск: python3 pipeline/fix_rusal_hwnm_closing_date_and_price.py
        python3 pipeline/fix_rusal_hwnm_closing_date_and_price.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g8f1fab29'

OLD_EXTRA = (
    'Русал приобрел 30% акций китайской компании HWNM, владеющей '
    'глиноземным заводом в провинции Хэбэй мощностью 4,8 млн тонн '
    'сырья в год. После завершения сделки компании будут получать '
    'произведенный глинозем пропорционально своим долям.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Фактическое закрытие произошло позже объявления: «Русал» '
    'получил права собственности на долю только в апреле 2024 года, '
    'а итоговое вознаграждение оказалось выше первоначально '
    'заявленного — по условиям соглашения сумма скорректирована с '
    '$264 млн до $316 млн.'
)

NEW_SRC = [
    ['Ведомости', 'https://www.vedomosti.ru/business/articles/2024/08/29/1058835-rusal-kupila-glinozemnogo'],
    ['AKM', 'https://www.akm.ru/news/pokupka_hwnm_oboshlas_rusalu_v_316_mln/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
