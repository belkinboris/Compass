# -*- coding: utf-8 -*-
"""Приток, 11:20 МСК 30 сентября 2026: РИА Недвижимость (первоисточник,
с цитатой пресс-службы «Эталона») сообщила, что Группа «Эталон» продала
земельный участок на Ярославской улице на севере Москвы девелоперу
«Зиккурат» — под строительство офисного центра. Переход права состоялся
за несколько дней до публикации, сумма не раскрыта. «Деловой Петербург»
пересказывает ту же новость почти дословно (нашёл через саб-агента —
в HTML-коде dp.ru есть ссылка на оригинал РИА). Ворота не пропустили
черновик автоматически (заголовок «сменил владельца» не разобрался на
стороны). Собрал вручную, тот же класс случая, что карточки Боброва и
Экзекова.

Саб-агент нашёл второй репост (ABN.Agency, СПб) — но и он сам ссылается на
РИА, это не независимое расследование, а тот же первоисточник. Про
«Зиккурат»: создан в конце 2020 года Владимиром Ковалёвым, ранее
основавшим геодезическую и проектную компанию «Олимпроект» — фон из того
же источника РИА. ИНН/ОГРН «Зиккурата» саб-агент в открытых реестрах не
нашёл.

«Эталон» уже есть в базе как профиль компании (`ga37e3cf6`, «Эталон Груп»)
— привязал продавца. У «Зиккурата» профиля нет, отдельно не заводил ради
одной сделки с землёй.

Запуск: python3 pipeline/fix_add_etalon_zikkurat_land_card.py [--write]
"""
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'ingest'))

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')


def main(write=False):
    import promote

    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    ids = {c['id'] for c in data['deals']}
    new_id = promote.new_id(ids)

    draft = {
        'date': '2026-09-30',
        'title': 'Группа «Эталон» продала участок под офисный центр на севере Москвы девелоперу «Зиккурат»',
        'ind': 'Недвижимость',
        'type': 'M&A',
        'status': 'Закрыта',
        'seller': 'Группа «Эталон»',
        'asset': 'земельный участок (0,3 га) на Ярославской улице на севере Москвы под строительство офисного центра',
        'src': [['РИА Недвижимость', 'https://realty.ria.ru/20260930/etalon-2121127154.html'],
                ['Деловой Петербург', 'https://www.dp.ru/a/2026/09/30/ofisnij-proekt-jetalona-na']],
        'events': [
            {'kind': 'closed', 'date': '2026-09-30', 'title': 'Сделка завершена',
             'note': 'Переход права собственности на участок состоялся за несколько дней до '
                     'публикации; сумма сделки не раскрыта.',
             'source': ['РИА Недвижимость', 'https://realty.ria.ru/20260930/etalon-2121127154.html']},
        ],
    }
    card = promote.to_card(draft, new_id)
    card['buyer_name'] = 'Девелопер «Зиккурат»'
    card['eco']['context'] = (
        'На участке согласовано строительство офисного комплекса наземной площадью '
        '12 тыс. м² и подземной — 4,8 тыс. м², высотой десять этажей. В «Эталоне» '
        'объяснили продажу управлением земельным портфелем: вырученные деньги пойдут на '
        'погашение корпоративного долга и на более приоритетные жилые проекты. '
        'Это не первая подобная сделка для '
        'девелопера: в январе 2026 года он продал по схеме sale & leaseback бизнес-центр '
        'в Приморском районе Петербурга (за 1,4–1,6 млрд ₽ по оценке рынка), а в июне '
        '2025 года — бизнес-центр на Богатырском проспекте (оценка рынка — около 1 млрд ₽). '
        '«Зиккурат» создан в конце 2020 года Владимиром Ковалёвым, ранее основавшим '
        'геодезическую и проектную компанию «Олимпроект».'
    )
    card['themes'] = ['Недвижимость']
    card['seller_id'] = 'ga37e3cf6'
    # `to_card` не ставит `added` — обычно его ставит `approve.py` при выводе
    # карточки из pending.json; прямая запись минует этот путь, дата не
    # выдумана — карточка правда добавлена сегодня.
    card['added'] = '2026-09-30'

    data['deals'].append(card)
    print('Добавлена карточка %s: %s' % (new_id, card['title']))

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
