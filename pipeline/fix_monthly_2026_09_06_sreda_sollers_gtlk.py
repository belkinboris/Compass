def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    sreda = by_id[SREDA_ID]
    sollers = by_id[SOLLERS_ID]
    gtlk = by_id[GTLK_ID]

    assert sreda['law']['struct'] == SREDA_OLD_LAW_STRUCT
    assert sollers['eco']['fin'] == SOLLERS_OLD_ECO_FIN
    assert gtlk['eco']['context'] == GTLK_OLD_ECO_CONTEXT

    print('=== sreda: law.struct ===')
    print(SREDA_NEW_LAW_STRUCT)
    print()
    print('=== sollers: eco.fin ===')
    print(SOLLERS_NEW_ECO_FIN)
    print()
    print('=== gtlk: eco.context ===')
    print(GTLK_NEW_ECO_CONTEXT)

    if write:
        sreda['law']['struct'] = SREDA_NEW_LAW_STRUCT
        sollers['eco']['fin'] = SOLLERS_NEW_ECO_FIN
        gtlk['eco']['context'] = GTLK_NEW_ECO_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
