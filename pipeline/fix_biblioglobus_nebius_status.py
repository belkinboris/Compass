import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_STATUS_BG = 'Обсуждается'
OLD_ECO_CONTEXT_BG = (
    'В пресс-службе «Бибилио-глобуса» сообщили, что смена владельцев не '
    'планируется и магазин работает в штатном режиме. В середине ноября '
    'на сайте недвижимости ЦИАН появилось объявление о сдаче в аренду '
    'помещений «Библио-глобуса» в центре Москвы: три этажа торгового '
    'дома площадью 3609,1 квадратных метра предлагали снять за 12 '
    'миллионов рублей в месяц. Позже объявление сняли. В пресс-службе '
    'магазина добавили, что рассматривают варианты передачи отдельных '
    'площадей в аренду.'
)
NEW_ECO_CONTEXT_BG = OLD_ECO_CONTEXT_BG + (
    ' Сделка с «Читай-городом» не состоялась: по данным на май 2026 года, '
    'выручка ООО «Торговый дом «Библио-Глобус»» за 2025 год составила '
    '320,4 млн ₽ (на 21,8% меньше, чем годом ранее), убыток сократился с '
    '74,8 до 18,9 млн ₽; вместо продажи рассматривается сдача помещений '
    'в аренду.'
)

OLD_ECO_CONTEXT_NEBIUS = (
    'Арбитражный суд Калининградской области принял иск акционеров Nebius '
    'Group к Nebius Group N.V. (Нидерланды) и АО «Солид менеджмент». '
    'Заседание назначено на 18 декабря 2024 года. Соистцами выступают '
    'более 20 акционеров, которые хотят признать сделку по продаже '
    'российской части бизнеса недействительной.'
)
NEW_ECO_CONTEXT_NEBIUS = OLD_ECO_CONTEXT_NEBIUS + (
    ' 19 декабря 2024 года Арбитражный суд Калининградской области '
    'отказал миноритариям в признании сделки по выкупу российского '
    '«Яндекса» недействительной.'
)


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    bg = by_id['c36556448']
    nebius = by_id['c33a55069']

    assert bg.get('status') == OLD_STATUS_BG, \
        'c36556448 status уже другой: %r' % (bg.get('status'),)
    assert bg['eco']['context'] == OLD_ECO_CONTEXT_BG, \
        'c36556448 eco.context уже другой: %r' % (bg['eco']['context'],)
    assert nebius.get('status') is None, \
        'c33a55069 status уже занят: %r' % (nebius.get('status'),)
    assert nebius['eco']['context'] == OLD_ECO_CONTEXT_NEBIUS, \
        'c33a55069 eco.context уже другой: %r' % (nebius['eco']['context'],)

    print('c36556448: status "Обсуждается" -> "Не состоялась"; eco.context '
          'дополнен (выручка 2025, сдача в аренду вместо продажи)')
    print('c33a55069: status None -> "Не состоялась" (иск отклонён '
          '19.12.2024); eco.context дополнен')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    bg['status'] = 'Не состоялась'
    bg['eco']['context'] = NEW_ECO_CONTEXT_BG

    nebius['status'] = 'Не состоялась'
    nebius['eco']['context'] = NEW_ECO_CONTEXT_NEBIUS

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
