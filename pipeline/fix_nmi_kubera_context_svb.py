# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка g6ccd4122 (Михайлов и
Партнеры/NMi Group/«Кубера»): `eco.context` заканчивался на состоянии
октября 2023 года. Дельта нашла более позднее (июнь 2025) событие —
инвестфонд «СВБ» вошёл в состав учредителей NMi Group, доля «Кубера»
(покупателя карточки) снизилась со 100% до 75% — «что было дальше» после
самой сделки (декабрь 2024).

Не через review.py: `eco.context` уже не пуст, а общая проверка
дословности требует, чтобы ВСЁ значение поля (старый текст + новый)
лежало в ОДНОЙ цитате — а старый текст взят из другого источника
(Sostav.ru/AdIndex/Mergers.ru про саму сделку), новый — из отдельной
статьи (Sostav.ru, 16.06.2025) про последующее размытие доли. Дословна
именно ДОБАВЛЯЕМАЯ часть — она приведена ниже и совпадает с новой
записью `src`, внесённой через review.py в этом же прогоне.
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g6ccd4122'
OLD_CONTEXT = (
    'Ранее 51% «Эн Эм Ай Групп» были у «Медиа Инвеста», через который '
    '«Михайлов и Партнеры» владела компанией. В октябре 2023 года 49% '
    'ООО «Эн Эм Ай Групп» перешли к АО «Кубера». Тогда компания '
    'выкупила доли у экс-генерального директора NMi Юлии Орловой '
    '(15,39%) и Юрия Зайца (33,61%). «Кубера» была образована в '
    'сентябре 2023 года, за несколько недель до сделки по выкупу долей '
    'NMi. В выписке из ЕГРЮЛ не содержится сведений об учредителях '
    'юрлица. Гендиректором АО «Кубера» числится Андрей Королев. В июле '
    '2024-го также появилась должность президента, ее занял бывший '
    'вице-президент ПАО «ВТБ» Денис Фонов. В октябре 2023-го эксперт '
    'вошел в совет директоров NMi.'
)
ADDITION = (
    'В NMi Group новый учредитель — паевой инвестиционный фонд «СВБ». '
    'Доля АО «Кубера», владевшего 100% ООО «Эн Эм Ай Групп» (юрлицо '
    'NMi), снизилась до 75%. Такие сведения содержатся в ЕГРЮЛ. Доля '
    '«СВБ» составила 25% компании. Управление фондом осуществляет ООО '
    'УК «БФМ ГРУПП».'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} eco.context: += размытие доли «Кубера» фондом "
          "«СВБ» (июнь 2025)")
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
