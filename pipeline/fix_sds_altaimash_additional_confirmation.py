# -*- coding: utf-8 -*-
"""Заметка 501 (консоль, 4 сентября 2026): «Ещё поищи сведений и
вернись. Примем решение», отвечая на карточку `g401b169a» (СДС-Холдинг
продаёт 75% АО НПК «Алтаймаш» группе «Талтэк»).

Найдено новое, независимое подтверждение — не о самой сделке
напрямую, а КОСВЕННОЕ, но более сильное, чем реестровый кадровый
сигнал: altapress.ru, 19 апреля 2024 года (проверено прямым чтением),
пишет о перестановке в руководстве Барнаульского вагоноремонтного
завода (БВРЗ, тоже актив «Талтэка») и упоминает переход «Алтайвагона»
под «Талтэк» КАК УЖЕ СОСТОЯВШИЙСЯ факт, в прошедшем времени, безо
всяких оговорок «по неофициальным данным» — это статья другого издания
на другую тему (про БВРЗ, не про саму сделку), которая просто исходит
из смены собственника как из данности. Прямого официального
подтверждения ИМЕННО сделки (пресс-релиз, отчётность, реестр акций АО)
по-прежнему не найдено.

Запуск: python3 pipeline/fix_sds_altaimash_additional_confirmation.py [--write]
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g401b169a'
OLD_EXTRA = (
    '«СДС-Холдинг» продаёт группе «Талтэк» 75% в АО НПК «Алтаймаш», '
    'которому принадлежит 100% ООО «Алтайвагон». По неофициальным '
    'данным, сделка либо уже закрыта, либо согласована в главном и '
    'стороны обсуждают отдельные условия; о закрытии в тот же день '
    'говорил и «РЖД-Партнер» — со ссылкой на участников рынка и с '
    'оговоркой, что сведения неофициальные. По данным агрегаторов '
    'ЕГРЮЛ, к маю 2025 года гендиректором «Алтаймаша» стала Наталья '
    'Михель: это косвенный признак перестройки управления, но не '
    'подтверждение смены собственника.'
)
ADDITION = (
    ' 19 апреля 2024 года altapress.ru, рассказывая о смене '
    'руководства СОСЕДНЕГО актива «Талтэка» — Барнаульского '
    'вагоноремонтного завода, — упоминает переход «Алтайвагона» под '
    '«Талтэк» как уже состоявшийся факт, без оговорок о '
    'неофициальности: независимое издание на другую тему исходит из '
    'смены собственника как из данности. Прямого официального '
    'подтверждения самой сделки (пресс-релиз, отчётность, реестр '
    'акций АО) по-прежнему не найдено.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {c['id']: c for c in data['deals']}
    card = by_id[CARD_ID]
    assert card['extra'] == OLD_EXTRA, card['extra']
    card['extra'] = OLD_EXTRA + ADDITION
    print(f'{CARD_ID}.extra: добавлено косвенное подтверждение (altapress.ru)')

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
            f.write('\n')
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
