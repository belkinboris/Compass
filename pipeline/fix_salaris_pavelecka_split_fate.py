import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'ga3376e53'

OLD_ECO_CONTEXT = '—'
NEW_ECO_CONTEXT = (
    'Судьба двух центров, выставленных на продажу одним пресс-релизом, '
    'разошлась. ТЦ «Саларис» продан: 14 декабря 2023 года новым '
    'собственником стало АО «Лаут», связанное (через гендиректора '
    'Владимира Мамонова) с семьёй Александра Ракшина — основателя '
    'сети «Мария-Ра»; консультанты оценивали сделку в 24–27 млрд ₽, '
    'точная сумма не раскрывалась. «Павелецкая плаза» на 15 декабря '
    '2023 года — днём позже — по-прежнему принадлежала структуре '
    'Сергея Гордеева (Mall Management Group/Plaza B.V.): в этот день '
    'её владелец, ООО «Павелецкая площадь», подал иск к «Адидасу» на '
    'более 230 млн ₽. Более поздних сведений о продаже «Павелецкой '
    'плазы» не нашлось.'
)

NEW_SRC = [
    ['РИА Недвижимость', 'https://realty.ria.ru/20231214/salaris-1915710810.html'],
    ['РИА Недвижимость', 'https://realty.ria.ru/20231215/plaza-1915956905.html'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    new_src = deal['src'] + NEW_SRC

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
