# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка g6aabf02a
(ГК Merlion рассматривала покупку Kuppersberg, сделка не состоялась) —
карточка уже подробно проработала срыв переговоров и последующую
консолидацию 95% Андижаном Моисеевым; найден один новый, но
непрямолинейный факт о судьбе вышедшего совладельца.

Проверено лично прямым WebFetch (данные ЕГРЮЛ через агрегатор):
компания Зазы Горгиджанова, через которую он вёл розницу под брендом
Kuppersberg, — ООО «Купперсберг-Импорт» — 25 июля 2025 года
переименована в ООО «ЗГ-Импорт» (единственный учредитель — сам
Горгиджанов, 100%). Ни один источник не называет это прямым
следствием декабрьской (2024 года) продажи его доли Моисееву, но
совпадение по существу (слово «Купперсберг» ушло из названия компании
бывшего совладельца бренда) делает связь правдоподобной — добавлено с
честной оговоркой, без утверждения причинно-следственной связи.

НЕ ВКЛЮЧЕНО: свежие финансовые показатели Kuppersberg/«Эм-джи русланд»
за 2024-2025 годы — агрегаторы (РБК Компании и др.) дают между собой
несовместимые цифры и одновременно показывают ДОПРОДАЖНЫЙ состав
учредителей — то есть карточки компаний в реестрах не актуализированы
и доверять им нельзя; текущий статус Дмитрия Шашкина (гендиректор,
5% на декабрь 2024) — свежих подтверждений не нашлось.

Запуск: python3 pipeline/fix_kuppersberg_gorgidzhanov_rename.py
        python3 pipeline/fix_kuppersberg_gorgidzhanov_rename.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g6aabf02a'

OLD_CONTEXT = (
    'По данным «СПАРК-Интерфакс», бренд Kuppersberg принадлежит ООО '
    '«Эм-джи русланд». Merlion вышел из переговоров; в декабре 2024 '
    'года сооснователь компании Заза Горгиджанов продал свои 50% '
    'второму инвестору Андижану Моисееву, консолидировавшему 95%.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' По данным ЕГРЮЛ, 25 июля 2025 года компания Горгиджанова ООО '
    '«Купперсберг-Импорт» (100% в его собственности) переименована в '
    'ООО «ЗГ-Импорт» — слово «Купперсберг» ушло из названия; прямой '
    'связи с продажей доли в бренде источники не называют, но '
    'совпадение по существу делает её правдоподобной.'
)

NEW_SRC = [
    ['ЕГРЮЛ (агрегатор)', 'https://www.tbank.ru/business/contractor/legal/1157746124590/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT

    new_src = deal['src'] + NEW_SRC

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
