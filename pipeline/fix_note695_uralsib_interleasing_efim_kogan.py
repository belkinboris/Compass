"""Приток 19.09.2026, часовой прогон 10:20 МСК — ответ на заметку владельца
№695. Владелец попросил переделать карточку «на Ефима Когана» — но прямая
проверка источников показывает, что это была бы ошибка: сам источник
карточки (frankmedia.ru, ноябрь 2023) прямо называет владелицей
«Интерлизинга» Людмилу Коган, а не Ефима — «"Интерлизинг" полностью
принадлежит мажоритарной собственнице банка "Уралсиб" Людмиле Коган».
Ефим Коган (сын Людмилы) вышел из капитала «Интерлизинга» ЕЩЁ РАНЬШЕ — под
конец 2021 года, продав свою долю в 90% матери (dp.ru, 12.01.2022) — то
есть до всех событий, которые уже описаны в карточке, включая
реструктуризацию 2024 года в ООО «Ил Холдинг» (это тоже была передача от
Людмилы себе же, не от Ефима). Переименовывать продавца на «Ефим Коган»
означало бы противоречить дословной цитате источника. Вместо этого
добавляем факт о выходе Ефима Когана как исторический контекст — вероятно,
именно это имя владелец и имел в виду, — не трогая остальную карточку.
"""
import json
import sys

DATA_PATH = 'static/data/deals_promoted.json'

OLD_CONTEXT = (
    'По состоянию на 2025 год ни один из пяти претендентов не подтверждён '
    'как реальный покупатель. Вместо продажи стратегу — внутренняя '
    'реструктуризация: в сентябре 2024 года Людмила Коган передала свою '
    '100%-ю долю на созданное ею же ООО «Ил Холдинг» (сохранив 99,99% в '
    'новой структуре), в феврале 2025 года назначен новый генеральный '
    'директор. По собственным заявлениям компании (июнь 2024 года), '
    'готовится к IPO, размещение на тот момент не состоялось.'
)
ADDED_PREFIX = (
    'Ещё раньше, под конец 2021 года, из капитала «Интерлизинга» вышел '
    'совладелец Ефим Коган: он продал свою долю в 90% матери, Людмиле '
    'Коган, которая ранее владела оставшимися 10% и в результате стала '
    'единственным участником компании. '
)


def main(write):
    data = json.load(open(DATA_PATH, encoding='utf-8'))
    card = next(d for d in data['deals'] if d['id'] == 'g2800e337')
    assert card['eco']['context'] == OLD_CONTEXT

    card['eco']['context'] = ADDED_PREFIX + OLD_CONTEXT

    if write:
        json.dump(data, open(DATA_PATH, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
        print('g2800e337: добавлен факт о выходе Ефима Когана (2021). ЗАПИСАНО.')
    else:
        print('Сухой прогон. Повторите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
