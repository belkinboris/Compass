"""Приток 19.09.2026, часовой прогон 10:20 МСК — ответ на заметку владельца
№694. Источники карточки не подтверждают переход Comcity к Совкомбанку:
РИА Недвижимость (июль 2025) называет банк только крупным АРЕНДАТОРОМ,
Интерфакс на дату перерегистрации управляющей компании прямо писал, что
«информация о покупателе... не отражена». Последняя ПОДТВЕРЖДЁННАЯ смена
собственника — октябрь 2022 года, PPF Real Estate продала комплекс
инвесткомпании Inventa (управляет активами Авигдора Ярдени, который
владеет 0,99% банка «Хоум Кредит энд Финанс» — то самое лицо, которое
источник называет «совладельцем банка «Хоум кредит»»). Переписываем
карточку под подтверждённую сделку PPF → Inventa, Совкомбанк остаётся
только как неподтверждённое упоминание в контексте.
"""
import json
import sys

DATA_PATH = 'static/data/deals_promoted.json'

OLD_TITLE = 'Совкомбанк приобрёл бизнес-центр Comcity у Inventa'
NEW_TITLE = 'PPF Real Estate продала бизнес-парк Comcity инвесткомпании Inventa'

OLD_CONTEXT = (
    'До этого, в октябре 2022 года, Comcity сменил владельца впервые: '
    'чешская PPF Real Estate продала комплекс инвесткомпании Inventa, '
    'управляющей активами израильско-грузинского бизнесмена Авигдора '
    'Ярдени (рыночная оценка на тот момент — 25–27 млрд ₽ без НДС). '
    'Переход к Совкомбанку в 2023 году ни разу не подтверждён деловым '
    'изданием напрямую — Интерфакс на дату перерегистрации управляющей '
    'компании прямо писал, что «информация о покупателе... не отражена», '
    'а самая свежая публикация (июль 2025 года) называет Совкомбанк только '
    'крупным арендатором комплекса (почти 15 тыс. кв. м), не упоминая его '
    'как собственника.'
)
NEW_CONTEXT = (
    'В октябре 2022 года чешская PPF Real Estate продала комплекс '
    'инвесткомпании Inventa, управляющей активами израильско-грузинского '
    'бизнесмена Авигдора Ярдени, который владеет 0,99% банка «Хоум Кредит '
    'энд Финанс» (рыночная оценка на тот момент — 25–27 млрд ₽ без НДС). '
    'Переход к Совкомбанку в 2023 году ни разу не подтверждён деловым '
    'изданием напрямую — Интерфакс на дату перерегистрации управляющей '
    'компании прямо писал, что «информация о покупателе... не отражена», '
    'а самая свежая публикация (июль 2025 года) называет Совкомбанк только '
    'крупным арендатором комплекса (почти 15 тыс. кв. м), не упоминая его '
    'как собственника.'
)


def main(write):
    data = json.load(open(DATA_PATH, encoding='utf-8'))
    card = next(d for d in data['deals'] if d['id'] == 'g560a4b70')
    assert card['title'] == OLD_TITLE
    assert card['eco']['context'] == OLD_CONTEXT
    assert card['buyer'] == 'gb7e1e33a'
    assert card['seller'] == 'Inventa'
    assert card['date'] == '2022-08-01'

    card['title'] = NEW_TITLE
    card['eco']['context'] = NEW_CONTEXT
    card['buyer'] = None
    card['buyer_name'] = 'Inventa (структуры Авигдора Ярдени)'
    card['seller_id'] = 'g7b8bd1f5'
    card['seller'] = 'PPF Real Estate'
    card['date'] = '2022-10-01'

    if write:
        json.dump(data, open(DATA_PATH, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
        print('g560a4b70 переписана под PPF -> Inventa. ЗАПИСАНО.')
    else:
        print('Сухой прогон. Повторите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
