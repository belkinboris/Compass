# -*- coding: utf-8 -*-
"""Месячная очередь, 9 сентября 2026 — дочитывание карточки `g925a9d17`
(«Реструктуризация Группы Циан: редомициляция и публичный обмен акций»,
добавлена в базу 3 августа 2026, полностью обыскана в тот же день).

Дельта-поиск (саб-агент + личная проверка) нашёл два новых факта. Личный
WebFetch подтвердил дословно:

1) Объём первого этапа обмена. akm.ru (итоги обмена CIAN PLC на МКПАО
   «Циан»): «16.197 млн акций и АДР CIAN PLC были обменяны на такое же
   количество акций МКПАО «Циан»» — «приблизительно 21% всех выпущенных и
   находящихся в обращении акций МКПАО «Циан»», «около 80% ценных бумаг в
   свободном обращении CIAN PLC»; обмен «производится по коэффициенту 1:1
   (без осуществления денежных расчетов) через компанию Cian Investments
   Limited».

2) Размер специального дивиденда, о котором уже шла речь в `law.appr`, но
   без конкретной суммы. cnews.ru (29.10.2025): «выплатить специальные
   дивиденды в размере 104 руб. на одну акцию. Их общий размер может
   составить 7,5 млрд руб.»; «Датой для дивидендной отсечки предлагается
   установить 12 декабря 2025 г.»

Запуск:
    python3 pipeline/fix_cian_restructuring_exchange_and_dividend.py            # сухой прогон
    python3 pipeline/fix_cian_restructuring_exchange_and_dividend.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_ECO_SHARE = (
    'Группа создала новую холдинговую компанию, перевела её в Российскую '
    'Федерацию и получила публичный статус: акции и американские '
    'депозитарные расписки прежней холдинговой компании CIAN plc обменяли '
    'на акции МКПАО «ЦИАН», а те получили листинг на Московской бирже.'
)
NEW_ECO_SHARE = OLD_ECO_SHARE + (
    ' На первом этапе обменяно 16,197 млн акций и депозитарных расписок '
    '(около 21% акций МКПАО «Циан» и около 80% бумаг CIAN plc в свободном '
    'обращении) по коэффициенту 1:1 через компанию Cian Investments Limited.'
)

OLD_LAW_APPR = (
    'Проект был стратегически важен для Группы Циан: совет директоров '
    'МКПАО «Циан» смог рекомендовать специальный дивиденд, и 1 декабря '
    '2025 года акционеры МКПАО «Циан» его утвердили. Быстрое завершение '
    'публичного обмена дало инвесторам, которые были акционерами МКАО '
    '«ЦН», не только торгуемые акции, но и возможность получить этот '
    'дивиденд деньгами.'
)
NEW_LAW_APPR = (
    'Проект был стратегически важен для Группы Циан: совет директоров '
    'МКПАО «Циан» смог рекомендовать специальный дивиденд в размере 104 ₽ '
    'на акцию (до 7,5 млрд ₽ всего, отсечка — 12 декабря 2025 года), и '
    '1 декабря 2025 года акционеры МКПАО «Циан» его утвердили. Быстрое '
    'завершение публичного обмена дало инвесторам, которые были '
    'акционерами МКАО «ЦН», не только торгуемые акции, но и возможность '
    'получить этот дивиденд деньгами.'
)

NEW_SRC = [
    ['AKM', 'https://www.akm.ru/news/gruppa_tsian_obyavila_itogi_obmena_aktsiy_i_adr_cian_plc_na_aktsii_mkpao_tsian/'],
    ['CNews', 'https://www.cnews.ru/news/top/2025-10-29_aktsioneram_tsian_vyplatyat'],
]


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['g925a9d17']

    assert d['eco']['share'] == OLD_ECO_SHARE, \
        'g925a9d17 eco.share уже другой: %r' % (d['eco']['share'],)
    assert d['law']['appr'] == OLD_LAW_APPR, \
        'g925a9d17 law.appr уже другой: %r' % (d['law']['appr'],)
    urls = {s[1] for s in d['src']}
    for src in NEW_SRC:
        assert src[1] not in urls, 'источник уже добавлен: %s' % src[1]

    print('g925a9d17: eco.share дополнен (объём первого этапа обмена — '
          '16,197 млн бумаг, ~21%/~80% free float, Cian Investments '
          'Limited); law.appr дополнен (размер дивиденда 104 ₽/акция, '
          'до 7,5 млрд ₽, отсечка 12 декабря 2025); добавлены источники '
          'akm.ru, cnews.ru')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['eco']['share'] = NEW_ECO_SHARE
    d['law']['appr'] = NEW_LAW_APPR
    d['src'].extend(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
