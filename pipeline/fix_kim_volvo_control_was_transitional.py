# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g87d4faf4 («Игорь Ким получил контроль над российскими активами
Volvo», закрыта 6 сентября 2023) — контроль Кима был переходным звеном:
уже через 2,5 месяца, 23 ноября 2023, завод куплен другим, конечным
покупателем — это отдельная карточка базы (geaedd22c), не дублирую её
содержание здесь, только даю перекрёстную ссылку по существу.

Проверено лично прямым WebFetch (Интерфакс,
https://www.interfax.ru/business/933148 — источник уже стоит в
`src` карточки geaedd22c): «Покупателем активов завода АО «Стоков
машинное оборудование» (ранее — АО(Н) «Вольво Восток»)... выступило
подконтрольное группе АО «АМО»» (группа «Промышленные инвестиции»
Дмитрия Стрежнева), «закрытие сделки произошло 23 ноября» [2023] —
статья не упоминает структуры Кима вовсе, сделка описана как прямая
между Volvo и новым покупателем.

Карточка geaedd22c («ГК «Промышленные инвестиции» приобрела завод
Volvo в Калуге») уже полностью содержит дальнейшую судьбу актива
(переименование в АО «АМО», выпуск «Урал Next» из машинокомплектов
«Урала», остановка производства май 2025 — апрель 2026, план на 2026
год ~1,5 тыс. машин) и обновлена этим же месяцем (followup_researched
2026-09-01) — повторять эти факты здесь означало бы дублировать уже
написанное на другой карточке.

НЕ ВКЛЮЧЕНО: судьба доли структур Кима («Группа Астон») при переходе к
«Промышленным инвестициям» — ни один источник её не проясняет (продал,
вышел без компенсации, или просто утратил операционный контроль без
изменения юридического владения) — не домысливаю; судьба лизинговой
компании «Стоков Финансовые Услуги» (Никита Ряузов) — источники
подтверждают её текущую деятельность (сопровождение старых контрактов),
но не называют владельца после 2023 года.

Запуск: python3 pipeline/fix_kim_volvo_control_was_transitional.py
        python3 pipeline/fix_kim_volvo_control_was_transitional.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g87d4faf4'

OLD_EXTRA = (
    'Сделка касается перехода под операционный контроль бизнесмена '
    'Игоря Кима ряда дочерних структур Volvo в России, включая завод '
    'по производству грузовиков в Калуге. Непосредственный контроль '
    'Ким получил в ООО «Стоков Конструкция» через контролируемую им '
    'ООО «Группа "Астон"» (99% владение с 6 сентября). Никита Ряузов '
    '(партнер Кима) возглавил лизинговую компанию Volvo AB (ООО '
    '«Стоков Финансовые Услуги»). Алексей Санников (первый зампред '
    'правления «Экспобанка») стал гендиректором завода Volvo Trucks '
    '(АО «Стоков Машинное Оборудование»).'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Контроль Кима оказался переходным звеном: уже 23 ноября 2023 '
    'года завод куплен группой «Промышленные инвестиции» Дмитрия '
    'Стрежнева (дальнейшая судьба актива — переименование в АО «АМО», '
    'выпуск «Урал Next», остановка и возобновление производства — '
    'описана в отдельной карточке базы, geaedd22c).'
)

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/business/933148'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
