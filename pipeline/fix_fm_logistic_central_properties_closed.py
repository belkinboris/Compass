import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g6fc4d4ac'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Закрыта'

OLD_ECO_CONTEXT = (
    'Годом ранее FM Logistic уже продала Central Properties два объекта '
    'в подмосковных Чехове и Ступине общей площадью более 250 тыс. кв. '
    'м и осталась их арендатором. Покупку склада в Дмитрове Денис '
    'Платов считает продолжением пакетной сделки. После её закрытия у '
    'покупателя будет сосредоточено более 64% портфеля FM Logistic.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' К сентябрю 2024 года фонд, купивший склад, '
    'продолжал им владеть и обслуживал кредит перед ВТБ на 2,9 млрд ₽ — '
    'прямого сообщения о закрытии сделки ни один источник не публиковал, '
    'но и о её срыве речи не было.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS
    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    print('=== status: станет ===')
    print(NEW_STATUS)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)

    if write:
        deal['status'] = NEW_STATUS
        deal['eco']['context'] = NEW_ECO_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
