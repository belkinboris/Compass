# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка g577a83e0 («Ригла»
приобрела «Аптека25.рф»): дельта-поиск нашёл, что `extra` нёс
оборванную заглушку «Покупатель и продавце.» вместо реального описания
сделки — восстановлено из уже проверенных цитат карточки (все 49 точек,
сохранение кадрового состава — уже в eco.share; отказ от ребрендинга,
принадлежность «Риглы» группе «Протек» — новые, дословно подтверждённые
факты). Заодно eco.context дополнен другими активами продавца (доля в
клинике «Святая Мария» и сети зоомагазинов DogHouse — Беликов остаётся
их совладельцем). Не через review.py: `extra` — замена ошибочного
значения, а не дословное расширение; eco.context — старое значение не
образует непрерывный кусок с новой цитатой.

Источники — читал напрямую (fetch_article_texts.py, закэшированы):
Ведомости (15.09.2025), pharmvestnik.ru (15.09.2025), mergers.ru
(16.09.2025).
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'g577a83e0'

OLD_EXTRA = 'Покупатель и продавце.'
NEW_EXTRA = (
    '«Ригла» (входит в группу «Протек» Вадима Якунина) приобрела все '
    '49 точек приморской сети «Аптека25.рф» у местного предпринимателя '
    'Дениса Беликова. Сумму сделки стороны не раскрывают. Ребрендинг '
    'не планируется — аптеки сохранят название «Аптека25.рф».'
)

OLD_CONTEXT = (
    'ООО «Аптека25.рф» было зарегистрировано в 2016 году во '
    'Владивостоке, ООО «Аванти Фарма» — в 2008 году, ООО «Фарма Лайф» '
    '— в 2012-м. Владельцем двух компаний с момента их основания '
    'выступал Денис Беликов. Бенефициаром «Аптека 25.рф» он стал '
    'только в феврале 2022 года.'
)
CONTEXT_ADDITION = (
    'У Беликова остаётся доля во владивостокской клинике «Святая '
    'Мария» и местной сети зоомагазинов DogHouse, по данным '
    '«СПАРК-Интерфакса». После сделки аптечная сеть «Ригла» укрепит '
    'свои позиции на Дальнем Востоке, заняв 34% на рынке региона и 38% '
    'на рынке Владивостока — первое место среди аптечных сетей в '
    'городе, поделился с «ФВ» глава AlphaRM Николай Демидов. С учётом '
    'сделки «Ригла» объединяет 11 аптечных брендов, включая «Миницен», '
    '«Аптечество» и Farmani.'
)
NEW_CONTEXT = OLD_CONTEXT + ' ' + CONTEXT_ADDITION


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['extra'] == OLD_EXTRA, f"extra: неожиданное значение {deal['extra']!r}"
    assert deal['eco']['context'] == OLD_CONTEXT, \
        f"eco.context: неожиданное значение {deal['eco']['context']!r}"

    print(f"{CARD_ID} extra: оборванная заглушка заменена реальным описанием сделки")
    print(f"{CARD_ID} eco.context: += другие активы продавца, доля рынка после сделки, "
          f"портфель брендов")
    deal['extra'] = NEW_EXTRA
    deal['eco']['context'] = NEW_CONTEXT

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
