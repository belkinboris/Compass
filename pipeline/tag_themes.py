# -*- coding: utf-8 -*-
"""Разметка тематических тэгов по сделкам (static/data/deals_promoted.json).

Принципы:
- Тема считается только по полям, описывающим САМУ сделку (title / eco.share /
  eco.rationale / law.struct, для согласований — law.appr). Поле `extra` намеренно
  НЕ используется: там часто лежит исторический фон («актив в 2022 году был передан
  местному менеджменту»), который даёт ложные срабатывания на текущую сделку.
- Поле `type` тоже НЕ используется как текст: в базе встречались неверные значения
  (напр. «Продажа с торгов» на сделке, купленной напрямую у владельца).
- Где есть надёжное структурное поле — берём его, а не текст (СП определяется по kind).
- Есть guard-паттерны против отрицаний («вне торгов», «без публичного аукциона»).

Запуск:
    python3 pipeline/tag_themes.py            # сухой прогон, только статистика
    python3 pipeline/tag_themes.py --write    # записать поле themes в JSON
"""
import json
import re
import sys
import collections

PATH = 'static/data/deals_promoted.json'


def core(d):
    """Только то, что описывает саму сделку."""
    e = d.get('eco') or {}
    l = d.get('law') or {}
    return ' '.join([
        d.get('title') or '',
        e.get('share') or '',
        e.get('rationale') or '',
        l.get('struct') or '',
    ])


def core_appr(d):
    return core(d) + ' ' + ((d.get('law') or {}).get('appr') or '')


def head(d):
    """Только то, чем сделка НАЗЫВАЕТСЯ: заголовок, предмет и доля.

    Нужен темам, которые описывают ПРИРОДУ сделки, а не слово где-то в
    тексте. Замер 3 сентября 2026 показал, чем это отличается: правило
    «IPO / SPO» по всему тексту ловило «перед планируемым выходом на IPO»
    и «заработал в результате IPO» — сделка при этом была обычной покупкой
    доли; правило «Искусственный интеллект» ловило «сосредоточиться на
    разработках в области ИИ» в карточке о продаже аптечной сети. Тема —
    про предмет сделки, и проверять её надо там, где предмет назван."""
    # `eco.share` сюда НЕ входит, хотя поле и называется «Предмет / доля»:
    # замер показал, что в нём часто лежит целый абзац пересказа («компания
    # рассматривает возможность проведения IPO»), и тема снова начинала
    # считаться по слову в тексте, а не по природе сделки.
    return ' '.join([d.get('title') or '', d.get('asset') or ''])


FOREIGN = (
    r'уход\w*\s+(?:из России|иностран)|ушл\w+\s+из России|покида\w+\s+российск|'
    r'прода\w+\s+(?:100%\s+|свой\s+|свои\s+)?российск\w+\s+(?:бизнес|актив|подразделен|дочк|структур)|'
    r'российск\w+\s+(?:бизнес|актив|подразделен|дочк)\w*\s+'
    r'(?:немецк|британск|американск|французск|финск|японск|итальянск|шведск|австрийск|'
    r'нидерландск|голландск|швейцарск|датск|норвежск|польск|турецк|корейск|испанск|бельгийск)|'
    r'выход\w+\s+(?:иностранн|из российск)|деконсолидац|'
    r'выкуп\w*\s+(?:у\s+)?иностранн\w+\s+(?:владел|акционер|собственник)|'
    r'(?:выкупил\w*|приобрел\w*|купил\w*|прода\w+)\s+(?:100%\s+)?российск\w+\s+подразделен'
)

# (паттерн, извлекатель текста, антипаттерн, структурный признак).
# Структурный признак — предикат по надёжным полям kind/type; срабатывает
# независимо от текста. pat=None -> тема определяется ТОЛЬКО структурно.
THEMES = {
    'Уход иностранного владельца': (
        FOREIGN, core, None,
        lambda d: d.get('type') == 'Выкуп у иностранного владельца'),
    'Правкомиссия / указ президента': (
        r'правительственн\w+\s+комисси|правкомисси|указ\w*\s+президент|'
        r'разрешени\w+\s+президент|временн\w+\s+управлени', core_appr, None, None),
    # 5 сентября 2026: раздел «Аналитики» об изъятых активах показал, что
    # правило видело четверть таких сделок (16 из ~55): не было слов о
    # временном управлении по указу, конфискации, деприватизации и продаже
    # изъятого Росимуществом, а согласования (law.appr — где чаще всего и
    # стоит «указ президента передал … во временное управление») не читались.
    # Хвост дотегирован add_nationalization_theme_batch.py (каждый id прочитан);
    # здесь — чтобы новые карточки притока получали тему сами. `extra`
    # по-прежнему не читаем: там исторический фон, а не сама сделка.
    'Национализация / иск Генпрокуратуры': (
        r'Генпрокуратур|обращ\w+\s+в\s+(?:доход|собственност\w*)\s+государств|национализ|'
        r'признан\w+\s+экстремистск|изъят\w+\s+(?:в\s+(?:пользу|доход)\s+государств|государством)|'
        r'конфиск\w+\s+в\s+доход|деприватизац|экспроприац|'
        r'(?:передан\w*|перешл\w*|перед[аё]\w*|получил\w*)\s+[^.;]{0,80}?во?\s+временн\w+\s+управлен|'
        r'Росимуществ\w*\s+(?:продал|продаёт|выставил|выставляет)\w*\s+[^.;]{0,80}?(?:изъят|конфиск|национализ)',
        core_appr, None, None),
    # «Торги» — это и продажа с молотка, и биржа (урок CLAUDE.md). Голое
    # слово давало ложные срабатывания ровно этого вида: «приостановка
    # торгов на американской бирже», «30 дней после начала торгов» у IPO,
    # «участникам торгов предложили купить 11,5%» при размещении. Слово
    # засчитывается только в аукционном обороте, а рядом стоящая биржа
    # отменяет тему целиком.
    'Продажа с торгов': (
        r'аукцион|Российский аукционный дом|РТС-Тендер|публичн\w+\s+предложени|'
        r'(?:на|с|через)\s+(?:открыт\w+\s+|электронн\w+\s+|публичн\w+\s+)?торг(?:ах|ов|и)\b|'
        r'выставл\w+\s+на\s+торги|победител\w*\s+торгов|итог\w*\s+торгов|'
        r'торги\s+(?:состоял|проход|назначен|признан)', core,
        r'вне\s+торгов|без\s+публичн\w+\s+аукцион|без\s+торгов|не\s+состоял\w+\s+аукцион|'
        r'бирж|начал\w*\s+торгов|приостановк\w*\s+торгов|участник\w*\s+торгов',
        lambda d: d.get('type') == 'Продажа с торгов'),
    # Отрицание «не банкротство» ловилось как признак банкротства: у карточки
    # «Шереметьево приобрёл активы Домодедово» в тексте прямо написано «(по
    # иску Генпрокуратуры, НЕ банкротство)» — и тема ставилась именно на этих
    # словах. Тот же класс, что уже отсечён у торгов («вне торгов»).
    'Банкротство / долги': (
        r'банкротств|финансов\w+\s+оздоровлен|конкурсн\w+\s+производств|'
        r'выкуп\w*\s+долг|санаци|санирова', core,
        r'не\s+банкротств|без\s+банкротств|не\s+явля\w+\s+банкротств|'
        r'вне\s+процедур\w*\s+банкротств|избежа\w+\s+банкротств', None),
    'IPO / SPO': (
        r'\bIPO\b|\bSPO\b|pre-?IPO|размещени\w+\s+акций|котировальн\w+\s+список', head, None,
        lambda d: d.get('kind') == 'ipo' or str(d.get('type') or '').upper().startswith('IPO')),
    'Венчур / раунд': (
        r'раунд\w*\s+[A-DA-Я]\b|pre-?seed|seed-?раунд|венчурн\w+\s+инвест|'
        r'посевн\w+\s+раунд|Series\s+[A-D]\b', core, None,
        lambda d: d.get('type') in ('Венчурная инвестиция', 'Инвестиционный раунд')),
    'Консолидация доли': (
        r'консолидир\w*\s+(?:контроль|долю|пакет|100|\d{1,3}%)|увеличил\w*\s+(?:свою\s+)?долю|'
        r'выкуп\w*\s+оставш|довел\w*\s+(?:свою\s+)?долю|нарастил\w*\s+долю', core, None, None),
    # Замечание партнёра 31 августа 2026 («Неужели создания СП реально 2?»):
    # тема считалась только по структурному признаку kind == 'jv', а он стоит
    # у 4 карточек из 1563. Текст добавлен, но только про СОЗДАНИЕ (выкуп
    # доли партнёра в существующем СП — не эта тема): «создали СП»,
    # «создают совместное предприятие», «объединяют активы», «передала … в
    # совместное предприятие». Тип «СП»/«Создание СП» — тоже признак.
    'Создание СП': (
        r'созда\w+\s+(?:совместн\w+\s+(?:предприяти|компани|фонд|логистическ)|СП\b)|'
        r'объедин\w+\s+(?:свои\s+)?(?:активы|бизнес)|'
        r'(?:передал\w*|внес\w*|вложил\w*|внёс\w*)\s+[^.;]{0,80}\s+в\s+(?:совместн\w+\s+предприяти|СП\b)|'
        r'(?:^|[^а-яё])СП\s+(?:для|по)\s|запуск\w*\s+совместн\w+',
        core, r'выкуп\w*\s+[^.;]{0,40}\s+в\s+(?:совместн|СП\b)|доля\s+в\s+СП',
        lambda d: d.get('kind') == 'jv' or d.get('type') in ('СП', 'Создание СП')),
    'Искусственный интеллект': (
        r'(?:\bИИ\b|искусственн\w*\s+интеллект|artificial\s+intelligence|'
        r'(?:^|[^a-z])AI(?:[^a-z]|$)|нейросет|генеративн\w+\s+(?:модел|ИИ)|'
        r'\bLLM\b|машинн\w+\s+обучен)', head, None,
        lambda d: d.get('ind') == 'Искусственный интеллект'
                  or 'Искусственный интеллект' in (d.get('industries') or [])),
}


def themes_of(d):
    tags = []
    for name, (pat, getter, anti, struct) in THEMES.items():
        hit = bool(struct(d)) if struct else False
        if not hit and pat is not None:
            text = getter(d)
            hit = bool(re.search(pat, text, re.I))
            if hit and anti and re.search(anti, text, re.I):
                hit = False
        if hit:
            tags.append(name)
    return tags


def add_themes(deal):
    """Дописать темы карточке, НИЧЕГО НЕ УДАЛЯЯ. Возвращает добавленные.

    Почему только дописываем. Поле `themes` в базе давно живёт своей жизнью:
    замер 3 сентября 2026 — у 82 карточек стоят темы, которых нынешние
    правила не подтверждают (их ставили руками и отдельными скриптами, и
    среди них есть верные). Сплошная перезапись `themes_of()` снесла бы их
    все разом. Поэтому у притока и дочитывания — только дописывание: новая
    тема появляется, старая не исчезает никогда. Убрать неверную тему может
    человек отдельным скриптом, прочитав карточку.
    """
    have = list(deal.get('themes') or [])
    added = [t for t in themes_of(deal) if t not in have]
    if added:
        deal['themes'] = have + added
    return added


assert add_themes({'title': 'IPO «Группа Астра» на Московской бирже'}) == ['IPO / SPO']
_keep = {'title': 'Обычная покупка доли', 'themes': ['Ручная тема']}
assert add_themes(_keep) == [] and _keep['themes'] == ['Ручная тема'], 'чужая тема не должна исчезать'


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deals = data['deals']
    stats = collections.Counter()
    per = collections.Counter()
    for d in deals:
        tags = themes_of(d)
        if tags:
            d['themes'] = tags
            per[len(tags)] += 1
            for t in tags:
                stats[t] += 1
        else:
            d.pop('themes', None)
    for k, v in stats.most_common():
        print(f'{v:5}  {k}')
    tagged = sum(per.values())
    print(f'\nразмечено сделок: {tagged} / {len(deals)}  ({tagged * 100 // len(deals)}%)')
    print('тем на сделку:', sorted(per.items()))
    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=1, ensure_ascii=False)
        print('\nЗАПИСАНО в', PATH)


if __name__ == '__main__':
    main(write='--write' in sys.argv)
