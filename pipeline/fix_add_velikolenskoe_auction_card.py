"""Приток, 16:20 МСК 29 сентября 2026: URA.RU (со ссылкой на данные
«Федресурса») сообщил, что торги по продаже имущественного комплекса
обанкротившегося ООО «Великоленское» (Пермский край, молочное, мясное и
зерновое производство) не состоялись из-за отсутствия заявок — лот
выставляли единым комплексом за 235,53 млн ₽. Повторные торги назначены
на 11 ноября со сниженной стартовой ценой 211,98 млн ₽. Ворота не
пропустили черновик как сделку (заголовок не разобрался на стороны
автоматически). Собрал вручную — тот же класс случая, что карточка
Боброва (`g5b4e85aa`) этим же часом.

Есть спор об оценке: бывший владелец Михаил Трушников оспаривает в
арбитраже цену (125,3 млн ₽ по майской оценке), считая активы дороже, —
перенесено в law.struct дословно, без домысливания, кто прав.

Источник единственный (URA.RU) — честно в eco.context.

Запуск: python3 pipeline/fix_add_velikolenskoe_auction_card.py [--write]
"""
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'ingest'))

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')


def main(write=False):
    import promote

    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    ids = {c['id'] for c in data['deals']}
    new_id = promote.new_id(ids)

    draft = {
        'date': '2026-09-29',
        'title': 'Торги по продаже обанкротившегося пермского агрохолдинга «Великоленское» не состоялись',
        'ind': 'Агро',
        'type': 'Продажа с торгов',
        'status': 'Не состоялась',
        'sum': '235,53 млн ₽',
        'seller': 'ООО «Великоленское» (конкурсное производство)',
        'asset': 'имущественный комплекс ООО «Великоленское»',
        'src': [['URA.RU', 'https://ura.news/news/1053131915']],
        'events': [
            {'kind': 'cancelled', 'date': '2026-09-29', 'title': 'Торги признаны несостоявшимися',
             'note': 'Торги по продаже имущественного комплекса обанкротившегося ООО '
                     '«Великоленское» не состоялись из-за отсутствия заявок.',
             'source': ['URA.RU', 'https://ura.news/news/1053131915']},
        ],
    }
    card = promote.to_card(draft, new_id)
    card['eco']['sum'] = draft['sum']
    card['eco']['context'] = (
        'На повторных торгах начальная стоимость имущества снижена до 211,98 млн ₽; '
        'аукцион назначен на 11 ноября, заявки принимаются до 30 октября. В состав лота '
        'входят земельные участки, здания и сооружения, оборудование, инвентарь, сырьё, '
        'готовая продукция. «Великоленское» специализировалось на производстве молочной, '
        'мясной и зерновой продукции, а также развивало агродеревню «Степаново городище». '
        'В феврале 2024 года Арбитражный суд Пермского края признал предприятие банкротом '
        'и открыл конкурсное производство — на тот момент задолженность перед кредиторами '
        'составляла 34,3 млн ₽.'
    )
    card['law']['struct'] = (
        'В мае 2026 года рыночную стоимость комплекса оценили в 125,3 млн ₽. С этой суммой '
        'не согласился бывший владелец «Великоленского» Михаил Трушников — по его мнению, '
        'активы предприятия стоят дороже; он оспорил в арбитражном суде решение собрания '
        'кредиторов об условиях продажи имущества. Владельцами компании являются Михаил '
        'Трушников и ООО «Инвестиции и консалтинг».'
    )
    card['themes'] = ['Продажа с торгов']
    # `to_card` не ставит `added` — обычно его ставит `approve.py` при выводе
    # карточки из pending.json; прямая запись минует этот путь, дата не
    # выдумана — карточка правда добавлена сегодня.
    card['added'] = '2026-09-29'

    data['deals'].append(card)
    print('Добавлена карточка %s: %s' % (new_id, card['title']))

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
