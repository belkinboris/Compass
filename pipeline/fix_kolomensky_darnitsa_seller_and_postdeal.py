# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка `g31541607`
(«БКХ «Коломенский» приобрёл ГК «Дарница»», закрыта, 2023) — дочитывание
нашло продавца (структурное поле было пустым) и судьбу компании после
сделки.

Проверено (по докладу саб-агента, дословные цитаты):
- kommersant.ru/doc/6174028: «100% долей в уставном капитале «Дарницы»
  владеет АО «Аладушкин групп» бизнесмена Александра Аладушкина» —
  независимо подтверждено sostav.ru («100% долей… владеет АО «Аладушкин
  групп», принадлежащая бизнесмену Александру Аладушкину», «Дарницу» он
  выкупил в 2013 году»).
- audit-it.ru/contragent/1117847306807_ooo-gk-darnitsa: «Новый
  учредитель – ООО БКХ "КОЛОМЕНСКИЙ"» (с 14.09.2023) — подтверждает дату
  закрытия; компания статус «действующая коммерческая»; «В 2025 году
  организация получила выручку в сумме 5,4 млрд руб.… прибыль в размере
  81,3 млн руб.» — компания продолжает работать под своим именем и
  брендом, переименования или закрытия площадок не найдено.

НЕ ВНЕСЕНО: (1) точная (не оценочная) сумма сделки — во всех источниках
только одна и та же оценка эксперта («не более 3 млрд ₽» / «около 3 млрд
₽»), уже отражённая в карточке; фигура «1,5 млрд ₽», которая тоже стоит
в `eco.val`, отдельным источником саб-агентом не переподтверждена, но и
не опровергнута — оставлена как есть; (2) юридический/финансовый
консультант — ноль по ~15 проверенным источникам (Коммерсантъ ×3, РБК,
Ведомости.СПб, ТАСС, Sostav, Агроинвестор, Fontanka, DP.ru, TAdviser,
официальный релиз Хлеб.ру); (3) точная сумма долга «Дарницы» — ни один
источник не называет цифру, только качественное «долговая нагрузка».

Запуск: python3 pipeline/fix_kolomensky_darnitsa_seller_and_postdeal.py
        python3 pipeline/fix_kolomensky_darnitsa_seller_and_postdeal.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g31541607'

OLD_SELLER = None
NEW_SELLER = 'АО «Аладушкин групп» (Александр Аладушкин)'

OLD_ECO_CONTEXT = (
    'По неофициальным данным, «Дарница» могла быть заинтересована в '
    'продаже бизнеса «Коломенскому» из-за долгов. Исполнительный '
    'директор Национального союза хлебопечения Рустам Айдиев поясняет, '
    'что раньше основная производственная площадка «Дарницы» стояла в '
    'арендованном имущественном комплексе, который компания впоследствии '
    'выкупила, видимо, на заёмные средства. Это, по его мнению, не могло '
    'не повлиять на рост долговой нагрузки производителя.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' После сделки (закрыта 14 сентября 2023 года) '
    '«Дарница» продолжила работать как отдельное юрлицо и бренд: в 2025 '
    'году её выручка составила 5,4 млрд ₽, прибыль — 81,3 млн ₽; '
    'переименования или закрытия площадок не было.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal.get('seller') == OLD_SELLER
    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    print('=== seller: станет ===')
    print(NEW_SELLER)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)

    if write:
        deal['seller'] = NEW_SELLER
        deal['eco']['context'] = NEW_ECO_CONTEXT
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
