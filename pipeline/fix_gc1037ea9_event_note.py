# -*- coding: utf-8 -*-
"""Карточка gc1037ea9 (приток, 25 ноября 2026): events[0].note обрывался
многоточием на середине («Самого разработчика…») и почти дословно повторял
предложение источника («Эксперты оценили сделку в … и считают, что за
закрытым фондом может стоять крупный инвестор»). events[0] — элемент
списка, `review.py`'s get_field/set_field его не достает (путь только через
точку в имени поля), поэтому правится отдельным разовым скриптом — тот же
прием, что и в предыдущих карточках притока (fixes/g67cacd7e_*,
fixes/gc708f8c0_*). Дата этапа также переносится на 10 ноября 2026 — день
регистрации перехода доли в ЕГРЮЛ (review.py уже перенес туда карточную
`date` тем же днем).

Запуск:
    python3 pipeline/fix_gc1037ea9_event_note.py            # сухой прогон
    python3 pipeline/fix_gc1037ea9_event_note.py --write     # запись
"""
import json
import sys

PATH = "static/data/pending.json"
ID = "gc1037ea9"

OLD_NOTE = ('ЗПИФ «Аталанта» под управлением «Вим сбережения» купил 7,8% в российском '
            'разработчике полного цикла оборудования для ЦОД и телекома. Эксперты '
            'оценили сделку в 2–4 млрд руб. и считают, что за закрытым фондом может '
            'стоять крупный инвестор. Самого разработчика…')
NEW_NOTE = ('ЗПИФ «Аталанта» получил 7,8% долей в «Бифорком тек» — не выкупом у '
            'прежнего владельца, а через увеличение уставного капитала компании; '
            'переход был зарегистрирован в ЕГРЮЛ 10 ноября 2026 года. Названные '
            'эксперты расходятся в оценке пакета — от 2 до 4 млрд рублей — и '
            'полагают, что за непубличным фондом может стоять крупный '
            'институциональный игрок.')
OLD_DATE = '2026-11-25'
NEW_DATE = '2026-11-10'


def main(write):
    with open(PATH, encoding='utf-8') as f:
        base = json.load(f)
    by_id = {c['id']: c for c in base['cards']}
    c = by_id[ID]
    ev = c['events'][0]
    assert ev['note'] == OLD_NOTE, 'events[0].note уже другой — уже правили?'
    assert ev['date'] == OLD_DATE, 'events[0].date уже другой — уже правили?'
    ev['note'] = NEW_NOTE
    ev['date'] = NEW_DATE
    print('%s: events[0].note переписан своими словами без обрыва; events[0].date -> %s' % (ID, NEW_DATE))

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(base, f, ensure_ascii=False, indent=1)
            f.write('\n')
        print('\nЗАПИСАНО.')
    else:
        print('\nСухой прогон — ничего не записано. Добавьте --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
