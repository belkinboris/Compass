import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g8ce554c5'

OLD_EXTRA = (
    'Девелопер «Эталон» приобретает участок почти на 30 га у '
    'регионального девелопера «Рамо-М». На площадке планируется '
    'строительство жилого комплекса на 250 000 кв.м. Возможна '
    'последующая покупка ТЦ «Парк хаус» для второй очереди ЖК.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' По данным агрегаторов ЕГРЮЛ, к 2025 году единственным '
    'учредителем ООО «Бугры1» (компания с этой землёй на балансе) '
    'значится не структура «Эталона», а «Специализированный застройщик '
    '«Семья-7»» — не установленная связь с «Эталоном»; ни начала '
    'строительства, ни покупки ТЦ «Парк хаус» публично не подтверждено.'
)

NEW_SRC = [
    ['ЕГРЮЛ (агрегатор)', 'https://star-pro.ru/proverka-kontragenta/organization/1217800035650--ooo-bugry1'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
