import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g256dd345'

OLD_STATUS = 'Обсуждается'
NEW_STATUS = 'Закрыта'

OLD_CONTEXT = (
    'Весной 2023 года банк выставил птицефабрику на торги с начальной'
    ' ценой 1,95 млрд ₽. Аукцион не состоялся: заявок не поступило.'
)
NEW_CONTEXT = (
    OLD_CONTEXT + ' Сделка закрылась в октябре 2023 года, итоговая цена'
    ' не раскрывалась. В феврале 2025 года 100% долей птицефабрики'
    ' перешли к ЗПИФ «Агро-Капитал», а в июле 2025 года — к ООО «ПРО'
    ' Яйцо»; оба перехода — внутри той же группы «Таврос», не продажа'
    ' третьей стороне.'
)

OLD_TARGET_FIN = 'Выручка птицефабрики за 2022 год — 3,6 млрд ₽, чистая прибыль — 15,8 млн ₽.'
NEW_TARGET_FIN = (
    OLD_TARGET_FIN + ' За 2024 год выручка выросла на 19,5% (до 5,4 млрд'
    ' ₽), прибыль увеличилась на 134% (до 3 млрд ₽).'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['status'] == OLD_STATUS
    assert deal['eco']['context'] == OLD_CONTEXT
    assert deal['eco']['target_fin'] == OLD_TARGET_FIN

    print('=== status: станет ===')
    print(NEW_STATUS)
    print('\n=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== eco.target_fin: станет ===')
    print(NEW_TARGET_FIN)

    if write:
        deal['status'] = NEW_STATUS
        deal['eco']['context'] = NEW_CONTEXT
        deal['eco']['target_fin'] = NEW_TARGET_FIN
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
