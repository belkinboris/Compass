import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g585f0c61'

OLD_EXTRA = (
    'Приобретение ООО «ДЖОН ДИР ФАЙНЭНШЛ» инвестиционной группой '
    '«Инсайт» Авета Миркаяна. Сделка закрыта 7 марта 2023 года. '
    'Эксперты оценивают сумму возможно в 11 млрд руб. Источники '
    'финансирования включали размещение облигаций на 11 млрд руб.'
)
NEW_EXTRA = (
    'Приобретение ООО «ДЖОН ДИР ФАЙНЭНШЛ» инвестиционной группой '
    '«Инсайт» Авета Миракяна. Сделка закрыта 7 марта 2023 года. '
    'Эксперты оценивают сумму возможно в 11 млрд руб. Источники '
    'финансирования включали размещение облигаций на 11 млрд руб.'
)

OLD_LAW_APPR = 'Публично не сообщалось'
NEW_LAW_APPR = (
    'Сделка была одобрена подкомиссией правительственной комиссии по '
    'контролю за осуществлением иностранных инвестиций в начале 2023 '
    'года.'
)

OLD_ECO_CONTEXT = (
    '«Наша цель — выстроить лизинговый холдинг, который объединит '
    'именно лизинговые компании с разными компетенциями. '
    'Последовательно следуя этой стратегии, мы приобрели «Джон Дир '
    'Файнэншл» и не исключаем совершения и других сделок на этом '
    'рынке»,— заявил в связи с последним приобретением представитель '
    '«Инсайта».'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' В апреле 2023 года компания переименована в '
    'Fleet Finance, штат вырос с 17 человек (март 2023) до около 40. '
    'Обещание «не исключаем совершения и других сделок на этом рынке» '
    'сбылось: в августе 2023 года «Инсайт» купила «РНЛ Лизинг» у '
    'группы Renault, а в августе 2026 года «Флит Лизинг» купил «МБ РУС '
    'Финанс» у «Автодома» (бывшая «дочка» Mercedes-Benz).'
)

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/business/890070'],
    ['agroinvestor.ru', 'https://www.agroinvestor.ru/business-pages/41113-fleet-finance-staryy-novyy-brend-na-lizingovom-rynke/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA
    assert deal['law']['appr'] == OLD_LAW_APPR
    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    existing_urls = {s[1] for s in deal['src']}
    add_src = [s for s in NEW_SRC if s[1] not in existing_urls]
    new_src = deal['src'] + add_src

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== law.appr: станет ===')
    print(NEW_LAW_APPR)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    if add_src:
        print('\n=== src: добавится ===')
        for s in add_src:
            print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['law']['appr'] = NEW_LAW_APPR
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
