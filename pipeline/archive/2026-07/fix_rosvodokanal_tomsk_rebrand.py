"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g173f659d (ГК «Росводоканал» приобрела ООО «Томскводоканал») —
интеграция актива после сделки не была отражена. Проверено лично
прямым WebFetch двух источников.

`eco.context` (дополнено). Интеграция завершилась ребрендингом.
Дословно (РИА Томск, 17.02.2026): «Ребрендинг «Томскводоканала»
является завершающим этапом его интеграции в ГК «Росводоканал»;
переименование в «Росводоканал Томск» не потребует существенных
затрат». Новый оператор обсуждает переход инфраструктуры на
концессию с крупными инвестициями: дословно (гендиректор «Росводоканал
Томск» Игорь Мажейкин, март 2026): «в рамках концессии мы
рассматриваем мероприятия... на 60 миллиардов рублей» — на фоне
износа сетей 60-70%, по его же словам.

НЕ ВКЛЮЧЕНО: судьба Кирилла Новожилова (стал директором компании
«Деревенское молочко» с 11 февраля 2026 года) — источник не связывает
это назначение с продажей «Томскводоканала» прямо, это отдельная
карьерная веха, не факт об ЭТОЙ сделке. Судьба Татьяны Мальцевой,
консультанты сделки, точная сумма — не найдены ни в одном источнике.
Судебный эпизод с незаконной майнинг-фермой на водозаборе (штраф 350
тыс. ₽, январь 2024) — датирован ДО закрытия сделки (1 марта 2024),
не относится к периоду после смены собственника.

Запуск: python3 pipeline/fix_rosvodokanal_tomsk_rebrand.py
        python3 pipeline/fix_rosvodokanal_tomsk_rebrand.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g173f659d'

OLD_CONTEXT = (
    'ранее 80% долей «Томскводоканала» принадлежало местному '
    'предпринимателю Кириллу Новожилову (бывший депутат думы Томска, '
    'также занимается молочным бизнесом), еще 20% — Татьяне Мальцевой.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' 17 февраля 2026 года интеграция завершилась ребрендингом: '
    '«Томскводоканал» переименован в «Росводоканал Томск». Новый '
    'оператор обсуждает переход инфраструктуры на концессию — '
    'гендиректор «Росводоканал Томск» Игорь Мажейкин заявил (март '
    '2026): «в рамках концессии мы рассматриваем мероприятия... на 60 '
    'миллиардов рублей» — на фоне износа сетей 60-70%.'
)

NEW_SRC = [
    ['РИА Томск', 'https://www.riatomsk.ru/article/20260217/tomskvodokanal-rebrending-rosvodokanal-tomsk'],
    ['РИА Томск', 'https://www.riatomsk.ru/article/20260312/rosvodokanal-rasschitivaet-privlech-60-mlrd-rub-v-tomskie-seti'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_CONTEXT
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.context: станет ===')
    print(NEW_CONTEXT)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_CONTEXT
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
