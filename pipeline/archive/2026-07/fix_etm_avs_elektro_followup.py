# -*- coding: utf-8 -*-
"""Месячная очередь, 8 сентября 2026 — карточка `cccedc36b» (ЭТМ купил
«АВС-Электро», май 2025). Найдено продолжение: спустя год после сделки
«АВС-Электро» показала резкое падение выручки и убыток, гендиректор
сменился. Личный WebFetch (kommersant.ru/doc/8553683, 02.04.2026):
«Выручка компании упала с 10,28 до 5,16 млрд руб.»; «С убытками на 964,6
млн руб. завершило 2025 год воронежское ООО «АВС-Электро»» (годом ранее
— чистая прибыль 197,7 млн ₽); «С 1 апреля 2026-го генеральным
директором предприятия был назначен Евгений Поздняков. Он сменил
Наталью Шишкину, которая руководила фирмой с мая 2020 года» — статья
прямо связывает это со сделкой: «В мае прошлого года о слиянии с
«АВС-Электро» объявило питерское ООО «ТД "Электротехмонтаж"»».

Отдельно проверено и НЕ является тем же событием: упомянутое в самом же
источнике-слаге RusCable.ru объединение «Русский Свет»/«Минимакс» — сам
источник прямо разводит два события («По неподтвержденной информации
26 июня произошла и другая крупная сделка — Русский Свет и Минимакс
объединяются»), это не факт для этой карточки.

Точные юрлица (найдены, но НЕ вносятся в структурные поля без решения
о создании профилей компаний — это работа отдельного прогона): ЭТМ =
АО «ТД Электротехмонтаж» (СПб, с 2024 года), АВС-Электро = ООО
«АВС-Электро» (Воронеж, с 2001 года).

Поле `eco.context` уже прошло вычитку — за основу слияния взят ТЕКУЩИЙ
текст с диска. `law.struct` тоже проходило вычитку, но не трогается.

Запуск:
    python3 pipeline/fix_etm_avs_elektro_followup.py            # сухой прогон
    python3 pipeline/fix_etm_avs_elektro_followup.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'
CARD_ID = 'cccedc36b'

OLD_CONTEXT = (
    'Крупнейший дистрибьютор инженерных систем ТД Электротехмонтаж (ЭТМ, '
    'Санкт-Петербург) приобрел ООО АВС-электро (Воронеж), оптово-'
    'розничного торговца электротехническими материалами и оборудованием '
    'с услугами электромонтажа и пусконаладки.'
)
NEW_CONTEXT = OLD_CONTEXT + (
    ' Спустя год после сделки, по итогам 2025 года, у «АВС-Электро» '
    'выручка упала с 10,28 до 5,16 млрд ₽, а прибыль (197,7 млн ₽ за '
    '2024 год) сменилась убытком в 964,6 млн ₽; с 1 апреля 2026 года '
    'гендиректором вместо Натальи Шишкиной, руководившей компанией с '
    '2020 года, назначен Евгений Поздняков.'
)

NEW_SRC = ['Коммерсантъ', 'https://www.kommersant.ru/doc/8553683']


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}
    card = by_id[CARD_ID]

    assert card['eco']['context'] == OLD_CONTEXT, \
        'eco.context уже другой: %r' % (card['eco']['context'],)

    print('eco.context: добавляется факт о падении выручки и смене '
          'гендиректора АВС-Электро (Коммерсантъ, 02.04.2026)')
    existing_urls = {s[1] for s in card['src']}
    if NEW_SRC[1] not in existing_urls:
        print('src: добавляется', NEW_SRC)

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    card['eco']['context'] = NEW_CONTEXT
    if NEW_SRC[1] not in existing_urls:
        card['src'].append(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
