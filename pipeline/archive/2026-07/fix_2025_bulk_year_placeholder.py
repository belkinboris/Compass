# -*- coding: utf-8 -*-
"""Семь карточек несли год «2025» (без месяца и дня — заглушка компактного
импорта), а источники прямо датируют события 2026 годом.

ЧТО СЛОМАНО. Все семь карточек попали в базу без точной даты — только год.
При дочитывании очереди 2025 года («срез» этой рутины) источники каждой из
них оказались статьями «Коммерсанта» или «Известий», датированными
апрелем-маем 2026 года, и текст описывает событие как текущее/недавнее
(«следует из сообщения компании от 28 мая», «в мае было осуществлено»,
«22 мая 2026» в метаданных статьи и т. д.) — то есть год-заглушка «2025»
оказался неверным, а не просто неточным.

ПОЧЕМУ НЕ ЧЕРЕЗ `review.py`. `date_is_supported()` намеренно запрещает
менять год — перенос года обязан быть отдельным, явным решением с
проверяемым источником (см. уроки CLAUDE.md про g6d73538c, gd6b3c796,
ge0f7b957), а не автоматической правкой в общей таблице.

ПОЧЕМУ ПОЛНАЯ ДАТА, А НЕ ТОЛЬКО ГОД. У каждой карточки источник называет не
только год, но и точный день публикации/события — ничего не приходится
досочинять:
  - g5b8fa758 (Яндекс/Островок): kommersant.ru датирует материал
    «28.05.2026, 13:04», текст — «в мае было осуществлено 24,8%…»
    (в настоящем, «в мае» = май текущего для статьи года).
  - gb2d5da8c (Орехов/«Азот»): «увеличил долю... следует из сообщения
    компании от 28 мая», статья kommersant.ru датирована «28.05.2026».
  - g10053480 (Таврос/«Саратов-Птица»): kommersant.ru — «15.05.2026, 02:24».
  - ge361bfa8 (Харитонин/Reckitt): iz.ru — метатег
    «2026-05-22T00:01:00+03:00», в подписи «22 мая 2026, 00:01».
  - gd1b1a94e (Бумеранг Капитал/Cofix): kommersant.ru — «19.04.2026, 15:33».
  - g670ed747 (ГК «Кириллица»/Луговское месторождение): kommersant.ru —
    «25.05.2026, 12:01», текст говорит о планах «до конца этого года» и
    «испытания начнутся осенью этого года» — тот же 2026 год.
  - g8dfb3aa0 (Supplement Group/«Лейблпак»): kommersant.ru — «20.02.2026,
    06:00 обновлено 17:50, 25.02». У этой же карточки — второй, независимый
    дефект: статус стоял «Закрыта», хотя текст прямо это опровергает:
    «В материал внесены изменения: ранее представители Supplement Group
    утверждали, что сделка закрыта, но после уточнили, что она только
    согласована» — реальный статус на момент публикации «Обсуждается»
    (заключено соглашение о намерениях, не закрытие).

Все семь карточек статусом «Обсуждается»/«Закрыта» относятся к 2026 году —
это выводит их из среза 2025 года, которым занимается эта рутина; дальше их
читает поток 2026 года.

Запуск:
    python3 pipeline/fix_2025_bulk_year_placeholder.py            # сухой прогон
    python3 pipeline/fix_2025_bulk_year_placeholder.py --write    # записать
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

FIXES = [
    dict(id='g5b8fa758', old_date='2025', new_date='2026-05-28',
         quote='kommersant.ru датирует материал «28.05.2026, 13:04»; '
               'текст — «Через «Островок» в мае было осуществлено 24,8% '
               'гостиничных бронирований»'),
    dict(id='gb2d5da8c', old_date='2025', new_date='2026-05-28',
         quote='увеличил долю в крупном производителе удобрений ГК «Азот» '
               'с 60% до 100%, следует из сообщения компании от 28 мая — '
               'статья kommersant.ru датирована «28.05.2026, 20:32»'),
    dict(id='g10053480', old_date='2025', new_date='2026-05-15',
         quote='kommersant.ru датирует материал «15.05.2026, 02:24»'),
    dict(id='ge361bfa8', old_date='2025', new_date='2026-05-22',
         quote='iz.ru: метатег публикации «2026-05-22T00:01:00+03:00», '
               'в подписи «22 мая 2026, 00:01»'),
    dict(id='gd1b1a94e', old_date='2025', new_date='2026-04-19',
         quote='kommersant.ru датирует материал «19.04.2026, 15:33»'),
    dict(id='g670ed747', old_date='2025', new_date='2026-05-25',
         quote='kommersant.ru датирует материал «25.05.2026, 12:01»; '
               'текст — «Испытания на Луговском месторождении начнутся '
               'осенью этого года»'),
    dict(id='g8dfb3aa0', old_date='2025', new_date='2026-02-20',
         old_status='Закрыта', new_status='Обсуждается',
         quote='kommersant.ru датирует материал «20.02.2026, 06:00 '
               'обновлено 17:50, 25.02»; текст — «В материал внесены '
               'изменения: ранее представители Supplement Group '
               'утверждали, что сделка закрыта, но после уточнили, что '
               'она только согласована»'),
]


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}

    for fix in FIXES:
        deal = by_id.get(fix['id'])
        assert deal is not None, 'нет сделки %s' % fix['id']
        assert deal.get('date') == fix['old_date'], \
            '%s: дата уже другая: %r, ожидали %r' % (
                fix['id'], deal.get('date'), fix['old_date'])
        if 'old_status' in fix:
            assert deal.get('status') == fix['old_status'], \
                '%s: статус уже другой: %r, ожидали %r' % (
                    fix['id'], deal.get('status'), fix['old_status'])
        print('%s: date %r -> %r' % (fix['id'], fix['old_date'], fix['new_date']))
        if 'old_status' in fix:
            print('  status %r -> %r' % (fix['old_status'], fix['new_status']))
        print('  цитата: %r' % fix['quote'])

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    for fix in FIXES:
        deal = by_id[fix['id']]
        deal['date'] = fix['new_date']
        if 'old_status' in fix:
            deal['status'] = fix['new_status']

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
