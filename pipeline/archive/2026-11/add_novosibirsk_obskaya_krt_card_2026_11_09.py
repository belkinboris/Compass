# -*- coding: utf-8 -*-
"""Приток, 9 ноября 2026: NGS.RU сообщила, что участок на берегу Оби в
Новосибирске (улицы Обская, Бердский переулок, Закавказская, почти 1,8 га) —
проект комплексного развития территории (КРТ) — выставлен на торги на
площадке «ГИС Торги»; стартовая цена реализации проекта — 319,1 млн ₽,
аукцион назначен на конец ноября 2026 года (точная дата в статье не
названа).

Заголовок источника («Участок с частными и аварийными домами у берега Оби
выставили на торги — за землю просят почти 320 миллионов рублей») написан
обзорно, без структуры «X продал Y» — ворота (promote.py) отклонили
находку: «не установлен предмет сделки». Та же картина, что у памятника
архитектуры в Краснодаре (g134d5b0e) и мусоросжигательного завода в
Ростове-на-Дону (add_rostov_incineration_plant_card_2026_11_09.py) — лот
предметно описан (адрес/ориентиры, площадь, цена, обязательства
застройщика), карточка собирается вручную.

Организатор торгов НЕ назван в статье явно — сказано только, что
объявление появилось на «ГИС Торги». В июле 2026 года мэрия Новосибирска
публиковала проект постановления о КРТ этой территории, но прямой связи
«мэрия = организатор этого аукциона» источник не утверждает — поэтому
seller сформулирован честно, без приписывания точного органа. WebSearch
по деталям лота (сумма, адреса, площадка) второй источник не нашёл —
обычное дело для муниципального аукциона в день публикации объявления
(та же картина у Ростова/Кургана, see g955d2c6b/accepted_notes).

На участке сейчас 16 частных домов и 3 многоквартирных дома; в заголовке
источника они названы «аварийными», но в тексте статьи прямо об
аварийности всех построек не сказано — в eco.context это разделено.
Дом на Обской, 78, не расселяют 8 лет; в августе 2026 этим заинтересовался
глава СК РФ Александр Бастрыкин, облСК завел дело о халатности (ст. 293 УК).

Продавец/организатор — не компания, профиль не заводится (не юрлицо).
Собрано вручную — не в базу напрямую, а в pending.json, чтобы карточка
прошла обычный путь: accept_card.py -> second_reading.py -> ship_card.py.

Запуск: python3 pipeline/archive/2026-11/add_novosibirsk_obskaya_krt_card_2026_11_09.py [--write]
"""
import json
import os
import sys
from datetime import datetime, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
INGEST = os.path.join(os.path.dirname(os.path.dirname(HERE)), 'ingest')
if INGEST not in sys.path:
    sys.path.insert(0, INGEST)

SRC = ('NGS.RU', 'https://ngs.ru/text/realty/2026/11/09/76753936/')


def main(write):
    import promote

    pending = promote.load_pending()
    existing_ids = {c['id'] for c in pending['cards']}
    base = json.load(open(promote.DATA, encoding='utf-8'))
    existing_ids |= {c['id'] for c in base['deals']}
    new_id = promote.new_id(existing_ids)

    draft = {
        'date': '2026-11-09',
        'title': 'Участок на Обской в Новосибирске выставлен на торги почти за 320 млн ₽',
        'ind': 'Недвижимость',
        'type': 'Продажа с торгов',
        'status': 'Обсуждается',
        'sum': '319,1 млн ₽ (стартовая цена)',
        'seller': 'Организатор торгов не назван явно источником (объявление на площадке '
                  '«ГИС Торги»; проект КРТ анонсировала мэрия Новосибирска в июле 2026 года)',
        'asset': 'Участок почти 1,8 га на берегу Оби в Новосибирске (улицы Обская, '
                 'Бердский переулок, Закавказская) под проект комплексного развития '
                 'территории (КРТ) — с обязательствами по расселению, строительству '
                 'жилого комплекса, детского сада и дороги',
        'src': [SRC],
        'events': [
            {'kind': 'negotiations', 'date': '2026-11-09', 'title': 'Торги назначены',
             'note': 'Аукцион по продаже проекта КРТ назначен на конец ноября 2026 года '
                     '(точная дата в источнике не указана), площадка — «ГИС Торги».',
             'source': list(SRC)},
        ],
    }
    card = promote.to_card(draft, new_id)
    card['eco']['sum'] = draft['sum']
    card['eco']['context'] = (
        'Проект КРТ территории впервые анонсирован в июле 2026 года, когда мэрия '
        'Новосибирска опубликовала проект постановления о комплексном развитии. '
        'Сейчас на участке 16 частных домов и 3 многоквартирных дома; в заголовке '
        'источника они названы «аварийными», но текст статьи прямо утверждает это '
        'не про все постройки. Дом на Обской, 78, не расселяют 8 лет — в августе '
        '2026 года этим заинтересовался глава СК РФ Александр Бастрыкин, после чего '
        'следственные органы региона возбудили уголовное дело о халатности по статье '
        '293 УК РФ. Победитель торгов обязан расселить и снести все постройки до '
        '1 августа 2030 года, построить на их месте жилой комплекс, достроить и '
        'оборудовать детский сад на 265 мест по улице Владимира Заровного, 9 (к концу '
        '2030 года), построить дорогу по Бердскому переулку от Обской до перспективной '
        '2-й Обской улицы, провести инфраструктуру и благоустройство; срок завершения '
        'строительства — 1 ноября 2033 года, благоустройства — 1 декабря 2033 года.'
    )
    card['themes'] = ['Продажа с торгов', 'Недвижимость']
    card['pending_since'] = datetime.now(timezone.utc).isoformat(timespec='seconds')

    pending['cards'].append(card)
    print('Добавлена карточка %s в pending.json: %s' % (new_id, card['title']))

    if write:
        promote.save_pending(pending)
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main('--write' in sys.argv)
