def _get(obj, field):
    for p in field.split('.'):
        obj = obj.get(p) if isinstance(obj, dict) else None
    return obj


def _set(obj, field, value):
    parts = field.split('.')
    for p in parts[:-1]:
        obj = obj.setdefault(p, {})
    obj[parts[-1]] = value


def apply(data):
    import fact_edit_guard
    deals = {d['id']: d for d in data['deals']}
    n = 0
    for cid, field, old, new, quote, url in CH:
        card = deals[cid]
        if _get(card, field) == new:
            continue
        assert _get(card, field) == old, (cid, field, _get(card, field))
        _set(card, field, new)
        if field in FACT:
            fact_edit_guard.log(card, field, new, quote or 'снято: ' + str(old)[:80], url or '', BY)
        n += 1
    for comp, field, old, new in COMP:
        c = data['companies'][comp]
        if c.get(field) == new:
            continue
        assert c.get(field) == old, (comp, field, c.get(field))
        c[field] = new
        n += 1
    for cid, rows in SRC.items():
        src = deals[cid].setdefault('src', [])
        have = {u for _t, u in src}
        for t, u in rows:
            if u not in have:
                src.append([t, u])
                n += 1
    for cid, paths in NOTES.items():
        notes = deals[cid].setdefault('accepted_notes', {})
        for path, value in paths.items():
            if _get(notes, path) == value:
                continue
            assert _get(notes, path) is None, (cid, path, _get(notes, path))
            _set(notes, path, value)
            n += 1
        if not notes:
            deals[cid].pop('accepted_notes', None)
    return n


