def get(obj, path):
    for k in path.split('.'):
        if not isinstance(obj, dict):
            return None
        obj = obj.get(k)
    return obj


def put(obj, path, value):
    keys = path.split('.')
    for k in keys[:-1]:
        obj = obj.setdefault(k, {})
    if value is None:
        obj.pop(keys[-1], None)
    else:
        obj[keys[-1]] = value


_ALL = []


def all_fixes():
    """Все записи FIXES, без фильтра REVIEW_ONLY: занятое чужой записью поле надо видеть всегда."""
    if not _ALL:
        import review
        saved = os.environ.pop('REVIEW_ONLY', None)
        try:
            _ALL.extend(review.load_fixes())
        finally:
            if saved is not None:
                os.environ['REVIEW_ONLY'] = saved
    return _ALL


def absorb_fixes(card, path):
    """Поле переписано, а в таблице правок есть запись на него — ее отпечаток в proofread_absorbed."""
    import review
    for f in all_fixes():
        if f['id'] == card['id'] and f['field'] == path and f.get('new') is not None:
            fp = review.fix_fingerprint(f['new'])
            lst = card.setdefault('proofread_absorbed', {}).setdefault(path, [])
            if fp not in lst:
                lst.append(fp)


def apply(data):
    import fact_edit_guard
    deals = {d['id']: d for d in data['deals']}
    done = todo = 0
    for cid, path, was, new, quote, url in DEAL_OPS:
        card = deals[cid]
        cur = get(card, path)
        if isinstance(was, tuple) and was[0] == 'REPL':
            _, a, b = was
            if b in cur and a not in cur:
                done += 1
                continue
            assert cur.count(a) == 1, '%s %s: нет фрагмента %r' % (cid, path, a)
            put(card, path, cur.replace(a, b))
            absorb_fixes(card, path)
            print('  ПРАВИМ %s %s: …%s… -> …%s…' % (cid, path, a[:40], b[:50]))
            todo += 1
            continue
        if isinstance(was, tuple) and was[0] == 'APPEND':
            _, tail, add = was
            if cur.endswith(add):
                done += 1
                continue
            assert cur.endswith(tail), '%s %s: поле кончается не так: %r' % (cid, path, cur[-60:])
            put(card, path, cur + add)
            absorb_fixes(card, path)
            print('  ДОПИСАНО %s %s: %s…' % (cid, path, add.strip()[:60]))
            todo += 1
            continue
        if path.startswith('retracted.'):
            lst = card.setdefault('retracted', {}).setdefault(path.split('.', 1)[1], [])
            add = [v for v in new if v not in lst]
            if not add:
                done += 1
                continue
            lst.extend(add)
            print('  СНЯТО %s %s: %r' % (cid, path, add))
            todo += 1
            continue
        if cur == new:
            done += 1
            continue
        assert cur == was, '%s %s: в базе %r, ожидали %r' % (cid, path, cur, was)
        put(card, path, new)
        absorb_fixes(card, path)
        if quote:
            fact_edit_guard.log(card, path, new, quote, url, BY, TODAY)
        print('  ПРАВИМ %s %s: %r -> %r' % (cid, path, str(was)[:50], str(new)[:60]))
        todo += 1
    for cid, i, f, old, new in EVENTS:
        ev = deals[cid]['events'][i]
        if ev.get(f) == new:
            done += 1
            continue
        assert ev.get(f) == old, (cid, i, f, ev.get(f))
        ev[f] = new
        print('  ЭТАП %s events[%d].%s -> %r' % (cid, i, f, str(new)[:60]))
        todo += 1
    an = deals['g9878a8ba'].setdefault('accepted_notes', {}).setdefault('no_profile', {})
    if an.get('buyer') != MANT_NOTE_NEW:
        assert str(an.get('buyer') or '').startswith(MANT_NOTE_OLD_START), an.get('buyer')
        an['buyer'] = MANT_NOTE_NEW
        print('  ПОМЕТКА g9878a8ba accepted_notes.no_profile.buyer')
        todo += 1
    else:
        done += 1
    return done, todo


