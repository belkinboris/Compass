# -*- coding: utf-8 -*-
"""Приток, 9 ноября 2026: 161.RU сообщила, что департамент имущественно-
земельных отношений Ростова-на-Дону (ДИЗО) выставил на аукцион недостроенный
мусоросжигательный завод у Соловьиной рощи. В лот входят земельный участок
3701 кв. м (31,6 млн ₽) и три недостроенных здания общей площадью 3500 кв. м
со строительной готовностью 42% — главный корпус (1339,5 кв. м),
административно-бытовой корпус (2086,8 кв. м) и переходная галерея
(73,7 кв. м), вместе 15,1 млн ₽; итого начальная цена лота 46,7 млн ₽ без
НДС. Строительство остановилось предположительно в конце 1980-х; о продаже
стало известно в августе 2026 года, когда вопрос вынесли на заседание
гордумы. Аукцион назначен на 30 ноября 2026 года.

Заголовок источника («Недостроенный завод у Соловьиной рощи в Ростове
продадут на аукционе») обзорный, без структуры «X продаёт Y» — ворота
(promote.py) отклонили находку: «не установлен предмет сделки». Тот же
случай, что с памятником архитектуры в Краснодаре (g134d5b0e,
pipeline/archive/2026-11/add_krasnodar_landmark_card_2026_11_09.py) и с
недостроем на бульваре Солнечном в Кургане (g955d2c6b) — муниципальный
аукцион недостроенного объекта, лот предметно описан (адрес/ориентир,
площади, цена), собирается карточка вручную.

Второй источник с теми же деталями (адрес, цена, дата аукциона) не найден
WebSearch на момент сборки — обычное дело для муниципального аукциона в
день объявления (та же картина у Кургана, see g955d2c6b/accepted_notes).

Продавец — не компания, а городской департамент имущества, организатор
торгов; профиль не заводится (как у g955d2c6b/g134d5b0e). Собрано вручную —
не в базу напрямую, а в pending.json, чтобы карточка прошла обычный путь:
accept_card.py -> second_reading.py -> ship_card.py.

Запуск: python3 pipeline/archive/2026-11/add_rostov_incineration_plant_card_2026_11_09.py [--write]
"""
import json
import os
import sys
from datetime import datetime, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
INGEST = os.path.join(os.path.dirname(os.path.dirname(HERE)), 'ingest')
if INGEST not in sys.path:
    sys.path.insert(0, INGEST)

SRC = ('161.RU', 'https://161.ru/text/gorod/2026/11/09/76753123/')


def main(write):
    import promote

    pending = promote.load_pending()
    existing_ids = {c['id'] for c in pending['cards']}
    base = json.load(open(promote.DATA, encoding='utf-8'))
    existing_ids |= {c['id'] for c in base['deals']}
    new_id = promote.new_id(existing_ids)

    draft = {
        'date': '2026-11-09',
        'title': 'ДИЗО Ростова-на-Дону выставил на торги недостроенный '
                 'мусоросжигательный завод у Соловьиной рощи',
        'ind': 'Недвижимость',
        'type': 'Продажа с торгов',
        'status': 'Обсуждается',
        'sum': '46,7 млн ₽ (стартовая цена, без НДС)',
        'seller': 'Департамент имущественно-земельных отношений Ростова-на-Дону (ДИЗО)',
        'asset': 'Земельный участок 3701 кв. м и три недостроенных здания общей '
                 'площадью 3500 кв. м (готовность 42%) бывшего мусоросжигательного '
                 'завода у Соловьиной рощи в Ростове-на-Дону',
        'src': [SRC],
        'events': [
            {'kind': 'negotiations', 'date': '2026-11-09', 'title': 'Аукцион назначен',
             'note': 'Аукцион по продаже лота назначен на 30 ноября 2026 года.',
             'source': list(SRC)},
        ],
    }
    card = promote.to_card(draft, new_id)
    card['eco']['sum'] = draft['sum']
    card['eco']['val'] = (
        'Начальная цена лота — 46,7 млн ₽ без НДС: 31,6 млн ₽ за земельный участок '
        '3701 кв. м и 15,1 млн ₽ за три здания — главный корпус (1339,5 кв. м), '
        'административно-бытовой корпус (2086,8 кв. м) и переходную галерею '
        '(73,7 кв. м).'
    )
    card['eco']['context'] = (
        'Строительство мусоросжигательного завода остановилось предположительно '
        'в конце 1980-х годов; степень готовности зданий — 42%. О продаже лота '
        'стало известно в августе 2026 года, когда вопрос вынесли на заседание '
        'ростовской гордумы — по мнению властей, здания находятся в плохом '
        'состоянии. Сейчас в заброшенных корпусах, по данным «Яндекс. Карт», '
        'играют в страйкбол.'
    )
    card['themes'] = ['Продажа с торгов', 'Недвижимость']
    card['pending_since'] = datetime.now(timezone.utc).isoformat(timespec='seconds')

    pending['cards'].append(card)
    print('Добавлена карточка %s в pending.json: %s' % (new_id, card['title']))

    if write:
        promote.save_pending(pending)
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main('--write' in sys.argv)
