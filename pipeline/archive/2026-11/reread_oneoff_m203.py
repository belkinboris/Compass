def get(obj, path):
    for k in path.split('.'):
        obj = (obj or {}).get(k)
    return obj


def put(obj, path, value):
    keys = path.split('.')
    for k in keys[:-1]:
        obj = obj.setdefault(k, {})
    obj[keys[-1]] = value


def apply(data):
    """Возвращает число примененных правок; уже стоящее значение пропускается."""
    by = {d['id']: d for d in data['deals']}
    n = 0
    for cid, new in NEW_COMPANIES.items():
        if cid not in data['companies']:
            data['companies'][cid] = dict(new)
            n += 1
    for cid, field, old, new, quote, url in DEAL_EDITS:
        c = by[cid]
        cur = get(c, field)
        if cur == new:
            continue
        assert cur == old, (cid, field, cur)
        put(c, field, new)
        fact_edit_guard.log(c, field, new, quote, url, BY, DAY)
        n += 1
    # gdf44a92b: в заметке о продавцах — двое, не трое
    c = by['gdf44a92b']
    note = 'физлица, профилей нет; найдены по истории участников ЕГРЮЛ: 28.07.2025 вышли Павел Соколов (56%) и Глеб Драгунов (34%)'
    if c['accepted_notes']['no_profile'].get('seller') != note:
        c['accepted_notes']['no_profile']['seller'] = note
        n += 1
    c = by['g5dc6cb47']
    note = 'физлицо, профиля нет; Татьяна Даниленко владела 100% ООО «Назия» (единственный участник КМЗ) до 17.07.2025 (Neftegaz.RU по Rusprofile; «Фонтанка» 14.01.2026)'
    if (c.get('accepted_notes') or {}).get('no_profile', {}).get('seller') != note:
        c.setdefault('accepted_notes', {}).setdefault('no_profile', {})['seller'] = note
        n += 1
    for cid, field, old, new in COMPANY_EDITS:
        p = data['companies'][cid]
        if p.get(field) == new:
            continue
        assert p.get(field) == old, (cid, field, p.get(field))
        p[field] = new
        n += 1
    return n


def registry(write):
    rows = json.load(open(REG, encoding='utf-8'))
    have = {r['company_id']: r for r in rows}
    todo = []
    for row in REGISTRY:
        cur = have.get(row['company_id'])
        if cur and cur.get('inn') == row['inn']:
            continue
        clash = [r['company_id'] for r in rows if r.get('inn') == row['inn'] and r['company_id'] != row['company_id']]
        assert not clash, (row['inn'], clash)
        todo.append(row)
    if write:
        for row in todo:
            if row['company_id'] in have:
                assert fns_notes_to_registry.edit_registry_entry(row['company_id'], row)
            else:
                rows = json.load(open(REG, encoding='utf-8'))
                rows.append(row)
                with open(REG, 'w', encoding='utf-8') as fh:
                    json.dump(rows, fh, ensure_ascii=False, indent=1)
    return len(todo)


def main(write):
    raw = open(DATA, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    n = apply(data)
    bad = fact_edit_guard.unbacked(old, data)
    assert not bad, bad
    r = registry(False)
    if not write:
        print('Сухой прогон: правок базы %d, записей реестра ИНН %d. Запись — с ключом --write.' % (n, r))
        return 0
    if n:
        fresh_raw = open(DATA, encoding='utf-8').read()
        fresh = json.loads(fresh_raw)
        apply(fresh)
        with open(DATA, 'w', encoding='utf-8') as f:
            f.write(json.dumps(fresh, ensure_ascii=False, indent=1) + ('\n' if fresh_raw.endswith('\n') else ''))
    registry(True)
    print('ЗАПИСАНО: правок базы %d, записей реестра ИНН %d.' % (n, r) if (n or r) else 'уже применено')
    return 0


if __name__ == '__main__':
    sys.exit(main('--write' in sys.argv[1:]))
