def _get(card, field):
    return fact_edit_guard.get(card, field)


def _set(card, field, value):
    if '.' in field:
        head, tail = field.split('.', 1)
        card.setdefault(head, {})[tail] = value
    else:
        card[field] = value


# Партия сдается частями; карточки второй части пишутся только вместе с ее планом.
ACTIVE = {'g1df89416', 'gfde94a49', 'gcc054516', 'g91d021c6'}


def apply(data):
    deals = {d['id']: d for d in data['deals']}
    comps, mk = data['companies'], data.setdefault('match_keys', {})
    done = []
    for pid, prof in NEW_PROFILES.items():
        if pid not in comps and prof.get('for') in ACTIVE:
            comps[pid] = {k: v for k, v in prof.items() if k != 'for'}
            mk[pid] = list(NEW_MATCH[pid])
            done.append('новый профиль %s %s' % (pid, prof['name']))
    for cid, field, old, new, quote, url in CARD:
        if cid not in ACTIVE:
            continue
        card = deals[cid]
        cur = _get(card, field)
        if new is None:
            continue
        if cur == new:
            continue
        assert cur == old, (cid, field, cur)
        _set(card, field, new)
        if field in fact_edit_guard.FACT_FIELDS:
            fact_edit_guard.log(card, field, new, quote, url, BY, DAY)
        done.append('%s %s: %s → %s' % (cid, field, old, new))
    for cid, field, old in RETRACT + [r for r in RETRACT_MORE if r[0] in ACTIVE]:
        r = deals[cid].setdefault('retracted', {}).setdefault(field, [])
        if old not in r:
            r.append(old)
            done.append('%s retracted.%s += %s' % (cid, field, old))
    for pid, field, old, new in PROFILE + [p[:4] for p in PROFILE_MORE if p[4] in ACTIVE]:
        cur = comps[pid].get(field)
        if cur == new:
            continue
        assert cur == old, (pid, field, cur)
        comps[pid][field] = new
        done.append('профиль %s %s → %s' % (pid, field, new[:60]))
    for pid, old, new in MATCH:
        if mk.get(pid) == new:
            continue
        assert mk.get(pid) == old, (pid, mk.get(pid))
        mk[pid] = new
        done.append('match_keys %s → %s' % (pid, new))
    return done


def main(write):
    raw = open(DATA, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    done = apply(data)
    print('\n'.join(done) or 'уже применено')
    if not done:
        return 0
    mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
    bad = fact_edit_guard.unbacked(old, data)
    assert not bad, bad
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return 0
    fresh_raw = open(DATA, encoding='utf-8').read()
