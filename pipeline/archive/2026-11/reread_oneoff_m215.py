def _walk(card, path):
    parts = path.split('.')
    obj = card
    for p in parts[:-1]:
        obj = obj[int(p)] if isinstance(obj, list) else obj.setdefault(p, {})
    return obj, (int(parts[-1]) if isinstance(obj, list) else parts[-1])


def _get(card, path):
    obj, k = _walk(card, path)
    if isinstance(obj, list):
        return obj[k]
    return obj.get(k, ABSENT)


def apply(data):
    by = {d['id']: d for d in data['deals']}
    n = 0
    for cid, path, old, new, quote, url in OPS:
        c = by[cid]
        cur = _get(c, path)
        if (new is None and cur is ABSENT) or cur == new:
            continue
        assert cur == old, (cid, path, cur)
        obj, k = _walk(c, path)
        if new is None:
            del obj[k]
        else:
            obj[k] = new
        if path in RETRACT and old not in (ABSENT, None, '—'):
            c.setdefault('retracted', {}).setdefault(path, []).append(old)
        if path in fact_edit_guard.FACT_FIELDS:
            fact_edit_guard.log(c, path, new, quote, url, BY, DAY)
        n += 1
    comps = data['companies']
    for comp, field, old, new in COMPANY_OPS:
        if comps[comp].get(field) == new:
            continue
        assert comps[comp].get(field) == old, (comp, comps[comp].get(field))
        comps[comp][field] = new
        n += 1
    return n


def main(write):
    raw = open(DATA, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    n = apply(data)
    if not n:
        print('Уже применено.')
        return 0
    mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
    bad = fact_edit_guard.unbacked(old, data)
    assert not bad, bad
    if not write:
        print('Сухой прогон: %d правок. Запись — с ключом --write.' % n)
        return 0
    fresh_raw = open(DATA, encoding='utf-8').read()
    fresh = json.loads(fresh_raw)
    apply(fresh)
    with open(DATA, 'w', encoding='utf-8') as f:
        f.write(json.dumps(fresh, ensure_ascii=False, indent=1) + ('\n' if fresh_raw.endswith('\n') else ''))
    print('ЗАПИСАНО: %d правок.' % n)
    return 0


if __name__ == '__main__':
    sys.exit(main('--write' in sys.argv))
