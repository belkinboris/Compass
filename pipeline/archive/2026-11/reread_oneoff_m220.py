def card_of(data, cid):
    return next(x for x in data['deals'] if x['id'] == cid)


def get(card, field):
    if field.startswith('events.'):
        _e, i, k = field.split('.')
        return card['events'][int(i)][k]
    if '.' in field:
        a, b = field.split('.', 1)
        return (card.get(a) or {}).get(b)
    return card.get(field)


def put(card, field, value):
    if field.startswith('events.'):
        _e, i, k = field.split('.')
        card['events'][int(i)][k] = value
    elif '.' in field:
        a, b = field.split('.', 1)
        card.setdefault(a, {})[b] = value
    else:
        card[field] = value


def edit(card, field, old, new, quote=None, url=None):
    cur = get(card, field)
    if cur == new:
        return False
    assert cur == old, (card['id'], field, cur)
    put(card, field, new)
    if quote and field in fact_edit_guard.FACT_FIELDS:
        fact_edit_guard.log(card, field, new, quote, url, BY, DAY)
    return True


