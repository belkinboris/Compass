def _get(c, path):
    o = c
    parts = path.split('.')
    for p in parts[:-1]:
        o = o[int(p)] if p.isdigit() else o[p]
    return o, (int(parts[-1]) if parts[-1].isdigit() else parts[-1])


def apply(data):
    by = {d['id']: d for d in data['deals']}
    comps = data['companies'] if isinstance(data['companies'], dict) else {c['id']: c for c in data['companies']}
    n = 0
    for cid, path, old, new, quote, url in SETS:
        c = by[cid]
        part = path.endswith('@')
        o, k = _get(c, path.rstrip('@'))
        cur = o.get(k) if isinstance(o, dict) else o[k]
        if part:
            if (new and new in cur) or (not new and old not in cur):
                continue
            assert cur.count(old) == 1, (cid, path, cur)
            o[k] = cur.replace(old, new)
            fact_edit_guard.log(c, path.rstrip('@'), o[k], quote, url, BY, DAY)
        else:
            if cur == new:
                continue
            assert cur == old, (cid, path, cur)
            o[k] = new
            if (cid, path) in RETRACT:
                c.setdefault('retracted', {}).setdefault(path, []).append(old)
            fact_edit_guard.log(c, path, new, quote, url, BY, DAY)
        n += 1
    c = by['g09b38753']
    an = c.setdefault('accepted_notes', {})
    if an.get('no_profile', {}).get('seller') != SELLER_NOTE:
        an.setdefault('no_profile', {})['seller'] = SELLER_NOTE
        an.get('no_inn', {}).pop('buyer', None)
        if 'no_inn' in an and not an['no_inn']:
            del an['no_inn']
        n += 1
    p = comps[BUYER[0]]
    if p.get('inn') != BUYER[1]:
        assert not p.get('inn'), p.get('inn')
        p['inn'], p['ogrn'] = BUYER[1], BUYER[2]
        n += 1
    c = by[SRC_FIRST[0]]
    if c['src'][0][1] != SRC_FIRST[1]:
        first = [s for s in c['src'] if s[1] == SRC_FIRST[1]]
        assert len(first) == 1
        c['src'] = first + [s for s in c['src'] if s[1] != SRC_FIRST[1]]
        n += 1
    return n


def main(write):
    raw = open(DATA, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    n = apply(data)
    if not n:
        print('Уже применено.')
        return 0
    mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
    bad = fact_edit_guard.unbacked(old, data)
    assert not bad, bad
    if not write:
        print('Сухой прогон: %d правок. Запись — с ключом --write.' % n)
        return 0
    fresh_raw = open(DATA, encoding='utf-8').read()
    fresh = json.loads(fresh_raw)
    apply(fresh)
    with open(DATA, 'w', encoding='utf-8') as f:
        f.write(json.dumps(fresh, ensure_ascii=False, indent=1) + ('\n' if fresh_raw.endswith('\n') else ''))
    print('ЗАПИСАНО: %d правок.' % n)
    return 0


if __name__ == '__main__':
    sys.exit(main('--write' in sys.argv))
