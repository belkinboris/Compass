FILE_EDITS = [('test_data.py', 'MA_PARTIES_BACKLOG', 'cd51336b7')]

# Снятые неверные значения — в retracted, чтобы обогащение их не вернуло.
RETRACT = ('sum', 'status', 'buyer_name', 'asset', 'seller')


def get(obj, path):
    for k in path.split('.'):
        if not isinstance(obj, dict) or k not in obj:
            return MISSING
        obj = obj[k]
    return obj


def put(obj, path, value):
    keys = path.split('.')
    for k in keys[:-1]:
        obj = obj.setdefault(k, {})
    if value == MISSING:
        obj.pop(keys[-1], None)
    else:
        obj[keys[-1]] = value


def apply(data, verbose=False):
    import fact_edit_guard
    deals = {d['id']: d for d in data['deals']}
    done = todo = 0
    for cid, path, was, new, quote, url in DEAL_OPS:
        card = deals[cid]
        cur = get(card, path)
        if cur == new:
            done += 1
            continue
        assert cur == was, '%s %s: в базе %r, ожидали %r' % (cid, path, cur, was)
        put(card, path, new)
        if path in RETRACT and was not in (MISSING, None, '', 'Не раскрыта', '—'):
            lst = card.setdefault('retracted', {}).setdefault(path, [])
            if was not in lst:
                lst.append(was)
        if quote:
            fact_edit_guard.log(card, path, None if new == MISSING else new, quote, url, BY, TODAY)
        if verbose:
            print('  ПРАВИМ %s %s: %r -> %r' % (cid, path, str(was)[:50], str(new)[:60]))
        todo += 1
    for pid, path, was, new in COMPANY_OPS:
        prof = data['companies'][pid]
        cur = get(prof, path)
        if cur == new:
            done += 1
            continue
        assert cur == was, '%s %s: в базе %r, ожидали %r' % (pid, path, cur, was)
        put(prof, path, new)
        if verbose:
            print('  ПРОФИЛЬ %s %s: %r -> %r' % (pid, path, str(was)[:50], str(new)[:60]))
        todo += 1
    return done, todo


def main(argv):
    write = '--write' in argv
    import mass_edit_guard
    data = json.load(open(DATA, encoding='utf-8'))      # перечитываем прямо перед записью
    old = copy.deepcopy(data)
    done, todo = apply(data, verbose=True)
    print('уже применено: %d, к записи: %d' % (done, todo))
    if not todo:
        print('Уже применено.')
        return 0
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return 0
    mass_edit_guard.check(old, data, key=os.environ.get('MASS_OK'))
    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    bl = os.path.join(ROOT, 'pipeline', 'text_rules_baseline.json')
    if BASELINE_DROP and os.path.exists(bl):
        base = json.load(open(bl, encoding='utf-8'))
        keep = [k for k in base['known'] if k not in BASELINE_DROP]
        if len(keep) != len(base['known']):
            base['known'] = keep
            raw = open(bl, encoding='utf-8').read()
            with open(bl, 'w', encoding='utf-8') as f:
                f.write(json.dumps(base, ensure_ascii=False, indent=1) + ('\n' if raw.endswith('\n') else ''))
            print('из text_rules_baseline.json убрано: %d' % len(BASELINE_DROP))
    import re
    for rel, name, item in FILE_EDITS:
        path = os.path.join(ROOT, rel)
        text = open(path, encoding='utf-8').read()
        m = re.search(r'^%s = \{([^}]*)\}$' % name, text, re.M)
        assert m, (rel, name)
        items = [x.strip() for x in m.group(1).split(',') if x.strip()]
        if '"%s"' % item not in items:
            continue
        items.remove('"%s"' % item)
        line = '%s = {%s}' % (name, ', '.join(items)) if items else '%s = set()' % name
        open(path, 'w', encoding='utf-8').write(text[:m.start()] + line + text[m.end():])
        print('правка %s: %s без %s' % (rel, name, item))
    print('записано')
    return 0


