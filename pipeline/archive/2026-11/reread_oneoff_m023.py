def _get(c, f):
    if '.' in f:
        a, b = f.split('.', 1)
        return (c.get(a) or {}).get(b)
    return c.get(f)


def _set(c, f, v):
    if '.' in f:
        a, b = f.split('.', 1)
        c.setdefault(a, {})[b] = v
    elif v is None:
        c.pop(f, None)
    else:
        c[f] = v


def apply(data):
    by = {d['id']: d for d in data['deals']}
    n = 0
    for cid, f, old, new, quote, url in EDITS:
        c = by[cid]
        cur = _get(c, f)
        if cur == new or (new is None and cur in (None, '')):
            continue
        assert isinstance(cur, str) and cur.startswith(old), (cid, f, cur)
        _set(c, f, new)
        n += 1
        if f in fact_edit_guard.FACT_FIELDS:
            fact_edit_guard.log(c, f, new, quote, url, BY, DAY)
        if (cid, f) in RETRACT:
            r = c.setdefault('retracted', {}).setdefault(f, [])
            if RETRACT[(cid, f)] not in r:
                r.append(RETRACT[(cid, f)])
    for cid, basis in DATE_BASIS.items():
        if by[cid].get('date_basis') != basis:
            assert by[cid].get('date_basis') in (None, ''), (cid, by[cid].get('date_basis'))
            by[cid]['date_basis'] = basis
            n += 1
    comps = data['companies']
    for pid, f, old, new in COMPANY_EDITS:
        p = comps[pid]
        if p.get(f) == new:
            continue
        assert p.get(f) == old, (pid, f, p.get(f))
        if new is None:
            p.pop(f, None)
        else:
            p[f] = new
        n += 1
    return n


def main(write):
    raw = open(DATA, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    n = apply(data)
    mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
    bad = fact_edit_guard.unbacked(old, data)
    assert not bad, bad
    if not n:
        print('Уже применено: правок нет.')
        return 0
    if not write:
        print('Сухой прогон: %d правок. Запись — с ключом --write.' % n)
        return 0
    fresh_raw = open(DATA, encoding='utf-8').read()
    fresh = json.loads(fresh_raw)
    apply(fresh)
    with open(DATA, 'w', encoding='utf-8') as f:
        f.write(json.dumps(fresh, ensure_ascii=False, indent=1) + ('\n' if fresh_raw.endswith('\n') else ''))
    print('ЗАПИСАНО: %d правок.' % n)
    return 0


if __name__ == '__main__':
    sys.exit(main('--write' in sys.argv[1:]))
