def get(c, path):
    cur = c
    for p in path.split('.'):
        if not isinstance(cur, dict):
            return None
        cur = cur.get(p)
    return cur


def put(c, path, val):
    parts = path.split('.')
    cur = c
    for p in parts[:-1]:
        cur = cur.setdefault(p, {})
    if val is None:
        cur.pop(parts[-1], None)
    else:
        cur[parts[-1]] = val


def same_old(cur, old):
    if isinstance(old, tuple) and old[0] == '^':
        return isinstance(cur, str) and cur.startswith(old[1])
    if isinstance(old, tuple) and old[0] == 'in':
        return isinstance(cur, str) and old[1] in cur
    return cur == old


def apply(data):
    by = {d['id']: d for d in data['deals']}
    n = 0
    for cid, field, old, new, quote, url in SETS:
        c = by[cid]
        cur = get(c, field)
        if cur == new:
            continue
        assert same_old(cur, old), (cid, field, cur)
        if field in RETRACT and cur and not isinstance(old, tuple):
            r = c.setdefault('retracted', {}).setdefault(field, [])
            if cur not in r:
                r.append(cur)
        put(c, field, new)
        if field == 'sum':
            c['eco']['sum'] = new
            c.pop('sum_basis', None)
            fact_edit_guard.log(c, 'eco.sum', new, quote, url, BY, DAY)
        if field == 'date':
            if cid in DATE_BASIS:
                c['date_basis'] = DATE_BASIS[cid]
            else:
                c.pop('date_basis', None)
        fact_edit_guard.log(c, field, new, quote, url, BY, DAY)
        n += 1
    for cid, path, old, new in TEXT:
        c = by[cid]
        cur = get(c, path)
        if isinstance(new, tuple):
            if isinstance(cur, str) and new[1] in cur and new[0] not in cur:
                continue
            assert same_old(cur, old), (cid, path, cur)
            put(c, path, cur.replace(new[0], new[1]))
            n += 1
            continue
        if cur == new:
            continue
        assert same_old(cur, old), (cid, path, cur)
        put(c, path, new)
        n += 1
    for cid, (mode, old_url, row) in SRC.items():
        src = by[cid]['src']
        if any(s[1] == row[1] for s in src):
            continue
        if mode == 'replace':
            idx = [i for i, s in enumerate(src) if s[1] == old_url]
            assert idx, (cid, 'src')
            src[idx[0]] = row
        else:
            src.append(row)
        n += 1
    return n


