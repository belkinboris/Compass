def _get(card, path):
    cur = card
    for p in path.split('.'):
        if isinstance(cur, list):
            cur = cur[int(p)] if int(p) < len(cur) else None
        else:
            cur = (cur or {}).get(p)
    return cur


def _set(card, path, value):
    parts = path.split('.')
    cur = card
    for p in parts[:-1]:
        cur = cur[int(p)] if isinstance(cur, list) else cur.setdefault(p, {})
    if isinstance(cur, list):
        cur[int(parts[-1])] = value
    else:
        cur[parts[-1]] = value


def _absorb(card, field, fixes):
    """Записи таблицы FIXES на это поле применены раньше: отпечатки — в proofread_absorbed,
    иначе review.py увидит расхождение и вернет старое значение (docs/card_editing.md)."""
    import review
    marks = card.setdefault('proofread_absorbed', {}).setdefault(field, [])
    for r in fixes:
        if r.get('id') == card['id'] and r.get('field') == field and r.get('new') is not None:
            fp = review.fix_fingerprint(r['new'])
            if fp not in marks:
                marks.append(fp)


def apply(data, fixes):
    by = {d['id']: d for d in data['deals']}
    n = 0
    for cid, field, old, new, quote, url in EDITS:
        c = by[cid]
        if field == 'src+':
            if any(new[1] in s for s in c.get('src') or []):
                continue
            c.setdefault('src', []).append(new)
            n += 1
            continue
        if field == 'src:first':
            src = c.get('src') or []
            i = next(i for i, s in enumerate(src) if new in s)
            if i == 0:
                continue
            src.insert(0, src.pop(i))
            n += 1
            continue
        if ':' in field:
            base, op = field.split(':')
            cur = _get(c, base) or ''
            if op == 'append':
                if cur.endswith(new):
                    continue
                _set(c, base, cur + new)
            else:
                if new in cur:
                    continue
                assert cur.count(old) == 1, (cid, field, cur[:200])
                _set(c, base, cur.replace(old, new))
            _absorb(c, base, fixes)
            n += 1
            continue
        cur = _get(c, field)
        if cur == new:
            continue
        assert cur == old, (cid, field, cur)
        _set(c, field, new)
        if (cid, field) in RETRACT and old:
            lst = c.setdefault('retracted', {}).setdefault(field, [])
            if old not in lst:
                lst.append(old)
        if quote:
            fact_edit_guard.log(c, field, new, quote, url, BY, DAY)
        _absorb(c, field, fixes)
        n += 1
    return n


def main(write):
    import review
    fixes = review.load_fixes()
    raw = open(DATA, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    n = apply(data, fixes)
    if not n:
        print('Уже применено.')
        return 0
    mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
    bad = fact_edit_guard.unbacked(old, data)
    assert not bad, bad
    if not write:
        print('Сухой прогон: %d правок. Запись — с ключом --write.' % n)
        return 0
    fresh_raw = open(DATA, encoding='utf-8').read()      # перечитать прямо перед записью
    fresh = json.loads(fresh_raw)
    apply(fresh, fixes)
    with open(DATA, 'w', encoding='utf-8') as f:
        f.write(json.dumps(fresh, ensure_ascii=False, indent=1) + ('\n' if fresh_raw.endswith('\n') else ''))
    print('ЗАПИСАНО: %d правок.' % n)
    return 0


