def get(c, path):
    cur = c
    for p in path.split('.'):
        if not isinstance(cur, dict):
            return None
        cur = cur.get(p)
    return cur


def put(c, path, val):
    parts = path.split('.')
    cur = c
    for p in parts[:-1]:
        cur = cur.setdefault(p, {})
    if val is None:
        cur.pop(parts[-1], None)
    else:
        cur[parts[-1]] = val


def same_old(cur, old):
    if isinstance(old, tuple):
        return isinstance(cur, str) and cur.startswith(old[1])
    return cur == old


RETRACT = ('status', 'seller', 'asset', 'sum', 'buyer_name')


def apply(data):
    by = {d['id']: d for d in data['deals']}
    n = 0
    for cid, field, old, new, quote, url in SETS:
        c = by[cid]
        cur = get(c, field)
        if cur == new:
            continue
        assert same_old(cur, old), (cid, field, cur)
        if field in RETRACT and cur and not isinstance(old, tuple) and field != 'asset':
            c.setdefault('retracted', {}).setdefault(field, []).append(cur)
        put(c, field, new)
        if field == 'sum':
            c['eco']['sum'] = new
            fact_edit_guard.log(c, 'eco.sum', new, quote, url, BY, DAY)
        if field == 'date':
            if cid in DATE_BASIS:
                c['date_basis'] = DATE_BASIS[cid]
            else:
                c.pop('date_basis', None)
        fact_edit_guard.log(c, field, new, quote, url, BY, DAY)
        n += 1
    for cid, src in SRC_KEEP.items():
        if by[cid]['src'] != src:
            by[cid]['src'] = src
            n += 1
    for cid, kv in FIXUP.items():
        for path, val in kv.items():
            if get(by[cid], path) != val:
                put(by[cid], path, val)
                n += 1
    return n


def main(write):
    raw = open(DATA, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    n = apply(data)
    if not n:
        print('Уже применено.')
        return 0
    mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
    bad = fact_edit_guard.unbacked(old, data)
    assert not bad, bad
    if not write:
        print('Сухой прогон: %d правок. Запись — с ключом --write.' % n)
        return 0
    fresh_raw = open(DATA, encoding='utf-8').read()
    fresh = json.loads(fresh_raw)
    apply(fresh)
    with open(DATA, 'w', encoding='utf-8') as f:
        f.write(json.dumps(fresh, ensure_ascii=False, indent=1) + ('\n' if fresh_raw.endswith('\n') else ''))
    print('ЗАПИСАНО: %d правок.' % n)
    return 0


