def get(card, f):
    v = card
    for p in f.split('.'):
        v = (v or {}).get(p)
    return v


def setf(card, f, val):
    parts = f.split('.')
    for p in parts[:-1]:
        card = card.setdefault(p, {})
    card[parts[-1]] = val


def apply(data):
    cards = {c['id']: c for c in data['deals']}
    done = []
    for cid, f, old, new, quote, url in SETS:
        c = cards[cid]
        if get(c, f) == new:
            continue
        assert get(c, f) == old, (cid, f, get(c, f))
        setf(c, f, new)
        if quote:
            fact_edit_guard.log(c, f, new, quote, url, BY)
        done.append('%s %s: %r -> %r' % (cid, f, old, new))
    for cid, f, old, new in PROSE:
        c = cards[cid]
        cur = get(c, f) or ''
        if new in cur:
            continue
        assert cur.count(old) == 1, (cid, f, old)
        setf(c, f, cur.replace(old, new))
        done.append('%s %s: + %r' % (cid, f, new[:60]))
    for pid, f, old, new in PROFILES:
        p = data['companies'][pid]
        if p.get(f):
            continue
        assert p.get(f) == old, (pid, f, p.get(f))
        p[f] = new
        done.append('профиль %s %s -> %r' % (pid, f, new))
    return done


