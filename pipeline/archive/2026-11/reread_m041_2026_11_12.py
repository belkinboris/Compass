def _get(o, field):
    for p in field.split('.'):
        o = o.get(p) if isinstance(o, dict) else None
    return o


def _set(card, field, value):
    parts = field.split('.')
    o = card
    for p in parts[:-1]:
        o = o.setdefault(p, {})
    o[parts[-1]] = value


def apply(data):
    import review
    import fact_edit_guard
    from source_names import edition_label
    deals = {d['id']: d for d in data['deals']}
    done = 0
    for cid, field, old, new, quote, url in DEAL:
        card = deals[cid]
        cur = _get(card, field)
        if cur == new:
            continue
        assert cur == old, (cid, field, cur)
        _set(card, field, new)
        done += 1
        if field in fact_edit_guard.FACT_FIELDS:
            fact_edit_guard.log(card, field, new, quote, url, BY)
        for fx in review.FIXES:
            if fx.get('id') == cid and fx.get('field') == field and fx.get('new') != new:
                fp = review.fix_fingerprint(fx['new'])
                lst = card.setdefault('proofread_absorbed', {}).setdefault(field, [])
                if fp not in lst:
                    lst.append(fp)
    for cid, field, old, new in SET_RAW:
        card = deals[cid]
        if card.get(field) == new:
            continue
        assert card.get(field) == old, (cid, field, card.get(field))
        card[field] = new
        done += 1
    for coid, field, old, new in COMPANY:
        c = data['companies'][coid]
        if c.get(field) == new:
            continue
        assert c.get(field) == old, (coid, field, c.get(field))
        c[field] = new
        done += 1
    for cid, field, value in RETRACT:
        lst = deals[cid].setdefault('retracted', {}).setdefault(field, [])
        if value not in lst:
            lst.append(value)
            done += 1
    for cid, url in SRC_ADD:
        card = deals[cid]
        if not any(s[1] == url for s in card.get('src') or []):
            card.setdefault('src', []).append([edition_label(url), url])
            done += 1
    for cid, notes in NOTES.items():
        acc = deals[cid].setdefault('accepted_notes', {})
        for k, v in notes.items():
            if isinstance(v, dict):
                for kk, vv in v.items():
                    if acc.setdefault(k, {}).get(kk) != vv:
                        acc[k][kk] = vv
                        done += 1
            elif acc.get(k) != v:
                acc[k] = v
                done += 1
    return done


def registry(write):
    import fns_registry
    import fns_notes_to_registry
    n = 0
    for coid, row in REGISTRY.items():
        cur = fns_registry.by_company_id().get(coid) or {}
        if cur.get('inn') == row['inn'] and cur.get('decision') == row['decision']:
            continue
        assert fns_registry.inn_is_valid(row['inn'])
        n += 1
        if write:
            assert fns_notes_to_registry.edit_registry_entry(coid, row), coid
    return n


