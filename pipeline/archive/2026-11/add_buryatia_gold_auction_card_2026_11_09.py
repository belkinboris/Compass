# -*- coding: utf-8 -*-
"""Приток, 9 ноября 2026: ТАСС сообщил, что участок россыпного золота на
ручье Гулхэн (приток реки Талали) в Бурятии продан на аукционе компании
«Куту» за 574 млн ₽ — почти в 20 раз дороже стартовой цены 29 млн ₽ (574 /
29 ≈ 19,8, арифметика сходится с заголовком источника). В торгах участвовали
девять компаний, победитель определился на 108-м шаге. Лицензия на разведку
и добычу — на 20 лет; запасы участка — 302 кг золота, геологоразведка велась
с 1940-х по 1980-е годы. По закону «О недрах» победитель должен внести
итоговый платеж в течение месяца, иначе лицензия перейдет участнику,
предложившему предыдущую цену в ходе торгов.

Заголовок источника («В Бурятии участок россыпного золота продали почти в
20 раз дороже стартовой цены») обзорный, без структуры «X купил Y» — ворота
(promote.py) отклонили находку: «не названа ни одна сторона». Тот же случай,
что с «Голдрупп» на участке река Чапа — ручей Цой в Красноярском крае
(g51fa80ce) — аукцион Роснедра на право недропользования, карточка собрана
вручную, не в базу напрямую, а в pending.json, чтобы пройти обычный путь:
accept_card.py -> second_reading.py -> ship_card.py.

Источник и его проверка: прямой WebFetch на tass.ru отклонен защитой от
ботов (JS-challenge servicepipe.tech, пустая страница без текста) — ту же
страницу прочитали через ридер-прокси r.jina.ai (двумя отдельными запросами,
с одинаковыми цифрами в обоих). WebSearch не нашел независимого второго
источника с теми же деталями на момент сборки (обычное дело для новости об
итогах аукциона в день объявления — та же картина у «Голдрупп», где сюжет
тоже был односточникован). Самостоятельная проверка факта продажи — через
арифметику заголовка (574 млн / 29 млн ≈ 19,8 ≈ «почти в 20 раз») и через
совпадение цифр между двумя независимыми чтениями через ридер-прокси.

Продавец — не компания. Как и у «Голдрупп» (g51fa80ce), организатор
аукционов на право недропользования по закону — Роснедра; в статье ТАСС
итоги сообщает пресс-служба Минприроды России (регулятор, курирующий
Роснедра), само ведомство-организатор по имени не названо — seller оставлен
как «Роснедра» по тому же прецеденту. Покупатель («Куту») назван только
по имени, без ИНН и реквизитов — профиль компании не заводим на этом шаге
(решение accept_card.py: искать компанию в реестрах — либо оставить как у
«Голдрупп», без публичного следа).

Запуск: python3 pipeline/archive/2026-11/add_buryatia_gold_auction_card_2026_11_09.py [--write]
"""
import json
import os
import sys
from datetime import datetime, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
INGEST = os.path.join(os.path.dirname(os.path.dirname(HERE)), 'ingest')
if INGEST not in sys.path:
    sys.path.insert(0, INGEST)

SRC = ('ТАСС', 'https://tass.ru/ekonomika/28297803')


def main(write):
    import promote

    pending = promote.load_pending()
    existing_ids = {c['id'] for c in pending['cards']}
    base = json.load(open(promote.DATA, encoding='utf-8'))
    existing_ids |= {c['id'] for c in base['deals']}
    new_id = promote.new_id(existing_ids)

    draft = {
        'date': '2026-11-09',
        'title': '«Куту» выиграла аукцион на участок россыпного золота в Бурятии '
                 'почти в 20 раз дороже стартовой цены',
        'ind': 'ГМК и добыча',
        'type': 'Продажа с торгов',
        'status': 'Закрыта',
        'sum': '574 млн ₽',
        'seller': 'Роснедра',
        'buyer_name': '«Куту»',
        'asset': 'право геологического изучения и добычи на участке россыпного золота '
                 'ручей Гулхэн (приток реки Талали) в Бурятии',
        'src': [SRC],
        'events': [
            {'kind': 'closed', 'date': '2026-11-09', 'title': 'Аукцион завершен, определен победитель',
             'note': 'Аукцион на участок россыпного золота ручей Гулхэн (приток реки Талали) '
                      'в Бурятии выиграла компания «Куту»: итоговый платеж — 574 млн ₽ при '
                      'стартовой цене 29 млн ₽ (почти 20-кратный рост). В торгах участвовали '
                      'девять компаний, победитель определился на 108-м шаге.',
             'source': list(SRC)},
        ],
    }
    card = promote.to_card(draft, new_id)
    card['eco']['sum'] = draft['sum']
    card['eco']['val'] = (
        'Стартовая цена лота — 29 млн ₽, итоговый платеж победителя — 574 млн ₽ '
        '(рост почти в 20 раз). В торгах участвовали девять компаний, победитель '
        'определился на 108-м шаге.'
    )
    card['eco']['context'] = (
        'Участок — россыпное золото на ручье Гулхэн, притоке реки Талали в Бурятии, '
        'запасы оценены в 302 кг; геологоразведка на территории велась с 1940-х по '
        '1980-е годы. Лицензия выдается на 20 лет на право разведки и добычи. По '
        'закону «О недрах» победитель должен внести итоговый платеж в течение '
        'месяца — иначе лицензия перейдет участнику, предложившему предыдущую цену '
        'в ходе торгов. Имя победителя в источнике дано только как «Куту», без ИНН '
        'и других реквизитов — независимо проверить, что это за компания, не '
        'удалось.'
    )
    card['law']['terms'] = (
        'Победитель обязан внести итоговый платеж в течение месяца с даты аукциона, '
        'иначе лицензия переходит участнику, предложившему предыдущую цену (закон '
        '«О недрах»).'
    )
    card['themes'] = ['Продажа с торгов', 'ГМК и добыча']
    card['pending_since'] = datetime.now(timezone.utc).isoformat(timespec='seconds')

    pending['cards'].append(card)
    print('Добавлена карточка %s в pending.json: %s' % (new_id, card['title']))

    if write:
        promote.save_pending(pending)
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main('--write' in sys.argv)
