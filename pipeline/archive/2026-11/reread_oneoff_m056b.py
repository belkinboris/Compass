def _get(obj, field):
    for p in field.split('.'):
        obj = obj.get(p) if isinstance(obj, dict) else None
    return obj


def _set(obj, field, value):
    parts = field.split('.')
    for p in parts[:-1]:
        obj = obj.setdefault(p, {})
    if value is NONE:
        obj.pop(parts[-1], None)
    else:
        obj[parts[-1]] = value


def apply(data):
    n = 0
    deals = {d['id']: d for d in data['deals']}
    for cid, field, old, new, quote, url in _SET:
        card = deals[cid]
        cur = _get(card, field)
        if (new is NONE and cur is None) or (new is not NONE and cur == new):
            continue
        assert cur == old, (cid, field, cur)
        _set(card, field, new)
        if quote:
            fact_edit_guard.log(card, field, None if new is NONE else new, quote, url, BY)
        n += 1
    for cid, field, value in _RETRACT:
        lst = deals[cid].setdefault('retracted', {}).setdefault(field, [])
        if value not in lst:
            lst.append(value)
            n += 1
    for cid, role, text in _NOTES:
        np = deals[cid].setdefault('accepted_notes', {}).setdefault('no_profile', {})
        if np.get(role) != text:
            np[role] = text
            n += 1
    for cid, label, url in _SRC:
        src = deals[cid].setdefault('src', [])
        if not any(u == url for _l, u in src):
            src.append([label, url])
            n += 1
    for comp, field, old, new in _COMP:
        c = data['companies'][comp]
        if c.get(field) == new or (field == 'legal_short' and c.get(field)):
            continue      # правовую форму могла уже поставить party_legal_names.py из реестра
        assert c.get(field) == old, (comp, field, c.get(field))
        c[field] = new
        n += 1
    return n


