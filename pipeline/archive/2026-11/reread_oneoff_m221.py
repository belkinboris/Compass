def fixes():
    global _FIX
    if _FIX is None:
        import review
        _FIX = review.FIXES
    return _FIX


def absorb_old(card, field):
    import review
    lst = card.setdefault('proofread_absorbed', {}).setdefault(field, [])
    for f in fixes():
        if f['id'] == card['id'] and f['field'] == field and f.get('new') is not None:
            v = f['new'][1] if field == 'src' else f['new']
            fp = review.fix_fingerprint(v)
            if fp not in lst:
                lst.append(fp)


def get(card, field):
    c = card
    for p in field.split('.'):
        c = c.get(p) if isinstance(c, dict) else None
    return c


def put(card, field, value):
    parts = field.split('.')
    c = card
    for p in parts[:-1]:
        c = c.setdefault(p, {})
    c[parts[-1]] = value


def retract(card, field, value):
    r = card.setdefault('retracted', {}).setdefault(field, [])
    if value not in r:
        r.append(value)


PROBLEMS = []


def setf(card, field, old, new, quote=None, url=None, out=None, retr=False):
    cur = get(card, field)
    if cur == new:
        return
    assert cur == old, (card['id'], field, cur)
    if field in PROSE and new not in ('—', None) and quote:
        import prose_gate
        for p in prose_gate.prose_problems(new, quote, field):
            PROBLEMS.append('%s %s: %s' % (card['id'], field, p))
    put(card, field, new)
    absorb_old(card, field)
    if retr and old not in (None, '—', ''):
        retract(card, field.split('.')[-1] if field == 'eco.sum' else field, old)
    if field in fact_edit_guard.FACT_FIELDS:
        fact_edit_guard.log(card, field, new, quote, url, BY)
    out.append('%s %s -> %s' % (card['id'], field, str(new)[:70]))


def add_src(card, name, url, out, first=False):
    src = card.setdefault('src', [])
    if any(len(s) > 1 and s[1] == url for s in src):
        return
    if first:
        src.insert(0, [name, url])
    else:
        src.append([name, url])
    out.append('%s src + %s' % (card['id'], name))


def drop_src(card, url, out):
    import review
    src = card.get('src') or []
    if not any(len(s) > 1 and s[1] == url for s in src):
        return
    card['src'] = [s for s in src if not (len(s) > 1 and s[1] == url)]
    lst = card.setdefault('proofread_absorbed', {}).setdefault('src', [])
    fp = review.fix_fingerprint(url)
    if fp not in lst:
        lst.append(fp)
    out.append('%s src - %s' % (card['id'], url))


def set_sum(card, old, new, quote, url, out):
    if card.get('sum') == new and card['eco'].get('sum') == new:
        return
    assert card['eco'].get('sum') == old, (card['id'], card.get('sum'), card['eco'].get('sum'))
    if card.get('sum') not in (None, '—', new):
        retract(card, 'sum', card.get('sum'))
    card['sum'] = new
    card['eco']['sum'] = new
    retract(card, 'sum', old)
    absorb_old(card, 'eco.sum')
    fact_edit_guard.log(card, 'sum', new, quote, url, BY)
    fact_edit_guard.log(card, 'eco.sum', new, quote, url, BY)
    out.append('%s sum -> %s' % (card['id'], new))


def set_desc(comps, cid, start, desc, out):
    p = comps[cid]
    if p.get('desc') != desc:
        assert (p.get('desc') or '').startswith(start), p.get('desc')
        p['desc'] = desc
        out.append('%s desc' % cid)


def set_note(card, role, text, out):
    notes = card.setdefault('accepted_notes', {}).setdefault('no_profile', {})
    if notes.get(role) != text:
        notes[role] = text
        out.append('%s accepted_notes.no_profile.%s' % (card['id'], role))


