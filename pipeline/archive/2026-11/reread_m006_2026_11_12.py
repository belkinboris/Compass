def registry_block(rows):
    lines = ['', '', '# Вычитка m006 — %s (pipeline/archive/2026-11/reread_m006_2026_11_12.py).' % DAY, 'REGISTRY += [']
    for r in rows:
        lines += ['    {"company_id": %r, "decision": "confirmed", "inn": %r,' % (r['company_id'], r['inn']),
                  '     "reason": %r,' % r['reason'],
                  '     "date": %r},' % r['date']]
    lines.append(']')
    return '\n'.join(lines)


