def main(argv):
    with open(BASE, encoding='utf-8') as fh:
        raw = fh.read()
    data = json.loads(raw)
    deals = {d['id']: d for d in data['deals']}

    c = deals['gc9ea6b08']
    assert c['date'] == '2026-05-08', c['date']
    c['date'] = '2026'
    ret = c.setdefault('retracted', {}).setdefault('seller', [])
    if 'Teleperformance' not in ret:
        ret.append('Teleperformance')
    c.setdefault('accepted_notes', {}).setdefault('no_profile', {})['seller'] = NO_SELLER
    print('gc9ea6b08: date 2026-05-08 -> 2026; retracted.seller += Teleperformance; accepted_notes.no_profile.seller')

    v = deals['g7bbe19c2']
    v.setdefault('accepted_notes', {}).setdefault('no_profile', {})['seller'] = NO_SELLER_DOMINA
    print('g7bbe19c2: accepted_notes.no_profile.seller (продавцы — физлица)')

    k = deals['g56d19a38']
    assert k['law']['adv'] == ADV_OLD, k['law']['adv']
    k['law']['adv'] = ADV_NEW
    print('g56d19a38: law.adv + советник Павел Анненков')

    for cid, fields in PROFILES.items():
        comp = data['companies'][cid]
        for field, (old, new) in fields.items():
            assert comp.get(field) == old, (cid, field, comp.get(field))
            comp[field] = new
            print('%s.%s: %r -> %r' % (cid, field, old[:50], new[:50]))

    if '--write' not in argv:
        print('Сухой прогон. Запись — с ключом --write.')
        return
    # Перечитать базу прямо перед записью (docs/card_editing.md, «Безопасная запись базы»):
    # между чтением и записью приток мог запушить свое.
    with open(BASE, encoding='utf-8') as fh:
        assert fh.read() == raw, 'база изменилась во время прогона — перезапустите'
    out = json.dumps(data, ensure_ascii=False, indent=1)
    if raw.endswith('\n'):
        out += '\n'
    with open(BASE, 'w', encoding='utf-8') as fh:
        fh.write(out)
    print('записано')


if __name__ == '__main__':
    main(sys.argv[1:])
