def _get(obj, field):
    for p in field.split('.'):
        if not isinstance(obj, dict) or p not in obj:
            return None
        obj = obj[p]
    return obj


def _set(obj, field, value):
    parts = field.split('.')
    for p in parts[:-1]:
        obj = obj.setdefault(p, {})
    if value == '-':
        obj.pop(parts[-1], None)
    else:
        obj[parts[-1]] = value


def _apply(data, log=print):
    import fact_edit_guard
    import review
    deals = {d['id']: d for d in data['deals']}
    touched = set()
    for cid, field, old, new, quote, url in ONE_OFF:
        card = deals[cid]
        cur = _get(card, field)
        if isinstance(new, tuple):                       # замена куска внутри прозы
            a, b = new
            if b in (cur or '') and a not in (cur or ''):
                log('уже применено: %s %s' % (cid, field))
            else:
                assert (cur or '').count(a) == 1, (cid, field, cur)
                _set(card, field, cur.replace(a, b))
                fact_edit_guard.log(card, field, cur.replace(a, b), quote, url, BY)
            touched.add((cid, field))
            continue
        target = None if new == '-' else new
        if cur == target and (new != '-' or field not in card or card.get(field) is None):
            log('уже применено: %s %s' % (cid, field))
            touched.add((cid, field))
            continue
        assert cur == old, (cid, field, cur)
        _set(card, field, new)
        if new != '-':
            fact_edit_guard.log(card, field, new, quote, url, BY)
        touched.add((cid, field))
    for cid, basis in _DATE_BASIS:
        deals[cid]['date_basis'] = basis
    for cid, field, value in _RETRACT:
        lst = deals[cid].setdefault('retracted', {}).setdefault(field, [])
        if value not in lst:
            lst.append(value)
    for cid, path, value in _NOTES:
        notes = deals[cid].setdefault('accepted_notes', {})
        cur = _get(notes, path)
        if cur == value:
            continue
        assert cur is None, (cid, path, cur)
        _set(notes, path, value)
    for comp, field, old, new in _COMPANY:
        c = data['companies'][comp]
        if c.get(field) == new:
            continue
        assert old == '*' or c.get(field) == old, (comp, field, c.get(field))
        c[field] = new
    # отпечатки записей таблицы на поля, переписанные в этой партии (таблицей или здесь)
    mine = {(f['id'], f['field']) for f in review.load_fixes()
            if f.get('id') in IDS and f.get('field') != 'src'
            and f.get('why', '').startswith('вычитка 12 ноября 2026 (партия m005)')}
    for cid, field in sorted(mine | touched):
        recs = [f for f in review.load_fixes() if (f.get('id'), f.get('field')) == (cid, field)]
        if not recs:
            continue
        marks = deals[cid].setdefault('proofread_absorbed', {}).setdefault(field, [])
        for f in recs:
            fp = review.fix_fingerprint(f['new'])
            if fp not in marks:
                marks.append(fp)


