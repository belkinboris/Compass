def _get(card, field):
    o = card
    for p in field.split('.'):
        o = o.get(p) if isinstance(o, dict) else None
    return o


def _set(card, field, value):
    parts = field.split('.')
    o = card
    for p in parts[:-1]:
        o = o.setdefault(p, {})
    o[parts[-1]] = value


def _apply(data):
    sys.path.insert(0, os.path.join(ROOT, 'pipeline'))
    sys.path.insert(0, os.path.join(ROOT, 'pipeline', 'ingest'))
    import fact_edit_guard
    import review
    deals = {d['id']: d for d in data['deals']}
    comps = data['companies']
    changed = 0
    for cid, field, old, new, quote, url in SET:
        card = deals[cid]
        cur = _get(card, field)
        if cur == new:
            continue                                   # уже применено
        if isinstance(old, tuple):
            assert cur in old, (cid, field, cur)
        elif isinstance(old, str) and old.startswith('#sha1:'):
            assert hashlib.sha1(str(cur).encode('utf-8')).hexdigest()[:12] == old[6:], (cid, field, cur)
        else:
            assert cur == old, (cid, field, cur)
        _set(card, field, new)
        changed += 1
        if field in fact_edit_guard.FACT_FIELDS:
            assert quote and url, (cid, field)
            fact_edit_guard.log(card, field, new, quote, url, BY)
        # запись таблицы правок на это поле (живая или архивная) больше не задание
        marks = card.setdefault('proofread_absorbed', {}).setdefault(field, [])
        for f in review.FIXES:
            if (f.get('id'), f.get('field')) == (cid, field) and f.get('new') != new:
                fp = review.fix_fingerprint(f['new'])
                if fp not in marks:
                    marks.append(fp)
        if not marks:
            card['proofread_absorbed'].pop(field, None)
    for cid, field, value in RETRACT:
        lst = deals[cid].setdefault('retracted', {}).setdefault(field, [])
        if value not in lst:
            lst.append(value)
    for cid, label, url in SRC_ADD:
        src = deals[cid].setdefault('src', [])
        if not any(u == url for _l, u in src):
            src.append([label, url])
    for comp, field, old, new in COMPANY:
        cur = comps[comp].get(field)
        if cur == new:
            continue
        assert cur == old, (comp, field, cur)
        comps[comp][field] = new
    for cid, notes in NOTES.items():
        acc = deals[cid].setdefault('accepted_notes', {})
        for k, v in notes.items():
            if isinstance(v, dict):
                acc.setdefault(k, {}).update(v)
            else:
                acc[k] = v
    return changed


