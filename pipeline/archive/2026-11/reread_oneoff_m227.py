# Первоисточник первым: Retail.ru и Sostav пересказывают «Ведомости» («сообщают «Ведомости»»).
SRC_FIRST = [('ge5d7cce6', ['Ведомости', 'https://www.vedomosti.ru/business/articles/2022/08/22/937119-amerikanskii-samsonite-prodal'])]

REGISTRY_DATE = {'gef7d7e86', 'g2b958c12', 'g1e6bcc9d'}
RETRACT = {'buyer_name', 'seller', 'sum', 'asset'}


def get(c, f):
    if '.' in f:
        a, b = f.split('.', 1)
        return (c.get(a) or {}).get(b)
    return c.get(f)


def put(c, f, v):
    if '.' in f:
        a, b = f.split('.', 1)
        c.setdefault(a, {})[b] = v
    else:
        c[f] = v


def apply(data):
    by = {d['id']: d for d in data['deals']}
    n = 0
    for cid, f, old, new, quote, url in EDITS:
        c = by[cid]
        if get(c, f) == new:
            continue
        assert get(c, f) == old, (cid, f, get(c, f))
        put(c, f, new)
        if f in RETRACT and old not in ('—', 'Не раскрыта'):
            c.setdefault('retracted', {}).setdefault(f, []).append(old)
        if f == 'date' and cid in REGISTRY_DATE:
            c['date_basis'] = 'registry'
        fact_edit_guard.log(c, f, new, quote, url, BY, DAY)
        n += 1
    for cid, f, old, new in PROSE:
        c = by[cid]
        v = get(c, f)
        if new in v:
            continue
        assert old in v, (cid, f)
        put(c, f, v.replace(old, new))
        n += 1
    for cid, item in SRC_FIRST:
        c = by[cid]
        if c['src'] and c['src'][0][1] == item[1]:
            continue
        c['src'] = [item] + [x for x in c['src'] if x[1] != item[1]]
        n += 1
    for cid, notes in NOTES.items():
        np_ = by[cid].setdefault('accepted_notes', {}).setdefault('no_profile', {})
        for role, text in notes.items():
            if np_.get(role) != text:
                np_[role] = text
                n += 1
    return n


def main(write):
    raw = open(DATA, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    n = apply(data)
    if not n:
        print('Уже применено.')
        return 0
    mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
    bad = fact_edit_guard.unbacked(old, data)
    assert not bad, bad
    if not write:
        print('Сухой прогон: %d правок. Запись — с ключом --write.' % n)
        return 0
    fresh_raw = open(DATA, encoding='utf-8').read()
    fresh = json.loads(fresh_raw)
    apply(fresh)
    with open(DATA, 'w', encoding='utf-8') as f:
        f.write(json.dumps(fresh, ensure_ascii=False, indent=1) + ('\n' if fresh_raw.endswith('\n') else ''))
    print('ЗАПИСАНО: %d правок.' % n)
    return 0


if __name__ == '__main__':
    sys.exit(main('--write' in sys.argv[1:]))
