def _get(card, field):
    if '.' in field:
        head, tail = field.split('.', 1)
        return (card.get(head) or {}).get(tail)
    return card.get(field)


def _set(card, field, value):
    if '.' in field:
        head, tail = field.split('.', 1)
        card.setdefault(head, {})[tail] = value
    else:
        card[field] = value


def apply(data):
    by = {d['id']: d for d in data['deals']}
    comps = data['companies']
    n = 0
    for cid, (old, new, quote, url) in SELLERS.items():
        c = by[cid]
        if c.get('seller') == new:
            continue
        assert c.get('seller') == old and not c.get('seller_id'), (cid, c.get('seller'))
        c['seller'] = new
        fact_edit_guard.log(c, 'seller', new, quote, url, BY, DAY)
        n += 1
    for cid, field, old, new in PROSE:
        c = by[cid]
        if _get(c, field) == new:
            continue
        assert _get(c, field) == old, (cid, field, _get(c, field))
        _set(c, field, new)
        n += 1
    for cid, field, old, new in PIECES:
        c = by[cid]
        v = _get(c, field) or ''
        if new in v:
            continue
        assert v.count(old) == 1, (cid, field)
        _set(c, field, v.replace(old, new))
        n += 1
    for cid, url, old, new in SRC_LABELS:
        rows = [s for s in by[cid].get('src') or [] if len(s) > 1 and s[1] == url]
        assert len(rows) == 1, (cid, url)
        if rows[0][0] == new:
            continue
        assert rows[0][0] == old, (cid, rows[0][0])
        rows[0][0] = new
        n += 1
    for pid, (old, new) in PROFILES.items():
        p = comps[pid]
        if p.get('desc') == new:
            continue
        assert p.get('desc') == old, (pid, p.get('desc'))
        p['desc'] = new
        n += 1
    for cid, text in REGISTRY.items():
        c = by[cid]
        if (c.get('checked') or {}).get('registry_owners') == text:
            continue
        c.setdefault('checked', {})['registry_owners'] = text
        n += 1
    return n


def registry(write):
    import fns_registry
    reg_raw = open(REG_JSON, encoding='utf-8').read()
    rows = json.loads(reg_raw)
    n = 0
    for cid, old_inn, row in REGISTRY_EDIT:
        hits = [i for i, r in enumerate(rows) if r.get('company_id') == cid]
        assert len(hits) == 1, (cid, hits)
        r = rows[hits[0]]
        if r.get('inn') == row['inn']:
            continue
        assert r.get('inn') == old_inn, (cid, r)
        assert fns_registry.inn_is_valid(row['inn']), row['inn']
        assert not [x for x in rows if x.get('inn') == row['inn']], 'ИНН уже у другого профиля'
        rows[hits[0]] = dict({'company_id': cid}, **row)
        print('реестр %s: %s → %s' % (cid, old_inn, row['inn']))
        n += 1
    if n and write:
        with open(REG_JSON, 'w', encoding='utf-8') as fh:
            fh.write(json.dumps(rows, ensure_ascii=False, indent=1) + ('\n' if reg_raw.endswith('\n') else ''))
    return n


def main(write):
    raw = open(DATA, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    n = apply(data)
    m = registry(write)
    if not n and not m:
        print('Уже применено.')
        return 0
    mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
    bad = fact_edit_guard.unbacked(old, data)
    assert not bad, bad
    if not write:
        print('Сухой прогон: %d правок базы, %d строк реестра. Запись — с ключом --write.' % (n, m))
        return 0
    if n:
        fresh_raw = open(DATA, encoding='utf-8').read()
        fresh = json.loads(fresh_raw)
        apply(fresh)
        with open(DATA, 'w', encoding='utf-8') as f:
            f.write(json.dumps(fresh, ensure_ascii=False, indent=1) + ('\n' if fresh_raw.endswith('\n') else ''))
    print('ЗАПИСАНО: %d правок базы, %d строк реестра.' % (n, m))
    return 0


if __name__ == '__main__':
    sys.exit(main('--write' in sys.argv))
