RETRACT = [('c06611bae', 'status', 'Не состоялась')]


def get(card, f):
    v = card
    for p in f.split('.'):
        v = v.get(p) if isinstance(v, dict) else None
    return v


def setf(card, f, val):
    parts = f.split('.')
    for p in parts[:-1]:
        card = card.setdefault(p, {})
    if val == DEL:
        card.pop(parts[-1], None)
    else:
        card[parts[-1]] = val


def apply(data):
    cards = {c['id']: c for c in data['deals']}
    done = []
    for cid, f, old, new, quote, url in ROWS:
        c = cards[cid]
        cur = get(c, f)
        if cur == new or (new == DEL and cur is None):
            continue
        assert cur == old, (cid, f, cur)
        setf(c, f, new)
        if quote:
            fact_edit_guard.log(c, f, new, quote.replace('ё', 'е'), url, BY, DAY)
        done.append('%s %s' % (cid, f))
    for cid, f, val in RETRACT:
        r = cards[cid].setdefault('retracted', {}).setdefault(f, [])
        if val not in r:
            r.append(val)
            done.append('%s retracted.%s' % (cid, f))
    return done


def main(write):
    raw = open(DB, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    done = apply(data)
    if not done:
        print('Уже применено.')
        return 0
    mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
    bad = fact_edit_guard.unbacked(old, data)
    assert not bad, bad
    print('\n'.join(done))
    if not write:
        print('Сухой прогон: %d правок. Запись — с ключом --write.' % len(done))
        return 0
    fresh_raw = open(DB, encoding='utf-8').read()
    fresh = json.loads(fresh_raw)
    apply(fresh)
    with open(DB, 'w', encoding='utf-8') as f:
        f.write(json.dumps(fresh, ensure_ascii=False, indent=1) + ('\n' if fresh_raw.endswith('\n') else ''))
    print('ЗАПИСАНО: %d правок.' % len(done))
    return 0


