def set_val(obj, key, old, new):
    assert obj.get(key) == old, (key, obj.get(key), old)
    obj[key] = new


def retract(card, field, value):
    lst = card.setdefault('retracted', {}).setdefault(field, [])
    if value not in lst:
        lst.append(value)


def note(card, idx, kind, old_start, new):
    ev = card['events'][idx]
    assert ev['kind'] == kind and ev['note'].startswith(old_start), (card['id'], idx, ev['kind'], ev['note'][:60])
    ev['note'] = new


def absorb(card, field):
    """Поле правится мимо таблицы, а у него есть запись FIXES (архив): ее
    отпечаток — в proofread_absorbed (docs/card_editing.md, «Правка поля мимо
    таблицы синхронизирует запись»), иначе запись сочтут непримененной."""
    marks = card.setdefault('proofread_absorbed', {}).setdefault(field, [])
    for f in review.FIXES:
        if f['id'] == card['id'] and f['field'] == field and f.get('new') is not None:
            fp = review.fix_fingerprint(f['new'])
            if fp not in marks:
                marks.append(fp)


def drop_note(card, role):
    card.get('accepted_notes', {}).get('no_profile', {}).pop(role, None)


