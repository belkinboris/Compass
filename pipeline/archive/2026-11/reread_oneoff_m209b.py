def _get(card, field):
    if '.' in field:
        head, tail = field.split('.', 1)
        return (card.get(head) or {}).get(tail, NO)
    return card.get(field, NO)


def _set(card, field, value):
    if '.' in field:
        head, tail = field.split('.', 1)
        box = card.setdefault(head, {})
    else:
        box, tail = card, field
    if value is DEL:
        box.pop(tail, None)
    else:
        box[tail] = value


def apply(data):
    by = {d['id']: d for d in data['deals']}
    n = 0
    for cid, field, old, new, quote, url in EDITS:
        c = by[cid]
        cur = _get(c, field)
        if (new is DEL and cur is NO) or (new is not DEL and cur == new):
            continue
        assert cur == old, (cid, field, cur)
        _set(c, field, new)
        if field in fact_edit_guard.FACT_FIELDS:
            fact_edit_guard.log(c, field, None if new is DEL else new, quote, url, BY, DAY)
        n += 1
    for cid, rows in SRC_ADD.items():
        c = by[cid]
        have = {u for _n, u in c.get('src') or []}
        for row in rows:
            if row[1] not in have:
                c.setdefault('src', []).append(list(row))
                n += 1
    for cid, (field, value) in RETRACT.items():
        lst = by[cid].setdefault('retracted', {}).setdefault(field, [])
        if value not in lst:
            lst.append(value)
            n += 1
    if DESC:
        comp = data['companies'][DESC[0]]
        if comp.get('desc') != DESC[2]:
            assert comp.get('desc') == DESC[1], comp.get('desc')
            comp['desc'] = DESC[2]
            n += 1
    return n


