def _get(card, field):
    o = card
    for p in field.split('.'):
        o = o.get(p) if isinstance(o, dict) else None
    return o


def _set(card, field, value):
    parts = field.split('.')
    o = card
    for p in parts[:-1]:
        o = o.setdefault(p, {})
    if value is None and parts[-1] in ('date_basis', 'sum_basis', 'buyer'):
        if parts[-1] == 'buyer':
            o[parts[-1]] = None
        else:
            o.pop(parts[-1], None)
    else:
        o[parts[-1]] = value


def _absorb(card, field, fixes):
    import review
    for r in fixes:
        if r['id'] == card['id'] and r['field'] == field and r.get('new') is not None:
            fp = review.fix_fingerprint(r['new'])
            lst = card.setdefault('proofread_absorbed', {}).setdefault(field, [])
            if fp not in lst:
                lst.append(fp)


def apply(data):
    import review
    fixes = review.load_fixes()
    by = {d['id']: d for d in data['deals']}
    n = 0
    for cid, field, old, new, quote, url in EDITS:
        c = by[cid]
        cur = _get(c, field)
        if field == 'g162de6fb' or (cid == 'g162de6fb' and field == 'eco.rationale'):
            if 'по словам Кирш,' not in (cur or ''):
                continue
            new = cur.replace('по словам Кирш,', 'по словам владельца «Гельтека» Сергея Кирша,')
        elif cid == 'g24b33459' and field == 'eco.context':
            if KUM_EXIT in (cur or ''):
                continue
            new = cur.rstrip() + '\n\n' + KUM_EXIT
        elif cid == 'gmru-arnest-reckitt' and field == 'eco.context':
            if GMRU_NEW_TAIL in (cur or ''):
                continue
            assert GMRU_OLD_TAIL in cur, cur
            new = cur.replace(GMRU_OLD_TAIL, GMRU_NEW_TAIL)
        elif cid == 'g22000f22' and field == 'eco.share':
            if cur == new:
                continue
            assert cur.startswith('Почти 20% акций ПАО «Детский мир» — доли бывшего'), cur
        else:
            if cur == new:
                continue
            assert cur == old, (cid, field, cur)
        _set(c, field, new)
        _absorb(c, field, fixes)
        if field in fact_edit_guard.FACT_FIELDS or field in ('date_basis', 'sum_basis', 'law.terms'):
            fact_edit_guard.log(c, field, new, quote, url, BY, DAY)
        n += 1
    for cid, (key, text) in NOTES.items():
        an = by[cid].setdefault('accepted_notes', {}).setdefault('checked', {})
        if an.get(key) != text:
            an[key] = text
            n += 1
    cid, text = NO_PROFILE_BUYER
    np_ = by[cid].setdefault('accepted_notes', {}).setdefault('no_profile', {})
    if np_.get('buyer') != text:
        np_['buyer'] = text
        n += 1
    return n


def main(write):
    raw = open(DATA, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    n = apply(data)
    if not n:
        print('Уже применено.')
        return 0
    mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
    bad = fact_edit_guard.unbacked(old, data)
    assert not bad, bad
    if not write:
        print('Сухой прогон: %d правок. Запись — с ключом --write.' % n)
        return 0
    fresh_raw = open(DATA, encoding='utf-8').read()
    fresh = json.loads(fresh_raw)
    apply(fresh)
    with open(DATA, 'w', encoding='utf-8') as f:
        f.write(json.dumps(fresh, ensure_ascii=False, indent=1) + ('\n' if fresh_raw.endswith('\n') else ''))
    print('ЗАПИСАНО: %d правок.' % n)
    return 0


