def get(card, field):
    if '.' in field:
        h, t = field.split('.', 1)
        return (card.get(h) or {}).get(t, MISSING)
    return card.get(field, MISSING)


def put(card, field, value):
    if '.' in field:
        h, t = field.split('.', 1)
        card.setdefault(h, {})[t] = value
    else:
        card[field] = value


def apply(data):
    by = {d['id']: d for d in data['deals']}
    n = 0
    for cid, field, old, new, quote, url in EDITS:
        c = by[cid]
        cur = get(c, field)
        if cur == new:
            continue
        assert cur == old, (cid, field, cur)
        put(c, field, new)
        if field in FACT:
            fact_edit_guard.log(c, field, new, quote, url, BY, DAY)
        n += 1
    for cid, field, old, new in COMPANIES:
        co = data['companies'][cid]
        cur = co.get(field, MISSING)
        if cur == new:
            continue
        assert cur == old, (cid, field, cur)
        co[field] = new
        n += 1
    for cid, rows in ADD_SRC.items():
        c = by[cid]
        have = {u for _, u in c.get('src') or []}
        for name, url in rows:
            if url not in have:
                c.setdefault('src', []).append([name, url])
                n += 1
    for cid in DATE_REGISTRY:
        if by[cid].get('date_basis') != 'registry':
            by[cid]['date_basis'] = 'registry'
            n += 1
    for cid, notes in NOTES.items():
        an = by[cid].setdefault('accepted_notes', {})
        for k, v in notes.items():
            if isinstance(v, dict):
                sub = an.setdefault(k, {})
                for kk, vv in v.items():
                    if sub.get(kk) != vv:
                        sub[kk] = vv
                        n += 1
            elif an.get(k) != v:
                an[k] = v
                n += 1
    for cid, field, old in DELETE:
        c = by[cid]
        if field not in c:
            continue
        assert c[field] == old, (cid, field, c[field])
        del c[field]
        n += 1
    for cid, field, value in RETRACT:
        lst = by[cid].setdefault('retracted', {}).setdefault(field, [])
        if value not in lst:
            lst.append(value)
            n += 1
    return n


def main(write):
    raw = open(DATA, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    n = apply(data)
    if not n:
        print('Уже применено.')
        return 0
    mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
    bad = fact_edit_guard.unbacked(old, data)
    assert not bad, bad
    if not write:
        print('Сухой прогон: %d правок. Запись — с ключом --write.' % n)
        return 0
    fresh_raw = open(DATA, encoding='utf-8').read()
    fresh = json.loads(fresh_raw)
    apply(fresh)
    with open(DATA, 'w', encoding='utf-8') as f:
        f.write(json.dumps(fresh, ensure_ascii=False, indent=1) + ('\n' if fresh_raw.endswith('\n') else ''))
    print('ЗАПИСАНО: %d правок.' % n)
    return 0


if __name__ == '__main__':
    sys.exit(main('--write' in sys.argv[1:]))
