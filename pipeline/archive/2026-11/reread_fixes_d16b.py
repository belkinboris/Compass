def _get(c, path):
    cur = c
    for p in path.split('.'):
        if isinstance(cur, list):
            cur = cur[int(p)]
        else:
            if p not in cur:
                return MISSING
            cur = cur[p]
    return cur


def _set(c, path, value):
    parts = path.split('.')
    cur = c
    for p in parts[:-1]:
        cur = cur[int(p)] if isinstance(cur, list) else cur[p]
    last = parts[-1]
    if isinstance(cur, list):
        cur[int(last)] = value
    elif value is None:
        cur.pop(last, None)
    else:
        cur[last] = value


def apply(data):
    by = {d['id']: d for d in data['deals']}
    n = 0
    for cid, path, old, new, quote, url, _cls in ROWS:
        c = by[cid]
        if path == 'src+':
            if any(s[1] == new[1] for s in c.get('src') or []):
                continue
            c['src'].append(list(new))
            n += 1
            continue
        if path == 'src_first':
            urls = [s[1] for s in c['src']]
            if urls[0] == new:
                continue
            assert urls == old, (cid, urls)
            c['src'].sort(key=lambda s: s[1] != new)
            n += 1
            continue
        cur = _get(c, path)
        if cur == new or (new is None and cur == MISSING):
            continue
        assert cur == old, (cid, path, cur)
        _set(c, path, new)
        if path in FACTS:
            fact_edit_guard.log(c, path, new, quote, url, BY, DAY)
        n += 1
    return n


def main(write):
    raw = open(DATA, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    n = apply(data)
    if not n:
        print('Уже применено.')
        return 0
    mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
    bad = fact_edit_guard.unbacked(old, data)
    assert not bad, bad
    if not write:
        print('Сухой прогон: %d правок. Запись — с ключом --write.' % n)
        return 0
    fresh_raw = open(DATA, encoding='utf-8').read()
    fresh = json.loads(fresh_raw)
    apply(fresh)
    with open(DATA, 'w', encoding='utf-8') as f:
        f.write(json.dumps(fresh, ensure_ascii=False, indent=1) + ('\n' if fresh_raw.endswith('\n') else ''))
    print('ЗАПИСАНО: %d правок.' % n)
    return 0


