def apply(data):
    by = {d['id']: d for d in data['deals']}
    n = 0
    for cid, sec, f, cut in STRIP:
        c = by[cid]
        v = c[sec].get(f) or ''
        if cut in v:
            c[sec][f] = v.replace(cut, '')
            n += 1
        else:
            assert cut.strip() not in v, (cid, f)
    for cid, add in CONTEXT:
        c = by[cid]
        v = c['eco'].get('context') or ''
        if add in v:
            continue
        c['eco']['context'] = (v.rstrip() + ' ' + add).strip()
        n += 1
    for cid, sec, f, old, new in REPLACE:
        c = by[cid]
        v = c[sec].get(f) or ''
        if new in v:
            continue
        assert old in v, (cid, f)
        c[sec][f] = v.replace(old, new)
        n += 1
    cid, old, new, quote, url = SHARE
    c = by[cid]
    if c['eco'].get('share') != new:
        assert c['eco'].get('share') == old, c['eco'].get('share')
        c['eco']['share'] = new
        fact_edit_guard.log(c, 'eco.share', new, quote, url, BY, DAY)
        n += 1
    for cid, s in SRC:
        c = by[cid]
        if any((x[1] if isinstance(x, list) else x) == s[1] for x in c.get('src') or []):
            continue
        c.setdefault('src', []).append(s)
        n += 1
    c = by[BG]
    if c['title'] != BG_TITLE[1]:
        assert c['title'] == BG_TITLE[0], c['title']
        c['title'] = BG_TITLE[1]
        fact_edit_guard.log(c, 'title', BG_TITLE[1], BG_TITLE[2], BG_URL, BY, DAY)
        n += 1
    if c['sum'] != BG_SUM[1]:
        assert c['sum'] == BG_SUM[0] and c['eco']['sum'] == BG_SUM[0], c['sum']
        c['sum'] = c['eco']['sum'] = BG_SUM[1]
        c['sum_basis'] = 'reported'
        for f in ('sum', 'eco.sum'):
            fact_edit_guard.log(c, f, BG_SUM[1], BG_SUM[2], BG_URL, BY, DAY)
        n += 1
    if c['date'] != BG_DATE[1]:
        assert c['date'] == BG_DATE[0], c['date']
        c['date'] = BG_DATE[1]
        c.pop('date_basis', None)
        fact_edit_guard.log(c, 'date', BG_DATE[1], BG_DATE[2], BG_URL, BY, DAY)
        n += 1
    ev = [e for e in c.get('events') or [] if e.get('kind') == 'approval']
    if ev and ev[0].get('note') != BG_NOTE[1]:
        assert ev[0].get('note') == BG_NOTE[0], ev[0].get('note')
        ev[0]['note'] = BG_NOTE[1]
        n += 1
    np_ = c.setdefault('accepted_notes', {}).setdefault('no_profile', {})
    if np_.get('buyer') != BG_BUYER_NOTE:
        np_['buyer'] = BG_BUYER_NOTE
        n += 1
    return n


def main(write):
    raw = open(DATA, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    n = apply(data)
    if not n:
        print('Уже применено.')
        return 0
    mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
    bad = fact_edit_guard.unbacked(old, data)
    assert not bad, bad
    if not write:
        print('Сухой прогон: %d правок. Запись — с ключом --write.' % n)
        return 0
    fresh_raw = open(DATA, encoding='utf-8').read()
    fresh = json.loads(fresh_raw)
    apply(fresh)
    with open(DATA, 'w', encoding='utf-8') as f:
        f.write(json.dumps(fresh, ensure_ascii=False, indent=1) + ('\n' if fresh_raw.endswith('\n') else ''))
    print('ЗАПИСАНО: %d правок.' % n)
    return 0


if __name__ == '__main__':
    sys.exit(main('--write' in sys.argv))
