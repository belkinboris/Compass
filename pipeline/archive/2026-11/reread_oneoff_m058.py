def apply_legal(data):
    deals = {d['id']: d for d in data['deals']}
    comps = data['companies']
    want = dict((k, v) for k, v in LEGAL.items() if v)
    # Стороны, чьи id видны только через карточку: предмет MFG, «Возрождение», «РусГидро» и Green Crab.
    for cid, role, val in (('gb9fdfce4', 'target', 'АО «Мэлон Фэшн Груп»'),       # АО "МЭЛОН ФЭШН ГРУП", ИНН 7839326623
                           ('g4c3f2103', 'seller_id', 'ООО АПК «Возрождение»'),    # ИНН 2634090865
                           ('g446bbeee', 'buyer', 'ПАО «РусГидро»'),               # ИНН 2460066195
                           ('g446bbeee', 'seller_id', 'ООО «Серенити инвест»'),    # ИНН 7703808500
                           ('g446bbeee', 'target', 'ООО «РусГидро каршеринг»')):   # ИНН 2536331086
        want[deals[cid][role]] = val
    for pid, val in want.items():
        cur = comps[pid].get('legal_short')
        if cur == val:
            continue
        assert not cur, (pid, cur)
        comps[pid]['legal_short'] = val
        CHANGED.append('profile %s legal_short' % pid)
    for cid, basis in DATE_BASIS.items():
        if deals[cid].get('date_basis') != basis:
            assert not deals[cid].get('date_basis'), (cid, deals[cid].get('date_basis'))
            deals[cid]['date_basis'] = basis
            CHANGED.append('%s date_basis' % cid)


