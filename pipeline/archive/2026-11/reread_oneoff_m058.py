def get(card, field):
    if '.' in field:
        a, b = field.split('.', 1)
        return (card.get(a) or {}).get(b)
    return card.get(field)


def put(card, field, value):
    if '.' in field:
        a, b = field.split('.', 1)
        card.setdefault(a, {})[b] = value
    else:
        if value is None:
            card.pop(field, None)
        else:
            card[field] = value


def setf(card, field, old, new, quote=None, url=None):
    cur = get(card, field)
    if cur == new:
        return
    assert cur == old, (card['id'], field, cur)
    put(card, field, new)
    if field in FACTS:
        assert quote and url, (card['id'], field)
        fact_edit_guard.log(card, field, new, quote, url, BY)
    CHANGED.append('%s %s' % (card['id'], field))


def retract(card, field, value):
    lst = card.setdefault('retracted', {}).setdefault(field, [])
    if value not in lst:
        lst.append(value)


def add_src(card, label, url, first=False):
    src = card.setdefault('src', [])
    if any(u == url for _l, u in src):
        return
    if first:
        src.insert(0, [label, url])
    else:
        src.append([label, url])
    CHANGED.append('%s src+%s' % (card['id'], url))


def notes(card, key, value):
    n = card.setdefault('accepted_notes', {})
    if n.get(key) != value:
        n[key] = value


def comp(comps, cid, field, old, new):
    cur = comps[cid].get(field)
    if cur == new:
        return
    assert cur == old, (cid, field, cur)
    comps[cid][field] = new
    CHANGED.append('profile %s %s' % (cid, field))


