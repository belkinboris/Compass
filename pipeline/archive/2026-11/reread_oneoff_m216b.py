def _walk(card, path):
    parts = path.split('.')
    obj = card
    for p in parts[:-1]:
        obj = obj[int(p)] if isinstance(obj, list) else obj.setdefault(p, {})
    return obj, (int(parts[-1]) if isinstance(obj, list) else parts[-1])


def _get(card, path):
    obj, k = _walk(card, path)
    if isinstance(obj, list):
        return obj[k]
    return obj.get(k, A)


def apply(data):
    by = {d['id']: d for d in data['deals']}
    n = 0
    targets = set((data.get('merged') or {}).values())
    for cid, expect in REMOVE.items():
        if cid not in by:
            continue
        assert expect in str(by[cid].get('title')), (cid, by[cid].get('title'))
        assert cid not in targets, '%s — цель слияния' % cid
        data['deals'] = [d for d in data['deals'] if d['id'] != cid]
        n += 1
    by = {d['id']: d for d in data['deals']}
    for cid, new in NEW_COMPANIES.items():
        if cid not in data['companies']:
            data['companies'][cid] = dict(new)
            n += 1
    for cid, path, old, new, quote, url, flags in OPS:
        if cid in REMOVE:
            continue
        c = by[cid]
        cur = _get(c, path)
        if cur == new:
            continue
        assert cur == old, (cid, path, cur)
        obj, k = _walk(c, path)
        if new == A:
            del obj[k]
        else:
            obj[k] = new
        if path in RETRACT and old not in (A, None, '—') and 'noretract' not in flags:
            c.setdefault('retracted', {}).setdefault(path, []).append(old)
        if path in fact_edit_guard.FACT_FIELDS:
            fact_edit_guard.log(c, path, None if new == A else new, quote, url, BY, DAY)
        n += 1
    comps = data['companies']
    for comp, field, old, new in COMPANY_OPS:
        if comps[comp].get(field, A) == new:
            continue
        assert comps[comp].get(field, A) == old, (comp, field, comps[comp].get(field))
        comps[comp][field] = new
        n += 1
    return n


def registry(write):
    rows = json.load(open(REG, encoding='utf-8'))
    have = {r['company_id']: r for r in rows}
    todo = []
    for row in REGISTRY:
        cur = have.get(row['company_id'])
        if cur and cur.get('inn') == row['inn']:
            continue
        clash = [r['company_id'] for r in rows if r.get('inn') == row['inn'] and r['company_id'] != row['company_id']]
        assert not clash, (row['inn'], clash)
        assert not cur, ('у профиля уже другой ИНН', row['company_id'], cur.get('inn'))
        todo.append(row)
    if write and todo:
        rows = json.load(open(REG, encoding='utf-8'))
        rows.extend(todo)
        with open(REG, 'w', encoding='utf-8') as fh:
            json.dump(rows, fh, ensure_ascii=False, indent=1)
    return len(todo)


def main(write):
    raw = open(DATA, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    n = apply(data)
    r = registry(False)
    if not n and not r:
        print('Уже применено.')
        return 0
    mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
    bad = fact_edit_guard.unbacked(old, data)
    assert not bad, bad
    if not write:
        print('Сухой прогон: правок базы %d, записей реестра ИНН %d. Запись — с ключом --write.' % (n, r))
        return 0
    if n:
        fresh_raw = open(DATA, encoding='utf-8').read()
        fresh = json.loads(fresh_raw)
        apply(fresh)
        with open(DATA, 'w', encoding='utf-8') as f:
            f.write(json.dumps(fresh, ensure_ascii=False, indent=1) + ('\n' if fresh_raw.endswith('\n') else ''))
    registry(True)
    if REMOVE:
        import fix_files
        for cid in REMOVE:
            fix_files.drop_fixes_for(cid, write=True)
        if os.path.exists(DISCREP):
            q = json.load(open(DISCREP, encoding='utf-8'))
            kept = [r for r in q if r.get('id') not in REMOVE]
            if len(kept) != len(q):
                json.dump(kept, open(DISCREP, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
        # Признаки будущих сделок, собранные из снятой карточки (signals.py, origin «card»), — тоже снять.
        if os.path.exists(SIGNALS):
            raw_s = open(SIGNALS, encoding='utf-8').read()
            sig = json.loads(raw_s)
            keep = [r for r in sig['signals'] if r.get('deal_id') not in REMOVE]
