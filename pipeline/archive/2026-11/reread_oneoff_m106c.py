RETRACT = ('buyer_name', 'seller', 'asset', 'sum', 'status')


def get(obj, path):
    for k in path.split('.'):
        obj = (obj or {}).get(k)
    return obj


def put(obj, path, value):
    keys = path.split('.')
    for k in keys[:-1]:
        obj = obj.setdefault(k, {})
    if value is None:
        obj.pop(keys[-1], None)
    else:
        obj[keys[-1]] = value


def apply_deals(data):
    by = {d['id']: d for d in data['deals']}
    n = 0
    for row in DEAL_EDITS:
        cid, field, old, new, quote, url = row[:6]
        c = by[cid]
        cur = get(c, field)
        if len(row) > 6:
            if new in (cur or ''):
                continue
            assert (cur or '').count(old) == 1, (cid, field)
            put(c, field, cur.replace(old, new))
            fact_edit_guard.log(c, field, get(c, field), quote, url, BY, DAY)
            n += 1
            continue
        if cur == new:
            continue
        assert cur == old, (cid, field, cur)
        put(c, field, new)
        if field in RETRACT and old:
            lst = c.setdefault('retracted', {}).setdefault(field, [])
            if old not in lst:
                lst.append(old)
        fact_edit_guard.log(c, field, new, quote, url, BY, DAY)
        n += 1
    for cid, role, old, new in NOTES:
        notes = by[cid].setdefault('accepted_notes', {}).setdefault('no_profile', {})
        if notes.get(role) == new:
            continue
        assert notes.get(role) == old, (cid, role, notes.get(role))
        notes[role] = new
        n += 1
    return n


def apply(data):
    comps = data['companies']
    n = apply_deals(data)
    for cid, field, old, new in PROFILE:
        c = comps[cid]
        cur = c.get(field)
        if (new is DROP and field not in c) or cur == new:
            continue
        assert cur == old, (cid, field, cur)
        if new is DROP:
            del c[field]
        else:
            c[field] = new
        n += 1
    for cid, old, new in MATCH_KEYS:
        cur = data['match_keys'].get(cid)
        if cur == new:
            continue
        assert cur == old, (cid, cur)
        data['match_keys'][cid] = new
        n += 1
    return n


def registry(write):
    rows = json.load(open(REG, encoding='utf-8'))
    have = {r['company_id']: r for r in rows}
    todo = []
    for row in REGISTRY:
        cur = have.get(row['company_id'])
        assert cur, row['company_id']
        if cur.get('inn') == row['inn'] and cur.get('decision') == row['decision'] and cur.get('date') == DAY:
            continue
        if row['inn']:
            clash = [r['company_id'] for r in rows if r.get('inn') == row['inn'] and r['company_id'] != row['company_id']]
            assert not clash, (row['inn'], clash)
        todo.append(row)
    if write:
        for row in todo:
            assert fns_notes_to_registry.edit_registry_entry(row['company_id'], row)
    return len(todo)


def main(write):
    raw = open(DATA, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    n = apply(data)
    if n:
        mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
    bad = fact_edit_guard.unbacked(old, data)
    assert not bad, bad
    r = registry(False)
    if not write:
        print('Сухой прогон: правок базы %d, записей реестра ИНН %d. Запись — с ключом --write.' % (n, r))
        return 0
    if n:
        fresh_raw = open(DATA, encoding='utf-8').read()
        fresh = json.loads(fresh_raw)
        apply(fresh)
        with open(DATA, 'w', encoding='utf-8') as f:
            f.write(json.dumps(fresh, ensure_ascii=False, indent=1) + ('\n' if fresh_raw.endswith('\n') else ''))
    registry(True)
    print('ЗАПИСАНО: правок базы %d, записей реестра ИНН %d.' % (n, r) if (n or r) else 'Уже применено.')
    return 0


