def _get(card, field):
    o = card
    for p in field.split('.'):
        o = o.get(p) if isinstance(o, dict) else None
    return o


def _set(card, field, value):
    parts = field.split('.')
    o = card
    for p in parts[:-1]:
        o = o.setdefault(p, {})
    o[parts[-1]] = value


def apply(data):
    deals = {d['id']: d for d in data['deals']}
    n = 0
    for cid, field, old, new, quote, url in _SET:
        card = deals[cid]
        cur = _get(card, field)
        if cur == new:
            continue
        assert cur == old, (cid, field, cur)
        _set(card, field, new)
        if quote:
            fact_edit_guard.log(card, field, new, quote, url, BY)
            if field == 'sum':
                fact_edit_guard.log(card, 'eco.sum', new, quote, url, BY)
        n += 1
    for cid, field, value in _RETRACT:
        lst = deals[cid].setdefault('retracted', {}).setdefault(field, [])
        if value not in lst:
            lst.append(value)
            n += 1
    for cid, url in _SRC_DROP:
        src = deals[cid].get('src') or []
        keep = [s for s in src if s[1] != url]
        if len(keep) != len(src):
            assert keep, cid
            deals[cid]['src'] = keep
            n += 1
    for comp, field, old, new in _PROFILE:
        c = data['companies'][comp]
        if c.get(field) == new:
            continue
        assert c.get(field) == old, (comp, field, c.get(field))
        c[field] = new
        n += 1
    for comp, short in _LEGAL:
        c = data['companies'][comp]
        if c.get('legal_short') != short:
            assert not c.get('legal_short'), (comp, c.get('legal_short'))
            c['legal_short'] = short
            n += 1
    for cid, notes in _NOTES.items():
        acc = deals[cid].setdefault('accepted_notes', {})
        for k, v in notes.items():
            if isinstance(v, dict):
                cur = acc.setdefault(k, {})
                for a, b in v.items():
                    if cur.get(a) != b:
                        cur[a] = b
                        n += 1
            elif acc.get(k) != v:
                acc[k] = v
                n += 1
    return n


