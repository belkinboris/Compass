def get(card, field):
    cur = card
    for k in field.split('.'):
        cur = (cur or {}).get(k)
    return cur


def put(card, field, value):
    parts = field.split('.')
    cur = card
    for k in parts[:-1]:
        cur = cur.setdefault(k, {})
    cur[parts[-1]] = value


def apply(data):
    deals = {d['id']: d for d in data['deals']}
    comps = data['companies']
    out = []
    for cid, field, old, new, quote, url in FACTS:
        c = deals[cid]
        if get(c, field) == new:
            continue
        assert get(c, field) == old, (cid, field, get(c, field))
        put(c, field, new)
        if old and field in ('sum', 'seller', 'buyer_name', 'asset'):
            r = c.setdefault('retracted', {}).setdefault(field, [])
            if old not in r:
                r.append(old)
        fact_edit_guard.log(c, field, new, quote, url, BY)
        out.append('%s %s -> %r' % (cid, field, new))
    for cid, field, old, new in PLAIN:
        c = deals[cid]
        if get(c, field) == new:
            continue
        assert get(c, field) == old, (cid, field, get(c, field))
        put(c, field, new)
        out.append('%s %s -> %r' % (cid, field, new))
    for pid, old, new in PROFILES:
        p = comps[pid]
        if p.get('desc') == new:
            continue
        assert p.get('desc') == old, (pid, p.get('desc'))
        p['desc'] = new
        out.append('%s desc' % pid)
    for cid, pair in SRC:
        c = deals[cid]
        if pair[1] not in [u for _n, u in c.get('src') or []]:
            c.setdefault('src', []).append(pair)
            out.append('%s src + %s' % (cid, pair[0]))
    return out


def main(argv):
    data = json.load(open(DATA, encoding='utf-8'))
    out = apply(data)
    print('\n'.join(out) or 'уже применено')
    if '--write' in argv and out:
        data = json.load(open(DATA, encoding='utf-8'))      # перечитать прямо перед записью
        apply(data)
        with open(DATA, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('записано')
    return 0


