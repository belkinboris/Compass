def get(c, field):
    v = c
    for p in field.split('.'):
        v = (v or {}).get(p)
    return v


def put(c, field, value):
    parts = field.split('.')
    t = c
    for p in parts[:-1]:
        t = t.setdefault(p, {})
    t[parts[-1]] = value


def apply(data):
    by = {d['id']: d for d in data['deals']}
    n = 0
    for cid, (old, quote, url) in SUMS.items():
        c = by[cid]
        if c['sum'] == 'Не раскрыта':
            continue
        assert c['sum'] == old and c['eco']['sum'] == old, (cid, c['sum'])
        c['sum'] = 'Не раскрыта'
        c['eco']['sum'] = 'Не раскрыта'
        c.pop('sum_basis', None)
        r = c.setdefault('retracted', {}).setdefault('sum', [])
        if old not in r:
            r.append(old)
        fact_edit_guard.log(c, 'sum', 'Не раскрыта', quote, url, BY, DAY)
        fact_edit_guard.log(c, 'eco.sum', 'Не раскрыта', quote, url, BY, DAY)
        n += 1
    for cid, (old, new, quote, url) in DATES.items():
        c = by[cid]
        if c['date'] == new and c.get('date_basis') == 'registry':
            continue
        assert c['date'] == old, (cid, c['date'])
        c['date'] = new
        c['date_basis'] = 'registry'
        fact_edit_guard.log(c, 'date', new, quote, url, BY, DAY)
        n += 1
    for cid, old, new, quote, url in ROLES:
        c = by[cid]
        adv = c['law']['adv']
        rows = [r for r in adv if r[1] == 'Advance Capital']
        assert len(rows) == 1, cid
        if rows[0][0] == new:
            continue
        assert rows[0][0] == old, (cid, rows[0][0])
        rows[0][0] = new
        fact_edit_guard.log(c, 'law.adv', adv, quote, url, BY, DAY)
        n += 1
    c = by['g399c1f98']
    if not any(r[1] == NIK[1] for r in c['law']['adv']):
        c['law']['adv'].append(list(NIK))
        fact_edit_guard.log(c, 'law.adv', c['law']['adv'], Q_NIK, ADV422, BY, DAY)
        n += 1
    for cid, field, old, new, quote, url in TEXT:
        c = by[cid]
        cur = get(c, field)
        if cur == new:
            continue
        assert cur == old, (cid, field, cur)
        put(c, field, new)
        if field in fact_edit_guard.FACT_FIELDS:
            fact_edit_guard.log(c, field, new, quote, url, BY, DAY)
        n += 1
    return n


def main(write):
    raw = open(DATA, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    n = apply(data)
    if not n:
        print('Уже применено.')
        return 0
    mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
    bad = fact_edit_guard.unbacked(old, data)
    assert not bad, bad
    if not write:
        print('Сухой прогон: %d правок. Запись — с ключом --write.' % n)
        return 0
    fresh_raw = open(DATA, encoding='utf-8').read()      # перечитать прямо перед записью
    fresh = json.loads(fresh_raw)
    apply(fresh)
