# -*- coding: utf-8 -*-
"""Приток, 9 ноября 2026: 93.RU сообщила, что памятник архитектуры на улице
Красной, 166 в Краснодаре (бывшая Екатеринодарская женская учительская
семинария, позже — КубГТУ) — федеральное имущество, администрация Кубани
решила продать его с торгов новому собственнику. Торги назначены на 27
ноября, начальная цена 136,1 млн ₽, заявки принимаются с конца октября.

Заголовок источника («Столетний призрак. Как изнутри выглядит памятник
архитектуры в центре Краснодара, который продают за 136 млн — фото») не
имеет структуры «X продаёт Y» — ворота (draft.py/promote.py) не смогли
вытащить предмет и стороны автоматически (та же картина, что у «Дом.РФ»/
Караул, docs/intake_gates.md, «План министерства продать госпакет —
карточка, собранная вручную»). Собрано вручную — не в базу напрямую (это
было нормой в июле 2026, до второго чтения с 9 октября), а в pending.json,
чтобы карточка прошла обычный путь: accept_card.py -> second_reading.py ->
ship_card.py.

Продавец — федеральное имущество, администрация Кубани выступает лишь
распорядителем решения о продаже; поэтому seller оставлен текстом
"Федеральное имущество (решение о продаже — администрация Кубани)",
профиль компании не заводится (не юрлицо).

Запуск: python3 pipeline/archive/2026-11/add_krasnodar_landmark_card_2026_11_09.py [--write]
"""
import json
import os
import sys
from datetime import datetime, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
INGEST = os.path.join(os.path.dirname(os.path.dirname(HERE)), 'ingest')
if INGEST not in sys.path:
    sys.path.insert(0, INGEST)

SRC = ('93.RU', 'https://93.ru/text/gorod/2026/11/09/76745873/')


def main(write):
    import promote

    pending = promote.load_pending()
    existing_ids = {c['id'] for c in pending['cards']}
    base = json.load(open(promote.DATA, encoding='utf-8'))
    existing_ids |= {c['id'] for c in base['deals']}
    new_id = promote.new_id(existing_ids)

    draft = {
        'date': '2026-11-09',
        'title': 'Памятник архитектуры на Красной в Краснодаре выставили на торги за 136 млн ₽',
        'ind': 'Недвижимость',
        'type': 'Продажа с торгов',
        'status': 'Обсуждается',
        'sum': '136,1 млн ₽',
        'seller': 'Федеральное имущество (решение о продаже — администрация Кубани)',
        'asset': 'Памятник архитектуры на ул. Красной, 166 в Краснодаре (бывшая Екатеринодарская '
                 'женская учительская семинария) с земельным участком в аренду',
        'src': [SRC],
        'events': [
            {'kind': 'negotiations', 'date': '2026-11-09', 'title': 'Торги назначены',
             'note': 'Заявки принимаются с конца октября 2026 года, сами торги — 27 ноября 2026 года.',
             'source': list(SRC)},
        ],
    }
    card = promote.to_card(draft, new_id)
    card['eco']['sum'] = draft['sum']
    card['eco']['context'] = (
        'Здание построено в 1910-1915 годах в стиле раннего модерна по проекту архитектора '
        'Гавриила Никитина — в нем размещалась Екатеринодарская женская учительская семинария, '
        'позже корпус передавали Кубанскому государственному университету и сельхозинституту. '
        'Сейчас здание заброшено: кирпичная кладка разрушается, часть окон отсутствует, внутри '
        'плесень и трещины в коммуникациях, на крыше проросли деревья — по инженерному отчету, '
        'надежность несущих конструкций снижена до недопустимого уровня, и без ремонта зданию '
        'грозит обрушение. Победителю торгов вместе со зданием перейдет в аренду земельный '
        'участок, также находящийся в федеральной собственности; на него ляжет бремя '
        'реставрации.'
    )
    card['themes'] = ['Продажа с торгов', 'Недвижимость']
    card['pending_since'] = datetime.now(timezone.utc).isoformat(timespec='seconds')

    pending['cards'].append(card)
    print('Добавлена карточка %s в pending.json: %s' % (new_id, card['title']))

    if write:
        promote.save_pending(pending)
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main('--write' in sys.argv)
