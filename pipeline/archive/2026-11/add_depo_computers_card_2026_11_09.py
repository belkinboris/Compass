# -*- coding: utf-8 -*-
"""Приток, 9 ноября 2026: CNews сообщила, что DEPO Computers (ООО «ДЕПО
Электроникс») перешел под контроль неизвестной компании — заголовок
источника («Знаменитый российский производитель электроники перешел к
неизвестному владельцу на фоне розыска прежнего собственника») без
структуры «X купил Y»: подлежащее — сам предмет сделки, а не покупатель, и
статья построена вокруг уголовного дела прежнего владельца, а не вокруг
сделки. Ворота (promote.py) такой заголовок не пропускают — тот же класс,
что «План министерства продать госпакет» и «обрезанный заголовок»
(docs/intake_gates.md; образцы ручной сборки — pipeline/archive/2026-11/
add_krasnodar_landmark_card_2026_11_09.py, add_rostov_incineration_plant_
card_2026_11_09.py). В теле статьи сделка названа прямо и подтверждена
реестром, поэтому карточка собирается вручную.

ЧТО ПРОВЕРЕНО. По данным ЕГРЮЛ (пересказанным в статье), 27 октября 2026
года 100% долей ООО «ДЕПО Электроникс» перешли от Сергея Эскина (99%) и
Алексея Ирисова (1%) к ООО «Кванто Спейс» — юрлицу, зарегистрированному
21 июля 2026 года, за несколько месяцев до сделки. CNews называет нового
юридического владельца напрямую (не «неизвестная компания» — это заголовок
о настоящем бенефициаре, который действительно не раскрыт), а заявленную
источником рынка версию о реальном покупателе — ИТ-компании ABR technology
— прямо помечает как неподтвержденную документами. DEPO Computers не
ответили на запрос CNews. WebSearch другими изданиями этого события не
нашел (слишком узкая новость о реестре, без своего инфоповода за пределами
CNews) — дубль не по пропуску, а по отсутствию второго источника на момент
сборки; дубль по базе не найден (`grep -i "depo\|эскин"` по
deals_promoted.json и pending.json — пусто).

ПОЧЕМУ БЕЗ ПРОФИЛЕЙ КОМПАНИЙ. И «ДЕПО Электроникс», и «Кванто Спейс»
называют ровно одно юрлицо — по правилу (docs/card_parties.md,
accept_card.single_legal_entity/single_brand) это обычно повод завести
профиль, а не оставить текстом. ИНН искался: публичный бесплатный поиск
ЕГРЮЛ (`pipeline.fns_unresolved_queue.attempt_public_egrul_match`) из этой
песочницы недоступен — таймаут TLS-хендшейка к egrul.nalog.ru; rusprofile.ru
отдал 403; общий веб-поиск (WebSearch) точных совпадений не нашел — у
«Кванто Спейс» это ожидаемо (компания зарегистрирована 21 июля 2026 года,
агрегаторы ее еще не проиндексировали). Платную квоту api-fns.ru (ключ
`API_FNS_KEY` в этом контейнере есть) сознательно не трогал — она у проекта
ограничена и уже заканчивалась на похожих карточках (см. докстрока
`attempt_public_egrul_match`), и это не моя сессия решает, стоит ли ее
расходовать. Профили и ИНН — задача следующего шага (accept_card.py с
обычным доступом к сети/реестру), не этого скрипта.

Собрано вручную — не в базу напрямую, а в pending.json, чтобы карточка
прошла обычный путь: accept_card.py -> second_reading.py -> ship_card.py.

Запуск: python3 pipeline/archive/2026-11/add_depo_computers_card_2026_11_09.py [--write]
"""
import json
import os
import sys
from datetime import datetime, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
INGEST = os.path.join(os.path.dirname(os.path.dirname(HERE)), 'ingest')
if INGEST not in sys.path:
    sys.path.insert(0, INGEST)

SRC = ('CNews', 'https://www.cnews.ru/news/top/2026-11-09_krupnyj_proizvoditel_elektroniki')

# id зафиксирован константой после первого (сухого) запуска — promote.new_id()
# недетерминирован, и повторный запуск при конфликте ребейза иначе сменил бы
# id карточки (docs/intake_gates.md, «id ручной сборки — константой»,
# случай Экспобанка 11 сентября 2026).
DEAL_ID = 'g09b38753'


def main(write):
    import promote

    pending = promote.load_pending()
    existing_ids = {c['id'] for c in pending['cards']}
    base = json.load(open(promote.DATA, encoding='utf-8'))
    existing_ids |= {c['id'] for c in base['deals']}
    new_id = DEAL_ID if DEAL_ID not in existing_ids else promote.new_id(existing_ids)

    draft = {
        'date': '2026-10-27',
        'title': '«Кванто Спейс» купил производителя электроники DEPO Computers у Сергея Эскина',
        'ind': 'ИТ и интернет',
        'type': 'M&A',
        'status': 'Закрыта',
        'sum': 'Не раскрыта (по оценке аналитиков — не выше 3 млрд ₽)',
        'seller': 'Сергей Эскин и Алексей Ирисов',
        'buyer_name': '«Кванто Спейс»',
        'asset': '100% ООО «ДЕПО Электроникс» (бренд DEPO Computers — серверы, системы хранения '
                 'данных, коммутаторы, рабочие станции, моноблоки, ноутбуки и персональные '
                 'компьютеры)',
        'src': [SRC],
        'events': [
            {'kind': 'closed', 'date': '2026-10-27',
             'title': '100% «ДЕПО Электроникс» перешли к «Кванто Спейс»',
             'note': 'Переход доли зарегистрирован в ЕГРЮЛ 27 октября 2026 года; настоящего '
                     'владельца «Кванто Спейс» источник не раскрывает.',
             'source': list(SRC)},
        ],
    }
    card = promote.to_card(draft, new_id)
    card['eco']['sum'] = draft['sum']
    card['eco']['target_fin'] = (
        'Выручка ООО «ДЕПО Электроникс» за 2025 год — 15 млрд ₽ (+24% к 2024 году), чистая '
        'прибыль — 610,4 млн ₽ (-21% к 2024 году); среднесписочная численность на конец 2025 '
        'года — 461 человек.'
    )
    card['law']['struct'] = (
        'По данным ЕГРЮЛ, 27 октября 2026 года 100% долей ООО «ДЕПО Электроникс» перешли от '
        'прежних владельцев — Сергея Эскина (99%) и Алексея Ирисова (1%) — к ООО «Кванто Спейс», '
        'зарегистрированному 21 июля 2026 года с уставным капиталом 10 тыс. ₽; гендиректор и '
        'единственный совладелец по ЕГРЮЛ — Сергей Стефашин. Ни «Кванто Спейс», ни Стефашин '
        'участникам рынка не известны, реквизиты компании (ИНН) источник не называет. DEPO '
        'Computers не ответили на запрос CNews.'
    )
    card['eco']['context'] = (
        'Источник CNews на рынке называет возможным настоящим покупателем ИТ-компанию ABR '
        'technology (производство в Лобне, выручка за 2025 год 2,2 млрд ₽) — версия не '
        'подтверждена документами, реквизиты ABR technology не раскрыты. Аналитик Strategy '
        'Partners Анна Васильева считает, что покупка может быть инвестицией в готовый бизнес '
        'с инфраструктурой, клиентской базой и брендом, либо интересом к рынку отечественной '
        'вычислительной техники и импортозамещению.\n\n'
        'Сергей Эскин, бывший владелец DEPO Computers, по версии следствия был организатором '
        'схемы и бенефициаром ООО «Антей», которое в 2016 году получило контракт Минобороны на '
        '367,1 млн ₽ на поставку USB-носителей и ноутбуков — вместо заявленной российской '
        'продукции поставили китайскую технику, на которой только гравировали серийные номера '
        'и надписи «МО РФ». В июле 2022 года Эскина заочно арестовали и объявили в '
        'международный розыск, он находится за границей; суд взыскал с фигурантов почти '
        '370 млн ₽ в пользу Минобороны. В октябре 2024 года Эскина и других топ-менеджеров '
        'признали виновными, Эскину назначили 8 лет колонии общего режима.'
    )
    card['themes'] = ['M&A', 'ИТ и интернет']
    card['pending_since'] = datetime.now(timezone.utc).isoformat(timespec='seconds')

    pending['cards'].append(card)
    print('Добавлена карточка %s в pending.json: %s' % (new_id, card['title']))

    if write:
        promote.save_pending(pending)
        print('Записано.')
    else:
        print('(сухой прогон, для записи — --write)')


if __name__ == '__main__':
    main('--write' in sys.argv)
