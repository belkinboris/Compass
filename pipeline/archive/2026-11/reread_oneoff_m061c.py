def apply(data):
    by = {d['id']: d for d in data['deals']}
    for cid, fn in PLAN.items():
        card = by[cid]
        if any(e.get('by') == BY for e in card.get('fact_log') or []):
            continue          # уже применено: повторный запуск ничего не меняет
        fn(card, data['companies'])


