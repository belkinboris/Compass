def get(c, path):
    cur = c
    for p in path.split('.'):
        if isinstance(cur, list) and p.isdigit():
            cur = cur[int(p)] if int(p) < len(cur) else None
        elif isinstance(cur, dict):
            cur = cur.get(p)
        else:
            return None
    return cur


def put(c, path, val):
    parts = path.split('.')
    cur = c
    for p in parts[:-1]:
        cur = cur[int(p)] if isinstance(cur, list) else cur.setdefault(p, {})
    if isinstance(cur, list):
        cur[int(parts[-1])] = val
    else:
        cur[parts[-1]] = val


def same_old(cur, old):
    if isinstance(old, tuple):
        return isinstance(cur, str) and cur.startswith(old[1])
    return cur == old


def apply(data):
    by = {d['id']: d for d in data['deals']}
    n = 0
    for cid, field, old, new, quote, url in SETS:
        c = by[cid]
        cur = get(c, field)
        if cur == new:
            continue
        assert same_old(cur, old), (cid, field, cur)
        if field in ('status', 'seller', 'asset', 'buyer_name') and cur and not isinstance(old, tuple):
            c.setdefault('retracted', {}).setdefault(field, []).append(cur)
        put(c, field, new)
        if field == 'eco.sum' and c.get('sum') is not None:
            c['sum'] = new
            fact_edit_guard.log(c, 'sum', new, quote, url, BY, DAY)
        if field == 'date' and cid in DATE_BASIS:
            c['date_basis'] = DATE_BASIS[cid]
        fact_edit_guard.log(c, field, new, quote, url, BY, DAY)
        n += 1
    for cid, key in DELETE:
        if key in by[cid]:
            val = by[cid].pop(key)
            if key == 'buyer_name' and val:
                by[cid].setdefault('retracted', {}).setdefault(key, []).append(val)
            fact_edit_guard.log(by[cid], key, None, EGRUL_PZ if cid == 'g5745c187' else EGRUL_SM, '', BY, DAY)
            n += 1
    for cid, src in SRC_KEEP.items():
        if by[cid]['src'] != src:
            by[cid]['src'] = src
            n += 1
    for cid, kv in FIXUP.items():
        for path, val in kv.items():
            if get(by[cid], path) != val:
                put(by[cid], path, val)
                n += 1
    comps = data['companies']
    for cid, kv in COMPANY.items():
        for k, v in kv.items():
            cur = comps[cid].get(k)
            if cur == v:
                continue
            old = COMPANY_OLD.get((cid, k))
            assert (cur is None and old is None) or (old is not None and str(cur).startswith(old)), (cid, k, cur)
            comps[cid][k] = v
            n += 1
    return n


def main(write):
    raw = open(DATA, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    n = apply(data)
    if not n:
        print('Уже применено.')
        return 0
    mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
    bad = fact_edit_guard.unbacked(old, data)
    assert not bad, bad
    if not write:
        print('Сухой прогон: %d правок. Запись — с ключом --write.' % n)
        return 0
    fresh_raw = open(DATA, encoding='utf-8').read()
    fresh = json.loads(fresh_raw)
    apply(fresh)
    with open(DATA, 'w', encoding='utf-8') as f:
        f.write(json.dumps(fresh, ensure_ascii=False, indent=1) + ('\n' if fresh_raw.endswith('\n') else ''))
    print('ЗАПИСАНО: %d правок.' % n)
    return 0


if __name__ == '__main__':
    sys.exit(main('--write' in sys.argv))
