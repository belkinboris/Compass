"""Текст новых карточек продаж иностранцев 2022 года (10 ноября 2026) по тестам
базы: орган в «Согласованиях», именительный падеж, без id в тексте, кавычки,
«собеседник» — не наш голос. Без ключа — сухой прогон; --write — запись."""
import json, sys
P = 'static/data/deals_promoted.json'
FIX = [  # id, поле, старое, новое
 ('g0858a500', 'law.appr', 'В «Соллерсе» в ноябре 2022 года сказали, что разрешение на сделку получено; какой орган его выдал, не уточняется.',
  '—'),
 ('g16540a36', 'buyer_name', 'компании Юрье Пенни', 'Юрье Пенни'),
 ('ge5d7cce6', 'eco.context', ' (карточка g83ad1f72).', '.'),
 ('g46b308d6', 'eco.val', 'Собеседники газеты допускали', 'По неофициальным данным, допускалось'),
 ('g660f4097', 'law.struct', 'ООО «АПК «Михайловский» из группы', 'ООО «АПК «Михайловский»» из группы'),
 ('gfb282142', 'law.struct', 'АО «Промышленная компания «Литум».', 'АО «Промышленная компания «Литум»».'),
 ('g070084ad', 'eco.val', 'собеседники ДП не взялись ее оценить, потому что условия неизвестны', 'оценить ее нельзя, потому что условия неизвестны'),
 ('ga024ea1e', 'eco.rationale', 'по словам источника «Коммерсанта»', 'по данным «Коммерсанта»'),
 ('gdc38f29c', 'eco.share', 'Акции АО «ПГ «Метран» (178 + 1 обыкновенная)', 'Акции АО «ПГ «Метран»» (178 + 1 обыкновенная)'),
]
d = json.load(open(P, encoding='utf-8')); n = {x['id']: x for x in d['deals']}
for cid, field, old, new in FIX:
    a, *b = field.split('.')
    obj = n[cid] if not b else n[cid][a]
    k = b[0] if b else a
    assert old in obj[k], (cid, field, obj[k])
    obj[k] = obj[k].replace(old, new)
    print(cid, field, '->', obj[k][:120])
if '--write' in sys.argv:
    json.dump(d, open(P, 'w', encoding='utf-8'), ensure_ascii=False, indent=1); open(P, 'a').write('\n')
    print('записано')
