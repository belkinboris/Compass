def drop_note(card):
    notes = card.get('accepted_notes') or {}
    (notes.get('no_profile') or {}).pop('target', None)
    if notes.get('no_profile') is not None and not notes['no_profile']:
        notes.pop('no_profile')
    card['accepted_notes'] = notes


def apply(data, rows):
    D = {d['id']: d for d in data['deals']}
    C = data['companies']
    MK = data['match_keys']
    have_inn = {r.get('inn') for r in rows if r.get('inn')} | {r.get('inn') for r in fr.REGISTRY if r.get('inn')}
    names = {c['name'] for c in C.values()}
    made = []
    for cid, name, legal, ind, desc, decision, inn, ogrn, regnum, aliases, why in ITEMS:
        card = D[cid]
        if card.get('target'):
            assert C[card['target']]['name'] == name, (cid, card['target'])
            continue
        assert fr.inn_is_valid(inn) and inn not in have_inn and name not in names, (cid, inn, name)
        pid = accept_card._new_profile_id(data, name)
        C[pid] = {'name': name, 'ind': ind, 'desc': desc, 'kpi': [], 'legal_short': legal}
        if aliases:
            MK[pid] = aliases
        row = {'company_id': pid, 'decision': decision, 'inn': inn,
               'reason': 'E13, поиск 7 ноября 2026 (%s): %s Источники: %s.' % (SRC, why, FIVE[inn]), 'date': DAY}
        if regnum:
            row['cbr_regnum'] = regnum
        rows.append(row)
        card['target'] = pid
        drop_note(card)
        made.append((cid, pid, name, inn))
    # Huhtamaki — лот
    cid, name, ind, desc, why = LOT
    card = D[cid]
    if not card.get('target'):
        assert name not in names
        pid = accept_card._new_profile_id(data, name)
        C[pid] = {'name': name, 'ind': ind, 'desc': desc, 'kpi': [], 'lot': True}
        MK[pid] = ['хухтамаки']
        rows.append({'company_id': pid, 'decision': 'lot', 'inn': None,
                     'reason': 'E13, поиск 7 ноября 2026 (%s): %s Источники: %s.' % (SRC, why, FIVE['lot']), 'date': DAY})
        card['target'] = pid
        drop_note(card)
        made.append((cid, pid, name, 'лот'))
    # Sylvamo — профиль комбината уже есть, с тем же ИНН
    card = D['g14acee12']
    reg = {r['company_id']: r for r in rows}
    assert reg[SVETOGORSK]['inn'] == '4704012472'
