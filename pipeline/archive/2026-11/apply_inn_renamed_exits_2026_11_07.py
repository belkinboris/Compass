def main(write):
    raw = open(DATA, encoding='utf-8').read()
    reg_raw = open(REG, encoding='utf-8').read()
    data, old, rows = json.loads(raw), json.loads(raw), json.loads(reg_raw)
    for m in apply(data, rows):
        print('  %s → %s %s (%s)' % m)
    mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return
    assert open(DATA, encoding='utf-8').read() == raw, 'база изменилась во время прогона — перезапустите'
    assert open(REG, encoding='utf-8').read() == reg_raw, 'реестр изменился во время прогона — перезапустите'
    open(DATA, 'w', encoding='utf-8').write(json.dumps(data, ensure_ascii=False, indent=1) + ('\n' if raw.endswith('\n') else ''))
    open(REG, 'w', encoding='utf-8').write(json.dumps(rows, ensure_ascii=False, indent=1) + ('\n' if reg_raw.endswith('\n') else ''))
    print('записано')


