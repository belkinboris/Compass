def _get(card, field):
    if '.' in field:
        a, b = field.split('.', 1)
        return (card.get(a) or {}).get(b)
    return card.get(field)


def _set(card, field, value):
    if '.' in field:
        a, b = field.split('.', 1)
        card.setdefault(a, {})
        if value is DEL:
            card[a].pop(b, None)
        else:
            card[a][b] = value
    elif value is DEL:
        card.pop(field, None)
    else:
        card[field] = value


def apply(data):
    by = {d['id']: d for d in data['deals']}
    n = 0
    for cid, field, old, new, quote, url in EDITS:
        c = by[cid]
        cur = _get(c, field)
        if (new is DEL and cur is None) or (new is not DEL and cur == new):
            continue
        if old is not None:
            assert cur == old, (cid, field, cur)
        if (cid, field) in RETRACT:
            c.setdefault('retracted', {}).setdefault(field, [])
            if RETRACT[(cid, field)] not in c['retracted'][field]:
                c['retracted'][field].append(RETRACT[(cid, field)])
        _set(c, field, new)
        if field in FACT:
            assert quote and url, (cid, field)
            fact_edit_guard.log(c, field, None if new is DEL else new, quote, url, BY, DAY)
        n += 1
    for cid, i, key, value in EVENTS:
        ev = by[cid]['events'][i]
        if ev.get(key) != value:
            ev[key] = value
            n += 1
    # Первоисточник первым: «Коммерсантъ» вперед пересказа «Русского венчура».
    c = by['gcaa03820']
    if c['src'] and c['src'][0][1] != KOM_PSB:
        k = [s for s in c['src'] if s[1] == KOM_PSB]
        assert k, 'нет Коммерсанта в src'
        c['src'] = k + [s for s in c['src'] if s[1] != KOM_PSB]
        n += 1
    for cid, text in NOTES.items():
        notes = by[cid].setdefault('accepted_notes', {})
        np = notes.setdefault('no_profile', {})
        if np.get('seller') != text:
            np['seller'] = text
            n += 1
    return n


def main(write):
    raw = open(DATA, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    n = apply(data)
    if not n:
        print('Уже применено.')
        return 0
    mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
    bad = fact_edit_guard.unbacked(old, data)
    assert not bad, bad
    if not write:
        print('Сухой прогон: %d правок. Запись — с ключом --write.' % n)
        return 0
    fresh_raw = open(DATA, encoding='utf-8').read()
    fresh = json.loads(fresh_raw)
    apply(fresh)
    with open(DATA, 'w', encoding='utf-8') as f:
        f.write(json.dumps(fresh, ensure_ascii=False, indent=1) + ('\n' if fresh_raw.endswith('\n') else ''))
    print('ЗАПИСАНО: %d правок.' % n)
    return 0


if __name__ == '__main__':
    sys.exit(main('--write' in sys.argv[1:]))
