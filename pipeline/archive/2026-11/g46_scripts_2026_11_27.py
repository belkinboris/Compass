def _get(card, field):
    node = card
    for k in field.split('.'):
        if not isinstance(node, dict):
            return None
        node = node.get(k)
    return node


def _put(card, field, value):
    keys = field.split('.')
    node = card
    for k in keys[:-1]:
        node = node.setdefault(k, {})
    if value is None and keys[-1] in node and field in ('buyer_name', 'seller_id', 'buyer', 'target', 'date_basis'):
        node.pop(keys[-1])
    else:
        node[keys[-1]] = value


def setf(card, field, old, new, quote=None, url=None):
    """Поле: assert на старое значение; факт — с цитатой в fact_log."""
    cur = _get(card, field)
    if cur == new:
        return 0
    assert cur == old, (card['id'], field, cur)
    _put(card, field, new)
    if field in fact_edit_guard.FACT_FIELDS and quote:
        fact_edit_guard.log(card, field, new, quote, url, BY, DAY)
        QUOTES.append((card['id'], field, quote))
    CHANGES.append((card['id'], field, old, new))
    TOUCHED.add((card['id'], field))
    return 1


def repl(card, field, old_sub, new_sub):
    """Замена куска прозы: старый кусок ровно один раз."""
    cur = _get(card, field) or ''
    if old_sub not in cur and new_sub in cur:
        return 0
    assert cur.count(old_sub) == 1, (card['id'], field, old_sub[:60])
    _put(card, field, cur.replace(old_sub, new_sub))
    CHANGES.append((card['id'], field, '…' + old_sub, '…' + new_sub))
    TOUCHED.add((card['id'], field))
    return 1


def note_set(card, path, new, expect):
    """Заметка приемки: `expect` — начало прежнего текста (или None — заметки не было)."""
    notes = card.setdefault('accepted_notes', {})
    node = notes
    for k in path[:-1]:
        node = node.setdefault(k, {})
    cur = node.get(path[-1])
    if cur == new:
        return 0
    assert (cur is None) if expect is None else (isinstance(cur, str) and cur.startswith(expect)), (card['id'], path, cur)
    node[path[-1]] = new
    CHANGES.append((card['id'], 'accepted_notes.' + '.'.join(path), cur, new))
    return 1


def note_pop(card, path, expect):
    node = card.get('accepted_notes') or {}
    for k in path[:-1]:
        node = node.get(k) or {}
    cur = node.get(path[-1])
    if cur is None:
        return 0
    assert cur.startswith(expect), (card['id'], path, cur)
    node.pop(path[-1])
    if path[:-1] and not node:
        (card['accepted_notes']).pop(path[0])
    CHANGES.append((card['id'], 'accepted_notes.' + '.'.join(path), cur, None))
    return 1


def add_src(card, label, url):
    if any(s[1] == url for s in card.get('src') or []):
        return 0
    card.setdefault('src', []).append([label, url])
    CHANGES.append((card['id'], 'src', None, [label, url]))
    return 1


def comp_set(data, cid, field, old, new):
    c = data['companies'][cid]
    if c.get(field) == new:
        return 0
    assert c.get(field) == old, (cid, field, c.get(field))
    c[field] = new
    CHANGES.append((cid, 'companies.' + field, old, new))
    return 1


def add_profile(data, cid):
    prof = NEW_PROFILES[cid]
    if cid in data['companies']:
        assert data['companies'][cid]['name'] == prof['name'], cid
        return 0
    names = {(v.get('name') or '').lower() for v in data['companies'].values()}
    assert prof['name'].lower() not in names, prof['name']
    data['companies'][cid] = dict(prof)
    CHANGES.append((cid, 'companies (новый профиль)', None, prof['name']))
    return 1


