def absorb(data):
    D = {d['id']: d for d in data['deals']}
    added = 0
    for cid, field in sorted(set(CHANGED)):
        for f in [f for f in review.FIXES if f['id'] == cid and f['field'] == field]:
            if f.get('new') is None or field == 'src':
                continue
            marks = D[cid].setdefault('proofread_absorbed', {}).setdefault(field, [])
            fp = review.fix_fingerprint(f['new'])
            if fp not in marks and not review.already_applied(f, D[cid], data['companies']):
                marks.append(fp)
                added += 1
    return added


