def registry(svn):
    rows = json.load(open(REG, encoding='utf-8'))
    idx = {r['company_id']: i for i, r in enumerate(rows)}
    tail = {r['company_id'] for r in fr.REGISTRY} - set(idx)

    def edit(cid, old_inn, decision, inn, reason):
        r = rows[idx[cid]]
        if r.get('inn') == inn and r['decision'] == decision:
            return
        assert r.get('inn') == old_inn, (cid, r.get('inn'))
        rows[idx[cid]] = {'company_id': cid, 'decision': decision, 'inn': inn,
                          'reason': reason + ' Прежняя запись (%s): %s' % (r['date'], r['reason']), 'date': DAY}

    def add(cid, inn, reason):
        if cid in idx and rows[idx[cid]].get('inn') == inn:
            return
        assert cid not in idx and cid not in tail, cid
        assert fr.inn_is_valid(inn), inn
        rows.append({'company_id': cid, 'decision': 'confirmed', 'inn': inn, 'reason': reason, 'date': DAY})

