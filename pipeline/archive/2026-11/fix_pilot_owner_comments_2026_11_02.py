import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
BASE = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')
sys.path.insert(0, os.path.join(ROOT, 'pipeline', 'ingest'))
sys.path.insert(0, os.path.join(ROOT, 'pipeline'))
sys.path.insert(0, ROOT)


def put(obj, key, old, new, label):
    """Поле, у которого есть запись FIXES: старое или уже новое (если review.py прошел первым)."""
    assert obj.get(key) in (old, new), (label, obj.get(key))
    obj[key] = new


def rename(comps, cid, old, new):
    assert comps[cid]['name'] in (old, new), (cid, comps[cid]['name'])
    comps[cid]['name'] = new


def legal(comps, cid, old, new):
    assert comps[cid].get('legal_short') in (old, new), (cid, comps[cid].get('legal_short'))
    comps[cid]['legal_short'] = new


def main(argv):
    from review import fix_fingerprint
    raw = open(BASE, encoding='utf-8').read()
    data = json.loads(raw)
    deals = {d['id']: d for d in data['deals']}
    comps = data['companies']
    mk = data['match_keys']

    # --- ПармаВуд
    pv = deals['g1d36d186']
    assert pv.get('target') in (None, 'gfe098d01') and pv.get('asset_id') in ('gfe098d01', None)
    pv['target'] = 'gfe098d01'
    pv.pop('asset_id', None)
    put(pv, 'asset', 'лесозаготовительная компания ПармаВуд', 'ПармаВуд', 'g1d36d186.asset')
    rename(comps, 'gfe098d01', 'ООО ПармаВуд', 'ПармаВуд')
    rename(comps, 'gcdf5803f', 'ООО Лузалес', 'Лузалес')
    # Описание профиля идет в пост строкой «Предмет: …» (format_post): «рубит
    # лес силами подрядчиков» владелец назвал непонятным, а «ее купил …» —
    # действие стороны, check_post такое не пропускает.
    put(comps['gfe098d01'], 'desc',
        'Лесозаготовительная компания: рубит лес на арендованных участках силами подрядчиков. В 2026 году ее купил '
        'Сыктывкарский ЛПК у «Лузалеса».',
        'Лесозаготовительная компания: заготавливает древесину на арендованных лесных участках с помощью '
        'подрядчиков.', 'gfe098d01.desc')
    for cid, alias in (('gfe098d01', 'пармавуд'), ('gcdf5803f', 'лузалес')):
        if alias not in mk.setdefault(cid, []):
            mk[cid].append(alias)

    # --- Урбантех / Нетвижн
    rename(comps, 'g006e1e6c', 'ООО «Нетвижн»', 'Нетвижн')

    # --- Аэрофлот / Директ Стар
    ae = deals['gc9ea6b08']
    put(ae, 'date', '2026', '2026-05-08', 'gc9ea6b08.date')
    ae['date_basis'] = 'registry'
    put(ae['law'], 'struct',
        '«Аэрофлот» стал владельцем 80% ООО «УК Директ Стар», головной компании группы; переход доли отражен в '
        'ЕГРЮЛ в начале мая.',
        '«Аэрофлот» не покупал долю у прежних участников, а вошел в капитал ООО «УК Директ Стар» через его '
        'увеличение и получил 80%. По данным ЕГРЮЛ, номинал доли Екатерины Осиной не изменился, а ее доля '
        'снизилась с 99,9999% до 20%.', 'gc9ea6b08.law.struct')
    note = ae.setdefault('accepted_notes', {}).setdefault('no_profile', {})
    assert str(note.get('seller', '')).startswith('Teleperformance вышла из актива') or \
        str(note.get('seller', '')).startswith('Продавца нет'), note.get('seller')
    note['seller'] = ('Продавца нет: «Аэрофлот» вошел в капитал ООО «УК Директ Стар» через его увеличение — по '
                      'истории участников ЕГРЮЛ (8 мая 2026) номинал доли Екатерины Осиной не изменился, доля '
                      'упала с 99,9999% до 20%; Teleperformance вышла из актива еще в декабре 2025 года')
    rename(comps, 'gf3ed02a1', 'ПАО «Аэрофлот»', 'Аэрофлот')

    # --- Совкомбанк / Капитал МС
    sk = deals['g56d19a38']
    assert sk.get('target') in (None, 'g76cf6406') and sk.get('asset_id') in ('g76cf6406', None)
    sk['target'] = 'g76cf6406'
    sk.pop('asset_id', None)
    rename(comps, 'g76cf6406', 'ООО «Капитал Медицинское Страхование»', 'Капитал МС')
    legal(comps, 'g76cf6406', None, 'ООО «Капитал МС»')
    if 'капитал мс' not in mk.setdefault('g76cf6406', []):
        mk['g76cf6406'].append('капитал мс')
    put(comps['g76cf6406'], 'desc',
        'Второй по числу застрахованных страховщик ОМС: 21,9 млн человек на конец 2025 года. До 2018 года назывался '
        '«РГС-Медицина»; в 2026 году 100% купил Совкомбанк у ООО «Союз» Евгения Гинера.',
        'Второй по числу застрахованных страховщик ОМС: 21,9 млн человек на конец 2025 года. До 2018 года назывался '
        '«РГС-Медицина». Юрлицо — ООО «Капитал Медицинское Страхование» (ОГРН 1027806865481).', 'g76cf6406.desc')
    rename(comps, 'g28372137', '«Союз» (Евгений Гинер)', 'Союз')
    assert comps['g28372137'].get('legal_short') == 'ООО «Союз»'
    rename(comps, 'gb7e1e33a', 'ПАО «Совкомбанк»', 'Совкомбанк')
    adv_old = [['Юридический консультант продавца', 'Delcredere',
                'Продажа 100% доли ООО «Капитал Медицинское Страхование» («Капитал МС») Совкомбанку. Партнер '
                'Марат Агабалян, советник Павел Анненков. Источник: pravo.ru/company_news/263818/']]
    adv_new = [['Юридический консультант продавца', 'Delcredere', 'Партнер Марат Агабалян, советник Павел Анненков']]
    put(sk['law'], 'adv', adv_old, adv_new, 'g56d19a38.law.adv')

    # --- X5 / ВКТ
    x5 = deals['g489b4309']
    put(x5, 'date', '2026-05-04', '2026-05-08', 'g489b4309.date')
    x5['date_basis'] = 'registry'
    put(x5['eco'], 'share', 'Нижегородский дистрибьютор продуктов питания «ВКТ» (ООО «Торговый дом ВКТ»).',
        '100% доли в ООО «Торговый дом ВКТ».', 'g489b4309.eco.share')
    put(x5['law'], 'struct',
        'Покупателем выступило ПАО «Корпоративный центр ИКС 5» (X5). По данным «Контур.Фокуса», учредитель ООО '
        '«Торговый дом ВКТ» — Анна Фомичева.',
        'Сделку объявило ПАО «Корпоративный центр ИКС 5», а 100% ООО «Торговый дом ВКТ» перешли к ООО «ИКС 5 '
        'для бизнеса». Компанию продала ее единственная владелица Анна Фомичева.', 'g489b4309.law.struct')
    legal(comps, 'gddadfff8', 'ПАО «Корпоративный Центр ИКС 5»', 'ПАО «Корпоративный центр ИКС 5»')
    mk['g01a9e264'] = [a for a in mk.get('g01a9e264', [])
                       if a not in ('торговый дом вкт',
                                    'анна фомичева (продавец, владелец 100% долей ооо торговый дом вкт)')]
    assert mk['g01a9e264'] == ['анна фомичева'], mk['g01a9e264']

    # --- Свеза / ЦФУ
    sv = deals['g53bd1536']
    s_old = 'АО «Московский Центр Упаковки» (49%), Ольга Истомина (41%), Антон Русских (10%)'
    put(sv, 'seller', s_old, s_old.replace('Центр Упаковки', 'центр упаковки'), 'g53bd1536.seller')
    seen = sv.setdefault('proofread_absorbed', {}).setdefault('seller', [])
    if fix_fingerprint(s_old) not in seen:      # запись архива 2026-10 на это поле
        seen.append(fix_fingerprint(s_old))
    # Регистр и абзацы review.py не применит: already_applied() сравнивает без
    # учета регистра и пробелов и считает такую запись уже примененной.
    # Поэтому эти три правки — здесь (записи FIXES синхронизированы).
    st = sv['law']['struct']
    assert 'АО «Московский Центр Упаковки»' in st or 'АО «Московский центр упаковки»' in st, st
    sv['law']['struct'] = st.replace('АО «Московский Центр Упаковки»', 'АО «Московский центр упаковки»')
    for cid, cuts in (('g718e3d0e', (' Новые переговоры шли девять месяцев', ' Теперь компания говорит')),
                      ('gb92f7119', (' Прокурор заявил на заседании', ' Адвокат Кира Корума собирается'))):
        ctx = deals[cid]['eco']['context']
        for cut in cuts:
            if ('\n\n' + cut.strip()) in ctx:
                continue                                  # уже разбито на абзацы
            assert ctx.count(cut) == 1, (cid, cut)
            ctx = ctx.replace(cut, '\n\n' + cut.strip(), 1)
        deals[cid]['eco']['context'] = ctx
    rename(comps, 'g83d157e5', 'ООО «Центр фармацевтической упаковки»', 'Центр фармацевтической упаковки')
    legal(comps, 'g83d157e5', 'ООО «ЦФУ»', 'ООО «Центр фармацевтической упаковки»')

    # --- Flowwow / Яндекс
    legal(comps, 'yandex', None, 'МКПАО «Яндекс»')
    rename(comps, 'g578c62cd', 'Flowwow (ООО «ФЛАУВАУ»)', 'Flowwow')
    legal(comps, 'g578c62cd', 'ООО «ФЛАУВАУ»', 'ООО «Флаувау»')

    print('g1d36d186 target/asset/2 профиля; gc9ea6b08 дата, law.struct, заметка, профиль; g56d19a38 target, '
          '3 профиля, law.adv; g489b4309 дата, предмет, law.struct, legal_short, псевдонимы; g53bd1536 продавец, '
          'профиль; g718e3d0e 2 legal_short, профиль; g6663f201 профиль')
    if '--write' not in argv:
        print('Сухой прогон. Запись — с ключом --write.')
        return
    assert open(BASE, encoding='utf-8').read() == raw, 'база изменилась во время прогона — перезапустите'
    out = json.dumps(data, ensure_ascii=False, indent=1) + ('\n' if raw.endswith('\n') else '')
    open(BASE, 'w', encoding='utf-8').write(out)
    print('записано')


if __name__ == '__main__':
    main(sys.argv[1:])
