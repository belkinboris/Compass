def _walk(obj, parts):
    for p in parts:
        obj = obj[int(p)] if isinstance(obj, list) else obj.get(p)
        if obj is None:
            return None
    return obj


def _get(card, field):
    return _walk(card, field.split('.'))


def _set(card, field, value):
    parts = field.split('.')
    obj = card
    for p in parts[:-1]:
        obj = obj[int(p)] if isinstance(obj, list) else obj.setdefault(p, {})
    last = parts[-1]
    if value is DEL:
        obj.pop(last, None)
    elif isinstance(obj, list):
        obj[int(last)] = value
    else:
        obj[last] = value


def apply(data):
    by = {d['id']: d for d in data['deals']}
    n = 0
    for cid, field, old, new, quote, url in _SET:
        c = by[cid]
        base, _, mode = field.partition('@')
        cur = _get(c, base)
        if mode == 'tail':
            if new and cur.endswith(new.strip()) and old not in cur:
                continue
            if not new and old not in cur:
                continue
            assert old in cur, (cid, field)
            value = cur.replace((' ' + old) if (' ' + old) in cur else old, new)
        elif mode == 'head':
            if cur.startswith(new):
                continue
            assert cur.startswith(old), (cid, field, cur[:40])
            value = new + cur[len(old):]
        elif mode == 'insert1':
            if any(s[1] == new[1] for s in cur):
                continue
            value = cur[:1] + [new] + cur[1:]
        else:
            if (new is DEL and cur is None) or cur == new:
                continue
            if old is not None:
                assert cur == old, (cid, field, cur)
            value = new
        _set(c, base, value)
        if base in fact_edit_guard.FACT_FIELDS or base in ('date', 'status'):
            fact_edit_guard.log(c, base, None if value is DEL else value, quote, url, BY, DAY)
        n += 1
    for cid, field, val in _RETRACT:
        r = by[cid].setdefault('retracted', {}).setdefault(field, [])
        if val not in r:
            r.append(val)
            n += 1
    return n


def main(write):
    raw = open(DATA, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    n = apply(data)
    if not n:
        print('Уже применено.')
        return 0
    mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
    bad = fact_edit_guard.unbacked(old, data)
    assert not bad, bad
    if not write:
        print('Сухой прогон: %d правок. Запись — с ключом --write.' % n)
        return 0
    fresh_raw = open(DATA, encoding='utf-8').read()
    fresh = json.loads(fresh_raw)
    apply(fresh)
    with open(DATA, 'w', encoding='utf-8') as f:
        f.write(json.dumps(fresh, ensure_ascii=False, indent=1) + ('\n' if fresh_raw.endswith('\n') else ''))
    print('ЗАПИСАНО: %d правок.' % n)
    return 0


if __name__ == '__main__':
    sys.exit(main('--write' in sys.argv[1:]))
