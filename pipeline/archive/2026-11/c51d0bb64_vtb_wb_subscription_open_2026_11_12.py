"""Карточка `c51d0bb64` («Партнерство Wildberries и ВТБ по развитию WB
Банка») несла только перенос SPO. Сегодняшний приток принес исход:
подписка на допэмиссию фактически открылась (Ведомости, 12.11.2026) —
ворота не связали новость с карточкой (слабое совпадение заголовка:
«ВТБ» + «допэмиссия» совпало с ТГК-1, g3c7dd2e2, не с этой карточкой).
Это НЕ `POSTWORTHY_MILESTONE_KINDS` (сделка не одобрена, не закрыта и не
сорвалась — подписка на SPO самого ВТБ это лишь механика финансирования),
поэтому `review.py --milestone` и отдельный пост не нужны — обычное
дополнение ленты сделки.

Почему не через таблицу FIXES (review.py): events[] — индексированный
путь, который review.py не читает; eco.context — ДОБАВЛЕНИЕ к уже
длинному полю, а check() в review.py валидирует цитатой ВСЕ поле
целиком (числа и 17-словные цепочки из старого текста, обеспеченные
более ранними правками, не лежат в новой цитате) — тот же класс
ограничения, что уже встречался в этом дне (ge31110bc, g1c8087ad).

Источник (дочитан по кэшу data/inbox/raw/2026-11-12-articles.jsonl):
  Ведомости  https://www.vedomosti.ru/investments/news/2026/11/12/1244904-vtb-otkril-podpisku
"""
import json
import os
import sys

ROOT = '/home/user/Compass'
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'c51d0bb64'
VEDOMOSTI = ['Ведомости', 'https://www.vedomosti.ru/investments/news/2026/11/12/1244904-vtb-otkril-podpisku']

OLD_CONTEXT = ('28 августа 2026 года первый зампред ВТБ Дмитрий Пьянов сообщил, что покупка миноритарной доли в WB-банке и финтех-активах перенесена на сентябрь, но параметры допэмиссии под нее принципиально не пересматривались: банк не форсирует сделку, понимая, что управленческие и человеческие ресурсы партнера заняты последствиями чрезвычайных событий. 31 августа 2026 года он уточнил, что допэмиссия пройдет в прежних диапазонах 300–400 млрд рублей, ближе к нижней границе, а участие розничных инвесторов будет скромным из-за разрыва в цене акций. Под вход в WB Банк ВТБ проводит допэмиссию около 500 млрд ₽ — это объем размещения акций самого банка, а не цена партнерства; стоимость доли не раскрыта. 24 сентября 2026 года глава ВТБ Андрей Костин сообщил о новом переносе: «Да, она (допэмиссия — ИФ) перенеслась, но она будет», — сказал он, отвечая на вопрос, перенеслось ли SPO на октябрь. 29 сентября 2026 года Пьянов уточнил: параметры SPO (цена, объем, якорные инвесторы) не меняются, а сделку с RWB банк рассчитывает закрыть «ближе к концу октября». 30 октября 2026 года Пьянов сообщил, что стороны активно готовят договор купли-продажи доли в WB Банке и у них остается немного открытых вопросов — в основном по взаимным гарантиям в самом договоре, и именно его юридическое оформление, а не пересмотр условий сделки, стало причиной новой задержки; по его словам, ВТБ исходит из того, что сделка будет закрыта. Он также назвал точные параметры допэмиссии: до 49% акций ВТБ по цене размещения 87 рублей за акцию, при этом доля государства в банке после SPO останется выше 50%.')

ADDED_CONTEXT = (' 12 ноября 2026 года банк наконец раскрыл окно для действующих акционеров: '
                  'заявления на выкуп новых бумаг принимаются три недели, крайний срок — '
                  '30 ноября; если бы выкупили весь объем, ВТБ получил бы около 547 млрд рублей, '
                  'хотя менеджмент по-прежнему ориентирует на нижнюю часть диапазона.')

NEW_CONTEXT = OLD_CONTEXT + ADDED_CONTEXT

NEW_EVENT = {
    'kind': 'negotiations', 'date': '2026-11-12',
    'title': 'Подписка на допэмиссию открыта',
    'note': ('ВТБ открыл акционерам подписку на допэмиссию, которую с лета несколько раз '
              'откладывал … владельцы акций на 6 июня 2026 г. могут подать заявления и оплатить '
              'новые бумаги с 13 по 30 ноября 2026 г. включительно.'),
    'source': list(VEDOMOSTI),
}


def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    by_id = {d['id']: d for d in data['deals']}
    card = by_id.get(CARD_ID)
    if card is None:
        print('ОТКАЗ: карточки %s нет в базе' % CARD_ID)
        return 1

    assert card['eco']['context'] == OLD_CONTEXT
    assert len(card.get('events', [])) == 3, card.get('events')
    assert card['events'][-1]['date'] == '2026-10-30', card['events'][-1]

    print('ПРАВКА %s' % CARD_ID)
    print('  eco.context : +%r' % ADDED_CONTEXT)
    print('  events      : +negotiations 2026-11-12')
    if not write:
        print('\nСухой прогон. Применение — с ключом --write.')
        return 0

    card['eco']['context'] = NEW_CONTEXT
    card.setdefault('events', []).append(NEW_EVENT)

    fresh = json.load(open(DATA, encoding='utf-8'))
    fresh_by_id = {d['id']: d for d in fresh['deals']}
    fresh_card = fresh_by_id[CARD_ID]
    assert fresh_card['eco']['context'] == OLD_CONTEXT, 'карточку кто-то уже поправил — перечитайте'
    idx = fresh['deals'].index(fresh_card)
    fresh['deals'][idx] = card

    json.dump(fresh, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('\nПрименено.')
    return 0


if __name__ == '__main__':
    sys.exit(main(write='--write' in sys.argv))
