def _get(obj, field):
    for p in field.split('.'):
        obj = obj.get(p) if isinstance(obj, dict) else None
    return obj


def _set(obj, field, value):
    parts = field.split('.')
    for p in parts[:-1]:
        obj = obj.setdefault(p, {})
    obj[parts[-1]] = value


def _apply(data):
    import fact_edit_guard
    deals = {d['id']: d for d in data['deals']}
    done = 0
    for cid, field, old, new, quote, url, _why in ONE_OFF:
        card = deals[cid]
        cur = _get(card, field)
        if cur == new:
            continue                                        # уже применено
        assert cur == old, (cid, field, cur)
        _set(card, field, new)
        fact_edit_guard.log(card, field, new, quote, url, _BY)
        done += 1
    for cid, field, old, new in _SET:
        cur = _get(deals[cid], field)
        if cur == new:
            continue
        assert cur == old, (cid, field, cur)
        _set(deals[cid], field, new)
    for cid, field, value in _RETRACT:
        lst = deals[cid].setdefault('retracted', {}).setdefault(field, [])
        if value not in lst:
            lst.append(value)
    for cid, keys in _POP:
        assert deals[cid].get('seller_id') is None and deals[cid].get('seller') is None, cid
        for k in keys:
            deals[cid].pop(k, None)
    for cid, path, value in _NOTES:
        notes = deals[cid].setdefault('accepted_notes', {})
        if _get(notes, path) == value:
            continue
        assert _get(notes, path) is None, (cid, path, _get(notes, path))
        _set(notes, path, value)
    for comp, field, old, new in _COMPANY:
        c = data['companies'][comp]
        if c.get(field) == new:
            continue
        assert c.get(field) == old, (comp, field, c.get(field))
        c[field] = new
    return done


def _self_check(data):
    """Проза — через те же ворота, что и review.py; заголовок — по стандарту."""
    import prose_gate
    import title_standard
    deals = {d['id']: d for d in data['deals']}
    bad = []
    for cid, field, old, new, quote, url, _why in ONE_OFF:
        if field == 'title':
            card = dict(deals[cid], title=new)
            if title_standard.verb_ok(card) is False:
                bad.append('%s title не по стандарту: %s' % (cid, new))
        elif field in prose_gate.PROSE_WRITTEN and new not in ('—', ''):
            for p in prose_gate.prose_problems(new, quote, field):
                bad.append('%s %s: %s' % (cid, field, p))
    return bad


