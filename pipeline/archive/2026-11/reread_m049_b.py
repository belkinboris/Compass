def _get(obj, field):
    for p in field.split('.'):
        obj = obj.get(p) if isinstance(obj, dict) else None
    return obj


def _set(obj, field, value):
    parts = field.split('.')
    for p in parts[:-1]:
        obj = obj.setdefault(p, {})
    if value is None:
        obj.pop(parts[-1], None)
    else:
        obj[parts[-1]] = value


def _apply(data):
    import fact_edit_guard
    deals = {d['id']: d for d in data['deals']}
    done = 0
    for cid, field, old, new, quote, url in ONE_OFF:
        card = deals[cid]
        cur = _get(card, field)
        if cur == new:
            continue
        assert cur == old, (cid, field, cur)
        _set(card, field, new)
        fact_edit_guard.log(card, field, new, quote, url, _BY)
        done += 1
    for cid, field, old, new in _SET:
        cur = _get(deals[cid], field)
        if cur == new:
            continue
        assert cur == old, (cid, field, cur)
        _set(deals[cid], field, new)
        done += 1
    for cid, url in _SRC_DROP:
        deals[cid]['src'] = [s for s in deals[cid].get('src') or [] if s[1] != url]
    for cid, field, value in _RETRACT:
        lst = deals[cid].setdefault('retracted', {}).setdefault(field, [])
        if value not in lst:
            lst.append(value)
    for cid, path, value in _NOTES:
        notes = deals[cid].setdefault('accepted_notes', {})
        if _get(notes, path) != value:
            _set(notes, path, value)
    for comp, field, old, new in _COMPANY:
        c = data['companies'][comp]
        if c.get(field) == new:
            continue
        assert c.get(field) == old, (comp, field, c.get(field))
        if new is None:
            c.pop(field, None)
        else:
            c[field] = new
    for cid, field, value, quote, url in PARTY_LOG:
        card = deals[cid]
        if not any(r.get('field') == field and r.get('new') == value for r in card.get('fact_log') or []):
            fact_edit_guard.log(card, field, value, quote, url, _BY)
    return done


