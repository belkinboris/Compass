"""Описания профилей после второго чтения приточных карточек 5 ноября 2026.

Что было: у RBE Group описание «эксплуатация коммерческой недвижимости» и отрасль
«Строительство» (по Коммерсанту группа специализируется на корпоративном питании; пост о
покупке рыболовной компании открывался строкой про недвижимость); у «Цифровых привычек» в
описании стояла история pre-IPO 2024 года (описание профиля не должно пересказывать сделку,
и в источниках новой карточки этого нет); у «Сильвер Салмон» город повторялся в строке
«Предмет» поста; у «Простора» в посте не было видно, что компания создана в июле 2026.

Запуск: python3 pipeline/archive/2026-11/fix_profile_descs_intake_2026_11_05.py [--write]
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
BASE = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

EDITS = {
    'gee79811a': {
        'ind': ('Строительство', 'Пищепром и напитки'),
        'desc': ('Группа компаний в сфере эксплуатации и обслуживания коммерческой недвижимости и инфраструктуры.',
                 'Группа компаний, которая специализируется на корпоративном питании. Работает с 2004 года.')},
    'g6017899e': {
        'desc': ('ИТ-группа компаний; в 2024 году провела pre-IPO размещение на 700–1000 млн ₽ при оценке 5–7 млрд ₽. '
                 'Юрлицо — АО «Цифровые привычки».',
                 'ИТ-группа компаний, разработчик собственного программного обеспечения и заказной разработки для '
                 'крупных корпоративных заказчиков. Юрлицо — АО «Цифровые привычки».')},
    'g9e146528': {
        'desc': ('Организатор любительской рыбалки на Камчатке. Компания из Петропавловска-Камчатского: за ней '
                 'закреплены квоты на любительский лов лососевых на реках Камчатка, Воровская, Тихая, Быстрая и Удочка.',
                 'Организатор любительской рыбалки на Камчатке. За ней закреплены квоты на любительский лов лососевых '
                 'на реках Камчатка, Воровская, Тихая, Быстрая и Удочка.')},
    'g3a2c8cb7': {
        'desc': ('Московская компания по управлению недвижимостью. Зарегистрирована в июле 2026 года.',
                 'Созданная в июле 2026 года московская компания по аренде и управлению недвижимостью.')},
}


def main(write):
    raw = open(BASE, encoding='utf-8').read()               # перечитано прямо перед записью
    data = json.loads(raw)
    for cid, fields in EDITS.items():
        for f, (old, new) in fields.items():
            assert data['companies'][cid][f] == old, (cid, f, data['companies'][cid][f])
            data['companies'][cid][f] = new
            print(cid, f, '->', new[:60])
    if write:
        out = json.dumps(data, ensure_ascii=False, indent=1)
        if raw.endswith('\n'):
            out += '\n'
        open(BASE, 'w', encoding='utf-8').write(out)
        print('записано')
    else:
        print('Сухой прогон. Запись — с ключом --write.')


if __name__ == '__main__':
    main('--write' in sys.argv)
