OLD = '\n\n'.join([P1, OLD_P2, OLD_P3])
NEW = '\n\n'.join([P1, NEW_P2, NEW_P3])


def main(write):
    doc = json.load(open(PENDING, encoding='utf-8'))  # перечитываем прямо перед записью
    c = next(x for x in doc['cards'] if x['id'] == CID)
    cur = c['eco']['context']
    if cur == NEW:
        print('уже применено')
        return 0
    assert cur == OLD, cur
    c['eco']['context'] = NEW
    print('eco.context: заменен (%d -> %d знаков)' % (len(OLD), len(NEW)))
    if write:
        s = json.dumps(doc, ensure_ascii=False, indent=1)
        open(PENDING, 'w', encoding='utf-8').write(s)
        print('Записано.')
    else:
        print('Сухой прогон. Запись — с ключом --write.')
    return 0


if __name__ == '__main__':
    sys.exit(main('--write' in sys.argv))
