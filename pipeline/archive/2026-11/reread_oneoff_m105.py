def _set(card, field, value):
    if '.' in field:
        head, tail = field.split('.', 1)
        if value is None:
            (card.get(head) or {}).pop(tail, None)
        else:
            card.setdefault(head, {})[tail] = value
    elif value is None:
        card.pop(field, None)
    else:
        card[field] = value


def _same_old(cur, old):
    if isinstance(old, str) and old.endswith('...'):
        return isinstance(cur, str) and cur.startswith(old[:-3])
    return cur == old


def _mine(cid):
    return cid != COMCITY if PART['cards'] is None else cid in PART['cards']


def apply_profiles(comps, mk):
    n = 0
    for pid, prof in NEW_PROFILES.items():
        if pid not in comps:
            comps[pid] = json.loads(json.dumps(prof))
            mk[pid] = list(NEW_MATCH[pid])
            n += 1
    for pid, field, old, new in PROFILE:
        cur = comps[pid].get(field)
        if cur == new:
            continue
        assert cur == old, (pid, field, cur)
        if new is None:
            comps[pid].pop(field, None)
        else:
            comps[pid][field] = new
        n += 1
    for pid, old, new in MATCH:
        if mk.get(pid) != new:
            assert mk.get(pid) == old, (pid, mk.get(pid))
            mk[pid] = list(new)
            n += 1
    return n


def apply(data):
    by = {d['id']: d for d in data['deals']}
    comps, mk = data['companies'], data.setdefault('match_keys', {})
    n = apply_profiles(comps, mk) if PART['first'] else 0
    for cid, field, old, new, quote, url in CARD:
        if not _mine(cid):
            continue
        c = by[cid]
        cur = fact_edit_guard.get(c, field)
        if new == 'PREPEND':
            new = C_LOGO + (cur[len(C_LOGO):] if cur.startswith(C_LOGO) else cur)
        elif new == 'APPEND':
            new = cur if cur.endswith(S_VG) else cur + S_VG
        if cur == new:
            continue
        assert _same_old(cur, old), (cid, field, cur)
        _set(c, field, new)
        if isinstance(cur, str) and (field == 'title' or field.startswith(('eco.', 'law.', 'extra'))):
            fp = review.fix_fingerprint(cur)
            box = c.setdefault('proofread_absorbed', {}).setdefault(field, [])
            if fp not in box:
                box.append(fp)
        if field in FACT:
            fact_edit_guard.log(c, field, new, quote, url, BY, DAY)
        n += 1
    for cid, field, old in RETRACT:
        if not _mine(cid):
            continue
        box = by[cid].setdefault('retracted', {}).setdefault(field, [])
        if old not in box:
            box.append(old)
            n += 1
    if _mine(COMCITY):
        c = by[COMCITY]
        if RIA in c['src']:
            c['src'] = [s for s in c['src'] if s != RIA]
            n += 1
    for cid, (group, key, text) in NOTES.items():
        if not _mine(cid):
            continue
        box = by[cid].setdefault('accepted_notes', {}).setdefault(group, {})
        if box.get(key) != text:
            box[key] = text
            n += 1
    for cid, (role, value, url) in PARTY_EVIDENCE.items():
        if not _mine(cid):
            continue
        ev = by[cid].setdefault('party_evidence', {})
        row = {'value': value, 'method': 'registry_owner_history', 'url': url}
        if ev.get(role) != [row]:
            ev[role] = [row]
            n += 1
    return n


def apply_reg(rows):
    if not PART['first']:
        return 0
    n = 0
    have = {r.get('company_id'): r for r in rows}
    for row in REG_NEW:
        if row['company_id'] not in have:
            rows.append(dict(row))
            n += 1
    for pid, upd in REG_EDIT.items():
        r = have[pid]
        if any(r.get(k) != v for k, v in upd.items()):
            for k, v in upd.items():
                if v is None:
                    r.pop(k, None)
                else:
                    r[k] = v
            n += 1
    return n


