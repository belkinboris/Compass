def get(card, field):
    cur = card
    for k in field.split('.'):
        if not isinstance(cur, dict):
            return None
        cur = cur.get(k)
    return cur


def put(card, field, value):
    keys = field.split('.')
    cur = card
    for k in keys[:-1]:
        cur = cur.setdefault(k, {})
    if value is None:
        cur.pop(keys[-1], None)
    else:
        cur[keys[-1]] = value


def absorb(card, field, new):
    """Запись FIXES на это поле, применявшаяся раньше: ее отпечаток — в proofread_absorbed,
    чтобы таблица считала ее примененной (docs/card_editing.md, «Правка поля мимо таблицы»)."""
    import review
    for fx in review.FIXES:
        if fx.get('id') != card['id'] or fx.get('field') != field or fx.get('new') in (None, new):
            continue
        if isinstance(fx['new'], (list, dict)):
            continue
        fp = review.fix_fingerprint(fx['new'])
        lst = card.setdefault('proofread_absorbed', {}).setdefault(field, [])
        if fp not in lst:
            lst.append(fp)


def apply(data, verbose=False):
    by = {d['id']: d for d in data['deals']}
    done = skipped = 0
    for e in EDITS:
        card = by[e['id']]
        cur = get(card, e['field'])
        if cur == e['new']:
            skipped += 1
            continue
        assert cur == e['old'], '%s %s: в базе %r, ожидали %r' % (e['id'], e['field'], cur, e['old'])
        put(card, e['field'], e['new'])
        absorb(card, e['field'], e['new'])
        if e['field'] in FACT:
            fact_edit_guard.log(card, e['field'], e['new'], e['quote'], e['url'], BY, DAY)
        done += 1
        if verbose:
            print('%s %s: %r → %r' % (e['id'], e['field'], str(cur)[:70], str(e['new'])[:70]))
    for did, field, old_sub, new_sub in REPLACE:
        card = by[did]
        cur = get(card, field) or ''
        if old_sub is None:
            if cur.endswith(new_sub):
                skipped += 1
                continue
            new = cur + new_sub
        else:
            if old_sub not in cur:
                assert new_sub and new_sub in cur, '%s %s: нет ни старого, ни нового куска' % (did, field)
                skipped += 1
                continue
            new = cur.replace(old_sub, new_sub)
        put(card, field, new)
        absorb(card, field, new)
        done += 1
        if verbose:
            print('%s %s: правка куска текста' % (did, field))
    for cid, key, new in COMPANY:
        comp = data['companies'][cid]
        if comp.get(key) == new:
            skipped += 1
            continue
        comp[key] = new
        done += 1
        if verbose:
            print('профиль %s.%s → %r' % (cid, key, new[:70]))
    for did, label, url in SRC:
        card = by[did]
        if any(u == url for _l, u in card.get('src') or []):
            continue
        card.setdefault('src', []).append([label, url])
        done += 1
    for did, path, value in NOTES:
        card = by[did]
        if get(card, 'accepted_notes.' + path) == value:
            continue
        put(card, 'accepted_notes.' + path, value)
        done += 1
    for did, field, value in RETRACT:
        lst = by[did].setdefault('retracted', {}).setdefault(field, [])
        if value not in lst:
            lst.append(value)
    return done, skipped


def apply_fns(write):
    path = os.path.join(ROOT, 'pipeline', 'fns_registry.json')
    reg = json.load(open(path, encoding='utf-8'))
    n = 0
    for cid, old, new, reason in FNS:
        for row in reg:
            if row.get('company_id') == cid and row.get('decision') == old:
                row['decision'], row['reason'], row['date'] = new, reason, DAY
                row.pop('inn', None)
                n += 1
    if n and write:
        with open(path, 'w', encoding='utf-8') as fh:
            json.dump(reg, fh, ensure_ascii=False, indent=1)
            fh.write('\n')
    print('реестр ИНН: правок %d' % n)


def main(write):
    raw = open(DATA, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    done, skipped = apply(data, verbose=True)
    print('правок: %d, уже применено: %d' % (done, skipped))
    mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
    if not write:
        apply_fns(False)
        print('Сухой прогон. Запись — с ключом --write.')
        return 0
    apply_fns(True)
    if not done:
        print('Все уже применено.')
        rebaseline(json.loads(raw))
        return 0
    fresh_raw = open(DATA, encoding='utf-8').read()
    fresh = json.loads(fresh_raw)
    apply(fresh)
    with open(DATA, 'w', encoding='utf-8') as f:
        f.write(json.dumps(fresh, ensure_ascii=False, indent=1) + ('\n' if fresh_raw.endswith('\n') else ''))
    print('ЗАПИСАНО.')
    rebaseline(fresh)
    return 0


def rebaseline(data):
    """Исправленные старые нарушения правил текста уходят из text_rules_baseline.json (только карточки партии)."""
    import text_rules
    ids = {e['id'] for e in EDITS} | {r[0] for r in REPLACE}
    known = json.load(open(text_rules.BASELINE, encoding='utf-8'))
    now = {f[0] for f in text_rules.all_findings({'deals': [d for d in data['deals'] if d['id'] in ids]})}
    left = [fp for fp in known['known'] if fp.split('|')[0] not in ids or fp in now]
    if len(left) != len(known['known']):
        print('из списка старых нарушений убрано: %d' % (len(known['known']) - len(left)))
        known['known'] = left
        with open(text_rules.BASELINE, 'w', encoding='utf-8') as fh:
            json.dump(known, fh, ensure_ascii=False, indent=1)


