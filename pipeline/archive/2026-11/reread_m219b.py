def _get(obj, path):
    cur = obj
    for p in path:
        if isinstance(cur, list):
            cur = cur[int(p)]
        elif isinstance(cur, dict):
            if p not in cur:
                return _MISSING
            cur = cur[p]
        else:
            return _MISSING
    return cur


def _set(obj, path, value):
    cur = obj
    for p in path[:-1]:
        cur = cur[int(p)] if isinstance(cur, list) else cur.setdefault(p, {})
    last = path[-1]
    if value == _MISSING:
        if isinstance(cur, dict):
            cur.pop(last, None)
    elif isinstance(cur, list):
        cur[int(last)] = value
    else:
        cur[last] = value


def apply(data):
    by = {d['id']: d for d in data['deals']}
    comps = data['companies']
    n = 0
    for e in EDITS:
        if e['id'].startswith('C:'):
            root, path, card = comps[e['id'][2:]], e['field'].split('.'), None
        else:
            card = by[e['id']]
            root, path = card, e['field'].split('.')
        cur = _get(root, path)
        if cur == e['new']:
            continue
        assert cur == e['old'], (e['id'], e['field'], cur)
        _set(root, path, e['new'])
        if card is not None:
            if e.get('retract') and e['old'] not in (None, _MISSING, '', '—'):
                lst = card.setdefault('retracted', {}).setdefault(e['field'].split('.')[-1], [])
                if e['old'] not in lst:
                    lst.append(e['old'])
            if e['field'] in fact_edit_guard.FACT_FIELDS:
                nv = None if e['new'] == _MISSING else e['new']
                fact_edit_guard.log(card, e['field'], nv, e['quote'], e.get('url', ''), BY, DAY)
        n += 1
    return n


def drop_baseline(data):
    # Исправленные нарушения правил текста уходят из списка старых (text_rules_baseline.json),
    # только по карточкам этого скрипта и только если нарушения больше нет.
    sys.path.insert(0, ROOT)
    from pipeline import text_rules
    ids = {e['id'] for e in EDITS}
    now = {f[0] for f in text_rules.all_findings(data)}
    known = json.load(open(text_rules.BASELINE, encoding='utf-8'))
    left = [fp for fp in known['known'] if fp in now or fp.split('|')[0] not in ids]
    if len(left) != len(known['known']):
        known['known'] = left
        with open(text_rules.BASELINE, 'w', encoding='utf-8') as fh:
            json.dump(known, fh, ensure_ascii=False, indent=1)


def main(write):
    raw = open(DATA, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    n = apply(data)
    if not n:
        print('Уже применено.')
        return 0
    mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
    bad = fact_edit_guard.unbacked(old, data)
    assert not bad, bad
    if not write:
        print('Сухой прогон: %d правок. Запись — с ключом --write.' % n)
        return 0
    fresh_raw = open(DATA, encoding='utf-8').read()
    fresh = json.loads(fresh_raw)
    apply(fresh)
    with open(DATA, 'w', encoding='utf-8') as f:
        f.write(json.dumps(fresh, ensure_ascii=False, indent=1) + ('\n' if fresh_raw.endswith('\n') else ''))
    drop_baseline(fresh)
    print('ЗАПИСАНО: %d правок.' % n)
    return 0


if __name__ == '__main__':
    sys.exit(main('--write' in sys.argv[1:]))
