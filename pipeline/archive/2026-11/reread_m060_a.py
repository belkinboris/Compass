ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
DATA = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')
BY = 'вычитка 12 ноября 2026, партия m060'


def _get(o, field):
    for p in field.split('.'):
        o = o.get(p) if isinstance(o, dict) else None
    return o


def _set(o, field, value):
    parts = field.split('.')
    for p in parts[:-1]:
        o = o.setdefault(p, {})
    if value is None:
        o.pop(parts[-1], None)
    else:
        o[parts[-1]] = value


def company_id(name):
    return 'g' + hashlib.md5(('m060 ' + name).encode('utf-8')).hexdigest()[:8]


def _absorb(card, field):
    """Поле, у которого есть запись таблицы правок, правится мимо таблицы: отпечаток прежнего `new`
    кладется в proofread_absorbed (docs/card_editing.md, «Правка поля мимо таблицы»)."""
    sys.path.insert(0, os.path.join(ROOT, 'pipeline', 'ingest'))
    import review
    for r in review.FIXES:
        if r.get('id') == card['id'] and r.get('field') == field and r.get('new') is not None \
                and field != 'src':
            fp = review.fix_fingerprint(r['new'])
            lst = card.setdefault('proofread_absorbed', {}).setdefault(field, [])
            if fp not in lst:
                lst.append(fp)


def apply(data):
    sys.path.insert(0, os.path.join(ROOT, 'pipeline'))
    import fact_edit_guard
    deals = {d['id']: d for d in data['deals']}
    comps = data['companies']
    n = 0
    for key, prof in NEW_COMPANIES.items():
        cid = company_id(key)
        if cid in comps:
            continue
        comps[cid] = dict(prof)
        n += 1
    for cid, field, old, new in COMPANY_EDITS:
        c = comps[cid]
        if _get(c, field) == new:
            continue
        assert _get(c, field) == old, (cid, field, _get(c, field))
        _set(c, field, new)
        n += 1
    for row in EDITS:
        cid, field, old, new = row[:4]
        quote, url = (row[4], row[5]) if len(row) > 4 else (None, None)
        if isinstance(new, str) and new.startswith('@company:'):
            new = company_id(new[9:])
        if isinstance(old, str) and old.startswith('@company:'):
            old = company_id(old[9:])
        card = deals[cid]
        cur = _get(card, field)
        if cur == new:
            continue
        assert cur == old, (cid, field, cur)
        _set(card, field, new)
        _absorb(card, field)
        if quote:
            fact_edit_guard.log(card, field, new, quote, url, BY, date='2026-11-12')
        n += 1
    for cid, label, url in SRC_ADD:
        src = deals[cid].setdefault('src', [])
        if url not in [u for _l, u in src]:
            src.append([label, url])
            n += 1
    for cid, field, value in RETRACT:
        lst = deals[cid].setdefault('retracted', {}).setdefault(field, [])
        if value not in lst:
            lst.append(value)
            n += 1
    for cid, notes in NOTES.items():
        acc = deals[cid].setdefault('accepted_notes', {})
        for k, v in notes.items():
            if isinstance(v, dict):
                if any(acc.get(k, {}).get(a) != b for a, b in v.items()):
                    acc.setdefault(k, {}).update(v)
                    n += 1
            elif acc.get(k) != v:
                acc[k] = v
                n += 1
    return n


