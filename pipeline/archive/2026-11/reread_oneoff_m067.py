def get(c, f):
    if '.' in f:
        a, b = f.split('.', 1)
        return (c.get(a) or {}).get(b)
    return c.get(f)


def put(c, f, v):
    if '.' in f:
        a, b = f.split('.', 1)
        c.setdefault(a, {})[b] = v
    else:
        c[f] = v


def main(write):
    import fact_edit_guard, mass_edit_guard
    sys.path.insert(0, os.path.join(ROOT, 'pipeline', 'ingest'))
    global review
    import review
    d = json.load(open(DATA, encoding='utf-8'))   # перечитываем прямо перед записью
    old = copy.deepcopy(d)
    by = {x['id']: x for x in d['deals']}
    n = 0
    for row in DEAL:
        cid, f, a, b, q, url = row[:6]
        c = by[cid]
        cur = get(c, f)
        if cur == b:
            print('уже применено', cid, f)
            continue
        assert cur == a, (cid, f, cur)
        put(c, f, b)
        if f == 'date':
            for e in c.get('events') or []:
                if e.get('date') == a:
                    e['date'] = b
        if q:
            fact_edit_guard.log(c, f, b, q, url, BY)
        if len(row) > 6 and row[6]:
            # у поля есть запись FIXES в старом (чужом) файле партии: ее new больше не совпадет,
            # отпечаток — в proofread_absorbed, чтобы already_applied() считала ее примененной
            fp = review.fix_fingerprint(row[6])
            lst = c.setdefault('proofread_absorbed', {}).setdefault(f, [])
            if fp not in lst:
                lst.append(fp)
        if f in ('sum', 'seller', 'buyer_name', 'asset') and a not in (None, '', '—', 'Не раскрыта'):
            r = c.setdefault('retracted', {}).setdefault(f, [])
            if a not in r:
                r.append(a)
        print(cid, f, repr(a)[:60], '→', repr(b)[:60])
        n += 1
    for pid, f, a, b in COMP:
        p = d['companies'][pid]
        if p.get(f) == b and (b is not None or f not in p):
            print('уже применено', pid, f)
            continue
        assert p.get(f) == a, (pid, f, p.get(f))
        if b is None:
            p.pop(f, None)
        else:
            p[f] = b
        print(pid, f, repr(a)[:60], '→', repr(b)[:60])
        n += 1
    mass_edit_guard.check(old, d, os.environ.get('MASS_OK'))
    if write and n:
        with open(DATA, 'w', encoding='utf-8') as fh:
            json.dump(d, fh, ensure_ascii=False, indent=1)
        print('записано правок:', n)
    elif not write:
        print('сухой прогон, правок:', n)


if __name__ == '__main__':
    main('--write' in sys.argv)
