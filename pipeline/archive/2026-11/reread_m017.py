def get(obj, path):
    for p in path.split('.')[:-1]:
        obj = obj.setdefault(p, {})
    return obj, path.split('.')[-1]


def apply(data):
    by = {d['id']: d for d in data['deals']}
    done = skipped = 0
    for cid, field, old, new, quote, url in EDITS:
        c = by[cid]
        if field.startswith('company:'):
            coid, key = field[len('company:'):].split('.')
            holder, k = data['companies'][coid], key
        else:
            holder, k = get(c, field)
        cur = holder.get(k)
        if cur == new:
            skipped += 1
            continue
        if old is not None:
            assert cur == old, (cid, field, cur)
        holder[k] = new
        if field == 'eco.share' or field == 'sum':
            pass
        if not field.startswith('company:'):
            fact_edit_guard.log(c, field, new, quote, url, BY, DAY)
        if field == 'seller' and cid in SELLER_IDS:
            c['seller_id'] = SELLER_IDS[cid]
            fact_edit_guard.log(c, 'seller_id', SELLER_IDS[cid], quote, url, BY, DAY)
        done += 1
    for coid, ls in LEGAL.items():
        if not data['companies'][coid].get('legal_short'):
            data['companies'][coid]['legal_short'] = ls
            done += 1
    return done, skipped


def main(write):
    raw = open(DATA, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    done, skipped = apply(data)
    mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
    bad = fact_edit_guard.unbacked(old, data)
    assert not bad, bad
    if not write:
        print('Сухой прогон: правок %d, уже применено %d. Запись — с ключом --write.' % (done, skipped))
        return 0
    fresh_raw = open(DATA, encoding='utf-8').read()
    fresh = json.loads(fresh_raw)
    done, skipped = apply(fresh)
    if not done:
        print('Уже применено.')
        return 0
    with open(DATA, 'w', encoding='utf-8') as f:
        f.write(json.dumps(fresh, ensure_ascii=False, indent=1) + ('\n' if fresh_raw.endswith('\n') else ''))
    print('ЗАПИСАНО: %d правок.' % done)
    return 0


if __name__ == '__main__':
    sys.exit(main('--write' in sys.argv[1:]))
