def _get(obj, field):
    for p in field.split('.'):
        obj = obj.get(p) if isinstance(obj, dict) else None
    return obj


def _set(obj, field, value):
    parts = field.split('.')
    for p in parts[:-1]:
        obj = obj.setdefault(p, {})
    obj[parts[-1]] = value


def _apply(data, log):
    import review
    deals = {d['id']: d for d in data['deals']}
    comps = data['companies']
    for op in OPS:
        kind = op['op']
        card = deals.get(op.get('id')) if op.get('id') else None
        if kind == 'set':
            cur = _get(card, op['field'])
            assert cur == op['old'], (op['id'], op['field'], cur)
            _set(card, op['field'], op['new'])
            # Записи FIXES этого поля переписаны здесь — их отпечатки в proofread_absorbed.
            for f in review.FIXES:
                if (f['id'], f['field']) != (op['id'], op['field']) or f['new'] is None or f['new'] == op['new']:
                    continue
                marks = card.setdefault('proofread_absorbed', {}).setdefault(op['field'], [])
                fp = review.fix_fingerprint(f['new'])
                if fp not in marks:
                    marks.append(fp)
            log.append('%s %s' % (op['id'], op['field']))
        elif kind == 'src_add':
            assert not any(len(s) > 1 and s[1] == op['new'][1] for s in card['src']), (op['id'], op['new'])
            card['src'].append(op['new'])
            log.append('%s src + %s' % (op['id'], op['new'][1]))
        elif kind == 'evidence':
            card.setdefault('party_evidence', {})[op['role']] = op['new']
            log.append('%s party_evidence.%s' % (op['id'], op['role']))
        elif kind == 'retract':
            lst = card.setdefault('retracted', {}).setdefault(op['field'], [])
            for v in op['new']:
                if v not in lst:
                    lst.append(v)
            log.append('%s retracted.%s' % (op['id'], op['field']))
        elif kind == 'company':
            prof = comps[op['pid']]
            assert prof.get(op['field']) == op['old'], (op['pid'], op['field'], prof.get(op['field']))
            prof[op['field']] = op['new']
            log.append('профиль %s %s = %s' % (op['pid'], op['field'], op['new']))
        elif kind == 'event':
            ev = card['events'][op['index']]
            assert all(ev.get(k) == v for k, v in op['old'].items()), (op['id'], ev)
            ev.update(op['new'])
            log.append('%s events[%d]' % (op['id'], op['index']))
        else:
            raise AssertionError('неизвестная операция %r' % kind)


