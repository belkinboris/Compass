def apply(data, report=None):
    import review
    by = {d['id']: d for d in data['deals']}
    comps = data['companies']
    table = {}
    for fx in review.load_fixes():
        table.setdefault((fx['id'], fx['field']), []).append(fx)
    done = skipped = 0
    for op in OPS:
        card = by[op['id']]
        cur = review.get_field(card, op['field'])
        if cur == op['new']:
            skipped += 1
            continue
        assert cur == op['old'], (op['id'], op['field'], cur, op['old'])
        review.set_field(card, op['field'], op['new'])
        for fx in table.get((op['id'], op['field']), []):
            if fx.get('new') is not None:
                absorbed = card.setdefault('proofread_absorbed', {}).setdefault(op['field'], [])
                fp = review.fix_fingerprint(fx['new'])
                if fp not in absorbed:
                    absorbed.append(fp)
        if op['field'] in fact_edit_guard.FACT_FIELDS:
            fact_edit_guard.log(card, op['field'], op['new'], op['quote'].replace('ё', 'е').replace('Ё', 'Е'), op['url'], BY, DAY)
        done += 1
    for r in REPLACE:
        card = by[r['id']]
        cur = review.get_field(card, r['field'])
        if r['new'] in cur and r['old'] not in cur:
            skipped += 1
            continue
        assert cur.count(r['old']) == 1, (r['id'], r['field'])
        review.set_field(card, r['field'], cur.replace(r['old'], r['new']))
        done += 1
    for p in PROFILES:
        prof = comps[p['pid']]
        if prof.get(p['key']) == p['new'] or (p['key'] == 'legal_short' and prof.get('legal_short')):
            skipped += 1
            continue
        assert prof.get(p['key']) == p['old'], (p['pid'], p['key'], prof.get(p['key']))
        prof[p['key']] = p['new']
        done += 1
    for cid, field, value in RETRACT:
        lst = by[cid].setdefault('retracted', {}).setdefault(field, [])
        if value not in lst:
            lst.append(value)
    for cid, role, note in NOTES:
        by[cid].setdefault('accepted_notes', {}).setdefault('no_profile', {})[role] = note
    for s in ADD_SRC:
        card = by[s['id']]
        if not any(u == s['src'][1] for _l, u in card.get('src') or []):
            card.setdefault('src', []).append(list(s['src']))
    for cid, url in DEAD_SRC:
        card = by[cid]
        card['src'] = [x for x in card.get('src') or [] if x[1] != url]
    if report is not None:
        report.append((done, skipped))
    return data


def self_check():
    """Цитата каждой правки лежит в сохраненном тексте источника; проза проходит правила записи."""
    import review
    ft = [review.flat(x) for x in review.source_texts()]
    big = '\x00'.join(ft)

    class _Q:
        @staticmethod
        def real(q):
            parts = [p for p in review.QUOTE_SEP.split(str(q or '')) if p.strip()] or [q]
            return all(review.flat(p) in big for p in parts)
    bad = []
    for op in OPS + REPLACE:
        if not _Q.real(op['quote']):
            bad.append('%s %s: цитаты нет в тексте источника' % (op['id'], op['field']))
        if op['field'] in review.PROSE_WRITTEN and isinstance(op['new'], str) and op['new'] not in ('—', '') \
                and op in OPS:
            for p in review.prose_problems(op['new'], op['quote']):
                bad.append('%s %s: %s' % (op['id'], op['field'], p))
    for s in ADD_SRC:
        if not _Q.real(s['quote']):
            bad.append('%s src: цитаты нет' % s['id'])
    return bad


def main(write):
    raw = open(DATA, encoding='utf-8').read()
    old = json.loads(raw)
    rep = []
    new = apply(json.loads(raw), rep)
    print('правок: %d, уже применено: %d' % rep[0])
    if rep[0][0]:
        bad = self_check()
        for b in bad:
            print('  ОТКАЗ', b)
        assert not bad, 'есть отказы'
