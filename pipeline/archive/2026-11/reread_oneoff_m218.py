def _locate(data, cid, path):
    if path.startswith('company:'):
        cc, f = path[8:].split('.', 1)
        obj, parts = data['companies'][cc], f.split('.')
    else:
        obj, parts = next(d for d in data['deals'] if d['id'] == cid), path.split('.')
    for p in parts[:-1]:
        if isinstance(obj, list):
            obj = obj[int(p)]
        else:
            obj = obj.setdefault(p, {})
    return obj, parts[-1]


def _get(obj, key):
    if isinstance(obj, list):
        return obj[int(key)]
    return obj.get(key, MISSING)


def apply(data):
    by = {d['id']: d for d in data['deals']}
    n = 0
    for e in EDITS:
        obj, key = _locate(data, e['id'], e['f'])
        if e.get('op') == 'append':
            lst = obj.setdefault(key, [])
            if e['new'] in lst:
                continue
            lst.append(e['new'])
            n += 1
            continue
        cur = _get(obj, key)
        if cur == e['new']:
            continue
        assert cur == e['old'], (e['id'], e['f'], cur)
        if e['new'] == MISSING:
            del obj[key]
        elif isinstance(obj, list):
            obj[int(key)] = e['new']
        else:
            obj[key] = e['new']
        if not e['f'].startswith('company:') and e['f'] in fact_edit_guard.FACT_FIELDS:
            fact_edit_guard.log(by[e['id']], e['f'], None if e['new'] == MISSING else e['new'],
                                e.get('quote') or '', e.get('url') or '', BY, DAY)
        n += 1
    return n


def main(write):
    raw = open(DATA, encoding='utf-8').read()
    old, data = json.loads(raw), json.loads(raw)
    n = apply(data)
    if not n:
        print('Уже применено.')
        return 0
    mass_edit_guard.check(old, data, os.environ.get('MASS_OK'))
    bad = fact_edit_guard.unbacked(old, data)
    assert not bad, bad
    if not write:
        print('Сухой прогон: %d правок. Запись — с ключом --write.' % n)
        return 0
    fresh_raw = open(DATA, encoding='utf-8').read()
    fresh = json.loads(fresh_raw)
    apply(fresh)
    with open(DATA, 'w', encoding='utf-8') as f:
        f.write(json.dumps(fresh, ensure_ascii=False, indent=1) + ('\n' if fresh_raw.endswith('\n') else ''))
    print('ЗАПИСАНО: %d правок.' % n)
    return 0


if __name__ == '__main__':
    sys.exit(main('--write' in sys.argv))
