def _walk(obj, parts):
    for p in parts:
        obj = obj.get(p, MISSING) if isinstance(obj, dict) else MISSING
    return obj


def _set(obj, field, value):
    parts = field.split('.')
    for p in parts[:-1]:
        obj = obj.setdefault(p, {})
    if value is MISSING:
        obj.pop(parts[-1], None)
    else:
        obj[parts[-1]] = value


def _apply(data, log):
    from fact_edit_guard import log as fact_log
    deals = {d['id']: d for d in data['deals']}
    comps = data['companies']
    def _res(v):
        if isinstance(v, str) and v.startswith('@newco:'):
            name = v[7:]
            hit = [k for k, c in comps.items() if c.get('name') == name]
            assert len(hit) == 1, (name, hit)
            return hit[0]
        return v
    for op in OPS:
        kind = op['op']
        if kind == 'registry':
            continue
        if kind == 'newco':
            if any(c.get('name') == op['name'] for c in comps.values()):
                log.append('уже применено: профиль %s' % op['name'])
                continue
            sys.path.insert(0, os.path.join(ROOT, 'pipeline', 'ingest'))
            from accept_card import _new_profile_id
            cid = _new_profile_id(data, op['name'])
            comps[cid] = {'name': op['name'], 'ind': op['ind'], 'desc': op['desc'], 'kpi': [],
                          'legal_short': op['legal_short']}
            data.setdefault('match_keys', {})[cid] = list(op['keys'])
            log.append('новый профиль %s %s' % (cid, op['name']))
            continue
        op = dict(op, new=_res(op.get('new')))
        if kind == 'company':
            prof = comps[op['cid']]
            cur = prof.get(op['field'], MISSING)
            if cur == op['new']:
                log.append('уже применено: профиль %s %s' % (op['cid'], op['field']))
                continue
            assert cur == op['old'], (op['cid'], op['field'], cur)
            prof[op['field']] = op['new']
            log.append('профиль %s %s' % (op['cid'], op['field']))
            continue
        card = deals[op['id']]
        if kind == 'set':
            cur = _walk(card, op['field'].split('.'))
            if cur == op['new']:
                log.append('уже применено: %s %s' % (op['id'], op['field']))
                continue
            assert cur == op['old'] or (op['old'] in (None, MISSING) and cur in (None, MISSING)), (op['id'], op['field'], cur)
            _set(card, op['field'], op['new'])
            if 'q' in op:
                fact_log(card, op['field'], None if op['new'] is MISSING else op['new'], op['q'][0], op['q'][1], BY)
            log.append('%s %s' % (op['id'], op['field']))
        elif kind == 'replace':
            cur = _walk(card, op['field'].split('.'))
            if op['old'] not in cur and (not op['new'] or op['new'] in cur):
                log.append('уже применено: %s %s (фраза)' % (op['id'], op['field']))
                continue
            assert cur.count(op['old']) == 1, (op['id'], op['field'])
            _set(card, op['field'], cur.replace(op['old'], op['new']))
            log.append('%s %s (фраза)' % (op['id'], op['field']))
        elif kind == 'retract':
            lst = card.setdefault('retracted', {}).setdefault(op['field'], [])
            for v in op['new']:
                if v not in lst:
                    lst.append(v)
            log.append('%s retracted.%s' % (op['id'], op['field']))
        elif kind == 'addsrc':
            urls = [u for _l, u in (card.get('src') or [])]
            if op['new'][1] in urls:
                log.append('уже применено: %s src %s' % (op['id'], op['new'][1]))
                continue
            card.setdefault('src', []).append(list(op['new']))
            log.append('%s src + %s' % (op['id'], op['new'][1]))
        elif kind == 'note':
            notes = card.setdefault('accepted_notes', {})
            cur = _walk(notes, op['path'].split('.'))
            if cur == op['new']:
                log.append('уже применено: %s accepted_notes.%s' % (op['id'], op['path']))
                continue
            assert cur is MISSING, (op['id'], op['path'], cur)
            _set(notes, op['path'], op['new'])
            log.append('%s accepted_notes.%s' % (op['id'], op['path']))
        else:
            raise AssertionError(kind)


def _registry(write, log):
    import fns_registry
    from fns_notes_to_registry import edit_registry_entry
    for op in OPS:
        if op['op'] != 'registry':
            continue
        cur = fns_registry.by_company_id().get(op['cid']) or {}  # noqa
        if cur.get('inn') == op['new']['inn']:
            log.append('уже применено: реестр %s' % op['cid'])
            continue
        assert cur.get('inn') == op['old_inn'], (op['cid'], cur)
        if write:
            assert edit_registry_entry(op['cid'], op['new'])
        log.append('реестр %s: ИНН %s → %s' % (op['cid'], op['old_inn'], op['new']['inn']))


