def _get(obj, field):
    for p in field.split('.'):
        obj = obj.get(p) if isinstance(obj, dict) else None
    return obj


def _set(obj, field, value):
    parts = field.split('.')
    for p in parts[:-1]:
        obj = obj.setdefault(p, {})
    obj[parts[-1]] = value


def _apply(data, log):
    import review
    deals = {d['id']: d for d in data['deals']}
    comps = data['companies']
    for op in OPS:
        kind, tag = op['op'], op['tag']
        card = deals.get(op.get('id')) if op.get('id') else None
        if kind == 'set':
            cur = _get(card, op['field'])
            assert cur == op['old'], (tag, op['id'], op['field'], cur)
            _set(card, op['field'], op['new'])
            log.append('%-8s %s %s' % (tag, op['id'], op['field']))
        elif kind == 'evidence':
            card.setdefault('party_evidence', {})[op['role']] = op['new']
            log.append('%-8s %s party_evidence.%s' % (tag, op['id'], op['role']))
        elif kind == 'review_evidence':
            # Так же, как review.py: свидетельство роли указывает на то, что теперь в поле.
            if card.get('party_evidence'):
                url = next((s[1] for s in card.get('src') or []
                            if len(s) > 1 and str(s[1]).startswith('http')), None)
                card['party_evidence'][op['role']] = [{'value': card.get(op['field']), 'field': op['field'],
                                                       'method': 'human_review', 'url': url}]
                log.append('%-8s %s party_evidence.%s' % (tag, op['id'], op['role']))
        elif kind == 'retract':
            lst = card.setdefault('retracted', {}).setdefault(op['field'], [])
            for v in op['new']:
                if v not in lst:
                    lst.append(v)
            log.append('%-8s %s retracted.%s' % (tag, op['id'], op['field']))
        elif kind == 'note':
            notes = card.setdefault('accepted_notes', {})
            assert _get(notes, op['path']) is None, (tag, op['id'], op['path'], _get(notes, op['path']))
            _set(notes, op['path'], op['new'])
            log.append('%-8s %s accepted_notes.%s' % (tag, op['id'], op['path']))
        elif kind == 'company_of':
            pid = card[op['role']]
            assert comps[pid].get(op['field']) == op['old'], (tag, pid, comps[pid].get(op['field']))
            comps[pid][op['field']] = op['new']
            log.append('%-8s профиль %s %s' % (tag, pid, op['field']))
        elif kind == 'company':
            prof = comps[op['pid']]
            assert prof.get(op['field']) == op['old'], (tag, op['pid'], op['field'], prof.get(op['field']))
            prof[op['field']] = op['new']
            log.append('%-8s профиль %s %s' % (tag, op['pid'], op['field']))
        elif kind == 'src_remove':
            src = card.get('src') or []
            assert op['old'] in src, (tag, op['id'], src)
            src.remove(op['old'])
            assert any(len(s) > 1 and str(s[1]).startswith('http') for s in src), (tag, 'без http-ссылки')
            log.append('%-8s %s src − %s' % (tag, op['id'], op['old'][1]))
        elif kind == 'event':
            ev = (card.get('events') or [None])[op['index']]
            assert ev and all(ev.get(k) == v for k, v in op['old'].items()), (tag, op['id'], ev)
            ev.update(op['new'])
            log.append('%-8s %s events[%d] %s' % (tag, op['id'], op['index'], ', '.join(op['new'])))
        elif kind == 'absorb':
            # Запись поля уже применена review.py — иначе отпечатки спрятали бы непримененную правку.
            marks = card.setdefault('proofread_absorbed', {}).setdefault(op['field'], [])
            mine = [f for f in review.FIXES if f['id'] == op['id'] and f['field'] == op['field']]
            assert mine and any(_get(card, op['field']) == f['new'] or review.already_applied(f, card, comps)
                                for f in mine), (tag, op['id'], op['field'], 'поле не несет значение записи')
            for fp in op['new']:
                if fp not in marks:
                    marks.append(fp)
            log.append('%-8s %s proofread_absorbed.%s' % (tag, op['id'], op['field']))
        else:
            raise AssertionError('неизвестная операция %r' % kind)


def _registry(write, log):
    import fns_registry
    rows = json.load(open(REG_JSON, encoding='utf-8'))
    keys = ('company_id', 'decision', 'inn', 'reason', 'date')
    for e in REGISTRY_EDIT:
        hits = [i for i, r in enumerate(rows) if r.get('company_id') == e['company_id']]
        assert len(hits) == 1, (e['tag'], e['company_id'], hits)
        r = rows[hits[0]]
        assert all(r.get(k) == v for k, v in e['old'].items()), (e['tag'], r)
        assert not (set(r) - set(keys)), (e['tag'], 'лишние поля строки', set(r) - set(keys))
        rows[hits[0]] = {k: e['row'][k] for k in keys}
        log.append('%-8s реестр %s: %s %s → %s %s' % (e['tag'], e['company_id'], r['decision'], r.get('inn'),
                                                     e['row']['decision'], e['row']['inn']))
    known = {r['company_id'] for r in fns_registry.REGISTRY}
    inns = {r.get('inn') for r in fns_registry.REGISTRY if r.get('inn')}
    for e in REGISTRY_ADD + REGISTRY_EDIT:
        inn = e['row']['inn']
        assert inn is None or fns_registry.inn_is_valid(inn), (e['tag'], inn)
    for e in REGISTRY_ADD:
        assert e['row']['company_id'] not in known, (e['tag'], 'строка уже есть')
        assert e['row']['inn'] not in inns, (e['tag'], 'ИНН уже у другого профиля')
        log.append('%-8s реестр %s: новая строка %s %s' % (e['tag'], e['row']['company_id'],
                                                           e['row']['decision'], e['row']['inn']))
    if not write:
        return
    with open(REG_JSON, 'w', encoding='utf-8') as fh:
        json.dump(rows, fh, ensure_ascii=False, indent=1)
        fh.write('\n')
    src = open(REG_PY, encoding='utf-8').read()
    anchor = '\ndef by_company_id('
    assert src.count(anchor) == 1
    block = '# Вычитка 9 ноября 2026 (партия fe) — pipeline/archive/2026-11/apply_reread_oneoff_2026_11_09.py.\nREGISTRY += [\n'
    for e in REGISTRY_ADD:
        r = e['row']
        block += ('    {"company_id": %r, "decision": %r, "inn": %r,\n     "reason": %r,\n     "date": %r},\n'
                  % (r['company_id'], r['decision'], r['inn'], r['reason'], r['date']))
    block += ']\n\n'
    i = src.index(anchor) + 1
    open(REG_PY, 'w', encoding='utf-8').write(src[:i] + block + src[i:])


