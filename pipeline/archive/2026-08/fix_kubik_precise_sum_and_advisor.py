import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'gafe121ae'

OLD_VAL = '—'
NEW_VAL = (
    'По данным на август 2026 года: «Пятый объект — БЦ Кубик... 17 136 '
    'м² арендуемой площади, оценка 2,3 млрд ₽, около 125 тыс. ₽/м². Все '
    'площади занимает штаб-квартира IT-дистрибьютора Merlion по '
    'договору до мая 2033 года» (vc.ru).'
)

OLD_RATIONALE = (
    'Закрытие сделки по приобретению бизнес-центра «Кубик» подтверждает '
    'высокий интерес институциональных инвесторов к качественным '
    'офисным активам с устойчивым денежным потоком.'
)
NEW_RATIONALE = OLD_RATIONALE + (
    ' Консультантом сделки выступила компания Nikoliers. Руководитель '
    'направления по работе с недвижимостью «ВИМ Инвестиции» Андрей '
    'Колокольников: «За последний год управляющая компания ВИМ '
    'Сбережения приобрела активы с оценочной стоимостью свыше 24 млрд '
    'рублей и планирует дальнейшую диверсификацию портфеля коммерческой '
    'недвижимости» (nikoliers.ru, 21 апреля 2026).'
)

OLD_TERMS = '—'
NEW_TERMS = (
    'С третьего квартала 2026 года запланированы капитальные затраты на '
    '109 млн ₽: ремонт вентиляции и капитальный ремонт паркинга — 4,7% '
    'от цены покупки (vc.ru, 15 августа 2026).'
)

NEW_SRC = [
    ['Nikoliers', 'https://nikoliers.ru/media/news/vim-sberezheniya-priobrela-biznes-tsentr-kubik-v-myakinino/'],
    ['vc.ru', 'https://vc.ru/invest/3080151-zpif-rentnyy-dokhod-2-uvelichil-dokhody-ot-arendy'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['val'] == OLD_VAL
    assert deal['eco']['rationale'] == OLD_RATIONALE
    assert deal['law']['terms'] == OLD_TERMS
    for label, url in NEW_SRC:
        assert not any(s[1] == url for s in deal['src']), f'{url} уже в src'

    print('=== eco.val: станет ===')
    print(NEW_VAL)
    print('\n=== eco.rationale: станет ===')
    print(NEW_RATIONALE)
    print('\n=== law.terms: станет ===')
    print(NEW_TERMS)
    print('\n=== src добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['val'] = NEW_VAL
        deal['eco']['rationale'] = NEW_RATIONALE
        deal['law']['terms'] = NEW_TERMS
        deal['src'].extend(NEW_SRC)
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
