# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF), карточка gbdd4f990 (Hobby World/
«Звезда»): `eco.rationale` обрывался ровно на «уточнил топ-менеджер.» —
а сама прямая цитата, ради которой это предложение существует («Мы
планируем дальнейшее расширение производственного комплекса в Твери, но
будет это происходить за счет развития новых направлений»), не попала в
карточку, хотя источник (Коммерсантъ, уже в `src`) был прочитан и дал
предыдущее предложение того же абзаца. Дополнено дословно тем же
источником — план расширения тверского завода в связи со сделкой.

Не через review.py: старое значение поля — не дословная цитата с самого
начала (обрывается на «.» там, где в источнике «:»), поэтому расширение
требует замены всего значения целиком, а не точечной вставки в пустое
поле.
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CARD_ID = 'gbdd4f990'
OLD_RATIONALE = (
    'Сделка позволит Hobby World расширить воронку для привлечения '
    'большого круга покупателей, говорит Михаил Акулов. У «Звезды» есть '
    'большие компетенции в производстве пластиковых компонентов и '
    'моделей, уточнил топ-менеджер.'
)
NEW_RATIONALE = (
    'Сделка позволит Hobby World расширить воронку для привлечения '
    'большого круга покупателей, говорит Михаил Акулов. У «Звезды» есть '
    'большие компетенции в производстве пластиковых компонентов и '
    'моделей, уточнил топ-менеджер: «Производство — очень сложный '
    'процесс, перенос производственных комплексов — трудоемкая задача. '
    'Мы планируем дальнейшее расширение производственного комплекса в '
    'Твери, но будет это происходить за счет развития новых '
    'направлений».'
)


def main(write=False):
    data = json.load(open(PATH, encoding='utf-8'))
    deal = next(d for d in data['deals'] if d['id'] == CARD_ID)

    assert deal['eco']['rationale'] == OLD_RATIONALE, \
        f"eco.rationale: неожиданное значение {deal['eco']['rationale']!r}"

    print(f"{CARD_ID} eco.rationale: += прямая цитата про расширение "
          "завода в Твери")
    deal['eco']['rationale'] = NEW_RATIONALE

    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("ЗАПИСАНО")
    else:
        print("Сухой прогон. Запись — с --write.")


if __name__ == '__main__':
    import sys
    main(write='--write' in sys.argv)
