# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g685e38f9 (ГК «Рост» приобрела 50% «Агрокультура Групп», закрыта 15
сентября 2023) — вторые 50% консолидированы через корпоративную
реорганизацию, а не отдельную публичную сделку, группа «Рост» в целом
крупный и активно растущий игрок отрасли.

Проверено лично прямым WebFetch (Коммерсантъ,
https://www.kommersant.ru/doc/6237544 — источник уже был в карточке,
дочитан по содержанию): вторые 50% на момент сделки принадлежали АО
«Комета» (70% — гендиректор «Агрокультура Групп» Владимир Чернышев,
30% — Марк Будыко); источники предполагали, что «Рост» получит и эту
долю, но подтверждения на тот момент не было.

По данным саб-агента (реестровые данные ЕГРЮЛ через агрегаторы, не
дозаверено отдельным WebFetch): консолидация прошла не отдельной
публичной сделкой, а корпоративной реорганизацией в 2024 году —
«Пересвет-Агро» присоединено к УК «РОСТ» (ликвидировано 8 августа
2024), АО «Комета» ликвидировано 2 августа 2024 — обе доли перешли
структурам «Роста» напрямую; сегодня 100% «Агрокультура Групп»
принадлежит УК «РОСТ» (99%) и АО «ГК РОСТ» (1%).

Проверено лично прямым WebFetch (Коммерсантъ,
https://www.kommersant.ru/doc/8463701): «Выручка ГК «Рост» в 2025
году, по предварительным данным, составила 81,9 млрд руб.,
увеличившись год к году на 10%» (в 2024 году рост был почти 60% —
заметное замедление), «У группы 22 тепличных комплекса в разных
регионах России» (было 20 на момент сделки 2023 года); причины
замедления — снижение урожайности («в среднем 47,6 кг с 1 кв. м,
снизившись год к году на 2,3%»), стагнация спроса, рост заболеваемости
растений (тобамовирусы, мозаичные вирусы у томатов).

НЕ ВКЛЮЧЕНО: сумма ни первой, ни второй половины консолидации — не
названа ни одним источником; отдельные инвестиции именно в каширскую
площадку «Агрокультура Групп» — источники о ней после 2023 года не
пишут адресно, только в общих отраслевых обзорах; новые стройки группы
«Рост» в Сибири/на Дальнем Востоке и модернизация в Липецкой области —
не относятся к каширскому активу этой карточки, не переношу как факт
о ней.

Запуск: python3 pipeline/fix_gk_rost_agrokultura_full_consolidation.py
        python3 pipeline/fix_gk_rost_agrokultura_full_consolidation.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g685e38f9'

OLD_EXTRA = (
    'Сделка по приобретению 100% долей ООО «Пересвет-Агро», которое '
    'владеет 50% в «Агрокультура Групп». Продавец — РСХБ Управление '
    'Активами. Закрыта 15 сентября 2023 года.'
)
NEW_EXTRA = OLD_EXTRA + (
    ' Вторые 50% (принадлежавшие АО «Комета») консолидированы в 2024 '
    'году корпоративной реорганизацией: обе прежние структуры-держатели '
    'долей ликвидированы (август 2024), доли перешли напрямую УК «РОСТ» '
    'и АО «ГК РОСТ» — сегодня им принадлежит 100%. Сама группа «Рост» '
    'выросла с 20 до 22 тепличных комплексов, выручка за 2025 год — '
    '81,9 млрд ₽ (+10%, заметное замедление против роста почти на 60% '
    'в 2024 году) из-за снижения урожайности, стагнации спроса и роста '
    'заболеваемости растений.'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/8463701'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    new_src = deal['src'] + NEW_SRC

    print('=== extra: станет ===')
    print(NEW_EXTRA)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['extra'] = NEW_EXTRA
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
