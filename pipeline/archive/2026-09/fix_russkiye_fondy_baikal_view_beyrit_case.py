# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g778efcb9 («Группа "Русские фонды" получила контроль над отелем
Baikal View на Байкале», закрыта 2023) — сооснователь группы,
названный в самой карточке совладельцем структуры-покупателя, позже
задержан по обвинению в особо крупном мошенничестве.

Проверено лично прямым WebFetch (Коммерсантъ,
https://www.kommersant.ru/doc/6789093, 24.06.2024): «московская
полиция задержала совладельцев инвестиционной группы «Русские фонды»
Сергея Васильева и Константина Бейрита», подозреваются в «особо
крупном мошенничестве (ч. 4 ст. 159 УК РФ)» — по версии следствия,
хищения у шести негосударственных пенсионных фондов в 2018–2019 годах
на 8,8 млрд рублей (в том числе вывод 3,213 млрд рублей из НПФ
«Первый национальный пенсионный фонд» при его продаже Евгению
Новицкому в 2016 году). Дело не связано с отелем Baikal View, но
касается лица, названного в этой же карточке совладельцем
«Прибайкальского агропарка».

НЕ ВКЛЮЧЕНО: дальнейший ход дела (домашний арест, смягчение меры,
арест и снятие ареста с акций «Селигдара») — источники саб-агента
(Интерфакс, РБК) не дозабраны и не прочитаны дословно отдельным
WebFetch, переносить без личной проверки нельзя; судьба доли Марины
Улахановой и реконструкция отеля — публично не освещались.

Запуск: python3 pipeline/fix_russkiye_fondy_baikal_view_beyrit_case.py
        python3 pipeline/fix_russkiye_fondy_baikal_view_beyrit_case.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g778efcb9'

OLD_ECO_CONTEXT = (
    'Сооснователь группы «Русские фонды» Константин Бейрит и члены '
    'совета директоров подконтрольного ей ПАО «Селигдар» Сергей '
    'Татаринов и Геннадий Лаунер стали совладельцами ООО '
    '«Прибайкальский агропарк».'
)
NEW_ECO_CONTEXT = OLD_ECO_CONTEXT + (
    ' В июне 2024 года Бейрит и второй совладелец группы Сергей '
    'Васильев были задержаны по обвинению в особо крупном мошенничестве '
    '— по версии следствия, речь о хищении у шести негосударственных '
    'пенсионных фондов в 2018–2019 годах на 8,8 млрд ₽; к самому отелю '
    'Baikal View дело отношения не имеет.'
)

NEW_SRC = [
    ['Коммерсантъ', 'https://www.kommersant.ru/doc/6789093'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT

    new_src = deal['src'] + NEW_SRC

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
