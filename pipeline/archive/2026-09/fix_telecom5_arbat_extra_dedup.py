# -*- coding: utf-8 -*-
"""Побочная находка при собственной проверке правки (карточка
g3e3f233c, «Структура «Ростелекома» и «Сбербанка» продала бизнес-центр
на Арбате»): мой же предыдущий скрипт (`fix_dealsma_jargon_leak_in_
extra.py`) переписал `extra`, но первое предложение почти дословно
повторяло уже стоящие в `title`/`eco.share` слова («структура
«Ростелекома» и «Сбербанка» продала бизнес-центр... на Арбате») —
встроенная в `extraHtml()` защита от повторов (см. CLAUDE.md, «Один и
тот же текст лежит в двух полях») справедливо вырезала это предложение
целиком как дубль. Вместе с ним с экрана пропал и единственный НОВЫЙ
факт в том же предложении — что покупатель, ООО «Первый», принадлежит
семье основателя «Мария-Ра» Александра Ракшина. Проверено Playwright
после первой правки: на вкладке «Экономист» остался только текст про
сдачу в аренду, без единого слова о Ракшине.

Правка не меняет факты — только переставляет их так, чтобы предложение
про покупателя не повторяло дословно то, что уже сказано в `title`/
`eco.share`.

Запуск: python3 pipeline/fix_telecom5_arbat_extra_dedup.py
        python3 pipeline/fix_telecom5_arbat_extra_dedup.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g3e3f233c'

OLD_EXTRA = (
    'Структура «Ростелекома» и «Сбербанка» продала бизнес-центр '
    'площадью 6282 кв. м на Арбате компании ООО «Первый», '
    'принадлежащей семье основателя ритейлера «Мария-Ра» Александра '
    'Ракшина. Предполагается дальнейшее использование комплекса для '
    'сдачи в аренду.'
)
NEW_EXTRA = (
    'Покупатель, ООО «Первый», принадлежит семье основателя ритейлера '
    '«Мария-Ра» Александра Ракшина. Предполагается дальнейшее '
    'использование комплекса для сдачи в аренду.'
)


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['extra'] == OLD_EXTRA

    print('=== extra: станет ===')
    print(NEW_EXTRA)

    if write:
        deal['extra'] = NEW_EXTRA
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
