# -*- coding: utf-8 -*-
"""Месячная очередь (REVISION_BRIEF, третий уровень), карточка
g508140b8 («Виктор Шкуренко купил сеть алкомаркетов "Мир вкуса" у
Натальи Уснунц», закрыта 2023) — уточнена история кузбасских
приобретений Шкуренко и текущая структура владения объектом по ЕГРЮЛ.

Проверено лично прямым WebFetch (NewsOmsk,
https://newsomsk.ru/news/137354-omskiy_predprinimatel_shkurenko_kupil_novokuznetsk/):
«ранее Шкуренко купил здание торгового центра "Простор" в Прокопьевске
Кемеровской области, а также две компании крупнейшего дистрибутора
продуктов питания в Кемерово», «Это третья компания, которую мы
приобрели на Кузбассе за короткий срок» — уточняет, КАКИЕ именно две
компании были куплены на Кузбассе до этой сделки (не «Бас-тон» — та
покупка томская, отдельная от кузбасской серии, это уже верно
различала сама карточка).

Проверено лично прямым WebFetch (KS-online,
https://ksonline.ru/509892/krupnyj-sibirskij-produktovyj-ritejler-vyhodit-na-moskovskij-rynok/):
«в 2020-2021 годах он также купил томского дистрибьютора кондитерских
изделий "Салют" и новосибирского дистрибьютора ТД "АБК – Новая
Сибирь". В феврале 2022 года бизнесмен объявлял о приобретении
томской дистрибуторской компании "Бас-тон"» — более широкий список
приобретений 2020-2022 годов вне Кузбасса.

Проверено лично прямым WebFetch (СПАРК-Интерфакс,
https://spark-interfax.ru/kemerovskaya-oblast-novokuznetsk/ooo-iva-inn-4220038769-ogrn-1084220003658-b717834e3ce345bea205797b0155ea00):
«Грибов Павел Анатольевич, генеральный директор», единственный
учредитель — «ТД ШКУРЕНКО, ООО» — объект полностью интегрирован в
группу как юрлицо (не куплен через перевод контрактов на торговый
дом, как для части других сделок Шкуренко), директор сменился с
прежних владельцев на назначенного менеджера.

НЕ ВКЛЮЧЕНО: достижение цели «5 млрд оборота в Кемеровской области в
2024 году» — ни один источник не подтверждает и не опровергает итог;
дальнейшая судьба сети «Мир вкуса» (не упомянута в обзорной статье
2026 года о структуре группы, но там перечислены только продуктовые
сети, а «Мир вкуса» — алкогольная розница другого профиля, поэтому
отсутствие в списке ничего не доказывает); что стало с Натальей
Уснунц после продажи — источников нет; юридический консультант
сделки — не назван нигде.

Запуск: python3 pipeline/fix_shkurenko_iva_kuzbass_history_and_ownership.py
        python3 pipeline/fix_shkurenko_iva_kuzbass_history_and_ownership.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g508140b8'

OLD_ECO_CONTEXT = (
    'Ранее сообщалось, что господин Шкуренко приобрел приобрел томскую '
    'торговую компанию «Бас-тон». Предприниматель отмечал, что с учетом '
    'приобретения томской компании, выручка ТД «Шкуренко» в 2022 году '
    'увеличится до 20 млрд руб. По итогам 2021 года она составила '
    '17 млрд руб.'
)
NEW_ECO_CONTEXT = OLD_ECO_CONTEXT + (
    ' Две предыдущие покупки на Кузбассе, о которых говорит сам '
    'Шкуренко («это третья компания... за короткий срок»), — здание '
    'торгового центра «Простор» в Прокопьевске и две компании '
    'крупнейшего дистрибутора продуктов питания в Кемерово; отдельно от '
    'кузбасской серии — приобретения в других регионах: томский '
    'дистрибьютор кондитерских изделий «Салют» и новосибирский '
    'дистрибьютор ТД «АБК – Новая Сибирь» (2020–2021), а также '
    '«Бас-тон» (февраль 2022).'
)

OLD_LAW_STRUCT = '—'
NEW_LAW_STRUCT = (
    'По данным СПАРК-Интерфакс, единственный учредитель ООО «Ива» — '
    'ООО «ТД Шкуренко» (объект интегрирован в группу как юрлицо '
    'целиком, а не через перевод контрактов на торговый дом), '
    'гендиректор — Павел Грибов.'
)

NEW_SRC = [
    ['NewsOmsk', 'https://newsomsk.ru/news/137354-omskiy_predprinimatel_shkurenko_kupil_novokuznetsk/'],
    ['KS-online', 'https://ksonline.ru/509892/krupnyj-sibirskij-produktovyj-ritejler-vyhodit-na-moskovskij-rynok/'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['law']['struct'] == OLD_LAW_STRUCT

    new_src = deal['src'] + NEW_SRC

    print('=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)
    print('\n=== src: добавится ===')
    for s in NEW_SRC:
        print(s)

    if write:
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['law']['struct'] = NEW_LAW_STRUCT
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
