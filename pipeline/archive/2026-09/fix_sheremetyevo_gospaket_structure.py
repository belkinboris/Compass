# -*- coding: utf-8 -*-
"""Дневная очередь (REVISION_BRIEF, первый уровень — первый глубокий
проход после появления карточки), g2f5143f4 («Минфин планирует продать
госпакет аэропорта Шереметьево до конца года», добавлена 2 сентября
2026) — структура владения аэропортом (кто реально контролирует
частный пакет) и условия предстоящей приватизации не были внесены,
хотя оба уже стояли в источнике карточки.

Проверено лично прямым WebFetch (Интерфакс, источник самой карточки,
https://www.interfax.ru/business/1112656): «Пакет акций в размере
66,06% в МАШ контролирует ООО "Шереметьево Холдинг", единственным
владельцем которого является МКООО "ТПС Авиа Холдинг ЛТД"»;
государственное имущество — 30,46%, «Аэрофлот» — 2,43%, менеджмент —
1,05%; «Доля в 65,22% в TPS Avia Holding была у траста в интересах
семей Александра Пономаренко и Александра Скоробогатько, 34,78% было
у Аркадия Ротенберга»; условия указа при отчуждении акций —
«сохранение основного вида деятельности предприятия, модернизации его
мощностей и запрете на отчуждение акций иностранным лицам»;
распоряжение о «золотой акции» подписано премьер-министром Мишустиным
18 августа (2026).

НЕ ВКЛЮЧЕНО: расхождение между «30,43%» (цифра из самого указа, по
пересказу Интерфакса) и «30,46%» (структура собственности на конец
января 2026 по тому же источнику) — техническое, вероятно, разные
даты среза, не разрешено додумыванием; версия The Bell/Novaya Gazeta
Europe о том, что госпакет может достаться самому Ротенбергу, —
спекуляция одного специфического издания без подтверждения сторон,
не факт; старое соглашение акционеров 2020 года о праве «Шереметьево
Холдинга» выкупить госпакет по формуле «оценка плюс 35%» — статье
шесть лет, не подтверждено действующим в 2026 году, требует отдельной
проверки, если понадобится.

Запуск: python3 pipeline/fix_sheremetyevo_gospaket_structure.py
        python3 pipeline/fix_sheremetyevo_gospaket_structure.py --write
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g2f5143f4'

OLD_LAW_STRUCT = '—'
NEW_LAW_STRUCT = (
    'Частным пакетом (66,06%) владеет ООО «Шереметьево Холдинг» через '
    'МКООО «ТПС Авиа Холдинг ЛТД» (резидент САР на острове Октябрьский, '
    'ранее — кипрская TPS Avia Holding). В TPS Avia Holding 65,22% — у '
    'траста в интересах семей Александра Пономаренко и Александра '
    'Скоробогатько, 34,78% — у Аркадия Ротенберга. Помимо госпакета '
    '(30,46%), в структуре также 2,43% у «Аэрофлота» и 1,05% у '
    'менеджмента аэропорта.'
)

OLD_LAW_APPR = '—'
NEW_LAW_APPR = (
    'Указ президента об исключении Шереметьево из перечня стратегических '
    'предприятий подписан в начале августа 2026 года и обязывает при '
    'продаже сохранить основной вид деятельности, провести модернизацию '
    'мощностей и запрещает отчуждение акций иностранным лицам и '
    'подконтрольным им юрлицам. 18 августа 2026 премьер-министр Михаил '
    'Мишустин отдельно подписал распоряжение об использовании '
    '«золотой акции» — права РФ участвовать в управлении аэропортом.'
)

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/business/1112656'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal['law']['struct'] == OLD_LAW_STRUCT
    assert deal['law']['appr'] == OLD_LAW_APPR

    existing_urls = {s[1] for s in deal['src']}
    add_src = [s for s in NEW_SRC if s[1] not in existing_urls]
    new_src = deal['src'] + add_src

    print('=== law.struct: станет ===')
    print(NEW_LAW_STRUCT)
    print('\n=== law.appr: станет ===')
    print(NEW_LAW_APPR)
    if add_src:
        print('\n=== src: добавится ===')
        for s in add_src:
            print(s)

    if write:
        deal['law']['struct'] = NEW_LAW_STRUCT
        deal['law']['appr'] = NEW_LAW_APPR
        deal['src'] = new_src
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
