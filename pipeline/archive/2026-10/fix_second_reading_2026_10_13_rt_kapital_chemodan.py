    print('ПРАВКА профиля g3b3da4cd: desc')
    if not write:
        print('\nСухой прогон. Применение — с ключом --write.')
        return 0

    c1['eco']['share'] = SHARE1_NEW
    c1['law']['struct'] = STRUCT1_NEW

    c2['title'] = TITLE2_NEW
    c2['eco']['share'] = SHARE2_NEW
    c2['eco']['val'] = VAL2_NEW
    c2['law']['terms'] = TERMS2_NEW
    c2['eco']['context'] = CONTEXT2_NEW
