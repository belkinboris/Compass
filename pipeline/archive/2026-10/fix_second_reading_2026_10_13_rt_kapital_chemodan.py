    fresh = json.load(open(DATA, encoding='utf-8'))
    fresh_cards = {c['id']: c for c in fresh['cards']}
    fresh_c1 = fresh_cards['g6c1f9d4e']
    fresh_c2 = fresh_cards['g83ad1f72']
    assert fresh_c1['eco']['share'] == SHARE1_OLD, 'g6c1f9d4e уже изменена — перечитайте'
    assert fresh_c2['title'] == TITLE2_OLD, 'g83ad1f72 уже изменена — перечитайте'

    idx1 = fresh['cards'].index(fresh_c1)
    idx2 = fresh['cards'].index(fresh_c2)
    fresh['cards'][idx1] = c1
    fresh['cards'][idx2] = c2
    json.dump(fresh, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)

