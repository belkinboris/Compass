def main(write=False):
    data = json.load(open(DATA, encoding='utf-8'))
    cards = {c['id']: c for c in data['cards']}
    promoted = json.load(open(PROMOTED, encoding='utf-8'))
    comps = promoted['companies']

    c1 = cards['g6c1f9d4e']
    assert c1['eco']['share'] == SHARE1_OLD
    assert c1['law']['struct'] == STRUCT1_OLD

    c2 = cards['g83ad1f72']
    assert c2['title'] == TITLE2_OLD
    assert c2['eco']['share'] == SHARE2_OLD
    assert c2['eco']['val'] == VAL2_OLD
