def apply(data):
    by = {x['id']: x for x in data['deals']}
    n = 0
    for i, p in FILL.items():
        x = by[i]
        assert not (x.get('buyer') or x.get('buyer_name') or x.get('seller') or x.get('seller_id')), i
        b, s = p['buyer'], p['seller']
        if b:
            if b.get('id'):
                assert b['id'] in data['companies'], (i, b)
                x['buyer'] = b['id']
            else:
                x['buyer_name'] = b['name']
        if s:
            x['seller'] = s['name']; x['seller_src'] = 'text'
            if s.get('id'):
                assert s['id'] in data['companies'], (i, s)
                x['seller_id'] = s['id']
        n += 1
        print('стороны', i, '|', x['title'][:60], '|', b and b['name'], '←', s and s['name'])
    for i, r in NO_PARTIES.items():
        x = by[i]
        assert not x.get('no_parties'), i
        x['no_parties'] = r
        print('без сторон', i, '|', x['title'][:60], '|', r[:80])
    return n


