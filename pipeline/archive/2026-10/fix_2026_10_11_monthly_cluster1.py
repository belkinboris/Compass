def get(card, field):
    obj = card
    for part in field.split('.')[:-1]:
        obj = obj[part]
    return obj[field.split('.')[-1]]


def set_(card, field, value):
    obj = card
    parts = field.split('.')
    for part in parts[:-1]:
        obj = obj[part]
    obj[parts[-1]] = value


def main(write):
    data = json.load(open(DATA_PATH, encoding='utf-8'))
    deals = data['deals'] if isinstance(data, dict) else data
    by_id = {d['id']: d for d in deals}

    for edit in EDITS:
        card = by_id[edit['id']]
        current = get(card, edit['field'])
        if current != edit['old']:
            raise SystemExit('%s.%s: в базе %r, ожидали %r' % (
                edit['id'], edit['field'], current, edit['old']))
        new_value = edit['old'] + edit['append']
        set_(card, edit['field'], new_value)
        existing_src = card.setdefault('src', [])
        for pair in edit['src']:
            if pair not in existing_src:
                existing_src.append(pair)

    # g0931ed04.law.terms не было в proofread_absorbed — без синхронизации
    # review.py откажет на следующей самопроверке (поле больше не равно
    # исходной записи FIXES, а отпечатка старого текста в absorbed нет).
    card = by_id['g0931ed04']
    absorbed = card.setdefault('proofread_absorbed', {})
    fp = fix_fingerprint('Акции шестой обозначенной в указе президента компании, АО '
                          '«Нива-СВ», собственностью Северной верфи не стали, в ОСК это не '
                          'комментируют.')
    lst = absorbed.setdefault('law.terms', [])
    if fp not in lst:
        lst.append(fp)

    if write:
        json.dump(data, open(DATA_PATH, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
        for edit in EDITS:
            print('%s.%s — записано.' % (edit['id'], edit['field']))
    else:
        print('Сухой прогон: применил бы %d правок выше. Повторите с --write.' % len(EDITS))


if __name__ == '__main__':
    main(write='--write' in sys.argv)
