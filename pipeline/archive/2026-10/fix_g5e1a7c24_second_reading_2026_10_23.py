def fix_card(pending):
    card = [c for c in pending['cards'] if c.get('id') == CARD]
    assert len(card) == 1, 'карточки %s нет в pending.json' % CARD
    card = card[0]
    changed = []
    for (sec, key), (old, new) in CARD_FIX.items():
        cur = card[sec][key]
        if new in cur:
            continue
        assert old in cur, (sec, key, cur)
        card[sec][key] = cur.replace(old, new)
        changed.append('%s.%s' % (sec, key))
    return changed


def fix_profiles(data):
    changed = []
    for cid, (old, new) in PROFILE_FIX.items():
        c = data['companies'][cid]
        if c.get('desc') == new:
            continue
        assert c.get('desc') == old, (cid, c.get('desc'))
        c['desc'] = new
        changed.append(cid)
    return changed


def dump(path, obj):
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(obj, f, ensure_ascii=False, indent=1)


def main(write):
    # сухой прогон на снимке
    p = json.load(open(PENDING, encoding='utf-8'))
    d = json.load(open(DATA, encoding='utf-8'))
    print('карточка:', fix_card(p) or 'уже исправлена')
    print('профили:', fix_profiles(d) or 'уже исправлены')
    if not write:
        print('сухой прогон; --write — записать')
        return
    # перечитать прямо перед записью: приток может писать файлы параллельно
    p = json.load(open(PENDING, encoding='utf-8'))
    if fix_card(p):
        dump(PENDING, p)
    d = json.load(open(DATA, encoding='utf-8'))
    if fix_profiles(d):
        dump(DATA, d)
    print('записано')


if __name__ == '__main__':
    main('--write' in sys.argv)
