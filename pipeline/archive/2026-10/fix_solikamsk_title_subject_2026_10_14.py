"""«Соликамскбумпром» (g002710cf): заголовок и предмет по замечанию владельца
14 октября 2026: «непонятно название… нужно писать конкретнее: подписали
соглашение о намерении передать 83,3% акций»; «в предмете лучше не писать,
что договор купли-продажи пока не подписывали — к предмету не относится;
в карточке это должно быть». Оговорка «только со слов завода» и «договор
не подписан» переезжают из «Предмета / доли» в «Структуру сделки».
Карточка снова уходит в консоль на подтверждение (снимаются отметки
отправки и снимок поста). Без ключа — сухой прогон, запись по --write."""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = os.path.join(ROOT, 'static', 'data', 'pending.json')
ID = 'g002710cf'
OLD_TITLE = '«Соликамскбумпром» заявил о соглашении с китайским инвестором «Юнь Чоу»'
NEW_TITLE = '«Соликамскбумпром» сообщил о соглашении о намерениях передать 83,3% акций «Юнь Чоу»'
OLD_SHARE = ('На суде по делу о банкротстве завод заявил, что «Юнь Чоу» купит 83,3% акций комбината, '
             'а соглашение о намерении уже подписано, — это известно только со слов завода и не '
             'подтверждено ни судом, ни кредиторами. Договор купли-продажи стороны пока не подписывали.')
NEW_SHARE = ('83,3% акций АО «Соликамскбумпром» — контрольный пакет одного из крупнейших в стране '
             'производителей газетной бумаги.')
NEW_STRUCT = ('О соглашении о намерениях с «Юнь Чоу» известно только со слов завода: он заявил об '
              'этом на суде по делу о банкротстве, ни суд, ни кредиторы этого не подтвердили. '
              'Договор купли-продажи стороны пока не подписывали.')
raw = open(P, encoding='utf-8').read()
pending = json.loads(raw)
card = next(c for c in pending['cards'] if c['id'] == ID)
assert card['title'] == OLD_TITLE, card['title']
assert card['eco']['share'] == OLD_SHARE, card['eco']['share']
assert card['law']['struct'] in ('—', '', None), card['law']['struct']
card['title'] = NEW_TITLE
card['eco']['share'] = NEW_SHARE
card['law']['struct'] = NEW_STRUCT
for k in ('draft_sent', 'post_draft_sent', 'post_preview'):
    card.pop(k, None)
print('%s: заголовок, предмет, структура; к повторной отправке в консоль' % ID)
if '--write' in sys.argv:
    out = json.dumps(pending, ensure_ascii=False, indent=1)
    if raw.endswith('\n'):
        out += '\n'
    open(P, 'w', encoding='utf-8').write(out)
    print('записано')
