def get(card, field):
    a, _, b = field.partition('.')
    return card.get(a) if not b else (card.get(a) or {}).get(b)


def put(card, field, value):
    a, _, b = field.partition('.')
    if not b:
        if value is None:
            card.pop(a, None)
        else:
            card[a] = value
    else:
        card.setdefault(a, {})
        if value is None:
            card[a].pop(b, None)
        else:
            card[a][b] = value


def main(argv):
    base = json.load(open(DATA, encoding='utf-8'))
    byid = {d['id']: d for d in base['deals']}
    for cid, field, old, new in EDITS:
        cur = get(byid[cid], field)
        if old is not None:
            assert cur == old, (cid, field, cur)
        else:
            assert cur, (cid, field)
        print('%s %s: %r → %r' % (cid, field, (cur or '')[:50], (new or '')[:50]))
    if '--write' not in argv:
        print('Сухой прогон. Запись — с ключом --write.')
        return 0
    for cid, field, old, new in EDITS:
        put(byid[cid], field, new)
    json.dump(base, open(DATA, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print('Записано: %d правок.' % len(EDITS))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
