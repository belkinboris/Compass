def get(o, path):
    for k in path[:-1]:
        o = o[k]
    return o, path[-1]


def main(write):
    data = json.load(open(DATA, encoding='utf-8'))
    deals = {d['id']: d for d in data['deals']}
    for did, path, old, new in EDITS:
        if old == new:
            continue
        holder, key = get(deals[did], path)
        if new in holder[key] and old not in holder[key]:
            continue
        assert holder[key].count(old) == 1, (did, path, old)
        before = holder[key]
        holder[key] = holder[key].replace(old, new)
        # Поле, поставленное таблицей FIXES, — отпечаток прежнего текста в
        # proofread_absorbed (docs/card_editing.md), иначе review.py сочтет
        # запись непримененной.
        field = '.'.join(map(str, path))
        if not isinstance(path[-1], int) and 'events' not in path and path != ('title',):
            deals[did].setdefault('proofread_absorbed', {}).setdefault(field, [])
            fp = review.fix_fingerprint(before)
            if fp not in deals[did]['proofread_absorbed'][field]:
                deals[did]['proofread_absorbed'][field].append(fp)
        print('%s %s: %s → %s' % (did, '.'.join(map(str, path)), old[:50], new[:50]))
    if write:
        with open(DATA, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=1, ensure_ascii=False)
            f.write('\n')


if __name__ == '__main__':
    main('--write' in sys.argv)
