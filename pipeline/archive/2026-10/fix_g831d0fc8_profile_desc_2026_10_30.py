#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Описания двух профилей, заведенных приемкой карточки g831d0fc8 (особняк на
Фурштатской, 60А): у покупателя «Резотстрой» снята неподтвержденная цель
создания («для покупки недвижимости» — в источниках этого нет) и первое
предложение сделано коротким, чтобы строка «Покупатель» поста читалась
вслух; у продавца «Стрела» — прошедшее время: после этой же сделки
компания зданием не владеет.

Без ключа — сухой прогон, запись по --write; перед записью файл
перечитывается, старые значения проверяются assert.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

CHANGES = {
    'g000e6f6c': (
        'Петербургская компания, созданная в январе 2026 года для покупки недвижимости. Единственный '
        'акционер — Юлия Карпова, которой принадлежат также гостиничные компании «Курэйтэд» и «Аспен '
        'Отель Групп». Юрлицо — АО «Резотстрой».',
        'Петербургская компания Юлии Карповой, зарегистрирована в январе 2026 года. Ей же принадлежат '
        'гостиничные компании «Курэйтэд» и «Аспен Отель Групп». Юрлицо — АО «Резотстрой».',
    ),
    'gec329495': (
        'Петербургская компания — собственник исторического особняка на Фурштатской улице, 60А (бывший '
        'доходный дом Спиридонова), который купила в 2024 году под апарт-отель. 99,9% акций — у ЗПИФ '
        '«Газпромбанк — Промышленные инвестиции», 0,1% — у ООО «Корпорация финансирования газовой '
        'отрасли». Юрлицо — АО «Стрела».',
        'Петербургская компания, владевшая историческим особняком на Фурштатской улице, 60А (бывший '
        'доходный дом Спиридонова): купила его в 2024 году под апарт-отель. 99,9% акций — у ЗПИФ '
        '«Газпромбанк — Промышленные инвестиции», 0,1% — у ООО «Корпорация финансирования газовой '
        'отрасли». Юрлицо — АО «Стрела».',
    ),
}


def main(write):
    base = json.load(open(PATH, encoding='utf-8'))
    comps = base['companies']
    for cid, (old, new) in CHANGES.items():
        assert comps[cid]['desc'] == old, (cid, comps[cid]['desc'])
        print('%s %s:\n  было: %s\n  станет: %s' % ('ПИШЕМ' if write else 'СУХО', cid, old, new))
        comps[cid]['desc'] = new
    if write:
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(base, f, ensure_ascii=False, indent=1)
            f.write('\n')
        print('Записано.')
    else:
        print('Сухой прогон. Запись — с ключом --write.')


if __name__ == '__main__':
    main('--write' in sys.argv)
