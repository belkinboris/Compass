import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, 'static', 'data', 'deals_promoted.json')

DEAL_ID = 'g28f173ca'

OLD_SELLER = None
NEW_SELLER = 'ООО «Тонкости продаж»'

OLD_ECO_CONTEXT = (
    '«Тонкости туризма» — один из ключевых активов медианаправления '
    'МТС Travel, куда входят также брендированный онлайн-журнал и '
    'собственные путеводители. Дополнительные вложения в '
    'технологическое развитие всех медиапроектов сервиса составляют '
    'около 100 млн ₽.'
)
NEW_ECO_CONTEXT = (
    OLD_ECO_CONTEXT + ' Продавец, ООО «Тонкости продаж», принадлежал '
    'шести физлицам во главе с гендиректором Еленой Батоговой (33% '
    'доли); юрлицо исключено из ЕГРЮЛ в марте 2025 года. Портал '
    'tonkosti.ru продолжает работать под тем же брендом в структуре '
    'МТС Трэвел.'
)

OLD_SRC = [['Ведомости', 'https://www.vedomosti.ru/media/articles/2023/05/11/974485-servis-mts-travel-kupil-prava-na-vipusk-onlain-zhurnala-tonkosti-turizma']]
NEW_SRC = OLD_SRC + [
    ['Интерфакс', 'https://www.interfax.ru/business/900908'],
    ['Тонкости туризма (о проекте)', 'https://tonkosti.ru/О_проекте'],
]


def main(write=False):
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    deal = next(d for d in data['deals'] if d['id'] == DEAL_ID)

    assert deal.get('seller') == OLD_SELLER
    assert deal['eco']['context'] == OLD_ECO_CONTEXT
    assert deal['src'] == OLD_SRC

    print('=== seller: станет ===')
    print(NEW_SELLER)
    print('\n=== eco.context: станет ===')
    print(NEW_ECO_CONTEXT)
    print('\n=== src: станет ===')
    print(NEW_SRC)

    if write:
        deal['seller'] = NEW_SELLER
        deal['eco']['context'] = NEW_ECO_CONTEXT
        deal['src'] = NEW_SRC
        with open(PATH, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print('\nЗаписано.')
    else:
        print('\nСухой прогон — ничего не записано. Запустите с --write.')


if __name__ == '__main__':
    main(write='--write' in sys.argv)
