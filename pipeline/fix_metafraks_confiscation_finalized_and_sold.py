# -*- coding: utf-8 -*-
"""Месячная очередь качества, 11 сентября 2026 — карточка `c1062263e`
(«Изъятие акций Метафракс Кемикалс в собственность государства по
решению суда», 2023) описывала только первую инстанцию; дальнейшая
судьба решения и актива были неизвестны.

Личный WebFetch подтвердил дословно:

1) Интерфакс, https://www.interfax.ru/russia/947856: «96,9% акций АО
   "Метафракс Кемикалс" перешли в пользу государства» (решение от
   27 февраля 2024 г.); «АО "Росхим" (ранее - АО "Русский водород") с
   1 февраля 2024 года назначено управляющей организацией АО
   "Метафракс Кемикалс"».

2) Интерфакс, https://www.interfax.ru/business/979475: «В лот входят
   284 599 228 обыкновенных акций АО "Метафракс Кемикалс" (96,9%
   уставного капитала). Начальная цена лота установлена на уровне
   14,7 млрд рублей»; «Заявки на участие принимаются с 4 по 30
   сентября, состав участников будет подведен 7 октября, а итоги
   аукциона - 9 октября»; в обновлении той же статьи — «"Росхим" купил
   у Росимущества 97% акций "Метафракс Кемикалс"».

Изъятие вступило в силу окончательно (кассация подтвердила решение),
временное управление сменилось продажей: «Росхим» выкупил пакет на
торгах в октябре 2024 года и остаётся владельцем. Точная сумма
финальной покупки (совпала ли со стартовой ценой 14,7 млрд ₽) не
подтверждена дословно ни в одном источнике — не вносится в `sum`.

Правка сливает новый факт в УЖЕ существующую запись FIXES для
`eco.context` (`pipeline/ingest/fixes/batch_c_2023.py`, там же
пояснение) — таблица не умеет двух записей на одно поле.

Запуск:
    python3 pipeline/fix_metafraks_confiscation_finalized_and_sold.py            # сухой прогон
    python3 pipeline/fix_metafraks_confiscation_finalized_and_sold.py --write    # запись
"""
import json
import sys

DATA = 'static/data/deals_promoted.json'

OLD_ECO_CONTEXT = (
    'Согласно СПАРК, акционерами «Метафракс Кемикалс» являются '
    '«Метахолдинг» с долей 95,88%, гендиректор предприятия Владимир '
    'Даут (0,5%), «Метафракс Трейдинг» (0,27%) и Виктор Майер (0,01%)'
)
NEW_ECO_CONTEXT = OLD_ECO_CONTEXT + (
    '. 27 февраля 2024 года кассация подтвердила: 96,9% акций перешли '
    'государству. С 1 февраля 2024 года управляющей организацией была '
    'назначена АО «Росхим», а в октябре 2024 года «Росхим» выкупил тот '
    'же пакет у Росимущества на торгах (стартовая цена лота — '
    '14,7 млрд ₽) и остаётся владельцем.'
)

NEW_SRC = [
    ['Интерфакс', 'https://www.interfax.ru/russia/947856'],
    ['Интерфакс', 'https://www.interfax.ru/business/979475'],
]


def main(write=False):
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    by_id = {d['id']: d for d in data['deals']}

    d = by_id['c1062263e']

    assert d['eco']['context'] == OLD_ECO_CONTEXT, 'eco.context уже другой'
    assert d.get('status') is None, 'status уже занят: %r' % (d.get('status'),)
    urls = {s[1] for s in d['src']}
    for src in NEW_SRC:
        assert src[1] not in urls, 'источник уже добавлен: %s' % src[1]

    print('c1062263e: eco.context дополнен окончательным исходом (кассация, '
          'продажа Росхиму на торгах), status -> Закрыта, добавлены два '
          'источника')

    if not write:
        print('Сухой прогон. Запись — с ключом --write.')
        return

    d['eco']['context'] = NEW_ECO_CONTEXT
    d['status'] = 'Закрыта'
    d['src'].extend(NEW_SRC)

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('Записано.')


if __name__ == '__main__':
    main('--write' in sys.argv)
