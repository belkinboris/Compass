# -*- coding: utf-8 -*-
"""Показатели, которые считаются ИЗ отчётности, а не лежат в ней готовыми.

Просьба Дани (19 сентября 2026): «из БФО реально наверное из финансовых
результатов можно подгрузить ебитду», плюс оборотный капитал и
закредитованность. Разбор, что из этого правда:

  * ОБОРОТНЫЙ КАПИТАЛ и ЗАКРЕДИТОВАННОСТЬ — считаются полностью, из строк,
    которые у нас уже лежат в базе с первого дня синхронизации с ФНС
    (`db/models.FinancialReport`). Отдельно ходить никуда не нужно.
  * EBITDA — НЕ СЧИТАЕТСЯ, и это не «пока не сделали», а свойство
    источника. Амортизации нет ни в балансе, ни в отчёте о финансовых
    результатах, ни в отчёте о движении денежных средств: её раскрывают в
    пояснениях к отчётности, а в ГИР БО пояснения машинно не отдаются
    (см. `fns_client.FULL_LINE_SECTIONS` — весь набор строк, который
    приходит от API, там перечислен построчно). Написать «EBITDA» над
    числом, в котором нет амортизации, значит соврать в самом заметном
    месте карточки — тем более что у производственной компании амортизация
    легко составляет десятки процентов этой величины.

    Поэтому считаем и называем своим именем то, что действительно
    выводится: прибыль до процентов и налога (2300 + 2330). Это ближайшая
    к EBITDA величина из открытых данных, и в подписи прямо сказано, чем
    она от EBITDA отличается. Тот же принцип, по которому мультипликаторы
    считаются «цена ÷ выручка или операционная прибыль», а не «EV/EBITDA»,
    которого у нас нет (CLAUDE.md, разбор рецензента, находка 7).

    ЧТО ИЗ «ЛЕСЕНКИ ПРИБЫЛИ» ДОСТУПНО, А ЧТО НЕТ. Отчёт о финансовых
    результатах даёт четыре уровня прибыли готовыми строками — валовую
    (2100), от продаж (2200), до налогообложения (2300, она же EBT) и
    чистую (2400), — плюс проценты к уплате (2330), из которых собирается
    EBIT. Всё, что требует амортизации, не собирается ни из чего:
    ни EBITDA, ни OIBDA, ни EBIDA. Оценивать амортизацию по изменению
    основных средств и капитальным вложениям из отчёта о движении денег
    можно только вместе с выбытием, которого в открытых данных нет, —
    это и был бы «правдоподобный» ответ вместо пустого поля.

    ЗНАКИ СТРОК ИЗМЕРЕНЫ, А НЕ УГАДАНЫ (19 сентября 2026, живые ответы
    боевого сайта). Расходные строки приходят ПОЛОЖИТЕЛЬНЫМИ, вычитать их
    надо самому: у «Лузалеса» за 2025 год 2110 − 2120 = 2100 и
    2100 − 2210 − 2220 = 2200 сходятся до рубля. Там, где знак всё же может
    разойтись между источниками (проценты к уплате), берём модуль, а где
    можно — считаем через уже нормализованные поля, а не через сырые строки:
    коммерческие и управленческие расходы получаются как «валовая прибыль
    минус прибыль от продаж», и знак в этой формуле не участвует вовсе.

ГРАНИЦА МОДУЛЯ. Здесь только арифметика над одним годом одного юрлица: ни
сети, ни базы, ни суждений о периметре. Вопрос «описывает ли отчётность
этого юрлица купленный бизнес» решается чтением в слое фактов и сюда не
относится — на профиле компании мы показываем показатели ИМЕННО ЭТОГО
юрлица и так и подписываем.

ОДИН ИСПОЛНИТЕЛЬ. Считает сервер, клиент только рисует готовые числа с
готовыми подписями (`static/index.html`, вкладка «Финансы»). Клиентских
копий формул нет намеренно: две копии правил в Python и JS уже разъезжались
(CLAUDE.md, «Слой фактов»), и повторять это ради четырёх делений незачем.
"""
from __future__ import annotations

# Знаменатель меньше этой величины считаем нулём: у спящего юрлица в
# отчётности встречаются рубли и десятки рублей, и деление на них даёт
# «долг к капиталу ×4 000 000» — число верное и бессмысленное.
MIN_DENOMINATOR_RUB = 100_000.0

# Строки, которых нет среди 15 нормализованных полей, — берём из полного
# набора строк отчёта.
INTEREST_PAID_CODE = "2330"      # проценты к уплате
COST_OF_SALES_CODE = "2120"      # себестоимость продаж
OPERATING_CASH_CODE = "4100"     # сальдо денежных потоков от текущих операций

DAYS_IN_YEAR = 365


def _f(value) -> float | None:
    """Число или None. Numeric из SQLAlchemy приходит как Decimal, из JSON —
    как int/float/str; всё это одинаково годится для арифметики."""
    if value is None or isinstance(value, bool):
        return None
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def _line(full_lines, code: str) -> float | None:
    """Значение строки БФО по коду из payload полной отчётности (уже в рублях,
    см. `fns_client.full_lines_payload`)."""
    for section in full_lines or []:
        for row in section.get("rows") or []:
            if row.get("code") == code:
                return _f(row.get("value_rub"))
    return None


# ЧТО ПОКАЗЫВАТЬ СРАЗУ, А ЧТО ПОД КНОПКОЙ (решение владельца, 19 сентября
# 2026: «слишком много показателей и выглядит как мусор»). Пятнадцать
# карточек с тремя строками пояснения под каждой читаются как свалка, и
# читатель не находит в них того, за чем пришёл.
#
# Наверху — те четыре-пять чисел, которыми компанию описывают в одной фразе
# при разговоре о сделке: «выручка столько, прибыль такая, чистый долг
# такой, долг к прибыли столько». Выручка и чистая прибыль уже стоят выше
# графиками, поэтому сюда идут прибыль до процентов и налога, рентабельность
# по ней, чистый долг, долг к прибыли и оборотный капитал — последний
# потому, что его уровень на закрытии обсуждают в каждой второй сделке.
#
# Остальное не выбрасывается: оно считается по тем же данным и открывается
# кнопкой. Спрятать — не то же самое, что удалить, и разбор глубже одной
# фразы тоже кому-то нужен.
PRIMARY_KEYS = ("ebit", "operating_margin", "net_debt",
                "net_debt_to_operating_profit", "working_capital")


def _money(key, label, value, how, group):
    return {"key": key, "label": label, "kind": "money", "value_rub": value,
            "how": how, "group": group, "primary": key in PRIMARY_KEYS}


def _ratio(key, label, value, how, group, unit="x", digits=2):
    """Отношение. `unit` решает и подпись, и точность: «×2,5» осмысленно с
    сотыми, «192,25 дня» — ложная точность, дни считаются целыми."""
    return {"key": key, "label": label, "kind": "ratio",
            "value": round(value, digits) if digits else round(value),
            "unit": unit, "how": how, "group": group,
            "primary": key in PRIMARY_KEYS}


def _percent(key, label, value, how, group):
    return {"key": key, "label": label, "kind": "percent",
            "value": round(value, 1), "how": how, "group": group,
            "primary": key in PRIMARY_KEYS}


def derive(report: dict) -> dict:
    """Посчитанное по одному годовому отчёту.

    На входе — payload отчёта (`main._report_payload`): 15 нормализованных
    полей в рублях плюс `full_lines`. На выходе — `{"metrics": [...],
    "notes": [...]}`. Метрика, у которой не хватило исходной строки, В ОТВЕТ
    НЕ ПОПАДАЕТ ВОВСЕ: пустое поле честнее прочерка, и прочерк на экране
    читается как «посчитали и вышло ноль».
    """
    r = report or {}
    full_lines = r.get("full_lines")

    revenue = _f(r.get("revenue_rub"))
    op_profit = _f(r.get("operating_profit_rub"))
    pre_tax = _f(r.get("profit_before_tax_rub"))
    net_profit = _f(r.get("net_profit_rub"))
    current_assets = _f(r.get("current_assets_rub"))
    short_term = _f(r.get("short_term_liabilities_rub"))
    long_term = _f(r.get("long_term_liabilities_rub"))
    equity = _f(r.get("equity_rub"))
    borrowings = _f(r.get("borrowings_rub"))
    cash = _f(r.get("cash_rub"))
    inventory = _f(r.get("inventory_rub"))
    receivables = _f(r.get("receivables_rub"))
    payables = _f(r.get("payables_rub"))
    gross_profit = _f(r.get("gross_profit_rub"))
    interest = _line(full_lines, INTEREST_PAID_CODE)
    cost_of_sales = _line(full_lines, COST_OF_SALES_CODE)
    operating_cash = _line(full_lines, OPERATING_CASH_CODE)

    metrics: list[dict] = []
    notes: list[str] = []

    # --- прибыльность --------------------------------------------------
    PROFIT = "Прибыльность"
    # Прибыль до процентов и налога. Проценты к уплате в отчёте стоят со
    # знаком «минус» внутри прибыли до налогообложения — прибавляем модуль,
    # иначе у компании с большим долгом величина уедет в другую сторону.
    if pre_tax is not None and interest is not None:
        metrics.append(_money(
            "ebit", "Прибыль до процентов и налога", pre_tax + abs(interest),
            "Прибыль до налогообложения плюс проценты по кредитам.",
            PROFIT))
    big_revenue = revenue is not None and revenue >= MIN_DENOMINATOR_RUB
    if big_revenue and gross_profit is not None:
        metrics.append(_percent(
            "gross_margin", "Валовая рентабельность", gross_profit / revenue * 100,
            "Сколько остаётся от выручки после себестоимости — до зарплат офиса, "
            "рекламы, процентов и налогов.", PROFIT))
    if big_revenue and op_profit is not None:
        metrics.append(_percent(
            "operating_margin", "Рентабельность по прибыли от продаж",
            op_profit / revenue * 100,
            "Прибыль от продаж, делённая на выручку.", PROFIT))
    # Коммерческие и управленческие расходы считаем как «валовая прибыль минус
    # прибыль от продаж», а не складывая строки 2210 и 2220: знак в этой
    # формуле не участвует вовсе, и упрощённая форма отчётности её не ломает.
    if big_revenue and gross_profit is not None and op_profit is not None:
        metrics.append(_percent(
            "sgna_share", "Расходы на продажи и управление", (gross_profit - op_profit) / revenue * 100,
            "Доля выручки, которая уходит на зарплаты офиса, рекламу и управление — "
            "то есть на всё, что не себестоимость.", PROFIT))
    if revenue is not None and revenue >= MIN_DENOMINATOR_RUB and net_profit is not None:
        metrics.append(_percent(
            "net_margin", "Рентабельность по чистой прибыли",
            net_profit / revenue * 100,
            "Чистая прибыль, делённая на выручку.", PROFIT))
    if net_profit is not None and equity is not None and equity >= MIN_DENOMINATOR_RUB:
        metrics.append(_percent(
            "roe", "Отдача на собственный капитал", net_profit / equity * 100,
            "Чистая прибыль к собственному капиталу: сколько компания заработала "
            "на каждый рубль, вложенный её собственниками.", PROFIT))

    # --- откуда взялась прибыль ------------------------------------------
    # Разница между прибылью до налога и прибылью от продаж — это всё, что
    # компания заработала (или потеряла) НЕ на основной деятельности:
    # дивиденды от дочерних компаний, курсовые разницы, продажа имущества,
    # проценты. Замер того же дня: у «Урбантеха» прибыль до налога
    # 2,2 млрд ₽ при прибыли от продаж 164 млн ₽ — в тринадцать раз больше,
    # и покупателю такой компании важно увидеть это до, а не после сделки.
    SOURCE = "Откуда прибыль"
    if pre_tax is not None and op_profit is not None:
        metrics.append(_money(
            "non_operating_profit", "Прибыль не от продаж", pre_tax - op_profit,
            "Разница между прибылью до налога и прибылью от продаж: дивиденды от "
            "других компаний, курсовые разницы, продажа имущества, проценты. "
            "Со знаком «минус» — основная деятельность кормит всё остальное.", SOURCE))
    if operating_cash is not None and net_profit is not None and net_profit >= MIN_DENOMINATOR_RUB:
        metrics.append(_ratio(
            "cash_conversion", "Денег от работы на рубль прибыли", operating_cash / net_profit,
            "Сколько живых денег принесла текущая работа на каждый рубль чистой прибыли. "
            "Заметно меньше рубля — прибыль есть на бумаге, а деньги застряли "
            "в запасах и долгах покупателей.", SOURCE, unit="₽"))

    # --- оборотный капитал ----------------------------------------------
    WC = "Оборотный капитал"
    if current_assets is not None and short_term is not None:
        metrics.append(_money(
            "working_capital", "Оборотный капитал", current_assets - short_term,
            "Оборотные активы минус краткосрочные обязательства. "
            "Со знаком «минус» — короткие долги больше того, чем компания может их закрыть.",
            WC))
    # Операционный рабочий капитал — то, что в сделках обсуждают как «уровень
    # оборотного капитала на закрытии»: запасы и дебиторка за вычетом того,
    # что компания должна поставщикам. Деньги и кредиты сюда не входят.
    if inventory is not None and receivables is not None and payables is not None:
        metrics.append(_money(
            "operating_working_capital", "Запасы и дебиторка за вычетом кредиторки",
            inventory + receivables - payables,
            "Запасы плюс дебиторская задолженность минус кредиторская. "
            "Столько денег заморожено в текущей работе компании.", WC))
    # Цикл: сколько дней проходит от вложения денег в запасы до возврата
    # деньгами от покупателя, за вычетом отсрочки, которую даёт поставщик.
    # Дни запасов и кредиторки считают к себестоимости, дни дебиторки — к
    # выручке; себестоимость берём по модулю, потому что у неё единственной
    # из трёх знаменателей знак теоретически может разойтись между формами.
    if (inventory is not None and receivables is not None and payables is not None
            and big_revenue and cost_of_sales is not None
            and abs(cost_of_sales) >= MIN_DENOMINATOR_RUB):
        cost = abs(cost_of_sales)
        inventory_days = inventory / cost * DAYS_IN_YEAR
        payable_days = payables / cost * DAYS_IN_YEAR
        receivable_days = receivables / revenue * DAYS_IN_YEAR
        days = inventory_days + receivable_days - payable_days
        metrics.append(_ratio(
            "cash_cycle", "Цикл оборотного капитала", days,
            "Дней от вложения денег в запасы до возврата их от покупателя, за вычетом "
            "отсрочки, которую даёт поставщик. Чем короче, тем меньше денег нужно "
            "держать в обороте.", WC, unit="дн.", digits=0))

    # --- долговая нагрузка ----------------------------------------------
    DEBT = "Долговая нагрузка"
    if borrowings is not None:
        metrics.append(_money(
            "debt", "Кредиты и займы", borrowings,
            "Долгосрочные и краткосрочные заёмные средства вместе. "
            "Задолженность перед поставщиками сюда не входит.", DEBT))
        if cash is not None:
            metrics.append(_money(
                "net_debt", "Чистый долг", borrowings - cash,
                "Кредиты и займы минус деньги на счетах. "
                "Со знаком «минус» — денег на счетах больше, чем долгов.", DEBT))
        if equity is not None and equity >= MIN_DENOMINATOR_RUB:
            metrics.append(_ratio(
                "debt_to_equity", "Долг к собственному капиталу", borrowings / equity,
                "Кредиты и займы, делённые на собственный капитал.", DEBT))
        elif equity is not None and equity < 0:
            notes.append(
                "Собственный капитал отрицательный — накопленные убытки превысили вложения "
                "в компанию. Отношение долга к капиталу в таком случае не считают.")
        if op_profit is not None and cash is not None:
            if op_profit >= MIN_DENOMINATOR_RUB:
                metrics.append(_ratio(
                    "net_debt_to_operating_profit", "Чистый долг к прибыли от продаж",
                    (borrowings - cash) / op_profit,
                    "Примерно столько лет нужно работать с такой же прибылью, чтобы закрыть долг.",
                    DEBT))
            elif op_profit <= 0:
                notes.append(
                    "Прибыли от продаж за этот год нет, поэтому отношение долга к прибыли "
                    "не считаем: делить на убыток бессмысленно.")
    if op_profit is not None and interest is not None and abs(interest) >= MIN_DENOMINATOR_RUB:
        metrics.append(_ratio(
            "interest_coverage", "Прибыль от продаж к процентам по кредитам",
            op_profit / abs(interest),
            "Во сколько раз прибыль от продаж больше процентов, которые компания платит "
            "по кредитам. Меньше единицы — прибыли не хватает даже на проценты.", DEBT))

    if not metrics:
        return {"metrics": [], "notes": []}

    # ОДНО ИСКЛЮЧЕНИЕ ИЗ ПОСТОЯННОГО СПИСКА: «прибыль не от продаж» поднимается
    # наверх, когда её больше, чем прибыли от продаж. Это не украшение —
    # без неё соседнее число вводит в заблуждение: у «Урбантеха» за 2025 год
    # рентабельность по чистой прибыли выходит 93,6%, и выглядит это как
    # выдающийся бизнес, пока не увидишь, что почти вся прибыль пришла не от
    # продаж. Предупреждение показывается тогда, когда есть о чём
    # предупреждать, а не всегда.
    by_key = {m["key"]: m for m in metrics}
    aside, sales = by_key.get("non_operating_profit"), op_profit
    if aside is not None and sales is not None and abs(aside["value_rub"]) > abs(sales):
        aside["primary"] = True

    notes.append(
        "EBITDA по открытой отчётности посчитать нельзя: амортизацию раскрывают в "
        "пояснениях к отчётности, а они в машинном виде не публикуются. Ближайшее, что "
        "считается, — прибыль до процентов и налога.")
    return {"metrics": metrics, "notes": notes}
