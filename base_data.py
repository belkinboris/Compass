# -*- coding: utf-8 -*-
"""Единственная точка чтения `deals_promoted.json` в памяти процесса сайта.

ЗАЧЕМ. До 8 сентября 2026 база (10 МБ на диске) разбиралась заново на
КАЖДЫЙ запрос: `deal_catalog.load_deals()`, `company_catalog.load_company_
catalog()` и `main._read_json` читали один и тот же файл каждый своим
`json.loads`. Один разбор — это ≈72 МБ в памяти, и они складывались:
эндпоинт мультипликаторов читал базу дважды за запрос, а страница любой
сделки — ещё раз на `get_deal()`. Замер: процесс после старта 150 МБ,
после восьми одновременных запросов к аналитике — 725 МБ.

Чем это кончилось. На боевом сервере (1 ГБ) при деплое одновременно живут
старый контейнер, новый и сама сборка; памяти не хватало, и ядро убивало
самый крупный процесс — наш `uvicorn`. Системные инженеры Timeweb прислали
строку OOM-killer от 8 сентября 12:21:19 МСК: `task=uvicorn`,
`anon-rss:489624kB`, `global_oom`. Отсюда всё, что мы видели снаружи:
процесс исчезал без «Shutting down» (SIGKILL не даёт ничего записать),
сайт лежал, деплой падал с «Deploy failed». То есть причина сводилась не к
платформе и не к обработчику остановки, а к тому, сколько мы едим.

УСТРОЙСТВО. Файл читается один раз и живёт в памяти одной копией;
следующий запрос получает ТОТ ЖЕ объект, а не свою копию. Свежесть — по
паре (время правки, размер) файла: `data_refresh` подменяет файл на диске
раз в 5 минут, и подмена сама сбрасывает кэш, ничего звать не нужно.
Блокировка нужна, потому что синхронные обработчики FastAPI выполняются в
пуле потоков: без неё восемь потоков на холодном кэше начали бы разбирать
файл одновременно и вернули бы ровно ту картину, ради которой всё
затевалось.

ПОЧЕМУ ОТДАЁМ ОБЩИЙ ОБЪЕКТ, А НЕ КОПИЮ. Копия стоила бы тех же 72 МБ и
обнулила бы смысл. Это безопасно ровно потому, что проверено: на путях
сайта карточки не изменяются — пишет в них только конвейер
(`facts.derive`, `pipeline/*`), который работает в другом процессе и с
файлом, а не с этим кэшем. Если однажды появится код сайта, которому
нужно изменить карточку, он обязан работать с копией (`copy.deepcopy`), а
не править общий объект: иначе правка молча просочится всем читателям.
"""
from __future__ import annotations

import json
import threading
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent
PROMOTED_PATH = ROOT / "static" / "data" / "deals_promoted.json"

_LOCK = threading.Lock()
_KEY: tuple[float, int] | None = None
_DATA: dict[str, Any] = {}


def _stamp() -> tuple[float, int] | None:
    """(время правки, размер) — по ним видно подмену файла `data_refresh`."""
    try:
        st = PROMOTED_PATH.stat()
    except OSError:
        return None
    return (st.st_mtime, st.st_size)


def promoted() -> dict[str, Any]:
    """Разобранная база: `{'deals': [...], 'companies': {...}, ...}`.

    Возвращает ОБЩИЙ объект — изменять его нельзя (см. докстринг модуля).
    Файл, которого нет или который не разбирается, даёт пустой словарь: сайт
    в этом случае показывает пустую базу, но не падает.
    """
    global _KEY, _DATA
    key = _stamp()
    if key is not None and key == _KEY:
        return _DATA
    with _LOCK:
        # второй поток мог разобрать файл, пока мы ждали блокировку
        key = _stamp()
        if key is not None and key == _KEY:
            return _DATA
        if key is None:
            _KEY, _DATA = None, {}
            return _DATA
        try:
            data = json.loads(PROMOTED_PATH.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            _KEY, _DATA = None, {}
            return _DATA
        _DATA = data if isinstance(data, dict) else {}
        _KEY = key
        return _DATA


def drop() -> None:
    """Забыть разобранную базу. Нужна там, где файл заменили прямо сейчас и
    ждать проверки времени правки не хочется, — и в тестах."""
    global _KEY, _DATA
    with _LOCK:
        _KEY, _DATA = None, {}
