@pytest.mark.parametrize("question", KOMPROMAT)
def test_kompromat_requests_are_refused(question):
    """Главная находка 19 сентября: ассистент шёл в интернет и собирал досье
    на реальные компании и людей из анонимных каналов («Компромат ГРУ») и
    сайтов жалоб, подводя итог словами «компрометирующий материал»."""
    v = policy.classify(question)
    assert v.kind == policy.KOMPROMAT, question
    assert v.refused and v.answer


