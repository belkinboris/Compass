def test_refusal_texts_are_russian_and_offer_help():
    """Отказ 19 сентября приходил по-английски («I'm sorry, but I can't help
    with that») посреди русского интерфейса. И отказ обязан говорить, с чем
    ассистент ПОМОЖЕТ, иначе человек уходит с ощущением, что сервис сломан."""
    for kind, text in policy.ANSWERS.items():
        assert not any(ch.isascii() and ch.isalpha() for ch in text.replace("«", "").replace("»", "")), kind
        assert "Что могу" in text or "могу" in text, kind
        assert len(text) > 120, kind


