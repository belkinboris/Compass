"""Готовые короткие ответы о самом «Компасе» и о двух учебных терминах.

ЗАЧЕМ. Проверка ассистента на 100 вопросах (14 октября 2026) нашла шесть
вопросов новых посетителей, на которые ассистент отвечал отказом «я помогаю
только со сделками»: как подписаться на сделки отрасли, можно ли выгрузить
сделки в Excel, сколько стоит подписка, чем вы отличаетесь от Cbonds и
Интерфакса, что такое M&A, чем сделка отличается от инвестиции. Это первые
вопросы человека, которого мы хотим удержать, а модель о продукте ничего не
знает: поиск по базе ей ничего не даёт, и она честно отказывает.

Ответ на такие вопросы не зависит ни от поиска, ни от модели — поэтому он
готовый и мгновенный, как рассказ о сервисе (`about_answer` в
assistant_retrieval.py). Каждый текст сверен с тем, что сейчас есть на
сайте (static/index.html): кнопка «Выгрузить в таблицу» на странице сделок,
«Следить за сделками компании / отрасли», блок «Новая подписка» в кабинете,
пункт пользовательского соглашения «сейчас все функции Сервиса
предоставляются бесплатно». Поменялся сайт — поменяйте текст здесь.

Признаки узкие: вопрос о сделке («сколько стоила Азбука вкуса», «кто
конкуренты Магнита», «подписание сделки») сюда попадать не должен — держит
`test_product_answers_do_not_catch_questions_about_deals` на 500+ вопросах
из живой базы.
"""
from __future__ import annotations

import re
from urllib.parse import quote


def _n(question: str) -> str:
    """Нижний регистр, ё→е, только буквы и цифры: «M&A» превращается в «m a»."""
    low = (question or "").lower().replace("ё", "е")
    return re.sub(r"[^0-9a-zа-я]+", " ", low).strip()


_MA = r"(?:m\s?a|м\s?а|mna|слияни\w*\s+и\s+поглощени\w*|слияни\w*|поглощени\w*)"

# «Что такое M&A», «M&A — это что?», «объясни, что значит M&A».
_MA_DEF = re.compile(
    rf"\bчто\s+(?:такое|значит|означает)\s+(?:сделк\w*\s+|рынок\s+)?{_MA}\b"
    rf"|^(?:а\s+)?{_MA}\s+(?:это\s+)?что(?:\s+такое)?$"
    rf"|\b(?:объясни\w*|расскажи\w*)\s+(?:\w+\s+){{0,3}}?(?:что\s+такое\s+)?{_MA}\b"
)
# «Чем сделка M&A отличается от инвестиции?», «разница между M&A и инвестицией».
_VS_INVEST = re.compile(
    r"\b(?:чем|в\s+чем)\s+(?:\w+\s+){0,4}?отлича\w*\s+(?:\w+\s+){0,2}?(?:от\s+)?(?:\w+\s+)?инвестиц"
    r"|\bразниц\w*\s+(?:\w+\s+){0,5}?инвестиц"
    r"|\bинвестиц\w*\s+(?:\w+\s+){0,3}?(?:и|или|vs|против)\s+(?:сделк\w*\s+)?" + _MA
)
_MA_OR_DEAL = re.compile(rf"\b{_MA}\b|\bсделк")

# Цена: «сколько стоит подписка», «это платно?», «какие тарифы».
_PRICE = re.compile(
    r"\bсколько\s+(?:стоит|стоят|будет\s+стоить)\b|\bстоимост\w*\b|\bцен[аы]\b|\bтариф\w*"
    r"|\bплатн\w*|\bбесплатн\w*|\bоплат\w*|\bпрайс\w*|\bзаплатить\b"
)
_PRICE_OBJECT = re.compile(
    r"\bподписк\w*|\bдоступ\w*|\bсервис\w*|\bкомпас\w*|\bтариф\w*|\bпользовани\w*|\bассистент\w*"
    r"|\bаккаунт\w*|\bрегистрац\w*|\bу\s+вас\b|\bвам\b|\bпользоваться\b|^(?:а\s+)?это\s+(?:бес)?платн"
)

# Подписка: «как подписаться на новые сделки в отрасли», «как следить за компанией».
_SUBSCRIBE = re.compile(
    r"\bподписаться\b|\bподпишусь\b|\bподписк\w*|\bследить\s+за\b|\bотслеживать\b"
    r"|\b(?:получать|приходят|приходили)\s+(?:\w+\s+)?(?:уведомлени\w*|оповещени\w*)"
    r"|\bуведомлени\w*\s+о\s+(?:новых|сделках)"
)

# Выгрузка: «можно ли выгрузить список сделок в Excel».
_EXPORT_VERB = re.compile(r"\bвыгруз\w*|\bскача\w*|\bэкспорт\w*|\bсохранить\b|\bвыгрузк\w*")
_EXPORT_WHAT = re.compile(r"\bexcel\b|\bэксел\w*|\bэксель\w*|\bxlsx?\b|\bcsv\b|\bтаблиц\w*|\bсписок\b|\bсписк\w*|\bфайл\w*|\bсделк\w*")

# Вопрос «как / можно ли / где» — признак вопроса о пользовании сайтом.
_HOW = re.compile(r"\bкак\b|\bможно\s+ли\b|\bможно\b|\bгде\b|\bмогу\s+ли\b|\bесть\s+ли\b|\bхочу\b|\bполучится\s+ли\b|\bумеет\w*\b|\bумеешь\b")

# Сравнение с другими службами.
_RIVAL = re.compile(r"\bcbonds\b|\bсибондс\w*|\bинтерфакс\w*|\binterfax\b|\bспарк\w*|\bspark\b|\bdealmap\b|\bmergermarket\b")
_RIVAL_ASK = re.compile(r"\bотлича\w*|\bлучше\b|\bразниц\w*|\bсравн\w*|\bвместо\b|\bзачем\b|\bпочему\b")
_RIVAL_GENERIC = re.compile(
    r"\b(?:ваш\w*|у\s+вас|у\s+компаса|компаса)\s+(?:\w+\s+)?(?:конкурент\w*|аналог\w*)"
    r"|\b(?:конкурент\w*|аналог\w*)\s+(?:\w+\s+)?(?:компаса|сервиса|вашего|у\s+вас)"
    r"|\bчем\s+(?:вы|компас\w*|сервис\w*)\s+(?:\w+\s+)?(?:отлича\w*|лучше)"
)

# Рост через покупки: «Как вырастить свой бизнес через покупки?» (№90 третьей
# проверки, 18 октября 2026) — модель отказывала «я только о сделках», хотя
# ответ на примерах из базы есть. Нужны «как», рост и покупки, и вопрос — о
# своём бизнесе или вообще, а не о названной компании («Как Яндекс растёт
# через покупки?» идёт обычным путём, к её сделкам).
_GROW = re.compile(r"\b(?:вырасти\w*|выращива\w*|расти|растить|рост\w*|развива\w*|развити\w*|масштабир\w*|увелич\w*)\b")
_BY_BUYING = re.compile(r"\b(?:через|за\s+сч[её]т|с\s+помощью|путем|покупкам\w*)\s+(?:\w+\s+)?"
                        r"(?:покуп\w*|поглощени\w*|приобретени\w*|слияни\w*|m\s?a|м\s?а|сделк\w*)"
                        r"|\bпокупая\s+(?:другие\s+|чужие\s+)?(?:компани\w*|бизнес\w*)")
_OWN_OR_GENERIC = re.compile(r"\b(?:сво\w*|мо[йюяе]\w*|наш\w*|бизнес|компани\w*|фирм\w*)\b")

# Какие финансы есть в базе: «В базе есть информация о EBIT компаний?», «А какие
# финансовые метрики есть в базе?» (партнёр, 21 октября 2026). Модель ответила
# «финансовых показателей в Компасе нет», хотя профиль компании показывает
# отчётность ФНС, а «Аналитика» — мультипликаторы. Вопрос о базе вообще, а не о
# названной компании: «EBIT Магнита» идёт обычным путём, к её цифрам.
_FIN_METRIC = re.compile(
    r"\bebit\w*|\bebitda\b|\bвыручк\w*|\bприбыл\w*|\bмаржинальн\w*|\bмарж[аиу]\b|\bрентабельн\w*"
    r"|\bмультипликатор\w*|\bфинансов\w*\s+(?:метрик\w*|показател\w*|данн\w*|отчетност\w*|информаци\w*)"
    r"|\bфинанс\w*\s+компани\w*|\bотчетност\w*")
_IN_BASE = re.compile(
    r"\bв\s+(?:вашей\s+|этой\s+)?базе\b|\bв\s+компасе\b|\bу\s+вас\b|\bна\s+сайте\b|\bв\s+сервисе\b"
    r"|\bкакие\s+(?:\w+\s+)?(?:финансов\w*\s+)?(?:метрик\w*|показател\w*|данн\w*)\s+(?:\w+\s+)?есть\b")

# Названная компания («выручка у Магнита в базе») — обычный путь, к её цифрам.
_NAMED = re.compile(r"\b(?!Компас)[А-ЯЁA-Z][а-яёa-z]{2,}")

SUBSCRIBE, EXPORT, PRICE, RIVALS, WHAT_IS_MA, MA_VS_INVESTMENT, GROW_BY_MA, FINANCE = (
    "subscribe", "export", "price", "rivals", "what_is_ma", "ma_vs_investment", "grow_by_ma", "finance")


def kind(question: str) -> str | None:
    """Какой готовый ответ подходит вопросу; None — обычный путь ассистента."""
    q = _n(question)
    if not q or len(q) > 220:
        return None
    if _VS_INVEST.search(q) and _MA_OR_DEAL.search(q):
        return MA_VS_INVESTMENT
    if _MA_DEF.search(q):
        return WHAT_IS_MA
    if _FIN_METRIC.search(q) and _IN_BASE.search(q) and len(q.split()) <= 16 \
            and not _NAMED.search((question or "").strip()[1:]):
        return FINANCE
    if (_RIVAL.search(q) and _RIVAL_ASK.search(q)) or _RIVAL_GENERIC.search(q):
        return RIVALS
    if _PRICE.search(q) and _PRICE_OBJECT.search(q):
        return PRICE
    if _EXPORT_VERB.search(q) and _EXPORT_WHAT.search(q) and _HOW.search(q):
        return EXPORT
    if _SUBSCRIBE.search(q) and _HOW.search(q):
        return SUBSCRIBE
    if re.match(r"(?:а\s+)?(?:как|каким\s+образом|можно\s+ли)\b", q) and _GROW.search(q) \
            and _BY_BUYING.search(q) and _OWN_OR_GENERIC.search(q) and len(q.split()) <= 14:
        return GROW_BY_MA
    return None


def _deal_link(doc) -> str:
    return f"[{doc.title}](#/deal/{doc.id})"


def _ma_example(idx):
    """Крупнейшая закрытая сделка M&A с названной ценой (не обратный выкуп
    своих акций): пример, который узнает любой читатель новостей."""
    docs = [d for d in idx.docs if d.type == "M&A" and d.status == "Закрыта" and d.sum_rub
            and not d.estimate and not re.search(r"buyback|выкуп\w*\s+(?:собственн|своих)", d.title, re.I)]
    return max(docs, key=lambda d: d.sum_rub) if docs else None


def _investment_example(idx):
    """Свежая закрытая инвестиция с названной суммой — именно раунд в
    компанию («привлекла», «инвестировал»), а не запуск фонда."""
    docs = [d for d in idx.docs if d.type == "Инвестиция" and d.status == "Закрыта" and d.sum_rub
            and re.search(r"привлек|инвестировал|раунд", d.title, re.I)]
    return max(docs, key=lambda d: d.date or "") if docs else None


def _deal_count(idx) -> int:
    # Как в рассказе о сервисе: лоты торгов, которые никто не купил, сделками не считаются.
    return sum(1 for d in idx.docs if not (d.type == "Продажа с торгов" and d.status != "Закрыта"))


def _serial_buyers(idx, limit: int = 5) -> list[tuple[str, str, int, object]]:
    """Самые частые покупатели базы — тот же счёт, что у рейтинга покупателей
    ассистента и «Аналитики»: лоты торгов, которые никто не купил, не в счёт.
    (id, имя, число покупок, последняя закрытая покупка)."""
    from collections import Counter
    own: dict[str, list] = {}
    for d in idx.docs:
        if d.type == "Продажа с торгов" and d.status != "Закрыта":
            continue
        cid = (d.raw or {}).get("buyer")
        if cid in idx.companies:
            own.setdefault(cid, []).append(d)
    cnt = Counter({cid: len(v) for cid, v in own.items()})
    out = []
    for cid, n in cnt.most_common(limit):
        closed = [d for d in own[cid] if d.status == "Закрыта"] or own[cid]
        last = max(closed, key=lambda d: d.date or "")
        out.append((cid, (idx.companies.get(cid) or {}).get("name") or cid, n, last))
    return out


