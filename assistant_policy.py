# -*- coding: utf-8 -*-
"""Политика ассистента: на какие вопросы «Компас» не отвечает вовсе.

ЗАЧЕМ ОТДЕЛЬНЫЙ СЛОЙ, А НЕ СТРОКА В СИСТЕМНОМ ПРОМПТЕ. 19 сентября 2026
партнёр (Ксюша) и Артём прогнали ассистента по «неудобным» вопросам, и
выяснилось, что отказывать ему, по сути, нечем:

  * «Найди компромат на ВТБ» и «Найди компромат на Никольскую Консалтинг» —
    ассистент послушно шёл в интернет и СОБИРАЛ досье: обвинения из каналов
    с говорящими названиями («Компромат ГРУ»), с сайтов жалоб, с именами
    конкретных живых юристов, и сам подводил итог словами «это упоминание
    используется как компрометирующий материал, связывающий фирму с
    потенциальными финансовыми махинациями». Про реальную юрфирму и
    реального человека. Реакция партнёра: «Ему надо как-то заблочить всю
    эту херню».
  * «Какие сделки совершены в нарушение закона?» — первым сообщением
    называл реальную сделку и реальные имена сторон, как будто отвечая по
    существу, и только вторым, после переформулировки, признавал, что
    признаков незаконности ни в базе, ни в источниках нет.
  * «Нужно ли удостоверять ДКП доли у нотариуса?», «а если не удостоверю,
    что будет?» — выдавал полноценную юридическую консультацию со
    ссылками на Росреестр и КонсультантПлюс.
  * «Хочу купить акции Сбербанка. Стоит?» — пересказывал прогнозы
    аналитиков.

Во всех четырёх случаях модель вела себя ровно так, как ей велено: в
SYSTEM_WEB написано «от тебя ждут вывод, а не пересказ выдачи». Дефект не
в формулировке промпта, а в том, что НИКТО НЕ РЕШАЛ, отвечать ли на этот
вопрос вообще. Отказ, если и случался, рождался внутри модели —
недетерминированно, иногда по-английски («I'm sorry, but I can't help with
that»), и ПОСЛЕ того, как поиск уже сходил в интернет и притащил ссылки,
которые интерфейс всё равно показывал рядом с отказом.

Поэтому решение — не ещё одна строка в промпте (её модель имеет право
понять по-своему), а ГЕЙТ ПЕРЕД ВСЕМ ОСТАЛЬНЫМ: чистая функция без сети и
без модели, которая смотрит на вопрос и говорит «на это мы не отвечаем» с
готовым русским текстом. Тот же приём, что уже стоит в `promote.py` на
воротах притока: механика отвечает за «этого брать нельзя», чтение (здесь —
модель) за «что здесь на самом деле сказано».

ЧТО ЭТО ДАЁТ, КРОМЕ САМОГО ОТКАЗА:
  * запрос не уходит ни в Яндекс, ни в модель — ни денег, ни секунд, ни
    «источников», которые нечем оправдать;
  * текст отказа один и тот же, по-русски, и лежит в одном месте — его
    можно прочитать глазами и поправить, не трогая поведение модели;
  * поведение проверяется тестом на реальных вопросах из переписки, а не
    «кажется, модель теперь откажет».

ГРАНИЦА. Гейт ловит то, что опознаётся ПО СЛОВАМ вопроса: просьбу собрать
негатив, просьбу дать юридическую или инвестиционную консультацию, вопрос,
который просит назвать сделки незаконными. Он НЕ пытается распознать
«вопрос не по теме» вообще (песня, знакомства, видеоигры) — у таких
вопросов нет общего словаря, регулярка на них давала бы ложные отказы на
живых вопросах о рынке. Это остаётся модели, которая с ними справляется, —
а код отвечает за то, чтобы к её отказу не подставлялись случайные ссылки
из поиска (см. `looks_like_refusal`).
"""
from __future__ import annotations

import re
from dataclasses import dataclass

OK = "ok"
KOMPROMAT = "kompromat"
LEGAL_ADVICE = "legal_advice"
INVESTMENT_ADVICE = "investment_advice"
WRONGDOING = "wrongdoing"


@dataclass(frozen=True)
class Verdict:
    kind: str
    answer: str = ""

    @property
    def refused(self) -> bool:
        return self.kind != OK


# Тексты отказов. Правило «язык для людей» из CLAUDE.md: так, как сказали бы
# вслух коллеге. Каждый отказ обязан не просто отказывать, а говорить, с чем
# ассистент ПОМОЖЕТ, — иначе человек уходит с пустыми руками и ощущением,
# что сервис сломался.
ANSWERS = {
    KOMPROMAT: (
        "«Компас» — справочник о сделках, а не досье на компании и людей. "
        "Собирать негатив, компромат или обвинения я не буду: в открытых источниках "
        "такое обычно приходит из анонимных каналов и сайтов жалоб, проверить это "
        "нечем, а речь о реальных людях и фирмах.\n\n"
        "Что могу: рассказать о сделках компании, её роли покупателя или продавца, "
        "показателях из отчётности и о том, кто сделку сопровождал."
    ),
    LEGAL_ADVICE: (
        "Юридических консультаций я не даю — «Компас» рассказывает о том, как прошли "
        "конкретные сделки, а не о том, как оформить вашу.\n\n"
        "Что могу: показать, как была устроена похожая сделка из базы, какие "
        "согласования в ней упоминались и какие юрфирмы её сопровождали. "
        "По самому правовому вопросу лучше поговорить с юристом."
    ),
    INVESTMENT_ADVICE: (
        "Советов, что покупать и продавать, я не даю — это не то, чем занимается «Компас».\n\n"
        "Что могу: рассказать о сделках с участием компании, о её выручке и прибыли "
        "по отчётности и о том, за сколько её покупали, если сумма раскрывалась."
    ),
    WRONGDOING: (
        "«Компас» не помечает сделки как законные или незаконные и не оценивает, "
        "нарушил ли кто-то санкции или закон: мы записываем только то, что стороны, "
        "консультанты и деловые СМИ раскрыли публично. Такого признака в базе нет, и "
        "называть конкретные сделки в ответ на такой вопрос я не стану — это были бы "
        "обвинения в адрес реальных компаний без каких-либо оснований.\n\n"
        "Что могу: показать сделки, которые не состоялись, которые проходили "
        "согласование ФАС или правкомиссии, или те, где стороны публично спорили."
    ),
}


def _n(question: str) -> str:
    """Нормализованный вопрос: нижний регистр, ё→е, только буквы и цифры."""
    low = (question or "").lower().replace("ё", "е")
    return re.sub(r"[^0-9a-zа-я]+", " ", low).strip()


# --- компромат ---------------------------------------------------------------
# Прямая просьба собрать негатив. Слова выбраны так, чтобы они означали САМО
# НАМЕРЕНИЕ, а не тему: «компромат», «дискредитирующий», «что плохого».
# «Скандал» и «расследование» сюда НЕ входят: «сделка сорвалась из-за скандала»
# и «расследование ФАС» — обычные вопросы про рынок. «Досье» тоже НЕ входит,
# хотя просилось: это слово нашего же интерфейса — на странице компании стоит
# ссылка «Полное досье компании», и «нужно досье на X» читается как просьба
# открыть профиль, а не накопать грязи.
_KOMPROMAT = re.compile(
    r"компромат"
    r"|компрометирующ"
    r"|дискредитир"
    r"|порочащ"
    r"|(?:собери|найди|нужен|нужна|нужно|есть|поищи|ищу|накопай|раскопай|подбери)\w*\s+"
    r"(?:\w+\s+){0,3}?(?:негатив|грязь)"
    r"|(?:негатив|грязь)\w*\s+(?:на|о|про)\s"
    r"|что\s+(?:плохого|дурного|нехорошего)\s+(?:известно\s+)?(?:о|про|на)\s"
    r"|чем\s+(?:можно\s+)?(?:очернить|опорочить)"
)

# --- вопрос-обвинение --------------------------------------------------------
# «Назови сделки, которые незаконны / нарушили санкции / сделаны в обход
# закона». Опасность не в теме, а в форме: вопрос просит СПИСОК РЕАЛЬНЫХ
# СДЕЛОК под обвинительным ярлыком, и любой названный в ответ становится
# обвинённым. Требуем И обвинительное слово, И разговор о сделках/компаниях,
# чтобы «незаконная перепланировка» из чужого контекста не ловилась.
_ACCUSATION = re.compile(
    r"незаконн"
    r"|неправомерн"
    r"|противозаконн"
    r"|в\s+нарушение\s+закон"
    r"|нарушал\w*\s+(?:закон|санкцион|санкци)"
    r"|нарушен\w*\s+(?:закон|санкцион|санкци)"
    r"|нарушил\w*\s+(?:закон|санкцион|санкци)"
    r"|обход\w*\s+(?:закон|санкци)"
    r"|мошенничеств"
    r"|отмыван\w*\s+"
    r"|коррупцион"
    r"|преступн"
    r"|в\s+обход\s+"
    r"|без\s+(?:должного|надлежащего|необходимого)\s+согласован"
    r"|нарушал\w*\s+государственн"
    r"|признак\w*\s+незаконн"
)
_DEAL_SUBJECT = re.compile(r"сделк|покупк|компани|актив|бизнес|фирм|банк|холдинг|группа")

# --- юридическая консультация ------------------------------------------------
# Вопрос не о конкретной сделке рынка, а «как мне оформить / что мне будет».
# Признак — связка «модальность обращения к себе» + правовая материя.
_LEGAL_MATTER = re.compile(
    r"нотариус|нотариальн|удостоверя|удостовер|договор\w*\s+купли|дкп"
    r"|устав\w*\b|доверенност|госпошлин|регистрац\w*\s+прав|росреестр"
    r"|преимущественн\w*\s+прав|оферт|акцепт|неустойк|штраф"
    r"|налогообложен|ндфл|ндс\b|подсудн|исков\w*\s+давност"
    r"|corporate\s+action|due\s+diligence\s+как"
)
_ADVICE_FRAME = re.compile(
    r"\bнужно\s+ли\b|\bобязательно\s+ли\b|\bнадо\s+ли\b|\bможно\s+ли\s+(?:мне|нам|я)\b"
    r"|\bимею\s+ли\s+я\b|\bвправе\s+ли\b|\bдолжен\s+ли\s+я\b"
    r"|\bкак\s+(?:мне|нам)\b|\bчто\s+(?:мне|нам)\s+(?:делать|грозит|будет)\b"
    # «А если я его не удостоверю, то что будет?» — продолжение консультации:
    # само по себе слово-маркер правовой материи уже стоит рядом (проверка
    # идёт через И с `_LEGAL_MATTER`), поэтому «что будет» здесь безопасно:
    # на «что будет с компанией после сделки» оно одно не сработает.
    r"|\bчто\s+будет\b|\bесли\s+(?:я|мы)\b(?:\s+\w+){0,2}\s+не\b|\bесли\s+не\s+удостовер"
    r"|\bкак\s+(?:правильно\s+)?(?:оформить|составить|заключить|провести|зарегистрировать)\b"
    r"|\bкакие\s+документы\s+(?:нужны|нужно|требуются)\b"
    r"|\bгрозит\s+ли\b|\bчем\s+это\s+грозит\b"
)

# --- инвестиционный совет ----------------------------------------------------
_INVEST = re.compile(
    r"\bстоит\s+ли\s+(?:мне\s+|сейчас\s+)?(?:покупать|купить|брать|вкладывать|инвестировать|продавать)"
    r"|\b(?:хочу|планирую|собираюсь)\s+(?:купить|приобрести|вложить)\w*\s+(?:акци|облигац|бумаг|долю\s+в)"
    r"|\bкуда\s+(?:лучше\s+)?(?:вложить|инвестировать)"
    r"|\bво\s+что\s+(?:вложить|инвестировать)"
    r"|\bкакие\s+акци\w*\s+(?:купить|покупать|брать|выбрать)"
    r"|\b(?:выгодно|прибыльно)\s+ли\s+(?:покупать|вкладывать|инвестировать)"
    r"|\bдержать\s+или\s+продавать"
    r"|\bбудут\s+ли\s+расти\s+акци"
    r"|\bпрогноз\w*\s+(?:цены|курса)\s+акци"
    r"|\bкакие\s+бумаги\s+(?:купить|брать)"
)
# «Хочу купить акции Сбербанка. Стоит?» — совет спрашивают вторым предложением,
# без глагола. Ловится парой «намерение купить бумаги» + «стоит».
_INVEST_INTENT = re.compile(r"(?:купить|покупк\w*|приобрести|вложить\w*)\s+(?:\w+\s+){0,2}?(?:акци|облигац|бумаг|пае)")
_INVEST_ASK = re.compile(r"\bстоит\b|\bсовету\w*\b|\bкак\s+думаешь\b|\bчто\s+скажешь\b|\bразумно\s+ли\b")


def classify(question: str) -> Verdict:
    """Решение о вопросе ДО поиска и модели. Возвращает Verdict; `refused`
    False — обычный путь ассистента, True — готовый ответ, дальше не идём."""
    q = _n(question)
    if not q:
        return Verdict(OK)

    if _KOMPROMAT.search(q):
        return Verdict(KOMPROMAT, ANSWERS[KOMPROMAT])

    if _ACCUSATION.search(q) and _DEAL_SUBJECT.search(q):
        return Verdict(WRONGDOING, ANSWERS[WRONGDOING])

    if _INVEST.search(q) or (_INVEST_INTENT.search(q) and _INVEST_ASK.search(q)):
        return Verdict(INVESTMENT_ADVICE, ANSWERS[INVESTMENT_ADVICE])

    if _LEGAL_MATTER.search(q) and _ADVICE_FRAME.search(q):
        return Verdict(LEGAL_ADVICE, ANSWERS[LEGAL_ADVICE])

    return Verdict(OK)


# Отказ, который написала САМА модель (вопрос не по теме: песня, знакомства,
# видеоигры). Гейт такие не ловит и не должен, но код обязан узнать отказ,
# чтобы не подставлять к нему список найденных в интернете ссылок: 19 сентября
# 2026 к отказу отвечать про знакомства прилетели ссылки на форумы «Отношения
# с бывшим зеком» — их добавил `_sources_footer`, потому что в ответе не было
# ни одной markdown-ссылки, и код решил, что модель «забыла» процитировать.
_REFUSAL_MARKERS = re.compile(
    r"не\s+могу\s+помочь"
    r"|могу\s+помочь\s+только"
    r"|не\s+даю\s+(?:юридическ|инвестиционн|консультац)"
    r"|не\s+отвеча\w*\s+на\s+так"
    r"|(?:это\s+)?не\s+(?:моя\s+тема|по\s+теме)"
    r"|только\s+по\s+вопросам,?\s+связанным\s+со\s+сделк"
    r"|i\s*'?m\s+sorry|i\s+can\s*'?t\s+help",
    re.I,
)


def looks_like_refusal(answer: str) -> bool:
    """Похоже ли, что модель отказалась отвечать. Нужно ровно для одного
    решения: показывать ли рядом найденные в интернете источники."""
    head = " ".join((answer or "").split())[:400].replace("ё", "е")
    return bool(_REFUSAL_MARKERS.search(head))
