# ------------------------------------------------------------------ расчёт
PAID_ROW = None      # заполняется первым построенным листом расчёта


def sheet_calc(wb, ref, scen_letter, scen_name):
    """Помесячный расчёт одной цены: воронка, выручка, расходы, налоги, деньги."""
    global PAID_ROW
    ws = wb.create_sheet("Расчёт %s" % scen_name)
    ws.column_dimensions["A"].width = 44
    ws.freeze_panes = "B4"
    for i in range(MONTHS):
        ws.column_dimensions[get_column_letter(2 + i)].width = 12

    A = lambda key: "Допущения!$%s$%d" % (scen_letter, ref[key])   # noqa: E731
    col = lambda i: get_column_letter(2 + i)                       # noqa: E731

    r = 1
    put(ws, r, 1, "Расчёт по месяцам — подписка %s в месяц" % scen_name, H1); r += 1
    put(ws, r, 1, "Каждая клетка — формула от листа «Допущения», колонка %s. Меняете там — меняется здесь."
        % scen_letter, SMALL); r += 1

    put(ws, r, 1, "Месяц", BOLD, fill=FILL_HEAD)
    for i in range(MONTHS):
        put(ws, r, 2 + i, month_name(i), BOLD, fill=FILL_HEAD)
    r += 1

    def line(name, formula, fmt=RUB, font=NORM, note=None):
        nonlocal r
        put(ws, r, 1, name, font)
        for i in range(MONTHS):
            put(ws, r, 2 + i, formula(i), font, fmt=fmt)
        if note:
            put(ws, r, 2 + MONTHS, note, SMALL, wrap=True)
        r += 1
        return r - 1

    def sec(title):
        nonlocal r
        put(ws, r, 1, title, H2, fill=FILL_HEAD)
        for c in range(2, 2 + MONTHS):
            ws.cell(row=r, column=c).fill = FILL_HEAD
        r += 1

    sec("Воронка")
    seen = line("Зарегистрировано всего (накопленно)", lambda i: "", RUB0)
    org = line("  из них органических за месяц", lambda i: "", RUB0)
    paid_reg = line("  из них из платного продвижения", lambda i: "=%s/%s" % (A("mkt"), A("cpr")), RUB0,
                    note="Бюджет продвижения, делённый на стоимость одной регистрации. Вот здесь "
                         "деньги превращаются в людей — и здесь же видно, во сколько это обходится.")
    reg = line("Регистраций за месяц", lambda i: "", RUB0,
               note="Рост гасится по мере заполнения рынка: множитель «сколько ещё осталось "
                    "незарегистрированных» из потолка. Без него экспонента обещает рост, "
                    "которому неоткуда взяться.")
    for i in range(MONTHS):
        room = ("MAX(0,1-%s%d/%s)" % (col(i - 1), seen, A("ceiling"))) if i else "1"
        ws.cell(row=org, column=2 + i,
                value="=%s*(1+%s)^%d" % (A("reg_org0"), A("reg_growth"), i)).number_format = RUB0
        ws.cell(row=reg, column=2 + i,
                value="=ROUND((%s%d+%s%d)*%s,0)" % (col(i), org, col(i), paid_reg, room)
                ).number_format = RUB0
        ws.cell(row=seen, column=2 + i,
                value=("=%s%d" % (col(i), reg)) if i == 0
                      else "=%s%d+%s%d" % (col(i - 1), seen, col(i), reg)).number_format = RUB0
    new = line("Новых платящих за месяц",
               lambda i: "=IFERROR(ROUND(INDEX($B$%d:$%s$%d,1,COLUMN()-1-%s)*%s,0),0)"
                         % (reg, col(MONTHS - 1), reg, A("conv_lag"), A("conv")), RUB0,
               note="Регистрация превращается в оплату не сразу: воронка с задержкой из допущений.")
    paid = line("Платящих всего на конец месяца", lambda i: "", RUB0)
    for i in range(MONTHS):
        if i == 0:
            body = "%s+%s%d" % (A("paid0"), col(i), new)
        else:
            body = ("%s%d*(1-%s*(1-%s*%d/%d))+%s%d"
                    % (col(i - 1), paid, A("churn"), A("share_y"), i, MONTHS, col(i), new))
        # Больше, чем есть на рынке готовых платить, взяться неоткуда.
        ws.cell(row=paid, column=2 + i,
                value="=MIN(%s,%s*%s)" % (body, A("ceiling"), A("pay_share"))).number_format = RUB0
    put(ws, paid, 2 + MONTHS,
        "Годовые подписки не отваливаются помесячно — доля годовых растёт линейно и гасит отток.",
        SMALL, wrap=True)
    if PAID_ROW is None:
        PAID_ROW = paid

    sec("Выручка")
    rev = line("Выручка за месяц",
               lambda i: "=%s%d*(%s*(1-%s*%d/%d)+%s/12*%s*%d/%d)"
                         % (col(i), paid, A("price_m"), A("share_y"), i, MONTHS,
                            A("price_y"), A("share_y"), i, MONTHS),
               note="Годовая подписка признаётся равномерно (1/12 в месяц) — так честнее для P&L. "
                    "Деньгами она приходит сразу, это видно в строке ниже.")
    cash_in = line("Поступило денег за месяц",
                   lambda i: "=%s%d+%s%d*%s*%d/%d*(%s-%s/12)"
                             % (col(i), rev, col(i), new, A("share_y"), i, MONTHS,
                                A("price_y"), A("price_y")),
                   note="Годовые подписчики платят за год вперёд: в месяц продажи приходит вся сумма.")

    sec("Расходы")
    host = line("Хостинг и домен", lambda i: "=%s" % A("host"))
    ai = line("Ассистент", lambda i: "=%s+%s%d*%s" % (A("ai"), col(i), paid, A("ai_per_user")))
    fns = line("API-ФНС", lambda i: "=%s" % A("fns"))
    kassa = line("Онлайн-касса и чеки (54-ФЗ)", lambda i: "=%s" % A("kassa"),
                 note="Статья, которой не было бы при продаже компаниям по счёту.")
    acc = line("Бухгалтерия", lambda i: "=%s" % A("acc"))
    regi = line("Реестродержатель (АО)", lambda i: "=%s" % A("reg"))
    legal = line("Юрист и товарный знак", lambda i: "=%s" % A("legal"))
    mkt = line("Платное продвижение", lambda i: "=%s" % A("mkt"))
    misc = line("Прочее", lambda i: "=%s" % A("misc"))
    acq = line("Комиссия за приём платежей", lambda i: "=%s%d*%s" % (col(i), cash_in, A("acq")))
    refund = line("Возвраты", lambda i: "=%s%d*%s" % (col(i), rev, A("refund")),
                  note="Право физлица отказаться от неиспользованного периода.")
    gd = line("Зарплата гендиректора", lambda i: "=%s" % A("gd_salary"))
    team = line("Команда на подряде", lambda i: "=%s" % A("team_cost"))
    dev = line("Разработчик", lambda i: "=IF(%d>=%s,%s,0)" % (i + 1, A("dev_start"), A("dev_cost")))
    ins = line("Страховые взносы за гендиректора",
               lambda i: "=MAX(%s,%s)*%s" % (A("gd_salary"), A("mrot"), A("ins_rate")), RUB, RED,
               note="ОБЯЗАТЕЛЬНЫ С 01.01.2026 даже без трудового договора и без зарплаты: "
                    "ФЗ от 28.11.2025 № 425-ФЗ изменил п. 1 ст. 421 НК РФ. Подробности — "
                    "на листе «Налоги и риски».")
    costs = line("Расходы всего",
                 lambda i: "=SUM(%s%d:%s%d)" % (col(i), host, col(i), ins), RUB, BOLD)

    sec("Налоги")
    rev_ytd = line("Доход накопленным итогом за год",
                   lambda i: "=SUM($%s$%d:%s%d)" % (col(max(0, 3 - 0 if False else (0 if i < 3 else 3))), rev, col(i), rev)
                   if False else "=SUM($%s$%d:%s%d)" % (col(0 if i < 3 else 3), rev, col(i), rev),
                   note="Год считается календарный: старт в октябре, поэтому первый календарный год "
                        "у нас три месяца, а полный год начинается с января.")
    vat = line("НДС",
               lambda i: "=IF(%s%d>%s,%s%d*%s,0)" % (col(i), rev_ytd, A("vat_limit"), col(i), rev, A("vat_rate")),
               note="Пока доход с начала года не перевалил за 20 млн ₽ — НДС нет вовсе.")
    base = line("База УСН (доходы минус расходы)",
                lambda i: "=%s%d-%s%d-%s%d" % (col(i), rev, col(i), costs, col(i), vat))
    usn = line("Налог УСН",
               lambda i: "=MAX(%s%d*%s,%s%d*%s)" % (col(i), base, A("usn"), col(i), rev, A("usn_min")),
               note="Большее из двух: 15% с разницы или 1% с дохода. В убыточные месяцы платится "
                    "минимальный налог — его платят и при убытке, это регулярно забывают.")
    taxes = line("Налоги всего", lambda i: "=%s%d+%s%d" % (col(i), vat, col(i), usn), RUB, BOLD)

    sec("Итог")
    prof = line("Прибыль до налогов", lambda i: "=%s%d-%s%d" % (col(i), rev, col(i), costs), RUB, BOLD)
    net = line("Чистая прибыль", lambda i: "=%s%d-%s%d" % (col(i), prof, col(i), taxes), RUB, BOLD)
    flow = line("Денежный поток за месяц",
                lambda i: "=%s%d-%s%d-%s%d" % (col(i), cash_in, col(i), costs, col(i), taxes), RUB, BOLD)
    cash = line("Деньги на конец месяца", lambda i: "", RUB, BOLD)
    for i in range(MONTHS):
        f = ("=%s+%s%d" % (A("cash0"), col(i), flow)) if i == 0 \
            else "=%s%d+%s%d" % (col(i - 1), cash, col(i), flow)
        ws.cell(row=cash, column=2 + i, value=f).number_format = RUB
    put(ws, cash, 2 + MONTHS, "Месяц, в котором это число уходит в минус, — тот, до которого нужны деньги.",
        SMALL, wrap=True)
    ws.column_dimensions[get_column_letter(2 + MONTHS)].width = 60
    return ws, {"rev": rev, "costs": costs, "net": net, "cash": cash, "paid": paid,
                "flow": flow, "taxes": taxes, "ins": ins, "reg": reg}


