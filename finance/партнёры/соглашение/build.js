const runs = (parts, opts = {}) => parts.map(p =>
  typeof p === "string"
    ? new TextRun({ text: p, ...opts })
    : p.ph
      ? new TextRun({ text: `[${p.ph}]`, highlight: "yellow", ...opts })
      : new TextRun({ ...opts, ...p }));

const P = (parts, o = {}) => new Paragraph({
  children: runs(Array.isArray(parts) ? parts : [parts], o.run || {}),
  alignment: o.align || AlignmentType.JUSTIFIED,
  spacing: { after: o.after ?? 120, line: 276 },
  indent: o.indent,
  keepNext: o.keepNext,
});
const H = (text) => new Paragraph({
  children: [new TextRun({ text, bold: true })],
  spacing: { before: 240, after: 120 }, keepNext: true,
});
const CL = (num, parts) => P([`${num}. `, ...(Array.isArray(parts) ? parts : [parts])]);

