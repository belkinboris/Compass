head("4. ДВА ГОДА, ЕСЛИ ПРОДАВАТЬ И ФИЗЛИЦАМ, И КОМПАНИЯМ")

# Сколько новых корпоративных клиентов в месяц. Продаёт основатель: в базе
# ПОИМЕННО названы 86 фирм в каталоге консультантов и 286 фирм в самих
# сделках — это готовый список для обзвона, а не холодный рынок.
def corp_new(m, start=4, cap=3):
    if m < start:
        return 0
    return min(cap, 1 + (m - start) // 7)


def run_both(scen="990 ₽", corp_price=250000, ao=False, usn=False,
             mkt=None, corp_start=4, corp_cap=3, sales_from=None, sales_cost=120000):
    """Возвращает помесячные строки: физлица из модели + корпораты сверху."""
    p = dict(cm.SCEN[scen])
    fix_was = dict(cm.FIX)
    if mkt is not None:
        cm.FIX = dict(cm.FIX); cm.FIX["mkt"] = mkt
    _, b2c = cm.run(scen, p)
    cm.FIX = fix_was

    rows, clients, cash = [], 0.0, cm.CASH0
    for i in range(MONTHS):
        m = i + 1
        clients = clients * (1 - CORP_CHURN_Y / 12) + corp_new(m, corp_start, corp_cap)
        corp_rev = clients * corp_price / 12
        corp_costs = clients * CORP_VAR
        sales = sales_cost if (sales_from and m >= sales_from) else 0

        base_costs = b2c[i]["costs"]
        if ao:
            base_costs += sum(AO_EXTRA.values())
        if usn:
            base_costs += max(cm.FIX["gd_salary"], cm.MROT) * cm.INS_RATE - cm.INJURY_YEAR / 12

        rev = b2c[i]["rev"] + corp_rev
        costs = base_costs + corp_costs + sales
        # Корпораты платят за год вперёд — деньги приходят в месяц продажи.
        cash_in = b2c[i]["rev"] + corp_new(m, corp_start, corp_cap) * corp_price
        vat = 0.0     # порог 20 млн ₽ в год на этих объёмах не достигается
        usn = max((rev - costs) * cm.USN, rev * cm.USN_MIN)
        net = rev - costs - usn
        cash += cash_in - costs - usn
        rows.append(dict(m=m, subs=b2c[i]["paid"], clients=clients, rev=rev,
                         costs=costs, net=net, cash=cash))
    return rows


