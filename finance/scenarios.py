USN_RATE, USN_MIN = 0.15, 0.01        # минимальный налог — 1% от дохода ЗА ГОД
AUSN_RATE, AUSN_MIN = 0.20, 0.03      # минимальный налог — 3% от дохода ЗА МЕСЯЦ
GD_INS_YEAR = cm.MROT * cm.INS_RATE * 12      # взносы за директора на УСН
AUSN_INJURY_YEAR = 2959.0


def tax_usn(months):
    """УСН «доходы минус расходы» за год: большее из 15% с прибыли и 1% с дохода."""
    rev = sum(m["rev"] for m in months)
    profit = rev - sum(m["costs"] for m in months)
    return max(profit * USN_RATE, rev * USN_MIN)


def tax_ausn(months):
    """АУСН: налог считается ПОМЕСЯЧНО, минимальный — 3% дохода каждого месяца."""
    return sum(max((m["rev"] - m["costs"]) * AUSN_RATE, m["rev"] * AUSN_MIN) for m in months)


