"""Адрес Telegram Bot API: напрямую или через релей.

ЗАЧЕМ. Прямая связь Timeweb (РФ) -> api.telegram.org нестабильна. Это не
догадка: в соседнем проекте владельца («Автопост», тот же хостинг) замерено
~32% отказов на попытку соединения (19 июля 2026), и решено это было релеем
на Cloudflare Workers, а не увеличением числа повторов — повторы борются со
следствием, релей убирает причину на уровне сети.

КАК. `TELEGRAM_API_BASE` = адрес воркера (`https://имя.workers.dev`). Воркер
прозрачно пробрасывает путь `/bot<токен>/<метод>` и возвращает ответ Bot API
без изменений, поэтому к конкретному боту он не привязан — один и тот же
воркер обслуживает и «Автопост», и «Компас». Пусто = прямой api.telegram.org,
поведение ровно прежнее.

ПРО ОТСУТСТВУЮЩУЮ СХЕМУ. Значение без `https://` даёт `UnsupportedProtocol`
мгновенно, без единой попытки сети, — такую ошибку легко принять за сетевую и
искать причину не там (в «Автопосте» на это потратили время 19 июля 2026).
Поэтому схему дописываем сами, а не полагаемся на то, что её не забудут.
"""
import os

DIRECT = 'https://api.telegram.org'


def api_root():
    base = (os.environ.get('TELEGRAM_API_BASE') or '').strip().rstrip('/')
    if not base:
        return DIRECT
    if not base.startswith(('http://', 'https://')):
        base = 'https://' + base
    return base


def method_url(token, method):
    """Полный адрес метода Bot API: <корень>/bot<токен>/<метод>."""
    return '%s/bot%s/%s' % (api_root(), token, method)
